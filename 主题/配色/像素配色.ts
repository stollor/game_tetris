import { 配置游戏主题 } from "../../框架/样式/样式";
import type { 按钮样式, 游戏主题 } from "../../框架/样式/类型";
import { 像素色串, type 像素视觉规范, 砖机液晶规范, 街机彩砖规范 } from "../像素/像素规范";

function 由像素规范做配色(规范: 像素视觉规范): 游戏主题 {
  const 色 = 规范.色;
  const 钮字 = 规范.深色 ? 色.夜 : 色.墨;
  const 点字 = 规范.深色 ? 色.墨 : 色.底;
  const 次底 = 规范.深色 ? 色.纸 : 色.底;
  const 描边 = 色.壳;
  const 按钮 = (主色: number, 字: number): 按钮样式 => ({
    默认: { 背景: 像素色串(主色), 文字: 像素色串(字), 描边: 像素色串(描边) },
    移入: { 背景: 像素色串(色.亮), 文字: 像素色串(钮字), 描边: 像素色串(描边) },
    点击: { 背景: 像素色串(色.暗), 文字: 像素色串(点字), 描边: 像素色串(描边) },
    禁用: {
      背景: 像素色串(色.暗),
      文字: 像素色串(规范.深色 ? 色.次字 : 色.底),
      描边: 像素色串(色.暗),
    },
  });
  return {
    元信息: { 名称: 规范.名称 },
    页面: { 背景: 像素色串(色.底), 背景远景: 像素色串(色.夜), 光晕: 像素色串(色.亮) },
    文字: {
      主要: 像素色串(色.墨),
      次要: 像素色串(色.墨),
      弱化: 像素色串(色.次字),
      强调: 像素色串(规范.深色 ? 色.亮 : 色.墨),
      成功: 像素色串(规范.深色 ? 色.绿 : 色.墨),
      警告: 像素色串(规范.深色 ? 色.黄 : 色.墨),
      危险: 像素色串(规范.深色 ? 色.红 : 色.墨),
    },
    面板: {
      主面板: {
        背景: 像素色串(次底),
        描边: 像素色串(描边),
        标题文字: 像素色串(色.墨),
        正文文字: 像素色串(色.墨),
        阴影: 像素色串(色.暗),
      },
      次级面板: { 背景: 像素色串(规范.深色 ? 色.暗纸 : 色.亮), 描边: 像素色串(描边) },
      分组线: 像素色串(色.暗),
      遮罩: { 背景: 像素色串(色.壳), 透明度: 0.72 },
    },
    按钮: { 主要: 按钮(色.亮, 钮字), 次要: 按钮(次底, 规范.深色 ? 色.墨 : 色.墨) },
    输入框: {
      默认: { 背景: 像素色串(次底), 文字: 像素色串(色.墨), 描边: 像素色串(描边) },
      聚焦: { 背景: 像素色串(次底), 文字: 像素色串(色.墨), 描边: 像素色串(色.亮) },
      禁用: {
        背景: 像素色串(色.暗),
        文字: 像素色串(规范.深色 ? 色.次字 : 色.底),
        描边: 像素色串(色.暗),
      },
      占位文字: 像素色串(色.次字),
      轨道: 像素色串(描边),
    },
    游戏区域: {
      背景: 像素色串(色.底),
      网格线: 像素色串(色.暗),
      描边: 像素色串(描边),
      高亮: 像素色串(规范.深色 ? 色.亮 : 色.墨),
    },
  };
}

export const 像素配色: 游戏主题 = 由像素规范做配色(砖机液晶规范);
export const 彩砖配色: 游戏主题 = 由像素规范做配色(街机彩砖规范);

配置游戏主题({
  [砖机液晶规范.名称]: 像素配色,
  [街机彩砖规范.名称]: 彩砖配色,
});

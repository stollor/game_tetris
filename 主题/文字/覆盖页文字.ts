import type { 文字样式 } from "../../框架/界面/绘制/协议";
import { 是像素风格 } from "../像素/像素风格";
import { 游戏字体 } from "./字体";
import { 派生霓虹文字样式 } from "./文字样式";

/**
 * Phaser 场景里直接 `scene.add.text(...)` 且没写 `fontFamily` 时，Phaser `TextStyle` 的默认族是
 * `Courier`（拉丁字母/数字/空格按等宽走），CJK 走系统回退；而共享霓虹文字用的是
 * `游戏外观.字体.家族`（拉丁走 Segoe UI）。覆盖页（设置/成就/排行榜）的原生标题、副题、
 * 列表行、状态等文字就是前者，要让 Three 与 Phaser 逐像素一致必须沿用同一族。
 *
 * 数值以 Phaser 截图为真相：`文字宽度.ts` 实测 "马拉松 排行榜" 22px 粗体下
 * Courier 145.2px / 霓虹栈 138.07px，与两侧截图文字外框完全吻合。
 */
const Phaser原生字体族 = "Courier";

export interface 覆盖页文字样式选项 {
  字号: number;
  颜色: number | string;
  字重?: "常规" | "粗体";
  对齐?: "左" | "中" | "右";
  描边?: { 颜色: number | string; 粗细: number };
}

/** 覆盖页原生文字的共享样式：字号/颜色/字重/对齐按调用点给，字体族固定为 Phaser 原生默认。 */
export function 派生覆盖页文字样式(选项: 覆盖页文字样式选项): 文字样式 {
  return 派生霓虹文字样式("正文", {
    字体: 是像素风格() ? 游戏字体.家族 : Phaser原生字体族,
    字号: 选项.字号,
    颜色: 选项.颜色,
    ...(选项.字重 ? { 字重: 选项.字重 } : {}),
    ...(选项.对齐 ? { 对齐: 选项.对齐 } : {}),
    ...(选项.描边 ? { 描边: 选项.描边 } : {}),
  });
}

import { 亮色, 暗色 } from "../../../.gamemaker/依赖/框架/界面/颜色工具";
import { 糖果规范 } from "../../主题/糖果/糖果规范";
import { 绘制扇贝边, 绘制条纹篷, 绘制糖粒 } from "../../预制体/基础/装饰与蒙层/糖果花纹";
import { 绘制暗角, 随机值 } from "./通用";

/**
 * 「糖果超甜」的正式背景：深巧克力底 + 顶部粉白条纹遮阳篷 + 四角甜点插画 +
 * 漂浮糖粒与糖霜光斑。与像素/立体背景同职责：只依赖 `图形对象` 与 `糖果规范`，
 * 不读设置、不 import 引擎运行时；静态层可单独取帧给缩略图与预览。
 */

const 色 = 糖果规范.色;

/** 顶部遮阳篷高度（按高度比例，小屏不至于吃掉半个画面）。 */
function 篷高(高: number): number {
  return Math.min(糖果规范.背景.顶部条纹高, 高 * 0.1);
}

/** 静态底图：底、暗角、遮阳篷、四角甜点与散落糖粒。 */
export function 绘制糖果背景(绘图: 图形对象, 宽: number, 高: number): void {
  // 巧克力底：竖向渐变，底部更深，像烤盘里的巧克力。
  绘图
    .fillGradientStyle(
      亮色(色.巧克力, 0.16),
      亮色(色.巧克力, 0.16),
      色.巧克力深,
      色.巧克力深,
      1,
      1,
      1,
      1,
    )
    .fillRect(0, 0, 宽, 高);
  // 糖霜细点：固定随机种子，帧间不闪。
  for (let 序 = 0; 序 < 140; 序 += 1) {
    const x = 随机值(序 + 1201) * 宽;
    const y = 随机值(序 + 1321) * 高;
    const r = 0.7 + 随机值(序 + 1441) * 1.1;
    绘图.fillStyle(色.糖纸, 0.05 + 随机值(序 + 1561) * 0.05).fillCircle(x, y, r);
  }
  // 四角甜点：左上棒棒糖、右上马卡龙、左下巧克力球、右下甜甜圈。
  const 单位 = Math.min(宽, 高);
  绘制棒棒糖(绘图, 宽 * 0.12, 高 * 0.12, 单位 * 0.085);
  绘制马卡龙(绘图, 宽 * 0.9, 高 * 0.1, 单位 * 0.075, 色.草莓浅, 色.草莓);
  绘制巧克力球(绘图, 宽 * 0.08, 高 * 0.9, 单位 * 0.06);
  绘制甜甜圈(绘图, 宽 * 0.93, 高 * 0.92, 单位 * 0.07);
  // 散落的糖粒与糖针
  const 糖色 = [色.薄荷, 色.叶绿, 色.蓝莓, 色.葡萄, 色.橙, 色.柠檬, 色.草莓糖];
  for (let 序 = 0; 序 < 糖果规范.背景.糖粒数; 序 += 1) {
    const x = 随机值(序 + 2101) * 宽;
    const y = 篷高(高) + 随机值(序 + 2221) * (高 - 篷高(高) - 高 * 0.06);
    const 色值 = 糖色[序 % 糖色.length] ?? 色.草莓糖;
    绘制糖粒(
      绘图,
      x,
      y,
      1.2 + 随机值(序 + 2341) * 1.6,
      色值,
      0.28 + 随机值(序 + 2461) * 0.2,
      随机值(序 + 2581) * Math.PI,
    );
  }
  // 中景再放两颗糖，避免整屏只有边角有甜点，纯享时中间太空；位置避开标题与主按钮。
  绘制马卡龙(绘图, 宽 * 0.9, 高 * 0.45, 单位 * 0.034, 色.薄荷, 色.薄荷深);
  绘制巧克力球(绘图, 宽 * 0.1, 高 * 0.58, 单位 * 0.03);
  // 顶部遮阳篷：粉白斜条纹 + 波浪下缘。
  绘制条纹篷(绘图, 0, 0, 宽, 篷高(高), 色.粉, 色.草莓深, 色.粉);
  // 篷下一条奶油细边，压住波浪与底色的交界。
  绘图.fillStyle(色.奶油, 0.9).fillRect(0, 篷高(高) + 2, 宽, Math.max(1.4, 高 * 0.003));
  // 底部扇贝托盘边：和棋盘底沿的糖纸呼应。
  绘制扇贝边(
    绘图,
    0,
    高 - Math.max(6, 高 * 0.008),
    宽,
    色.草莓深,
    0.55,
    "下",
    高 * 0.009,
    高 * 0.02,
  );
  绘制暗角(绘图, 宽, 高);
}

/** 动态层：缓慢飘落的糖粒、糖霜光斑与甜点微光；亮度乘子与其它主题一致。 */
export function 绘制糖果背景动态(
  绘图: 图形对象,
  宽: number,
  高: number,
  时间秒: number,
  亮度 = 1,
): void {
  const 单位 = Math.min(宽, 高);
  const 糖色 = [色.薄荷, 色.叶绿, 色.蓝莓, 色.葡萄, 色.橙, 色.柠檬, 色.草莓糖];
  // 飘落糖粒：每颗按不同速度与横向摆幅循环下落。
  for (let 序 = 0; 序 < 30; 序 += 1) {
    const 速度 = 0.012 + 随机值(序 + 3101) * 0.02;
    const 循环 = (时间秒 * 速度 + 随机值(序 + 3221)) % 1;
    const y = 高 * 1.02 - 循环 * 高 * 1.08;
    const 摆 = Math.sin(时间秒 * (0.4 + 随机值(序 + 3341) * 0.6) + 序) * 宽 * 0.02;
    const x = 随机值(序 + 3461) * 宽 + 摆;
    const 半径 = 1.2 + 随机值(序 + 3581) * 1.8;
    const 色值 = 糖色[序 % 糖色.length] ?? 色.草莓糖;
    绘制糖粒(
      绘图,
      x,
      y,
      半径,
      色值,
      (0.3 + 随机值(序 + 3701) * 0.25) * 亮度,
      时间秒 * (0.4 + 序 * 0.05),
    );
  }
  // 甜点微光：四角插画上缓慢呼吸的高光。
  const 呼吸 = 0.5 + 0.5 * Math.sin(时间秒 * 1.1);
  绘制光斑(绘图, 宽 * 0.12, 高 * 0.12, 单位 * 0.1, 色.粉, 0.1 * 呼吸 * 亮度);
  绘制光斑(绘图, 宽 * 0.9, 高 * 0.1, 单位 * 0.09, 色.草莓浅, 0.08 * 呼吸 * 亮度);
  绘制光斑(绘图, 宽 * 0.92, 高 * 0.9, 单位 * 0.09, 色.金, 0.07 * (1 - 呼吸) * 亮度);
  // 篷沿高光缓移：像糖霜在灯下反光。
  绘图
    .fillStyle(色.糖纸, 0.06 * 亮度)
    .fillRect(0, 篷高(高) * (0.2 + 0.2 * Math.sin(时间秒 * 0.6)), 宽, Math.max(1, 高 * 0.01));
}

/** 柔和光斑：两层同心圆，叠加后不刺眼。 */
function 绘制光斑(
  绘图: 图形对象,
  x: number,
  y: number,
  半径: number,
  颜: number,
  透明度: number,
): void {
  绘图.fillStyle(颜, 透明度 * 0.35).fillCircle(x, y, 半径);
  绘图.fillStyle(颜, 透明度 * 0.22).fillCircle(x, y, 半径 * 0.62);
}


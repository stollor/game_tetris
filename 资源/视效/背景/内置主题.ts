/**
 * 极光原野的纯配方：底图 + 动态细节。四套主题里只有极光原野是「内置风景」，
 * 其余三套各有专属背景配方。本文件只依赖 `图形对象` 与共享配置，不 import 引擎运行时。
 */

export type 内置主题名称 = "极光原野";

/** 内置主题的代表色，与下方绘制用色同源；供 Three 的顶栏衬底/文字对比度读取。 */
export const 内置主题外观: Record<内置主题名称, { 主色: number; 强调: number }> = {
  极光原野: { 主色: 0x081726, 强调: 0x3ff0c0 },
};

export function 是内置主题(主题: 背景主题): 主题 is 内置主题名称 {
  return 主题 === "极光原野";
}

/** 内置主题静态底图（含统一暗角）。 */
export function 绘制内置背景静底(绘图: 图形对象, 宽: number, 高: number): void {
  绘制原野底图(绘图, 宽, 高);
  绘制暗角(绘图, 宽, 高);
}

/** 内置主题动态层；时间秒按主题动画速度换算到与原 Phaser 版一致的时间轴。 */
export function 绘制内置背景动态(
  绘图: 图形对象,
  宽: number,
  高: number,
  时间秒: number,
  亮度 = 1,
): void {
  绘制极光动画(绘图, 宽, 高, 时间秒 * 1000 * 背景主题配置.极光原野.动画速度, 亮度);
}


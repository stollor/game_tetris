import { 背景主题配置 } from "../../主题/外观/背景主题";
import type { 背景主题 } from "../../主题/外观/背景主题";
import { 像素规范 } from "../../主题/像素/像素规范";
import { 是像素风格 } from "../../主题/像素/像素风格";
import { 立体规范 } from "../../主题/立体/立体规范";
import { 是立体风格 } from "../../主题/立体/立体风格";
import type { 图形对象 } from "../../../.gamemaker/依赖/框架/界面/绘制/协议";
import { 绘制液晶背景, 绘制液晶背景动态 } from "./像素背景";
import { 内置主题外观, 是内置主题, 绘制内置背景动态, 绘制内置背景静底 } from "./内置主题";
import { 绘制街机彩砖背景, 绘制街机彩砖背景动态 } from "./街机彩砖背景";
import { 绘制立体晶格背景, 绘制立体晶格背景动态 } from "./立体晶格背景";

/**
 * 背景视觉配方的唯一入口（引擎无关纯函数）：
 * - 四套主题各有一张正式背景：极光原野内置风景、砖机液晶掌机井、街机彩砖、立体晶格；
 * - Three 版页面直接用 `画笔.图形` 调用，不再另画简化背景。
 *
 * 约束：只依赖 `图形对象` 契约和共享配置，不 import 引擎运行时；
 * 绘制参数全部来自调用方，函数内不读场景/设置/存档。
 */

/** 冻结入口参数：宽高为逻辑像素；时间秒为动画时间轴；动态=false 时画固定静态帧。 */
export interface 背景绘制参数 {
  宽: number;
  高: number;
  主题: 背景主题;
  动态: boolean;
  时间秒: number;
  /** 缩略图/固定样品：按 主题 画指定背景，不被当前主题风格改写。 */
  按名称绘制?: boolean;
}

/** 静态底图参数。 */
export interface 背景静态参数 {
  宽: number;
  高: number;
  主题: 背景主题;
  /** 缩略图/固定样品：按 主题 画指定背景，不被当前主题风格改写。 */
  按名称绘制?: boolean;
}

/** 动态层参数。 */
export interface 背景动态参数 {
  宽: number;
  高: number;
  主题: 背景主题;
  时间秒: number;
  /** 图层亮度乘子；单画布合成时传 `背景主题配置.动画亮度`，分图层时传 1。 */
  亮度?: number;
  /** 缩略图/固定样品：按 主题 画指定背景，不被当前主题风格改写。 */
  按名称绘制?: boolean;
}

/** 背景外观配色（Three 顶栏衬底/浅底压暗用），颜色取自共享配置。 */
export interface 背景外观配色 {
  主色: number;
  强调: number;
  文字基调: "浅底" | "深底";
}

/** 完整背景画面（静态 + 动态，一次调用画完）。 */
export function 绘制背景(绘图: 图形对象, 参数: 背景绘制参数): void {
  绘制背景静底(绘图, {
    宽: 参数.宽,
    高: 参数.高,
    主题: 参数.主题,
    按名称绘制: 参数.按名称绘制,
  });
  if (!参数.动态) return;
  绘制背景动态(绘图, {
    宽: 参数.宽,
    高: 参数.高,
    主题: 参数.主题,
    时间秒: 参数.时间秒,
    亮度: 读取背景动态亮度(参数.主题),
    按名称绘制: 参数.按名称绘制,
  });
}

/** 静态底图：页面按当前主题风格分发，样品按传入的主题名分发。 */
export function 绘制背景静底(绘图: 图形对象, 参数: 背景静态参数): void {
  if (!参数.按名称绘制) {
    if (是像素风格()) {
      绘制像素风格静底(绘图, 参数.宽, 参数.高);
      return;
    }
    if (是立体风格()) {
      绘制立体晶格背景(绘图, 参数.宽, 参数.高);
      return;
    }
    绘制内置背景静底(绘图, 参数.宽, 参数.高);
    return;
  }
  按主题绘制静底(绘图, 参数.宽, 参数.高, 参数.主题);
}

/** 动态层：页面按当前主题风格分发，样品按传入的主题名分发。 */
export function 绘制背景动态(绘图: 图形对象, 参数: 背景动态参数): void {
  if (!参数.按名称绘制) {
    if (是像素风格()) {
      绘制像素风格动态(绘图, 参数.宽, 参数.高, 参数.时间秒, 参数.亮度 ?? 1);
      return;
    }
    if (是立体风格()) {
      绘制立体晶格背景动态(绘图, 参数.宽, 参数.高, 参数.时间秒, 参数.亮度 ?? 1);
      return;
    }
    绘制内置背景动态(绘图, 参数.宽, 参数.高, 参数.时间秒, 参数.亮度 ?? 1);
    return;
  }
  按主题绘制动态(绘图, 参数.宽, 参数.高, 参数.主题, 参数.时间秒, 参数.亮度 ?? 1);
}

/** 当前像素规范决定液晶壳还是街机彩砖后景。 */
function 绘制像素风格静底(绘图: 图形对象, 宽: number, 高: number): void {
  if (像素规范.名称 === "街机彩砖") 绘制街机彩砖背景(绘图, 宽, 高);
  else 绘制液晶背景(绘图, 宽, 高);
}

function 绘制像素风格动态(
  绘图: 图形对象,
  宽: number,
  高: number,
  时间秒: number,
  亮度: number,
): void {
  if (像素规范.名称 === "街机彩砖") 绘制街机彩砖背景动态(绘图, 宽, 高, 时间秒, 亮度);
  else 绘制液晶背景动态(绘图, 宽, 高, 时间秒, 亮度);
}

/** 按主题名直接分发：四套主题各一张正式背景。 */
function 按主题绘制静底(绘图: 图形对象, 宽: number, 高: number, 主题: 背景主题): void {
  if (主题 === "砖机液晶") 绘制液晶背景(绘图, 宽, 高);
  else if (主题 === "街机彩砖") 绘制街机彩砖背景(绘图, 宽, 高);
  else if (主题 === "立体晶格") 绘制立体晶格背景(绘图, 宽, 高);
  else 绘制内置背景静底(绘图, 宽, 高);
}

function 按主题绘制动态(
  绘图: 图形对象,
  宽: number,
  高: number,
  主题: 背景主题,
  时间秒: number,
  亮度: number,
): void {
  if (主题 === "砖机液晶") 绘制液晶背景动态(绘图, 宽, 高, 时间秒, 亮度);
  else if (主题 === "街机彩砖") 绘制街机彩砖背景动态(绘图, 宽, 高, 时间秒, 亮度);
  else if (主题 === "立体晶格") 绘制立体晶格背景动态(绘图, 宽, 高, 时间秒, 亮度);
  else 绘制内置背景动态(绘图, 宽, 高, 时间秒, 亮度);
}

/** 动态层亮度：只有内置极光风景按配置缩放，专属后景固定 1。 */
export function 读取背景动态亮度(主题: 背景主题): number {
  if (!是内置主题(主题)) return 1;
  return 背景主题配置[主题].动画亮度;
}

/** 背景代表色：像素/立体主题取自身规范，极光原野取内置配方用色。 */
export function 读取背景外观配色(主题: 背景主题): 背景外观配色 {
  if (是像素风格()) return { 主色: 像素规范.色.夜, 强调: 像素规范.色.黄, 文字基调: "深底" };
  if (是立体风格()) return { 主色: 立体规范.界面.壳, 强调: 立体规范.界面.灯, 文字基调: "深底" };
  if (是内置主题(主题)) {
    const 外观 = 内置主题外观[主题];
    return { 主色: 外观.主色, 强调: 外观.强调, 文字基调: 背景主题配置[主题].文字基调 };
  }
  return {
    主色: 背景主题配置[主题].预览配色[0],
    强调: 背景主题配置[主题].预览配色[1],
    文字基调: 背景主题配置[主题].文字基调,
  };
}

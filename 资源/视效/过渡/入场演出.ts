/**
 * 模式选择 → 对局的接力入场：时间轴与姿态计算在这里，具体画法按当前主题分发到
 * `转场主题/` 下的五套画法。本文件只决定「什么时候、什么位置」，不决定「什么质感」。
 */

export function 计算模式入场姿态(秒: number, 原: 流转矩形, 宽: number, 高: number) {
  const t = Math.max(0, 秒);
  const 时 = 入场参数.时间;
  const 曲 = 入场参数.曲线;
  const 居中进度 = 快出(比例(t, 时.居中起, 时.居中止), 曲.居中);
  const 收 = 比例(t, 时.收束起, 时.收束止);
  const 压缩进度 = 收 ** 曲.收束;
  const 浮 = Math.sin(Math.PI * 比例(t, 0, 时.收束起)) * 入场参数.运动.聚焦放大;
  const 当前宽 = 原.宽 * (1 + 浮) + (宽 - 原.宽 * (1 + 浮)) * 收 ** 曲.展宽;
  const 当前高 = 原.高 * (1 + 浮) + (入场参数.运动.线高 - 原.高 * (1 + 浮)) * 压缩进度;
  const 中心X = 原.左 + 原.宽 / 2 + (宽 / 2 - 原.左 - 原.宽 / 2) * 居中进度;
  const 中心Y = 原.上 + 原.高 / 2 + (高 / 2 - 原.上 - 原.高 / 2) * 居中进度;
  const 矩形 = { 左: 中心X - 当前宽 / 2, 上: 中心Y - 当前高 / 2, 宽: 当前宽, 高: 当前高 };
  const 幕面进度 = 比例(t, 时.幕布起, 时.收束止) ** 曲.幕布;
  // 幕面终点取卡片正在收束的上下边，不再追逐另一套独立横轴。
  const 幕缝 = {
    顶: Math.max(0, 矩形.上 * 幕面进度),
    底: Math.min(高, 高 - (高 - 矩形.上 - 当前高) * 幕面进度),
  };
  return {
    阶段: t < 0.18 ? "退场" : t < 时.居中止 ? "居中" : t < 时.收束止 ? "压线" : "蓄力",
    退场进度: 比例(t, 0, 时.退场),
    居中进度,
    压缩进度,
    幕面进度,
    矩形,
    幕缝,
    内容透明度: 1 - 比例(t, 时.内容起, 时.内容止) ** 2,
    线脉冲:
      t < 时.收束止
        ? 比例(t, 入场参数.能量.预亮起, 时.收束止) ** 1.5
        : 1 - (1 - 入场参数.能量.释放余辉) * 快出(比例(t, 时.收束止, 时.凝聚止), 2),
    完成: t >= 模式退场时长,
  };
}

export function 计算退场进度(秒: number, 距离: number): number {
  const 时 = 入场参数.时间;
  const 延迟 = Math.min(3, Math.max(0, 距离)) * 时.错峰;
  return 比例(秒, 延迟, 延迟 + 时.退场);
}

export function 计算对局入场姿态(秒: number) {
  const t = Math.max(0, 秒);
  const 时 = 入场参数.时间;
  const 节拍 = t < 时.Ready起 ? "展开" : t < 时.Ready止 ? "Ready" : t < 时.Go止 ? "Go" : "完成";
  return {
    展开进度: 快出(比例(t, 0, 时.释放止), 入场参数.曲线.释放),
    节拍,
    线脉冲: 入场参数.能量.释放余辉 * (1 - 快出(比例(t, 0, 入场参数.能量.释放衰减止), 2)),
    完成: t >= 对局入场时长,
  };
}

export function 计算分组入场姿态(秒: number, 组: keyof typeof 入场参数.分组) {
  const { 起, 止 } = 入场参数.分组[组];
  const p = 快出(比例(秒, 起, 止), 入场参数.曲线.落位);
  if (p === 1) return { 透明度: 1, 偏移X: 0, 偏移Y: 0, 缩放Y: 1, 完成: true };
  const 余 = 1 - p;
  const 幅 = 入场参数.运动;
  return {
    透明度: 组 === "棋盘" ? 1 : p,
    偏移X: 组 === "侧栏" ? 幅.侧栏位移 * 余 : 0,
    偏移Y: 组 === "顶栏" ? -幅.顶栏位移 * 余 : 组 === "操作区" ? 幅.操作位移 * 余 : 0,
    缩放Y: 组 === "棋盘" ? 1 - 幅.棋盘收拢 * 余 : 1,
    完成: 秒 >= 止,
  };
}

export function 计算网格入场透明度(秒: number): number {
  return 快出(比例(秒, 入场参数.网格.起, 入场参数.网格.止), 2);
}

export function 计算展开幕缝(展开: number, 高: number): 转场幕缝 {
  const 顶 = ((高 - 入场参数.运动.线高) / 2) * (1 - Math.min(1, Math.max(0, 展开)));
  return { 顶, 底: 高 - 顶 };
}

/**
 * 入场幕面：上下两片幕布，缝由时间轴给出。`覆盖度` 决定主题画法的量化/过冲程度，
 * `边线` 是接缝边线透明度（收束阶段 0，展开阶段随进度淡出）。
 */
export function 绘制入场幕面(
  画笔: 画笔,
  宽: number,
  高: number,
  模式: 游戏模式,
  缝: 转场幕缝,
  覆盖度: number,
  边线 = 0,
): void {
  转场画法表[读取转场风格()].绘制幕面(画笔.图形, {
    宽,
    高,
    缝,
    覆盖度,
    模式色: 模式主题色(模式),
    边线,
  });
}


/**
 * 转场时间轴的读取端：遮罩由动画层按主题画法绘制，这里只算节拍、分组落位与 Ready/Go。
 * 「什么时候露出什么」在动画层与主题画法里；页面只关心内容什么时候落位、什么时候解锁输入。
 */

export type 入场节拍 = "揭示" | "Ready" | "Go" | "完成";

/** 按当前主题画一帧转场遮罩与强调；动画层与界面预览共用这一入口。 */
export function 绘制转场遮罩(图: 图形对象, 帧: 转场帧): void {
  const 画法 = 转场画法表[读取转场风格()];
  画法.绘制遮罩(图, 帧);
  画法.绘制强调?.(图, 帧);
}

export function 计算入场节拍(秒: number): { 揭示进度: number; 节拍: 入场节拍; 完成: boolean } {
  const t = Math.max(0, 秒);
  const 时 = 入场参数.时间;
  const 节拍: 入场节拍 =
    t < 时.Ready起 ? "揭示" : t < 时.Ready止 ? "Ready" : t < 时.Go止 ? "Go" : "完成";
  return {
    揭示进度: 快出(比例(t, 0, 时.揭示止), 4),
    节拍,
    完成: t >= 对局入场时长,
  };
}

export function 计算分组入场姿态(秒: number, 组: keyof typeof 入场参数.分组) {
  const { 起, 止 } = 入场参数.分组[组];
  const p = 快出(比例(秒, 起, 止), 入场参数.曲线.落位);
  if (p === 1) return { 透明度: 1, 偏移X: 0, 偏移Y: 0, 缩放Y: 1, 完成: true };
  const 余 = 1 - p;
  const 幅 = 入场参数.运动;
  return {
    透明度: 组 === "棋盘" ? 1 : p,
    偏移X: 组 === "侧栏" ? 幅.侧栏位移 * 余 : 0,
    偏移Y: 组 === "顶栏" ? -幅.顶栏位移 * 余 : 组 === "操作区" ? 幅.操作位移 * 余 : 0,
    缩放Y: 组 === "棋盘" ? 1 - 幅.棋盘收拢 * 余 : 1,
    完成: 秒 >= 止,
  };
}

export function 计算网格入场透明度(秒: number): number {
  return 快出(比例(秒, 入场参数.网格.起, 入场参数.网格.止), 2);
}

/**
 * Ready/Go 节拍：主题底纹由转场画法画在文字之下，文字与音效仍由页面统一驱动。
 * 只有展开阶段才会调用；节拍未到或已过时什么都不画。
 */
export function 绘制开局节拍(画笔: 画笔, 宽: number, 高: number, 模式: 游戏模式, 秒: number): void {
  const { 节拍 } = 计算入场节拍(秒);
  if (节拍 !== "Ready" && 节拍 !== "Go") return;
  const 时 = 入场参数.时间;
  const 起 = 节拍 === "Ready" ? 时.Ready起 : 时.Ready止;
  const 止 = 节拍 === "Ready" ? 时.Ready止 : 时.Go止;
  const t = Math.max(0, 秒 - 起);
  const 入 = 快出(比例(t, 0, 时.节拍进入), 3);
  const 出 = 比例(秒, 止 - 时.节拍退出, 止) ** 2;
  const 显 = 入 * (1 - 出);
  const 图 = 画笔.图形;
  转场画法表[读取转场风格()].绘制节拍底纹?.(图, {
    宽,
    高,
    模式色: 模式主题色(模式),
    显,
  });
  图.save().setAlpha(显);
  画笔.绘制文字({
    文案: 节拍.toUpperCase(),
    x: 宽 / 2,
    y: 高 / 2 + (1 - 入) * 入场参数.运动.节拍位移 - 出 * 3,
    锚点: "中中",
    缩放: 0.97 + 入 * 0.03 + 出 * 0.01,
    样式: 派生霓虹文字样式("按钮", {
      // 字号是文字图集键，必须是整数：宽 × 0.125 在手机上会得到 48.75 这类浮点，
      // 每个尺寸档都会新建一张图集且永不回收。
      字号: Math.min(量化字号(宽 * 0.125), 节拍 === "Ready" ? 46 : 54),
      字重: "粗体",
      颜色: 节拍 === "Ready" ? "#fff8e7" : 模式主题色文本(模式),
      字距: 2,
      描边: { 颜色: "#101a28", 粗细: 1.5 },
    }),
  });
  图.restore();
}

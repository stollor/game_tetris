import type { 图形对象 } from "../../../../.gamemaker/依赖/框架/界面/绘制/协议";
import { 暗色, 混色 } from "../../../../.gamemaker/依赖/框架/界面/颜色工具";
import { 按名称取像素规范 } from "../../../主题/像素/像素规范";
import { 入场参数 } from "../入场参数";
import type { 幕面参数, 接缝参数, 节拍底纹参数, 转场画法 } from "./类型";

/**
 * 砖机液晶（Brick LCD）的转场画法：四色 LCD 点阵幕布 + 8 档量化合拢 + 液晶接缝。
 *
 * 语汇：
 * - 幕面按 4px 网格铺成「外缘墨 → 中段暗 → 接缝侧亮砖带」，整片不透明，砖缝用更深一档实色；
 * - 合拢进度先量化到 8 档（`量化覆盖度`），合拢边再按列叠 0~2 格锯齿（`列错峰` / `合拢齿格`），
 *   所以收放是「像素动画」的顿挫，不是一条平滑直线；
 * - 接缝是一行 8px 高的亮/底交替液晶块，中央 8px 光标块在强度峰值闪，余辉时回落到暗。
 *
 * 规范色一律取 `按名称取像素规范("砖机液晶")`，不能用绘制期活规范 `像素规范`，
 * 否则五套主题同屏预览或试穿时会拿错主题的四色。
 */
const 规 = 按名称取像素规范("砖机液晶");
/** 点阵单位：4px 网格、8px 砖高、8 档量化（与规范的动画步频一致）。 */
const 网格 = 规.网格;
const 砖高 = 网格 * 2;
const 砖宽 = 网格 * 4;

/** 液晶合拢的量化档数：取规范里的动画步频，转场与像素动画同一步频。 */
export const 液晶档数 = 规.动画步频;

/**
 * 把连续的合拢进度量化成液晶的 8 档帧进度。
 * 输入 `覆盖度`：0 = 幕布完全打开，1 = 完全合拢；越界夹到 0..1，非有限值按 0 处理。
 * 输出 0、1/8、2/8 … 1 之一（向下取整）：幕布只在 8 个台阶上换帧，做出像素动画的顿挫感。
 */
export function 量化覆盖度(覆盖度: number): number {
  if (!Number.isFinite(覆盖度)) return 0;
  const 夹 = Math.min(1, Math.max(0, 覆盖度));
  return Math.floor(夹 * 液晶档数) / 液晶档数;
}

/** 列错峰表：两列一组同档，合拢边读起来像砖块错缝，而不是随机噪点。 */
const 列错峰表 = [0, 0, 1, 1, 2, 2, 1, 1] as const;
/** 行错峰表：节拍底纹的点阵行错开 0~2 格，避免点阵排成笔直的横线。 */
const 行错峰表 = [0, 1, 2, 0, 2, 1] as const;

function 取错峰表(表: readonly number[], 序: number): number {
  if (!Number.isFinite(序)) return 0;
  const 长度 = 表.length;
  const 位 = ((Math.trunc(序) % 长度) + 长度) % 长度;
  return 表[位] ?? 0;
}

/**
 * 列错峰：返回第 `列` 列在合拢边上的错峰档位。
 * 输入列序号（可为负、可非整数，按整数归一）；输出 0、1、2 之一，同一列永远同一档。
 */
export function 列错峰(列: number): number {
  return 取错峰表(列错峰表, 列);
}

/**
 * 行错峰：返回第 `行` 行的错峰档位，供节拍底纹把点阵行错开。
 * 输入行序号（可为负、可非整数，按整数归一）；输出 0、1、2 之一，同一行永远同一档。
 */
export function 行错峰(行: number): number {
  return 取错峰表(行错峰表, 行);
}

/** 锯齿模板：一格一档地收，8 档循环一圈，越靠后越平。 */
const 齿模板 = [0, 1, 2, 1, 2, 1, 2, 1] as const;

/**
 * 合拢齿格：某一列在合拢边上突出几格（1 格 = 4px）。
 * 输入 `列` 列序号与 `覆盖度` 原始合拢进度；输出 0、1、2 三档。
 * 覆盖度先量化到 8 档再叠加列错峰，所以锯齿只在 8 个台阶上换形；
 * 完全合拢（覆盖度 = 1）时收平为 0，接缝落在一条直线上。
 */
export function 合拢齿格(列: number, 覆盖度: number): number {
  const 档 = Math.round(量化覆盖度(覆盖度) * 液晶档数);
  if (档 >= 液晶档数) return 0;
  return 齿模板[(档 + 列错峰(列)) % 齿模板.length] ?? 0;
}

/** 把距屏幕外缘的距离换成屏坐标：朝下（上片幕布）从顶量，否则从底量。 */
function 取Y(高: number, 朝下: boolean, 距离: number): number {
  return 朝下 ? 距离 : 高 - 距离;
}

/** 画一条贴着外缘、跨距离 [距起, 距止] 的横条。 */
function 画条(
  图: 图形对象,
  x: number,
  条宽: number,
  高: number,
  朝下: boolean,
  距起: number,
  距止: number,
  色: number,
): void {
  if (距止 <= 距起 || 条宽 <= 0) return;
  const 顶 = 朝下 ? 距起 : 高 - 距止;
  图.fillStyle(色, 1).fillRect(x, 顶, 条宽, 距止 - 距起);
}

/** 沿外缘距离每 `间隔` 画一条 1px 点阵格线（填实色，不透明）。 */
function 画格线(
  图: 图形对象,
  宽: number,
  高: number,
  朝下: boolean,
  距起: number,
  距止: number,
  间隔: number,
  色: number,
): void {
  const 首 = Math.ceil(距起 / 间隔) * 间隔;
  for (let 距 = 首; 距 < 距止; 距 += 间隔) {
    图.fillStyle(色, 1).fillRect(0, 取Y(高, 朝下, 距), 宽, 1);
  }
}

/**
 * 画一片幕布（上片朝下、下片朝上）。
 * `厚` 是幕布到屏幕外缘的距离；颜色从外缘向内依次是墨、暗、亮砖带。
 */
function 绘制一片(
  图: 图形对象,
  宽: number,
  高: number,
  厚: number,
  朝下: boolean,
  覆盖度: number,
  边线: number,
  模式色: number,
): void {
  if (厚 <= 0) return;
  // 三段配色的厚度都对齐 8px 砖高：外缘墨场 → 中段暗带 → 接缝侧亮砖带。
  const 亮厚 = Math.min(厚, Math.max(砖高, Math.round((厚 * 0.3) / 砖高) * 砖高), 砖高 * 5);
  const 暗厚 = Math.min(
    厚 - 亮厚,
    Math.max(砖高 * 2, Math.round((厚 * 0.32) / 砖高) * 砖高),
    砖高 * 10,
  );
  const 墨厚 = 厚 - 亮厚 - 暗厚;
  const 亮起 = 墨厚 + 暗厚;

  // 墨底整片填实：幕布必须不透明，能盖住模式选择页的内容。
  画条(图, 0, 宽, 高, 朝下, 0, 厚, 规.色.墨);
  if (暗厚 > 0) 画条(图, 0, 宽, 高, 朝下, 墨厚, 亮起, 规.色.暗);

  // 接缝侧亮砖带：每列按齿格错开，合拢边因此是阶梯马赛克。
  const 列数 = Math.ceil(宽 / 砖宽);
  if (厚 < 砖高) {
    // 幕布还没一块砖厚时整条画完，不为几像素铺砖。
    画条(图, 0, 宽, 高, 朝下, 亮起, 厚, 规.色.亮);
  } else {
    const 可齿 = Math.max(0, Math.floor(厚 / 砖高));
    for (let 列 = 0; 列 < 列数; 列 += 1) {
      const x = 列 * 砖宽;
      const 齿 = Math.min(合拢齿格(列, 覆盖度), 2, 可齿);
      画条(图, x, Math.min(砖宽, 宽 - x), 高, 朝下, 亮起, 厚 + 齿 * 网格, 规.色.亮);
    }
    // 竖砖缝：把亮砖带切成 16×8 的砖块，1px 实色，不透页面。
    for (let 列 = 1; 列 < 列数; 列 += 1) {
      画条(图, 列 * 砖宽 - 1, 1, 高, 朝下, 亮起, 厚, 规.色.墨);
    }
  }

  // 点阵格线：比所在段再深一档，1px 实色；越靠外越疏，把图元压在两百个以内。
  if (亮厚 >= 砖高) 画格线(图, 宽, 高, 朝下, 亮起, 厚, 砖高, 规.色.墨);
  if (暗厚 >= 砖高) 画格线(图, 宽, 高, 朝下, 墨厚, 亮起, 砖高, 规.色.墨);
  if (墨厚 >= 网格) 画格线(图, 宽, 高, 朝下, 0, 墨厚, 砖高 * 3, 暗色(规.色.墨, 0.45));

  // 接缝边线：只在页面给透明度时画，收束阶段为 0。
  if (边线 > 0) {
    const 边Y = 朝下 ? 厚 - 1 : 高 - 厚;
    图.fillStyle(混色(模式色, 规.色.底, 0.35), Math.min(1, 边线)).fillRect(0, 边Y, 宽, 1);
  }
}

function 绘制幕面(图: 图形对象, 参数: 幕面参数): void {
  const { 宽, 高, 缝, 覆盖度, 边线, 模式色 } = 参数;
  if (缝.顶 > 0) 绘制一片(图, 宽, 高, 缝.顶, true, 覆盖度, 边线, 模式色);
  const 下厚 = 高 - 缝.底;
  if (下厚 > 0) 绘制一片(图, 宽, 高, 下厚, false, 覆盖度, 边线, 模式色);
}

function 绘制接缝(图: 图形对象, 参数: 接缝参数): void {
  const { 宽, 高, 模式色, 强度 } = 参数;
  const 强 = Number.isFinite(强度) ? Math.min(1, Math.max(0, 强度)) : 0;
  const 中央 = Math.round(高 / 2); // 严格落在页面中线，误差 0px
  const 带顶 = 中央 - 砖高 / 2;

  // 上下各一道 1px 墨线：把 8px 液晶接缝从幕布亮砖带里切出来。
  图
    .fillStyle(规.色.墨, 1)
    .fillRect(0, 带顶 - 1, 宽, 1)
    .fillRect(0, 带顶 + 砖高, 宽, 1);

  // 暗底：接缝带始终是实体，砖缝不透出页面内容。
  图.fillStyle(规.色.暗, 1).fillRect(0, 带顶, 宽, 砖高);

  // 亮/底交替的液晶方块，1px 竖砖缝；余辉时整体向暗回落，块形仍可读。
  const 列数 = Math.ceil(宽 / 砖高);
  for (let 列 = 0; 列 < 列数; 列 += 1) {
    const x = 列 * 砖高;
    const 块宽 = Math.min(砖高 - 1, 宽 - x);
    if (块宽 <= 0) break;
    const 原色 = 列 % 2 === 0 ? 规.色.底 : 规.色.亮;
    图.fillStyle(混色(规.色.暗, 原色, 0.3 + 0.7 * 强), 1).fillRect(x, 带顶, 块宽, 砖高);
  }

  // 中央 8px 光标块：强度峰值时用模式色闪一下，余辉时回落到暗。
  const 光标 = 中央 - 砖高 / 2;
  const 峰值 = 强 >= 0.85;
  图
    .fillStyle(峰值 ? 混色(规.色.底, 模式色, 0.6) : 混色(规.色.暗, 规.色.底, 强 * 0.7), 1)
    .fillRect(光标, 带顶, 砖高, 砖高);
  // 峰值时内芯留一格最亮底色，像液晶光标在闪。
  if (峰值) 图.fillStyle(规.色.底, 1).fillRect(光标 + 2, 带顶 + 2, 砖高 - 4, 砖高 - 4);
}

/** 节拍暗底相对共享「节拍压暗」的倍数：四色 LCD 需要更实的暗场才压得住彩色棋盘。 */
const 节拍压暗倍数 = 2.6;

function 绘制节拍底纹(图: 图形对象, 参数: 节拍底纹参数): void {
  const { 宽, 高, 模式色, 显 } = 参数;
  const 强 = Number.isFinite(显) ? Math.min(1, Math.max(0, 显)) : 0;
  if (强 <= 0) return;
  const 中央 = Math.round(高 / 2);

  // 点阵暗底：整屏压一层墨，Ready/Go 落在 LCD 点阵的暗场上。
  图.fillStyle(规.色.墨, 入场参数.颜色.节拍压暗 * 节拍压暗倍数 * 强).fillRect(0, 0, 宽, 高);

  // 扫描行：中线上下每 8px 一条，越靠外越淡。
  const 行数 = Math.min(8, Math.floor(高 / 2 / 砖高));
  for (let 行 = 1; 行 <= 行数; 行 += 1) {
    const 透明 = 0.28 * 强 * (1 - 行 / (行数 + 1));
    const y = 中央 + 行 * 砖高;
    图
      .fillStyle(规.色.暗, 透明)
      .fillRect(0, y, 宽, 1)
      .fillRect(0, 中央 - 行 * 砖高, 宽, 1);
  }

  // 点阵小块：两行错峰的点，给底纹液晶点阵的方向感。
  for (let 行 = 0; 行 < 2; 行 += 1) {
    const y = 中央 + (30 + 行 * 砖高 * 2);
    const 偏移 = 行错峰(行) * 砖高;
    for (let x = 偏移; x < 宽; x += 砖高 * 5) {
      图.fillStyle(规.色.暗, 0.5 * 强).fillRect(x, y, 砖高 / 2, 砖高 / 2);
    }
  }

  // 模式色小块：中线下方一条短横与两侧方格，只作模式强调。
  图.fillStyle(模式色, 0.9 * 强).fillRect(宽 / 2 - 18, 中央 + 34, 36, 2);
  图
    .fillStyle(模式色, 0.55 * 强)
    .fillRect(宽 / 2 - 30, 中央 + 33, 6, 4)
    .fillRect(宽 / 2 + 24, 中央 + 33, 6, 4);
}

export const 液晶画法: 转场画法 = { 绘制幕面, 绘制接缝, 绘制节拍底纹 };

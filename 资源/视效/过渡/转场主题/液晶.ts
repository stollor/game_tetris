import type { 图形对象, 矩形 } from "../../../../.gamemaker/依赖/框架/界面/绘制/协议";
import { 按名称取像素规范 } from "../../../主题/像素/像素规范";
import { 夹进度 } from "../入场参数";
import type { 节拍底纹参数, 转场帧, 转场画法 } from "./类型";

/**
 * 砖机液晶的转场：CRT 关机 / 开机语汇，4px 点阵、四色、8 档量化。
 *
 * 收束（0→1）：选中的模式卡先在原位像素化（4px 点阵行由实到碎），点阵行按行向中线塌陷，
 * 压成一条横贯全屏的 8px 亮扫描线；扫描线再向上下按 8 档量化逐行铺满点阵幕。
 * 展开（1→0）：点阵幕从外缘向中线逐行退回，新画面一行行被刷出来，0.62 秒内露完。
 *
 * 颜色只读冻结的「砖机液晶」像素规范（不用绘制期活规范）；点阵幕始终不透明；
 * 一帧图元最多约 130 个（整屏扫描带 = 1 块墨底 + 106 条点阵行 + 前沿强调），低于 200 预算。
 */
const 规 = 按名称取像素规范("砖机液晶");
const 网格 = 规.网格;
const 色 = 规.色;

/** 卡片像素化占收束前 34%，之后才是「压线 → 铺满点阵幕」。 */
export const 液晶卡片占比 = 0.34;
/** 8 档铺满只占扫描段前 85%，剩下的是关机黑场：切页前整屏必须盖住，包括货币角标。 */
const 铺满占比 = 0.85;

/** 亮扫描线高 8px：两块 4px 点阵行叠起来，正好一个液晶块。 */
const 扫描线高 = 网格 * 2;
/** 点阵幕行距 8px：4px 点阵行 + 4px 暗缝。 */
const 点距 = 网格 * 2;

/** 半屏能排下的 4px 行数；展开逐行点亮以此为准。 */
function 半行数(高: number): number {
  return Math.max(1, Math.round(高 / 2 / 网格));
}

/**
 * 收束扫描段的 8 档覆盖度：把线性进度量化到 1/8 步进，端点精确。
 * 输入：扫描段内进度 0..1；输出：0、1/8 … 1 的离散值——CRT 是跳着亮的，不做平滑渐变。
 * 量化向上取整、且只用扫描段前 85% 走完 8 档，所以收束 0.9s 起整屏已经盖满。
 */
export function 量化覆盖度(进度: number): number {
  const 夹 = 夹进度(进度);
  if (夹 >= 1) return 1;
  return Math.min(1, Math.ceil((夹 / 铺满占比) * 8) / 8);
}

/**
 * 展开时每侧已点亮的行数（4px 一行，从中线往外）。
 * 输入：屏高、展开进度 0..1；输出：0..半行数 的整数；进度 1 时等于半行数（新画面完全露出）。
 */
export function 点亮行(高: number, 进度: number): number {
  const 总 = 半行数(高);
  const 夹 = 夹进度(进度);
  if (夹 >= 1) return 总;
  return Math.min(总, Math.floor(总 * 夹));
}

/**
 * 一条扫描带里的点阵行数（带高按 8px 行距铺 4px 点阵行）。
 * 输入：带高 px；输出：行数——用于核对单帧图元预算，不参与绘制。
 */
export function 扫描行(带高: number): number {
  if (!(带高 > 0)) return 0;
  return Math.max(0, Math.floor((带高 - 网格) / 点距) + 1);
}

/** 相位内进度 → 整屏覆盖度 0..1。收束前 34% 只像素化卡片，点阵幕还没出现。 */
function 读取覆盖度(帧: 转场帧): number {
  if (帧.阶段 === "收束") {
    if (帧.进度 <= 液晶卡片占比) return 0;
    return 量化覆盖度((帧.进度 - 液晶卡片占比) / (1 - 液晶卡片占比));
  }
  return 1 - 点亮行(帧.高, 帧.进度) / 半行数(帧.高);
}

/**
 * 点阵幕每侧盖住的厚度，4px 对齐；收束与展开共用同一套几何。
 * 收束：幕从中线向上下长厚；展开：幕从外缘向中线变薄——语义都是「每侧盖住多少」。
 */
function 幕厚度(帧: 转场帧): number {
  const 覆盖 = 读取覆盖度(帧);
  const 半 = 帧.高 / 2;
  if (覆盖 >= 1) return 半;
  if (覆盖 <= 0) return 0;
  return Math.min(半, Math.round((半 * 覆盖) / 网格) * 网格);
}

/** 画一条点阵扫描带：墨底铺满（遮罩必须不透明），再压 4px 点阵行。 */
function 画扫描带(图: 图形对象, 宽: number, 上: number, 下: number): void {
  const 带高 = 下 - 上;
  if (带高 <= 0) return;
  const 行数 = 扫描行(带高);
  // 墨底一次铺满（遮罩必须不透明），点阵行按颜色分两批画：fillStyle 只设两次，图元预算才够。
  图.fillStyle(色.墨, 1).fillRect(0, 上, 宽, 带高);
  图.fillStyle(色.暗, 1);
  for (let 序 = 0; 序 < 行数; 序 += 1) {
    if (序 % 4 === 3) continue;
    图.fillRect(0, 上 + 序 * 点距, 宽, 网格);
  }
  // 每第四条提亮成刷新线，幕面才有层次而不是纯黑。
  图.fillStyle(色.亮, 1);
  for (let 序 = 3; 序 < 行数; 序 += 4) 图.fillRect(0, 上 + 序 * 点距, 宽, 网格);
}

/** 每条的错峰系数；固定表而不是随机，同一帧反复重绘才能完全复现。 */
const 错峰 = [0.13, 0.61, 0.37, 0.82, 0.05, 0.49, 0.71, 0.26];

/**
 * 卡片像素化的形状：卡面按 4px 切成一行行（由实到碎），两端崩出 4px 碎点。
 * 输入：原卡矩形（可空）、屏宽高、收束进度 0..1；输出：本帧要画的点阵行与碎点，全部 4px 网格对齐。
 * 进度到卡片占比时返回空——卡已经压成中线扫描线，交给亮线画法。
 */
export function 卡片碎片(
  原卡: 矩形 | null,
  宽: number,
  高: number,
  进度: number,
): { 横条: 矩形[]; 点块: 矩形[]; 可见: boolean } {
  const t = 夹进度(进度 / 液晶卡片占比);
  if (t >= 1) return { 横条: [], 点块: [], 可见: false };
  // 没有原卡的入口从屏中一小块卡面出发，塌陷过程才不会突然凭空出现整条线。
  const 起 = 原卡 ?? {
    左: 宽 * 0.22,
    上: 高 / 2 - 网格 * 12,
    宽: 宽 * 0.56,
    高: 网格 * 24,
  };
  const 缓 = t * t * (3 - 2 * t);
  const 左 = 起.左 * (1 - 缓);
  const 宽值 = 起.宽 + (宽 - 起.宽) * 缓;
  const 上 = 起.上 + (高 / 2 - 扫描线高 / 2 - 起.上) * 缓;
  const 高值 = 起.高 + (扫描线高 - 起.高) * 缓;
  // 4px 点阵行：卡面按 4px 切成一行一行，塌陷时行数跟着变少，压成线时只剩两行。
  const 条数 = Math.max(1, Math.min(24, Math.round(高值 / 网格)));
  const 条高 = 高值 / 条数;
  const 横条: 矩形[] = [];
  const 点块: 矩形[] = [];
  for (let 序 = 0; 序 < 条数; 序 += 1) {
    const 抖 = 错峰[序 % 错峰.length] * 0.65 + 错峰[(序 * 5 + 3) % 错峰.length] * 0.35;
    // 由实到碎：抖得厉害的行先断开，卡面从整块裂成一排排点阵行。
    if (t > 0.26 && 抖 < (t - 0.26) * 0.9) continue;
    const 缩进 = Math.round((宽值 * 0.16 * t * (0.3 + 抖)) / 网格) * 网格;
    const 行左 = Math.round((左 + 缩进) / 网格) * 网格;
    const 行宽 = Math.max(网格, Math.round((宽值 - 缩进 * 2) / 网格) * 网格);
    const 行上 = Math.round((上 + 序 * 条高) / 网格) * 网格;
    const 行高 = Math.max(网格, Math.round(条高 / 网格) * 网格);
    if (t > 0.45 && 抖 > 0.55) {
      // 塌陷中段断成两截：卡面越往后越像断开的点阵，而不是整块板。
      const 断 = 点距 * 2;
      const 左段 = Math.max(网格, Math.round((行宽 * 0.45) / 网格) * 网格);
      横条.push({ 左: 行左, 上: 行上, 宽: 左段, 高: 行高 });
      横条.push({
        左: 行左 + 左段 + 断,
        上: 行上,
        宽: Math.max(网格, 行宽 - 左段 - 断),
        高: 行高,
      });
    } else {
      横条.push({ 左: 行左, 上: 行上, 宽: 行宽, 高: 行高 });
    }
    // 碎点：亮色 4px 块从行尾崩出来，卡面「像素化」全靠这一层被看见。
    if (t > 0.3 && 抖 > 0.52) 点块.push({ 左: 行左 + 行宽 + 网格, 上: 行上, 宽: 网格, 高: 网格 });
    if (t > 0.46 && 抖 < 0.3) 点块.push({ 左: 行左 - 点距, 上: 行上, 宽: 网格, 高: 网格 });
    if (t > 0.6) {
      const 内点 = Math.round((行左 + 行宽 * (0.3 + 抖 * 0.5)) / 网格) * 网格;
      点块.push({ 左: 内点, 上: 行上, 宽: 网格, 高: 网格 });
    }
  }
  return { 横条, 点块, 可见: 横条.length > 0 };
}

/** 卡片段：卡面像素化并塌向中线，只在收束前 34% 画。 */
function 绘制卡片段(图: 图形对象, 帧: 转场帧): void {
  const 碎 = 卡片碎片(帧.原卡, 帧.宽, 帧.高, 帧.进度);
  if (!碎.可见) return;
  图.fillStyle(色.墨, 1);
  for (const 条 of 碎.横条) 图.fillRect(条.左, 条.上, 条.宽, 条.高);
  图.fillStyle(色.底, 1);
  for (const 点 of 碎.点块) 图.fillRect(点.左, 点.上, 点.宽, 点.高);
}

function 绘制遮罩(图: 图形对象, 帧: 转场帧): void {
  const { 宽, 高 } = 帧;
  if (帧.阶段 === "收束" && 帧.进度 < 液晶卡片占比) 绘制卡片段(图, 帧);
  const 覆盖 = 读取覆盖度(帧);
  // 接力点（收束 1 / 展开 0）都走「整屏一条带」这一支：两阶段的绘制调用必须逐条相同。
  if (覆盖 >= 1) {
    画扫描带(图, 宽, 0, 高);
    return;
  }
  if (覆盖 <= 0) return;
  const 半 = 高 / 2;
  const 厚 = 幕厚度(帧);
  if (帧.阶段 === "收束") {
    // 关机：亮扫描线从中线向上下长厚，直到吞掉整屏。
    画扫描带(图, 宽, 半 - 厚, 半 + 厚);
    return;
  }
  // 开机：幕退到上下外缘，中间露出新画面；退幕边缘就是新画面被刷出来的前沿。
  画扫描带(图, 宽, 0, 厚);
  画扫描带(图, 宽, 高 - 厚, 高);
}

/**
 * 扫描前沿：在幕的边缘压一条亮点阵行，再往里错位撒 4px 点。
 * 关机时它跟着幕向外扫，开机时它跟着幕向内退——两段的边缘都不会是一条死直线。
 */
function 画前沿(
  图: 图形对象,
  宽: number,
  高: number,
  行上: number,
  强度: number,
  向里: -1 | 1,
): void {
  if (行上 < 0 || 行上 + 网格 > 高) return;
  图.fillStyle(色.底, 强度);
  图.fillRect(0, 行上, 宽, 网格);
  const 格宽 = 宽 / 8;
  for (let 序 = 0; 序 < 8; 序 += 1) {
    const 跳 = 序 % 2 === 0 ? 点距 : 点距 + 网格;
    const 点上 = 行上 + 向里 * 跳;
    if (点上 < 0 || 点上 + 网格 > 高) continue;
    图.fillRect(序 * 格宽, 点上, 格宽, 网格);
  }
}

/** 中线 CRT 束：卡片塌陷的落点，也是展开时新画面从中线裂开的起点。 */
function 绘制强调(图: 图形对象, 帧: 转场帧): void {
  const { 宽, 高 } = 帧;
  const 强度 = 帧.阶段 === "收束" ? 夹进度(帧.进度 / 液晶卡片占比) : 1 - 夹进度(帧.进度 / 0.4);
  if (强度 <= 0.01) return;
  // 收束时这条线由卡宽长到全宽；展开时保持全宽再淡出，接缝两侧都是它。
  const 长 = 帧.阶段 === "收束" ? 宽 * 强度 : 宽;
  const 左 = (宽 - 长) / 2;
  const 上 = 高 / 2 - 扫描线高 / 2;
  图.fillStyle(色.底, 强度).fillRect(左, 上, 长, 扫描线高);
  图.fillStyle(色.亮, 强度 * 0.7).fillRect(左, 上 + 扫描线高 - 2, 长, 2);
  const 覆盖 = 读取覆盖度(帧);
  if (覆盖 <= 0 || 覆盖 >= 1) return;
  const 厚 = 幕厚度(帧);
  if (帧.阶段 === "收束") {
    // 关机：前沿贴着幕的上下边缘往外扫。
    画前沿(图, 宽, 高, Math.max(0, 高 / 2 - 厚), 强度, 1);
    画前沿(图, 宽, 高, Math.min(高 - 网格, 高 / 2 + 厚 - 网格), 强度, -1);
    return;
  }
  // 开机：前沿就是上下两块幕的内边缘。
  画前沿(图, 宽, 高, Math.max(0, 厚 - 网格), 强度, -1);
  画前沿(图, 宽, 高, Math.min(高 - 网格, 高 - 厚), 强度, 1);
}

/** Ready/Go 底纹：点阵暗底 + 扫描行 + 模式色小块，画在文字之下。 */
function 绘制节拍底纹(图: 图形对象, 参数: 节拍底纹参数): void {
  const { 宽, 高, 模式色, 显 } = 参数;
  if (显 <= 0) return;
  图.fillStyle(色.暗, 0.72 * 显).fillRect(0, 0, 宽, 高);
  // 扫描行只铺文字上下一条横带，整屏铺要 100+ 条，图元花得没必要。
  const 带上 = 高 / 2 - 高 * 0.17;
  const 带高 = 高 * 0.34;
  图.fillStyle(色.亮, 0.26 * 显).fillRect(0, 带上, 宽, 带高);
  图.fillStyle(色.底, 0.3 * 显);
  for (let y = 带上; y + 网格 <= 带上 + 带高; y += 点距) 图.fillRect(0, y, 宽, 网格);
  // 模式色小块：模式色落在四色里可能偏暗，先垫一条亮点线保证可读。
  const 块宽 = Math.min(宽 * 0.18, 64);
  const 块左 = 宽 / 2 - 块宽 / 2;
  const 块上 = 高 / 2 + 高 * 0.1;
  图.fillStyle(色.底, 0.7 * 显).fillRect(块左, 块上, 块宽, 网格);
  图.fillStyle(模式色, 0.9 * 显).fillRect(块左 + 网格, 块上 - 点距, 块宽 - 点距, 扫描线高);
}

/** 覆盖比：点阵幕盖住屏高的比例。收束 0→1、展开 1→0，接力点由「整屏」这一支保证等于 1。 */
function 覆盖比(帧: 转场帧): number {
  const 覆盖 = 读取覆盖度(帧);
  if (覆盖 >= 1) return 1;
  if (覆盖 <= 0) return 0;
  return Math.min(1, (幕厚度(帧) * 2) / Math.max(1, 帧.高));
}

export const 液晶画法: 转场画法 = { 覆盖比, 绘制遮罩, 绘制强调, 绘制节拍底纹 };

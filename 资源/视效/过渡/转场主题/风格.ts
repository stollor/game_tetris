import type { 主题解析结果 } from "../../../../.gamemaker/依赖/框架/设置/主题组合";
import { 按名称取像素规范 } from "../../../主题/像素/像素规范";
import { 读取当前主题解析 } from "../../../主题/配色/主题读取";
import type { 转场主题 } from "./类型";

/**
 * 主题槽位 → 转场风格。判据与背景/像素特效一致：
 * - 界面表现=糖果/立体 直接决定软糖与机架语汇；
 * - 界面表现=像素 时再看界面配色选中的像素规范，区分四色液晶与七色彩砖；
 * - 其余（霓虹玻璃）走极光。
 */
export function 解析转场风格(解析: 主题解析结果): 转场主题 {
  const 槽 = (编号: string) => 解析.槽位.find((项) => 项.槽位.编号 === 编号)?.资源.值 ?? null;
  const 表现 = 槽("界面表现");
  if (表现 === "糖果") return "糖果";
  if (表现 === "立体") return "立体";
  if (表现 === "像素")
    return 按名称取像素规范(槽("界面配色")).名称 === "街机彩砖" ? "彩砖" : "液晶";
  return "极光";
}

/** 当前玩家主题（含商店整页试穿）对应的转场风格。 */
export function 读取转场风格(): 转场主题 {
  return 解析转场风格(读取当前主题解析());
}

import type { 图形对象, 矩形 } from "../../../../.gamemaker/依赖/框架/界面/绘制/协议";
import { 亮色, 暗色, 混色 } from "../../../../.gamemaker/依赖/框架/界面/颜色工具";
import { 按名称取像素规范 } from "../../../主题/像素/像素规范";
import { 夹进度 } from "../入场参数";
import type { 节拍底纹参数, 转场帧, 转场画法 } from "./类型";

/**
 * 街机彩砖的转场：不压线、不上下拉幕，整段演出是一面「砖墙」。
 *
 * 收束：选中的模式卡先原地碎成 2:1 的七色砖块（用 `原卡`，不会一上来整屏遮住），
 *       随后砖墙从卡片位置向四周砌开 —— 离卡越近的砖越早落位，落砖带 1~2px 回弹，
 *       行与行错峰；砌满后深底兜住砖缝，整片不透明。
 * 展开：整面砖墙从屏幕四边向中心逐块压暗、坠落、消失，0.62 秒内退干净，露出新画面。
 *
 * 覆盖比按砖块面积加权推导（见 `砖墙覆盖比`），所以两阶段的进度与真实盖住多少严格对应；
 * 接力点（收束 1 / 展开 0）两块砖的可见度、偏移、压暗都是同一个满值，绘制调用逐条一致，
 * 跨页切页那一帧不会露馅。
 */

const 规 = 按名称取像素规范("街机彩砖");
/** 七色砖料：红黄绿蓝紫青橙，取具体规范而不是绘制期活规范，五主题同屏试穿也不会拿错色盘。 */
const 七色: readonly number[] = [
  规.色.红,
  规.色.黄,
  规.色.绿,
  规.色.蓝,
  规.色.紫,
  规.色.青,
  规.色.橙,
];
/** 深底：砖缝、还没砌到的行都由它兜住，遮罩必须不透明。 */
const 深底 = 规.色.远;
/** 卡面底色：比深底亮一档，卡片碎开前还能看出是「一张卡」。 */
const 卡面 = 规.色.夜;

/** 砖缝宽度（逻辑像素）：砖与砖之间露出的深底宽度。 */
export const 砖缝 = 2;
/** 单帧图元预算：砖块一多就整体放大砖形，绝不按像素格子砌。 */
export const 单帧图元预算 = 200;
/** 收束里卡片碎砖所占的进度：在这之前只有卡片阶段，之后砖墙已经盖上来。 */
export const 卡片占比 = 0.36;
/** 卡片开始溶解的进度：砖墙从卡片位置砌上来，卡片同时淡出，两者交叠不会硬切。 */
export const 卡片溶解起 = 0.22;
/** 第一块砖开始落位的进度；收束 0 必须一块都没有（覆盖比 0）。 */
export const 收束起点 = 0.18;
/** 收束扩散占的进度幅：离卡最远的砖在 起点+铺幅 才开始落位。 */
export const 收束铺幅 = 0.6;
/** 收束单砖落位坡：越过延迟后用这么短的坡落定。 */
export const 收束落位坡 = 0.2;
/** 展开单砖熄灭坡：越短砖掉得越干脆。 */
export const 展开落位坡 = 0.4;
/** 展开里最晚熄灭的砖（屏幕正中心）的延迟上限。 */
export const 展开延迟上限 = 0.55;
/** 落砖时砖块抬起的高度（逻辑像素），配合回弹不超过 2px。 */
export const 落砖抬升 = 1.6;
/** 展开时砖块坠落的距离（按砖高倍数）：掉下去时正好让开新画面。 */
const 坠落倍数 = 1.4;

/** 0..1 夹取；非法进度（NaN/Infinity）按 0 处理，画法不接受非有限数。 */
function 夹01(值: number): number {
  return Number.isFinite(值) ? Math.min(1, Math.max(0, 值)) : 0;
}

/** 取正的有限数，给宽高与卡片尺寸兜底。 */
function 正数(值: number, 兜底: number): number {
  return Number.isFinite(值) && 值 > 0 ? 值 : 兜底;
}

/** 行列归一到 0..周期-1：小数按整格取整，负数与超界按周期回绕，非法值按 0。 */
function 归一周期(值: number, 周期: number): number {
  if (!Number.isFinite(值) || 周期 <= 0) return 0;
  return ((Math.floor(值) % 周期) + 周期) % 周期;
}

/** 砖格节距：砖形固定 2:1，只按屏幕预算放大。 */
export interface 砖块节距 {
  砖宽: number;
  砖高: number;
}

/** 一块砖：位置与尺寸已裁到屏幕内；`宽/高` 是砖面，不含右侧与下侧的砖缝。 */
export interface 砖块 {
  左: number;
  上: number;
  宽: number;
  高: number;
  行: number;
  列: number;
  色: number;
}

/** 一行砖：行号从屏幕顶起算，`高` 是这一行占的行高（含底缝）。 */
export interface 砖块行 {
  行: number;
  上: number;
  高: number;
  砖: 砖块[];
}

/** 一块砖在某一帧的落位状态，绘制只读它。 */
export interface 砖块姿态 {
  砖: 砖块;
  /** 0..1 已盖住多少：收束从 0 长到 1，展开从 1 掉到 0。 */
  见: number;
  /** 0..1 实际不透明度：收束半透明浮出再落定，展开随坠落一起淡出。 */
  透明: number;
  /** 纵向偏移：收束落砖回弹、展开坠落。 */
  偏移Y: number;
  /** 0..1 压暗：砖块还没落定或正在坠落时更暗。 */
  压暗: number;
}

/** 整屏砖格数上界（错缝与左右半砖各多算两列），用来卡单帧预算。 */
function 砖格上界(宽: number, 高: number, 节距: 砖块节距): number {
  return (Math.ceil(宽 / 节距.砖宽) + 2) * Math.ceil(高 / 节距.砖高);
}

/**
 * 按屏幕宽高求砖块节距：保持 2:1 砖形，从最小可用砖开始放大，
 * 取第一款让整屏砌满（含每行一块深底）也不超 `单帧图元预算` 的尺寸。
 * 390×844 落在 80×40（砖面 78×38），整屏约 121 块砖。
 */
export function 砖块尺寸(宽: number, 高: number): 砖块节距 {
  const 屏宽 = 正数(宽, 390);
  const 屏高 = 正数(高, 844);
  for (let 砖高 = 12; 砖高 <= 128; 砖高 += 2) {
    const 节距 = { 砖宽: 砖高 * 2, 砖高 };
    const 行数 = Math.ceil(屏高 / 砖高);
    if (砖格上界(屏宽, 屏高, 节距) + 行数 + 10 <= 单帧图元预算) return 节距;
  }
  return { 砖宽: 256, 砖高: 128 };
}

/**
 * 整屏砖墙布局：行从屏幕顶向下排，奇数行右移半块做错缝；
 * 边缘砖按屏幕裁切（会得到半砖），砖面再向里收 `砖缝`，砖缝留给深底。
 */
export function 砖块布局(宽: number, 高: number, 节距?: 砖块节距): 砖块行[] {
  const 屏宽 = 正数(宽, 390);
  const 屏高 = 正数(高, 844);
  const 格 = 节距 ?? 砖块尺寸(屏宽, 屏高);
  const 行列表: 砖块行[] = [];
  const 行数 = Math.ceil(屏高 / 格.砖高);
  for (let 行 = 0; 行 < 行数; 行 += 1) {
    const 上 = 行 * 格.砖高;
    const 行高 = Math.min(格.砖高, 屏高 - 上);
    if (行高 <= 0) break;
    const 面高 = 行高 - 砖缝;
    const 砖: 砖块[] = [];
    if (面高 > 0) {
      const 错缝 = (行 % 2) * (格.砖宽 / 2);
      for (let 列 = -1; 列 * 格.砖宽 - 错缝 < 屏宽; 列 += 1) {
        const 格左 = 列 * 格.砖宽 - 错缝;
        const 左 = Math.max(0, 格左);
        const 右 = Math.min(屏宽, 格左 + 格.砖宽);
        // 屏幕外缘的砖不再收缝，否则最右侧会留一条漏出下面页面的缝。
        const 面宽 = 右 - 左 - (右 >= 屏宽 ? 0 : 砖缝);
        if (面宽 <= 0) continue;
        砖.push({ 左, 上, 宽: 面宽, 高: 面高, 行, 列, 色: 砖块颜色(行, 列) });
      }
    }
    行列表.push({ 行, 上, 高: 行高, 砖 });
  }
  return 行列表;
}

/** 砖色色号：一整行（一皮）共用一个色相，七色按行轮转，整墙按行成带。 */
export function 砖块色号(行: number): number {
  const 行号 = Number.isFinite(行) ? Math.floor(行) : 0;
  return 归一周期(行号, 七色.length);
}

/**
 * 砖面颜色：所在皮向深底压暗，按行列哈希做明暗抖动（同皮里有层次）；
 * 每四块压暗一块，砖墙带街机砖的节奏，不至于糊成一条纯色带。
 */
export function 砖块颜色(行: number, 列: number): number {
  const 行号 = Number.isFinite(行) ? Math.floor(行) : 0;
  const 列号 = Number.isFinite(列) ? Math.floor(列) : 0;
  const 抖 = 归一周期(行号 * 7 + 列号 * 3, 5) * 0.035;
  const 基 = 混色(七色[砖块色号(行号)] ?? 规.色.暗, 深底, 0.26 + 抖);
  return 归一周期(列号, 4) === 3 ? 暗色(基, 0.2) : 基;
}

/** 收束的出发点卡片矩形：没有卡片入口（如直接进对局）时缩成屏幕中心一点。 */
export function 卡片矩形(帧: 转场帧): 矩形 {
  const 宽 = 正数(帧.宽, 1);
  const 高 = 正数(帧.高, 1);
  const 卡 = 帧.原卡;
  if (
    卡 &&
    [卡.左, 卡.上, 卡.宽, 卡.高].every((值) => Number.isFinite(值)) &&
    卡.宽 > 0 &&
    卡.高 > 0
  )
    return { 左: 卡.左, 上: 卡.上, 宽: 卡.宽, 高: 卡.高 };
  return { 左: 宽 / 2 - 1, 上: 高 / 2 - 1, 宽: 2, 高: 2 };
}

/** 砖块中心到卡片的归一距离：卡片内部为 0、屏幕最远角为 1。收束扩散的快慢按它排。 */
export function 离卡距离(帧: 转场帧, 中心X: number, 中心Y: number): number {
  const 宽 = 正数(帧.宽, 1);
  const 高 = 正数(帧.高, 1);
  const 卡 = 卡片矩形(帧);
  const 卡中X = 卡.左 + 卡.宽 / 2;
  const 卡中Y = 卡.上 + 卡.高 / 2;
  const 横 = Math.max(0, Math.abs(中心X - 卡中X) - 卡.宽 / 2);
  const 纵 = Math.max(0, Math.abs(中心Y - 卡中Y) - 卡.高 / 2);
  const 最远 = Math.hypot(Math.max(卡中X, 宽 - 卡中X), Math.max(卡中Y, 高 - 卡中Y));
  if (!(最远 > 0)) return 0;
  return 夹01(Math.hypot(横, 纵) / 最远);
}

/** 砖块中心到最近屏幕边的归一距离：贴边 0、屏幕中心 1。展开时贴边的先掉。 */
export function 离边距离(帧: 转场帧, 中心X: number, 中心Y: number): number {
  const 宽 = 正数(帧.宽, 1);
  const 高 = 正数(帧.高, 1);
  const 半 = Math.max(1, Math.min(宽, 高) / 2);
  return 夹01(Math.min(中心X, 宽 - 中心X, 中心Y, 高 - 中心Y) / 半);
}

/**
 * 行错峰：整行同相位，行与行错开 ±0.01。
 * 行内不抖动，保证同一行里已落位的砖始终是连续一段，深底只铺这一段就不会漏底。
 */
function 行错峰(行: number): number {
  return (归一周期(行 * 5, 7) - 3) * 0.01;
}

/** 收束逐块延迟：离卡越远越晚落位，行间再错峰，砖墙从卡片位置向外砌开。 */
export function 收束延迟(帧: 转场帧, 砖: 砖块): number {
  const 距 = 夹01(离卡距离(帧, 砖.左 + 砖.宽 / 2, 砖.上 + 砖.高 / 2) + 行错峰(砖.行));
  return 收束起点 + 收束铺幅 * 距;
}

/** 展开逐块延迟：贴边先熄灭、屏幕中心最晚，四边同时向中心收。 */
export function 展开延迟(帧: 转场帧, 砖: 砖块): number {
  const 距 = 夹01(离边距离(帧, 砖.左 + 砖.宽 / 2, 砖.上 + 砖.高 / 2) + 行错峰(砖.行) * 0.5);
  return 展开延迟上限 * 距;
}

/**
 * 一块砖的可见度：收束单调涨到 1、展开单调退到 0。
 * 两端都夹在 0..1，接力点（收束 1 / 展开 0）两边都恰好是 1。
 */
export function 砖块可见度(帧: 转场帧, 砖: 砖块): number {
  const 进度 = 夹01(帧.进度);
  if (帧.阶段 === "收束") return 夹01((进度 - 收束延迟(帧, 砖)) / 收束落位坡);
  return 1 - 夹01((进度 - 展开延迟(帧, 砖)) / 展开落位坡);
}

/**
 * 落砖偏移：未落定时抬起，落地时越过 1~2px 再回弹，落定精确归零。
 * 只挪砖本身，不动行距，所以砖缝宽度始终稳定。
 */
export function 落砖偏移(见: number): number {
  const t = 夹01(见);
  if (t >= 1) return 0;
  return -落砖抬升 * (1 - t) ** 2 + Math.sin(t * Math.PI) * 0.6;
}

/** 一块砖在当前帧的姿态：收束先压暗再落定回弹，展开先压暗再坠落。 */
export function 砖块姿态(帧: 转场帧, 砖: 砖块): 砖块姿态 {
  const 见 = 砖块可见度(帧, 砖);
  const 压暗 = 0.42 * (1 - 见);
  if (帧.阶段 === "收束")
    // 收束的砖一出现就先露半张脸再落定，前沿不会糊成一条黑带；接力点仍是精确的 1。
    return { 砖, 见, 透明: 见 >= 1 ? 1 : 0.5 + 0.5 * 见, 偏移Y: 落砖偏移(见), 压暗 };
  return { 砖, 见, 透明: 见, 偏移Y: 砖.高 * 坠落倍数 * (1 - 见) ** 2, 压暗 };
}

/** 覆盖比推导：已见砖面面积 / 整墙砖面面积。收束 0→1、展开 1→0，两端精确到 0 与 1。 */
export function 砖墙覆盖比(帧: 转场帧): number {
  const 行列表 = 砖块布局(帧.宽, 帧.高);
  let 已盖 = 0;
  let 满铺 = 0;
  for (const 行 of 行列表) {
    for (const 砖 of 行.砖) {
      const 面积 = 砖.宽 * 砖.高;
      已盖 += 面积 * 砖块可见度(帧, 砖);
      满铺 += 面积;
    }
  }
  return 满铺 > 0 ? 夹01(已盖 / 满铺) : 0;
}

/** 卡片显示度：砖墙从卡片位置砌上来时，卡片同步淡出。 */
export function 卡片显示度(进度: number): number {
  const 幅 = Math.max(0.01, 卡片占比 - 卡片溶解起);
  return 1 - 夹进度((夹01(进度) - 卡片溶解起) / 幅);
}

/** 一块砖的砖面：顶亮底暗的纵向渐变；`透明` 管出现/坠落，`压暗` 管落定前的暗度。 */
function 绘制砖面(图: 图形对象, 姿态: 砖块姿态): void {
  const { 砖, 透明, 偏移Y, 压暗 } = 姿态;
  const 基 = 压暗 > 0 ? 混色(砖.色, 深底, 压暗) : 砖.色;
  const 上色 = 亮色(基, 0.16);
  const 下色 = 暗色(基, 0.26);
  图
    .fillGradientStyle(上色, 上色, 下色, 下色, 透明, 透明, 透明, 透明)
    .fillRect(砖.左, 砖.上 + 偏移Y, 砖.宽, 砖.高);
}

/**
 * 卡片阶段的碎卡：把 `原卡` 原位切成 2:1 的七色砖块，砖色按行成带，
 * 与整墙同一套语汇 —— 这张卡看起来就是接下来那面砖墙的一小块。
 * 尺寸按预算自适（最多 8 行），大卡片也不会爆图元。
 */
function 绘制碎卡(图: 图形对象, 帧: 转场帧): void {
  const 显 = 卡片显示度(帧.进度);
  if (显 <= 0.02) return;
  const 卡 = 卡片矩形(帧);
  const 卡宽 = 正数(卡.宽, 0);
  const 卡高 = 正数(卡.高, 0);
  if (卡宽 <= 0 || 卡高 <= 0) return;
  // 碎砖行数按卡高估（约 24px 一层），砖形保持 2:1
  const 行数 = Math.max(1, Math.min(8, Math.round(卡高 / 24)));
  const 砖高 = 卡高 / 行数;
  const 砖宽 = 砖高 * 2;
  const 列数 = Math.max(1, Math.min(16, Math.ceil(卡宽 / 砖宽)));
  图.fillStyle(卡面, 显).fillRoundedRect(卡.左, 卡.上, 卡宽, 卡高, 8);
  for (let 行 = 0; 行 < 行数; 行 += 1) {
    const 上 = 卡.上 + 行 * 砖高;
    const 面高 = Math.min(砖高, 卡高 - 行 * 砖高) - 砖缝;
    if (面高 <= 0) continue;
    const 色 = 混色(七色[砖块色号(行)] ?? 规.色.亮, 深底, 0.2);
    for (let 列 = 0; 列 < 列数; 列 += 1) {
      const 左 = 卡.左 + 列 * 砖宽;
      const 面宽 = Math.min(砖宽, 卡宽 - 列 * 砖宽) - 砖缝;
      if (面宽 <= 0) continue;
      图.fillStyle(色, 显).fillRect(左, 上, 面宽, 面高);
    }
  }
}

/**
 * 遮罩：逐行「深底 + 砖块」。深底只铺这一行已经见到的砖的范围，
 * 所以砖缝永远是深底、整片已盖区域不透明，而还没砌到的地方仍然露出下面的页面。
 */
function 绘制遮罩(图: 图形对象, 帧: 转场帧): void {
  const 宽 = 正数(帧.宽, 1);
  const 高 = 正数(帧.高, 1);
  for (const 行 of 砖块布局(宽, 高)) {
    const 姿态 = 行.砖.map((砖) => 砖块姿态(帧, 砖)).filter((项) => 项.见 > 0);
    const 首 = 姿态[0];
    const 末 = 姿态.at(-1);
    if (!首 || !末) continue;
    const 左 = 首.砖.左;
    // 深底右端多让一条砖缝：砖面只收到缝内，最右一块的缝也得由深底兜住。
    const 右 = Math.min(宽, 末.砖.左 + 末.砖.宽 + 砖缝);
    图.fillStyle(深底, 1).fillRect(左, 行.上, 右 - 左, 行.高);
    for (const 项 of 姿态) 绘制砖面(图, 项);
  }
  // 卡片阶段只盖卡片本身：碎片从卡片矩形长出来，别一上来整屏遮住。
  if (帧.阶段 === "收束" && 夹01(帧.进度) < 卡片占比) 绘制碎卡(图, 帧);
}

/**
 * 强调：卡片阶段给模式色描边（一眼看出是选中的那张卡）；
 * 扩散/展开阶段在上下缘压一排街机灯条，中段最亮、两端归零，跨页接缝不残留。
 */
function 绘制强调(图: 图形对象, 帧: 转场帧): void {
  const 宽 = 正数(帧.宽, 1);
  const 高 = 正数(帧.高, 1);
  const 进度 = 夹01(帧.进度);
  const 模式色 = Number.isFinite(帧.模式色) ? 帧.模式色 : 规.色.亮;
  if (帧.阶段 === "收束" && 进度 < 卡片占比) {
    const 显 = 卡片显示度(进度);
    if (显 <= 0.02) return;
    const 卡 = 卡片矩形(帧);
    图
      .lineStyle(2, 亮色(模式色, 0.3), 显)
      .strokeRoundedRect(卡.左, 卡.上, 正数(卡.宽, 1), 正数(卡.高, 1), 8);
    return;
  }
  const 强度 = Math.sin(Math.PI * 进度);
  if (强度 < 0.02) return;
  const 段宽 = 宽 / 七色.length;
  for (let 序 = 0; 序 < 七色.length; 序 += 1) {
    const 色 = 七色[序] ?? 规.色.亮;
    const 亮 = 强度 * (0.6 + 0.4 * (序 % 2));
    图.fillStyle(色, 0.5 * 亮).fillRect(序 * 段宽, 0, Math.max(1, 段宽 - 1), 3);
    图.fillStyle(色, 0.5 * 亮).fillRect(序 * 段宽, 高 - 3, Math.max(1, 段宽 - 1), 3);
  }
}

/** Ready/Go 底纹：深底压屏 + 中央上下两组七色灯条 + 上下缘七色点阵，像街机台面的灯板。 */
function 绘制节拍底纹(图: 图形对象, 参数: 节拍底纹参数): void {
  const 显 = 夹01(参数.显);
  if (显 <= 0) return;
  const 宽 = 正数(参数.宽, 1);
  const 高 = 正数(参数.高, 1);
  图.fillStyle(卡面, 0.52 * 显).fillRect(0, 0, 宽, 高);
  const 中 = 高 / 2;
  const 条宽 = Math.round(宽 * 0.46);
  const 条左 = Math.round((宽 - 条宽) / 2);
  for (let 序 = 0; 序 < 七色.length; 序 += 1) {
    const 色 = 七色[序] ?? 规.色.亮;
    图.fillStyle(色, 0.62 * 显).fillRect(条左, 中 - 78 - 序 * 5, 条宽, 2);
    图.fillStyle(色, 0.62 * 显).fillRect(条左, 中 + 64 + 序 * 5, 条宽, 2);
  }
  const 点距 = 20;
  const 点数 = Math.max(1, Math.floor(宽 / 点距));
  const 起X = (宽 - (点数 - 1) * 点距) / 2;
  for (let 序 = 0; 序 < 点数; 序 += 1) {
    const 色 = 七色[序 % 七色.length] ?? 规.色.亮;
    const x = 起X + 序 * 点距 - 3;
    图.fillStyle(色, 0.3 * 显).fillRect(x, 8, 6, 6);
    图.fillStyle(色, 0.3 * 显).fillRect(x, 高 - 14, 6, 6);
  }
}


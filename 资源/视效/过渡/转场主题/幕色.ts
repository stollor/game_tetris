import { 混色 } from "../../../../.gamemaker/依赖/框架/界面/颜色工具";
import type { 游戏模式 } from "../../../../代码/玩法/再消一行";
import { 模式主题色 } from "../../../主题/配色/模式配色";
import { 入场参数 } from "../入场参数";

/**
 * 极光幕色：幕外深、幕内浅，两者只按模式色轻度染色（0.1）。
 * 模式色在幕布上只能是强调，不能把整块幕布染成模式色 —— 那是转场主题化之前的做法。
 */
export function 读取幕色(模式色: number): { 外: number; 内: number } {
  const 色 = 入场参数.颜色;
  return {
    外: 混色(色.幕外, 模式色, 色.主题染色),
    内: 混色(色.幕内, 模式色, 色.主题染色),
  };
}

/** 按模式取极光幕色；页面与验收只传模式，不自己拼颜色。 */
export function 读取入场幕色(模式: 游戏模式): { 外: number; 内: number } {
  return 读取幕色(模式主题色(模式));
}

import type { 图形对象, 点 } from "../../../../.gamemaker/依赖/框架/界面/绘制/协议";
import { 亮色, 暗色, 混色 } from "../../../../.gamemaker/依赖/框架/界面/颜色工具";
import { 糖果规范 } from "../../../主题/糖果/糖果规范";
import { 绘制糖钉 } from "../../../预制体/基础/装饰与蒙层/糖果质感";
import { 夹进度 } from "../入场参数";
import type { 幕面参数, 接缝参数, 节拍底纹参数, 转场画法 } from "./类型";

/**
 * 「糖果超甜」的转场画法：上下两片软糖幕合拢，缝边一圈奶油裱花扇贝，
 * 合拢后接缝留下一条草莓糖浆条，Ready/Go 背后铺奶油光晕与粉色糖牌。
 *
 * 语汇与糖果面板/背景共用一套：颜色、圆角、花边、描边只取 `糖果规范`，
 * 深浅只走 `混色`/`亮色`/`暗色` 派生，不在这里留字面色值；
 * 时间轴只读 `入场参数` 的派生量（覆盖度/强度），不自己数秒、不改节拍。
 */
const 规 = 糖果规范;
const 花 = 规.花边;
const 描 = 规.描边;

/** 幕的朝向：上幕盖住上半屏，下幕盖住下半屏；接缝分别是它们的内侧边。 */
type 幕朝向 = "上" | "下";

/**
 * 一排奶油裱花的圆心 X（逻辑像素）。
 * 颗数按 `花边.步长` 取整、余量均摊到间距（间距大于两倍半径，颗与颗才咬得开），
 * 两端各留半颗，扇贝不会半颗挂在屏幕边上。返回长度就是这一排要画的颗数。
 */
export function 裱花圆心(宽: number): number[] {
  const 有效宽 = Math.max(0, 宽);
  if (有效宽 <= 0) return [];
  const 颗数 = Math.max(1, Math.floor(有效宽 / 花.步长));
  const 间距 = 有效宽 / 颗数;
  return Array.from({ length: 颗数 }, (_, 序) => 间距 * (序 + 0.5));
}

/**
 * 软糖回弹：合拢末段的弹性过冲（逻辑像素，0 ~ 1.5）。
 * 覆盖度 0.62 之前是硬糖直落，之后鼓一下再落回 0，收尾时恰好贴住接缝。
 * 它只喂给扇贝半径/位置与高光透明度：接缝由页面给定，移动接缝会和幕布错位。
 */
export function 软糖回弹(覆盖度: number): number {
  if (!Number.isFinite(覆盖度)) return 0;
  const 末段 = 夹进度((覆盖度 - 0.62) / 0.38);
  if (末段 <= 0 || 末段 >= 1) return 0;
  return Math.sin(末段 * Math.PI) * 1.8 * (1 - 末段 * 0.4);
}

/**
 * 糖浆接缝的厚度（逻辑像素）：强度越高越厚，余辉回落时收薄。
 * 基准 10（花边半径 + 内缩）→ 峰值 13（再加一层描边外径），压得住幕布中央的 2px 缝。
 * 强度非有限值时按 0 处理，避免把 NaN 带进绘制参数。
 */
export function 糖浆厚度(强度: number): number {
  const 强 = Number.isFinite(强度) ? 夹进度(强度) : 0;
  return 花.半径 + 花.内缩 + 强 * 描.外;
}

/**
 * 软糖幕的轮廓（局部坐标：y = 0 是外缘，y = 幕高 是接缝边）。
 * 只有外缘两个角是圆的（半径取 `圆角.面板`）：幕布铺满整屏，接缝侧一旦带圆角
 * 就会在缝边啃出缺口、和页面给的缝对不上，所以接缝侧只留一条直边。
 */
export function 软糖幕轮廓(宽: number, 幕高: number): 点[] {
  if (宽 <= 0 || 幕高 <= 0) return [];
  const 内缩 = 描.外;
  const 圆 = Math.max(0, Math.min(规.圆角.面板, 幕高 * 0.9, 宽 / 2 - 内缩));
  const 每角段数 = 6;
  // 按逆时针从接缝左下角起笔：左侧直边 → 左外圆角 → 外缘直边 → 右外圆角 → 右侧直边。
  const 点集: 点[] = [{ x: 内缩, y: 幕高 }];
  if (圆 <= 0.5) {
    点集.push({ x: 内缩, y: 0 }, { x: 宽 - 内缩, y: 0 });
  } else {
    const 左心 = { x: 内缩 + 圆, y: 圆 };
    for (let 段 = 0; 段 <= 每角段数; 段 += 1) {
      const 角 = Math.PI + (段 / 每角段数) * (Math.PI / 2);
      点集.push({ x: 左心.x + Math.cos(角) * 圆, y: 左心.y + Math.sin(角) * 圆 });
    }
    const 右心 = { x: 宽 - 内缩 - 圆, y: 圆 };
    for (let 段 = 0; 段 <= 每角段数; 段 += 1) {
      const 角 = Math.PI * 1.5 + (段 / 每角段数) * (Math.PI / 2);
      点集.push({ x: 右心.x + Math.cos(角) * 圆, y: 右心.y + Math.sin(角) * 圆 });
    }
  }
  点集.push({ x: 宽 - 内缩, y: 幕高 });
  return 点集;
}

/** 一片软糖幕：糖衣面 + 外缘草莓粉高光带 + 接缝侧奶油裱花扇贝。 */
function 绘制软糖幕(
  图: 图形对象,
  宽: number,
  高: number,
  幕高: number,
  朝向: 幕朝向,
  弹: number,
  边线: number,
  模式色: number,
): void {
  const 朝上 = 朝向 === "上";
  const 向 = 朝上 ? 1 : -1; // 从幕内指向缝隙的方向
  const 接缝Y = 朝上 ? 幕高 : 高 - 幕高;
  const 外色 = 规.色.巧克力;
  const 内色 = 混色(规.色.巧克力, 规.色.酒红, 0.7);

  // ① 幕底：整块铺满（含屏幕四角），保证不漏出下面的页面。
  //    软糖面往里收 描边.外，外缘圆角才看得见、接缝侧才是直边。
  图.fillStyle(暗色(规.色.巧克力深, 0.35), 1).fillRect(0, 朝上 ? 0 : 高 - 幕高, 宽, 幕高);

  // ② 糖衣面：外缘亮、接缝侧深的巧克力→酒红渐变，外缘两角软糖圆角。
  const 轮廓 = 软糖幕轮廓(宽, 幕高).map(({ x, y }) => ({ x, y: 朝上 ? y : 高 - y }));
  if (轮廓.length >= 3)
    图
      .fillGradientStyle(
        朝上 ? 外色 : 内色,
        朝上 ? 外色 : 内色,
        朝上 ? 内色 : 外色,
        朝上 ? 内色 : 外色,
      )
      .fillPoints(轮廓, true);

  // ③ 草莓粉高光带：贴外缘的一条圆角软带，朝外浓、朝接缝淡，读作糖衣反光。
  const 边距 = 描.外 + 规.圆角.小 * 0.6;
  const 带宽 = 宽 - 边距 * 2;
  const 带高 = Math.min(幕高 * 0.16, 花.步长 * 0.8);
  if (带宽 > 12 && 带高 >= 2.5) {
    const 带Y = 朝上 ? 边距 : 高 - 边距 - 带高;
    const 闪光 = 混色(规.色.草莓浅, 规.色.粉, 0.5);
    图
      .fillGradientStyle(
        闪光,
        闪光,
        闪光,
        闪光,
        朝上 ? 0.3 : 0,
        朝上 ? 0.3 : 0,
        朝上 ? 0 : 0.3,
        朝上 ? 0 : 0.3,
      )
      .fillRoundedRect(边距, 带Y, 带宽, 带高, 带高 / 2);
  }

  // ④ 接缝侧的奶油裱花：一条暗色背条压出咬缝与贴边阴影，再排一排奶油鼓包。
  const 圆心 = 裱花圆心(宽);
  if (圆心.length > 0) {
    const 间距 = 宽 / 圆心.length;
    const 半径 = Math.max(1.2, Math.min(花.半径, 间距 / 2 - 0.5) + 弹 * 0.4);
    const 圆心Y = 接缝Y + 向 * (弹 - 花.内缩);
    const 背高 = Math.min(半径 + 花.内缩, 幕高);
    图.fillStyle(暗色(规.色.奶油, 0.45), 0.62).fillRect(0, 朝上 ? 接缝Y - 背高 : 接缝Y, 宽, 背高);
    const 线厚 = Math.min(描.高光, 幕高 * 0.2); // 1~2px 的奶油描边，做裱花的根
    图.fillStyle(规.色.奶油, 0.9).fillRect(0, 朝上 ? 接缝Y - 线厚 : 接缝Y, 宽, 线厚);
    图.fillStyle(规.色.奶油, 1);
    for (const x of 圆心) 图.fillCircle(x, 圆心Y, 半径);
    图.fillStyle(亮色(规.色.奶油, 0.26), Math.min(1, 0.9 + 弹 * 0.08));
    for (const x of 圆心) 图.fillCircle(x - 0.4, 圆心Y - 0.7, 半径 * 0.78);
  }

  // ⑤ 边线：模式色只作强调，收束阶段为 0，展开阶段随进度淡出。
  if (边线 > 0)
    图
      .fillStyle(混色(规.色.草莓, 模式色, 0.3), Math.min(1, 0.55 * 边线))
      .fillRect(0, 朝上 ? 接缝Y - 1 : 接缝Y, 宽, 1);
}

function 绘制幕面(图: 图形对象, 参数: 幕面参数): void {
  const { 宽, 高, 缝, 覆盖度, 模式色, 边线 } = 参数;
  if (宽 <= 0 || 高 <= 0) return;
  const 弹 = 软糖回弹(覆盖度);
  if (缝.顶 > 0.5) 绘制软糖幕(图, 宽, 高, 缝.顶, "上", 弹, 边线, 模式色);
  if (高 - 缝.底 > 0.5) 绘制软糖幕(图, 宽, 高, 高 - 缝.底, "下", 弹, 边线, 模式色);
}

function 绘制接缝(图: 图形对象, 参数: 接缝参数): void {
  const { 宽, 高, 模式色, 强度 } = 参数;
  if (宽 <= 0 || 高 <= 0) return;
  const 中Y = 高 / 2; // 接缝中心严格在屏幕中线
  const 厚 = 糖浆厚度(强度);
  const 糖色 = 规.色.草莓;
  const 光色 = 混色(规.色.草莓浅, 模式色, 0.22);

  // ① 糖浆向外发散的光：贴缝最亮、向外淡出；强度越高越亮，余辉阶段收掉。
  if (强度 > 0) {
    const 光高 = 高 * 0.05;
    图
      .fillGradientStyle(光色, 光色, 光色, 光色, 0, 0, 0.2 * 强度, 0.2 * 强度)
      .fillRect(0, 中Y - 厚 / 2 - 光高, 宽, 光高);
    图
      .fillGradientStyle(光色, 光色, 光色, 光色, 0.2 * 强度, 0.2 * 强度, 0, 0)
      .fillRect(0, 中Y + 厚 / 2, 宽, 光高);
  }

  // ② 糖浆条：上亮下深的厚胶囊，两端的圆角交给糖滴盖住。
  图
    .fillGradientStyle(
      规.色.草莓浅,
      规.色.草莓浅,
      混色(糖色, 规.色.草莓深, 0.55),
      混色(糖色, 规.色.草莓深, 0.55),
    )
    .fillRoundedRect(0, 中Y - 厚 / 2, 宽, 厚, 厚 / 2);
  // ③ 奶油高光：贴着上沿的一条亮带。
  图
    .fillStyle(规.色.奶油, 0.72)
    .fillRoundedRect(宽 * 0.05, 中Y - 厚 * 0.34, 宽 * 0.9, 厚 * 0.3, 厚 * 0.15);

  // ④ 两端糖滴：深色垫圈 + 糖身 + 高光点。
  for (const x of [厚 * 0.6, 宽 - 厚 * 0.6]) {
    图.fillStyle(规.色.草莓深, 0.85).fillCircle(x, 中Y, 厚 * 0.85);
    图.fillStyle(糖色, 1).fillCircle(x, 中Y - 0.2, 厚 * 0.7);
    图.fillStyle(规.色.白, 0.6).fillCircle(x - 厚 * 0.22, 中Y - 厚 * 0.3, 厚 * 0.26);
  }
}

function 绘制节拍底纹(图: 图形对象, 参数: 节拍底纹参数): void {
  const { 宽, 高, 模式色, 显 } = 参数;
  if (显 <= 0 || 宽 <= 0 || 高 <= 0) return;
  const 中Y = 高 / 2;
  const 牌宽 = Math.min(宽 * 0.66, 宽 - 规.圆角.面板 * 2);
  const 牌高 = Math.min(高 * 0.13, 规.圆角.面板 * 4.6);
  if (牌宽 <= 0 || 牌高 <= 0) return;
  const 圆角 = Math.min(规.圆角.面板, 牌高 / 2);
  const 牌左 = 宽 / 2 - 牌宽 / 2;
  const 牌上 = 中Y - 牌高 / 2;

  // ① 压暗：巧克力糖底，Ready/Go 的字才读得清。
  图.fillStyle(规.色.巧克力深, 0.3 * 显).fillRect(0, 0, 宽, 高);
  // ② 奶油光晕：四圈由外到内逐级加亮，退场时一起收（分层画才没有硬边圆圈）。
  for (const [半径比, 透明] of [
    [0.52, 0.03],
    [0.4, 0.033],
    [0.28, 0.036],
    [0.16, 0.039],
  ] as const)
    图.fillStyle(规.色.奶油, 透明 * 显).fillCircle(宽 / 2, 中Y, 宽 * 半径比);
  // ③ 粉色糖牌：上亮下深的圆角块，模式色只在光晕里点一下。
  图
    .fillGradientStyle(
      混色(规.色.草莓, 规.色.白, 0.2),
      混色(规.色.草莓, 模式色, 0.18),
      规.色.草莓,
      规.色.草莓,
      0.42 * 显,
      0.42 * 显,
      0.42 * 显,
      0.42 * 显,
    )
    .fillRoundedRect(牌左, 牌上, 牌宽, 牌高, 圆角);
  // ④ 奶油裱花内线。
  图
    .lineStyle(描.奶油, 规.色.奶油, 0.5 * 显)
    .strokeRoundedRect(
      牌左 + 描.内,
      牌上 + 描.内,
      牌宽 - 描.内 * 2,
      牌高 - 描.内 * 2,
      Math.max(2, 圆角 - 描.内),
    );
  // ⑤ 四角糖钉。
  const 钉 = 规.面板.铆钉半径;
  const 缩 = 圆角 * 0.7;
  for (const [x, y] of [
    [牌左 + 缩, 牌上 + 缩],
    [牌左 + 牌宽 - 缩, 牌上 + 缩],
    [牌左 + 缩, 牌上 + 牌高 - 缩],
    [牌左 + 牌宽 - 缩, 牌上 + 牌高 - 缩],
  ] as const)
    绘制糖钉(图, x, y, 钉, 规.色.奶油, 显);
}

export const 糖果画法: 转场画法 = { 绘制幕面, 绘制接缝, 绘制节拍底纹 };

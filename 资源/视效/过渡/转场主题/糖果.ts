/**
 * 「糖果超甜」的转场：不学压线/幕布，走软糖自己的两段动势。
 *
 * 收束（1.06s）：被选中的模式卡在原位「鼓」起来（圆角矩形膨胀 + 弹性过冲）变成一颗粉糖，
 *   巧克力糖浆再从卡心涌出来，圆盘一路铺满整屏 —— 边缘是软边糖浆前沿 + 奶油裱花，没有一条直线幕布。
 * 展开（0.62s 露完）：糖浆从屏幕中心「融化」开一个圆孔（iris），孔边挂奶油裱花与奶油气泡，
 *   孔一圈圈涨大把新画面露出来，随后让位给 Ready/Go 节拍。
 *
 * 糖浆取深巧克力而不是草莓粉：糖果页的方块、板框、按钮本身就是玫瑰粉，幕布再取粉，
 * 整屏和页面就分不开（验收按 24×24 格均色判「盖住/露出」会误判）；糖果味交给
 * 粉糖卡、草莓糖边与奶油裱花去给。`绘制遮罩` 只画不透明填充，`绘制强调` 才画半透明装饰。
 *
 * 只画表现：只用 `图形对象` 协议；颜色/圆角/花边/描边只取 `糖果规范`，深浅只走
 * `混色`/`亮色`/`暗色` 派生；不读业务状态、不改时间轴。
 */
const 规 = 糖果规范;
const 花 = 规.花边;
const 描 = 规.描边;

/** 糖浆主色：深巧克力里透一点酒红，铺满时是一层厚巧克力糖浆。 */
const 糖浆色 = 混色(规.色.巧克力深, 规.色.酒红, 0.5);
/** 糖浆前沿的草莓糖边：深巧克力底色上唯一的那道亮边。 */
const 糖浆边色 = 规.色.草莓深;

/** 收束前段留给「模式卡鼓起」的进度占比；之后由糖浆圆盘向外铺满。 */
export const 糖果卡片占比 = 0.34;

/** 糖浆要多铺一圈半径才盖得住最远的屏幕角，软边不会在角上露馅。 */
const 糖浆余量 = 花.半径 + 描.外;
/** 圆盘铺到覆盖比多少就算盖满：余下的进度留给「停稳」，跨页前一刻不再生长。 */
const 铺满覆盖 = 0.995;
/** 孔洞开到覆盖比多少就算露尽：展开末帧刚好把整屏让干净。 */
const 露尽覆盖 = 0.995;

/** 三次平滑：首尾速度为 0，膨胀与融化都不在两端「顿」一下。 */
function 平滑(t: number): number {
  const x = 夹进度(t);
  return x * x * (3 - 2 * x);
}

/**
 * 软糖弹性映射（0..1）：末段才鼓起来的一记过冲，收尾回到 0。
 * 给卡片膨胀、糖浆前沿的奶油环与气泡用；**不参与覆盖比**，
 * 所以收束 1 / 展开 0 的接力点永远是整数 1。
 */
export function 软糖回弹(进度: number): number {
  const 末段 = 夹进度((夹进度(进度) - 0.62) / 0.38);
  if (末段 <= 0 || 末段 >= 1) return 0;
  return Math.sin(末段 * Math.PI) * (1 - 末段 * 0.4);
}

/**
 * 收束的覆盖曲线：0→1。前 `糖果卡片占比` 只把卡鼓起来（覆盖 0→0.18），
 * 之后糖浆圆盘铺满；整段单调不减，收束 1 恰为 1。
 */
export function 软糖膨胀曲线(进度: number): number {
  const t = 夹进度(进度);
  if (t <= 0) return 0;
  if (t >= 1) return 1;
  if (t <= 糖果卡片占比) return 0.18 * (t / 糖果卡片占比);
  return 0.18 + 0.82 * 平滑((t - 糖果卡片占比) / (1 - 糖果卡片占比));
}

/** 覆盖比：收束 0→1、展开 1→0；接力点（收束 1 / 展开 0）都恰为 1。 */
export function 糖果覆盖比(帧: 转场帧): number {
  const t = 夹进度(帧.进度);
  if (帧.阶段 === "收束") return 软糖膨胀曲线(t);
  return 1 - 平滑(t);
}

/**
 * 软糖圆盘半径：`满半径` 是从出发点盖住最远屏幕角所需的距离。
 * 覆盖 0 → 0，覆盖 ≥ 铺满覆盖 → 满半径；前段慢、后段稳，读作糖浆越铺越快再停住。
 */
export function 糖果软糖半径(满半径: number, 覆盖: number): number {
  const 上限 = Math.max(0, 满半径);
  const t = 夹进度(夹进度(覆盖) / 铺满覆盖);
  return 上限 * t ** 1.5;
}

/**
 * 融化孔半径：覆盖 1（盖满）→ 0；覆盖 ≤ 1-露尽覆盖 时孔已大过整屏（画面完全露出）。
 * 和 `糖果软糖半径` 共用同一套幂次语汇，一胀一消；孔边由 `绘制强调` 补裱花。
 */
export function 糖果融化半径(满半径: number, 覆盖: number): number {
  const 上限 = Math.max(0, 满半径);
  const t = 夹进度((1 - 夹进度(覆盖)) / 露尽覆盖);
  return 上限 * t ** 1.15;
}

/** 屏幕四角里离出发点最远的距离，再加一圈软边余量。 */
function 读取满半径(心X: number, 心Y: number, 宽: number, 高: number): number {
  return (
    Math.max(
      Math.hypot(心X, 心Y),
      Math.hypot(宽 - 心X, 心Y),
      Math.hypot(心X, 高 - 心Y),
      Math.hypot(宽 - 心X, 高 - 心Y),
    ) + 糖浆余量
  );
}

/** 模式卡的原位矩形：没有卡片出发的入口（预览、直接进对局）用屏幕中心一小块当卡。 */
export function 糖果卡片矩形(帧: 转场帧): 矩形 {
  return (
    帧.原卡 ?? {
      左: 帧.宽 / 2 - 帧.宽 * 0.16,
      上: 帧.高 / 2 - Math.max(6, 帧.高 * 0.02),
      宽: 帧.宽 * 0.32,
      高: Math.max(12, 帧.高 * 0.04),
    }
  );
}

/** 卡片鼓起来的样子：圆角从卡片圆角鼓到面板圆角，尺寸带一次弹性过冲。 */
function 卡片鼓起(帧: 转场帧): { 卡: 矩形; 圆角: number } {
  const 原 = 糖果卡片矩形(帧);
  const 卡t = 夹进度(夹进度(帧.进度) / 糖果卡片占比);
  const 膨 = 1 + 0.1 * 卡t + 0.05 * 软糖回弹(卡t);
  const 宽 = Math.max(2, 原.宽 * 膨);
  const 高 = Math.max(2, 原.高 * 膨);
  return {
    卡: { 左: 原.左 + 原.宽 / 2 - 宽 / 2, 上: 原.上 + 原.高 / 2 - 高 / 2, 宽, 高 },
    圆角: 规.圆角.卡片 + (规.圆角.面板 - 规.圆角.卡片) * 卡t,
  };
}

/** 盖满整屏：收束末帧与展开首帧共用这一笔，跨页接缝才会逐笔一致、不露下面的页面。 */
function 绘制盖满(图: 图形对象, 帧: 转场帧): void {
  图.fillStyle(糖浆色, 1).fillRect(0, 0, 帧.宽, 帧.高);
}

/** 收束遮罩：巧克力糖壳包住模式卡（含奶油裱花），草莓糖浆再从卡心鼓出来把它吞掉。 */
function 绘制收束遮罩(图: 图形对象, 帧: 转场帧, 覆盖: number): void {
  const { 卡, 圆角 } = 卡片鼓起(帧);
  const 卡圆角 = Math.max(1, Math.min(圆角, 卡.宽 / 2, 卡.高 / 2));
  const 卡t = 夹进度(帧.进度 / 糖果卡片占比);
  // ① 糖壳：比原卡外扩一圈描边，把页面上的模式卡整个包住。
  图
    .fillStyle(规.色.巧克力深, 1)
    .fillRoundedRect(
      卡.左 - 描.外,
      卡.上 - 描.外,
      卡.宽 + 描.外 * 2,
      卡.高 + 描.外 * 2,
      卡圆角 + 描.外,
    );
  // ② 卡身：糖纸裹草莓粉的一颗软糖，越鼓越亮；巧克力糖浆盖上来时才分得开。
  const 卡身 = 混色(规.色.草莓深, 规.色.草莓, 0.15 + 0.5 * 卡t);
  图
    .fillGradientStyle(亮色(卡身, 0.18), 亮色(卡身, 0.09), 暗色(卡身, 0.14), 暗色(卡身, 0.26))
    .fillRoundedRect(卡.左, 卡.上, 卡.宽, 卡.高, 卡圆角);
  // ③ 卡上的奶油双线裱花 + 糖钉，再压一条从上沿淡出的糖衣反光。
  绘制奶油内衬(图, 卡.左, 卡.上, 卡.宽, 卡.高, 卡圆角, 规.色.糖纸, 0.82, true);
  const 反光高 = Math.min(卡.高 * 0.34, 26);
  图
    .fillGradientStyle(规.色.白, 规.色.白, 规.色.白, 规.色.白, 0.22, 0.14, 0, 0)
    .fillRoundedRect(
      卡.左 + 描.外 + 2,
      卡.上 + 描.外 + 1.5,
      卡.宽 - (描.外 + 2) * 2,
      反光高,
      Math.max(2, 卡圆角 - 描.外),
    );
  // ④ 糖浆圆盘：外沿一圈草莓糖边，主体是巧克力糖浆；半径 0 时不画。
  const 心X = 卡.左 + 卡.宽 / 2;
  const 心Y = 卡.上 + 卡.高 / 2;
  const 半径 = 糖果软糖半径(读取满半径(心X, 心Y, 帧.宽, 帧.高), 覆盖);
  if (半径 <= 0.75) return;
  图.fillStyle(糖浆边色, 1).fillCircle(心X, 心Y, 半径 + 花.内缩);
  图.fillStyle(糖浆色, 1).fillCircle(心X, 心Y, 半径);
}

/** 圆孔四角的补丁：方孔的角落在圆外那一块，把方孔修成圆孔。 */
function 圆角补丁(中X: number, 中Y: number, 半径: number, 横: number, 纵: number): 点[] {
  const 点集: 点[] = [{ x: 中X + 横 * 半径, y: 中Y + 纵 * 半径 }];
  const 起角 = 纵 < 0 ? -Math.PI / 2 : Math.PI / 2;
  const 扫 = (横 * (纵 < 0 ? 1 : -1) * Math.PI) / 2;
  const 段数 = 6;
  // 从方角的一条边端沿圆弧走到另一条边端，再回到角点：围出的就是角上的盖板。
  for (let 序 = 0; 序 <= 段数; 序 += 1) {
    const 角 = 起角 + 扫 * (序 / 段数);
    点集.push({ x: 中X + Math.cos(角) * 半径, y: 中Y + Math.sin(角) * 半径 });
  }
  return 点集;
}

/** 展开遮罩：整屏盖住，只在中心留一个圆孔（四块盖板 + 四角补丁拼成一块不透明遮罩）。 */
function 绘制展开遮罩(图: 图形对象, 帧: 转场帧, 覆盖: number): void {
  const { 宽, 高 } = 帧;
  const 中X = 宽 / 2;
  const 中Y = 高 / 2;
  const 孔 = 糖果融化半径(读取满半径(中X, 中Y, 宽, 高), 覆盖);
  const 色 = 糖浆色;
  图.fillStyle(色, 1);
  // 孔以上/以下两块整宽盖板。
  图.fillRect(0, 0, 宽, Math.max(0, 中Y - 孔));
  图.fillRect(0, 中Y + 孔, 宽, Math.max(0, 高 - 中Y - 孔));
  // 孔左右两侧的盖板；孔高过屏幕时它们自然收成 0 宽，调用序列仍然固定。
  const 带顶 = Math.max(0, 中Y - 孔);
  const 带高 = Math.max(0, Math.min(高, 中Y + 孔) - 带顶);
  图.fillRect(0, 带顶, Math.max(0, 中X - 孔), 带高);
  图.fillRect(中X + 孔, 带顶, Math.max(0, 宽 - 中X - 孔), 带高);
  // 四角补丁：孔还小的时候，把方角补回圆弧外面，孔才是圆的。
  for (const 横 of [-1, 1])
    for (const 纵 of [-1, 1]) 图.fillStyle(色, 1).fillPoints(圆角补丁(中X, 中Y, 孔, 横, 纵), true);
}

function 绘制遮罩(图: 图形对象, 帧: 转场帧): void {
  if (帧.宽 <= 0 || 帧.高 <= 0) return;
  const 覆盖 = 糖果覆盖比(帧);
  if (帧.阶段 === "收束") {
    // 接力点（收束 1）走「盖满」这一笔：与展开 0 的遮罩逐笔一致。
    if (覆盖 >= 1) 绘制盖满(图, 帧);
    else 绘制收束遮罩(图, 帧, 覆盖);
    return;
  }
  if (覆盖 >= 1) 绘制盖满(图, 帧);
  else if (覆盖 > 0) 绘制展开遮罩(图, 帧, 覆盖);
}

/** 收束强调：糖浆前沿的厚糖边 + 奶油裱花 + 糖衣反光，外加表面气泡与两颗挂下来的糖滴。 */
function 绘制糖浆强调(图: 图形对象, 帧: 转场帧, 覆盖: number): void {
  const { 卡 } = 卡片鼓起(帧);
  const 心X = 卡.左 + 卡.宽 / 2;
  const 心Y = 卡.上 + 卡.高 / 2;
  const 半径 = 糖果软糖半径(读取满半径(心X, 心Y, 帧.宽, 帧.高), 覆盖);
  if (半径 <= 3) return;
  const 弹 = 软糖回弹(覆盖);
  const 余 = 1 - 覆盖 ** 3;
  // 前沿只在糖浆攒出一点体积后才画环：小水洼阶段画环会变成一圈「甜甜圈」。
  const 环透 = 余 * 夹进度((半径 - 10) / 26);
  if (环透 > 0.02) {
    图.lineStyle(描.外 + 2.5, 糖浆边色, 0.95 * 环透).strokeCircle(心X, 心Y, 半径 + 1);
    图
      .lineStyle(描.奶油 + 1.8 + 弹 * 1.2, 规.色.奶油, 0.95 * 环透)
      .strokeCircle(心X, 心Y, Math.max(1, 半径 - 3));
    图.lineStyle(1.3, 规.色.白, 0.38 * 环透).strokeCircle(心X, 心Y, Math.max(1, 半径 - 5.6));
  }
  // 左上糖衣反光：糖浆表面的一块柔光。
  图
    .fillStyle(规.色.草莓浅, 0.14 * 余)
    .fillEllipse(心X - 半径 * 0.32, 心Y - 半径 * 0.4, 半径 * 0.52, 半径 * 0.26);
  // 糖浆表面的小气泡：跟着糖浆一起长大，铺满前收掉。
  for (const [横, 纵, 大小] of [
    [0.34, 0.18, 4.2],
    [-0.2, 0.52, 3.1],
    [0.5, -0.28, 2.6],
  ] as const) {
    const 泡X = 心X + 半径 * 横;
    const 泡Y = 心Y + 半径 * 纵;
    图.fillStyle(规.色.奶油, 0.16 * 余).fillCircle(泡X, 泡Y, 大小 * (1 + 弹 * 0.3));
  }
  // 两颗糖滴：贴着前沿挂在糖面上。
  for (const [横, 纵] of [
    [-0.62, 0.55],
    [0.66, -0.5],
  ] as const) {
    const 滴X = 心X + 半径 * 横;
    const 滴Y = 心Y + 半径 * 纵;
    图.fillStyle(规.色.草莓, 0.9 * 余).fillCircle(滴X, 滴Y, 3.2 + 弹);
    图.fillStyle(规.色.白, 0.45 * 余).fillCircle(滴X - 1, 滴Y - 1.2, 1.2);
  }
}

/** 展开强调：糖浆圆孔边的厚糖边 + 奶油裱花 + 顶光，外加三颗奶油气泡与两滴挂下来的糖浆。 */
function 绘制展开强调(图: 图形对象, 帧: 转场帧, 覆盖: number): void {
  if (覆盖 <= 0.005 || 覆盖 >= 1) return;
  const 中X = 帧.宽 / 2;
  const 中Y = 帧.高 / 2;
  const 孔 = 糖果融化半径(读取满半径(中X, 中Y, 帧.宽, 帧.高), 覆盖);
  if (孔 <= 1) return;
  // 融化两头都带一点软：孔刚开、快开尽时各鼓一下。
  const 弹 = 软糖回弹(覆盖) + 软糖回弹(1 - 覆盖);
  const 厚 = 描.外 + 2.4 + 弹 * 1.6;
  // ① 糖层断面：孔内圈的投影落在新画面上，读作糖霜层有厚度。
  图.lineStyle(厚 + 1.5, 暗色(糖浆色, 0.62), 0.34).strokeCircle(中X, 中Y, 孔 - 厚 / 2);
  // ② 糖浆的厚边：孔外一圈草莓糖边，把巧克力糖层圈住。
  图.lineStyle(厚, 糖浆边色, 0.9).strokeCircle(中X, 中Y, 孔 + 厚 / 2);
  // ③ 奶油裱花：孔沿一圈奶油糖霜，越往外越鼓。
  图.lineStyle(描.奶油 + 1.8, 规.色.奶油, 0.95).strokeCircle(中X, 中Y, Math.max(1, 孔 - 0.8));
  // ④ 顶光：奶油上的窄高光。
  图.lineStyle(1.3, 规.色.白, 0.42).strokeCircle(中X, 中Y, Math.max(1, 孔 - 3.8));
  // ⑤ 奶油气泡：三颗贴着孔边浮在糖浆里，随孔外扩、到边就收掉。
  const 泡透 = 0.55 * Math.sin(Math.PI * 夹进度(1 - 覆盖));
  const 泡半径 = 2.6 + 弹 * 1.8;
  if (泡透 > 0.02)
    for (const 角 of [0.9, 2.7, 4.5]) {
      const 泡X = 中X + Math.cos(角) * (孔 + 泡半径 + 3);
      const 泡Y = 中Y + Math.sin(角) * (孔 + 泡半径 + 3);
      图.fillStyle(规.色.奶油, 泡透).fillCircle(泡X, 泡Y, 泡半径);
      图
        .fillStyle(规.色.白, 泡透 * 0.8)
        .fillCircle(泡X - 泡半径 * 0.3, 泡Y - 泡半径 * 0.35, 泡半径 * 0.4);
    }
  // ⑤ 糖滴：两滴挂进孔里的草莓糖浆，滴头朝孔心，读作正在融化。
  for (const 角 of [1.9, 5.2]) {
    const 滴X = 中X + Math.cos(角) * (孔 - 5);
    const 滴Y = 中Y + Math.sin(角) * (孔 - 5);
    图.fillStyle(规.色.草莓, 0.92).fillCircle(滴X, 滴Y, 3.4 + 弹);
    图.fillStyle(规.色.草莓浅, 0.8).fillCircle(滴X + 0.8, 滴Y + 1, 1.9 + 弹 * 0.4);
    图.fillStyle(规.色.白, 0.5).fillCircle(滴X - 1.2, 滴Y - 1.4, 1.1);
  }
}

function 绘制强调(图: 图形对象, 帧: 转场帧): void {
  const 覆盖 = 糖果覆盖比(帧);
  if (覆盖 >= 1) return;
  if (帧.阶段 === "收束") {
    if (覆盖 > 0) 绘制糖浆强调(图, 帧, 覆盖);
    return;
  }
  绘制展开强调(图, 帧, 覆盖);
}

/** 沿一条横向边排布奶油裱花的圆心 X；颗数按 `花边.步长` 取整，两端各留半颗。 */
export function 裱花圆心(宽: number): number[] {
  const 有效宽 = Math.max(0, 宽);
  if (有效宽 <= 0) return [];
  const 颗数 = Math.max(1, Math.floor(有效宽 / 花.步长));
  const 间距 = 有效宽 / 颗数;
  return Array.from({ length: 颗数 }, (_, 序) => 间距 * (序 + 0.5));
}

function 绘制节拍底纹(图: 图形对象, 参数: 节拍底纹参数): void {
  const { 宽, 高, 模式色, 显 } = 参数;
  if (显 <= 0 || 宽 <= 0 || 高 <= 0) return;
  const 中Y = 高 / 2;
  const 牌宽 = Math.min(宽 * 0.66, 宽 - 规.圆角.面板 * 2);
  const 牌高 = Math.min(高 * 0.13, 规.圆角.面板 * 4.6);
  if (牌宽 <= 0 || 牌高 <= 0) return;
  const 圆角 = Math.min(规.圆角.面板, 牌高 / 2);
  const 牌左 = 宽 / 2 - 牌宽 / 2;
  const 牌上 = 中Y - 牌高 / 2;

  // ① 压暗：薄薄一层巧克力糖雾。深了会把整屏压成幕布色，验收会判成「还没揭开」。
  图.fillStyle(规.色.巧克力深, 0.12 * 显).fillRect(0, 0, 宽, 高);
  // ② 奶油光晕：七圈由外到内逐级加亮，退场时一起收（层多、步小，看不见硬边圆圈）。
  for (const [半径比, 透明] of [
    [0.56, 0.018],
    [0.48, 0.019],
    [0.4, 0.02],
    [0.32, 0.022],
    [0.24, 0.024],
    [0.17, 0.026],
    [0.11, 0.028],
  ] as const)
    图.fillStyle(规.色.奶油, 透明 * 显).fillCircle(宽 / 2, 中Y, 宽 * 半径比);
  // ③ 粉色糖牌：上亮下深的圆角块，模式色只在右上角点一下。
  图
    .fillGradientStyle(
      混色(规.色.草莓, 规.色.白, 0.2),
      混色(规.色.草莓, 模式色, 0.18),
      规.色.草莓,
      规.色.草莓,
      0.42 * 显,
      0.42 * 显,
      0.42 * 显,
      0.42 * 显,
    )
    .fillRoundedRect(牌左, 牌上, 牌宽, 牌高, 圆角);
  // ④ 奶油裱花内线 + 顶边一排扇贝（糖纸波浪口）。
  图
    .lineStyle(描.奶油, 规.色.奶油, 0.5 * 显)
    .strokeRoundedRect(
      牌左 + 描.内,
      牌上 + 描.内,
      牌宽 - 描.内 * 2,
      牌高 - 描.内 * 2,
      Math.max(2, 圆角 - 描.内),
    );
  const 圆心 = 裱花圆心(牌宽 - 描.外 * 2);
  const 间距 = 圆心.length > 0 ? (牌宽 - 描.外 * 2) / 圆心.length : 牌宽;
  const 半颗 = Math.min(花.半径, 间距 / 2 - 0.5);
  for (const 偏移 of 圆心) {
    const x = 牌左 + 描.外 + 偏移;
    图.fillStyle(暗色(规.色.草莓深, 0.35), 0.55 * 显).fillCircle(x, 牌上 + 2, 半颗 + 0.8);
    图.fillStyle(规.色.草莓浅, 0.95 * 显).fillCircle(x, 牌上 + 2, 半颗);
    图.fillStyle(规.色.白, 0.4 * 显).fillCircle(x - 0.4, 牌上 + 1.2, 半颗 * 0.42);
  }
  // ⑤ 四角糖钉。
  const 钉 = 规.面板.铆钉半径;
  const 缩 = 圆角 * 0.7;
  for (const [x, y] of [
    [牌左 + 缩, 牌上 + 缩],
    [牌左 + 牌宽 - 缩, 牌上 + 缩],
    [牌左 + 缩, 牌上 + 牌高 - 缩],
    [牌左 + 牌宽 - 缩, 牌上 + 牌高 - 缩],
  ] as const)
    绘制糖钉(图, x, y, 钉, 规.色.奶油, 显);
}


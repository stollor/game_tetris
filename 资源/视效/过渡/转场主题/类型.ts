import type { 图形对象, 矩形 } from "../../../../.gamemaker/依赖/框架/界面/绘制/协议";

/**
 * 转场画法契约（v2）：主题自己决定「怎么盖住」和「怎么露出」，不再共用压线/上下幕布。
 *
 * 收束：0 = 从被选中的模式卡出发，1 = 盖满整屏；展开：0 = 盖满整屏，1 = 新画面完全露出。
 * 两个阶段的边界必须严丝合缝：收束 1 与展开 0 画出的遮罩要完全一样（都盖满整屏），
 * 否则跨页那一帧会露馅。
 */

/** 五套主题各自的转场风格（与主题槽位一一对应）。 */
export type 转场主题 = "极光" | "液晶" | "彩砖" | "立体" | "糖果";

export type 转场阶段 = "收束" | "展开";

export interface 转场帧 {
  宽: number;
  高: number;
  /** 模式主题色：只作强调，主体材质与基色来自各主题自己的规范。 */
  模式色: number;
  阶段: 转场阶段;
  /** 阶段内进度 0..1（收束 0=卡片出发、1=盖满；展开 0=盖满、1=完全露出）。 */
  进度: number;
  /** 收束阶段选中的模式卡矩形（页面坐标，y 向下）；没有卡片出发的入口为 null。 */
  原卡: 矩形 | null;
}

/** Ready/Go 节拍的主题底纹，画在文字之下。 */
export interface 节拍底纹参数 {
  宽: number;
  高: number;
  模式色: number;
  /** 0..1 出现强度，退场时归零。 */
  显: number;
}

/** 一套主题的转场画法。只画表现，不读业务状态，也不改时间轴。 */
export interface 转场画法 {
  /**
   * 遮罩盖住屏幕的比例（0 = 完全露出，1 = 盖满整屏）。
   * 收束必须 0→1、展开必须 1→0；接力点（收束 1 / 展开 0）必须等于 1，
   * 这是跨页接缝不露馅的硬约束，也让画法可被单测直接验证。
   */
  覆盖比(帧: 转场帧): number;
  /** 画「盖住画面的部分」：收束逐帧盖满，展开逐帧让开。 */
  绘制遮罩(图: 图形对象, 帧: 转场帧): void;
  /** 可选：画在遮罩之上的接缝/强调（亮线、糖浆边、灯条等）。 */
  绘制强调?(图: 图形对象, 帧: 转场帧): void;
  /** 可选：Ready/Go 背后的主题底纹。 */
  绘制节拍底纹?(图: 图形对象, 参数: 节拍底纹参数): void;
}

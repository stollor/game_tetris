import type { 图形对象 } from "../../../../.gamemaker/依赖/框架/界面/绘制/协议";

/**
 * 转场风格：由当前主题的槽位解析而来，只决定「这套主题怎么演」。
 * 时长、错峰与 Ready/Go 节拍仍由 `入场参数.ts` 统一，五套主题共享同一条时间轴。
 */
export type 转场主题 = "极光" | "液晶" | "彩砖" | "立体" | "糖果";

/** 幕布接缝：顶/底是被幕布盖住的上下边界（页面坐标，中心恒定在屏幕中线）。 */
export interface 转场幕缝 {
  顶: number;
  底: number;
}

/**
 * 幕面参数。
 * - `覆盖度`：0 = 两片幕布完全打开（缝覆盖整屏），1 = 完全合拢（缝=中央 2px 线）；
 * - `模式色`：只作强调色，主题基色来自各自规范，避免五套主题都染成模式色；
 * - `边线`：接缝边线透明度，收束阶段为 0，展开阶段随进度淡出。
 */
export interface 幕面参数 {
  宽: number;
  高: number;
  缝: 转场幕缝;
  覆盖度: number;
  模式色: number;
  边线: number;
}

/** 接缝强调：模式卡收束末帧与对局展开首帧共用，保证跨页接缝是同一套画法。 */
export interface 接缝参数 {
  宽: number;
  高: number;
  模式色: number;
  /** 0..1，闭合瞬间达峰，跨页后是释放余辉。 */
  强度: number;
}

/** Ready/Go 节拍的主题底纹，画在文字之下。 */
export interface 节拍底纹参数 {
  宽: number;
  高: number;
  模式色: number;
  /** 0..1 出现强度，退场时归零。 */
  显: number;
}

/** 一套主题的转场画法。只画表现，不读业务状态，也不改节拍。 */
export interface 转场画法 {
  绘制幕面(图: 图形对象, 参数: 幕面参数): void;
  绘制接缝(图: 图形对象, 参数: 接缝参数): void;
  /** 可选：Ready/Go 背后的主题底纹。 */
  绘制节拍底纹?(图: 图形对象, 参数: 节拍底纹参数): void;
}

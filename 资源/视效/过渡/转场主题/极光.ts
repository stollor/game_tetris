import type { 图形对象, 矩形 } from "../../../../.gamemaker/依赖/框架/界面/绘制/协议";
import { 亮色, 混色 } from "../../../../.gamemaker/依赖/框架/界面/颜色工具";
import { 入场参数, 夹进度 } from "../入场参数";
import type { 节拍底纹参数, 转场帧, 转场画法 } from "./类型";

/**
 * 极光原野（默认主题）的转场：选中卡 → 压成中央亮线 → 亮线向上下铺开成霓虹幕布，
 * 展开时幕布自中线向边缘退去、留一道余辉。它是其余四套主题的基线，节奏与它们共用。
 */

const 色 = {
  幕外: 0x182b3f,
  幕内: 0x82939b,
  主题染色: 0.1,
  线提亮: 0.22,
  卡面: 0x184b72,
};

/** 幕色：幕外深、幕内浅，只按模式色轻度染色。 */
export function 读取幕色(模式色: number): { 外: number; 内: number } {
  return {
    外: 混色(色.幕外, 模式色, 色.主题染色),
    内: 混色(色.幕内, 模式色, 色.主题染色),
  };
}

/** 卡片阶段占收束前 44%，之后由中央线铺满整屏。 */
export const 极光卡片占比 = 0.44;

function 缓入出(t: number): number {
  const 夹 = 夹进度(t);
  return 夹 * 夹 * (3 - 2 * 夹);
}

/** 收束阶段的卡片矩形：从模式卡原位向屏幕中线收成一根全宽细线。 */
export function 极光卡片矩形(帧: 转场帧): 矩形 {
  const 卡 = 帧.原卡 ?? { 左: 帧.宽 / 2 - 1, 上: 帧.高 / 2 - 1, 宽: 2, 高: 2 };
  const t = 缓入出(帧.进度 / 极光卡片占比);
  const 线高 = 入场参数.运动.线高;
  const 目标上 = 帧.高 / 2 - 线高 / 2;
  return {
    左: 卡.左 + (0 - 卡.左) * t,
    上: 卡.上 + (目标上 - 卡.上) * t,
    宽: 卡.宽 + (帧.宽 - 卡.宽) * t,
    高: 卡.高 + (线高 - 卡.高) * t,
  };
}

/**
 * 覆盖板：上半板与下半板两块。
 * - 收束：两块从中心分界向外长（先盖中心、后盖边缘），到 1 时正好拼满整屏；
 * - 展开：两块从整屏向中心缩（光从中心先露出来），到 1 时退干净。
 * 接力点（收束 1 / 展开 0）两块都是 [0,高/2] 与 [高/2,高]，跨页接缝完全一致。
 */
export function 极光覆盖板(帧: 转场帧): {
  上半: { 起: number; 止: number };
  下半: { 起: number; 止: number };
} {
  const 半 = 帧.高 / 2;
  if (帧.阶段 === "收束") {
    const t = 缓入出((帧.进度 - 极光卡片占比) / (1 - 极光卡片占比));
    const 高 = 半 * t;
    return { 上半: { 起: 半 - 高, 止: 半 }, 下半: { 起: 半, 止: 半 + 高 } };
  }
  const t = 缓入出(帧.进度);
  return { 上半: { 起: 0, 止: 半 * (1 - t) }, 下半: { 起: 半 + 半 * t, 止: 帧.高 } };
}

function 绘制遮罩(图: 图形对象, 帧: 转场帧): void {
  const { 宽 } = 帧;
  const 幕色 = 读取幕色(帧.模式色);
  const 中 = 混色(幕色.外, 幕色.内, 0.55);
  if (帧.阶段 === "收束" && 帧.进度 < 极光卡片占比) {
    // 卡片本体先代替模式卡：深玻璃卡面 + 模式色霓虹边 + 收束时压向中线的一条亮芯。
    const 卡 = 极光卡片矩形(帧);
    const t = 夹进度(帧.进度 / 极光卡片占比);
    const 边色 = 亮色(帧.模式色, 色.线提亮 * (0.25 + t * 0.75));
    const 圆角 = 10 * (1 - t);
    图
      .fillStyle(混色(色.卡面, 0x050d18, 0.35 + 0.3 * t), 1)
      .fillRoundedRect(卡.左, 卡.上, Math.max(1, 卡.宽), Math.max(1, 卡.高), 圆角);
    if (t < 1) {
      图
        .lineStyle(2, 边色, 0.95)
        .strokeRoundedRect(卡.左, 卡.上, Math.max(1, 卡.宽), Math.max(1, 卡.高), 圆角);
      // 卡面上一道随压缩变窄的亮带：卡片被压成线的过程看得见。
      const 芯高 = Math.max(2, 卡.高 * (1 - t) * 0.5);
      图
        .fillGradientStyle(边色, 边色, 边色, 边色, 0, 0, 0.5, 0.5)
        .fillRect(卡.左 + 6, 卡.上 + (卡.高 - 芯高) / 2, Math.max(1, 卡.宽 - 12), 芯高);
      图
        .fillGradientStyle(边色, 边色, 边色, 边色, 0.18, 0.18, 0, 0)
        .fillRect(卡.左, 卡.上 - 5, Math.max(1, 卡.宽), 5);
    }
  }
  const 板 = 极光覆盖板(帧);
  const 上高 = 板.上半.止 - 板.上半.起;
  const 下高 = 板.下半.止 - 板.下半.起;
  if (上高 > 0)
    图
      .fillGradientStyle(幕色.外, 幕色.外, 中, 中)
      .fillRect(0, 板.上半.起, 宽, Math.max(0, 上高 - 1));
  if (下高 > 0)
    图
      .fillGradientStyle(中, 中, 幕色.外, 幕色.外)
      .fillRect(0, 板.下半.起 + 1, 宽, Math.max(0, 下高 - 1));
  // 前沿亮边：收束时在覆盖板上缘，展开时在同一处（新画面从这条边露出来）。
  if (上高 > 0) 图.fillStyle(亮色(幕色.内, 0.5), 0.9).fillRect(0, 板.上半.起, 宽, 1);
  if (下高 > 0) 图.fillStyle(亮色(幕色.内, 0.5), 0.9).fillRect(0, 板.下半.止 - 1, 宽, 1);
}

/** 覆盖比：两块覆盖板合计高度占屏高的比例。 */
function 覆盖比(帧: 转场帧): number {
  const 板 = 极光覆盖板(帧);
  const 高 = 板.上半.止 - 板.上半.起 + (板.下半.止 - 板.下半.起);
  return Math.min(1, Math.max(0, 高 / Math.max(1, 帧.高)));
}

function 绘制强调(图: 图形对象, 帧: 转场帧): void {
  const { 宽, 高 } = 帧;
  const 线高 = 入场参数.运动.线高;
  const 中Y = 高 / 2 - 线高 / 2;
  // 收束后段与展开前段共用的中央亮线；展开末段淡出成余辉。
  const 强度 =
    帧.阶段 === "收束"
      ? 夹进度((帧.进度 - 极光卡片占比) / (1 - 极光卡片占比))
      : 1 - 夹进度(帧.进度 / 0.35);
  if (强度 <= 0.01) return;
  const 线色 = 亮色(帧.模式色, 色.线提亮 * 强度);
  图.fillStyle(线色, 1).fillRect(0, 中Y, 宽, 线高);
  图.fillStyle(亮色(线色, 0.22), 强度 * 0.6).fillRect(宽 * 0.25, 中Y + 0.5, 宽 * 0.5, 1);
  // 极光光晕：中线上下两道渐隐带，收束时提亮、展开时收掉。
  图
    .fillGradientStyle(线色, 线色, 线色, 线色, 0.16 * 强度, 0.16 * 强度, 0, 0)
    .fillRect(0, 中Y - 高 * 0.07, 宽, 高 * 0.07);
  图
    .fillGradientStyle(线色, 线色, 线色, 线色, 0, 0, 0.16 * 强度, 0.16 * 强度)
    .fillRect(0, 中Y + 线高, 宽, 高 * 0.07);
}

function 绘制节拍底纹(图: 图形对象, 参数: 节拍底纹参数): void {
  const { 宽, 高, 模式色, 显 } = 参数;
  if (显 <= 0) return;
  图.fillStyle(0x0a1220, 入场参数.颜色.节拍压暗 * 显).fillRect(0, 0, 宽, 高);
  图.fillStyle(模式色, 显).fillRect(宽 / 2 - 20 * 显, 高 / 2 + 34, 40 * 显, 2);
}

export const 极光画法: 转场画法 = { 覆盖比, 绘制遮罩, 绘制强调, 绘制节拍底纹 };

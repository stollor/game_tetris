/**
 * 收束在 94% 处就要求主题「盖满」，最后 6% 保持满屏。
 * 动画层按这个比例压缩主题收到的进度：切页前几十毫秒必须已经全屏盖住（含货币层），
 * 不能等到最后一帧才合满——否则截图/跨页那一瞬会露出金币角标。
 */
export const 收束铺满比 = 0.94;

export const 模式退场时长 = 入场参数.时间.收束止;
export const 对局入场时长 = 入场参数.时间.Go止;
export const 棋盘展开时长 = 入场参数.时间.揭示止;
export const 准备起始时刻 = 入场参数.时间.Ready起;
export type 入场分组 = keyof typeof 入场参数.分组;

/** 时间轴内的线性进度，夹在 0..1。 */
export function 比例(秒: number, 起: number, 止: number): number {
  return Math.min(1, Math.max(0, (秒 - 起) / (止 - 起)));
}

/** 先快后慢的出场曲线：1-(1-t)^指数。 */
export function 快出(t: number, 指数: number): number {
  return 1 - (1 - t) ** 指数;
}

/** 夹在 0..1 的通用进度，供主题画法量化或过冲。 */
export function 夹进度(值: number): number {
  return Math.min(1, Math.max(0, 值));
}

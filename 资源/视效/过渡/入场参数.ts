/** 时间轴内的线性进度，夹在 0..1。 */
export function 比例(秒: number, 起: number, 止: number): number {
  return Math.min(1, Math.max(0, (秒 - 起) / (止 - 起)));
}

/** 先快后慢的出场曲线：1-(1-t)^指数。 */
export function 快出(t: number, 指数: number): number {
  return 1 - (1 - t) ** 指数;
}

/** 夹在 0..1 的通用进度，供主题画法量化或过冲。 */
export function 夹进度(值: number): number {
  return Math.min(1, Math.max(0, 值));
}

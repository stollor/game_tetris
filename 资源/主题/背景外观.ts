import type { 游戏设置 } from "../../代码/设置/游戏设置";
import { 获取游戏设置 } from "../../代码/设置/游戏设置";
import { 压暗, 填充矩形 } from "../../.gamemaker/依赖/框架/界面/控件/工具";
import type { 矩形, 绘制环境 } from "../../.gamemaker/依赖/框架/界面/控件/类型";
import { 读取背景外观配色 } from "../视效/背景/背景绘制";

/**
 * Three 版背景外观：只把共享配置换算成页面需要的外观值，不再另画简化背景。
 * 页面背景统一用 `资源/视效/背景/背景绘制.ts` 的 `绘制背景(画笔.图形, 参数)`；
 * 这里保留顶栏衬底与外观读取，供游戏页面基类/设置外观卡用。
 */

export interface 背景外观 {
  名称: string;
  主色: number;
  强调: number;
  文字基调: "浅底" | "深底";
}

/** 读取当前设置对应主题的外观；颜色与文字基调全部来自共享背景配置。 */
export function 读取背景外观(设置: 游戏设置 = 获取游戏设置()): 背景外观 {
  const 主题 = 设置.主题选择;
  return { 名称: 主题, ...读取背景外观配色(主题) };
}

/** 悬浮面板/顶部栏底衬：从背景取半透明底色，页面顶栏用。 */
export function 绘制顶栏衬底(环境: 绘制环境, 矩形: 矩形, 外观: 背景外观, 透明度 = 0.72): void {
  填充矩形(环境.合批, 环境.文字.读取纯色紫外线(), 矩形, 压暗(外观.主色, 0.55), 透明度);
  填充矩形(
    环境.合批,
    环境.文字.读取纯色紫外线(),
    { 左: 矩形.左, 上: 矩形.上 + 矩形.高 - 1, 宽: 矩形.宽, 高: 1 },
    外观.强调,
    0.3,
  );
}

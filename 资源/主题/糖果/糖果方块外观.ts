/**
 * 「糖果超甜」方块外观：七种方块各自包成一颗糖，颜色与糖身参数只在这里定义一次。
 *
 * 七型对应五款糖：O 巧克力、I 蛋挞、T 棒棒糖、L/J 拐棍糖（互为镜像，换口味换色）、
 * Z/S 奶茶（互为镜像，换口味换色）。形状本身由各绘制模块按格集推导，
 * 本文件只管「这颗糖是什么颜色、什么口味」。
 */

export type 糖果块种类 = "巧克力" | "蛋挞" | "棒棒糖" | "拐棍糖" | "奶茶";

export interface 糖果块样式 {
  种类: 糖果块种类;
  /** 糖身主色。 */
  主色: number;
  /** 轮廓与暗侧边。 */
  深色: number;
  /** 受光面与亮边。 */
  浅色: number;
  /** 糖身上的装饰色（奶油螺旋、蛋液、饮料、条纹）。 */
  装饰: number;
  /** 装饰的暗色（条纹缝隙、果肉阴影）。 */
  装饰深: number;
  /** 可选的高饱和点缀（棒棒糖糖针这类要跳出来的小颗粒）；不写就用装饰色。 */
  点缀?: readonly number[];
}


/** 每套主题只有「整套」一个维度：整套主题一次替换全部槽位，不提供单项混搭。 */
function 主题维度表(名称: 主题名): 主题维度 {
  const 覆盖 = Object.fromEntries(槽位列表.map((槽) => [槽, 资源编号(槽, 主题槽位[名称][槽])]));
  const 曲目 = 主题曲目(名称);
  return {
    编号: "整套",
    名称: "整套主题",
    说明: "整套主题一次性替换全部槽位。",
    槽位: 槽位列表,
    默认: 名称,
    选项: [
      {
        编号: 名称,
        名称,
        说明: 简中.主题说明[名称],
        覆盖,
        // 用正式背景配方定格一帧，看到的就是这套主题的真实画面。
        展示: { 样品: "game-background", 状态: { 主题: 名称, 播放: "定格", 时间: "2" } },
        试听: {
          类型: "音乐",
          id: 曲目[0] ?? "再消一行.菜单",
          条目: 曲目,
        },
      },
    ],
  };
}

/** 只声明职责和真实配置引用；颜色、曲谱、绘制实现仍由原模块提供。 */
export function 读取游戏主题目录(): 主题组合目录 {
  if (目录) return 目录;
  const 资源: 主题资源[] = Object.entries(资源定义表).map(([编号, 定义]) => {
    const 槽位 = 编号.slice(0, 编号.indexOf(".")) as 槽位编号;
    return {
      编号,
      名称: 定义.名称,
      槽位,
      契约: `${槽位}.v1`,
      方式: 定义.方式 ?? "参数",
      值: 定义.值,
      源码: [{ 路径: 定义.路径, 导出: 定义.导出 }],
    };
  });
  /** 槽位缺省跟随默认主题；动态层缺省为关闭，供「背景动态」开关局部覆盖。 */
  const 槽位默认: Record<槽位编号, string | null> = {
    ...主题槽位[默认主题编号],
    动态背景: null,
  };
  const 槽位 = 槽位列表.map((编号) => ({
    编号,
    名称: 编号,
    契约: `${编号}.v1`,
    默认: 资源编号(编号, 槽位默认[编号]),
    ...(实现槽位.includes(编号) ? { 允许实现替换: true } : {}),
  }));
  const 主题: 主题定义[] = 主题列表.map((名称) => ({
    编号: 名称,
    名称,
    说明: 简中.主题说明[名称],
    维度: [主题维度表(名称)],
    ...(名称 === 默认主题编号 ? { 默认: true } : {}),
  }));
  目录 = {
    槽位,
    资源,
    主题,
    预制体: 预制体声明,
    游戏应用: { 表: "presentation", 字段: "默认主题" },
  };
  return 目录;
}

/** 选择缺省沿用设置里的整套主题；关闭动态层时只局部覆盖动态背景一个槽位。 */
export function 解析游戏主题(设置: 游戏设置, 选择?: string): 主题解析结果 {
  const 主题 = 选择 ?? 设置.主题选择;
  const 局部: Record<string, string> = 设置.背景动态
    ? {}
    : { 动态背景: 资源编号("动态背景", null) };
  return 解析主题组合(读取游戏主题目录(), 主题 || 默认主题编号, 局部);
}

/** 主题结果回写设置：主题选择、框架 CSS 样式与动态开关都从解析结果取。 */
export function 主题结果转设置(设置: 游戏设置, 结果: 主题解析结果): 游戏设置 {
  const 值 = (槽: 槽位编号) => 结果.槽位.find((项) => 项.槽位.编号 === 槽)?.资源.值;
  const 样式 = 值("界面配色");
  if (typeof 样式 !== "string") throw new Error("主题界面配色未接入");
  return {
    ...设置,
    主题选择: 是主题名(结果.主题) ? 结果.主题 : 默认主题编号,
    样式,
    背景动态: 值("动态背景") !== null,
  };
}

/** 当前设置所属的整套主题名；主题不提供单项混搭，因此选择串就是主题名。 */
export function 读取当前主题选择(设置: 游戏设置 = 获取游戏设置()): string {
  const 结果 = 解析游戏主题(设置);
  return 生成主题选择(结果.主题 ?? 默认主题编号);
}

let 上次键 = "";
let 上次结果: 主题解析结果 | undefined;
/** 页面与音频频繁读取相同设置；只缓存解析，不缓存绘制对象或声音节点。 */
export function 读取有效游戏主题(设置: 游戏设置): 主题解析结果 {
  const 键 = JSON.stringify([设置.主题选择, 设置.背景动态]);
  if (键 !== 上次键 || !上次结果) {
    上次结果 = 解析游戏主题(设置);
    上次键 = 键;
  }
  return 上次结果;
}

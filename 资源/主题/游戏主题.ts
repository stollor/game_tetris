/**
 * 《再消一行》Three 版的游戏主题：把 `资源/主题/配色/主题读取.ts` 的语义主题与方块外观
 * 换算成 Three 版使用的数值色。页面与对局共用同一份主题数据，不各取各的配置。
 */

function 颜色值(颜色: string): number {
  return Number.parseInt(颜色.replace("#", ""), 16);
}

function 亮度(色值: number): number {
  const 红 = (色值 >> 16) & 0xff;
  const 绿 = (色值 >> 8) & 0xff;
  const 蓝 = 色值 & 0xff;
  return (红 * 299 + 绿 * 587 + 蓝 * 114) / 1000;
}

/** 主题槽位里的取值，供本文件换算数值色。 */
function 槽值(解析: ReturnType<typeof 读取有效游戏主题>, 槽: string): unknown {
  return 解析.槽位.find((项) => 项.槽位.编号 === 槽)?.资源.值;
}

/** 设置 → 游戏主题。像素主题用自己的配色，其余按设置里的主题样式取色。 */
export function 创建游戏主题(设置: 游戏设置 = 获取游戏设置(), 预览样式?: 样式选择): 游戏主题 {
  设置 = 主题结果转设置(设置, 读取有效游戏主题(设置));
  const 解析 = 读取有效游戏主题(设置);
  const 配色值 = 槽值(解析, "界面配色");
  const 样式 = 预览样式 ?? (typeof 配色值 === "string" && 是像素主题(配色值) ? 配色值 : 设置.样式);
  const 主题 = 界面主题(样式);
  const 方块 = 解析方块外观(槽值(解析, "方块外观"));
  const 底色 = 颜色值(主题.页面.背景);
  return {
    名称: 主题.元信息.名称,
    深色: 亮度(底色) < 132,
    颜色: {
      底色,
      面板: 颜色值(主题.面板.主面板.背景),
      浮层: 颜色值(主题.面板.次级面板.背景),
      描边: 颜色值(主题.面板.主面板.描边),
      主字: 颜色值(主题.文字.主要),
      次字: 颜色值(主题.文字.次要),
      暗字: 颜色值(主题.文字.弱化),
      强调: 颜色值(主题.文字.强调),
      成功: 颜色值(主题.文字.成功),
      警告: 颜色值(主题.文字.警告),
      危险: 颜色值(主题.文字.危险),
    },
    方块: { ...方块.颜色 },
  };
}

import type { 样式选择 } from "../../../.gamemaker/依赖/框架/设置/设置";
import { 界面主题, 颜色值 } from "./主题读取";

/** 页面级语义色：一次性从 `资源/主题/配色/主题读取.ts` 换算，页面不写颜色字面量。 */
export interface 页面语义色 {
  背景: number;
  面板: number;
  面板描边: number;
  正文: number;
  次要: number;
  弱化: number;
  强调: number;
  分组线: number;
  按钮底: number;
  轨道: number;
  遮罩: number;
  遮罩透明度: number;
}

export function 读取页面语义色(样式?: 样式选择): 页面语义色 {
  const 主题 = 界面主题(样式);
  return {
    背景: 颜色值(主题.页面.背景),
    面板: 颜色值(主题.面板.主面板.背景),
    面板描边: 颜色值(主题.面板.主面板.描边),
    正文: 颜色值(主题.面板.主面板.正文文字),
    次要: 颜色值(主题.文字.次要),
    弱化: 颜色值(主题.文字.弱化),
    强调: 颜色值(主题.文字.强调),
    分组线: 颜色值(主题.面板.分组线),
    按钮底: 颜色值(主题.按钮.次要.默认.背景),
    轨道: 颜色值(主题.输入框.轨道),
    遮罩: 颜色值(主题.面板.遮罩.背景),
    遮罩透明度: 主题.面板.遮罩.透明度,
  };
}

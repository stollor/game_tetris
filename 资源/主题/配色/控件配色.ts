import type { 游戏主题 } from "../../../代码/应用/接口/服务";
import type { 界面配色 } from "../../../.gamemaker/依赖/框架/界面/控件/类型";
import { 收藏色 } from "./收藏配色";

/**
 * 游戏主题 → 控件库界面配色。控件只认语义角色，换主题时页面不重新取色。
 */

function 亮度(色值: number): number {
  const 红 = (色值 >> 16) & 0xff;
  const 绿 = (色值 >> 8) & 0xff;
  const 蓝 = 色值 & 0xff;
  return (红 * 299 + 绿 * 587 + 蓝 * 114) / 1000;
}

/** 在给定底色上应使用的文字色。 */
export function 主题对比字色(底色: number): number {
  return 亮度(底色) > 150 ? 收藏色.墨 : 收藏色.纸;
}

function 提亮(颜色: number, 比例: number): number {
  const 通道 = (偏移: number) => Math.round(((颜色 >> 偏移) & 0xff) * (1 - 比例) + 0xff * 比例);
  return (通道(16) << 16) | (通道(8) << 8) | 通道(0);
}

export function 主题转界面配色(主题: 游戏主题): 界面配色 {
  const { 颜色 } = 主题;
  const 遮罩 = 主题.深色 ? 收藏色.夜 : 收藏色.墨;
  return {
    底色: 颜色.底色,
    面板: 颜色.面板,
    浮层: 颜色.浮层,
    描边: 颜色.描边,
    主字: 颜色.主字,
    次字: 颜色.次字,
    弱字: 颜色.暗字,
    强调: 颜色.强调,
    强调字: 主题对比字色(颜色.强调),
    主按钮面板: 颜色.强调,
    主按钮字: 主题对比字色(颜色.强调),
    次按钮面板: 颜色.浮层,
    次按钮字: 颜色.主字,
    危险: 颜色.危险,
    成功: 颜色.成功,
    警告: 颜色.警告,
    遮罩,
    遮罩透明度: 0.8,
  };
}

/** 顶栏按钮悬浮底：比面板再亮一点。 */
export function 主题提亮(颜色: number, 比例 = 0.12): number {
  return 提亮(颜色, 比例);
}

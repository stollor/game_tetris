import type { 字号档 } from "../../../.gamemaker/依赖/框架/界面/控件/类型";
import type { 文字档位配置 as GM文字档位配置 } from "../../../.gamemaker/依赖/框架/界面/文字档位";
import type { 文字样式 } from "../../../.gamemaker/依赖/框架/界面/绘制/协议";
import { 游戏外观 } from "../外观/游戏外观";
import { 读取霓虹文字样式 } from "./文字样式";

/**
 * 游戏文字配置：默认字体栈、控件三档字号映射与文字档位配置。
 *
 * 框架文字服务的默认字体是中性 "sans-serif"，游戏在这里给出自己的字体栈；
 * 三档字号/字重与旧版三档文字图集和 `视觉/绘制.ts` 的档位语义完全一致
 * （小 14 常规 / 中 18 常规 / 大 24 粗体），只承载语义档位，不改变烘焙字号。
 */

/** 默认字体栈：与 `读取霓虹文字样式` 使用的字体家族同源。 */
export const 默认字体栈: string = 游戏外观.字体.家族;

export const 字号档设置: Record<字号档, { 字号: number; 字重: "常规" | "粗体" }> = {
  小: { 字号: 14, 字重: "常规" },
  中: { 字号: 18, 字重: "常规" },
  大: { 字号: 24, 字重: "粗体" },
};

/** 控件文字档位配置：从字号映射派生，档位名用语义档位名。 */
export const 文字档位配置: GM文字档位配置 = {
  档位: (["小", "中", "大"] as const).map((档) => ({ 名称: 档, 字号: 字号档设置[档].字号 })),
};

/**
 * 文字光栅口径：按**显示字号 1:1 光栅**，既不分档烘焙，也不做字号复用（大字号烘焙、显示时缩小）。
 *
 * 目标平台是 DPR1 手机（`配置/项目设置.json`），画布像素就是 CSS 像素，任何非整数倍缩小都会让
 * 11~18px 的中文笔画出现灰边、断笔：13 号按 16 号光栅缩到 0.8125 时，一屏标签肉眼可见发虚。
 * 共享图集页把多字号混进同一页，实测关掉复用后页数、纹理字节与绘制调用都不变
 * （见 `测试/浏览器/文字图集验收.ts`），所以清晰度没有性能代价。
 * 要重开复用必须先拿出 DPR≥2 真机或 `--DPR=2` 的清晰度证据，并同步改这段说明。
 */
export const 文字光栅口径 = {
  分档烘焙: false,
  字号复用: false,
} as const;

/** 档位 → 共享文字样式：字体与正文颜色取霓虹菜单 token，字号/字重取档位映射。 */
export function 读取档位文字样式(档: 字号档): 文字样式 {
  const 档位 = 字号档设置[档];
  return { ...读取霓虹文字样式("正文"), 字号: 档位.字号, 字重: 档位.字重 };
}

/** 篷檐：上沿跟着罐身圆角走，下沿一排向下鼓的浅扇贝（奶油帘）。 */
function 篷檐路径(
  笔: CanvasRenderingContext2D,
  左: number,
  上: number,
  宽: number,
  篷高: number,
  圆角: number,
  瓣R: number,
  瓣深: number,
): void {
  const 右 = 左 + 宽;
  const 底 = 上 + 篷高;
  const 角 = Math.min(圆角, 宽 / 2, 篷高 * 0.9);
  const 内宽 = 宽 - 角 * 2;
  const 数 = Math.max(2, Math.round(内宽 / (瓣R * 2)));
  const 步 = 内宽 / 数;
  笔.moveTo(左 + 角, 上);
  笔.lineTo(右 - 角, 上);
  笔.arcTo(右, 上, 右, 上 + 角, 角);
  笔.lineTo(右, 底);
  for (let 序 = 0; 序 < 数; 序 += 1) {
    const 右缘 = 右 - 角 - 步 * 序;
    笔.quadraticCurveTo(右缘 - 步 / 2, 底 + 瓣深 * 2, 右缘 - 步, 底);
  }
  笔.lineTo(左, 底);
  笔.lineTo(左, 上 + 角);
  笔.arcTo(左, 上, 左 + 角, 上, 角);
  笔.closePath();
}

/** 底带：井底一排向上鼓的浅扇贝，瓣沿压进井里，读作罐底裱花。 */
function 底带路径(
  笔: CanvasRenderingContext2D,
  井左: number,
  井宽: number,
  下: number,
  基: number,
  瓣R: number,
  瓣深: number,
): void {
  const 数 = Math.max(2, Math.round(井宽 / (瓣R * 2)));
  const 步 = 井宽 / 数;
  笔.moveTo(井左, 下);
  笔.lineTo(井左, 基);
  for (let 序 = 0; 序 < 数; 序 += 1) {
    const 左缘 = 井左 + 步 * 序;
    笔.quadraticCurveTo(左缘 + 步 / 2, 基 - 瓣深 * 2, 左缘 + 步, 基);
  }
  笔.lineTo(井左 + 井宽, 下);
  笔.closePath();
}

/**
 * 花边圆盘：一圈互相压叠的圆瓣，取它们的并集——瓣是圆的、瓣间是尖缝，
 * 读作奖章的花边（与共享「云边」的余弦波不同，这里要的是十二片圆瓣）。
 */
function 花瓣圆盘路径(
  笔: CanvasRenderingContext2D,
  cx: number,
  cy: number,
  半径: number,
  瓣数: number,
): void {
  const 瓣R = 半径 * 0.26;
  const 心距 = 半径 - 瓣R;
  for (let 序 = 0; 序 < 瓣数; 序 += 1) {
    const a = (序 / 瓣数) * Math.PI * 2 - Math.PI / 2;
    const x = cx + Math.cos(a) * 心距;
    const y = cy + Math.sin(a) * 心距;
    笔.moveTo(x + 瓣R, y);
    笔.arc(x, y, 瓣R, 0, Math.PI * 2, false);
  }
}

/** 缎带尾：从奖章盘后向外下垂的一段带子，末端切出 V 口。 */
function 缎带路径(
  笔: CanvasRenderingContext2D,
  cx: number,
  cy: number,
  半径: number,
  向: 1 | -1,
): void {
  const 轮廓 = [
    [0.3, 0.32],
    [1.06, 0.7],
    [1.08, 1.36],
    [0.84, 1.12],
    [0.66, 1.42],
    [0.22, 0.58],
  ] as const;
  笔.moveTo(cx + 向 * 半径 * 轮廓[0][0], cy + 半径 * 轮廓[0][1]);
  for (const [x, y] of 轮廓.slice(1)) 笔.lineTo(cx + 向 * 半径 * x, cy + 半径 * y);
  笔.closePath();
}


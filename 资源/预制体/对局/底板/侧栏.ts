/**
 * 奶油罐：圆角罐身（下移一档的奶油深侧边 + 大柔影）→ 玫瑰木井 →
 * 井底上鼓扇贝 → 罐口篷檐（下垂扇贝压住井沿，带一圈落进井里的柔影）。
 */
export function 画纸杯(
  笔: CanvasRenderingContext2D,
  左: number,
  上: number,
  宽: number,
  高: number,
  圆角: number,
): void {
  const 尺 = 量罐(宽, 高, 圆角);
  const 下 = 上 + 高;
  // 罐口比舱位抬高一档：标题胶囊压在罐肩上（参考图里胶囊中心在罐口之下），
  // 文字仍按舱位中心画，所以只抬罐身、不动胶囊。
  const 抬 = Math.min(5, 高 * 0.06);
  const 罐上 = 上 - 抬;
  const 篷底 = 上 + 尺.篷高;
  const 底基 = 下 - 尺.底高;
  const 井左 = 左 + 尺.边;
  const 井宽 = 宽 - 尺.边 * 2;
  const 井高 = 底基 - 篷底;
  const 井圆 = Math.min(寸.圆角.井, 井宽 / 4, 井高 / 4);

  // ① 罐身：奶油面 + 下移的奶油深侧边，罐底因此露出一圈暗边。
  画块(笔, 色.奶油, 色.奶油深, () => 圆角矩形路径(笔, 左, 罐上, 宽, 高 + 抬, 尺.圆角), {
    侧厚: 寸.侧厚.面板,
    影透明: 寸.影.透明,
  });

  // ② 井：玫瑰木圆角矩形，四周留一圈奶油罐壁；上下边沿稍后由篷檐与底带压住。
  笔.beginPath();
  圆角矩形路径(笔, 井左, 篷底, 井宽, 井高, 井圆);
  填充(笔, 色.玫瑰木);
  描边(笔, 色.玫瑰木深, 1);

  // ③ 底带：先垫一层上移的奶油深做瓣沿暗边，再压奶油面。
  笔.beginPath();
  底带路径(笔, 井左, 井宽, 下 - 1.4, 底基 - 1.6, 尺.底瓣, 尺.底瓣深);
  填充(笔, 色.奶油深);
  笔.beginPath();
  底带路径(笔, 井左, 井宽, 下, 底基, 尺.底瓣, 尺.底瓣深);
  填充(笔, 色.奶油);

  // ④ 篷檐：奶油深侧边（下移）带柔影落进井里，再压奶油面。
  画块(
    笔,
    色.奶油,
    色.奶油深,
    () => 篷檐路径(笔, 左, 罐上, 宽, 尺.篷高 + 抬, 尺.圆角, 尺.篷瓣, 尺.篷瓣深),
    { 侧厚: 2.2, 影透明: 0.55 },
  );

  // ⑤ 篷檐上沿一道更亮的奶油唇：篷檐才不是从罐身上长出来的。
  笔.beginPath();
  笔.moveTo(左 + 尺.圆角, 罐上 + 0.6);
  笔.lineTo(左 + 宽 - 尺.圆角, 罐上 + 0.6);
  笔.strokeStyle = 串(色.奶油浅, 0.7);
  笔.lineWidth = 1.2;
  笔.stroke();
}

/** 标题胶囊：奶油浅描边框 + 玫瑰木浅底，字由文字层压在同一中心。 */
export function 画标签牌(
  笔: CanvasRenderingContext2D,
  中心X: number,
  中心Y: number,
  宽: number,
  高: number,
): void {
  const 左 = 中心X - 宽 / 2;
  const 上 = 中心Y - 高 / 2;
  const 圆 = 高 / 2;
  const 边 = 3;

  // ① 胶囊底：奶油浅外框 + 下移一档的奶油深侧边 + 柔影。
  画块(笔, 色.奶油浅, 色.奶油深, () => 圆角矩形路径(笔, 左, 上, 宽, 高, 圆), {
    侧厚: 2,
    影透明: 0.26,
  });
  笔.beginPath();
  圆角矩形路径(笔, 左 + 0.6, 上 + 0.6, 宽 - 1.2, 高 - 1.2, 圆 - 0.6);
  描边(笔, 色.奶油深, 1.1);

  // ② 内层玫瑰木底：比罐口的井亮一档，胶囊才浮在篷檐上。
  笔.beginPath();
  圆角矩形路径(笔, 左 + 边, 上 + 边, 宽 - 边 * 2, 高 - 边 * 2, Math.max(2, 圆 - 边));
  填充(笔, 色.玫瑰木浅);
  描边(笔, 色.玫瑰木深, 1);
}

/** 金杯：横杯口、收口杯身、两侧杯柄、杯脚与底座；金面 + 下移一档的金深侧边。 */
function 画金杯(笔: CanvasRenderingContext2D, cx: number, cy: number, 半径: number): void {
  const 画 = (下移: number, 面: number) => {
    const R = 半径;
    const 杯Y = cy - R * 0.42 + 下移;
    // 杯口横唇
    笔.beginPath();
    圆角矩形路径(笔, cx - R * 0.33, 杯Y - R * 0.26, R * 0.66, R * 0.1, R * 0.05);
    填充(笔, 面);
    // 杯身：上沿贴着杯口、下沿收成圆底
    笔.beginPath();
    笔.moveTo(cx - R * 0.27, 杯Y - R * 0.16);
    笔.lineTo(cx + R * 0.27, 杯Y - R * 0.16);
    笔.quadraticCurveTo(cx + R * 0.24, 杯Y + R * 0.04, cx + R * 0.09, 杯Y + R * 0.07);
    笔.quadraticCurveTo(cx, 杯Y + R * 0.09, cx - R * 0.09, 杯Y + R * 0.07);
    笔.quadraticCurveTo(cx - R * 0.24, 杯Y + R * 0.04, cx - R * 0.27, 杯Y - R * 0.16);
    笔.closePath();
    填充(笔, 面);
    // 杯柄：两侧半圆环，开口朝杯身
    笔.strokeStyle = 串(面);
    笔.lineWidth = R * 0.07;
    笔.beginPath();
    笔.arc(cx + R * 0.3, 杯Y - R * 0.1, R * 0.13, -Math.PI * 0.46, Math.PI * 0.46, false);
    笔.stroke();
    笔.beginPath();
    笔.arc(cx - R * 0.3, 杯Y - R * 0.1, R * 0.13, Math.PI * 0.54, Math.PI * 1.46, false);
    笔.stroke();
    // 杯脚 + 底座
    笔.beginPath();
    圆角矩形路径(笔, cx - R * 0.045, 杯Y + R * 0.06, R * 0.09, R * 0.15, R * 0.03);
    填充(笔, 面);
    笔.beginPath();
    圆角矩形路径(笔, cx - R * 0.17, 杯Y + R * 0.2, R * 0.34, R * 0.09, R * 0.045);
    填充(笔, 面);
  };
  画(1.2, 色.金深);
  画(0, 色.金);
}

/** 奖章盘：两条粉缎带尾 + 花边粉圆盘 + 玫瑰木奖章底 + 金杯（纪录值由矢量层压上）。 */
export function 画奖章盘(
  笔: CanvasRenderingContext2D,
  中心X: number,
  中心Y: number,
  半径: number,
): void {
  // ① 缎带尾：压在盘后，末端 V 口露在盘下方两侧。
  for (const 向 of [-1, 1] as const)
    画块(笔, 色.粉, 色.粉深, () => 缎带路径(笔, 中心X, 中心Y, 半径, 向), {
      侧厚: 2.2,
      影透明: 0.3,
    });

  // ② 花边圆盘：粉面 + 下移的粉深侧边 + 大柔影（外沿不描硬线，保持面是一块纯色）。
  画块(笔, 色.粉, 色.粉深, () => 花瓣圆盘路径(笔, 中心X, 中心Y, 半径, 12), {
    侧厚: 2.4,
    影透明: 0.34,
  });

  // ③ 奖章底：玫瑰木浅圆井，金杯与数值都压在它上面。
  笔.beginPath();
  笔.arc(中心X, 中心Y, 半径 * 0.73, 0, Math.PI * 2);
  填充(笔, 色.奖章);

  // ④ 金杯：画在画布上才有平滑曲线与侧边，矢量层只剩纪录数值。
  画金杯(笔, 中心X, 中心Y, 半径);
}


import { 串, 圆角矩形路径, 填充, 描边, 画块 } from "../../基础/装饰与蒙层/扁平笔法";

/**
 * 底板·侧栏（扁平版）：暂存位与队列位的奶油罐、两枚标题胶囊、底部奖章盘。
 *
 * 罐子是参考图里的「奶油罐」：圆角罐身 + 上沿篷檐（一排下垂扇贝）+ 井底一排上鼓扇贝，
 * 井是玫瑰木；标题胶囊（玫瑰木底 + 奶油描边）压在罐口正中。
 * 扁平规则：面只用一个纯色，立体感靠「奶油深侧边 + 大柔影」，不用渐变、颗粒、内阴影。
 *
 * 文字与方块不在这里画：标题文字走文字服务、方块/预览走矢量动态层，
 * 所以胶囊只做底、井只做底，位置和舱位一一对应。
 */

const 色 = 扁平外观.色;
const 寸 = 扁平外观.尺寸;

/** 把值夹在区间内。 */
function 夹(值: number, 低: number, 高: number): number {
  return Math.max(低, Math.min(高, 值));
}

/** 一只奶油罐的比例尺：罐壁厚、篷檐/底带高、两排扇贝的瓣宽与瓣深。 */
interface 罐尺 {
  边: number;
  圆角: number;
  篷高: number;
  底高: number;
  篷瓣: number;
  篷瓣深: number;
  底瓣: number;
  底瓣深: number;
}

function 量罐(宽: number, 高: number, 圆角: number): 罐尺 {
  const 边 = 夹(宽 * 0.085, 6, 9);
  const 井宽 = 宽 - 边 * 2;
  return {
    边,
    圆角: Math.min(圆角, 寸.圆角.面板 + 2, 宽 / 2, 高 / 3),
    篷高: 夹(高 * 0.11, 22, 34),
    底高: 夹(高 * 0.09, 12, 24),
    篷瓣: 夹(宽 * 0.072, 5.5, 8),
    篷瓣深: Math.max(3.6, 夹(宽 * 0.072, 5.5, 8) * 0.8),
    底瓣: 夹(井宽 * 0.1, 5.5, 8),
    底瓣深: Math.max(3, 夹(井宽 * 0.1, 5.5, 8) * 0.55),
  };
}


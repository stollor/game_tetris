import { 暗色 } from "../../../../.gamemaker/依赖/框架/界面/颜色工具";
import type { 对局布局数据 } from "../../../../代码/页面/布局/对局布局";
import { 扁平外观 } from "../../../主题/糖果/扁平外观";
import { 串, 圆角矩形路径, 填充, 描边, 画块, 铺斜纹 } from "../../基础/装饰与蒙层/扁平笔法";

/**
 * 底板·棋盘：新参考图的扁平 2.5D 棋盘框与井。
 *
 * 几何全部以 `布局.棋盘`（井口 = 方块落点区）为锚点向外量，井矩形永不偏移；
 * 框只往井口外侧长（左右各 14、上下各 16），整块仍落在布局给的棋盘舱位里。
 *
 * 由外到内四层，每层只有纯色面 + 一档侧边 + 一层柔影，没有渐变、内阴影和铆钉：
 *   ① 外框：粉色圆角底板，外沿一圈更亮的粉亮边，底面一道深粉侧边 + 落影
 *   ② 拐杖糖立柱：左右两根奶油／粉 −38° 斜纹立柱，裁在外框圆角里
 *   ③ 井：深酒红纯色 + 一档更深的细点阵，井口压一道暗线
 *   ④ 框内装饰：篷檐奶油条（上沿跟外框圆角、下沿扇贝）→ 内粉带（扇贝压进井口）
 *      → 井底奶油扇贝；三层各自带柔影，影子落在下一层上而不是自己身上
 *
 * 糖果块、幽灵、当前块都由矢量层叠在这张底板之上，这里只画静态外观。
 */

const 色 = 扁平外观.色;
const 寸 = 扁平外观.尺寸;

/** 框厚：自井口向外量。左右受舱位挤压（井口左 14、右 10 到侧栏），比上下薄。 */
const 框厚 = { 左: 14, 上: 16, 右: 14, 下: 16 };
/** 外沿圆角：参考图里框角接近四分之一圆，比框厚再大一档。 */
const 外圆角 = 16;
/** 井口圆角。 */
const 井圆角 = 寸.圆角.井;
/** 篷檐奶油条高度（到下沿波浪基线）。 */
const 篷檐高 = 13;
/** 篷檐下沿扇贝起伏与周期。 */
const 篷檐幅 = 2.6;
const 篷檐瓣距 = 22;
/** 内粉带下沿扇贝压进井口的深度与周期。 */
const 内扇贝幅 = 5.5;
const 内瓣距 = 24;
/** 井底奶油扇贝压进井口的深度。 */
const 底扇贝幅 = 4.8;
/** 井底奶油扇贝的直边厚度。 */
const 底奶油厚 = 5.2;
/** 立柱斜纹：比共享规格稍宽，才对得上参考图拐杖糖的大条宽。 */
const 柱条宽 = 8;
const 柱条距 = 16;
/** 井底扇贝周期：参考图约 0.8 格。 */
const 瓣距 = 21;
/** 井点阵点距与半径（参考图 10 世界像素 / 0.9）。 */
const 点距 = 10;
const 点半径 = 0.9;

interface 框矩形 {
  左: number;
  上: number;
  宽: number;
  高: number;
}

/** 一条横向扇贝边：从 起X 到 止X 铺一串二次曲线瓣，`峰` 为正朝下、为负朝上。 */
function 横扇贝(
  笔: CanvasRenderingContext2D,
  起X: number,
  止X: number,
  y: number,
  峰: number,
  周期 = 瓣距,
): void {
  const 长 = 止X - 起X;
  const 数 = Math.max(1, Math.round(Math.abs(长) / 周期));
  const 步 = 长 / 数;
  for (let i = 1; i <= 数; i += 1)
    笔.quadraticCurveTo(起X + 步 * (i - 0.5), y + 峰 * 2, 起X + 步 * i, y);
}

/** 篷檐：压在框顶的奶油条，上沿交给外框裁剪，下沿扇贝。 */
function 篷檐路径(笔: CanvasRenderingContext2D, 外: 框矩形): void {
  const 左 = 外.左 - 1.2;
  const 右 = 外.左 + 外.宽 + 1.2;
  const 底 = 外.上 + 篷檐高;
  笔.moveTo(左, 外.上 - 1.2);
  笔.lineTo(右, 外.上 - 1.2);
  笔.lineTo(右, 底);
  横扇贝(笔, 右, 左, 底, 篷檐幅, 篷檐瓣距);
  笔.closePath();
}

/** 内粉带：篷檐下面露出的粉框带，下沿扇贝压进井口。 */
function 内粉带路径(笔: CanvasRenderingContext2D, 外: 框矩形, 井上: number): void {
  const 左 = 外.左 - 1.2;
  const 右 = 外.左 + 外.宽 + 1.2;
  const 顶 = 外.上 + 篷檐高 - 2.4;
  笔.moveTo(左, 顶);
  笔.lineTo(右, 顶);
  笔.lineTo(右, 井上);
  横扇贝(笔, 右, 左, 井上, 内扇贝幅, 内瓣距);
  笔.closePath();
}

/** 井底奶油扇贝：直边落在井口下面，一串半圆压进井底。 */
function 底扇贝路径(笔: CanvasRenderingContext2D, 外: 框矩形, 井下: number): void {
  const 左 = 外.左 - 1.2;
  const 右 = 外.左 + 外.宽 + 1.2;
  const 直边 = 井下 + 底奶油厚;
  笔.moveTo(左, 直边);
  笔.lineTo(右, 直边);
  笔.lineTo(右, 井下);
  横扇贝(笔, 右, 左, 井下, -底扇贝幅);
  笔.closePath();
}

/**
 * 画糖果棋盘：外框、拐杖糖立柱、篷檐、内粉带、井底扇贝与井点阵。
 * 井矩形与 `布局.棋盘` 完全一致，方块落点区不变。
 */
export function 画糖果棋盘(笔: CanvasRenderingContext2D, 布局: 对局布局数据): void {
  const 井 = 布局.棋盘;
  const 井下 = 井.上 + 井.高;
  const 井右 = 井.左 + 井.宽;
  const 外: 框矩形 = {
    左: 井.左 - 框厚.左,
    上: 井.上 - 框厚.上,
    宽: 井.宽 + 框厚.左 + 框厚.右,
    高: 井.高 + 框厚.上 + 框厚.下,
  };

  /* ---------- ① 外框底板：柔影 + 一档侧边 + 纯粉面 ---------- */
  画块(笔, 色.粉, 色.粉深, () => 圆角矩形路径(笔, 外.左, 外.上, 外.宽, 外.高, 外圆角), {
    侧厚: 寸.侧厚.面板,
    影透明: 0.3,
  });
  // 外沿亮边：扁平图里外轮廓靠一圈更亮的粉收口，不用描边阴影。
  笔.save();
  笔.beginPath();
  圆角矩形路径(笔, 外.左 + 0.9, 外.上 + 0.9, 外.宽 - 1.8, 外.高 - 1.8, 外圆角 - 0.9);
  描边(笔, 色.粉浅, 1.4, 0.88);
  笔.restore();

  /* ---------- ② 拐杖糖立柱：奶油／粉 −38° 斜纹，裁在外框圆角 + 立柱矩形里 ---------- */
  笔.save();
  笔.beginPath();
  圆角矩形路径(笔, 外.左, 外.上, 外.宽, 外.高, 外圆角);
  笔.clip();
  // 斜带是整高平行四边形，必须按立柱宽度再裁一次，否则底带会漏出斜纹。
  for (const [柱左, 柱宽] of [
    [外.左, 井.左 - 外.左],
    [井右, 外.左 + 外.宽 - 井右],
  ] as const) {
    笔.save();
    笔.beginPath();
    笔.rect(柱左, 外.上, 柱宽, 外.高);
    笔.clip();
    铺斜纹(笔, 柱左, 外.上, 柱宽, 外.高, 色.奶油, { 条宽: 柱条宽, 间距: 柱条距 });
    笔.restore();
  }
  笔.restore();

  /* ---------- ③ 井：深酒红纯色 + 更深的细点阵 ---------- */
  笔.save();
  笔.beginPath();
  圆角矩形路径(笔, 井.左, 井.上, 井.宽, 井.高, 井圆角);
  笔.clip();
  填充(笔, 色.井);
  const 点色 = 串(暗色(色.井, 0.26), 0.45);
  笔.fillStyle = 点色;
  笔.beginPath();
  for (let 纵 = 井.上 + 点距 * 0.5; 纵 < 井下; 纵 += 点距) {
    for (let 横 = 井.左 + 点距 * 0.5; 横 < 井右; 横 += 点距) {
      笔.moveTo(横 + 点半径, 纵);
      笔.arc(横, 纵, 点半径, 0, Math.PI * 2);
    }
  }
  笔.fill();
  笔.restore();

  // 井口压一道暗线，把井与框分开（同色系深一档，不用内阴影）。
  笔.save();
  笔.beginPath();
  圆角矩形路径(笔, 井.左 + 0.4, 井.上 + 0.4, 井.宽 - 0.8, 井.高 - 0.8, 井圆角);
  描边(笔, 暗色(色.井, 0.55), 1.1, 0.5);
  笔.restore();

  /* ---------- ④ 框内装饰：全部裁在外框圆角里，影子落在下一层上 ---------- */
  笔.save();
  笔.beginPath();
  圆角矩形路径(笔, 外.左, 外.上, 外.宽, 外.高, 外圆角);
  笔.clip();

  // 内粉带：篷檐下方露出的一圈粉框，扇贝压进井口，柔影落在井上。
  画块(笔, 色.粉, 色.粉深, () => 内粉带路径(笔, 外, 井.上), {
    侧厚: 2,
    影透明: 0.32,
  });

  // 井底奶油扇贝：压在井底沿，影子落在下方粉带与井底之间；扇贝本身不叠侧边，
  // 免得奶油深色在粉带上读成一条金线。
  画块(笔, 色.奶油, 色.奶油深, () => 底扇贝路径(笔, 外, 井下), {
    侧厚: 0,
    影透明: 0.3,
  });

  // 篷檐奶油条最后压顶，影子落在内粉带上。
  画块(笔, 色.奶油浅, 色.奶油深, () => 篷檐路径(笔, 外), {
    侧厚: 0,
    影透明: 0.3,
  });
  笔.restore();
}

/** 巧克力条（左移 / 右移）：圆角长条，面上三段斜纹，底下露一档深棕侧边。 */
function 画巧克力键(
  笔: CanvasRenderingContext2D,
  中心X: number,
  中心Y: number,
  区宽: number,
  区高: number,
): void {
  const 宽 = 区宽 - 3;
  const 高 = Math.min(区高 * 0.74, 宽 / 2.15);
  const 左 = 中心X - 宽 / 2;
  const 顶 = 中心Y - 高 / 2 - 寸.侧厚.键 / 2;
  const 圆角 = Math.min(寸.圆角.键, 高 * 0.18);
  const 路径 = () => 圆角矩形路径(笔, 左, 顶, 宽, 高, 圆角);
  画块(笔, 色.巧克力, 色.巧克力深, 路径);
  // 三段斜纹：右上到左下，压进键面圆角里
  笔.save();
  笔.beginPath();
  路径();
  笔.clip();
  铺斜纹(笔, 左, 顶, 宽, 高, 色.巧克力深, {
    条宽: 宽 * 0.13,
    间距: 宽 * 0.3,
    角度: 寸.条纹.角度,
    透明: 0.16,
  });
  笔.restore();
}

/**
 * 软降·糖纸糖：粉色胶囊身 + 顶部亮带 + 两端三瓣扭结 + 金箍。
 * 中央双人字图标留给矢量层（与其它键同一套图标笔画）。
 */
function 画糖纸糖(
  笔: CanvasRenderingContext2D,
  中心X: number,
  中心Y: number,
  区宽: number,
  区高: number,
): void {
  const 总宽 = 区宽 * 0.9;
  const 身高 = 区高 * 0.68;
  const 扭宽 = 总宽 * 0.12;
  const 身宽 = 总宽 - 扭宽 * 2;
  const 中心 = 中心Y - 寸.侧厚.键 / 2;
  const 身左 = 中心X - 身宽 / 2;
  const 身顶 = 中心 - 身高 / 2;

  // ① 两端三瓣扭结：三片花瓣作一条路径落影压色，再用深粉折缝把三瓣读出来
  for (const 向 of [-1, 1] as const) {
    const 根X = 中心X + 向 * (身宽 / 2 - 2);
    const 瓣纵 = 身高 * 0.19;
    const 瓣横 = 扭宽 * 0.58;
    const 瓣心 = [
      { x: 根X + 向 * 瓣横 * 0.5, y: 中心 - 瓣纵 * 1.5 },
      { x: 根X + 向 * 瓣横, y: 中心 },
      { x: 根X + 向 * 瓣横 * 0.5, y: 中心 + 瓣纵 * 1.5 },
    ];
    画块(
      笔,
      色.糖纸扭结,
      色.糖纸扭结,
      () => {
        for (const 点 of 瓣心) {
          笔.moveTo(点.x + 瓣横, 点.y);
          笔.ellipse(点.x, 点.y, 瓣横, 瓣纵, 0, 0, Math.PI * 2);
        }
      },
      { 侧厚: 0, 影透明: 0.34 },
    );
    for (const 点 of 瓣心) {
      笔.beginPath();
      笔.ellipse(点.x, 点.y, 瓣横, 瓣纵, 0, 0, Math.PI * 2);
      描边(笔, 色.糖纸深, 1, 0.35);
    }
  }

  // ② 糖身：大柔影 + 深粉侧边 + 纯色粉面
  const 身路径 = () => 圆角矩形路径(笔, 身左, 身顶, 身宽, 身高, 身高 / 2);
  画块(笔, 色.糖纸, 色.糖纸深, 身路径);

  // ③ 顶部亮带：糖身里一道更亮的窄带，贴着上沿
  笔.save();
  笔.beginPath();
  身路径();
  笔.clip();
  笔.beginPath();
  圆角矩形路径(笔, 身左 + 3, 身顶 + 1, 身宽 - 6, 身高 * 0.14, 身高 * 0.1);
  填充(笔, 色.糖纸浅);
  笔.restore();

  // ④ 金箍：糖身两端各一道竖金条
  const 箍宽 = Math.max(4.2, 身宽 * 0.045);
  const 箍高 = 身高 * 0.6;
  for (const 向 of [-1, 1] as const) {
    const 箍左 = 中心X + 向 * (身宽 / 2) - 箍宽 / 2 - 向 * 1.5;
    笔.beginPath();
    圆角矩形路径(笔, 箍左, 中心 - 箍高 / 2, 箍宽, 箍高, 2.2);
    填充(笔, 色.金);
    描边(笔, 色.金深, 1);
  }
}

/* ------------------------------------------------------------------ */
/* 六键的键身                                                          */
/* ------------------------------------------------------------------ */

/** 画一颗键的键身（不含图标）。矩形取对局布局里这颗键的区域。 */
export function 画糖果键身(
  笔: CanvasRenderingContext2D,
  键: 对局布局操作键,
  左: number,
  上: number,
  宽: number,
  高: number,
): void {
  const 中心X = 左 + 宽 / 2;
  const 中心Y = 上 + 高 / 2;
  if (键.名称 === "左转") 画饼干键(笔, 中心X, 中心Y, 宽, 高);
  else if (键.名称 === "暂存操作") 画威化键(笔, 中心X, 中心Y, 宽, 高);
  else if (键.名称 === "右转") 画甜甜圈键(笔, 中心X, 中心Y, 宽, 高);
  else if (键.名称 === "软降") 画糖纸糖(笔, 中心X, 中心Y, 宽, 高);
  else 画巧克力键(笔, 中心X, 中心Y, 宽, 高);
}


/** 花边漩涡饼干（左转）：一圈花边，纯色饼干面，底下露一档焦糖侧边。 */
function 画饼干键(
  笔: CanvasRenderingContext2D,
  中心X: number,
  中心Y: number,
  区宽: number,
  区高: number,
): void {
  const 横半径 = Math.min(区宽 * 0.3, 区高 * 0.67);
  const 纵半径 = 区高 * 0.44;
  const 中心 = 中心Y - 寸.侧厚.键 / 2;
  画块(笔, 色.饼干, 色.饼干深, () => 花边椭圆路径(笔, 中心X, 中心, 横半径, 纵半径, 11), {});
}

/** 波浪边威化（暂存）：四边一圈圆齿，橙色纯色面，底下露一档暗橙侧边。 */
function 画威化键(
  笔: CanvasRenderingContext2D,
  中心X: number,
  中心Y: number,
  区宽: number,
  区高: number,
): void {
  const 瓣 = Math.max(3.6, Math.min(区高 * 0.1, 5.6));
  const 宽 = 区宽 * 0.89;
  const 高 = 区高 * 0.89;
  const 左 = 中心X - 宽 / 2;
  const 顶 = 中心Y - 高 / 2 - 寸.侧厚.键 / 2;
  画块(
    笔,
    色.威化,
    色.威化深,
    () => 扇贝矩形路径(笔, 左 + 瓣, 顶 + 瓣, 宽 - 瓣 * 2, 高 - 瓣 * 2, 瓣),
    {},
  );
}

/** 糖霜甜甜圈（右转）：更密的一圈云朵边，粉色纯色面，底下露一档深粉侧边。 */
function 画甜甜圈键(
  笔: CanvasRenderingContext2D,
  中心X: number,
  中心Y: number,
  区宽: number,
  区高: number,
): void {
  const 横半径 = Math.min(区宽 * 0.32, 区高 * 0.7);
  const 纵半径 = 区高 * 0.45;
  const 中心 = 中心Y - 寸.侧厚.键 / 2;
  画块(笔, 色.甜甜圈, 色.甜甜圈深, () => 花边椭圆路径(笔, 中心X, 中心, 横半径, 纵半径, 10), {});
}


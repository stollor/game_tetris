/** 玫瑰木托盘：亮粉圆角框 + 玫瑰木内面，整盘一道大柔影落在背景上。 */
export function 画糖果操作托盘(
  笔: CanvasRenderingContext2D,
  左: number,
  上: number,
  宽: number,
  高: number,
): void {
  const 圆角 = Math.min(16, 高 * 0.13);
  const 边厚 = Math.max(4, Math.min(6, 高 * 0.04));
  // ① 亮粉圆角框（顺带落整盘柔影）
  画块(笔, 色.托边, 色.托边, () => 圆角矩形路径(笔, 左, 上, 宽, 高, 圆角), {
    侧厚: 0,
    影透明: 0.4,
  });
  // ② 玫瑰木内面
  笔.beginPath();
  圆角矩形路径(笔, 左 + 边厚, 上 + 边厚, 宽 - 边厚 * 2, 高 - 边厚 * 2, Math.max(5, 圆角 - 边厚));
  填充(笔, 色.托底);
}


/** 触屏操作键底板：GM `.gamemaker/依赖/框架/界面/按钮` 默认底板（玻璃按钮）+ 主题配色。 */
export function 绘制操作键底板(
  绘图: 图形对象,
  参数: 操作键参数,
  配色: { 面板色: number; 边框色: number },
): void {
  const { 矩形, 可用, 高亮 } = 参数;
  if (是像素风格()) {
    绘制像素面板(
      绘图,
      矩形.左,
      矩形.上,
      矩形.宽,
      矩形.高,
      高亮 ? 像素规范.色.黄 : 可用 ? 像素规范.色.纸 : 像素规范.色.暗纸,
    );
    return;
  }
  // 糖果顶栏角钮：粉糖胶囊按钮，高亮时换成草莓粉糖体。
  if (是糖果风格()) {
    绘制糖果按钮(绘图, 矩形.左 + 矩形.宽 / 2, 矩形.上 + 矩形.高 / 2, 矩形.宽, 矩形.高, {
      填色: 高亮 ? 糖果规范.色.草莓浅 : 糖果规范.色.粉,
      边框色: 糖果规范.色.草莓深,
      强调色: 糖果规范.色.金,
      选中: 高亮 ?? false,
      透明度: 可用 ? 1 : 0.55,
      圆角: 糖果规范.圆角.小,
      糖纸: false,
    });
    return;
  }
  const 中心X = 矩形.左 + 矩形.宽 / 2;
  const 中心Y = 矩形.上 + 矩形.高 / 2;
  绘制玻璃按钮底板(绘图, 中心X, 中心Y, 矩形.宽, 矩形.高, {
    填色: 配色.面板色,
    边框色: 配色.边框色,
    强调色: 配色.边框色,
    透明度: 可用 ? 0.92 : 0.5,
    边透明度: 可用 ? 0.55 : 0.3,
    悬停: false,
    选中: 高亮 ?? false,
  });
}

export interface 暂停面板参数 {
  矩形: 矩形;
  遮罩色: number;
  遮罩透明度: number;
  面板色: number;
  描边色: number;
  强调色: number;
  逻辑宽: number;
  逻辑高: number;
}

/** 暂停面板：全屏遮罩 + 玻璃面板（GM `.gamemaker/依赖/框架/界面/暂停菜单` 的面板视觉）。 */
export function 绘制暂停面板(绘图: 图形对象, 参数: 暂停面板参数): void {
  const { 矩形, 遮罩色, 遮罩透明度, 面板色, 描边色, 强调色, 逻辑宽, 逻辑高 } = 参数;
  if (是像素风格()) {
    绘图.fillStyle(像素规范.色.夜, 遮罩透明度).fillRect(0, 0, 逻辑宽, 逻辑高);
    绘制像素面板(绘图, 矩形.左, 矩形.上, 矩形.宽, 矩形.高);
    return;
  }
  // 糖果暂停层：巧克力遮罩 + 奶油裱花面板。
  if (是糖果风格()) {
    绘图.fillStyle(糖果规范.色.巧克力深, 遮罩透明度).fillRect(0, 0, 逻辑宽, 逻辑高);
    绘制糖果面板(绘图, 矩形.左, 矩形.上, 矩形.宽, 矩形.高, {
      圆角: 糖果规范.圆角.面板,
      填色: 糖果规范.色.巧克力浅,
      边色: 糖果规范.色.草莓,
      底边色: 糖果规范.色.巧克力深,
      高光: true,
      铆钉: true,
    });
    return;
  }
  绘图.fillStyle(遮罩色, 遮罩透明度).fillRect(0, 0, 逻辑宽, 逻辑高);
  绘制玻璃面板基底(绘图, 矩形.左, 矩形.上, 矩形.宽, 矩形.高, {
    圆角: 16,
    填色: 面板色,
    透明度: 0.98,
    边色: 描边色,
    边透明度: 0.8,
    强调色,
  });
}

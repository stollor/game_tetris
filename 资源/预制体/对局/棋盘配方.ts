/** 预览卡：玻璃面板 + 首卡强调条（取自 下一个方块栏 的原绘制）。 */
export function 绘制预览卡(绘图: 图形对象, 参数: 预览卡参数): void {
  const { 左, 上, 宽, 高, 圆角, 填色, 边色, 边透明度, 强调色, 高光, 首位 } = 参数;
  if (是像素风格()) {
    绘制像素面板(绘图, 左, 上, 宽, 高, 像素规范.色.夜, 首位 ? 像素规范.色.青 : 像素规范.色.紫);
    return;
  }
  // 糖果预览卡：草莓粉纸页，首位左侧补一条金色糖条。
  if (是糖果风格()) {
    const 色 = 糖果规范.色;
    绘制糖果纸页(绘图, 左, 上, 宽, 高, {
      圆角: Math.max(圆角, 糖果规范.圆角.卡片),
      填色: 首位 ? 色.草莓浅 : 色.奶油,
      边色: 首位 ? 色.草莓 : 色.奶油深,
      透明度: 0.98,
    });
    if (首位) 绘图.fillStyle(色.金, 0.92).fillRoundedRect(左 + 4, 上 + 8, 3, 高 - 16, 2);
    return;
  }
  绘制玻璃面板基底(绘图, 左, 上, 宽, 高, {
    圆角,
    填色,
    透明度: 0.98,
    边色,
    边透明度,
    投影: false,
    高光,
    强调色,
  });
  if (首位) {
    绘图.fillStyle(边色, 0.85).fillRoundedRect(左 + 3, 上 + 10, 3, 高 - 20, 2);
  }
}


/** 棋盘底：外框 + 网格。位置与外观不变，独立成层后不要跟已落格子一起重建。 */
export function 绘制棋盘底(
  绘图: 图形对象,
  输入: 棋盘输入,
  棋盘左 = 输入.棋盘.左 + 输入.偏移X,
  棋盘上 = 输入.棋盘.上 + 输入.偏移Y,
): void {
  // 透视主题的井是 3D 房间，2D 底板会整块盖住它；拆带后这个入口被单独调用，必须自己守门控。
  if (是透视棋盘()) return;
  棋盘2D绘制计数.底 += 1;
  const { 宽, 高, 列, 行 } = 输入.棋盘;
  const 格 = 输入.格子大小;
  绘制棋盘外框(绘图, {
    左: 棋盘左,
    上: 棋盘上,
    宽,
    高,
    格子: 格,
    透明度: 1,
    背景色: 游戏外观.棋盘.背景色,
    边框色: 游戏外观.棋盘.边框色,
  });
  if (!输入.显示网格) return;
  绘图.save();
  if (输入.网格透明度 != null) 绘图.setAlpha(输入.网格透明度);
  绘图.translateCanvas(棋盘左, 棋盘上);
  绘制棋盘网格(绘图, {
    宽,
    高,
    格子: 格,
    列数: 列,
    行数: 行,
    网格色: 读取对局界面色().网格线,
  });
  绘图.restore();
}


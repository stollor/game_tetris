/**
 * 「糖果超甜」的对局仪表：三块奶油裱花名牌（LV / 分数 / 行数），
 * 巧克力底 + 草莓粉面 + 金色读数，分数牌顶一只蝴蝶结，底沿一条金灯带。
 *
 * 坐标全部沿用 `计算对局仪表` 的舱位，不另立布局；读数仍走滚动数位与同一套文字样式，
 * 只把形状换成糖纸语言。只在 `仪表表现 = 糖果` 时被 `绘制对局仪表` 调起。
 */

type 仪表定位 = ReturnType<typeof 计算对局仪表>;

const 色 = 糖果规范.色;

function 创建名牌字(笔: 画笔) {
  return (文案: string, x: number, 底: number, 字号: number, 宽: number, 颜色: number) => {
    let 样式 = 读取对局文字样式("信息数值", { 字号, 颜色 });
    const 测 = 笔.测量文字(文案, 样式);
    if (测.宽 > 宽) 样式 = { ...样式, 字号: Math.max(11, (字号 * 宽) / 测.宽) };
    const 高 = 笔.测量文字(文案, 样式).高;
    笔.绘制文字({ 文案, 样式, 锚点: "中上", x, y: 底 - 高 + Math.max(0, 样式.字号 - 21) / 4 });
  };
}

/** 一块奶油名牌：巧克力底、草莓粉面、奶油裱花内衬与顶边扇贝。 */
function 绘制名牌(
  笔: 画笔,
  矩: { 左: number; 上: number; 宽: number; 高: number },
  主: boolean,
): void {
  const 图 = 笔.图形;
  const 圆角 = Math.min(糖果规范.仪表.圆角, 矩.高 / 2);
  // 底板投影
  图.fillStyle(色.巧克力深, 0.4).fillRoundedRect(矩.左 + 1, 矩.上 + 4, 矩.宽, 矩.高, 圆角);
  绘制糖果面板(图, 矩.左, 矩.上, 矩.宽, 矩.高, {
    圆角,
    填色: 主 ? 色.巧克力浅 : 色.巧克力,
    边色: 色.草莓浅,
    铆钉: false,
    花边: false,
    投影: false,
  });
  if (主) {
    // 主牌用蝴蝶结封口，不再加扇贝，避免和上方的模式徽章叠两层花边。
    if (矩.宽 > 90)
      绘制蝴蝶结(图, 矩.左 + 矩.宽 / 2, 矩.上 + 2, Math.min(20, 矩.宽 * 0.12), 色.粉, 色.草莓深);
  } else {
    // 侧牌顶边扇贝花边：名牌的「糖纸口」。
    绘制扇贝边(
      图,
      矩.左 + 8,
      矩.上,
      矩.宽 - 16,
      色.粉,
      0.95,
      "上",
      糖果规范.仪表.花边步长 * 0.42,
      糖果规范.仪表.花边步长,
    );
  }
  // 底沿金灯带：与霓虹装置的灯条同一语义，位置改到名牌内侧。
  图
    .fillStyle(色.金, 主 ? 0.9 : 0.55)
    .fillRoundedRect(矩.左 + 14, 矩.上 + 矩.高 - 6, 矩.宽 - 28, 糖果规范.仪表.底部灯条高, 2);
  // 两角糖粒点缀
  绘制糖粒(图, 矩.左 + 12, 矩.上 + 矩.高 * 0.32, 2.2, 色.金, 0.8, 0.4);
  绘制糖粒(图, 矩.左 + 矩.宽 - 12, 矩.上 + 矩.高 * 0.32, 2.2, 色.金, 0.8, -0.4);
}

/** 名牌顶部的语义标记：等级标 LV、行数三条横线或目标菱形，位置沿用装置仪表。 */
function 绘制名牌标记(笔: 画笔, 定位: 仪表定位, 字: ReturnType<typeof 创建名牌字>): void {
  const 图 = 笔.图形;
  const 左X = 定位.左.左 + 定位.左.宽 / 2;
  const 右X = 定位.右.左 + 定位.右.宽 / 2;
  if (定位.计时栏 !== "左") 字("LV", 左X, 定位.左.上 + 19, 10, 定位.左.宽 - 12, 色.粉);
  if (定位.计时栏 === "右") return;
  if (定位.目标行数) {
    图.lineStyle(1.4, 色.粉, 0.85).strokePoints(
      [
        { x: 右X, y: 定位.右.上 + 8 },
        { x: 右X + 5, y: 定位.右.上 + 12 },
        { x: 右X, y: 定位.右.上 + 16 },
        { x: 右X - 5, y: 定位.右.上 + 12 },
      ],
      true,
    );
    return;
  }
  图.lineStyle(1.5, 色.粉, 0.85);
  for (let 序 = 0; 序 < 3; 序 += 1)
    图.lineBetween(右X - 7, 定位.右.上 + 8 + 序 * 4, 右X + 7, 定位.右.上 + 8 + 序 * 4);
}

/** 单个舱位的读数：等级 / 分数 / 行数或计时，与装置仪表共用同一套坐标。 */
function 绘制名牌读数(
  笔: 画笔,
  输入: 对局仪表输入,
  定位: 仪表定位,
  字: ReturnType<typeof 创建名牌字>,
): void {
  const 图 = 笔.图形;
  const 左X = 定位.左.左 + 定位.左.宽 / 2;
  const 右X = 定位.右.左 + 定位.右.宽 / 2;
  const 主X = 定位.分数X;
  const 金 = 色.金;
  const 奶油 = 色.奶油;
  const 次 = 色.粉;
  if (定位.计时栏 !== "左") 字(String(输入.等级), 左X, 定位.数值底, 21, 定位.左.宽 - 12, 金);
  if (定位.目标行数) {
    const 主值 = String(输入.行数);
    const 主样 = 读取对局文字样式("信息数值", { 字号: 36, 颜色: 奶油 });
    const 副样 = 读取对局文字样式("信息数值", { 字号: 18, 颜色: 次 });
    const 主宽 = 笔.测量文字(主值, 主样).宽;
    const 副文 = `/${定位.目标行数}`;
    const 副宽 = 笔.测量文字(副文, 副样).宽;
    const 起 = 主X - (主宽 + 副宽 + 5) / 2;
    字(主值, 起 + 主宽 / 2, 定位.数值底, 36, 主宽 + 1, 奶油);
    字(副文, 起 + 主宽 + 5 + 副宽 / 2, 定位.数值底, 18, 副宽 + 1, 次);
    const 进度 = Math.min(1, 输入.行数 / 定位.目标行数);
    图
      .fillStyle(色.金, 0.85)
      .fillRoundedRect(
        定位.主.左 + 17,
        定位.主.上 + 定位.主.高 - 4,
        (定位.主.宽 - 34) * 进度,
        2.5,
        1.5,
      );
  } else if (定位.计时栏 !== "右") {
    字(String(输入.行数), 右X, 定位.数值底, 21, 定位.右.宽 - 12, 金);
  }
  // 分数：滚动数位、击中时提亮，与现有仪表同一算法。
  const 强度 = 输入.计分.击中;
  const 值 = 输入.计分.显示分数;
  const 位数 = Math.max(6, Math.floor(Math.max(0, 值)).toString().length);
  let 样式 = 读取对局文字样式("信息数值", {
    字号: 定位.分数字号,
    颜色: 混色(奶油, 金, 强度),
  });
  const 数宽 = 笔.测量文字("0".repeat(位数), 样式).宽;
  if (数宽 > 定位.分数宽) 样式 = { ...样式, 字号: (样式.字号 * 定位.分数宽) / 数宽 };
  const 字宽 = 笔.测量文字("0", 样式).宽;
  const 行高 = 笔.测量文字("0", 样式).高;
  const 底 = 定位.数值底 + Math.max(0, 样式.字号 - 21) / 4 - Math.sin(强度 * Math.PI) * 2;
  const 上 = 底 - 行高;
  笔.压入裁剪({ 左: 定位.分数X - 定位.分数宽 / 2, 上, 宽: 定位.分数宽, 高: 行高 });
  读取滚动数位(值, 位数).forEach((位, i) => {
    const x = 定位.分数X + (i - (位数 - 1) / 2) * 字宽;
    笔.绘制文字({ 文案: String(位.数字), 样式, 锚点: "中上", x, y: 上 - 位.进度 * 行高 });
    if (位.进度 > 0)
      笔.绘制文字({ 文案: String(位.下一个), 样式, 锚点: "中上", x, y: 上 + (1 - 位.进度) * 行高 });
  });
  笔.弹出裁剪();
  // 计时（极限模式）：粉牌上的巧克力色时钟与金色读数。
  if (定位.计时栏) {
    const 时限 = 输入.模式 === "极限";
    const 毫秒 = 时限 ? 输入.剩余毫秒 : 输入.有效毫秒;
    const 紧迫 = 时限 && 毫秒 <= 10000;
    const 临近 = 时限 && 毫秒 <= 30000;
    const 脉冲 = 紧迫 && !输入.省电 ? (1 + Math.sin((输入.有效毫秒 / 1000) * Math.PI * 4)) / 2 : 0;
    const 钟色 = 紧迫 ? 色.草莓糖 : 临近 ? 色.柠檬 : 色.金;
    const 槽 = 定位.计时栏 === "右" ? 定位.右 : 定位.左;
    const x = 槽.左 + 槽.宽 / 2;
    const y = 槽.上 + 12;
    图.lineStyle(1.6, 钟色, 0.85).strokeCircle(x, y, 9 + 脉冲);
    图
      .lineStyle(1.6, 钟色, 0.95)
      .lineBetween(x, y - 5, x, y)
      .lineBetween(x, y, x + 4, y + 2);
    字(格式化仪表时间(毫秒, 紧迫), x, 定位.数值底, 紧迫 ? 23 : 22, 槽.宽 - 12, 钟色);
    if (时限)
      图
        .fillStyle(钟色, 0.35 + 脉冲 * 0.35)
        .fillRoundedRect(
          槽.左 + 17,
          槽.上 + 槽.高 - 5,
          (槽.宽 - 34) * Math.min(1, Math.max(0, 毫秒 / 模式配置.极限毫秒)),
          2.5,
          1.5,
        );
  }
}

/** 对局仪表「糖果」表现：静态画三块名牌，动态画读数。 */
export function 绘制对局仪表糖果(笔: 画笔, 输入: 对局仪表输入, 部分: "静态" | "动态"): void {
  const 定位 = 计算对局仪表(输入.布局, 输入.模式);
  const 字 = 创建名牌字(笔);
  if (部分 === "静态") {
    绘制名牌(笔, 定位.左, false);
    绘制名牌(笔, 定位.主, true);
    绘制名牌(笔, 定位.右, false);
    绘制名牌标记(笔, 定位, 字);
    // 名牌之间一小段糖针连线，读作同一串糖果挂饰。
    for (let 序 = 0; 序 < 4; 序 += 1) {
      const t = (序 + 0.5) / 4;
      const y = 定位.主.上 + 定位.主.高 / 2;
      绘制糖粒(
        笔.图形,
        定位.左.左 + 定位.左.宽 + (定位.主.左 - 定位.左.左 - 定位.左.宽) * t,
        y,
        1.4,
        色.粉,
        0.7,
        0.6,
      );
    }
    return;
  }
  绘制名牌读数(笔, 输入, 定位, 字);
}

/** 读取名牌配色（测试与预览用）：不吃灰的语义色别名。 */
export const 糖果仪表配色 = {
  面板: 色.巧克力浅,
  主面板: 色.巧克力,
  描边: 色.草莓浅,
  强调: 色.金,
} as const;

/**
 * 「糖果超甜」的对局仪表：三块玫瑰木票据名牌（LV / 分数 / 行数），分数牌嵌深酒红读数窗、
 * 两侧压麦穗；名牌下方一条糖绳横穿全屏，正中系蝴蝶结，把顶栏和棋盘分开。
 *
 * 坐标全部沿用 `计算对局仪表` 的舱位，不另立布局；读数仍走滚动数位与同一套文字样式，
 * 只把形状换成糖果语言。只在 `仪表表现 = 糖果` 时被 `绘制对局仪表` 调起。
 */

type 仪表定位 = ReturnType<typeof 计算对局仪表>;
type 矩 = { 左: number; 上: number; 宽: number; 高: number };

const 色 = 糖果规范.色;
// 扁平版牌面是玫瑰木，读数走奶油象牙、标签走浅鲑粉（与参考图一致，别再走金/暗玫瑰）。
const 读数阴影 = { 颜色: 0x3f1218, 模糊: 0, 偏移X: 0, 偏移Y: 1 };
const 数值色 = 扁平外观.色.象牙;
const 标签色 = 扁平外观.色.标签粉;

function 创建名牌字(笔: 画笔) {
  return (文案: string, x: number, 底: number, 字号: number, 宽: number, 颜色: number) => {
    let 样式 = { ...读取对局文字样式("信息数值", { 字号, 颜色 }), 阴影: 读数阴影 };
    const 测 = 笔.测量文字(文案, 样式);
    // 字号是文字图集键，必须是整数，否则每个浮点值都会新建一张图集且永不回收。
    if (测.宽 > 宽) 样式 = { ...样式, 字号: 量化字号((字号 * 宽) / 测.宽) };
    const 高 = 笔.测量文字(文案, 样式).高;
    笔.绘制文字({ 文案, 样式, 锚点: "中上", x, y: 底 - 高 + Math.max(0, 样式.字号 - 21) / 4 });
  };
}

function 转边界(矩形: 矩, 缩 = 0): 边界 {
  return {
    左: 矩形.左 + 缩,
    上: 矩形.上 + 缩,
    右: 矩形.左 + 矩形.宽 - 缩,
    下: 矩形.上 + 矩形.高 - 缩,
  };
}

/**
 * 一块奶油糖票名牌：浅奶油/浅粉糖面压在深玫瑰糖边上，六层质感——
 * 三层落影、深玫瑰糖边、上亮下暗糖面、顶棱高光、内嵌奶油读数窗、两侧糖钉耳。
 */
function 绘制名牌(图: 图形对象, 矩形: 矩, 主: boolean): void {
  const 凹 = 主 ? 11 : 9;
  const 填色 = 主 ? 混色(色.粉, 色.奶油, 0.24) : 混色(色.粉, 色.奶油, 0.4);
  const 窗缩 = 主 ? 7 : 6.5;
  // ①接触投影：三层同形下移外扩，浅色名牌压在深色底上才有份量。
  for (const [下移, 外扩, 透明] of [
    [2.2, 0.8, 0.4],
    [5.4, 2.4, 0.22],
    [8.8, 4.6, 0.11],
  ] as const)
    图
      .fillStyle(色.巧克力深, 透明)
      .fillPoints(内凹角多边形(转边界({ ...矩形, 上: 矩形.上 + 下移 }, -外扩), 凹 + 外扩), true);
  // ⑥糖体侧壁：奶油面下移一档压成深奶油，底缘再压暗，读作厚糖片。
  图
    .fillStyle(混色(暗色(填色, 0.26), 色.莓, 0.3), 1)
    .fillPoints(内凹角多边形(转边界({ ...矩形, 上: 矩形.上 + 3.2 }, 0), 凹), true);
  图
    .fillStyle(混色(暗色(填色, 0.44), 色.莓深, 0.24), 0.9)
    .fillPoints(内凹角多边形(转边界({ ...矩形, 上: 矩形.上 + 1.4 }, 0), 凹), true);
  // ②深玫瑰糖边
  图.fillStyle(色.莓深, 1).fillPoints(内凹角多边形(转边界(矩形, -2), 凹 + 2), true);
  // ③奶油糖面：左上受光、右下转成浅粉。
  图
    .fillGradientStyle(
      亮色(填色, 0.2),
      亮色(填色, 0.06),
      混色(填色, 色.粉深, 0.24),
      混色(填色, 色.粉深, 0.44),
      1,
      1,
      1,
      1,
    )
    .fillPoints(内凹角多边形(转边界(矩形), 凹), true);
  // ④顶棱高光：一条窄亮线压在直边上，左侧再补一点镜面。
  图
    .lineStyle(1.8, 色.白, 0.6)
    .lineBetween(矩形.左 + 凹 + 2, 矩形.上 + 1.4, 矩形.左 + 矩形.宽 - 凹 - 2, 矩形.上 + 1.4);
  图
    .fillStyle(色.白, 0.4)
    .fillEllipse(
      矩形.左 + 矩形.宽 * 0.2,
      矩形.上 + 矩形.高 * 0.2,
      矩形.宽 * 0.16,
      Math.max(1.4, 矩形.高 * 0.1),
    );
  // ⑤读数窗：浅浅凹一层，上沿一圈玫瑰影、下沿一条反光唇。
  const 窗边界 = 转边界(矩形, 窗缩);
  const 窗 = 内凹角多边形(窗边界, 凹 - 2);
  const 窗色 = 混色(色.奶油, 色.粉, 主 ? 0.55 : 0.4);
  图.fillStyle(色.莓深, 1).fillPoints(内凹角多边形(转边界(矩形, 窗缩 - 1.2), 凹 - 1.2), true);
  图
    .fillGradientStyle(
      亮色(窗色, 0.12),
      亮色(窗色, 0.12),
      混色(窗色, 色.粉深, 0.3),
      混色(窗色, 色.粉深, 0.34),
      1,
      1,
      1,
      1,
    )
    .fillPoints(窗, true);
  // 窗顶内阴影：直边段内压一条玫瑰暗带，凹角处不铺，避免糊出矩形边。
  图
    .fillGradientStyle(色.莓深, 色.莓深, 色.莓深, 色.莓深, 0.34, 0.34, 0, 0)
    .fillRect(
      窗边界.左 + 凹,
      窗边界.上 + 0.8,
      窗边界.右 - 窗边界.左 - 凹 * 2,
      Math.min(9, (窗边界.下 - 窗边界.上) * 0.34),
    );
  图
    .fillGradientStyle(色.白, 色.白, 色.白, 色.白, 0, 0, 0.5, 0.5)
    .fillRect(
      矩形.左 + 窗缩 + 凹,
      矩形.上 + 矩形.高 - 窗缩 - 2.4,
      矩形.宽 - 窗缩 * 2 - 凹 * 2,
      1.6,
    );
  // 裱线：窗前一圈深玫瑰描边 + 板面内一圈白线，收口干净。
  图.lineStyle(1.3, 色.莓深, 0.72).strokePoints(内凹角多边形(转边界(矩形, 窗缩 - 2.6), 凹), true);
  图.lineStyle(1.1, 色.白, 0.6).strokePoints(内凹角多边形(转边界(矩形, 0.8), 凹 + 0.8), true);
  // 两侧糖钉耳：4px 宽的小耳，把名牌咬在糖墙上。
  for (const 向 of [-1, 1] as const) {
    const 耳X = 向 < 0 ? 矩形.左 - 3.2 : 矩形.左 + 矩形.宽 - 0.8;
    图
      .fillStyle(色.莓深, 1)
      .fillRoundedRect(耳X - 0.6, 矩形.上 + 矩形.高 * 0.3, 4.4, 矩形.高 * 0.44, 2);
    图
      .fillGradientStyle(亮色(填色, 0.22), 亮色(填色, 0.22), 填色, 填色, 1, 1, 1, 1)
      .fillRoundedRect(耳X, 矩形.上 + 矩形.高 * 0.3 + 0.8, 3.2, 矩形.高 * 0.44 - 1.6, 1.6);
  }
  if (!主) return;
  const 中Y = 矩形.上 + 矩形.高 * 0.62;
  绘制麦穗(图, 矩形.左 + 21, 中Y, 1);
  绘制麦穗(图, 矩形.左 + 矩形.宽 - 21, 中Y, -1);
}

/** 麦穗：一根弧形茎上交错四对叶，向读数方向收拢；方向 1 朝右开、−1 镜像。 */
function 绘制麦穗(图: 图形对象, x: number, y: number, 方向: 1 | -1): void {
  const 茎: 点[] = [];
  for (let i = 0; i <= 8; i += 1) {
    const t = i / 8;
    茎.push({ x: x + 方向 * (Math.sin(t * 1.2) * 5), y: y + 10 - t * 22 });
  }
  图.lineStyle(1.2, 混色(色.草莓深, 色.粉深, 0.35), 0.62).strokePoints(茎, false);
  图.fillStyle(混色(色.草莓深, 色.粉深, 0.35), 0.62);
  for (let 序 = 0; 序 < 4; 序 += 1) {
    const t = 0.2 + 序 * 0.22;
    const 根 = 茎[Math.round(t * 8)] ?? { x, y };
    for (const 侧 of [-1, 1]) {
      const 角 = (侧 < 0 ? -2.3 : -0.8) * (方向 > 0 ? 1 : -1) + (方向 > 0 ? 0 : Math.PI);
      const 长 = 5.5 - 序 * 0.6;
      图.save().translateCanvas(根.x, 根.y).rotateCanvas(角);
      图.fillEllipse(长 / 2, 0, 长, 2.4);
      图.restore();
    }
  }
}

/**
 * 名牌顶部的语义标签：LV / SCORE / LINES（限时模式的舱位画时钟图标，不再叠字标签）。
 * 文字一律保留原坐标；行数三横线与目标菱形这类标记形状，底板接管糖果静态外观后交给画布。
 */
function 绘制名牌标记(笔: 画笔, 定位: 仪表定位, 极限 = false): void {
  const 图 = 笔.图形;
  const 左X = 定位.左.左 + 定位.左.宽 / 2;
  const 右X = 定位.右.左 + 定位.右.宽 / 2;
  const 主X = 定位.主.左 + 定位.主.宽 / 2;
  const 标签: [string, number, number][] = [];
  if (定位.计时舱 !== "左") 标签.push(["LV", 左X, 定位.左.宽 - 10]);
  标签.push([定位.目标行数 ? "LINES" : 极限 ? "TIME" : "SCORE", 主X, 定位.主.宽 - 24]);
  标签.push([
    定位.计时舱 === "左" || 定位.目标行数 || 极限 ? "SCORE" : "LINES",
    右X,
    定位.右.宽 - 10,
  ]);
  for (const [文案, x, 宽] of 标签) {
    let 样式 = {
      ...读取对局文字样式("信息标签", { 字号: 11, 颜色: 标签色 }),
      字距: 1.4,
    };
    const 测 = 笔.测量文字(文案, 样式);
    if (测.宽 > 宽) 样式 = { ...样式, 字号: 量化字号((样式.字号 * 宽) / 测.宽, 9) };
    const 高 = 笔.测量文字(文案, 样式).高;
    笔.绘制文字({
      文案,
      样式,
      锚点: "中上",
      x,
      y: 是糖果底板() ? 定位.主.上 + 6 : 定位.数值底 - 33 - 高,
    });
  }
  if (是糖果底板()) return;
  if (定位.目标行数) {
    图.lineStyle(1.4, 标签色, 0.85).strokePoints(
      [
        { x: 右X, y: 定位.右.上 + 8 },
        { x: 右X + 5, y: 定位.右.上 + 12 },
        { x: 右X, y: 定位.右.上 + 16 },
        { x: 右X - 5, y: 定位.右.上 + 12 },
      ],
      true,
    );
    return;
  }
  图.fillStyle(标签色, 0.85);
  for (let 序 = 0; 序 < 3; 序 += 1)
    图.fillRoundedRect(右X - 7, 定位.右.上 + 7 + 序 * 4, 14, 1.8, 0.9);
}

/** 读数：等级 / 分数 / 行数或计时，与装置仪表共用同一套坐标。 */
function 绘制名牌读数(
  笔: 画笔,
  输入: 对局仪表输入,
  定位: 仪表定位,
  字: ReturnType<typeof 创建名牌字>,
): void {
  const 图 = 笔.图形;
  const 左X = 定位.左.左 + 定位.左.宽 / 2;
  const 右X = 定位.右.左 + 定位.右.宽 / 2;
  const 主X = 定位.主.左 + 定位.主.宽 / 2;
  // 牌面是玫瑰木：读数走金、标签与分母走奶油粉，金只留给进度与强调。
  if (定位.计时舱 !== "左") 字(String(输入.等级), 左X, 定位.数值底, 24, 定位.左.宽 - 14, 数值色);
  if (定位.目标行数) {
    const 主值 = String(输入.行数);
    const 主样 = 读取对局文字样式("信息数值", { 字号: 34, 颜色: 数值色 });
    const 副样 = 读取对局文字样式("信息数值", { 字号: 18, 颜色: 标签色 });
    const 主宽 = 笔.测量文字(主值, 主样).宽;
    const 副文 = `/${定位.目标行数}`;
    const 副宽 = 笔.测量文字(副文, 副样).宽;
    const 起 = 主X - (主宽 + 副宽 + 5) / 2;
    字(主值, 起 + 主宽 / 2, 定位.数值底, 34, 主宽 + 1, 数值色);
    字(副文, 起 + 主宽 + 5 + 副宽 / 2, 定位.数值底, 18, 副宽 + 1, 标签色);
    const 进度 = Math.min(1, 输入.行数 / 定位.目标行数);
    const 槽左 = 定位.主.左 + 30;
    const 槽宽 = 定位.主.宽 - 60;
    const 槽上 = 定位.主.上 + 定位.主.高 - 11;
    图.fillStyle(混色(色.莓深, 色.巧克力, 0.35), 0.55).fillRoundedRect(槽左, 槽上, 槽宽, 4, 2);
    if (进度 > 0)
      图.fillStyle(色.金深, 0.98).fillRoundedRect(槽左, 槽上, Math.max(4, 槽宽 * 进度), 4, 2);
  } else if (定位.分数舱 !== "右" && 定位.计时舱 !== "左") {
    字(String(输入.行数), 右X, 定位.数值底, 24, 定位.右.宽 - 14, 数值色);
  }
  // 分数：滚动数位、击中时向金色提亮，与现有仪表同一算法。
  const 强度 = 输入.计分.击中;
  const 值 = 输入.计分.显示分数;
  const 位数 = Math.max(6, Math.floor(Math.max(0, 值)).toString().length);
  let 样式 = {
    ...读取对局文字样式("信息数值", {
      字号: 定位.分数字号 + 2,
      颜色: 混色(数值色, 色.金深, 强度 * 0.6),
    }),
    阴影: 读数阴影,
  };
  const 数宽 = 笔.测量文字("0".repeat(位数), 样式).宽;
  // 字号是文字图集键，必须是整数（这里原来连 floor 都没有，每个位数档都会新建一张图集）。
  if (数宽 > 定位.分数宽) 样式 = { ...样式, 字号: 量化字号((样式.字号 * 定位.分数宽) / 数宽) };
  // 名牌上沿压着 SCORE 标签：按「标签底 + 间距」收一次字号，
  // 否则 38px 的主读数会顶到标签上（马拉松模式尤其明显）。
  const 标签底 =
    定位.主.上 +
    6 +
    笔.测量文字(定位.目标行数 ? "LINES" : "SCORE", {
      ...读取对局文字样式("信息标签", { 字号: 11 }),
      字距: 1.4,
    }).高;
  for (let 收缩 = 0; 收缩 < 4; 收缩 += 1) {
    const 试行高 = 笔.测量文字("0", 样式).高;
    const 试底 = 定位.数值底 + Math.max(0, 样式.字号 - 21) / 4;
    if (试底 - 试行高 >= 标签底 + 4) break;
    const 目标行高 = Math.max(14, 试底 - 标签底 - 4);
    样式 = { ...样式, 字号: 量化字号(Math.max(20, (样式.字号 * 目标行高) / 试行高)) };
  }
  const 字宽 = 笔.测量文字("0", 样式).宽;
  const 行高 = 笔.测量文字("0", 样式).高;
  const 底 = 定位.数值底 + Math.max(0, 样式.字号 - 21) / 4 - Math.sin(强度 * Math.PI) * 2;
  const 上 = 底 - 行高;
  笔.压入裁剪({ 左: 定位.分数X - 定位.分数宽 / 2, 上, 宽: 定位.分数宽, 高: 行高 + 3 });
  读取滚动数位(值, 位数).forEach((位, i) => {
    const x = 定位.分数X + (i - (位数 - 1) / 2) * 字宽;
    笔.绘制文字({ 文案: String(位.数字), 样式, 锚点: "中上", x, y: 上 - 位.进度 * 行高 });
    if (位.进度 > 0)
      笔.绘制文字({ 文案: String(位.下一个), 样式, 锚点: "中上", x, y: 上 + (1 - 位.进度) * 行高 });
  });
  笔.弹出裁剪();
  if (定位.计时舱) 绘制计时(笔, 输入, 定位, 字);
}

/** 计时：极限模式倒计时、冲刺模式正计时；临近与紧迫换色并脉动。 */
function 绘制计时(
  笔: 画笔,
  输入: 对局仪表输入,
  定位: 仪表定位,
  字: ReturnType<typeof 创建名牌字>,
): void {
  const 图 = 笔.图形;
  const 时限 = 输入.模式 === "极限";
  const 毫秒 = 时限 ? 输入.剩余毫秒 : 输入.有效毫秒;
  const 紧迫 = 时限 && 毫秒 <= 10000;
  const 临近 = 时限 && 毫秒 <= 30000;
  const 脉冲 = 紧迫 && !输入.省电 ? (1 + Math.sin((输入.有效毫秒 / 1000) * Math.PI * 4)) / 2 : 0;
  const 钟色 = 紧迫 ? 色.草莓糖 : 临近 ? 色.橙 : 标签色;
  const 槽 = 定位.计时舱 === "主" ? 定位.主 : 定位.左;
  const x = 槽.左 + 槽.宽 / 2;
  const y = 槽.上 + 12;
  图.lineStyle(1.5, 钟色, 0.85).strokeCircle(x, y, 5.5 + 脉冲);
  图
    .lineStyle(1.4, 钟色, 0.9)
    .lineBetween(x, y - 3, x, y)
    .lineBetween(x, y, x + 2.5, y + 1.5);
  字(格式化仪表时间(毫秒, 紧迫), x, 定位.数值底, 紧迫 ? 23 : 22, 槽.宽 - 14, 钟色);
  if (时限) {
    const 槽左 = 槽.左 + 14;
    const 槽宽 = 槽.宽 - 28;
    const 槽上 = 槽.上 + 槽.高 - 9;
    图.fillStyle(混色(色.莓深, 色.巧克力, 0.35), 0.5).fillRoundedRect(槽左, 槽上, 槽宽, 3, 1.5);
    图
      .fillStyle(钟色, 0.72 + 脉冲 * 0.28)
      .fillRoundedRect(
        槽左,
        槽上,
        槽宽 * Math.min(1, Math.max(0, 毫秒 / 模式配置.极限毫秒)),
        3,
        1.5,
      );
  }
}

/** 糖绳：一条斜扭的玫瑰糖绳横跨全屏，正中系一只蝴蝶结。 */
function 绘制糖绳(图: 图形对象, 左: number, 右: number, y: number): void {
  const 粗 = 7;
  const 边 = { 左, 上: y - 粗 / 2, 右, 下: y + 粗 / 2 };
  // ①三层落影：糖绳挂在巧克力墙上，影子先落下去。
  for (const [下移, 外扩, 透明] of [
    [2, 0.5, 0.28],
    [5, 2, 0.14],
    [8, 3.6, 0.07],
  ] as const)
    图
      .fillStyle(色.巧克力深, 透明)
      .fillRoundedRect(左, 边.上 + 下移, 右 - 左, 粗 + 外扩, 粗 / 2 + 外扩);
  // ②深色糖边 ⑥侧壁
  图.fillStyle(色.莓暗, 1).fillRoundedRect(左 - 1, 边.上 - 1, 右 - 左 + 2, 粗 + 3.6, 粗 / 2 + 1);
  图.fillStyle(暗色(色.莓, 0.34), 1).fillRoundedRect(左, 边.上 + 2.4, 右 - 左, 粗, 粗 / 2);
  // ③糖面
  const 绳 = 圆角多边形(边, 同角(粗 / 2));
  图
    .fillGradientStyle(亮色(色.莓亮, 0.16), 色.莓亮, 色.莓, 暗色(色.莓, 0.28), 1, 1, 1, 1)
    .fillPoints(绳, true);
  // 糖绳的斜扭：亮暗斜纹交替，读作拧起来的糖。
  图.fillStyle(色.莓浅, 0.7);
  for (let s = Math.floor((左 - 边.下) / 6) * 6; s < 右 - 边.上; s += 6) {
    const 段 = 裁进凸形(斜带(s, 2.4, 边.上, 边.下), 绳);
    if (段.length >= 3) 图.fillPoints(段, true);
  }
  图.fillStyle(色.莓暗, 0.35);
  for (let s = Math.floor((左 - 边.下) / 6) * 6 + 3; s < 右 - 边.上; s += 6) {
    const 段 = 裁进凸形(斜带(s, 1.8, 边.上, 边.下), 绳);
    if (段.length >= 3) 图.fillPoints(段, true);
  }
  // ④顶棱高光 ⑤底部内阴影
  图.fillStyle(色.白, 0.3).fillRoundedRect(左 + 3, 边.上 + 1, 右 - 左 - 6, 1.6, 0.8);
  图.fillStyle(暗色(色.莓, 0.3), 0.5).fillRoundedRect(左 + 3, 边.下 - 2.4, 右 - 左 - 6, 1.6, 0.8);
  绘制蝴蝶结(图, (左 + 右) / 2, y - 1, 34, 色.草莓, 色.草莓深);
}

/** 模式名底板：一颗糖纸包装的长糖，两端金箍与扭结糖纸。文字由调用方画在上面。 */
export function 绘制糖果标题徽章(
  图: 图形对象,
  中心X: number,
  中心Y: number,
  宽: number,
  高: number,
): void {
  const 身高 = 高 * 0.78;
  const 身宽 = Math.max(60, 宽 - 30);
  const 身左 = 中心X - 身宽 / 2;
  const 身上 = 中心Y - 身高 / 2;
  for (const 向 of [-1, 1] as const)
    绘制糖纸扭结(
      图,
      中心X + 向 * (身宽 / 2 + 2),
      中心Y,
      身高,
      向,
      色.草莓浅,
      混色(色.草莓深, 色.莓, 0.3),
    );
  // 六层糖体：投影 / 侧壁 / 深莓边 / 顶亮底暗的草莓糖面 / 顶棱高光 / 底部内阴影。
  // 糖身比糖纸深一档，白字才压得住；顶亮压小，避免整颗糖糊成浅粉。
  绘制糖片(图, 身左, 身上, 身宽, 身高, {
    圆角: 身高 / 2,
    填色: 混色(色.草莓深, 色.莓, 0.32),
    边色: 色.莓暗,
    描宽: 2.2,
    厚度: 3,
    高光: true,
    内阴影: true,
    顶亮: 0.16,
    底暗: 0.36,
  });
  // 大块糖衣反光：一条偏左的亮带 + 左上镜面，读作硬糖的玻璃糖衣。
  图
    .fillGradientStyle(色.白, 色.白, 色.白, 色.白, 0.26, 0.1, 0, 0)
    .fillRoundedRect(身左 + 12, 身上 + 2.6, 身宽 * 0.46, 身高 * 0.24, 身高 * 0.12);
  图
    .fillStyle(色.白, 0.38)
    .fillEllipse(身左 + 身宽 * 0.22, 身上 + 身高 * 0.21, 身宽 * 0.11, Math.max(1.4, 身高 * 0.08));
  // 象牙裱线：糖身内侧一圈细线，把糖衣收住。
  图
    .lineStyle(1.2, 色.象牙, 0.7)
    .strokeRoundedRect(身左 + 3.5, 身上 + 3.5, 身宽 - 7, 身高 - 7, (身高 - 7) / 2);
  for (const 向 of [-1, 1] as const) {
    const x = 中心X + 向 * (身宽 / 2 - 2);
    图
      .fillStyle(色.莓暗, 1)
      .fillRoundedRect(x - 4.8, 中心Y - 身高 * 0.38 - 1, 9.6, 身高 * 0.76 + 2, 3.2);
    图
      .fillGradientStyle(
        混色(色.金, 色.金深, 0.3),
        混色(色.金, 色.金深, 0.3),
        色.金深,
        色.金深,
        1,
        1,
        1,
        1,
      )
      .fillRoundedRect(x - 3.8, 中心Y - 身高 * 0.38, 7.6, 身高 * 0.76, 2.6);
    图.fillStyle(色.白, 0.5).fillRoundedRect(x - 2.2, 中心Y - 身高 * 0.31, 1.5, 身高 * 0.54, 0.7);
    图.fillStyle(色.白, 0.34).fillCircle(x - 1.4, 中心Y - 身高 * 0.3, Math.max(0.9, 身高 * 0.045));
    绘制闪星(图, 中心X + 向 * (身宽 / 2 - 18), 中心Y, 4.5);
  }
}

/** 四角闪星。 */
function 绘制闪星(图: 图形对象, x: number, y: number, 尺寸: number): void {
  const 腰 = 尺寸 * 0.28;
  图.fillStyle(色.象牙, 0.95).fillPoints(
    [
      { x, y: y - 尺寸 },
      { x: x + 腰, y: y - 腰 },
      { x: x + 尺寸, y },
      { x: x + 腰, y: y + 腰 },
      { x, y: y + 尺寸 },
      { x: x - 腰, y: y + 腰 },
      { x: x - 尺寸, y },
      { x: x - 腰, y: y - 腰 },
    ],
    true,
  );
}

/** 对局仪表「糖果」表现：静态画名牌与糖绳，动态画读数。 */
export function 绘制对局仪表糖果(笔: 画笔, 输入: 对局仪表输入, 部分: "静态" | "动态"): void {
  const 定位 = 计算对局仪表(输入.布局, 输入.模式);
  if (部分 === "静态") {
    // 底板接管糖果静态外观后，名牌与糖绳的形状交给画布，这里只留文字标签。
    if (!是糖果底板()) {
      绘制名牌(笔.图形, 定位.左, false);
      绘制名牌(笔.图形, 定位.右, false);
      绘制名牌(笔.图形, 定位.主, true);
      const 布局 = 输入.布局;
      const 名牌底 = 定位.主.上 + 定位.主.高;
      const 框顶 = 布局.棋盘.上 - 读取糖果框厚(布局.格子大小) - 1.5;
      if (布局.侧栏 && 框顶 - 名牌底 > 14)
        绘制糖绳(笔.图形, 8, 布局.视口宽 - 8, (名牌底 + 框顶) / 2);
    }
    绘制名牌标记(笔, 定位);
    return;
  }
  绘制名牌读数(笔, 输入, 定位, 创建名牌字(笔));
}


export interface 方块单元外观 {
  /** 直接给方案对象（纯配方用法），或给外观名称/留空按当前设置解析（旧调用兼容用法）。 */
  方案?: 方块外观方案 | 方块外观名称;
  色值: number;
  格子: number;
  透明度?: number;
  圆角比例?: number;
  /** 幽灵投影：只画轮廓与微弱填充。 */
  幽灵?: boolean;
}

/** 纯配方参数：方案必须由调用方给出，函数内不读设置/场景。 */
export interface 方块单元绘制参数 extends 方块单元外观 {
  方案: 方块外观方案;
}

/** 解析方块外观方案：传对象直接用；传名称按外观表解析；都不传回退当前设置（兼容旧调用）。 */
export function 解析方块单元方案(外观: 方块单元外观): 方块外观方案 {
  if (typeof 外观.方案 === "object") return 外观.方案;
  if (typeof 外观.方案 === "string") return 解析方块外观(外观.方案);
  return 解析方块外观(undefined);
}

/**
 * 统一绘制棋盘格、预览块和原型块使用的程序化方块单元（玩法专属视觉配方，引擎无关）。
 * 宝石质感：外圈暗色包边、受光主体、顶部高光与底部背光，形成斜面体积。
 * Three 只使用纯绘制指令；接口结构满足 `图形对象`。
 */
export function 绘制方块单元(绘图: 图形对象, x: number, y: number, 外观: 方块单元绘制参数): void {
  if (外观.方案.质感 === "像素") {
    绘制糖果方块(
      绘图,
      x,
      y,
      外观.格子,
      外观.色值,
      外观.透明度,
      外观.幽灵,
      按名称取像素规范(外观.方案.名称),
    );
    return;
  }
  if (外观.方案.质感 === "糖果") {
    const 透明度 = 外观.透明度 ?? 1;
    // 按颜色反查方块类型：同色玻璃体内用类型决定糖纹（条纹/饼干/糖粒），调用方不必多传一参。
    const 类型 = (Object.keys(外观.方案.颜色) as (keyof typeof 外观.方案.颜色)[]).find(
      (项) => 外观.方案.颜色[项] === 外观.色值,
    );
    if (外观.幽灵) 绘制果冻幽灵(绘图, x, y, 外观.格子, 外观.色值, 透明度);
    else 绘制果冻单元(绘图, x, y, 外观.格子, 外观.色值, 透明度, 类型);
    return;
  }
  // 立体质感：立方体填满格子；幽灵投影仍走平面轮廓，读作「落点提示」而非实体。
  if (外观.方案.质感 === "立体" && !外观.幽灵) {
    绘制立方单元(绘图, x, y, 外观.格子, 外观.色值, 外观.透明度 ?? 1);
    return;
  }
  const 格子 = 外观.格子;
  const 方案 = 外观.方案;
  const 透明度 = 外观.透明度 ?? 1;
  const 圆角 = 方案.质感 === "像素" ? 0 : Math.max(2, 格子 * (外观.圆角比例 ?? 0.15));
  if (外观.幽灵) {
    绘制幽灵单元(绘图, x, y, 格子, 圆角, 外观.色值, 透明度);
    return;
  }
  const 色值 = 外观.色值;
  const 深 = 暗色(色值, 0.52);
  const 内缩 = Math.max(1, 格子 * 0.07);
  // 底部柔影，让方块浮在格面上
  绘图.fillStyle(0x000000, 0.32 * 透明度).fillRoundedRect(x + 1, y + 2.5, 格子 - 1, 格子 - 1, 圆角);
  // 外圈包边（深色），形成斜面外沿
  绘图.fillStyle(深, 0.96 * 透明度).fillRoundedRect(x, y, 格子 - 1, 格子 - 1, 圆角);
  // 主体受光面
  绘图
    .fillStyle(色值, 0.98 * 透明度)
    .fillRoundedRect(x + 内缩, y + 内缩, 格子 - 1 - 内缩 * 2, 格子 - 1 - 内缩 * 2, 圆角 * 0.8);
  // 上半受光提亮
  const 内宽 = Math.max(0, 格子 - 1 - 内缩 * 2);
  绘图
    .fillStyle(亮色(色值, 0.34), 0.55 * 透明度)
    .fillRect(x + 内缩 + 圆角 * 0.6, y + 内缩 + 1, 内宽 - 圆角 * 1.2, (格子 - 1) * 0.34);
  // 顶部镜面高光
  绘图
    .fillStyle(0xffffff, 0.5 * 透明度)
    .fillRoundedRect(
      x + 格子 * 0.18,
      y + 格子 * 0.11,
      Math.max(1, 格子 * 0.42),
      Math.max(1, 格子 * 0.1),
      格子 * 0.05,
    );
  // 底部背光
  绘图
    .fillStyle(0x000000, 0.26 * 透明度)
    .fillRect(
      x + 内缩 + 圆角 * 0.6,
      y + 格子 - 2.5 - (格子 - 1) * 0.22,
      内宽 - 圆角 * 1.2,
      (格子 - 1) * 0.2,
    );
  // 内侧亮边
  绘图
    .lineStyle(1, 亮色(色值, 0.52), 0.5 * 透明度)
    .strokeRoundedRect(x + 内缩, y + 内缩, 格子 - 1 - 内缩 * 2, 格子 - 1 - 内缩 * 2, 圆角 * 0.8);
  // 外沿描边
  绘图
    .lineStyle(1, 亮色(色值, 0.24), 0.62 * 透明度)
    .strokeRoundedRect(x, y, 格子 - 1, 格子 - 1, 圆角);
}

export interface 方块组格 {
  列: number;
  行: number;
  类型: 方块类型;
}

/**
 * 画一组格子（棋盘已落格、当前块、预览块）。糖果质感一格一颗、不连携，
 * 其它质感同样逐格画；原点是第 0 列第 0 行格子的左上角，`格内缩` 只作用于逐格画法。
 */
export function 绘制方块组(
  绘图: 图形对象,
  原点X: number,
  原点Y: number,
  格列表: readonly 方块组格[],
  外观: Omit<方块单元绘制参数, "色值" | "幽灵">,
  格内缩 = 0,
): void {
  const 格 = 外观.格子;
  if (外观.方案.质感 === "糖果") {
    const 颜色 = 外观.方案.颜色;
    绘制果冻组(
      绘图,
      原点X,
      原点Y,
      格,
      格列表.map((项) => ({ ...项, 色值: 颜色[项.类型] })),
      外观.透明度 ?? 1,
    );
    return;
  }
  // 同一格外观在棋盘里重复上百次：按「方案 + 格子 + 色值」烘进动态图集 / 缓存几何，
  // 重建时只贴图或平移重放，不再逐格重新三角化与扩描边。
  const 透明度档 = Math.round((外观.透明度 ?? 1) * 8);
  // 键按方块类型预计算：棋盘一帧要画上百格，逐格拼字符串会成为热路径开销。
  const 键表 = new Map<方块类型, string>();
  if (绘图.缓存图案 || 绘图.缓存绘制) {
    for (const 类型 of Object.keys(外观.方案.颜色) as 方块类型[]) {
      键表.set(
        类型,
        `方块|${外观.方案.名称}|${格}|${外观.方案.颜色[类型]}|${外观.圆角比例 ?? ""}|${透明度档}`,
      );
    }
  }
  for (const 项 of 格列表) {
    const 色值 = 外观.方案.颜色[项.类型];
    const x = 原点X + 项.列 * 格 + 格内缩;
    const y = 原点Y + 项.行 * 格 + 格内缩;
    if (绘图.缓存图案 || 绘图.缓存绘制) {
      const 键 = 键表.get(项.类型) ?? "";
      const 参数 = { ...外观, 色值 };
      // 默认走几何缓存（本机实测：动态图集降三角形但主线程无收益，图集能力保留、按设备档位再启用）。
      if (绘图.缓存绘制) {
        绘图.缓存绘制(键, (录制) => 绘制方块单元(录制, 0, 0, 参数), x, y);
        continue;
      }
      if (绘图.缓存图案?.(键, { 左: x, 上: y, 宽: 格, 高: 格 }, (录制) => 绘制方块单元(录制, 0, 0, 参数))) {
        continue;
      }
    }
    绘制方块单元(绘图, x, y, { ...外观, 色值 });
  }
}

/** 幽灵投影：极弱轮廓提示落点，不与实块抢眼。 */
function 绘制幽灵单元(
  绘图: 图形对象,
  x: number,
  y: number,
  格子: number,
  圆角: number,
  色值: number,
  透明度: number,
): void {
  const 内缩 = Math.max(1, 格子 * 0.11);
  绘图
    .fillStyle(色值, 0.1 * 透明度)
    .fillRoundedRect(x + 内缩, y + 内缩, 格子 - 1 - 内缩 * 2, 格子 - 1 - 内缩 * 2, 圆角);
  绘图
    .lineStyle(Math.max(1, 格子 * 0.055), 亮色(色值, 0.35), 0.65 * 透明度)
    .strokeRoundedRect(x + 内缩, y + 内缩, 格子 - 1 - 内缩 * 2, 格子 - 1 - 内缩 * 2, 圆角);
  // 只在左上/右下留两个短角标，弱化提示
  const 角 = Math.max(2, 格子 * 0.13);
  for (const [角X, 角Y, 水平, 垂直] of [
    [x + 内缩, y + 内缩, 1, 1],
    [x + 格子 - 1 - 内缩 - 角, y + 格子 - 1 - 内缩 - 角, -1, -1],
  ] as [number, number, number, number][]) {
    绘图
      .fillStyle(色值, 0.2 * 透明度)
      .fillRect(水平 > 0 ? 角X : 角X, 角Y, 角, 1.5)
      .fillRect(角X, 垂直 > 0 ? 角Y : 角Y, 1.5, 角);
  }
}

/**
 * 绘制方块外圈辉光（建议画在混合模式为 ADD 的图层上，得到霓虹泛光）。
 * 与 绘制方块单元 配套使用，位置尺寸保持一致。
 */
export function 绘制方块单元辉光(
  绘图: 图形对象,
  x: number,
  y: number,
  外观: 方块单元绘制参数,
): void {
  if (外观.方案.质感 === "像素" || 外观.方案.质感 === "糖果") return;
  const 格子 = 外观.格子;
  const 方案 = 外观.方案;
  const 透明度 = (外观.透明度 ?? 1) * 方案.辉光;
  const 圆角 = Math.max(2, 格子 * (外观.圆角比例 ?? 0.15));
  for (let 层 = 0; 层 < 3; 层 += 1) {
    const 外扩 = 1 + 层 * 2.2;
    绘图
      .fillStyle(亮色(外观.色值, 0.18), (0.12 - 层 * 0.035) * 透明度)
      .fillRoundedRect(x - 外扩, y - 外扩, 格子 - 1 + 外扩 * 2, 格子 - 1 + 外扩 * 2, 圆角 + 外扩);
  }
}


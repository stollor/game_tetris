import type { 点 } from "../../../../.gamemaker/依赖/框架/界面/绘制/协议";
import type { 方块类型 } from "../../../../代码/玩法/再消一行";
import { type 糖果块样式, 糖果块样式表 } from "../../../主题/糖果/糖果方块外观";
import { 同角, 圆角多边形 } from "../../基础/装饰与蒙层/圆角裁剪";

/**
 * 糖果方块几何：一格糖的格子矩形、糖色与透明度。
 *
 * 糖果方块一格一颗（见 `糖果方块单元`），绘制模块只拿这一格的位置和它的糖色，
 * 不自己数格子，也不参与「哪几格连在一起」的推导。
 */

export interface 糖果块几何 {
  /** 一个格的边长。 */
  格: number;
  /** 这一格的左上角与右下角（世界坐标）。 */
  左: number;
  上: number;
  右: number;
  下: number;
  /** 格心（世界坐标）。 */
  中心X: number;
  中心Y: number;
  样式: 糖果块样式;
  透明度: number;
}

export function 构建几何(
  左: number,
  上: number,
  格: number,
  种类: 方块类型,
  透明度 = 1,
): 糖果块几何 {
  return {
    格,
    左,
    上,
    右: 左 + 格,
    下: 上 + 格,
    中心X: 左 + 格 / 2,
    中心Y: 上 + 格 / 2,
    样式: 糖果块样式表[种类],
    透明度,
  };
}

/** 暗侧边：主色压暗一档，糖底读作有厚度。 */
export function 暗侧(样式: 糖果块样式): number {
  const r = (样式.主色 >> 16) & 0xff;
  const g = (样式.主色 >> 8) & 0xff;
  const b = 样式.主色 & 0xff;
  const 混 = (值: number, 目标: number) => Math.round(值 * 0.62 + 目标 * 0.38);
  return (
    (混(r, (样式.深色 >> 16) & 0xff) << 16) |
    (混(g, (样式.深色 >> 8) & 0xff) << 8) |
    混(b, 样式.深色 & 0xff)
  );
}

/** 这一格的圆角矩形：四边各内缩 `内缩`，圆角 `圆角`（巧克力、蛋挞这类整格造型用）。 */
export function 圆角块(几何: 糖果块几何, 内缩: number, 圆角: number): 点[] {
  return 圆角多边形(
    {
      左: 几何.左 + 内缩,
      上: 几何.上 + 内缩,
      右: 几何.右 - 内缩,
      下: 几何.下 - 内缩,
    },
    同角(圆角),
  );
}

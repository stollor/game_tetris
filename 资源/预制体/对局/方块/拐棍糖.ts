/** 糖管外轮廓：两侧偏移线 + 两端圆头，顺时针一圈。 */
function 管轮廓(采样: readonly 中轴采样[], 半径: number): 点[] {
  const 首 = 采样[0];
  const 末 = 采样[采样.length - 1];
  const 左 = 采样.map((项) => 沿(项.位, 项.法, 半径));
  const 右 = 采样.map((项) => 沿(项.位, 项.法, -半径));
  const 头段 = Math.max(5, Math.ceil(半径 / 1.1));
  const 轮廓: 点[] = [...左];
  for (let 步 = 1; 步 < 头段; 步 += 1) {
    const 角 = (Math.PI * 步) / 头段;
    轮廓.push({
      x: 末.位.x + 末.法.x * Math.cos(角) * 半径 + 末.切.x * Math.sin(角) * 半径,
      y: 末.位.y + 末.法.y * Math.cos(角) * 半径 + 末.切.y * Math.sin(角) * 半径,
    });
  }
  for (let 序 = 右.length - 1; 序 >= 0; 序 -= 1) 轮廓.push(右[序]);
  for (let 步 = 1; 步 < 头段; 步 += 1) {
    const 角 = (Math.PI * 步) / 头段;
    轮廓.push({
      x: 首.位.x - 首.法.x * Math.cos(角) * 半径 - 首.切.x * Math.sin(角) * 半径,
      y: 首.位.y - 首.法.y * Math.cos(角) * 半径 - 首.切.y * Math.sin(角) * 半径,
    });
  }
  return 轮廓;
}

/**
 * 条纹周期与条宽：糖棍越短周期越密，保证 25px 下至少两道清楚的白纹；
 * 单格那截短棍另给一档，两道纹加两个圆头就够，不再碎成细线。
 */
function 取条纹参数(中轴: 中轴, 格: number, 单格: boolean): { 周期: number; 宽: number } {
  if (单格) return { 周期: 格 * 0.3, 宽: 格 * 0.12 };
  const 周期 = Math.min(格 * 条纹周期比, Math.max(格 * 0.4, 中轴.总长 / 2.9));
  return { 周期, 宽: 周期 * (条纹宽比 / 条纹周期比) };
}

/** 条纹：沿弧长等距切段，每段是夹在左右两条偏移线之间的四边形（弯处补采样点跟着弯）。 */
function 条纹带集(中轴: 中轴, 半径: number, 格: number, 周期: number, 宽: number): 点[][] {
  const 集: 点[][] = [];
  const 起相 = Math.min(格 * 0.16, 中轴.总长 * 0.08);
  const 尾界 = 中轴.总长 - Math.min(格 * 0.14, 中轴.总长 * 0.06);
  for (let 起 = 起相; 起 + 宽 < 尾界; 起 += 周期) {
    const 止 = 起 + 宽;
    const 头 = 弧长取位(中轴.采样, 起);
    const 尾 = 弧长取位(中轴.采样, 止);
    const 左 = [沿(头.位, 头.法, 半径)];
    const 右 = [沿(头.位, 头.法, -半径)];
    for (const 项 of 中轴.采样) {
      if (项.弧长 <= 起 || 项.弧长 >= 止) continue;
      左.push(沿(项.位, 项.法, 半径));
      右.push(沿(项.位, 项.法, -半径));
    }
    左.push(沿(尾.位, 尾.法, 半径));
    右.push(沿(尾.位, 尾.法, -半径));
    集.push([...左, ...右.reverse()]);
  }
  return 集;
}

/** 端头高光：贴圆头内侧的一小片浅色椭圆，读作糖衣反光。 */
function 画端头高光(
  绘图: 图形对象,
  采样: 中轴采样,
  半宽: number,
  浅色: number,
  透明度: number,
): void {
  const 光向 = 采样.法.y <= 0 ? 采样.法 : { x: -采样.法.x, y: -采样.法.y };
  const 心 = {
    x: 采样.位.x + 光向.x * 半宽 * 0.4 - 采样.切.x * 半宽 * 0.34,
    y: 采样.位.y + 光向.y * 半宽 * 0.4 - 采样.切.y * 半宽 * 0.34,
  };
  绘图.fillStyle(浅色, 0.34 * 透明度);
  绘图.fillPoints(椭圆点集(心, 采样.切, 光向, 半宽 * 0.46, 半宽 * 0.17), true);
}

/** 糖身：落影 → 深色包边 → 暗侧 + 受光主体 → 条纹 → 端头高光。 */
function 画糖身(
  绘图: 图形对象,
  几何: 糖果块几何,
  中轴: 中轴,
  半宽: number,
  条纹: { 周期: number; 宽: number },
): void {
  const { 透明度, 样式, 格 } = 几何;
  const 边线 = Math.max(0.9, 格 * 边线比);

  绘图.fillStyle(样式.深色, 0.3 * 透明度);
  绘图.fillPoints(
    管轮廓(中轴.采样, 半宽 + 边线 * 0.7).map((位) => ({ x: 位.x, y: 位.y + 格 * 0.09 })),
    true,
  );

  绘图.fillStyle(样式.深色, 透明度);
  绘图.fillPoints(管轮廓(中轴.采样, 半宽 + 边线), true);

  绘图.fillStyle(暗侧(样式), 透明度);
  绘图.fillPoints(管轮廓(中轴.采样, 半宽), true);
  const 收 = 格 * 受光收比;
  绘图.fillStyle(样式.主色, 透明度);
  绘图.fillPoints(
    管轮廓(中轴.采样, 半宽 - 收).map((位) => ({ x: 位.x, y: 位.y - 收 })),
    true,
  );

  绘图.fillStyle(样式.装饰, 透明度);
  for (const 带 of 条纹带集(中轴, 半宽 + 格 * 0.012, 格, 条纹.周期, 条纹.宽)) {
    绘图.fillPoints(带, true);
  }

  if (中轴.采样.length > 0) {
    画端头高光(绘图, 中轴.采样[0], 半宽, 样式.浅色, 透明度);
    画端头高光(绘图, 中轴.采样[中轴.采样.length - 1], 半宽, 样式.浅色, 透明度);
  }
}

/* ------------------------------------------------------------------ */
/* 蝴蝶结                                                              */
/* ------------------------------------------------------------------ */

/**
 * 只有真正带拐角的形状才压蝴蝶结（蝴蝶结是 L 型的记忆点，不是每块都盖）：
 * 直线糖棍（残缺只剩长臂 / 两格）与单格一律不画，免得满盘铺满金色小贴纸。
 * 小格（< 30px）再收一档：缩到 0.62 格宽、去掉飘带，只留两个圈和结心。
 */
function 取蝴蝶结(中轴: 中轴, 半宽: number, 格: number): 蝴蝶结 | null {
  if (中轴.弯段.length === 0) return null;
  const 弯 = 中轴.弯段[0];
  const 入向 = 中轴.采样[弯.起序].切;
  const 出向 = 中轴.采样[弯.止序].切;
  const 中弧长 = (中轴.采样[弯.起序].弧长 + 中轴.采样[弯.止序].弧长) / 2;
  const 中位 = 弧长取位(中轴.采样, 中弧长);
  // 法向是「行进方向左侧」；拐弯往里收的一侧随左转/右转翻转，弯外才是压蝴蝶结的一侧。
  const 叉 = 入向.x * 出向.y - 入向.y * 出向.x;
  const 内 = 叉 < 0 ? 中位.法 : { x: -中位.法.x, y: -中位.法.y };
  const 外 = { x: -内.x, y: -内.y };
  const 小格 = 格 < 30;
  return {
    心: 沿(中位.位, 外, 半宽 * 0.9 + 格 * 0.02),
    展轴: 中位.切,
    垂轴: 外,
    // 展轴总宽 = 2.16 × 尺寸：0.4 格 → 0.86 格宽；小格 0.29 格 → 0.62 格宽。
    尺寸: 格 * (小格 ? 0.287 : 0.4),
    有飘带: !小格,
  };
}

/** 蝴蝶结：两个圈 + 中心结（+ 大格时两条飘带），暗金包边、亮金高光。 */
function 画蝴蝶结(绘图: 图形对象, 结: 蝴蝶结, 样式: 糖果块样式, 透明度: number): void {
  const { 心, 展轴: 展, 垂轴: 垂, 尺寸: 尺, 有飘带 } = 结;
  const 金 = 样式.装饰深;
  const 暗金 = 混色(金, 样式.深色, 0.45);
  const 亮金 = 混色(金, 样式.装饰, 0.6);
  const 边 = Math.max(0.55, 尺 * 0.09);
  const 局部 = (沿展: number, 沿垂: number): 点 => ({
    x: 心.x + 展.x * 沿展 + 垂.x * 沿垂,
    y: 心.y + 展.y * 沿展 + 垂.y * 沿垂,
  });

  绘图.fillStyle(样式.深色, (有飘带 ? 0.18 : 0.12) * 透明度);
  绘图.fillPoints(
    椭圆点集(
      { x: 心.x + 尺 * 0.02, y: 心.y + 尺 * (有飘带 ? 0.16 : 0.1) },
      展,
      垂,
      尺 * 0.95,
      尺 * (有飘带 ? 0.4 : 0.3),
    ),
    true,
  );

  if (有飘带) {
    for (const 侧 of [-1, 1] as const) {
      const 飘带 = [
        局部(侧 * 尺 * 0.05, 尺 * 0.1),
        局部(侧 * 尺 * 0.24, 尺 * 0.19),
        局部(侧 * 尺 * 0.39, 尺 * 0.98),
        局部(侧 * 尺 * 0.22, 尺 * 0.84),
        局部(侧 * 尺 * 0.07, 尺 * 0.96),
      ];
      const 基点 = 局部(侧 * 尺 * 0.14, 尺 * 0.15);
      绘图.fillStyle(暗金, 透明度);
      绘图.fillPoints(外扩点集(飘带, 基点, 边), true);
      绘图.fillStyle(金, 透明度);
      绘图.fillPoints(飘带, true);
    }
  }

  for (const 侧 of [-1, 1] as const) {
    const 圈心 = 局部(侧 * 尺 * 0.53, 尺 * 0.02);
    绘图.fillStyle(暗金, 透明度);
    绘图.fillPoints(椭圆点集(圈心, 展, 垂, 尺 * 0.55, 尺 * 0.36), true);
    绘图.fillStyle(金, 透明度);
    绘图.fillPoints(椭圆点集(圈心, 展, 垂, 尺 * 0.55 - 边, 尺 * 0.36 - 边), true);
  }

  const 结边 = 边 * 0.55;
  绘图.fillStyle(暗金, 透明度);
  绘图.fillPoints(椭圆点集(局部(0, 尺 * 0.03), 展, 垂, 尺 * 0.29, 尺 * 0.25), true);
  绘图.fillStyle(金, 透明度);
  绘图.fillPoints(椭圆点集(局部(0, 尺 * 0.03), 展, 垂, 尺 * 0.29 - 结边, 尺 * 0.25 - 结边), true);

  if (!有飘带) return;
  绘图.fillStyle(亮金, 0.8 * 透明度);
  绘图.fillPoints(椭圆点集(局部(0, -尺 * 0.07), 展, 垂, 尺 * 0.13, 尺 * 0.05), true);
}

/* ------------------------------------------------------------------ */
/* 兜底：分叉 / 成环的并块                                            */
/* ------------------------------------------------------------------ */

/**
 * 不成一根糖棍的并块（两粒 L 侧并、或围成方环）退回并块外形 + 斜条纹，
 * 至少保持糖果配色与斜纹语言一致；这种情况只在同型糖真的粘成一片时出现。
 */
function 画兜底(绘图: 图形对象, 几何: 糖果块几何): void {
  const 面 = 画并块外形(绘图, 几何);
  const 周期 = 几何.格 * 条纹周期比;
  const 带宽 = 几何.格 * 条纹宽比;
  const 上 = 几何.上;
  const 下 = 几何.上 + 几何.行数 * 几何.格;
  const 起界 = 几何.左 - 下;
  const 止界 = 几何.左 + 几何.列数 * 几何.格 - 上;
  绘图.fillStyle(几何.样式.装饰, 几何.透明度);
  for (let 起 = 起界; 起 < 止界; 起 += 周期) {
    for (const 形 of 面) {
      const 带 = 裁进凸形(斜带(起, 带宽, 上, 下), 形);
      if (带.length >= 3) 绘图.fillPoints(带, true);
    }
  }
}


import type { 图形对象 } from "../../../../.gamemaker/依赖/框架/界面/绘制/协议";
import { 同角, 圆角多边形, 斜带, 裁进凸形, type 边界 } from "../../基础/装饰与蒙层/圆角裁剪";
import { 暗侧, type 糖果块几何 } from "./几何";

/**
 * 拐棍糖（L / J 型，互为镜像）：一格一块拐棍糖方片。
 *
 * 糖块是「圆角方身 + 45° 一组奶白斜条纹 + 顶棱高光」，全部按格宽推；
 * L 与 J 只差口味色（草莓 / 薄荷），形状与朝向无关，相邻格也不会被拉成一根长糖棍。
 */
export function 绘制拐棍糖(绘图: 图形对象, 几何: 糖果块几何): void {
  const { 格, 样式, 透明度 } = 几何;
  const 缩 = Math.max(0.6, 格 * 0.05);
  const 圆角 = 格 * 0.28;
  const 边: 边界 = {
    左: 几何.左 + 缩,
    上: 几何.上 + 缩,
    右: 几何.右 - 缩,
    下: 几何.下 - 缩,
  };
  const 描 = Math.max(1, 格 * 0.07);
  const 内边: 边界 = { 左: 边.左 + 描, 上: 边.上 + 描, 右: 边.右 - 描, 下: 边.下 - 描 };
  const 内圆角 = Math.max(0.8, 圆角 - 描);
  const 收 = 格 * 0.055;
  const 面 = 圆角多边形(内边, 同角(内圆角));

  // ① 落影：压在格底，和满盘里其它糖同一档
  绘图.fillStyle(0x1c0a08, 0.3 * 透明度);
  绘图.fillPoints(
    圆角多边形({ ...边, 上: 边.上 + 格 * 0.09, 下: 边.下 + 格 * 0.09 }, 同角(圆角)),
    true,
  );
  // ② 深色包边
  绘图.fillStyle(样式.深色, 透明度);
  绘图.fillPoints(圆角多边形(边, 同角(圆角)), true);
  // ③ 暗侧糖身 + 受光主体：底边留一道厚，读作有厚度的糖片
  绘图.fillStyle(暗侧(样式), 透明度);
  绘图.fillPoints(面, true);
  绘图.fillStyle(样式.主色, 透明度);
  绘图.fillPoints(圆角多边形({ ...内边, 下: 内边.下 - 收 }, 同角(内圆角)), true);
  // ④ 斜条纹：拐棍糖的招牌，45° 一组等宽奶白带，裁进糖面
  const 周期 = 格 * 0.34;
  const 带宽 = 格 * 0.15;
  for (let 起 = 边.左 - 边.下; 起 < 边.右 - 边.上; 起 += 周期) {
    const 带 = 裁进凸形(斜带(起, 带宽, 边.上, 边.下), 面);
    if (带.length >= 3) 绘图.fillStyle(样式.装饰, 透明度).fillPoints(带, true);
  }
  // ⑤ 顶棱高光 + 左上反光
  const 光Y = 内边.上 + Math.max(0.8, 格 * 0.045);
  绘图
    .lineStyle(Math.max(0.8, 格 * 0.04), 样式.浅色, 0.55 * 透明度)
    .lineBetween(内边.左 + 内圆角 * 0.7, 光Y, 内边.右 - 内圆角 * 0.7, 光Y);
  绘图.fillStyle(样式.浅色, 0.26 * 透明度);
  绘图.fillEllipse(内边.左 + 格 * 0.2, 内边.上 + 格 * 0.17, 格 * 0.16, Math.max(0.7, 格 * 0.06));
}

/**
 * 拐棍糖（L / J 型，互为镜像）：沿格集走的一根粗糖管，拐角用大圆角弯过去，
 * 条纹按中轴弧长等距铺开，拐弯外侧压一只金色小蝴蝶结。
 *
 * 做法是「粗折线加宽」：先把格集收成一条格心折线，在拐角处切成圆弧中轴，
 * 再按每点法向偏移出左右两条边、两端补圆头，得到整根糖的外轮廓。
 * 条纹是一段段夹在两条偏移线之间的四边形，不依赖裁剪；L/J 与 4 个旋转朝向
 * 都由格集自动推出来，颜色只从 `几何.样式` 取。
 *
 * 蝴蝶结只属于「真正带拐角」的形状：残缺只剩长臂 / 两格、以及单格，都只画
 * 一截带条纹的糖棍、不盖结——满盘塌下来的零散格里，金色贴纸比糖本身还抢眼。
 * 小格（< 30px）连拐角上的结也收一档：缩到 0.62 格宽、去掉飘带，降低细节密度。
 * 分叉或带环的并块退回并块外形 + 斜条纹。
 */

/** 糖管半宽（相对格宽）；拐弯处还要再收，保证内侧留出一圈圆角不塌成折角。 */
const 半宽比 = 0.36;
/** 深色包边宽度（相对格宽）。 */
const 边线比 = 0.06;
/** 拐弯半径（相对格宽）：给到近 0.6 格，外弯半径才接近一格。 */
const 弯半径比 = 0.57;
/** 内弯至少留一圈半径（相对格宽），小于这个值拐角会挤成一个尖。 */
const 内弯留比 = 0.14;
/** 条纹周期与条宽（相对格宽），沿中轴弧长铺。 */
const 条纹周期比 = 0.64;
const 条纹宽比 = 0.26;
/** 受光主体相对暗侧糖身向上收的厚度（相对格宽），底边留一条暗侧做厚度。 */
const 受光收比 = 0.055;

/** 中轴采样：位置、切向、法向（指向拐弯内侧）与累计弧长。 */
interface 中轴采样 {
  位: 点;
  切: 点;
  法: 点;
  弧长: number;
}

/** 一段圆弧拐弯在采样序列里的下标范围，用来把蝴蝶结压在弯外侧。 */
interface 弯段 {
  起序: number;
  止序: number;
}

interface 中轴 {
  采样: 中轴采样[];
  弯段: 弯段[];
  总长: number;
  /** 所有拐弯里最小的半径；管半宽不能超过它，否则内侧偏移会翻折。 */
  最小弯半径: number;
}

/** 蝴蝶结：结心、圈展开轴、飘带朝外轴、半展开宽，以及是否带飘带。 */
interface 蝴蝶结 {
  心: 点;
  展轴: 点;
  垂轴: 点;
  尺寸: number;
  有飘带: boolean;
}

function 单位(向量: 点): 点 {
  const 长 = Math.hypot(向量.x, 向量.y);
  return 长 > 1e-6 ? { x: 向量.x / 长, y: 向量.y / 长 } : { x: 1, y: 0 };
}

function 沿(位: 点, 向: 点, 量: number): 点 {
  return { x: 位.x + 向.x * 量, y: 位.y + 向.y * 量 };
}

function 归一化角(角: number): number {
  let 值 = 角;
  while (值 > Math.PI) 值 -= Math.PI * 2;
  while (值 < -Math.PI) 值 += Math.PI * 2;
  return 值;
}

function 混色(甲: number, 乙: number, 比: number): number {
  const 混 = (a: number, b: number) => Math.round(a * (1 - 比) + b * 比);
  return (
    (混((甲 >> 16) & 0xff, (乙 >> 16) & 0xff) << 16) |
    (混((甲 >> 8) & 0xff, (乙 >> 8) & 0xff) << 8) |
    混(甲 & 0xff, 乙 & 0xff)
  );
}

/** 椭圆点集：轴甲、轴乙是两条单位轴，长度按轴分别给。 */
function 椭圆点集(心: 点, 轴甲: 点, 轴乙: 点, 甲长: number, 乙长: number, 段 = 18): 点[] {
  const 集: 点[] = [];
  for (let 序 = 0; 序 < 段; 序 += 1) {
    const 角 = (Math.PI * 2 * 序) / 段;
    集.push({
      x: 心.x + 轴甲.x * Math.cos(角) * 甲长 + 轴乙.x * Math.sin(角) * 乙长,
      y: 心.y + 轴甲.y * Math.cos(角) * 甲长 + 轴乙.y * Math.sin(角) * 乙长,
    });
  }
  return 集;
}

/** 把点集以某点为中心沿径向推出去 `量`，给蝴蝶结的飘带补一圈暗金边。 */
function 外扩点集(点集: readonly 点[], 心: 点, 量: number): 点[] {
  return 点集.map((位) => {
    const 差 = { x: 位.x - 心.x, y: 位.y - 心.y };
    const 长 = Math.hypot(差.x, 差.y);
    if (长 < 1e-6) return 位;
    return { x: 位.x + (差.x / 长) * 量, y: 位.y + (差.y / 长) * 量 };
  });
}


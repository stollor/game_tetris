/**
 * 格集若是一条不自交的相邻折线（单格 / 直线 / 带拐弯的 L 形都算），
 * 就返回格心序列（从一端走到另一端）；分叉或有环时返回 null。
 */
function 取格心序列(几何: 糖果块几何): 点[] | null {
  const 格位 = 几何.格外形;
  const 数 = 格位.length;
  const 索引 = new Map<string, number>();
  for (let 序 = 0; 序 < 数; 序 += 1) 索引.set(`${格位[序].列},${格位[序].行}`, 序);
  const 邻接: number[][] = 格位.map(() => []);
  let 边数 = 0;
  for (let 序 = 0; 序 < 数; 序 += 1) {
    const 形 = 格位[序];
    for (const [横, 纵] of [
      [1, 0],
      [-1, 0],
      [0, 1],
      [0, -1],
    ] as const) {
      const 对 = 索引.get(`${形.列 + 横},${形.行 + 纵}`);
      if (对 === undefined) continue;
      if (对 > 序) 边数 += 1;
      邻接[序].push(对);
    }
    if (邻接[序].length > 2) return null;
  }
  if (边数 !== 数 - 1) return null;
  let 端 = 邻接.findIndex((集) => 集.length <= 1);
  if (端 < 0) 端 = 0;
  const 序列: number[] = [];
  let 前 = -1;
  let 当前 = 端;
  while (当前 >= 0) {
    序列.push(当前);
    const 下 = 邻接[当前].find((值) => 值 !== 前) ?? -1;
    前 = 当前;
    当前 = 下;
  }
  if (序列.length !== 数) return null;
  // 统一从靠下（同高时靠右）的一端起步：同一根糖换个格序也画成同一副样子，
  // 条纹相位与直线棍端头的蝴蝶结才不会在重算时来回跳。
  const 头 = 格位[序列[0]];
  const 尾 = 格位[序列[序列.length - 1]];
  if (尾.行 > 头.行 || (尾.行 === 头.行 && 尾.列 > 头.列)) 序列.reverse();
  return 序列.map((序) => {
    const 形 = 格位[序];
    return { x: 形.单元左 + 几何.格 / 2, y: 形.单元上 + 几何.格 / 2 };
  });
}

/** 把格心折线的每个真实拐角切成圆弧，再按弧长采样出切向与法向。 */
function 构建中轴(格心: readonly 点[], 格: number): 中轴 {
  const 目标半径 = 格 * 弯半径比;
  const 段向: 点[] = [];
  const 段长: number[] = [];
  for (let 序 = 0; 序 < 格心.length - 1; 序 += 1) {
    const 差 = { x: 格心[序 + 1].x - 格心[序].x, y: 格心[序 + 1].y - 格心[序].y };
    段长.push(Math.hypot(差.x, 差.y));
    段向.push(单位(差));
  }
  const 累计 = [0];
  for (let 序 = 0; 序 < 段长.length; 序 += 1) 累计.push(累计[序] + 段长[序]);

  // 只有真正转向的格心才是拐角；一条直臂上的中间格不切圆角。
  const 弯处: number[] = [];
  for (let 序 = 1; 序 < 格心.length - 1; 序 += 1) {
    const 叉 = 段向[序 - 1].x * 段向[序].y - 段向[序 - 1].y * 段向[序].x;
    if (Math.abs(叉) > 0.1) 弯处.push(序);
  }
  const 弯半径 = 格心.map(() => 0);
  弯处.forEach((序, 位) => {
    const 前拐 = 位 > 0 ? 弯处[位 - 1] : 0;
    const 后拐 = 位 < 弯处.length - 1 ? 弯处[位 + 1] : 格心.length - 1;
    // 相邻两个弯之间两段圆弧相加不能超过直段，端头一侧则留一点直段给圆头。
    const 前界 = (位 > 0 ? 0.5 : 0.85) * (累计[序] - 累计[前拐]);
    const 后界 = (位 < 弯处.length - 1 ? 0.5 : 0.85) * (累计[后拐] - 累计[序]);
    弯半径[序] = Math.min(目标半径, 前界, 后界);
  });

  const 折线: 点[] = [格心[0]];
  const 推点 = (位: 点) => {
    const 末 = 折线[折线.length - 1];
    if (末 && Math.hypot(位.x - 末.x, 位.y - 末.y) < 1e-4) return;
    折线.push(位);
  };
  const 弯范围: 弯段[] = [];
  for (let 序 = 0; 序 < 格心.length - 1; 序 += 1) {
    const 向 = 段向[序];
    const 下个弯 = 序 + 1 < 格心.length - 1 ? 弯半径[序 + 1] : 0;
    const 拐点 = 格心[序 + 1];
    const 直末 = 沿(拐点, 向, -下个弯);
    推点(直末);
    if (下个弯 <= 0) continue;
    const 后向 = 段向[序 + 1];
    const 圆心 = 沿(沿(拐点, 向, -下个弯), 后向, 下个弯);
    const 起角 = Math.atan2(直末.y - 圆心.y, 直末.x - 圆心.x);
    const 终位 = 沿(拐点, 后向, 下个弯);
    const 终角 = Math.atan2(终位.y - 圆心.y, 终位.x - 圆心.x);
    const 差角 = 归一化角(终角 - 起角);
    const 步数 = Math.max(4, Math.ceil(Math.abs(差角) / 0.16));
    const 起序 = 折线.length - 1;
    for (let 步 = 1; 步 <= 步数; 步 += 1) {
      const 角 = 起角 + (差角 * 步) / 步数;
      推点({ x: 圆心.x + Math.cos(角) * 下个弯, y: 圆心.y + Math.sin(角) * 下个弯 });
    }
    弯范围.push({ 起序, 止序: 折线.length - 1 });
  }

  const 采样: 中轴采样[] = [];
  let 累 = 0;
  for (let 序 = 0; 序 < 折线.length; 序 += 1) {
    if (序 > 0) 累 += Math.hypot(折线[序].x - 折线[序 - 1].x, 折线[序].y - 折线[序 - 1].y);
    const 前 = 折线[Math.max(0, 序 - 1)];
    const 后 = 折线[Math.min(折线.length - 1, 序 + 1)];
    const 切 = 单位({ x: 后.x - 前.x, y: 后.y - 前.y });
    采样.push({ 位: 折线[序], 切, 法: { x: 切.y, y: -切.x }, 弧长: 累 });
  }
  const 有效半径 = 弯半径.filter((值) => 值 > 0);
  return {
    采样,
    弯段: 弯范围,
    总长: 累,
    最小弯半径: 有效半径.length > 0 ? Math.min(...有效半径) : 目标半径,
  };
}

/** 按累计弧长在中轴上取点（含插值出的切向与法向）。 */
function 弧长取位(采样: readonly 中轴采样[], 弧长: number): { 位: 点; 切: 点; 法: 点 } {
  let 低 = 0;
  let 高 = 采样.length - 1;
  while (低 < 高 - 1) {
    const 中 = (低 + 高) >> 1;
    if (采样[中].弧长 <= 弧长) 低 = 中;
    else 高 = 中;
  }
  const 甲 = 采样[低];
  const 乙 = 采样[高];
  const 跨 = 乙.弧长 - 甲.弧长;
  const 比 = 跨 > 1e-6 ? Math.min(1, Math.max(0, (弧长 - 甲.弧长) / 跨)) : 0;
  const 位 = { x: 甲.位.x + (乙.位.x - 甲.位.x) * 比, y: 甲.位.y + (乙.位.y - 甲.位.y) * 比 };
  const 切 = 单位({
    x: 甲.切.x + (乙.切.x - 甲.切.x) * 比,
    y: 甲.切.y + (乙.切.y - 甲.切.y) * 比,
  });
  return { 位, 切, 法: { x: 切.y, y: -切.x } };
}


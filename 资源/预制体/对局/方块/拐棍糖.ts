/* 入口                                                                */
/* ------------------------------------------------------------------ */

/** 单格：一截断掉的短糖棍（竖放），圆头 + 深描边 + 两道条纹，不压蝴蝶结。 */
function 画单格(绘图: 图形对象, 几何: 糖果块几何): void {
  const 格 = 几何.格;
  const 中轴 = 构建中轴(
    [
      { x: 几何.中心X, y: 几何.中心Y - 格 * 0.25 },
      { x: 几何.中心X, y: 几何.中心Y + 格 * 0.25 },
    ],
    格,
  );
  画糖身(绘图, 几何, 中轴, 格 * 0.18, 取条纹参数(中轴, 格, true));
}

export function 绘制拐棍糖(绘图: 图形对象, 几何: 糖果块几何): void {
  const { 格 } = 几何;
  if (几何.单格) {
    画单格(绘图, 几何);
    return;
  }
  const 格心 = 取格心序列(几何);
  if (!格心 || 格心.length < 2) {
    画兜底(绘图, 几何);
    return;
  }
  const 中轴 = 构建中轴(格心, 格);
  const 半宽 = Math.min(格 * 半宽比, 中轴.最小弯半径 - 格 * 内弯留比);
  画糖身(绘图, 几何, 中轴, 半宽, 取条纹参数(中轴, 格, false));
  const 结 = 取蝴蝶结(中轴, 半宽, 格);
  if (结) 画蝴蝶结(绘图, 结, 几何.样式, 几何.透明度);
}

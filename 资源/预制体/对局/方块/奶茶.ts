import type { 图形对象, 点 } from "../../../../.gamemaker/依赖/框架/界面/绘制/协议";
import { 同角, 圆角多边形, 裁进凸形, type 边界 } from "../../基础/装饰与蒙层/圆角裁剪";
import { 暗侧, type 糖果块几何 } from "./几何";

/**
 * 奶茶（Z / S 型，互为镜像）：一格一块奶茶方糖。
 *
 * 辨识点是一只「装满饮料的方杯」：深色杯边 → 主色杯身 → 杯口一条奶盖。
 * 格 ≥ 30 再补细节（暗杯壁圈、液面亮带、两块冰、一片果片、杯底暗边、左侧反光），
 * 25px 的棋盘格只留前面三件套。
 *
 * 只用纯色 + 透明度，不用渐变；花纹都按世界坐标算多边形，只借 裁进凸形 收边。
 * Z 与 S 只差口味色（鲜橙水果茶 / 蓝莓气泡），形状与相邻格无关。
 */

/** 一格为 25px 时的比例，按格宽推。 */
const 缝比 = 0.02;
const 描比 = 0.07;
/** 杯的圆角：撑满一格时仍读得出是圆角方块。 */
const 杯圆角比 = 0.18;
/** 格宽达到这个值才补冰块 / 果片 / 液面亮带这些细节。 */
const 细节格 = 30;

/**
 * 杯身撑满这一格：深色杯边 → 主色杯身 → 杯口奶盖。
 * 格 ≥ 30 再补：暗杯壁圈、液面亮带、两块冰块、一片果片、杯底暗边、左侧反光。
 */
export function 绘制奶茶(绘图: 图形对象, 几何: 糖果块几何): void {
  const { 格, 透明度 } = 几何;
  const { 主色, 深色, 浅色, 装饰, 装饰深 } = 几何.样式;
  const 体暗 = 暗侧(几何.样式);
  const 细节 = 格 >= 细节格;
  const 缝 = Math.max(0.4, 格 * 缝比);
  const 描 = Math.max(1, 格 * 描比);
  const 边: 边界 = {
    左: 几何.左 + 缝,
    上: 几何.上 + 缝,
    右: 几何.右 - 缝,
    下: 几何.下 - 缝,
  };
  const 宽 = 边.右 - 边.左;
  const 高 = 边.下 - 边.上;
  const 圆 = Math.min(宽, 高) * 杯圆角比;

  // ① 落影
  绘图.fillStyle(0x1c0a08, 0.3 * 透明度);
  绘图.fillPoints(
    圆角多边形({ 左: 边.左, 上: 边.上 + 格 * 0.09, 右: 边.右, 下: 边.下 + 格 * 0.09 }, 同角(圆)),
    true,
  );

  // ② 深色杯边：撑满这一格
  绘图.fillStyle(深色, 透明度);
  绘图.fillPoints(圆角多边形(边, 同角(圆)), true);

  // ③ 杯身：主色一块，粗看就是一块方糖大小的杯
  const 内: 边界 = { 左: 边.左 + 描, 上: 边.上 + 描, 右: 边.右 - 描, 下: 边.下 - 描 };
  const 内宽 = 内.右 - 内.左;
  const 内高 = 内.下 - 内.上;
  const 内圆 = Math.max(0.8, 圆 - 描);
  const 液: 边界 = 细节
    ? { 左: 内.左 + 内宽 * 0.06, 上: 内.上, 右: 内.右 - 内宽 * 0.06, 下: 内.下 - 内高 * 0.05 }
    : 内;
  const 液宽 = 液.右 - 液.左;
  const 液高 = 液.下 - 液.上;
  const 液形 = 圆角多边形(液, 同角(Math.max(0.8, 内圆 - (细节 ? 描 * 0.5 : 0))));
  if (细节) {
    绘图.fillStyle(体暗, 透明度);
    绘图.fillPoints(圆角多边形(内, 同角(内圆)), true);
  }
  绘图.fillStyle(主色, 透明度);
  绘图.fillPoints(液形, true);

  // ④ 杯口奶盖：25px 下就靠这一条读「杯里有料」，下沿在细节档才起伏
  const 盖底 = 液.上 + 液高 * (细节 ? 0.26 : 0.3);
  const 波: 点[] = [
    { x: 液.左 - 1, y: 液.上 - 1 },
    { x: 液.右 + 1, y: 液.上 - 1 },
  ];
  if (细节) {
    for (let i = 0; i <= 8; i += 1) {
      const t = 1 - i / 8;
      波.push({ x: 液.左 + 液宽 * t, y: 盖底 + Math.sin(t * Math.PI * 3) * 液高 * 0.035 });
    }
  } else {
    波.push({ x: 液.右 + 1, y: 盖底 }, { x: 液.左 - 1, y: 盖底 });
  }
  const 盖形 = 裁进凸形(波, 液形);
  if (盖形.length >= 3) {
    绘图.fillStyle(装饰, 0.92 * 透明度);
    绘图.fillPoints(盖形, true);
  }

  if (!细节) return;

  // ⑤ 液面亮带：奶盖下面一条浅色，读作饮料表面
  绘图.fillStyle(浅色, 0.4 * 透明度);
  绘图.fillPoints(
    裁进凸形(
      [
        { x: 液.左 - 1, y: 盖底 - 1 },
        { x: 液.右 + 1, y: 盖底 - 1 },
        { x: 液.右 + 1, y: 液.上 + 液高 * 0.44 },
        { x: 液.左 - 1, y: 液.上 + 液高 * 0.44 },
      ],
      液形,
    ),
    true,
  );

  // ⑥ 冰块（装饰色半透明块）与果片：格子比略高，冰块竖着错开摆
  const 冰 = Math.min(液宽, 液高) * 0.34;
  const 冰位: readonly (readonly [number, number])[] = [
    [0.5, 0.4],
    [0.42, 0.54],
  ];
  for (const [u, v] of 冰位) {
    绘图.fillStyle(装饰, 0.5 * 透明度);
    绘图.fillRoundedRect(液.左 + 液宽 * u - 冰 / 2, 液.上 + 液高 * v - 冰 / 2, 冰, 冰, 冰 * 0.3);
  }
  const 果R = Math.min(液宽, 液高) * 0.3;
  const 果位: readonly [number, number] = [0.44, 0.64];
  画果片(绘图, 液.左 + 液宽 * 果位[0], 液.上 + 液高 * 果位[1], 果R, 装饰, 装饰深, 透明度);

  // ⑦ 杯底一条暗边
  const 底形 = 裁进凸形(
    [
      { x: 液.左 - 1, y: 液.下 - 液高 * 0.16 },
      { x: 液.右 + 1, y: 液.下 - 液高 * 0.16 },
      { x: 液.右 + 1, y: 液.下 + 1 },
      { x: 液.左 - 1, y: 液.下 + 1 },
    ],
    液形,
  );
  if (底形.length >= 3) {
    绘图.fillStyle(深色, 0.45 * 透明度);
    绘图.fillPoints(底形, true);
  }

  // ⑧ 杯身左侧一道浅色反光
  绘图.fillStyle(浅色, 0.22 * 透明度);
  绘图.fillRoundedRect(
    液.左 + 液宽 * 0.08,
    液.上 + 液高 * 0.34,
    Math.max(1.2, 液宽 * 0.055),
    液高 * 0.34,
    Math.max(0.6, 液宽 * 0.028),
  );
}

/** 果片：一小片圆片，外圈装饰深、内芯装饰色，再压几道瓣。 */
function 画果片(
  绘图: 图形对象,
  cx: number,
  cy: number,
  半径: number,
  装饰: number,
  装饰深: number,
  透明度: number,
): void {
  if (半径 < 1.6) return;
  绘图.fillStyle(装饰深, 透明度);
  绘图.fillCircle(cx, cy, 半径);
  绘图.fillStyle(装饰, 透明度);
  绘图.fillCircle(cx, cy, 半径 * 0.86);
  绘图.fillStyle(装饰深, 0.8 * 透明度);
  for (let 瓣 = 0; 瓣 < 6; 瓣 += 1) {
    const 角 = (Math.PI / 3) * 瓣 + Math.PI / 6;
    const 点集: 点[] = [{ x: cx, y: cy }];
    for (let k = -1; k <= 1; k += 1) {
      const a = 角 + k * 0.05;
      点集.push({ x: cx + Math.cos(a) * 半径 * 0.8, y: cy + Math.sin(a) * 半径 * 0.8 });
    }
    绘图.fillPoints(点集, true);
  }
}

/* 吸管                                                                */
/* ------------------------------------------------------------------ */

/**
 * 管的走向：整条贴着杯子铺满自己那 2 格，到杯心拐一次 90° 扎进杯里。
 * 横管贴在杯口上沿、先横后竖；竖管贴在杯壁、先竖后横。两段互相垂直，拐弯一眼看得见。
 */
function 取管路径(几何: 糖果块几何, 管框: 框, 杯框: 框): 弯管路径 {
  const 格 = 几何.格;
  const 半 = (格 * 管宽比) / 2;

  if (管框.宽 >= 管框.高) {
    // 横躺管：整条压在杯口上沿，管心到杯心正上方拐下去
    const 纵 = 管框.下 - 半;
    const 拐 = { x: 夹(杯框.中心X, 管框.左, 管框.右), y: 纵 };
    const 起 = { x: 拐.x >= 管框.中心X ? 管框.左 + 半 : 管框.右 - 半, y: 纵 };
    return { 起, 拐, 止: { x: 拐.x, y: 杯框.下 - 杯框.高 * 杯底留白比 } };
  }

  // 竖立管：整条贴着杯壁，到杯心那一行拐进去
  const 横 = 杯框.中心X < 管框.中心X ? 管框.左 + 半 : 管框.右 - 半;
  const 拐 = { x: 横, y: 夹(杯框.中心Y, 管框.上, 管框.下) };
  const 起 = { x: 横, y: 拐.y >= 管框.中心Y ? 管框.上 + 半 : 管框.下 - 半 };
  return { 起, 拐, 止: { x: 杯框.中心X, y: 拐.y } };
}

/** 画一根弯吸管：深色描边 → 奶油白管身 → 沿管身的主色条纹；两段圆头胶囊叠出圆角弯头。 */
function 画吸管(绘图: 图形对象, 几何: 糖果块几何, 路径: 弯管路径, 透明度: number): void {
  const 格 = 几何.格;
  const { 主色, 深色, 装饰 } = 几何.样式;
  const 描 = Math.max(0.8, 格 * 0.055);
  const 管宽 = 格 * 管宽比;
  // 横段是 Z 的「上横带」，保持粗；拐下去插进杯子的那一段收细到 0.55，
  // 否则竖直段和两条横带一样粗，整颗糖会读成 S/L 而不是 Z。
  const 段们 = [
    { 起: 路径.起, 止: 路径.拐, 宽: 管宽 },
    { 起: 路径.拐, 止: 路径.止, 宽: 管宽 * 0.55 },
  ];

  // ① 管影：整根管子往下错一点，压在杯口上不飘
  const 影移 = 格 * 0.07;
  绘图.fillStyle(0x1c0a08, 0.22 * 透明度);
  for (const 段 of 段们) {
    绘图.fillPoints(
      圆头带({ x: 段.起.x, y: 段.起.y + 影移 }, { x: 段.止.x, y: 段.止.y + 影移 }, 段.宽),
      true,
    );
  }

  // ② 深色管边：两段各描一圈，合起来就是整根弯管的外轮廓
  绘图.fillStyle(深色, 透明度);
  for (const 段 of 段们) 绘图.fillPoints(圆头带(段.起, 段.止, 段.宽 + 描 * 2), true);

  // ③ 管身：主色打底（和杯身同色），整颗糖才连成一个 Z 轮廓；白条纹只是装饰
  const 管身 = 段们.map((段) => 圆头带(段.起, 段.止, 段.宽));
  绘图.fillStyle(主色, 透明度);
  for (const 形 of 管身) 绘图.fillPoints(形, true);

  // ④ 沿管身交替的奶油白条纹，两段各自按管轴铺，拐弯处自然接上
  const 斑宽 = 格 * 管纹比;
  for (let 序 = 0; 序 < 段们.length; 序 += 1) {
    const 形 = 管身[序];
    if (形) 画管纹(绘图, 段们[序], 形, 段们[序]?.宽 ?? 管宽, 斑宽, 装饰, 透明度);
  }
}

/** 沿一段管身铺条纹：垂直于管轴的窄带，裁进管身凸形后填主色。 */
function 画管纹(
  绘图: 图形对象,
  段: { 起: 点; 止: 点 },
  管身: readonly 点[],
  管宽: number,
  斑宽: number,
  主色: number,
  透明度: number,
): void {
  const dx = 段.止.x - 段.起.x;
  const dy = 段.止.y - 段.起.y;
  const 长 = Math.hypot(dx, dy);
  if (长 < 斑宽) return;
  const ux = dx / 长;
  const uy = dy / 长;
  const 半 = 管宽 / 2;
  const 道数 = Math.floor(长 / 斑宽);
  for (let 道 = 1; 道 < 道数; 道 += 2) {
    const 起T = 道 * 斑宽;
    const 止T = 起T + 斑宽;
    const 带: 点[] = [
      { x: 段.起.x + ux * 起T - uy * 半, y: 段.起.y + uy * 起T + ux * 半 },
      { x: 段.起.x + ux * 止T - uy * 半, y: 段.起.y + uy * 止T + ux * 半 },
      { x: 段.起.x + ux * 止T + uy * 半, y: 段.起.y + uy * 止T - ux * 半 },
      { x: 段.起.x + ux * 起T + uy * 半, y: 段.起.y + uy * 起T - ux * 半 },
    ];
    const 形 = 裁进凸形(带, 管身);
    if (形.length < 3) continue;
    绘图.fillStyle(主色, 透明度);
    绘图.fillPoints(形, true);
  }
}

/** 圆头胶囊：一段粗线加两端半圆，顺时针凸多边形，可直接喂 `裁进凸形`。 */
function 圆头带(起: 点, 止: 点, 宽: number): 点[] {
  const 半 = 宽 / 2;
  const dx = 止.x - 起.x;
  const dy = 止.y - 起.y;
  const 角 = Math.atan2(dy, dx);
  const 段 = 5;
  const 点集: 点[] = [];
  if (Math.hypot(dx, dy) < 0.01) {
    for (let i = 0; i <= 12; i += 1) {
      const t = 角 - Math.PI / 2 + (Math.PI * 2 * i) / 12;
      点集.push({ x: 起.x + Math.cos(t) * 半, y: 起.y + Math.sin(t) * 半 });
    }
    return 点集;
  }
  const 横 = Math.cos(角);
  const 纵 = Math.sin(角);
  点集.push({ x: 起.x + 纵 * 半, y: 起.y - 横 * 半 });
  点集.push({ x: 止.x + 纵 * 半, y: 止.y - 横 * 半 });
  for (let i = 1; i < 段; i += 1) {
    const t = 角 - Math.PI / 2 + (Math.PI * i) / 段;
    点集.push({ x: 止.x + Math.cos(t) * 半, y: 止.y + Math.sin(t) * 半 });
  }
  点集.push({ x: 止.x - 纵 * 半, y: 止.y + 横 * 半 });
  点集.push({ x: 起.x - 纵 * 半, y: 起.y + 横 * 半 });
  for (let i = 1; i < 段; i += 1) {
    const t = 角 + Math.PI / 2 + (Math.PI * i) / 段;
    点集.push({ x: 起.x + Math.cos(t) * 半, y: 起.y + Math.sin(t) * 半 });
  }
  return 点集;
}


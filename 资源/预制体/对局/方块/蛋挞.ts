import type { 图形对象, 点 } from "../../../../.gamemaker/依赖/框架/界面/绘制/协议";
import { 同角, 圆角多边形, 裁进凸形, type 边界 } from "../../基础/装饰与蒙层/圆角裁剪";
import type { 糖果块几何 } from "./几何";

/**
 * 蛋挞（I 型）：酥皮塔皮 + 奶黄蛋液 + 焦橙斑点，沿包围盒拉成一条长蛋挞。
 *
 * 其它糖是一层糖身，蛋挞故意多一层体积：深色包边 → 塔皮侧壁（一档暗色、带竖向褶）
 * → 金色塔皮顶面 → 深色分界线 + 奶油亮线 → 奶黄蛋液面 → 焦橙斑点。
 * 塔皮外缘沿轮廓弧长排一圈扇形花边（扇贝），侧壁下沿因此是波浪底。
 *
 * 造型只吃包围盒，所以 4×1 横条、1×4 竖条、残缺 2~3 格与单格走同一条路径：
 * 长边决定蛋挞的长轴、短边固定一格，旋转后就是同款蛋挞换一个朝向；
 * 单格时自动收成一颗迷你蛋挞（圆形塔皮 + 两三块焦斑）。
 */
export function 绘制蛋挞(绘图: 图形对象, 几何: 糖果块几何): void {
  const { 格, 样式, 透明度 } = 几何;
  if (透明度 <= 0) return;

  const 宽 = 几何.列数 * 格;
  const 高 = 几何.行数 * 格;
  const 短 = Math.min(宽, 高);
  const 边距 = Math.max(0.6, 格 * 0.025);
  const 描边 = Math.max(0.9, 格 * 0.055);
  // 花边周期：25px 格下按 0.34 格排会有 17 个瓣，缩到屏幕上就是一圈锯齿噪点（满盘最显乱的一处）。
  // 小格直接放到 0.62 格，瓣数减半，读作「捏出来的塔皮边」；大格才用细瓣。
  const 周期 = Math.max(6, 格 * (格 < 30 ? 0.92 : 0.38));
  const 幅度 = 周期 * 0.3; // 花边鼓出量：约三分之一周期时读作捏出来的塔皮边
  const 步 = Math.max(0.9, 格 * 0.045);

  // ① 外轮廓：塔皮占满包围盒，留一点边距给相邻的糖
  const 外: 边界 = {
    左: 几何.左 + 边距,
    上: 几何.上 + 边距,
    右: 几何.左 + 宽 - 边距,
    下: 几何.上 + 高 - 边距,
  };
  const 圆角 = 短 * 0.46;
  const 壁高 = Math.min(Math.max(短 * 0.19, 2), 短 * 0.28);
  const 壁线 = 外.下 - 壁高;
  const 塔皮 = 塔皮轮廓(外, 圆角, 周期, 幅度, 步);
  const 顶色 = 混色(样式.主色, 样式.装饰深, 0.18);
  const 壁色 = 混色(样式.主色, 样式.装饰深, 0.62);
  const 影 = 格 * 0.09;

  // ② 落影：与其它糖同一档，压在格子下沿
  绘图.fillStyle(0x1c0a08, 0.3 * 透明度);
  绘图.fillPoints(塔皮轮廓({ ...外, 上: 外.上 + 影, 下: 外.下 + 影 }, 圆角, 周期, 幅度, 步), true);

  // ③ 深色包边：比塔皮再外扩一档，花边峰值仍落在格内
  绘图.fillStyle(样式.深色, 透明度);
  绘图.fillPoints(
    塔皮轮廓(
      { 左: 外.左 - 描边, 上: 外.上 - 描边, 右: 外.右 + 描边, 下: 外.下 + 描边 },
      圆角 + 描边,
      周期,
      幅度,
      步,
    ),
    true,
  );

  // ④ 塔皮侧壁：整块先铺暗一档的塔皮色，顶面再盖上去，剩下的下沿就是厚度
  绘图.fillStyle(壁色, 透明度);
  绘图.fillPoints(塔皮, true);

  // 侧壁竖褶：塔皮一格一格捏出来的棱，只落在直边上，端头的圆弧保持干净
  const 裁形 = 圆角多边形(
    {
      左: 外.左 + 描边 * 0.6,
      上: 外.上 + 描边 * 0.6,
      右: 外.右 - 描边 * 0.6,
      下: 外.下 - 描边 * 0.6,
    },
    同角(Math.max(0, 圆角 - 描边 * 0.6)),
  );
  const 棱宽 = Math.max(0.9, 格 * 0.045);
  const 棱距 = Math.max(2.6, 格 * 0.2);
  const 直起 = 外.左 + 圆角;
  const 直止 = 外.右 - 圆角;
  if (直止 - 直起 > 棱距 * 0.5) {
    绘图.fillStyle(样式.装饰深, 0.34 * 透明度);
    const 棱数 = Math.max(1, Math.floor((直止 - 直起) / 棱距));
    for (let 序 = 1; 序 < 棱数; 序 += 1) {
      const x = 直起 + ((直止 - 直起) * 序) / 棱数;
      const 棱 = 裁进凸形(
        [
          { x: x - 棱宽 / 2, y: 壁线 },
          { x: x + 棱宽 / 2, y: 壁线 },
          { x: x + 棱宽 / 2, y: 外.下 },
          { x: x - 棱宽 / 2, y: 外.下 },
        ],
        裁形,
      );
      if (棱.length >= 3) 绘图.fillPoints(棱, true);
    }
  }

  // ⑤ 塔沿悬出的一线暗影：顶面比侧壁鼓出来一点，交界处压暗
  绘图.fillStyle(样式.深色, 0.3 * 透明度);
  绘图.fillPoints(裁横带(塔皮, 壁线, 壁线 + Math.max(0.9, 格 * 0.055)), true);

  // ⑥ 金色塔皮顶面：切在壁线以上，花边整圈是金的（最外一圈才是深色包边）
  绘图.fillStyle(顶色, 透明度);
  绘图.fillPoints(裁横带(塔皮, 外.上 - 描边, 壁线), true);

  // 顶面下沿受光：塔沿的圆弧边先亮后暗，读作悬出的一圈边
  绘图.fillStyle(样式.浅色, 0.34 * 透明度);
  绘图.fillPoints(裁横带(塔皮, 壁线 - 描边 * 0.5 - Math.max(0.6, 格 * 0.035), 壁线), true);

  // ⑦ 蛋液面：内缩 0.18 格，外圈一道深色分界线 + 一圈奶油亮线
  const 液缩 = 格 * (几何.单格 ? 0.16 : 0.18);
  const 液: 边界 = {
    左: 外.左 + 描边 + 液缩,
    上: 外.上 + 描边 + 液缩,
    右: 外.右 - 描边 - 液缩,
    下: 壁线 - 描边 * 0.7 - 格 * 0.05,
  };
  const 液宽 = 液.右 - 液.左;
  const 液高 = 液.下 - 液.上;
  const 液圆角 = Math.min(液宽, 液高) * 0.48;
  const 分界 = 描边 * 0.9 + Math.max(0.35, 格 * 0.012);
  const 奶油 = Math.max(0.55, 格 * 0.022);
  绘图.fillStyle(样式.深色, 0.75 * 透明度);
  绘图.fillPoints(
    圆角多边形(
      { 左: 液.左 - 分界, 上: 液.上 - 分界, 右: 液.右 + 分界, 下: 液.下 + 分界 },
      同角(液圆角 + 分界),
    ),
    true,
  );
  绘图.fillStyle(样式.浅色, 0.85 * 透明度);
  绘图.fillPoints(
    圆角多边形(
      { 左: 液.左 - 奶油, 上: 液.上 - 奶油, 右: 液.右 + 奶油, 下: 液.下 + 奶油 },
      同角(液圆角 + 奶油),
    ),
    true,
  );
  绘图.fillStyle(样式.装饰, 透明度);
  绘图.fillPoints(圆角多边形(液, 同角(液圆角)), true);

  // ⑧ 蛋液面的光：上缘受光、下缘压暗，纯色带做出挞水凝住的厚度
  const 蛋液 = 圆角多边形(液, 同角(液圆角));
  绘图.fillStyle(样式.装饰深, 0.14 * 透明度);
  绘图.fillPoints(裁横带(蛋液, 液.下 - 液高 * 0.3, 液.下), true);
  绘图.fillStyle(样式.浅色, 0.22 * 透明度);
  绘图.fillPoints(裁横带(蛋液, 液.上, 液.上 + 液高 * 0.24), true);

  // ⑨ 焦橙斑点：3~5 块椭圆，大小不一、错开摆；单格只留两三颗
  const 沿横 = 液宽 >= 液高;
  const 液短 = Math.min(液宽, 液高);
  const 液中心X = (液.左 + 液.右) / 2;
  const 液中心Y = (液.上 + 液.下) / 2;
  const 斑点表 = 取斑点表(Math.max(几何.列数, 几何.行数));
  const 斑比 = 几何.单格 ? 0.76 : 1;
  for (const [u, v, k] of 斑点表) {
    const 沿半径 = 液短 * 0.24 * k * 斑比;
    const 横半径 = 液短 * 0.165 * k * 斑比;
    const 半沿 = (沿横 ? 液宽 : 液高) / 2 - 沿半径 - Math.max(0.6, 格 * 0.03);
    const 半横 = 液短 / 2 - 横半径 - Math.max(0.5, 格 * 0.025);
    if (半沿 <= 0 || 半横 <= 0) continue;
    const 沿偏 = (u - 0.5) * 2 * 半沿;
    const 横偏 = (v - 0.5) * 2 * 半横;
    const cx = 沿横 ? 液中心X + 沿偏 : 液中心X + 横偏;
    const cy = 沿横 ? 液中心Y + 横偏 : 液中心Y + 沿偏;
    const rx = 沿横 ? 沿半径 : 横半径;
    const ry = 沿横 ? 横半径 : 沿半径;
    绘图.fillStyle(样式.装饰深, 0.9 * 透明度);
    绘图.fillPoints(椭圆(cx, cy, rx, ry), true);
    // 焦斑靠上的一点糖色，像烤化的挞水表面（只在大尺寸出现，小格留纯色斑）
    if (沿半径 >= 2.6) {
      绘图.fillStyle(混色(样式.装饰深, 样式.装饰, 0.55), 0.3 * 透明度);
      绘图.fillPoints(椭圆(cx - rx * 0.16, cy - ry * 0.2, rx * 0.38, ry * 0.32), true);
    }
  }
}

/** 扇贝外轮廓：基线内缩一个幅度，沿弧长每「周期」鼓出一个半圆，峰值正好回到原边界。 */
function 塔皮轮廓(边: 边界, 圆角: number, 周期: number, 幅度: number, 步: number): 点[] {
  const 基: 边界 = {
    左: 边.左 + 幅度,
    上: 边.上 + 幅度,
    右: 边.右 - 幅度,
    下: 边.下 - 幅度,
  };
  return 扇贝(基, Math.max(0.4, 圆角 - 幅度), 周期, 幅度, 步);
}

/**
 * 扇贝折线：沿圆角矩形的弧长排半圆花边，向外鼓出「幅度」。
 * 半圆剖面用 sqrt(1-(2t-1)²)，波谷处收成尖，读作捏出来的塔皮边。
 */
function 扇贝(基: 边界, 圆角: number, 周期: number, 幅度: number, 步: number): 点[] {
  const 底 = 密圆角矩形(基, 圆角, 步);
  const 数 = 底.length;
  if (数 < 4) return 底;
  const 弧长: number[] = [0];
  for (let i = 1; i <= 数; i += 1) {
    const 前 = 底[i - 1];
    const 当 = 底[i % 数];
    弧长.push(弧长[i - 1] + Math.hypot(当.x - 前.x, 当.y - 前.y));
  }
  let 中心X = 0;
  let 中心Y = 0;
  for (const p of 底) {
    中心X += p.x;
    中心Y += p.y;
  }
  中心X /= 数;
  中心Y /= 数;
  const 结果: 点[] = [];
  for (let i = 0; i < 数; i += 1) {
    const 前 = 底[(i - 1 + 数) % 数];
    const 后 = 底[(i + 1) % 数];
    const 切x = 后.x - 前.x;
    const 切y = 后.y - 前.y;
    const 长 = Math.hypot(切x, 切y) || 1;
    let 法x = 切y / 长;
    let 法y = -切x / 长;
    const 当 = 底[i];
    if (法x * (当.x - 中心X) + 法y * (当.y - 中心Y) < 0) {
      法x = -法x;
      法y = -法y;
    }
    const t = (弧长[i] % 周期) / 周期;
    const 鼓 = Math.sqrt(Math.max(0, 1 - (2 * t - 1) ** 2));
    结果.push({ x: 当.x + 法x * 幅度 * 鼓, y: 当.y + 法y * 幅度 * 鼓 });
  }
  return 结果;
}

/** 顺时针圆角矩形，按固定步长密采点，给花边当弧长基线。 */
function 密圆角矩形(边: 边界, 圆角: number, 步: number): 点[] {
  const 点集: 点[] = [];
  const 限 = Math.max(0, Math.min(边.右 - 边.左, 边.下 - 边.上) / 2);
  const r = Math.min(Math.max(0, 圆角), 限);
  const 直边 = (起: 点, 止: 点) => {
    const 段 = Math.max(1, Math.ceil(Math.hypot(止.x - 起.x, 止.y - 起.y) / 步));
    for (let i = 1; i < 段; i += 1) {
      点集.push({
        x: 起.x + ((止.x - 起.x) * i) / 段,
        y: 起.y + ((止.y - 起.y) * i) / 段,
      });
    }
  };
  const 弧 = (cx: number, cy: number, 起角: number) => {
    const 段 = r <= 0.05 ? 1 : Math.max(3, Math.ceil(((Math.PI / 2) * r) / 步));
    for (let i = 0; i <= 段; i += 1) {
      const a = 起角 + (Math.PI / 2) * (i / 段);
      点集.push({ x: cx + Math.cos(a) * r, y: cy + Math.sin(a) * r });
    }
  };
  弧(边.左 + r, 边.上 + r, Math.PI);
  直边({ x: 边.左 + r, y: 边.上 }, { x: 边.右 - r, y: 边.上 });
  弧(边.右 - r, 边.上 + r, Math.PI * 1.5);
  直边({ x: 边.右, y: 边.上 + r }, { x: 边.右, y: 边.下 - r });
  弧(边.右 - r, 边.下 - r, 0);
  直边({ x: 边.右 - r, y: 边.下 }, { x: 边.左 + r, y: 边.下 });
  弧(边.左 + r, 边.下 - r, Math.PI / 2);
  直边({ x: 边.左, y: 边.下 - r }, { x: 边.左, y: 边.上 + r });
  return 点集;
}

/** 保留 y ∈ [上界, 下界] 的横带；输入凸多边形，输出仍是凸多边形。 */
function 裁横带(点集: readonly 点[], 上界: number, 下界: number): 点[] {
  return 裁下(裁上(点集, 下界), 上界);
}

function 裁上(点集: readonly 点[], 上限: number): 点[] {
  const 出: 点[] = [];
  for (let i = 0; i < 点集.length; i += 1) {
    const 前 = 点集[(i - 1 + 点集.length) % 点集.length];
    const 当 = 点集[i];
    const 前内 = 前.y <= 上限;
    const 当内 = 当.y <= 上限;
    if (前内 !== 当内) {
      const t = (上限 - 前.y) / (当.y - 前.y || 1);
      出.push({ x: 前.x + (当.x - 前.x) * t, y: 上限 });
    }
    if (当内) 出.push(当);
  }
  return 出;
}

function 裁下(点集: readonly 点[], 下限: number): 点[] {
  const 出: 点[] = [];
  for (let i = 0; i < 点集.length; i += 1) {
    const 前 = 点集[(i - 1 + 点集.length) % 点集.length];
    const 当 = 点集[i];
    const 前内 = 前.y >= 下限;
    const 当内 = 当.y >= 下限;
    if (前内 !== 当内) {
      const t = (下限 - 前.y) / (当.y - 前.y || 1);
      出.push({ x: 前.x + (当.x - 前.x) * t, y: 下限 });
    }
    if (当内) 出.push(当);
  }
  return 出;
}

/** 椭圆折线，段数随半径走。 */
function 椭圆(中心X: number, 中心Y: number, 横半径: number, 纵半径: number): 点[] {
  const 段 = Math.max(10, Math.ceil((横半径 + 纵半径) * 1.6));
  const 点集: 点[] = [];
  for (let i = 0; i < 段; i += 1) {
    const a = (i / 段) * Math.PI * 2;
    点集.push({ x: 中心X + Math.cos(a) * 横半径, y: 中心Y + Math.sin(a) * 纵半径 });
  }
  return 点集;
}

/** 焦斑摆位：[沿长轴的 0~1, 横向的 0~1, 大小倍率]；按蛋挞长度挑一组。 */
function 取斑点表(长格: number): readonly (readonly [number, number, number])[] {
  if (长格 >= 4) {
    return [
      [0.1, 0.32, 1.15],
      [0.32, 0.7, 0.82],
      [0.52, 0.36, 1],
      [0.72, 0.66, 0.9],
      [0.9, 0.34, 0.7],
    ];
  }
  if (长格 === 3) {
    return [
      [0.14, 0.34, 1.1],
      [0.45, 0.68, 0.86],
      [0.75, 0.36, 0.96],
      [0.93, 0.62, 0.66],
    ];
  }
  if (长格 === 2) {
    return [
      [0.22, 0.36, 1.05],
      [0.58, 0.66, 0.82],
      [0.86, 0.38, 0.78],
    ];
  }
  return [
    [0.26, 0.34, 0.92],
    [0.72, 0.62, 0.7],
  ];
}

/** 一档混色：以「甲」为主，掺入「乙」的比例。 */
function 混色(甲: number, 乙: number, 比: number): number {
  const 通道 = (移: number) => {
    const a = (甲 >> 移) & 0xff;
    const b = (乙 >> 移) & 0xff;
    return Math.round(a + (b - a) * 比);
  };
  return (通道(16) << 16) | (通道(8) << 8) | 通道(0);
}

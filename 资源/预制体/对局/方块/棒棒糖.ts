import type { 图形对象, 点 } from "../../../../.gamemaker/依赖/框架/界面/绘制/协议";
import { 同角, 圆角多边形, 裁进凸形, type 边界 } from "../../基础/装饰与蒙层/圆角裁剪";
import { 暗侧, type 糖果块几何 } from "./几何";

/**
 * 棒棒糖（T 型）：三格糖头包成一颗草莓粉胶囊糖，奶油螺旋绕在糖面上，几粒糖针撒在两端；
 * 剩下的那一格当签子，从糖头背面伸出去一截。
 *
 * 朝向不写死：糖头长轴取格集里格数最多的那一行或那一列（T 是 3 格，残缺时 2 格），
 * 签子就是剩下的格，从糖头哪一侧伸出去由它在格集里的位置决定。
 * 旋转、残缺、单格因此走同一套推导；只剩一格时退化成一颗圆糖（签子碎片也画成糖）。
 *
 * 糖面花纹全部是纯色多边形：螺旋用三段粗圆弧拼出来，再用 `裁进凸形` 收进胶囊圆角。
 */

/** 糖头长轴朝向。 */
type 头轴 = "横" | "竖";

/** 糖头局部坐标系：长轴沿「沿」、短轴沿「垂」，坐标以糖头中心为原点，单位是逻辑像素。 */
interface 糖头基 {
  心X: number;
  心Y: number;
  沿X: number;
  沿Y: number;
  垂X: number;
  垂Y: number;
  /** 长轴半长、短轴半宽。 */
  长半: number;
  短半: number;
}

interface 格位 {
  列: number;
  行: number;
}

function 建基(心X: number, 心Y: number, 长半: number, 短半: number, 轴: 头轴): 糖头基 {
  return 轴 === "横"
    ? { 心X, 心Y, 沿X: 1, 沿Y: 0, 垂X: 0, 垂Y: 1, 长半, 短半 }
    : { 心X, 心Y, 沿X: 0, 沿Y: 1, 垂X: -1, 垂Y: 0, 长半, 短半 };
}

/** 局部坐标（沿轴、横向）换算到世界坐标。 */
function 定位(基: 糖头基, 沿: number, 垂: number): 点 {
  return {
    x: 基.心X + 基.沿X * 沿 + 基.垂X * 垂,
    y: 基.心Y + 基.沿Y * 沿 + 基.垂Y * 垂,
  };
}

/** 四边各向内收 `量`；保证收完仍是正着的矩形（极小格时退化也画得出）。 */
function 内缩边(边: 边界, 量: number): 边界 {
  const 横量 = Math.min(量, (边.右 - 边.左) * 0.34);
  const 纵量 = Math.min(量, (边.下 - 边.上) * 0.34);
  return { 左: 边.左 + 横量, 上: 边.上 + 纵量, 右: 边.右 - 横量, 下: 边.下 - 纵量 };
}

/**
 * 粗圆弧带：沿椭圆弧铺一条带子，半径从 `起比` 长到 `止比`（相对糖头半长/半宽），
 * 厚度从 `厚起` 收到 `厚止`；两条接起来就是螺旋。
 */
function 弧带(
  基: 糖头基,
  起比: number,
  止比: number,
  厚起: number,
  厚止: number,
  起角: number,
  止角: number,
): 点[] {
  const 段 = Math.max(5, Math.ceil(Math.abs(止角 - 起角) / 0.16));
  const 外: 点[] = [];
  const 内: 点[] = [];
  for (let i = 0; i <= 段; i += 1) {
    const t = i / 段;
    const 角 = 起角 + (止角 - 起角) * t;
    const 比 = 起比 + (止比 - 起比) * t;
    const 余 = Math.cos(角);
    const 正 = Math.sin(角);
    const 偏 = (厚起 + (厚止 - 厚起) * t) / 2;
    外.push(定位(基, 余 * 比 * 基.长半 + 余 * 偏, 正 * 比 * 基.短半 + 正 * 偏));
    内.push(定位(基, 余 * 比 * 基.长半 - 余 * 偏, 正 * 比 * 基.短半 - 正 * 偏));
  }
  return [...外, ...内.reverse()];
}

/** 糖针：绕糖头中心定位的一根圆角斜条。 */
function 糖针(基: 糖头基, 沿: number, 垂: number, 长: number, 宽: number, 倾斜: number): 点[] {
  const 角 = Math.atan2(基.沿Y, 基.沿X) + 倾斜;
  const 余弦 = Math.cos(角);
  const 正弦 = Math.sin(角);
  const 原形 = 圆角多边形({ 左: -长 / 2, 上: -宽 / 2, 右: 长 / 2, 下: 宽 / 2 }, 同角(宽 / 2));
  return 原形.map((p) => 定位(基, 沿 + p.x * 余弦 - p.y * 正弦, 垂 + p.x * 正弦 + p.y * 余弦));
}

/**
 * 糖体三层：深色描边 → 主色糖面 → 底部一档暗带（纯色，不用渐变）。
 * 返回糖面（描边内侧）多边形，花纹裁进它才不会压到描边。
 */
function 画糖体(绘图: 图形对象, 边: 边界, 圆头: number, 描边: number, 几何: 糖果块几何): 点[] {
  const { 样式, 透明度 } = 几何;
  const 外形 = 圆角多边形(边, 同角(圆头));
  绘图.fillStyle(样式.深色, 透明度);
  绘图.fillPoints(外形, true);

  const 内边 = 内缩边(边, 描边);
  const 内形 = 圆角多边形(内边, 同角(Math.max(0.5, 圆头 - 描边)));
  绘图.fillStyle(样式.主色, 透明度);
  绘图.fillPoints(内形, true);

  const 高 = 内边.下 - 内边.上;
  const 带高 = 高 * 0.16;
  const 暗带 = 裁进凸形(
    [
      { x: 内边.左, y: 内边.下 - 带高 },
      { x: 内边.右, y: 内边.下 - 带高 },
      { x: 内边.右, y: 内边.下 },
      { x: 内边.左, y: 内边.下 },
    ],
    内形,
  );
  if (暗带.length >= 3) {
    绘图.fillStyle(暗侧(样式), 0.4 * 透明度);
    绘图.fillPoints(暗带, true);
  }
  return 内形;
}

/** 糖面上的奶油螺旋：两道粗弧对开、从糖沿收进糖心，纯色，裁进糖面。 */
function 画螺旋(
  绘图: 图形对象,
  基: 糖头基,
  糖面: readonly 点[],
  几何: 糖果块几何,
  尺度: number,
): void {
  const { 样式, 透明度 } = 几何;
  const 短径 = 基.短半 * 2;
  // 一条真正的螺旋：半径从外缘 0.95 收到中心 0.1，同时绕 1.15 圈，
  // 带子宽度从外向内收细。两段弧那种画法在 25px 下会被读成「两个白钩子」，
  // 连续螺旋才能一眼看出是棒棒糖。
  const 圈 = Math.PI * 2 * 1.15;
  const 起角 = -1.9;
  const 厚起 = 短径 * 0.26 * 尺度;
  const 厚止 = 短径 * 0.11 * 尺度;
  绘图.fillStyle(样式.装饰, 透明度);
  const 带 = 裁进凸形(弧带(基, 0.95 * 尺度, 0.1 * 尺度, 厚起, 厚止, 起角, 起角 + 圈), 糖面);
  if (带.length >= 3) 绘图.fillPoints(带, true);
  // 螺旋收在糖心，留一颗主色小圆点当螺旋眼
  const 心眼 = Math.max(1, 基.短半 * 0.13 * 尺度);
  绘图.fillStyle(样式.主色, 透明度);
  绘图.fillCircle(基.心X, 基.心Y, 心眼);
}

/** 糖针：25px 格下密度太高（满盘会乱），格 < 30 不画；优先用高饱和点缀色轮换，深色细边从糖面里挑出来。 */
function 画糖针(绘图: 图形对象, 基: 糖头基, 糖面: readonly 点[], 几何: 糖果块几何): void {
  const { 格, 样式, 透明度 } = 几何;
  // 25px 只留两粒很小的点缀，糖头不至于空成一块白；格 ≥ 30 才铺满四粒。
  const 小数 = 格 < 30;
  const 直径 = 基.短半 * 2;
  const 长 = 直径 * 0.36;
  const 宽 = Math.max(1.8, 直径 * 0.13);
  const 色表 = 样式.点缀?.length ? 样式.点缀 : [样式.装饰, 样式.浅色, 样式.装饰深];
  const 位表: readonly (readonly [number, number, number])[] = [
    [-0.44, -0.24, -0.7],
    [-0.28, 0.28, -0.5],
    [0.4, 0.02, -0.56],
  ];
  const 数 = 小数 ? 2 : 位表.length;
  for (let 序 = 0; 序 < 数; 序 += 1) {
    const 位 = 位表[序];
    if (!位) continue;
    const 条 = 裁进凸形(糖针(基, 位[0] * 基.长半, 位[1] * 直径, 长, 宽, 位[2]), 糖面);
    if (条.length < 3) continue;
    绘图.lineStyle(Math.max(0.45, 格 * 0.022), 样式.深色, 0.45 * 透明度);
    绘图.strokePoints(条, true);
    绘图.fillStyle(色表[序 % 色表.length] ?? 样式.装饰, 透明度);
    绘图.fillPoints(条, true);
  }
}

/** 单格：没有朝向信息，收成一颗圆糖——糖头、螺旋、糖针，不要签子。 */
function 画圆糖(绘图: 图形对象, 几何: 糖果块几何, 描边: number): void {
  const { 格, 透明度 } = 几何;
  const 内缩 = Math.max(0.7, 格 * 0.04);
  const 边: 边界 = {
    左: 几何.左 + 内缩,
    上: 几何.上 + 内缩,
    右: 几何.左 + 格 - 内缩,
    下: 几何.上 + 格 - 内缩,
  };
  const 半径 = Math.min(边.右 - 边.左, 边.下 - 边.上) / 2;
  const 基 = 建基((边.左 + 边.右) / 2, (边.上 + 边.下) / 2, 半径, 半径, "横");

  绘图.fillStyle(0x1c0a08, 0.3 * 透明度);
  绘图.fillPoints(
    圆角多边形({ ...边, 上: 边.上 + 格 * 0.08, 下: 边.下 + 格 * 0.08 }, 同角(半径)),
    true,
  );

  const 糖面 = 画糖体(绘图, 边, 半径, 描边, 几何);
  画螺旋(绘图, 基, 糖面, 几何, 0.95);
  画糖针(绘图, 基, 糖面, 几何);
}

/** 签子：深色描边 + 米白棒身；圆角朝外，顶端藏进糖头里。 */
function 画签子(绘图: 图形对象, 边: 边界, 几何: 糖果块几何, 描边: number): void {
  const { 样式, 透明度 } = 几何;
  const 圆角 = Math.min(边.右 - 边.左, 边.下 - 边.上) / 2;
  绘图.fillStyle(样式.深色, 透明度);
  绘图.fillPoints(圆角多边形(边, 同角(圆角)), true);

  const 内边 = 内缩边(边, 描边);
  const 内圆角 = Math.max(0.4, Math.min(内边.右 - 内边.左, 内边.下 - 内边.上) / 2);
  绘图.fillStyle(样式.装饰, 透明度);
  绘图.fillPoints(圆角多边形(内边, 同角(内圆角)), true);
}

export function 绘制棒棒糖(绘图: 图形对象, 几何: 糖果块几何): void {
  const { 格, 透明度 } = 几何;
  const 描边 = Math.max(1.1, 格 * 0.075);

  if (几何.单格) {
    画圆糖(绘图, 几何, 描边);
    return;
  }

  // ① 格集 → 糖头长轴：格数最多的那条线就是糖头；另一侧的格是签子。
  // 格位取自 格外形 的包围盒相对列/行：真实调用方（糖果方块单元）传的是棋盘绝对格位，
  // 而 几何.行格数/列格数/有() 按相对下标统计，喂绝对格位会全为 0 —— 起/止 会算成
  // Infinity/-Infinity，进一步让 心X 变 NaN。这里自己按相对列/行重算，绝对/相对都成立。
  const 格列: 格位[] = 几何.格外形.map((项) => ({ 列: 项.列, 行: 项.行 }));
  if (格列.length === 0) return;
  const 行格数: number[] = [];
  for (let 行 = 0; 行 < 几何.行数; 行 += 1) {
    行格数.push(格列.filter((位) => 位.行 === 行).length);
  }
  const 列格数: number[] = [];
  for (let 列 = 0; 列 < 几何.列数; 列 += 1) {
    列格数.push(格列.filter((位) => 位.列 === 列).length);
  }
  const 最多行 = Math.max(...行格数);
  const 最多列 = Math.max(...列格数);
  const 轴: 头轴 = 最多行 >= 最多列 ? "横" : "竖";
  const 线 = 轴 === "横" ? 行格数.indexOf(最多行) : 列格数.indexOf(最多列);
  const 头格 = 格列.filter((位) => (轴 === "横" ? 位.行 === 线 : 位.列 === 线));
  const 签格 = 格列.filter((位) => (轴 === "横" ? 位.行 !== 线 : 位.列 !== 线));
  const 起 = Math.min(...头格.map((位) => (轴 === "横" ? 位.列 : 位.行)));
  const 止 = Math.max(...头格.map((位) => (轴 === "横" ? 位.列 : 位.行)));

  // ② 糖头：短轴比格略胖（上下各胀 0.03 格，约 1.06 格高），两端圆角取半高，读作圆片而非细长胶囊
  const 内缩 = Math.max(0.8, 格 * 0.035);
  // 糖头短轴给到 1.5 格：3 格宽 × 1.5 格高 = 2:1，25px 下才读成参考图那种「胖圆糖头」而不是一根粉条。
  // 上下各探出 0.25 格，仍在包围盒 0.35 格约束内；签子起点跟着头心走，会自动让位。
  const 膨 = 格 * 0.25;
  const 头边: 边界 =
    轴 === "横"
      ? {
          左: 几何.左 + 起 * 格 + 内缩,
          上: 几何.上 + 线 * 格 - 膨,
          右: 几何.左 + (止 + 1) * 格 - 内缩,
          下: 几何.上 + (线 + 1) * 格 + 膨,
        }
      : {
          左: 几何.左 + 线 * 格 - 膨,
          上: 几何.上 + 起 * 格 + 内缩,
          右: 几何.左 + (线 + 1) * 格 + 膨,
          下: 几何.上 + (止 + 1) * 格 - 内缩,
        };
  const 长半 = 轴 === "横" ? (头边.右 - 头边.左) / 2 : (头边.下 - 头边.上) / 2;
  const 短半 = 轴 === "横" ? (头边.下 - 头边.上) / 2 : (头边.右 - 头边.左) / 2;
  const 头心X = (头边.左 + 头边.右) / 2;
  const 头心Y = (头边.上 + 头边.下) / 2;
  const 基 = 建基(头心X, 头心Y, 长半, 短半, 轴);

  // ③ 签子边：从糖头中心往签子那侧量，末梢探出格底 0.08 格（不压到邻格）
  const 签宽 = Math.max(2.6, 格 * 0.36);
  const 探出 = 格 * 0.08;
  let 签边: 边界 | null = null;
  if (签格.length > 0) {
    if (轴 === "横") {
      const 行表 = 签格.map((位) => 位.行);
      const 列表 = 签格.map((位) => 位.列);
      const 签列 = (Math.min(...列表) + Math.max(...列表)) / 2;
      const 签心X = 几何.左 + (签列 + 0.5) * 格;
      const 下伸 = Math.max(...行表) > 线;
      签边 = {
        左: 签心X - 签宽 / 2,
        上: 下伸 ? 头心Y : 几何.上 + Math.min(...行表) * 格 - 探出,
        右: 签心X + 签宽 / 2,
        下: 下伸 ? 几何.上 + (Math.max(...行表) + 1) * 格 + 探出 : 头心Y,
      };
    } else {
      const 列表 = 签格.map((位) => 位.列);
      const 行表 = 签格.map((位) => 位.行);
      const 签心Y = 几何.上 + ((Math.min(...行表) + Math.max(...行表) + 1) / 2) * 格;
      const 右伸 = Math.max(...列表) > 线;
      签边 = {
        左: 右伸 ? 头心X : 几何.左 + Math.min(...列表) * 格 - 探出,
        上: 签心Y - 签宽 / 2,
        右: 右伸 ? 几何.左 + (Math.max(...列表) + 1) * 格 + 探出 : 头心X,
        下: 签心Y + 签宽 / 2,
      };
    }
  }

  // ④ 落影：糖头 + 签子一起压一层
  绘图.fillStyle(0x1c0a08, 0.3 * 透明度);
  if (签边) {
    绘图.fillPoints(
      圆角多边形(
        { ...签边, 上: 签边.上 + 格 * 0.09, 下: 签边.下 + 格 * 0.09 },
        同角(Math.min(签边.右 - 签边.左, 签边.下 - 签边.上) / 2),
      ),
      true,
    );
  }
  绘图.fillPoints(
    圆角多边形(
      { ...头边, 上: 头边.上 + 格 * 0.09, 下: 头边.下 + 格 * 0.09 },
      同角(Math.min(短半, 长半)),
    ),
    true,
  );

  // ⑤ 签子在糖头背后，先画；糖头盖住它的上端
  if (签边) 画签子(绘图, 签边, 几何, 描边);

  // ⑥ 糖头
  const 糖面 = 画糖体(绘图, 头边, Math.min(短半, 长半), 描边, 几何);
  画螺旋(绘图, 基, 糖面, 几何, 1);
  画糖针(绘图, 基, 糖面, 几何);
}

import type {
  界面资源样品,
  界面资源状态字段,
  界面资源绘制环境,
} from "../../../.gamemaker/依赖/框架/开发/界面资源协议";
import { 读取可选主题 } from "../../../.gamemaker/依赖/框架/设置/主题组合";
import { type 游戏设置, 默认设置 } from "../../../代码/设置/游戏设置";
import { 主题结果转设置, 解析游戏主题, 读取游戏主题目录, 默认主题编号 } from "../../主题/主题组合";

export const 主题组合目录 = 读取游戏主题目录();
export const 主题状态键 = "资源主题";
/** 每个主题都包含完整维度，预览先选主题；维度变体写在值里，可直接切单个维度。 */
export const 主题状态: 界面资源状态字段 = {
  键: 主题状态键,
  名称: "预览主题",
  默认: 默认主题编号,
  选项: 读取可选主题(主题组合目录).map((项) => 项.编号),
  主题选择: true,
};
/** 把预览选中的主题换算成隔离设置；不写存档，也不放宽所有权校验。 */
export function 读取预览主题设置(
  状态: Readonly<Record<string, string>>,
  设置: 游戏设置 = 默认设置,
): 游戏设置 {
  const 主题 = 状态[主题状态键];
  return 主题结果转设置(设置, 解析游戏主题(设置, 主题 || 默认主题编号));
}
/** 页面内再次改设置也必须如实报告，不能把最初声明冒充当前有效实现。 */
export function 读取预览主题解析(状态: Readonly<Record<string, string>>, 设置: 游戏设置) {
  const 声明 = 解析游戏主题(设置, 状态[主题状态键] || 默认主题编号);
  const 实际 = 解析游戏主题(设置);
  const 设置可表达 = 解析游戏主题(主题结果转设置(设置, 声明));
  return {
    主题: 声明.主题,
    选项: 声明.选项,
    槽位: 实际.槽位.map((项) => {
      const 原 = 声明.槽位.find((原) => 原.槽位.编号 === 项.槽位.编号);
      const 设置值 = 设置可表达.槽位.find((槽) => 槽.槽位.编号 === 项.槽位.编号);
      // 未进入旧设置字段的表现/资源仍用完整声明；页面内真正改过的设置保留实际值。
      return 原 && 设置值?.资源.编号 === 项.资源.编号 ? 原 : 项;
    }),
  };
}

/** 为旧独立样品补齐正式主题上下文，绘制仍调用原配方。 */
export function 接入资源主题(样品: 界面资源样品, 槽位: readonly string[]): 界面资源样品 {
  let 读取: typeof import("../../主题/配色/主题读取");
  function 在主题内(环境: 界面资源绘制环境, 绘制: (环境: 界面资源绘制环境) => boolean) {
    const 设置 = 读取预览主题设置(环境.状态);
    const 状态 = { ...环境.状态 };
    if (样品.编号 === "game-background") {
      状态.主题 = 设置.主题选择;
      状态.动态 = 设置.背景动态 ? "是" : "否";
    }
    if (样品.编号 === "block-shape") 状态.外观 = 设置.主题选择;
    读取.设置预览主题读取(
      () => 设置,
      () => 读取预览主题解析(状态, 设置),
    );
    try {
      return 绘制({ ...环境, 状态 });
    } finally {
      读取.设置预览主题读取();
    }
  }
  const 主题管理字段 =
    样品.编号 === "game-background"
      ? ["主题", "动态"]
      : 样品.编号 === "block-shape"
        ? ["外观"]
        : [];
  return {
    ...样品,
    主题槽位: 槽位,
    状态: [主题状态, ...样品.状态.filter((字段) => !主题管理字段.includes(字段.键))],
    async 准备资源() {
      const 资源 = await 样品.准备资源?.();
      读取 = await import("../../主题/配色/主题读取");
      return 资源;
    },
    绘制(环境) {
      在主题内(环境, (值) => {
        样品.绘制(值);
        return false;
      });
    },
    绘制帧: 样品.绘制帧
      ? (环境, 时间) => 在主题内(环境, (值) => 样品.绘制帧?.(值, 时间) ?? false) === true
      : undefined,
  };
}

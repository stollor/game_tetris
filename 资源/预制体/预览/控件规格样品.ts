export function 创建仪表预览输入(
  状态: Readonly<Record<string, string>>,
  时间秒 = 0,
): import("../对局/对局仪表").对局仪表输入 {
  const 配置 = 样品布局.仪表;
  const 模式 = 状态.模式 === "冲刺" || 状态.模式 === "极限" ? 状态.模式 : "马拉松";
  const 主题 = 主题组合.解析游戏主题(读取预览主题设置(状态), 状态[主题状态键]);
  const 值 = (槽位: string) => 主题.槽位.find((项) => 项.槽位.编号 === 槽位)?.资源.值;
  const 反馈 = new 计分反馈.计分反馈();
  反馈.重置(配置.初始分数);
  if (状态.演示 === "计分反馈") {
    const 秒 = 时间秒 % 配置.动画周期秒;
    反馈.加分(配置.加分后分数, 配置.起点, true);
    反馈.更新(Math.min(秒, 配置.击中秒));
    if (秒 > 配置.击中秒) 反馈.更新(秒 - 配置.击中秒);
  }
  return {
    布局: 对局布局.计算对局布局(配置.画布宽, 配置.布局高, { 模式, 阶段: "进行中" }),
    模式,
    等级: 配置.等级,
    行数: 配置.行数,
    计分: 反馈.读取(),
    剩余毫秒: 配置.剩余毫秒,
    有效毫秒: 配置.有效毫秒,
    省电: false,
    表现: 值("仪表表现") === "像素" ? "像素" : 值("仪表表现") === "条带" ? "条带" : "装置",
    纹样: 值("仪表纹样") === "平涂" ? "平涂" : "灯条",
  };
}


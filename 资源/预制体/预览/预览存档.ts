import type { 存储接口 } from "../../../.gamemaker/依赖/框架/存档";
import { 收藏存档键 } from "../../../代码/存档/收藏";

/**
 * 预览专属存档：键加前缀，读写都落在预览档，不污染玩家真存档。
 *
 * GM 看板预览以前用只读固定档，导致「解锁全部主题」不保存、设置里切换主题永远
 * 因「未拥有」跳商店、商店与设置的主题不一致。改成可写预览档后，这些操作在预览里
 * 和正式游戏一致（刷新页面也保留），又不会改到 `再消一行:收藏` 真档。
 */
const 预览收藏前缀 = "再消一行:预览:";

/** 预览起始金币：比正式初始值宽裕，方便直接试购买/整套流程。 */
export const 预览初始金币 = 680;

/** 第一次打开预览时的起始档：金币够买主题，已购留空以便看「未拥有」态。 */
const 预览初始存档 = JSON.stringify({
  版本: 2,
  数据: {
    金币: 预览初始金币,
    累计获得: 预览初始金币,
    已购: [],
    已结算: [],
    已领成就: [],
    最近首局日期: "",
  },
});

export function 创建预览存储(): 存储接口 {
  const 加前缀 = (键: string) => 预览收藏前缀 + 键;
  return {
    getItem: (键) => {
      const 已有 = localStorage.getItem(加前缀(键));
      if (已有 !== null) return 已有;
      if (键 !== 收藏存档键) return null;
      localStorage.setItem(加前缀(键), 预览初始存档);
      return 预览初始存档;
    },
    setItem: (键, 值) => localStorage.setItem(加前缀(键), 值),
  };
}

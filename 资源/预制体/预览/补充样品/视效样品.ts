/** 样品衬底：只提供对比度，不参与被预览导出的视觉。 */
function 铺衬底(环境: 界面资源绘制环境, 宽: number, 高: number, 色 = 衬底色): void {
  环境.画笔.图形.fillStyle(色, 1).fillRect(0, 0, 宽, 高);
}

/** 像素特效按 10×20 棋盘定位，浅格线只用来核对特效落位。 */
function 铺格线衬底(环境: 界面资源绘制环境, 宽: number, 高: number): void {
  const 图 = 环境.画笔.图形;
  图.fillStyle(衬底色, 1).fillRect(0, 0, 宽, 高);
  for (let x = 0; x < 宽; x += 像素格) 图.fillStyle(0x1a2448, 0.45).fillRect(x, 0, 1, 高);
  for (let y = 0; y < 高; y += 像素格) 图.fillStyle(0x1a2448, 0.45).fillRect(0, y, 宽, 1);
}

/** 对局特效按正式 390×844 布局落位：衬底用同一份棋盘几何，特效才不会偏到画面外。 */
function 铺对局棋盘衬底(环境: 界面资源绘制环境): void {
  const 图 = 环境.画笔.图形;
  const { 左, 上, 格, 列, 行 } = 操作布局模块.布局.棋盘;
  图.fillStyle(衬底色, 1).fillRect(0, 0, 390, 844);
  for (let 行号 = 0; 行号 < 行; 行号 += 1)
    for (let 列号 = 0; 列号 < 列; 列号 += 1)
      图.fillStyle(0x1a2448, 0.85).fillRect(左 + 列号 * 格 + 1, 上 + 行号 * 格 + 1, 格 - 2, 格 - 2);
}


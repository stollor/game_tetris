/**
 * 预览主题只能临时注入：用状态里的主题编号换一份隔离设置，画完立刻还原，
 * 这样同一份卡片可以切主题，也不会把主题泄漏到其它样品。
 */
function 在预览主题内<T>(状态: Readonly<Record<string, string>>, 绘制: () => T): T {
  const 设置 = 读取预览主题设置(状态, {
    ...设置模块.默认设置,
    显示网格: true,
  });
  主题读取.设置预览主题读取(
    () => 设置,
    () => 主题组合.解析游戏主题(设置, 状态.资源主题),
  );
  try {
    return 绘制();
  } finally {
    主题读取.设置预览主题读取();
  }
}

function 铺底色(画笔: 画笔, 宽: number, 高: number): void {
  const 色 = 解析颜色数值(主题读取.界面主题().页面.背景);
  画笔.图形.fillStyle(色, 1).fillRect(0, 0, 宽, 高);
}

/** 卡片类样品用主面板色承托，避免深色底上只剩一片同色。 */
function 铺面板底(画笔: 画笔, 宽: number, 高: number): void {
  const 色 = 解析颜色数值(主题读取.界面主题().面板.主面板.背景);
  画笔.图形.fillStyle(色, 1).fillRect(0, 0, 宽, 高);
}

function 铺立体底(画笔: 画笔, 宽: number, 高: number): void {
  画笔.图形.fillStyle(立体规范模块.立体规范.界面.壳, 1).fillRect(0, 0, 宽, 高);
}

function 读取模式(值: string | undefined): 游戏模式 {
  return 模式选项.find((项) => 项 === 值) ?? "马拉松";
}

function 读取方块外观(值: string | undefined) {
  const 名称 = 方块外观选项.find((项) => 项 === 值) ?? "极光原野";
  return 方块外观表.解析方块外观(名称);
}

function 创建模式布局(模式: 游戏模式, 视口高 = 844): 对局布局数据 {
  return 布局模块.计算对局布局(局部视口宽, 视口高, {
    屏幕适配: "手机竖屏",
    模式,
    阶段: "进行中",
  });
}

function 创建计分视图(显示分数: number, 击中 = 0, 流光: 计分反馈视图["流光"] = []): 计分反馈视图 {
  return { 显示分数, 目标分数: 显示分数, 击中, 流光 };
}

function 创建仪表输入(
  布局: 对局布局数据,
  模式: 游戏模式,
  覆盖: Partial<对局仪表输入> = {},
): 对局仪表输入 {
  return {
    布局,
    模式,
    等级: 7,
    行数: 32,
    计分: 创建计分视图(12340),
    剩余毫秒: 92000,
    有效毫秒: 312000,
    省电: false,
    ...覆盖,
  };
}

/** 信息栏贴在对局顶栏下方；局部样品把它平移到画面上方一行。 */
function 平移信息栏(画笔: 画笔, 布局: 对局布局数据, 上边距: number): void {
  画笔.图形.translateCanvas(0, 上边距 - (布局.信息栏.中心Y - 布局.信息栏.高 / 2));
}


/** 结算面板几何：中心/顶部/尺寸/视口比例（与 Phaser 版 霓虹结算几何 同形）。 */
export interface 霓虹结算几何 {
  中心X: number;
  顶: number;
  宽: number;
  高: number;
  比例: number;
}

/** 结算面板纯布局：比例、面板矩形、文字位置与两个按钮矩形。 */
export interface 霓虹结算布局 {
  几何: 霓虹结算几何;
  左: number;
  列宽: number;
  徽标: { 中心X: number; 上: number };
  分数: { 中心X: number; 上: number };
  统计标签Y: number;
  统计数值Y: number;
  金币行Y: number;
  金币区: { 左: number; 上: number; 宽: number; 高: number };
  奖励Y: number;
  提示区: { 左: number; 上: number; 宽: number; 高: number };
  重开: { 中心X: number; 中心Y: number; 宽: number; 高: number };
  菜单: { 中心X: number; 中心Y: number; 宽: number; 高: number };
}

/** 方块结算台：统计、飘字与操作各占独立区域，飘字全程不会覆盖按钮。 */
export function 计算霓虹结算布局(屏宽: number, 屏高: number): 霓虹结算布局 {
  const 比例 = Math.min(1, (屏宽 - 32) / 358, (屏高 - 48) / 600);
  const 中心X = 屏宽 / 2;
  const 顶 = (屏高 - 600 * 比例) / 2;
  const 面板宽 = 358 * 比例;
  const 左 = 中心X - 面板宽 / 2;
  return {
    几何: { 中心X, 顶, 宽: 面板宽, 高: 600 * 比例, 比例 },
    左,
    列宽: (面板宽 - 36 * 比例) / 3,
    徽标: { 中心X, 上: 顶 + 32 * 比例 },
    分数: { 中心X, 上: 顶 + 208 * 比例 },
    统计标签Y: 顶 + 285 * 比例,
    统计数值Y: 顶 + 316 * 比例,
    金币行Y: 顶 + 374 * 比例,
    金币区: { 左: 左 + 24 * 比例, 上: 顶 + 350 * 比例, 宽: 面板宽 - 48 * 比例, 高: 48 * 比例 },
    奖励Y: 顶 + 430 * 比例,
    提示区: { 左: 左 + 18 * 比例, 上: 顶 + 402 * 比例, 宽: 面板宽 - 36 * 比例, 高: 64 * 比例 },
    重开: {
      中心X,
      中心Y: 顶 + 502 * 比例,
      宽: 面板宽 - 48 * 比例,
      高: 52 * 比例,
    },
    菜单: {
      中心X,
      中心Y: 顶 + 560 * 比例,
      宽: 面板宽 - 48 * 比例,
      高: 40 * 比例,
    },
  };
}

/** 结算遮罩：整屏压暗（Phaser 结算面板 遮罩图形 的同算法）。 */
export function 绘制结算遮罩(绘图: 图形对象, 屏宽: number, 屏高: number): void {
  const 调色板 = 读取霓虹调色板();
  绘图.fillStyle(调色板.遮罩, 0.82).fillRect(0, 0, 屏宽, 屏高);
}

/** 结算底板与阶梯角饰；方块、统计模块和动画由结算演出配方装配。 */
export function 绘制结算面板(绘图: 图形对象, 布局: 霓虹结算布局): void {
  if (是像素风格()) {
    绘制像素面板(
      绘图,
      布局.左,
      布局.几何.顶,
      布局.几何.宽,
      布局.几何.高,
      像素规范.色.纸,
      像素规范.色.紫,
    );
    return;
  }
  const 调色板 = 读取霓虹调色板();
  const { 几何, 左 } = 布局;
  const { 顶, 宽: 面板宽, 高: 面板高, 比例 } = 几何;
  绘制霓虹玻璃(绘图, 左, 顶, 面板宽, 面板高, {
    圆角: 16,
    透明度: 0.96,
    边色: 调色板.面板描边,
    边透明度: 0.45,
    强调色: 调色板.强调,
    高光: true,
  });
  for (const 方向 of [-1, 1]) {
    const x = 方向 < 0 ? 左 + 10 * 比例 : 左 + 面板宽 - 30 * 比例;
    绘图
      .fillStyle(调色板.强调, 0.7)
      .fillRect(x, 顶 - 3 * 比例, 20 * 比例, 5 * 比例)
      .fillRect(x + (方向 < 0 ? -13 : 20) * 比例, 顶 + 9 * 比例, 13 * 比例, 5 * 比例);
  }
}


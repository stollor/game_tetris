/** 结算页文字角色。 */
export type 结算文字角色 = "徽标" | "标题" | "分数" | "统计标签" | "统计数值" | "奖励" | "金币";

/** 结算文字样式（字号为 Phaser 布局后最终值，已含 比例=1 的基准）。 */
export function 读取结算文字样式(角色: 结算文字角色, 覆盖?: Partial<文字样式>): 文字样式 {
  const 字体 = 游戏外观.字体.家族;
  const 主题 = 界面主题();
  const 调色板 = 读取霓虹调色板();
  const 正文 = 颜色值(主题.面板.主面板.正文文字);
  let 基础: 文字样式;
  switch (角色) {
    case "徽标":
      基础 = { 字体, 字号: 12, 字重: "粗体", 颜色: 调色板.强调 };
      break;
    case "标题":
      基础 = {
        字体,
        字号: 28,
        字重: "粗体",
        颜色: 正文,
      };
      break;
    case "分数":
      基础 = { 字体, 字号: 38, 字重: "粗体", 颜色: 调色板.强调 };
      break;
    case "统计标签":
      基础 = { 字体, 字号: 11, 颜色: 颜色值(主题.文字.次要) };
      break;
    case "统计数值":
      基础 = { 字体, 字号: 18, 字重: "粗体", 颜色: 正文 };
      break;
    case "奖励":
      基础 = { 字体, 字号: 12, 颜色: 调色板.强调 };
      break;
    case "金币":
      基础 = { 字体, 字号: 20, 字重: "粗体", 颜色: 0xffe7a8 };
      break;
  }
  return 覆盖 ? { ...基础, ...覆盖 } : 基础;
}

/** 结算按钮视觉：重开=主要配色（可用）/禁用配色，菜单=次要配色（框架 界面按钮 口径）。 */
export function 读取结算按钮视觉(种类: "重开" | "重开禁用" | "菜单", 样式?: string): 对局按钮视觉 {
  const 主题 = 界面主题(霓虹界面主题.find((项) => 项 === 样式));
  const 按钮 = 主题.按钮;
  if (种类 === "重开")
    return {
      填色: 颜色值(按钮.主要.默认.描边),
      边框色: 颜色值(按钮.主要.默认.描边),
      文字色: 颜色值(按钮.主要.默认.文字),
      透明度: 0.98,
      边透明度: 0.55,
      字号: 游戏外观.字体.按钮,
    };
  if (种类 === "重开禁用")
    return {
      填色: 颜色值(按钮.主要.禁用.背景),
      边框色: 颜色值(按钮.主要.禁用.描边),
      文字色: 颜色值(按钮.主要.禁用.文字),
      透明度: 0.92,
      边透明度: 0.55,
      字号: 游戏外观.字体.按钮,
    };
  return {
    填色: 颜色值(按钮.次要.默认.背景),
    边框色: 颜色值(按钮.次要.默认.描边),
    文字色: 颜色值(按钮.次要.默认.文字),
    透明度: 0.92,
    边透明度: 0.55,
    字号: 游戏外观.字体.辅助 + 2,
  };
}

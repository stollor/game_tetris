/** 标题区三行文字：主标题（风景标题 token，28 粗体描边）、副题、消息（金色 13px）。 */
export function 生成商店标题文字项(
  宽: number,
  标题: string,
  副题: string,
  消息: string,
  标题Y: number,
  副题Y: number,
  消息Y: number,
): 文字项[] {
  const 外观 = 解析商店外观();
  // 糖果的标题与消息压在粉白条纹篷/巧克力底上，靠描边保证两种底都能读。
  const 深描边 = { 颜色: 商店色串(糖果规范.色.巧克力深), 粗细: 4 };
  const 消息描边 =
    外观.风格 === "霓虹"
      ? { 颜色: "#16303a", 粗细: 3 }
      : 外观.风格 === "糖果"
        ? { 颜色: 深描边.颜色, 粗细: 3 }
        : undefined;
  const 项: 文字项[] = [
    {
      文案: 标题,
      样式: {
        ...读取霓虹文字样式("风景标题"),
        字体: 外观.字体,
        颜色: 外观.文字.标题,
        ...(外观.风格 === "糖果" ? { 描边: 深描边 } : {}),
      },
      锚点: "中上",
      x: 宽 / 2,
      y: 标题Y,
    },
    {
      文案: 副题,
      样式: {
        ...读取霓虹文字样式("风景说明"),
        字体: 外观.字体,
        颜色: 外观.文字.副题,
      },
      锚点: "中上",
      x: 宽 / 2,
      y: 副题Y,
    },
  ];
  if (消息)
    项.push({
      文案: 消息,
      样式: {
        字体: 外观.字体,
        字号: 13,
        颜色: 外观.文字.消息,
        ...(消息描边 ? { 描边: 消息描边 } : {}),
      },
      锚点: "中上",
      x: 宽 / 2,
      y: 消息Y,
    });
  return 项;
}

/** 商店墨迹位置的小幅修正；字号和字体由各角色的文字配方统一提供。 */
export const 商店文字补偿 = {
  部位名称: { x: 0, y: -2 },
  目录名称: { x: 0, y: -1 },
  金币: { x: 2, y: 0 },
} as const;

export function 应用商店文字补偿(项: 文字项, 角色: keyof typeof 商店文字补偿): 文字项 {
  const 差 = 商店文字补偿[角色];
  return { ...项, x: 项.x + 差.x, y: 项.y + 差.y };
}

/** 按钮使用合法的中文字体与实际设计字号，按底色选择文字对比色。 */

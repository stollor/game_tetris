/**
 * DPR1 时一条 1~2px 的居中描边会被抗锯齿摊到路径两侧各 `线宽/2` 覆盖率的相邻两行；
 * 硬边实色无法复刻这种覆盖率。
 * 办法：DPR1 用「外扩 0.5 的 1px 描边 + 内缩 0.5 的 1px 描边」各带 `线宽/2` 透明度；
 * DPR≥2 时逻辑像素正落设备像素，直接用原生描边。
 * 与 `资源/预制体/基础/面板/覆盖页面板.ts` 的 1px 落地同一思路，这里补圆角矩形版本。
 */
export interface 商店描边方式 {
  圆角(绘图: 图形对象, 区: 矩形, 圆角: number, 线宽: number, 颜色: number, 透明度: number): void;
}

/** 原生描边：按给定线宽整圈描边，行为与重构前一致。 */
export const 商店原生描边: 商店描边方式 = {
  圆角(绘图, 区, 圆角, 线宽, 颜色, 透明度) {
    绘图.lineStyle(线宽, 颜色, 透明度).strokeRoundedRect(区.左, 区.上, 区.宽, 区.高, 圆角);
  },
};

/** 按钮描边：不透明按钮底板上描边整圈可见，强度按名义值的 0.45 落地。 */
export const 商店按钮描边: 商店描边方式 = {
  圆角(绘图, 区, 圆角, 线宽, 颜色, 透明度) {
    绘图
      .lineStyle(线宽, 颜色, 透明度 * 0.45)
      .strokeRoundedRect(区.左, 区.上, 区.宽, 区.高, Math.max(1, 圆角));
  },
};

/** 像素对齐描边：只画四段 90° 角弧，复刻旧画布圆角描边的落点。 */
export const 商店像素对齐描边: 商店描边方式 = {
  圆角(绘图, 区, 圆角, 线宽, 颜色, 透明度) {
    // 旧画布的圆角描边实测：直边几乎不落色
    // （未选中牌白边 0.16 直边不可见、选中牌金边直边只有约 4 成强度），只有四角弧最亮；
    // 硬边整圈描边会让每条直边多出一整条实色线。只画四段 90° 角弧实测最接近。
    const 半径 = Math.max(0, Math.min(圆角, 区.宽 / 2, 区.高 / 2));
    if (半径 <= 0) {
      绘图.lineStyle(线宽, 颜色, 透明度).strokeRect(区.左, 区.上, 区.宽, 区.高);
      return;
    }
    绘图.lineStyle(线宽, 颜色, 透明度);
    const 半圆 = Math.PI / 2;
    const 四角: readonly (readonly [number, number, number, number])[] = [
      [区.左 + 半径, 区.上 + 半径, Math.PI, Math.PI * 1.5],
      [区.左 + 区.宽 - 半径, 区.上 + 半径, Math.PI * 1.5, Math.PI * 2],
      [区.左 + 区.宽 - 半径, 区.上 + 区.高 - 半径, 0, 半圆],
      [区.左 + 半径, 区.上 + 区.高 - 半径, 半圆, Math.PI],
    ];
    for (const [圆心X, 圆心Y, 起始, 结束] of 四角) {
      绘图.beginPath();
      绘图.arc(圆心X, 圆心Y, 半径, 起始, 结束, false);
      绘图.strokePath();
    }
  },
};


/** 标题区三行文字：主标题（风景标题 token，28 粗体描边）、副题、消息（金色 13px）。 */
export function 生成商店标题文字项(
  宽: number,
  标题: string,
  副题: string,
  消息: string,
  标题Y: number,
  副题Y: number,
  消息Y: number,
): 文字项[] {
  const 外观 = 解析商店外观();
  const 消息描边 = 外观.风格 === "霓虹" ? { 颜色: "#16303a", 粗细: 3 } : undefined;
  const 项: 文字项[] = [
    {
      文案: 标题,
      样式: {
        ...读取霓虹文字样式("风景标题"),
        字体: 外观.字体,
        颜色: 外观.文字.标题,
      },
      锚点: "中上",
      x: 宽 / 2,
      y: 标题Y,
    },
    {
      文案: 副题,
      样式: {
        ...读取霓虹文字样式("风景说明"),
        字体: 外观.字体,
        颜色: 外观.文字.副题,
      },
      锚点: "中上",
      x: 宽 / 2,
      y: 副题Y,
    },
  ];
  if (消息)
    项.push({
      文案: 消息,
      样式: {
        字体: 外观.字体,
        字号: 13,
        颜色: 外观.文字.消息,
        ...(消息描边 ? { 描边: 消息描边 } : {}),
      },
      锚点: "中上",
      x: 宽 / 2,
      y: 消息Y,
    });
  return 项;
}

/** 商店墨迹位置的小幅修正；字号和字体由各角色的文字配方统一提供。 */
export const 商店文字补偿 = {
  部位名称: { x: 0, y: -2 },
  部位价格: { x: 0, y: 0 },
  目录名称: { x: 0, y: -1 },
  金币: { x: 2, y: 0 },
} as const;

export function 应用商店文字补偿(项: 文字项, 角色: keyof typeof 商店文字补偿): 文字项 {
  const 差 = 商店文字补偿[角色];
  return 差.x === 0 && 差.y === 0 ? 项 : { ...项, x: 项.x + 差.x, y: 项.y + 差.y };
}

/** 按钮使用合法的中文字体与实际设计字号，按底色选择文字对比色。 */
export function 生成商店按钮文字项(
  中心X: number,
  中心Y: number,
  文案: string,
  数据: 收藏按钮数据,
  字号 = 16,
): 文字项 {
  const 外观 = 解析商店外观();
  const 配色 = 读取收藏按钮配色(数据);
  return {
    文案,
    样式: {
      字体: 外观.字体,
      字号,
      颜色: 配色.文字色,
      字重: "粗体",
    },
    锚点: "中中",
    x: 中心X,
    y: 中心Y,
  };
}


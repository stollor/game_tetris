/**
 * 商店视觉配方：纸页、按钮底板、商店目录、部位卡与部位图标。
 * 只输出绘制指令与文字项，不读存档、设置或语言；主题外观与文案由调用方给出。
 *
 * 四套材质语言：霓虹=玻璃坞区+收藏纸页，像素=实边液晶井，立体=斜切金属机架，
 * 糖果=深巧克力坞区 + 草莓粉目录卡 + 奶油纸页（面板/按钮走 `基础/面板|按钮` 的糖纸原语）。
 * 语义色全部来自 `商店外观`，本文件不再留字面色。
 */

export interface 商店主题外观 {
  名称: string;
  主色: number;
  强调: number;
  方块: readonly number[];
}

export interface 收藏按钮数据 {
  金色?: boolean;
  纸面?: boolean;
  /** 糖纸扭结朝向；并排的购买按钮各留外端，接缝侧留空。缺省两端。 */
  糖纸侧?: 糖纸侧;
}

export interface 收藏按钮状态 {
  已选?: boolean;
  悬停?: boolean;
  按下?: boolean;
  可用?: boolean;
}

type 按钮角色 = "主" | "次" | "淡";

function 按钮角色(数据: 收藏按钮数据): 按钮角色 {
  if (数据.金色) return "主";
  if (数据.纸面) return "淡";
  return "次";
}

/** 收藏纸页：霓虹是投影纸页，像素是实边液晶井，立体是凹陷机架窗，糖果是奶油交易纸页。 */
export function 绘制收藏纸页(绘图: 图形对象, x: number, y: number, 宽: number, 高: number): void {
  const 外观 = 解析商店外观();
  if (外观.风格 === "像素") {
    绘制像素面板(绘图, x, y, 宽, 高, 外观.纸页.填充, 外观.纸页.填充, false, 外观.纸页.描边);
    return;
  }
  if (外观.风格 === "立体") {
    绘制金属板(绘图, x, y, 宽, 高, { 切: 外观.圆角.纸页, 凹: true, 描边宽: 2 });
    return;
  }
  if (外观.风格 === "糖果") {
    // 奶油纸页：巧克力外沿 + 金色裱花内衬 + 顶部扇贝花边，读作一张糖铺小票。
    绘制糖果纸页(绘图, x, y, 宽, 高, {
      圆角: 外观.圆角.纸页,
      填色: 外观.纸页.填充,
      边色: 外观.纸页.内描边,
      底边色: 外观.纸页.描边,
    });
    return;
  }
  绘图.fillStyle(0x030d13, 0.26).fillRoundedRect(x + 3, y + 8, 宽, 高, 14);
  绘图.fillStyle(外观.纸页.填充).fillRoundedRect(x, y, 宽, 高, 外观.圆角.纸页);
  绘图.lineStyle(1, 外观.纸页.内描边, 0.6).strokeRoundedRect(x + 5, y + 5, 宽 - 10, 高 - 10, 8);
}

/** 收藏按钮的文字色方案：金底/纸底用深字，墨底用正文色；像素与立体按各自规范给字色。 */
export function 读取收藏按钮配色(数据: 收藏按钮数据): {
  面板色: string;
  强调色: string;
  文字色: string;
  字重: "粗体" | "常规";
} {
  const 外观 = 解析商店外观();
  const 配色 = 外观.按钮[按钮角色(数据)];
  return {
    面板色: 商店色串(配色.填充),
    强调色: 商店色串(配色.描边),
    文字色: 配色.文字,
    字重: 数据.金色 ? "粗体" : "常规",
  };
}

/** 按钮底板（中心定位）：纸页与商店共用的手作风。 */
export function 绘制收藏按钮底板(
  绘图: 图形对象,
  中心X: number,
  中心Y: number,
  宽: number,
  高: number,
  数据: 收藏按钮数据,
  状态: 收藏按钮状态 = {},
  描边: 商店描边方式 = 商店原生描边,
): void {
  const 外观 = 解析商店外观();
  const 配色 = 外观.按钮[按钮角色(数据)];
  const 可用 = 状态.可用 !== false;
  if (外观.风格 === "像素") {
    绘制像素面板(
      绘图,
      中心X - 宽 / 2,
      中心Y - 高 / 2,
      宽,
      高,
      状态.已选 ? 外观.卡片.点亮 : 配色.填充,
      配色.填充,
      状态.按下,
      状态.已选 ? 外观.卡片.点亮 : 配色.描边,
    );
    return;
  }
  if (外观.风格 === "立体") {
    // 「金色」（整套）只点亮灯边，不能当成按下：金属板的按下会整体下沉一个厚度，
    // 两颗按钮同高同顶时会看起来一高一低。
    绘制金属板(绘图, 中心X - 宽 / 2, 中心Y - 高 / 2, 宽, 高, {
      切: 外观.圆角.按钮,
      按下: 状态.按下 === true,
      强调: 数据.金色 === true || 状态.已选 === true || 状态.悬停 === true,
      透明度: 可用 ? 1 : 外观.按钮.禁用透明度,
      描边宽: 1.6,
    });
    return;
  }
  if (外观.风格 === "糖果") {
    const 强调 = 数据.金色 === true || 状态.已选 === true || 状态.悬停 === true;
    // 方键（交易纸页的关闭 ×）走马卡龙圆盘，其余是糖纸胶囊；扭结只出现在够宽的按钮上。
    if (Math.abs(宽 - 高) <= 2) {
      绘制糖果圆键(绘图, 中心X, 中心Y, Math.min(宽, 高) / 2, 配色.填充, {
        悬停: 状态.悬停 === true,
        按下: 状态.按下 === true,
        选中: 状态.已选 === true,
      });
      return;
    }
    绘制糖果按钮(绘图, 中心X, 中心Y, 宽, 高, {
      填色: 配色.填充,
      边框色: 配色.描边,
      强调色: 强调 ? 糖果规范.色.金 : 配色.描边,
      悬停: 状态.悬停 === true,
      按下: 状态.按下 === true,
      选中: 状态.已选 === true,
      透明度: 可用 ? 1 : 外观.按钮.禁用透明度,
      圆角: 外观.圆角.按钮,
      糖纸: 宽 > 44,
      糖纸侧: 数据.糖纸侧,
    });
    return;
  }
  const x = 中心X - 宽 / 2;
  const y = 中心Y - 高 / 2;
  绘图.fillStyle(0x041218, 0.3).fillRoundedRect(x, y + 3, 宽, 高, 7);
  绘图
    .fillStyle(配色.填充, 可用 ? 1 : 外观.按钮.禁用透明度)
    .fillRoundedRect(x, y, 宽, 高, 外观.圆角.按钮);
  描边.圆角(
    绘图,
    { 左: x, 上: y, 宽, 高 },
    外观.圆角.按钮,
    状态.已选 ? 2 : 1,
    状态.已选 ? 0xffe6a2 : 配色.描边,
    可用 ? 0.9 : 0.35,
  );
  绘图.lineStyle(1, 0xfff5cc, 状态.按下 ? 0.06 : 0.22).lineBetween(x + 8, y + 2, x + 宽 - 8, y + 2);
  if (状态.悬停) 绘图.fillStyle(0xfff8d6, 0.06).fillRoundedRect(x + 2, y + 2, 宽 - 4, 高 - 4, 6);
}

/** 收藏按钮文字项：颜色跟随底色，字号沿用常规按钮默认（16px）。 */
export function 生成收藏按钮文字项(
  中心X: number,
  中心Y: number,
  文案: string,
  数据: 收藏按钮数据,
  字号 = 16,
): 文字项 {
  const 配色 = 读取收藏按钮配色(数据);
  return {
    文案,
    样式: 派生霓虹文字样式("按钮", {
      字号,
      字重: 配色.字重,
      颜色: 配色.文字色,
    }),
    锚点: "中中",
    x: 中心X,
    y: 中心Y,
  };
}

/** 商店部位卡：卡片底色 + 主题描边，预览中时点亮强调（已拥有由蒙层与对勾另画）。 */
export function 绘制商店部位底板(
  绘图: 图形对象,
  区: 矩形,
  预览中: boolean,
  悬停 = false,
  描边: 商店描边方式 = 商店原生描边,
): void {
  const 外观 = 解析商店外观();
  if (外观.风格 === "像素") {
    绘制像素面板(
      绘图,
      区.左,
      区.上,
      区.宽,
      区.高,
      外观.卡片.填充,
      预览中 || 悬停 ? 外观.卡片.点亮 : 外观.卡片.填充,
      false,
      预览中 ? 外观.卡片.点亮 : 外观.卡片.描边,
    );
    return;
  }
  if (外观.风格 === "立体") {
    绘制金属板(绘图, 区.左, 区.上, 区.宽, 区.高, {
      切: 外观.圆角.卡片,
      强调: 预览中 || 悬停,
      描边宽: 预览中 ? 2.6 : 悬停 ? 2 : 1.4,
    });
    return;
  }
  if (外观.风格 === "糖果") {
    // 部位卡 = 巧克力浅糖块：深巧克力外沿 + 草莓裱花，预览中/悬停换成金色裱花。
    const 亮 = 预览中 || 悬停;
    绘制糖果面板(绘图, 区.左, 区.上, 区.宽, 区.高, {
      圆角: 外观.圆角.卡片,
      填色: 外观.卡片.填充,
      边色: 亮 ? 外观.卡片.点亮 : 外观.卡片.描边,
      底边色: 糖果规范.色.巧克力深,
      铆钉: false,
    });
    if (亮)
      绘图
        .lineStyle(2, 外观.卡片.点亮, 0.95)
        .strokeRoundedRect(区.左 + 1, 区.上 + 1, 区.宽 - 2, 区.高 - 2, 外观.圆角.卡片);
    return;
  }
  绘图
    .fillStyle(外观.卡片.填充, 悬停 || 预览中 ? 0.96 : 外观.卡片.透明度)
    .fillRoundedRect(区.左, 区.上, 区.宽, 区.高, 外观.圆角.卡片);
  描边.圆角(
    绘图,
    区,
    外观.圆角.卡片,
    1.5,
    预览中 ? 外观.卡片.点亮 : 外观.卡片.描边,
    预览中 ? 0.95 : 外观.卡片.暗描边透明度,
  );
}

/**
 * 已拥有部位卡：整卡压一层中性蒙层，底板与左侧预览一起退到背景；
 * 名字与对勾由调用方画在蒙层之上，状态仍然读得出来。
 */
export function 绘制商店部位已拥有蒙层(绘图: 图形对象, 区: 矩形): void {
  const 外观 = 解析商店外观();
  const 色 = 外观.卡片.已拥有蒙层;
  const 透明度 = 外观.卡片.已拥有蒙层透明度;
  if (外观.风格 === "像素") {
    绘图.fillStyle(色, 透明度).fillRect(区.左, 区.上, 区.宽, 区.高);
    return;
  }
  绘图.fillStyle(色, 透明度).fillRoundedRect(区.左, 区.上, 区.宽, 区.高, 外观.圆角.卡片);
}

/** 已拥有部位卡的选中描边：蒙层压过之后补画，选中与已拥有两条状态同时成立。 */
export function 绘制商店部位选中描边(绘图: 图形对象, 区: 矩形): void {
  const 外观 = 解析商店外观();
  // 浅液晶的点亮色是亮黄，压在灰蒙层上会消失；已拥有状态统一用该风格的高对比标记色。
  const 色 = 外观.卡片.已拥有标记;
  if (外观.风格 === "像素") {
    const 粗 = 像素规范.描边;
    绘图.fillStyle(色, 0.95);
    绘图.fillRect(区.左, 区.上, 区.宽, 粗);
    绘图.fillRect(区.左, 区.上 + 区.高 - 粗, 区.宽, 粗);
    绘图.fillRect(区.左, 区.上 + 粗, 粗, 区.高 - 粗 * 2);
    绘图.fillRect(区.左 + 区.宽 - 粗, 区.上 + 粗, 粗, 区.高 - 粗 * 2);
    return;
  }
  const 圆角 = 外观.圆角.卡片;
  if (圆角 > 0)
    绘图.lineStyle(2, 色, 0.95).strokeRoundedRect(区.左 + 1, 区.上 + 1, 区.宽 - 2, 区.高 - 2, 圆角);
  else 绘图.lineStyle(2, 色, 0.95).strokeRect(区.左 + 1, 区.上 + 1, 区.宽 - 2, 区.高 - 2);
}

/** 已拥有对勾：像素风格走点阵，其余走双段折线 + 关节圆点，读作「已买」。 */
export function 绘制商店部位已拥有对勾(绘图: 图形对象, 区: 矩形): void {
  const 外观 = 解析商店外观();
  const 色 = 外观.卡片.已拥有标记;
  if (外观.风格 === "像素") {
    const 图案 = 像素图标.对勾;
    const 格 = Math.max(1, Math.floor(Math.min(区.宽, 区.高) / 图案.length));
    绘制像素图案(
      绘图,
      图案,
      区.左 + (区.宽 - 格 * 图案.length) / 2,
      区.上 + (区.高 - 格 * 图案.length) / 2,
      格,
      色,
    );
    return;
  }
  const 粗 = Math.max(1.6, Math.min(区.宽, 区.高) * 0.18);
  const 左 = 区.左 + 区.宽 * 0.14;
  const 拐X = 区.左 + 区.宽 * 0.4;
  const 拐Y = 区.上 + 区.高 * 0.78;
  const 右 = 区.左 + 区.宽 * 0.88;
  const 顶 = 区.上 + 区.高 * 0.2;
  绘图.lineStyle(粗, 色, 1);
  绘图.lineBetween(左, 区.上 + 区.高 * 0.48, 拐X, 拐Y);
  绘图.lineBetween(拐X, 拐Y, 右, 顶);
  绘图.fillStyle(色).fillCircle(拐X, 拐Y, 粗 / 2);
}

export function 绘制商店目录底板(
  绘图: 图形对象,
  区: 矩形,
  选中: boolean,
  _悬停 = false,
  描边: 商店描边方式 = 商店原生描边,
): void {
  const 外观 = 解析商店外观();
  if (外观.风格 === "像素") {
    绘制像素面板(
      绘图,
      区.左,
      区.上,
      区.宽,
      区.高,
      外观.目录.填充,
      外观.目录.填充,
      false,
      选中 ? 外观.目录.点亮 : 外观.目录.描边,
    );
    return;
  }
  if (外观.风格 === "立体") {
    绘制金属板(绘图, 区.左, 区.上, 区.宽, 区.高, {
      切: 外观.圆角.目录,
      强调: 选中,
      描边宽: 选中 ? 2.4 : 1.2,
    });
    return;
  }
  if (外观.风格 === "糖果") {
    // 目录卡 = 草莓粉糖纸：粉底 + 深粉裱花，选中时裱花与外沿一起转金。
    绘制糖果面板(绘图, 区.左, 区.上, 区.宽, 区.高, {
      圆角: 外观.圆角.目录,
      填色: 外观.目录.填充,
      边色: 选中 ? 外观.目录.点亮 : 外观.目录.描边,
      底边色: 糖果规范.色.巧克力深,
      铆钉: false,
      投影: false,
    });
    if (选中)
      绘图
        .lineStyle(2, 外观.目录.点亮, 0.95)
        .strokeRoundedRect(区.左 + 1, 区.上 + 1, 区.宽 - 2, 区.高 - 2, 外观.圆角.目录);
    return;
  }
  绘图.fillStyle(外观.目录.填充, 1).fillRoundedRect(区.左, 区.上, 区.宽, 区.高, 外观.圆角.目录);
  描边.圆角(
    绘图,
    区,
    外观.圆角.目录,
    1.5,
    选中 ? 外观.目录.点亮 : 外观.目录.描边,
    选中 ? 0.9 : 0.18,
  );
}

/** 未拥有目录卡的封条：一条压在卡顶的「未拆封」条，三套材质各有各的落法。 */
export function 绘制商店目录封条(绘图: 图形对象, 区: 矩形): void {
  const 外观 = 解析商店外观();
  if (外观.风格 === "像素") {
    绘图.fillStyle(外观.目录.封条).fillRect(区.左, 区.上, 区.宽, 区.高);
    return;
  }
  if (外观.风格 === "立体") {
    绘图.fillStyle(外观.目录.封条).fillRect(区.左, 区.上, 区.宽, 区.高);
    绘图
      .lineStyle(1, 外观.目录.缩略淡边, 0.45)
      .lineBetween(区.左, 区.上 + 0.5, 区.左 + 区.宽, 区.上 + 0.5);
    return;
  }
  if (外观.风格 === "糖果") {
    // 封条 = 一条草莓糖纸绑带，中央一颗金色封签，读作「没拆封」。
    绘图
      .fillStyle(外观.目录.封条, 1)
      .fillRoundedRect(区.左, 区.上, 区.宽, 区.高, Math.min(区.高 / 2, 3.5));
    绘图
      .fillStyle(糖果规范.色.糖纸, 0.35)
      .fillRoundedRect(
        区.左 + 区.宽 * 0.1,
        区.上 + Math.max(1, 区.高 * 0.2),
        区.宽 * 0.34,
        Math.max(1, 区.高 * 0.28),
        1,
      );
    绘图
      .fillStyle(外观.目录.名牌线, 1)
      .fillCircle(区.左 + 区.宽 / 2, 区.上 + 区.高 / 2, Math.max(1.8, 区.高 * 0.52));
    return;
  }
  绘图
    .fillStyle(外观.目录.封条, 0.95)
    .fillRoundedRect(区.左, 区.上, 区.宽, 区.高, Math.min(区.高 / 2, 4));
}

/**
 * 缩略图四周的态度：未拥有只有一圈淡边（画面被收着），
 * 已拥有换成氛围色——外层柔光 + 一圈实边，像装裱后点亮。
 */
export function 绘制商店目录缩略边(绘图: 图形对象, 区: 矩形, 已拥有: boolean): void {
  const 外观 = 解析商店外观();
  if (外观.风格 === "糖果") {
    if (!已拥有) {
      // 未拆封：一圈巧克力细框把缩略图「压」在卡面里。
      绘图
        .lineStyle(1.5, 外观.目录.缩略淡边, 0.4)
        .strokeRoundedRect(区.左 + 1, 区.上 + 1, 区.宽 - 2, 区.高 - 2, 6);
      return;
    }
    // 已拥有：金色糖衣柔光三层 + 一圈金边，读作拆封后被点亮。
    for (let 层 = 0; 层 < 3; 层 += 1) {
      const 扩 = 2 + 层 * 2;
      绘图
        .fillStyle(外观.目录.缩略氛围, 0.09 - 层 * 0.025)
        .fillRoundedRect(区.左 - 扩, 区.上 - 扩, 区.宽 + 扩 * 2, 区.高 + 扩 * 2, 8);
    }
    绘图
      .lineStyle(2, 外观.目录.缩略氛围, 0.9)
      .strokeRoundedRect(区.左 + 1, 区.上 + 1, 区.宽 - 2, 区.高 - 2, 6);
    return;
  }
  if (!已拥有) {
    if (外观.风格 === "像素") {
      const p = Math.max(1, Math.round(区.高 * 0.03));
      绘图.fillStyle(外观.目录.缩略淡边, 0.5);
      绘图.fillRect(区.左, 区.上, 区.宽, p);
      绘图.fillRect(区.左, 区.上 + 区.高 - p, 区.宽, p);
      绘图.fillRect(区.左, 区.上, p, 区.高);
      绘图.fillRect(区.左 + 区.宽 - p, 区.上, p, 区.高);
      return;
    }
    绘图
      .lineStyle(1, 外观.目录.缩略淡边, 外观.风格 === "立体" ? 0.25 : 0.12)
      .strokeRoundedRect(
        区.左 + 0.5,
        区.上 + 0.5,
        区.宽 - 1,
        区.高 - 1,
        外观.风格 === "立体" ? 4 : 3,
      );
    return;
  }
  // 氛围：三层外扩柔光；像素风格不用半透明柔光，靠实边。
  if (外观.风格 !== "像素") {
    for (let 层 = 0; 层 < 3; 层 += 1) {
      const 扩 = 2 + 层 * 2;
      绘图
        .fillStyle(外观.目录.缩略氛围, 0.07 - 层 * 0.02)
        .fillRoundedRect(
          区.左 - 扩,
          区.上 - 扩,
          区.宽 + 扩 * 2,
          区.高 + 扩 * 2,
          外观.风格 === "立体" ? 6 : 5,
        );
    }
  }
  if (外观.风格 === "像素") {
    const p = Math.max(2, Math.round(区.高 * 0.055));
    绘图.fillStyle(外观.目录.缩略氛围);
    绘图.fillRect(区.左, 区.上, 区.宽, p);
    绘图.fillRect(区.左, 区.上 + 区.高 - p, 区.宽, p);
    绘图.fillRect(区.左, 区.上, p, 区.高);
    绘图.fillRect(区.左 + 区.宽 - p, 区.上, p, 区.高);
    return;
  }
  绘图
    .lineStyle(外观.风格 === "立体" ? 2 : 1.5, 外观.目录.缩略氛围, 0.9)
    .strokeRoundedRect(
      区.左 + 0.5,
      区.上 + 0.5,
      区.宽 - 1,
      区.高 - 1,
      外观.风格 === "立体" ? 5 : 4,
    );
}

/**
 * 已拥有的名牌：比卡窄一圈、底部留 4px，读作「嵌进去的铭牌」而不是贴边色带。
 * 未拥有不画名牌，名称仍落在同一块区域，所以文字位置不随状态跳动。
 */
export function 计算商店目录名牌(卡: 矩形): 矩形 {
  return { 左: 卡.左 + 2, 上: 卡.上 + 卡.高 - 27, 宽: 卡.宽 - 4, 高: 23 };
}

/** 目录名称的基线锚点：给名牌左端的书脊亮条留出空隙，上下留白均衡。 */
export function 计算商店目录名称位置(卡: 矩形): { x: number; y: number } {
  return { x: 卡.左 + 13, y: 卡.上 + 卡.高 - 22 };
}

/**
 * 已拥有目录卡的名牌：一块嵌进卡里的铭牌。
 * 装饰由三层组成：左端一道竖亮条（书脊/封签）、底面自上而下的微弱光晕（点亮感）、
 * 右端一颗小方块（方块游戏的招牌）。未拥有不画名牌，名称直接压在卡面上，两态一眼可分。
 */
export function 绘制商店目录名牌(绘图: 图形对象, 卡: 矩形, 已拥有: boolean): void {
  if (!已拥有) return;
  const 外观 = 解析商店外观();
  const 板 = 计算商店目录名牌(卡);
  const 线 = 外观.目录.名牌线;
  // 右端装饰：一颗小方块，顶部提亮、底部压暗，读作有厚度而不是一个色块。
  const 饰 = Math.max(5, Math.round(板.高 * 0.3));
  const 饰左 = 板.左 + 板.宽 - 饰 - 7;
  const 饰上 = 板.上 + Math.round((板.高 - 饰) / 2);
  const 画方块 = () => {
    绘图.fillStyle(线).fillRect(饰左, 饰上, 饰, 饰);
    绘图.fillStyle(0xffffff, 0.55).fillRect(饰左, 饰上, 饰, Math.max(1, Math.round(饰 * 0.3)));
    绘图
      .fillStyle(0x000000, 0.3)
      .fillRect(
        饰左,
        饰上 + 饰 - Math.max(1, Math.round(饰 * 0.3)),
        饰,
        Math.max(1, Math.round(饰 * 0.3)),
      );
  };
  if (外观.风格 === "像素") {
    绘图.fillStyle(外观.目录.名牌底).fillRect(板.左, 板.上, 板.宽, 板.高);
    绘图.fillStyle(线).fillRect(板.左, 板.上, 板.宽, 像素规范.描边);
    // 左端竖亮条：像素风用直角实条。
    绘图.fillStyle(线).fillRect(板.左, 板.上, 像素规范.描边, 板.高);
    画方块();
    return;
  }
  if (外观.风格 === "立体") {
    绘制金属板(绘图, 板.左, 板.上, 板.宽, 板.高, { 切: 4, 凹: true, 描边宽: 1 });
    绘图.fillStyle(线, 0.9).fillRect(板.左 + 5, 板.上 + 4, 2, 板.高 - 8);
    画方块();
    return;
  }
  if (外观.风格 === "糖果") {
    // 深巧克力铭牌：金线描边 + 左端金色书脊，压在草莓粉卡面上最沉得住字。
    绘图
      .fillStyle(外观.目录.名牌底, 外观.目录.名牌底透明度)
      .fillRoundedRect(板.左, 板.上, 板.宽, 板.高, 5);
    绘图.lineStyle(1, 线, 0.7).strokeRoundedRect(板.左 + 0.5, 板.上 + 0.5, 板.宽 - 1, 板.高 - 1, 5);
    绘图.fillStyle(线, 0.9).fillRoundedRect(板.左 + 4, 板.上 + 5, 2, 板.高 - 10, 1);
    画方块();
    return;
  }
  // 霓虹：玻璃铭牌 —— 自上而下的微弱光晕 + 左书脊 + 顶缘亮线。
  绘图
    .fillStyle(外观.目录.名牌底, 外观.目录.名牌底透明度)
    .fillRoundedRect(板.左, 板.上, 板.宽, 板.高, 4);
  绘图
    .fillGradientStyle(线, 线, 线, 线, 0.16, 0.16, 0.02, 0.02)
    .fillRoundedRect(板.左, 板.上, 板.宽, 板.高, 4);
  绘图.fillStyle(线, 0.9).fillRoundedRect(板.左 + 4, 板.上 + 5, 2, 板.高 - 10, 1);
  绘图.lineStyle(1, 线, 0.8).lineBetween(板.左 + 10, 板.上 + 0.5, 板.左 + 板.宽 - 14, 板.上 + 0.5);
  画方块();
}

export function 绘制商店部位预览底板(绘图: 图形对象, 区: 矩形): void {
  const 外观 = 解析商店外观();
  if (外观.风格 === "像素") {
    绘图.fillStyle(外观.卡片.预览底).fillRect(区.左, 区.上, 区.宽, 区.高);
    return;
  }
  if (外观.风格 === "立体") {
    绘制金属板(绘图, 区.左, 区.上, 区.宽, 区.高, { 切: 2, 凹: true, 描边宽: 1 });
    return;
  }
  if (外观.风格 === "糖果") {
    // 预览底 = 一块巧克力凹槽，内容（风景/图标）再叠在上面。
    绘制糖果凹槽(绘图, 区.左, 区.上, 区.宽, 区.高);
    return;
  }
  绘图.fillStyle(外观.卡片.预览底, 0.9).fillRoundedRect(区.左, 区.上, 区.宽, 区.高, 6);
}

/** 商店坞区底板：一条铺满宽度的托底。 */
export function 绘制商店坞区底板(绘图: 图形对象, 区: 矩形): void {
  const 外观 = 解析商店外观();
  if (外观.风格 === "像素") {
    绘图.fillStyle(外观.面板.填充).fillRect(区.左, 区.上, 区.宽, 区.高);
    绘图.fillStyle(外观.面板.描边).fillRect(区.左, 区.上, 区.宽, 像素规范.描边);
    return;
  }
  if (外观.风格 === "立体") {
    绘制金属板(绘图, 区.左, 区.上, 区.宽, 区.高, { 切: 0, 描边宽: 0 });
    return;
  }
  if (外观.风格 === "糖果") {
    // 坞区 = 深巧克力托底：近乎直角填满屏宽，顶边一排奶油扇贝像遮阳篷的下沿。
    绘制糖果面板(绘图, 区.左, 区.上, 区.宽, 区.高, {
      圆角: 0,
      填色: 外观.面板.填充,
      边色: 外观.面板.描边,
      底边色: 糖果规范.色.巧克力深,
      铆钉: false,
      投影: false,
      高光: false,
    });
    return;
  }
  绘图.fillStyle(外观.面板.填充, 外观.面板.透明度).fillRect(区.左, 区.上, 区.宽, 区.高);
}


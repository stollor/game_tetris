/**
 * 主题卡/主题大预览的引擎无关配方：商店与设置外观页共用。
 * 卡面只用主题目录给出的真实配色与方块外观方案作画，不做空卡；
 * 文案（名称、状态、说明）由调用方按语言服务给，配方不读设置也不读存档。
 */

export const 主题卡常量 = {
  卡宽: 96,
  卡高: 104,
  间距: 8,
  列表高: 120,
} as const;

/** 主题卡面的真实视觉参数：配色来自主题界面配色，方块来自主题方块外观方案。 */
export interface 主题卡外观 {
  名称: string;
  说明: string;
  背景色: number;
  面板色: number;
  强调色: number;
  文字色: number;
  次要色: number;
  方块方案: 方块外观方案;
}

export interface 主题卡状态 {
  /** 当前正在使用的主题。 */
  已选?: boolean;
  /** 已拥有（含默认主题），未拥有时卡面显示价格。 */
  已拥有?: boolean;
  悬停?: boolean;
}

/** 大预览里的示例方块排布：一行七种方块，色相顺序与对局一致。 */
const 示例方块: readonly 方块类型[] = ["I", "O", "T", "S", "Z", "J", "L"];

function 卡面文字色(外观: 主题卡外观, 已选: boolean): number {
  return 已选 ? 外观.强调色 : 外观.文字色;
}

/** 主题卡预览区（绝对坐标）：上方留给配色与方块，下方两行文字。 */
export function 主题卡预览矩形(矩形: 矩形): 矩形 {
  return {
    左: 矩形.左 + 6,
    上: 矩形.上 + 6,
    宽: 矩形.宽 - 12,
    高: 矩形.高 - 42,
  };
}

/** 一行七个示例方块在给定区域内的排布（含方块边长）。 */
function 方块陈列(区域: 矩形, 数量: number): { 格: number; 左: number; 上: number } {
  const 间距 = 3;
  const 格 = Math.max(4, Math.min(18, (区域.宽 - 间距 * (数量 - 1)) / 数量, 区域.高 * 0.42));
  const 宽 = 数量 * 格 + (数量 - 1) * 间距;
  return { 格, 左: 区域.左 + (区域.宽 - 宽) / 2 + 格 / 2, 上: 区域.上 + 区域.高 * 0.62 };
}

/** 主题卡底板：面板色 + 强调色描边；已选加粗并点亮右上角标。 */
export function 绘制主题卡底板(
  绘图: 图形对象,
  矩形: 矩形,
  外观: 主题卡外观,
  状态: 主题卡状态 = {},
): void {
  const 圆角 = 是像素风格() ? 0 : 8;
  if (是像素风格()) {
    绘图.fillStyle(外观.面板色, 1).fillRect(矩形.左, 矩形.上, 矩形.宽, 矩形.高);
    绘图
      .lineStyle(状态.已选 ? 2 : 1, 卡面文字色(外观, !!状态.已选), 状态.已选 ? 1 : 0.5)
      .strokeRect(矩形.左, 矩形.上, 矩形.宽, 矩形.高);
    return;
  }
  绘图.fillStyle(外观.面板色, 1).fillRoundedRect(矩形.左, 矩形.上, 矩形.宽, 矩形.高, 圆角);
  绘图
    .lineStyle(状态.已选 || 状态.悬停 ? 2 : 1, 卡面文字色(外观, !!状态.已选), 状态.已选 ? 1 : 0.42)
    .strokeRoundedRect(矩形.左 + 0.5, 矩形.上 + 0.5, 矩形.宽 - 1, 矩形.高 - 1, 圆角);
}

/**
 * 主题卡预览：主题背景色打底 + 主题强调色渐变 + 主题方块外观的七色示例。
 * 已拥有才画出完整方块；未拥有画成暗色剪影，让「没买」和「买了」一眼可分。
 */
export function 绘制主题卡预览(
  绘图: 图形对象,
  矩形: 矩形,
  外观: 主题卡外观,
  状态: 主题卡状态 = {},
): void {
  const 预览 = 主题卡预览矩形(矩形);
  const 圆角 = 是像素风格() ? 0 : 5;
  if (是像素风格()) 绘图.fillStyle(外观.背景色, 1).fillRect(预览.左, 预览.上, 预览.宽, 预览.高);
  else 绘图.fillStyle(外观.背景色, 1).fillRoundedRect(预览.左, 预览.上, 预览.宽, 预览.高, 圆角);
  绘图
    .fillGradientStyle(外观.背景色, 外观.背景色, 外观.强调色, 外观.强调色, 1, 1, 0.35, 0.35)
    .fillRect(预览.左, 预览.上, 预览.宽, 预览.高);
  const 陈列 = 方块陈列(预览, 示例方块.length);
  const 可见 = 状态.已拥有 ?? true;
  示例方块.forEach((类型, i) => {
    const 色值 = 外观.方块方案.颜色[类型];
    const x = 陈列.左 + i * (陈列.格 + 3);
    const y = 陈列.上 - 陈列.格 / 2;
    if (可见) {
      绘制方块辉光(绘图, x, y, { 方案: 外观.方块方案, 色值, 格子: 陈列.格 });
      绘制方块单元(绘图, x, y, { 方案: 外观.方块方案, 色值, 格子: 陈列.格 });
      return;
    }
    绘图.fillStyle(外观.次要色, 0.28).fillRect(x + 1, y + 1, 陈列.格 - 2, 陈列.格 - 2);
  });
  // 底部强调线：选中时点亮，与卡面描边一起表达「正在使用」。
  绘图
    .fillStyle(外观.强调色, 状态.已选 ? 0.95 : 0.4)
    .fillRect(预览.左, 预览.上 + 预览.高 - 2, 预览.宽, 2);
}

/** 主题卡文字项：名称一行、状态一行（状态文案由调用方给，例如「使用中」「▣ 280」「去商店」）。 */
export function 生成主题卡文字项(
  矩形: 矩形,
  外观: 主题卡外观,
  状态: 主题卡状态,
  状态文案: string,
): 文字项[] {
  const 已选 = 状态.已选 === true;
  return [
    {
      文案: 外观.名称,
      样式: 派生霓虹文字样式("正文", {
        字号: 13,
        字重: "粗体",
        颜色: 卡面文字色(外观, 已选),
        对齐: "中",
      }),
      锚点: "中上",
      x: 矩形.左 + 矩形.宽 / 2,
      y: 矩形.上 + 矩形.高 - 32,
    },
    {
      文案: 状态文案,
      样式: 派生霓虹文字样式("正文", {
        字号: 11,
        颜色: 已选 ? 外观.强调色 : 外观.次要色,
        对齐: "中",
      }),
      锚点: "中上",
      x: 矩形.左 + 矩形.宽 / 2,
      y: 矩形.上 + 矩形.高 - 16,
    },
  ];
}

/** 大预览里界面示意的按钮区域（相对预览面板左上角）。 */
export function 主题预览按钮矩形(面板: 矩形, 序号: number, 数量: number): 矩形 {
  const 间距 = 10;
  const 宽 = Math.min(120, (面板.宽 - 40 - 间距 * (数量 - 1)) / Math.max(1, 数量));
  return {
    左: 面板.左 + (面板.宽 - (宽 * 数量 + 间距 * (数量 - 1))) / 2 + 序号 * (宽 + 间距),
    上: 面板.上 + 面板.高 - 46,
    宽,
    高: 30,
  };
}

/**
 * 主题大预览：商店选中主题时占据上半屏的真实表现 ——
 * 主题背景色 + 强调色的整块主题底、七色方块阵列、示例界面按钮。
 */
export function 绘制主题大预览(
  绘图: 图形对象,
  面板: 矩形,
  外观: 主题卡外观,
  状态: 主题卡状态 = {},
): void {
  const 圆角 = 是像素风格() ? 0 : 10;
  if (是像素风格()) 绘图.fillStyle(外观.背景色, 1).fillRect(面板.左, 面板.上, 面板.宽, 面板.高);
  else 绘图.fillStyle(外观.背景色, 1).fillRoundedRect(面板.左, 面板.上, 面板.宽, 面板.高, 圆角);
  绘图
    .fillGradientStyle(外观.背景色, 外观.背景色, 外观.强调色, 外观.强调色, 1, 1, 0.3, 0.3)
    .fillRect(面板.左, 面板.上, 面板.宽, 面板.高);
  const 陈列 = 方块陈列(
    { 左: 面板.左 + 16, 上: 面板.上 + 24, 宽: 面板.宽 - 32, 高: 面板.高 * 0.5 },
    示例方块.length,
  );
  示例方块.forEach((类型, i) => {
    const 色值 = 外观.方块方案.颜色[类型];
    const x = 陈列.左 + i * (陈列.格 + 3);
    const y = 陈列.上 - 陈列.格 / 2;
    绘制方块辉光(绘图, x, y, { 方案: 外观.方块方案, 色值, 格子: 陈列.格 });
    绘制方块单元(绘图, x, y, { 方案: 外观.方块方案, 色值, 格子: 陈列.格 });
  });
  绘图
    .fillStyle(外观.强调色, 状态.已选 ? 0.95 : 0.5)
    .fillRect(面板.左, 面板.上 + 面板.高 - 3, 面板.宽, 3);
}

/** 大预览的文字项：主题名、主题说明、状态；示意的界面按钮文案由调用方按语言给。 */
export function 生成主题预览文字项(
  面板: 矩形,
  外观: 主题卡外观,
  状态: 主题卡状态,
  状态文案: string,
  按钮文案: readonly string[],
): 文字项[] {
  const 已选 = 状态.已选 === true;
  const 结果: 文字项[] = [
    {
      文案: 外观.名称,
      样式: 派生霓虹文字样式("正文", { 字号: 20, 字重: "粗体", 颜色: 外观.文字色, 对齐: "左" }),
      锚点: "左上",
      x: 面板.左 + 18,
      y: 面板.上 + 14,
    },
    {
      文案: 外观.说明,
      样式: 派生霓虹文字样式("正文", { 字号: 12, 颜色: 外观.次要色, 对齐: "左" }),
      锚点: "左上",
      x: 面板.左 + 18,
      y: 面板.上 + 42,
      最大宽: 面板.宽 - 36,
    },
    {
      文案: 状态文案,
      样式: 派生霓虹文字样式("正文", {
        字号: 12,
        字重: "粗体",
        颜色: 已选 ? 外观.强调色 : 外观.次要色,
        对齐: "右",
      }),
      锚点: "右上",
      x: 面板.左 + 面板.宽 - 18,
      y: 面板.上 + 18,
    },
  ];
  按钮文案.forEach((文案, 序号) => {
    const 矩形 = 主题预览按钮矩形(面板, 序号, 按钮文案.length);
    结果.push({
      文案,
      样式: 派生霓虹文字样式("正文", {
        字号: 13,
        颜色: 已选 ? 外观.文字色 : 外观.次要色,
        对齐: "中",
      }),
      锚点: "中中",
      x: 矩形.左 + 矩形.宽 / 2,
      y: 矩形.上 + 矩形.高 / 2,
    });
  });
  return 结果;
}

/** 大预览里的示例按钮底板：只在有文字时一并画出来，避免「有字无钮」。 */
export function 绘制主题预览按钮(绘图: 图形对象, 面板: 矩形, 外观: 主题卡外观, 数量: number): void {
  const 圆角 = 是像素风格() ? 0 : 7;
  for (let i = 0; i < 数量; i++) {
    const 矩形 = 主题预览按钮矩形(面板, i, 数量);
    if (是像素风格()) {
      绘图.fillStyle(外观.面板色, 0.92).fillRect(矩形.左, 矩形.上, 矩形.宽, 矩形.高);
    } else {
      绘图.fillStyle(外观.面板色, 0.92).fillRoundedRect(矩形.左, 矩形.上, 矩形.宽, 矩形.高, 圆角);
    }
    绘图
      .lineStyle(1.5, 外观.强调色, 0.85)
      .strokeRoundedRect(矩形.左, 矩形.上, 矩形.宽, 矩形.高, 圆角);
  }
}

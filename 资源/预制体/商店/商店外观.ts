/**
 * 像素（砖机液晶 / 街机彩砖）：坞区是暗色液晶底带，卡片是纸面井、选中点亮强调色。
 * 像素色盘里「纸/墨」本身就是明暗一对（液晶浅纸深墨、彩砖深纸奶油墨），
 * 所以卡片底取 `纸`、描边与文字取 `墨` 两套主题都成立，不另写字面色。
 */
function 像素商店外观(): 商店外观 {
  const 色 = 像素规范.色;
  const 主字 = 像素规范.深色 ? 色.夜 : 色.墨;
  return {
    风格: "像素",
    字体: 游戏外观.字体.家族,
    圆角: { 卡片: 0, 按钮: 0, 纸页: 0, 目录: 0 },
    面板: { 填充: 色.远, 透明度: 1, 描边: 色.墨, 描边透明度: 1 },
    卡片: {
      填充: 色.纸,
      透明度: 1,
      描边: 色.墨,
      点亮: 色.黄,
      暗描边透明度: 1,
      预览底: 色.暗,
    },
    目录: { 填充: 色.纸, 描边: 色.墨, 点亮: 色.黄, 角标底: 色.暗 },
    按钮: {
      主: { 填充: 色.黄, 描边: 色.墨, 文字: 色串(主字) },
      次: { 填充: 色.纸, 描边: 色.墨, 文字: 色串(色.墨) },
      // 浅液晶上「暗底 + 墨字」读不出来，淡按钮也用纸面，只把描边收成次级色。
      淡: { 填充: 色.纸, 描边: 色.暗, 文字: 色串(色.墨) },
      禁用透明度: 0.5,
    },
    纸页: {
      填充: 色.纸,
      描边: 色.墨,
      内描边: 色.暗,
      标题: 色串(色.墨),
      正文: 色串(色.墨),
      数值: 色串(色.墨),
      说明: 色串(色.次字),
    },
    文字: {
      标题: 色串(色.墨),
      // 浅色液晶屏上的 13px 说明用暗色会糊，退回墨色；深色彩砖仍用次级灰做层级。
      副题: 色串(像素规范.深色 ? 色.次字 : 色.墨),
      消息: 色串(色.墨),
      部位: 色串(色.墨),
      目录: 色串(色.墨),
    },
    遮罩: { 颜色: 色.壳, 透明度: 0.72 },
  };
}


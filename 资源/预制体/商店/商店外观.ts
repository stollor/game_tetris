/**
 * 商店自己的视觉词汇：坞区底板、部位卡、目录卡、收藏按钮、交易纸页与文字色。
 *
 * 商店是「全屏试穿 + 收藏纸页」的独立场景，控件形状与其它页面不同，所以不复用
 * `预制体/基础/按钮|面板` 的整块配方；但语义色一律取对应主题的既有规范
 * （像素四色/像素色盘、立体界面色、霓虹调色板、收藏色），不在这里另立配色来源。
 * 三种风格由 `风格` 字段分派：像素走 `绘制像素面板`，立体走斜切金属板，霓虹沿用玻璃与纸页。
 */

export type 商店风格 = "霓虹" | "像素" | "立体";

export interface 商店按钮配色 {
  /** 填充色（数字，绘制用）。 */
  填充: number;
  /** 描边色。 */
  描边: number;
  /** 文字色（十六进制串，文字服务用）。 */
  文字: string;
}

export interface 商店外观 {
  风格: 商店风格;
  字体: string;
  /** 商店只用自己的圆角刻度：像素风格一律直角。 */
  圆角: { 卡片: number; 按钮: number; 纸页: number; 目录: number };
  /** 坞区整条底板。 */
  面板: { 填充: number; 透明度: number; 描边: number; 描边透明度: number };
  /** 部位卡（左侧图标 + 名称 + 价格）。 */
  卡片: {
    填充: number;
    透明度: number;
    描边: number;
    点亮: number;
    暗描边透明度: number;
    预览底: number;
  };
  目录: { 填充: number; 描边: number; 点亮: number; 角标底: number };
  按钮: { 主: 商店按钮配色; 次: 商店按钮配色; 淡: 商店按钮配色; 禁用透明度: number };
  纸页: {
    填充: number;
    描边: number;
    内描边: number;
    标题: string;
    正文: string;
    数值: string;
    说明: string;
  };
  文字: {
    标题: string;
    副题: string;
    消息: string;
    部位: string;
    目录: string;
  };
  遮罩: { 颜色: number; 透明度: number };
}

function 色串(值: number): string {
  return `#${值.toString(16).padStart(6, "0")}`;
}

/** 数字色转文字色：绘制指令要数字，文字服务要十六进制串。 */
export function 商店色串(值: number): string {
  return 色串(值);
}


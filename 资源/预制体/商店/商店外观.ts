let 缓存: { 解析: 主题解析结果; 外观: 商店外观 } | undefined;

/** 当前试穿主题的商店外观；解析结果按对象身份缓存，切主题即换新表。 */
export function 解析商店外观(): 商店外观 {
  const 解析 = 读取当前主题解析();
  if (缓存?.解析 === 解析) return 缓存.外观;
  const 外观 = 是像素风格() ? 像素商店外观() : 是立体风格() ? 立体商店外观() : 霓虹商店外观();
  缓存 = { 解析, 外观 };
  return 外观;
}

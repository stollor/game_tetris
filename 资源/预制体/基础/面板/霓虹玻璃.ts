import { 查找地点 } from "../../../../代码/框架配置/旅行地点";
import type { 图形对象 } from "../../../../.gamemaker/依赖/框架/界面/绘制/协议";
import { 绘制地点纹样 } from "../../外观/旅行纹样";
import { type 玻璃面板选项, 绘制玻璃面板基底 } from "./玻璃面板基底";

/**
 * 霓虹玻璃面板：主题面板底/描边、地点纹样与角饰的游戏视觉。
 * 引擎无关的玻璃质感原语在 `资源/预制体/基础/面板/玻璃面板基底.ts`，柔影在 `资源/视效/特效/柔影.ts`，
 * 玻璃按钮底板在 `资源/预制体/基础/按钮/玻璃按钮底板.ts`；这里只是按主题取色后交给面板基底。
 */

/**
 * 霓虹玻璃底板：统一用当前主题的面板底色与描边，其余圆角、透明度、强调辉光由调用方指定。
 * 直接画在场景已有的 Graphics 上，避免为每块装饰单独建容器。
 */
export function 绘制霓虹玻璃(
  图形: 图形对象,
  x: number,
  y: number,
  宽: number,
  高: number,
  选项: 玻璃面板选项 = {},
): void {
  const 调色板 = 读取霓虹调色板();
  绘制玻璃面板基底(图形, x, y, 宽, 高, {
    填色: 调色板.面板底,
    边色: 调色板.面板描边,
    ...选项,
  });
  if (是像素风格() || 是立体风格()) return;
  const 地点 = 查找地点(调色板.样式);
  if (地点) {
    绘制地点纹样(图形, x + 8, y + 5, 18, 地点.纹样, 0.65);
    绘制地点纹样(图形, x + 宽 - 28, y + 高 - 25, 18, 地点.纹样, 0.65);
  }
  const 强调 = 选项.强调色 ?? 调色板.强调;
  const 角长 = Math.min(16, 宽 / 8, 高 / 8);
  // 角部装饰留在边缘，不侵入正文和交互区域。
  图形.lineStyle(2, 强调, 0.8);
  for (const [角x, 角y, 横, 纵] of [
    [x + 4, y + 4, 1, 1],
    [x + 宽 - 4, y + 高 - 4, -1, -1],
  ]) {
    图形.lineBetween(角x, 角y + 角长 * 纵, 角x, 角y);
    图形.lineBetween(角x, 角y, 角x + 角长 * 横, 角y);
  }
}

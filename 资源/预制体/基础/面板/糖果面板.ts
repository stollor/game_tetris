/**
 * 糖果面板：厚巧克力描边 + 渐变糖衣主面 + 奶油双线裱花 + 顶部鼓起的扇贝花边。
 *
 * 这是糖果主题的通用底板，替代霓虹玻璃面板在糖果主题下的落点：
 * 面板/卡片/纸页/坞区都走同一份「糖纸 + 裱花」语言，只按调用方给的颜色区分层级。
 * 六层质感（投影/糖边/糖面/高光/内阴影/侧壁）统一由 `糖果质感` 叠出。
 */

export interface 糖果面板选项 {
  圆角?: number;
  填色?: number;
  /** 裱花与外描边的主色，缺省取草莓浅。 */
  边色?: number;
  /** 最外层巧克力边，缺省取巧克力深。 */
  底边色?: number;
  透明度?: number;
  /** 顶边扇贝花边。 */
  花边?: boolean;
  /** 四角奶油糖钉。 */
  铆钉?: boolean;
  /** 底部软影；贴边面板可关掉。 */
  投影?: boolean;
  /** 顶部糖衣高光。 */
  高光?: boolean;
  /** 糖体侧壁厚度；缺省按高度取 2~4px，厚面板才看得出糖身。 */
  厚度?: number;
}

/** 画一块糖果面板（左上角定位）。 */
export function 绘制糖果面板(
  绘图: 图形对象,
  x: number,
  y: number,
  宽: number,
  高: number,
  选项: 糖果面板选项 = {},
): void {
  const 圆角 = Math.max(2, Math.min(选项.圆角 ?? 糖果规范.圆角.面板, 宽 / 2, 高 / 2));
  const 填色 = 选项.填色 ?? 糖果规范.色.巧克力浅;
  const 边色 = 选项.边色 ?? 糖果规范.色.草莓浅;
  const 底边色 = 选项.底边色 ?? 糖果规范.色.巧克力深;
  const 透明度 = 选项.透明度 ?? 1;
  // 投影 / 侧壁 / 深糖边 / 顶亮底暗糖面 / 底部内阴影一次叠齐，高光另外画软带。
  绘制糖片(绘图, x, y, 宽, 高, {
    圆角,
    填色,
    边色: 底边色,
    描宽: Math.max(2, 糖果规范.描边.外 * 0.9),
    厚度: 选项.厚度 ?? Math.max(0, Math.min(4, 高 * 0.055)),
    透明度,
    投影: 选项.投影 !== false && 高 > 14,
    高光: false,
    内阴影: 高 > 24,
  });
  const 内缩 = 糖果规范.描边.外;
  // 糖衣顶部的软高光带：只压在上沿，不铺满整块面板。
  if (选项.高光 !== false && 高 > 24)
    绘图
      .fillGradientStyle(
        糖果规范.色.白,
        糖果规范.色.白,
        糖果规范.色.白,
        糖果规范.色.白,
        0.3 * 透明度 * 提亮系数(填色),
        0.24 * 透明度 * 提亮系数(填色),
        0,
        0,
      )
      .fillRoundedRect(
        x + 内缩 + 2,
        y + 内缩 + 1,
        宽 - 内缩 * 2 - 4,
        Math.min(高 * 0.28, 11),
        Math.min(圆角 - 内缩, 7),
      );
  // 左上镜面：一颗糖衣反光点，位置随面板大小走。
  if (高 > 26 && 宽 > 40)
    绘图
      .fillStyle(糖果规范.色.白, 0.32 * 透明度 * 提亮系数(填色))
      .fillEllipse(
        x + Math.min(宽 * 0.24, 46),
        y + Math.min(高 * 0.2, 14),
        Math.min(宽 * 0.16, 26),
        Math.min(高 * 0.08, 5.5),
      );
  // 奶油双线裱花 + 糖钉
  if (宽 > 26 && 高 > 22)
    绘制奶油内衬(绘图, x, y, 宽, 高, 圆角, 边色, 0.72 * 透明度, 选项.铆钉 !== false);
  // 顶边扇贝花边：双层鼓起，带阴影，读作糖纸的波浪口。
  if (选项.花边 !== false && 宽 > 30)
    绘制扇贝边(
      绘图,
      x + 4,
      y,
      宽 - 8,
      边色,
      0.96 * 透明度,
      "上",
      糖果规范.花边.半径,
      糖果规范.花边.步长,
      糖果规范.色.草莓深,
    );
}

/** 浅色纸页：面板的「奶油纸」变体，花色更淡，用于商店纸页/弹层正文。 */
export function 绘制糖果纸页(
  绘图: 图形对象,
  x: number,
  y: number,
  宽: number,
  高: number,
  选项: 糖果面板选项 = {},
): void {
  绘制糖果面板(绘图, x, y, 宽, 高, {
    圆角: 糖果规范.圆角.纸页,
    填色: 糖果规范.色.奶油,
    边色: 糖果规范.色.草莓,
    高光: true,
    铆钉: false,
    ...选项,
  });
}

/** 凹槽：内容区下沉的巧克力槽（预览卡、计数窗）。 */
export function 绘制糖果凹槽(
  绘图: 图形对象,
  x: number,
  y: number,
  宽: number,
  高: number,
  圆角 = 糖果规范.圆角.卡片,
): void {
  const 色 = 糖果规范.色;
  const r = Math.max(2, Math.min(圆角, 宽 / 2, 高 / 2));
  // 外沿一圈鼓起的奶油唇：凹槽本体是沉下去的，唇要先亮起来。
  绘图
    .fillStyle(混色(色.草莓深, 色.莓暗, 0.45), 0.55)
    .fillRoundedRect(x - 1.5, y - 1, 宽 + 3, 高 + 3, r + 1.5);
  绘图.fillStyle(色.巧克力深, 0.96).fillRoundedRect(x, y, 宽, 高, r);
  // 井壁：上深下浅的竖渐变，底缘透出一点糖色，才不是一块纯黑。
  绘图
    .fillGradientStyle(
      暗色(色.巧克力, 0.42),
      暗色(色.巧克力, 0.42),
      暗色(色.巧克力, 0.08),
      暗色(色.巧克力, 0.16),
      0.96,
      0.96,
      0.96,
      0.96,
    )
    .fillRoundedRect(x + 1.6, y + 1.6, 宽 - 3.2, 高 - 3.2, Math.max(1, r - 1.6));
  // 顶壁内阴影：凹槽深度全靠这一条，越靠近上沿越黑。
  绘图
    .fillGradientStyle(色.巧克力深, 色.巧克力深, 色.巧克力深, 色.巧克力深, 0.7, 0.7, 0, 0)
    .fillRoundedRect(x + 2, y + 2, 宽 - 4, Math.min(高 * 0.34, 14), Math.max(1, r - 2));
  // 底缘反光：内容压下去后，槽底受一点糖面反射。
  绘图
    .fillGradientStyle(色.草莓深, 色.草莓深, 色.草莓深, 色.草莓深, 0, 0, 0.32, 0.32)
    .fillRoundedRect(x + 3, y + 高 - Math.min(高 * 0.3, 10) - 2, 宽 - 6, Math.min(高 * 0.3, 10), 3);
  // 内壁双线：外圈深巧克力、内圈淡奶油，收口干净。
  绘图.lineStyle(1.4, 色.草莓深, 0.7).strokeRoundedRect(x + 0.7, y + 0.7, 宽 - 1.4, 高 - 1.4, r);
  绘图
    .lineStyle(1, 色.奶油, 0.4)
    .strokeRoundedRect(x + 2.4, y + 2.4, 宽 - 4.8, 高 - 4.8, Math.max(1, r - 2.4));
}

/** 糖果名牌选项：顶栏仪表与卡片角标共用的票据形。 */
export interface 糖果名牌选项 {
  填色?: number;
  边色?: number;
  窗色?: number;
  透明度?: number;
  /** 读数窗内缩；窗越深越像凹进去的读数口。 */
  窗缩?: number;
}

/**
 * 票据名牌：外沿深巧克力、玫瑰木面板、两侧糖钉小耳、内嵌凹陷读数窗。
 * 位置宽高由调用方给定，不在这里改布局。
 */
export function 绘制糖果名牌(
  绘图: 图形对象,
  x: number,
  y: number,
  宽: number,
  高: number,
  选项: 糖果名牌选项 = {},
): void {
  const 色 = 糖果规范.色;
  const 填色 = 选项.填色 ?? 色.莓;
  const 边色 = 选项.边色 ?? 色.莓暗;
  const 透明度 = 选项.透明度 ?? 1;
  const 圆角 = Math.min(糖果规范.圆角.卡片, 高 * 0.34);
  const 耳宽 = Math.min(9, 宽 * 0.07);
  const 耳高 = 高 * 0.5;
  // 投影：名牌浮在巧克力墙上，三层落影要实。
  绘图
    .fillStyle(色.巧克力深, 0.44 * 透明度)
    .fillRoundedRect(x - 1.5, y + 2.5, 宽 + 3, 高, 圆角 + 1.5);
  绘图
    .fillStyle(色.巧克力深, 0.22 * 透明度)
    .fillRoundedRect(x - 3.5, y + 6, 宽 + 7, 高, 圆角 + 3.5);
  // 两侧小耳：铆在面板边上的糖钉耳，让名牌读作徽章而不是圆角矩形。
  for (const 侧 of [0, 1] as const) {
    const 耳X = 侧 === 0 ? x - 耳宽 + 1.5 : x + 宽 - 1.5;
    绘图.fillStyle(边色, 透明度).fillRoundedRect(耳X, y + (高 - 耳高) / 2, 耳宽, 耳高, 3);
    绘图
      .fillGradientStyle(
        亮色(填色, 0.24),
        亮色(填色, 0.24),
        填色,
        填色,
        透明度,
        透明度,
        透明度,
        透明度,
      )
      .fillRoundedRect(耳X + 1, y + (高 - 耳高) / 2 + 1, 耳宽 - 2, 耳高 - 2, 2);
  }
  // 主板：深巧克力边 + 顶亮底暗的木面。
  绘图.fillStyle(边色, 透明度).fillRoundedRect(x - 1.5, y - 1.5, 宽 + 3, 高 + 3, 圆角 + 1.5);
  绘图
    .fillGradientStyle(
      亮色(填色, 0.3),
      亮色(填色, 0.12),
      暗色(填色, 0.2),
      暗色(填色, 0.34),
      透明度,
      透明度,
      透明度,
      透明度,
    )
    .fillRoundedRect(x, y, 宽, 高, 圆角);
  // 板面顶部一条受光棱 + 底部内阴影。
  绘图
    .fillGradientStyle(色.白, 色.白, 色.白, 色.白, 0.34 * 透明度, 0.2 * 透明度, 0, 0)
    .fillRoundedRect(x + 3, y + 1.5, 宽 - 6, Math.max(2, 高 * 0.2), 2);
  绘图
    .fillGradientStyle(色.巧克力深, 色.巧克力深, 色.巧克力深, 色.巧克力深, 0, 0, 0.28, 0.34)
    .fillRoundedRect(x + 2, y + 高 - Math.min(8, 高 * 0.24), 宽 - 4, Math.min(8, 高 * 0.24), 3);
  // 读数窗：往里凹一层，上沿最暗、下沿有一条反光唇。
  const 窗缩 = 选项.窗缩 ?? 4;
  if (宽 > 窗缩 * 4 && 高 > 窗缩 * 3) {
    const 窗宽 = 宽 - 窗缩 * 2;
    const 窗高 = 高 - 窗缩 * 2;
    const 窗圆 = Math.max(2, 圆角 - 窗缩);
    const 窗色 = 选项.窗色 ?? 混色(色.莓深, 色.井, 0.55);
    绘图
      .fillStyle(混色(边色, 色.巧克力深, 0.6), 透明度)
      .fillRoundedRect(x + 窗缩 - 1, y + 窗缩 - 1, 窗宽 + 2, 窗高 + 2, 窗圆 + 1);
    绘图
      .fillGradientStyle(窗色, 窗色, 窗色, 窗色, 透明度, 透明度, 透明度, 透明度)
      .fillRoundedRect(x + 窗缩, y + 窗缩, 窗宽, 窗高, 窗圆);
    // 读数窗上沿内阴影：窗是凹进去的，光落不进来。
    绘图
      .fillGradientStyle(色.井, 色.井, 色.井, 色.井, 0.62 * 透明度, 0.62 * 透明度, 0, 0)
      .fillRoundedRect(x + 窗缩, y + 窗缩, 窗宽, Math.min(窗高 * 0.4, 9), 窗圆);
    // 下沿反光唇：窗底接住一点糖衣的光。
    绘图
      .fillGradientStyle(色.象牙, 色.象牙, 色.象牙, 色.象牙, 0, 0, 0.28 * 透明度, 0.28 * 透明度)
      .fillRoundedRect(x + 窗缩 + 2, y + 高 - 窗缩 - 2.5, 窗宽 - 4, 1.4, 0.7);
    绘图
      .lineStyle(1.1, 色.象牙, 0.5 * 透明度)
      .strokeRoundedRect(x + 窗缩 - 0.5, y + 窗缩 - 0.5, 窗宽 + 1, 窗高 + 1, 窗圆);
  }
  绘图
    .lineStyle(1, 色.莓浅, 0.55 * 透明度)
    .strokeRoundedRect(x + 1, y + 1, 宽 - 2, 高 - 2, 圆角 - 1);
  const 钉 = 糖果规范.面板.铆钉半径 * 0.9;
  绘制糖钉(绘图, x + 5.5, y + 高 / 2, 钉, 色.草莓浅, 透明度);
  绘制糖钉(绘图, x + 宽 - 5.5, y + 高 / 2, 钉, 色.草莓浅, 透明度);
}

/** 凹槽读数位：一块糖片凹进去的小窗（卡片计数、徽标底）。 */
export function 绘制糖果窗口(
  绘图: 图形对象,
  x: number,
  y: number,
  宽: number,
  高: number,
  圆角 = 糖果规范.圆角.小,
): void {
  const 色 = 糖果规范.色;
  const r = Math.max(2, Math.min(圆角, 宽 / 2, 高 / 2));
  绘图.fillStyle(亮色(色.奶油, 0.3), 0.55).fillRoundedRect(x - 1, y - 1, 宽 + 2, 高 + 2, r + 1);
  绘图.fillStyle(暗色(色.巧克力, 0.35), 1).fillRoundedRect(x, y, 宽, 高, r);
  绘图
    .fillGradientStyle(
      色.井,
      色.井,
      混色(色.井, 色.莓深, 0.35),
      混色(色.井, 色.莓深, 0.35),
      0.95,
      0.95,
      0.95,
      0.95,
    )
    .fillRoundedRect(x + 1, y + 1, 宽 - 2, 高 - 2, Math.max(1, r - 1));
  绘图
    .fillGradientStyle(色.巧克力深, 色.巧克力深, 色.巧克力深, 色.巧克力深, 0.7, 0.7, 0, 0)
    .fillRoundedRect(x + 1.5, y + 1.5, 宽 - 3, Math.min(高 * 0.4, 5), Math.max(1, r - 1.5));
}

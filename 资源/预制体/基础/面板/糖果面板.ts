import type { 图形对象 } from "../../../../.gamemaker/依赖/框架/界面/绘制/协议";
import { 亮色, 暗色 } from "../../../../.gamemaker/依赖/框架/界面/颜色工具";
import { 糖果规范 } from "../../../主题/糖果/糖果规范";
import { 绘制奶油内衬, 绘制扇贝边, 绘制糖衣高光 } from "../装饰与蒙层/糖果花纹";

/**
 * 糖果面板：厚巧克力描边 + 渐变糖衣主面 + 奶油双线裱花 + 顶部鼓起的扇贝花边。
 *
 * 这是糖果主题的通用底板，替代霓虹玻璃面板在糖果主题下的落点：
 * 面板/卡片/纸页/坞区都走同一份「糖纸 + 裱花」语言，只按调用方给的颜色区分层级。
 */

export interface 糖果面板选项 {
  圆角?: number;
  填色?: number;
  /** 裱花与外描边的主色，缺省取草莓浅。 */
  边色?: number;
  /** 最外层巧克力边，缺省取巧克力深。 */
  底边色?: number;
  透明度?: number;
  /** 顶边扇贝花边。 */
  花边?: boolean;
  /** 四角奶油糖钉。 */
  铆钉?: boolean;
  /** 底部软影；贴边面板可关掉。 */
  投影?: boolean;
  /** 顶部糖衣高光。 */
  高光?: boolean;
}

/** 画一块糖果面板（左上角定位）。 */
export function 绘制糖果面板(
  绘图: 图形对象,
  x: number,
  y: number,
  宽: number,
  高: number,
  选项: 糖果面板选项 = {},
): void {
  const 圆角 = Math.max(2, Math.min(选项.圆角 ?? 糖果规范.圆角.面板, 宽 / 2, 高 / 2));
  const 填色 = 选项.填色 ?? 糖果规范.色.巧克力浅;
  const 边色 = 选项.边色 ?? 糖果规范.色.草莓浅;
  const 底边色 = 选项.底边色 ?? 糖果规范.色.巧克力深;
  const 透明度 = 选项.透明度 ?? 1;
  if (选项.投影 !== false && 高 > 14) {
    // 双层软影：贴边一层深、外扩一层淡，压在巧克力底上像糖块浮起来。
    绘图
      .fillStyle(底边色, 糖果规范.阴影.透明度 * 0.55 * 透明度)
      .fillRoundedRect(
        x - 糖果规范.阴影.扩散,
        y + 糖果规范.阴影.偏移Y + 2,
        宽 + 糖果规范.阴影.扩散 * 2,
        高,
        圆角 + 糖果规范.阴影.扩散,
      );
    绘图
      .fillStyle(底边色, 糖果规范.阴影.透明度 * 透明度)
      .fillRoundedRect(
        x + 糖果规范.阴影.扩散 * 0.5,
        y + 糖果规范.阴影.偏移Y,
        宽,
        高,
        圆角 + 糖果规范.阴影.扩散,
      );
  }
  const 内缩 = 糖果规范.描边.外;
  // 巧克力外沿 + 一圈受光边
  绘图.fillStyle(底边色, 透明度).fillRoundedRect(x, y, 宽, 高, 圆角);
  绘图
    .lineStyle(1.2, 亮色(底边色, 0.32), 0.55 * 透明度)
    .strokeRoundedRect(x + 0.8, y + 0.8, 宽 - 1.6, 高 - 1.6, 圆角);
  // 糖衣主面：纯色打底，再叠上白下黑的透明渐变，让糖面鼓起来。
  const 面圆角 = Math.max(2, 圆角 - 内缩);
  绘图
    .fillStyle(填色, 透明度)
    .fillRoundedRect(x + 内缩, y + 内缩, 宽 - 内缩 * 2, 高 - 内缩 * 2, 面圆角);
  绘图
    .fillGradientStyle(
      0xffffff,
      0xffffff,
      0x000000,
      0x000000,
      0.18 * 透明度,
      0.12 * 透明度,
      0.1 * 透明度,
      0.03 * 透明度,
    )
    .fillRoundedRect(x + 内缩, y + 内缩, 宽 - 内缩 * 2, 高 - 内缩 * 2, 面圆角);
  if (选项.高光 !== false && 高 > 24)
    绘制糖衣高光(绘图, x + 内缩, y + 内缩, 宽 - 内缩 * 2, 高 - 内缩 * 2, 圆角 - 内缩);
  // 底部内阴影：让糖衣有厚度。
  if (高 > 20)
    绘图
      .fillStyle(暗色(填色, 0.42), 0.3 * 透明度)
      .fillRoundedRect(
        x + 内缩 + 2,
        y + 高 - 内缩 - Math.min(12, 高 * 0.22),
        宽 - 内缩 * 2 - 4,
        Math.min(9, 高 * 0.17),
        4,
      );
  // 奶油双线裱花 + 糖钉
  if (宽 > 26 && 高 > 22)
    绘制奶油内衬(绘图, x, y, 宽, 高, 圆角, 边色, 0.72 * 透明度, 选项.铆钉 !== false);
  // 顶边扇贝花边：双层鼓起，带阴影，读作糖纸的波浪口。
  if (选项.花边 !== false && 宽 > 30) {
    绘制扇贝边(
      绘图,
      x + 4,
      y,
      宽 - 8,
      边色,
      0.96 * 透明度,
      "上",
      糖果规范.花边.半径,
      糖果规范.花边.步长,
      糖果规范.色.草莓深,
    );
  }
}

/** 浅色纸页：面板的「奶油纸」变体，花色更淡，用于商店纸页/弹层正文。 */
export function 绘制糖果纸页(
  绘图: 图形对象,
  x: number,
  y: number,
  宽: number,
  高: number,
  选项: 糖果面板选项 = {},
): void {
  绘制糖果面板(绘图, x, y, 宽, 高, {
    圆角: 糖果规范.圆角.纸页,
    填色: 糖果规范.色.奶油,
    边色: 糖果规范.色.草莓,
    高光: true,
    铆钉: false,
    ...选项,
  });
}

/** 凹槽：内容区下沉的巧克力槽（预览卡、计数窗）。 */
export function 绘制糖果凹槽(
  绘图: 图形对象,
  x: number,
  y: number,
  宽: number,
  高: number,
  圆角 = 糖果规范.圆角.卡片,
): void {
  const r = Math.max(2, Math.min(圆角, 宽 / 2, 高 / 2));
  绘图.fillStyle(糖果规范.色.巧克力深, 0.92).fillRoundedRect(x, y, 宽, 高, r);
  绘图
    .fillGradientStyle(
      糖果规范.色.巧克力,
      糖果规范.色.巧克力,
      糖果规范.色.巧克力深,
      糖果规范.色.巧克力深,
      0.9,
      0.9,
      0.9,
      0.9,
    )
    .fillRoundedRect(x + 1.5, y + 1.5, 宽 - 3, 高 - 3, Math.max(1, r - 1.5));
  // 内壁暗边：凹槽的深度。
  绘图
    .fillStyle(0x000000, 0.18)
    .fillRoundedRect(x + 2, y + 2, 宽 - 4, Math.max(2, 高 * 0.16), Math.max(1, r - 2));
  绘图
    .lineStyle(1.4, 糖果规范.色.草莓深, 0.7)
    .strokeRoundedRect(x + 0.7, y + 0.7, 宽 - 1.4, 高 - 1.4, r);
  绘图
    .lineStyle(1, 糖果规范.色.奶油, 0.45)
    .strokeRoundedRect(x + 2.2, y + 2.2, 宽 - 4.4, 高 - 4.4, Math.max(1, r - 2.2));
}

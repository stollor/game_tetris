/**
 * 糖果按钮：胶囊糖体 + 两端糖纸扭结 + 顶部糖衣高光；圆形键走马卡龙圆盘。
 *
 * 形状语言与面板同源（巧克力边、奶油裱花、软糖厚度），状态只有悬停提亮、
 * 按下下沉与选中描边三种，不改调用方的按钮语义。
 */

export interface 糖果按钮选项 {
  填色?: number;
  边框色?: number;
  强调色?: number;
  悬停?: boolean;
  按下?: boolean;
  选中?: boolean;
  透明度?: number;
  /** 圆角；缺省取胶囊（高的一半）。 */
  圆角?: number;
  /** 两端糖纸扭结；小图标键关掉更像软糖纽扣。 */
  糖纸?: boolean;
  /** 扭结朝向；缺省两端。并排成对的按钮收掉接缝侧，扭结才不会互相压住。 */
  糖纸侧?: 糖纸侧;
}

/** 糖纸扭结长在哪端：并排按钮各自只留靠屏幕外缘的那一端。 */
export type 糖纸侧 = "两端" | "左" | "右";

/**
 * 扭结的根与朝向：根在胶囊端口内缩 2px，再朝外长一个扭结长度。
 * 并排两颗胶囊的间隙只有 10px 时，两侧扭结会各自越界 16px 叠在一起，
 * 所以接缝侧必须由调用方收掉（见 `糖纸侧`）。
 */
function 计算糖纸扭结位(
  左: number,
  宽: number,
  侧: 糖纸侧 = "两端",
): { 根: number; 方向: 1 | -1 }[] {
  const 位: { 根: number; 方向: 1 | -1 }[] = [];
  if (侧 !== "右") 位.push({ 根: 左 + 2, 方向: -1 });
  if (侧 !== "左") 位.push({ 根: 左 + 宽 - 2, 方向: 1 });
  return 位;
}

/** 画一颗糖果按钮（中心定位）。 */
export function 绘制糖果按钮(
  绘图: 图形对象,
  中心X: number,
  中心Y: number,
  宽: number,
  高: number,
  选项: 糖果按钮选项 = {},
): void {
  const 填色 = 选项.填色 ?? 糖果规范.色.粉;
  const 边框色 = 选项.边框色 ?? 糖果规范.色.草莓深;
  const 透明度 = 选项.透明度 ?? 1;
  const 按下 = 选项.按下 ?? false;
  const 悬停 = 选项.悬停 ?? false;
  const 下沉 = 按下 ? 糖果规范.按钮.按下下沉 : 0;
  const 顶 = 中心Y - 高 / 2 + 下沉;
  const 左 = 中心X - 宽 / 2;
  const 圆角 = Math.max(2, Math.min(选项.圆角 ?? 高 / 2, 宽 / 2, 高 / 2));
  const 面填 = 悬停 && !按下 ? 亮色(填色, 0.1) : 填色;
  // 浅色糖（奶油/粉）提亮和镜面都要收着用，否则整颗键糊成一块白。
  const 提 = 提亮系数(面填);
  // 糖纸扭结先画：从糖身两端后面伸出来，被糖体压住根口才像拧出来的糖纸。
  if (选项.糖纸 !== false && 宽 > 44) {
    const 半高 = (高 / 2) * 糖果规范.按钮.糖纸高占比;
    for (const { 根, 方向 } of 计算糖纸扭结位(左, 宽, 选项.糖纸侧)) {
      绘制糖纸扭结(
        绘图,
        根,
        顶 + 高 / 2 + (按下 ? 0.5 : 1.5),
        半高 * 2,
        方向,
        面填,
        混色(暗色(面填, 0.26), 糖果规范.色.草莓深, 0.28),
      );
    }
  }
  // 六层糖体：投影 / 侧壁 / 巧克力边 / 顶亮底暗糖面 / 顶棱高光 / 底部内阴影。
  绘制糖片(绘图, 左, 顶, 宽, 高, {
    圆角,
    填色: 面填,
    边色: 糖果规范.色.巧克力深,
    描宽: 1.6,
    厚度: 按下 ? 1.2 : 2.6,
    透明度,
    投影: !按下,
    高光: true,
    内阴影: true,
    顶亮: 0.24,
    底暗: 0.28,
  });
  // 药丸凹槽：只有中等明度的糖才压得出凹陷，浅色糖上会变成一块白斑。
  if (高 > 26 && 宽 > 90 && 提 < 0.72)
    绘图
      .fillStyle(糖果规范.色.白, 0.1 * 透明度)
      .fillRoundedRect(左 + 宽 * 0.18, 顶 + 高 * 0.42, 宽 * 0.64, 高 * 0.34, 高 * 0.17);
  // 顶部糖衣高光：一条贴顶棱的亮带 + 一个镜面点。
  if (高 > 14) {
    const 白 = 糖果规范.色.白;
    绘图
      .fillGradientStyle(
        白,
        白,
        白,
        白,
        糖果规范.按钮.高光透明 * 透明度 * 提,
        0.4 * 透明度 * 提,
        0,
        0,
      )
      .fillRoundedRect(左 + 宽 * 0.16, 顶 + 3, 宽 * 0.36, Math.max(1.8, 高 * 0.14), 2);
    绘图
      .fillStyle(白, 0.46 * 透明度 * 提)
      .fillEllipse(左 + 宽 * 0.28, 顶 + 高 * 0.24, Math.max(3, 宽 * 0.09), Math.max(1.2, 高 * 0.1));
  }
  // 奶油内衬描边：糖面被一圈糖纸咬住。
  绘图
    .lineStyle(1.4, 糖果规范.色.糖纸, 0.45 * 透明度)
    .strokeRoundedRect(左 + 3.4, 顶 + 3.4, 宽 - 6.8, 高 - 6.8, Math.max(1, 圆角 - 3.4));
  // 状态描边
  const 边色 = 选项.强调色 ?? 边框色;
  const 边透明 = 选项.选中 ? 0.95 : 悬停 ? 0.85 : 0.65;
  绘图
    .lineStyle(选项.选中 ? 2.2 : 1.6, 边色, 边透明 * 透明度)
    .strokeRoundedRect(左, 顶, 宽, 高, 圆角);
}

/** 马卡龙圆键：外圈糖壳 + 内圈糖霜 + 中心图标位。用于旋转/暂存/方向等圆形操作键。 */
export function 绘制糖果圆键(
  绘图: 图形对象,
  中心X: number,
  中心Y: number,
  半径: number,
  填色: number,
  选项: { 悬停?: boolean; 按下?: boolean; 选中?: boolean } = {},
): void {
  const 下移 = 选项.按下 ? 1.5 : 0;
  const cy = 中心Y + 下移;
  const 面 = 选项.悬停 && !选项.按下 ? 亮色(填色, 0.1) : 填色;
  const 阴 = 糖果规范.色.巧克力深;
  // ①接触投影：三层同心圆，最远一层几乎化开。
  if (!选项.按下)
    for (const [下移影, 透明] of [
      [2.4, 0.34],
      [5.4, 0.18],
      [8.6, 0.09],
    ] as const)
      绘图.fillStyle(阴, 透明).fillCircle(中心X + 0.5, cy + 下移影, 半径 + 0.6);
  // ②深色糖边 ⑥侧壁：外壳下移一圈露出糖身，再压暗底缘。
  const 厚 = 选项.按下 ? 1.2 : 3;
  绘图.fillStyle(暗色(填色, 0.36), 1).fillCircle(中心X, cy + 厚, 半径);
  绘图
    .fillStyle(暗色(填色, 0.52), 0.9)
    .fillCircle(中心X, cy + Math.max(1, 厚 * 0.45), 半径 - 1);
  绘图.fillStyle(阴, 1).fillCircle(中心X, cy, 半径 + 0.8);
  // ③马卡龙糖壳：上亮下暗，右侧再收一档。
  绘图
    .fillGradientStyle(
      亮色(面, 0.26),
      亮色(面, 0.16),
      暗色(面, 0.22),
      暗色(面, 0.3),
      1,
      1,
      1,
      1,
    )
    .fillCircle(中心X, cy, 半径 - 0.8);
  绘图.fillStyle(暗色(面, 0.2), 0.35).fillCircle(中心X + 半径 * 0.24, cy + 半径 * 0.18, 半径 * 0.8);
  // 糖壳的褶皱脚：一圈略暗的环，读作马卡龙的两片壳。
  绘图.lineStyle(1.6, 暗色(面, 0.24), 0.55).strokeCircle(中心X, cy, 半径 * 0.8);
  // ④奶油糖霜：外圈奶油、内圈提亮，中心是图标位。
  绘图.fillStyle(糖果规范.色.奶油, 0.94).fillCircle(中心X, cy, 半径 * 0.66);
  绘图
    .fillGradientStyle(
      亮色(面, 0.3),
      亮色(面, 0.3),
      暗色(面, 0.1),
      暗色(面, 0.18),
      0.9,
      0.9,
      0.9,
      0.9,
    )
    .fillCircle(中心X, cy, 半径 * 0.54);
  绘图.fillStyle(暗色(面, 0.16), 0.4).fillCircle(中心X, cy + 半径 * 0.1, 半径 * 0.44);
  // ⑤顶棱高光：左上两道镜面；浅色糖壳上的反光要淡一档。
  const 提 = 提亮系数(面);
  绘图
    .fillStyle(糖果规范.色.白, (选项.按下 ? 0.3 : 0.62) * 提)
    .fillEllipse(中心X - 半径 * 0.34, cy - 半径 * 0.42, 半径 * 0.46, 半径 * 0.24);
  绘图
    .fillStyle(糖果规范.色.白, 0.34 * 提)
    .fillCircle(中心X + 半径 * 0.38, cy + 半径 * 0.4, 半径 * 0.08);
  绘图.lineStyle(1.4, 糖果规范.色.糖纸, 0.5).strokeCircle(中心X, cy, Math.max(1, 半径 - 4.5));
  if (选项.选中) 绘图.lineStyle(2.2, 糖果规范.色.金, 0.95).strokeCircle(中心X, cy, 半径);
}

/** 花边椭圆：外缘按瓣数起伏的饼干轮廓，起伏深度是半径的比例。 */
function 花边椭圆点(
  中心X: number,
  中心Y: number,
  横半径: number,
  纵半径: number,
  瓣数: number,
  起伏: number,
): 点[] {
  const 段 = 瓣数 * 6;
  return Array.from({ length: 段 }, (_, 序) => {
    const 角 = (序 / 段) * Math.PI * 2;
    const 缩 = 1 - 起伏 * (1 - Math.abs(Math.cos((角 * 瓣数) / 2)));
    return { x: 中心X + Math.cos(角) * 横半径 * 缩, y: 中心Y + Math.sin(角) * 纵半径 * 缩 };
  });
}

function 平移点(点集: readonly 点[], 横移: number, 纵移: number): 点[] {
  return 点集.map((p) => ({ x: p.x + 横移, y: p.y + 纵移 }));
}

function 椭圆点(中心X: number, 中心Y: number, 横半径: number, 纵半径: number, 段 = 40): 点[] {
  return Array.from({ length: 段 }, (_, 序) => {
    const 角 = (序 / 段) * Math.PI * 2;
    return { x: 中心X + Math.cos(角) * 横半径, y: 中心Y + Math.sin(角) * 纵半径 };
  });
}

/**
 * 花边黄油饼干：左转键与角键。饼干有侧面厚度、凸起内圈与一圈戳孔，按下时整块下沉、厚度变薄。
 * 中心定位，横纵半径分开以便压成扁饼干。
 */
export function 绘制花边饼干(
  绘图: 图形对象,
  中心X: number,
  中心Y: number,
  横半径: number,
  纵半径: number,
  按下 = false,
): void {
  const 色 = 糖果规范.色;
  const 厚 = Math.max(2.5, 纵半径 * (按下 ? 0.08 : 0.15));
  const cy = 中心Y - 厚 / 2 + (按下 ? 1.5 : 0);
  const 瓣数 = Math.max(10, Math.round((横半径 + 纵半径) / 4.2));
  const 外形 = 花边椭圆点(中心X, cy, 横半径, 纵半径, 瓣数, 0.07);
  // ①接触投影：三层沿边外扩，饼干才压在托盘里。
  绘制形状投影(绘图, 外形, 按下 ? 0.55 : 1, 1, 色.巧克力深, 0.9);
  // ②深色糖边 ⑥侧壁：焦糖色侧壁比饼干面暗一档，底缘再压暗。
  绘图
    .fillStyle(色.饼干焦, 1)
    .fillPoints(平移点(花边椭圆点(中心X, cy, 横半径 + 1.2, 纵半径 + 1.2, 瓣数, 0.07), 0, 厚), true);
  绘图
    .fillStyle(暗色(色.饼干焦, 0.22), 1)
    .fillPoints(
      平移点(花边椭圆点(中心X, cy, 横半径 + 1.2, 纵半径 + 1.2, 瓣数, 0.07), 0, 厚 * 0.45),
      true,
    );
  绘图
    .fillStyle(色.饼干焦, 1)
    .fillPoints(花边椭圆点(中心X, cy, 横半径 + 1.2, 纵半径 + 1.2, 瓣数, 0.07), true);
  // ③饼干面：顶亮底暗，右侧切一刀暗面。
  绘图
    .fillGradientStyle(
      亮色(色.饼干浅, 0.2),
      亮色(色.饼干浅, 0.04),
      色.饼干,
      混色(色.饼干, 色.饼干深, 0.42),
      1,
      1,
      1,
      1,
    )
    .fillPoints(外形, true);
  绘图
    .fillGradientStyle(色.饼干, 色.饼干深, 色.饼干, 色.饼干深, 0, 0.3, 0, 0.3)
    .fillPoints(平移点(外形, 横半径 * 0.18, 0), true);
  // ④顶棱高光：外缘一圈奶油亮弧 + 左上镜面。
  绘图.lineStyle(1.4, 亮色(色.饼干浅, 0.5), 0.65).strokePoints(外形, true);
  // 花瓣棱：每道外缘凹谷向内拉一条压痕，读成菊花模压出的饼干。
  for (let 序 = 0; 序 < 瓣数; 序 += 1) {
    const 角 = (序 / 瓣数) * Math.PI * 2 + Math.PI / 瓣数;
    const 余 = Math.cos(角);
    const 正 = Math.sin(角);
    绘图
      .lineStyle(Math.max(1, 纵半径 * 0.05), 色.饼干深, 0.45)
      .lineBetween(
        中心X + 余 * 横半径 * 0.68,
        cy + 正 * 纵半径 * 0.66,
        中心X + 余 * 横半径 * 0.9,
        cy + 正 * 纵半径 * 0.88,
      );
  }
  // 凸起内圈：下沿暗线 + 上沿亮线，读成压模压出的台阶。
  const 内横 = 横半径 * 0.64;
  const 内纵 = 纵半径 * 0.6;
  绘图
    .lineStyle(Math.max(1.4, 纵半径 * 0.07), 色.饼干深, 0.75)
    .strokePoints(椭圆点(中心X, cy + 1, 内横, 内纵), true);
  绘图.lineStyle(1.2, 色.饼干浅, 0.95).strokePoints(椭圆点(中心X, cy - 0.6, 内横, 内纵), true);
  绘图
    .fillStyle(亮色(色.饼干, 0.12), 0.85)
    .fillPoints(椭圆点(中心X, cy, 内横 - 1.5, 内纵 - 1.5), true);
  绘图
    .fillStyle(色.白, 按下 ? 0.18 : 0.38)
    .fillEllipse(中心X - 横半径 * 0.36, cy - 纵半径 * 0.52, 横半径 * 0.5, 纵半径 * 0.2);
}

/** 糖霜甜甜圈：右转键。面团圈上浇一层滴落的草莓糖霜，撒彩针；箭头压在糖霜中心。 */
export function 绘制糖霜甜甜圈(
  绘图: 图形对象,
  中心X: number,
  中心Y: number,
  横半径: number,
  纵半径: number,
  按下 = false,
): void {
  const 色 = 糖果规范.色;
  const 厚 = Math.max(2.5, 纵半径 * (按下 ? 0.1 : 0.18));
  const cy = 中心Y - 厚 / 2 + (按下 ? 1.5 : 0);
  const 面团 = 椭圆点(中心X, cy, 横半径, 纵半径, 48);
  // ①接触投影：面团压进托盘的三层落影。
  绘制形状投影(绘图, 面团, 按下 ? 0.55 : 1, 1, 色.巧克力深, 0.9);
  // ②深色糖边 ⑥侧壁：焦糖侧壁向下露一圈，底缘再压暗。
  绘图
    .fillStyle(色.饼干深, 1)
    .fillPoints(平移点(椭圆点(中心X, cy, 横半径 + 1.2, 纵半径 + 1.2, 48), 0, 厚), true);
  绘图
    .fillStyle(暗色(色.饼干深, 0.25), 1)
    .fillPoints(平移点(椭圆点(中心X, cy, 横半径 + 1.2, 纵半径 + 1.2, 48), 0, 厚 * 0.45), true);
  绘图.fillStyle(色.饼干焦, 1).fillPoints(椭圆点(中心X, cy, 横半径 + 1.2, 纵半径 + 1.2, 48), true);
  // ③面团面：顶亮底暗。
  绘图
    .fillGradientStyle(
      亮色(色.饼干浅, 0.18),
      色.饼干浅,
      色.饼干,
      暗色(色.饼干, 0.2),
      1,
      1,
      1,
      1,
    )
    .fillPoints(面团, true);
  // 糖霜：两组正弦叠出不规则滴落边，下缘多垂一点。
  const 段 = 64;
  const 糖霜 = Array.from({ length: 段 }, (_, 序) => {
    const 角 = (序 / 段) * Math.PI * 2;
    const 滴 = 0.045 * Math.sin(角 * 7 + 0.6) + 0.03 * Math.sin(角 * 13 + 1.7);
    const 垂 = Math.max(0, Math.sin(角)) * 0.05;
    const 缩 = 0.84 + 滴 + 垂;
    return {
      x: 中心X + Math.cos(角) * 横半径 * 缩,
      y: cy - 纵半径 * 0.04 + Math.sin(角) * 纵半径 * 缩,
    };
  });
  // 糖霜：滴落边外扩一圈深草莓边，面上再压顶亮底暗与镜面。
  绘图.fillStyle(色.草莓深, 1).fillPoints(平移点(糖霜, 0, 1.8), true);
  绘图.lineStyle(2.2, 色.草莓深, 1).strokePoints(糖霜, true);
  绘图
    .fillGradientStyle(
      亮色(色.草莓浅, 0.08),
      色.草莓浅,
      色.草莓,
      混色(色.草莓, 色.草莓深, 0.38),
      1,
      1,
      1,
      1,
    )
    .fillPoints(糖霜, true);
  绘图
    .fillStyle(色.白, 0.3)
    .fillEllipse(中心X - 横半径 * 0.3, cy - 纵半径 * 0.52, 横半径 * 0.56, 纵半径 * 0.16);
  // 中心孔：糖霜内缘一圈暗边，孔里露面团。
  const 孔横 = 横半径 * 0.24;
  const 孔纵 = 纵半径 * 0.24;
  绘图.fillStyle(色.草莓深, 1).fillPoints(椭圆点(中心X, cy, 孔横 + 1.6, 孔纵 + 1.6, 24), true);
  绘图
    .fillGradientStyle(色.饼干深, 色.饼干深, 色.饼干, 色.饼干, 1, 1, 1, 1)
    .fillPoints(椭圆点(中心X, cy + 0.6, 孔横, 孔纵, 24), true);
  const 糖针 = [色.薄荷, 色.柠檬, 色.蓝莓, 色.糖纸, 色.葡萄, 色.叶绿];
  const 针长 = Math.max(2.4, 纵半径 * 0.13);
  for (let 序 = 0; 序 < 22; 序 += 1) {
    const 角 = 序 * 2.399 + 0.4;
    const 环 = 0.42 + ((序 * 37) % 10) / 30;
    const x = 中心X + Math.cos(角) * 横半径 * 环;
    const y = cy + Math.sin(角) * 纵半径 * 环;
    const 斜 = 序 * 1.13;
    const dx = (Math.cos(斜) * 针长) / 2;
    const dy = (Math.sin(斜) * 针长) / 2;
    绘图
      .lineStyle(Math.max(1.5, 纵半径 * 0.065), 糖针[序 % 糖针.length] ?? 色.薄荷, 0.95)
      .lineBetween(x - dx, y - dy, x + dx, y + dy);
  }
  绘图
    .fillStyle(色.白, 按下 ? 0.2 : 0.5)
    .fillEllipse(中心X - 横半径 * 0.38, cy - 纵半径 * 0.46, 横半径 * 0.42, 纵半径 * 0.16);
}

/**
 * 扇贝苏打饼干：暂存键。四边一圈圆齿、内框压线与两排戳孔，和暂存槽的「收进盒里」区分开。
 * 中心定位，宽高为饼干本体（不含圆齿外凸）。
 */
export function 绘制扇贝饼干(
  绘图: 图形对象,
  中心X: number,
  中心Y: number,
  宽: number,
  高: number,
  按下 = false,
): void {
  const 色 = 糖果规范.色;
  const 厚 = 按下 ? 3 : 7;
  const 顶 = 中心Y - 高 / 2 - 厚 / 2 + (按下 ? 1.5 : 0);
  const 左 = 中心X - 宽 / 2;
  const 齿 = Math.max(3, 高 * 0.085);
  const 齿列 = Math.max(4, Math.round(宽 / (齿 * 2.4)));
  const 齿行 = Math.max(3, Math.round(高 / (齿 * 2.4)));
  const 圆齿 = (外扩: number, 纵移: number, 填: (x: number, y: number, r: number) => void) => {
    for (let 序 = 0; 序 <= 齿列; 序 += 1) {
      const x = 左 + (宽 * 序) / 齿列;
      填(x, 顶 + 纵移, 齿 + 外扩);
      填(x, 顶 + 高 + 纵移, 齿 + 外扩);
    }
    for (let 序 = 1; 序 < 齿行; 序 += 1) {
      const y = 顶 + (高 * 序) / 齿行 + 纵移;
      填(左, y, 齿 + 外扩);
      填(左 + 宽, y, 齿 + 外扩);
    }
  };
  const 画层 = (外扩: number, 纵移: number, 色值: number, 透明: number) => {
    绘图
      .fillStyle(色值, 透明)
      .fillRoundedRect(左 - 外扩, 顶 + 纵移 - 外扩, 宽 + 外扩 * 2, 高 + 外扩 * 2, 齿);
    圆齿(外扩, 纵移, (x, y, r) => 绘图.fillCircle(x, y, r));
  };
  // ①接触投影：三层依次下移外扩，饼干才压在操作盘里。
  画层(2.6, 厚 + 1.4, 色.巧克力深, 按下 ? 0.16 : 0.26);
  画层(1.4, 厚 + 4.8, 色.巧克力深, 按下 ? 0.1 : 0.16);
  画层(0.6, 厚 + 8.2, 色.巧克力深, 按下 ? 0.05 : 0.09);
  // ②深色糖边 ⑥侧壁：焦糖外沿、深饼干侧壁，底缘再压一档。
  画层(1.4, 0, 色.饼干焦, 1);
  画层(0, 厚, 色.饼干深, 1);
  画层(0, 厚 * 0.45, 暗色(色.饼干深, 0.3), 1);
  画层(0, 0, 色.饼干, 1);
  // ③饼干面：上亮下暗，顶棱再压一条奶油光。
  绘图
    .fillGradientStyle(
      亮色(色.饼干浅, 0.24),
      亮色(色.饼干浅, 0.06),
      色.饼干,
      混色(色.饼干, 色.饼干深, 0.4),
      0.95,
      0.95,
      0.95,
      0.95,
    )
    .fillRoundedRect(左 - 齿 * 0.6, 顶 - 齿 * 0.6, 宽 + 齿 * 1.2, 高 * 0.55, 齿);
  const 框缩 = 齿 + 3;
  绘图
    .lineStyle(1.4, 色.饼干深, 0.7)
    .strokeRoundedRect(左 + 框缩, 顶 + 框缩 + 0.8, 宽 - 框缩 * 2, 高 - 框缩 * 2, 4);
  绘图
    .lineStyle(1, 色.饼干浅, 0.9)
    .strokeRoundedRect(左 + 框缩, 顶 + 框缩 - 0.4, 宽 - 框缩 * 2, 高 - 框缩 * 2, 4);
  const 孔半径 = Math.max(0.9, 高 * 0.035);
  for (const 行 of [0.3, 0.7])
    for (const 列 of [0.2, 0.8]) {
      const x = 左 + 宽 * 列;
      const y = 顶 + 高 * 行;
      绘图.fillStyle(色.饼干焦, 0.7).fillCircle(x, y, 孔半径);
      绘图.fillStyle(色.饼干浅, 0.7).fillCircle(x, y + 孔半径 * 0.8, 孔半径 * 0.6);
    }
  绘图
    .fillStyle(色.白, 按下 ? 0.15 : 0.32)
    .fillEllipse(左 + 宽 * 0.28, 顶 + 高 * 0.2, 宽 * 0.3, 高 * 0.1);
}

/**
 * 双格巧克力：左右移动键。外壳带侧面厚度，面上两块倒角凸起的巧克力格，中间压出凹槽。
 * 中心定位。
 */
export function 绘制巧克力条(
  绘图: 图形对象,
  中心X: number,
  中心Y: number,
  宽: number,
  高: number,
  按下 = false,
): void {
  const 色 = 糖果规范.色;
  const 厚 = 按下 ? 3 : 7;
  const 顶 = 中心Y - 高 / 2 - 厚 / 2 + (按下 ? 1.5 : 0);
  const 左 = 中心X - 宽 / 2;
  const 圆角 = Math.min(9, 高 * 0.18);
  // 六层巧克力板：投影 / 侧壁 / 深巧克力边 / 顶亮底暗的巧克力面。
  绘制糖片(绘图, 左, 顶, 宽, 高, {
    圆角,
    填色: 混色(色.可可, 色.可可深, 0.78),
    边色: 色.巧克力深,
    描宽: 2.4,
    厚度: 厚,
    投影: !按下,
    高光: true,
    内阴影: true,
    顶亮: 0.06,
    底暗: 0.5,
  });
  // 两块凸起的巧克力格：外圈斜面（上亮下暗）+ 顶面 + 顶棱高光，中间留一道凹槽。
  const 内左 = 左 + 5;
  const 内上 = 顶 + 5;
  const 内宽 = 宽 - 10;
  const 内高 = 高 - 10;
  const 缝 = Math.max(3, 内宽 * 0.05);
  const 块宽 = (内宽 - 缝) / 2;
  const 块半径 = Math.max(2, Math.min(5, 内高 * 0.24));
  for (const 序 of [0, 1] as const) {
    const bx = 内左 + 序 * (块宽 + 缝);
    const by = 内上;
    const 边 = 圆角多边形(
      { 左: bx, 上: by, 右: bx + 块宽, 下: by + 内高 },
      同角(块半径),
    );
    绘制形状投影(绘图, 边, 按下 ? 0.4 : 0.75, 1, 色.巧克力深, 0.6);
    // 斜面：底暗、顶亮，读作倒角。
    绘图.fillStyle(暗色(色.可可, 0.42), 1).fillPoints(平移点(边, 0, 1.4), true);
    绘图.fillStyle(暗色(色.可可, 0.2), 1).fillPoints(边, true);
    绘图
      .fillGradientStyle(
        亮色(色.可可, 0.3),
        亮色(色.可可, 0.18),
        色.可可,
        暗色(色.可可, 0.12),
        1,
        1,
        1,
        1,
      )
      .fillPoints(圆角多边形({ 左: bx + 1.3, 上: by + 1.3, 右: bx + 块宽 - 1.3, 下: by + 内高 - 1.3 }, 同角(块半径 - 1)), true);
    // 顶面斜光：两道光带跟着主光从左上斜下。
    const 顶面形 = 圆角多边形(
      { 左: bx + 2, 上: by + 2, 右: bx + 块宽 - 2, 下: by + 内高 - 2 },
      同角(Math.max(1, 块半径 - 2)),
    );
    for (const [起, 带宽, 透明] of [
      [bx - by + 内高 * 0.1, 内宽 * 0.14, 0.2],
      [bx - by + 内高 * 0.42, 内宽 * 0.06, 0.14],
    ] as const) {
      const 光 = 裁进凸形(斜带(起, 带宽, by, by + 内高), 顶面形);
      if (光.length >= 3) 绘图.fillStyle(色.白, 按下 ? 透明 * 0.5 : 透明).fillPoints(光, true);
    }
    // 顶棱高光条：贴在每块的上沿。
    绘图
      .fillStyle(色.白, 按下 ? 0.12 : 0.3)
      .fillRoundedRect(bx + 块宽 * 0.18, by + 2, 块宽 * 0.5, 1.5, 0.8);
  }
  // 中缝：两块之间压一道深槽，光在这里断掉。
  绘图
    .fillStyle(色.巧克力深, 0.7)
    .fillRoundedRect(内左 + 块宽 + 1, 内上 + 2, Math.max(1.5, 缝 - 2), 内高 - 4, 1);
  绘图
    .fillStyle(色.白, 0.16)
    .fillRoundedRect(内左 + 块宽 + 1.6, 内上 + 2.4, 1, 内高 - 5, 0.5);
}

/**
 * 珊瑚糖纸糖：软降键。圆润糖身、金色收口与两端扭结糖纸，双折线压在糖身中心。
 * 中心定位，宽高是整颗糖（含扭结）的外接框。
 */
export function 绘制糖纸硬降(
  绘图: 图形对象,
  中心X: number,
  中心Y: number,
  宽: number,
  高: number,
  按下 = false,
): void {
  const 色 = 糖果规范.色;
  const 厚 = 按下 ? 2 : 4;
  const cy = 中心Y - 厚 / 2 + (按下 ? 1.5 : 0);
  const 身高 = 高 - 厚 - 4;
  const 身宽 = Math.max(身高 * 1.3, 宽 - 身高 * 1.3);
  const 左 = 中心X - 身宽 / 2;
  const 顶 = cy - 身高 / 2;
  const 圆角 = 身高 / 2;
  for (const 向 of [-1, 1] as const)
    绘制糖纸扭结(绘图, 中心X + 向 * (身宽 / 2 - 2), cy, 身高, 向, 色.珊瑚, 色.珊瑚深);
  // 六层糖身：投影 / 侧壁 / 深莓边 / 顶亮底暗的珊瑚糖面 / 顶棱高光 / 底部内阴影。
  绘制糖片(绘图, 左, 顶, 身宽, 身高, {
    圆角,
    填色: 混色(色.珊瑚, 色.珊瑚深, 0.32),
    边色: 色.莓暗,
    描宽: 2.2,
    厚度: 厚,
    投影: !按下,
    高光: true,
    内阴影: true,
    顶亮: 0.2,
    底暗: 0.34,
  });
  // 金色收口：糖身两端各一道金箍，带暗边、渐变与一道竖向高光。
  for (const 向 of [-1, 1] as const) {
    const x = 中心X + 向 * (身宽 / 2 - 身高 * 0.2);
    绘图.fillStyle(色.金深, 1).fillRoundedRect(x - 3.6, 顶 + 身高 * 0.1, 7.2, 身高 * 0.8, 3.6);
    绘图
      .fillGradientStyle(色.金, 色.金, 色.金深, 色.金深, 1, 1, 1, 1)
      .fillRoundedRect(x - 2.8, 顶 + 身高 * 0.12, 4.6, 身高 * 0.76, 2.6);
    绘图
      .fillStyle(色.白, 0.6)
      .fillRoundedRect(x - 2.1, 顶 + 身高 * 0.18, 1.5, 身高 * 0.56, 0.8);
    绘图
      .fillStyle(色.白, 0.4)
      .fillCircle(x - 1.4, 顶 + 身高 * 0.2, Math.max(0.8, 身高 * 0.035));
  }
  // 顶棱高光带 + 镜面：糖面上沿被主光扫亮。
  绘图
    .fillGradientStyle(色.白, 色.白, 色.白, 色.白, 按下 ? 0.24 : 0.56, 0.34, 0, 0)
    .fillRoundedRect(左 + 身高 * 0.42, 顶 + 2.5, 身宽 * 0.44, Math.max(2, 身高 * 0.14), 3);
  绘图
    .fillStyle(色.白, 按下 ? 0.18 : 0.36)
    .fillCircle(左 + 身高 * 0.62, 顶 + 身高 * 0.26, Math.max(1.3, 身高 * 0.06));
}

/**
 * 常规按钮配方：玻璃底板与文字色按框架 `界面按钮` 的现行算法
 * （采用传入配色 + 文字色跟随底色），直接画在画笔.图形 上。
 */

export type 常规按钮变体 = "主要" | "次要" | "普通";

/** 按钮当前视觉状态；框架按钮在重绘时给出的就是这四个布尔。 */
export interface 常规按钮状态 {
  已选?: boolean;
  悬停?: boolean;
  按下?: boolean;
  可用?: boolean;
}

export interface 常规按钮选项 extends 常规按钮状态 {
  变体?: 常规按钮变体;
  /** 覆盖调色板按钮变体的个别差异（模式强调色、纯享胶囊底色等）。 */
  面板色?: string;
  边框色?: string;
  强调色?: string;
  面板透明度?: number;
  边框透明度?: number;
}

export interface 常规按钮文字选项 extends 常规按钮选项 {
  字号?: number;
  字重?: "常规" | "粗体";
  图标?: 旅行图标名称;
  图标尺寸?: number;
  图文方向?: "横排" | "竖排";
}

export function 读取常规按钮配色(变体: 常规按钮变体 = "次要"): 常规按钮配色 {
  const 调色板 = 读取霓虹调色板();
  if (变体 === "主要") return 调色板.主要按钮;
  if (变体 === "普通") return 调色板.普通按钮;
  return 调色板.次要按钮;
}

/** 按钮底色：已选/按下用强调色，其余用面板色（与框架采用传入配色的分支一致）。 */
export function 读取常规按钮底色(选项: 常规按钮选项 = {}): string {
  const 配色 = 读取常规按钮配色(选项.变体);
  const 强调色 = 选项.强调色 ?? 配色.边框;
  if (选项.已选 || 选项.按下) return 强调色;
  return 选项.面板色 ?? 配色.面板;
}

/**
 * 文字色跟随底色：框架 `获取适配文字色` 的同算法（sRGB 相对亮度取对比更高的一侧）。
 * 框架只按构造时的已选状态取一次色，悬停/按下不重算，因此这里也只依赖已选。
 */
export function 读取常规按钮文字色(选项: 常规按钮选项 = {}): string {
  const 配色 = 读取常规按钮配色(选项.变体);
  const 背景色 = (选项.已选 ?? false) ? (选项.强调色 ?? 配色.边框) : (选项.面板色 ?? 配色.面板);
  const 色值 = 解析颜色数值(背景色);
  if (是像素风格()) {
    if (像素规范.深色) {
      return 色值 === 像素规范.色.亮 || 色值 === 像素规范.色.黄 || 色值 === 像素规范.色.橙
        ? 像素色串(像素规范.色.夜)
        : 像素色串(像素规范.色.墨);
    }
    return 色值 === 像素规范.色.墨 || 色值 === 像素规范.色.暗
      ? 像素色串(像素规范.色.底)
      : 像素色串(像素规范.色.墨);
  }
  if (是立体风格()) return 颜色字符串(立体规范.界面.字);
  const 通道 = [16, 8, 0].map((位移) => {
    const sRGB = ((色值 >> 位移) & 0xff) / 255;
    return sRGB <= 0.04045 ? sRGB / 12.92 : ((sRGB + 0.055) / 1.055) ** 2.4;
  });
  const 亮度 = 0.2126 * (通道[0] ?? 0) + 0.7152 * (通道[1] ?? 0) + 0.0722 * (通道[2] ?? 0);
  const 深色对比 = (亮度 + 0.05) / 0.05;
  const 浅色对比 = 1.05 / (亮度 + 0.05);
  return 浅色对比 >= 深色对比 ? "#fff8e7" : "#241d12";
}

/** 按钮文字样式（含按底色算出的颜色），Three 侧用它测量与绘制按钮标签。 */
export function 读取常规按钮文字样式(
  选项: 常规按钮文字选项 = {},
  覆盖?: Partial<文字样式>,
): 文字样式 {
  return 派生霓虹文字样式("按钮", {
    字号: 选项.字号 ?? 16,
    ...(选项.字重 ? { 字重: 选项.字重 } : {}),
    颜色: 读取常规按钮文字色(选项),
    ...覆盖,
  });
}

/** 按钮底板：状态与配色规则集中在这里，Phaser/Three 两版画同一组像素指令。 */
export function 绘制常规按钮(
  绘图: 图形对象,
  中心X: number,
  中心Y: number,
  宽: number,
  高: number,
  选项: 常规按钮选项 = {},
): void {
  const 配色 = 读取常规按钮配色(选项.变体);
  const 按钮规格 = 读取按钮规格(选项.变体);
  const 已选 = 选项.已选 ?? false;
  const 按下 = 选项.按下 ?? false;
  const 悬停 = 选项.悬停 ?? false;
  const 填色 = 解析颜色数值(读取常规按钮底色(选项));
  const 描边色 = 解析颜色数值(选项.强调色 ?? 配色.边框);
  const 面板透明度 =
    选项.面板透明度 ??
    (按下 || 已选
      ? Math.max(按钮规格.面板透明度, 0.98)
      : 悬停
        ? Math.max(按钮规格.面板透明度, 0.97)
        : 按钮规格.面板透明度);
  const 边框透明度 =
    选项.边框透明度 ??
    (已选
      ? Math.max(按钮规格.描边透明度, 0.9)
      : 悬停
        ? Math.max(按钮规格.描边透明度, 0.8)
        : 按钮规格.描边透明度);
  绘制玻璃按钮底板(绘图, 中心X, 中心Y + (按下 ? 按钮规格.下沉 : 0), 宽, 高, {
    圆角: 按钮规格.圆角,
    描边宽: 按钮规格.描边宽,
    填色,
    边框色: 解析颜色数值(选项.边框色 ?? 配色.边框),
    强调色: 描边色,
    悬停,
    透明度: 面板透明度,
    边透明度: 边框透明度,
  });
  if (import.meta.env.GM_TEST === "1") 记录资源绘制("资源/预制体/基础/按钮/按钮配方.ts", "绘制常规按钮");
}

export interface 常规按钮图标 {
  名称: 旅行图标名称;
  中心X: number;
  中心Y: number;
  尺寸: number;
}

export interface 常规按钮内容 {
  文字项: 文字项 | null;
  图标: 常规按钮图标 | null;
}

/**
 * 按钮图文布局（与框架 `界面按钮` 的 布局图文 同算法）：图标的显示尺寸固定，
 * 竖排时图标在上、文字在下；横排时图标在左、文字在右。
 */
export function 生成常规按钮内容(
  中心X: number,
  中心Y: number,
  文案: string,
  选项: 常规按钮文字选项 = {},
  标签尺寸: { 宽: number; 高: number } = { 宽: 0, 高: 0 },
): 常规按钮内容 {
  const 按钮规格 = 读取按钮规格(选项.变体);
  const 图标尺寸 = 选项.图标尺寸 ?? 22;
  const 竖排 = 选项.图文方向 === "竖排";
  const 间距 = 按钮规格.图标间距;
  const 中心Y带下沉 = 中心Y + (选项.按下 ? 按钮规格.下沉 : 0);
  let 标签偏移X = 0;
  let 标签偏移Y = 0;
  let 图标: 常规按钮图标 | null = null;
  if (选项.图标) {
    if (竖排) {
      const 总高 = 图标尺寸 + 间距 + 标签尺寸.高;
      图标 = {
        名称: 选项.图标,
        中心X,
        中心Y: 中心Y带下沉 - 总高 / 2 + 图标尺寸 / 2,
        尺寸: 图标尺寸,
      };
      标签偏移Y = 总高 / 2 - 标签尺寸.高 / 2;
    } else {
      图标 = {
        名称: 选项.图标,
        中心X: 中心X - (标签尺寸.宽 + 间距) / 2,
        中心Y: 中心Y带下沉,
        尺寸: 图标尺寸,
      };
      标签偏移X = (图标尺寸 + 间距) / 2;
    }
  }
  const 文字项: 文字项 | null = 文案
    ? {
        文案,
        样式: 读取常规按钮文字样式(选项),
        锚点: "中中",
        x: 中心X + 标签偏移X,
        y: 中心Y带下沉 + 标签偏移Y,
      }
    : null;
  return { 文字项, 图标 };
}

/** 把程序化旅行图标按 32×32 源尺寸缩放画到按钮内（与 Phaser generateTexture 同一套指令）。 */
export function 绘制常规按钮图标(绘图: 图形对象, 图标: 常规按钮图标): void {
  绘图.save();
  绘图.translateCanvas(图标.中心X - 图标.尺寸 / 2, 图标.中心Y - 图标.尺寸 / 2);
  绘图.scaleCanvas(图标.尺寸 / 32);
  绘制旅行图标(绘图, 图标.名称);
  绘图.restore();
}

/** 常规按钮按下与松开的缩放和时长。 */
export const 常规按钮动效 = { 按下X: 0.975, 按下Y: 0.96, 按下毫秒: 65, 松开毫秒: 170 } as const;

export function 计算常规按钮按压(按下: boolean, 毫秒: number, 起始X: number, 起始Y: number) {
  const 时长 = 按下 ? 常规按钮动效.按下毫秒 : 常规按钮动效.松开毫秒;
  const t = Math.min(1, Math.max(0, 毫秒 / 时长));
  const u = t - 1;
  const 缓动 = 按下 ? 1 - (1 - t) ** 2 : 1 + 2.70158 * u ** 3 + 1.70158 * u ** 2;
  return {
    x: 起始X + ((按下 ? 常规按钮动效.按下X : 1) - 起始X) * 缓动,
    y: 起始Y + ((按下 ? 常规按钮动效.按下Y : 1) - 起始Y) * 缓动,
    完成: t === 1,
  };
}

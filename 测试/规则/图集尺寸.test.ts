import { describe, expect, test } from "bun:test";
import {
  判断九宫,
  判断纯色极简,
  合适页边,
  图集间隙,
  图集页档表,
  放入页空间,
  新建页空间,
  选择入集页,
  选择页档,
  type 页空间,
} from "../../代码/性能/图集尺寸";

/** 已用满的页：沿用到 已用高 = 边长，任何块都放不下。 */
function 满页(边: number): 页空间 {
  return { 边, 货架: [], 已用高: 边, 空闲: [] };
}

describe("图集尺寸", () => {
  test("图章页按内容放大且不超过 1024", () => {
    expect(合适页边(40, 20, 1024, 256)).toBe(256);
    expect(合适页边(900, 900, 1024, 256)).toBe(1024);
    expect(合适页边(40, 48, 512, 512)).toBe(512);
  });

  test("同样式的宽块和窄块共用九宫键", () => {
    const 窄 = 判断九宫([7, 0x123456, 1, 3, 0, 0, 80, 48], 80, 48);
    const 宽 = 判断九宫([7, 0x123456, 1, 3, 0, 0, 180, 48], 180, 48);
    expect(窄?.键).toBe(宽?.键);
    expect(窄 && 窄.边 * 2).toBeLessThan(80);
  });

  test("并排两块、渐变和太小的图不收成九宫", () => {
    expect(判断九宫([7, 1, 1, 3, 0, 0, 40, 80, 3, 50, 0, 40, 80], 90, 80)).toBeNull();
    expect(判断九宫([21, 0, 0, 0, 0, 0, 0, 0, 0, 3, 0, 0, 80, 48], 80, 48)).toBeNull();
    expect(判断九宫([7, 1, 1, 3, 0, 0, 20, 12], 20, 12)).toBeNull();
  });
});

describe("纯色极简判定", () => {
  test("单个填充矩形直接原生绘制", () => {
    expect(判断纯色极简([7, 0x123456, 1, 3, 0, 0, 80, 48])).toBe(true);
  });

  test("忽略 Phaser 构造器固定写入的 lineStyle/fillStyle 前导", () => {
    // Phaser 4.2.1 的 Graphics 构造器会先写 [6,1,0,0] 与 [7,0,0]，真实缓冲区以此开头。
    expect(判断纯色极简([6, 1, 0, 0, 7, 0, 0, 7, 0x3366ff, 1, 3, 0, 0, 60, 40])).toBe(true);
    // 真正的描边仍拒绝。
    expect(判断纯色极简([6, 2, 0xffffff, 1, 3, 0, 0, 40, 40, 9])).toBe(false);
  });

  test("至多两块矩形，可带 SAVE/RESTORE/TRANSLATE/SCALE", () => {
    expect(判断纯色极简([7, 1, 1, 3, 0, 0, 40, 80, 3, 50, 0, 40, 80])).toBe(true);
    expect(判断纯色极简([14, 16, 10, 20, 7, 1, 1, 17, 2, 2, 3, 0, 0, 40, 40, 15])).toBe(true);
  });

  test("三块矩形、渐变、描边、圆弧、三角、路径都不算极简", () => {
    expect(判断纯色极简([7, 1, 1, 3, 0, 0, 40, 40, 3, 0, 40, 40, 40, 3, 0, 80, 40, 40])).toBe(
      false,
    );
    expect(判断纯色极简([21, 0, 0, 0, 0, 0, 0, 0, 0, 3, 0, 0, 80, 48])).toBe(false);
    expect(判断纯色极简([6, 1, 0xffffff, 1, 3, 0, 0, 40, 40])).toBe(false);
    expect(判断纯色极简([0, 0, 0, 10, 0, 1, 0, 0, 3, 0, 0, 40, 40])).toBe(false);
    expect(判断纯色极简([10, 0, 0, 10, 0, 5, 10, 7, 1, 1])).toBe(false);
    expect(判断纯色极简([8])).toBe(false);
  });

  test("只有填充色或带 ROTATE 不算极简", () => {
    expect(判断纯色极简([7, 1, 1])).toBe(false);
    expect(判断纯色极简([7, 1, 1, 18, 1, 3, 0, 0, 40, 40])).toBe(false);
    expect(判断纯色极简([])).toBe(false);
  });
});

describe("页档选择", () => {
  test("按块尺寸选最小可放页档", () => {
    expect(选择页档(40, 20)?.边).toBe(256);
    expect(选择页档(300, 200)?.边).toBe(512);
    expect(选择页档(800, 600)?.边).toBe(1024);
  });

  test("单帧上限与页尺寸分开：1022 可入 1024 页，1023 超页", () => {
    expect(选择页档(1022, 10)?.边).toBe(1024);
    expect(选择页档(1023, 10)).toBeNull();
    expect(选择页档(0, 10)).toBeNull();
  });
});

describe("页分配选择", () => {
  test("空页池先开小页", () => {
    const 结果 = 选择入集页([], 40, 40);
    expect(结果.类型).toBe("新页");
    if (结果.类型 === "新页") {
      expect(结果.空间.边).toBe(256);
      expect(结果.位).toEqual({ x: 0, y: 0 });
      expect(结果.页序).toBe(0);
    }
  });

  test("现有页有空位优先复用", () => {
    const 结果 = 选择入集页([{ 边: 256, 空间: 新建页空间(256) }], 40, 40);
    expect(结果.类型).toBe("现有页");
    if (结果.类型 === "现有页") expect(结果.页序).toBe(0);
  });

  test("档内页数未满就开新页，页满才升档", () => {
    const 两满 = [
      { 边: 256, 空间: 满页(256) },
      { 边: 256, 空间: 满页(256) },
    ];
    const 升档 = 选择入集页(两满, 40, 40);
    expect(升档.类型).toBe("新页");
    if (升档.类型 === "新页") expect(升档.空间.边).toBe(512);

    const 一满 = [{ 边: 256, 空间: 满页(256) }];
    const 同档新页 = 选择入集页(一满, 40, 40);
    expect(同档新页.类型).toBe("新页");
    if (同档新页.类型 === "新页") expect(同档新页.空间.边).toBe(256);
  });

  test("所有页档都满时返回页满", () => {
    const 满 = [...图集页档表].flatMap((档) =>
      Array.from({ length: 档.最多页 }, () => ({ 边: 档.边, 空间: 满页(档.边) })),
    );
    expect(选择入集页(满, 40, 40)).toEqual({ 类型: "不入集", 原因: "页满" });
  });

  test("超过单帧上限返回超页", () => {
    expect(选择入集页([], 1500, 10)).toEqual({ 类型: "不入集", 原因: "超页" });
  });

  test("大块只开 1024 页且该档只允许一页", () => {
    const 首块 = 选择入集页([], 900, 900);
    expect(首块.类型).toBe("新页");
    if (首块.类型 !== "新页") return;
    expect(首块.空间.边).toBe(1024);
    const 次块 = 选择入集页([{ 边: 1024, 空间: 首块.空间 }], 900, 900);
    expect(次块).toEqual({ 类型: "不入集", 原因: "页满" });
  });
});

describe("页空间货架分配", () => {
  test("同高度的小块排在同一行", () => {
    const 首 = 放入页空间(新建页空间(256), 40, 40);
    expect(首?.位).toEqual({ x: 0, y: 0 });
    if (!首) return;
    const 次 = 放入页空间(首.空间, 40, 40);
    expect(次?.位).toEqual({ x: 40 + 图集间隙, y: 0 });
  });

  test("空闲块大于请求块两倍半时不复用", () => {
    const 空间: 页空间 = {
      边: 256,
      货架: [],
      已用高: 0,
      空闲: [{ x: 100, y: 100, 宽: 200, 高: 200 }],
    };
    const 结果 = 放入页空间(空间, 10, 10);
    // 空闲块太大时走新货架，空闲表保留原块。
    expect(结果?.位).toEqual({ x: 0, y: 0 });
    expect(结果?.空间.空闲).toHaveLength(1);
  });
});

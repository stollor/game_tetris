import { expect, test } from "bun:test";
import { 应用装备音效 } from "../代码/框架配置/旅行音效";
import { 基础音效库, 消行谱, 连击谱, 音效库 } from "../代码/框架配置/音效";

test("装备映射使用试听相同谱，动态消行与连击保留参数，取消或未知装备回退", () => {
  const 移动 = 基础音效库.find((项) => 项.名称 === "移动");
  const 试听 = 音效库.find((项) => 项.id === "旅行.成都熊猫.移动");
  if (移动?.类型 !== "合成" || 试听?.类型 !== "合成") throw Error("夹具缺失");
  expect(应用装备音效(移动.谱, "成都熊猫")).toEqual(试听.谱);
  expect(应用装备音效(移动.谱, "成都熊猫")).not.toEqual(移动.谱);
  expect(应用装备音效(移动.谱, "")).toBe(移动.谱);
  expect(应用装备音效(移动.谱, "未知")).toBe(移动.谱);
  expect(应用装备音效(消行谱(1), "成都熊猫")).not.toEqual(应用装备音效(消行谱(4), "成都熊猫"));
  expect(应用装备音效(连击谱(2), "成都熊猫")).not.toEqual(应用装备音效(连击谱(5), "成都熊猫"));
});

import { type 再消一行状态, 移动方块 } from "../../代码/玩法/再消一行";

/** 只准备棋盘，不执行硬降，浏览器验收仍走玩家输入的真实事件链。 */
export function 准备消行样本(状态: 再消一行状态, 行数: 1 | 4, 保留堆叠 = false): void {
  if (行数 === 4) {
    状态.当前方块.类型 = "I";
    状态.最后旋转 = false;
    状态.当前方块.格子 = [-1, 0, 1, 2].map((行) => ({ 列2: 8, 行2: 行 * 2 }));
  }
  for (const 行 of 状态.棋盘.slice(-行数)) {
    for (let 列 = 0; 列 < 行.length; 列++)
      行[列] = 行数 === 4 ? (列 === 4 ? null : "J") : 列 < 3 || 列 > 6 ? "J" : null;
  }
  const 保留行 = 状态.棋盘.at(-5);
  if (保留堆叠 && 保留行) 保留行[0] = "L";
}

/** 修复前的具体失败局面：T贴右墙，下方邻块阻挡错误的右旋占格。 */
export function 准备贴墙旋转样本(状态: 再消一行状态): void {
  for (let i = 0; i < 9; i++) 移动方块(状态, 0, 1);
  while (移动方块(状态, 1)) {}
  const 行 = 状态.棋盘[11];
  if (行) 行[8] = "O";
}

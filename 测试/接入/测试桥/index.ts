/**
 * 调试桥：启动层统一挂 window.__three版__ 与 window.__再消一行测试__。
 * 对局页只实现 页面实例 上的可选读取方法/测试控制/读取界面，桥负责转发并拼装
 * 场景栈、循环、渲染、合批、音频与内存统计；浏览器验收脚本只依赖这里的读取接口。
 * __再消一行测试__ 保持稳定的项目内验收接口名，底层仅由 Three 提供。
 */

export interface 调试桥选项 {
  性能: 游戏性能接口;
  登记提交(提交: () => void): void;
  请求渲染(): void;
  导航: 导航服务;
  渲染: 渲染编排;
  合批: 图元合批;
  循环: 游戏循环;
  服务: 应用服务;
  栈: 场景栈<页面上下文>;
  读取页面编号(): 页面编号;
  读取当前页(): 页面实例 | undefined;
  /** 对局页实例：覆盖页在栈顶时仍能读阶段/测试控制。 */
  读取对局页?(): 页面实例 | undefined;
  读取文字统计?: () => { 小: unknown; 中: unknown; 大: unknown };
  /** 图元合批统计（新绘制层）。 */
  读取图元统计?: () => 图元合批统计;
  /** 资源层纹理统计。 */
  读取纹理统计?: () => 资源统计;
  /** 共享文字服务的文字图集统计。 */
  读取文字图集统计?: () => unknown;
  /** P3 图层缓存统计（重建/跳过/失效原因/各层耗时）。 */
  读取图层缓存统计?: () => unknown;
  /** P3 背景调度统计（档位/间隔/绘制次数）。 */
  读取背景调度统计?: () => unknown;
  停止(): void;
}

/** 旧验收脚本用 操作(名称) 驱动键盘；这里转成真实 KeyboardEvent，走对局页自己的按键监听。 */
const 操作按键表: Record<string, KeyboardEventInit> = {
  左移: { code: "ArrowLeft", key: "ArrowLeft" },
  右移: { code: "ArrowRight", key: "ArrowRight" },
  旋转: { code: "ArrowUp", key: "ArrowUp" },
  软降: { code: "ArrowDown", key: "ArrowDown" },
  硬降: { code: "Space", key: " " },
  暂存: { code: "KeyC", key: "c" },
  暂停: { code: "KeyP", key: "p" },
};

export function 挂载调试桥(选项: 调试桥选项): () => void {
  const 读取当前页 = () => 选项.读取当前页();
  const 读取对局页 = () => 选项.读取对局页?.();

  const 读取状态 = () => {
    const 顶 = 读取当前页();
    const 对局 = 读取对局页();
    const 对局快照 = 对局?.读取快照?.();
    const 顶快照 = 顶 && 顶 !== 对局 ? 顶.读取快照?.() : undefined;
    return {
      ...(对局快照 && typeof 对局快照 === "object" ? 对局快照 : {}),
      ...(顶快照 && typeof 顶快照 === "object" ? 顶快照 : {}),
      页面: 选项.读取页面编号(),
      场景栈: 选项.栈.读取栈().map((项) => 项.名称),
    };
  };

  const 读取统计 = () => {
    const 页 = 读取对局页() ?? 读取当前页();
    const 解析 = 读取有效游戏主题(选项.服务.设置.读取());
    const 槽 = (编号: string) => 解析.槽位.find((项) => 项.槽位.编号 === 编号)?.资源.值 ?? null;
    return {
      循环: 选项.循环.读取统计(),
      渲染: 选项.渲染.读取统计(),
      合批: 选项.合批.读取统计(),
      图元: 选项.读取图元统计?.() ?? null,
      纹理: 选项.读取纹理统计?.() ?? null,
      文字: 选项.读取文字统计?.() ?? null,
      文字图集: 选项.读取文字图集统计?.() ?? null,
      图层缓存: 选项.读取图层缓存统计?.() ?? null,
      背景调度: 选项.读取背景调度统计?.() ?? null,
      内存: 选项.服务.内存(),
      画布: {
        宽: 选项.渲染.画布.width,
        高: 选项.渲染.画布.height,
        视口宽: 选项.渲染.画布.dataset.视口宽 ?? "",
        视口高: 选项.渲染.画布.dataset.视口高 ?? "",
      },
      设备像素比: window.devicePixelRatio,
      页面: 选项.读取页面编号(),
      场景栈: 选项.栈.读取栈().map((项) => 项.名称),
      对局统计: 页?.读取对局统计?.() ?? { 操作次数: 0, 落块数: 0, 消行次数: 0 },
      操作记录: 页?.读取操作记录?.() ?? [],
      主题: 选项.服务.主题.读取().名称,
      棋盘表现: 槽("棋盘表现"),
      仪表表现: 槽("仪表表现"),
      透视棋盘: 读取透视棋盘占用(),
      省电: 选项.服务.设置.读取().省电模式,
      音频: 选项.服务.音频.读取状态(),
      金币: 选项.服务.金币.读取().金币,
    };
  };

  const 测试控制 = () => 读取对局页()?.测试 ?? 读取当前页()?.测试;

  const 读取界面 = (): 界面快照 => 读取当前页()?.读取界面?.() ?? { 按钮: [] };

  const 派发键 = (类型: KeyboardEventInit): void => {
    window.dispatchEvent(new KeyboardEvent("keydown", { ...类型, bubbles: true }));
    window.dispatchEvent(new KeyboardEvent("keyup", { ...类型, bubbles: true }));
  };

  const 旧接口 = {
    开始绘制采样: () => 选项.渲染.开始绘制采样(),
    结束绘制采样: () => 选项.渲染.结束绘制采样(),
    读取状态,
    读取原始状态: () => 读取对局页()?.读取原始状态?.() ?? 读取当前页()?.读取原始状态?.() ?? null,
    读取统计,
    读取界面,
    读取设置: () => 选项.服务.设置.读取(),
    更新设置: (变化: Parameters<应用服务["设置"]["更新"]>[0]) => 选项.服务.设置.更新(变化),
    读取音频: () => 选项.服务.音频.读取状态(),
    增加金币: (数量: number) => 选项.服务.金币.增加(数量),
    操作: (名称: string) => {
      const 键 = 操作按键表[名称];
      if (键) {
        派发键(键);
        return;
      }
      if (名称 === "重新开始") 派发键({ code: "KeyR", key: "r" });
    },
    停止: () => 选项.停止(),
  };

  const 对局桥 = {
    读取状态,
    读取界面,
    读取音频: () => 选项.服务.音频.读取状态(),
    设置序列: (序列: readonly string[]) => {
      const 控制 = 测试控制();
      if (控制?.设置序列) {
        控制.设置序列(序列);
        return;
      }
      for (const 块 of 序列) if (操作按键表[块]) 派发键(操作按键表[块]);
    },
    准备单行消除: () => 测试控制()?.准备单行消除?.(),
    准备四行消除: (继续连击?: boolean, 保留堆叠?: boolean) =>
      测试控制()?.准备四行消除?.(继续连击, 保留堆叠),
    读取特效: () => 测试控制()?.读取特效?.() ?? null,
    准备目标达成: () => 测试控制()?.准备目标达成?.(),
    硬降: () => {
      const 控制 = 测试控制();
      if (控制?.硬降) 控制.硬降();
      else 派发键({ code: "Space", key: " " });
    },
    设置暂停: (暂停: boolean) => 测试控制()?.设置暂停?.(暂停),
    结束当前对局: () => 测试控制()?.结束当前对局?.(),
    准备结算: (完赛?: boolean) => 测试控制()?.准备结算?.(完赛),
    进入素材场景: (场景: string, 宽?: number, 高?: number, 皮肤?: string) => {
      if (皮肤 && 宽 && 高) 应用素材皮肤(皮肤, 宽, 高);
      else if (宽 && 高) 更新游戏设置({ 屏幕适配: 高 > 宽 * 1.05 ? "手机竖屏" : "电脑横屏" });
      const 页面 = ["菜单", "设置", "成就", "排行榜", "商店"] as const;
      if ((页面 as readonly string[]).includes(场景)) {
        选项.导航.进入(场景 as (typeof 页面)[number]);
        选项.请求渲染();
        return;
      }
      if (场景 === "模式选择") {
        选项.导航.进入("模式选择");
        选项.请求渲染();
        return;
      }
      if (场景 === "对局" || 场景 === "结算成功" || 场景 === "结算失败") {
        选项.导航.进入("对局", { 模式: "冲刺", 跳过入场: true });
        const 控制 = 测试控制();
        控制?.标记不写存档();
        if (场景 === "对局") 控制?.摆好素材画面();
        else 控制?.准备结算(场景 === "结算成功");
        选项.请求渲染();
        return;
      }
      throw new Error(
        `未知素材场景：${场景}。可以填：主界面、模式选择、对局、结算成功、结算失败、设置、成就、排行榜、商店`,
      );
    },
    开始素材演示: (参数: {
      模式: 游戏模式;
      皮肤: string;
      目标: "成功" | "失败";
      秒数: number;
      宽: number;
      高: number;
    }) => {
      应用素材皮肤(参数.皮肤, 参数.宽, 参数.高);
      选项.导航.进入("对局", { 模式: 参数.模式, 入场演出: true });
      测试控制()?.开始素材演示({ 目标: 参数.目标, 秒数: 参数.秒数 });
      选项.请求渲染();
    },
    读取素材演示: () => ({
      场景: 选项.栈.读取栈().at(-1)?.名称 ?? 选项.读取页面编号(),
      ...素材演示状态,
    }),
    准备倒计时: (剩余毫秒: number) => 测试控制()?.准备倒计时?.(剩余毫秒),
    准备贴墙旋转: () => 测试控制()?.准备贴墙旋转?.(),
  };

  const 桥 = 创建测试桥接({
    读取主题: () => {
      const 设置 = 选项.服务.设置.读取();
      // 单独的预览配色覆写不能冒充正式主题提交帧。
      if (选项.服务.主题.读取().名称 !== (设置.旅行样式 ?? 设置.样式)) return;
      const 主题 = 读取有效游戏主题(设置);
      return {
        项目默认: 项目默认主题,
        选择: 生成主题选择(主题.主题 ?? 项目默认主题, 主题.选项),
        槽位: Object.fromEntries(主题.槽位.map((项) => [项.槽位.编号, 项.资源.编号])),
      };
    },
    性能: 选项.性能,
    请求渲染: 选项.请求渲染,
    读取快照: () => {
      const 页名 = 选项.栈.读取栈().at(-1)?.名称 ?? 选项.读取页面编号();
      const 界面 = 读取界面();
      const 交互 = 界面.按钮.map((项, 编号) => ({
        id: 页名 + "/" + 编号 + "/" + 项.名称,
        name: 项.名称,
        label: 项.名称,
        type: "button",
        sceneId: 页名,
        visible: true,
        enabled: 项.可用 !== false,
        bounds: { x: 项.左, y: 项.上, width: 项.宽, height: 项.高 },
      }));
      return {
        game: "再消一行",
        sceneId: 页名,
        sceneName: 页名,
        width: 选项.渲染.读取逻辑尺寸().宽,
        height: 选项.渲染.读取逻辑尺寸().高,
        state: 读取状态(),
        texts: [...(界面.文字 ?? [])],
        interactives: 交互,
        nodes: [
          ...交互.map((项) => ({
            id: 项.id,
            name: 项.name,
            type: "按钮",
            text: 项.label,
            visible: 项.visible,
            active: 项.enabled,
            bounds: 项.bounds,
            childCount: 0,
          })),
          ...(界面.文字 ?? []).map((文案, 编号) => ({
            id: 页名 + "/文字/" + 编号,
            name: 文案,
            type: "文字",
            text: 文案,
            visible: true,
            active: false,
            bounds: null,
            childCount: 0,
          })),
        ],
        diagnostics: {
          errors: [],
          warnings: [],
        },
      };
    },
  });
  选项.登记提交(桥.提交帧);
  桥.挂载();
  const 压力 = 创建资源压力(选项.渲染);
  const 控制 = 注册游戏测试控制({
    项目: "再消一行",
    性能: 选项.性能,
    状态: () => ({
      页面: 选项.读取页面编号(),
      当前页: 选项.栈.读取栈().at(-1)?.名称 ?? "",
      金币: 选项.服务.金币.读取().金币,
    }),
    命令: [
      ...(["菜单", "模式选择", "设置", "成就", "排行榜", "商店"] as const).map((页面) => ({
        编号: "导航." + 页面,
        名称: 页面,
        说明: "进入真实页面",
        分组: "导航",
        影响存档: false,
        执行: () => {
          选项.导航.进入(页面);
          选项.请求渲染();
        },
      })),
      {
        编号: "对局.开始",
        名称: "开始马拉松",
        说明: "开始真实对局，结算会保存纪录和奖励",
        分组: "对局",
        影响存档: true,
        执行: () => 选项.导航.进入("对局", { 模式: "马拉松" }),
      },
      {
        编号: "对局.四行",
        名称: "准备四行",
        说明: "设置当前局测试棋盘，后续落块会保存进度",
        分组: "对局",
        影响存档: true,
        执行: () => {
          测试控制()?.准备四行消除();
          选项.请求渲染();
        },
      },
      {
        编号: "压力.纹理",
        名称: "纹理压力",
        说明: "分配或释放真实256像素GPU纹理，不写存档",
        分组: "资源压力",
        影响存档: false,
        参数: [
          {
            键: "数量",
            名称: "纹理数量",
            说明: "256像素GPU纹理数量",
            类型: "数值",
            最小: 0,
            最大: 64,
            步长: 1,
          },
        ],
        执行: (参数) => {
          压力.设置(Number(参数.数量));
          选项.请求渲染();
        },
      },
    ],
  });
  if (是否本机或局域网(location.hostname)) Object.assign(旧接口, { 设置资源压力: 压力.设置 });
  // 私有兼容接口只转发现有页面与资源，不维护另一份状态。

  Object.assign(window, { __three版__: 旧接口, __再消一行测试__: 对局桥 });
  return () => {
    选项.登记提交(() => {});
    控制.断开();
    压力.清理();
    桥.销毁();
    Reflect.deleteProperty(window, "__three版__");
    Reflect.deleteProperty(window, "__再消一行测试__");
  };
}

/**
 * 调试桥：启动层统一挂 window.__three版__ 与 window.__再消一行测试__。
 * 对局页只实现 页面实例 上的可选读取方法/测试控制/读取界面，桥负责转发并拼装
 * 场景栈、循环、渲染、合批、音频与内存统计；浏览器验收脚本只依赖这里的读取接口。
 * __再消一行测试__ 保持稳定的项目内验收接口名，底层仅由 Three 提供。
 */

export interface 调试桥选项 {
  性能: 游戏性能接口;
  登记提交(提交: () => void): void;
  请求渲染(): void;
  导航: 导航服务;
  渲染: 渲染编排;
  合批: 图元合批;
  循环: 游戏循环;
  服务: 应用服务;
  栈: 场景栈<页面上下文>;
  读取页面编号(): 页面编号;
  读取当前页(): 页面实例 | undefined;
  /** 跨页开合动画是否在播放：过渡期间点击会被框架丢弃，验收脚本据此先等位。 */
  读取界面开合中?(): boolean;
  /** 对局页实例：覆盖页在栈顶时仍能读阶段/测试控制。 */
  读取对局页?(): 页面实例 | undefined;
  读取文字统计?: () => { 小: unknown; 中: unknown; 大: unknown };
  /** 图元合批统计（新绘制层）。 */
  读取图元统计?: () => 图元合批统计;
  /** 资源层纹理统计。 */
  读取纹理统计?: () => 资源统计;
  /** 共享文字服务的文字图集统计。 */
  读取文字图集统计?: () => unknown;
  /** 共享文字页画布快照（调试/验收出图集截图）。 */
  读取文字图集快照?: () => unknown;
  /** P3 图层缓存统计（重建/跳过/失效原因/各层耗时）。 */
  读取图层缓存统计?: () => unknown;
  /** P3 背景调度统计（档位/间隔/绘制次数）。 */
  读取背景调度统计?: () => unknown;
  /** 压测采样（帧节奏 + 资源账本时间线）；只在 GM_TEST 下由启动层传入。 */
  压测?: 压测采样;
  停止(): void;
}

/**
 * 素材目录里声明的一档「皮肤」：这一局不换局，按宣发节奏依次切全部主题，
 * 用来录「同一局连续展示五套主题」的实机视频。名字与 配置/素材采集.json 的 皮肤 一致。
 */
export const 全主题巡演 = "全主题巡演";

/**
 * 宣发片节奏：前 3 秒快闪五套（每套 0.6 秒），随后每套各停留 3 秒；
 * 节奏走完停在最后一档，用 0.1 秒的落子间隔把剩下的行数打完。全程同一局，状态不重置。
 */
export const 宣发节奏: readonly { 主题: 主题名; 秒数: number }[] = [
  ...主题列表.map((主题) => ({ 主题, 秒数: 0.6 })),
  ...主题列表.map((主题) => ({ 主题, 秒数: 3 })),
];

/**
 * 素材录制换主题：素材脚本不碰存档实现，走金币服务的正式购买路径临时解锁，
 * 再切到该主题；未知主题直接报错，避免录出一套不存在的画面。
 */
function 应用素材主题(选项: 调试桥选项, 主题: string): void {
  if (!是主题名(主题)) throw new Error(`未知主题：${主题}`);
  const 金币 = 选项.服务.金币;
  if (主题 !== 默认主题 && !金币.读取().已购主题.includes(主题)) {
    金币.增加(主题价格[主题]);
    金币.购买主题(主题);
  }
  更新游戏设置({ 主题选择: 主题 });
}


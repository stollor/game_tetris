export function 挂载调试桥(选项: 调试桥选项): () => void {
  const 读取当前页 = () => 选项.读取当前页();
  const 读取对局页 = () => 选项.读取对局页?.();

  const 读取状态 = () => {
    const 顶 = 读取当前页();
    const 对局 = 读取对局页();
    const 对局快照 = 对局?.读取快照?.();
    const 顶快照 = 顶 && 顶 !== 对局 ? 顶.读取快照?.() : undefined;
    return {
      ...(对局快照 && typeof 对局快照 === "object" ? 对局快照 : {}),
      ...(顶快照 && typeof 顶快照 === "object" ? 顶快照 : {}),
      页面: 选项.读取页面编号(),
      场景栈: 选项.栈.读取栈().map((项) => 项.名称),
    };
  };

  const 读取统计 = () => {
    const 页 = 读取对局页() ?? 读取当前页();
    const 解析 = 读取有效游戏主题(选项.服务.设置.读取());
    const 槽 = (编号: string) => 解析.槽位.find((项) => 项.槽位.编号 === 编号)?.资源.值 ?? null;
    return {
      循环: 选项.循环.读取统计(),
      渲染: 选项.渲染.读取统计(),
      合批: 选项.合批.读取统计(),
      图元: 选项.读取图元统计?.() ?? null,
      纹理: 选项.读取纹理统计?.() ?? null,
      文字: 选项.读取文字统计?.() ?? null,
      文字图集: 选项.读取文字图集统计?.() ?? null,
      图层缓存: 选项.读取图层缓存统计?.() ?? null,
      背景调度: 选项.读取背景调度统计?.() ?? null,
      内存: 选项.服务.内存(),
      画布: {
        宽: 选项.渲染.画布.width,
        高: 选项.渲染.画布.height,
        视口宽: 选项.渲染.画布.dataset.视口宽 ?? "",
        视口高: 选项.渲染.画布.dataset.视口高 ?? "",
      },
      设备像素比: window.devicePixelRatio,
      页面: 选项.读取页面编号(),
      场景栈: 选项.栈.读取栈().map((项) => 项.名称),
      对局统计: 页?.读取对局统计?.() ?? { 操作次数: 0, 落块数: 0, 消行次数: 0 },
      操作记录: 页?.读取操作记录?.() ?? [],
      主题: 选项.服务.主题.读取().名称,
      棋盘表现: 槽("棋盘表现"),
      仪表表现: 槽("仪表表现"),
      透视棋盘: 读取透视棋盘占用(),
      省电: 选项.服务.设置.读取().省电模式,
      音频: 选项.服务.音频.读取状态(),
      金币: 选项.服务.金币.读取().金币,
    };
  };

  const 测试控制 = () => 读取对局页()?.测试 ?? 读取当前页()?.测试;

  /** 宣发录像会话：MediaRecorder 与已收集分片；同一时间只允许一段。 */
  let 素材录像: { 录制: MediaRecorder; 分片: Blob[] } | null = null;

  /**
   * 素材场景切换是异步的：导航刚发出时测试控制还挂在旧页上，这时摆画面等于空调用。
   * 等对局页真正进场（页面编号变成「对局」）后再摆，截图和录像才都有真实对局画面。
   */
  const 安排素材画面 = (场景: "对局" | "结算成功" | "结算失败") => {
    const 截止 = performance.now() + 10000;
    const 尝试 = () => {
      if (performance.now() > 截止) return;
      if (选项.读取页面编号() !== "对局") {
        requestAnimationFrame(尝试);
        return;
      }
      const 控制 = 测试控制();
      if (!控制) {
        requestAnimationFrame(尝试);
        return;
      }
      控制.标记不写存档();
      if (场景 === "对局") 控制.摆好素材画面();
      else 控制.准备结算(场景 === "结算成功");
      选项.请求渲染();
    };
    requestAnimationFrame(尝试);
  };

  const 读取界面 = (): 界面快照 => 读取当前页()?.读取界面?.() ?? { 按钮: [] };

  const 派发键 = (类型: KeyboardEventInit): void => {
    window.dispatchEvent(new KeyboardEvent("keydown", { ...类型, bubbles: true }));
    window.dispatchEvent(new KeyboardEvent("keyup", { ...类型, bubbles: true }));
  };

  const 旧接口 = {
    开始绘制采样: () => 选项.渲染.开始绘制采样(),
    结束绘制采样: () => 选项.渲染.结束绘制采样(),
    读取状态,
    读取原始状态: () => 读取对局页()?.读取原始状态?.() ?? 读取当前页()?.读取原始状态?.() ?? null,
    读取统计,
    读取文字图集快照: () => 选项.读取文字图集快照?.() ?? null,
    读取界面,
    读取界面开合中: () => 选项.读取界面开合中?.() ?? false,
    读取设置: () => 选项.服务.设置.读取(),
    更新设置: (变化: Parameters<应用服务["设置"]["更新"]>[0]) => 选项.服务.设置.更新(变化),
    读取音频: () => 选项.服务.音频.读取状态(),
    增加金币: (数量: number) => 选项.服务.金币.增加(数量),
    压测: 选项.压测
      ? {
          重置: () => 选项.压测?.重置(),
          读取: () => 选项.压测?.读取() ?? null,
          读取计数: () => 选项.压测?.读取计数() ?? {},
        }
      : undefined,
    操作: (名称: string) => {
      const 键 = 操作按键表[名称];
      if (键) {
        派发键(键);
        return;
      }
      if (名称 === "重新开始") 派发键({ code: "KeyR", key: "r" });
    },
    停止: () => 选项.停止(),
  };

  const 对局桥 = {
    读取状态,
    读取界面,
    读取音频: () => 选项.服务.音频.读取状态(),
    设置序列: (序列: readonly string[]) => {
      const 控制 = 测试控制();
      if (控制?.设置序列) {
        控制.设置序列(序列);
        return;
      }
      for (const 块 of 序列) if (操作按键表[块]) 派发键(操作按键表[块]);
    },
    准备单行消除: () => 测试控制()?.准备单行消除?.(),
    准备四行消除: (继续连击?: boolean, 保留堆叠?: boolean) =>
      测试控制()?.准备四行消除?.(继续连击, 保留堆叠),
    读取特效: () => 测试控制()?.读取特效?.() ?? null,
    准备目标达成: () => 测试控制()?.准备目标达成?.(),
    硬降: () => {
      const 控制 = 测试控制();
      if (控制?.硬降) 控制.硬降();
      else 派发键({ code: "Space", key: " " });
    },
    设置暂停: (暂停: boolean) => 测试控制()?.设置暂停?.(暂停),
    结束当前对局: () => 测试控制()?.结束当前对局?.(),
    准备结算: (完赛?: boolean) => 测试控制()?.准备结算?.(完赛),
    /** 压测快进：构造马拉松后期（消行/等级/分数/堆叠），不写存档。 */
    快进后期: (选项: { 消行数?: number; 分数?: number; 最长连击?: number; 堆叠行?: number }) =>
      测试控制()?.快进后期?.(选项),
    /** 压测自动对战：按间隔自动落子，直到 停止自动对战。 */
    开始自动对战: (选项: { 间隔秒: number }) => 测试控制()?.开始自动对战?.(选项),
    停止自动对战: () => 测试控制()?.停止自动对战?.(),
    进入素材场景: (场景: string, 宽?: number, 高?: number, 主题?: string) => {
      if (主题) 应用素材主题(选项, 主题);
      if (宽 && 高) 更新游戏设置({ 屏幕适配: 高 > 宽 * 1.05 ? "手机竖屏" : "电脑横屏" });
      // 素材目录用「主界面」叫主页，页面编号叫「菜单」；其余单页场景同名直通。
      const 场景页: Record<string, 页面编号> = {
        主界面: "菜单",
        菜单: "菜单",
        设置: "设置",
        成就: "成就",
        排行榜: "排行榜",
        商店: "商店",
      };
      const 页面 = 场景页[场景];
      if (页面) {
        选项.导航.进入(页面);
        选项.请求渲染();
        return;
      }
      if (场景 === "模式选择") {
        选项.导航.进入("模式选择");
        选项.请求渲染();
        return;
      }
      if (场景 === "对局" || 场景 === "结算成功" || 场景 === "结算失败") {
        选项.导航.进入("对局", { 模式: "冲刺", 跳过入场: true });
        安排素材画面(场景);
        选项.请求渲染();
        return;
      }
      throw new Error(
        `未知素材场景：${场景}。可以填：主界面、模式选择、对局、结算成功、结算失败、设置、成就、排行榜、商店`,
      );
    },
    开始素材演示: (参数: {
      模式: 游戏模式;
      皮肤: string;
      目标: "成功" | "失败";
      秒数: number;
      宽: number;
      高: number;
    }) => {
      const 巡演 = 参数.皮肤 === 全主题巡演;
      if (巡演) 应用素材主题(选项, 默认主题);
      else 应用素材主题(选项, 参数.皮肤);
      更新游戏设置({ 屏幕适配: 参数.高 > 参数.宽 * 1.05 ? "手机竖屏" : "电脑横屏" });
      选项.导航.进入("对局", { 模式: 参数.模式, 入场演出: true });
      测试控制()?.开始素材演示({
        目标: 参数.目标,
        秒数: 参数.秒数,
        主题节奏: 巡演 ? 宣发节奏 : undefined,
        收尾间隔秒: 0.1,
      });
      选项.请求渲染();
    },
    读取素材演示: () => ({
      场景: 选项.栈.读取栈().at(-1)?.名称 ?? 选项.读取页面编号(),
      ...素材演示状态,
    }),
    /**
     * 宣发录像：画布画面 + 游戏音频合成一条流交给 MediaRecorder，音画同源天然同步。
     * 停止后回 base64 webm；录制脚本落盘后再用 ffmpeg 转 H.264/AAC 的 mp4。
     * 音频走音频服务的录音分流，音乐与音效照常出声，不静音、不改设置。
     */
    开始素材录像: (帧率 = 30) => {
      if (素材录像) return false;
      const 视频轨 = 选项.渲染.画布.captureStream(帧率).getVideoTracks();
      const 音频流 = 选项.服务.音频.读取录音流();
      const 流 = new MediaStream([...视频轨, ...(音频流?.getAudioTracks() ?? [])]);
      const 录制 = new MediaRecorder(流, {
        mimeType: MediaRecorder.isTypeSupported("video/webm;codecs=vp9,opus")
          ? "video/webm;codecs=vp9,opus"
          : "video/webm",
        videoBitsPerSecond: 12_000_000,
        audioBitsPerSecond: 160_000,
      });
      const 分片: Blob[] = [];
      录制.ondataavailable = (事件) => {
        if (事件.data.size > 0) 分片.push(事件.data);
      };
      录制.start(250);
      素材录像 = { 录制, 分片 };
      return true;
    },
    停止素材录像: () =>
      new Promise<string>((完成) => {
        const 当前 = 素材录像;
        if (!当前) {
          完成("");
          return;
        }
        素材录像 = null;
        当前.录制.onstop = () => {
          const 读 = new FileReader();
          读.onload = () => 完成(String(读.result ?? ""));
          读.onerror = () => 完成("");
          读.readAsDataURL(new Blob(当前.分片, { type: "video/webm" }));
        };
        当前.录制.stop();
      }),
    /**
     * 素材采集的「场景就绪」判定：素材目录用「主界面」，页面编号叫「菜单」；
     * 结算场景落在浮层「结算」。GM 有这个钩子就不再按 sceneId 硬等 20 秒。
     */
    等待场景: async (场景: string, 毫秒?: number) => {
      const 目标页 =
        场景 === "主界面" ? "菜单" : 场景 === "结算成功" || 场景 === "结算失败" ? "结算" : 场景;
      const 截止 = performance.now() + 8000;
      while (performance.now() < 截止 && 选项.读取页面编号() !== 目标页)
        await new Promise((完成) => setTimeout(完成, 50));
      if (毫秒) await new Promise((完成) => setTimeout(完成, Math.min(毫秒, 400)));
    },
    准备倒计时: (剩余毫秒: number) => 测试控制()?.准备倒计时?.(剩余毫秒),
    准备贴墙旋转: () => 测试控制()?.准备贴墙旋转?.(),
  };

  const 桥 = 创建测试桥接({
    读取主题: () => {
      const 设置 = 选项.服务.设置.读取();
      // 单独的预览配色覆写不能冒充正式主题提交帧。
      if (选项.服务.主题.读取().名称 !== 设置.样式) return;
      const 主题 = 读取有效游戏主题(设置);
      return {
        项目默认: 项目默认主题,
        选择: 生成主题选择(主题.主题 ?? 项目默认主题, 主题.选项),
        槽位: Object.fromEntries(主题.槽位.map((项) => [项.槽位.编号, 项.资源.编号])),
      };
    },
    性能: 选项.性能,
    请求渲染: 选项.请求渲染,
    读取快照: () => {
      const 页名 = 选项.栈.读取栈().at(-1)?.名称 ?? 选项.读取页面编号();
      const 界面 = 读取界面();
      const 交互 = 界面.按钮.map((项, 编号) => ({
        id: 页名 + "/" + 编号 + "/" + 项.名称,
        name: 项.名称,
        label: 项.名称,
        type: "button",
        sceneId: 页名,
        visible: true,
        enabled: 项.可用 !== false,
        bounds: { x: 项.左, y: 项.上, width: 项.宽, height: 项.高 },
      }));
      return {
        game: "再消一行",
        sceneId: 页名,
        sceneName: 页名,
        width: 选项.渲染.读取逻辑尺寸().宽,
        height: 选项.渲染.读取逻辑尺寸().高,
        state: 读取状态(),
        texts: [...(界面.文字 ?? [])],
        interactives: 交互,
        nodes: [
          ...交互.map((项) => ({
            id: 项.id,
            name: 项.name,
            type: "按钮",
            text: 项.label,
            visible: 项.visible,
            active: 项.enabled,
            bounds: 项.bounds,
            childCount: 0,
          })),
          ...(界面.文字 ?? []).map((文案, 编号) => ({
            id: 页名 + "/文字/" + 编号,
            name: 文案,
            type: "文字",
            text: 文案,
            visible: true,
            active: false,
            bounds: null,
            childCount: 0,
          })),
        ],
        diagnostics: {
          errors: [],
          warnings: [],
        },
      };
    },
  });
  选项.登记提交(桥.提交帧);
  桥.挂载();
  const 压力 = 创建资源压力(选项.渲染);
  const 控制 = 注册游戏测试控制({
    项目: "再消一行",
    性能: 选项.性能,
    状态: () => {
      const 收藏 = 选项.服务.金币.读取();
      return {
        页面: 选项.读取页面编号(),
        当前页: 选项.栈.读取栈().at(-1)?.名称 ?? "",
        金币: 收藏.金币,
        主题: 选项.服务.主题.读取().名称,
        已购主题: `${收藏.已购主题.length}/${可购主题.length}`,
        成就: `${选项.服务.成就.读取已解锁().length}/${选项.服务.成就.全部定义().length}`,
      };
    },
    命令: [
      ...(["菜单", "模式选择", "设置", "成就", "排行榜", "商店"] as const).map((页面) => ({
        编号: "导航." + 页面,
        名称: 页面,
        说明: "进入真实页面",
        分组: "导航",
        影响存档: false,
        执行: () => {
          选项.导航.进入(页面);
          选项.请求渲染();
        },
      })),
      {
        编号: "对局.开始",
        名称: "开始马拉松",
        说明: "开始真实对局，结算会保存纪录和奖励",
        分组: "对局",
        影响存档: true,
        执行: () => 选项.导航.进入("对局", { 模式: "马拉松" }),
      },
      {
        编号: "对局.四行",
        名称: "准备四行",
        说明: "设置当前局测试棋盘，后续落块会保存进度",
        分组: "对局",
        影响存档: true,
        执行: () => {
          测试控制()?.准备四行消除();
          选项.请求渲染();
        },
      },
      // —— 金币：直接改存档余额，用来验证商店定价、补齐价与买不起的提示 ——
      {
        编号: "金币.加1000",
        名称: "金币 +1000",
        说明: "直接写入 1000 金币",
        分组: "金币",
        影响存档: true,
        执行: () => {
          选项.服务.金币.增加(1000);
          选项.请求渲染();
        },
      },
      {
        编号: "金币.加10000",
        名称: "金币 +10000",
        说明: "一次加满，便于验证整套购买",
        分组: "金币",
        影响存档: true,
        执行: () => {
          选项.服务.金币.增加(10000);
          选项.请求渲染();
        },
      },
      {
        编号: "金币.设置",
        名称: "设置金币",
        说明: "把余额改成指定值，验证边界与提示",
        分组: "金币",
        影响存档: true,
        参数: [
          {
            键: "数量",
            名称: "金币数量",
            说明: "0 ~ 1000000，步长 100",
            类型: "数值",
            最小: 0,
            最大: 1000000,
            步长: 100,
          },
        ],
        执行: (参数) => {
          选项.服务.金币.设置金币(Number(参数.数量));
          选项.请求渲染();
        },
      },
      {
        编号: "金币.清零",
        名称: "金币清零",
        说明: "余额归零，验证买不起的提示",
        分组: "金币",
        影响存档: true,
        执行: () => {
          选项.服务.金币.设置金币(0);
          选项.请求渲染();
        },
      },
      // —— 主题：所有权与穿戴，验证商店未购/已购/补齐价与真实画面 ——
      {
        编号: "主题.全解锁",
        名称: "解锁全部主题",
        说明: "直接授予三套在售主题，不扣金币",
        分组: "主题",
        影响存档: true,
        执行: () => {
          for (const 主题 of 可购主题) 选项.服务.金币.设置主题拥有(主题, true);
          选项.请求渲染();
        },
      },
      {
        编号: "主题.全上锁",
        名称: "上锁全部主题",
        说明: "收回三套在售主题；当前穿戴退回默认",
        分组: "主题",
        影响存档: true,
        执行: () => {
          for (const 主题 of 可购主题) 选项.服务.金币.设置主题拥有(主题, false);
          if (选项.服务.设置.读取().主题选择 !== 默认主题)
            选项.服务.设置.更新({ 主题选择: 默认主题 });
          选项.请求渲染();
        },
      },
      {
        编号: "主题.解锁",
        名称: "解锁指定主题",
        说明: "授予整套主题的全部部位",
        分组: "主题",
        影响存档: true,
        参数: [
          {
            键: "主题",
            名称: "主题",
            说明: "在售三套主题",
            类型: "选项",
            选项: [...可购主题],
          },
        ],
        执行: (参数) => {
          const 主题 = String(参数.主题);
          if (!是主题名(主题)) throw new Error(`未知主题：${主题}`);
          选项.服务.金币.设置主题拥有(主题, true);
          选项.请求渲染();
        },
      },
      {
        编号: "主题.上锁",
        名称: "上锁指定主题",
        说明: "收回整套主题；正在穿戴会退回默认",
        分组: "主题",
        影响存档: true,
        参数: [
          {
            键: "主题",
            名称: "主题",
            说明: "在售三套主题",
            类型: "选项",
            选项: [...可购主题],
          },
        ],
        执行: (参数) => {
          const 主题 = String(参数.主题);
          if (!是主题名(主题)) throw new Error(`未知主题：${主题}`);
          选项.服务.金币.设置主题拥有(主题, false);
          if (选项.服务.设置.读取().主题选择 === 主题) 选项.服务.设置.更新({ 主题选择: 默认主题 });
          选项.请求渲染();
        },
      },
      {
        编号: "主题.切换",
        名称: "切换穿戴主题",
        说明: "一步切到指定主题；未拥有会先解锁",
        分组: "主题",
        影响存档: true,
        参数: [
          {
            键: "主题",
            名称: "主题",
            说明: "五套主题任选",
            类型: "选项",
            选项: [...主题列表],
          },
        ],
        执行: (参数) => {
          const 主题 = String(参数.主题);
          if (!是主题名(主题)) throw new Error(`未知主题：${主题}`);
          if (主题 !== 默认主题 && !选项.服务.金币.读取().已购主题.includes(主题))
            选项.服务.金币.设置主题拥有(主题, true);
          选项.服务.设置.更新({ 主题选择: 主题 });
          选项.请求渲染();
        },
      },
      // —— 成就：验证成就页与可重复领取的奖励 ——
      {
        编号: "成就.全解锁",
        名称: "解锁全部成就",
        说明: "按目标值补齐所有成就进度",
        分组: "成就",
        影响存档: true,
        执行: () => {
          for (const 项 of 选项.服务.成就.全部定义()) 选项.服务.成就.推进(项.编号, 项.目标);
          选项.请求渲染();
        },
      },
      {
        编号: "成就.清空",
        名称: "清空成就与领取记录",
        说明: "进度归零，成就奖励可重新领取",
        分组: "成就",
        影响存档: true,
        执行: () => {
          选项.服务.成就.重置();
          选项.服务.金币.清空已领成就();
          选项.请求渲染();
        },
      },
      // —— 存档：整档回退，执行前由看板二次确认 ——
      {
        编号: "存档.重置",
        名称: "重置收藏存档",
        说明: "金币、主题、结算与成就全部归零",
        分组: "存档",
        影响存档: true,
        危险: true,
        执行: () => {
          选项.服务.金币.重置();
          选项.服务.成就.重置();
          选项.请求渲染();
        },
      },
      {
        编号: "压力.纹理",
        名称: "纹理压力",
        说明: "分配或释放真实256像素GPU纹理，不写存档",
        分组: "资源压力",
        影响存档: false,
        参数: [
          {
            键: "数量",
            名称: "纹理数量",
            说明: "256像素GPU纹理数量",
            类型: "数值",
            最小: 0,
            最大: 64,
            步长: 1,
          },
        ],
        执行: (参数) => {
          压力.设置(Number(参数.数量));
          选项.请求渲染();
        },
      },
    ],
  });
  if (是否本机或局域网(location.hostname)) Object.assign(旧接口, { 设置资源压力: 压力.设置 });
  // 私有兼容接口只转发现有页面与资源，不维护另一份状态。

  Object.assign(window, { __three版__: 旧接口, __再消一行测试__: 对局桥 });
  return () => {
    选项.登记提交(() => {});
    控制.断开();
    压力.清理();
    桥.销毁();
    Reflect.deleteProperty(window, "__three版__");
    Reflect.deleteProperty(window, "__再消一行测试__");
  };
}

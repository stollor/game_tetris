/**
 * 浏览器压测采样：把「帧节奏 + 游戏资源账本」按 1 秒窗口聚合成点，供压测脚本读时间线。
 *
 * 只由启动层在 `GM_TEST` 下创建，玩家包里不存在。采样只在真正提交的渲染帧上推进，
 * 被节流/按需跳过的帧不计入，避免把「按需渲染的空等」当成掉帧。
 * 每个窗口读一次资源账本（纹理/文字图集/合批/图层缓存/内存），代价约几十微秒。
 */

/** 一个窗口末尾的资源账本快照。字段全部来自现有统计，不另建事实源。 */
export interface 压测资源快照 {
  绘制调用: number;
  四边形数: number;
  绘制批数: number;
  缓冲字节: number;
  纹理数: number;
  纹理字节: number;
  文字图集数: number;
  文字页数: number;
  文字纹理字节: number;
  文字版本: number;
  待确认退役图集数: number;
  待确认退役字节: number;
  /** 预算兜底强制释放的退役图集数；>0 说明退役链靠安全网收口。 */
  强制退役释放数: number;
  最大四边形容量: number;
  扩容次数: number;
  丢弃数: number;
  /** 本帧上传的批数与字节估算（动态层重建后的 GPU 上传带宽）。 */
  上传批数: number;
  上传字节估算: number;
  /** 合批空闲缩容次数；>0 说明容量回收在工作。 */
  收缩次数: number;
  内存已用MB: number | null;
  音频上下文: string;
  等级: number;
  分数: number;
  消行数: number;
  /** 累计渲染帧数 / 跳过帧数：区分「浏览器不产帧」与「游戏逐帧跳过」。 */
  渲染帧数: number;
  跳过帧数: number;
  /** 循环是否走空闲心跳（true = 不是满帧调度）。 */
  空闲: boolean;
  /** 是否省电档（帧率上限 30）。 */
  省电: boolean;
  /** 渲染编排当前帧率上限（60/30/0=不限）：区分「游戏自己限帧」与「浏览器不产帧」。 */
  帧率上限: number;
  /** 页面隐藏/有焦点：失焦或隐藏会改变浏览器帧节奏，不能当成游戏掉帧。 */
  隐藏: boolean;
  有焦点: boolean;
}

export interface 压测分布 {
  样本数: number;
  平均: number | null;
  P50: number | null;
  P95: number | null;
  P99: number | null;
  最大: number | null;
}

export interface 压测点 {
  秒数: number;
  帧数: number;
  /** 相邻提交帧的挂钟间隔（毫秒）。 */
  帧间隔: 压测分布;
  /** 单帧「逻辑 + 绘制」墙钟（毫秒），不含空等。 */
  整帧工作: 压测分布;
  /** 帧间隔 > 50ms 的帧数（肉眼可见的顿挫）。 */
  长任务帧数: number;
  /** 帧间隔 > 33.4ms 的帧数（跌破 30fps 的帧）。 */
  慢帧数: number;
  /** 本窗内因文字图集版本变化而触发整帧全量重绘的帧数。 */
  全量帧数: number;
  /** 本窗内的累计事件增量（全量帧/淘汰/版本变化/扩容）。 */
  计数: Record<string, number>;
  资源: 压测资源快照;
}

export interface 压测汇总 {
  秒数: number;
  帧数: number;
  /** 全部提交帧的相邻间隔分布。 */
  帧间隔: 压测分布;
  /** 全部提交帧的「逻辑 + 绘制」墙钟分布。 */
  整帧工作: 压测分布;
  平均帧间隔: number | null;
  长任务帧数: number;
  慢帧数: number;
  全量帧数: number;
  /** 有效窗（跳过前 2 秒预热）首窗与末窗的帧间隔 P95，用来看「是否越跑越慢」。 */
  首窗帧间隔P95: number | null;
  末窗帧间隔P95: number | null;
  /** 末窗 / 首窗 帧间隔 P95 比值；>1 表示后期更慢。 */
  退化比: number | null;
  /** 全时段累计事件计数。 */
  计数: Record<string, number>;
}

export interface 压测采样 {
  /** 每提交一帧调用一次；`时刻毫秒` 用同一个时间源（performance.now）。 */
  记录帧(选项: { 时刻毫秒: number; 逻辑毫秒: number; 绘制毫秒: number; 全量帧: boolean }): void;
  /** 累计事件计数（淘汰数/版本变化/扩容等）。 */
  计数(名称: string, 增量?: number): void;
  /** 清空时间线；保留资源读取闭包。压测前调用。 */
  重置(): void;
  /** 停止采样并返回时间线与汇总（不清空，可重复读）。 */
  读取(): { 点: 压测点[]; 汇总: 压测汇总 };
  /** 只读当前累积的事件计数（不停止采样）。 */
  读取计数(): Record<string, number>;
}

export interface 压测采样选项 {
  /** 每窗口读一次资源账本；窗口边界按提交帧的挂钟累计时间切。 */
  读取资源: () => 压测资源快照;
  /** 窗口毫秒，默认 1000。 */
  窗口毫秒?: number;
}

/** 保留的原始样本上限（60fps 下约 55 分钟）；超过后丢最早的，长跑也不无界增长。 */
const 样本上限 = 200_000;

function 分位(排序: readonly number[], 比例: number): number | null {
  return 排序.length ? (排序[Math.ceil(排序.length * 比例) - 1] ?? null) : null;
}

function 分布(列表: readonly number[]): 压测分布 {
  if (!列表.length) return { 样本数: 0, 平均: null, P50: null, P95: null, P99: null, 最大: null };
  const 排序 = [...列表].sort((甲, 乙) => 甲 - 乙);
  const 合计 = 列表.reduce((和, 值) => 和 + 值, 0);
  return {
    样本数: 列表.length,
    平均: 合计 / 列表.length,
    P50: 分位(排序, 0.5),
    P95: 分位(排序, 0.95),
    P99: 分位(排序, 0.99),
    最大: 排序.at(-1) ?? null,
  };
}

function 推入样本(列表: number[], 值: number) {
  if (列表.length >= 样本上限) 列表.shift();
  列表.push(值);
}

function 创建空白状态() {
  return {
    点: [] as 压测点[],
    全部间隔: [] as number[],
    全部工作: [] as number[],
    帧数: 0,
    秒数: 0,
    首帧毫秒: null as number | null,
    上次帧毫秒: null as number | null,
    窗起毫秒: null as number | null,
    窗间隔: [] as number[],
    窗工作: [] as number[],
    窗长任务: 0,
    窗慢帧: 0,
    窗全量帧: 0,
    窗计数: {} as Record<string, number>,
    计数: {} as Record<string, number>,
  };
}

type 采样状态 = ReturnType<typeof 创建空白状态>;

export function 创建压测采样(选项: 压测采样选项): 压测采样 {
  const 窗口毫秒 = 选项.窗口毫秒 ?? 1000;
  let 状态: 采样状态 = 创建空白状态();

  const 累计 = (表: Record<string, number>, 名称: string, 增量: number) => {
    表[名称] = (表[名称] ?? 0) + 增量;
  };

  /** 一个窗口结束：生成点并重置窗口量。 */
  const 收窗 = () => {
    const 增量: Record<string, number> = {};
    for (const [名, 值] of Object.entries(状态.窗计数)) 增量[名] = 值;
    状态.点.push({
      秒数: Number(状态.秒数.toFixed(3)),
      帧数: 状态.窗间隔.length,
      帧间隔: 分布(状态.窗间隔),
      整帧工作: 分布(状态.窗工作),
      长任务帧数: 状态.窗长任务,
      慢帧数: 状态.窗慢帧,
      全量帧数: 状态.窗全量帧,
      计数: 增量,
      资源: 选项.读取资源(),
    });
    状态.窗起毫秒 = 状态.上次帧毫秒;
    状态.窗间隔 = [];
    状态.窗工作 = [];
    状态.窗长任务 = 0;
    状态.窗慢帧 = 0;
    状态.窗全量帧 = 0;
    状态.窗计数 = {};
  };

  const 汇总 = (): 压测汇总 => {
    // 跳过前 2 秒预热，避免首帧着色器编译污染「越跑越慢」的对照。
    const 有效窗 = 状态.点.filter((点) => 点.秒数 >= 2 && 点.帧间隔.样本数 > 0);
    const 首窗 = 有效窗.at(0)?.帧间隔.P95 ?? null;
    const 末窗 = 有效窗.at(-1)?.帧间隔.P95 ?? null;
    const 间隔 = 分布(状态.全部间隔);
    return {
      秒数: Number(状态.秒数.toFixed(3)),
      帧数: 状态.帧数,
      帧间隔: 间隔,
      整帧工作: 分布(状态.全部工作),
      平均帧间隔: 间隔.平均,
      长任务帧数: 状态.点.reduce((和, 点) => 和 + 点.长任务帧数, 0),
      慢帧数: 状态.点.reduce((和, 点) => 和 + 点.慢帧数, 0),
      全量帧数: 状态.点.reduce((和, 点) => 和 + 点.全量帧数, 0),
      首窗帧间隔P95: 首窗,
      末窗帧间隔P95: 末窗,
      退化比: 首窗 && 末窗 ? 末窗 / 首窗 : null,
      计数: { ...状态.计数 },
    };
  };

  return {
    记录帧: (帧) => {
      if (状态.首帧毫秒 === null) {
        状态.首帧毫秒 = 帧.时刻毫秒;
        状态.窗起毫秒 = 帧.时刻毫秒;
      }
      const 上次 = 状态.上次帧毫秒;
      if (上次 !== null) {
        const 间隔 = 帧.时刻毫秒 - 上次;
        if (间隔 >= 0) {
          状态.窗间隔.push(间隔);
          推入样本(状态.全部间隔, 间隔);
          if (间隔 > 50) 状态.窗长任务++;
          if (间隔 > 1000 / 30) 状态.窗慢帧++;
        }
      }
      状态.上次帧毫秒 = 帧.时刻毫秒;
      状态.秒数 = (帧.时刻毫秒 - (状态.首帧毫秒 ?? 帧.时刻毫秒)) / 1000;
      状态.帧数++;
      const 工作 = 帧.逻辑毫秒 + 帧.绘制毫秒;
      状态.窗工作.push(工作);
      推入样本(状态.全部工作, 工作);
      if (帧.全量帧) 状态.窗全量帧++;
      if (状态.窗起毫秒 !== null && 帧.时刻毫秒 - 状态.窗起毫秒 >= 窗口毫秒) 收窗();
    },
    计数: (名称, 增量 = 1) => {
      累计(状态.计数, 名称, 增量);
      累计(状态.窗计数, 名称, 增量);
    },
    重置: () => {
      状态 = 创建空白状态();
    },
    读取: () => ({ 点: [...状态.点], 汇总: 汇总() }),
    读取计数: () => ({ ...状态.计数 }),
  };
}

import { expect, test } from "bun:test";
import { 计算颜色对比度, 颜色字符串 } from "../../../../.gamemaker/依赖/框架/界面/颜色工具";
import { 默认设置 } from "../../../../代码/设置/游戏设置";
import { 读取暂停按钮视觉 } from "../../../../代码/页面/布局/对局布局";
import { 立体规范 } from "../../../../资源/主题/立体/立体规范";
import { 是立体风格 } from "../../../../资源/主题/立体/立体风格";
import { 设置预览主题读取 } from "../../../../资源/主题/配色/主题读取";
import { 读取覆盖页按钮视觉 } from "../../../../资源/预制体/基础/按钮/覆盖页按钮配方";
import { 读取预览主题解析, 读取预览主题设置 } from "../../../../资源/预制体/预览/主题状态";

/**
 * 按钮文字色必须跟着**实际落地**的底板走。
 *
 * 历史 bug：暂停菜单已选键铺「点击」态底色、却取「默认」态深色字，砖机液晶 1.83:1、
 * 街机彩砖 1.95:1；立体晶格的金属板根本不画配色表填色，字色却按填色算深色，
 * 选中项直接消失（1.33:1）。所有主题的选中/未选、主/次按钮文字都要 ≥ AA 4.5。
 */
const 主题列表 = ["极光原野", "砖机液晶", "街机彩砖", "立体晶格", "糖果超甜"] as const;
const 深金属板 = 颜色字符串(立体规范.界面.板);

function 在主题下<T>(主题: string, 动作: () => T): T {
  const 状态 = { 资源主题: 主题 };
  const 设置 = 读取预览主题设置(状态, 默认设置);
  设置预览主题读取(
    () => 设置,
    () => 读取预览主题解析(状态, 设置),
  );
  try {
    return 动作();
  } finally {
    设置预览主题读取();
  }
}

/** 立体风格底色不落地，真实底板是深金属板；其余主题按配色表铺色。 */
function 实际底板(配色底色: string): string {
  return 是立体风格() ? 深金属板 : 配色底色;
}

for (const 主题 of 主题列表) {
  test(`${主题}：覆盖页按钮的已选/未选文字都压得住实际底板`, () => {
    const 结果 = 在主题下(主题, () => {
      const 未选 = 读取覆盖页按钮视觉(false);
      const 已选 = 读取覆盖页按钮视觉(true);
      return [
        { 名: "未选", 文字: 未选.文字色, 底: 实际底板(未选.面板色) },
        { 名: "已选", 文字: 已选.文字色, 底: 实际底板(已选.面板色) },
      ];
    });
    for (const 项 of 结果)
      expect({
        主题,
        状态: 项.名,
        对比度: (计算颜色对比度(项.文字, 项.底) ?? 0) >= 4.5,
      }).toEqual({ 主题, 状态: 项.名, 对比度: true });
  });

  test(`${主题}：暂停菜单按钮的已选/未选文字都压得住实际底板`, () => {
    const 结果 = 在主题下(主题, () => {
      const 未选 = 读取暂停按钮视觉(false);
      const 已选 = 读取暂停按钮视觉(true);
      return [
        { 名: "未选", 文字: 颜色字符串(未选.文字色), 底: 实际底板(颜色字符串(未选.填色)) },
        { 名: "已选", 文字: 颜色字符串(已选.文字色), 底: 实际底板(颜色字符串(已选.填色)) },
      ];
    });
    for (const 项 of 结果)
      expect({
        主题,
        状态: 项.名,
        对比度: (计算颜色对比度(项.文字, 项.底) ?? 0) >= 4.5,
      }).toEqual({ 主题, 状态: 项.名, 对比度: true });
  });
}

interface 抓帧缓冲 {
  名称: string;
  阶段: "收束" | "展开";
  目标秒: number;
  抓帧秒: number | null;
  截图后秒: number | null;
  截图前: 页面读数;
  截图后: 页面读数;
  截图毫秒: number;
  错过: boolean;
  路径: string;
}

/**
 * 轮询时间轴，命中目标秒时立刻截图。
 * 收束读 `转场:收束:<秒>`；命中前若已切到对局页，标记「错过」而不是干等超时
 * （1.06s 一到页面就切走，主线程抖动时最后一帧可能抢不到）。
 */
async function 抓帧(页: Page, 主题: 主题, 项: 抓帧项): Promise<抓帧缓冲> {
  const { 阶段, 目标秒 } = 项;
  const 路径 = join(输出, 主题, `${项.名称}.png`);
  const 超时毫秒 = 阶段 === "收束" ? 6000 : 8000;
  try {
    await 页.waitForFunction(
      (参数: { 阶段: string; 目标秒: number }) => {
        const 桥 = window.__three版__;
        const 界面 = 桥?.读取界面();
        const 状态 = 桥?.读取状态();
        const 标记 = (错过: boolean, 秒: number | null): boolean => {
          window.__转场抓帧__ = {
            秒,
            节拍: (界面?.文字 ?? []).find((行) => 行.startsWith("入场:")) ?? "",
            页面: 状态?.页面 ?? null,
            帧间隔毫秒: 桥?.读取统计().循环.平均帧间隔毫秒 ?? 16.7,
            按钮数: (界面?.按钮 ?? []).length,
            含模式卡: (界面?.按钮 ?? []).some((按钮) => 按钮.名称.includes("模式")),
            错过,
          };
          return true;
        };
        if (参数.阶段 === "收束") {
          const 行 = (界面?.文字 ?? []).find((行) => 行.startsWith("转场:收束:"));
          const 秒 = 行 ? Number(行.slice("转场:收束:".length)) : null;
          if (typeof 秒 === "number" && Number.isFinite(秒) && 秒 >= 参数.目标秒) {
            return 标记(false, 秒);
          }
          // 已切页 = 这一帧永远等不到了，标记错过让断言如实失败。
          if (状态?.页面 === "对局") return 标记(true, null);
          return false;
        }
        const 秒 = 状态?.入场秒;
        if (typeof 秒 !== "number" || 秒 < 参数.目标秒) return false;
        return 标记(false, 秒);
      },
      { 阶段, 目标秒 },
      { polling: "raf", timeout: 超时毫秒 },
    );
  } catch {
    const 快照 = await 读页面(页);
    throw new Error(
      `抓帧超时「${项.名称}」：${JSON.stringify({ 页面: 快照.页面, 转场: 快照.转场, 入场秒: 快照.入场秒, 节拍: 快照.节拍 })}`,
    );
  }
  const 截图前 = await 读页面(页);
  const 截起 = Date.now();
  await 页.screenshot({ path: 路径 });
  const 截图毫秒 = Date.now() - 截起;
  const 读数 = await 页.evaluate((阶段名) => {
    const 桥 = window.__three版__;
    const 标记 = window.__转场抓帧__ ?? null;
    const 状态 = 桥?.读取状态();
    const 文字 = 桥?.读取界面().文字 ?? [];
    return {
      标记,
      秒:
        阶段名 === "收束"
          ? (() => {
              const 行 = 文字.find((行) => 行.startsWith("转场:收束:"));
              const 值 = 行 ? Number(行.slice("转场:收束:".length)) : null;
              return typeof 值 === "number" && Number.isFinite(值) ? 值 : null;
            })()
          : typeof 状态?.入场秒 === "number"
            ? 状态.入场秒
            : null,
    };
  }, 阶段);
  const 截图后 = await 读页面(页);
  // 收束帧的截图若跨过了 1.06 切页点，画面已经是新页面，这一帧不能当收束末帧用。
  const 切页了 = 阶段 === "收束" && 截图后.页面 !== "模式选择";
  return {
    名称: 项.名称,
    阶段,
    目标秒,
    抓帧秒: 读数.标记?.秒 ?? null,
    截图后秒: 读数.秒,
    截图前,
    截图后,
    截图毫秒,
    错过: (读数.标记?.错过 ?? true) || 切页了,
    路径,
  };
}


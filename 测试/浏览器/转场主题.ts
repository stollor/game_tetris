/** 幕布覆盖/露出用「最近参照」分类：更接近幕布帧算幕布，更接近内容帧算露出。 */
function 判为幕布(帧格: readonly 格统计[], 幕布格: readonly 格统计[], 内容格: readonly 格统计[]) {
  return 帧格.map((格, 序) => {
    const 幕 = 幕布格[序];
    const 内 = 内容格[序];
    if (!幕 || !内) return true;
    return 色距(格, 幕) <= 色距(格, 内);
  });
}


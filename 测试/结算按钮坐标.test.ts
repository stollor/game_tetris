import { expect, test } from "bun:test";
import { 绘制结算操作 } from "../视效/特效/结算演出";

/**
 * 结算按钮画在**小尺寸节点**里：形状走节点局部坐标（0..宽），文字必须按节点绘制矩阵换算到绘制空间。
 * 曾经漏了这层换算，按钮文字全跑到页面左上角（按钮看起来没字）——这里守住坐标契约。
 */
test("结算按钮文字按点变换换到绘制空间", () => {
  const 文字: { 文案: string; x: number; y: number }[] = [];
  const 图形 = new Proxy(
    {},
    {
      get: () => (...参数: unknown[]) => {
        if (参数.length === 1 && typeof 参数[0] === "object" && 参数[0] && "文案" in 参数[0])
          return 图形;
        return 图形;
      },
    },
  ) as never;
  const 画笔 = {
    图形,
    绘制文字: (项: { 文案: string; x: number; y: number }) => {
      文字.push({ 文案: 项.文案, x: 项.x, y: 项.y });
      return { 宽: 100, 高: 20 };
    },
    测量文字: () => ({ 宽: 100, 高: 20 }),
    读取纯色紫外线: () => ({ u: 0, v: 0, 宽: 1, 高: 1 }),
    绘制纹理帧: () => false,
    绘制散图: () => false,
    重置: () => {},
    压入裁剪: () => {},
    弹出裁剪: () => {},
  } as never;

  // 节点在页面 (100, 300) 处，宽 300 高 52：局部文字点 (150, 26) 应映射到 (250, 326)。
  绘制结算操作(画笔, { 左: 0, 上: 0, 宽: 300, 高: 52 }, "返回主菜单", "菜单", "默认", 900, false, (点) => ({
    x: 点.x + 100,
    y: 点.y + 300,
  }));
  const 按钮文字 = 文字.find((项) => 项.文案 === "返回主菜单");
  expect(按钮文字).toBeDefined();
  expect(按钮文字?.x).toBeCloseTo(250, 5);
  expect(按钮文字?.y).toBeCloseTo(326, 5);

  // 不传变换时保持旧行为（整页绘制节点：局部坐标即绘制坐标）。
  文字.length = 0;
  绘制结算操作(画笔, { 左: 0, 上: 0, 宽: 300, 高: 52 }, "返回主菜单", "菜单", "默认", 900, false);
  expect(文字[0]?.x).toBeCloseTo(150, 5);
  expect(文字[0]?.y).toBeCloseTo(26, 5);
});

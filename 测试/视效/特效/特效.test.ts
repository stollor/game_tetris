  /** 最小文字图集：只记录文字项并写一块文字四边形，不依赖 canvas。 */
  function 假图集工厂(文本记录: 文本记录[]) {
    return (选项: 文字图集选项): 文字图集接口 => {
      const 纹理 = new Texture();
      const 测量 = (文本: string) => Array.from(文本).length * 选项.字号;
      const 页面边长 = 选项.页面边长 ?? 1024;
      return {
        注册: () => undefined,
        读取纹理: () => 纹理,
        读取纯色紫外线: () => 白块,
        读取行高: () => 选项.字号,
        测量,
        排版: (文本, 最大宽度) => ({
          行: [{ 文本, 宽: 测量(文本), 字形: [] }],
          宽: Math.min(测量(文本), 最大宽度),
          高: 选项.字号,
        }),
        绘制: (合批, 文本, 绘制选项) => {
          const 宽 = 测量(文本);
          文本记录.push({
            文本,
            字号: 选项.字号,
            左: 绘制选项.左,
            上: 绘制选项.上,
            宽,
            颜色: 绘制选项.颜色,
          });
          合批.添加({
            左: 绘制选项.左,
            上: 绘制选项.上,
            宽,
            高: 选项.字号,
            紫外线: 白块,
            颜色: 绘制选项.颜色,
            纹理: 绘制选项.纹理序号,
          });
          return { 行: [], 宽: 0, 高: 0 };
        },
        读取统计: () => ({ 页数: 1, 字形数: 0, 页面边长, 纹理字节: 页面边长 ** 2 * 4 }),
        销毁: () => undefined,
      };
    };
  }


  function 在矩形内(形: { 左: number; 上: number; 宽: number; 高: number }, 框: 矩形): boolean {
    const 容差 = 1e-6;
    return (
      形.左 >= 框.左 - 容差 &&
      形.上 >= 框.上 - 容差 &&
      形.左 + 形.宽 <= 框.左 + 框.宽 + 容差 &&
      形.上 + 形.高 <= 框.上 + 框.高 + 容差
    );
  }

  function 点在矩形内(点: { x: number; y: number }, 框: 矩形): boolean {
    const 容差 = 1e-6;
    return (
      点.x >= 框.左 - 容差 &&
      点.y >= 框.上 - 容差 &&
      点.x <= 框.左 + 框.宽 + 容差 &&
      点.y <= 框.上 + 框.高 + 容差
    );
  }

  function 转按钮矩形(按钮布局: { 中心X: number; 中心Y: number; 宽: number; 高: number }): 矩形 {
    return {
      左: 按钮布局.中心X - 按钮布局.宽 / 2,
      上: 按钮布局.中心Y - 按钮布局.高 / 2,
      宽: 按钮布局.宽,
      高: 按钮布局.高,
    };
  }


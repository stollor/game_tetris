import { describe, expect, test } from "bun:test";
import { 下落缓动, 计算下移行数, 计算消行变形 } from "../../../资源/视效/特效/消行补间";
import { 计算拖尾残影 } from "../../../资源/视效/透视/透视棋盘";

/**
 * 透视主题的消行/下落反馈口径。
 * 井内是 3D 房间，2D 的 绘制消行光带 / 绘制落块拖尾 在这里被跳过，
 * 这两条纯函数就是它的全部动效来源：口径乱了，动画就会变成「整行方块一起被吸走」
 * 或「砸下来毫无反馈」。
 */
describe("透视对局动效", () => {
  test("消行先亮起再收缩到 0，不会停在半空的小方点", () => {
    const 起始 = 计算消行变形(0, 0, 10);
    expect(起始.缩比).toBe(1);
    // 前 30% 只闪白、不缩小
    const 半亮 = 计算消行变形(0.15, 0, 10);
    expect(半亮.缩比).toBe(1);
    expect(半亮.提亮).toBeGreaterThan(起始.提亮);
    // 后段收缩到接近 0，并且越来越亮
    const 末段 = 计算消行变形(1, 0, 10);
    expect(末段.缩比).toBeLessThan(0.001);
    expect(末段.提亮).toBeGreaterThan(0.95);
    // 中段必须真的在缩，而不是瞬间消失
    expect(计算消行变形(0.6, 0, 10).缩比).toBeLessThan(0.95);
    expect(计算消行变形(0.6, 0, 10).缩比).toBeGreaterThan(0.01);
  });

  test("消行按列错峰：左侧先动，右侧后动", () => {
    const 左 = 计算消行变形(0.5, 0, 10);
    const 右 = 计算消行变形(0.5, 9, 10);
    expect(左.缩比).toBeLessThan(右.缩比);
    // 提亮在闪段就饱和了，错峰要看更早的进度
    expect(计算消行变形(0.32, 0, 10).提亮).toBeGreaterThan(计算消行变形(0.32, 9, 10).提亮);
  });

  test("硬降拖尾与落块同帧出现，随后由远到近回收", () => {
    const 拖尾 = { 列: [{ 列: 3, 底行: 11 }], 类型: "I" as const, 距离: 10, 进度: 0 };
    const 落地瞬间 = 计算拖尾残影(拖尾, 20);
    // 落地那一瞬整条拖尾就在（不能等主体先落地再一块块补）
    expect(落地瞬间.length).toBeGreaterThan(3);
    expect(落地瞬间.every((项) => 项.行 < 11 && 项.行 >= 0 && 项.列 === 3)).toBe(true);

    // 之后回收：越高的残影越早消失，最终整条消失
    const 中段 = 计算拖尾残影({ ...拖尾, 进度: 0.5 }, 20);
    const 末段 = 计算拖尾残影({ ...拖尾, 进度: 1 }, 20);
    expect(中段.length).toBeLessThan(落地瞬间.length);
    expect(末段).toHaveLength(0);
    if (中段.length) {
      // 剩下的都是离落点更近的那些（行号更大）
      expect(Math.min(...中段.map((项) => 项.行))).toBeGreaterThan(
        Math.min(...落地瞬间.map((项) => 项.行)),
      );
    }
  });

  test("硬降残影越远越小，超出井顶的残影被裁掉", () => {
    const 残影 = 计算拖尾残影({ 列: [{ 列: 0, 底行: 12 }], 类型: "O", 距离: 6, 进度: 0 }, 20);
    expect(残影.length).toBeGreaterThan(1);
    for (let i = 1; i < 残影.length; i += 1)
      expect(残影[i]!.缩放比).toBeLessThan(残影[i - 1]!.缩放比);
    const 贴顶 = 计算拖尾残影({ 列: [{ 列: 0, 底行: 1 }], 类型: "O", 距离: 7, 进度: 0 }, 20);
    expect(贴顶.every((项) => 项.行 >= 0)).toBe(true);
  });

  test("消行时上方行按「下方消掉几行就下移几行」补间，下方行不动", () => {
    // 消掉第 15 行：它上面的行各下移 1 行，下面的行不动
    expect(计算下移行数(10, [15])).toBe(1);
    expect(计算下移行数(14, [15])).toBe(1);
    expect(计算下移行数(16, [15])).toBe(0);
    expect(计算下移行数(19, [15])).toBe(0);
    // 一次消掉多行：每行按自己下方的消行数计
    expect(计算下移行数(10, [12, 15, 19])).toBe(3);
    expect(计算下移行数(13, [12, 15, 19])).toBe(2);
    expect(计算下移行数(16, [12, 15, 19])).toBe(1);
    // 位移量随缓动从 0 到整行：进度 0 时还停在原位，进度 0.4 时已到位
    expect(计算下移行数(10, [15]) * 下落缓动(0)).toBe(0);
    expect(计算下移行数(10, [15]) * 下落缓动(0.4)).toBe(1);
  });

  test("消行期间上方行做下移补间：进度越往下越接近新位置", () => {
    expect(下落缓动(0)).toBe(0);
    expect(下落缓动(0.4)).toBe(1);
    expect(下落缓动(1)).toBe(1);
    // 缓出：前段落得快、末段收尾
    expect(下落缓动(0.2)).toBeGreaterThan(0.5);
  });
});

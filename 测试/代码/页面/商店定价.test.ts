import { describe, expect, test } from "bun:test";
import {
  商店主题列表,
  在售主题列表,
  已拥有,
  是可购主题,
  计算报价,
} from "../../../代码/页面/商店定价";
import { 主题列表, 默认主题 } from "../../../代码/项目配置/主题目录";

/**
 * 商店定价只看「主题目录 + 已购列表」，不读存档实现也不另算折扣；
 * 未购买的主题报价非零，页面据此不写设置，设置层还会再校验一次所有权。
 */
describe("商店定价", () => {
  test("默认主题出厂即拥有、报价为 0，其余主题按目录报价", () => {
    expect(已拥有([], 默认主题)).toBe(true);
    expect(计算报价(默认主题, [])).toBe(0);
    expect(已拥有([], "砖机液晶")).toBe(false);
    expect(计算报价("砖机液晶", [])).toBe(280);
    expect(计算报价("立体晶格", [])).toBe(480);
  });

  test("买过的主题报价归零，报价不再变化", () => {
    const 已购 = ["砖机液晶"];
    expect(已拥有(已购, "砖机液晶")).toBe(true);
    expect(计算报价("砖机液晶", 已购)).toBe(0);
    expect(计算报价("街机彩砖", 已购)).toBe(280);
  });

  test("商店展示四套主题，默认主题展示但不可购买", () => {
    expect(商店主题列表()).toEqual(主题列表);
    expect(在售主题列表()).toEqual(["砖机液晶", "街机彩砖", "立体晶格"]);
    expect(是可购主题("砖机液晶")).toBe(true);
    expect(是可购主题(默认主题)).toBe(false);
    expect(是可购主题("成都熊猫")).toBe(false);
  });
});

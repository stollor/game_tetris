import { describe, expect, test } from "bun:test";
import {
  商店主题列表,
  在售主题列表,
  已拥有,
  是可购主题,
  计算报价,
} from "../../../代码/页面/商店定价";
import { 主题列表, 默认主题 } from "../../../代码/项目配置/主题目录";
import { 外观编号, 外观部位列表 } from "../../../代码/项目配置/外观部位";

/**
 * 商店定价只看「主题目录 + 已购部位列表」，不读存档实现也不另算折扣；
 * 单件只解锁对应部位，动态背景含静态，整套只对未购部位打 72 折并向上到 10。
 */
describe("商店定价", () => {
  test("默认主题出厂即拥有、所有部位免费，基础整套为 510", () => {
    expect(已拥有([], 默认主题)).toBe(true);
    expect(计算报价(默认主题, "整套", [])).toBe(0);
    for (const 部位 of 外观部位列表) {
      expect(已拥有([], 默认主题, 部位)).toBe(true);
      expect(计算报价(默认主题, 部位, [])).toBe(0);
    }
    expect(已拥有([], "砖机液晶")).toBe(false);
    // (180+140+120+100+160)*.72=504，向上到 10 为 510；静态背景不计入整套原价。
    expect(计算报价("砖机液晶", "整套", [])).toBe(510);
    expect(计算报价("立体晶格", "整套", [])).toBe(510);
  });

  test("单件按原价，动态背景在已购静态后只补差价", () => {
    expect(计算报价("砖机液晶", "静态背景", [])).toBe(80);
    expect(计算报价("砖机液晶", "动态背景", [])).toBe(180);
    expect(计算报价("砖机液晶", "界面样式", [])).toBe(140);
    expect(计算报价("砖机液晶", "方块外观", [])).toBe(120);
    expect(计算报价("砖机液晶", "音效套装", [])).toBe(100);
    expect(计算报价("砖机液晶", "音乐", [])).toBe(160);

    const 已购 = [外观编号("砖机液晶", "静态背景")];
    expect(计算报价("砖机液晶", "动态背景", 已购)).toBe(100);
    expect(已拥有(已购, "砖机液晶", "静态背景")).toBe(true);
    expect(已拥有(已购, "砖机液晶", "动态背景")).toBe(false);
    expect(已拥有(已购, "砖机液晶")).toBe(false);
  });

  test("整套只对未购部位折扣，补齐后归零", () => {
    const 已购 = [外观编号("砖机液晶", "方块外观")];
    expect(已拥有(已购, "砖机液晶", "方块外观")).toBe(true);
    expect(已拥有(已购, "砖机液晶", "音乐")).toBe(false);
    // 剩余 580*.72=417.6，向上到 10 为 420。
    expect(计算报价("砖机液晶", "整套", 已购)).toBe(420);

    const 整套已购 = 外观部位列表.map((部位) => 外观编号("砖机液晶", 部位));
    expect(已拥有(整套已购, "砖机液晶")).toBe(true);
    expect(计算报价("砖机液晶", "整套", 整套已购)).toBe(0);
    expect(计算报价("街机彩砖", "整套", 整套已购)).toBe(510);
  });

  test("商店展示四套主题，默认主题展示但不可购买", () => {
    expect(商店主题列表()).toEqual(主题列表);
    expect(在售主题列表()).toEqual(["砖机液晶", "街机彩砖", "立体晶格"]);
    expect(是可购主题("砖机液晶")).toBe(true);
    expect(是可购主题(默认主题)).toBe(false);
    expect(是可购主题("成都熊猫")).toBe(false);
  });
});

import { describe, expect, test } from "bun:test";
import { 计算对局布局 } from "../../../../代码/页面/布局/对局布局";
import { 对局像素规格 } from "../../../../资源/主题/像素/对局像素规格";

/**
 * 像素主题的井底压边：像素框线与方块描边同色，最底一行贴死框线时读起来像
 * 方块溢出井底（1.2.1 用户反馈）。压边把 20 行网格整体上移一条空带，
 * 非像素主题必须完全不受影响。
 */
describe("对局布局 · 像素井底压边", () => {
  const 选项 = { 模式: "马拉松", 阶段: "进行中" } as const;

  test("像素主题留出井底压边，方块下沿与棋盘下沿之间空出一条带", () => {
    const 布局 = 计算对局布局(390, 844, { ...选项, 棋盘底部留白: 对局像素规格.棋盘.井底留白 });
    const 方块下沿 = 布局.棋盘.上 + 20 * 布局.格子大小;
    const 棋盘下沿 = 布局.棋盘.上 + 布局.棋盘.高;
    expect(棋盘下沿 - 方块下沿).toBe(对局像素规格.棋盘.井底留白);
    expect(布局.棋盘.高).toBe(20 * 布局.格子大小 + 对局像素规格.棋盘.井底留白);
    // 棋盘仍要完整落在操作区之上
    expect(棋盘下沿).toBeLessThan(布局.操作区顶);
  });

  test("不带留白时棋盘高仍是 20 行（平面主题不受影响）", () => {
    const 布局 = 计算对局布局(390, 844, 选项);
    expect(布局.棋盘.高).toBe(20 * 布局.格子大小);
    expect(布局.棋盘.上 + 布局.棋盘.高).toBe(布局.棋盘.上 + 20 * 布局.格子大小);
  });

  test("压边不改变格距与棋盘宽度", () => {
    const 平面 = 计算对局布局(390, 844, 选项);
    const 像素 = 计算对局布局(390, 844, { ...选项, 棋盘底部留白: 对局像素规格.棋盘.井底留白 });
    expect(像素.格子大小).toBe(平面.格子大小);
    expect(像素.棋盘.宽).toBe(平面.棋盘.宽);
    expect(像素.棋盘.左).toBe(平面.棋盘.左);
  });
});

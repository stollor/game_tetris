test("退场中间帧同步移动文字、图形和裁剪，绘制后恢复变换", () => {
  const { 上下文 } = 创建页面上下文();
  const 画笔 = 上下文.资源.画笔;
  const 文字点: { x: number; y: number }[] = [];
  const 裁剪: { 左: number; 上: number }[] = [];
  画笔.绘制文字 = (项) => {
    文字点.push(项);
    return { 宽: 0, 高: 0 };
  };
  画笔.压入裁剪 = (矩形) => {
    裁剪.push(矩形);
  };
  const 图形 = 画笔.图形 as Three图形;
  绘制页面过渡(画笔, 页面过渡时长 / 2, 100, -80, (动效画笔) => {
    动效画笔.绘制文字({
      文案: "测试",
      锚点: "左上",
      x: 10,
      y: 20,
      样式: { 字号: 12, 颜色: "#ffffff" },
    });
    动效画笔.压入裁剪({ 左: 10, 上: 20, 宽: 30, 高: 40 });
    expect(图形.读取矩阵().e).toBe(50);
    expect(图形.读取矩阵().f).toBe(-40);
    expect(图形.读取透明度()).toBe(0.5);
  });
  expect(文字点[0]).toMatchObject({ x: 60, y: -20 });
  expect(裁剪[0]).toMatchObject({ 左: 60, 上: -20 });
  expect(图形.读取矩阵().e).toBe(0);
  expect(图形.读取透明度()).toBe(1);
});

test("菜单与模式选择一次流转完成，期间不重入切换", () => {
  const { 上下文, 命中 } = 创建页面上下文();
  const 页面 = new 主界面(上下文);
  页面.进入();
  const 点按钮 = (名称: string) => {
    const 按钮 = 页面.读取界面().按钮.find((项) => 项.名称 === 名称);
    if (!按钮) throw Error(名称);
    const 点 = { x: 按钮.左 + 按钮.宽 / 2, y: 按钮.上 + 按钮.高 / 2 };
    命中.派发("按下", 点);
    命中.派发("抬起", 点);
  };
  for (const [按钮名, 出发状态, 目标状态, 完成按钮] of [
    ["开始游戏", "菜单", "模式选择", "返回"],
    ["返回", "模式选择", "菜单", "开始游戏"],
  ]) {
    点按钮(按钮名);
    expect(页面.读取界面().文字).toContain("过渡:流转");
    expect(页面.读取界面().文字).toContain(`状态:${出发状态}`);
    expect(页面.读取界面().按钮).toHaveLength(0);
    页面.更新(界面流转时长 / 2);
    expect(页面.读取界面().文字).toContain(`状态:${出发状态}`);
    expect(页面.读取界面().按钮).toHaveLength(0);
    页面.更新(界面流转时长 / 2);
    expect(页面.读取界面().文字).toContain(`状态:${目标状态}`);
    expect(页面.读取界面().文字).toContain("过渡:无");
    expect(页面.读取界面().按钮.some((项) => 项.名称 === 完成按钮)).toBe(true);
  }
});

test("主菜单纯享按一次流转返回，商店仍先移出再移入", () => {
  for (const 页面类 of [主界面, 商店界面]) {
    const { 上下文, 命中 } = 创建页面上下文();
    const 页面 = new 页面类(上下文);
    页面.进入();
    const 点 = (名称: string) => {
      const 按钮 = 页面.读取界面().按钮.find((项) => 项.名称 === 名称);
      if (!按钮) throw Error(名称);
      const 坐标 = { x: 按钮.左 + 按钮.宽 / 2, y: 按钮.上 + 按钮.高 / 2 };
      命中.派发("按下", 坐标);
      命中.派发("抬起", 坐标);
    };
    if (页面类 === 主界面) {
      命中.派发("按下", { x: 200, y: 750 });
      命中.派发("抬起", { x: 200, y: 750 });
      页面.更新(界面流转时长);
    } else {
      点("商店:纯享");
      页面.更新(页面过渡时长);
      页面.更新(页面过渡时长);
    }
    点(页面类 === 主界面 ? "纯享:返回" : "商店:返回");
    expect(页面.读取界面().文字).toContain(页面类 === 主界面 ? "过渡:流转" : "过渡:移出");
    expect(页面.读取界面().按钮).toHaveLength(0);
    页面.更新(页面类 === 主界面 ? 界面流转时长 / 2 : 页面过渡时长);
    expect(页面.读取界面().文字).toContain(页面类 === 主界面 ? "过渡:流转" : "过渡:移入");
    expect(页面.读取界面().按钮).toHaveLength(0);
    页面.更新(页面类 === 主界面 ? 界面流转时长 / 2 : 页面过渡时长);
    expect(页面.读取界面().文字).toContain("过渡:无");
    expect(
      页面.读取界面().按钮.some((项) => 项.名称 === (页面类 === 主界面 ? "开始游戏" : "商店:纯享")),
    ).toBe(true);
    页面.销毁();
  }
});

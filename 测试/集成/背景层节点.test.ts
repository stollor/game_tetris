import { expect, test } from "bun:test";
import { 近景页 } from "../../代码/页面/层/背景/近景页";
import { 远景页 } from "../../代码/页面/层/背景/远景页";
import { 创建页面上下文 } from "./主界面与控件.test.ts";

/**
 * 背景层页面必须走节点树：远景/近景的风景画在整页绘制节点里。
 * 曾经它们依赖已删除的旧 `绘制内容` 钩子，基类不走旧路径后背景直接变黑——这里守住这条回归。
 */
test("背景层远景/近景页是节点页面，风景画在整页绘制节点里", () => {
  const { 上下文 } = 创建页面上下文();
  const 用例 = [
    { 页类: 远景页, 节点名: "背景:远景:风景" },
    { 页类: 近景页, 节点名: "背景:近景:动态" },
  ] as const;
  for (const { 页类, 节点名 } of 用例) {
    const 页 = new 页类(上下文);
    页.进入();
    expect(页.使用节点树()).toBe(true);
    const 路径 = 页.读取节点快照().map((项) => 项.路径);
    expect(路径.some((项) => 项.endsWith(节点名))).toBe(true);
    // 每个背景页只有一条绘制带、一个整页绘制节点，进/退/销毁不累积命中区。
    const 区域数 = 上下文.资源.命中.读取区域数();
    页.退出();
    expect(上下文.资源.命中.读取区域数()).toBe(区域数 - 1);
    页.销毁();
  }
});

describe("图层缓存转场失效", () => {
  /** 图层指纹可控的合批替身：用来复现「内容指纹静音」并确认转场标脏不被它吞掉。 */
  function 创建指纹缓存() {
    const 合批 = {
      指纹: 1,
      开始写层: () => {},
      移除层: () => 0,
      读取层指纹: () => 合批.指纹,
    };
    return 创建图层缓存({ 合批, 每页子层数: 7 });
  }

  test("内容指纹学到的静音不会吞掉转场标脏，READY/遮罩能按时清掉", () => {
    const 缓存 = 创建指纹缓存();
    缓存.同步栈([{ 名称: "转场动画" }]);
    缓存.进入页面("转场动画", 0);

    // 第一帧：进入强制重建，指纹从 0 开始不参与静音学习。
    缓存.开始帧();
    缓存.进入页面("转场动画", 0);
    expect(缓存.需要重建("转场动画", 0)).toBe(true);
    缓存.开始重建("转场动画", 0);
    缓存.提交();

    // 第二帧：内容没变的「内容」标脏 → 学到该原因可静音。
    缓存.开始帧();
    缓存.进入页面("转场动画", 0);
    缓存.标记失效("转场动画", [0], "内容");
    expect(缓存.需要重建("转场动画", 0)).toBe(true);
    缓存.开始重建("转场动画", 0);
    缓存.提交();

    // 第三帧：同原因同内容 → 被静音（这就是当初吞掉「转场结束清空」的那条路径）。
    缓存.开始帧();
    缓存.进入页面("转场动画", 0);
    缓存.标记失效("转场动画", [0], "内容");
    expect(缓存.需要重建("转场动画", 0)).toBe(false);

    // 转场标脏是强制原因：必须重建，不参与静音。
    缓存.开始帧();
    缓存.进入页面("转场动画", 0);
    缓存.标记失效("转场动画", [0], "转场");
    expect(缓存.需要重建("转场动画", 0)).toBe(true);
  });
});

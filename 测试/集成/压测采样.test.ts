import { describe, expect, test } from "bun:test";
import { 创建压测采样, type 压测资源快照 } from "../接入/压测采样";

/** 构造一份「什么都没在涨」的资源快照；需要变化的字段单独覆盖。 */
function 资源(覆盖: Partial<压测资源快照> = {}): 压测资源快照 {
  return {
    绘制调用: 0,
    四边形数: 0,
    绘制批数: 0,
    缓冲字节: 0,
    纹理数: 0,
    纹理字节: 0,
    文字图集数: 0,
    文字页数: 0,
    文字纹理字节: 0,
    文字版本: 0,
    待确认退役图集数: 0,
    待确认退役字节: 0,
    强制退役释放数: 0,
    最大四边形容量: 0,
    扩容次数: 0,
    丢弃数: 0,
    上传批数: 0,
    上传字节估算: 0,
    收缩次数: 0,
    内存已用MB: null,
    音频上下文: "running",
    等级: 1,
    分数: 0,
    消行数: 0,
    渲染帧数: 0,
    跳过帧数: 0,
    空闲: false,
    省电: false,
    帧率上限: 60,
    隐藏: false,
    有焦点: true,
    ...覆盖,
  };
}

/** 按固定帧间隔喂 `帧数` 帧，返回喂完后的采样器（时刻从 0 起算）。 */
function 喂帧(
  采样: ReturnType<typeof 创建压测采样>,
  帧间隔毫秒: number,
  帧数: number,
  逻辑毫秒 = 1,
  绘制毫秒 = 2,
): number {
  let 时刻 = 0;
  采样.记录帧({ 时刻毫秒: 时刻, 逻辑毫秒, 绘制毫秒, 全量帧: false });
  for (let i = 1; i < 帧数; i++) {
    时刻 += 帧间隔毫秒;
    采样.记录帧({ 时刻毫秒: 时刻, 逻辑毫秒, 绘制毫秒, 全量帧: false });
  }
  return 时刻;
}

describe("压测采样", () => {
  test("首帧不计间隔；满 1 秒窗口才出一个点", () => {
    const 采样 = 创建压测采样({ 读取资源: () => 资源() });
    // 0, 16.7, … 1002ms：第一个窗口在越界那帧收口，共 60 个间隔。
    喂帧(采样, 16.7, 61);
    const { 点 } = 采样.读取();
    expect(点.length).toBe(1);
    expect(点[0]?.帧数).toBe(60);
    expect(点[0]?.帧间隔.样本数).toBe(60);
  });

  test("分布口径：P50/P95/P99 与平均都来自窗口内帧间隔", () => {
    const 采样 = 创建压测采样({ 读取资源: () => 资源() });
    喂帧(采样, 10, 101);
    const 点 = 采样.读取().点[0];
    expect(点?.帧间隔.样本数).toBe(100);
    expect(点?.帧间隔.平均).toBeCloseTo(10, 5);
    expect(点?.帧间隔.P50).toBeCloseTo(10, 5);
    expect(点?.帧间隔.P95).toBeCloseTo(10, 5);
    expect(点?.帧间隔.P99).toBeCloseTo(10, 5);
    expect(点?.整帧工作.平均).toBeCloseTo(3, 5);
  });

  test("长任务与慢帧按 50ms / 30fps 两条线分别计数", () => {
    const 采样 = 创建压测采样({ 读取资源: () => 资源() });
    let 时刻 = 0;
    采样.记录帧({ 时刻毫秒: 0, 逻辑毫秒: 0, 绘制毫秒: 0, 全量帧: false });
    // 第一窗：25 × 40ms = 1000ms —— 每个间隔都跌破 30fps，但都不算长任务。
    for (let i = 0; i < 25; i++) {
      时刻 += 40;
      采样.记录帧({ 时刻毫秒: 时刻, 逻辑毫秒: 0, 绘制毫秒: 0, 全量帧: false });
    }
    expect(采样.读取().点[0]?.慢帧数).toBe(25);
    expect(采样.读取().点[0]?.长任务帧数).toBe(0);
    // 第二窗：17 × 60ms = 1020ms —— 两条线都记。
    for (let i = 0; i < 17; i++) {
      时刻 += 60;
      采样.记录帧({ 时刻毫秒: 时刻, 逻辑毫秒: 0, 绘制毫秒: 0, 全量帧: false });
    }
    const 第二窗 = 采样.读取().点[1];
    expect(第二窗?.慢帧数).toBe(17);
    expect(第二窗?.长任务帧数).toBe(17);
  });

  test("全量帧与自定义计数按窗口增量、全时段累加", () => {
    const 采样 = 创建压测采样({ 读取资源: () => 资源() });
    let 时刻 = 0;
    采样.记录帧({ 时刻毫秒: 0, 逻辑毫秒: 0, 绘制毫秒: 0, 全量帧: true });
    for (let i = 0; i < 60; i++) {
      时刻 += 16.7;
      采样.计数("淘汰图集", 1);
      采样.记录帧({ 时刻毫秒: 时刻, 逻辑毫秒: 0, 绘制毫秒: 0, 全量帧: i === 5 });
    }
    const { 点, 汇总 } = 采样.读取();
    expect(点.length).toBe(1);
    expect(点[0]?.全量帧数).toBe(2);
    expect(点[0]?.计数.淘汰图集).toBe(60);
    expect(汇总.全量帧数).toBe(2);
    expect(汇总.计数.淘汰图集).toBe(60);
    expect(采样.读取计数().淘汰图集).toBe(60);
  });

  test("退化比用有效首窗与末窗的 P95 比值，跳过 2 秒预热窗", () => {
    const 采样 = 创建压测采样({ 读取资源: () => 资源() });
    let 时刻 = 0;
    const 喂一段 = (帧间隔: number, 帧数: number) => {
      for (let i = 0; i < 帧数; i++) {
        时刻 += 帧间隔;
        采样.记录帧({ 时刻毫秒: 时刻, 逻辑毫秒: 0, 绘制毫秒: 0, 全量帧: false });
      }
    };
    采样.记录帧({ 时刻毫秒: 0, 逻辑毫秒: 0, 绘制毫秒: 0, 全量帧: false });
    // 第 1 窗（<2 秒，只作预热，不参与退化比）：40ms 慢帧
    喂一段(40, 26);
    // 第 2、3 窗：10ms
    喂一段(10, 200);
    // 第 4 窗：20ms，应当被识别为退化
    喂一段(20, 60);
    const { 点, 汇总 } = 采样.读取();
    expect(点.length).toBeGreaterThanOrEqual(3);
    expect(汇总.首窗帧间隔P95).toBeCloseTo(10, 5);
    expect(汇总.末窗帧间隔P95).toBeCloseTo(20, 5);
    expect(汇总.退化比).toBeCloseTo(2, 5);
  });

  test("重置清空时间线与计数，但保留资源读取", () => {
    let 缓冲 = 1024;
    const 采样 = 创建压测采样({ 读取资源: () => 资源({ 缓冲字节: 缓冲 }) });
    喂帧(采样, 10, 120);
    采样.计数("全量帧");
    expect(采样.读取().点.length).toBe(1);
    采样.重置();
    expect(采样.读取().点).toEqual([]);
    expect(采样.读取计数()).toEqual({});
    缓冲 = 4096;
    喂帧(采样, 10, 110);
    const 点 = 采样.读取().点[0];
    expect(点?.资源.缓冲字节).toBe(4096);
  });
});

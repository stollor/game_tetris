import { describe, expect, test } from "bun:test";
import {
  创建浮层节点,
  创建遮罩节点,
  界面层,
  设为界面层,
} from "../../.gamemaker/依赖/框架/界面/层级";
import { 绘制带 } from "../../.gamemaker/依赖/框架/界面/绘制带";
import { 绘制组件 } from "../../.gamemaker/依赖/框架/节点/组件/绘制";
import { 节点 } from "../../.gamemaker/依赖/框架/节点/节点";

/**
 * 语义层级是「浮层压对位置」的唯一契约：业务不写带号，框架保证
 * 遮罩在内容之下、浮层在控件之上。1.2.0 曾把这两条规则漏成数字带，炸出
 * 设置界面黑遮罩与商店确认纸页穿透。
 */
describe("框架语义层级", () => {
  test("层序固定：遮罩 < 内容 < 控件 < 浮层", () => {
    expect(界面层.底层).toBeLessThan(界面层.内容);
    expect(界面层.内容).toBeLessThan(界面层.控件);
    expect(界面层.控件).toBeLessThan(界面层.浮层);
    expect(界面层.底层).toBe(绘制带.动态);
    expect(界面层.浮层).toBeGreaterThan(绘制带.交互);
  });

  test("创建遮罩节点落在最底层，创建浮层节点落在最高带", () => {
    const 根 = new 节点("根");
    const 遮罩 = 创建遮罩节点(根, {
      名称: "遮罩",
      坐标: { 位置X: 0, 位置Y: 0, 宽: 100, 高: 100 },
      组件: new 绘制组件({ 绘制: () => undefined }),
    });
    const 浮层 = 创建浮层节点(根, {
      名称: "浮层",
      坐标: { 位置X: 0, 位置Y: 0, 宽: 100, 高: 100 },
      组件: new 绘制组件({ 绘制: () => undefined }),
    });
    expect(遮罩.读取绘制带()).toBe(界面层.底层);
    expect(浮层.读取绘制带()).toBe(界面层.浮层);
  });

  test("设为界面层按语义改带，控件层覆盖自动分成的文字带", () => {
    const 根 = new 节点("根");
    const 文字 = 创建浮层节点(根, {
      名称: "文字",
      坐标: { 位置X: 0, 位置Y: 0, 宽: 10, 高: 10 },
      组件: new 绘制组件({ 绘制: () => undefined }),
    });
    设为界面层(文字, "控件");
    expect(文字.读取绘制带()).toBe(界面层.控件);
    设为界面层(文字, "浮层");
    expect(文字.读取绘制带()).toBe(界面层.浮层);
  });

  test("浮层遮罩/浮层是基类三条带之外的两条扩展带", () => {
    expect(Number(界面层.浮层遮罩)).toBe(绘制带.交互 + 1);
    expect(Number(界面层.浮层)).toBe(绘制带.交互 + 2);
  });
});

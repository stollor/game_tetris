function 假存储(): Storage {
  const 数据 = new Map<string, string>();
  return {
    get length() {
      return 数据.size;
    },
    clear: () => 数据.clear(),
    getItem: (键: string) => 数据.get(键) ?? null,
    key: (索引: number) => [...数据.keys()][索引] ?? null,
    removeItem: (键: string) => void 数据.delete(键),
    setItem: (键: string, 值: string) => void 数据.set(键, 值),
  };
}


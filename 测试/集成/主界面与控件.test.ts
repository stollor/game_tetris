function 点按钮(
  命中: 命中分发,
  页面: {
    读取界面(): {
      按钮: readonly { 名称: string; 左: number; 上: number; 宽: number; 高: number }[];
    };
  },
  名称: string,
): void {
  const 按钮 = 页面.读取界面().按钮.find((项) => 项.名称 === 名称);
  if (!按钮) throw Error(`缺少按钮：${名称}`);
  const 点 = { x: 按钮.左 + 按钮.宽 / 2, y: 按钮.上 + 按钮.高 / 2 };
  命中.派发("按下", 点);
  命中.派发("抬起", 点);
}

function 滑动(命中: 命中分发, 从: { x: number; y: number }, 到: { x: number; y: number }): void {
  命中.派发("按下", 从);
  命中.派发("抬起", 到, { 起始坐标: 从, 经过毫秒: 120 });
}


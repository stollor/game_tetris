/**
 * 游戏侧画笔装配/配方接入测试：GM 已承载文字服务/画笔/控件文字适配的通用用例
 * （GM `测试/规则/框架/Three*.test.ts`），这里只验证《再消一行》自己的注入值：
 * 默认字体栈、三档字号映射、文字档位配置派生、档位样式 token，以及启动层同款装配后
 * 控件文字与页面自绘文字都落到同一个画笔上。不依赖 canvas/WebGL。
 */

const 白块: 紫外线矩形 = { u: 0, v: 0, 宽: 0.1, 高: 0.1 };

interface 假图集记录 {
  选项: 文字图集选项;
  调用: { 文本: string; 颜色: readonly number[] }[];
}

function 假图集工厂(记录表: 假图集记录[]) {
  return (选项: 文字图集选项): 文字图集接口 => {
    const 记录: 假图集记录 = { 选项, 调用: [] };
    记录表.push(记录);
    const 页面边长 = 选项.页面边长 ?? 1024;
    const 纹理 = new Texture();
    const 测量 = (文本: string) => Array.from(文本).length * 选项.字号;
    return {
      注册: () => undefined,
      读取纹理: () => 纹理,
      读取纯色紫外线: () => 白块,
      读取行高: () => 选项.字号,
      测量,
      排版: (文本: string, 最大宽度: number) => ({
        行: [{ 文本, 宽: 测量(文本), 字形: [] }],
        宽: Math.min(测量(文本), 最大宽度),
        高: 选项.字号,
      }),
      绘制: (_合批, 文本, 绘制选项) => {
        记录.调用.push({ 文本, 颜色: 绘制选项.颜色 ?? [1, 1, 1, 1] });
        return { 行: [], 宽: 0, 高: 0 };
      },
      读取统计: () => ({ 页数: 1, 字形数: 0, 页面边长, 纹理字节: 页面边长 * 页面边长 * 4 }),
      销毁: () => undefined,
    };
  };
}

function 空资源层(): 资源层 {
  return {
    读取帧: () => undefined,
    读取页纹理: () => undefined,
    读取散图: () => undefined,
    读取统计: () => ({ 图集数: 0, 页数: 0, 帧数: 0, 纹理字节: 0, 散图数: 0 }),
    销毁: () => undefined,
  };
}

/** 与启动层相同的装配顺序：文字服务 → 画笔 → 控件文字。 */
function 创建装配() {
  const 图集记录: 假图集记录[] = [];
  const 合批 = new 图元合批({ 纹理: new Texture() });
  const 文字 = 创建文字服务({
    登记纹理: () => () => undefined,
    字体: 默认字体栈,
    档位配置: 文字档位配置,
    创建图集: 假图集工厂(图集记录),
  });
  const 画笔 = 创建画笔({ 合批, 文字服务: 文字, 资源层: 空资源层() });
  const 控件文字 = 创建控件文字服务({
    画笔,
    读取档位样式: (档) => 读取档位文字样式(档),
    读取纯色紫外线: () => {
      const 纯色 = 合批.读取纯色();
      if (!纯色) throw new Error("图元合批尚未设置纯色白块");
      return 纯色.紫外线;
    },
  });
  const 环境: 绘制环境 = {
    合批,
    图形: 画笔.图形,
    方块方案: 方块外观方案表[0],
    画笔,
    主题: 创建游戏主题({ ...默认设置 }),
  };
  return { 图集记录, 合批, 文字, 画笔, 控件文字, 环境 };
}

test("文字配置：默认字体栈、三档字号映射与档位配置派生保持旧版语义", () => {
  expect(默认字体栈).toBe('"Segoe UI", "Microsoft YaHei", sans-serif');
  expect(默认字体栈).toBe(游戏外观.字体.家族);
  expect(字号档设置).toEqual({
    小: { 字号: 14, 字重: "常规" },
    中: { 字号: 18, 字重: "常规" },
    大: { 字号: 24, 字重: "粗体" },
  });
  expect(文字档位配置).toEqual({
    档位: [
      { 名称: "小", 字号: 14 },
      { 名称: "中", 字号: 18 },
      { 名称: "大", 字号: 24 },
    ],
  });

  const 正文 = 读取霓虹文字样式("正文");
  for (const 档 of ["小", "中", "大"] as const) {
    const 样式 = 读取档位文字样式(档);
    // 字号/字重取档位映射，字体继承正文 token（= 默认字体栈），颜色保留基础样式由控件请求覆盖。
    expect(样式).toMatchObject({
      字体: 默认字体栈,
      字号: 字号档设置[档].字号,
      字重: 字号档设置[档].字重,
      颜色: 正文.颜色,
    });
  }
});

test("装配：文字服务带游戏字体与档位配置，画笔白块与文字图集同源", () => {
  const { 图集记录, 合批, 文字, 画笔 } = 创建装配();
  // 基础图集用游戏字体栈（不是框架默认 "sans-serif"）。
  expect(图集记录[0]?.选项.字体).toBe(默认字体栈);
  // 档位配置只暴露/映射，不参与烘焙：按请求字号建图集，键里是请求字号。
  expect(文字.读取档位配置()).toEqual(文字档位配置);
  expect(文字.读取档位(19)?.名称).toBe("中");
  expect(文字.读取档位(16)?.名称).toBe("小");
  文字.测量("甲", { 字号: 19, 颜色: 0xffffff });
  expect(图集记录[1]?.选项).toMatchObject({ 字体: 默认字体栈, 字号: 19 });
  expect(文字.读取统计().图集列表[1]?.键).toBe(`文字/${默认字体栈}|19|常规|2`);

  // 画笔把文字服务基础白块登记进合批，并设置纯色 UV。
  const 纯色 = 合批.读取纯色();
  expect(纯色?.紫外线).toEqual(白块);
  expect(画笔.读取纯色紫外线()).toEqual(白块);

  文字.销毁();
  合批.销毁();
});

test("控件文字按游戏档位样式测量/绘制，颜色由控件请求覆盖", () => {
  const { 控件文字, 图集记录 } = 创建装配();
  expect(控件文字.读取行高("小")).toBe(14);
  expect(控件文字.读取行高("中")).toBe(18);
  expect(控件文字.读取行高("大")).toBe(24);
  expect(控件文字.测量("AB", "大")).toBe(48);

  const 结果 = 控件文字.绘制(
    { 添加: () => true },
    {
      文本: "标题",
      左: 10,
      上: 20,
      字号档: "中",
      颜色: 0xffcc00,
      对齐: "左",
    },
  );
  // 2 字 × 18，行高 = 18 → 一行。
  expect(结果).toEqual({ 宽: 36, 高: 18, 行数: 1 });
  const 中记录 = 图集记录.find((项) => 项.选项.字号 === 18);
  expect(中记录?.选项.字体).toBe(默认字体栈);
  const 调用 = 中记录?.调用.at(-1);
  expect(调用?.文本).toBe("标题");
  expect(调用?.颜色[0]).toBeCloseTo(0xff / 255);
  expect(调用?.颜色[1]).toBeCloseTo(0xcc / 255);
  expect(调用?.颜色[2]).toBeCloseTo(0);
});

test("视觉/绘制接入：页面自绘文字与矩形走同一个画笔与档位映射", () => {
  const { 环境, 合批, 图集记录 } = 创建装配();
  // 行高按档位样式测量：大档 24。
  expect(绘制文字行高(环境, "大")).toBe(24);
  expect(绘制文字行高(环境, "小")).toBe(14);

  const 宽 = 绘制文字(环境, "大", "12", 20, 30, { 颜色: 0x112233 });
  expect(宽).toBe(48);
  const 大记录 = 图集记录.find((项) => 项.选项.字号 === 24);
  expect(大记录?.选项.字体).toBe(默认字体栈);
  expect(大记录?.选项.字重).toBe("bold");
  const 调用 = 大记录?.调用.at(-1);
  expect(调用?.文本).toBe("12");
  expect(调用?.颜色[0]).toBeCloseTo(0x11 / 255);
  expect(调用?.颜色[3]).toBeCloseTo(1);

  // 纯色矩形复用画笔白块 UV，写进共享合批。
  const 之前 = 合批.读取统计().四边形数;
  添加矩形(环境, { 左: 1, 上: 2, 宽: 3, 高: 4 }, 0x00ff00, 0.5);
  expect(合批.读取统计().四边形数).toBe(之前 + 1);
});

import { describe, expect, test } from "bun:test";
import {
  模式名称,
  模式目标文案,
  读取对局计时文案,
  读取每日日期,
} from "../代码/three版/对局/四模式";
import {
  更新最近结算,
  清空最近结算,
  记录最近结算,
  读取最近结算,
} from "../代码/three版/对局/最近对局";
import {
  type 最近结算,
  生成对局结果,
  生成结算徽标,
  生成结算统计,
  结算标题,
  结算重开锁毫秒,
  读取历史最佳文案,
  读取奖励文案,
  读取重开锁剩余毫秒,
} from "../代码/three版/对局/结算数据";
import { 创建新局, type 游戏模式 } from "../代码/玩法/再消一行";
import { 获取文案 } from "../代码/配置/再消一行文案";

function 模式状态(模式: 游戏模式) {
  return 创建新局(() => 0.5, [], 模式);
}

const 文案 = 获取文案("简体中文");

describe("Three 版四模式展示口径", () => {
  test("每日日期取 UTC 日期，同一天稳定", () => {
    const 时间 = new Date("2026-10-20T23:30:00Z");
    expect(读取每日日期(时间)).toBe("2026-10-20");
    expect(读取每日日期(new Date("2026-10-20T00:10:00Z"))).toBe("2026-10-20");
  });

  test("四种模式名称与目标文案", () => {
    expect(模式名称("马拉松", 文案)).toBe(文案.模式马拉松);
    expect(模式名称("每日挑战", 文案)).toBe(文案.模式每日挑战);
    expect(模式目标文案("冲刺", 文案)).toContain("40");
    expect(模式目标文案("极限", 文案)).toContain("120");
    expect(模式目标文案("马拉松", 文案)).toBe("目标 100L");
  });

  test("冲刺按 50ms 整桶计时、极限显示剩余整秒、每日挑战显示日期", () => {
    const 状态 = 模式状态("冲刺");
    状态.有效用时 = 12345;
    expect(读取对局计时文案("冲刺", 状态, "2026-10-20")).toBe("40L · 12.30s");
    状态.阶段 = "暂停";
    expect(读取对局计时文案("冲刺", 状态, "2026-10-20")).toBe("40L · 12.35s");

    const 极限 = 模式状态("极限");
    极限.剩余时间 = 119500;
    expect(读取对局计时文案("极限", 极限, "2026-10-20")).toBe("120s");

    expect(读取对局计时文案("每日挑战", 模式状态("每日挑战"), "2026-10-20")).toBe("2026-10-20");
    expect(读取对局计时文案("马拉松", 模式状态("马拉松"), "2026-10-20")).toBe("");
  });

  test("结算结果按模式记用时：马拉松/每日挑战为 null，冲刺/极限记有效用时", () => {
    const 冲刺 = 模式状态("冲刺");
    冲刺.有效用时 = 12345;
    冲刺.分数 = 800;
    冲刺.消行数 = 10;
    const 冲刺结果 = 生成对局结果("冲刺", 冲刺, "2026-10-20");
    expect(冲刺结果.用时毫秒).toBe(12345);
    expect(冲刺结果.完赛).toBe(false);
    expect(冲刺结果.日期).toBe("2026-10-20");
    expect(生成对局结果("马拉松", 模式状态("马拉松"), "2026-10-20").用时毫秒).toBeNull();
    expect(生成对局结果("每日挑战", 模式状态("每日挑战"), "2026-10-20").用时毫秒).toBeNull();
  });
});

describe("Three 版结算数据", () => {
  test("冲刺结算看用时与历史最佳，极限看等级/行数，其余看行数/等级/连击", () => {
    const 冲刺 = { ...生成对局结果("冲刺", 模式状态("冲刺"), "2026-10-20"), 用时毫秒: 63210 };
    const 冲刺统计 = 生成结算统计("冲刺", 冲刺, { 分数: 999, 用时: 62000 }, 文案);
    expect(冲刺统计.map((项) => 项.标签)).toEqual([文案.有效用时, 文案.消除行数, 文案.历史最佳]);
    expect(冲刺统计[0]?.数值).toBe("63.21s");
    expect(冲刺统计[2]?.数值).toBe("62.00s");

    const 极限 = { ...生成对局结果("极限", 模式状态("极限"), "2026-10-20"), 等级: 6, 消行数: 55 };
    const 极限统计 = 生成结算统计("极限", 极限, { 分数: 5200, 用时: null }, 文案);
    expect(极限统计[0]?.标签).toContain(文案.最高等级);
    expect(极限统计[0]?.数值).toBe("6 / 55");
    expect(极限统计[1]?.标签).toBe(文案.有效用时);

    const 马拉松 = { ...生成对局结果("马拉松", 模式状态("马拉松"), "2026-10-20"), 最长连击: 4 };
    const 马拉松统计 = 生成结算统计("马拉松", 马拉松, null, 文案);
    expect(马拉松统计.map((项) => 项.标签)).toEqual([文案.消除行数, 文案.最高等级, 文案.最佳连击]);
    expect(马拉松统计[1]?.数值).toBe("1");
  });

  test("历史最佳与徽标按模式区分，冲刺未完赛不写纪录", () => {
    expect(读取历史最佳文案("冲刺", null, 文案)).toBe(文案.暂无完赛纪录);
    expect(读取历史最佳文案("冲刺", { 分数: 0, 用时: 55000 }, 文案)).toBe("55.00s");
    expect(读取历史最佳文案("马拉松", null, 文案)).toBe(文案.暂无纪录);
    expect(读取历史最佳文案("马拉松", { 分数: 12345, 用时: null }, 文案)).toBe("12,345 pts");

    const 冲刺 = { ...生成对局结果("冲刺", 模式状态("冲刺"), "2026-10-20"), 完赛: true };
    expect(生成结算徽标("冲刺", 冲刺, true, 文案)).toContain(文案.纪录刷新);
    expect(生成结算徽标("冲刺", 冲刺, false, 文案)).toContain(文案.纪录未刷新);
    expect(生成结算徽标("极限", 冲刺, false, 文案)).toBe(`${文案.模式极限} · ${文案.纪录未刷新}`);
    const 马拉松 = { ...生成对局结果("马拉松", 模式状态("马拉松"), "2026-10-20"), 完赛: true };
    expect(生成结算徽标("马拉松", 马拉松, false, 文案)).toContain(文案.挑战完成);
    expect(结算标题({ ...马拉松, 完赛: false }, 文案)).toBe(文案.游戏结束);
  });

  test("马拉松与每日挑战结束 3 秒防误触，冲刺/极限不锁", () => {
    const 结束 = 100000;
    expect(读取重开锁剩余毫秒("马拉松", 结束, 结束)).toBe(结算重开锁毫秒);
    expect(读取重开锁剩余毫秒("每日挑战", 结束, 结束 + 2000)).toBe(1000);
    expect(读取重开锁剩余毫秒("马拉松", 结束, 结束 + 5000)).toBe(0);
    expect(读取重开锁剩余毫秒("冲刺", 结束, 结束)).toBe(0);
    expect(读取重开锁剩余毫秒("极限", 结束, 结束)).toBe(0);
  });

  test("奖励文案：成功显示新增金币、0 新增显示原因、失败提示重试", () => {
    const 基础: 最近结算 = {
      编号: "test",
      结果: 生成对局结果("马拉松", 模式状态("马拉松"), "2026-10-20"),
      目标达成: false,
      刷新纪录: false,
      历史最佳: null,
      金币: { 新增: 55, 总额: 175, 原因: "对局 30" },
      金币失败原因: "",
      新成就: [],
      结束时刻毫秒: 0,
      奖励输入: {
        编号: "test",
        分数: 0,
        消行: 0,
        用时: 0,
        落块: 0,
        破纪录: false,
        日期: "2026-10-20",
      },
    };
    expect(读取奖励文案(基础)).toBe("旅行方块币 +55");
    expect(读取奖励文案({ ...基础, 金币: { 新增: 0, 总额: 120, 原因: "对局满45秒" } })).toBe(
      "对局满45秒",
    );
    expect(读取奖励文案({ ...基础, 金币: null, 金币失败原因: "存储空间不足" })).toContain(
      "点击这里重试",
    );
    expect(读取奖励文案({ ...基础, 金币: null, 金币失败原因: "" })).toBe("");
  });
});

describe("Three 版最近结算单例", () => {
  test("写入、读取、更新与清空，编号不一致不覆盖", () => {
    清空最近结算();
    expect(读取最近结算()).toBeNull();
    const 结算: 最近结算 = {
      编号: "a",
      结果: 生成对局结果("马拉松", 模式状态("马拉松"), "2026-10-20"),
      目标达成: false,
      刷新纪录: true,
      历史最佳: null,
      金币: null,
      金币失败原因: "",
      新成就: ["first-lock"],
      结束时刻毫秒: 1,
      奖励输入: {
        编号: "a",
        分数: 0,
        消行: 0,
        用时: 0,
        落块: 0,
        破纪录: false,
        日期: "2026-10-20",
      },
    };
    记录最近结算(结算);
    expect(读取最近结算()?.编号).toBe("a");
    更新最近结算({ ...结算, 编号: "b" });
    expect(读取最近结算()?.编号).toBe("a");
    更新最近结算({ ...结算, 金币失败原因: "重试" });
    expect(读取最近结算()?.金币失败原因).toBe("重试");
    清空最近结算();
    expect(读取最近结算()).toBeNull();
  });
});

test("五模式像素仪表保留真实分数等级行数计时与目标", () => {
  for (const 模式 of ["马拉松", "冲刺", "极限", "每日挑战", "练习"] as const) {
    const 记录 = 记录绘制();
    const 输入 = {
      布局: 计算对局布局(390, 844, { 模式, 阶段: "进行中" }),
      模式,
      等级: 7,
      行数: 12,
      计分: { 显示分数: 12345, 目标分数: 12345, 击中: 0.5, 流光: [] },
      剩余毫秒: 9000,
      有效毫秒: 45000,
      省电: false,
    };
    绘制对局仪表像素(记录.笔, 输入, "静态");
    绘制对局仪表像素(记录.笔, 输入, "动态");
    核对像素(记录.调用);
    expect(记录.文字).toContain("012345");
    if (模式 === "极限") {
      expect(记录.文字.some((值) => 值 === "0:09" || 值 === "9.0")).toBe(true);
      expect(记录.文字).toContain("7");
    } else if (模式 === "冲刺") {
      expect(记录.文字.some((值) => 值.startsWith("12/"))).toBe(true);
      expect(记录.文字).toContain("0:45");
    } else {
      expect(记录.文字.some((值) => 值 === "12" || 值.startsWith("12/"))).toBe(true);
      expect(记录.文字).toContain("7");
    }
  }
});

test("落块消行锁定庆祝只绘制实色方格，已结束特效不残留", () => {
  const 记录 = 记录绘制();
  绘制像素落块拖尾(记录.图形, {
    列: [{ 列: 4, 底: 360, 初始高度: 240 }],
    色: 像素规范.色.青,
    格: 24,
    进度: 0.25,
    拖尾长: 240,
  });
  绘制像素锁定闪光(记录.图形, { 格子: [[4, 19]], 格: 24, 透明度: 0.5 });
  绘制像素消行(记录.图形, { 行: [18, 19], 时间毫秒: 120, 格: 24, 强调色: 像素规范.色.青 });
  绘制像素四行庆祝(记录.图形, { 格: 24, 时间毫秒: 120, 时长毫秒: 900 });
  核对像素(记录.调用);
  const 后 = 记录.调用.length;
  绘制像素落块拖尾(记录.图形, { 列: [], 色: 0, 格: 24, 进度: 1, 拖尾长: 240 });
  绘制像素消行(记录.图形, { 行: [19], 时间毫秒: 1000, 格: 24, 强调色: 0 });
  绘制像素四行庆祝(记录.图形, { 格: 24, 时间毫秒: 900, 时长毫秒: 900 });
  expect(记录.调用.length).toBe(后);
});


function 记录绘制() {
  const 调用: { 方法: string; 参数: unknown[] }[] = [];
  let 图形: 图形对象;
  图形 = new Proxy({} as 图形对象, {
    get(_目标, 属性) {
      return (...参数: unknown[]) => {
        调用.push({ 方法: String(属性), 参数 });
        return 图形;
      };
    },
  });
  const 文字: string[] = [];
  const 笔: 画笔 = {
    图形,
    测量文字: (文案, 样式) => ({ 宽: (文案.length * 样式.字号) / 2, 高: 样式.字号 }),
    绘制文字: (项) => {
      文字.push(项.文案);
      return { 宽: 24, 高: 16 };
    },
    绘制纹理帧: () => false,
    绘制散图: () => false,
    读取纯色紫外线: () => ({ u: 0, v: 0, 宽: 1, 高: 1 }),
    重置: () => {},
    压入裁剪: () => {},
    弹出裁剪: () => {},
  };
  return { 图形, 笔, 调用, 文字 };
}

function 核对像素(调用: ReturnType<typeof 记录绘制>["调用"]) {
  expect(
    调用.some((项) =>
      /Circle|Ellipse|Rounded|Gradient|Triangle|Points|Path|lineBetween/.test(项.方法),
    ),
  ).toBe(false);
  for (const 项 of 调用.filter((项) => 项.方法 === "fillRect")) {
    expect(项.参数.every((值) => typeof 值 === "number" && Number.isFinite(值))).toBe(true);
    expect(Number(项.参数[2])).toBeGreaterThanOrEqual(0);
    expect(Number(项.参数[3])).toBeGreaterThanOrEqual(0);
  }
}

test("街机彩砖方块实心七色，描边走壳色", () => {
  const 设置 = { ...默认设置, 主题选择: 街机彩砖规范.名称 };
  设置预览主题读取(
    () => 设置,
    () => 解析游戏主题(设置, 街机彩砖规范.名称),
  );
  try {
    expect(像素规范.名称).toBe("街机彩砖");
    const 图案 = Object.values(街机彩砖规范.方块).map((色) => {
      const 记录 = 记录绘制();
      绘制糖果方块(记录.图形, 0, 0, 24, 色);
      核对像素(记录.调用);
      const 填色 = 记录.调用.filter((项) => 项.方法 === "fillStyle").map((项) => 项.参数[0]);
      expect(填色).toContain(色);
      expect(填色).toContain(街机彩砖规范.色.壳);
      return JSON.stringify(记录.调用.filter((项) => 项.方法 === "fillRect"));
    });
    expect(new Set(图案).size).toBe(7);
  } finally {
    设置预览主题读取();
  }
});


/**
 * Three 版对局接入 代码/玩法 的计分链路验证：
 * 页面只负责把输入接到这些规则调用，所以这里直接验证「真实按键路径 → 计分/事件」。
 */

function 填底行(状态: ReturnType<typeof 创建新局>, 空列: readonly number[]): void {
  const 底行 = 状态.棋盘.at(-1);
  if (!底行) throw new Error("缺少底行");
  for (let 列 = 0; 列 < 底行.length; 列++) 底行[列] = 空列.includes(列) ? null : "J";
}

/** 硬降到最底需要下落的行数：最低格落到可见最底行（19）。 */
function 读取下落距离(状态: ReturnType<typeof 创建新局>): number {
  const 最低格 = Math.max(...读取格子(状态.当前方块).map(([, 行]) => 行));
  return 19 - 最低格;
}

describe("Three 版计分接入", () => {
  test("单行消除记 100 分并产生消行事件与落块事件", () => {
    const 状态 = 创建新局(() => 0.5, ["I", "O"], "马拉松");
    填底行(状态, [3, 4, 5, 6]);
    const 硬降分 = 读取下落距离(状态) * 2;
    硬降(状态, () => 0.5);
    expect(状态.消行数).toBe(1);
    // 空棋盘消 1 行同时是完美清场：100 + 1000，再加硬降分。
    expect(状态.分数).toBe(100 + 1000 + 硬降分);
    expect(状态.落块事件?.行数).toBe(1);
    expect(状态.落块事件?.T旋).toBe("无");
    expect(状态.落块事件?.全清).toBe(true);
    expect(状态.消行事件?.行).toEqual([19]);
  });

  test("四行全清 = 800 × 等级 + 1000 × 等级，全清标记驱动完美清场反馈", () => {
    const 状态 = 创建新局(() => 0.5, ["I", "O"], "马拉松");
    状态.当前方块.格子 = [-1, 0, 1, 2].map((行) => ({ 列2: 8, 行2: 行 * 2 }));
    for (const 行 of 状态.棋盘.slice(-4)) {
      行.fill("J");
      行[4] = null;
    }
    const 硬降分 = 读取下落距离(状态) * 2;
    硬降(状态, () => 0.5);
    expect(状态.消行数).toBe(4);
    expect(状态.分数).toBe(800 + 1000 + 硬降分);
    expect(状态.落块事件?.全清).toBe(true);
    expect(状态.棋盘.every((行) => 行.every((格) => 格 === null))).toBe(true);
    if (!状态.落块事件) throw new Error("缺少落块事件");
    expect(获取技巧反馈(状态.落块事件, false)).toContain("完美清场");
  });

  test("连续两次单行消除触发连击倍率 1.2", () => {
    const 状态 = 创建新局(() => 0.5, ["I", "O", "T"], "马拉松");
    填底行(状态, [0, 1, 2, 3]);
    for (let 次 = 0; 次 < 3; 次++) 移动方块(状态, -1, 0, () => 0.5);
    const 首距离 = 读取下落距离(状态) * 2;
    硬降(状态, () => 0.5);
    expect(状态.消行数).toBe(1);
    expect(状态.分数).toBe(100 + 1000 + 首距离);
    expect(状态.连击).toBe(1);
    填底行(状态, [4, 5]);
    const 次距离 = 读取下落距离(状态) * 2;
    硬降(状态, () => 0.5);
    expect(状态.消行数).toBe(2);
    expect(状态.落块事件?.连击).toBe(2);
    // 第二次基础分 100 × 连击倍率 1.2 + 硬降分；O 还压着上层一行，所以不是完美清场。
    expect(状态.分数).toBe(100 + 1000 + 首距离 + Math.floor(100 * 1.2) + 次距离);
  });

  test("连续四行触发背靠背标记与 1.5 倍加成", () => {
    const 状态 = 创建新局(() => 0.5, ["I", "I"], "马拉松");
    const 摆四行缺口 = () => {
      for (const 行 of 状态.棋盘.slice(-4)) {
        行.fill("J");
        行[4] = null;
      }
    };
    状态.当前方块.格子 = [-1, 0, 1, 2].map((行) => ({ 列2: 8, 行2: 行 * 2 }));
    摆四行缺口();
    硬降(状态, () => 0.5);
    expect(状态.落块事件?.连续高难).toBe(false);
    expect(状态.消行数).toBe(4);
    // 下一块 I 重新摆成竖条再消四行，验证背靠背只由连续高难触发。
    状态.当前方块.格子 = [-1, 0, 1, 2].map((行) => ({ 列2: 8, 行2: 行 * 2 }));
    摆四行缺口();
    硬降(状态, () => 0.5);
    expect(状态.落块事件?.连续高难).toBe(true);
    expect(状态.消行数).toBe(8);
    if (!状态.落块事件) throw new Error("缺少落块事件");
    expect(获取技巧反馈(状态.落块事件, false)).toContain("背靠背");
  });

  test("旋转方块与会话输入一致：左转/180° 都走规则踢墙", () => {
    const 状态 = 创建新局(() => 0.5, ["T", "I"], "马拉松");
    expect(旋转方块(状态, 1, false, () => 0.5)).toBe(true);
    expect(状态.当前方块.旋转).toBe(1);
    expect(旋转方块(状态, 1, true, () => 0.5)).toBe(true);
    expect(状态.当前方块.旋转).toBe(3);
    expect(状态.最后旋转).toBe(true);
  });

  test("软降/硬降的分数在锁定后计入，暂存换块会重置暂存状态", () => {
    const 状态 = 创建新局(() => 0.5, ["T", "I", "O"], "马拉松");
    expect(软降一步(状态, () => 0.5)).toBe(true);
    expect(状态.软降分).toBe(1);
    expect(暂存换块(状态, () => 0.5)).toBe(true);
    expect(状态.暂存方块).toBe("T");
    expect(状态.本块已暂存).toBe(true);
    expect(暂存换块(状态, () => 0.5)).toBe(false);
    const 前 = 状态.软降分;
    硬降(状态, () => 0.5);
    expect(状态.软降分).toBe(0);
    expect(状态.分数).toBeGreaterThanOrEqual(前);
  });

  test("暂停冻结有效用时与极限剩余时间，恢复后继续累计", () => {
    const 极限 = 创建新局(() => 0.5, [], "极限");
    更新时钟(极限, 300, () => 0.5);
    expect(极限.有效用时).toBe(300);
    expect(极限.剩余时间).toBe(120000 - 300);
    切换暂停(极限);
    expect(极限.阶段).toBe("暂停");
    更新时钟(极限, 1000, () => 0.5);
    expect(极限.有效用时).toBe(300);
    expect(极限.剩余时间).toBe(120000 - 300);
    切换暂停(极限);
    更新时钟(极限, 200, () => 0.5);
    expect(极限.有效用时).toBe(500);
    expect(极限.剩余时间).toBe(120000 - 500);
  });

  test("极限倒计时归零结束，结算结果带有效用时", () => {
    const 状态 = 创建新局(() => 0.5, [], "极限");
    状态.剩余时间 = 400;
    状态.有效用时 = 119600;
    状态.分数 = 900;
    更新时钟(状态, 500, () => 0.5);
    expect(状态.阶段).toBe("结束");
    expect(状态.剩余时间).toBe(0);
    const 结果 = 生成对局结果("极限", 状态, "2026-10-20");
    expect(结果.完赛).toBe(false);
    expect(结果.用时毫秒).toBe(120100);
  });

  test("冲刺第 40 行完赛结束，结算结果标记完赛并保留有效用时", () => {
    const 状态 = 创建新局(() => 0.5, ["I", "O"], "冲刺");
    状态.消行数 = 39;
    状态.等级 = 5;
    状态.有效用时 = 45678;
    填底行(状态, [3, 4, 5, 6]);
    硬降(状态, () => 0.5);
    expect(状态.消行数).toBe(40);
    expect(状态.完赛).toBe(true);
    expect(状态.阶段).toBe("结束");
    const 结果 = 生成对局结果("冲刺", 状态, "2026-10-20");
    expect(结果.完赛).toBe(true);
    expect(结果.用时毫秒).toBe(45678);
  });

  test("每日挑战同日期重开序列一致，不同日期序列不同", () => {
    const 日期 = "2026-10-20";
    expect(每日种子(日期)).toBe(每日种子(日期));
    expect(每日方块序列(日期, 14)).toEqual(每日方块序列(日期, 14));
    expect(每日方块序列(日期, 14)).not.toEqual(每日方块序列("2026-10-21", 14));

    const 首局 = 创建新局(创建模式随机源("每日挑战", 日期), [], "每日挑战");
    const 重开 = 创建新局(创建模式随机源("每日挑战", 日期), [], "每日挑战");
    expect(重开.当前方块.类型).toBe(首局.当前方块.类型);
    expect(重开.下一个方块).toBe(首局.下一个方块);
    expect(重开.后续方块).toEqual(首局.后续方块);
    expect(重开.袋子).toEqual(首局.袋子);
  });

  test("落块事件驱动技巧反馈：T 旋/四连消/连击/背靠背文案", () => {
    const 事件 = {
      序号: 1,
      格子: [] as [number, number][],
      类型: "T" as const,
      行数: 4,
      T旋: "完整" as const,
      全清: true,
      连击: 3,
      连续高难: true,
      得分: 1500,
    };
    const 文本 = 获取技巧反馈(事件, false);
    expect(文本).toContain("完美清场");
    expect(文本).toContain("T 旋");
    expect(文本).toContain("四连消");
    expect(文本).toContain("连击 ×3");
    expect(文本).toContain("背靠背");
    expect(文本).toContain("+1500");
    expect(获取技巧反馈({ ...事件, T旋: "迷你" }, false)).toContain("迷你 T 旋");
    expect(
      获取技巧反馈({ ...事件, T旋: "无", 行数: 2, 连击: 0, 连续高难: false, 全清: false }, false),
    ).toContain("消除 2 行");
  });

  test("读取格子与预览格子口径一致，供幽灵落点与预览栏绘制", () => {
    const 状态 = 创建新局(() => 0.5, ["T"], "马拉松");
    const 格子 = 读取格子(状态.当前方块);
    expect(格子).toHaveLength(4);
    expect(格子.every(([列, 行]) => Number.isInteger(列) && Number.isInteger(行))).toBe(true);
  });
});

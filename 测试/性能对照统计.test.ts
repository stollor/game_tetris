import { describe, expect, test } from "bun:test";
import { 汇总数值, 解析轮次, 计算增量, 计算采样窗口, 重置计数 } from "./浏览器/性能对照统计";

describe("轮次参数", () => {
  test("缺省为 3，接受正整数", () => {
    expect(解析轮次([])).toBe(3);
    expect(解析轮次(["--轮次=1"])).toBe(1);
    expect(解析轮次(["--轮次=12"])).toBe(12);
  });

  test("拒绝 0、负数、小数、非数字与空值", () => {
    for (const 原文 of ["0", "-1", "1.5", "abc", "", "+2", " 2 "]) {
      expect(() => 解析轮次([`--轮次=${原文}`])).toThrow(/正整数|安全整数/);
    }
  });

  test("拒绝裸 --轮次 参数", () => {
    expect(() => 解析轮次(["--轮次", "3"])).toThrow(/--轮次=<正整数>/);
  });
});

describe("采样窗口", () => {
  test("用前后读数差算 FPS", () => {
    const 结果 = 计算采样窗口({ 帧计数: 100, 时刻毫秒: 1000 }, { 帧计数: 160, 时刻毫秒: 2000 });
    expect(结果.帧增量).toBe(60);
    expect(结果.经过毫秒).toBe(1000);
    expect(结果.FPS).toBe(60);
  });

  test("拒绝计数器重置导致的负帧增量", () => {
    expect(() =>
      计算采样窗口({ 帧计数: 200, 时刻毫秒: 1000 }, { 帧计数: 10, 时刻毫秒: 2000 }),
    ).toThrow(/负增量/);
  });

  test("拒绝零时间与时间倒流", () => {
    expect(() =>
      计算采样窗口({ 帧计数: 1, 时刻毫秒: 1000 }, { 帧计数: 2, 时刻毫秒: 1000 }),
    ).toThrow(/大于 0/);
    expect(() =>
      计算采样窗口({ 帧计数: 1, 时刻毫秒: 2000 }, { 帧计数: 2, 时刻毫秒: 1000 }),
    ).toThrow(/负增量/);
  });
});

test("差值拒绝负数；重置计数拒绝负值", () => {
  expect(计算增量(10, 25, "绘制帧")).toBe(15);
  expect(() => 计算增量(25, 10, "绘制帧")).toThrow(/负增量/);
  expect(重置计数(0)).toBe(0);
  expect(重置计数(12.5)).toBe(12.5);
  expect(() => 重置计数(-1)).toThrow(/不能为负/);
});

test("汇总：忽略缺失值，给出中位数与范围", () => {
  expect(汇总数值([3, null, 1, undefined, 2])).toEqual({
    样本数: 3,
    中位数: 2,
    最小: 1,
    最大: 3,
  });
  expect(汇总数值([4, 1, 3, 2])).toEqual({
    样本数: 4,
    中位数: 2.5,
    最小: 1,
    最大: 4,
  });
  expect(汇总数值([null, undefined])).toEqual({
    样本数: 0,
    中位数: null,
    最小: null,
    最大: null,
  });
});

test("两套主题的顶栏外观配色仍取自身规范", () => {
  const 街机 = 记录();
  const 晶格 = 记录();
  在主题内("街机彩砖", () => {
    expect(读取背景外观配色("极光原野").文字基调).toBe("深底");
    街机.图.fillStyle(读取背景外观配色("极光原野").主色);
  });
  在主题内("立体晶格", () => {
    expect(读取背景外观配色("极光原野").文字基调).toBe("深底");
    晶格.图.fillStyle(读取背景外观配色("极光原野").主色);
  });
  expect(序列(街机.调用)[0][1]).not.toBe(序列(晶格.调用)[0][1]);
  expect(默认主题编号).toBe("极光原野");
});

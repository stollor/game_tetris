/**
 * 根据固定的设备轴和固定头尾区，计算响应式设计画布。
 * 设计坐标仍使用基准宽高；头尾保持基准尺寸，中间区域吸收高度变化。
 */
export interface 响应式视口配置 {
  视口宽: number;
  视口高: number;
  基准宽: number;
  基准高: number;
  固定轴: "宽度" | "高度";
  顶栏高: number;
  底栏起点: number;
  中区最小高: number;
  最大比例?: number;
}

export interface 响应式视口结果 {
  比例: number;
  左: number;
  顶: number;
  设计宽: number;
  设计高: number;
  中区高: number;
  全局缩放: boolean;
  映射Y(设计Y: number): number;
}

/** 固定顶栏与底栏，只让中区伸缩；中区低于最小高度时整体等比缩小。 */
export function 计算响应式视口(配置: 响应式视口配置): 响应式视口结果 {
  const 最大比例 = 配置.最大比例 ?? 1.25;
  const 宽度比例 = 配置.视口宽 / 配置.基准宽;
  const 高度比例 = 配置.视口高 / 配置.基准高;
  let 比例 = 配置.固定轴 === "宽度" ? Math.min(最大比例, 宽度比例) : Math.min(最大比例, 高度比例);
  let 设计宽 = 配置.视口宽 / 比例;
  let 设计高 = 配置.视口高 / 比例;
  const 基准中区高 = 配置.底栏起点 - 配置.顶栏高;
  let 中区高 = 设计高 - 配置.顶栏高 - (配置.基准高 - 配置.底栏起点);
  const 全局缩放 =
    中区高 < 配置.中区最小高 ||
    (配置.固定轴 === "高度" && 配置.视口宽 / 配置.视口高 < 配置.基准宽 / 配置.基准高);

  if (全局缩放) {
    比例 = Math.min(最大比例, 宽度比例, 高度比例);
    设计宽 = 配置.基准宽;
    设计高 = 配置.基准高;
    中区高 = 基准中区高;
  }

  const 逻辑画布宽 = 全局缩放 || 配置.固定轴 === "宽度" ? 配置.基准宽 : 设计宽;
  const 左 = (配置.视口宽 - 逻辑画布宽 * 比例) / 2;
  const 顶 = (配置.视口高 - 设计高 * 比例) / 2;
  const 中区偏移 = 全局缩放 ? 0 : Math.max(0, (中区高 - 基准中区高) / 2);

  return {
    比例,
    左,
    顶,
    设计宽: 逻辑画布宽,
    设计高,
    中区高,
    全局缩放,
    映射Y(设计Y: number): number {
      if (全局缩放) return 顶 + 设计Y * 比例;
      let 映射后Y = 设计Y;
      if (设计Y >= 配置.顶栏高 && 设计Y < 配置.底栏起点) {
        映射后Y = 设计Y + 中区偏移;
      } else if (设计Y >= 配置.底栏起点) {
        映射后Y = 设计Y + (设计高 - 配置.基准高);
      }
      return 顶 + 映射后Y * 比例;
    },
  };
}

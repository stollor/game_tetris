import type { 渲染编排 } from "../../框架/世界/渲染编排";
import type { 页面编号 } from "../应用/接口/上下文";
import type { 设置服务 } from "../应用/接口/服务";
import { 是省电模式, 画质参数 } from "./画质";

/**
 * 性能控制：把省电模式/页面类型翻译成渲染编排的帧率上限与按需渲染。
 * - 复用游戏画质的自动设备判定与30/60帧配置；
 * - 对局进行中连续出帧，其它页面（菜单/设置/暂停）按需渲染，靠 请求重绘 唤醒。
 */

export interface 性能控制 {
  设置页面(页面: 页面编号, 对局进行中: boolean): void;
  请求重绘(): void;
  应用(): void;
  读取省电(): boolean;
  读取上限(): number;
}

export function 创建性能控制(渲染: 渲染编排, 设置: 设置服务): 性能控制 {
  let 页面: 页面编号 = "菜单";
  let 对局进行中 = false;
  let 省电 = false;
  let 上限 = 60;

  const 应用 = () => {
    const 设置值 = 设置.读取();
    const 当前省电 = 是省电模式(设置值.省电模式);
    省电 = 当前省电;
    上限 = 当前省电 ? 画质参数.省电帧率 : 画质参数.标准帧率;
    渲染.设置最大帧率(上限);
    渲染.设置按需渲染(!(页面 === "对局" && 对局进行中));
    渲染.请求重绘();
  };

  设置.订阅(() => 应用());

  return {
    设置页面: (值, 进行中) => {
      页面 = 值;
      对局进行中 = 进行中;
      应用();
    },
    请求重绘: () => 渲染.请求重绘(),
    应用,
    读取省电: () => 省电,
    读取上限: () => 上限,
  };
}

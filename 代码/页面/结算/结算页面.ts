/**
 * 结算覆盖页：压在结束的对局上，显示分数/等级/消行/用时/金币/新纪录/成就，
 * 提供「重新开始」「返回主菜单」；马拉松/每日挑战结束 3 秒内不可重开，防误触。
 * 数据来自对局页写入的 最近结算，参数里的 对局结果 只作兜底。
 */

function 兜底结算(结果: 对局结果): 最近结算 {
  return {
    编号: `兜底-${结果.日期}-${结果.分数}`,
    结果,
    目标达成: false,
    刷新纪录: false,
    历史最佳: null,
    金币: null,
    金币失败原因: "",
    新成就: [],
    结束时刻毫秒: Date.now(),
    奖励输入: {
      编号: `兜底-${结果.日期}-${结果.分数}`,
      分数: 结果.分数,
      消行: 结果.消行数,
      用时: 结果.用时毫秒 ?? 0,
      落块: 0,
      破纪录: false,
      日期: 结果.日期,
    },
  };
}

export class 结算页面 extends 页面基类<页面上下文> {
  private 数据: 最近结算;
  private 重开按钮: 按钮 | null = null;
  private 菜单按钮: 按钮 | null = null;
  private 重试按钮: 按钮 | null = null;
  private readonly 分数 = new 数值面板({ 矩形: { 左: 0, 上: 0, 宽: 1, 高: 1 }, 标签: "", 值: 0 });
  private readonly 飘字 = new 轻提示队列(1);
  private readonly 待播飘字: {
    在: number;
    文本: string;
    秒: number;
    类型: 结算飘字外观["类型"];
  }[] = [];
  private 当前飘字: 结算飘字外观["类型"] = "说明";
  private 飘字开始 = 0;
  private 飘字绘制状态: 轻提示样式状态 | null = null;
  private 已播编号 = "";
  private 已进入 = false;
  private 上次数秒 = -1;
  private 动画毫秒 = 0;
  private 上次绘制毫秒 = -1000;

  constructor(上下文: 页面上下文) {
    super(上下文, { 名称: "结算", 深度: 30, 独占: true, 背景: false });
    this.数据 = 兜底结算({
      模式: "马拉松",
      分数: 0,
      消行数: 0,
      等级: 1,
      最长连击: 0,
      用时毫秒: null,
      完赛: false,
      日期: 上下文.服务.当日日期(),
    });
  }

  进入(): void {
    const 结果 = this.上下文.参数.结果;
    this.数据 = 读取最近结算() ?? (结果 ? 兜底结算(结果) : this.数据);
    this.已进入 = true;
    this.上次数秒 = -1;
    const 首次 = this.已播编号 !== this.数据.编号;
    this.已播编号 = this.数据.编号;
    this.动画毫秒 = 首次 ? 0 : 5000;
    this.上次绘制毫秒 = -1000;
    this.分数.设置数值(0, true);
    this.分数.设置数值(this.数据.结果.分数, !首次 || this.省电());
    this.飘字.清空();
    this.待播飘字.length = 0;
    if (首次) this.编排飘字();
    super.进入();
  }

  退出(): void {
    super.退出();
    this.飘字.清空();
    this.待播飘字.length = 0;
    this.已进入 = false;
  }

  调整尺寸(): void {
    if (!this.已进入) return;
    super.调整尺寸();
  }

  更新(秒: number): void {
    if (!this.已进入) return;
    {
      this.动画毫秒 += Math.max(0, 秒) * 1000;
      if (this.动画毫秒 >= 260) this.分数.更新(秒);
      this.飘字.更新(秒);
      while (this.待播飘字[0] && this.待播飘字[0].在 <= this.动画毫秒) {
        const 项 = this.待播飘字.shift();
        if (!项) break;
        const 已过秒 = (this.动画毫秒 - 项.在) / 1000;
        if (已过秒 >= 项.秒) continue;
        this.当前飘字 = 项.类型;
        this.飘字开始 = 项.在;
        this.飘字.显示(项.文本, 项.秒);
        this.飘字.更新(已过秒);
      }
      // 先降低请求率让框架进入100ms心跳，80ms容差可避免心跳略短时隔拍。
      const 帧间隔 = this.动画毫秒 < 5000 ? 0 : this.省电() ? 80 : 1000 / 30;
      if (this.动画毫秒 - this.上次绘制毫秒 >= 帧间隔 - 0.1) {
        this.上次绘制毫秒 = this.动画毫秒;
        this.请求重绘();
      }
    }
    this.重开按钮?.设置禁用(!this.可操作() || this.读取锁剩余毫秒() > 0);
    this.菜单按钮?.设置禁用(!this.可操作());
    this.重试按钮?.设置禁用(!this.可操作());
    super.更新(秒);
    const 剩余 = this.读取锁剩余毫秒();
    const 倒计时秒 = Math.ceil(剩余 / 1000);
    // 3 秒防误触期间每秒重绘一次按钮倒计时。
    if (倒计时秒 !== this.上次数秒) {
      this.上次数秒 = 倒计时秒;
      this.请求重绘();
    }
  }

  /** 待机循环正常档 30Hz；省电档交回框架的 100ms 空闲心跳。 */
  读取需要连续帧(): boolean {
    return (
      this.已进入 &&
      (!this.省电() ||
        this.动画毫秒 < 结算入场毫秒 ||
        this.待播飘字.length > 0 ||
        this.飘字.读取列表().length > 0 ||
        this.分数.读取显示值() !== this.分数.读取目标值())
    );
  }

  protected 绘制内容(_环境: 绘制环境): void {
    const 资源 = this.上下文.资源;
    const 文案 = this.上下文.服务.语言.读取();
    const 英文 = this.上下文.服务.语言.是否英文();
    绘制结算演出(资源.画笔, {
      标题: 结算标题(this.数据.结果, 文案),
      模式: 模式名称(this.数据.结果.模式, 文案),
      新纪录: this.数据.刷新纪录 ? (英文 ? "NEW BEST" : "新纪录") : "",
      分数: Math.round(this.分数.读取显示值()),
      金币: this.数据.金币?.新增 ?? null,
      金币标签: 英文 ? "COINS EARNED" : "本局获得",
      循环提示: this.读取循环提示(),
      统计: 生成结算统计(this.数据.结果.模式, this.数据.结果, this.数据.历史最佳, 文案),
      方块方案: 读取方块外观方案(this.上下文.服务.设置.读取()),
      挑战结果: 读取挑战结果(this.数据.结果),
      宽: 资源.逻辑宽,
      高: 资源.逻辑高,
      经过毫秒: this.动画毫秒,
      省电: this.省电(),
    });
  }

  protected 绘制覆盖(环境: 绘制环境): void {
    const 资源 = this.上下文.资源;
    const 定位 = 计算霓虹结算布局(资源.逻辑宽, 资源.逻辑高);
    this.飘字绘制状态 = 绘制结算飘字(资源.画笔, 环境, this.飘字, 定位, {
      类型: this.当前飘字,
      经过毫秒: this.动画毫秒 - this.飘字开始,
      数量: this.数据.金币?.新增 ?? 0,
      省电: this.省电(),
      成就图标:
        this.当前飘字 === "成就"
          ? 成就图标编号列表.find((项) => 项 === this.数据.新成就[0])
          : undefined,
    });
  }

  protected 读取文字快照(): readonly string[] {
    return [结算标题(this.数据.结果, this.上下文.服务.语言.读取())];
  }

  // 结算必须通过菜单或重开离开，不能由通用返回键弹回已结束的对局。
  protected 返回(): void {}

  /** 调试桥在结算覆盖页上读取的结算明细（验收直接断言金币/纪录/锁）。 */
  读取快照() {
    const 文案 = this.上下文.服务.语言.读取();
    const 结果 = this.数据.结果;
    return {
      页面: "结算",
      阶段: "结束",
      模式: 结果.模式,
      分数: 结果.分数,
      消行数: 结果.消行数,
      等级: 结果.等级,
      最长连击: 结果.最长连击,
      完赛: 结果.完赛,
      用时毫秒: 结果.用时毫秒,
      日期: 结果.日期,
      挑战结果: 读取挑战结果(结果),
      标题: 结算标题(结果, 文案),
      徽标: 生成结算徽标(结果.模式, 结果, this.数据.刷新纪录, 文案),
      统计: 生成结算统计(结果.模式, 结果, this.数据.历史最佳, 文案),
      刷新纪录: this.数据.刷新纪录,
      历史最佳: this.数据.历史最佳,
      金币奖励: this.数据.金币,
      金币失败原因: this.数据.金币失败原因,
      新成就: this.数据.新成就,
      成就文案: 读取成就文案(
        this.数据.新成就,
        this.上下文.服务.成就.全部定义(),
        this.上下文.服务.语言.是否英文(),
      ),
      奖励文案: 读取奖励文案(this.数据),
      金币余额: this.读取金币余额(),
      重开锁剩余毫秒: this.读取锁剩余毫秒(),
      动画毫秒: this.动画毫秒,
      显示分数: Math.round(this.分数.读取显示值()),
      显示金币: this.数据.金币
        ? 读取结算金币动画(this.动画毫秒 - 结算奖励开始毫秒, this.数据.金币.新增, this.省电())
            .显示数量
        : null,
      演出阶段: this.动画毫秒 < 5000 ? "入场" : "循环",
      循环帧间隔毫秒: this.省电() ? 100 : 1000 / 30,
      循环提示: this.读取循环提示(),
      需要连续帧: this.读取需要连续帧(),
      飘字: this.飘字.读取列表(),
      飘字类型: this.当前飘字,
      飘字绘制: this.飘字绘制状态,
      提示区: 计算霓虹结算布局(this.上下文.资源.逻辑宽, this.上下文.资源.逻辑高).提示区,
      金币动画: this.数据.金币
        ? 读取结算金币动画(
            this.动画毫秒 - 结算奖励开始毫秒,
            this.数据.金币.新增,
            this.上下文.服务.设置.读取().省电模式 === "开",
          )
        : null,
    };
  }

  /* ---------------------------------------------------------------- */

  private 读取锁剩余毫秒(): number {
    return 读取重开锁剩余毫秒(this.数据.结果.模式, this.数据.结束时刻毫秒, Date.now());
  }

  private 读取金币余额(): number {
    try {
      return this.上下文.服务.金币.读取().金币;
    } catch {
      return 0;
    }
  }

  protected 构建(): void {
    const 资源 = this.上下文.资源;
    const 矩形 = this.读取按钮矩形();
    const 添加 = (种类: "重开" | "菜单" | "重试", 区域: typeof 矩形.重开, 点击: () => void) =>
      this.创建按钮(种类 === "重开" ? "重新开始" : 种类 === "菜单" ? "返回主菜单" : "重试奖励", {
        矩形: 区域,
        禁用: !this.可操作() || (种类 === "重开" && this.读取锁剩余毫秒() > 0),
        点击,
        绘制底板: (_环境, 状态) =>
          绘制结算操作(
            资源.画笔,
            状态.矩形,
            this.读取操作文案(种类),
            种类,
            状态.阶段,
            this.动画毫秒,
            this.省电(),
          ),
        绘制文字: () => {},
      });
    this.重开按钮 = 添加("重开", 矩形.重开, () => this.重开());
    this.菜单按钮 = 添加("菜单", 矩形.菜单, () => this.返回主菜单());
    this.重试按钮 =
      this.数据.金币失败原因 && !this.数据.金币
        ? 添加("重试", this.读取重试矩形(), () => this.重试奖励())
        : null;
  }

  private 省电(): boolean {
    return this.上下文.服务.设置.读取().省电模式 === "开";
  }

  private 读取循环提示() {
    if (
      (this.数据.金币失败原因 && !this.数据.金币) ||
      this.待播飘字.length ||
      this.飘字.读取列表().length
    )
      return undefined;
    const 英文 = this.上下文.服务.语言.是否英文();
    const 编号 =
      this.数据.新成就[
        Math.floor(Math.max(0, this.动画毫秒 - 5000) / 3200) % this.数据.新成就.length
      ];
    const 成就 = this.上下文.服务.成就.全部定义().find((项) => 项.编号 === 编号);
    return 成就
      ? {
          文本: 英文 ? 成就.英文 : `已收藏 · ${成就.名称}`,
          图标: 成就图标编号列表.find((项) => 项 === 编号),
        }
      : {
          文本: this.数据.刷新纪录
            ? 英文
              ? "PERSONAL BEST!"
              : "纪录已刷新！"
            : 英文
              ? "ROUND COMPLETE"
              : "本局已结算",
        };
  }

  private 可操作(): boolean {
    return this.动画毫秒 >= (this.省电() ? 350 : 800);
  }

  private 读取操作文案(种类: "重开" | "菜单" | "重试"): string {
    const 英文 = this.上下文.服务.语言.是否英文();
    if (种类 === "菜单") return 英文 ? "MENU" : "返回主菜单";
    if (种类 === "重试") return 英文 ? "SAVE FAILED · RETRY" : "奖励未保存 · 点击重试";
    const 秒 = Math.ceil(this.读取锁剩余毫秒() / 1000);
    return `${英文 ? "PLAY AGAIN" : "再来一局"}${秒 > 0 ? ` · ${秒}` : ""}`;
  }

  private 编排飘字(起点 = 0): void {
    // 保存失败需要明确可重试的操作，成功后再播放奖励和成就，避免飘字盖住重试按钮。
    if (this.数据.金币失败原因 && !this.数据.金币) return;
    const 数量 = this.数据.金币?.新增 ?? 0;
    const 英文 = this.上下文.服务.语言.是否英文();
    const 原因 = this.数据.金币?.原因 ?? "";
    const 说明 = 原因.startsWith("对局满")
      ? 英文
        ? `Coins: ${金币奖励配置.有效对局秒}s + ${金币奖励配置.有效落块数} drops`
        : `奖励条件：${金币奖励配置.有效对局秒}秒 · ${金币奖励配置.有效落块数}次落块`
      : 原因;
    if (this.数据.金币)
      this.待播飘字.push({
        在: 起点 + 结算奖励开始毫秒,
        文本: 数量 > 0 ? (英文 ? "REWARD SAVED" : "奖励已入账") : 说明,
        秒: 结算奖励秒,
        类型: "说明",
      });
    const 新成就 = this.数据.新成就;
    const 定义 = this.上下文.服务.成就.全部定义().find((项) => 项.编号 === 新成就[0]);
    if (定义) {
      const 英文 = this.上下文.服务.语言.是否英文();
      const 文本 = 英文
        ? `${定义.英文}${新成就.length > 1 ? ` +${新成就.length - 1}` : ""}`
        : `${定义.名称}${新成就.length > 1 ? ` 等${新成就.length}项` : ""}`;
      this.待播飘字.push({
        在: 起点 + (this.数据.金币 ? 结算成就开始毫秒 : 结算奖励开始毫秒),
        文本,
        秒: 结算成就秒,
        类型: "成就",
      });
    }
  }

  private 读取重试矩形() {
    const 定位 = 计算霓虹结算布局(this.上下文.资源.逻辑宽, this.上下文.资源.逻辑高);
    return { 左: 定位.提示区.左 + 8, 上: 定位.奖励Y - 8, 宽: 定位.提示区.宽 - 16, 高: 42 };
  }

  private 重开(): void {
    if (!this.可操作() || this.读取锁剩余毫秒() > 0) return;
    this.上下文.导航.替换("对局", { 模式: this.数据.结果.模式 });
  }

  private 读取按钮矩形() {
    const 定位 = 计算霓虹结算布局(this.上下文.资源.逻辑宽, this.上下文.资源.逻辑高);
    const 转矩形 = (按钮: typeof 定位.重开) => ({
      左: 按钮.中心X - 按钮.宽 / 2,
      上: 按钮.中心Y - 按钮.高 / 2,
      宽: 按钮.宽,
      高: 按钮.高,
    });
    return { 重开: 转矩形(定位.重开), 菜单: 转矩形(定位.菜单) };
  }

  private 返回主菜单(): void {
    this.上下文.导航.替换("主界面");
  }

  /** 结算页测试/重试用：金币奖励失败后按同一编号重试并刷新展示数据。 */
  重试奖励(): void {
    if (this.数据.金币 || !this.数据.金币失败原因) return;
    try {
      const 结果 = this.上下文.服务.金币.结算对局(this.数据.奖励输入);
      if (结果.成功) {
        this.数据 = {
          ...this.数据,
          金币: { 新增: 结果.新增, 总额: 结果.金币, 原因: 结果.原因 },
          金币失败原因: "",
        };
        更新最近结算(this.数据);
        this.飘字.清空();
        this.待播飘字.length = 0;
        this.编排飘字(Math.max(0, this.动画毫秒 - 结算奖励开始毫秒));
      } else {
        this.数据 = { ...this.数据, 金币失败原因: 结果.原因 };
      }
    } catch {
      this.数据 = { ...this.数据, 金币失败原因: "旅行奖励保存失败" };
    }
    if (this.已进入) this.重建();
    this.请求重绘();
  }
}

export const 创建结算页面: 页面工厂 = (上下文: 页面上下文) => new 结算页面(上下文);

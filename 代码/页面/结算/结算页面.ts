/**
 * 结算覆盖页：压在结束的对局上，显示分数/等级/消行/用时/金币/新纪录/成就，
 * 提供「重新开始」「返回主菜单」；马拉松/每日挑战结束 3 秒内不可重开，防误触。
 * 数据来自对局页写入的 最近结算，参数里的 对局结果 只作兜底。
 *
 * 节点结构：结算演出绘制节点（带 0）+ 飘字绘制节点（带 1）+ 重新开始/返回主菜单/重试奖励按钮节点。
 */

function 兜底结算(结果: 对局结果): 最近结算 {
  return {
    编号: `兜底-${结果.日期}-${结果.分数}`,
    结果,
    目标达成: false,
    刷新纪录: false,
    历史最佳: null,
    金币: null,
    金币失败原因: "",
    新成就: [],
    结束时刻毫秒: Date.now(),
    奖励输入: {
      编号: `兜底-${结果.日期}-${结果.分数}`,
      分数: 结果.分数,
      消行: 结果.消行数,
      用时: 结果.用时毫秒 ?? 0,
      落块: 0,
      破纪录: false,
      日期: 结果.日期,
    },
  };
}

export class 结算页面 extends 页面基类<页面上下文> {
  private 数据: 最近结算;
  private readonly 分数 = new 数值面板({ 矩形: { 左: 0, 上: 0, 宽: 1, 高: 1 }, 标签: "", 值: 0 });
  private readonly 飘字 = new 轻提示队列(1);
  private readonly 待播飘字: {
    在: number;
    文本: string;
    秒: number;
    类型: 结算飘字外观["类型"];
  }[] = [];
  private 当前飘字: 结算飘字外观["类型"] = "说明";
  private 飘字开始 = 0;
  private 飘字绘制状态: 轻提示样式状态 | null = null;
  private 已播编号 = "";
  private 已进入 = false;
  private 上次数秒 = -1;
  private 动画毫秒 = 0;
  private 上次绘制毫秒 = -1000;
  private 上次禁用: boolean | null = null;

  private 演出节点: 节点 | null = null;
  private 飘字节点: 节点 | null = null;
  private 重开节点: 节点 | null = null;
  private 菜单节点: 节点 | null = null;
  private 重试节点: 节点 | null = null;

  constructor(上下文: 页面上下文) {
    // 浮在对局上的普通页面：不暂停对局更新、不遮同层页面（要看见对局）、独占命中。
    super(上下文, {
      名称: "结算",
      弹窗: true,
      开合: { 打开秒: 0.3, 关闭秒: 0.2 },
      不透明: false,
      暂停下层: false,
      独占命中: true,
      节点树: { 绘制带数: 2 },
    });
    this.数据 = 兜底结算({
      模式: "马拉松",
      分数: 0,
      消行数: 0,
      等级: 1,
      最长连击: 0,
      用时毫秒: null,
      完赛: false,
      日期: 上下文.服务.当日日期(),
    });
  }

  进入(): void {
    const 结果 = this.上下文.参数.结果;
    this.数据 = 读取最近结算() ?? (结果 ? 兜底结算(结果) : this.数据);
    this.已进入 = true;
    this.上次数秒 = -1;
    const 首次 = this.已播编号 !== this.数据.编号;
    this.已播编号 = this.数据.编号;
    this.动画毫秒 = 首次 ? 0 : 5000;
    this.上次绘制毫秒 = -1000;
    this.分数.设置数值(0, true);
    this.分数.设置数值(this.数据.结果.分数, !首次 || this.省电());
    this.飘字.清空();
    this.待播飘字.length = 0;
    if (首次) this.编排飘字();
    super.进入();
  }

  退出(): void {
    super.退出();
    this.飘字.清空();
    this.待播飘字.length = 0;
    this.已进入 = false;
  }

  调整尺寸(): void {
    if (!this.已进入) return;
    super.调整尺寸();
  }

  更新(秒: number): void {
    if (!this.已进入) return;
    this.动画毫秒 += Math.max(0, 秒) * 1000;
    if (this.动画毫秒 >= 260) this.分数.更新(秒);
    this.飘字.更新(秒);
    while (this.待播飘字[0] && this.待播飘字[0].在 <= this.动画毫秒) {
      const 项 = this.待播飘字.shift();
      if (!项) break;
      const 已过秒 = (this.动画毫秒 - 项.在) / 1000;
      if (已过秒 >= 项.秒) continue;
      this.当前飘字 = 项.类型;
      this.飘字开始 = 项.在;
      this.飘字.显示(项.文本, 项.秒);
      this.飘字.更新(已过秒);
    }
    // 先降低请求率让框架进入 100ms 心跳，80ms 容差可避免心跳略短时隔拍。
    const 帧间隔 = this.动画毫秒 < 5000 ? 0 : this.省电() ? 80 : 1000 / 30;
    if (this.动画毫秒 - this.上次绘制毫秒 >= 帧间隔 - 0.1) {
      this.上次绘制毫秒 = this.动画毫秒;
      this.请求重绘();
    }
    super.更新(秒);
    // 按钮禁用随「入场可操作 + 重开锁」变化；变化时只重放按钮参数并标脏演出带。
    const 禁用 = !this.可操作() || this.读取锁剩余毫秒() > 0;
    if (禁用 !== this.上次禁用) {
      this.上次禁用 = 禁用;
      this.重开节点?.读取组件<按钮组件>(按钮组件)?.应用参数(this.重开参数());
      this.菜单节点?.读取组件<按钮组件>(按钮组件)?.应用参数(this.菜单参数());
      this.重试节点?.读取组件<按钮组件>(按钮组件)?.应用参数(this.重试参数());
      this.标记失效([0, 1], "结算按钮");
    }
    const 剩余 = this.读取锁剩余毫秒();
    const 倒计时秒 = Math.ceil(剩余 / 1000);
    if (倒计时秒 !== this.上次数秒) {
      this.上次数秒 = 倒计时秒;
      this.请求重绘();
    }
  }

  /** 待机循环正常档 30Hz；省电档交回框架的 100ms 空闲心跳。 */
  读取需要连续帧(): boolean {
    return (
      this.已进入 &&
      (!this.省电() ||
        this.动画毫秒 < 结算入场毫秒 ||
        this.待播飘字.length > 0 ||
        this.飘字.读取列表().length > 0 ||
        this.分数.读取显示值() !== this.分数.读取目标值())
    );
  }

  protected 构建节点树(页面: 节点): void {
    页面.设置开合行为({ 类型: "显隐" });
    this.演出节点 = 创建注册节点(页面, {
      名称: "结算:演出",
      坐标: { 位置X: 0, 位置Y: 0, 宽: this.逻辑宽, 高: this.逻辑高, 锚点X: 0, 锚点Y: 0, 绘制带: 0 },
      组件: new 绘制组件({ 绘制: (环境) => this.绘制演出节点(环境) }),
    });
    this.飘字节点 = 创建注册节点(页面, {
      名称: "结算:飘字",
      坐标: { 位置X: 0, 位置Y: 0, 宽: this.逻辑宽, 高: this.逻辑高, 锚点X: 0, 锚点Y: 0, 绘制带: 1 },
      组件: new 绘制组件({ 绘制: (环境) => this.绘制飘字节点(环境) }),
    });
    const 矩形 = this.读取按钮矩形();
    this.重开节点 = this.创建按钮节点(
      页面,
      "重新开始",
      矩形.重开,
      () => this.重开(),
      this.重开参数(),
    );
    this.菜单节点 = this.创建按钮节点(
      页面,
      "返回主菜单",
      矩形.菜单,
      () => this.返回主菜单(),
      this.菜单参数(),
    );
    this.重试节点 = this.创建按钮节点(
      页面,
      "重试奖励",
      this.读取重试矩形(),
      () => this.重试奖励(),
      this.重试参数(),
    );
    this.应用注册参数(页面);
  }

  /** 数据 / 语言 / 尺寸变化：重放按钮几何与可见性。 */
  protected 应用注册参数(_页面: 节点): void {
    const 矩形 = this.读取按钮矩形();
    this.重开节点?.读取二维坐标()?.更新参数(this.区域坐标(矩形.重开));
    this.菜单节点?.读取二维坐标()?.更新参数(this.区域坐标(矩形.菜单));
    this.重试节点?.读取二维坐标()?.更新参数(this.区域坐标(this.读取重试矩形()));
    this.重开节点?.读取组件<按钮组件>(按钮组件)?.应用参数(this.重开参数());
    this.菜单节点?.读取组件<按钮组件>(按钮组件)?.应用参数(this.菜单参数());
    this.重试节点?.读取组件<按钮组件>(按钮组件)?.应用参数(this.重试参数());
    const 显示重试 = Boolean(this.数据.金币失败原因) && !this.数据.金币;
    this.重试节点?.设置可见(显示重试);
    this.演出节点?.读取二维坐标()?.更新参数({ 宽: this.逻辑宽, 高: this.逻辑高 });
    this.飘字节点?.读取二维坐标()?.更新参数({ 宽: this.逻辑宽, 高: this.逻辑高 });
  }

  private 创建按钮节点(
    页面: 节点,
    名称: string,
    矩形: { 左: number; 上: number; 宽: number; 高: number },
    点击: () => void,
    参数: ConstructorParameters<typeof 按钮组件>[0],
  ): 节点 {
    return 创建注册节点(页面, {
      名称,
      坐标: this.区域坐标(矩形),
      组件: new 按钮组件({ ...参数, 点击 }),
    });
  }

  private 区域坐标(矩形: { 左: number; 上: number; 宽: number; 高: number }) {
    return {
      位置X: 矩形.左 + 矩形.宽 / 2,
      位置Y: this.逻辑高 - (矩形.上 + 矩形.高 / 2),
      宽: 矩形.宽,
      高: 矩形.高,
    };
  }

  // ---- 按钮参数（禁用随演出/锁变化） ----

  private 重开参数(): ConstructorParameters<typeof 按钮组件>[0] {
    return {
      禁用: !this.可操作() || this.读取锁剩余毫秒() > 0,
      点击: () => this.重开(),
      绘制: (环境, 状态) => this.绘制操作按钮(环境, 状态.矩形, "重开", 状态.按下),
    };
  }

  private 菜单参数(): ConstructorParameters<typeof 按钮组件>[0] {
    return {
      禁用: !this.可操作(),
      点击: () => this.返回主菜单(),
      绘制: (环境, 状态) => this.绘制操作按钮(环境, 状态.矩形, "菜单", 状态.按下),
    };
  }

  private 重试参数(): ConstructorParameters<typeof 按钮组件>[0] {
    return {
      禁用: !this.可操作(),
      点击: () => this.重试奖励(),
      绘制: (环境, 状态) => this.绘制操作按钮(环境, 状态.矩形, "重试", 状态.按下),
    };
  }

  private 绘制操作按钮(
    环境: 节点绘制环境,
    矩形: { 宽: number; 高: number },
    种类: "重开" | "菜单" | "重试",
    按下: boolean,
  ): void {
    const 资源 = this.上下文.资源;
    在本地空间绘制(环境, () => {
      // 形状用节点本地空间画，文字按节点绘制矩阵换算到绘制空间（否则会跑到页面左上角）。
      const 文字变换 = (点: { x: number; y: number }) => 变换点(环境.绘制矩阵, 点);
      绘制结算操作(
        资源.画笔,
        { 左: 0, 上: 0, 宽: 矩形.宽, 高: 矩形.高 },
        this.读取操作文案(种类),
        种类,
        按下 ? "按下" : "默认",
        this.动画毫秒,
        this.省电(),
        文字变换,
      );
    });
  }

  // ---- 绘制节点 ----

  private 绘制演出节点(环境: 节点绘制环境): void {
    const 资源 = this.上下文.资源;
    const 文案 = this.上下文.服务.语言.读取();
    const 画笔 = 画法画笔(环境);
    在本地空间绘制(环境, () => {
      绘制结算演出(画笔, {
        标题: 结算标题(this.数据.结果, 文案),
        模式: 模式名称(this.数据.结果.模式, 文案),
        新纪录: this.数据.刷新纪录 ? 文案.结算新纪录 : "",
        分数: Math.round(this.分数.读取显示值()),
        金币: this.数据.金币?.新增 ?? null,
        金币标签: 文案.结算获得,
        循环提示: this.读取循环提示(),
        统计: 生成结算统计(this.数据.结果.模式, this.数据.结果, this.数据.历史最佳, 文案),
        方块方案: 读取方块外观方案(this.上下文.服务.设置.读取()),
        挑战结果: 读取挑战结果(this.数据.结果),
        宽: 资源.逻辑宽,
        高: 资源.逻辑高,
        经过毫秒: this.动画毫秒,
        省电: this.省电(),
      });
    });
  }

  private 绘制飘字节点(环境: 节点绘制环境): void {
    const 资源 = this.上下文.资源;
    const 定位 = 计算霓虹结算布局(资源.逻辑宽, 资源.逻辑高);
    const 绘制环境: 绘制环境 = {
      合批: 资源.合批,
      文字: this.上下文.文字,
      配色: this.上下文.读取配色(),
    };
    在本地空间绘制(环境, () => {
      this.飘字绘制状态 = 绘制结算飘字(画法画笔(环境), 绘制环境, this.飘字, 定位, {
        类型: this.当前飘字,
        经过毫秒: this.动画毫秒 - this.飘字开始,
        数量: this.数据.金币?.新增 ?? 0,
        省电: this.省电(),
        成就图标:
          this.当前飘字 === "成就"
            ? 成就图标编号列表.find((项) => 项 === this.数据.新成就[0])
            : undefined,
      });
    });
  }

  protected 读取文字快照(): readonly string[] {
    return [结算标题(this.数据.结果, this.上下文.服务.语言.读取())];
  }

  // 结算必须通过菜单或重开离开，不能由通用返回键弹回已结束的对局。
  protected 返回(): void {}

  /** 调试桥在结算覆盖页上读取的结算明细（验收直接断言金币/纪录/锁）。 */
  读取快照() {
    const 文案 = this.上下文.服务.语言.读取();
    const 结果 = this.数据.结果;
    return {
      页面: "结算",
      阶段: "结束",
      模式: 结果.模式,
      分数: 结果.分数,
      消行数: 结果.消行数,
      等级: 结果.等级,
      最长连击: 结果.最长连击,
      完赛: 结果.完赛,
      用时毫秒: 结果.用时毫秒,
      日期: 结果.日期,
      挑战结果: 读取挑战结果(结果),
      标题: 结算标题(结果, 文案),
      徽标: 生成结算徽标(结果.模式, 结果, this.数据.刷新纪录, 文案),
      统计: 生成结算统计(结果.模式, 结果, this.数据.历史最佳, 文案),
      刷新纪录: this.数据.刷新纪录,
      历史最佳: this.数据.历史最佳,
      金币奖励: this.数据.金币,
      金币失败原因: this.数据.金币失败原因,
      新成就: this.数据.新成就,
      成就文案: 读取成就文案(this.数据.新成就, 文案),
      奖励文案: 读取奖励文案(this.数据, 文案),
      金币余额: this.读取金币余额(),
      重开锁剩余毫秒: this.读取锁剩余毫秒(),
      动画毫秒: this.动画毫秒,
      显示分数: Math.round(this.分数.读取显示值()),
      显示金币: this.数据.金币
        ? 读取结算金币动画(this.动画毫秒 - 结算奖励开始毫秒, this.数据.金币.新增, this.省电())
            .显示数量
        : null,
      演出阶段: this.动画毫秒 < 5000 ? "入场" : "循环",
      循环帧间隔毫秒: this.省电() ? 100 : 1000 / 30,
      循环提示: this.读取循环提示(),
      需要连续帧: this.读取需要连续帧(),
      飘字: this.飘字.读取列表(),
      飘字类型: this.当前飘字,
      飘字绘制: this.飘字绘制状态,
      提示区: 计算霓虹结算布局(this.上下文.资源.逻辑宽, this.上下文.资源.逻辑高).提示区,
      金币动画: this.数据.金币
        ? 读取结算金币动画(
            this.动画毫秒 - 结算奖励开始毫秒,
            this.数据.金币.新增,
            this.上下文.服务.设置.读取().省电模式 === "开",
          )
        : null,
    };
  }

  private 读取锁剩余毫秒(): number {
    return 读取重开锁剩余毫秒(this.数据.结果.模式, this.数据.结束时刻毫秒, Date.now());
  }

  private 读取金币余额(): number {
    try {
      return this.上下文.服务.金币.读取().金币;
    } catch {
      return 0;
    }
  }

  private 省电(): boolean {
    return this.上下文.服务.设置.读取().省电模式 === "开";
  }

  private 读取循环提示() {
    if (
      (this.数据.金币失败原因 && !this.数据.金币) ||
      this.待播飘字.length ||
      this.飘字.读取列表().length
    )
      return undefined;
    const 文案 = this.上下文.服务.语言.读取();
    const 编号 =
      this.数据.新成就[
        Math.floor(Math.max(0, this.动画毫秒 - 5000) / 3200) % this.数据.新成就.length
      ];
    const 名称 = 文案.成就名称[编号];
    return 名称
      ? {
          文本: 填充文案(文案.成就解锁, { 名称 }),
          图标: 成就图标编号列表.find((项) => 项 === 编号),
        }
      : {
          文本: this.数据.刷新纪录 ? 文案.结算纪录刷新 : 文案.结算已结算,
        };
  }

  private 可操作(): boolean {
    return this.动画毫秒 >= (this.省电() ? 350 : 800);
  }

  private 读取操作文案(种类: "重开" | "菜单" | "重试"): string {
    const 文案 = this.上下文.服务.语言.读取();
    if (种类 === "菜单") return 文案.返回主菜单;
    if (种类 === "重试") return 文案.结算重试;
    const 秒 = Math.ceil(this.读取锁剩余毫秒() / 1000);
    return 秒 > 0 ? 填充文案(文案.结算重开倒计时, { 秒 }) : 文案.结算重开;
  }

  private 编排飘字(起点 = 0): void {
    // 保存失败需要明确可重试的操作，成功后再播放奖励和成就，避免飘字盖住重试按钮。
    if (this.数据.金币失败原因 && !this.数据.金币) return;
    const 数量 = this.数据.金币?.新增 ?? 0;
    const 文案 = this.上下文.服务.语言.读取();
    const 原因 = this.数据.金币?.原因 ?? "";
    const 说明 = this.数据.金币?.原因编号 === "对局未达标"
      ? 填充文案(文案.结算奖励条件, {
          秒: 金币奖励配置.有效对局秒,
          次数: 金币奖励配置.有效落块数,
        })
      : 原因;
    if (this.数据.金币)
      this.待播飘字.push({
        在: 起点 + 结算奖励开始毫秒,
        文本: 数量 > 0 ? 文案.结算奖励入账 : 说明,
        秒: 结算奖励秒,
        类型: "说明",
      });
    const 新成就 = this.数据.新成就;
    const 名称 = 新成就.length > 0 ? 文案.成就名称[新成就[0]!] : undefined;
    if (名称) {
      const 文本 =
        新成就.length > 1
          ? 填充文案(文案.结算成就更多, { 名称, 数量: 新成就.length })
          : 名称;
      this.待播飘字.push({
        在: 起点 + (this.数据.金币 ? 结算成就开始毫秒 : 结算奖励开始毫秒),
        文本,
        秒: 结算成就秒,
        类型: "成就",
      });
    }
  }

  private 读取重试矩形() {
    const 定位 = 计算霓虹结算布局(this.上下文.资源.逻辑宽, this.上下文.资源.逻辑高);
    return { 左: 定位.提示区.左 + 8, 上: 定位.奖励Y - 8, 宽: 定位.提示区.宽 - 16, 高: 42 };
  }

  private 重开(): void {
    if (!this.可操作() || this.读取锁剩余毫秒() > 0) return;
    this.上下文.导航.替换("对局", { 模式: this.数据.结果.模式 });
  }

  private 读取按钮矩形() {
    const 定位 = 计算霓虹结算布局(this.上下文.资源.逻辑宽, this.上下文.资源.逻辑高);
    const 转矩形 = (按钮: typeof 定位.重开) => ({
      左: 按钮.中心X - 按钮.宽 / 2,
      上: 按钮.中心Y - 按钮.高 / 2,
      宽: 按钮.宽,
      高: 按钮.高,
    });
    return { 重开: 转矩形(定位.重开), 菜单: 转矩形(定位.菜单) };
  }

  private 返回主菜单(): void {
    this.上下文.导航.替换("菜单");
  }

  /** 结算页测试/重试用：金币奖励失败后按同一编号重试并刷新展示数据。 */
  重试奖励(): void {
    if (this.数据.金币 || !this.数据.金币失败原因) return;
    try {
      const 结果 = this.上下文.服务.金币.结算对局(this.数据.奖励输入);
      if (结果.成功) {
        this.数据 = {
          ...this.数据,
          金币: { 新增: 结果.新增, 总额: 结果.金币, 原因: 结果.原因, 原因编号: 结果.原因编号 },
          金币失败原因: "",
        };
        更新最近结算(this.数据);
        this.飘字.清空();
        this.待播飘字.length = 0;
        this.编排飘字(Math.max(0, this.动画毫秒 - 结算奖励开始毫秒));
      } else {
        this.数据 = { ...this.数据, 金币失败原因: 结果.原因 };
      }
    } catch {
      this.数据 = {
        ...this.数据,
        金币失败原因: this.上下文.服务.语言.读取().结算奖励失败,
      };
    }
    if (this.已进入) this.重建();
    this.请求重绘();
  }

  /** 测试用：类型对齐轻提示队列（避免未使用导入）。 */
  protected get 轻提示(): 轻提示队列类型 {
    return this.飘字;
  }
}

export const 创建结算页面: 页面工厂 = (上下文: 页面上下文) => new 结算页面(上下文);

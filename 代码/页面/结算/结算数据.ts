/**
 * 结算页的数据口径：按模式拼统计项、徽标、新纪录与奖金文案。
 * 纯函数，不读存档也不改状态；数据来源由对局页在结束时填进 最近结算。
 */

/** 马拉松与每日挑战结束后的重开防误触窗口，与 Phaser 版一致。 */
export const 结算重开锁毫秒 = 3000;

export interface 结算统计项 {
  标签: string;
  数值: string;
}

export interface 金币奖励 {
  新增: number;
  总额: number;
  /** 已本地化的展示原因；需要判断原因种类时用 原因编号。 */
  原因: string;
  原因编号?: 收藏原因编号;
}

export interface 最近结算 {
  编号: string;
  结果: 对局结果;
  /** 配置的马拉松行数目标是否已达成（完成后仍可继续）。 */
  目标达成: boolean;
  刷新纪录: boolean;
  历史最佳: 对局纪录 | null;
  /** 对局金币结算结果；失败时为 null，原因写在 金币失败原因。 */
  金币: 金币奖励 | null;
  金币失败原因: string;
  新成就: string[];
  /** 结束时刻（毫秒时间戳），结算页据此算 3 秒重开锁。 */
  结束时刻毫秒: number;
  /** 本局领奖输入，结算页重试时原样复用（同一编号幂等）。 */
  奖励输入: 对局奖励输入;
}

/** 结算面板按钮是否已解锁：只有马拉松/每日挑战有 3 秒防误触。 */
export function 读取重开锁剩余毫秒(
  模式: 游戏模式,
  结束时刻毫秒: number,
  现在毫秒 = Date.now(),
): number {
  if (!是否使用马拉松结算重开锁(模式)) return 0;
  return Math.max(0, 结算重开锁毫秒 - Math.max(0, 现在毫秒 - 结束时刻毫秒));
}

/** 结算标题用的挑战结果：马拉松是普通结算，其余模式必须明确成功/失败。 */
export type 挑战结果 = "成功" | "失败" | "普通";

/**
 * 按模式配置判定挑战结果。目标值只读 模式配置，不在这里另写一套数值；
 * 马拉松始终是普通结算，不把「完赛」当成挑战成功/失败。
 */
export function 读取挑战结果(结果: 对局结果): 挑战结果 {
  switch (结果.模式) {
    case "冲刺":
      return 结果.完赛 || 结果.消行数 >= 模式配置.冲刺目标行数 ? "成功" : "失败";
    case "极限":
      // 极限坚持到计时结束才算成功，提前结束（含主动结束）都是失败。
      return (结果.用时毫秒 ?? 0) >= 模式配置.极限毫秒 ? "成功" : "失败";
    case "每日挑战":
      return 结果.消行数 >= 模式配置.马拉松目标行数 ? "成功" : "失败";
    default:
      return "普通";
  }
}

export function 结算标题(结果: 对局结果, 文案: 游戏文案): string {
  const 挑战 = 读取挑战结果(结果);
  if (挑战 === "成功") return 文案.挑战成功;
  if (挑战 === "失败") return 文案.挑战失败;
  return 文案.本局结算;
}

export function 生成结算徽标(
  模式: 游戏模式,
  结果: 对局结果,
  刷新纪录: boolean,
  文案: 游戏文案,
): string {
  const 名称 = 模式名称(模式, 文案);
  if (模式 === "冲刺") {
    const 完赛 = 结果.完赛 ? 文案.挑战完成 : 文案.未完赛;
    return `${名称} · ${完赛} · ${刷新纪录 ? 文案.纪录刷新 : 文案.纪录未刷新}`;
  }
  if (模式 === "极限") {
    return `${名称} · ${刷新纪录 ? 文案.纪录刷新 : 文案.纪录未刷新}`;
  }
  return `${名称} · ${结果.完赛 ? 文案.挑战完成 : 文案.本局结算}`;
}

export function 读取历史最佳文案(
  模式: 游戏模式,
  历史最佳: 对局纪录 | null,
  文案: 游戏文案,
): string {
  if (!历史最佳) return 模式 === "冲刺" ? 文案.暂无完赛纪录 : 文案.暂无纪录;
  if (模式 === "冲刺") {
    return 历史最佳.用时 !== null ? 格式化用时(历史最佳.用时) : 文案.暂无完赛纪录;
  }
  return `${历史最佳.分数.toLocaleString()} pts`;
}

/** 结算统计项按模式区分：冲刺看用时、极限看等级/行数、其余看行数/等级/连击。 */
export function 生成结算统计(
  模式: 游戏模式,
  结果: 对局结果,
  历史最佳: 对局纪录 | null,
  文案: 游戏文案,
): 结算统计项[] {
  if (模式 === "冲刺") {
    return [
      { 标签: 文案.有效用时, 数值: 格式化用时(结果.用时毫秒 ?? 0) },
      { 标签: 文案.消除行数, 数值: String(结果.消行数) },
      { 标签: 文案.历史最佳, 数值: 读取历史最佳文案(模式, 历史最佳, 文案) },
    ];
  }
  if (模式 === "极限") {
    return [
      {
        标签: `${文案.最高等级} / ${文案.消除行数}`,
        数值: `${结果.等级} / ${结果.消行数}`,
      },
      { 标签: 文案.有效用时, 数值: 格式化用时(结果.用时毫秒 ?? 0) },
      { 标签: 文案.历史最佳, 数值: 读取历史最佳文案(模式, 历史最佳, 文案) },
    ];
  }
  return [
    { 标签: 文案.消除行数, 数值: String(结果.消行数) },
    { 标签: 文案.最高等级, 数值: String(结果.等级) },
    { 标签: 文案.最佳连击, 数值: String(结果.最长连击) },
  ];
}

/** 由规则状态生成结算输入：马拉松/每日挑战不记用时，冲刺/极限记有效用时。 */
export function 生成对局结果(模式: 游戏模式, 状态: 再消一行状态, 日期: string): 对局结果 {
  const 用时毫秒 = 模式 === "马拉松" || 模式 === "每日挑战" ? null : Math.round(状态.有效用时);
  return {
    模式,
    分数: 状态.分数,
    消行数: 状态.消行数,
    等级: 状态.等级,
    最长连击: 状态.最长连击,
    用时毫秒,
    完赛: 状态.完赛,
    日期,
  };
}

/** 结算面板的金币奖励文案，失败时提示点击重试。 */
export function 读取奖励文案(结算: 最近结算, 文案: 游戏文案): string {
  if (结算.金币) {
    return 结算.金币.新增 > 0
      ? 填充文案(文案.方块币奖励, { 数量: 结算.金币.新增 })
      : 结算.金币.原因;
  }
  if (结算.金币失败原因) return `${结算.金币失败原因}\n点击这里重试`;
  return "";
}

/** 新解锁成就的展示名：最多两个，其余合并成 +N。 */
export function 读取成就文案(编号列表: readonly string[], 文案: 游戏文案): string {
  const 名称 = 编号列表.map((编号) => 文案.成就名称[编号]).filter((项) => 项 !== undefined);
  if (!名称.length) return "";
  const 前两个 = 填充文案(文案.成就解锁, { 名称: 名称.slice(0, 2).join(" / ") });
  return 名称.length > 2
    ? `${前两个}${填充文案(文案.成就更多, { 数量: 名称.length - 2 })}`
    : 前两个;
}

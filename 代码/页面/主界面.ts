/**
 * 主界面（7A/7C）：与 Phaser 版同款三态。
 * - 菜单态：共享背景（页面基类）+ 金币条 + 标题 + 3 个左侧角钮 + 开始游戏；
 * - 模式选择态：很小的游戏名 + 大号「选择模式」+ 模式装置卡（练习卡无排行小牌）+ 方块传送台；
 *   金币和游戏名与菜单共用流转身份，位置或大小不同时只位移、变形，不重复淡出再淡入；
 * - 纯享态（7C）：全屏风景 + 胶囊返回 + 风景标题/副题 + 底部圆点，左右切景/下滑返回。
 * 视觉来自项目组件，文字统一走 文字项 + 画笔.绘制文字。
 */

interface 按钮区域布局 {
  中心X: number;
  中心Y: number;
  宽: number;
  高: number;
}

interface 模式卡绘制项 {
  区域: 模式卡区域;
  数据: 模式卡数据;
}

function 按钮矩形(区域: 按钮区域布局) {
  return {
    左: 区域.中心X - 区域.宽 / 2,
    上: 区域.中心Y - 区域.高 / 2,
    宽: 区域.宽,
    高: 区域.高,
  };
}

export class 主界面 extends 页面基类 {
  private 状态: "菜单" | "模式选择" | "纯享" = "菜单";
  private 布局!: 主界面布局;
  private 金币 = 0;
  private 英文 = false;
  private 模式卡列表: readonly 模式卡绘制项[] = [];
  private 纯享主题: 背景主题 = "极光原野";
  /** 只由按钮的按下/松开/取消写入，供配方画按下态，不另做命中。 */
  private 按下中 = new Set<string>();
  private readonly 按钮动效 = new Map<
    string,
    { 按下: boolean; 毫秒: number; 起始X: number; 起始Y: number; x: number; y: number }
  >();
  /** 模式选择页的待机时钟，只驱动方块浮动，不跟满帧重画整页。 */
  private 场景秒 = 0;
  private 装饰绘制秒 = 0;
  private 启动: { 模式: 游戏模式; 秒: number } | null = null;

  constructor(上下文: 页面上下文) {
    super(上下文, { 名称: "主界面" });
  }

  进入(): void {
    this.过渡 = null;
    this.启动 = null;
    super.进入();
    this.恢复音频();
  }

  恢复(): void {
    super.恢复();
    this.恢复音频();
  }

  /** 从商店/子页面回来时恢复菜单音乐与氛围；已在播放就不重播。 */
  private 恢复音频(): void {
    const 音频 = this.上下文.服务.音频;
    音频.设置暂停(false);
    音频.播放音乐("再消一行.菜单");
    音频.播放氛围(this.上下文.服务.设置.读取().背景主题);
  }

  更新(秒: number): void {
    super.更新(秒);
    if (this.过渡) {
      this.过渡.秒 += 秒;
      if (this.过渡.秒 >= 界面流转时长) {
        this.状态 = this.过渡.到达;
        this.过渡 = null;
        this.刷新背景();
        this.重建();
      }
      this.请求重绘();
    }
    // 纯享态风景由启动层背景调度按画质档位重画动态层，这里只推进按钮动效。
    if (this.状态 === "模式选择" || this.过渡?.到达 === "模式选择") this.推进模式选择动效(秒);
    for (const [名称, 状态] of this.按钮动效) {
      状态.毫秒 += 秒 * 1000;
      const 缩放 = 计算常规按钮按压(状态.按下, 状态.毫秒, 状态.起始X, 状态.起始Y);
      状态.x = 缩放.x;
      状态.y = 缩放.y;
      if (!缩放.完成) this.请求重绘();
      else if (!状态.按下) this.按钮动效.delete(名称);
    }
  }

  protected 构建(): void {
    this.英文 = this.上下文.服务.语言.是否英文();
    this.金币 = this.上下文.服务.金币.读取().金币;
    this.布局 = 计算主界面布局(this.逻辑宽, this.逻辑高, this.状态);
    this.模式卡列表 = this.读取模式卡列表(this.布局);
    if (this.过渡 || this.启动) return;
    if (this.状态 === "纯享") {
      this.构建纯享();
      return;
    }
    const 角钮动作: Record<string, () => void> = {
      设置: () => this.跳转("设置"),
      成就: () => this.跳转("成就"),
      商店: () => this.跳转("商店"),
    };
    // 纯享入口手势层先注册：控件层后注册者优先命中，按钮热区在其后注册才能压住它。
    if (this.状态 === "菜单")
      this.创建滑动热区({
        矩形: 全屏区域(this.逻辑宽, this.逻辑高),
        点击: () => this.进入纯享(),
        滑动: (方向) => {
          if (方向 === "上") this.进入纯享();
        },
      });
    // 菜单态才有左侧角钮；模式选择态与 Phaser 版一致：角钮移出并禁用命中。
    if (this.状态 === "菜单")
      this.布局.角钮.项.forEach((项, 索引) => {
        const 点击 = 角钮动作[项.文案.中文];
        this.创建按钮(项.文案.中文, {
          绘制底板: () => {},
          移出取消: true,
          矩形: 按钮矩形({
            中心X: this.布局.角钮.中心X,
            中心Y: this.布局.角钮.中心Y[索引] ?? 0,
            宽: this.布局.角钮.宽,
            高: this.布局.角钮.高,
          }),
          点击: 点击 ?? (() => undefined),
          按下: () => this.按下刷新(项.文案.中文, true),
          松开: () => this.按下刷新(项.文案.中文, false),
          取消: () => this.按下刷新(项.文案.中文, false),
        });
      });
    const 开始 = this.布局.开始钮;
    if (开始) {
      this.创建按钮("开始游戏", {
        绘制底板: () => {},
        移出取消: true,
        矩形: 按钮矩形(开始),
        点击: () => this.切换状态("模式选择"),
        按下: () => this.按下刷新("开始游戏", true),
        松开: () => this.按下刷新("开始游戏", false),
        取消: () => this.按下刷新("开始游戏", false),
      });
      return;
    }
    const 模式选择 = this.布局.模式选择;
    if (!模式选择) return;
    for (const { 区域, 数据 } of this.模式卡列表) {
      this.创建按钮(`开始:${区域.模式}`, {
        绘制底板: () => {},
        移出取消: true,
        矩形: 按钮矩形(区域),
        点击: () => this.开始启动模式(区域.模式),
        按下: () => this.按下刷新(`开始:${区域.模式}`, true),
        松开: () => this.按下刷新(`开始:${区域.模式}`, false),
        取消: () => this.按下刷新(`开始:${区域.模式}`, false),
      });
      if (!数据.有排行) continue;
      // 排行钮位置与绘制共用模式卡配方的同一份几何。
      const 排行区域 = 计算模式卡排行区域(区域);
      this.创建按钮(`排行榜:${区域.模式}`, {
        绘制底板: () => {},
        移出取消: true,
        矩形: 按钮矩形(排行区域),
        点击: () => {
          if (this.启动) return;
          this.跳转("排行榜", { 模式: 区域.模式 });
        },
        按下: () => this.按下刷新(`排行榜:${区域.模式}`, true),
        松开: () => this.按下刷新(`排行榜:${区域.模式}`, false),
        取消: () => this.按下刷新(`排行榜:${区域.模式}`, false),
      });
    }
    this.创建按钮("返回", {
      绘制底板: () => {},
      移出取消: true,
      矩形: 按钮矩形(模式选择.返回钮),
      点击: () => this.切换状态("菜单"),
      按下: () => this.按下刷新("返回", true),
      松开: () => this.按下刷新("返回", false),
      取消: () => this.按下刷新("返回", false),
    });
  }

  private 构建纯享(): void {
    const 纯享 = 计算纯享布局(this.逻辑宽, this.逻辑高);
    if (!纯享) return;
    this.创建滑动热区({
      矩形: 全屏区域(this.逻辑宽, this.逻辑高),
      滑动: (方向) => {
        if (方向 === "左") this.切纯享(1);
        else if (方向 === "右") this.切纯享(-1);
        else if (方向 === "下") this.退出纯享();
      },
    });
    this.创建按钮("纯享:返回", {
      绘制底板: () => {},
      移出取消: true,
      矩形: 按钮矩形(纯享.返回钮),
      点击: () => this.退出纯享(),
      按下: () => this.按下刷新("纯享:返回", true),
      松开: () => this.按下刷新("纯享:返回", false),
      取消: () => this.按下刷新("纯享:返回", false),
    });
  }

  private 按下刷新(名称: string, 按下: boolean): void {
    const 当前 = this.按钮动效.get(名称);
    this.按钮动效.set(名称, {
      按下,
      毫秒: 0,
      起始X: 当前?.x ?? 1,
      起始Y: 当前?.y ?? 1,
      x: 当前?.x ?? 1,
      y: 当前?.y ?? 1,
    });
    if (按下) this.按下中.add(名称);
    else this.按下中.delete(名称);
    this.请求重绘();
  }

  /** 流转进行中背景跟着到达屏走，纯享风景可以在界面块移动时已经铺上。 */
  private 呈现状态(): "菜单" | "模式选择" | "纯享" {
    return this.过渡?.到达 ?? this.状态;
  }

  /** 纯享态风景始终动态（与 Phaser 版一致）；菜单/模式选择跟随玩家设置。 */
  读取背景动态(): boolean {
    if (this.呈现状态() === "纯享") return true;
    return super.读取背景动态();
  }

  /** 纯享态把主体画在动态层；其余状态用启动层注入的设置背景。 */
  protected 绘制背景静底(环境: 绘制环境, 信息: 页面背景信息): void {
    if (this.呈现状态() !== "纯享") {
      super.绘制背景静底(环境, 信息);
      return;
    }
    绘制背景静底(this.上下文.资源.画笔.图形, {
      宽: 信息.宽,
      高: 信息.高,
      主题: this.纯享主题,
      静态主体: !信息.动态,
      按名称绘制: true,
    });
    if (读取背景外观(this.上下文.服务.设置.读取()).文字基调 === "浅底")
      this.上下文.资源.画笔.图形.fillStyle(环境.配色.底色, 0.34).fillRect(0, 0, 信息.宽, 信息.高);
  }

  protected 绘制背景动态(_环境: 绘制环境, 信息: 页面背景信息): void {
    if (this.呈现状态() !== "纯享") {
      super.绘制背景动态(_环境, 信息);
      return;
    }
    绘制背景动态(this.上下文.资源.画笔.图形, {
      宽: 信息.宽,
      高: 信息.高,
      主题: this.纯享主题,
      时间秒: 信息.时间秒,
      亮度: 读取背景动态亮度(this.纯享主题),
      按名称绘制: true,
    });
  }

  private 过渡: {
    出发: "菜单" | "模式选择" | "纯享";
    到达: "菜单" | "模式选择" | "纯享";
    秒: number;
  } | null = null;

  /** 素材截图直接打开模式列表，不经过按钮按下动画。 */
  打开模式选择(): void {
    if (this.状态 === "模式选择" || this.过渡 || this.启动) return;
    this.开始切换("模式选择");
  }

  private 开始切换(目标: "菜单" | "模式选择" | "纯享"): void {
    if (this.过渡 || this.启动 || this.状态 === 目标) return;
    const 出发 = this.状态;
    this.过渡 = { 出发, 到达: 目标, 秒: 0 };
    this.启动 = null;
    this.按下中.clear();
    this.按钮动效.clear();
    this.控件层.清空();
    if (出发 === "纯享" || 目标 === "纯享") this.刷新背景();
    this.请求重绘();
  }

  /** 待机约12帧重画内容层；模式入场期间跟帧，保证居中、压线与幕面连续。 */
  private 推进模式选择动效(秒: number): void {
    this.场景秒 += 秒;
    if (this.过渡) return;
    if (this.启动) {
      this.启动.秒 += 秒;
      if (this.启动.秒 >= 模式退场时长) {
        const 模式 = this.启动.模式;
        this.启动 = null;
        this.开始游戏(模式);
        return;
      }
    }
    const 演出中 = this.启动 !== null;
    if (演出中 || this.场景秒 - this.装饰绘制秒 >= 1 / 12) {
      this.装饰绘制秒 = this.场景秒;
      this.请求重绘();
    }
  }

  private 开始启动模式(模式: 游戏模式): void {
    if (this.启动 || this.过渡) return;
    this.启动 = { 模式, 秒: 0 };
    this.控件层.清空();
    this.按下中.clear();
    this.按钮动效.clear();
    this.请求重绘();
  }

  private 读取模式卡动效(模式: 游戏模式): 模式卡绘制状态 {
    const 按下 = this.按下中.has(`开始:${模式}`);
    return {
      按下,
      下沉: 按下 ? 3 : 0,
      时间秒: this.场景秒,
      点亮: 按下 ? [1, 1, 1, 1] : [0, 0, 0, 0],
      排行按下: this.按下中.has(`排行榜:${模式}`),
    };
  }

  private 读取返回姿态(): 传送姿态 {
    return {
      下沉: this.按下中.has("返回") ? 1 : 0,
      点亮: [0, 0, 0, 0],
      完成: false,
    };
  }

  private 进入纯享(): void {
    if (this.过渡 || this.状态 === "纯享") return;
    const 解锁 = 已解锁风景列表();
    const 当前 = 获取设置背景主题(this.上下文);
    this.纯享主题 = 解锁.includes(当前) ? 当前 : (解锁[0] ?? 当前);
    this.开始切换("纯享");
  }

  private 切纯享(方向: -1 | 1): void {
    this.纯享主题 = 相邻已解锁风景(this.纯享主题, 方向);
    this.重建();
    this.刷新背景();
  }

  private 退出纯享(): void {
    this.开始切换("菜单");
  }

  private 切换状态(状态: "菜单" | "模式选择"): void {
    this.开始切换(状态);
  }

  protected 返回(): void {
    if (this.过渡 || this.启动) return;
    if (this.状态 === "纯享") this.退出纯享();
    else if (this.状态 === "模式选择") this.切换状态("菜单");
  }

  private 开始游戏(模式: 游戏模式): void {
    this.上下文.导航.进入("对局", { 模式, 入场演出: true });
  }

  protected 绘制内容(): void {
    const 画笔 = this.上下文.资源.画笔;
    if (this.启动) {
      this.绘制模式入场(画笔);
      return;
    }
    if (!this.过渡) {
      for (const 块 of this.带绘制(this.布局)) 块.绘制(画笔);
      return;
    }
    const 出发 = 计算主界面布局(this.逻辑宽, this.逻辑高, this.过渡.出发);
    const 到达 = 计算主界面布局(this.逻辑宽, this.逻辑高, this.过渡.到达);
    播放界面流转(画笔, this.带绘制(出发), this.带绘制(到达), this.过渡.秒 / 界面流转时长, {
      宽: this.逻辑宽,
      高: this.逻辑高,
    });
  }

  读取需要连续帧(): boolean {
    return this.启动 !== null || this.过渡 !== null;
  }

  private 绘制模式入场(画笔: 画笔): void {
    const 启动 = this.启动;
    const 卡 = this.模式卡列表.find((项) => 项.区域.模式 === 启动?.模式);
    if (!启动 || !卡) return;
    const 原 = 按钮矩形(卡.区域);
    const 姿态 = 计算模式入场姿态(启动.秒, 原, this.逻辑宽, this.逻辑高);
    const 选中序号 = this.模式卡列表.indexOf(卡);
    for (const 块 of this.带绘制(this.布局)) {
      if (块.身份 === `模式:${启动.模式}`) continue;
      const 序号 = this.模式卡列表.findIndex((项) => 块.身份 === `模式:${项.区域.模式}`);
      const 距离 = 序号 < 0 ? 0 : Math.abs(序号 - 选中序号);
      播放界面流转(画笔, [块], [], 计算退场进度(启动.秒, 距离), {
        宽: this.逻辑宽,
        高: this.逻辑高,
      });
    }
    绘制入场幕面(画笔, this.逻辑宽, this.逻辑高, 启动.模式, 姿态.幕缝);
    const 色 = 亮色(模式主题色(启动.模式), 入场参数.颜色.线提亮 * 姿态.线脉冲);
    绘制流转块(
      画笔,
      { 身份: `模式:${启动.模式}`, 来源: "出发", 透明度: 1, 静止: 原, 当前: 姿态.矩形 },
      (笔) => {
        笔.图形
          .fillStyle(混色(入场参数.颜色.卡面, 色, 姿态.压缩进度 ** 0.6), 1)
          .fillRoundedRect(原.左, 原.上, 原.宽, 原.高, 10 * (1 - 姿态.压缩进度));
        笔.图形
          .lineStyle(1, 色, 0.7 * (1 - 姿态.压缩进度))
          .strokeRoundedRect(原.左, 原.上, 原.宽, 原.高, 10 * (1 - 姿态.压缩进度));
        // 整卡先参与收束，内容直到压缩后段才消融，最终沿同一轮廓凝成线。
        if (姿态.内容透明度 > 0) {
          笔.图形.save().setAlpha(姿态.内容透明度);
          绘制模式卡(笔.图形, 卡.区域, 卡.数据, { 时间秒: this.场景秒 });
          for (const 项 of 生成模式卡文字项(卡.区域, 卡.数据)) 笔.绘制文字(项);
          笔.图形.restore();
        }
      },
    );
    if (姿态.压缩进度 === 1) 绘制凝聚横线(画笔, this.逻辑宽, this.逻辑高, 启动.模式, 姿态.线脉冲);
  }

  private 文字数据() {
    return {
      英文: this.英文,
      游戏名称: this.上下文.服务.语言.读取().游戏名称,
    };
  }

  private 带绘制(布局: 主界面布局) {
    return 生成主界面流转块({
      布局,
      文字: this.文字数据(),
      金币: this.金币,
      测量: (文案, 样式) => this.上下文.资源.画笔.测量文字(文案, 样式),
    }).map((块) => ({
      ...块,
      绘制: (画笔: 画笔) => this.绘制流转块内容(块.身份, 布局, 画笔),
    }));
  }

  /** 按流转身份画这一屏的静止内容。位置和缩放由框架套在画笔上。 */
  private 绘制流转块内容(身份: string, 布局: 主界面布局, 画笔: 画笔): void {
    const 图形 = 画笔.图形;
    if (身份 === "纯享") {
      this.绘制纯享(图形, 画笔);
      return;
    }
    if (身份 === "金币") {
      this.绘制金币(图形, 画笔, 计算金币条(布局.金币.左, 布局.金币.上, this.金币));
      return;
    }
    if (身份 === "游戏标题" || 身份 === "选择模式") {
      const 游戏名称 = this.文字数据().游戏名称;
      for (const 项 of 生成主界面文字项(布局, this.文字数据())) {
        const 是游戏名 = 项.文案 === 游戏名称;
        if (身份 === "游戏标题" ? 是游戏名 : !是游戏名) 画笔.绘制文字(项);
      }
      if (身份 === "选择模式" && 布局.模式选择 && !布局.视口.矮屏)
        绘制模式标题饰(图形, 布局.模式选择.标题.x, 布局.模式选择.标题.y + 26, this.场景秒);
      return;
    }
    if (身份.startsWith("角钮:")) {
      const 名称 = 身份.slice("角钮:".length);
      const 索引 = 布局.角钮.项.findIndex((项) => 项.文案.中文 === 名称);
      const 项 = 布局.角钮.项[索引];
      const 中心Y = 布局.角钮.中心Y[索引];
      if (!项 || 中心Y === undefined) return;
      this.绘制按钮(
        图形,
        画笔,
        { 中心X: 布局.角钮.中心X, 中心Y, 宽: 布局.角钮.宽, 高: 布局.角钮.高 },
        this.英文 ? 项.文案.英文 : 项.文案.中文,
        {
          变体: "次要",
          字号: 12,
          图标: 项.图标,
          图标尺寸: 18,
          图文方向: "竖排",
          按下: this.按下中.has(名称),
          名称,
        },
      );
      return;
    }
    if (身份 === "开始游戏" && 布局.开始钮) {
      const 开始 = 布局.开始钮;
      this.绘制按钮(图形, 画笔, 开始, this.英文 ? 开始.文案.英文 : 开始.文案.中文, {
        变体: "主要",
        字号: 16,
        面板透明度: 0.78,
        强调色: 读取霓虹调色板().强调色,
        按下: this.按下中.has("开始游戏"),
        名称: "开始游戏",
      });
      return;
    }
    if (身份.startsWith("模式:")) {
      const 模式 = 身份.slice("模式:".length);
      const 找到 = this.读取模式卡列表(布局).find((项) => 项.区域.模式 === 模式);
      if (!找到) return;
      const 动效 = this.读取模式卡动效(找到.区域.模式);
      绘制模式卡(图形, 找到.区域, 找到.数据, 动效);
      for (const 项 of 生成模式卡文字项(找到.区域, 找到.数据))
        画笔.绘制文字({ ...项, y: 项.y + (动效.下沉 ?? 0) });
      return;
    }
    if (身份 === "返回" && 布局.模式选择) {
      const 返回姿态 = this.读取返回姿态();
      const 文案 = this.英文 ? 布局.模式选择.返回钮.文案.英文 : 布局.模式选择.返回钮.文案.中文;
      绘制返回传送装置(图形, 布局.模式选择.返回钮, {
        时间秒: this.场景秒,
        下沉: 返回姿态.下沉,
        点亮: 返回姿态.点亮,
        文案,
      });
      画笔.绘制文字(生成返回按键文字项(布局.模式选择.返回钮, 文案, 返回姿态.下沉));
    }
  }

  private 读取模式卡列表(布局: 主界面布局): readonly 模式卡绘制项[] {
    const 今日 = this.上下文.服务.当日日期();
    return (布局.模式选择?.卡 ?? []).map((区域) => ({
      区域,
      数据: 组装模式卡数据(
        区域.模式,
        this.英文,
        this.上下文.服务.纪录.读取(区域.模式, 区域.模式 === "每日挑战" ? 今日 : undefined),
      ),
    }));
  }

  /** 纯享态：厚按键返回 + 标题/副题 + 底部圆点；风景由基类背景静/动层绘制。 */
  private 绘制纯享(图形: 图形对象, 画笔: 画笔): void {
    const 纯享 = 计算纯享布局(this.逻辑宽, this.逻辑高);
    if (!纯享) return;
    const 说明 = 风景说明(this.纯享主题);
    for (const 项 of 生成纯享文字项(纯享, 说明)) 画笔.绘制文字(项);
    const 返回 = 纯享.返回钮;
    const 按下 = this.按下中.has("纯享:返回");
    const 文案 = this.英文 ? "Back" : "返回";
    const 下沉 = 按下 ? 1 : 0;
    绘制返回传送装置(图形, 返回, { 时间秒: this.场景秒, 下沉, 点亮: [], 文案 });
    画笔.绘制文字(生成返回按键文字项(返回, 文案, 下沉));
    const 解锁 = 已解锁风景列表();
    const 当前 = Math.max(0, 解锁.indexOf(this.纯享主题));
    绘制纯享圆点(图形, this.逻辑宽, this.逻辑高, 解锁.length, 当前);
  }

  private 绘制金币(图形: 图形对象, 画笔: 画笔, 布局: 金币条布局): void {
    绘制金币条(图形, 布局);
    for (const 项 of 生成金币条文字项(布局, this.金币)) 画笔.绘制文字(项);
  }

  /** 一块共享配方按钮：底板 + 可选图标 + 文字项（文字色按底色对比自动取）。 */
  private 绘制按钮(
    图形: 图形对象,
    画笔: 画笔,
    区域: 按钮区域布局,
    文案: string,
    选项: 常规按钮文字选项 & 常规按钮状态 & { 名称?: string },
  ): void {
    const 标签尺寸 = 画笔.测量文字(文案, 读取常规按钮文字样式(选项));
    const 内容 = 生成常规按钮内容(区域.中心X, 区域.中心Y, 文案, 选项, 标签尺寸);
    const 缩放 = 选项.名称 ? this.按钮动效.get(选项.名称) : undefined;
    图形.save();
    图形.translateCanvas(区域.中心X, 区域.中心Y);
    图形.scaleCanvas(缩放?.x ?? 1, 缩放?.y ?? 1);
    图形.translateCanvas(-区域.中心X, -区域.中心Y);
    绘制常规按钮(图形, 区域.中心X, 区域.中心Y, 区域.宽, 区域.高, 选项);
    if (内容.图标) 绘制常规按钮图标(图形, 内容.图标);
    图形.restore();
    if (内容.文字项)
      画笔.绘制文字({
        ...内容.文字项,
        x: 区域.中心X + (内容.文字项.x - 区域.中心X) * (缩放?.x ?? 1),
        y: 区域.中心Y + (内容.文字项.y - 区域.中心Y) * (缩放?.y ?? 1),
        缩放X: 缩放?.x,
        缩放Y: 缩放?.y,
      });
  }

  protected 读取文字快照(): readonly string[] {
    const 金币 = this.上下文.服务.金币.读取().金币;
    const 今日 = this.上下文.服务.当日日期();
    return [
      `状态:${this.状态}`,
      `退场:${this.过渡 ? this.过渡.秒 : "无"}`,
      `过渡:${this.过渡 ? "流转" : "无"}`,
      `启动:${this.启动?.模式 ?? "无"}`,
      `入场:${this.启动 ? 计算模式入场姿态(this.启动.秒, { 左: 0, 上: 0, 宽: 1, 高: 1 }, this.逻辑宽, this.逻辑高).阶段 : "无"}`,
      `入场秒:${this.启动?.秒 ?? 0}`,
      `金币:${金币}`,
      ...(this.状态 === "纯享" ? [`纯享:${this.纯享主题}`] : []),
      ...(this.布局.模式选择?.卡.map((区域) => {
        const 纪录 = this.上下文.服务.纪录.读取(
          区域.模式,
          区域.模式 === "每日挑战" ? 今日 : undefined,
        );
        return `${区域.模式}:${纪录?.分数 ?? 0}`;
      }) ?? []),
    ];
  }
}

function 全屏区域(宽: number, 高: number): { 左: number; 上: number; 宽: number; 高: number } {
  return { 左: 0, 上: 0, 宽, 高 };
}

function 获取设置背景主题(上下文: 页面上下文): 背景主题 {
  return 上下文.服务.设置.读取().背景主题;
}

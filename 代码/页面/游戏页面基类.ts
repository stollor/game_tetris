import { 绘制顶栏衬底, 读取背景外观 } from "../../主题/背景外观";
import { 绘制单行文字 } from "../../框架/界面/控件/工具";
import type { 按钮 } from "../../框架/界面/控件/按钮";
import type { 矩形, 绘制环境 } from "../../框架/界面/控件/类型";
import { 页面基类 as 框架页面基类, type 界面快照 } from "../../框架/界面/页面基类";
import { 页面开合命中层 } from "../../视效/过渡/页面开合";
import type { 页面上下文, 页面参数, 页面编号 } from "../应用/接口/上下文";

/**
 * 《再消一行》Three 版页面基类：在框架页面基类上补本游戏自己的外观约定——
 * 顶栏 64px、右上角「返回主菜单」按钮 96×34、页面标题、页面编号跳转。
 * 背景、配色、导航全部来自 `页面上下文`；这里不读存档、不画背景配方。
 */
export abstract class 页面基类 extends 框架页面基类<页面上下文> {
  读取界面(): 界面快照 {
    const 界面 = super.读取界面();
    if (this.上下文.资源.命中.读取活动层() !== 页面开合命中层) return 界面;
    return {
      按钮: 界面.按钮.map((按钮) => ({ ...按钮, 可用: false })),
      文字: [...(界面.文字 ?? []), "页面开合:播放中"],
    };
  }

  /** 顶栏：背景衬底 + 标题 + 可选返回按钮。返回顶栏底边 y。 */
  protected 绘制顶栏(环境: 绘制环境, 标题: string): number {
    const 高 = 64;
    绘制顶栏衬底(
      环境,
      { 左: 0, 上: 0, 宽: this.逻辑宽, 高 },
      读取背景外观(this.上下文.服务.设置.读取()),
      0.78,
    );
    绘制单行文字(
      环境,
      { 左: 16, 上: 0, 宽: this.逻辑宽 - 32, 高 },
      标题,
      "中",
      环境.配色.主字,
      "左",
    );
    return 高;
  }

  /** 添加「返回主菜单」按钮（右上角），子页面通用。 */
  protected 添加返回按钮(文案 = "返回主菜单"): 按钮 {
    return this.创建按钮("返回主菜单", {
      矩形: this.返回按钮矩形(),
      文案,
      字号档: "小",
      变体: "次要",
      点击: () => this.上下文.导航.返回(),
    });
  }

  protected 返回按钮矩形(): 矩形 {
    const 宽 = 96;
    const 高 = 34;
    return { 左: this.逻辑宽 - 宽 - 14, 上: 15, 宽, 高 };
  }

  /** 页面标题文字（顶栏左侧用）。 */
  protected 页面标题(): string {
    return this.页面名称;
  }

  protected 跳转(页面: 页面编号, 参数?: 页面参数): void {
    this.上下文.导航.进入(页面, 参数);
  }
}

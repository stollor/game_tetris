import { 页面基类 as 框架页面基类, type 界面快照 } from "../../.gamemaker/依赖/框架/界面/页面基类";
import type { 页面上下文 } from "../应用/接口/上下文";

/**
 * 《再消一行》Three 版页面基类：在框架页面基类上补本游戏自己的约定——
 * 页面开合期间把界面快照里的按钮统一标为不可用，避免开合动画中被点穿。
 * 背景在背景层、金币在货币层、提示在提示层；页面只画自己的节点树。
 */
export abstract class 页面基类 extends 框架页面基类<页面上下文> {
  读取界面(): 界面快照 {
    const 界面 = super.读取界面();
    if (!this.上下文.读取界面开合中?.()) return 界面;
    return {
      按钮: 界面.按钮.map((按钮) => ({ ...按钮, 可用: false })),
      文字: [...(界面.文字 ?? []), "页面开合:播放中"],
    };
  }
}

  // ---- 内容坐标（内容本地、左上角 y 向下，与旧实现一致） ----

  private 选项按钮区(行布局: 已布局行): 矩形 {
    const 窄 = this.内容宽 - 8 < 460;
    return {
      左: 窄 ? 4 : 164,
      上: 行布局.上 + (窄 ? 36 : 0),
      宽: this.内容宽 - 8 - (窄 ? 0 : 160),
      高: 36,
    };
  }

  private 选项按钮矩形(区: 矩形, 序号: number, 数量: number): 矩形 {
    const 窄 = this.内容宽 - 8 < 460;
    const 间距 = 窄 ? 4 : 10;
    const 宽 = 窄
      ? (区.宽 - 间距 * (数量 - 1)) / 数量
      : Math.max(76, Math.min(160, (区.宽 - 间距 * (数量 - 1)) / 数量));
    return {
      左: 区.左 + (区.宽 - (宽 * 数量 + 间距 * (数量 - 1))) / 2 + 序号 * (宽 + 间距),
      上: 区.上,
      宽,
      高: 区.高,
    };
  }


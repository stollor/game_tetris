function 用户标识(英文: boolean): string {
  const 身份 = 读取Tap用户身份();
  if (身份.openid) return 身份.openid;
  if (身份.nickName) return 身份.nickName;
  return 英文 ? "Not signed in" : "未登录";
}

function 存档时间文案(时间: number | null, 英文: boolean): string {
  if (!时间 || !Number.isFinite(时间)) return 英文 ? "No save yet" : "尚无存档";
  return new Date(时间).toLocaleString(英文 ? "en-GB" : "zh-CN", { hour12: false });
}

function 存档状态文案(状态: 云同步状态码, 原因: string, 英文: boolean, 同步中: boolean): string {
  if (同步中 || 状态 === "同步中") return 英文 ? "Syncing…" : "同步中…";
  if (英文) {
    if (状态 === "已同步") return "Synced";
    if (状态 === "失败") return `Failed · ${原因 || "error"}`;
    if (状态 === "未登录") return "Sign in to sync";
    if (状态 === "无能力") return "Cloud save unavailable";
    if (状态 === "跳过") return 原因 || "Skipped";
    return "Not synced yet";
  }
  if (状态 === "已同步") return "已同步";
  if (状态 === "失败") return `失败 · ${原因 || "未知错误"}`;
  if (状态 === "未登录") return "未登录，无法同步";
  if (状态 === "无能力") return "当前环境不支持云存档";
  if (状态 === "跳过") return 原因 || "已跳过";
  return "尚未同步";
}

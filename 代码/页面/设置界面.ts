  private 绘制外观卡(
    环境: 节点绘制环境,
    布局: 外观卡布局,
    卡: 外观卡源,
    画笔: ReturnType<typeof 读取画笔>,
  ): void {
    const 数据: 外观卡数据 = {
      标签: 卡.标签,
      面板色: 卡.面板色,
      背景色: 卡.背景色,
      强调色: 卡.强调色,
      类型: 卡.类型 === "套装" ? "背景" : 卡.类型,
      方块方案: 卡.方块方案 as 方块外观名称 | undefined,
      背景值: 卡.背景值 as 背景主题 | undefined,
      已选: this.是否选中外观卡(卡),
    };
    绘制外观卡边框(环境.图形, 布局, 数据);
    const 画了 = 绘制外观卡预览(环境.图形, 布局, 数据, (绘图, 左, 上, 格, 方案, 类型) => {
      const 方案数据 = 解析方块外观(方案);
      绘制方块单元(绘图, 左, 上, { 方案: 方案数据, 色值: 方案数据.颜色[类型], 格子: 格 });
    });
    if (!画了 && 卡.背景值 && (卡.类型 === "背景" || 卡.类型 === "套装")) {
      const 预览 = 外观卡预览矩形(布局, 数据);
      环境.图形.save();
      try {
        环境.图形.translateCanvas(预览.左, 预览.上);
        绘制背景(环境.图形, {
          宽: 预览.宽,
          高: 预览.高,
          主题: 卡.背景值 as Parameters<typeof 绘制背景>[1]["主题"],
          动态: false,
          时间秒: 0,
          按名称绘制: true,
        });
      } finally {
        环境.图形.restore();
      }
    }
    if (画笔) {
      画笔.绘制文字({
        ...生成外观卡文字项(布局, 数据),
        变换: 文字空间矩阵(环境, 外观卡列表常量.卡高),
      });
    }
  }

  private 是否选中外观卡(卡: 外观卡源): boolean {
    const 设置 = this.上下文.服务.设置.读取();
    if (卡.类型 === "套装") return 卡.已选 === true;
    if (卡.类型 === "方块") return 设置.方块外观 === 卡.方块方案;
    if (卡.类型 === "背景") return 设置.背景主题 === 卡.背景值;
    return (设置.旅行样式 ?? 设置.样式) === 卡.名称;
  }


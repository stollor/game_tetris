/** 与 GM 框架 获取游戏界面色彩 相同的取值口径（设置.样式 → 语义色）。 */
function 读取设置外观(设置: 游戏设置): 设置外观 {
  const 主题 = 界面主题(设置.旅行样式 ?? 设置.样式);
  return {
    强调色: 颜色值(主题.文字.强调),
    面板: 颜色值(主题.面板.主面板.背景),
    面板描边: 颜色值(主题.面板.主面板.描边),
    正文: 颜色值(主题.面板.主面板.正文文字),
    次要: 颜色值(主题.文字.次要),
    轨道: 颜色值(主题.输入框.轨道),
    遮罩: 颜色值(主题.面板.遮罩.背景),
    遮罩透明度: 主题.面板.遮罩.透明度,
    页面背景: 颜色值(主题.页面.背景),
  };
}


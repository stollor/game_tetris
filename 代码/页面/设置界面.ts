  /** 内容绘制节点：分组标题、分隔线、行标签、信息行与账户行文字（交互控件由子节点自己画）。 */
  private 绘制内容区(环境: 节点绘制环境): void {
    const 画笔 = 读取画笔(环境);
    const 矩形 = 环境.节点.读取本地矩形();
    if (!画笔 || !矩形) return;
    const 设置 = this.上下文.服务.设置.读取();
    const 外观 = this.外观;
    const 变换 = 文字空间矩阵(环境, 矩形.高);
    const 文字 = (项: 文字项) => 画笔.绘制文字({ ...项, 变换 });
    在本地空间绘制(环境, () => {
      const 图形 = 环境.图形;
      for (const 分组 of this.分组布局) {
        if (分组.标题) {
          文字(生成分组标题文字项(分组.标题布局, 分组.标题, 外观.强调色));
          绘制覆盖页分隔线(
            图形,
            分组.标题布局.左,
            分组.标题布局.分隔线Y,
            分组.标题布局.宽,
            外观.强调色,
          );
        }
        for (const 行布局 of 分组.行) this.绘制行文字(图形, 行布局, 设置, 文字);
      }
    });
  }

  private 绘制行文字(
    图形: Parameters<typeof 绘制覆盖页分隔线>[0],
    行布局: 已布局行,
    设置: 游戏设置,
    文字: (项: 文字项) => void,
  ): void {
    const 行 = 行布局.行;
    const 外观 = this.外观;
    const 标签样式 = 派生霓虹文字样式("正文", { 字号: 16, 颜色: 外观.正文, 对齐: "左" });
    if (行.类型 === "选项") {
      文字({ 文案: 行.标题, 样式: 标签样式, 锚点: "左中", x: 6, y: 行布局.上 + 18 });
      return;
    }
    if (行.类型 === "开关") {
      文字({ 文案: 行.标题, 样式: 标签样式, 锚点: "左中", x: 6, y: 行布局.上 + 18 });
      return;
    }
    if (行.类型 === "音量") {
      文字({
        文案: `${行.标题}  ${设置[行.键]}%`,
        样式: 派生霓虹文字样式("正文", { 字号: 14, 颜色: 外观.正文, 对齐: "左" }),
        锚点: "左中",
        x: 6,
        y: 行布局.上 + 18,
      });
      return;
    }
    if (行.类型 === "语言") {
      文字({
        文案: 行.标题,
        样式: 派生霓虹文字样式("正文", { 字号: 15, 颜色: 外观.正文, 对齐: "左" }),
        锚点: "左中",
        x: 6,
        y: 行布局.上 + 18,
      });
      return;
    }
    if (行.类型 === "信息") {
      行.条目.forEach((条, i) => {
        const 顶 = 行布局.上 + i * 46;
        const 标签样式2 = 派生霓虹文字样式("正文", { 字号: 12, 颜色: 外观.次要, 对齐: "左" });
        const 值样式 = 派生霓虹文字样式("正文", { 字号: 15, 颜色: 外观.正文, 对齐: "左" });
        文字({ 文案: 条.标签, 样式: 标签样式2, 锚点: "左上", x: 6, y: 顶 + 2 });
        文字({
          文案: this.单行(文案裁剪器, 条.值, 值样式, this.内容宽 - 16),
          样式: 值样式,
          锚点: "左上",
          x: 6,
          y: 顶 + 20,
        });
      });
      return;
    }
    if (行.类型 === "外观" && !行.隐藏标题) {
      文字({
        文案: 行.标题,
        样式: 派生霓虹文字样式("正文", { 字号: 14, 颜色: 外观.正文, 对齐: "左" }),
        锚点: "左上",
        x: 4,
        y: 行布局.上 + 8,
      });
    }
    void 图形;
  }


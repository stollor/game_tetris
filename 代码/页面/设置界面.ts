  private 单行(
    测量: (文案: string, 样式: 文字项["样式"]) => { 宽: number },
    文案: string,
    样式: 文字项["样式"],
    最大宽: number,
  ): string {
    if (测量(文案, 样式).宽 <= 最大宽) return 文案;
    const 字符 = Array.from(文案);
    let 结果 = "…";
    for (let i = 0; i < 字符.length; i++) {
      const 候选 = `${字符.slice(0, i + 1).join("")}…`;
      if (测量(候选, 样式).宽 > 最大宽) break;
      结果 = 候选;
    }
    return 结果;
  }


  private 布局分组(设置: 游戏设置, 英文: boolean): 已布局分组[] {
    const 分组 = this.生成分组(设置, 英文);
    const 结果: 已布局分组[] = [];
    let y = 4;
    for (const [序号, 项] of 分组.entries()) {
      if (序号 > 0) y += 组间距;
      const 有标题 = 项.标题.length > 0;
      const 标题布局 = { 左: 4, 上: y, 宽: this.内容宽 - 8, 分隔线Y: 有标题 ? y + 分组标题高 : y };
      if (有标题) y += 分组标题高 + 分组标题间距;
      const 行: 已布局行[] = [];
      for (const [i, 行项] of 项.行.entries()) {
        const 高 = 行项.类型 === "选项" && this.内容宽 - 8 >= 460 ? 36 : 行高(行项);
        行.push({ 上: y, 高, 行: 行项 });
        y += 高 + (i === 项.行.length - 1 ? 0 : 行间距);
      }
      结果.push({ 标题: 项.标题, 标题布局, 行 });
    }
    return 结果;
  }


  /** 切页签 / 重建：销毁内容节点下的控件节点，按当前分组重新创建。 */
  private 重建内容(): void {
    if (!this.内容节点) return;
    for (const 子 of [...this.内容节点.子]) 子.销毁();
    this.内容控件 = [];
    this.计算分组();
    this.内容节点.读取二维坐标()?.更新参数({ 高: this.内容高() });
    this.更新视口与内容();
    this.更新页签节点();
    let 控件序号 = 0;
    for (const 项 of this.列表项) {
      if (项.类型 !== "行") continue;
      this.创建行控件(this.内容节点, 项.布局, 控件序号++);
    }
    this.滚动?.设置偏移(this.滚动位置);
    this.滚动位置 = this.滚动?.读取偏移() ?? 0;
    this.标记失效([0], "内容");
  }


function 行高(行: 设置行): number {
  if (行.类型 === "外观") return 行.隐藏标题 ? 外观卡列表常量.列表高 + 8 : 182;
  if (行.类型 === "选项") return 72;
  if (行.类型 === "开关") return 36;
  if (行.类型 === "信息") return 行.条目.length * 46;
  if (行.类型 === "动作") return 48;
  return 36;
}

function 查找已购(已购: readonly string[], 部位: string): string[] {
  return 已购
    .filter((编号) => 编号.endsWith(`.${部位}`))
    .map((编号) => 编号.slice(0, -部位.length - 1));
}


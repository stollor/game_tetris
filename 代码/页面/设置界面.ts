function 当前语言文案(语言: 游戏设置["语言"], 文案: { 设置跟随系统: string }): string {
  if (语言 === "English") return "English";
  if (语言 === "简体中文") return "简体中文";
  return 文案.设置跟随系统;
}

function 用户标识(未登录: string): string {
  const 身份 = 读取Tap用户身份();
  if (身份.openid) return 身份.openid;
  if (身份.nickName) return 身份.nickName;
  return 未登录;
}

function 存档时间文案(时间: number | null, 尚无存档: string): string {
  if (!时间 || !Number.isFinite(时间)) return 尚无存档;
  return new Date(时间).toLocaleString("zh-CN", { hour12: false });
}

function 存档状态文案(
  状态: 云同步状态码,
  原因: string,
  文案: {
    设置云同步中: string;
    设置已同步: string;
    设置同步失败: string;
    设置未登录无法同步: string;
    设置不支持云存档: string;
    设置已跳过: string;
    设置尚未同步: string;
    未知错误: string;
  },
  同步中: boolean,
): string {
  if (同步中 || 状态 === "同步中") return 文案.设置云同步中;
  if (状态 === "已同步") return 文案.设置已同步;
  if (状态 === "失败") return 填充文案(文案.设置同步失败, { 原因: 原因 || 文案.未知错误 });
  if (状态 === "未登录") return 文案.设置未登录无法同步;
  if (状态 === "无能力") return 文案.设置不支持云存档;
  if (状态 === "跳过") return 原因 || 文案.设置已跳过;
  return 文案.设置尚未同步;
}

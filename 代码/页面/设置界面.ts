/**
 * 设置页：独立遮罩节点 + 整屏面板容器（壳体 / 页签 / 滚动视口 / 内容 / 页脚）。
 *
 * 内容分三页（常规 / 外观 / 账号），外观再分套装与自定义。行内可交互项都是独立节点
 * （选项按钮、开关、滑块、语言下拉、动作按钮、外观卡按钮）；行文字与分组标题合在内容绘制节点里。
 * 语言下拉展开时在面板容器下追加临时节点（遮罩 + 面板 + 选项），关闭时销毁并随面板一起动。
 *
 * 节点首次进入构建，之后常驻；主题 / 语言 / 设置变化只重算注册参数，切页签重建内容节点子树。
 */


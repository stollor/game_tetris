/**
 * 排行榜页：整页底板/标题/状态绘制节点 + 周期页签节点 + 滚动视口（内含榜单行绘制节点）+ 返回/登录按钮节点。
 *
 * 榜单行是纯展示单元，合在一个内容绘制节点里画；周期切换只换数据与已选，不重建节点。
 * 首次进入构建、之后常驻；数据/语言/资源/主题/尺寸变化只重算注册参数并标脏。
 */

interface 榜面缓存 {
  状态文案: string;
  分数列表: readonly Tap排行榜分数[];
  需登录?: boolean;
  /** 本轮查询已有结果：空提示只在查完且没有成绩时出现。 */
  已加载?: boolean;
  /** 「我的」那一行（已本地化），空串表示还没有我的成绩。 */
  我的行?: string;
}

export class 排行榜界面 extends 页面基类 {
  private 模式: 游戏模式 = "马拉松";
  private 周期: 排行榜周期 = "总";
  private 滚动: 滚动组件 | null = null;
  private 滚动位置 = 0;
  private 缓存: 榜面缓存 = { 状态文案: "", 分数列表: [] };
  private 加载中 = false;
  private 色: 页面语义色 = 读取页面语义色(this.上下文.服务.设置.读取().样式);

  private 底板节点: 节点 | null = null;
  private 标题节点: 节点 | null = null;
  private 状态节点: 节点 | null = null;
  private 空提示节点: 节点 | null = null;
  private 行节点: 节点[] = [];
  private 页签节点: 节点 | null = null;
  private 内容节点: 节点 | null = null;
  private 返回节点: 节点 | null = null;
  private 登录节点: 节点 | null = null;

  constructor(上下文: 页面上下文) {
    // 整页不透明底、标题与榜单都画在页面节点上。
    super(上下文, {
      名称: "排行榜",
      独占命中: true,
      开合: { 打开秒: 0.3, 关闭秒: 0.25 },
      节点树: { 绘制带数: 1 },
    });
  }

  进入(): void {
    this.模式 = this.上下文.参数.模式 ?? "马拉松";
    this.周期 = "总";
    this.缓存 = { 状态文案: "", 分数列表: [] };
    super.进入();
    this.确保标题节点();
    void this.刷新在线榜();
  }

  /** 跨页流转会销毁到达页的「排行榜:标题」；页面常驻，再次进入时按同一份构造补一棵。 */
  private 确保标题节点(): void {
    const 根 = this.读取节点根();
    if (!根 || 查找节点(根, "排行榜:标题")) return;
    this.标题节点 = this.创建标题节点(根);
    this.应用注册参数(根);
  }

  private 创建标题节点(页面: 节点): 节点 {
    return 创建文字节点(
      页面,
      { 名称: "排行榜:标题", 项: this.标题文字项() },
      this.逻辑高,
      this.测量文字,
    );
  }

  protected 构建节点树(页面: 节点): void {
    页面.设置开合行为({ 类型: "滑入", 方向: "右" });
    const 布局 = this.计算布局();
    this.底板节点 = 创建整页绘制节点(页面, "排行榜:底板", this.逻辑宽, this.逻辑高, (环境) =>
      this.绘制底板(环境),
    );
    this.标题节点 = this.创建标题节点(页面);
    this.状态节点 = 创建文字节点(
      页面,
      { 名称: "排行榜:状态", 项: this.状态文字项() },
      this.逻辑高,
      this.测量文字,
    );
    this.空提示节点 = 创建文字节点(
      页面,
      { 名称: "排行榜:空提示", 项: this.空提示文字项() },
      this.逻辑高,
      this.测量文字,
    );
    // 周期页签：一整行一个节点，条目等分。
    this.页签节点 = new 节点("排行榜周期");
    this.页签节点.挂载组件(
      new 坐标2D组件({
        位置X: 布局.页签.左,
        位置Y: this.逻辑高 - 布局.页签.上 - 布局.页签.高,
        宽: 排行榜周期顺序.length * 布局.页签.宽 + (排行榜周期顺序.length - 1) * 布局.页签.间距,
        高: 布局.页签.高,
        锚点X: 0,
        锚点Y: 0,
      }),
    );
    this.页签节点.挂载组件(this.创建页签组件());
    页面.添加子(this.页签节点);
    // 榜单滚动区：视口裁剪 + 内容绘制节点。
    const 视口 = new 节点("排行榜:列表");
    视口.挂载组件(
      new 坐标2D组件({
        位置X: 布局.列表.左,
        位置Y: this.逻辑高 - 布局.列表.上 - 布局.列表.高,
        宽: 布局.列表.宽,
        高: 布局.列表.高,
        锚点X: 0,
        锚点Y: 0,
        裁剪: true,
      }),
    );
    this.滚动 = new 滚动组件({ 方向: "垂直" });
    视口.挂载组件(this.滚动);
    页面.添加子(视口);
    this.内容节点 = new 节点("排行榜:内容");
    this.内容节点.挂载组件(
      new 坐标2D组件({
        位置X: 0,
        位置Y: 布局.列表.高,
        宽: 布局.列表.宽,
        高: Math.max(布局.列表.高, 40),
        锚点X: 0,
        锚点Y: 1,
      }),
    );
    this.内容节点.挂载组件(new 绘制组件({ 绘制: () => {} }));
    视口.添加子(this.内容节点);
    this.滚动.应用参数({ 内容节点: this.内容节点, 方向: "垂直" });
    this.滚动.设置偏移(this.滚动位置);
    const 按钮行 = 布局.按钮行;
    this.返回节点 = 创建按钮节点(
      页面,
      "返回主菜单",
      {
        中心X: 按钮行.左 + 按钮行.宽 / 2,
        中心Y: 按钮行.上 + 按钮行.高 / 2,
        宽: 按钮行.宽,
        高: 按钮行.高,
      },
      this.逻辑高,
      { 点击: () => this.上下文.导航.返回(), 绘制: (环境) => this.绘制返回按钮(环境) },
    );
    this.登录节点 = 创建按钮节点(
      页面,
      "登录 Tap",
      {
        中心X: 按钮行.左 + 按钮行.宽 + 按钮行.间距 + 按钮行.宽 / 2,
        中心Y: 按钮行.上 + 按钮行.高 / 2,
        宽: 按钮行.宽,
        高: 按钮行.高,
      },
      this.逻辑高,
      { 点击: () => void this.登录(), 绘制: (环境) => this.绘制登录按钮(环境) },
    );
    this.应用注册参数(页面);
  }

  private 创建页签组件(): 页签组件 {
    const 文案 = this.上下文.服务.语言.读取();
    return new 页签组件({
      条目: 排行榜周期顺序.map((周期) => 周期标签(周期, 文案)),
      已选: 排行榜周期顺序.indexOf(this.周期),
      间距: this.计算布局().页签.间距,
      变化: (序号) => {
        const 周期 = 排行榜周期顺序[序号];
        if (!周期 || this.周期 === 周期 || this.加载中) return;
        this.周期 = 周期;
        this.缓存 = { 状态文案: this.上下文.服务.语言.读取().排行榜加载中, 分数列表: [] };
        this.重建();
        void this.刷新在线榜();
      },
      绘制底板: (环境, 状态) => {
        const 矩形 = 状态.矩形;
        绘制覆盖页按钮(
          环境.图形,
          矩形.左 + 矩形.宽 / 2,
          矩形.上 + 矩形.高 / 2,
          矩形.宽,
          矩形.高,
          状态.已选,
        );
      },
      绘制文字: (环境, 状态) => {
        const 画笔 = 读取画笔(环境);
        if (!画笔) return;
        画笔.绘制文字(
          生成页面文字项(
            "中中",
            状态.矩形.左 + 状态.矩形.宽 / 2,
            状态.矩形.上 + 状态.矩形.高 / 2,
            13,
            this.色.正文,
            "常规",
            "中",
            状态.文案,
            undefined,
            读取覆盖页按钮文字样式(状态.已选, 13),
          ),
        );
      },
    });
  }

  /** 主题 / 语言 / 尺寸 / 数据变化：重算注册参数与内容高度，只标脏不重建节点。 */
  protected 应用注册参数(_页面: 节点): void {
    this.色 = 读取页面语义色(this.上下文.服务.设置.读取().样式);
    const 布局 = this.计算布局();
    this.底板节点?.读取二维坐标()?.更新参数({
      位置X: 0,
      位置Y: 0,
      宽: this.逻辑宽,
      高: this.逻辑高,
      锚点X: 0,
      锚点Y: 0,
    });
    this.页签节点?.读取二维坐标()?.更新参数({
      位置X: 布局.页签.左,
      位置Y: this.逻辑高 - 布局.页签.上 - 布局.页签.高,
      宽: 排行榜周期顺序.length * 布局.页签.宽 + (排行榜周期顺序.length - 1) * 布局.页签.间距,
      高: 布局.页签.高,
    });
    this.页签节点?.读取组件<页签组件>(页签组件)?.应用参数({
      条目: 排行榜周期顺序.map((周期) => 周期标签(周期, this.上下文.服务.语言.读取())),
      已选: 排行榜周期顺序.indexOf(this.周期),
      间距: 布局.页签.间距,
      变化: (序号) => {
        const 周期 = 排行榜周期顺序[序号];
        if (!周期 || this.周期 === 周期 || this.加载中) return;
        this.周期 = 周期;
        this.缓存 = { 状态文案: this.上下文.服务.语言.读取().排行榜加载中, 分数列表: [] };
        this.重建();
        void this.刷新在线榜();
      },
      绘制底板: (环境, 状态) => {
        const 矩形 = 状态.矩形;
        绘制覆盖页按钮(
          环境.图形,
          矩形.左 + 矩形.宽 / 2,
          矩形.上 + 矩形.高 / 2,
          矩形.宽,
          矩形.高,
          状态.已选,
        );
      },
      绘制文字: (环境, 状态) => {
        const 画笔 = 读取画笔(环境);
        if (!画笔) return;
        画笔.绘制文字({
          ...生成页面文字项(
            "中中",
            状态.矩形.左 + 状态.矩形.宽 / 2,
            状态.矩形.上 + 状态.矩形.高 / 2,
            13,
            this.色.正文,
            "常规",
            "中",
            状态.文案,
            undefined,
            读取覆盖页按钮文字样式(状态.已选, 13),
          ),
          变换: 文字空间矩阵(环境, 环境.节点.读取本地矩形()?.高 ?? 布局.页签.高),
        });
      },
    });
    const 视口 = this.滚动?.节点;
    视口?.读取二维坐标()?.更新参数({
      位置X: 布局.列表.左,
      位置Y: this.逻辑高 - 布局.列表.上 - 布局.列表.高,
      宽: 布局.列表.宽,
      高: 布局.列表.高,
      锚点X: 0,
      锚点Y: 0,
      裁剪: true,
    });
    this.内容节点?.读取二维坐标()?.更新参数({
      位置X: 0,
      位置Y: 布局.列表.高,
      宽: 布局.列表.宽,
      高: Math.max(布局.列表.高, this.缓存.分数列表.length * 布局.行高 + 8),
      锚点X: 0,
      锚点Y: 1,
    });
    更新文字节点(
      this.标题节点,
      { 名称: "排行榜:标题", 项: this.标题文字项() },
      this.逻辑高,
      this.测量文字,
    );
    更新文字节点(
      this.状态节点,
      { 名称: "排行榜:状态", 项: this.状态文字项() },
      this.逻辑高,
      this.测量文字,
    );
    更新文字节点(
      this.空提示节点,
      { 名称: "排行榜:空提示", 项: this.空提示文字项() },
      this.逻辑高,
      this.测量文字,
    );
    this.空提示节点?.设置可见(this.读取应显示空提示());
    this.重建行节点();
    const 按钮行 = 布局.按钮行;
    this.返回节点?.读取二维坐标()?.更新参数({
      位置X: 按钮行.左 + 按钮行.宽 / 2,
      位置Y: this.逻辑高 - (按钮行.上 + 按钮行.高 / 2),
      宽: 按钮行.宽,
      高: 按钮行.高,
    });
    this.登录节点?.读取二维坐标()?.更新参数({
      位置X: 按钮行.左 + 按钮行.宽 + 按钮行.间距 + 按钮行.宽 / 2,
      位置Y: this.逻辑高 - (按钮行.上 + 按钮行.高 / 2),
      宽: 按钮行.宽,
      高: 按钮行.高,
    });
  }

  调整尺寸(): void {
    super.调整尺寸();
    const 根 = this.读取节点根();
    if (根) this.应用注册参数(根);
  }

  private 计算布局() {
    return 计算排行榜页布局(this.逻辑宽, this.逻辑高);
  }

  // ---- 绘制 ----

  private 测量文字 = (文案: string, 样式: 文字项["样式"]) =>
    this.上下文.资源.画笔.测量文字(文案, 样式);

  private 标题文字项(): 文字项 {
    const 布局 = this.计算布局();
    return 生成页面文字项(
      "中中",
      布局.标题中心.x,
      布局.标题中心.y,
      22,
      this.色.正文,
      "粗体",
      "中",
      填充文案(this.上下文.服务.语言.读取().排行榜标题, { 模式: this.模式 }),
    );
  }

  private 状态文字项(): 文字项 {
    const 文案 = this.上下文.服务.语言.读取();
    const 布局 = this.计算布局();
    const 状态 = this.加载中 ? 文案.排行榜加载中 : this.缓存.状态文案;
    return {
      文案: 状态,
      样式: 派生覆盖页文字样式({ 字号: 12, 颜色: this.色.次要, 对齐: "中" }),
      锚点: "中上",
      x: 布局.状态.中心X,
      y: 布局.状态.上,
      最大宽: 布局.状态.最大宽,
    };
  }

  private 空提示文字项(): 文字项 {
    return 生成页面文字项(
      "中中",
      this.计算布局().状态.中心X,
      168,
      14,
      this.色.次要,
      "常规",
      "中",
      this.上下文.服务.语言.读取().排行榜空提示,
    );
  }

  private 读取应显示空提示(): boolean {
    return (
      !this.缓存.分数列表.length && !this.加载中 && !this.缓存.需登录 && this.缓存.已加载 === true
    );
  }

  private 绘制底板(环境: 节点绘制环境): void {
    在本地空间绘制(环境, () => {
      环境.图形.fillStyle(this.色.面板, 1).fillRect(0, 0, this.逻辑宽, this.逻辑高);
    });
  }

  /** 榜单行：每行一个节点，行内坐标从 0 起，滚动/位移时整行跟随。 */
  private 重建行节点(): void {
    const 内容 = this.内容节点;
    if (!内容) return;
    for (const 节点 of this.行节点) 内容.移除子(节点);
    this.行节点 = [];
    const 布局 = this.计算布局();
    const 文案 = this.上下文.服务.语言.读取();
    const 内容高 = Math.max(布局.列表.高, this.缓存.分数列表.length * 布局.行高 + 8);
    this.缓存.分数列表.forEach((项, i) => {
      const 行矩形 = { 左: 0, 上: 0, 宽: 布局.行宽, 高: 布局.行板高 };
      const 行左 = Math.max(0, (this.逻辑宽 - 布局.行宽) / 2 - 布局.列表.左);
      const 行节点 = new 节点(`排行榜行:${i + 1}`);
      行节点.挂载组件(
        new 坐标2D组件({
          位置X: 行左,
          位置Y: 内容高 - i * 布局.行高,
          宽: 布局.行宽,
          高: 布局.行板高,
          锚点X: 0,
          锚点Y: 1,
        }),
      );
      行节点.挂载组件(
        new 绘制组件({
          绘制: (环境) => this.绘制榜单行(环境, 项, i, 行矩形, 文案),
        }),
      );
      内容.添加子(行节点);
      this.行节点.push(行节点);
    });
  }

  private 绘制榜单行(
    环境: 节点绘制环境,
    项: Tap排行榜分数,
    i: number,
    行矩形: { 左: number; 上: number; 宽: number; 高: number },
    文案: 游戏文案,
  ): void {
    const 画笔 = 画法画笔(环境);
    在本地空间绘制(环境, () => {
      const 图形 = 环境.图形;
      图形
        .fillStyle(this.色.按钮底, 0.65)
        .fillRoundedRect(行矩形.左, 行矩形.上, 行矩形.宽, 行矩形.高, 10);
      const 名 = 项.user?.name || 文案.排行榜玩家;
      const 排名 = 项.rankDisplay ?? String(项.rank ?? i + 1);
      const 分 = 项.scoreDisplay ?? 格式化榜分数(this.模式, 项.score);
      画笔.绘制文字(
        生成页面文字项("左上", 12, 行矩形.上 + 12, 14, this.色.强调, "粗体", "左", `#${排名}`),
      );
      画笔.绘制文字(生成页面文字项("左上", 64, 行矩形.上 + 12, 14, this.色.正文, "常规", "左", 名));
      画笔.绘制文字(
        生成页面文字项("右上", 行矩形.宽 - 12, 行矩形.上 + 12, 14, this.色.正文, "常规", "右", 分),
      );
    });
  }

  private 绘制返回按钮(环境: 节点绘制环境): void {
    const 画笔 = 读取画笔(环境);
    const 矩形 = 环境.节点.读取本地矩形();
    if (!画笔 || !矩形) return;
    const 区域 = 由矩形得到装置区域({ 左: 0, 上: 0, 宽: 矩形.宽, 高: 矩形.高 });
    在本地空间绘制(环境, () => {
      const 文字 = this.上下文.服务.语言.读取().返回;
      绘制返回传送装置(环境.图形, 区域, { 时间秒: 0, 下沉: 0, 点亮: [], 文案: 文字 });
      画笔.绘制文字({
        ...生成返回按键文字项(区域, 文字),
        变换: 文字空间矩阵(环境, 矩形.高),
      });
    });
  }

  private 绘制登录按钮(环境: 节点绘制环境): void {
    const 画笔 = 读取画笔(环境);
    const 矩形 = 环境.节点.读取本地矩形();
    if (!画笔 || !矩形) return;
    const 文字 = this.上下文.服务.语言.读取().排行榜登录Tap;
    在本地空间绘制(环境, () => {
      绘制覆盖页按钮(环境.图形, 矩形.宽 / 2, 矩形.高 / 2, 矩形.宽, 矩形.高);
      画笔.绘制文字({
        文案: 文字,
        样式: 读取覆盖页按钮文字样式(false, 15),
        锚点: "中中",
        x: 矩形.宽 / 2,
        y: 矩形.高 / 2,
        变换: 文字空间矩阵(环境, 矩形.高),
      });
    });
  }

  private 登录(): void {
    const 英文 = this.上下文.服务.语言.是否英文();
    const 文案 = this.上下文.服务.语言.读取();
    void 请求Tap登录(英文).then((结果) => {
      this.缓存 = {
        ...this.缓存,
        状态文案: 结果.完成 ? 文案.排行榜登录成功 : 结果.原因,
        已加载: false,
        我的行: "",
      };
      this.重建();
      if (结果.完成) void this.刷新在线榜();
    });
  }

  private 读取滚动位置(): number {
    return this.滚动?.读取偏移() ?? 0;
  }

  protected 读取文字快照(): readonly string[] {
    const 当地 = this.上下文.服务.纪录.读取(
      this.模式,
      this.模式 === "每日挑战" ? this.上下文.服务.当日日期() : undefined,
    );
    return [
      `模式:${this.模式}`,
      `周期:${this.周期}`,
      `状态:${this.缓存.状态文案}`,
      `我的:${this.缓存.我的行 || "无"}`,
      `行数:${this.缓存.分数列表.length}`,
      `滚动:${this.读取滚动位置()}`,
      `本地最佳:${
        当地
          ? this.模式 === "冲刺"
            ? `${typeof 当地.用时 === "number" ? (当地.用时 / 1000).toFixed(2) : "—"}s`
            : 当地.分数
          : 0
      }`,
      `在线:${this.上下文.服务.平台.是否可用() ? "可用" : "仅本地"}`,
    ];
  }

  private async 刷新在线榜(): Promise<void> {
    const 英文 = this.上下文.服务.语言.是否英文();
    const 文案 = this.上下文.服务.语言.读取();
    if (this.加载中) return;
    this.加载中 = true;
    this.缓存 = { 状态文案: 文案.排行榜加载中, 分数列表: [] };
    this.重建();
    const 结果 = await 加载排行榜数据({ 模式: this.模式, 周期: this.周期, 条数: 20, 英文 });
    this.加载中 = false;
    const 我的 = 结果.我的;
    const 我的行 =
      我的 && (我的.rank != null || 我的.score != null)
        ? 填充文案(文案.排行榜我的名次, {
            名次: 我的.rankDisplay ?? 我的.rank ?? "—",
            分数: 我的.scoreDisplay ?? 格式化榜分数(this.模式, 我的.score),
          })
        : 文案.排行榜我的暂无成绩;
    this.缓存 = {
      状态文案: 结果.完成
        ? `${我的行}${结果.当前周期展示 ? ` · ${结果.当前周期展示}` : ""}`
        : 结果.需登录
          ? 文案.排行榜需登录
          : 格式化排行榜错误(结果.代码, 结果.原因, 英文),
      分数列表: 结果.完成 ? 结果.分数列表 : [],
      需登录: 结果.需登录,
      已加载: 结果.完成,
      我的行: 结果.完成 ? 我的行 : "",
    };
    this.重建();
  }
}

function 生成页面文字项(
  锚点: 文字项["锚点"],
  x: number,
  y: number,
  字号: number,
  颜色: number,
  字重: "常规" | "粗体",
  对齐: "左" | "中" | "右",
  文案: string,
  最大宽?: number,
  样式?: 文字项["样式"],
): 文字项 {
  return {
    文案,
    样式: 样式 ?? 派生覆盖页文字样式({ 字号, 颜色, 字重, 对齐 }),
    锚点,
    x,
    y,
    最大宽,
  };
}

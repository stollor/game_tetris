/**
 * 模式选择页：游戏名 / 「选择模式」标题 / 5 张模式卡 / 返回装置 / 入场演出，全部是节点。
 *
 * 模式卡是游戏特有组件（卡内整卡与排行钮两个命中区，视觉由模式卡预制体画）；
 * 选中模式后播入场演出：内容节点隐藏、整页演出节点接管，演出结束再进对局。
 * 首次进入构建节点树，之后常驻；资源/主题/语言/尺寸变化只重算注册参数。
 *
 * 跨页过渡仍由页面声明（P4 改自动配对），身份与位移与旧实现一致。
 */

interface 按钮区域布局 {
  中心X: number;
  中心Y: number;
  宽: number;
  高: number;
}

interface 模式卡绘制项 {
  区域: 模式卡区域;
  数据: 模式卡数据;
}

function 按钮矩形(区域: 按钮区域布局): 流转矩形 {
  return {
    左: 区域.中心X - 区域.宽 / 2,
    上: 区域.中心Y - 区域.高 / 2,
    宽: 区域.宽,
    高: 区域.高,
  };
}

export class 模式选择页 extends 页面基类 {
  private 英文 = false;
  private 模式卡列表: readonly 模式卡绘制项[] = [];
  /** 待机时钟，只驱动方块浮动与标题饰，不跟满帧重画整页。 */
  private 场景秒 = 0;
  private 装饰绘制秒 = 0;
  private 启动: { 模式: 游戏模式; 秒: number } | null = null;

  private 游戏名节点: 节点 | null = null;
  private 标题节点: 节点 | null = null;
  private 返回节点: 节点 | null = null;
  private 演出节点: 节点 | null = null;
  private 卡节点 = new Map<游戏模式, 节点>();

  constructor(上下文: 页面上下文) {
    super(上下文, {
      名称: "模式选择",
      开合: { 打开秒: 0.3, 关闭秒: 0.25 },
      节点树: { 绘制带数: 1 },
    });
  }

  进入(): void {
    this.启动 = null;
    this.场景秒 = 0;
    this.装饰绘制秒 = 0;
    super.进入();
  }

  private get 布局(): 模式选择布局 {
    return 计算模式选择布局(this.逻辑宽, this.逻辑高);
  }

  更新(秒: number): void {
    super.更新(秒);
    this.推进动效(秒);
  }

  protected 构建节点树(页面: 节点): void {
    this.英文 = this.上下文.服务.语言.是否英文();
    this.模式卡列表 = this.读取模式卡列表(this.布局);
    const 布局 = this.布局;
    const [游戏名项, 标题项] = 生成模式选择文字项(布局, this.文字数据());
    this.游戏名节点 = 创建文字节点(
      页面,
      { 名称: "游戏标题", 项: 游戏名项! },
      this.逻辑高,
      this.测量文字(),
    );
    // 「选择模式」标题节点：文字 + 标题饰一起画，按 12fps 标脏驱动流光。
    this.标题节点 = 创建注册节点(页面, {
      名称: "选择模式",
      坐标: this.文字节点坐标(标题项!),
      组件: new 文字组件({
        绘制: (环境) => this.绘制标题节点(环境, 标题项!),
      }),
    }).设置开合行为({ 类型: "显隐" });
    for (const { 区域, 数据 } of this.模式卡列表) {
      const 节点 = 创建注册节点(页面, {
        名称: `模式:${区域.模式}`,
        坐标: this.卡节点坐标(区域),
        组件: new 模式卡组件({
          数据,
          点击: () => this.开始启动模式(区域.模式),
          排行点击: () => {
            if (this.启动) return;
            this.上下文.导航.进入("排行榜", { 模式: 区域.模式 });
          },
        }),
      });
      节点.设置开合行为({ 类型: "显隐" });
      this.卡节点.set(区域.模式, 节点);
    }
    this.返回节点 = 创建按钮节点(页面, "返回", 布局.返回钮, this.逻辑高, {
      点击: () => this.上下文.导航.返回(),
      绘制: (环境, 状态) => this.绘制返回按钮(环境, 状态.矩形, 状态.按下),
    }).设置开合行为({ 类型: "滑入", 方向: "下" });
    this.演出节点 = 创建整页绘制节点(页面, "模式:演出", this.逻辑宽, this.逻辑高, (环境) => {
      const 画笔 = 读取画笔(环境);
      if (画笔) 在本地空间绘制(环境, () => this.绘制模式入场(画笔));
    });
    this.演出节点.设置可见(false);
    this.应用注册参数(页面);
  }

  /** 主题 / 语言 / 尺寸 / 纪录变化：重算数据与注册参数，只标脏不重建节点。 */
  protected 应用注册参数(_页面: 节点): void {
    this.英文 = this.上下文.服务.语言.是否英文();
    const 布局 = this.布局;
    this.模式卡列表 = this.读取模式卡列表(布局);
    const [游戏名项, 标题项] = 生成模式选择文字项(布局, this.文字数据());
    更新文字节点(
      this.游戏名节点,
      { 名称: "游戏标题", 项: 游戏名项! },
      this.逻辑高,
      this.测量文字(),
    );
    if (this.标题节点) {
      this.标题节点.读取二维坐标()?.更新参数(this.文字节点坐标(标题项!));
      this.标题节点.读取组件<文字组件>(文字组件)?.应用参数({
        绘制: (环境) => this.绘制标题节点(环境, 标题项!),
      });
    }
    for (const { 区域, 数据 } of this.模式卡列表) {
      const 节点 = this.卡节点.get(区域.模式);
      if (!节点) continue;
      节点.读取二维坐标()?.更新参数(this.卡节点坐标(区域));
      节点.读取组件<模式卡组件>(模式卡组件)?.应用参数({
        数据,
        点击: () => this.开始启动模式(区域.模式),
        排行点击: () => {
          if (this.启动) return;
          this.上下文.导航.进入("排行榜", { 模式: 区域.模式 });
        },
      });
    }
    更新按钮节点(this.返回节点, 布局.返回钮, this.逻辑高, {
      点击: () => this.上下文.导航.返回(),
      绘制: (环境, 状态) => this.绘制返回按钮(环境, 状态.矩形, 状态.按下),
    });
    // 尺寸变化后整页演出节点跟着变。
    this.演出节点?.读取二维坐标()?.更新参数({
      位置X: 0,
      位置Y: 0,
      宽: this.逻辑宽,
      高: this.逻辑高,
      锚点X: 0,
      锚点Y: 0,
    });
  }

  调整尺寸(): void {
    super.调整尺寸();
    const 根 = this.读取节点根();
    if (根) this.应用注册参数(根);
  }

  /** 待机约 12 帧重画一次；模式入场期间跟帧。 */
  private 推进动效(秒: number): void {
    this.场景秒 += 秒;
    const 卡时间 = this.场景秒;
    for (const 节点 of this.卡节点.values())
      节点.读取组件<模式卡组件>(模式卡组件)?.设置时间秒(卡时间);
    if (this.启动) {
      this.启动.秒 += 秒;
      if (this.启动.秒 >= 模式退场时长) {
        const 模式 = this.启动.模式;
        this.启动 = null;
        this.切换演出显示(false);
        this.进入对局(模式);
        return;
      }
      this.标记失效([0], "演出");
      return;
    }
    if (this.场景秒 - this.装饰绘制秒 >= 1 / 12) {
      this.装饰绘制秒 = this.场景秒;
      this.标记失效([0], "动画");
    }
  }

  private 开始启动模式(模式: 游戏模式): void {
    if (this.启动) return;
    this.启动 = { 模式, 秒: 0 };
    this.切换演出显示(true);
    this.标记失效([0], "启动");
  }

  private 切换演出显示(演出中: boolean): void {
    for (const 节点 of this.卡节点.values()) 节点.设置可见(!演出中);
    this.游戏名节点?.设置可见(!演出中);
    this.标题节点?.设置可见(!演出中);
    this.返回节点?.设置可见(!演出中);
    this.演出节点?.设置可见(演出中);
  }

  private 进入对局(模式: 游戏模式): void {
    this.上下文.导航.进入("对局", { 模式, 入场演出: true });
  }

  // ---- 节点坐标与画法 ----

  private 测量文字() {
    return (文案: string, 样式: Parameters<页面上下文["资源"]["画笔"]["测量文字"]>[1]) =>
      this.上下文.资源.画笔.测量文字(文案, 样式);
  }

  /** 文字项（中中锚点）→ 节点坐标。 */
  private 文字节点坐标(项: 文字项) {
    const 尺寸 = this.上下文.资源.画笔.测量文字(项.文案, 项.样式);
    return { 位置X: 项.x, 位置Y: this.逻辑高 - 项.y, 宽: 尺寸.宽, 高: 尺寸.高 };
  }

  /** 模式卡区域（页面坐标）→ 节点坐标（y 向上，中心锚点）。 */
  private 卡节点坐标(区域: 模式卡区域) {
    return {
      位置X: 区域.中心X,
      位置Y: this.逻辑高 - 区域.中心Y,
      宽: 区域.宽,
      高: 区域.高,
    };
  }

  private 绘制标题节点(环境: 节点绘制环境, 项: 文字项): void {
    const 画笔 = 读取画笔(环境);
    const 矩形 = 环境.节点.读取本地矩形();
    if (!画笔 || !矩形) return;
    const 布局 = this.布局;
    画笔.绘制文字({
      ...项,
      锚点: "中中",
      x: 矩形.宽 / 2,
      y: 矩形.高 / 2,
      变换: 文字空间矩阵(环境, 矩形.高),
    });
    if (!布局.视口.矮屏) {
      在本地空间绘制(环境, () => {
        绘制模式标题饰(环境.图形, 矩形.宽 / 2, 矩形.高 / 2 + 26, this.场景秒);
      });
    }
  }

  /** 返回装置：传送装置 + 文字，画在按钮节点本地空间。 */
  private 绘制返回按钮(环境: 节点绘制环境, 矩形: { 宽: number; 高: number }, 按下: boolean): void {
    const 画笔 = 读取画笔(环境);
    if (!画笔) return;
    const 区域 = { 中心X: 矩形.宽 / 2, 中心Y: 矩形.高 / 2, 宽: 矩形.宽, 高: 矩形.高 };
    const 文案 = this.英文 ? "BACK" : "返回";
    绘制返回传送装置(环境.图形, 区域, {
      时间秒: this.场景秒,
      下沉: 按下 ? 1 : 0,
      点亮: [0, 0, 0, 0],
      文案,
    });
    画笔.绘制文字({
      ...生成返回按键文字项(区域, 文案, 按下 ? 1 : 0),
      变换: 文字空间矩阵(环境, 矩形.高),
    });
  }

  private 读取模式卡列表(布局: 模式选择布局): readonly 模式卡绘制项[] {
    const 今日 = this.上下文.服务.当日日期();
    return 布局.卡.map((区域) => ({
      区域,
      数据: 组装模式卡数据(
        区域.模式,
        this.英文,
        this.上下文.服务.纪录.读取(区域.模式, 区域.模式 === "每日挑战" ? 今日 : undefined),
      ),
    }));
  }

  private 文字数据() {
    return {
      英文: this.英文,
      游戏名称: this.上下文.服务.语言.读取().游戏名称,
    };
  }

  // ---- 入场演出（仍按页面坐标画，由整页演出节点接管） ----

  private 绘制模式入场(画笔: 画笔): void {
    const 启动 = this.启动;
    const 卡 = this.模式卡列表.find((项) => 项.区域.模式 === 启动?.模式);
    if (!启动 || !卡) return;
    const 原 = 按钮矩形(卡.区域);
    const 姿态 = 计算模式入场姿态(启动.秒, 原, this.逻辑宽, this.逻辑高);
    const 选中序号 = this.模式卡列表.indexOf(卡);
    this.模式卡列表.forEach((项, 序号) => {
      if (项.区域.模式 === 启动.模式) return;
      const 块: 可绘制流转块 = {
        身份: `模式:${项.区域.模式}`,
        矩形: 按钮矩形(项.区域),
        绘制: (笔) => 绘制模式卡(笔.图形, 项.区域, 项.数据, { 时间秒: this.场景秒 }),
      };
      const 距离 = Math.abs(序号 - 选中序号);
      播放块(画笔, 块, 计算退场进度(启动.秒, 距离), this.逻辑宽, this.逻辑高);
    });
    绘制入场幕面(画笔, this.逻辑宽, this.逻辑高, 启动.模式, 姿态.幕缝);
    const 色 = 亮色(模式主题色(启动.模式), 入场参数.颜色.线提亮 * 姿态.线脉冲);
    绘制流转块(
      画笔,
      { 身份: `模式:${启动.模式}`, 来源: "出发", 透明度: 1, 静止: 原, 当前: 姿态.矩形 },
      (笔) => {
        笔.图形
          .fillStyle(混色(入场参数.颜色.卡面, 色, 姿态.压缩进度 ** 0.6), 1)
          .fillRoundedRect(原.左, 原.上, 原.宽, 原.高, 10 * (1 - 姿态.压缩进度));
        笔.图形
          .lineStyle(1, 色, 0.7 * (1 - 姿态.压缩进度))
          .strokeRoundedRect(原.左, 原.上, 原.宽, 原.高, 10 * (1 - 姿态.压缩进度));
        if (姿态.内容透明度 > 0) {
          笔.图形.save().setAlpha(姿态.内容透明度);
          绘制模式卡(笔.图形, 卡.区域, 卡.数据, { 时间秒: this.场景秒 });
          for (const 项 of 生成模式卡文字项(卡.区域, 卡.数据)) 笔.绘制文字(项);
          笔.图形.restore();
        }
      },
    );
    if (姿态.压缩进度 === 1) 绘制凝聚横线(画笔, this.逻辑宽, this.逻辑高, 启动.模式, 姿态.线脉冲);
  }

  protected 读取文字快照(): readonly string[] {
    const 布局 = this.布局;
    const 今日 = this.上下文.服务.当日日期();
    return [
      "页面:模式选择",
      `开合:${this.上下文.过渡 ? "播放中" : "无"}`,
      `启动:${this.启动?.模式 ?? "无"}`,
      `入场:${this.启动 ? 计算模式入场姿态(this.启动.秒, { 左: 0, 上: 0, 宽: 1, 高: 1 }, this.逻辑宽, this.逻辑高).阶段 : "无"}`,
      `入场秒:${this.启动?.秒 ?? 0}`,
      ...布局.卡.map((区域) => {
        const 纪录 = this.上下文.服务.纪录.读取(
          区域.模式,
          区域.模式 === "每日挑战" ? 今日 : undefined,
        );
        return `${区域.模式}:${纪录?.分数 ?? 0}`;
      }),
    ];
  }
}

/** 退场中的一块：静止占位 + 淡出/收束进度。 */
function 播放块(画笔: 画笔, 块: 可绘制流转块, 线性进度: number, 宽: number, 高: number): void {
  播放界面流转(画笔, [块], [], 线性进度, { 宽, 高 });
}

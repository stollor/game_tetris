/**
 * 模式选择页：模式装置卡 + 返回传送装置 + 「选择模式」标题。
 * 游戏名与菜单页的大标题共用「游戏标题」身份，跨页只位移/变形；选中模式后播入场演出再进对局。
 * 背景在背景层、金币在货币层、提示在提示层，本页只画自己的内容。
 *
 * 跨页过渡：本页声明自己的 UI 元素为流转块（游戏标题、选择模式、每张模式卡、返回），
 * 从菜单进来时标题连续变形、模式卡从左右滑入；进纯享时它们按贴边规则滑出。
 * 背景不参与流转：它由背景层提供，三页共用同一张。
 */

interface 按钮区域布局 {
  中心X: number;
  中心Y: number;
  宽: number;
  高: number;
}

interface 模式卡绘制项 {
  区域: 模式卡区域;
  数据: 模式卡数据;
}

function 按钮矩形(区域: 按钮区域布局): 流转矩形 {
  return {
    左: 区域.中心X - 区域.宽 / 2,
    上: 区域.中心Y - 区域.高 / 2,
    宽: 区域.宽,
    高: 区域.高,
  };
}

export class 模式选择页 extends 页面基类 {
  private 英文 = false;
  private 模式卡列表: readonly 模式卡绘制项[] = [];
  /** 只由按钮的按下/松开/取消写入，供配方画按下态，不另做命中。 */
  private readonly 按下中 = new Set<string>();
  /** 待机时钟，只驱动方块浮动，不跟满帧重画整页。 */
  private 场景秒 = 0;
  private 装饰绘制秒 = 0;
  private 启动: { 模式: 游戏模式; 秒: number } | null = null;

  constructor(上下文: 页面上下文) {
    super(上下文, { 名称: "模式选择" });
  }

  进入(): void {
    this.启动 = null;
    this.按下中.clear();
    this.场景秒 = 0;
    this.装饰绘制秒 = 0;
    super.进入();
  }

  private get 布局(): 模式选择布局 {
    return 计算模式选择布局(this.逻辑宽, this.逻辑高);
  }

  更新(秒: number): void {
    super.更新(秒);
    this.推进动效(秒);
  }

  protected 构建(): void {
    this.英文 = this.上下文.服务.语言.是否英文();
    const 布局 = this.布局;
    this.模式卡列表 = this.读取模式卡列表(布局);
    for (const { 区域, 数据 } of this.模式卡列表) {
      this.创建按钮(`开始:${区域.模式}`, {
        绘制底板: () => {},
        移出取消: true,
        矩形: 按钮矩形(区域),
        点击: () => this.开始启动模式(区域.模式),
        按下: () => this.按下刷新(`开始:${区域.模式}`, true),
        松开: () => this.按下刷新(`开始:${区域.模式}`, false),
        取消: () => this.按下刷新(`开始:${区域.模式}`, false),
      });
      if (!数据.有排行) continue;
      // 排行钮位置与绘制共用模式卡配方的同一份几何。
      const 排行区域 = 计算模式卡排行区域(区域);
      this.创建按钮(`排行榜:${区域.模式}`, {
        绘制底板: () => {},
        移出取消: true,
        矩形: 按钮矩形(排行区域),
        点击: () => {
          if (this.启动) return;
          this.上下文.导航.进入("排行榜", { 模式: 区域.模式 });
        },
        按下: () => this.按下刷新(`排行榜:${区域.模式}`, true),
        松开: () => this.按下刷新(`排行榜:${区域.模式}`, false),
        取消: () => this.按下刷新(`排行榜:${区域.模式}`, false),
      });
    }
    this.创建按钮("返回", {
      绘制底板: () => {},
      移出取消: true,
      矩形: 按钮矩形(布局.返回钮),
      点击: () => this.上下文.导航.返回(),
      按下: () => this.按下刷新("返回", true),
      松开: () => this.按下刷新("返回", false),
      取消: () => this.按下刷新("返回", false),
    });
  }

  private 按下刷新(名称: string, 按下: boolean): void {
    if (按下) this.按下中.add(名称);
    else this.按下中.delete(名称);
    this.请求重绘();
  }

  /** 待机约 12 帧重画内容层；模式入场期间跟帧，保证居中、压线与幕面连续。 */
  private 推进动效(秒: number): void {
    this.场景秒 += 秒;
    if (this.启动) {
      this.启动.秒 += 秒;
      if (this.启动.秒 >= 模式退场时长) {
        const 模式 = this.启动.模式;
        this.启动 = null;
        this.进入对局(模式);
        return;
      }
    }
    const 演出中 = this.启动 !== null;
    if (演出中 || this.场景秒 - this.装饰绘制秒 >= 1 / 12) {
      this.装饰绘制秒 = this.场景秒;
      this.请求重绘();
    }
  }

  private 开始启动模式(模式: 游戏模式): void {
    if (this.启动) return;
    this.启动 = { 模式, 秒: 0 };
    this.控件层.清空();
    this.按下中.clear();
    this.请求重绘();
  }

  private 进入对局(模式: 游戏模式): void {
    this.上下文.导航.进入("对局", { 模式, 入场演出: true });
  }

  private 读取模式卡动效(模式: 游戏模式): 模式卡绘制状态 {
    const 按下 = this.按下中.has(`开始:${模式}`);
    return {
      按下,
      下沉: 按下 ? 3 : 0,
      时间秒: this.场景秒,
      点亮: 按下 ? [1, 1, 1, 1] : [0, 0, 0, 0],
      排行按下: this.按下中.has(`排行榜:${模式}`),
    };
  }

  private 读取返回姿态(): 传送姿态 {
    return {
      下沉: this.按下中.has("返回") ? 1 : 0,
      点亮: [0, 0, 0, 0],
      完成: false,
    };
  }

  private 读取模式卡列表(布局: 模式选择布局): readonly 模式卡绘制项[] {
    const 今日 = this.上下文.服务.当日日期();
    return 布局.卡.map((区域) => ({
      区域,
      数据: 组装模式卡数据(
        区域.模式,
        this.英文,
        this.上下文.服务.纪录.读取(区域.模式, 区域.模式 === "每日挑战" ? 今日 : undefined),
      ),
    }));
  }

  private 文字数据() {
    return {
      英文: this.英文,
      游戏名称: this.上下文.服务.语言.读取().游戏名称,
    };
  }

  protected 绘制内容(): void {
    const 画笔 = this.上下文.资源.画笔;
    const 图形 = 画笔.图形;
    if (this.启动) {
      this.绘制模式入场(画笔);
      return;
    }
    const 布局 = this.布局;
    for (const 项 of 生成模式选择文字项(布局, this.文字数据())) 画笔.绘制文字(项);
    if (!布局.视口.矮屏) 绘制模式标题饰(图形, 布局.标题.x, 布局.标题.y + 26, this.场景秒);
    for (const { 区域, 数据 } of this.模式卡列表) {
      const 动效 = this.读取模式卡动效(区域.模式);
      绘制模式卡(图形, 区域, 数据, 动效);
      for (const 项 of 生成模式卡文字项(区域, 数据))
        画笔.绘制文字({ ...项, y: 项.y + (动效.下沉 ?? 0) });
    }
    const 返回姿态 = this.读取返回姿态();
    const 文案 = this.英文 ? 布局.返回钮.文案.英文 : 布局.返回钮.文案.中文;
    绘制返回传送装置(图形, 布局.返回钮, {
      时间秒: this.场景秒,
      下沉: 返回姿态.下沉,
      点亮: 返回姿态.点亮,
      文案,
    });
    画笔.绘制文字(生成返回按键文字项(布局.返回钮, 文案, 返回姿态.下沉));
  }

  private 绘制模式入场(画笔: import("../../框架/界面/绘制/画笔").画笔): void {
    const 启动 = this.启动;
    const 布局 = this.布局;
    const 卡 = this.模式卡列表.find((项) => 项.区域.模式 === 启动?.模式);
    if (!启动 || !卡) return;
    const 原 = 按钮矩形(卡.区域);
    const 姿态 = 计算模式入场姿态(启动.秒, 原, this.逻辑宽, this.逻辑高);
    const 选中序号 = this.模式卡列表.indexOf(卡);
    for (const 块 of this.流转块列表(布局)) {
      if (块.身份 === `模式:${启动.模式}`) continue;
      const 序号 = this.模式卡列表.findIndex((项) => 块.身份 === `模式:${项.区域.模式}`);
      const 距离 = 序号 < 0 ? 0 : Math.abs(序号 - 选中序号);
      播放块(画笔, 块, 计算退场进度(启动.秒, 距离), this.逻辑宽, this.逻辑高);
    }
    绘制入场幕面(画笔, this.逻辑宽, this.逻辑高, 启动.模式, 姿态.幕缝);
    const 色 = 亮色(模式主题色(启动.模式), 入场参数.颜色.线提亮 * 姿态.线脉冲);
    绘制流转块(
      画笔,
      { 身份: `模式:${启动.模式}`, 来源: "出发", 透明度: 1, 静止: 原, 当前: 姿态.矩形 },
      (笔) => {
        笔.图形
          .fillStyle(混色(入场参数.颜色.卡面, 色, 姿态.压缩进度 ** 0.6), 1)
          .fillRoundedRect(原.左, 原.上, 原.宽, 原.高, 10 * (1 - 姿态.压缩进度));
        笔.图形
          .lineStyle(1, 色, 0.7 * (1 - 姿态.压缩进度))
          .strokeRoundedRect(原.左, 原.上, 原.宽, 原.高, 10 * (1 - 姿态.压缩进度));
        // 整卡先参与收束，内容直到压缩后段才消融，最终沿同一轮廓凝成线。
        if (姿态.内容透明度 > 0) {
          笔.图形.save().setAlpha(姿态.内容透明度);
          绘制模式卡(笔.图形, 卡.区域, 卡.数据, { 时间秒: this.场景秒 });
          for (const 项 of 生成模式卡文字项(卡.区域, 卡.数据)) 笔.绘制文字(项);
          笔.图形.restore();
        }
      },
    );
    if (姿态.压缩进度 === 1) 绘制凝聚横线(画笔, this.逻辑宽, this.逻辑高, 启动.模式, 姿态.线脉冲);
  }

  /** 本页要参与流转的块：游戏标题、选择模式标题、模式卡、返回（背景不在流转里）。 */
  private 流转块列表(布局: 模式选择布局): 可绘制流转块[] {
    const 块: 可绘制流转块[] = [];
    for (const 项 of 生成模式选择文字项(布局, this.文字数据())) {
      const 是游戏名 = 项.文案 === this.文字数据().游戏名称;
      块.push({
        身份: 是游戏名 ? "游戏标题" : "选择模式",
        矩形: 文字流转矩形(this.上下文, 项),
        位移: 是游戏名 ? { x: 0, y: -布局.视口.高 / 2 } : { x: 0, y: 36 },
        绘制: (笔) => {
          笔.绘制文字(项);
          if (!是游戏名 && !布局.视口.矮屏)
            绘制模式标题饰(笔.图形, 布局.标题.x, 布局.标题.y + 26, this.场景秒);
        },
      });
    }
    布局.卡.forEach((区域, 索引) => {
      块.push({
        身份: `模式:${区域.模式}`,
        矩形: 按钮矩形(区域),
        位移: { x: (索引 % 2 ? 1 : -1) * 布局.视口.宽, y: 0 },
        绘制: (笔) => {
          const 数据 = this.读取模式卡列表(布局).find((项) => 项.区域.模式 === 区域.模式)?.数据;
          if (!数据) return;
          const 动效 = this.读取模式卡动效(区域.模式);
          绘制模式卡(笔.图形, 区域, 数据, 动效);
          for (const 项 of 生成模式卡文字项(区域, 数据))
            笔.绘制文字({ ...项, y: 项.y + (动效.下沉 ?? 0) });
        },
      });
    });
    块.push({
      身份: "返回",
      矩形: 按钮矩形(布局.返回钮),
      位移: { x: 0, y: 100 },
      绘制: (笔) => {
        const 姿态 = this.读取返回姿态();
        const 文案 = this.英文 ? 布局.返回钮.文案.英文 : 布局.返回钮.文案.中文;
        绘制返回传送装置(笔.图形, 布局.返回钮, {
          时间秒: this.场景秒,
          下沉: 姿态.下沉,
          点亮: 姿态.点亮,
          文案,
        });
        笔.绘制文字(生成返回按键文字项(布局.返回钮, 文案, 姿态.下沉));
      },
    });
    return 块;
  }

  /** 跨页流转块：本页全部可见元素（身份与位移照搬重构前的主界面流转）。 */
  读取流转块(): readonly 可绘制流转块[] {
    return this.流转块列表(this.布局);
  }

  protected 绘制过渡(_环境: 绘制环境): void {
    绘制流转块列表(this.上下文, this.页面名称, this.读取流转块());
  }

  protected 读取文字快照(): readonly string[] {
    const 布局 = this.布局;
    const 今日 = this.上下文.服务.当日日期();
    return [
      "页面:模式选择",
      `过渡:${this.上下文.过渡 ? "流转" : "无"}`,
      `启动:${this.启动?.模式 ?? "无"}`,
      `入场:${this.启动 ? 计算模式入场姿态(this.启动.秒, { 左: 0, 上: 0, 宽: 1, 高: 1 }, this.逻辑宽, this.逻辑高).阶段 : "无"}`,
      `入场秒:${this.启动?.秒 ?? 0}`,
      ...布局.卡.map((区域) => {
        const 纪录 = this.上下文.服务.纪录.读取(
          区域.模式,
          区域.模式 === "每日挑战" ? 今日 : undefined,
        );
        return `${区域.模式}:${纪录?.分数 ?? 0}`;
      }),
    ];
  }
}

/** 退场中的一块：静止占位 + 淡出/收束进度。 */
function 播放块(
  画笔: import("../../框架/界面/绘制/画笔").画笔,
  块: 可绘制流转块,
  线性进度: number,
  宽: number,
  高: number,
): void {
  播放界面流转(画笔, [块], [], 线性进度, { 宽, 高 });
}

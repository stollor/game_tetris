/**
 * 成就页（7C）：与 Phaser 版同构——顶栏金币条 + 标题/副题 + 成就列表（行底板/进度线/文字）+ 返回按钮。
 * 视觉来自共享配方（页面配方/文字样式/金币条配方/按钮配方），滚动与命中用 GM Three 控件能力自绘。
 */

export class 成就界面 extends 页面基类 {
  private 滚动: 列表 | null = null;
  private 滚动位置 = 0;
  private 色: 页面语义色 = 读取页面语义色(
    this.上下文.服务.设置.读取().旅行样式 ?? this.上下文.服务.设置.读取().样式,
  );
  /** 上一帧列表滚动位置：惯性滚动只让控件层变化，列表视觉画在内容层。 */
  private 上次滚动 = 0;

  constructor(上下文: 页面上下文) {
    // 整页不透明底走背景静层；标题/列表/按钮走内容层，滚动时只重画内容。
    super(上下文, { 名称: "成就", 独占: true });
  }

  更新(秒: number): void {
    super.更新(秒);
    const 位置 = this.滚动?.读取滚动位置() ?? 0;
    if (位置 !== this.上次滚动) {
      this.上次滚动 = 位置;
      this.标记失效([页面绘制层.内容], "内容");
    }
  }

  protected 绘制背景静底(_环境: 绘制环境, 信息: 页面背景信息): void {
    this.上下文.资源.画笔.图形.fillStyle(this.色.面板, 1).fillRect(0, 0, 信息.宽, 信息.高);
  }

  进入(): void {
    super.进入();
    this.上下文.登记清理(this.上下文.服务.成就.订阅(() => this.重建()));
    this.上下文.登记清理(this.上下文.服务.金币.订阅(() => this.重建()));
    // 同步状态变化只让内容层失效，不重建页面（重建会再次触发补同步）。
    this.上下文.登记清理(订阅成就同步状态(() => this.标记失效([页面绘制层.内容], "成就同步")));
    this.自动领取();
    void 补同步已解锁成就(this.上下文.服务.成就.读取已解锁());
  }

  private 自动领取(): void {
    const 已解锁 = this.上下文.服务.成就.读取已解锁();
    if (已解锁.length === 0) return;
    const 结果 = this.上下文.服务.金币.领取成就(已解锁);
    if (结果.新增 <= 0) return;
    this.显示提示(
      this.上下文.服务.语言.是否英文()
        ? `Achievement rewards +${结果.新增}`
        : `成就奖励 +${结果.新增} 方块币`,
    );
  }

  protected 构建(): void {
    this.滚动位置 = this.滚动?.读取滚动位置() ?? this.滚动位置;
    this.控件层.清空();
    this.色 = 读取页面语义色(
      this.上下文.服务.设置.读取().旅行样式 ?? this.上下文.服务.设置.读取().样式,
    );
    const 页面布局 = 计算成就页布局(this.逻辑宽, this.逻辑高);
    this.滚动 = new 列表({
      矩形: 页面布局.列表,
      项布局: 成就定义.map((_, i) => ({
        起点: i * 页面布局.行高,
        长度: 页面布局.行高,
        横轴长度: 页面布局.行宽,
      })),
      创建项: () => [],
      显示滚动条: false,
      惯性: true,
    });
    this.控件层.添加(this.滚动);
    this.滚动.设置滚动位置(this.滚动位置);
    this.滚动位置 = this.滚动.读取滚动位置();
    this.上次滚动 = this.滚动.读取滚动位置();
    this.创建热区({
      名称: "返回主菜单",
      矩形: 页面布局.返回,
      点击: () => this.上下文.导航.返回(),
    });
  }

  protected 绘制内容(): void {
    const 画笔 = this.上下文.资源.画笔;
    const 图形 = 画笔.图形;
    if (!this.滚动) return;
    const 英文 = this.上下文.服务.语言.是否英文();
    const 色 = this.色;
    const 金币 = this.上下文.服务.金币.读取().金币;
    const 金币布局 = 计算金币条(16, 12, 金币);
    绘制金币条(图形, 金币布局);
    for (const 项 of 生成金币条文字项(金币布局, 金币)) 画笔.绘制文字(项);
    // 标题（窄屏避让金币条）
    const 标题文案 = `${英文 ? "Achievements" : "成就收藏"}  ${this.已得()} / ${成就定义.length}`;
    const 标题样式 = 派生霓虹文字样式("正文", {
      字号: 英文 ? 20 : 24,
      字重: "粗体",
      颜色: 色.正文,
      对齐: "中",
    });
    const 标题宽 = 画笔.测量文字(标题文案, 标题样式).宽;
    const 标题最小中心 = 16 + 金币布局.宽 + 12 + 标题宽 / 2;
    const 标题中心 = Math.max(
      this.逻辑宽 / 2,
      Math.min(标题最小中心, this.逻辑宽 - 12 - 标题宽 / 2),
    );
    画笔.绘制文字({ 文案: 标题文案, 样式: 标题样式, 锚点: "中中", x: 标题中心, y: 30 });
    画笔.绘制文字(
      生成页面文字项("中中", this.逻辑宽 / 2, 64, 13, 色.次要, "常规", "中", this.副标题(英文)),
    );
    const 可视 = this.滚动.读取可视矩形();
    const 偏移 = this.滚动.读取滚动位置();
    const 页面布局 = 计算成就页布局(this.逻辑宽, this.逻辑高);
    const 文字偏移 = { x: 可视.左, y: 可视.上 - 偏移 };
    const 暂存文字: 文字项[] = [];
    画笔.压入裁剪(可视);
    图形.save();
    图形.translateCanvas(可视.左, 可视.上 - 偏移);
    const 已解锁集合 = new Set(this.上下文.服务.成就.读取已解锁());
    for (const 序号 of this.滚动.读取可视项()) {
      const 定义 = 成就定义[序号];
      if (!定义) continue;
      const 已解锁 = 已解锁集合.has(定义.编号);
      const 进度 = this.上下文.服务.成就.读取进度(定义.编号);
      const 行矩形 = {
        ...this.滚动.读取项矩形(序号),
        高: 页面布局.行板高,
      };
      绘制列表行(图形, 行矩形, 色.按钮底, 已解锁 ? 色.强调 : 色.分组线, 0.7, 12, {
        比例: Math.min(1, 进度 / Math.max(1, 定义.目标)),
        轨道色: 色.分组线,
        强调色: 色.强调,
      });
      图形
        .save()
        .translateCanvas(行矩形.左 + 10, 行矩形.上 + 17)
        .scaleCanvas(1.25);
      绘制成就图标(图形, 定义.编号, 已解锁 ? 色.强调 : 色.正文);
      图形.restore();
      暂存文字.push(
        移位(
          生成页面文字项(
            "左上",
            行矩形.左 + 62,
            行矩形.上 + 10,
            16,
            已解锁 ? 色.强调 : 色.正文,
            "粗体",
            "左",
            `${已解锁 ? "✓ " : ""}${英文 ? 定义.英文 : 定义.名称}`,
            页面布局.行宽 - 140,
          ),
          文字偏移,
        ),
        移位(
          生成页面文字项(
            "左上",
            行矩形.左 + 62,
            行矩形.上 + 36,
            14,
            色.次要,
            "常规",
            "左",
            英文 ? 定义.英文说明 : 定义.说明,
            页面布局.行宽 - 78,
          ),
          文字偏移,
        ),
        移位(
          生成页面文字项(
            "右上",
            行矩形.左 + 行矩形.宽 - 16,
            行矩形.上 + 10,
            14,
            色.次要,
            "常规",
            "右",
            `${Math.min(进度, 定义.目标)}/${定义.目标}`,
          ),
          文字偏移,
        ),
      );
    }
    图形.restore();
    // 文字在图形平移之外绘制，仍保留列表屏幕裁剪。
    for (const 项 of 暂存文字) {
      if (项.y < 可视.上 - 24 || 项.y > 可视.上 + 可视.高 + 24) continue;
      画笔.绘制文字(项);
    }
    画笔.弹出裁剪();
    this.绘制返回按钮(图形, 画笔, 英文);
  }

  private 绘制返回按钮(图形: 图形对象, 画笔: 画笔, 英文: boolean): void {
    const 区域 = 由矩形得到装置区域(计算成就页布局(this.逻辑宽, this.逻辑高).返回);
    const 文案 = 英文 ? "Back" : "返回主菜单";
    绘制返回传送装置(图形, 区域, { 时间秒: 0, 下沉: 0, 点亮: [], 文案 });
    画笔.绘制文字(生成返回按键文字项(区域, 文案));
  }

  private 副标题(英文: boolean): string {
    const 普通 = 英文
      ? "Every game leaves a little progress."
      : "每项成就 +60 方块币，自动存入旅行收藏。";
    if (!探测Tap能力().有成就) return 普通;
    const 已解锁 = this.上下文.服务.成就.读取已解锁();
    if (已解锁.length === 0) return 普通;
    const 状态列表 = 已解锁
      .map((编号) => 读取成就同步状态(编号))
      .filter((项) => 项.状态 !== "未映射");
    if (状态列表.length === 0) return 普通;
    const 已同步 = 状态列表.filter((项) => 项.状态 === "已同步").length;
    const 有失败 = 状态列表.some((项) => 项.状态 === "失败");
    const 进行中 = 状态列表.some((项) => 项.状态 !== "已同步" && 项.状态 !== "失败");
    let 后缀 = "";
    if (有失败) 后缀 = 英文 ? " · retry pending" : " · 有失败";
    else if (进行中) 后缀 = 英文 ? " · syncing" : " · 同步中";
    return `${英文 ? "TapTap · Synced" : "TapTap · 已同步"} ${已同步}/${状态列表.length}${后缀}`;
  }

  private 已得(): number {
    return this.上下文.服务.成就.读取已解锁().length;
  }

  protected 读取文字快照(): readonly string[] {
    const 已解锁 = new Set(this.上下文.服务.成就.读取已解锁());
    return [
      `滚动:${this.滚动?.读取滚动位置() ?? 0}`,
      `列表模式:${this.滚动?.读取渲染模式()}`,
      `首项矩形:${JSON.stringify(this.滚动?.读取项矩形(0))}`,
      `解锁:${已解锁.size}`,
      `已领取:${this.上下文.服务.金币.读取().已领成就.length}`,
      ...成就定义.map((定义) => {
        const 状态 = 已解锁.has(定义.编号) ? "已解锁" : "未解锁";
        const 进度 = Math.min(this.上下文.服务.成就.读取进度(定义.编号), 定义.目标);
        return `${定义.名称}:${状态}:${进度}/${定义.目标}`;
      }),
      ...成就定义.map((定义) => `成就同步:${定义.编号}:${读取成就同步状态(定义.编号).状态}`),
    ];
  }
}

function 生成页面文字项(
  锚点: 文字项["锚点"],
  x: number,
  y: number,
  字号: number,
  颜色: number,
  字重: "常规" | "粗体",
  对齐: "左" | "中" | "右",
  文案: string,
  最大宽?: number,
): 文字项 {
  return {
    文案,
    样式: 派生霓虹文字样式("正文", { 字号, 颜色, 字重, 对齐 }),
    锚点,
    x,
    y,
    最大宽,
  };
}

function 移位(项: 文字项, 偏移: { x: number; y: number }): 文字项 {
  return { ...项, x: 项.x + 偏移.x, y: 项.y + 偏移.y };
}

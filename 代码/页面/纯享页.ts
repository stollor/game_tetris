/**
 * 纯享页：整页风景节点（所选主题的真实背景）+ 标题/副题 + 圆点 + 返回按钮。
 *
 * 游戏只有四套主题，纯享就是「整屏看主题背景」：左右滑动切主题、下滑或按钮返回。
 * 本页自带背景（遮挡背景层），所以从菜单和商店进入看到的是同一种画面。
 */

export type 纯享来源 = "菜单" | "商店";

export class 纯享页 extends 页面基类 {
  private 来源: 纯享来源 = "菜单";
  private 主题: 主题名 = 默认风景("");
  private 停留主题: readonly 主题名[] = [];
  private 动态 = true;
  private 沿用菜单背景 = true;
  private 场景背景秒 = 0;
  private 背景绘制秒 = 0;

  private 标题节点: 节点 | null = null;
  private 副题节点: 节点 | null = null;
  private 返回节点: 节点 | null = null;
  private 风景节点: 节点 | null = null;

  constructor(上下文: 页面上下文) {
    super(上下文, { 名称: "纯享", 开合: { 打开秒: 0.26, 关闭秒: 0.18 }, 节点树: { 绘制带数: 1 } });
  }

  /** 菜单入口保留正在显示的混搭背景，切景后才绘制自己的风景。 */
  读取窗口策略() {
    return {
      遮挡: this.上下文.参数.来源 === "商店",
      不透明: true,
      暂停下层: true,
      独占命中: true,
    };
  }

  进入(): void {
    const 参数 = this.上下文.参数;
    this.来源 = 参数.来源 === "商店" ? "商店" : "菜单";
    this.停留主题 = 风景浏览列表();
    const 设置 = this.上下文.服务.设置.读取();
    const 指定 = typeof 参数.风景 === "string" ? 参数.风景 : "";
    this.沿用菜单背景 = this.来源 === "菜单";
    const 候选 = 默认风景(指定 || 读取部位主题(设置, "静态背景"));
    this.主题 = this.停留主题.includes(候选) ? 候选 : (this.停留主题[0] ?? 候选);
    this.动态 = 参数.风景动态 ?? 读取背景动态(设置);
    this.场景背景秒 = 0;
    this.背景绘制秒 = 0;
    super.进入();
    const 根 = this.读取节点根();
    if (根) this.应用注册参数(根);
  }

  更新(秒: number): void {
    super.更新(秒);
    this.场景背景秒 += 秒;
  }

  /** 启动层背景调度会按画质档位调用：纯享页面自己画背景。 */
  读取背景动态(): boolean {
    return this.动态;
  }

  /** 背景调度到点：重画内容带（背景与浮层同一带）。 */
  刷新背景动态(): void {
    this.标记失效([0], "背景标识");
    this.背景绘制秒 = this.场景背景秒;
  }

  private get 纯享布局() {
    return 计算纯享布局(this.逻辑宽, this.逻辑高);
  }

  protected 构建节点树(页面: 节点): void {
    this.创建手势节点(页面);
    this.风景节点 = this.创建风景节点(页面);
    this.风景节点.设置可见(!this.沿用菜单背景);
    this.标题节点 = 创建文字节点(
      页面,
      { 名称: "纯享:标题", 项: this.标题项() },
      this.逻辑高,
      this.测量文字(),
    ).设置开合行为({ 类型: "显隐" }, { 类型: "缩放", 起始: 0.96 });
    this.副题节点 = 创建文字节点(
      页面,
      { 名称: "纯享:副题", 项: this.副题项() },
      this.逻辑高,
      this.测量文字(),
    ).设置开合行为({ 类型: "显隐" }, { 类型: "缩放", 起始: 0.96 });
    创建整页绘制节点(页面, "纯享:圆点", this.逻辑宽, this.逻辑高, (环境) => {
      在本地空间绘制(环境, () => this.绘制圆点(环境.图形));
    }).设置开合行为({ 类型: "显隐" });
    const 返回 = this.纯享布局.返回钮;
    this.返回节点 = 创建按钮节点(页面, "纯享:返回", 返回, this.逻辑高, {
      点击: () => this.返回(),
      绘制: (环境, 状态) => this.绘制返回按钮(环境, 状态.矩形, 状态.按下),
    }).设置开合行为({ 类型: "滑入", 方向: "下" });
  }

  /** 手势节点先加：整页滑动（左/右切景、下滑返回），按钮后加优先命中。 */
  private 创建手势节点(页面: 节点): void {
    创建注册节点(页面, {
      名称: "",
      坐标: { 位置X: 0, 位置Y: 0, 宽: this.逻辑宽, 高: this.逻辑高, 锚点X: 0, 锚点Y: 0 },
      组件: new 手势组件({
        滑动: (方向) => {
          if (方向 === "左") this.切风景(1);
          else if (方向 === "右") this.切风景(-1);
          else if (方向 === "下") this.返回();
        },
      }),
    });
  }

  /** 整屏风景节点：按主题名画该主题的真实背景（静止时只画静态帧）。 */
  private 创建风景节点(页面: 节点): 节点 {
    return 创建整页绘制节点(页面, "纯享:风景", this.逻辑宽, this.逻辑高, (环境) => {
      const 画笔 = 读取画笔(环境);
      if (!画笔) return;
      在本地空间绘制(环境, () => this.绘制风景(画笔));
    }).设置开合行为({ 类型: "显隐" });
  }

  /** 主题 / 语言 / 尺寸 / 风景变化：重算注册参数并标脏，不重建节点。 */
  protected 应用注册参数(_页面: 节点): void {
    更新文字节点(
      this.标题节点,
      { 名称: "纯享:标题", 项: this.标题项() },
      this.逻辑高,
      this.测量文字(),
    );
    更新文字节点(
      this.副题节点,
      { 名称: "纯享:副题", 项: this.副题项() },
      this.逻辑高,
      this.测量文字(),
    );
    更新按钮节点(this.返回节点, this.纯享布局.返回钮, this.逻辑高, {
      点击: () => this.返回(),
      绘制: (环境, 状态) => this.绘制返回按钮(环境, 状态.矩形, 状态.按下),
    });

    this.风景节点?.读取二维坐标()?.更新参数({ 宽: this.逻辑宽, 高: this.逻辑高 });
    this.风景节点?.设置可见(!this.沿用菜单背景);
  }

  调整尺寸(): void {
    super.调整尺寸();
    const 根 = this.读取节点根();
    if (根) this.应用注册参数(根);
  }

  private 切风景(方向: -1 | 1): void {
    this.沿用菜单背景 = false;
    this.主题 = 相邻风景(this.主题, 方向);
    const 根 = this.读取节点根();
    if (根) this.应用注册参数(根);
    this.刷新背景();
  }

  /** 风景换图：内容带整层重画。 */
  private 刷新背景(): void {
    this.标记失效([0], "背景标识");
  }

  // ---- 文字项与画法 ----

  private 测量文字() {
    return (文案: string, 样式: Parameters<页面上下文["资源"]["画笔"]["测量文字"]>[1]) =>
      this.上下文.资源.画笔.测量文字(文案, 样式);
  }

  private 标题项() {
    const 说明 = 风景说明(this.主题, this.上下文.服务.语言.读取());
    return 生成纯享文字项(this.纯享布局, { 标题: 说明.标题, 副题: 说明.副题 })[0]!;
  }

  private 副题项() {
    const 说明 = 风景说明(this.主题, this.上下文.服务.语言.读取());
    return 生成纯享文字项(this.纯享布局, { 标题: 说明.标题, 副题: 说明.副题 })[1]!;
  }

  /** 返回装置：传送装置 + 文字，画在按钮节点本地空间（左上角、y 向下）。 */
  private 绘制返回按钮(环境: 节点绘制环境, 矩形: { 宽: number; 高: number }, 按下: boolean): void {
    const 画笔 = 读取画笔(环境);
    if (!画笔) return;
    const 图形 = 环境.图形;
    const 区域 = { 中心X: 矩形.宽 / 2, 中心Y: 矩形.高 / 2, 宽: 矩形.宽, 高: 矩形.高 };
    const 文案 = this.上下文.服务.语言.读取().返回;
    绘制返回传送装置(图形, 区域, {
      时间秒: this.场景背景秒,
      下沉: 按下 ? 1 : 0,
      点亮: [],
      文案,
    });
    画笔.绘制文字({
      ...生成返回按键文字项(区域, 文案, 按下 ? 1 : 0),
      变换: 文字空间矩阵(环境, 矩形.高),
    });
  }

  private 绘制圆点(图形: 图形对象): void {
    const 当前 = Math.max(0, this.停留主题.indexOf(this.主题));
    绘制纯享圆点(图形, this.逻辑宽, this.逻辑高, this.停留主题.length, 当前);
  }

  /** 与商店使用相同背景配方和时间，不额外叠一层底色。 */
  private 绘制风景(画笔: 画笔): void {
    const 图形 = 画笔.图形;
    const 参数 = {
      宽: this.逻辑宽,
      高: this.逻辑高,
      主题: this.主题,
      按名称绘制: true,
    };
    绘制背景静底(图形, 参数);
    if (this.动态)
      绘制背景动态(图形, {
        ...参数,
        时间秒: this.上下文.读取背景时间?.() ?? this.背景绘制秒,
        亮度: 读取背景动态亮度(this.主题),
      });
  }

  protected 读取文字快照(): readonly string[] {
    return [
      "页面:纯享",
      `来源:${this.来源}`,
      `风景:${this.主题}`,
      `动态:${this.动态}`,
      `过渡:${this.上下文.过渡 ? "流转" : "无"}`,
    ];
  }
}

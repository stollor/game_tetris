/**
 * 纯享页：整页手势节点 + 风景绘制节点 + 标题/副题文字节点 + 圆点绘制节点 + 返回/动态按钮节点。
 *
 * 纯享只有一份实现：菜单页与商店页进入同一个纯享页，`参数.来源` 决定可切风景列表与是否带动态开关。
 * 背景由背景层（远景页 / 近景页）提供，本页不画风景；商店来源例外，风景画在本页的整页节点上。
 *
 * 节点首次进入构建、之后常驻；切风景 / 语言 / 尺寸变化只重算注册参数并标脏。
 * 跨页过渡仍由页面声明一块整屏「纯享」浮层（P4 改自动配对）。
 */

/** 纯享风景来源：菜单从已解锁风景里切，商店从旅行地点里切。 */
export type 纯享来源 = "菜单" | "商店";

export class 纯享页 extends 页面基类 {
  private 来源: 纯享来源 = "菜单";
  private 英文 = false;
  private 主题: 背景主题 = "极光原野";
  private 停留主题: readonly 背景主题[] = [];
  private 动态 = true;
  private 场景背景秒 = 0;
  private 背景绘制秒 = 0;

  private 标题节点: 节点 | null = null;
  private 副题节点: 节点 | null = null;
  private 返回节点: 节点 | null = null;
  private 动态节点: 节点 | null = null;
  private 风景节点: 节点 | null = null;

  constructor(上下文: 页面上下文) {
    super(上下文, { 名称: "纯享", 开合: { 打开秒: 0.3, 关闭秒: 0.25 }, 节点树: { 绘制带数: 1 } });
  }

  /** 商店来源要自带背景（商店挡住了背景层）；菜单来源用背景层那张，和菜单/模式选择一致。 */
  读取窗口策略() {
    return {
      遮挡: this.上下文.参数.来源 === "商店",
      不透明: true,
      暂停下层: true,
      独占命中: true,
    };
  }

  进入(): void {
    const 参数 = this.上下文.参数;
    this.来源 = 参数.来源 === "商店" ? "商店" : "菜单";
    this.英文 = this.上下文.服务.语言.是否英文();
    this.停留主题 = this.读取风景列表();
    const 指定 = 参数.风景 as 背景主题 | undefined;
    const 设置主题 = this.上下文.服务.设置.读取().背景主题;
    const 候选 = 指定 ?? (this.来源 === "商店" ? 设置主题 : 设置主题);
    this.主题 = this.停留主题.includes(候选) ? 候选 : (this.停留主题[0] ?? 候选);
    // 商店来源默认带动态开关（与重构前商店纯享态一致）；菜单来源跟随设置。
    this.动态 = this.来源 === "商店" ? true : 读取背景动态(this.上下文.服务.设置.读取());
    this.场景背景秒 = 0;
    super.进入();
  }

  更新(秒: number): void {
    super.更新(秒);
    this.场景背景秒 += 秒;
  }

  /** 启动层背景调度会按画质档位调用；只有商店来源的风景是本页画的。 */
  读取背景动态(): boolean {
    return this.来源 === "商店" && this.动态;
  }

  /** 背景调度到点：只重画本页内容（风景与浮层同一带）。 */
  刷新背景动态(): void {
    this.标记失效([0], "背景标识");
    this.背景绘制秒 = this.场景背景秒;
  }

  private 读取风景列表(): readonly 背景主题[] {
    if (this.来源 === "商店") return 地点皮肤表.map((项) => 项.名称 as 背景主题);
    return 已解锁风景列表();
  }

  private get 纯享布局() {
    return 计算纯享布局(this.逻辑宽, this.逻辑高);
  }

  protected 构建节点树(页面: 节点): void {
    this.创建手势节点(页面);
    this.风景节点 = this.创建风景节点(页面);
    this.标题节点 = 创建文字节点(
      页面,
      { 名称: "纯享:标题", 项: this.标题项() },
      this.逻辑高,
      this.测量文字(),
    ).设置开合行为({ 类型: "显隐" });
    this.副题节点 = 创建文字节点(
      页面,
      { 名称: "纯享:副题", 项: this.副题项() },
      this.逻辑高,
      this.测量文字(),
    ).设置开合行为({ 类型: "显隐" });
    // 圆点画在整页节点上（页面坐标），与旧的内容层绘制一致。
    创建整页绘制节点(页面, "纯享:圆点", this.逻辑宽, this.逻辑高, (环境) => {
      在本地空间绘制(环境, () => this.绘制圆点(环境.图形));
    }).设置开合行为({ 类型: "显隐" });
    const 返回 = this.纯享布局.返回钮;
    this.返回节点 = 创建按钮节点(页面, "纯享:返回", 返回, this.逻辑高, {
      点击: () => this.返回(),
      绘制: (环境, 状态) => this.绘制返回按钮(环境, 状态.矩形, 状态.按下),
    }).设置开合行为({ 类型: "滑入", 方向: "下" });
    if (this.来源 !== "商店") return;
    this.动态节点 = 创建按钮节点(页面, "纯享:动态", this.动态开关区域(), this.逻辑高, {
      点击: () => this.切换动态(),
      绘制: (环境) => this.绘制动态开关节点(环境),
    });
  }

  /** 手势节点先加：整页滑动（左/右切景、下滑返回），按钮后加优先命中。 */
  private 创建手势节点(页面: 节点): void {
    创建注册节点(页面, {
      名称: "",
      坐标: { 位置X: 0, 位置Y: 0, 宽: this.逻辑宽, 高: this.逻辑高, 锚点X: 0, 锚点Y: 0 },
      组件: new 手势组件({
        滑动: (方向) => {
          if (方向 === "左") this.切风景(1);
          else if (方向 === "右") this.切风景(-1);
          else if (方向 === "下") this.返回();
        },
      }),
    });
  }

  /** 商店来源的整屏风景节点：与背景层同一份画法，按地点名画、不被像素/立体后景改写。 */
  private 创建风景节点(页面: 节点): 节点 {
    const 节点 = 创建整页绘制节点(页面, "纯享:风景", this.逻辑宽, this.逻辑高, (环境) => {
      if (this.来源 !== "商店") return;
      const 画笔 = 读取画笔(环境);
      if (!画笔) return;
      在本地空间绘制(环境, () => this.绘制商店风景(画笔));
    });
    节点.设置可见(this.来源 === "商店");
    return 节点;
  }

  /** 主题 / 语言 / 尺寸 / 风景变化：重算注册参数并标脏，不重建节点。 */
  protected 应用注册参数(_页面: 节点): void {
    this.英文 = this.上下文.服务.语言.是否英文();
    this.风景节点?.设置可见(this.来源 === "商店");
    更新文字节点(
      this.标题节点,
      { 名称: "纯享:标题", 项: this.标题项() },
      this.逻辑高,
      this.测量文字(),
    );
    更新文字节点(
      this.副题节点,
      { 名称: "纯享:副题", 项: this.副题项() },
      this.逻辑高,
      this.测量文字(),
    );
    更新按钮节点(this.返回节点, this.纯享布局.返回钮, this.逻辑高, {
      点击: () => this.返回(),
      绘制: (环境, 状态) => this.绘制返回按钮(环境, 状态.矩形, 状态.按下),
    });
    if (this.动态节点) {
      更新按钮节点(this.动态节点, this.动态开关区域(), this.逻辑高, {
        点击: () => this.切换动态(),
        绘制: (环境) => this.绘制动态开关节点(环境),
      });
    }
  }

  调整尺寸(): void {
    super.调整尺寸();
    const 根 = this.读取节点根();
    if (根) this.应用注册参数(根);
  }

  private 切风景(方向: -1 | 1): void {
    if (this.来源 === "商店") {
      const 序号 = this.停留主题.indexOf(this.主题);
      const 下一个 = this.停留主题[(序号 + 方向 + this.停留主题.length) % this.停留主题.length];
      if (!下一个) return;
      this.主题 = 下一个;
    } else {
      this.主题 = 相邻已解锁风景(this.主题, 方向);
    }
    const 根 = this.读取节点根();
    if (根) this.应用注册参数(根);
    this.刷新背景();
  }

  private 切换动态(): void {
    this.动态 = !this.动态;
    const 根 = this.读取节点根();
    if (根) this.应用注册参数(根);
    this.刷新背景动态();
    this.刷新背景();
  }

  /** 风景换图/动态开关变化：内容带整层重画。 */
  private 刷新背景(): void {
    this.标记失效([0], "背景标识");
  }

  // ---- 文字项与画法 ----

  private 测量文字() {
    return (文案: string, 样式: Parameters<页面上下文["资源"]["画笔"]["测量文字"]>[1]) =>
      this.上下文.资源.画笔.测量文字(文案, 样式);
  }

  private 标题项() {
    return 生成纯享文字项(this.纯享布局, this.风景说明())[0]!;
  }

  private 副题项() {
    return 生成纯享文字项(this.纯享布局, this.风景说明())[1]!;
  }

  private 风景说明() {
    const 说明 = 风景说明(this.主题);
    if (this.来源 !== "商店") return 说明;
    const 地点 = 地点皮肤表.find((项) => 项.名称 === this.主题);
    if (!地点) return 说明;
    return { 标题: this.英文 ? 地点.英文 : 地点.名称, 副题: 地点.副题 };
  }

  private 动态开关区域() {
    return { 中心X: this.逻辑宽 - 108 + 46, 中心Y: 16 + 16, 宽: 92, 高: 32 };
  }

  /** 返回装置：传送装置 + 文字，画在按钮节点本地空间（左上角、y 向下）。 */
  private 绘制返回按钮(环境: 节点绘制环境, 矩形: { 宽: number; 高: number }, 按下: boolean): void {
    const 画笔 = 读取画笔(环境);
    if (!画笔) return;
    const 图形 = 环境.图形;
    const 区域 = { 中心X: 矩形.宽 / 2, 中心Y: 矩形.高 / 2, 宽: 矩形.宽, 高: 矩形.高 };
    const 文案 = this.英文 ? "Back" : "返回";
    绘制返回传送装置(图形, 区域, {
      时间秒: this.场景背景秒,
      下沉: 按下 ? 1 : 0,
      点亮: [],
      文案,
    });
    画笔.绘制文字({
      ...生成返回按键文字项(区域, 文案, 按下 ? 1 : 0),
      变换: 文字空间矩阵(环境, 矩形.高),
    });
  }

  /** 动态开关：收藏按钮底板 + 文字。 */
  private 绘制动态开关节点(环境: 节点绘制环境): void {
    const 画笔 = 读取画笔(环境);
    if (!画笔) return;
    const 矩形 = 环境.节点.读取本地矩形();
    if (!矩形) return;
    const 图形 = 环境.图形;
    绘制收藏按钮底板(图形, 矩形.宽 / 2, 矩形.高 / 2, 矩形.宽, 矩形.高, {}, { 已选: this.动态 });
    画笔.绘制文字({
      ...生成收藏按钮文字项(
        矩形.宽 / 2,
        矩形.高 / 2,
        `${this.英文 ? "Motion" : "动态"} ${this.动态 ? "开" : "关"}`,
        {},
        12,
      ),
      变换: 文字空间矩阵(环境, 矩形.高),
    });
  }

  private 绘制圆点(图形: 图形对象): void {
    const 当前 = Math.max(0, this.停留主题.indexOf(this.主题));
    绘制纯享圆点(图形, this.逻辑宽, this.逻辑高, this.停留主题.length, 当前);
  }

  /** 商店来源的整屏风景：与背景层同一份画法，按地点名画、不被像素/立体后景改写。 */
  private 绘制商店风景(画笔: 画笔): void {
    const 图形 = 画笔.图形;
    const 参数 = {
      宽: this.逻辑宽,
      高: this.逻辑高,
      主题: this.主题,
      静态主体: !this.动态,
      按名称绘制: true,
    };
    绘制背景静底(图形, 参数);
    if (this.动态)
      绘制背景动态(图形, {
        ...参数,
        时间秒: this.背景绘制秒,
        亮度: 读取背景动态亮度(this.主题),
      });
    if (读取背景外观(this.上下文.服务.设置.读取()).文字基调 === "浅底")
      图形.fillStyle(this.上下文.读取配色().底色, 0.34).fillRect(0, 0, this.逻辑宽, this.逻辑高);
  }

  protected 读取文字快照(): readonly string[] {
    return [
      "页面:纯享",
      `来源:${this.来源}`,
      `风景:${this.主题}`,
      `动态:${this.动态}`,
      `过渡:${this.上下文.过渡 ? "流转" : "无"}`,
    ];
  }
}

/**
 * 纯享页：全屏风景 + 胶囊返回 + 风景标题/副题 + 底部圆点 + 左右切景/下滑返回。
 *
 * 纯享只有一份实现：菜单页与商店页进入同一个纯享页，`参数.来源` 决定可切风景列表与是否带动态开关。
 *
 * 背景由背景层（远景页 / 近景页）提供，本页不画风景：菜单 / 模式选择 / 纯享三页的背景完全一致。
 * 商店来源例外：商店是「按地点风景试穿」且自带背景会挡住背景层，所以从商店进来的纯享
 * 沿用商店地点风景（`读取窗口策略` 里按来源声明遮挡）。
 *
 * 跨页过渡：只声明整屏一块「纯享」浮层（胶囊返回 / 标题 / 副题 / 圆点），整体向上 160px 滑入。
 */

/** 纯享风景来源：菜单从已解锁风景里切，商店从旅行地点里切。 */
export type 纯享来源 = "菜单" | "商店";

export class 纯享页 extends 页面基类 {
  private 来源: 纯享来源 = "菜单";
  private 英文 = false;
  private 主题: 背景主题 = "极光原野";
  private 停留主题: readonly 背景主题[] = [];
  private 动态 = true;
  private 场景背景秒 = 0;
  private 背景绘制秒 = 0;

  constructor(上下文: 页面上下文) {
    super(上下文, { 名称: "纯享" });
  }

  /** 商店来源要自带背景（商店挡住了背景层）；菜单来源用背景层那张，和菜单/模式选择一致。 */
  读取窗口策略() {
    return {
      遮挡: this.上下文.参数.来源 === "商店",
      不透明: true,
      暂停下层: true,
      独占命中: true,
    };
  }

  进入(): void {
    const 参数 = this.上下文.参数;
    this.来源 = 参数.来源 === "商店" ? "商店" : "菜单";
    this.英文 = this.上下文.服务.语言.是否英文();
    this.停留主题 = this.读取风景列表();
    const 指定 = 参数.风景 as 背景主题 | undefined;
    const 设置主题 = this.上下文.服务.设置.读取().背景主题;
    const 候选 = 指定 ?? (this.来源 === "商店" ? 设置主题 : 设置主题);
    this.主题 = this.停留主题.includes(候选) ? 候选 : (this.停留主题[0] ?? 候选);
    // 商店来源默认带动态开关（与重构前商店纯享态一致）；菜单来源跟随设置。
    this.动态 = this.来源 === "商店" ? true : 读取背景动态(this.上下文.服务.设置.读取());
    this.场景背景秒 = 0;
    // 自带背景的页面自己画风景，不登记背景层页面的清理。
    super.进入();
  }

  更新(秒: number): void {
    super.更新(秒);
    this.场景背景秒 += 秒;
  }

  /** 启动层背景调度会按画质档位调用；只有商店来源的风景是本页画的。 */
  读取背景动态(): boolean {
    return this.来源 === "商店" && this.动态;
  }

  /** 背景调度到点：只重画内容层（风景与标题都在这一层）。 */
  刷新背景动态(): void {
    this.标记失效([0], "背景标识");
    this.背景绘制秒 = this.场景背景秒;
  }

  private 读取风景列表(): readonly 背景主题[] {
    if (this.来源 === "商店") return 地点皮肤表.map((项) => 项.名称 as 背景主题);
    return 已解锁风景列表();
  }

  private get 纯享布局() {
    return 计算纯享布局(this.逻辑宽, this.逻辑高);
  }

  protected 构建(): void {
    const 纯享 = this.纯享布局;
    this.创建滑动热区({
      矩形: { 左: 0, 上: 0, 宽: this.逻辑宽, 高: this.逻辑高 },
      滑动: (方向) => {
        if (方向 === "左") this.切风景(1);
        else if (方向 === "右") this.切风景(-1);
        else if (方向 === "下") this.返回();
      },
    });
    this.创建按钮("纯享:返回", {
      绘制底板: () => {},
      移出取消: true,
      矩形: {
        左: 纯享.返回钮.中心X - 纯享.返回钮.宽 / 2,
        上: 纯享.返回钮.中心Y - 纯享.返回钮.高 / 2,
        宽: 纯享.返回钮.宽,
        高: 纯享.返回钮.高,
      },
      点击: () => this.返回(),
    });
    if (this.来源 !== "商店") return;
    this.创建按钮("纯享:动态", {
      绘制底板: () => {},
      移出取消: true,
      矩形: { 左: this.逻辑宽 - 108, 上: 16, 宽: 92, 高: 32 },
      点击: () => {
        this.动态 = !this.动态;
        this.重建();
        this.刷新背景动态();
        this.刷新背景();
      },
    });
  }

  private 切风景(方向: -1 | 1): void {
    if (this.来源 === "商店") {
      const 序号 = this.停留主题.indexOf(this.主题);
      const 下一个 = this.停留主题[(序号 + 方向 + this.停留主题.length) % this.停留主题.length];
      if (!下一个) return;
      this.主题 = 下一个;
    } else {
      this.主题 = 相邻已解锁风景(this.主题, 方向);
    }
    this.重建();
    this.刷新背景();
  }

  /** 风景换图/动态开关变化：内容层整层重画。 */
  private 刷新背景(): void {
    this.标记失效([0], "背景标识");
  }

  private 风景说明() {
    const 说明 = 风景说明(this.主题);
    if (this.来源 !== "商店") return 说明;
    const 地点 = 地点皮肤表.find((项) => 项.名称 === this.主题);
    if (!地点) return 说明;
    return { 标题: this.英文 ? 地点.英文 : 地点.名称, 副题: 地点.副题 };
  }

  protected 绘制内容(): void {
    const 画笔 = this.上下文.资源.画笔;
    // 只有商店来源自带风景；菜单来源的背景由背景层（远景/近景页）画。
    if (this.来源 === "商店") this.绘制商店风景(画笔);
    this.绘制浮层内容(画笔);
  }

  /** 商店来源的整屏风景：与背景层同一份画法，按地点名画、不被像素/立体后景改写。 */
  private 绘制商店风景(画笔: 画笔): void {
    风景流转块(this.上下文, {
      主题: this.主题,
      动态: this.动态,
      时间秒: this.背景绘制秒,
      按名称绘制: true,
      压暗: 读取背景外观(this.上下文.服务.设置.读取()).文字基调 === "浅底",
    }).绘制(画笔);
  }

  /** 风景之上的内容：胶囊返回 + 风景标题/副题 + 底部圆点（商店来源再加动态开关）。 */
  private 绘制浮层内容(画笔: 画笔): void {
    const 图形 = 画笔.图形;
    const 纯享 = this.纯享布局;
    for (const 项 of 生成纯享文字项(纯享, this.风景说明())) 画笔.绘制文字(项);
    const 返回 = 纯享.返回钮;
    const 按下 = false;
    const 文案 = this.英文 ? "Back" : "返回";
    绘制返回传送装置(图形, 返回, { 时间秒: this.场景背景秒, 下沉: 按下 ? 1 : 0, 点亮: [], 文案 });
    画笔.绘制文字(生成返回按键文字项(返回, 文案, 按下 ? 1 : 0));
    const 当前 = Math.max(0, this.停留主题.indexOf(this.主题));
    绘制纯享圆点(图形, this.逻辑宽, this.逻辑高, this.停留主题.length, 当前);
    if (this.来源 === "商店") this.绘制动态开关(图形, 画笔);
  }

  /**
   * 跨页流转块：整屏一块「纯享」浮层（只有胶囊返回 / 标题副题 / 圆点），向上 160px 滑入。
   * 背景不参与流转——三页共用背景层那一张，过渡中本来就不变。
   */
  读取流转块(): readonly 可绘制流转块[] {
    const 宽 = this.逻辑宽;
    const 高 = this.逻辑高;
    return [
      {
        身份: "纯享",
        矩形: { 左: 0, 上: 0, 宽, 高 },
        位移: { x: 0, y: 160 },
        绘制: (笔: 画笔) => this.绘制浮层内容(笔),
      },
    ];
  }

  protected 绘制过渡(_环境: 绘制环境): void {
    绘制流转块列表(this.上下文, this.页面名称, this.读取流转块());
  }

  private 绘制动态开关(图形: 图形对象, 画笔: 画笔): void {
    const 矩形 = { 左: this.逻辑宽 - 108, 上: 16, 宽: 92, 高: 32 };
    绘制收藏按钮底板(
      图形,
      矩形.左 + 矩形.宽 / 2,
      矩形.上 + 矩形.高 / 2,
      矩形.宽,
      矩形.高,
      {},
      { 已选: this.动态 },
    );
    画笔.绘制文字(
      生成收藏按钮文字项(
        矩形.左 + 矩形.宽 / 2,
        矩形.上 + 矩形.高 / 2,
        `${this.英文 ? "Motion" : "动态"} ${this.动态 ? "开" : "关"}`,
        {},
        12,
      ),
    );
  }

  protected 读取文字快照(): readonly string[] {
    return [
      "页面:纯享",
      `来源:${this.来源}`,
      `风景:${this.主题}`,
      `动态:${this.动态}`,
      `过渡:${this.上下文.过渡 ? "流转" : "无"}`,
    ];
  }
}

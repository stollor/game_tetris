/**
 * 菜单页：页面节点 + 标题 / 开始游戏 / 三个入口角钮 / 全屏手势，全部是节点或组件。
 *
 * - 标题 = 文字节点（文字组件，居中）；
 * - 角钮和开始游戏 = 按钮节点（按钮组件 + 注册处的预制体画法）；
 * - 空白处轻点 / 上滑 = 全屏手势节点（先添加，命中优先级低于按钮节点）。
 *
 * 首次进入构建节点树，之后常驻；主题 / 语言 / 尺寸变化只重算注册参数并标脏，不重建节点。
 * 页面开合由节点行为配置，共享标题通过导航显式配对。
 */

interface 按钮区域布局 {
  中心X: number;
  中心Y: number;
  宽: number;
  高: number;
}

export class 菜单页 extends 页面基类 {
  private 英文 = false;
  private 标题节点: 节点 | null = null;
  private 标题组件: 文字组件 | null = null;
  private 开始节点: 节点 | null = null;
  private 开始组件: 按钮组件 | null = null;
  private 角钮节点: 节点[] = [];
  private 角钮组件: 按钮组件[] = [];

  constructor(上下文: 页面上下文) {
    super(上下文, {
      名称: "菜单",
      开合: { 打开秒: 0.28, 关闭秒: 0.25 },
      节点树: { 绘制带数: 1 },
    });
  }

  进入(): void {
    super.进入();
    this.恢复音频();
  }

  恢复(): void {
    super.恢复();
    this.恢复音频();
  }

  /** 从商店/子页面回来时恢复菜单音乐；已在播放就不重播。 */
  private 恢复音频(): void {
    const 音频 = this.上下文.服务.音频;
    音频.设置暂停(false);
    音频.播放音乐("再消一行.菜单");
  }

  private get 布局(): 菜单布局 {
    return 计算菜单布局(this.逻辑宽, this.逻辑高);
  }

  protected 构建节点树(页面: 节点): void {
    // 手势节点先加：节点命中按兄弟逆序，后加的按钮优先命中。
    创建注册节点(页面, {
      名称: "",
      坐标: {
        位置X: 0,
        位置Y: 0,
        宽: this.逻辑宽,
        高: this.逻辑高,
        锚点X: 0,
        锚点Y: 0,
      },
      组件: new 手势组件({
        点击: () => this.进入纯享(),
        滑动: (方向) => {
          if (方向 === "上") this.进入纯享();
        },
      }),
    });
    this.标题节点 = this.创建标题节点(页面);
    const 布局 = this.布局;
    // 角钮顺序与界面快照一致：设置 / 成就 / 商店 / 开始游戏。
    布局.角钮.项.forEach((项, 索引) => {
      const 中心Y = 布局.角钮.中心Y[索引] ?? 0;
      const 组件 = new 按钮组件();
      const 节点 = 创建注册节点(页面, {
        名称: 项.文案.中文,
        坐标: {
          位置X: 布局.角钮.中心X,
          位置Y: this.逻辑高 - 中心Y,
          宽: 布局.角钮.宽,
          高: 布局.角钮.高,
        },
        组件,
      });
      节点.设置开合行为({ 类型: "滑入", 方向: "左" });
      this.角钮节点.push(节点);
      this.角钮组件.push(组件);
    });
    this.开始组件 = new 按钮组件();
    this.开始节点 = 创建注册节点(页面, {
      名称: "开始游戏",
      坐标: {
        位置X: 布局.开始钮.中心X,
        位置Y: this.逻辑高 - 布局.开始钮.中心Y,
        宽: 布局.开始钮.宽,
        高: 布局.开始钮.高,
      },
      组件: this.开始组件,
    }).设置开合行为({ 类型: "滑入", 方向: "下" });
    this.应用注册参数(页面);
  }

  /** 主题 / 语言 / 尺寸变化：重算布局与注册参数，只标脏，不重建节点。 */
  protected 应用注册参数(_页面: 节点): void {
    this.英文 = this.上下文.服务.语言.是否英文();
    const 布局 = this.布局;
    if (this.标题节点 && this.标题组件) {
      const 项 = this.标题项();
      this.标题组件.应用参数({ 文案: 项.文案, 样式: 项.样式, 对齐: "中", 垂直: "中" });
      this.标题节点.读取二维坐标()?.更新参数(this.文字节点坐标(项));
    }
    const 角钮动作: Record<string, () => void> = {
      设置: () => this.上下文.导航.进入("设置"),
      成就: () => this.上下文.导航.进入("成就", {}, { 关闭秒: 0 }),
      商店: () => this.上下文.导航.进入("商店", {}, { 关闭秒: 0 }),
    };
    布局.角钮.项.forEach((项, 索引) => {
      const 中心Y = 布局.角钮.中心Y[索引] ?? 0;
      const 文案 = this.英文 ? 项.文案.英文 : 项.文案.中文;
      const 组件 = this.角钮组件[索引];
      if (!组件) return;
      组件.应用参数({
        点击: 角钮动作[项.文案.中文],
        绘制: (环境, 状态) =>
          this.绘制按钮节点(环境, 状态, 文案, {
            变体: "次要",
            字号: 12,
            图标: 项.图标,
            图标尺寸: 18,
            图文方向: "竖排",
          }),
      });
      this.角钮节点[索引]?.读取二维坐标()?.更新参数({
        位置X: 布局.角钮.中心X,
        位置Y: this.逻辑高 - 中心Y,
        宽: 布局.角钮.宽,
        高: 布局.角钮.高,
      });
    });
    if (this.开始组件 && this.开始节点) {
      this.开始组件.应用参数({
        点击: () =>
          this.上下文.导航.进入("模式选择", {}, { 流转: [{ 从: "游戏标题", 到: "游戏标题" }] }),
        绘制: (环境, 状态) =>
          this.绘制按钮节点(环境, 状态, this.英文 ? 布局.开始钮.文案.英文 : 布局.开始钮.文案.中文, {
            变体: "主要",
            字号: 16,
            面板透明度: 0.78,
            强调色: 读取霓虹调色板().强调色,
          }),
      });
      this.开始节点.读取二维坐标()?.更新参数({
        位置X: 布局.开始钮.中心X,
        位置Y: this.逻辑高 - 布局.开始钮.中心Y,
        宽: 布局.开始钮.宽,
        高: 布局.开始钮.高,
      });
    }
  }

  调整尺寸(): void {
    super.调整尺寸();
    const 根 = this.读取节点根();
    if (根) this.应用注册参数(根);
  }

  private 进入纯享(): void {
    this.上下文.导航.进入("纯享", { 来源: "菜单" }, { 关闭秒: 0 });
  }

  // ---- 节点注册处的预制体画法 ----

  /** 按钮节点的画法：坐标是节点矩形左上角、y 向下（按钮组件已切好空间）。 */
  private 绘制按钮节点(
    环境: 节点绘制环境,
    状态: 按钮绘制状态,
    文案: string,
    选项: 常规按钮文字选项 & 常规按钮状态,
  ): void {
    const 画笔 = 读取画笔(环境);
    if (!画笔) return;
    const 矩形 = 状态.矩形;
    const 区域: 按钮区域布局 = {
      中心X: 矩形.宽 / 2,
      中心Y: 矩形.高 / 2,
      宽: 矩形.宽,
      高: 矩形.高,
    };
    // 按压进度当缩放：1 → 0.94，与旧的常规按钮按压动画视觉一致（静止帧恒为 1）。
    const 缩放 = 1 - 0.06 * 状态.按压进度;
    this.绘制按钮图形(
      环境.图形,
      画笔,
      区域,
      文案,
      { ...选项, 按下: 状态.按下 },
      { x: 缩放, y: 缩放 },
      文字空间矩阵(环境, 矩形.高),
    );
  }

  /** 一块共享配方按钮：底板 + 可选图标 + 文字项（文字色按底色对比自动取）。 */
  private 绘制按钮图形(
    图形: 图形对象,
    画笔: 画笔,
    区域: 按钮区域布局,
    文案: string,
    选项: 常规按钮文字选项 & 常规按钮状态,
    缩放: { x: number; y: number },
    文字变换?: ReturnType<typeof 文字空间矩阵>,
  ): void {
    const 标签尺寸 = 画笔.测量文字(文案, 读取常规按钮文字样式(选项));
    const 内容 = 生成常规按钮内容(区域.中心X, 区域.中心Y, 文案, 选项, 标签尺寸);
    图形.save();
    图形.translateCanvas(区域.中心X, 区域.中心Y);
    图形.scaleCanvas(缩放.x, 缩放.y);
    图形.translateCanvas(-区域.中心X, -区域.中心Y);
    绘制常规按钮(图形, 区域.中心X, 区域.中心Y, 区域.宽, 区域.高, 选项);
    if (内容.图标) 绘制常规按钮图标(图形, 内容.图标);
    图形.restore();
    if (内容.文字项) {
      const x = 区域.中心X + (内容.文字项.x - 区域.中心X) * 缩放.x;
      const y = 区域.中心Y + (内容.文字项.y - 区域.中心Y) * 缩放.y;
      画笔.绘制文字({
        ...内容.文字项,
        x,
        y,
        缩放X: 缩放.x,
        缩放Y: 缩放.y,
        ...(文字变换 ? { 变换: 文字变换 } : {}),
      });
    }
  }

  // ---- 标题节点 ----

  private 创建标题节点(页面: 节点): 节点 {
    const 标题项 = this.标题项();
    this.标题组件 = new 文字组件();
    return 创建注册节点(页面, {
      名称: "游戏标题",
      坐标: this.文字节点坐标(标题项),
      组件: this.标题组件,
    });
  }

  private 标题项(): 文字项 {
    return 生成菜单文字项(this.布局, this.文字数据())[0]!;
  }

  private 文字节点坐标(项: 文字项): { 位置X: number; 位置Y: number; 宽: number; 高: number } {
    const 尺寸 = this.上下文.资源.画笔.测量文字(项.文案, 项.样式);
    return { 位置X: 项.x, 位置Y: this.逻辑高 - 项.y, 宽: 尺寸.宽, 高: 尺寸.高 };
  }

  private 文字数据() {
    return {
      英文: this.英文,
      游戏名称: this.上下文.服务.语言.读取().游戏名称,
    };
  }

  // ---- 界面快照 ----

  protected 读取文字快照(): readonly string[] {
    return [
      "页面:菜单",
      `过渡:${this.上下文.过渡 ? "流转" : "无"}`,
      `标题:${this.文字数据().游戏名称}`,
      `金币:${this.上下文.服务.金币.读取().金币}`,
    ];
  }
}

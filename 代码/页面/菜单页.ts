/**
 * 菜单页：页面标题 + 开始游戏 + 左侧三个入口角钮（设置/成就/商店）。
 * 角钮是本页自己的控件，不是层；背景在背景层、金币在货币层、提示在提示层。
 * 空白处轻点或上滑进入纯享页，返回键不做事（根页）。
 *
 * 跨页过渡：本页声明自己的 UI 元素为流转块（游戏标题、三个角钮、开始游戏），
 * 进模式选择时标题连续变形、角钮向左滑出、开始游戏向下滑出。
 * 背景不参与流转：它由背景层提供，三页共用同一张。
 */

interface 按钮区域布局 {
  中心X: number;
  中心Y: number;
  宽: number;
  高: number;
}

function 全屏区域(宽: number, 高: number): { 左: number; 上: number; 宽: number; 高: number } {
  return { 左: 0, 上: 0, 宽, 高 };
}

export class 菜单页 extends 页面基类 {
  private 英文 = false;
  /** 只由按钮的按下/松开/取消写入，供配方画按下态，不另做命中。 */
  private readonly 按下中 = new Set<string>();
  private readonly 按钮动效 = new Map<
    string,
    { 按下: boolean; 毫秒: number; 起始X: number; 起始Y: number; x: number; y: number }
  >();
  constructor(上下文: 页面上下文) {
    super(上下文, { 名称: "菜单" });
  }

  进入(): void {
    super.进入();
    this.恢复音频();
  }

  恢复(): void {
    super.恢复();
    this.恢复音频();
  }

  /** 从商店/子页面回来时恢复菜单音乐与氛围；已在播放就不重播。 */
  private 恢复音频(): void {
    const 音频 = this.上下文.服务.音频;
    音频.设置暂停(false);
    音频.播放音乐("再消一行.菜单");
    音频.播放氛围(this.上下文.服务.设置.读取().背景主题);
  }

  private get 布局(): 菜单布局 {
    return 计算菜单布局(this.逻辑宽, this.逻辑高);
  }

  更新(秒: number): void {
    super.更新(秒);
    for (const [名称, 状态] of this.按钮动效) {
      状态.毫秒 += 秒 * 1000;
      const 缩放 = 计算常规按钮按压(状态.按下, 状态.毫秒, 状态.起始X, 状态.起始Y);
      状态.x = 缩放.x;
      状态.y = 缩放.y;
      if (!缩放.完成) this.请求重绘();
      else if (!状态.按下) this.按钮动效.delete(名称);
    }
  }

  protected 构建(): void {
    this.英文 = this.上下文.服务.语言.是否英文();
    const 布局 = this.布局;
    const 角钮动作: Record<string, () => void> = {
      设置: () => this.上下文.导航.进入("设置"),
      成就: () => this.上下文.导航.进入("成就"),
      商店: () => this.上下文.导航.进入("商店"),
    };
    // 纯享入口手势层先注册：控件层后注册者优先命中，按钮热区在其后注册才能压住它。
    this.创建滑动热区({
      矩形: 全屏区域(this.逻辑宽, this.逻辑高),
      点击: () => this.进入纯享(),
      滑动: (方向) => {
        if (方向 === "上") this.进入纯享();
      },
    });
    布局.角钮.项.forEach((项, 索引) => {
      const 点击 = 角钮动作[项.文案.中文];
      this.创建按钮(项.文案.中文, {
        绘制底板: () => {},
        移出取消: true,
        矩形: 按钮流转矩形({
          中心X: 布局.角钮.中心X,
          中心Y: 布局.角钮.中心Y[索引] ?? 0,
          宽: 布局.角钮.宽,
          高: 布局.角钮.高,
        }),
        点击: 点击 ?? (() => undefined),
        按下: () => this.按下刷新(项.文案.中文, true),
        松开: () => this.按下刷新(项.文案.中文, false),
        取消: () => this.按下刷新(项.文案.中文, false),
      });
    });
    this.创建按钮("开始游戏", {
      绘制底板: () => {},
      移出取消: true,
      矩形: 按钮流转矩形(布局.开始钮),
      点击: () => this.上下文.导航.进入("模式选择"),
      按下: () => this.按下刷新("开始游戏", true),
      松开: () => this.按下刷新("开始游戏", false),
      取消: () => this.按下刷新("开始游戏", false),
    });
  }

  private 按下刷新(名称: string, 按下: boolean): void {
    const 当前 = this.按钮动效.get(名称);
    this.按钮动效.set(名称, {
      按下,
      毫秒: 0,
      起始X: 当前?.x ?? 1,
      起始Y: 当前?.y ?? 1,
      x: 当前?.x ?? 1,
      y: 当前?.y ?? 1,
    });
    if (按下) this.按下中.add(名称);
    else this.按下中.delete(名称);
    this.请求重绘();
  }

  private 进入纯享(): void {
    this.上下文.导航.进入("纯享", { 来源: "菜单" });
  }

  /** 正常帧：标题 + 三个角钮 + 开始游戏（背景在背景层，不在这里画）。 */
  protected 绘制内容(): void {
    const 画笔 = this.上下文.资源.画笔;
    const 布局 = this.布局;
    for (const 项 of 生成菜单文字项(布局, this.文字数据())) 画笔.绘制文字(项);
    this.绘制角钮(画笔, 布局);
    this.绘制开始钮(画笔, 布局);
  }

  private 绘制角钮(画笔: 画笔, 布局: 菜单布局): void {
    for (const [索引, 项] of 布局.角钮.项.entries()) {
      const 中心Y = 布局.角钮.中心Y[索引];
      if (中心Y === undefined) continue;
      this.绘制按钮(
        画笔.图形,
        画笔,
        { 中心X: 布局.角钮.中心X, 中心Y, 宽: 布局.角钮.宽, 高: 布局.角钮.高 },
        this.英文 ? 项.文案.英文 : 项.文案.中文,
        {
          变体: "次要",
          字号: 12,
          图标: 项.图标,
          图标尺寸: 18,
          图文方向: "竖排",
          按下: this.按下中.has(项.文案.中文),
          名称: 项.文案.中文,
        },
      );
    }
  }

  private 绘制开始钮(画笔: 画笔, 布局: 菜单布局): void {
    const 开始 = 布局.开始钮;
    this.绘制按钮(画笔.图形, 画笔, 开始, this.英文 ? 开始.文案.英文 : 开始.文案.中文, {
      变体: "主要",
      字号: 16,
      面板透明度: 0.78,
      强调色: 读取霓虹调色板().强调色,
      按下: this.按下中.has("开始游戏"),
      名称: "开始游戏",
    });
  }

  /**
   * 跨页流转块：本页的 UI 元素（背景不在流转里，它由背景层常驻）。
   * 身份与位移照搬 `视效/过渡/主界面流转.ts`：游戏标题与模式选择共用身份，
   * 角钮向左滑出，开始游戏向下滑出。
   */
  读取流转块(): readonly 可绘制流转块[] {
    const 布局 = this.布局;
    const 块: 可绘制流转块[] = [];
    for (const 项 of 生成菜单文字项(布局, this.文字数据())) {
      块.push({
        身份: "游戏标题",
        矩形: 文字流转矩形(this.上下文, 项),
        位移: { x: 0, y: -this.逻辑高 / 2 },
        绘制: (笔: 画笔) => 笔.绘制文字(项),
      });
    }
    布局.角钮.项.forEach((项, 索引) => {
      const 中心Y = 布局.角钮.中心Y[索引];
      if (中心Y === undefined) return;
      块.push({
        身份: `角钮:${项.文案.中文}`,
        矩形: 按钮流转矩形({
          中心X: 布局.角钮.中心X,
          中心Y,
          宽: 布局.角钮.宽,
          高: 布局.角钮.高,
        }),
        位移: { x: -120, y: 0 },
        绘制: (笔: 画笔) =>
          this.绘制按钮(
            笔.图形,
            笔,
            { 中心X: 布局.角钮.中心X, 中心Y, 宽: 布局.角钮.宽, 高: 布局.角钮.高 },
            this.英文 ? 项.文案.英文 : 项.文案.中文,
            {
              变体: "次要",
              字号: 12,
              图标: 项.图标,
              图标尺寸: 18,
              图文方向: "竖排",
              按下: this.按下中.has(项.文案.中文),
              名称: 项.文案.中文,
            },
          ),
      });
    });
    块.push({
      身份: "开始游戏",
      矩形: 按钮流转矩形(布局.开始钮),
      位移: { x: 0, y: this.逻辑高 - 布局.开始钮.中心Y + 80 },
      绘制: (笔: 画笔) => this.绘制开始钮(笔, 布局),
    });
    return 块;
  }

  protected 绘制过渡(_环境: 绘制环境): void {
    绘制流转块列表(this.上下文, this.页面名称, this.读取流转块());
  }

  private 文字数据() {
    return {
      英文: this.英文,
      游戏名称: this.上下文.服务.语言.读取().游戏名称,
    };
  }

  /** 一块共享配方按钮：底板 + 可选图标 + 文字项（文字色按底色对比自动取）。 */
  private 绘制按钮(
    图形: 图形对象,
    画笔: 画笔,
    区域: 按钮区域布局,
    文案: string,
    选项: 常规按钮文字选项 & 常规按钮状态 & { 名称?: string },
  ): void {
    const 标签尺寸 = 画笔.测量文字(文案, 读取常规按钮文字样式(选项));
    const 内容 = 生成常规按钮内容(区域.中心X, 区域.中心Y, 文案, 选项, 标签尺寸);
    const 缩放 = 选项.名称 ? this.按钮动效.get(选项.名称) : undefined;
    图形.save();
    图形.translateCanvas(区域.中心X, 区域.中心Y);
    图形.scaleCanvas(缩放?.x ?? 1, 缩放?.y ?? 1);
    图形.translateCanvas(-区域.中心X, -区域.中心Y);
    绘制常规按钮(图形, 区域.中心X, 区域.中心Y, 区域.宽, 区域.高, 选项);
    if (内容.图标) 绘制常规按钮图标(图形, 内容.图标);
    图形.restore();
    if (内容.文字项)
      画笔.绘制文字({
        ...内容.文字项,
        x: 区域.中心X + (内容.文字项.x - 区域.中心X) * (缩放?.x ?? 1),
        y: 区域.中心Y + (内容.文字项.y - 区域.中心Y) * (缩放?.y ?? 1),
        缩放X: 缩放?.x,
        缩放Y: 缩放?.y,
      });
  }

  protected 读取文字快照(): readonly string[] {
    return [
      "页面:菜单",
      `过渡:${this.上下文.过渡 ? "流转" : "无"}`,
      `标题:${this.文字数据().游戏名称}`,
      `金币:${this.上下文.服务.金币.读取().金币}`,
    ];
  }
}

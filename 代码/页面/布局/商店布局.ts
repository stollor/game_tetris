import type { 矩形 } from "../../../.gamemaker/依赖/框架/界面/绘制/协议";
import { 计算金币条 } from "../../../资源/预制体/基础/条与数值/金币条配方";

/** 与旅行商店原布局一致，两种渲染后端共享全部陈列几何。 */
export function 计算商店布局(宽: number, 高: number) {
  const 扁 = 高 < 500;
  const 矮 = 高 < 640;
  const 卡高 = 扁 ? 34 : 矮 ? 40 : 48;
  const 买高 = 扁 ? 32 : 矮 ? 38 : 44;
  const 地点高 = 扁 ? 72 : 矮 ? 84 : 100;
  const 坞高 = 地点高 + 2 * (卡高 + 6) + 买高 + 28 + 52;
  const 坞顶 = 高 - 坞高 - 8;
  const 卡宽 = (宽 - 44) / 3;
  /**
   * 两颗购买按钮都保留两端糖纸：扭结从胶囊端口内缩 2px 后各外伸约 16px（高 44 时），
   * 中缝 44px 容下两侧共 32px 再留 12px 呼吸，两颗糖的「耳朵」才不会在接缝处互相压住。
   * 代价是胶囊收窄（390 宽下每颗 174→157），糖纸尺寸仍跟按钮高度走。
   */
  const 购买边距 = 16;
  const 购买缝 = 44;
  const 单宽 = (宽 - 购买边距 * 2 - 购买缝) / 2;
  const 买顶 = 坞顶 + 8 + 2 * (卡高 + 6);
  const 目录: 矩形 = { 左: 16, 上: 高 - 地点高 - 68, 宽: 宽 - 32, 高: 地点高 };
  const 目录卡宽 = 目录.宽 < 430 ? 96 : 118;
  /** 金币条（16,12）高 34：标题区紧接在它下面，与 原场景原式一致。 */
  const 标题Y = 12 + 计算金币条(16, 12, 0).高 + 6;
  // 地名 28px 且带描边，30 会让副题贴上描边；再留 10px。
  const 副题Y = 标题Y + 40;
  const 浮层顶 = 高 - 坞高 - 8;
  const 纯享: 矩形 = { 左: 宽 / 2 - 40, 上: 高 - 坞高 - 48, 宽: 80, 高: 32 };
  const 底板顶 = 纯享.上 + 纯享.高;
  return {
    卡高,
    买高,
    地点高,
    坞高,
    坞顶,
    部位卡: Array.from(
      { length: 6 },
      (_, i): 矩形 => ({
        左: 16 + (i % 3) * (卡宽 + 6),
        上: 坞顶 + 8 + Math.floor(i / 3) * (卡高 + 6),
        宽: 卡宽,
        高: 卡高,
      }),
    ),
    单件: { 左: 购买边距, 上: 买顶, 宽: 单宽, 高: 买高 },
    整套: { 左: 购买边距 + 单宽 + 购买缝, 上: 买顶, 宽: 单宽, 高: 买高 },
    目录,
    目录卡宽,
    目录卡高: 地点高 - 4,
    退出: { 左: 宽 / 2 - 74, 上: 高 - 60, 宽: 148, 高: 46 },
    纯享,
    /** 坞区浮层：玻璃底板、部位卡区、购买区（原场景 绘制浮层 原式）。 */
    浮层: {
      玻璃: { 左: 8, 上: 浮层顶, 宽: 宽 - 16, 高: 坞高 - 52 } satisfies 矩形,
      部位区: { 左: 16, 上: 浮层顶 + 8, 宽: 宽 - 32, 高: 卡高 } satisfies 矩形,
      购买区: { 左: 16, 上: 浮层顶 + 8 + 2 * (卡高 + 6), 宽: 宽 - 32, 高: 买高 } satisfies 矩形,
    },
    /** 标题区纵向基准：地名 / 副题 / 消息（原场景原式）。 */
    标题Y,
    副题Y,
    消息Y: 副题Y + 20,
    /**
     * 皮肤陈列底板：贴满左右，从纯享按钮下沿收到屏幕底。
     * 不留左右描边，风景不会从列表底下透出来。
     */
    底板: { 左: 0, 上: 底板顶, 宽, 高: 高 - 底板顶 } satisfies 矩形,
  };
}

/**
 * 商店按钮的图标 + 文字并排布局：图标在文字左侧、两者作为一组居中。
 * 复刻 旧版 框架 `界面按钮` 横排图文公式（图标 18、间距 4），供 Three 版按同一数值绘制。
 */
export function 计算商店按钮图文(
  中心X: number,
  中心Y: number,
  文字宽: number,
  图标尺寸 = 18,
  间距 = 4,
): {
  图标: { x: number; y: number; 尺寸: number };
  文字: { x: number; y: number };
} {
  return {
    图标: { x: 中心X - (文字宽 + 间距) / 2, y: 中心Y, 尺寸: 图标尺寸 },
    文字: { x: 中心X + (图标尺寸 + 间距) / 2, y: 中心Y },
  };
}

export function 计算商店方块陈列(宽: number, 高: number, 坞高: number) {
  const 可用宽 = 宽 - 48;
  const 可用高 = Math.max(96, 高 - 坞高 - 174);
  const 列 = 可用宽 < 520 ? (可用宽 < 380 ? 2 : 4) : 7;
  const 行 = Math.ceil(7 / 列);
  const 列距 = 16;
  const 行距 = 14;
  const 格 = Math.max(
    14,
    Math.min(
      36,
      Math.floor((可用宽 - (列 - 1) * 列距) / (列 * 4)),
      Math.floor((可用高 - (行 - 1) * 行距) / (行 * 2)),
    ),
  );
  const 槽宽 = 格 * 4;
  const 槽高 = 格 * 2;
  const 块宽 = 列 * 槽宽 + (列 - 1) * 列距;
  const 块高 = 行 * 槽高 + (行 - 1) * 行距;
  const 左 = (宽 - 块宽) / 2;
  const 顶 = 108 + Math.max(0, (可用高 - 块高) / 2);
  return { 列, 列距, 行距, 格, 槽宽, 槽高, 块宽, 块高, 左, 顶 };
}

export function 计算商店界面示意(宽: number, 高: number, 坞高: number): 矩形 {
  const 面板宽 = Math.min(400, 宽 - 72);
  const 面板高 = Math.min(188, Math.max(140, 高 - 坞高 - 140));
  return {
    左: (宽 - 面板宽) / 2,
    上: 96 + Math.max(0, (高 - 坞高 - 120 - 面板高) / 2),
    宽: 面板宽,
    高: 面板高,
  };
}

export function 计算商店确认布局(宽: number, 高: number) {
  const 面板宽 = Math.min(470, 宽 - 28);
  const 面板高 = Math.min(410, 高 - 24);
  const 面板: 矩形 = { 左: (宽 - 面板宽) / 2, 上: (高 - 面板高) / 2, 宽: 面板宽, 高: 面板高 };
  return {
    面板,
    确认: { 左: 面板.左 + 25, 上: 面板.上 + 面板高 - 112, 宽: 面板宽 - 50, 高: 46 },
    取消: { 左: 面板.左 + 25, 上: 面板.上 + 面板高 - 52, 宽: 面板宽 - 50, 高: 34 },
    关闭: { 左: 面板.左 + 面板宽 - 42, 上: 面板.上 + 14, 宽: 32, 高: 32 },
  };
}

/**
 * 已拥有部位卡的对勾位：落在原来价格那一行的左端，名字之下、卡片下沿之内。
 * 卡高只影响尺寸下限，宽屏（目标 390×844，卡高 48）下是 14px 标记。
 */
export function 计算商店部位对勾(卡: 矩形): 矩形 {
  const 边 = Math.max(10, Math.min(14, 卡.高 - 24));
  return { 左: 卡.左 + 46, 上: 卡.上 + 卡.高 - 边 - 9, 宽: 边, 高: 边 };
}

/**
 * 目录卡缩略区：未拥有时卡顶压着一条封条，缩略图从下面起、底边与名牌对齐；
 * 已拥有则「解封」——缩略图向上铺满到卡顶内边距，画面变长。
 * 两者底边都在名牌上沿，所以解封只往上长，不会晃到名称。
 */
export function 计算商店目录缩略(卡: 矩形, 已拥有: boolean): 矩形 {
  const 左右 = 4;
  const 底边 = 卡.上 + 卡.高 - 30;
  if (已拥有)
    return { 左: 卡.左 + 左右, 上: 卡.上 + 4, 宽: 卡.宽 - 左右 * 2, 高: 底边 - 卡.上 - 4 };
  return { 左: 卡.左 + 左右, 上: 卡.上 + 14, 宽: 卡.宽 - 左右 * 2, 高: 底边 - 卡.上 - 14 };
}

/** 未拥有目录卡顶部的封条：居中、比缩略图窄一圈，读作「未拆封」。 */
export function 计算商店目录封条(卡: 矩形) {
  const 宽 = 卡.宽 - 24;
  const 高 = Math.max(4, Math.round(卡.高 * 0.055));
  return { 左: 卡.左 + (卡.宽 - 宽) / 2, 上: 卡.上 + 4, 宽, 高 };
}

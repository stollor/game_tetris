import type { 矩形 } from "../../../.gamemaker/依赖/框架/界面/绘制/协议";
import { 主题卡常量 } from "../../../资源/预制体/商店/主题卡配方";
import { 计算金币条 } from "../../../资源/预制体/基础/条与数值/金币条配方";
import { 主题列表 } from "../../项目配置/主题目录";

/**
 * 主题商店的陈列几何：标题与金币条同旧版口径，中部整块给主题大预览，
 * 底部一横排主题卡（4 套全展示，默认主题标不可购买）+ 购买/使用按钮 + 纯享/退出。
 */

export interface 商店布局参数 {
  /** 主题卡数量；默认取目录里的四套。 */
  卡数?: number;
}

export function 计算商店布局(宽: number, 高: number, 参数: 商店布局参数 = {}) {
  const 扁 = 高 < 560;
  const 卡数 = 参数.卡数 ?? 主题列表.length;
  const 主按钮高 = 扁 ? 38 : 44;
  const 退出高 = 扁 ? 38 : 46;
  const 卡高 = 扁 ? 88 : 主题卡常量.卡高;
  /** 底部浮层区：主题卡一排 + 主按钮 + 纯享/退出一排。 */
  const 坞高 = 卡高 + 主按钮高 + 退出高 + 40;
  const 坞顶 = 高 - 坞高 - 8;
  const 卡间距 = 8;
  const 卡宽 = Math.min(主题卡常量.卡宽, (宽 - 32 - 卡间距 * (卡数 - 1)) / 卡数);
  const 卡顶 = 坞顶 + 8;
  const 主题卡: 矩形[] = Array.from({ length: 卡数 }, (_, i) => ({
    左: (宽 - (卡宽 * 卡数 + 卡间距 * (卡数 - 1))) / 2 + i * (卡宽 + 卡间距),
    上: 卡顶,
    宽: 卡宽,
    高: 卡高,
  }));
  const 买顶 = 卡顶 + 卡高 + 10;
  const 主按钮: 矩形 = { 左: 26, 上: 买顶, 宽: 宽 - 52, 高: 主按钮高 };
  const 底排顶 = 高 - 退出高 - 12;
  const 退出: 矩形 = { 左: 宽 / 2 - 74, 上: 底排顶, 宽: 148, 高: 退出高 };
  const 纯享: 矩形 = { 左: 退出.左 - 96, 上: 底排顶 + 6, 宽: 86, 高: 退出高 - 12 };
  /** 金币条（16,12）高 34：标题区紧接在它下面；扁屏压缩行距给预览留位置。 */
  const 标题Y = 12 + 计算金币条(16, 12, 0).高 + 6;
  const 副题Y = 标题Y + (扁 ? 30 : 40);
  const 消息Y = 副题Y + (扁 ? 16 : 20);
  // 预览顶到主题卡上方，任何高度都不与卡排重叠；扁屏最多压到 40。
  const 预览: 矩形 = {
    左: 16,
    上: 消息Y + (扁 ? 16 : 22),
    宽: 宽 - 32,
    高: Math.max(40, 卡顶 - 10 - (消息Y + (扁 ? 16 : 22))),
  };
  return {
    卡高,
    卡宽,
    卡间距,
    坞高,
    坞顶,
    主题卡,
    主按钮,
    退出,
    纯享,
    预览,
    标题Y,
    副题Y,
    消息Y,
  };
}

/**
 * 商店按钮的图标 + 文字并排布局：图标在文字左侧、两者作为一组居中。
 * 复刻 Phaser 框架 `界面按钮` 横排图文公式（图标 18、间距 4），供 Three 版按同一数值绘制。
 */
export function 计算商店按钮图文(
  中心X: number,
  中心Y: number,
  文字宽: number,
  图标尺寸 = 18,
  间距 = 4,
): {
  图标: { x: number; y: number; 尺寸: number };
  文字: { x: number; y: number };
} {
  return {
    图标: { x: 中心X - (文字宽 + 间距) / 2, y: 中心Y, 尺寸: 图标尺寸 },
    文字: { x: 中心X + (图标尺寸 + 间距) / 2, y: 中心Y },
  };
}

/** 购买确认纸页（保留旧几何：居中面板 + 确认/取消 + 右上关闭）。 */
export function 计算商店确认布局(宽: number, 高: number) {
  const 面板宽 = Math.min(470, 宽 - 28);
  const 面板高 = Math.min(410, 高 - 24);
  const 面板: 矩形 = { 左: (宽 - 面板宽) / 2, 上: (高 - 面板高) / 2, 宽: 面板宽, 高: 面板高 };
  return {
    面板,
    确认: { 左: 面板.左 + 25, 上: 面板.上 + 面板高 - 112, 宽: 面板宽 - 50, 高: 46 },
    取消: { 左: 面板.左 + 25, 上: 面板.上 + 面板高 - 52, 宽: 面板宽 - 50, 高: 34 },
    关闭: { 左: 面板.左 + 面板宽 - 42, 上: 面板.上 + 14, 宽: 32, 高: 32 },
  };
}

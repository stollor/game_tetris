/**
 * 主界面布局：把 `代码/场景/主界面/开始菜单.ts` 重构前的几何算法逐字搬出来，
 * Phaser 场景与 Three 主界面共用同一份数值。纯几何函数，不读设置/存档/语言。
 *
 * 坐标约定：按钮/标题给中心点（与框架按钮、文字锚点一致）；金币条只给左上角，
 * 宽度由余额文案长度决定（`代码/界面/金币条.ts` 的 计算金币条）。
 */

export type 主界面状态 = "菜单" | "模式选择" | "纯享";

export interface 主界面视口 {
  宽: number;
  高: number;
  竖屏: boolean;
  矮屏: boolean;
}

export interface 按钮区域 {
  中心X: number;
  中心Y: number;
  宽: number;
  高: number;
}

export interface 文案对 {
  中文: string;
  英文: string;
}

export interface 角钮项 {
  图标: 旅行图标名称;
  文案: 文案对;
}

export interface 模式卡区域 {
  模式: 游戏模式;
  中心X: number;
  中心Y: number;
  宽: number;
  高: number;
}

export interface 纯享布局 {
  返回钮: 按钮区域;
  标题: { x: number; y: number };
  说明: { x: number; y: number };
  圆点: { y: number; 选中半径: number; 未选半径: number };
}

export interface 主界面布局 {
  状态: 主界面状态;
  视口: 主界面视口;
  /** 金币条左上角；宽高按余额计算，见 计算金币条。 */
  金币: { 左: number; 上: number };
  /** 左侧竖排功能入口（设置/成就/商店）。 */
  角钮: {
    中心X: number;
    宽: number;
    高: number;
    项: readonly 角钮项[];
    中心Y: readonly number[];
  };
  标题?: { x: number; y: number };
  开始钮?: 按钮区域 & { 文案: 文案对 };
  模式选择?: {
    /** 很小的游戏名，和菜单上的大标题是同一块内容。 */
    游戏名: { x: number; y: number };
    /** 「选择模式」大标题。 */
    标题: { x: number; y: number };
    卡: readonly 模式卡区域[];
    返回钮: 按钮区域 & { 文案: 文案对 };
  };
  纯享?: 纯享布局;
}

/** 左侧功能入口的顺序与图标（文案由场景按语言取 中文/英文）。 */
export const 角钮项列表: readonly 角钮项[] = [
  { 图标: "设置", 文案: { 中文: "设置", 英文: "SET" } },
  { 图标: "成就", 文案: { 中文: "成就", 英文: "BEST" } },
  { 图标: "商店", 文案: { 中文: "商店", 英文: "SHOP" } },
];

function 计算角钮(视口: 主界面视口) {
  const 宽 = 视口.宽 < 420 ? 52 : 64;
  const 高 = 52;
  const 中心X = 视口.宽 < 420 ? 36 : 46;
  const 间距 = 视口.高 < 560 ? 56 : 64;
  const 起 = Math.round(视口.高 * (视口.高 < 560 ? 0.28 : 0.26));
  return {
    中心X,
    宽,
    高,
    项: 角钮项列表,
    中心Y: 角钮项列表.map((_, i) => 起 + i * 间距),
  };
}

function 计算模式选择(视口: 主界面视口) {
  const { 宽, 高, 竖屏, 矮屏 } = 视口;
  const 游戏名 = { x: 宽 / 2, y: 矮屏 ? 56 : 竖屏 ? 64 : 58 };
  const 标题 = { x: 宽 / 2, y: 矮屏 ? 86 : 竖屏 ? 112 : 96 };
  const 列 = 竖屏 || 宽 < 720 ? 1 : 2;
  const 卡宽 = Math.min(340, 列 === 1 ? 宽 - 48 : Math.min(320, (宽 - 72) / 2));
  let 卡高 = 矮屏 ? 68 : 竖屏 ? 96 : 108;
  const 横距 = 20;
  let 纵距 = 矮屏 ? 10 : 16;
  const 行 = Math.ceil(游戏模式顺序.length / 列);
  const 顶留 = 矮屏 ? 112 : 148;
  const 底留 = 矮屏 ? 92 : 108;
  const 可用高 = 高 - 顶留 - 底留;
  if (行 * 卡高 + (行 - 1) * 纵距 > 可用高 && 行 > 1) {
    纵距 = Math.min(纵距, 8);
    卡高 = Math.max(52, Math.floor((可用高 - (行 - 1) * 纵距) / 行));
  }
  const 块宽 = 列 * 卡宽 + (列 - 1) * 横距;
  const 块高 = 行 * 卡高 + (行 - 1) * 纵距;
  const 起x = 宽 / 2 - 块宽 / 2 + 卡宽 / 2;
  const 起y = 顶留 + (高 - 顶留 - 底留 - 块高) / 2 + 卡高 / 2;
  const 卡 = 游戏模式顺序.map((模式, i) => {
    const 列号 = 列 === 1 ? 0 : i % 列;
    const 行号 = 列 === 1 ? i : Math.floor(i / 列);
    return {
      模式,
      中心X: 起x + 列号 * (卡宽 + 横距),
      中心Y: 起y + 行号 * (卡高 + 纵距),
      宽: 卡宽,
      高: 卡高,
    } satisfies 模式卡区域;
  });
  return {
    游戏名,
    标题,
    卡,
    返回钮: {
      中心X: 宽 / 2,
      中心Y: 高 - (矮屏 ? 46 : 56),
      宽: Math.min(188, 宽 - 48),
      高: 矮屏 ? 54 : 68,
      文案: { 中文: "返回", 英文: "BACK" },
    },
  };
}

function 计算纯享(视口: 主界面视口): 纯享布局 {
  const { 宽, 高 } = 视口;
  const 返宽 = Math.min(132, Math.max(100, 宽 * 0.24));
  return {
    返回钮: { 中心X: 宽 - 返宽 / 2 - 16, 中心Y: 高 - 40, 宽: 返宽, 高: 40 },
    标题: { x: 24, y: 高 - 78 },
    说明: { x: 25, y: 高 - 42 },
    圆点: {
      y: 高 - 16,
      选中半径: 3.5,
      未选半径: 2.2,
    },
  };
}

export function 计算主界面布局(
  视口宽: number,
  视口高: number,
  状态: 主界面状态 = "菜单",
): 主界面布局 {
  const 视口: 主界面视口 = { 宽: 视口宽, 高: 视口高, 竖屏: 视口高 > 视口宽, 矮屏: 视口高 < 560 };
  const 布局: 主界面布局 = {
    状态,
    视口,
    金币: { 左: 16, 上: 12 },
    角钮: 计算角钮(视口),
  };
  if (状态 === "菜单") {
    布局.标题 = { x: 视口宽 / 2, y: Math.round(视口高 * (视口.竖屏 ? 0.36 : 0.32)) };
    布局.开始钮 = {
      中心X: 视口宽 / 2,
      中心Y: Math.round(视口高 * (视口.竖屏 ? 0.72 : 0.76)),
      宽: Math.min(390, 视口宽 - 48),
      高: 44,
      文案: { 中文: "开始游戏", 英文: "PLAY" },
    };
  }
  if (状态 === "模式选择") 布局.模式选择 = 计算模式选择(视口);
  if (状态 === "纯享") {
    布局.标题 = { x: 视口宽 / 2, y: Math.round(视口高 * (视口.竖屏 ? 0.36 : 0.32)) };
    布局.开始钮 = {
      中心X: 视口宽 / 2,
      中心Y: Math.round(视口高 * (视口.竖屏 ? 0.72 : 0.76)),
      宽: Math.min(390, 视口宽 - 48),
      高: 44,
      文案: { 中文: "开始游戏", 英文: "PLAY" },
    };
    布局.纯享 = 计算纯享(视口);
  }
  return 布局;
}

/** 纯享态底部风景圆点：x 按总数居中排开，当前项半径更大。 */
export function 计算纯享圆点(
  布局: 主界面布局,
  总数: number,
  当前索引: number,
): { x: number; y: number; 半径: number }[] {
  const 圆点 = 布局.纯享?.圆点;
  if (!圆点) return [];
  const 数量 = Math.max(1, 总数);
  const 点宽 = Math.min(14, 360 / 布局.视口.宽);
  const 起点X = 布局.视口.宽 / 2 - ((数量 - 1) * 点宽) / 2;
  const 当前 = Math.max(0, Math.min(数量 - 1, 当前索引));
  return Array.from({ length: 数量 }, (_, i) => ({
    x: 起点X + i * 点宽,
    y: 圆点.y,
    半径: i === 当前 ? 圆点.选中半径 : 圆点.未选半径,
  }));
}

export interface 主界面文字数据 {
  英文: boolean;
  游戏名称: string;
}

/** 主界面静态文字项：标题与模式选择页标题；按钮/模式卡/金币条文字各有自己的配方。 */
export function 生成主界面文字项(布局: 主界面布局, 数据: 主界面文字数据): 文字项[] {
  const 项: 文字项[] = [];
  if (布局.标题) {
    const 大 = 布局.视口.竖屏 && !布局.视口.矮屏;
    const 角色 = 数据.英文 ? (大 ? "英文主标题" : "英文主标题紧凑") : 大 ? "主标题" : "主标题紧凑";
    项.push({
      文案: 数据.游戏名称,
      样式: 读取霓虹文字样式(角色),
      锚点: "中中",
      x: 布局.标题.x,
      y: 布局.标题.y,
    });
  }
  if (布局.模式选择) {
    const 选择字号 = 布局.视口.矮屏 ? 22 : 布局.视口.竖屏 ? 34 : 28;
    const 游戏名角色 = 数据.英文 ? "英文主标题微" : "主标题微";
    const 选择基础 = 读取霓虹文字样式("选择模式标题");
    项.push({
      文案: 数据.游戏名称,
      样式: 派生霓虹文字样式(游戏名角色, 布局.视口.矮屏 ? { 字号: 12 } : undefined),
      锚点: "中中",
      x: 布局.模式选择.游戏名.x,
      y: 布局.模式选择.游戏名.y,
    });
    项.push({
      文案: 数据.英文 ? "CHOOSE MODE" : "选择模式",
      样式: 派生霓虹文字样式("选择模式标题", {
        字号: 选择字号,
        字重: "粗体",
        描边: 选择基础.描边 ? { ...选择基础.描边, 粗细: 选择字号 >= 28 ? 5 : 3 } : undefined,
      }),
      锚点: "中中",
      x: 布局.模式选择.标题.x,
      y: 布局.模式选择.标题.y,
    });
  }
  return 项;
}

/**
 * 主界面组合布局（兼容层）：菜单页 / 模式选择页 / 纯享页各自有独立布局模块，
 * 这里把它们组合成一份「全状态」布局，只服务两个老调用方：
 * `视效/过渡/主界面流转.ts` 与独立预览/规则测试的几何读取。
 * 新页面代码不要再引用本文件，直接用 `菜单布局`、`模式选择布局`、`纯享布局`。
 *
 * 金币条已移到货币层，`金币` 只保留给旧流转块的身份占位，页面不再绘制。
 */

export type 主界面状态 = "菜单" | "模式选择" | "纯享";
export type 主界面视口 = 界面视口;
export type 纯享布局 = 纯享页布局;

export interface 主界面布局 {
  状态: 主界面状态;
  视口: 主界面视口;
  /** 旧流转块用的金币条占位（货币层接管后页面不再画）。 */
  金币: { 左: number; 上: number };
  角钮: 菜单布局["角钮"];
  标题?: { x: number; y: number };
  开始钮?: 按钮区域 & { 文案: 文案对 };
  模式选择?: {
    游戏名: { x: number; y: number };
    标题: { x: number; y: number };
    卡: readonly 模式卡区域[];
    返回钮: 按钮区域 & { 文案: 文案对 };
  };
  纯享?: 纯享布局;
}

export function 计算主界面布局(
  视口宽: number,
  视口高: number,
  状态: 主界面状态 = "菜单",
): 主界面布局 {
  const 视口 = 计算界面视口(视口宽, 视口高);
  const 布局: 主界面布局 = {
    状态,
    视口,
    金币: { 左: 16, 上: 12 },
    角钮: 计算菜单布局(视口宽, 视口高).角钮,
  };
  if (状态 === "菜单") {
    const 菜单 = 计算菜单布局(视口宽, 视口高);
    布局.标题 = 菜单.标题;
    布局.开始钮 = 菜单.开始钮;
  }
  if (状态 === "模式选择") {
    const 模式选择 = 计算模式选择布局(视口宽, 视口高);
    布局.模式选择 = {
      游戏名: 模式选择.游戏名,
      标题: 模式选择.标题,
      卡: 模式选择.卡,
      返回钮: 模式选择.返回钮,
    };
  }
  if (状态 === "纯享") {
    布局.纯享 = 计算纯享页布局(视口宽, 视口高);
  }
  return 布局;
}

/** 纯享态底部风景圆点（旧口径：按主界面组合布局取值）。 */
export function 计算纯享圆点(
  布局: 主界面布局,
  总数: number,
  当前索引: number,
): { x: number; y: number; 半径: number }[] {
  const 圆点 = 布局.纯享?.圆点;
  if (!圆点) return [];
  const 数量 = Math.max(1, 总数);
  const 点宽 = Math.min(14, 360 / Math.max(1, 布局.视口.宽));
  const 起点X = 布局.视口.宽 / 2 - ((数量 - 1) * 点宽) / 2;
  const 当前 = Math.max(0, Math.min(数量 - 1, 当前索引));
  return Array.from({ length: 数量 }, (_, i) => ({
    x: 起点X + i * 点宽,
    y: 圆点.y,
    半径: i === 当前 ? 圆点.选中半径 : 圆点.未选半径,
  }));
}

export interface 主界面文字数据 {
  英文: boolean;
  游戏名称: string;
}

/** 全状态静态文字项：菜单标题，或模式选择页的小游戏名 + 「选择模式」大标题。 */
export function 生成主界面文字项(布局: 主界面布局, 数据: 主界面文字数据): 文字项[] {
  if (布局.状态 === "菜单" || 布局.状态 === "纯享") {
    const 菜单 = 计算菜单布局(布局.视口.宽, 布局.视口.高);
    return 生成菜单文字项(
      {
        ...菜单,
        标题: 布局.标题 ?? 菜单.标题,
      },
      数据,
    );
  }
  const 模式选择 = 计算模式选择布局(布局.视口.宽, 布局.视口.高);
  return 生成模式选择文字项(
    {
      ...模式选择,
      游戏名: 布局.模式选择?.游戏名 ?? 模式选择.游戏名,
      标题: 布局.模式选择?.标题 ?? 模式选择.标题,
      卡: 布局.模式选择?.卡 ?? 模式选择.卡,
      返回钮: 布局.模式选择?.返回钮 ?? 模式选择.返回钮,
    },
    数据,
  );
}


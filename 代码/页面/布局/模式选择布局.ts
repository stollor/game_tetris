import type { 文字项 } from "../../../.gamemaker/依赖/框架/界面/绘制/协议";
import { 游戏模式顺序 } from "../../../资源/主题/外观/游戏外观";
import { 派生霓虹文字样式, 读取霓虹文字样式 } from "../../../资源/主题/文字/文字样式";
import type { 游戏模式 } from "../../玩法/再消一行";
import type { 按钮区域, 文案对, 界面视口 } from "./菜单布局";

/**
 * 模式选择页布局：模式装置卡 + 返回传送装置 + 模式标题。
 * 几何数值逐字来自重构前的主界面布局，纯几何函数。
 */

export interface 模式卡区域 {
  模式: 游戏模式;
  中心X: number;
  中心Y: number;
  宽: number;
  高: number;
}

export interface 模式选择布局 {
  视口: 界面视口;
  /** 很小的游戏名，和菜单页上的大标题是同一块内容。 */
  游戏名: { x: number; y: number };
  /** 「选择模式」大标题。 */
  标题: { x: number; y: number };
  卡: readonly 模式卡区域[];
  返回钮: 按钮区域 & { 文案: 文案对 };
}

export interface 模式选择文字数据 {
  英文: boolean;
  游戏名称: string;
}

export function 计算模式选择布局(视口宽: number, 视口高: number): 模式选择布局 {
  const { 宽, 高, 竖屏, 矮屏 }: 界面视口 = {
    宽: 视口宽,
    高: 视口高,
    竖屏: 视口高 > 视口宽,
    矮屏: 视口高 < 560,
  };
  const 游戏名 = { x: 宽 / 2, y: 矮屏 ? 56 : 竖屏 ? 64 : 58 };
  const 标题 = { x: 宽 / 2, y: 矮屏 ? 86 : 竖屏 ? 112 : 96 };
  const 列 = 竖屏 || 宽 < 720 ? 1 : 2;
  const 卡宽 = Math.min(340, 列 === 1 ? 宽 - 48 : Math.min(320, (宽 - 72) / 2));
  let 卡高 = 矮屏 ? 68 : 竖屏 ? 96 : 108;
  const 横距 = 20;
  let 纵距 = 矮屏 ? 10 : 16;
  const 行 = Math.ceil(游戏模式顺序.length / 列);
  const 顶留 = 矮屏 ? 112 : 148;
  const 底留 = 矮屏 ? 92 : 108;
  const 可用高 = 高 - 顶留 - 底留;
  if (行 * 卡高 + (行 - 1) * 纵距 > 可用高 && 行 > 1) {
    纵距 = Math.min(纵距, 8);
    卡高 = Math.max(52, Math.floor((可用高 - (行 - 1) * 纵距) / 行));
  }
  const 块宽 = 列 * 卡宽 + (列 - 1) * 横距;
  const 块高 = 行 * 卡高 + (行 - 1) * 纵距;
  const 起x = 宽 / 2 - 块宽 / 2 + 卡宽 / 2;
  const 起y = 顶留 + (高 - 顶留 - 底留 - 块高) / 2 + 卡高 / 2;
  const 卡 = 游戏模式顺序.map((模式, i) => {
    const 列号 = 列 === 1 ? 0 : i % 列;
    const 行号 = 列 === 1 ? i : Math.floor(i / 列);
    return {
      模式,
      中心X: 起x + 列号 * (卡宽 + 横距),
      中心Y: 起y + 行号 * (卡高 + 纵距),
      宽: 卡宽,
      高: 卡高,
    } satisfies 模式卡区域;
  });
  return {
    视口: { 宽, 高, 竖屏, 矮屏 },
    游戏名,
    标题,
    卡,
    返回钮: {
      中心X: 宽 / 2,
      中心Y: 高 - (矮屏 ? 46 : 56),
      宽: Math.min(188, 宽 - 48),
      高: 矮屏 ? 54 : 68,
      文案: { 中文: "返回", 英文: "BACK" },
    },
  };
}

/** 模式选择页静态文字项：小游戏名 + 「选择模式」大标题。 */
export function 生成模式选择文字项(布局: 模式选择布局, 数据: 模式选择文字数据): 文字项[] {
  const 选择字号 = 布局.视口.矮屏 ? 22 : 布局.视口.竖屏 ? 34 : 28;
  const 游戏名角色 = 数据.英文 ? "英文主标题微" : "主标题微";
  const 选择基础 = 读取霓虹文字样式("选择模式标题");
  return [
    {
      文案: 数据.游戏名称,
      样式: 派生霓虹文字样式(游戏名角色, 布局.视口.矮屏 ? { 字号: 12 } : undefined),
      锚点: "中中",
      x: 布局.游戏名.x,
      y: 布局.游戏名.y,
    },
    {
      文案: 数据.英文 ? "CHOOSE MODE" : "选择模式",
      样式: 派生霓虹文字样式("选择模式标题", {
        字号: 选择字号,
        字重: "粗体",
        描边: 选择基础.描边 ? { ...选择基础.描边, 粗细: 选择字号 >= 28 ? 5 : 3 } : undefined,
      }),
      锚点: "中中",
      x: 布局.标题.x,
      y: 布局.标题.y,
    },
  ];
}

/**
 * 覆盖页（设置/成就/排行榜）共享几何：数值逐条来自 Phaser 场景的现行布局
 * （`代码/场景/成就/成就界面.ts`、`代码/场景/排行榜/排行榜界面.ts`），
 * Three 页与预览消费同一份纯函数；改这里必须两版一起验证。
 *
 * 只放纯几何，颜色与字号来自代码/主题/。
 */

export interface 矩形布局 {
  左: number;
  上: number;
  宽: number;
  高: number;
}

export interface 成就页布局 {
  列表: 矩形布局;
  行高: number;
  /** 行底板宽；由框架列表在视口横轴居中。 */
  行宽: number;
  行板高: number;
  /** 说明文字的换行宽。 */
  说明宽: number;
  /** 进度数字右端相对行容器左端的 x。 */
  数量X: number;
  返回: 矩形布局;
}

/** 成就页：列表居中、行高 94、板高 84、底部返回按钮。 */
export function 计算成就页布局(视口宽: number, 视口高: number): 成就页布局 {
  const 列表宽 = Math.min(680, 视口宽 - 32);
  const 返回宽 = Math.min(260, 视口宽 - 40);
  return {
    列表: { 左: (视口宽 - 列表宽) / 2, 上: 94, 宽: 列表宽, 高: 视口高 - 172 },
    行高: 94,
    行宽: 列表宽 - 12,
    行板高: 84,
    说明宽: 列表宽 - 110,
    数量X: 列表宽 - 28,
    返回: { 左: (视口宽 - 返回宽) / 2, 上: 视口高 - 55, 宽: 返回宽, 高: 42 },
  };
}

export interface 排行榜页布局 {
  标题中心: { x: number; y: number };
  /** 周期页签左端与间距；第 i 个左端 = 页签.左 + i * (页签.宽 + 页签.间距)。 */
  页签: { 左: number; 上: number; 宽: number; 高: number; 间距: number };
  /** 状态文案（我的名次）区域。 */
  状态: { 中心X: number; 上: number; 最大宽: number };
  列表: 矩形布局;
  行高: number;
  /** 榜单行底板宽。 */
  行宽: number;
  行板高: number;
  /** 底部两钮：第 i 个左端 = 按钮行.左 + i * (按钮行.宽 + 按钮行.间距)。 */
  按钮行: { 左: number; 上: number; 宽: number; 高: number; 间距: number };
}

/** 排行榜页：标题/周期页签/我的状态/榜单列表/底部返回与登录。 */
export function 计算排行榜页布局(视口宽: number, 视口高: number): 排行榜页布局 {
  const 签宽 = Math.min(72, (视口宽 - 48) / 4 - 6);
  return {
    标题中心: { x: 视口宽 / 2, y: 28 },
    页签: { 左: 24, 上: 51, 宽: 签宽, 高: 34, 间距: 8 },
    状态: { 中心X: 视口宽 / 2, 上: 112, 最大宽: Math.max(160, 视口宽 - 48) },
    列表: { 左: 16, 上: 128, 宽: 视口宽 - 32, 高: 视口高 - 200 },
    行高: 52,
    行宽: 视口宽 - 44,
    行板高: 44,
    按钮行: { 左: 视口宽 / 2 - 170, 上: 视口高 - 56, 宽: 160, 高: 40, 间距: 20 },
  };
}

/**
 * 《再消一行》的节点注册小工具：把布局给的几何 / 文字项换算成节点坐标（y 向上），
 * 并把预制体画法包进组件的绘制钩子。页面只写「有哪些节点」，不重复算锚点。
 */

export interface 文字节点约定 {
  名称: string;
  项: 文字项;
}

const 锚点比例 = {
  左上: [0, 0],
  左中: [0, 0.5],
  中上: [0.5, 0],
  中中: [0.5, 0.5],
  右上: [1, 0],
  右中: [1, 0.5],
} as const;

/** 把文字项换算成节点坐标：位置是锚点位置（y 向上），矩形按实测尺寸。 */
function 文字节点坐标(
  项: 文字项,
  页面高: number,
  测量: (文案: string, 样式: 文字项["样式"]) => { 宽: number; 高: number },
): { 位置X: number; 位置Y: number; 宽: number; 高: number; 锚点X: number; 锚点Y: number } {
  const 尺寸 = 测量(项.文案, 项.样式);
  const [锚点X, 锚点Y] = 锚点比例[项.锚点];
  const 高 = Math.max(1, 尺寸.高);
  // 锚点在上边时，节点底边要再下移一个文字高度，文字顶边才落在项.y。
  return {
    位置X: 项.x,
    位置Y: 页面高 - 项.y - (锚点Y === 0 ? 高 : 0),
    宽: Math.max(1, 尺寸.宽),
    高,
    锚点X,
    锚点Y,
  };
}

/** 文字组件画法：把注册的文字项按矩形中心重新锚定，并带上文字空间矩阵。 */
function 文字画法(项: () => 文字项): (环境: 节点绘制环境) => void {
  return (环境) => {
    const 画笔 = 读取画笔(环境);
    if (!画笔) return;
    const 矩形 = 环境.节点.读取本地矩形();
    if (!矩形) return;
    const 当前 = 项();
    画笔.绘制文字({
      ...当前,
      锚点: "中中",
      x: 矩形.宽 / 2,
      y: 矩形.高 / 2,
      变换: 文字空间矩阵(环境, 矩形.高),
    });
  };
}

export function 创建文字节点(
  父: 节点,
  约定: 文字节点约定,
  页面高: number,
  测量: (文案: string, 样式: 文字项["样式"]) => { 宽: number; 高: number },
): 节点 {
  const 组件 = new 文字组件({ 绘制: 文字画法(() => 约定.项) });
  return 创建注册节点(父, {
    名称: 约定.名称,
    坐标: 文字节点坐标(约定.项, 页面高, 测量),
    组件,
  });
}

export function 更新文字节点(
  节点: 节点 | null,
  约定: 文字节点约定,
  页面高: number,
  测量: (文案: string, 样式: 文字项["样式"]) => { 宽: number; 高: number },
): void {
  if (!节点) return;
  节点.读取二维坐标()?.更新参数(文字节点坐标(约定.项, 页面高, 测量));
  const 组件 = 节点.读取组件<文字组件>(文字组件);
  组件?.应用参数({ 绘制: 文字画法(() => 约定.项) });
}

export interface 按钮节点区域 {
  中心X: number;
  中心Y: number;
  宽: number;
  高: number;
}

export function 创建按钮节点(
  父: 节点,
  名称: string,
  区域: 按钮节点区域,
  页面高: number,
  参数: ConstructorParameters<typeof 按钮组件>[0],
): 节点 {
  const 组件 = new 按钮组件(参数);
  return 创建注册节点(父, {
    名称,
    坐标: {
      位置X: 区域.中心X,
      位置Y: 页面高 - 区域.中心Y,
      宽: 区域.宽,
      高: 区域.高,
    },
    组件,
  });
}

export function 更新按钮节点(
  节点: 节点 | null,
  区域: 按钮节点区域,
  页面高: number,
  参数: ConstructorParameters<typeof 按钮组件>[0],
): void {
  if (!节点) return;
  节点.读取二维坐标()?.更新参数({
    位置X: 区域.中心X,
    位置Y: 页面高 - 区域.中心Y,
    宽: 区域.宽,
    高: 区域.高,
  });
  节点.读取组件<按钮组件>(按钮组件)?.应用参数(参数);
}

/**
 * 区域画法：把页面坐标配方搬进一个独立的按钮/面板节点。
 * 配方写原页面矩形，节点自己位移/缩放时图形与文字一起走；节点本地坐标从 0 开始。
 */
export function 用区域画法(
  环境: 节点绘制环境,
  区域: { 左: number; 上: number },
  绘制: (画法: {
    图形: import("../../.gamemaker/依赖/框架/界面/绘制/协议").图形对象;
    画笔: import("../../.gamemaker/依赖/框架/界面/绘制/画笔").画笔;
  }) => void,
): void {
  区域画法(环境, 区域, 绘制);
}

/** 整页绘制节点：节点就是页面那一块，画法坐标等于绘制空间（左上角、y 向下）。 */
export function 创建整页绘制节点(
  父: 节点,
  名称: string,
  页面宽: number,
  页面高: number,
  绘制: (环境: 节点绘制环境) => void,
): 节点 {
  return 创建注册节点(父, {
    名称,
    坐标: { 位置X: 0, 位置Y: 0, 宽: 页面宽, 高: 页面高, 锚点X: 0, 锚点Y: 0 },
    组件: new 绘制组件({ 绘制 }),
  });
}

/** 满页矩形（绘制空间坐标），用于整页节点的钩子里按页面坐标画。 */
export function 满页矩形(页面宽: number, 页面高: number) {
  return { 左: 0, 上: 0, 宽: 页面宽, 高: 页面高 };
}

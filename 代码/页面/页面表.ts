import type { 页面上下文, 页面注册表 } from "../应用/接口/上下文";
import { 成就界面 } from "./成就界面";
import { 商店界面 } from "./商店界面";
import { 菜单页 } from "./菜单页";
import { 设置界面 } from "./设置界面";
import { 排行榜界面 } from "./排行榜界面";
import { 模式选择页 } from "./模式选择页";
import { 纯享页 } from "./纯享页";

/**
 * 页面表：启动层把这里返回的注册表与对局/暂停菜单/结算合并进页面宿主。
 * 页面宿主按名称缓存实例；每次进入从 上下文.参数 读取当前参数并重建控件。
 * 根页是「菜单」，暂停菜单与结算也是普通页面（浮在对局上）。
 */

export function 创建页面表(_上下文?: 页面上下文): 页面注册表 {
  return {
    菜单: (上下文) => new 菜单页(上下文),
    模式选择: (上下文) => new 模式选择页(上下文),
    纯享: (上下文) => new 纯享页(上下文),
    设置: (上下文) => new 设置界面(上下文),
    成就: (上下文) => new 成就界面(上下文),
    排行榜: (上下文) => new 排行榜界面(上下文),
    商店: (上下文) => new 商店界面(上下文),
  };
}

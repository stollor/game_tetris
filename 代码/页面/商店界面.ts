  private 确认交易(): void {
    const 确认 = this.确认;
    if (!确认) return;
    if (!确认.拥有) {
      const 结果 = this.上下文.服务.金币.购买(this.地点.名称, 确认.部位);
      if (!结果.成功) {
        this.消息 = 结果.原因 ?? "方块币不足";
        this.确认 = null;
        this.重建();
        return;
      }
    }
    this.穿戴部位(确认.部位);
    this.确认 = null;
    this.消息 = "";
    this.重建();
  }

  private 穿戴部位(部位: 外观部位 | "整套"): void {
    this.选中部位 = 部位 === "整套" ? this.选中部位 : 部位;
    const 变化: Partial<游戏设置> = {};
    const 名称 = this.地点.名称;
    const 要穿: readonly 外观部位[] = 部位 === "整套" ? 外观部位列表 : [部位];
    for (const 项 of 要穿) {
      if (项 === "静态背景") 变化.背景主题 = 名称;
      if (项 === "动态背景") 变化.背景主题 = 名称;
      if (项 === "界面样式") {
        变化.旅行样式 = 名称;
        变化.样式 = "夜空鎏金";
      }
      if (项 === "方块外观") 变化.方块外观 = 名称;
      if (项 === "音效套装") 变化.旅行音效 = 名称;
      if (项 === "音乐") 变化.旅行音乐 = 名称;
    }
    this.上下文.服务.设置.更新(变化);
  }


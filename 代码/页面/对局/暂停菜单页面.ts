/**
 * 暂停覆盖页：压在仍更新的对局上，画玻璃暂停面板或对局内设置。
 * 不透明默认 false、独占命中默认 true，棋盘继续画在下面。
 * 与对局的通信走模块级宿主登记，不另造管理器。
 */

let 暂停宿主: 对局页面 | null = null;
let 当前暂停菜单: 暂停菜单页面 | null = null;

export function 登记暂停宿主(页: 对局页面 | null): void {
  暂停宿主 = 页;
}

export function 读取暂停设置打开(): boolean {
  return 当前暂停菜单?.读取设置打开() ?? false;
}

export function 关闭暂停设置(): void {
  当前暂停菜单?.关闭设置();
}

function 暂停按钮名称(名称: 对局布局数据["暂停面板"]["按钮"][number]["名称"]): string {
  if (名称 === "继续") return "继续";
  if (名称 === "重开") return "重新开始";
  if (名称 === "设置") return "对局设置";
  return "返回主菜单";
}

export class 暂停菜单页面 extends 页面基类<页面上下文> {
  private 设置打开 = false;
  private 落点影滑块: 滑块 | null = null;
  private 网格开关: 开关 | null = null;
  private 按键说明开关: 开关 | null = null;
  private 取消设置订阅: (() => void) | null = null;

  constructor(上下文: 页面上下文) {
    // 浮在对局上的普通页面：不暂停对局更新、不遮同层页面（要看见对局）、独占命中。
    super(上下文, { 名称: "暂停菜单", 不透明: false, 暂停下层: false, 独占命中: true });
  }

  进入(): void {
    当前暂停菜单 = this;
    this.设置打开 = false;
    super.进入();
    this.取消设置订阅 = this.上下文.服务.设置.订阅((设置) => {
      this.落点影滑块?.设置值(设置.落点影透明度);
      this.网格开关?.设置值(设置.显示网格);
      this.按键说明开关?.设置值(设置.显示按键说明);
      this.请求重绘();
    });
  }

  退出(): void {
    if (当前暂停菜单 === this) 当前暂停菜单 = null;
    this.取消设置订阅?.();
    this.取消设置订阅 = null;
    this.落点影滑块 = null;
    this.网格开关 = null;
    this.按键说明开关 = null;
    this.设置打开 = false;
    super.退出();
  }

  读取设置打开(): boolean {
    return this.设置打开;
  }

  关闭设置(): void {
    if (!this.设置打开) return;
    this.设置打开 = false;
    this.重建();
  }

  读取界面(): 界面快照 {
    const 界面 = super.读取界面();
    if (!this.设置打开) return 界面;
    const 定位 = 计算对局设置布局(this.逻辑宽, this.逻辑高);
    const 设置 = this.上下文.服务.设置.读取();
    const 额外 = [
      { 名称: "落点影透明度", ...定位.滑块, 可用: true },
      { 名称: "网格", ...定位.开关.网格, 可用: true },
      { 名称: "网格:开", ...定位.开关.网格, 可用: true },
      { 名称: "网格:关", ...定位.开关.网格, 可用: true },
    ];
    if (定位.开关.按键说明) {
      额外.push(
        { 名称: "按键说明", ...定位.开关.按键说明, 可用: true },
        { 名称: "按键说明:开", ...定位.开关.按键说明, 可用: true },
        { 名称: "按键说明:关", ...定位.开关.按键说明, 可用: true },
      );
    }
    return {
      按钮: [...界面.按钮, ...额外],
      文字: [this.上下文.服务.语言.读取().对局设置, `${设置.落点影透明度}%`],
    };
  }

  protected 返回(): void {
    if (this.设置打开) {
      this.关闭设置();
      return;
    }
    暂停宿主?.设置暂停(false);
  }

  protected 读取文字快照(): readonly string[] {
    if (this.设置打开) {
      const 设置 = this.上下文.服务.设置.读取();
      return [this.上下文.服务.语言.读取().对局设置, `${设置.落点影透明度}%`];
    }
    return ["已暂停"];
  }

  protected 绘制内容(_环境: 绘制环境): void {
    const 资源 = this.上下文.资源;
    if (this.设置打开) {
      for (const 项 of 绘制对局设置(
        资源.画笔.图形,
        资源.逻辑宽,
        资源.逻辑高,
        this.上下文.服务.设置.读取(),
        this.上下文.服务.语言.读取(),
      ))
        资源.画笔.绘制文字(项);
      return;
    }
    绘制对局覆盖(this.读取对局环境(), { 布局: this.读取布局(), 提示: { 暂停: true } });
  }

  protected 构建(): void {
    if (this.设置打开) {
      this.构建设置();
      return;
    }
    for (const 项 of this.读取布局().暂停面板.按钮)
      this.创建按钮(暂停按钮名称(项.名称), {
        矩形: 项.矩形,
        绘制底板: () => {},
        点击: () => this.点击暂停按钮(项.名称),
      });
  }

  private 构建设置(): void {
    const 设置定位 = 计算对局设置布局(this.逻辑宽, this.逻辑高);
    const 设置 = this.上下文.服务.设置.读取();
    // 与弹窗基类同一套命中：先全屏关闭，后面板拦截，避免自写松开+矩形包含。
    this.添加控件(
      new 按钮({
        矩形: { 左: 0, 上: 0, 宽: this.逻辑宽, 高: this.逻辑高 },
        绘制底板: () => {},
        点击: () => this.关闭设置(),
      }),
    );
    this.添加控件(
      new 面板({
        矩形: 设置定位.面板,
        绘制底板: () => {},
      }),
    );
    this.添加控件(
      new 按钮({
        矩形: 设置定位.面板,
        绘制底板: () => {},
        点击: () => undefined,
      }),
    );
    for (const 项 of 设置定位.按钮)
      this.创建按钮(项.名称, {
        矩形: 项.矩形,
        绘制底板: () => {},
        点击: () => this.关闭设置(),
      });
    this.网格开关 = this.添加控件(
      new 开关({
        矩形: 设置定位.开关.网格,
        值: 设置.显示网格,
        绘制底板: () => {},
        变化: (值) => this.上下文.服务.设置.更新({ 显示网格: 值 }),
      }),
    );
    this.按键说明开关 = 设置定位.开关.按键说明
      ? this.添加控件(
          new 开关({
            矩形: 设置定位.开关.按键说明,
            值: 设置.显示按键说明,
            绘制底板: () => {},
            变化: (值) => this.上下文.服务.设置.更新({ 显示按键说明: 值 }),
          }),
        )
      : null;
    this.落点影滑块 = this.添加控件(
      new 滑块({
        矩形: 设置定位.滑块,
        值: 设置.落点影透明度,
        步进: 5,
        样式: { 滑块直径: 0 },
        绘制底板: () => {},
        变化: (值) => this.上下文.服务.设置.更新({ 落点影透明度: 值 }),
      }),
    );
  }

  private 点击暂停按钮(名称: 对局布局数据["暂停面板"]["按钮"][number]["名称"]): void {
    if (名称 === "继续") 暂停宿主?.设置暂停(false);
    else if (名称 === "重开") 暂停宿主?.重新开始();
    else if (名称 === "设置") this.打开设置();
    else this.上下文.导航.替换("菜单");
  }

  private 打开设置(): void {
    if (this.设置打开) return;
    this.设置打开 = true;
    this.重建();
  }

  private 读取布局(): 对局布局数据 {
    const 设置 = this.上下文.服务.设置.读取();
    return 计算对局布局(this.逻辑宽, this.逻辑高, {
      屏幕适配: 设置.屏幕适配,
      显示按键说明: 设置.显示按键说明,
      模式: this.读取模式(),
      阶段: "暂停",
    });
  }

  private 读取模式(): 游戏模式 {
    return 暂停宿主?.读取快照().模式 ?? "马拉松";
  }

  private 读取对局环境(): 对局绘制环境 {
    const 资源 = this.上下文.资源;
    return {
      合批: 资源.合批,
      图形: 资源.画笔.图形,
      方块方案: 读取方块外观方案(this.上下文.服务.设置.读取()),
      画笔: 资源.画笔,
      主题: this.上下文.主题,
    };
  }
}

export const 创建暂停菜单页面: 页面工厂 = (上下文: 页面上下文) => new 暂停菜单页面(上下文);

function 绘制棋盘(环境: 绘制环境, 视图: 对局视图, 偏移X: number, 偏移Y: number): void {
  const { 左, 上, 格, 列, 行 } = 布局.棋盘;
  const 棋盘左 = 左 + 偏移X;
  const 棋盘上 = 上 + 偏移Y;
  const 棋盘宽 = 列 * 格;
  const 棋盘高 = 行 * 格;
  // 外框/网格与 Phaser 预制体同一套配方（含三层柔影、圆角底板、中央柔光）。
  绘制棋盘外框(环境.图形, {
    左: 棋盘左,
    上: 棋盘上,
    宽: 棋盘宽,
    高: 棋盘高,
    格子: 格,
    透明度: 1,
    背景色: 游戏外观.棋盘.背景色,
    边框色: 游戏外观.棋盘.边框色,
  });
  if (视图.显示网格) {
    环境.图形.save();
    环境.图形.translateCanvas(棋盘左, 棋盘上);
    绘制棋盘网格(环境.图形, {
      宽: 棋盘宽,
      高: 棋盘高,
      格子: 格,
      列数: 列,
      行数: 行,
      网格色: 颜色值(界面主题().游戏区域.网格线),
    });
    环境.图形.restore();
  }
  const { 状态 } = 视图;
  for (let 行号 = 0; 行号 < 行; 行号++) {
    const 行数据 = 状态.棋盘[行号 + 2];
    if (!行数据) continue;
    for (let 列号 = 0; 列号 < 列; 列号++) {
      const 类型 = 行数据[列号];
      if (!类型) continue;
      绘制方块格(环境, 环境.主题.方块[类型], 棋盘左 + 列号 * 格, 棋盘上 + 行号 * 格, 格);
    }
  }
  // 幽灵落点先画，当前方块覆盖在上层。
  const 幽灵透明度 = Math.max(0, Math.min(1, 视图.落点影透明度 / 100)) * 0.32;
  const 当前类型 = 状态.当前方块.类型;
  for (const [列号, 行号] of 视图.影子) {
    if (行号 < 0 || 行号 >= 行 || 状态.棋盘[行号 + 2]?.[列号]) continue;
    绘制方块格(
      环境,
      环境.主题.方块[当前类型],
      棋盘左 + 列号 * 格,
      棋盘上 + 行号 * 格,
      格,
      幽灵透明度,
    );
  }
  for (const [列号, 行号] of 读取格子(状态.当前方块)) {
    if (行号 < 0 || 行号 >= 行) continue;
    绘制方块格(环境, 环境.主题.方块[当前类型], 棋盘左 + 列号 * 格, 棋盘上 + 行号 * 格, 格);
  }
}


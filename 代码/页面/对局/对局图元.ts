export function 绘制对局(环境: 绘制环境, 输入: 对局绘制输入): void {
  绘制顶栏(环境, 输入.视图);
  绘制预览区(环境, 输入.视图);
  绘制棋盘(环境, 输入.视图, 输入.偏移X, 输入.偏移Y);
  for (const [序号, 配方] of 操作按钮.entries()) {
    const 矩形 = 操作按钮矩形(配方.行, 配方.列);
    绘制按钮(环境, 矩形, 配方.标签, true, 序号 === 6 || 序号 === 7);
  }
  绘制提示层(环境, 输入.提示);
  绘制暂停层(环境, 输入.提示);
}


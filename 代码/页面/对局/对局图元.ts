/** 计算当前方块落到底的可见格子（不含自身已占用格）。 */
export function 计算影子(状态: 再消一行状态): [number, number][] {
  let 影 = 状态.当前方块;
  const 下移 = () => ({
    ...影,
    中心行2: 影.中心行2 + 2,
    格子: 影.格子.map((格) => ({ ...格, 行2: 格.行2 + 2 })),
  });
  while (可以放置(状态, 下移())) 影 = 下移();
  return 读取格子(影);
}

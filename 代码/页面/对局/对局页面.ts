    this.状态 = 创建新局(this.随机源, this.测试序列, this.模式);
    this.测试序列 = [];
    this.提示.技巧 = null;
    this.对局设置打开 = false;
    this.提示.成就 = null;
    this.提示.目标剩余秒 = 0;
    清空特效(this.特效);
    this.输入.清空();
    this.统计.操作次数 = 0;
    this.统计.落块数 = 0;
    this.统计.消行次数 = 0;
    this.最后落块序号 = 0;
    this.最后消行序号 = 0;

/**
 * 按共享文字样式画文字。Phaser 侧同一份样式用于 Text 的 fontFamily/fontSize/fontStyle/
 * letterSpacing，这里交给画笔的文字服务烘焙同一套字体图集。
 */
function 绘制样式文字(
  环境: 绘制环境,
  样式: 文字样式,
  文本: string,
  x: number,
  y: number,
  锚点: 文字锚点 = "左上",
  透明度 = 1,
): { 宽: number; 高: number } {
  const 半透明 = 透明度 < 1;
  if (半透明) {
    环境.图形.save();
    环境.图形.setAlpha(透明度);
  }
  const 行高 = 环境.画笔.测量文字("字", 样式).高;
  const 尺寸 = 环境.画笔.绘制文字({
    文案: 文本,
    样式,
    锚点,
    x,
    y: y - 文字对齐修正(样式.字号, 锚点, 行高),
  });
  if (半透明) 环境.图形.restore();
  return 尺寸;
}

/** 测量共享文字样式的排版尺寸。 */
function 测量样式文字(环境: 绘制环境, 样式: 文字样式, 文本: string) {
  return 环境.画笔.测量文字(文本, 样式);
}

/** 玻璃按钮底板 + 居中标签：按钮视觉由共享配方给出（框架 界面按钮 同算法）。 */
function 绘制按钮视觉(
  上下文: 绘图上下文,
  矩形: 矩形,
  标签: string,
  视觉: 对局按钮视觉,
  文字样式: 文字样式,
): void {
  const { 环境, 图形 } = 上下文;
  绘制玻璃按钮底板(图形, 矩形.左 + 矩形.宽 / 2, 矩形.上 + 矩形.高 / 2, 矩形.宽, 矩形.高, {
    填色: 视觉.填色,
    边框色: 视觉.边框色,
    强调色: 视觉.边框色,
    透明度: 视觉.透明度,
    边透明度: 视觉.边透明度,
  });
  绘制样式文字(环境, 文字样式, 标签, 矩形.左 + 矩形.宽 / 2, 矩形.上 + 矩形.高 / 2, "中中");
}

/** 中心 + 宽高的按钮几何转矩形。 */
function 转矩形(中心按钮: { 中心X: number; 中心Y: number; 宽: number; 高: number }): 矩形 {
  return {
    左: 中心按钮.中心X - 中心按钮.宽 / 2,
    上: 中心按钮.中心Y - 中心按钮.高 / 2,
    宽: 中心按钮.宽,
    高: 中心按钮.高,
  };
}

/** 顶栏：模式标题 / 暂停 + 等级·分数·消行统计条。 */
function 绘制顶栏(上下文: 绘图上下文, 输入: 对局绘制输入, 色: 界面色, 部分: 绘制部分): void {
  const { 环境, 图形, 布局 } = 上下文;
  if (部分 === "静态") {
    const 标题样式 = 读取对局文字样式("顶栏标题", { 字号: 布局.标题.字号 });
    const 标题尺寸 = 测量样式文字(环境, 标题样式, 输入.模式名);
    const 徽章宽 = Math.min(布局.视口宽 - 160, Math.max(112, 标题尺寸.宽 + 28));
    if (是立体风格())
      绘制立体标题徽章(图形, 布局.标题.中心X, 布局.标题.中心Y, 徽章宽, 立体规范.界面.徽章高);
    else {
      绘制玻璃面板基底(图形, 布局.标题.中心X - 徽章宽 / 2, 布局.标题.中心Y - 21, 徽章宽, 42, {
        圆角: 8,
        填色: 色.面板,
        透明度: 0.98,
        边色: 色.强调,
        边透明度: 0.75,
        高光: true,
      });
      图形.fillStyle(色.强调, 0.8).fillRect(布局.标题.中心X - 18, 布局.标题.中心Y + 19, 36, 2);
    }
    绘制样式文字(环境, 标题样式, 输入.模式名, 布局.标题.中心X, 布局.标题.中心Y, "中中");

    绘制对局仪表(环境.画笔, 读取仪表输入(输入), "静态");
    return;
  }
  // 动态：暂停按钮的标签随阶段变化；三列数值随分数/等级/消行变化。
  // Phaser 暂停按钮在结束态隐藏；暂停态标签变「继续」。
  if (输入.视图.状态.阶段 !== "结束")
    绘制图标角键(图形, 转矩形(布局.暂停按钮), 输入.视图.暂停 ? "继续" : "暂停");
  绘制对局仪表(环境.画笔, 读取仪表输入(输入), "动态");
}

function 读取仪表输入(输入: 对局绘制输入) {
  const 状态 = 输入.视图.状态;
  const 槽位 = 读取组件主题槽位(读取当前主题解析(), "对局仪表", 读取游戏主题目录());
  const 值 = (编号: string) => 槽位.find((项) => 项.槽位.编号 === 编号)?.资源.值;
  return {
    布局: 输入.布局,
    模式: 状态.模式,
    等级: 状态.等级,
    行数: 状态.消行数,
    计分: 输入.计分 ?? { 显示分数: 状态.分数, 目标分数: 状态.分数, 击中: 0, 流光: [] },
    剩余毫秒: 状态.剩余时间,
    有效毫秒: 状态.有效用时,
    省电: 输入.省电 === true,
    表现:
      值("仪表表现") === "像素"
        ? ("像素" as const)
        : 值("仪表表现") === "条带"
          ? ("条带" as const)
          : ("装置" as const),
    纹样: 值("仪表纹样") === "平涂" ? ("平涂" as const) : ("灯条" as const),
  };
}

export function 组装棋盘输入(输入: 对局绘制输入, 部分: 棋盘输入["部分"]): 棋盘输入 {
  const 状态 = 输入.视图.状态;
  const 当前格子 = 读取格子(状态.当前方块);
  const 转场中 = 输入.侧栏转场 && !输入.省电 && 输入.侧栏转场.经过秒 < 0.3;
  return {
    棋盘: 输入.布局.棋盘,
    格子大小: 输入.布局.格子大小,
    偏移X: 输入.偏移X,
    偏移Y: 输入.偏移Y,
    方案: 输入.视图.方块外观,
    格子: 状态.棋盘,
    当前格子,
    当前类型: 状态.当前方块.类型,
    影子: 输入.视图.影子,
    显示网格: 输入.视图.显示网格,
    落点影透明度: 输入.视图.落点影透明度,
    部分,
    网格透明度: 输入.入场秒 != null ? 计算网格入场透明度(输入.入场秒) : undefined,
    跳过当前方块: Boolean(转场中 && 当前格子.every(([, 行]) => 行 < 2)),
  };
}


/** 飞块在现有特效层上绘制，正常出队和暂存交换共用同一真实转场。 */
export function 绘制侧栏转场(环境: 绘制环境, 输入: 对局绘制输入): void {
  绘制计分流光(环境.画笔, 读取仪表输入(输入));
  if (!输入.侧栏转场 || 输入.省电) return;
  const 帧 = 读取侧栏转场帧(输入.侧栏转场, 输入.布局);
  for (const 块 of 帧.飞块)
    绘制居中方块(环境.图形, {
      方案: 输入.视图.方块外观,
      类型: 块.类型,
      区域: { 左: 块.x, 上: 块.y, 宽: 0, 高: 0 },
      格: 块.格,
      透明度: 块.透明度,
      圆角比例: 0.16,
    });
}

/** 桌面操作说明卡：不属于暂存槽，仍由页面按布局条件绘制。 */
function 绘制桌面说明卡(上下文: 绘图上下文, 输入: 对局绘制输入, 色: 界面色): void {
  const { 环境, 图形, 布局 } = 上下文;
  const 定位 = 计算对局附属布局(布局);
  const 说明面板 = 定位.说明.面板;
  if (布局.操作说明卡.底板可见)
    绘制霓虹玻璃(图形, 说明面板.左, 说明面板.上, 说明面板.宽, 说明面板.高, {
      填色: 色.面板,
      透明度: 0.98,
      高光: false,
    });
  if (!布局.操作说明卡.可见) return;
  const 说明 = 定位.说明;
  绘制样式文字(环境, 读取对局文字样式("说明标题"), 输入.文案.操作标题, 说明.标题.x, 说明.标题.y);
  [
    输入.文案.操作移动,
    输入.文案.操作旋转,
    输入.文案.操作半转,
    输入.文案.操作软降,
    输入.文案.操作硬降,
    输入.文案.操作暂停,
  ].forEach((行, 索引) => {
    const 点 = 说明.行[索引];
    if (点) 绘制样式文字(环境, 读取对局文字样式("说明正文"), 行, 点.x, 点.y);
  });
  绘制样式文字(
    环境,
    读取对局文字样式("说明提示"),
    输入.文案.快速移动提示,
    说明.提示.x,
    说明.提示.y,
  );
}

/** 暂停时状态行（Phaser 状态文字：按 P 或 Esc 继续 + 主面板底衬）。 */
function 绘制状态文字(上下文: 绘图上下文, 输入: 对局绘制输入, 色: 界面色): void {
  const { 环境, 布局 } = 上下文;
  if (!输入.提示.暂停) return;
  // 状态行画在暂停遮罩之下：用压暗后的颜色重画，等价 Phaser「先文字、后遮罩」的像素结果。
  const 基础样式 = 读取对局文字样式("状态文字");
  const 样式 = {
    ...基础样式,
    颜色: 遮罩压暗(解析颜色数值(基础样式.颜色)),
    ...(基础样式.描边
      ? { 描边: { ...基础样式.描边, 颜色: 遮罩压暗(解析颜色数值(基础样式.描边.颜色)) } }
      : {}),
  };
  const 尺寸 = 测量样式文字(环境, 样式, "按 P 或 Esc 继续");
  // Phaser 状态文字高度 = 字号 + 描边（不自带行高），底衬按它外扩 14/6。
  const 底衬宽 = 尺寸.宽 + 28;
  const 底衬高 = 样式.字号 + 1 + 12;
  const 中心X = 布局.状态文字.中心X;
  const 上 = 布局.状态文字.下;
  const 左 = 中心X - 底衬宽 / 2;
  const 顶 = 上 - 底衬高 / 2;
  if (是像素风格()) {
    绘制像素面板(上下文.图形, 左, 顶, 底衬宽, 底衬高, 像素规范.色.暗, 像素规范.色.墨);
  } else {
    添加矩形(环境, { 左, 上: 顶, 宽: 底衬宽, 高: 底衬高 }, 色.面板, 0.95);
    上下文.图形.lineStyle(1, 色.分组线, 0.35).strokeRoundedRect(左, 顶, 底衬宽, 底衬高, 10);
  }
  绘制样式文字(环境, 样式, "按 P 或 Esc 继续", 中心X, 上, "中中");
}

/** 暂停层：遮罩 + 玻璃面板 + 强调条 + 标题/说明 + 4 个按钮（框架 界面暂停菜单 同参数）。 */
function 绘制暂停层(上下文: 绘图上下文, 色: 界面色): void {
  const { 环境, 图形, 布局 } = 上下文;
  const 面板 = 布局.暂停面板;
  const 比例 = 面板.比例;
  const 宽 = 面板.宽 * 比例;
  const 高 = 面板.高 * 比例;
  const 左 = 面板.中心X - 宽 / 2;
  const 上 = 面板.中心Y - 高 / 2;
  添加矩形(环境, { 左: 0, 上: 0, 宽: 布局.视口宽, 高: 布局.视口高 }, 色.遮罩, 色.遮罩透明度);
  绘制玻璃面板基底(图形, 左, 上, 宽, 高, {
    圆角: 24,
    填色: 色.面板,
    透明度: 0.98,
    边色: 色.面板描边,
    边透明度: 0.9,
    强调色: 色.强调,
    高光: true,
  });
  // 顶部强调条（框架 界面暂停菜单.布局 的强调条几何）。
  添加矩形(环境, { 左: 面板.中心X - 60, 上: 上 + 2, 宽: 120, 高: 4 }, 色.强调, 0.85);
  绘制样式文字(环境, 读取对局文字样式("暂停标题"), "已暂停", 面板.中心X, 上 + 54 - 2, "中中");
  绘制样式文字(环境, 读取对局文字样式("暂停说明"), "当前进度已保留", 面板.中心X, 上 + 96, "中中");
  for (const 按钮 of 面板.按钮) {
    const 视觉 = 读取暂停按钮视觉(按钮.已选);
    绘制按钮视觉(上下文, 按钮.矩形, 按钮.标签, 视觉, 读取按钮标签样式(视觉.字号, 视觉.文字色));
  }
}

/** 暂停时场景层提示（Phaser 在结算几何位置画「已暂停」）：必须画在遮罩之前的内容层。 */
export function 绘制暂停提示文字(环境: 绘制环境, 布局: 对局布局数据): void {
  // 暂停标题保留原位置，不再跟随独立的结算台重排。
  const 比例 = Math.min(1, (布局.视口宽 - 28) / 380, (布局.视口高 - 28) / 400);
  绘制样式文字(
    环境,
    读取对局文字样式("提示标题"),
    "已暂停",
    布局.视口宽 / 2,
    (布局.视口高 - 400 * 比例) / 2 + 82 * 比例,
    "中中",
  );
}

/** 操作盘托盘画在静态层；键面和说明画在动态层，按下才能立刻变亮。 */
function 绘制操作区(
  上下文: 绘图上下文,
  部分: 绘制部分,
  按下名称: readonly string[],
  暂存禁用 = false,
): void {
  const { 布局 } = 上下文;
  if (!布局.操作区.显示) return;
  if (部分 === "静态") {
    绘制操作盘托盘(上下文.图形, 布局.操作区.键);
    return;
  }
  for (const 键 of 布局.操作区.键) {
    const 按下 = 按下名称.includes(键.名称);
    const 禁用 = 键.名称 === "暂存操作" && 暂存禁用;
    上下文.图形.save().setAlpha((上下文.入场透明度 ?? 1) * (禁用 ? 0.42 : 1));
    绘制操作键(上下文.图形, 键, 按下);
    上下文.图形.restore();
  }
}

/** 提示层：技巧/成就/目标达成（底衬沿用原实现，文字样式走共享配方）。 */
function 绘制提示层(上下文: 绘图上下文, 输入: 对局绘制输入, 色: 界面色): void {
  const { 环境, 布局 } = 上下文;
  const 中心X = 布局.提示文字.中心X;
  const 中心Y = 布局.提示文字.中心Y;
  if (输入.提示.技巧 && 输入.提示.技巧.比例 > 0) {
    const 行列表 = 输入.提示.技巧.文本.split("\n");
    const 样式 = 读取对局文字样式("说明正文", { 字号: 18, 颜色: 色.强调 });
    const 行高 = 测量样式文字(环境, 样式, "字").高;
    const 上 = 中心Y - 26 - (1 - 输入.提示.技巧.比例) * 20;
    const 宽 = Math.max(...行列表.map((行) => 测量样式文字(环境, 样式, 行).宽)) + 24;
    const 高 = 行列表.length * 行高 + 12;
    添加矩形(环境, { 左: 中心X - 宽 / 2, 上: 上 - 6, 宽, 高 }, 色.遮罩, 输入.提示.技巧.比例 * 0.7);
    for (const [序号, 行] of 行列表.entries())
      绘制样式文字(
        环境,
        { ...样式, 颜色: 序号 === 0 ? 色.强调 : 色.主字 },
        行,
        中心X,
        上 + 序号 * 行高,
        "中上",
        输入.提示.技巧.比例,
      );
  }
  if (输入.提示.成就 && 输入.提示.成就.比例 > 0) {
    const 文本 = 输入.提示.成就.文本;
    const 样式 = 读取对局文字样式("说明正文", { 颜色: 色.强调 });
    const 宽 = 测量样式文字(环境, 样式, 文本).宽 + 20;
    添加矩形(环境, { 左: 中心X - 宽 / 2, 上: 178, 宽, 高: 22 }, 色.面板, 输入.提示.成就.比例 * 0.9);
    绘制样式文字(环境, 样式, 文本, 中心X, 182, "中上", 输入.提示.成就.比例);
  }
  if (输入.提示.目标 !== null && 输入.提示.目标 > 0) {
    const 脉冲 = 0.6 + 0.4 * Math.sin(输入.提示.目标 * Math.PI * 8);
    const 样式 = 读取对局文字样式("说明标题", {
      字号: 布局.目标提示.字号,
      颜色: 色.强调,
    });
    绘制样式文字(
      环境,
      样式,
      "目标达成",
      布局.目标提示.中心X,
      布局.目标提示.中心Y,
      "中中",
      Math.min(1, 输入.提示.目标 * 1.4) * 脉冲,
    );
  }
}

/** 入场只改变现有分组的绘制姿态；归位后直接走正式绘制，保留像素坐标。 */
function 绘制入场分组(
  环境: 绘制环境,
  输入: 对局绘制输入,
  组: 入场分组,
  绘制: (上下文: 绘图上下文) => void,
): void {
  const 姿态 = 输入.入场秒 == null ? null : 计算分组入场姿态(输入.入场秒, 组);
  if (!姿态 || 姿态.完成) {
    绘制({ 环境, 图形: 环境.图形, 布局: 输入.布局 });
    return;
  }
  const 原 = { 左: 0, 上: 0, 宽: 输入.布局.视口宽, 高: 输入.布局.视口高 };
  const 当前高 = 原.高 * 姿态.缩放Y;
  绘制流转块(
    环境.画笔,
    {
      身份: 组,
      来源: "出发",
      透明度: 姿态.透明度,
      静止: 原,
      当前: { 左: 姿态.偏移X, 上: (原.高 - 当前高) / 2 + 姿态.偏移Y, 宽: 原.宽, 高: 当前高 },
    },
    (笔) => {
      绘制({
        环境: { ...环境, 图形: 笔.图形, 画笔: 笔 },
        图形: 笔.图形,
        布局: 输入.布局,
        入场透明度: 姿态.透明度,
      });
    },
  );
}

/** 静态内容层：背景之上的对局本体中不随帧变化的部分（顶栏框架/棋盘框与网格/已落格子/面板与标签）。 */
export function 绘制对局静态(环境: 绘制环境, 输入: 对局绘制输入): void {
  const 上下文: 绘图上下文 = { 环境, 图形: 环境.图形, 布局: 输入.布局 };
  const 色 = 读取对局界面色();
  // 遮光压在背景动之上、静态内容之下：静态层重建时一并补画，保证压暗层级不变。
  绘制对局遮光(环境.图形, 输入.布局.视口宽, 输入.布局.视口高, 输入.布局.竖屏);
  if (是立体风格()) 绘制立体机壳(环境.图形, 输入.布局.视口宽, 输入.布局.视口高, 输入.布局.棋盘);
  绘制入场分组(环境, 输入, "顶栏", (组) => 绘制顶栏(组, 输入, 色, "静态"));
  绘制入场分组(环境, 输入, "棋盘", (组) => 绘制棋盘(组.图形, 组装棋盘输入(输入, "静态")));
  绘制入场分组(环境, 输入, "侧栏", (组) => {
    if (!输入.布局.侧栏) 绘制桌面说明卡(组, 输入, 色);
    绘制暂存槽(组.环境.画笔, 组装暂存槽输入(输入, "静态"));
  });
  绘制入场分组(环境, 输入, "操作区", (组) => 绘制操作区(组, "静态", []));
  绘制状态文字(上下文, 输入, 色);
  // 场景层「已暂停」提示在遮罩下（Phaser 同层序），内容层绘制后即被遮罩压暗。
  if (输入.提示.暂停) 绘制暂停提示文字(环境, 输入.布局);
}

/** 动态内容层：活动块/幽灵/暂存与预览方块/计分数字/按钮态；进行中每帧重建。 */
export function 绘制对局动态(环境: 绘制环境, 输入: 对局绘制输入): void {
  const 色 = 读取对局界面色();
  绘制入场分组(环境, 输入, "顶栏", (组) => 绘制顶栏(组, 输入, 色, "动态"));
  绘制入场分组(环境, 输入, "棋盘", (组) => 绘制棋盘(组.图形, 组装棋盘输入(输入, "动态")));
  绘制入场分组(环境, 输入, "侧栏", (组) => 绘制暂存槽(组.环境.画笔, 组装暂存槽输入(输入, "动态")));
  绘制入场分组(环境, 输入, "操作区", (组) =>
    绘制操作区(组, "动态", 输入.按下操作键 ?? [], 输入.视图.状态.本块已暂存),
  );
}

/** 提示层：技巧/成就/目标达成，压在对局内容之上、特效应之下。 */
export function 绘制对局提示(环境: 绘制环境, 输入: 对局绘制输入): void {
  if (输入.提示.暂停) return;
  绘制提示层({ 环境, 图形: 环境.图形, 布局: 输入.布局 }, 输入, 读取对局界面色());
}

/** 覆盖层：暂停遮罩 + 面板（必须画在内容/提示/特效的所有图层之后）。 */
export function 绘制对局覆盖(
  环境: 绘制环境,
  输入: { 布局: 对局布局数据; 提示: { 暂停: boolean } },
): void {
  if (!输入.提示.暂停) return;
  绘制暂停层({ 环境, 图形: 环境.图形, 布局: 输入.布局 }, 读取对局界面色());
}

/** 操作键名称 → 虚拟键（命中注册与输入映射共用）。 */
export function 操作键虚拟键(键: 对局布局操作键): 虚拟键 {
  if (键.名称 === "左移") return "左";
  if (键.名称 === "右移") return "右";
  if (键.名称 === "软降") return "下";
  if (键.名称 === "硬降") return "硬降";
  if (键.名称 === "左转") return "左转";
  if (键.名称 === "右转") return "右转";
  return "暂存";
}

/** 原点、尺寸、控件位置取自 Phaser 的 界面对局设置菜单.布局。 */
export function 计算对局设置布局(宽: number, 高: number) {
  const 键盘说明 = 宽 > 高;
  const 面板高 = 键盘说明 ? 350 : 300;
  const 比例 = Math.min(1, (高 - 24) / 面板高);
  const 面板宽 = Math.min(480, 宽 / 比例 - 28);
  const 中心X = 宽 / 2;
  const 中心Y = 高 / 2;
  const 矩形 = (x: number, y: number, w: number, h: number): 矩形 => ({
    左: 中心X + (x - w / 2) * 比例,
    上: 中心Y + (y - h / 2) * 比例,
    宽: w * 比例,
    高: h * 比例,
  });
  const 面板 = 矩形(0, 0, 面板宽, 面板高);
  const 左 = 面板.左 + 28 * 比例;
  const 右 = 面板.左 + 面板.宽 - 28 * 比例;
  const 行 = (偏移: number) => 面板.上 + 偏移 * 比例;
  return {
    比例,
    中心X,
    中心Y,
    面板,
    滑块: 矩形(0, -面板高 / 2 + 112, Math.max(120, 面板宽 - 64), 32),
    文字: {
      标题: { x: 中心X, y: 行(34) },
      滑块标签: { x: 左, y: 行(76) },
      滑块值: { x: 右, y: 行(76) },
      网格: { x: 左, y: 行(158) },
      提示: { x: 左, y: 行(208) },
    },
    开关: {
      网格: 矩形(面板宽 / 2 - 50, -面板高 / 2 + 158, 52, 30),
      按键说明: 键盘说明 ? 矩形(面板宽 / 2 - 50, -面板高 / 2 + 208, 52, 30) : null,
    },
    按钮: [
      {
        名称: "关闭对局设置",
        文案: "×",
        矩形: 矩形(面板宽 / 2 - 26, -面板高 / 2 + 28, 32, 32),
      },
      {
        名称: "返回暂停菜单",
        文案: "返回暂停菜单",
        矩形: 矩形(0, -面板高 / 2 + (键盘说明 ? 288 : 238), 210, 42),
      },
    ],
  };
}

/** 设置面板的文字：纯计算，不画图（节点构建时也能安全调用）。 */
export function 计算对局设置文字项(
  宽: number,
  高: number,
  设置: 游戏设置,
  文案: 游戏文案,
): 文字项[] {
  const 外观 = 暂停外观();
  const 定位 = 计算对局设置布局(宽, 高);
  const { 比例 } = 定位;
  const 项: 文字项[] = [];
  const 文字 = (
    文: string,
    x: number,
    y: number,
    字号: number,
    锚点: 文字项["锚点"] = "左中",
    强调 = false,
    文字色?: number,
  ) =>
    项.push({
      文案: 文,
      x,
      y,
      锚点,
      样式: {
        字体: 游戏外观.字体.家族,
        字号: 字号 * 比例,
        字重: 强调 ? "粗体" : "常规",
        颜色: 文字色 ?? (强调 ? 外观.标题色 : 外观.说明色),
      },
    });
  const 位置 = 定位.文字;
  文字(文案.对局设置, 位置.标题.x, 位置.标题.y, 24, "中中", true);
  文字(文案.落点影透明度, 位置.滑块标签.x, 位置.滑块标签.y, 14);
  文字(`${设置.落点影透明度}%`, 位置.滑块值.x, 位置.滑块值.y, 14, "右中", true);
  文字(文案.显示网格, 位置.网格.x, 位置.网格.y, 14);
  if (宽 > 高) 文字(文案.显示按键说明, 位置.提示.x, 位置.提示.y, 14);
  for (const 按钮 of 定位.按钮)
    文字(
      按钮.文案 === "返回暂停菜单" ? 文案.返回暂停菜单 : 按钮.文案,
      按钮.矩形.左 + 按钮.矩形.宽 / 2,
      按钮.矩形.上 + 按钮.矩形.高 / 2,
      13,
      "中中",
      true,
      适配文字色(解析颜色数值(外观.按钮面板色)),
    );
  return 项;
}

/** 设置面板图形：遮罩 + 玻璃基底 + 滑块轨 + 开关 + 按钮底板。 */
export function 绘制对局设置图形(
  图形: 图形对象,
  宽: number,
  高: number,
  设置: 游戏设置,
): void {
  const 外观 = 暂停外观();
  const 定位 = 计算对局设置布局(宽, 高);
  const { 比例, 面板 } = 定位;
  const 弹层规格 = 读取控件规格().弹层;
  图形.fillStyle(解析颜色数值(外观.遮罩色), 弹层规格.遮罩透明度).fillRect(0, 0, 宽, 高);
  绘制玻璃面板基底(图形, 面板.左, 面板.上, 面板.宽, 面板.高, {
    圆角: 弹层规格.圆角 * 比例,
    描边宽: 弹层规格.描边宽,
    填色: 解析颜色数值(外观.面板色),
    透明度: 弹层规格.面板透明度,
    边色: 解析颜色数值(外观.边框色),
    边透明度: 弹层规格.描边透明度,
    强调色: 解析颜色数值(外观.强调色),
    高光: false,
  });
  const 轨 = 定位.滑块;
  const 轨Y = 轨.上 + 轨.高 / 2;
  const 轨X = 轨.左 + (轨.宽 * 设置.落点影透明度) / 100;
  图形
    .lineStyle(4 * 比例, 解析颜色数值(外观.按钮面板色))
    .lineBetween(轨.左, 轨Y, 轨.左 + 轨.宽, 轨Y);
  图形.lineStyle(4 * 比例, 解析颜色数值(外观.强调色)).lineBetween(轨.左, 轨Y, 轨X, 轨Y);
  图形.fillStyle(解析颜色数值(外观.强调色)).fillCircle(轨X, 轨Y, 8 * 比例);
  const 画开关 = (区: 矩形, 开: boolean) =>
    绘制开关(
      图形,
      {
        中心X: 区.左 + 区.宽 / 2,
        中心Y: 区.上 + 区.高 / 2,
        宽: 区.宽,
        高: 区.高,
      },
      开,
      解析颜色数值(外观.按钮面板色),
      解析颜色数值(外观.强调色),
    );
  画开关(定位.开关.网格, 设置.显示网格);
  if (定位.开关.按键说明) 画开关(定位.开关.按键说明, 设置.显示按键说明);
  for (const 按钮 of 定位.按钮) {
    const 矩 = 按钮.矩形;
    绘制玻璃按钮底板(图形, 矩.左 + 矩.宽 / 2, 矩.上 + 矩.高 / 2, 矩.宽, 矩.高, {
      填色: 解析颜色数值(外观.按钮面板色),
      边框色: 解析颜色数值(外观.强调色),
      强调色: 解析颜色数值(外观.强调色),
      选中: false,
    });
  }
}

/** 兼容旧入口：画完整设置面板并返回文字项。 */
export function 绘制对局设置(
  图形: 图形对象,
  宽: number,
  高: number,
  设置: 游戏设置,
  文案: 游戏文案,
): 文字项[] {
  绘制对局设置图形(图形, 宽, 高, 设置);
  return 计算对局设置文字项(宽, 高, 设置, 文案);
}

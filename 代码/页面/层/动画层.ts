import type { 图形对象 } from "../../../.gamemaker/依赖/框架/界面/绘制/协议";
import type { 画笔 } from "../../../.gamemaker/依赖/框架/界面/绘制/画笔";
import type { 页面绘制资源 } from "../../../.gamemaker/依赖/框架/界面/页面基类";
import { 模式主题色 } from "../../../资源/主题/配色/模式配色";
import {
  入场参数,
  收束铺满比,
  模式退场时长,
  绘制开局节拍,
  绘制转场遮罩,
} from "../../../资源/视效/过渡/入场演出";
import type { 转场帧 } from "../../../资源/视效/过渡/转场主题/类型";
import type { 转场服务 } from "../../应用/接口/转场";

/**
 * 动画层：转场演出的唯一落点，层序在所有页面层（含货币层、提示层）之上，
 * 所以幕布合拢时连金币角标一起盖住，展开时新画面从幕布底下露出来。
 *
 * 这里只做三件事：推进转场时钟、按当前主题画遮罩与强调、在展开阶段画 Ready/Go。
 * 页面自己不再画任何转场内容（模式卡收束、对局幕布都搬到这里）。
 */

/** 界面层名：动画层在默认层清单之后追加，是最上层。 */
export const 动画层名 = "动画";
/** 动画层里的页面名（与层同名会混淆，页面名单独区分）。 */
export const 动画层页名 = "转场动画";

const 层 = [0] as const;

export interface 动画层上下文 {
  资源: 页面绘制资源;
  画笔: 画笔;
  转场: 转场服务;
}

export class 动画层页面 {
  readonly 登记名称 = 动画层页名;
  private 退订: (() => void) | null = null;

  constructor(private readonly 上下文: 动画层上下文) {
    this.退订 = 上下文.转场.订阅(() => this.标记失效());
  }

  读取窗口策略() {
    return { 遮挡: false, 不透明: false, 暂停下层: false, 独占命中: false };
  }

  进入(): void {
    this.标记失效();
  }

  退出(): void {
    this.标记失效();
  }

  更新(秒: number): void {
    const 前 = this.上下文.转场.读取();
    this.上下文.转场.更新(秒);
    const 后 = this.上下文.转场.读取();
    if (前 !== null || 后 !== null) this.标记失效();
  }

  渲染(): void {
    const 资源 = this.上下文.资源;
    if (!资源.需要重建(动画层页名, 0)) return;
    资源.开始重建(动画层页名, 0);
    资源.设置绘制层(0);
    const 演出 = this.上下文.转场.读取();
    if (演出 === null) return;
    const 图: 图形对象 = this.上下文.画笔.图形;
    const 宽 = 资源.逻辑宽;
    const 高 = 资源.逻辑高;
    const 帧: 转场帧 = {
      宽,
      高,
      模式色: 模式主题色(演出.模式),
      阶段: 演出.阶段,
      进度:
        演出.阶段 === "收束"
          ? // 收束末段提前收满：画法在 94% 处拿到进度 1，最后 6% 保持满屏再切页。
            Math.min(1, 演出.秒 / (模式退场时长 * 收束铺满比))
          : Math.min(1, 演出.秒 / 入场参数.时间.揭示止),
      原卡: 演出.原卡,
    };
    绘制转场遮罩(图, 帧);
    if (演出.阶段 === "展开") 绘制开局节拍(this.上下文.画笔, 宽, 高, 演出.模式, 演出.秒);
  }

  调整尺寸(): void {
    this.标记失效();
  }

  销毁(): void {
    this.退订?.();
    this.退订 = null;
  }

  private 标记失效(): void {
    const 资源 = this.上下文.资源;
    资源.标记失效(动画层页名, [...层], "转场");
    if (资源.请求渲染) 资源.请求渲染();
    else 资源.请求重绘();
  }
}

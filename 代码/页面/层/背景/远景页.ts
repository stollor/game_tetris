import { 页面绘制层 } from "../../../../.gamemaker/依赖/框架/界面/页面基类";
import { 创建注册节点 } from "../../../../.gamemaker/依赖/框架/节点/注册";
import { 在本地空间绘制 } from "../../../../.gamemaker/依赖/框架/节点/渲染";
import { 绘制组件 } from "../../../../.gamemaker/依赖/框架/节点/组件/绘制";
import type { 节点 } from "../../../../.gamemaker/依赖/框架/节点/节点";
import { 读取背景外观 } from "../../../../资源/主题/背景外观";
import { 读取背景动态 } from "../../../../资源/视效/背景/背景开关";
import { 绘制背景静底 } from "../../../../资源/视效/背景/背景绘制";
import type { 页面上下文 } from "../../../应用/接口/上下文";
import { 页面基类 } from "../../游戏页面基类";

/**
 * 背景层 · 远景页：整屏风景的静态底图（在近景页下面一层）。
 * 与近景页一起替代六个页面各自的背景重写；设置里的背景资源/主题/动态/浅底压暗变化时重画。
 */

export const 远景页名 = "背景:远景";

export class 远景页 extends 页面基类 {
  constructor(上下文: 页面上下文) {
    super(上下文, {
      名称: 远景页名,
      层: "背景",
      暂停下层: false,
      独占命中: false,
      节点树: { 绘制带数: 1 },
    });
  }

  进入(): void {
    super.进入();
    this.上下文.登记清理(this.上下文.服务.设置.订阅(() => this.刷新()));
  }

  protected 构建节点树(页面: 节点): void {
    创建注册节点(页面, {
      名称: "背景:远景:风景",
      坐标: { 位置X: 0, 位置Y: 0, 宽: this.逻辑宽, 高: this.逻辑高, 锚点X: 0, 锚点Y: 0 },
      组件: new 绘制组件({ 绘制: (环境) => 在本地空间绘制(环境, () => this.绘制风景()) }),
    });
  }

  /** 设置变化（资源/主题/动态/省电/尺寸适配）只重画风景层。 */
  private 刷新(): void {
    this.标记失效([页面绘制层.内容], "背景标识");
  }

  private 绘制风景(): void {
    const 画笔 = this.上下文.资源.画笔;
    const 设置 = this.上下文.服务.设置.读取();
    绘制背景静底(画笔.图形, {
      宽: this.逻辑宽,
      高: this.逻辑高,
      主题: 设置.背景主题,
      // 动态层单独画主体（近景页），静态底不画主体，避免两层重复。
      静态主体: !读取背景动态(设置),
    });
    // 浅底背景下压一层主题底色，保证浅色文字/控件的可读性。
    if (读取背景外观(设置).文字基调 === "浅底")
      画笔.图形.fillStyle(this.环境.配色.底色, 0.34).fillRect(0, 0, this.逻辑宽, this.逻辑高);
  }

  protected 读取文字快照(): readonly string[] {
    return ["层:背景", "页:远景", `主题:${this.上下文.服务.设置.读取().背景主题}`];
  }
}

import { 页面绘制层 } from "../../../../.gamemaker/依赖/框架/界面/页面基类";
import { 创建注册节点 } from "../../../../.gamemaker/依赖/框架/节点/注册";
import { 在本地空间绘制 } from "../../../../.gamemaker/依赖/框架/节点/渲染";
import { 绘制组件 } from "../../../../.gamemaker/依赖/框架/节点/组件/绘制";
import type { 节点 } from "../../../../.gamemaker/依赖/框架/节点/节点";
import { 读取背景动态 } from "../../../../资源/视效/背景/背景开关";
import { 绘制背景动态, 读取背景动态亮度 } from "../../../../资源/视效/背景/背景绘制";
import type { 页面上下文 } from "../../../应用/接口/上下文";
import { 页面基类 } from "../../游戏页面基类";

/**
 * 背景层 · 近景页：风景的动态层（主体/波光/粒子），在远景页上面一层。
 * 动态重画由启动层的背景调度按画质档位驱动 `刷新背景动态()`；两层都不参与命中。
 */

export const 近景页名 = "背景:近景";

export class 近景页 extends 页面基类 {
  private 时间秒 = 0;

  constructor(上下文: 页面上下文) {
    super(上下文, {
      名称: 近景页名,
      层: "背景",
      暂停下层: false,
      独占命中: false,
      节点树: { 绘制带数: 1 },
    });
  }

  进入(): void {
    super.进入();
    this.上下文.登记清理(this.上下文.服务.设置.订阅(() => this.刷新()));
  }

  protected 构建节点树(页面: 节点): void {
    创建注册节点(页面, {
      名称: "背景:近景:动态",
      坐标: { 位置X: 0, 位置Y: 0, 宽: this.逻辑宽, 高: this.逻辑高, 锚点X: 0, 锚点Y: 0 },
      组件: new 绘制组件({ 绘制: (环境) => 在本地空间绘制(环境, () => this.绘制动态()) }),
    });
  }

  更新(秒: number): void {
    super.更新(秒);
    this.时间秒 += 秒;
  }

  /** 背景调度按画质档位询问：动态开着才需要低频重画。 */
  读取背景动态(): boolean {
    return 读取背景动态(this.上下文.服务.设置.读取());
  }

  /** 背景调度到点：只标脏风景层。 */
  刷新背景动态(): void {
    this.标记失效([页面绘制层.内容], "背景标识");
  }

  private 刷新(): void {
    this.标记失效([页面绘制层.内容], "背景标识");
  }

  private 绘制动态(): void {
    if (!this.读取背景动态()) return;
    const 主题 = this.上下文.服务.设置.读取().主题选择;
    绘制背景动态(this.上下文.资源.画笔.图形, {
      宽: this.逻辑宽,
      高: this.逻辑高,
      主题,
      时间秒: this.时间秒,
      亮度: 读取背景动态亮度(主题),
    });
  }

  protected 读取文字快照(): readonly string[] {
    return ["层:背景", "页:近景", `动态:${this.读取背景动态()}`];
  }
}

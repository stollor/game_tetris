import { 货币层页面, type 货币类型 } from "../../../框架/界面/层/货币层";
import { 生成金币条文字项, 绘制金币条, 计算金币条 } from "../../../预制体/基础/条与数值/金币条配方";
import type { 页面上下文 } from "../../应用/接口/上下文";

/**
 * 货币层 · 货币页：常驻的货币条，位置固定左上 16,12，横向排列。
 * 页面不再画金币条；进对局/结算时清空显示列表，回非对局页面恢复「金币」。
 */

export const 货币页名 = "货币";
export const 默认货币键: readonly string[] = ["金币"];

/** 启动层持有这个实例来发显示列表（发空数组即空层）。 */
export interface 货币页接口 {
  发送(键列表: readonly string[]): void;
  读取显示(): readonly string[];
}

export function 创建货币页(上下文: 页面上下文): 货币层页面 {
  const 画笔 = 上下文.资源.画笔;
  const 金币: 货币类型 = {
    键: "金币",
    名称: "金币",
    读取数值: () => 上下文.服务.金币.读取().金币,
    测量: (数值) => {
      const 布局 = 计算金币条(16, 12, 数值);
      return { 宽: 布局.宽, 高: 布局.高 };
    },
    绘制: (_环境, 矩形, 数值) => {
      const 布局 = 计算金币条(矩形.左, 矩形.上, 数值);
      绘制金币条(画笔.图形, 布局);
      for (const 项 of 生成金币条文字项(布局, 数值)) 画笔.绘制文字(项);
    },
  };
  const 页面 = new 货币层页面(
    {
      资源: 上下文.资源,
      文字: 上下文.文字,
      命中: 上下文.资源.命中,
      读取配色: 上下文.读取配色,
    },
    货币页名,
    {
      货币表: [金币],
      默认: [],
      左: 16,
      上: 12,
      间距: 8,
    },
  );
  return 页面;
}

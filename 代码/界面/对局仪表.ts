import type { 游戏模式 } from "../玩法/再消一行";
import type { 对局布局数据 } from "../页面/布局/对局布局";
import { 模式配置 } from "../项目配置/模式";

/** HUD 布局：由对局布局加模式算出舱位，绘制在 `预制体/对局/对局仪表.ts`。 */
export function 计算对局仪表(布局: 对局布局数据, 模式: 游戏模式) {
  const 栏 = 布局.信息栏;
  const 左 = 栏.中心X - 栏.宽 / 2;
  const 顶 = 栏.中心Y - 栏.高 / 2;
  const 主宽 = 栏.宽 * 0.49;
  const 侧宽 = 栏.宽 * 0.245 - 5;
  const 目标行数 =
    模式 === "冲刺" ? 模式配置.冲刺目标行数 : 模式 === "每日挑战" ? 模式配置.马拉松目标行数 : null;
  const 计时栏: "左" | "右" | null = 模式 === "极限" ? "右" : 模式 === "冲刺" ? "左" : null;
  return {
    主: { 左: 栏.中心X - 主宽 / 2, 上: 顶 - 2, 宽: 主宽, 高: 栏.高 + 7 },
    左: { 左, 上: 顶 + 7, 宽: 侧宽, 高: 栏.高 - 2 },
    右: { 左: 左 + 栏.宽 - 侧宽, 上: 顶 + 7, 宽: 侧宽, 高: 栏.高 - 2 },
    数值底: 顶 + 栏.高 - 5,
    目标行数,
    分数X: 目标行数 ? 左 + 栏.宽 - 侧宽 / 2 : 栏.中心X,
    分数字号: 目标行数 ? 18 : 36,
    分数宽: 目标行数 ? 侧宽 - 12 : 主宽 - 22,
    计时栏,
  };
}

export function 格式化仪表时间(毫秒: number, 精细 = false): string {
  const 秒 = Math.max(0, 毫秒) / 1000;
  const 整秒 = Math.ceil(秒);
  if (精细 && 秒 < 10) return 秒.toFixed(1);
  return `${Math.floor(整秒 / 60)}:${String(整秒 % 60).padStart(2, "0")}`;
}

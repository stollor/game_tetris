import type Phaser from "phaser";
import { 霓虹结算面板 } from "../../组件/霓虹街机/结算面板";
import type { 游戏文案 } from "../语言/类型";

export interface 结算面板回调 {
  重开: () => void;
  菜单: () => void;
}

/** 对局结算面板：标签来自文案，重开/返回行为由场景回调决定。 */
export function 创建对局结算面板(
  场景: Phaser.Scene,
  文案: 游戏文案,
  回调: 结算面板回调,
): 霓虹结算面板 {
  return new 霓虹结算面板(场景, {
    文案: {
      徽标: 文案.本局结算,
      分数: "000000",
      统计标签: [文案.消除行数, 文案.最高等级, 文案.最佳连击],
      统计数值: ["0", "1", "0"],
      重开: 文案.重新开始,
      菜单: 文案.返回主菜单,
    },
    回调,
  });
}

import type Phaser from "phaser";
import type { 界面按钮 } from "../../框架/界面/按钮";
import { 播放游戏音效, 解锁程序音频 } from "../../框架/音频/音频";
import { 创建霓虹按钮, type 霓虹按钮参数 } from "../../组件/霓虹街机/按钮";

export type { 霓虹按钮参数, 霓虹按钮变体 } from "../../组件/霓虹街机/按钮";

/** 菜单按钮：复用霓虹按钮配方，点击前统一播放开始音效，按下时解锁程序音频。 */
export function 创建菜单按钮(场景: Phaser.Scene, 参数: 霓虹按钮参数): 界面按钮 {
  const 原点击 = 参数.点击;
  return 创建霓虹按钮(场景, {
    ...参数,
    点击: () => {
      播放游戏音效("再消一行.开始");
      原点击();
    },
    覆盖: {
      按下: 解锁程序音频,
      ...参数.覆盖,
    },
  });
}

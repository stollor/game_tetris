import type { 游戏文案 } from "../语言/类型";
import { 主题列表, type 主题名, 默认主题 } from "../项目配置/主题目录";

/**
 * 纯享模式的风景口径：游戏只有四套主题，纯享看到的就是主题自己的背景，
 * 所以「风景」=「主题」。这里只做主题列表的顺序/循环/说明，不碰存档与绘制。
 */

/** 纯享可浏览的风景：四套主题按其目录顺序。 */
export function 风景浏览列表(): readonly 主题名[] {
  return 主题列表;
}

/** 当前主题在纯享里的标题与副题：标题是主题名，副题取文案字典里的主题说明。 */
export function 风景说明(主题: 主题名, 文案: 游戏文案): { 标题: string; 副题: string } {
  return { 标题: 主题, 副题: 文案.主题说明[主题] ?? "" };
}

/** 环形切换风景；当前不在列表里时从头开始。 */
export function 相邻风景(当前: 主题名, 方向: -1 | 1, 范围 = 风景浏览列表()): 主题名 {
  if (!范围.length) return 当前;
  const 起 = 范围.indexOf(当前);
  const 索引 = 起 < 0 ? 0 : 起;
  return 范围[(索引 + 方向 + 范围.length) % 范围.length] ?? 当前;
}

/** 纯享入口的默认风景：玩家当前主题。 */
export function 默认风景(当前主题: string): 主题名 {
  return 主题列表.find((项) => 项 === 当前主题) ?? 默认主题;
}

import type Phaser from "phaser";
import { 霓虹操作说明卡 } from "../../组件/霓虹街机/操作说明卡";
import type { 游戏文案 } from "../语言/类型";

/** 对局操作说明卡：标题、六条键位说明与快速移动提示，内容来自文案。 */
export function 创建对局操作说明(
  场景: Phaser.Scene,
  文案: 游戏文案,
  旋转180: boolean,
): 霓虹操作说明卡 {
  const 卡 = new 霓虹操作说明卡(场景, {
    标题: 文案.操作标题,
    说明: [
      文案.操作移动,
      文案.操作旋转,
      文案.操作半转,
      文案.操作软降,
      文案.操作硬降,
      文案.操作暂停,
    ],
    提示: 文案.快速移动提示,
  });
  卡.设置说明(2, 旋转180 ? 文案.操作半转 : 文案.操作半转关闭);
  return 卡;
}

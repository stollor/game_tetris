import 运行配置 from "../../配置/配置表.json";

const 玩法表 = 运行配置.表.find((表) => 表.id === "play-rules");
if (!玩法表) throw new Error("配置表缺少玩法运行值");

const 值 = 玩法表.值;
function 读取数值(键: keyof typeof 值): number {
  const 数值 = 值[键];
  if (typeof 数值 !== "number") throw Error(`玩法配置数值无效：${键}`);
  return 数值;
}


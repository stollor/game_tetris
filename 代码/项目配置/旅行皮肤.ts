import type { 地点名称, 地点皮肤 } from "../框架配置/旅行地点";

export type 外观部位 = "静态背景" | "动态背景" | "界面样式" | "方块外观" | "音效套装" | "音乐";
export const 外观部位列表: readonly 外观部位[] = [
  "静态背景",
  "动态背景",
  "界面样式",
  "方块外观",
  "音效套装",
  "音乐",
];
export function 外观编号(地点: 地点名称, 部位: 外观部位): string {
  return `${地点}.${部位}`;
}
export function 外观原价(地点: 地点皮肤, 部位: 外观部位): number {
  const 基价 = {
    静态背景: 80,
    动态背景: 180,
    界面样式: 140,
    方块外观: 120,
    音效套装: 100,
    音乐: 160,
  };
  return 基价[部位] + 地点.档位 * (部位 === "静态背景" ? 10 : 20);
}


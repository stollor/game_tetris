import { 套装折扣, 部位原价 } from "./外观部位";
/**
 * 主题目录：游戏只保留四套完整主题。
 *
 * 极光原野是默认主题、出厂即可用；其余三套用金币在商店购买。
 * 主题的配色、背景、方块、界面表现由 `资源/主题/主题组合.ts` 按同名槽位组合，
 * 这里只维护「有哪些主题、多少钱、默认是谁」，不描述任何视觉参数。
 */
export type 主题名 = "极光原野" | "砖机液晶" | "街机彩砖" | "立体晶格";

export const 主题列表: readonly 主题名[] = ["极光原野", "砖机液晶", "街机彩砖", "立体晶格"];

/** 游戏默认主题：出厂即拥有，不进商店。 */
export const 默认主题: 主题名 = "极光原野";

/** 商店在售主题：除默认主题外的整套主题。 */
export const 可购主题: readonly 主题名[] = 主题列表.filter((项) => 项 !== 默认主题);

/** 整套起价由部位原价与原折扣派生；补齐价由商店定价按实际已购计算。 */
const 整套起价 =
  Math.ceil(
    ((部位原价.动态背景 +
      部位原价.界面样式 +
      部位原价.方块外观 +
      部位原价.音效套装 +
      部位原价.音乐) *
      套装折扣) /
      10,
  ) * 10;
export const 主题价格: Record<主题名, number> = {
  极光原野: 0,
  砖机液晶: 整套起价,
  街机彩砖: 整套起价,
  立体晶格: 整套起价,
};

export function 是主题名(值: unknown): 值 is 主题名 {
  return typeof 值 === "string" && (主题列表 as readonly string[]).includes(值);
}


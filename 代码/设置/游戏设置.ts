function 是对象(值: unknown): 值 is Record<string, unknown> {
  return typeof 值 === "object" && 值 !== null;
}

function 有效透明度(值: unknown): 值 is number {
  return typeof 值 === "number" && Number.isInteger(值) && 值 >= 0 && 值 <= 100;
}

function 读取专属设置(): 再消一行专属设置 {
  try {
    const 独立设置 = localStorage.getItem(专属设置键);
    const 旧设置 = localStorage.getItem("gamemaker:settings");
    const 原文 = 独立设置 ?? 旧设置;
    if (!原文) return { ...默认专属设置 };
    const 内容: unknown = JSON.parse(原文);
    if (!是对象(内容)) return { ...默认专属设置 };
    const 收藏 = new 旅行收藏(localStorage);
    const 拥有地点 = (值: unknown, 部位: 外观部位) => {
      const 地点 = 查找地点(值);
      return 地点 && 收藏.拥有(地点.名称, 部位) ? 地点.名称 : null;
    };
    const 方块 = 解析方块外观(内容.方块外观);
    const 方块地点 = 查找地点(方块.名称);
    const 背景地点 = 拥有地点(内容.背景主题, "静态背景");
    return {
      背景音乐: 内容.背景音乐 === true,
      音乐音量: 有效透明度(内容.音乐音量) ? 内容.音乐音量 : 0,
      旅行样式: 拥有地点(内容.旅行样式, "界面样式"),
      旅行音效: 拥有地点(内容.旅行音效, "音效套装"),
      旅行音乐: 拥有地点(内容.旅行音乐, "音乐"),
      背景动态: 背景地点
        ? 内容.背景动态 !== false && 收藏.拥有(背景地点, "动态背景")
        : 内容.背景动态 !== false,
      省电模式: 内容.省电模式 === "开" || 内容.省电模式 === "关" ? 内容.省电模式 : "自动",
      背景音效音量: 有效透明度(内容.背景音效音量) ? 内容.背景音效音量 : 0,
      显示触屏提示: 内容.显示触屏提示 !== false,
      方块外观: !方块地点 || 收藏.拥有(方块地点.名称, "方块外观") ? 方块.名称 : "极光原野",
      旋转180: typeof 内容.旋转180 === "boolean" ? 内容.旋转180 : 默认专属设置.旋转180,
      落点影透明度: 有效透明度(内容.落点影透明度) ? 内容.落点影透明度 : 默认专属设置.落点影透明度,
      显示网格: typeof 内容.显示网格 === "boolean" ? 内容.显示网格 : 默认专属设置.显示网格,
      显示按键说明:
        typeof 内容.显示按键说明 === "boolean" ? 内容.显示按键说明 : 默认专属设置.显示按键说明,
      屏幕适配:
        内容.屏幕适配 === "手机竖屏" || 内容.屏幕适配 === "电脑横屏"
          ? 内容.屏幕适配
          : 默认专属设置.屏幕适配,
      背景主题:
        背景地点 ??
        (是基础背景(内容.背景主题) && 基础背景已解锁(内容.背景主题, localStorage)
          ? 内容.背景主题
          : 默认专属设置.背景主题),
    };
  } catch {
    return { ...默认专属设置 };
  }
}


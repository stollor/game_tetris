export function 更新游戏设置(变化: Partial<游戏设置>): 游戏设置 {
  const 通用变化: Partial<通用游戏设置> = {};
  if (变化.背景音乐 !== undefined) 通用变化.背景音乐 = 变化.背景音乐;
  if (变化.音乐音量 !== undefined) 通用变化.音乐音量 = 变化.音乐音量;
  if (变化.音效音量 !== undefined) 通用变化.音效音量 = 变化.音效音量;
  if (变化.主题 !== undefined) 通用变化.主题 = 变化.主题;
  if (变化.语言 !== undefined) 通用变化.语言 = 变化.语言;
  if (变化.样式 !== undefined) 通用变化.样式 = 变化.样式;

  const 专属变化: Partial<再消一行专属设置> = {};
  if (变化.背景音乐 !== undefined) 专属变化.背景音乐 = 变化.背景音乐;
  if (有效透明度(变化.音乐音量)) {
    专属变化.音乐音量 = 变化.音乐音量;
    专属变化.背景音乐 = 变化.背景音乐 ?? 变化.音乐音量 > 0;
    通用变化.背景音乐 = 专属变化.背景音乐;
  }
  const 收藏 = new 旅行收藏(localStorage);
  for (const [键, 部位] of [
    ["旅行样式", "界面样式"],
    ["旅行音效", "音效套装"],
    ["旅行音乐", "音乐"],
  ] as const) {
    const 值 = 变化[键];
    const 地点 = 查找地点(值);
    if (值 === null || (地点 && 收藏.拥有(地点.名称, 部位))) 专属变化[键] = 地点?.名称 ?? null;
  }
  if (变化.样式 !== undefined && 变化.旅行样式 === undefined) 专属变化.旅行样式 = null;
  if (变化.背景动态 !== undefined) {
    const 地点 = 查找地点(变化.背景主题 ?? 当前专属设置.背景主题);
    if (!变化.背景动态 || !地点 || 收藏.拥有(地点.名称, "动态背景"))
      专属变化.背景动态 = 变化.背景动态;
  }
  if (变化.省电模式 !== undefined) 专属变化.省电模式 = 变化.省电模式;
  if (有效透明度(变化.背景音效音量)) 专属变化.背景音效音量 = 变化.背景音效音量;
  if (变化.显示触屏提示 !== undefined) {
    专属变化.显示触屏提示 = 变化.显示触屏提示;
    // 与局内「显示按键说明」共用同一显隐意图，避免两处开关各写各的。
    if (变化.显示按键说明 === undefined) 专属变化.显示按键说明 = 变化.显示触屏提示;
  }
  if (变化.方块外观 !== undefined) {
    const 地点 = 查找地点(变化.方块外观);
    if (!地点 || 收藏.拥有(地点.名称, "方块外观"))
      专属变化.方块外观 = 解析方块外观(变化.方块外观).名称;
  }
  if (变化.旋转180 !== undefined) 专属变化.旋转180 = 变化.旋转180;
  if (变化.落点影透明度 !== undefined) 专属变化.落点影透明度 = 变化.落点影透明度;
  if (变化.显示网格 !== undefined) 专属变化.显示网格 = 变化.显示网格;
  if (变化.显示按键说明 !== undefined) {
    专属变化.显示按键说明 = 变化.显示按键说明;
    if (变化.显示触屏提示 === undefined) 专属变化.显示触屏提示 = 变化.显示按键说明;
  }
  if (变化.屏幕适配 !== undefined) 专属变化.屏幕适配 = 变化.屏幕适配;
  if (变化.背景主题 !== undefined) {
    const 地点 = 查找地点(变化.背景主题);
    const 可用 = 地点
      ? 收藏.拥有(地点.名称, "静态背景")
      : !是基础背景(变化.背景主题) || 基础背景已解锁(变化.背景主题, localStorage);
    if (可用) {
      专属变化.背景主题 = 变化.背景主题;
      if (地点 && !收藏.拥有(地点.名称, "动态背景")) 专属变化.背景动态 = false;
    }
  }

  if (Object.keys(通用变化).length > 0) 更新通用设置(通用变化);
  if (Object.keys(专属变化).length > 0) {
    当前专属设置 = { ...当前专属设置, ...专属变化 };
    try {
      localStorage.setItem(专属设置键, JSON.stringify(当前专属设置));
    } catch (错误) {
      console.warn("保存再消一行设置失败，本次会话仍会应用设置。", 错误);
    }
  }

  const 设置 = 获取游戏设置();
  window.dispatchEvent(new CustomEvent<游戏设置>("gamemaker:settings-change", { detail: 设置 }));
  return 设置;
}

export function 穿戴旅行外观(名称: 地点名称, 部位: 外观部位 | "整套"): boolean {
  const 收藏 = new 旅行收藏(localStorage);
  const 部位表: readonly 外观部位[] =
    部位 === "整套" ? ["动态背景", "界面样式", "方块外观", "音效套装", "音乐"] : [部位];
  if (!部位表.every((项) => 收藏.拥有(名称, 项))) return false;
  if (部位 === "整套") {
    更新游戏设置(主题结果转设置(获取游戏设置(), 解析游戏主题(获取游戏设置(), 名称)));
    return true;
  }
  const 变化: Partial<游戏设置> = {};
  for (const 项 of 部位表) {
    if (项 === "动态背景" || 项 === "静态背景") {
      变化.背景主题 = 名称;
      变化.背景动态 = 项 === "动态背景";
    }
    if (项 === "界面样式") {
      变化.旅行样式 = 名称;
      变化.样式 = "夜空鎏金";
    }
    if (项 === "方块外观") 变化.方块外观 = 名称;
    if (项 === "音效套装") 变化.旅行音效 = 名称;
    if (项 === "音乐") 变化.旅行音乐 = 名称;
  }
  更新游戏设置(变化);
  return true;
}

import { 游戏主题表 } from "../../../框架/样式/样式";
import type { 样式选择 } from "../../../框架/设置/设置";
import { type 地点名称, 地点皮肤表 } from "../../框架配置/旅行地点";
import { 游戏外观 } from "../外观/游戏外观";
import { 界面主题, 颜色值 } from "./主题读取";

export const 霓虹界面主题: readonly (样式选择 | 地点名称)[] = [
  ...(Object.keys(游戏主题表) as 样式选择[]),
  ...地点皮肤表.map((项) => 项.名称),
];
let 预览界面样式: 样式选择 | 地点名称 | undefined;

/** 预览整套配色；商店试穿和 GM 组件预览共用，不写入玩家设置。 */
export function 设置预览界面样式(样式?: 样式选择 | 地点名称): void {
  预览界面样式 = 样式;
}

export interface 常规按钮配色 {
  面板: string;
  边框: string;
  文字: string;
}

/**
 * 霓虹街机界面配色入口：把 `代码/主题/配色/主题读取.ts` 的语义主题和
 * `代码/主题/外观/游戏外观.ts` 的方块/画布色整理成语义角色，供各配方和场景统一取色。
 * 表现可整表替换；控件结构与玩法状态不依赖某一套皮。
 */
export interface 霓虹调色板 {
  样式: string;
  背景: number;
  棋盘底: number;
  棋盘描边: number;
  面板底: number;
  面板底字符串: string;
  面板描边: number;
  次级面板底: number;
  分组线: number;
  遮罩: number;
  遮罩透明度: number;
  强调: number;
  强调色: string;
  正文: string;
  标题: string;
  次要文字: string;
  弱化文字: string;
  主要按钮: 常规按钮配色;
  次要按钮: 常规按钮配色;
  普通按钮: 常规按钮配色;
  按钮面板透明度: number;
  按钮边框透明度: number;
  方块: {
    I: number;
    O: number;
    T: number;
    S: number;
    Z: number;
    J: number;
    L: number;
  };
}

export function 读取霓虹调色板(样式?: 样式选择 | 地点名称): 霓虹调色板 {
  const 主题 = 界面主题(样式 ?? 预览界面样式);
  const 按钮 = 主题.按钮;
  return {
    样式: 主题.元信息.名称,
    背景: 颜色值(主题.页面.背景),
    棋盘底: 颜色值(主题.游戏区域.背景),
    棋盘描边: 颜色值(主题.游戏区域.描边),
    面板底: 颜色值(主题.面板.主面板.背景),
    面板底字符串: 主题.面板.主面板.背景,
    面板描边: 颜色值(主题.面板.主面板.描边),
    次级面板底: 颜色值(主题.面板.次级面板.背景),
    分组线: 颜色值(主题.面板.分组线),
    遮罩: 颜色值(主题.面板.遮罩.背景),
    遮罩透明度: 主题.面板.遮罩.透明度,
    强调: 颜色值(主题.文字.强调),
    强调色: 主题.文字.强调,
    正文: 主题.面板.主面板.正文文字,
    标题: 主题.面板.主面板.标题文字,
    次要文字: 主题.文字.次要,
    弱化文字: 主题.文字.弱化,
    主要按钮: {
      面板: 按钮.主要.默认.背景,
      边框: 按钮.主要.默认.描边,
      文字: 按钮.主要.默认.文字,
    },
    次要按钮: {
      面板: 按钮.次要.默认.背景,
      边框: 按钮.次要.默认.描边,
      文字: 按钮.次要.默认.文字,
    },
    普通按钮: {
      面板: 主题.面板.次级面板.背景,
      边框: 主题.面板.次级面板.描边,
      文字: 主题.文字.弱化,
    },
    按钮面板透明度: 游戏外观.按钮.面板透明度,
    按钮边框透明度: 游戏外观.按钮.边框透明度,
    方块: 游戏外观.方块.颜色,
  };
}

/** 游戏默认主题：极光原野。配色、背景和方块外观均为极光原野。 */
export const 默认主题编号 = "极光原野";

const 资源编号 = (槽: string, 值: string | null) => `${槽}.${值 ?? "默认"}`;
const 基础配色列表 = Object.keys(再消一行主题);
const 基础方块列表 = 方块外观方案表.filter((项) => !查找地点(项.名称)).map((项) => 项.名称);
const 关闭动态 = "关闭动态";
const 默认音效 = "默认音效";
const 跟随对局 = "跟随对局";

let 目录: 主题组合目录 | undefined;

/** 只声明职责和真实配置引用；颜色、曲谱、绘制实现仍由原模块提供。 */
export function 读取游戏主题目录(): 主题组合目录 {
  if (目录) return 目录;
  const 资源: 主题资源[] = [];
  function 加入(
    槽: string,
    名称: string,
    值: string | null,
    路径: string,
    导出: string,
    方式: 主题资源["方式"] = "参数",
    配置?: string,
  ) {
    资源.push({
      编号: 资源编号(槽, 值),
      名称,
      槽位: 槽,
      契约: 槽 + ".v1",
      方式,
      值,
      源码: [{ 路径, 导出 }, ...(配置 ? [{ 路径: 配置, 导出: "地点皮肤表" }] : [])],
    });
  }
  for (const 名称 of [...基础配色列表, ...地点皮肤表.map((项) => 项.名称)]) {
    const 旅行 = !!查找地点(名称);
    for (const 槽 of ["界面配色", "控件外观"]) {
      加入(
        槽,
        名称,
        名称,
        `代码/主题/配色/${旅行 ? "旅行配色" : "基础配色"}.ts`,
        旅行 ? "旅行主题表" : "再消一行主题",
        "参数",
        旅行 ? "代码/框架配置/旅行地点.ts" : undefined,
      );
    }
  }
  for (const 名称 of [...基础背景列表, ...地点皮肤表.map((项) => 项.名称)]) {
    const 旅行 = !!查找地点(名称);
    for (const 槽 of ["静态背景", "动态背景"]) {
      加入(
        槽,
        名称,
        名称,
        `代码/视效/背景/${旅行 ? "旅行风景" : "内置主题"}.ts`,
        槽 === "动态背景"
          ? 旅行
            ? "绘制旅行动态"
            : "绘制内置背景动态"
          : 旅行
            ? "绘制旅行风景"
            : "绘制内置背景静底",
        "资源",
        旅行 ? "代码/框架配置/旅行地点.ts" : undefined,
      );
    }
  }
  加入("动态背景", 关闭动态, null, "代码/视效/背景/背景绘制.ts", "绘制背景动态");
  for (const 名称 of 基础方块列表)
    加入("方块外观", 名称, 名称, "代码/主题/外观/方块外观.ts", "方块外观方案表");
  for (const 项 of 地点皮肤表)
    加入(
      "方块外观",
      项.名称,
      项.名称,
      "代码/主题/外观/方块外观.ts",
      "方块外观方案表",
      "参数",
      "代码/框架配置/旅行地点.ts",
    );
  for (const 名称 of [null, ...地点皮肤表.map((项) => 项.名称)]) {
    加入(
      "音效套装",
      名称 ?? "默认操作音效",
      名称,
      名称 ? "代码/框架配置/旅行音效.ts" : "代码/框架配置/音效.ts",
      名称 ? "应用装备音效" : "音效库",
      "资源",
      名称 ? "代码/框架配置/旅行地点.ts" : undefined,
    );
    加入(
      "背景音乐",
      名称 ?? "跟随菜单与对局",
      名称,
      "代码/框架配置/音乐.ts",
      "音乐库",
      "资源",
      名称 ? "代码/框架配置/旅行地点.ts" : undefined,
    );
  }
  加入("视觉特效", "现有消行与落块特效", "默认", "代码/视效/特效/对局特效.ts", "绘制特效", "实现");
  const 槽位默认: Record<string, string> = {
    静态背景: 资源编号("静态背景", 默认设置.背景主题),
    动态背景: 资源编号("动态背景", 默认设置.背景动态 ? 默认设置.背景主题 : null),
    界面配色: 资源编号("界面配色", 默认设置.旅行样式 ?? 默认设置.样式),
    控件外观: 资源编号("控件外观", 默认设置.旅行样式 ?? 默认设置.样式),
    方块外观: 资源编号("方块外观", 默认设置.方块外观),
    音效套装: 资源编号("音效套装", 默认设置.旅行音效),
    背景音乐: 资源编号("背景音乐", 默认设置.旅行音乐),
    视觉特效: "视觉特效.默认",
  };
  const 槽位 = Object.entries(槽位默认).map(([编号, 默认]) => ({
    编号,
    名称: 编号,
    默认,
    契约: 编号 + ".v1",
  }));
  /** 真实资源值保留原编号；未归类外观独立收纳。 */
  function 维度(地点?: string, 待分类 = false): 主题维度[] {
    const 配色项 = 地点
      ? [地点]
      : 待分类
        ? 基础配色列表.filter((项) => 项 !== 默认主题编号)
        : [默认主题编号, ...基础配色列表.filter((项) => 项 !== 默认主题编号)];
    const 背景项 = 地点
      ? [地点]
      : 待分类
        ? 基础背景列表.filter((项) => 项 !== 默认主题编号)
        : [默认主题编号, ...基础背景列表.filter((项) => 项 !== 默认主题编号)];
    const 方块项 = 地点
      ? [地点]
      : 待分类
        ? 基础方块列表.filter((项) => 项 !== 默认主题编号)
        : [默认主题编号, ...基础方块列表.filter((项) => 项 !== 默认主题编号)];
    const 音效项 = 地点 ? [地点, 默认音效] : [默认音效];
    const 音乐项 = 地点 ? [地点, 跟随对局] : [跟随对局];
    return [
      {
        编号: "配色",
        名称: "配色",
        说明: "界面配色与控件外观。",
        槽位: ["界面配色", "控件外观"],
        默认: 配色项[0],
        选项: 配色项.map((名称) => ({
          编号: 名称,
          名称,
          隐藏: !地点 && !待分类 && 名称 !== 默认主题编号,
          说明: 查找地点(名称) ? "旅行主题配色。" : "基础语义配色。",
          覆盖: {
            界面配色: 资源编号("界面配色", 名称),
            控件外观: 资源编号("控件外观", 名称),
          },
          // 配色用语义色卡样品展示真实颜色，不写文字标签。
          展示: { 样品: "game-palette", 状态: { 主题: 名称 } },
        })),
      },
      {
        编号: "背景",
        名称: "背景",
        说明: "静态背景与动态层；动态背景可单独关闭。",
        槽位: ["静态背景", "动态背景"],
        默认: 背景项[0],
        选项: [
          ...背景项.map((名称) => ({
            编号: 名称,
            名称,
            隐藏: !地点 && !待分类 && 名称 !== 默认主题编号,
            说明: "静态风景与对应动态层。",
            覆盖: {
              静态背景: 资源编号("静态背景", 名称),
              动态背景: 资源编号("动态背景", 名称),
            },
            // 背景用正式配方定格一帧，看到的就是真实画面。
            展示: { 样品: "game-background", 状态: { 主题: 名称, 播放: "定格", 时间: "2" } },
          })),
          {
            编号: 关闭动态,
            名称: 关闭动态,
            说明: "只保留静态背景，不再绘制动态层。",
            覆盖: { 动态背景: 资源编号("动态背景", null) },
            展示: {
              样品: "game-background",
              状态: { 主题: 背景项[0], 动态: "否", 播放: "定格", 时间: "0" },
            },
          },
        ],
      },
      {
        编号: "方块",
        名称: "方块外观",
        说明: "七种方块的材质与配色。",
        槽位: ["方块外观"],
        默认: 方块项[0],
        选项: 方块项.map((名称) => ({
          编号: 名称,
          名称,
          隐藏: !地点 && !待分类 && 名称 !== 默认主题编号,
          说明: 解析方块外观(名称).说明,
          覆盖: { 方块外观: 资源编号("方块外观", 名称) },
          // 方块外观用真实方块单元展示材质差异。
          展示: { 样品: "block-shape", 状态: { 外观: 名称, 形状: "T" } },
        })),
      },
      {
        编号: "音效",
        名称: "音效套装",
        说明: "操作与消行音效。",
        槽位: ["音效套装"],
        默认: 音效项[0],
        选项: 音效项.map((名称) => ({
          编号: 名称,
          名称: 名称 === 默认音效 ? "默认操作音效" : 名称,
          说明: 名称 === 默认音效 ? "随界面主题的基础音效。" : "旅行地点音效。",
          覆盖: { 音效套装: 资源编号("音效套装", 名称 === 默认音效 ? null : 名称) },
          // 音效没有画面，给出真实音效条目用于试听，界面显示波形卡。
          试听: {
            类型: "音效",
            id: 名称 === 默认音效 ? "再消一行.消行" : `旅行.${名称}.消行`,
            条目: 音效库
              .filter((项) =>
                名称 === 默认音效
                  ? 项.id.startsWith("再消一行.") ||
                    (!地点 && !待分类 && 项.id === `旅行.氛围.${默认主题编号}`)
                  : 项.id.startsWith(`旅行.${名称}.`) || 项.id === `旅行.氛围.${名称}`,
              )
              .map((项) => 项.id),
          },
        })),
      },
      {
        编号: "音乐",
        名称: "背景音乐",
        说明: "菜单与对局共用的曲谱。",
        槽位: ["背景音乐"],
        默认: 音乐项[0],
        选项: 音乐项.map((名称) => ({
          编号: 名称,
          名称: 名称 === 跟随对局 ? "跟随菜单与对局" : 名称,
          说明: 名称 === 跟随对局 ? "随界面主题的基础音乐。" : "旅行地点曲谱。",
          覆盖: { 背景音乐: 资源编号("背景音乐", 名称 === 跟随对局 ? null : 名称) },
          // 音乐用真实曲目试听，界面显示波形卡。
          试听: {
            类型: "音乐",
            id: 名称 === 跟随对局 ? "再消一行.菜单" : `旅行.${名称}`,
            条目: 音乐库
              .filter((项) =>
                名称 === 跟随对局 ? 项.id.startsWith("再消一行.") : 项.id === `旅行.${名称}`,
              )
              .map((项) => 项.id),
          },
        })),
      },
      {
        编号: "特效",
        名称: "视觉特效",
        说明: "消行、落块与结算的绘制实现。",
        槽位: ["视觉特效"],
        默认: "现有特效",
        选项: [
          {
            编号: "现有特效",
            名称: "现有消行与落块特效",
            说明: "当前正式对局使用的特效实现。",
            覆盖: { 视觉特效: "视觉特效.默认" },
            // 特效直接用正式消行光带的定格帧展示真实效果。
            展示: { 样品: "line-clear", 状态: { 行数: "2" } },
            特效样品: ["line-clear", "line-trail", "lock-flash", "four-line-celebrate"],
          },
        ],
      },
    ];
  }
  const 主题: 主题定义[] = [
    {
      编号: 默认主题编号,
      名称: 默认主题编号,
      说明: "游戏默认主题：极光原野配色、背景和方块外观。",
      默认: true,
      维度: 维度(),
    },
    {
      编号: "待分类",
      名称: "待分类",
      说明: "尚未归入完整主题的外观。",
      维度: 维度(undefined, true),
    },
    ...地点皮肤表.map((项) => ({
      编号: 项.名称,
      名称: 项.名称,
      说明: 项.副题,
      维度: 维度(项.名称),
    })),
  ];
  目录 = { 槽位, 资源, 主题 };
  return 目录;
}

/** 旧设置就是已保存的局部选择；不新增存档字段，不改变购买/解锁校验。 */
export function 解析游戏主题(设置: 游戏设置, 选择?: string): 主题解析结果 {
  const 样式 = 设置.旅行样式 ?? 设置.样式;
  const 局部: Record<string, string> = 选择
    ? {}
    : {
        界面配色: 资源编号("界面配色", 样式),
        控件外观: 资源编号("控件外观", 样式),
        静态背景: 资源编号("静态背景", 设置.背景主题),
        动态背景: 资源编号("动态背景", 设置.背景动态 ? 设置.背景主题 : null),
        方块外观: 资源编号("方块外观", 设置.方块外观),
        音效套装: 资源编号("音效套装", 设置.旅行音效),
        背景音乐: 资源编号("背景音乐", 设置.旅行音乐),
      };
  const 目录 = 读取游戏主题目录();
  const 覆盖 = Object.fromEntries(
    Object.entries(局部).filter(
      ([槽, 编号]) => 目录.槽位.find((项) => 项.编号 === 槽)?.默认 !== 编号,
    ),
  );
  return 解析主题组合(目录, 选择, 覆盖);
}

export function 主题结果转设置(设置: 游戏设置, 结果: 主题解析结果): 游戏设置 {
  const 值 = (槽: string) => 结果.槽位.find((项) => 项.槽位.编号 === 槽)?.资源.值;
  const 样式 = 值("界面配色");
  const 地点 = 查找地点(样式);
  const 基础样式 =
    样式 === "夜空鎏金" || 样式 === "暖纸古典" || 样式 === "极光原野" ? 样式 : "夜空鎏金";
  const 背景 = 值("静态背景");
  const 背景名 = 基础背景列表.find((项) => 项 === 背景) ?? 查找地点(背景)?.名称;
  if (!背景名) throw new Error("主题静态背景未接入");
  return {
    ...设置,
    样式: 地点 ? "夜空鎏金" : 基础样式,
    旅行样式: 地点?.名称 ?? null,
    背景主题: 背景名,
    背景动态: 值("动态背景") !== null,
    方块外观: 解析方块外观(值("方块外观")).名称,
    旅行音效: 查找地点(值("音效套装"))?.名称 ?? null,
    旅行音乐: 查找地点(值("背景音乐"))?.名称 ?? null,
  };
}

/** 把「主题 + 维度选项」写回旧设置字段，供玩家穿戴入口复用。 */
export function 应用主题选择(设置: 游戏设置, 选择: string): 游戏设置 {
  return 主题结果转设置(设置, 解析游戏主题(设置, 选择));
}
/** 当前设置所属主题的完整选择串；只写出偏离主题默认的维度，串更短也更易读。 */
export function 读取当前主题选择(设置: 游戏设置): string {
  const 结果 = 解析游戏主题(设置);
  const 主题 = 读取游戏主题目录().主题.find((项) => 项.编号 === 结果.主题);
  const 偏离 = Object.fromEntries(
    Object.entries(结果.选项).filter(
      ([维度, 值]) => 主题?.维度.find((项) => 项.编号 === 维度)?.默认 !== 值,
    ),
  );
  return 生成主题选择(结果.主题 ?? 默认主题编号, 偏离);
}

let 上次键 = "";
let 上次结果: 主题解析结果 | undefined;
/** 页面与音频频繁读取相同设置；只缓存解析，不缓存绘制对象或声音节点。 */
export function 读取有效游戏主题(设置: 游戏设置): 主题解析结果 {
  const 键 = JSON.stringify([
    设置.样式,
    设置.旅行样式,
    设置.背景主题,
    设置.背景动态,
    设置.方块外观,
    设置.旅行音效,
    设置.旅行音乐,
  ]);
  if (键 !== 上次键 || !上次结果) {
    上次结果 = 解析游戏主题(设置);
    上次键 = 键;
  }
  return 上次结果;
}

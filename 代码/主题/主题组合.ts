import {
  type 主题组合目录,
  type 主题解析结果,
  type 主题资源,
  解析主题组合,
} from "../../框架/设置/主题组合";
import { 基础背景列表 } from "../存档/基础背景解锁";
import { 地点皮肤表, 查找地点 } from "../框架配置/旅行地点";
import { type 游戏设置, 默认设置 } from "../设置/游戏设置";
import { 方块外观方案表, 解析方块外观 } from "./外观/方块外观";
import { 再消一行主题 } from "./配色/基础配色";

let 目录: 主题组合目录 | undefined;
const 资源编号 = (槽: string, 值: string | null) => `${槽}.${值 ?? "默认"}`;

/** 只声明职责和真实配置引用；颜色、曲谱、绘制实现仍由原模块提供。 */
export function 读取游戏主题目录(): 主题组合目录 {
  if (目录) return 目录;
  const 资源: 主题资源[] = [];
  function 加入(
    槽: string,
    名称: string,
    值: string | null,
    路径: string,
    导出: string,
    方式: 主题资源["方式"] = "参数",
    配置?: string,
  ) {
    资源.push({
      编号: 资源编号(槽, 值),
      名称,
      槽位: 槽,
      契约: 槽 + ".v1",
      方式,
      值,
      源码: [{ 路径, 导出 }, ...(配置 ? [{ 路径: 配置, 导出: "地点皮肤表" }] : [])],
    });
  }
  for (const 名称 of [...Object.keys(再消一行主题), ...地点皮肤表.map((项) => 项.名称)]) {
    for (const 槽 of ["界面配色", "控件外观"]) {
      const 旅行 = !!查找地点(名称);
      加入(
        槽,
        名称,
        名称,
        `代码/主题/配色/${旅行 ? "旅行配色" : "基础配色"}.ts`,
        旅行 ? "旅行主题表" : "再消一行主题",
        "参数",
        旅行 ? "代码/框架配置/旅行地点.ts" : undefined,
      );
    }
  }
  for (const 名称 of [...基础背景列表, ...地点皮肤表.map((项) => 项.名称)]) {
    const 旅行 = !!查找地点(名称);
    for (const 槽 of ["静态背景", "动态背景"]) {
      const 动态 = 槽 === "动态背景";
      加入(
        槽,
        名称,
        名称,
        `代码/视效/背景/${旅行 ? "旅行风景" : "内置主题"}.ts`,
        旅行
          ? 动态
            ? "绘制旅行动态"
            : "绘制旅行风景"
          : 动态
            ? "绘制内置背景动态"
            : "绘制内置背景静底",
        "资源",
        旅行 ? "代码/框架配置/旅行地点.ts" : undefined,
      );
    }
  }
  加入("动态背景", "关闭动态", null, "代码/视效/背景/背景绘制.ts", "绘制背景动态");
  for (const 项 of 方块外观方案表)
    加入(
      "方块外观",
      项.名称,
      项.名称,
      "代码/主题/外观/方块外观.ts",
      "方块外观方案表",
      "参数",
      查找地点(项.名称) ? "代码/框架配置/旅行地点.ts" : undefined,
    );
  for (const 名称 of [null, ...地点皮肤表.map((项) => 项.名称)]) {
    加入(
      "音效套装",
      名称 ?? "默认操作音效",
      名称,
      名称 ? "代码/框架配置/旅行音效.ts" : "代码/框架配置/音效.ts",
      名称 ? "应用装备音效" : "音效库",
      "资源",
      名称 ? "代码/框架配置/旅行地点.ts" : undefined,
    );
    加入(
      "背景音乐",
      名称 ?? "跟随菜单与对局",
      名称,
      "代码/框架配置/音乐.ts",
      "音乐库",
      "资源",
      名称 ? "代码/框架配置/旅行地点.ts" : undefined,
    );
  }
  加入("视觉特效", "现有消行与落块特效", "默认", "代码/视效/特效/对局特效.ts", "绘制特效", "实现");
  const 默认: Record<string, string> = {
    静态背景: 资源编号("静态背景", 默认设置.背景主题),
    动态背景: 资源编号("动态背景", 默认设置.背景动态 ? 默认设置.背景主题 : null),
    界面配色: 资源编号("界面配色", 默认设置.旅行样式 ?? 默认设置.样式),
    控件外观: 资源编号("控件外观", 默认设置.旅行样式 ?? 默认设置.样式),
    方块外观: 资源编号("方块外观", 默认设置.方块外观),
    音效套装: 资源编号("音效套装", 默认设置.旅行音效),
    背景音乐: 资源编号("背景音乐", 默认设置.旅行音乐),
    视觉特效: "视觉特效.默认",
  };
  目录 = {
    槽位: Object.entries(默认).map(([编号, 默认]) => ({
      编号,
      名称: 编号,
      默认,
      契约: 编号 + ".v1",
    })),
    资源,
    方案: [
      ...地点皮肤表.map((项) => ({
        编号: 项.名称,
        名称: 项.名称,
        说明: 项.副题,
        种类: "完整主题" as const,
        覆盖: Object.fromEntries(
          Object.keys(默认)
            .filter((槽) => 槽 !== "视觉特效")
            .map((槽) => [槽, 资源编号(槽, 项.名称)]),
        ),
      })),
      ...Object.keys(再消一行主题).map((名称) => ({
        编号: "配色." + 名称,
        名称,
        说明: "界面配色与控件参数；背景、方块及音频继承游戏默认。",
        种类: "配色方案" as const,
        覆盖: { 界面配色: 资源编号("界面配色", 名称), 控件外观: 资源编号("控件外观", 名称) },
      })),
      ...基础背景列表.map((名称) => ({
        编号: "背景." + 名称,
        名称,
        说明: "仅替换静态与动态背景。",
        种类: "背景方案" as const,
        覆盖: { 静态背景: 资源编号("静态背景", 名称), 动态背景: 资源编号("动态背景", 名称) },
      })),
      ...方块外观方案表
        .filter((项) => !查找地点(项.名称))
        .map((项) => ({
          编号: "方块." + 项.名称,
          名称: 项.名称,
          说明: 项.说明,
          种类: "单项外观" as const,
          覆盖: { 方块外观: 资源编号("方块外观", 项.名称) },
        })),
    ],
  };
  return 目录;
}

/** 旧设置就是已保存的局部选择；不新增存档字段，不改变购买/解锁校验。 */
export function 解析游戏主题(设置: 游戏设置, 方案?: string): 主题解析结果 {
  const 样式 = 设置.旅行样式 ?? 设置.样式;
  const 局部: Record<string, string> = 方案
    ? {}
    : {
        界面配色: 资源编号("界面配色", 样式),
        控件外观: 资源编号("控件外观", 样式),
        静态背景: 资源编号("静态背景", 设置.背景主题),
        动态背景: 资源编号("动态背景", 设置.背景动态 ? 设置.背景主题 : null),
        方块外观: 资源编号("方块外观", 设置.方块外观),
        音效套装: 资源编号("音效套装", 设置.旅行音效),
        背景音乐: 资源编号("背景音乐", 设置.旅行音乐),
      };
  const 目录 = 读取游戏主题目录();
  const 覆盖 = Object.fromEntries(
    Object.entries(局部).filter(
      ([槽, 编号]) => 目录.槽位.find((项) => 项.编号 === 槽)?.默认 !== 编号,
    ),
  );
  return 解析主题组合(目录, 方案, 覆盖);
}

export function 主题结果转设置(设置: 游戏设置, 结果: 主题解析结果): 游戏设置 {
  const 值 = (槽: string) => 结果.槽位.find((项) => 项.槽位.编号 === 槽)?.资源.值;
  const 样式 = 值("界面配色");
  const 地点 = 查找地点(样式);
  const 基础样式 =
    样式 === "夜空鎏金" || 样式 === "暖纸古典" || 样式 === "青蓝未来" ? 样式 : "夜空鎏金";
  const 背景 = 值("静态背景");
  const 背景名 = 基础背景列表.find((项) => 项 === 背景) ?? 查找地点(背景)?.名称;
  if (!背景名) throw new Error("主题静态背景未接入");
  return {
    ...设置,
    样式: 地点 ? "夜空鎏金" : 基础样式,
    旅行样式: 地点?.名称 ?? null,
    背景主题: 背景名,
    背景动态: 值("动态背景") !== null,
    方块外观: 解析方块外观(值("方块外观")).名称,
    旅行音效: 查找地点(值("音效套装"))?.名称 ?? null,
    旅行音乐: 查找地点(值("背景音乐"))?.名称 ?? null,
  };
}

let 上次键 = "";
let 上次结果: 主题解析结果 | undefined;
/** 页面与音频频繁读取相同设置；只缓存解析，不缓存绘制对象或声音节点。 */
export function 读取有效游戏主题(设置: 游戏设置): 主题解析结果 {
  const 键 = JSON.stringify([
    设置.样式,
    设置.旅行样式,
    设置.背景主题,
    设置.背景动态,
    设置.方块外观,
    设置.旅行音效,
    设置.旅行音乐,
  ]);
  if (键 !== 上次键 || !上次结果) {
    上次结果 = 解析游戏主题(设置);
    上次键 = 键;
  }
  return 上次结果;
}
export function 应用主题方案(设置: 游戏设置, 方案: string): 游戏设置 {
  return 主题结果转设置(设置, 解析游戏主题(设置, 方案));
}

export function 解析方块外观(值: unknown): 方块外观方案 {
  const 名称 = 值 === "像素街机" ? "砖机液晶" : 值;
  return 方块外观方案表.find((项) => 项.名称 === 名称) ?? 方块外观方案表[0];
}

let 预览方块外观: 方块外观名称 | undefined;
export function 设置预览方块外观(值?: 方块外观名称): void {
  预览方块外观 = 值;
}
export function 读取当前方块外观(游戏选择: 方块外观名称): 方块外观方案 {
  return 解析方块外观(预览方块外观 ?? 游戏选择);
}

import type { 文字样式 } from "../../../框架/界面/绘制/协议";
import { 游戏外观 } from "../外观/游戏外观";
import { 读取霓虹调色板 } from "../配色/调色板";

/**
 * 霓虹街机文字角色表：游戏文字与 Three 文字服务共用同一套 token。
 * 字体一律取 `代码/主题/外观/游戏外观.ts`，颜色优先取 `代码/主题/配色/主题读取.ts` 语义色；
 * 标题/金币这类在旧的开始菜单与金币条里写死的字面值集中到这里，保证两版像素一致，
 * 后续要主题化时只改这一处。
 */

export type 霓虹文字角色 =
  | "主标题"
  | "主标题紧凑"
  | "主标题微"
  | "英文主标题"
  | "英文主标题紧凑"
  | "英文主标题微"
  | "选择模式标题"
  | "金币"
  | "按钮"
  | "角钮"
  | "模式卡标题"
  | "模式卡细节"
  | "模式卡说明"
  | "模式卡纪录"
  | "风景标题"
  | "风景说明"
  | "正文"
  | "次要"
  | "弱化"
  | "数值"
  | "徽标";

/** 旧开始菜单的标题字面色与描边；与 `代码/场景/主界面/开始菜单.ts` 重构前一致。 */
const 标题色 = "#fff8e7";
const 标题描边色 = "#16303a";
/** 金币/选择模式标题/旅行图标共用的暖金色。 */
const 暖金色 = "#ffe7a8";

export function 读取霓虹文字样式(角色: 霓虹文字角色): 文字样式 {
  const 字体 = 游戏外观.字体.家族;
  const 调色板 = 读取霓虹调色板();
  switch (角色) {
    case "主标题":
      return { 字体, 字号: 40, 字重: "粗体", 颜色: 标题色, 描边: { 颜色: 标题描边色, 粗细: 5 } };
    case "主标题紧凑":
      return { 字体, 字号: 32, 字重: "粗体", 颜色: 标题色, 描边: { 颜色: 标题描边色, 粗细: 5 } };
    case "英文主标题":
      return { 字体, 字号: 26, 字重: "粗体", 颜色: 标题色, 描边: { 颜色: 标题描边色, 粗细: 4 } };
    case "英文主标题紧凑":
      return { 字体, 字号: 22, 字重: "粗体", 颜色: 标题色, 描边: { 颜色: 标题描边色, 粗细: 4 } };
    case "主标题微":
      return { 字体, 字号: 13, 字重: "粗体", 颜色: 标题色, 描边: { 颜色: 标题描边色, 粗细: 2 } };
    case "英文主标题微":
      return { 字体, 字号: 12, 字重: "粗体", 颜色: 标题色, 描边: { 颜色: 标题描边色, 粗细: 2 } };
    case "选择模式标题":
      return { 字体, 字号: 15, 颜色: 暖金色, 描边: { 颜色: 标题描边色, 粗细: 4 } };
    case "金币":
      return { 字体, 字号: 15, 字重: "粗体", 颜色: 暖金色, 描边: { 颜色: 标题描边色, 粗细: 3 } };
    case "按钮":
      // 按钮文字色由按钮配方按底色对比计算后覆盖；这里给默认亮色兜底。
      return { 字体, 字号: 游戏外观.字体.按钮, 颜色: 标题色, 对齐: "中" };
    case "角钮":
      return { 字体, 字号: 12, 颜色: 标题色, 对齐: "中" };
    case "模式卡标题":
      return { 字体, 字号: 24, 字重: "粗体", 颜色: 调色板.正文, 对齐: "左" };
    case "模式卡细节":
      return { 字体, 字号: 14, 颜色: 调色板.强调色, 对齐: "左" };
    case "模式卡说明":
      return { 字体, 字号: 14, 颜色: 调色板.正文, 对齐: "左" };
    case "模式卡纪录":
      return { 字体, 字号: 14, 颜色: 调色板.正文, 对齐: "左" };
    case "风景标题":
      return { 字体, 字号: 28, 字重: "粗体", 颜色: 标题色, 描边: { 颜色: 标题描边色, 粗细: 4 } };
    case "风景说明":
      return { 字体, 字号: 13, 颜色: "#fff4d9", 描边: { 颜色: 标题描边色, 粗细: 3 } };
    case "正文":
      return { 字体, 字号: 游戏外观.字体.正文, 颜色: 调色板.正文 };
    case "次要":
      return { 字体, 字号: 游戏外观.字体.辅助, 颜色: 调色板.次要文字 };
    case "弱化":
      return { 字体, 字号: 游戏外观.字体.辅助, 颜色: 调色板.弱化文字 };
    case "数值":
      return { 字体, 字号: 18, 字重: "粗体", 颜色: 调色板.正文 };
    case "徽标":
      return { 字体, 字号: 12, 字重: "粗体", 颜色: 调色板.强调色 };
  }
}

/** 在角色 token 上覆盖个别差异（字号随布局缩放、强调色随模式切换等）。 */
export function 派生霓虹文字样式(角色: 霓虹文字角色, 覆盖?: Partial<文字样式>): 文字样式 {
  const 基础 = 读取霓虹文字样式(角色);
  return 覆盖 ? { ...基础, ...覆盖 } : 基础;
}

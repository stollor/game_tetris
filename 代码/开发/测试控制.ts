import type Phaser from "phaser";
import type { 游戏测试控制配置 } from "../../框架/开发/测试控制";
import { 打开覆盖页面 } from "../../框架/页面切换";
import { 执行收藏操作, 旅行收藏 } from "../存档/旅行收藏";

export function 创建再消一行测试控制(游戏: Phaser.Game): 游戏测试控制配置 {
  const 切页 = (目标: string, 数据?: object) => {
    for (const 场景 of 游戏.scene.getScenes(false)) 游戏.scene.stop(场景.scene.key);
    游戏.scene.start(目标, 数据);
  };
  const 对局 = () => {
    const 接口 = window.__再消一行测试__;
    if (!接口) throw new Error("请先开始一局游戏");
    return 接口;
  };
  return {
    项目: "再消一行",
    状态: () => ({
      当前页面: 游戏.scene.getScenes(true).at(-1)?.scene.key ?? "启动中",
      对局阶段: window.__再消一行测试__?.读取状态().阶段 ?? "未开始",
      分数: window.__再消一行测试__?.读取状态().分数 ?? 0,
      消行: window.__再消一行测试__?.读取状态().消行数 ?? 0,
      金币: new 旅行收藏(localStorage).读取().金币,
      收藏数: new 旅行收藏(localStorage).读取().已购.length,
    }),
    命令: [
      {
        编号: "start",
        名称: "开始指定模式",
        说明: "进入所选模式的新对局，不清除纪录和收藏",
        分组: "对局",
        影响存档: false,
        参数: [
          {
            键: "模式",
            名称: "游戏模式",
            类型: "选项",
            说明: "开始新局的模式",
            选项: ["马拉松", "冲刺", "极限", "每日挑战"],
          },
        ],
        执行: (参数) => 切页("再消一行对局", { 模式: 参数.模式 }),
      },
      {
        编号: "pause",
        名称: "暂停对局",
        说明: "暂停玩法与当前音乐",
        分组: "对局",
        影响存档: false,
        执行: () => 对局().设置暂停(true),
      },
      {
        编号: "resume",
        名称: "恢复对局",
        说明: "恢复暂停中的玩法",
        分组: "对局",
        影响存档: false,
        执行: () => 对局().设置暂停(false),
      },
      {
        编号: "four-lines",
        名称: "准备四行消除",
        说明: "放置四行缺口和I方块；后续硬降会触发真实得分与成就",
        分组: "反馈",
        影响存档: true,
        执行: () => 对局().准备四行消除(),
      },
      {
        编号: "drop",
        名称: "执行硬降",
        说明: "使用当前真实方块落地，触发实际结算与音效",
        分组: "反馈",
        影响存档: true,
        执行: () => {
          对局().设置暂停(false);
          对局().硬降();
        },
      },
      {
        编号: "settlement",
        名称: "预览结算",
        说明: "使用既有测试场景触发实际结算、纪录和成就，可能写入存档",
        分组: "反馈",
        影响存档: true,
        执行: () => 对局().准备结算(false),
      },
      {
        编号: "coins",
        名称: "增加旅行金币",
        说明: "向当前测试浏览器的收藏追加金币；保留已有购买与记录",
        分组: "旅行收藏",
        影响存档: true,
        参数: [
          {
            键: "数量",
            名称: "金币数量",
            类型: "数值",
            说明: "只追加，不清空收藏",
            最小: 1,
            最大: 1000000,
            步长: 1,
          },
        ],
        执行: async (参数) => {
          const 结果 = await 执行收藏操作((收藏) => 收藏.增加测试金币(Number(参数.数量)));
          if (!结果.成功) throw new Error(结果.原因);
        },
      },
      {
        编号: "shop",
        名称: "打开商店",
        说明: "在当前页面上打开真实商店，查看和购买外观",
        分组: "旅行收藏",
        影响存档: false,
        执行: () => {
          const 场景 = 游戏.scene.getScenes(true).at(-1);
          if (!场景) throw new Error("游戏尚未就绪");
          if (场景.scene.key !== "旅行商店")
            打开覆盖页面(场景, "旅行商店", { 返回页面: 场景.scene.key });
        },
      },
      {
        编号: "menu",
        名称: "返回主界面",
        说明: "退出当前页面回到主菜单，不领取未结束对局的金币",
        分组: "页面",
        影响存档: false,
        执行: () => 切页("开始菜单"),
      },
    ],
  };
}

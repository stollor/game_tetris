import type Phaser from "phaser";
import type { 游戏专项指标 } from "../../框架/开发/性能协议";
import { 读取程序声部 } from "../../框架/音频/程序音频";
import { 读取游戏音频状态 } from "../../框架/音频/音频";
import { 烘焙统计 } from "../性能/图形烘焙";
import { 渲染统计 } from "../性能/按需渲染";
import { 读取纹理缓存统计 } from "../性能/纹理缓存";

export function 读取再消一行性能(游戏: Phaser.Game): 游戏专项指标[] {
  const 音频 = 读取游戏音频状态();
  const 声部 = 读取程序声部();
  const 缓存 = 读取纹理缓存统计(游戏.textures);
  const 指标: 游戏专项指标[] = [
    ...(
      ["音效请求", "音效调用", "音效静音跳过", "音乐请求", "音乐调用", "音乐静音跳过"] as const
    ).map((名称) => ({ 名称, 单位: "次", 数值: 音频[名称], 累计: true })),
    { 名称: "程序声部在用", 单位: "路", 数值: 声部.声部在用 },
    { 名称: "程序声部空闲", 单位: "路", 数值: 声部.声部空闲 },
    { 名称: "噪声缓冲", 单位: "份", 数值: 声部.噪声缓冲 },
    { 名称: "跳过绘制", 单位: "次", 数值: 渲染统计.跳过, 累计: true },
    { 名称: "图形烘焙", 单位: "次", 数值: 烘焙统计.烘焙次数, 累计: true },
    { 名称: "烘焙贴图绘制", 单位: "次", 数值: 烘焙统计.贴图渲染, 累计: true },
    { 名称: "原生图形绘制", 单位: "次", 数值: 烘焙统计.原生渲染, 累计: true },
    { 名称: "独立纹理创建", 单位: "次", 数值: 烘焙统计.独立纹理, 累计: true },
    { 名称: "烘焙图集页", 单位: "页", 数值: 烘焙统计.图集页 },
    ...(["图章命中", "图章未命中", "图章图集创建", "图章独立创建"] as const).map((名称) => ({
      名称,
      单位: "次",
      数值: 烘焙统计[名称],
      累计: true,
    })),
  ];
  const 压力 = window.__GAMEMAKER_TEST__?.压力?.读取();
  if (压力)
    指标.push(
      { 名称: "压力创建耗时", 单位: "毫秒", 数值: 压力.创建毫秒 },
      { 名称: "压力清理耗时", 单位: "毫秒", 数值: 压力.清理毫秒 },
      { 名称: "压力实例", 单位: "个", 数值: 压力.数量 },
      { 名称: "压力触发批次", 单位: "次", 数值: 压力.触发批次, 累计: true },
      { 名称: "压力触发调用", 单位: "次", 数值: 压力.触发调用, 累计: true },
      { 名称: "压力更新帧", 单位: "帧", 数值: 压力.更新帧, 累计: true },
    );
  if (缓存)
    指标.push(
      { 名称: "生成贴图缓存", 单位: "项", 数值: 缓存.数量 },
      { 名称: "缓存引用", 单位: "次", 数值: 缓存.引用数 },
      { 名称: "缓存RGBA8估算", 单位: "字节", 数值: 缓存.像素数 * 4 },
      { 名称: "缓存像素预算使用率", 单位: "%", 数值: (缓存.像素数 / 缓存.像素上限) * 100 },
      { 名称: "缓存数量预算使用率", 单位: "%", 数值: (缓存.数量 / 缓存.数量上限) * 100 },
    );
  return 指标;
}

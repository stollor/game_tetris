import type { 矩形 } from "../../组件/绘制/图形对象";
import { 计算金币条 } from "../界面/金币条配方";

/** 与旅行商店原布局一致，两种渲染后端共享全部陈列几何。 */
export function 计算商店布局(宽: number, 高: number) {
  const 扁 = 高 < 500;
  const 矮 = 高 < 640;
  const 卡高 = 扁 ? 34 : 矮 ? 40 : 48;
  const 买高 = 扁 ? 32 : 矮 ? 38 : 44;
  const 地点高 = 扁 ? 72 : 矮 ? 84 : 100;
  const 坞高 = 地点高 + 2 * (卡高 + 6) + 买高 + 28 + 52;
  const 坞顶 = 高 - 坞高 - 8;
  const 卡宽 = (宽 - 44) / 3;
  const 单宽 = (宽 - 42) / 2;
  const 买顶 = 坞顶 + 8 + 2 * (卡高 + 6);
  const 目录: 矩形 = { 左: 16, 上: 高 - 地点高 - 68, 宽: 宽 - 32, 高: 地点高 };
  const 目录卡宽 = 目录.宽 < 430 ? 96 : 118;
  /** 金币条（16,12）高 34：标题区紧接在它下面，与 Phaser 场景原式一致。 */
  const 标题Y = 12 + 计算金币条(16, 12, 0).高 + 6;
  const 浮层顶 = 高 - 坞高 - 8;
  return {
    卡高,
    买高,
    地点高,
    坞高,
    坞顶,
    部位卡: Array.from(
      { length: 6 },
      (_, i): 矩形 => ({
        左: 16 + (i % 3) * (卡宽 + 6),
        上: 坞顶 + 8 + Math.floor(i / 3) * (卡高 + 6),
        宽: 卡宽,
        高: 卡高,
      }),
    ),
    单件: { 左: 16, 上: 买顶, 宽: 单宽, 高: 买高 },
    整套: { 左: 26 + 单宽, 上: 买顶, 宽: 单宽, 高: 买高 },
    目录,
    目录卡宽,
    目录卡高: 地点高 - 4,
    退出: { 左: 宽 / 2 - 48, 上: 高 - 46, 宽: 96, 高: 36 },
    纯享: { 左: 宽 / 2 - 40, 上: 高 - 坞高 - 48, 宽: 80, 高: 32 },
    /** 坞区浮层：玻璃底板、部位卡区、购买区（Phaser 场景 绘制浮层 原式）。 */
    浮层: {
      玻璃: { 左: 8, 上: 浮层顶, 宽: 宽 - 16, 高: 坞高 - 52 } satisfies 矩形,
      部位区: { 左: 16, 上: 浮层顶 + 8, 宽: 宽 - 32, 高: 卡高 } satisfies 矩形,
      购买区: { 左: 16, 上: 浮层顶 + 8 + 2 * (卡高 + 6), 宽: 宽 - 32, 高: 买高 } satisfies 矩形,
    },
    /** 标题区纵向基准：地名 / 副题 / 消息（Phaser 场景原式）。 */
    标题Y,
    副题Y: 标题Y + 30,
    消息Y: 标题Y + 50,
  };
}

/**
 * 商店按钮的图标 + 文字并排布局：图标在文字左侧、两者作为一组居中。
 * 复刻 Phaser 框架 `界面按钮` 横排图文公式（图标 18、间距 4），供 Three 版按同一数值绘制。
 */
export function 计算商店按钮图文(
  中心X: number,
  中心Y: number,
  文字宽: number,
  图标尺寸 = 18,
  间距 = 4,
): {
  图标: { x: number; y: number; 尺寸: number };
  文字: { x: number; y: number };
} {
  return {
    图标: { x: 中心X - (文字宽 + 间距) / 2, y: 中心Y, 尺寸: 图标尺寸 },
    文字: { x: 中心X + (图标尺寸 + 间距) / 2, y: 中心Y },
  };
}

export function 计算商店方块陈列(宽: number, 高: number, 坞高: number) {
  const 可用宽 = 宽 - 48;
  const 可用高 = Math.max(96, 高 - 坞高 - 174);
  const 列 = 可用宽 < 520 ? (可用宽 < 380 ? 2 : 4) : 7;
  const 行 = Math.ceil(7 / 列);
  const 列距 = 16;
  const 行距 = 14;
  const 格 = Math.max(
    14,
    Math.min(
      36,
      Math.floor((可用宽 - (列 - 1) * 列距) / (列 * 4)),
      Math.floor((可用高 - (行 - 1) * 行距) / (行 * 2)),
    ),
  );
  const 槽宽 = 格 * 4;
  const 槽高 = 格 * 2;
  const 块宽 = 列 * 槽宽 + (列 - 1) * 列距;
  const 块高 = 行 * 槽高 + (行 - 1) * 行距;
  const 左 = (宽 - 块宽) / 2;
  const 顶 = 108 + Math.max(0, (可用高 - 块高) / 2);
  return { 列, 列距, 行距, 格, 槽宽, 槽高, 块宽, 块高, 左, 顶 };
}

export function 计算商店界面示意(宽: number, 高: number, 坞高: number): 矩形 {
  const 面板宽 = Math.min(400, 宽 - 72);
  const 面板高 = Math.min(188, Math.max(140, 高 - 坞高 - 140));
  return {
    左: (宽 - 面板宽) / 2,
    上: 96 + Math.max(0, (高 - 坞高 - 120 - 面板高) / 2),
    宽: 面板宽,
    高: 面板高,
  };
}

export function 计算商店确认布局(宽: number, 高: number) {
  const 面板宽 = Math.min(470, 宽 - 28);
  const 面板高 = Math.min(410, 高 - 24);
  const 面板: 矩形 = { 左: (宽 - 面板宽) / 2, 上: (高 - 面板高) / 2, 宽: 面板宽, 高: 面板高 };
  return {
    面板,
    确认: { 左: 面板.左 + 25, 上: 面板.上 + 面板高 - 112, 宽: 面板宽 - 50, 高: 46 },
    取消: { 左: 面板.左 + 25, 上: 面板.上 + 面板高 - 52, 宽: 面板宽 - 50, 高: 34 },
    关闭: { 左: 面板.左 + 面板宽 - 42, 上: 面板.上 + 14, 宽: 32, 高: 32 },
  };
}

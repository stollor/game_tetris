/**
 * 四套内置背景主题的纯配方：底图 + 动态细节。
 * 与旅行地点一样只依赖 `图形对象`，Phaser 与 Three 共用；构图、数值、色值与原 Phaser 版逐字一致。
 * 动态函数带图层亮度乘子：Phaser 用图层对象 alpha（传 1），Three 单画布合成时用配置里的动画亮度。
 */

export type 内置主题名称 = Exclude<背景主题, 地点名称>;

/** 四套内置主题的代表色，与下方绘制用色同源；供 Three 的顶栏衬底/文字对比度读取。 */
export const 内置主题外观: Record<内置主题名称, { 主色: number; 强调: number }> = {
  晨光海岸: { 主色: 0x1d4f6d, 强调: 0xffd9a0 },
  云海山岚: { 主色: 0x2a4a5c, 强调: 0xfff6dd },
  极光原野: { 主色: 0x081726, 强调: 0x3ff0c0 },
  霓虹天际: { 主色: 0x120a26, 强调: 0xffd9a0 },
};

export function 是内置主题(主题: 背景主题): 主题 is 内置主题名称 {
  return 主题 === "晨光海岸" || 主题 === "云海山岚" || 主题 === "极光原野" || 主题 === "霓虹天际";
}

/** 内置主题静态底图（含统一暗角）。 */
export function 绘制内置背景静底(绘图: 图形对象, 宽: number, 高: number, 主题: 内置主题名称): void {
  if (主题 === "晨光海岸") 绘制海岸底图(绘图, 宽, 高);
  else if (主题 === "云海山岚") 绘制山岚底图(绘图, 宽, 高);
  else if (主题 === "极光原野") 绘制原野底图(绘图, 宽, 高);
  else 绘制天际底图(绘图, 宽, 高);
  绘制暗角(绘图, 宽, 高);
}

/** 内置主题动态层；时间秒按主题动画速度换算到与原 Phaser 版一致的时间轴。 */
export function 绘制内置背景动态(
  绘图: 图形对象,
  宽: number,
  高: number,
  主题: 内置主题名称,
  时间秒: number,
  亮度 = 1,
): void {
  const 毫秒 = 时间秒 * 1000 * 背景主题配置[主题].动画速度;
  if (主题 === "晨光海岸") 绘制海面动画(绘图, 宽, 高, 毫秒, 亮度);
  else if (主题 === "云海山岚") 绘制云层动画(绘图, 宽, 高, 毫秒, 0xffffff, 0.5 * 亮度);
  else if (主题 === "极光原野") 绘制极光动画(绘图, 宽, 高, 毫秒, 亮度);
  else 绘制城市动画(绘图, 宽, 高, 毫秒, 亮度);
}


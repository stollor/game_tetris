function 绘制海岸底图(绘图: 图形对象, 宽: number, 高: number): void {
  const 海平线 = 高 * 0.585;
  绘制天幕(绘图, 宽, 0, 海平线 + 4, [0x1c5a9c, 0x3f8cc2, 0x7fc3dc, 0xc9e7e6, 0xffe3b4]);
  const 日X = 宽 * 0.72;
  const 日Y = 高 * 0.27;
  绘制日轮(绘图, 日X, 日Y, Math.min(宽, 高) * 0.072, 0xfff3cf, 0xffd9a0, 1);
  // 远处薄云与近云
  绘制云朵(绘图, 宽 * 0.16, 高 * 0.2, 宽 * 0.075, 0xfff6e6, 0xd3e2ec, 0.85);
  绘制云朵(绘图, 宽 * 0.45, 高 * 0.13, 宽 * 0.055, 0xfff6e6, 0xd0e0ec, 0.7);
  绘制云朵(绘图, 宽 * 0.88, 高 * 0.36, 宽 * 0.085, 0xfff2dd, 0xcfe0ea, 0.62);
  绘制云朵(绘图, 宽 * 0.3, 高 * 0.38, 宽 * 0.06, 0xfff2dd, 0xc9dce8, 0.42);
  // 海平线雾光
  绘图.fillStyle(0xffe9c8, 0.5).fillRect(0, 海平线 - 高 * 0.045, 宽, 高 * 0.05);
  // 海面：由浅入深，与天空拉开层次
  绘制天幕(绘图, 宽, 海平线, 高, [0x4ba3bd, 0x2e83a1, 0x1f6484, 0x154a68]);
  // 太阳反光光路
  for (let i = 0; i < 16; i += 1) {
    const 比例 = i / 15;
    const y = 海平线 + (高 - 海平线) * 比例;
    const 宽度 = 宽 * (0.035 + 比例 * 0.11);
    绘图
      .fillStyle(0xffe7bd, 0.3 * (1 - 比例 * 0.72))
      .fillEllipse(日X + 宽 * 0.02 * 比例, y, 宽度, (高 - 海平线) * 0.045);
  }
  // 波纹光带：近大远小，亮度收敛
  for (let i = 0; i < 14; i += 1) {
    const 比例 = 0.08 + 随机值(i + 21) * 0.9;
    const y = 海平线 + (高 - 海平线) * 比例;
    const x = 随机值(i + 55) * 宽;
    const 长 = 宽 * (0.035 + 随机值(i + 87) * 0.1) * (0.6 + 比例 * 1.1);
    绘图
      .fillStyle(i % 3 === 0 ? 0xfff0cd : 0xc9f3ee, 0.08 + 随机值(i + 131) * 0.12)
      .fillRoundedRect(x, y, 长, Math.max(1.2, 高 * 0.0032), 3);
  }
  // 前景深色潮水
  绘图.fillStyle(0x1d4f6d, 0.55).fillRect(0, 高 * 0.92, 宽, 高 * 0.08);
  绘图.fillStyle(0x9adcd8, 0.2).fillEllipse(宽 * 0.5, 高 * 0.93, 宽 * 0.9, 高 * 0.012);
}

function 绘制海面动画(绘图: 图形对象, 宽: number, 高: number, 时间: number, 亮度: number): void {
  const 填 = (色: number, 透明度: number) => 绘图.fillStyle(色, 透明度 * 亮度);
  const 海平线 = 高 * 0.585;
  // 波光闪烁
  for (let i = 0; i < 30; i += 1) {
    const y = 海平线 + 随机值(i + 111) * (高 - 海平线) * 0.96;
    const 速度 = 14 + 随机值(i + 29) * 26;
    const 长 = 宽 * (0.02 + 随机值(i + 47) * 0.07);
    const x = ((随机值(i + 77) * 宽 + 时间 * 0.03 * 速度) % (宽 + 长)) - 长;
    const 闪 = 0.5 + Math.sin(时间 * 0.0016 + i * 1.7) * 0.5;
    填(i % 4 === 0 ? 0xfff2cf : 0xdbfff6, 0.1 + 闪 * 0.22).fillRoundedRect(
      x,
      y,
      长,
      Math.max(1.5, 高 * 0.0032),
      3,
    );
  }
  // 漂浮光尘
  for (let i = 0; i < 12; i += 1) {
    const x = (随机值(i + 210) * 宽 + 时间 * (0.004 + 随机值(i + 250) * 0.01)) % 宽;
    const y = 高 * (0.2 + 随机值(i + 270) * 0.6) + Math.sin(时间 * 0.0004 + i) * 高 * 0.012;
    填(0xfff4d8, 0.1 + 随机值(i + 290) * 0.12).fillCircle(x, y, 1.6 + 随机值(i + 310) * 2.6);
  }
  绘制云层动画(绘图, 宽, 高, 时间, 0xfffaf0, 0.3 * 亮度);
}


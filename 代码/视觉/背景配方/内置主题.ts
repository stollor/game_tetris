function 绘制原野底图(绘图: 图形对象, 宽: number, 高: number): void {
  const 地平线 = 高 * 0.68;
  绘制天幕(绘图, 宽, 0, 地平线 + 4, [0x050c1e, 0x0a1f3e, 0x14456b, 0x2c7f8c]);
  绘制星野(绘图, 宽, 高, 110, 500);
  // 月亮
  const 月X = 宽 * 0.2;
  const 月Y = 高 * 0.18;
  绘制光晕(绘图, 月X, 月Y, Math.min(宽, 高) * 0.05, 0xbfe6ff, 1.25, 8);
  绘图.fillStyle(0xe9f4ff, 0.95).fillCircle(月X, 月Y, Math.min(宽, 高) * 0.034);
  绘图.fillStyle(0xc7dcf2, 0.55).fillCircle(月X - 4, 月Y - 3, Math.min(宽, 高) * 0.02);
  绘图.fillStyle(0xffffff, 0.34).fillCircle(月X - 2, 月Y - 2, Math.min(宽, 高) * 0.024);
  // 静态极光帘幕（双遍重叠消除条纹）
  const 极光色 = [0x3ff0c0, 0x4de3d8, 0x7ad9ff, 0xa98cff];
  for (let 条 = 0; 条 < 4; 条 += 1) {
    const 色 = 极光色[条] ?? 0x4de3d8;
    const 基Y = 高 * (0.16 + 条 * 0.055);
    for (let 两遍 = 0; 两遍 < 2; 两遍 += 1) {
      const 步长 = Math.max(10, 宽 / (40 + 两遍 * 28));
      const 偏移 = 两遍 === 1 ? 步长 * 0.5 : 0;
      for (let x = -步长; x < 宽 + 步长; x += 步长) {
        const nx = x / 宽;
        const 波 = Math.sin(nx * 5.2 + 条 * 1.9) * 高 * 0.05 + Math.sin(nx * 11 + 条) * 高 * 0.018;
        const 顶 = 基Y + 波;
        const 帘高 = 高 * (0.14 + 0.06 * Math.sin(nx * 6.5 + 条 * 2.2));
        const α = (两遍 === 0 ? 0.07 : 0.038) * (0.82 + 0.18 * Math.sin(nx * 4.2 + 条));
        绘图.fillGradientStyle(色, 色, 色, 色, α, α, 0, 0).fillRect(x + 偏移, 顶, 步长 + 1, 帘高);
      }
    }
  }
  // 地面：丘陵与湖面
  绘制山脊(绘图, 宽, 地平线 + 高 * 0.02, 0x123048, 高 * 0.09, 211);
  绘图.fillStyle(0x0a1c30, 1).fillRect(0, 地平线, 宽, 高 - 地平线);
  // 湖面倒影
  const 湖顶 = 地平线 + 高 * 0.045;
  绘图.fillStyle(0x102c44, 0.9).fillRect(0, 湖顶, 宽, 高 * 0.2);
  for (let 条 = 0; 条 < 3; 条 += 1) {
    const 色 = 极光色[条] ?? 0x4de3d8;
    绘图.fillStyle(色, 0.07).fillRect(宽 * (0.1 + 条 * 0.22), 湖顶, 宽 * 0.16, 高 * 0.17);
  }
  for (let i = 0; i < 12; i += 1) {
    const y = 湖顶 + 随机值(i + 811) * 高 * 0.18;
    绘图
      .fillStyle(i % 2 ? 0x9be8e0 : 0x86c7ff, 0.1 + 随机值(i + 833) * 0.12)
      .fillRoundedRect(随机值(i + 855) * 宽, y, 宽 * (0.04 + 随机值(i + 877) * 0.1), 1.6, 2);
  }
  // 前景草坡
  绘图.fillStyle(0x081726, 1).fillEllipse(宽 * 0.5, 高 * 1.02, 宽 * 1.45, 高 * 0.3);
  绘图.fillStyle(0x0d2236, 1).fillEllipse(宽 * 0.12, 高 * 1.0, 宽 * 0.9, 高 * 0.22);
}

function 绘制极光动画(绘图: 图形对象, 宽: number, 高: number, 时间: number, 亮度: number): void {
  const 填 = (色: number, 透明度: number) => 绘图.fillStyle(色, 透明度 * 亮度);
  for (let 条 = 0; 条 < 3; 条++) 绘制极光帘幕(绘图, 宽, 高, 时间, 条, 亮度);
  // 星光闪烁
  for (let i = 0; i < 26; i += 1) {
    const 闪 = 0.5 + 0.5 * Math.sin(时间 * (0.0008 + 随机值(i + 61) * 0.0012) + i);
    填(0xffffff, 0.12 + 闪 * 0.3).fillCircle(
      随机值(i + 401) * 宽,
      随机值(i + 431) * 高 * 0.55,
      0.8 + 随机值(i + 461) * 1.2,
    );
  }
  // 湖面萤火
  for (let i = 0; i < 14; i += 1) {
    const x = (随机值(i + 501) * 宽 + Math.sin(时间 * 0.0004 + i) * 宽 * 0.03) % 宽;
    const y = 高 * (0.72 + 随机值(i + 531) * 0.22) + Math.sin(时间 * 0.0006 + i * 2) * 高 * 0.015;
    填(0xa8ffd9, 0.16 + 随机值(i + 561) * 0.22).fillCircle(x, y, 1.4 + 随机值(i + 591) * 2);
  }
}


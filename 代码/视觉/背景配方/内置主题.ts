/** 云层参数与「绘制云层动画」一致；Phaser 的烘焙替身按下标取同一组参数。 */
export function 云朵参数(
  i: number,
  宽: number,
  高: number,
  时间: number,
): { 尺寸: number; x: number; y: number } {
  const 尺寸 = 宽 * (0.05 + 随机值(i + 81) * 0.06);
  const x =
    ((随机值(i + 17) * (宽 + 尺寸 * 3) + 时间 * (0.004 + i * 0.0016)) % (宽 + 尺寸 * 3)) -
    尺寸 * 1.5;
  const y = 高 * (0.12 + 随机值(i + 41) * 0.3);
  return { 尺寸, x, y };
}

function 绘制云层动画(
  绘图: 图形对象,
  宽: number,
  高: number,
  时间: number,
  颜色: number,
  透明度: number,
): void {
  for (let i = 0; i < 5; i += 1) {
    const { 尺寸, x, y } = 云朵参数(i, 宽, 高, 时间);
    绘制云朵(绘图, x, y, 尺寸, 颜色, 混色(颜色, 0x6d87a8, 0.45), 透明度);
  }
}


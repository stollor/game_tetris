import type { 图形对象 } from "../../框架/界面/绘制/协议";
import { 查找地点 } from "../框架配置/旅行地点";
import type { 背景主题 } from "../设置/游戏设置";
import { 背景主题配置 } from "./外观/背景主题";
import { 内置主题外观, 是内置主题, 绘制内置背景动态, 绘制内置背景静底 } from "./背景配方/内置主题";
import { 绘制旅行动态, 绘制旅行风景 } from "./背景配方/旅行风景";

/**
 * 背景视觉配方的唯一入口（引擎无关纯函数）：
 * - Phaser 版 `代码/视觉/{霓虹背景,旅行风景,极光演出}.ts` 保留原有导出与签名，内部委托这里；
 * - Three 版页面直接用 `画笔.图形` 调用，不再另画简化背景。
 *
 * 约束：本文件与 `背景配方/` 只依赖 `图形对象` 契约和共享配置，不 import Phaser 运行时；
 * 绘制参数全部来自调用方，函数内不读场景/设置/存档。颜色与构图与原 Phaser 版逐字一致。
 */

/** 冻结入口参数：宽高为逻辑像素；时间秒为动画时间轴；动态=false 时画固定静态帧。 */
export interface 背景绘制参数 {
  宽: number;
  高: number;
  主题: 背景主题;
  动态: boolean;
  时间秒: number;
}

/** 静态底图参数（Phaser 把静态底与动态层分两遍画时使用）。 */
export interface 背景静态参数 {
  宽: number;
  高: number;
  主题: 背景主题;
  /** 旅行地点是否把主体（熊猫/行舟等）画进静态底图；动态层单独画主体时传 false。 */
  静态主体?: boolean;
}

/** 动态层参数（Phaser 用图层对象 alpha 时 亮度传 1）。 */
export interface 背景动态参数 {
  宽: number;
  高: number;
  主题: 背景主题;
  时间秒: number;
  /** 图层亮度乘子；单画布合成时传 `背景主题配置.动画亮度`，Phaser 分图层时传 1。 */
  亮度?: number;
}

/** 内置主题或旅行地点主题的背景外观（Three 顶栏衬底/浅底压暗用），颜色取自共享配置。 */
export interface 背景外观配色 {
  主色: number;
  强调: number;
  文字基调: "浅底" | "深底";
}

/**
 * 完整背景画面（静态 + 动态，一次调用画完）。
 * Phaser 为了减少每帧绘图开销会拆成「烘焙底图 + 独立动态层」，Three 直接调用本函数。
 */
export function 绘制背景(绘图: 图形对象, 参数: 背景绘制参数): void {
  绘制背景静底(绘图, {
    宽: 参数.宽,
    高: 参数.高,
    主题: 参数.主题,
    静态主体: !参数.动态,
  });
  if (!参数.动态) return;
  绘制背景动态(绘图, {
    宽: 参数.宽,
    高: 参数.高,
    主题: 参数.主题,
    时间秒: 参数.时间秒,
    亮度: 读取背景动态亮度(参数.主题),
  });
}

/** 静态底图：内置主题（含暗角）或旅行地点风景，可选是否把旅行主体画进底图。 */
export function 绘制背景静底(绘图: 图形对象, 参数: 背景静态参数): void {
  if (是内置主题(参数.主题)) {
    绘制内置背景静底(绘图, 参数.宽, 参数.高, 参数.主题);
    return;
  }
  const 地点 = 查找地点(参数.主题);
  if (!地点) return;
  绘制旅行风景(绘图, 参数.宽, 参数.高, 地点, 参数.静态主体 ?? true);
}

/** 动态层：内置主题的波光/云/极光/城市灯火，或旅行地点的主体与粒子。 */
export function 绘制背景动态(绘图: 图形对象, 参数: 背景动态参数): void {
  if (是内置主题(参数.主题)) {
    绘制内置背景动态(绘图, 参数.宽, 参数.高, 参数.主题, 参数.时间秒, 参数.亮度 ?? 1);
    return;
  }
  const 地点 = 查找地点(参数.主题);
  if (!地点) return;
  绘制旅行动态(绘图, 参数.宽, 参数.高, 参数.时间秒 * 1000, 地点);
}

/** 动态层亮度：Phaser 分图层时用对象 alpha 实现同一效果，此处只给单画布合成用。 */
export function 读取背景动态亮度(主题: 背景主题): number {
  // 旅行地点的动态层在 Phaser 版固定 alpha=1，不跟配置的 0.9 走；保持一致。
  if (!是内置主题(主题)) return 1;
  return 背景主题配置[主题].动画亮度;
}

/** 背景代表色：内置主题取配方用色，旅行地点取 地点皮肤表；文字基调取共享配置。 */
export function 读取背景外观配色(主题: 背景主题): 背景外观配色 {
  const 文字基调 = 背景主题配置[主题]?.文字基调 ?? "深底";
  if (是内置主题(主题)) {
    const 外观 = 内置主题外观[主题];
    return { 主色: 外观.主色, 强调: 外观.强调, 文字基调 };
  }
  const 地点 = 查找地点(主题);
  if (地点) return { 主色: 地点.主色, 强调: 地点.强调, 文字基调 };
  return {
    主色: 背景主题配置[主题]?.预览配色[0] ?? 0x120a26,
    强调: 背景主题配置[主题]?.预览配色[1] ?? 0xffd9a0,
    文字基调,
  };
}

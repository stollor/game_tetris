import { type 图形对象, type 文字项, type 矩形, 解析颜色数值 } from "../../框架/界面/绘制/协议";
import { 绘制玻璃按钮底板, 绘制玻璃面板基底 } from "../../组件/绘制/玻璃绘制";
import type { 游戏设置 } from "../设置/游戏设置";
import type { 游戏文案 } from "../语言/类型";
import { 游戏外观 } from "./外观/游戏外观";
import { 暂停外观 } from "./外观/界面主题";

/** 原点、尺寸、控件位置取自 Phaser 的 界面对局设置菜单.布局。 */
export function 计算对局设置布局(宽: number, 高: number) {
  const 比例 = Math.min(1, (高 - 24) / 430);
  const 面板宽 = Math.min(480, 宽 / 比例 - 28);
  const 中心X = 宽 / 2;
  const 中心Y = 高 / 2;
  const 矩形 = (x: number, y: number, w: number, h: number): 矩形 => ({
    左: 中心X + (x - w / 2) * 比例,
    上: 中心Y + (y - h / 2) * 比例,
    宽: w * 比例,
    高: h * 比例,
  });
  const 右 = 面板宽 / 2 - 28;
  return {
    比例,
    中心X,
    中心Y,
    面板: 矩形(0, 0, 面板宽, 430),
    滑块: 矩形(0, -101, Math.max(120, 面板宽 - 64), 32),
    按钮: [
      { 名称: "关闭对局设置", 文案: "×", 矩形: 矩形(面板宽 / 2 - 26, -188, 32, 32) },
      { 名称: "网格:开", 文案: "开", 矩形: 矩形(右 - 142, -49, 68, 34) },
      { 名称: "网格:关", 文案: "关", 矩形: 矩形(右 - 66, -49, 68, 34) },
      { 名称: "按键说明:开", 文案: "开", 矩形: 矩形(右 - 142, 1, 68, 34) },
      { 名称: "按键说明:关", 文案: "关", 矩形: 矩形(右 - 66, 1, 68, 34) },
      ...(["左转", "右转", "180度"] as const).map((值, i) => ({
        名称: `上键:${值}`,
        文案: 值 === "180度" ? "180°" : 值,
        矩形: 矩形(-76 + i * 76, 85, 68, 34),
      })),
      { 名称: "返回暂停菜单", 文案: "返回暂停菜单", 矩形: 矩形(0, 177, 210, 42) },
    ],
  };
}

export function 绘制对局设置(
  图形: 图形对象,
  宽: number,
  高: number,
  设置: 游戏设置,
  文案: 游戏文案,
): 文字项[] {
  const 外观 = 暂停外观();
  const 定位 = 计算对局设置布局(宽, 高);
  const { 比例, 面板 } = 定位;
  图形.fillStyle(解析颜色数值(外观.遮罩色), 外观.遮罩透明度).fillRect(0, 0, 宽, 高);
  绘制玻璃面板基底(图形, 面板.左, 面板.上, 面板.宽, 面板.高, {
    圆角: 22 * 比例,
    填色: 解析颜色数值(外观.面板色),
    透明度: 0.99,
    边色: 解析颜色数值(外观.边框色),
    边透明度: 0.92,
    强调色: 解析颜色数值(外观.强调色),
    高光: false,
  });
  const 项: 文字项[] = [];
  const 文字 = (
    文: string,
    x: number,
    y: number,
    字号: number,
    锚点: 文字项["锚点"] = "左中",
    强调 = false,
  ) =>
    项.push({
      文案: 文,
      x,
      y,
      锚点,
      样式: { 字体: 游戏外观.字体.家族, 字号: 字号 * 比例, 颜色: 强调 ? 外观.标题色 : 外观.说明色 },
    });
  const 左 = 面板.左 + 28 * 比例;
  const 顶 = 面板.上;
  文字(文案.对局设置, 定位.中心X, 顶 + 38 * 比例, 24, "中中", true);
  文字(文案.落点影透明度, 左, 顶 + 78 * 比例, 14);
  文字(`${设置.落点影透明度}%`, 面板.左 + 面板.宽 - 28 * 比例, 顶 + 78 * 比例, 14, "右中", true);
  文字(文案.显示网格, 左, 顶 + 166 * 比例, 14);
  文字(文案.显示按键说明, 左, 顶 + 216 * 比例, 14);
  文字(设置.语言 === "简体中文" ? "手机 ↑ 旋转方向" : "Touch ↑ rotation", 左, 顶 + 266 * 比例, 14);
  const 轨 = 定位.滑块;
  const 轨Y = 轨.上 + 轨.高 / 2;
  const 轨X = 轨.左 + (轨.宽 * 设置.落点影透明度) / 100;
  图形
    .lineStyle(4 * 比例, 解析颜色数值(外观.按钮面板色))
    .lineBetween(轨.左, 轨Y, 轨.左 + 轨.宽, 轨Y);
  图形.lineStyle(4 * 比例, 解析颜色数值(外观.强调色)).lineBetween(轨.左, 轨Y, 轨X, 轨Y);
  图形.fillStyle(解析颜色数值(外观.强调色)).fillCircle(轨X, 轨Y, 8 * 比例);
  for (const 按钮 of 定位.按钮) {
    const 选中 = 按钮.名称.startsWith("网格:")
      ? 设置.显示网格 === (按钮.名称 === "网格:开")
      : 按钮.名称.startsWith("按键说明:")
        ? 设置.显示按键说明 === (按钮.名称 === "按键说明:开")
        : 按钮.名称 === `上键:${设置.手机上键旋转}`;
    const 矩 = 按钮.矩形;
    绘制玻璃按钮底板(图形, 矩.左 + 矩.宽 / 2, 矩.上 + 矩.高 / 2, 矩.宽, 矩.高, {
      填色: 解析颜色数值(选中 ? 外观.强调色 : 外观.按钮面板色),
      边框色: 解析颜色数值(外观.强调色),
      强调色: 解析颜色数值(外观.强调色),
      选中,
    });
    文字(
      按钮.文案 === "返回暂停菜单"
        ? 文案.返回暂停菜单
        : 按钮.文案 === "开"
          ? 文案.开
          : 按钮.文案 === "关"
            ? 文案.关
            : 按钮.文案,
      矩.左 + 矩.宽 / 2,
      矩.上 + 矩.高 / 2,
      13,
      "中中",
      true,
    );
  }
  return 项;
}

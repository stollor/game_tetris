/* 对局布局（390×844 基准，坐标与现行 Three 实现逐字一致）                */
/* ------------------------------------------------------------------ */

export interface 对局布局 {
  逻辑宽: number;
  逻辑高: number;
  顶栏高度: number;
  棋盘: { 左: number; 上: number; 格: number; 列: number; 行: number; 内缩: number };
  棋盘外框: 矩形;
  预览: {
    上: number;
    暂存左: number;
    下一个左: number;
    下一个间距: number;
    下一个数量: number;
    格: number;
    宽: number;
    高: number;
  };
  控制: { 左: number; 宽: number; 高: number; 行一上: number; 行二上: number; 间隔: number };
  暂停面板: 矩形;
  结算面板: 矩形;
  离开按钮: 矩形;
  暂停按钮: 矩形;
  结算重开按钮: 矩形;
  结算菜单按钮: 矩形;
  统计列: readonly { 左: number; 键: "分数" | "消行" | "等级" }[];
}

/** 计算对局布局：基准 390×844 下数值与现行实现逐字一致，其他视口按比例缩放。 */
export function 计算对局布局(视口宽 = 390, 视口高 = 844): 对局布局 {
  const 宽比 = 视口宽 / 390;
  const 高比 = 视口高 / 844;
  const 按宽 = (值: number): number => 值 * 宽比;
  const 按高 = (值: number): number => 值 * 高比;
  const 逻辑宽 = 视口宽;
  const 逻辑高 = 视口高;
  const 棋盘 = {
    左: 按宽(65),
    上: 按高(191),
    格: 按宽(26),
    列: 10,
    行: 20,
    内缩: 按宽(5),
  };
  return {
    逻辑宽,
    逻辑高,
    顶栏高度: 按高(112),
    棋盘,
    棋盘外框: {
      左: 棋盘.左 - 棋盘.内缩,
      上: 棋盘.上 - 棋盘.内缩,
      宽: 棋盘.列 * 棋盘.格 + 棋盘.内缩 * 2,
      高: 棋盘.行 * 棋盘.格 + 棋盘.内缩 * 2,
    },
    预览: {
      上: 按高(118),
      暂存左: 按宽(20),
      下一个左: 按宽(128),
      下一个间距: 按宽(82),
      下一个数量: 3,
      格: 按宽(10),
      宽: 按宽(78),
      高: 按高(44),
    },
    控制: {
      左: 按宽(14),
      宽: 按宽(84),
      高: 按高(56),
      行一上: 按高(722),
      行二上: 按高(780),
      间隔: 按宽(8),
    },
    暂停面板: { 左: 按宽(35), 上: 按高(250), 宽: 按宽(320), 高: 按高(300) },
    结算面板: { 左: 按宽(30), 上: 按高(150), 宽: 按宽(330), 高: 按高(480) },
    离开按钮: { 左: 按宽(14), 上: 按高(8), 宽: 按宽(64), 高: 按高(30) },
    暂停按钮: { 左: 按宽(312), 上: 按高(8), 宽: 按宽(64), 高: 按高(30) },
    结算重开按钮: { 左: 按宽(115), 上: 按高(500), 宽: 按宽(160), 高: 按高(56) },
    结算菜单按钮: { 左: 按宽(115), 上: 按高(566), 宽: 按宽(160), 高: 按高(40) },
    统计列: [
      { 左: 按宽(20), 键: "分数" },
      { 左: 按宽(150), 键: "消行" },
      { 左: 按宽(280), 键: "等级" },
    ],
  };
}

/** 共享布局单例：Three 页面模块直接 import 该对象（等价于计算对局布局()）。 */
export const 对局布局: 对局布局 = 计算对局布局();


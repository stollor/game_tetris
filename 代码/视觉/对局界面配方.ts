/** 触屏操作键底板：GM `框架/界面/按钮` 默认底板（玻璃按钮）+ 主题配色。 */
export function 绘制操作键底板(
  绘图: 图形对象,
  参数: 操作键参数,
  配色: { 面板色: number; 边框色: number },
): void {
  const { 矩形, 可用, 高亮 } = 参数;
  const 中心X = 矩形.左 + 矩形.宽 / 2;
  const 中心Y = 矩形.上 + 矩形.高 / 2;
  绘制玻璃按钮底板(绘图, 中心X, 中心Y, 矩形.宽, 矩形.高, {
    填色: 配色.面板色,
    边框色: 配色.边框色,
    强调色: 配色.边框色,
    透明度: 可用 ? 0.92 : 0.5,
    边透明度: 可用 ? 0.55 : 0.3,
    悬停: false,
    选中: 高亮 ?? false,
  });
}


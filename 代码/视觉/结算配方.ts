/** 结算面板几何：中心/顶部/尺寸/视口比例（与 Phaser 版 霓虹结算几何 同形）。 */
export interface 霓虹结算几何 {
  中心X: number;
  顶: number;
  宽: number;
  高: number;
  比例: number;
}

/** 结算面板纯布局：比例、面板矩形、文字位置与两个按钮矩形。 */
export interface 霓虹结算布局 {
  几何: 霓虹结算几何;
  左: number;
  列宽: number;
  徽标: { 中心X: number; 上: number };
  分数: { 中心X: number; 上: number };
  统计标签Y: number;
  统计数值Y: number;
  金币行Y: number;
  奖励Y: number;
  重开: { 中心X: number; 中心Y: number; 宽: number; 高: number };
  菜单: { 中心X: number; 中心Y: number; 宽: number; 高: number };
}

/** 计算结算面板布局：与 Phaser 版 霓虹结算面板.布局 逐字一致。 */
export function 计算霓虹结算布局(屏宽: number, 屏高: number): 霓虹结算布局 {
  const 比例 = Math.min(1, (屏宽 - 28) / 380, (屏高 - 28) / 400);
  const 中心X = 屏宽 / 2;
  const 顶 = (屏高 - 400 * 比例) / 2;
  const 面板宽 = 380 * 比例;
  const 左 = 中心X - 面板宽 / 2;
  return {
    几何: { 中心X, 顶, 宽: 面板宽, 高: 400 * 比例, 比例 },
    左,
    列宽: 面板宽 / 3,
    徽标: { 中心X, 上: 顶 + 34 * 比例 },
    分数: { 中心X, 上: 顶 + 132 * 比例 },
    统计标签Y: 顶 + 180 * 比例,
    统计数值Y: 顶 + 210 * 比例,
    金币行Y: 顶 + 247 * 比例,
    奖励Y: 顶 + 258 * 比例,
    重开: {
      中心X,
      中心Y: 顶 + 307 * 比例,
      宽: 面板宽 - 48 * 比例,
      高: 44 * 比例,
    },
    菜单: {
      中心X,
      中心Y: 顶 + 356 * 比例,
      宽: 面板宽 - 48 * 比例,
      高: 38 * 比例,
    },
  };
}

/** 结算遮罩：整屏压暗（Phaser 结算面板 遮罩图形 的同算法）。 */
export function 绘制结算遮罩(绘图: 图形对象, 屏宽: number, 屏高: number): void {
  const 调色板 = 读取霓虹调色板();
  绘图.fillStyle(调色板.遮罩, 0.56).fillRect(0, 0, 屏宽, 屏高);
}

/** 结算面板底板：玻璃面板 + 顶部强调条 + 分数分隔线 + 统计列分隔线。 */
export function 绘制结算面板(绘图: 图形对象, 布局: 霓虹结算布局): void {
  const 调色板 = 读取霓虹调色板();
  const { 几何, 左 } = 布局;
  const { 顶, 宽: 面板宽, 高: 面板高, 比例 } = 几何;
  绘制霓虹玻璃(绘图, 左, 顶, 面板宽, 面板高, {
    圆角: 20,
    透明度: 0.98,
    边色: 调色板.面板描边,
    边透明度: 0.85,
    强调色: 调色板.强调,
    高光: true,
  });
  绘图
    .fillStyle(调色板.强调, 0.9)
    .fillRoundedRect(左 + 面板宽 / 2 - 64, 顶 + 12, 128, 4, 2)
    .lineStyle(1, 调色板.分组线, 0.9)
    .lineBetween(左 + 18, 顶 + 158 * 比例, 左 + 面板宽 - 18, 顶 + 158 * 比例);
  for (let 索引 = 1; 索引 < 3; 索引 += 1) {
    绘图.lineBetween(
      左 + 布局.列宽 * 索引,
      顶 + 170 * 比例,
      左 + 布局.列宽 * 索引,
      顶 + 232 * 比例,
    );
  }
}


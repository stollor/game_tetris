/**
 * 暂停遮罩之下的颜色等价物。
 *
 * Phaser 的暂停遮罩是形状层，会把先画的文字压暗；Three 同层里文字总是晚于形状绘制，
 * 文字会浮在遮罩上。状态行这类「本该被压暗」的文字改用压暗后的颜色重画，逐像素等价。
 */
export function 遮罩压暗(颜色: number): number {
  const 调色板 = 读取霓虹调色板();
  return 混色(颜色, 调色板.遮罩, 调色板.遮罩透明度);
}

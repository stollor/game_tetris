/** 顶栏角钮（离开 / 继续 / 暂停）：Phaser 创建霓虹按钮 次要变体 + 采用传入配色。 */
export function 读取角钮视觉(可用 = true): 对局按钮视觉 {
  const 色 = 读取对局界面色();
  const 底色 = 可用 ? 色.按钮次要.面板 : 色.按钮禁用.面板;
  return {
    填色: 底色,
    边框色: 可用 ? 色.按钮次要.描边 : 色.按钮禁用.描边,
    // 文字色跟随底色：框架 获取适配文字色 用相对亮度二选一，这里复用同一判据。
    文字色: 适配文字色(底色),
    透明度: 色.角钮面板透明度,
    边透明度: 色.角钮边框透明度,
    字号: 游戏外观.字体.辅助 + 1,
  };
}

/** 暂停菜单按钮：已选走「主要·点击」，其余走「次要·默认」（框架 界面按钮.当前按钮颜色）。 */

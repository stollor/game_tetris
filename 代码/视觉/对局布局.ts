/** 文字色跟随底色：与框架 `获取适配文字色` / 霓虹按钮文字色 相同的 sRGB 亮度判据。 */
export function 适配文字色(底色: number): number {
  const 线性 = [16, 8, 0].map((位移) => {
    const sRGB = ((底色 >> 位移) & 0xff) / 255;
    return sRGB <= 0.04045 ? sRGB / 12.92 : ((sRGB + 0.055) / 1.055) ** 2.4;
  });
  const 亮度 = 0.2126 * (线性[0] ?? 0) + 0.7152 * (线性[1] ?? 0) + 0.0722 * (线性[2] ?? 0);
  return 1.05 / (亮度 + 0.05) >= (亮度 + 0.05) / 0.05 ? 0xfff8e7 : 0x241d12;
}

/** 按角色取文字样式；覆盖项用于随状态变化的颜色（如已暂存用弱化色）。 */
export function 读取对局文字样式(角色: 对局文字角色, 覆盖?: Partial<文字样式>): 文字样式 {
  const 字体 = 游戏外观.字体.家族;
  const 主题 = 界面主题();
  const 色 = 读取对局界面色();
  let 基础: 文字样式;
  switch (角色) {
    case "顶栏标题":
      // Phaser 标题文字自建 Text 时指定的字体族（不是游戏外观字体）。
      基础 = {
        字体: "Arial, sans-serif",
        字号: 21,
        字重: "粗体",
        颜色: 色.主字,
        字距: 2,
        描边: { 颜色: 色.面板, 粗细: 1 },
      };
      break;
    case "信息标签":
      基础 = { 字体, 字号: 信息标签字号(), 颜色: 色.次字, 字距: 1 };
      break;
    case "信息数值":
      基础 = { 字体, 字号: 信息数值字号(), 字重: "粗体", 颜色: 色.正文 };
      break;
    case "说明标题":
      基础 = { 字体, 字号: 13, 字重: "粗体", 颜色: 色.强调 };
      break;
    case "说明正文":
      基础 = { 字体, 字号: 12, 颜色: 色.次字 };
      break;
    case "说明提示":
      基础 = { 字体, 字号: 11, 颜色: 色.暗字 };
      break;
    case "暂存标签":
      // Phaser 暂存方块栏 的标签是未指定字体族的原生 Text，默认 Courier。
      基础 = { 字体: "Courier", 字号: 11, 颜色: 色.主字 };
      break;
    case "预览标题":
      基础 = { 字体, 字号: 游戏外观.字体.辅助, 字重: "粗体", 颜色: 色.次字, 字距: 2 };
      break;
    case "纪录标签":
      基础 = { 字体, 字号: 12, 颜色: 色.正文, 字距: 2 };
      break;
    case "纪录值":
      基础 = { 字体, 字号: 16, 字重: "粗体", 颜色: 色.强调 };
      break;
    case "状态文字":
      // Phaser 状态文字是未指定字体族的原生 Text，默认 Courier。
      基础 = {
        字体: "Courier",
        字号: 13,
        字重: "粗体",
        颜色: 色.次字,
        描边: { 颜色: 色.面板, 粗细: 1 },
      };
      break;
    case "提示标题":
      // Phaser 场景提示文字：32px 起建，重排结算面板后按比例改成 28px，带 8px 主面板描边。
      基础 = {
        字体: "Courier",
        字号: 28,
        字重: "粗体",
        颜色: 颜色值(主题.面板.主面板.正文文字),
        描边: { 颜色: 颜色值(主题.面板.主面板.背景), 粗细: 8 },
      };
      break;
    case "暂停标题":
      基础 = { 字体, 字号: 29, 字重: "粗体", 颜色: 色.标题 };
      break;
    case "暂停说明":
      基础 = { 字体, 字号: 14, 颜色: 色.次字 };
      break;
  }
  return 覆盖 ? { ...基础, ...覆盖 } : 基础;
}


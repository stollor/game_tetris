/**
 * 对局整页布局：手机棋盘、窄管道侧栏与操作盘共用这一份几何，
 * 绘制、命中和转场以同一棋盘原点与整数格距定位。
 * 触屏操作盘是上三下三，软降更宽；暂停菜单仍是四键竖排。
 */

export interface 对局布局选项 {
  屏幕适配?: 屏幕适配选择;
  /** 设置里的「显示按键说明」；只影响桌面操作说明卡显隐；触屏键始终纯图形。 */
  显示按键说明?: boolean;
  模式: 游戏模式;
  阶段: 游戏阶段;
}

/** 触屏操作盘的六键。 */
export interface 对局布局操作键 {
  名称: string;
  中心X: number;
  中心Y: number;
  宽: number;
  高: number;
}

export interface 对局布局暂停按钮 {
  名称: "继续" | "重开" | "设置" | "菜单";
  标签: string;
  矩形: 矩形;
  已选: boolean;
}


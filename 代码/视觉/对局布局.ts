import type { 矩形 } from "../../组件/绘制/图形对象";
import type { 游戏模式, 游戏阶段 } from "../玩法/再消一行";
import type { 屏幕适配选择, 手机上键旋转 } from "../配置/再消一行设置";
import { 游戏外观 } from "../配置/游戏外观";

/**
 * 对局整页布局（引擎无关）：从 Phaser `代码/场景/对局/对局.ts` 的 `布局界面` 逐字移植，
 * Phaser 与 Three 都按这一份布局计算位置；390×844 下每个数值与 Phaser 现行实现一致。
 * 触屏操作区/暂停菜单用 GM 框架组件的布局算法与默认数值（6 键两行三列、4 键暂停菜单）。
 */

export interface 对局布局选项 {
  屏幕适配?: 屏幕适配选择;
  /** 设置里的「显示按键说明」；影响触屏键标签与桌面操作说明卡显隐。 */
  显示按键说明?: boolean;
  模式: 游戏模式;
  阶段: 游戏阶段;
  手机上键旋转?: 手机上键旋转;
  /** 英文文案下的触屏键提示。 */
  英文?: boolean;
}

/** 触屏操作键（Phaser 触屏操作区 6 键）与侧栏硬降键。 */
export interface 对局布局操作键 {
  名称: string;
  标签: string;
  中心X: number;
  中心Y: number;
  宽: number;
  高: number;
}

export interface 对局布局暂停按钮 {
  名称: "继续" | "重开" | "设置" | "菜单";
  标签: string;
  矩形: 矩形;
  已选: boolean;
}

export interface 对局布局数据 {
  视口宽: number;
  视口高: number;
  竖屏: boolean;
  紧凑: boolean;
  顶部信息底: number;
  操作区顶: number;
  格子大小: number;
  /** 棋盘内区：外框由 `绘制棋盘外框` 自动按 -10 扩展。 */
  棋盘: { 左: number; 上: number; 宽: number; 高: number; 列: number; 行: number };
  棋盘中心X: number;
  信息栏: { 中心X: number; 中心Y: number; 宽: number; 高: number; 列宽: number };
  离开按钮: { 中心X: number; 中心Y: number; 宽: number; 高: number };
  暂停按钮: { 中心X: number; 中心Y: number; 宽: number; 高: number };
  标题: { 中心X: number; 中心Y: number; 字号: number };
  模式文字: { 中心X: number; 上: number; 字号: number; 可见: boolean };
  侧栏: {
    左: number;
    顶: number;
    宽: number;
    高: number;
    底: number;
    预览栏: { 左: number; 顶: number; 宽: number; 高: number; 卡格: number };
    暂存: 矩形;
    下一个标签: { 左: number; 上: number };
    下一步卡: 矩形[];
    最佳纪录: { 标签X: number; 标签Y: number; 值X: number; 值Y: number };
    硬降: { 中心X: number; 中心Y: number; 宽: number; 高: number };
  } | null;
  操作区: { 显示: boolean; 字号: number; 键: 对局布局操作键[] };
  暂停面板: {
    中心X: number;
    中心Y: number;
    比例: number;
    宽: number;
    高: number;
    标题Y: number;
    说明Y: number;
    按钮: 对局布局暂停按钮[];
  };
  状态文字: { 中心X: number; 下: number };
  提示文字: { 中心X: number; 中心Y: number };
  目标提示: { 中心X: number; 中心Y: number; 字号: number };
  操作说明卡: { 可见: boolean; 左: number; 顶: number; 宽: number; 高: number };
}

const 信息栏高度 = 游戏外观.布局.信息栏高度;

/** 触屏操作区默认值（GM `框架/界面/预制体配置.ts` 的 触屏操作区 段）。 */
const 触屏 = {
  横向边距: 16,
  列间距: 10,
  按钮高度: 54,
  底部间距: 60,
  行间距: 64,
  最小宽度: 100,
} as const;

/** 计算对局整页布局。 */
export function 计算对局布局(视口宽: number, 视口高: number, 选项: 对局布局选项): 对局布局数据 {
  const 宽 = 视口宽;
  const 高 = 视口高;
  const 屏幕适配 = 选项.屏幕适配 ?? "自动";
  const 竖屏 = 屏幕适配 === "手机竖屏" || (屏幕适配 === "自动" && 高 > 宽 * 1.05 && 宽 < 1100);
  const 紧凑 = 宽 < 820 || 竖屏;
  const 顶部信息底 = 游戏外观.布局.顶部信息底;
  const 操作区顶 = 高 - 游戏外观.布局.操作区顶部间距;
  const 可用棋盘宽 = 竖屏 ? Math.min(440, 宽 - (宽 < 640 ? 190 : 270)) : 紧凑 ? 宽 - 28 : 宽 - 440;
  const 可用棋盘高 = 竖屏
    ? Math.max(游戏外观.布局.竖屏棋盘最小高度, 操作区顶 - 顶部信息底 - 游戏外观.布局.棋盘上下留白)
    : Math.max(
        高 < 560 ? 120 : 游戏外观.布局.竖屏棋盘最小高度,
        高 - 顶部信息底 - (紧凑 ? 游戏外观.布局.紧凑布局顶部偏移 : 32),
      );
  const 格子大小 = Math.max(
    高 < 560 && !竖屏 ? 8 : 14,
    Math.min(竖屏 ? 40 : 紧凑 ? 32 : 36, 可用棋盘宽 / 10, 可用棋盘高 / 20),
  );
  const 棋盘像素宽 = 10 * 格子大小;
  const 棋盘像素高 = 20 * 格子大小;
  let 棋盘左 = 0;
  let 棋盘上 = 0;
  let 侧栏: 对局布局数据["侧栏"] = null;
  if (竖屏) {
    if (宽 < 640) {
      棋盘左 = 14;
    } else {
      const 内容总宽 = 棋盘像素宽 + 16 + 260;
      棋盘左 = Math.round((宽 - 内容总宽) / 2);
    }
    棋盘上 = Math.round(顶部信息底 + Math.max(0, (操作区顶 - 顶部信息底 - 棋盘像素高) * 0.62));
    const 侧栏X = 棋盘左 + 棋盘像素宽 + (宽 < 640 ? 10 : 16);
    const 侧栏宽 = 宽 < 640 ? 宽 - 侧栏X - 8 : 260;
    const 侧栏顶 = 棋盘上 - 10;
    const 侧栏高 = 棋盘像素高 + 20;
    const 侧栏底 = 侧栏顶 + 侧栏高;
    // 预览栏（下一个方块栏 手机布局）：顶=侧栏顶+82、高=棋盘高-62-82；卡顶=预览顶+28。
    const 预览顶 = 侧栏顶 + 82;
    const 预览宽 = 侧栏宽;
    const 预览高 = 棋盘像素高 - 62 - 82;
    const 卡片顶 = 预览顶 + 28;
    const 卡宽 = 预览宽 - 16;
    const 卡高 = Math.max(34, (预览高 - 28 - 92 - 24) / 3);
    const 卡间距 = 游戏外观.方块.预览格间距;
    const 卡格 = Math.max(8, Math.min(30, (预览宽 - 24) / 4, (卡高 - 8) / 2));
    侧栏 = {
      左: 侧栏X,
      顶: 侧栏顶,
      宽: 侧栏宽,
      高: 侧栏高,
      底: 侧栏底,
      预览栏: { 左: 侧栏X, 顶: 预览顶, 宽: 预览宽, 高: 预览高, 卡格 },
      暂存: { 左: 侧栏X + 8, 上: 侧栏顶 + 2, 宽: 侧栏宽 - 16, 高: 72 },
      下一个标签: { 左: 侧栏X + 8, 上: 预览顶 + 8 },
      下一步卡: [0, 1, 2].map((索引) => ({
        左: 侧栏X + 8,
        上: 卡片顶 + 索引 * (卡高 + 卡间距),
        宽: 卡宽,
        高: 卡高,
      })),
      最佳纪录: {
        标签X: 侧栏X + 侧栏宽 / 2,
        标签Y: 侧栏底 - 124,
        值X: 侧栏X + 侧栏宽 / 2,
        值Y: 侧栏底 - 96,
      },
      硬降: {
        中心X: 侧栏X + 侧栏宽 / 2,
        中心Y: 侧栏底 - 32,
        宽: Math.max(76, 侧栏宽 - 20),
        高: 44,
      },
    };
  } else if (紧凑) {
    棋盘左 = Math.round((宽 - 棋盘像素宽) / 2);
    棋盘上 = Math.max(顶部信息底 + 12, Math.round((高 - 棋盘像素高 + 顶部信息底 - 124) / 2));
  } else {
    const 内容总宽 = 棋盘像素宽 + 32 + 244;
    棋盘左 = Math.round((宽 - 内容总宽) / 2);
    棋盘上 = Math.round(Math.max(顶部信息底 + 12, (高 - 棋盘像素高 + 顶部信息底) / 2));
  }
  const 棋盘中心X = 棋盘左 + 棋盘像素宽 / 2;
  // 触屏操作区（6 键，两行三列；算法与 框架/界面/触屏操作区.布局 一致）。
  const 列数 = 3;
  const 行数 = 2;
  const 显示宽 = Math.max(触屏.最小宽度, 宽 - 触屏.横向边距 * 2);
  const 按钮宽 = (显示宽 - 触屏.列间距 * (列数 - 1)) / 列数;
  const 左边 = (宽 - 显示宽) / 2;
  const 首行Y = 高 - 触屏.底部间距 - (行数 - 1) * 触屏.行间距;
  const 英文 = 选项.英文 === true;
  const 显示说明 = 选项.显示按键说明 !== false;
  const 上键说明 =
    选项.手机上键旋转 === "右转"
      ? 英文
        ? "Right\nHold swap"
        : "右转\n长按暂存"
      : 选项.手机上键旋转 === "180度"
        ? 英文
          ? "180°\nHold swap"
          : "180°\n长按暂存"
        : 英文
          ? "Left\nHold swap"
          : "左转\n长按暂存";
  const 键配方: { 名称: string; 标签: string }[] = [
    { 名称: "左转", 标签: 显示说明 ? (英文 ? "↺ Left turn" : "↺ 左转") : "↺" },
    { 名称: "旋转", 标签: 显示说明 ? `↑ ${上键说明}` : "↑" },
    { 名称: "右转", 标签: 显示说明 ? (英文 ? "↻ Right turn" : "↻ 右转") : "↻" },
    { 名称: "左移", 标签: 显示说明 ? (英文 ? "← Left" : "← 左移") : "←" },
    {
      名称: "软降",
      标签: 显示说明 ? (英文 ? "↓ Soft\nDouble drop" : "↓ 软降\n双击硬降") : "↓",
    },
    { 名称: "右移", 标签: 显示说明 ? (英文 ? "→ Right" : "→ 右移") : "→" },
  ];
  const 操作键: 对局布局操作键[] = 键配方.map((项, 索引) => ({
    名称: 项.名称,
    标签: 项.标签,
    中心X: 左边 + (索引 % 列数) * (按钮宽 + 触屏.列间距) + 按钮宽 / 2,
    中心Y: 首行Y + Math.floor(索引 / 列数) * 触屏.行间距,
    宽: 按钮宽,
    高: 触屏.按钮高度,
  }));
  // 暂停菜单（框架 界面暂停菜单 布局算法）：4 键垂直堆叠。
  const 暂停比例 = Math.min(1, (高 - 24) / 410);
  const 暂停面板宽 = Math.min(470, 宽 - 32) / 暂停比例;
  const 暂停面板高 = Math.min(410, 高 - 32) / 暂停比例;
  const 暂停按钮宽 = Math.min(350, 暂停面板宽 - 56);
  const 暂停行高 = [50, 44, 44, 44];
  const 暂停操作高 = 暂停行高.reduce((和, 高值) => 和 + 高值, 0) + 12 * 3;
  const 暂停操作中心Y = Math.min(46, 暂停面板高 / 2 - 暂停操作高 / 2 - 22);
  const 暂停配置: { 名称: 对局布局暂停按钮["名称"]; 标签: string; 已选: boolean }[] = [
    { 名称: "继续", 标签: "继续", 已选: true },
    { 名称: "重开", 标签: "重新开始", 已选: false },
    { 名称: "设置", 标签: "设置", 已选: false },
    { 名称: "菜单", 标签: "返回主界面", 已选: false },
  ];
  const 暂停按钮: 对局布局暂停按钮[] = 暂停配置.map((项, 索引) => {
    const 上方总高 = 暂停行高.slice(0, 索引).reduce((和, 高值) => 和 + 高值 + 12, 0);
    const 高值 = 暂停行高[索引] ?? 44;
    return {
      名称: 项.名称,
      标签: 项.标签,
      已选: 项.已选,
      矩形: {
        左: 宽 / 2 - 暂停按钮宽 / 2,
        上: 高 / 2 + 暂停操作中心Y - 暂停操作高 / 2 + 上方总高,
        宽: 暂停按钮宽,
        高: 高值,
      },
    };
  });
  return {
    视口宽: 宽,
    视口高: 高,
    竖屏,
    紧凑,
    顶部信息底,
    操作区顶,
    格子大小,
    棋盘: { 左: 棋盘左, 上: 棋盘上, 宽: 棋盘像素宽, 高: 棋盘像素高, 列: 10, 行: 20 },
    棋盘中心X,
    信息栏: {
      中心X: 宽 / 2,
      中心Y: 游戏外观.布局.信息栏顶部,
      宽: 宽 - 24,
      高: 信息栏高度,
      列宽: (宽 - 24) / 3,
    },
    离开按钮: { 中心X: 58, 中心Y: 38, 宽: 78, 高: 38 },
    暂停按钮: { 中心X: 宽 - 58, 中心Y: 38, 宽: 78, 高: 38 },
    标题: { 中心X: 宽 / 2, 中心Y: 38, 字号: 紧凑 ? 18 : 21 },
    模式文字: {
      中心X: 棋盘中心X,
      上: 棋盘上 - 12,
      字号: 竖屏 ? 11 : 12,
      可见: 选项.模式 !== "马拉松",
    },
    侧栏,
    操作区: { 显示: 竖屏 && 选项.阶段 === "进行中", 字号: 14, 键: 操作键 },
    暂停面板: {
      中心X: 宽 / 2,
      中心Y: 高 / 2,
      比例: 暂停比例,
      宽: 暂停面板宽,
      高: 暂停面板高,
      标题Y: -暂停面板高 / 2 + 54,
      说明Y: -暂停面板高 / 2 + 96,
      按钮: 暂停按钮,
    },
    状态文字: { 中心X: 宽 / 2, 下: Math.min(高 - 16, 棋盘上 + 棋盘像素高 + 18) },
    提示文字: { 中心X: 棋盘中心X, 中心Y: 棋盘上 + 棋盘像素高 / 2 - 30 },
    目标提示: {
      中心X: 棋盘中心X,
      中心Y: 棋盘上 + 棋盘像素高 / 2 - 30,
      字号: 竖屏 ? 24 : 28,
    },
    操作说明卡: {
      可见: 显示说明 && !竖屏 && 高 >= 560 && 棋盘左 >= 220 && 选项.阶段 !== "结束",
      左: 棋盘左 - 206,
      顶: 棋盘上 + 28,
      宽: 200,
      高: 230,
    },
  };
}

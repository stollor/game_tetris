/** 桌面/紧凑预览和暂存位置，取自 Phaser 对局.绘制下一个方块。 */
export function 计算对局附属布局(定位: 对局布局数据) {
  const { 棋盘, 紧凑, 竖屏, 视口宽: 宽, 视口高: 高 } = 定位;
  const 左 = 棋盘.左 + 棋盘.宽 + 20;
  const 顶 = 棋盘.上 + 8;
  const 侧宽 = 228;
  const 侧高 = 棋盘.高 - 16;
  const 矮 = 侧高 < 320;
  const 顶距 = 矮 ? 28 : 46;
  const 间距 = 矮 ? 6 : 12;
  const 卡高 = Math.max(30, (侧高 - 顶距 - (矮 ? 70 : 92) - 间距 * 2) / 3);
  const 暂存宽 = 紧凑 ? 94 : 200;
  const 暂存高 = 紧凑 ? 72 : 88;
  const 暂存X = 紧凑 ? 64 : 棋盘.左 - 122;
  const 暂存Y = 紧凑 ? Math.max(160, 棋盘.上 + 45) : Math.min(高 - 52, 棋盘.上 + 300);
  // 方块格尺寸与 Phaser 下一个方块栏.重绘 / 暂存方块栏.显示 同公式（桌面与紧凑分支）。
  const 预览格 = 紧凑 ? 11 : Math.max(8, Math.min(22, (卡高 - 20) / 2, (侧宽 - 40) / 4));
  const 暂存格 = Math.min(18, (暂存高 - 34) / 2, (暂存宽 - 20) / 4);
  return {
    可见: !竖屏,
    暂存: { 左: 暂存X - 暂存宽 / 2, 上: 暂存Y - 暂存高 / 2, 宽: 暂存宽, 高: 暂存高 },
    暂存格,
    预览面板: { 左, 上: 顶, 宽: 侧宽, 高: 侧高 },
    预览格,
    最佳纪录: {
      // Phaser 霓虹纪录页脚 桌面布局：左对齐在侧栏 X + 16，标签/数值分别在侧栏底 - 66 / - 44。
      左: 左 + 16,
      标签Y: 顶 + 侧高 - 66,
      值Y: 顶 + 侧高 - 44,
    },
    下一个标签: { 左: 紧凑 ? 宽 - 108 : 左 + 18, 上: 紧凑 ? 146 : 顶 + 16 },
    下一步卡: [0, 1, 2].map((i) => ({
      左: 紧凑 ? 宽 - 110 : 左 + 12,
      上: 紧凑 ? 168 + i * 62 : 顶 + 顶距 + i * (卡高 + 间距),
      宽: 紧凑 ? 94 : 侧宽 - 24,
      高: 紧凑 ? 50 : 卡高,
    })),
    说明: {
      标题: { x: 定位.操作说明卡.左, y: 定位.操作说明卡.顶 },
      行: Array.from({ length: 6 }, (_, i) => ({
        x: 定位.操作说明卡.左,
        y: 定位.操作说明卡.顶 + 26 + i * 24,
      })),
      提示: { x: 定位.操作说明卡.左, y: 定位.操作说明卡.顶 + 190 },
      面板: { 左: 棋盘.左 - 222, 上: 棋盘.上 + 12, 宽: 200, 高: 230 },
    },
  };
}

/** 触屏操作盘：上排三键等宽，下排左右较窄、软降占中间。 */
const 触屏 = {
  边距: 12,
  间距: 8,
  行高: 58,
  底边: 16,
  最小宽度: 280,
} as const;

/** 计算对局整页布局。 */
export function 计算对局布局(视口宽: number, 视口高: number, 选项: 对局布局选项): 对局布局数据 {
  const 宽 = 视口宽;
  const 高 = 视口高;
  const 屏幕适配 = 选项.屏幕适配 ?? "自动";
  const 竖屏 = 屏幕适配 === "手机竖屏" || (屏幕适配 === "自动" && 高 > 宽 * 1.05 && 宽 < 1100);
  const 紧凑 = 宽 < 820 || 竖屏;
  const 顶部信息底 = 游戏外观.布局.顶部信息底;
  const 操作区顶 = 高 - 游戏外观.布局.操作区顶部间距;
  const 可用棋盘宽 = 竖屏 ? Math.min(440, 宽 - (宽 < 640 ? 138 : 230)) : 紧凑 ? 宽 - 28 : 宽 - 440;
  const 棋盘区域顶 = 顶部信息底;
  const 可用棋盘高 = 竖屏
    ? Math.max(游戏外观.布局.竖屏棋盘最小高度, 操作区顶 - 棋盘区域顶 - 游戏外观.布局.棋盘上下留白)
    : Math.max(
        高 < 560 ? 120 : 游戏外观.布局.竖屏棋盘最小高度,
        高 - 顶部信息底 - (紧凑 ? 游戏外观.布局.紧凑布局顶部偏移 : 32),
      );
  const 格子大小 = Math.max(
    高 < 560 && !竖屏 ? 8 : 14,
    Math.floor(Math.min(竖屏 ? 40 : 紧凑 ? 32 : 36, 可用棋盘宽 / 10, 可用棋盘高 / 20)),
  );
  const 棋盘像素宽 = 10 * 格子大小;
  const 棋盘像素高 = 20 * 格子大小;
  let 棋盘左 = 0;
  let 棋盘上 = 0;
  let 侧栏: 对局布局数据["侧栏"] = null;
  if (竖屏) {
    if (宽 < 640) {
      棋盘左 = 14;
    } else {
      const 内容总宽 = 棋盘像素宽 + 16 + 260;
      棋盘左 = Math.round((宽 - 内容总宽) / 2);
    }
    棋盘上 = Math.round(棋盘区域顶 + Math.max(0, (操作区顶 - 棋盘区域顶 - 棋盘像素高) * 0.62));
    const 侧栏X = 棋盘左 + 棋盘像素宽 + (宽 < 640 ? 10 : 16);
    const 侧栏宽 = 宽 < 640 ? 宽 - 侧栏X - 8 : 260;
    const 侧栏顶 = 棋盘上 - 10;
    const 侧栏高 = 棋盘像素高 + 20;
    const 侧栏底 = 侧栏顶 + 侧栏高;
    const 预览顶 = 侧栏顶 + 104;
    const 预览宽 = 侧栏宽;
    const 预览高 = 侧栏高 - 104 - 96;
    const 卡片顶 = 预览顶 + 28;
    const 卡宽 = 预览宽 - 16;
    const 卡间距 = 8;
    const 卡高 = Math.max(34, (预览高 - 28 - 卡间距 * 2) / 3);
    const 卡格 = Math.floor(Math.max(8, Math.min(22, (预览宽 - 32) / 4, (卡高 * 0.9 - 12) / 2)));
    侧栏 = {
      左: 侧栏X,
      顶: 侧栏顶,
      宽: 侧栏宽,
      高: 侧栏高,
      底: 侧栏底,
      预览栏: { 左: 侧栏X, 顶: 预览顶, 宽: 预览宽, 高: 预览高, 卡格 },
      暂存: { 左: 侧栏X + 8, 上: 侧栏顶 + 2, 宽: 侧栏宽 - 16, 高: 88 },
      下一个标签: { 左: 侧栏X + 侧栏宽 / 2, 上: 预览顶 + 4 },
      下一步卡: [0, 1, 2].map((索引) => ({
        左: 侧栏X + 8,
        上: 卡片顶 + (索引 === 0 ? 0 : 卡高 * 1.2 + 卡间距 + (索引 - 1) * (卡高 * 0.9 + 卡间距)),
        宽: 卡宽,
        高: 卡高 * (索引 === 0 ? 1.2 : 0.9),
      })),
      最佳纪录: {
        标签X: 侧栏X + 侧栏宽 / 2,
        标签Y: 侧栏底 - 68,
        值X: 侧栏X + 侧栏宽 / 2,
        值Y: 侧栏底 - 44,
      },
    };
  } else if (紧凑) {
    棋盘左 = Math.round((宽 - 棋盘像素宽) / 2);
    棋盘上 = Math.max(顶部信息底 + 12, Math.round((高 - 棋盘像素高 + 顶部信息底 - 124) / 2));
  } else {
    const 内容总宽 = 棋盘像素宽 + 32 + 244;
    棋盘左 = Math.round((宽 - 内容总宽) / 2);
    棋盘上 = Math.round(Math.max(顶部信息底 + 12, (高 - 棋盘像素高 + 顶部信息底) / 2));
  }
  const 棋盘中心X = 棋盘左 + 棋盘像素宽 / 2;
  // 触屏操作盘：上排左转 / 暂存 / 右转，下排左移 / 软降 / 右移。
  const 显示宽 = Math.max(触屏.最小宽度, 宽 - 触屏.边距 * 2);
  const 左边 = (宽 - 显示宽) / 2;
  const 次行Y = 高 - 触屏.底边 - 触屏.行高 / 2;
  const 首行Y = 次行Y - 触屏.行高 - 触屏.间距;
  const 顶宽 = (显示宽 - 触屏.间距 * 2) / 3;
  const 侧宽 = (显示宽 - 触屏.间距 * 2) * 0.27;
  const 中宽 = 显示宽 - 触屏.间距 * 2 - 侧宽 * 2;
  const 显示说明 = 选项.显示按键说明 !== false;
  const 键配方 = ["左转", "暂存操作", "右转", "左移", "软降", "右移"];
  const 底中心 = [
    左边 + 侧宽 / 2,
    左边 + 侧宽 + 触屏.间距 + 中宽 / 2,
    左边 + 侧宽 + 触屏.间距 + 中宽 + 触屏.间距 + 侧宽 / 2,
  ];
  const 操作键: 对局布局操作键[] = 键配方.map((项, 索引) => {
    const 上排 = 索引 < 3;
    return {
      名称: 项,
      中心X: 上排 ? 左边 + 索引 * (顶宽 + 触屏.间距) + 顶宽 / 2 : (底中心[索引 - 3] ?? 0),
      中心Y: 上排 ? 首行Y : 次行Y,
      宽: 上排 ? 顶宽 : 索引 === 4 ? 中宽 : 侧宽,
      高: 触屏.行高,
    };
  });
  // 暂停菜单（框架 界面暂停菜单 布局算法）：4 键垂直堆叠。
  const 暂停比例 = Math.min(1, (高 - 24) / 410);
  const 暂停面板宽 = Math.min(470, 宽 - 32) / 暂停比例;
  const 暂停面板高 = Math.min(410, 高 - 32) / 暂停比例;
  const 暂停按钮宽 = Math.min(350, 暂停面板宽 - 56);
  const 暂停行高 = [50, 44, 44, 44];
  const 暂停操作高 = 暂停行高.reduce((和, 高值) => 和 + 高值, 0) + 12 * 3;
  const 暂停操作中心Y = Math.min(46, 暂停面板高 / 2 - 暂停操作高 / 2 - 22);
  const 暂停配置: { 名称: 对局布局暂停按钮["名称"]; 标签: string; 已选: boolean }[] = [
    { 名称: "继续", 标签: "继续", 已选: true },
    { 名称: "重开", 标签: "重新开始", 已选: false },
    { 名称: "设置", 标签: "设置", 已选: false },
    { 名称: "菜单", 标签: "返回主界面", 已选: false },
  ];
  const 暂停按钮: 对局布局暂停按钮[] = 暂停配置.map((项, 索引) => {
    const 上方总高 = 暂停行高.slice(0, 索引).reduce((和, 高值) => 和 + 高值 + 12, 0);
    const 高值 = 暂停行高[索引] ?? 44;
    return {
      名称: 项.名称,
      标签: 项.标签,
      已选: 项.已选,
      矩形: {
        左: 宽 / 2 - 暂停按钮宽 / 2,
        上: 高 / 2 + 暂停操作中心Y - 暂停操作高 / 2 + 上方总高,
        宽: 暂停按钮宽,
        高: 高值,
      },
    };
  });
  return {
    视口宽: 宽,
    视口高: 高,
    竖屏,
    紧凑,
    顶部信息底,
    操作区顶,
    格子大小,
    棋盘: { 左: 棋盘左, 上: 棋盘上, 宽: 棋盘像素宽, 高: 棋盘像素高, 列: 10, 行: 20 },
    棋盘中心X,
    信息栏: {
      中心X: 宽 / 2,
      中心Y: 游戏外观.布局.信息栏顶部,
      宽: 宽 - 24,
      高: 信息栏高度,
      列宽: (宽 - 24) / 3,
    },
    离开按钮: { 中心X: 43, 中心Y: 38, 宽: 48, 高: 38 },
    暂停按钮: { 中心X: 宽 - 43, 中心Y: 38, 宽: 48, 高: 38 },
    标题: { 中心X: 宽 / 2, 中心Y: 38, 字号: 紧凑 ? 20 : 23 },
    模式文字: {
      中心X: 棋盘中心X,
      上: 棋盘上 - 12,
      字号: 竖屏 ? 11 : 12,
      可见: 选项.模式 !== "马拉松",
    },
    侧栏,
    操作区: { 显示: 竖屏 && 选项.阶段 === "进行中", 字号: 14, 键: 操作键 },
    暂停面板: {
      中心X: 宽 / 2,
      中心Y: 高 / 2,
      比例: 暂停比例,
      宽: 暂停面板宽,
      高: 暂停面板高,
      标题Y: -暂停面板高 / 2 + 54,
      说明Y: -暂停面板高 / 2 + 96,
      按钮: 暂停按钮,
    },
    状态文字: { 中心X: 宽 / 2, 下: Math.min(高 - 16, 棋盘上 + 棋盘像素高 + 18) },
    提示文字: { 中心X: 棋盘中心X, 中心Y: 棋盘上 + 棋盘像素高 / 2 - 30 },
    目标提示: {
      中心X: 棋盘中心X,
      中心Y: 棋盘上 + 棋盘像素高 / 2 - 30,
      字号: 竖屏 ? 24 : 28,
    },
    操作说明卡: {
      底板可见: 显示说明 && !竖屏 && 高 >= 560 && 棋盘左 >= 220,
      可见: 显示说明 && !竖屏 && 高 >= 560 && 棋盘左 >= 220 && 选项.阶段 !== "结束",
      左: 棋盘左 - 206,
      顶: 棋盘上 + 28,
      宽: 200,
      高: 230,
    },
  };
}


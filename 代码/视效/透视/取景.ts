/**
 * 房间取景（纯函数，不依赖 three）。
 *
 * 相机永远正对开口、只看 -z 方向，不做俯仰与偏转——这是俄罗斯方块需要的正视图。
 *
 * 背墙保持 10×20 正方格；开口宽度按视口比展开，两侧内壁向背墙收拢。
 * 开口高度恒等于网格高度，顶底空白由后墙占比控制。
 *
 * 坐标：相机 z = +相机距离，开口 z = 0，背墙 z = -进深。
 * 世界高度 1 在距离 x 处的视口高度 = x × 2tan(视野/2)，记作视口(x)。
 *
 * 两条标定：
 * 1. 开口贴满视口：行 / 视口(相机距离) = 1      → 相机距离 = 行 / 视口单位
 * 2. 背墙占视口比例 p：行 / 视口(相机距离 + 进深) = p
 *    → 进深 = 相机距离 × (1/p - 1)
 */

export interface 房间取景输入 {
  /** 网格列数。 */
  列: number;
  /** 网格行数。 */
  行: number;
  /** 竖直视野角（度）。 */
  视野: number;
  /** 视口宽高比（宽 / 高）。 */
  宽高比: number;
  /** 背墙竖向占视口高度的比例。 */
  后墙占比: number;
}

export interface 房间取景结果 {
  /** 相机到开口距离。 */
  开口距离: number;
  /** 相机到背墙距离。 */
  背墙距离: number;
  /** 开口到背墙的进深。 */
  进深: number;
  /** 房间横截面的世界宽高，恒等于网格尺寸。 */
  宽: number;
  高: number;
  /** 口沿按视口宽高比展开，背墙尺寸和玩法格宽不变。 */
  开口宽: number;
  /** 相机位置：x/y 恒为 0。 */
  位置: [number, number, number];
  /** 注视点：背墙中心，与网格中心重合。 */
  目标: [number, number, number];
}

const 弧度 = Math.PI / 180;

export function 计算房间取景(输入: 房间取景输入): 房间取景结果 {
  const 视口单位 = 2 * Math.tan((输入.视野 * 弧度) / 2);
  // 约束 1：开口贴满视口，所以相机距离由行数与视野决定，与视口宽高比无关。
  const 开口距离 = 输入.行 / 视口单位;
  // 约束 2：背墙距离 = 行 / (占比 × 视口单位)，进而得到进深。
  const 占比 = Math.max(0.3, Math.min(0.98, 输入.后墙占比));
  const 背墙距离 = 输入.行 / (占比 * 视口单位);
  const 进深 = 背墙距离 - 开口距离;
  return {
    开口距离,
    背墙距离,
    进深,
    宽: 输入.列,
    高: 输入.行,
    开口宽: 输入.行 * 输入.宽高比,
    位置: [0, 0, 开口距离],
    目标: [0, 0, -进深],
  };
}

/** 后墙相对开口的缩小比例（世界尺寸相同，所以这里是画面比例）。 */
export function 计算后墙缩放(开口距离: number, 背墙距离: number): number {
  return 开口距离 / 背墙距离;
}

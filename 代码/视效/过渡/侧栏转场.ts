import type { 方块类型 } from "../../玩法/再消一行";
import type { 对局布局数据 } from "../../页面/布局/对局布局";

/** 只记录真实换块的旧内容，进度不改变玩法状态或等待输入。 */
export interface 侧栏转场 {
  类型: "出块" | "暂存";
  经过秒: number;
  移出: 方块类型;
  原格子: [number, number][];
  暂存: 方块类型 | null;
  队列: 方块类型[];
}

export const 侧栏转场时长 = 0.38;

export function 更新侧栏转场(转场: 侧栏转场, 秒: number): 侧栏转场 | null {
  const 经过秒 = 转场.经过秒 + Math.max(0, 秒);
  return 经过秒 >= 侧栏转场时长 ? null : { ...转场, 经过秒 };
}

export function 读取侧栏转场帧(转场: 侧栏转场, 布局: 对局布局数据) {
  const t = Math.max(0, Math.min(1, 转场.经过秒 / 侧栏转场时长));
  const 进度 = t * t * (3 - 2 * t);
  const 侧栏 = 布局.侧栏;
  const 首卡 = 侧栏?.下一步卡[0];
  const 飞块: { 类型: 方块类型; x: number; y: number; 格: number; 透明度: number }[] = [];
  const 出队 = 转场.类型 === "出块" || 转场.暂存 === null;
  if (!侧栏 || !首卡) return { 进度, 出队, 飞块 };
  const 出生 = { x: 布局.棋盘中心X, y: 布局.棋盘.上 + 布局.格子大小 * 0.55 };
  const 槽 = { x: 侧栏.暂存.左 + 侧栏.暂存.宽 / 2, y: 侧栏.暂存.上 + 侧栏.暂存.高 * 0.55 };
  const 飞行 = (
    类型: 方块类型,
    起: { x: number; y: number },
    终: { x: number; y: number },
    起格: number,
    终格: number,
  ) => {
    const 弯Y = Math.min(起.y, 终.y) - 95;
    const 横进度 = 起.x > 终.x ? 1 - (1 - 进度) ** 3 : 进度;
    飞块.push({
      类型,
      x: 起.x + (终.x - 起.x) * 横进度,
      y: (1 - 进度) ** 2 * 起.y + 2 * (1 - 进度) * 进度 * 弯Y + 进度 ** 2 * 终.y,
      格: 起格 + (终格 - 起格) * 进度,
      透明度: 0.82 + Math.sin(t * Math.PI) * 0.08,
    });
  };
  if (出队 && 转场.队列[0])
    飞行(
      转场.队列[0],
      { x: 首卡.左 + 首卡.宽 / 2, y: 首卡.上 + 首卡.高 / 2 },
      出生,
      侧栏.预览栏.卡格,
      布局.格子大小,
    );
  if (转场.类型 === "暂存") {
    const 列 = 转场.原格子.map(([列]) => 列);
    const 行 = 转场.原格子.map(([, 行]) => 行);
    const 起 = {
      x: 布局.棋盘.左 + ((Math.min(...列) + Math.max(...列) + 1) / 2) * 布局.格子大小,
      y: Math.max(
        布局.棋盘.上,
        布局.棋盘.上 + ((Math.min(...行) + Math.max(...行) + 1) / 2) * 布局.格子大小,
      ),
    };
    飞行(转场.移出, 起, 槽, 布局.格子大小, 20);
    if (转场.暂存) 飞行(转场.暂存, 槽, 出生, 20, 布局.格子大小);
  }
  return { 进度, 出队, 飞块 };
}

import { type 流转块, type 流转矩形, 由锚点取矩形 } from "../../../框架/界面/流转";
import type { 文字样式, 文字项 } from "../../../框架/界面/绘制/协议";
import { 计算金币条 } from "../../../组件/基础/金币条配方";
import { type 主界面布局, type 主界面文字数据, 生成主界面文字项 } from "../../页面/布局/主界面布局";

/**
 * 主界面三态各自要参与流转的块。
 * 身份相同的内容（金币、游戏标题）由框架决定停住、位移或变形。
 * 只在一侧出现的块声明希望的滑动方向；离屏幕边缘太远时，框架会改成原地淡入淡出。
 */

export interface 主界面流转输入 {
  布局: 主界面布局;
  文字: 主界面文字数据;
  金币: number;
  测量(文案: string, 样式: 文字样式): { 宽: number; 高: number };
}

function 按钮矩形(区域: { 中心X: number; 中心Y: number; 宽: number; 高: number }): 流转矩形 {
  return {
    左: 区域.中心X - 区域.宽 / 2,
    上: 区域.中心Y - 区域.高 / 2,
    宽: 区域.宽,
    高: 区域.高,
  };
}

function 文字矩形(项: 文字项, 测量: 主界面流转输入["测量"]): 流转矩形 {
  const 尺寸 = 测量(项.文案, 项.样式);
  const 宽 = 尺寸.宽 > 0 ? 尺寸.宽 : Math.max(1, Array.from(项.文案).length * 项.样式.字号);
  const 高 = 尺寸.高 > 0 ? 尺寸.高 : 项.样式.字号;
  return 由锚点取矩形(项.锚点, 项.x, 项.y, 宽, 高);
}

export function 生成主界面流转块(输入: 主界面流转输入): 流转块[] {
  const { 布局 } = 输入;
  const 块: 流转块[] = [];
  if (布局.状态 === "纯享" && 布局.纯享) {
    块.push({
      身份: "纯享",
      矩形: { 左: 0, 上: 0, 宽: 布局.视口.宽, 高: 布局.视口.高 },
      位移: { x: 0, y: 160 },
    });
    return 块;
  }
  const 金币 = 计算金币条(布局.金币.左, 布局.金币.上, 输入.金币);
  块.push({
    身份: "金币",
    矩形: { 左: 金币.左, 上: 金币.上, 宽: 金币.宽, 高: 金币.高 },
    位移: { x: 0, y: -100 },
  });
  for (const 项 of 生成主界面文字项(布局, 输入.文字)) {
    const 是游戏名 = 项.文案 === 输入.文字.游戏名称;
    块.push({
      身份: 是游戏名 ? "游戏标题" : "选择模式",
      矩形: 文字矩形(项, 输入.测量),
      位移: 是游戏名 ? { x: 0, y: -布局.视口.高 / 2 } : { x: 0, y: 36 },
    });
  }
  if (布局.状态 === "菜单") {
    布局.角钮.项.forEach((项, 索引) => {
      const 中心Y = 布局.角钮.中心Y[索引];
      if (中心Y === undefined) return;
      块.push({
        身份: `角钮:${项.文案.中文}`,
        矩形: 按钮矩形({
          中心X: 布局.角钮.中心X,
          中心Y,
          宽: 布局.角钮.宽,
          高: 布局.角钮.高,
        }),
        位移: { x: -120, y: 0 },
      });
    });
    if (布局.开始钮) {
      块.push({
        身份: "开始游戏",
        矩形: 按钮矩形(布局.开始钮),
        位移: { x: 0, y: 布局.视口.高 - 布局.开始钮.中心Y + 80 },
      });
    }
  }
  布局.模式选择?.卡.forEach((区域, 索引) => {
    块.push({
      身份: `模式:${区域.模式}`,
      矩形: 按钮矩形(区域),
      位移: { x: (索引 % 2 ? 1 : -1) * 布局.视口.宽, y: 0 },
    });
  });
  if (布局.模式选择) {
    块.push({
      身份: "返回",
      矩形: 按钮矩形(布局.模式选择.返回钮),
      位移: { x: 0, y: 100 },
    });
  }
  return 块;
}

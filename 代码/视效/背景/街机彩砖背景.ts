import type { 图形对象 } from "../../../框架/界面/绘制/协议";
import { 亮色, 暗色, 混色 } from "../../../框架/界面/颜色工具";
import { 街机彩砖规范 } from "../../主题/像素/像素规范";
import { 绘制天幕, 随机值 } from "./通用";

/**
 * 街机彩砖的专属后景：整个画面就是一台深色机台的正面。
 * 语言是 4px 像素网格——顶部跑马灯檐、机台壳体包住的点阵屏、底部像素彩砖墙、两侧机台轨。
 * 纯函数：只读 `街机彩砖规范`，不读设置与主题；静态底只烘一次，动态层把透明度统一乘 亮度。
 */

/** 七色序列，跑马灯与彩砖共用；顺序固定，保证同一时间点画面可复现。 */
function 取七色(): number[] {
  const 色 = 街机彩砖规范.色;
  return [色.红, 色.黄, 色.绿, 色.蓝, 色.紫, 色.青, 色.橙];
}

interface 机台尺度 {
  轨宽: number;
  檐高: number;
  底条: number;
  屏左: number;
  屏右: number;
  屏顶: number;
  屏底: number;
}

/** 机台骨架全部按宽高比例推导，不锁定 390×844。 */
function 取机台尺度(宽: number, 高: number): 机台尺度 {
  const 网格 = 街机彩砖规范.网格;
  const 轨宽 = Math.max(14, Math.min(18, Math.round(宽 * 0.042)));
  const 檐高 = Math.max(24, Math.min(38, Math.round(高 * 0.042)));
  const 底条 = Math.max(9, Math.min(14, Math.round(高 * 0.016)));
  const 窗厚 = 网格 * 2;
  return {
    轨宽,
    檐高,
    底条,
    屏左: 轨宽 + 窗厚,
    屏右: 宽 - 轨宽 - 窗厚,
    屏顶: 檐高 + 窗厚,
    屏底: 高 - 底条 - 窗厚,
  };
}

/** 檐口灯位：灯泡行位置与数量，静态灯与动态追光共用同一套坐标。 */
function 取檐灯(宽: number, 尺: 机台尺度): { y: number; 数: number } {
  return { y: Math.round(尺.檐高 * 0.3), 数: Math.floor((宽 - 尺.轨宽 * 2 - 24) / 20) };
}

/** 以屏幕窗口为基准，向外 距 处画一圈 厚 的实色框；同色实心，重叠不叠影。 */
function 画框环(
  图: 图形对象,
  宽: number,
  尺: 机台尺度,
  距: number,
  厚: number,
  色值: number,
): void {
  const 外 = 距 + 厚;
  const 上 = 尺.屏顶 - 外;
  const 下 = 尺.屏底 + 外;
  图.fillStyle(色值);
  图.fillRect(0, 上, 宽, 厚);
  图.fillRect(0, 下 - 厚, 宽, 厚);
  图.fillRect(尺.屏左 - 外, 上, 厚, 下 - 上);
  图.fillRect(尺.屏右 + 距, 上, 厚, 下 - 上);
}

/**
 * 机厅暗角：四条线性渐变压边。
 * 不用通用的 `绘制暗角`——它靠四角三层同心圆叠加，在提亮过的屏面上会留下肉眼可见的圆弧带。
 */
function 绘制机厅暗角(图: 图形对象, 宽: number, 高: number): void {
  const 暗 = 暗色(街机彩砖规范.色.夜, 0.6);
  图.fillGradientStyle(暗, 暗, 暗, 暗, 0.42, 0.42, 0, 0).fillRect(0, 0, 宽, 高 * 0.13);
  图.fillGradientStyle(暗, 暗, 暗, 暗, 0, 0, 0.46, 0.46).fillRect(0, 高 - 高 * 0.2, 宽, 高 * 0.2);
  图.fillGradientStyle(暗, 暗, 暗, 暗, 0.34, 0, 0.34, 0).fillRect(0, 0, 宽 * 0.11, 高);
  图.fillGradientStyle(暗, 暗, 暗, 暗, 0, 0.34, 0, 0.34).fillRect(宽 - 宽 * 0.11, 0, 宽 * 0.11, 高);
}

/** 静态底：天幕 → 屏面 → 顶光 → 彩砖墙 → 机台壳体 → 檐口 → 暗角。 */
export function 绘制街机彩砖背景(图: 图形对象, 宽: number, 高: number): void {
  if (!(宽 > 0) || !(高 > 0)) return;
  const 色 = 街机彩砖规范.色;
  const 网格 = 街机彩砖规范.网格;
  const 七 = 取七色();
  const 尺 = 取机台尺度(宽, 高);
  const 屏宽 = 尺.屏右 - 尺.屏左;
  const 屏高 = 尺.屏底 - 尺.屏顶;
  const 砖 = 8;
  const 砖距 = 12;

  // 天幕：机厅整体压暗，中段掺一点暖色，避免整屏发紫。
  绘制天幕(图, 宽, 0, 高, [色.夜, 色.底, 混色(色.暗纸, 色.亮, 0.05), 色.底, 色.夜]);
  // 屏面玻璃：比近黑的机壳亮一档，"深色井 + 亮屏幕"的关系靠这一层立住。
  图
    .fillStyle(混色(混色(色.纸, 色.次字, 0.12), 色.亮, 0.06), 0.38)
    .fillRect(尺.屏左, 尺.屏顶, 屏宽, 屏高);
  // 屏幕顶光：跑马灯往下洒的暖光，纵向两段渐变收干净，不留圆环。
  图
    .fillGradientStyle(色.亮, 色.亮, 色.亮, 色.亮, 0.07, 0.07, 0.02, 0.02)
    .fillRect(尺.屏左, 尺.屏顶, 屏宽, 高 * 0.07);
  图
    .fillGradientStyle(色.亮, 色.亮, 色.亮, 色.亮, 0.02, 0.02, 0, 0)
    .fillRect(尺.屏左, 尺.屏顶 + 高 * 0.07, 屏宽, 高 * 0.3);
  // 玻璃斜反光：一条极淡的平行四边形，给屏面一点玻璃厚度。
  图.fillStyle(亮色(色.纸, 0.2), 0.014).fillPoints([
    { x: 尺.屏左 + 屏宽 * 0.3, y: 尺.屏顶 },
    { x: 尺.屏左 + 屏宽 * 0.42, y: 尺.屏顶 },
    { x: 尺.屏左 + 屏宽 * 0.16, y: 尺.屏底 },
    { x: 尺.屏左 + 屏宽 * 0.04, y: 尺.屏底 },
  ]);

  // 像素彩砖墙（台座）：每一皮同色系、错缝连续；同皮里每四块压一块暗砖。
  const 台顶 = 尺.屏底 - 11 * 砖距;
  const 台列数 = Math.floor((屏宽 - 6) / 砖距);
  for (let 皮 = 0; 皮 < 11; 皮 += 1) {
    const 皮色 = 七[皮 % 七.length] ?? 色.蓝;
    const y = 台顶 + 皮 * 砖距;
    const 偏移 = (皮 % 2) * 6;
    for (const 暗砖 of [false, true]) {
      图.fillStyle(暗砖 ? 暗色(皮色, 0.38) : 皮色, 暗砖 ? 0.15 : 0.17);
      for (let 列 = 0; 列 < 台列数; 列 += 1) {
        if ((列 % 4 === 3) !== 暗砖) continue;
        图.fillRect(尺.屏左 + 偏移 + 列 * 砖距, y, 砖, 砖);
      }
    }
  }
  // 像素彩砖墙（两侧）：两列错缝砖，三行一组换色，从檐下一路铺到台座。
  const 侧顶 = 尺.屏顶 + 网格 * 2;
  const 侧行数 = Math.max(1, Math.floor((台顶 - 侧顶) / 砖距));
  const 侧砖色 = [色.蓝, 色.紫, 色.青];
  for (let 组 = 0; 组 < 侧砖色.length; 组 += 1) {
    图.fillStyle(侧砖色[组] ?? 色.蓝, 0.15);
    for (let 行 = 0; 行 < 侧行数; 行 += 1) {
      if (Math.floor(行 / 3) % 侧砖色.length !== 组) continue;
      const y = 侧顶 + 行 * 砖距;
      const 偏移 = (行 % 2) * 6;
      for (let 列 = 0; 列 < 2; 列 += 1) {
        const 左x = 尺.屏左 + 偏移 + 列 * 砖距;
        const 右x = 尺.屏右 - 砖 - 偏移 - 列 * 砖距;
        if (左x + 砖 > 尺.屏右 || 右x < 尺.屏左) continue;
        图.fillRect(左x, y, 砖, 砖);
        图.fillRect(右x, y, 砖, 砖);
      }
    }
  }
  // 机台壳体：先整块填到屏幕边缘，再向内收三层台阶 + 1px 亮棱，做出开窗厚度。
  const 壳色 = 暗色(色.壳, 0.45);
  图.fillStyle(壳色);
  图.fillRect(0, 0, 宽, 尺.屏顶);
  图.fillRect(0, 尺.屏底, 宽, 高 - 尺.屏底);
  图.fillRect(0, 尺.屏顶, 尺.屏左, 屏高);
  图.fillRect(尺.屏右, 尺.屏顶, 宽 - 尺.屏右, 屏高);
  画框环(图, 宽, 尺, 4, 4, 暗色(色.壳, 0.3));
  画框环(图, 宽, 尺, 2, 2, 暗色(色.壳, 0.62));
  画框环(图, 宽, 尺, 0, 2, 暗色(色.壳, 0.82));
  图.fillStyle(混色(色.暗, 色.次字, 0.55));
  图.fillRect(尺.屏左 - 1, 尺.屏顶 - 1, 屏宽 + 2, 1);
  图.fillRect(尺.屏左 - 1, 尺.屏底, 屏宽 + 2, 1);
  图.fillRect(尺.屏左 - 1, 尺.屏顶 - 1, 1, 屏高 + 2);
  图.fillRect(尺.屏右, 尺.屏顶 - 1, 1, 屏高 + 2);
  // 屏内的上沿投影：1px 亮棱下面压一点暗，开窗才有深度。
  图
    .fillGradientStyle(
      暗色(色.壳, 0.3),
      暗色(色.壳, 0.3),
      暗色(色.壳, 0.3),
      暗色(色.壳, 0.3),
      0.4,
      0.4,
      0,
      0,
    )
    .fillRect(尺.屏左, 尺.屏顶, 屏宽, 网格 * 3);

  // 侧轨：实心机台边 + 1px 金属高光 + 分段接缝，屏幕开窗靠它包住。
  const 轨光 = 亮色(色.次字, 0.2);
  图.fillStyle(轨光, 0.55).fillRect(1, 0, 1, 高);
  图.fillStyle(轨光, 0.55).fillRect(宽 - 2, 0, 1, 高);
  图.fillStyle(暗色(色.壳, 0.7), 0.85).fillRect(尺.轨宽 - 2, 0, 2, 高);
  图.fillStyle(暗色(色.壳, 0.7), 0.85).fillRect(宽 - 尺.轨宽, 0, 2, 高);
  for (let y = 尺.檐高 + 40; y < 高 - 尺.底条 - 24; y += 120) {
    图.fillStyle(暗色(色.壳, 0.7), 0.85).fillRect(0, Math.round(y), 尺.轨宽, 2);
    图.fillStyle(暗色(色.壳, 0.7), 0.85).fillRect(宽 - 尺.轨宽, Math.round(y), 尺.轨宽, 2);
  }

  // 顶部檐口：机台顶边 + 跑马灯面板，灯行是七色间的像素灯泡。
  const 檐灯 = 取檐灯(宽, 尺);
  图
    .fillGradientStyle(
      混色(色.壳, 色.暗纸, 0.22),
      混色(色.壳, 色.暗纸, 0.22),
      色.壳,
      色.壳,
      1,
      1,
      1,
      1,
    )
    .fillRect(0, 0, 宽, 尺.檐高);
  图.fillStyle(亮色(色.次字, 0.15), 0.35).fillRect(0, 0, 宽, 1);
  // 灯泡下的暖光先铺，灯泡盖在上面
  图
    .fillGradientStyle(色.亮, 色.亮, 色.亮, 色.亮, 0.02, 0.02, 0.11, 0.11)
    .fillRect(0, 檐灯.y - 8, 宽, 尺.檐高 - 檐灯.y + 8);
  for (let 色序 = 0; 色序 < 七.length; 色序 += 1) {
    图.fillStyle(七[色序] ?? 色.黄, 0.42);
    for (let 序 = 色序; 序 < 檐灯.数; 序 += 七.length) {
      图.fillRect(尺.轨宽 + 12 + 序 * 20, 檐灯.y, 6, 6);
    }
  }
  // 檐下金线 + 一道暗缝，把檐口和屏面分开
  图.fillStyle(色.亮, 0.45).fillRect(尺.轨宽 + 4, 尺.檐高 - 7, 宽 - 尺.轨宽 * 2 - 8, 1);
  图.fillStyle(色.亮, 0.4).fillRect(0, 尺.檐高 - 1, 宽, 1);
  图.fillStyle(暗色(色.壳, 0.5), 0.8).fillRect(0, 尺.檐高, 宽, 1);

  // 底部控制台檐：横梁 + 金线 + 三级矩形台阶，硬边无圆角。
  图.fillStyle(暗色(色.壳, 0.45)).fillRect(0, 高 - 尺.底条, 宽, 尺.底条);
  图.fillStyle(色.亮, 0.2).fillRect(0, 高 - 尺.底条, 宽, 1);
  图.fillStyle(暗色(色.壳, 0.7), 0.8).fillRect(0, 高 - 尺.底条 + 2, 宽, 1);
  for (let 级 = 0; 级 < 3; 级 += 1) {
    const 缩 = 级 * 5;
    图
      .fillStyle(暗色(色.壳, 0.1 + 级 * 0.1), 0.9)
      .fillRect(尺.轨宽 + 缩, 高 - 尺.底条 - 4 - 级 * 3, 宽 - 尺.轨宽 * 2 - 缩 * 2, 3);
  }
  // 四角螺丝：2×2 亮点 + 1px 阴影，把机台壳体的制造感点出来。
  for (const [螺丝x, 螺丝y] of [
    [尺.轨宽 - 3, 尺.檐高 + 6],
    [宽 - 尺.轨宽 + 1, 尺.檐高 + 6],
    [尺.轨宽 - 3, 高 - 尺.底条 - 8],
    [宽 - 尺.轨宽 + 1, 高 - 尺.底条 - 8],
  ] as const) {
    图.fillStyle(亮色(色.次字, 0.15), 0.5).fillRect(螺丝x, 螺丝y, 2, 2);
    图.fillStyle(暗色(色.壳, 0.5), 0.7).fillRect(螺丝x, 螺丝y + 2, 2, 1);
  }

  // 屏角切角：两层矩形台阶咬出机台开窗，比圆角更像素。
  for (const [角x, 角y, 横, 纵] of [
    [尺.屏左, 尺.屏顶, 1, 1],
    [尺.屏右, 尺.屏顶, -1, 1],
    [尺.屏左, 尺.屏底, 1, -1],
    [尺.屏右, 尺.屏底, -1, -1],
  ] as const) {
    for (let 级 = 0; 级 < 2; 级 += 1) {
      const 边长 = 网格 * (2 - 级);
      const x = 横 > 0 ? 角x - 网格 : 角x - 边长 + 网格;
      const y = 纵 > 0 ? 角y - 网格 : 角y - 网格;
      图.fillStyle(壳色).fillRect(x, y, 边长, 网格);
    }
  }

  绘制机厅暗角(图, 宽, 高);
}

/** 动态层：CRT 扫描带、侧轨跑马灯泡、像素余烬、中央光呼吸、檐口追光。 */
export function 绘制街机彩砖背景动态(
  图: 图形对象,
  宽: number,
  高: number,
  时间秒: number,
  亮度 = 1,
): void {
  if (!(宽 > 0) || !(高 > 0)) return;
  const 色 = 街机彩砖规范.色;
  const 网格 = 街机彩砖规范.网格;
  const 七 = 取七色();
  const 尺 = 取机台尺度(宽, 高);
  const 屏宽 = 尺.屏右 - 尺.屏左;
  const 屏高 = 尺.屏底 - 尺.屏顶;
  const 秒 = Math.max(0, 时间秒);
  // 动态层所有透明度都过这一层：亮度只缩放透明度，不改调用结构。
  const 填 = (色值: number, 透明度: number) => 图.fillStyle(色值, 透明度 * 亮度);

  // 1. CRT 扫描带：带芯 4px，上下各 8px 渐隐，是柔和的磷光带而不是一条硬线。
  const 相 = (((秒 % 4) + 4) % 4) / 4;
  const 扫y = 尺.屏顶 + Math.round((相 * 屏高) / 网格) * 网格;
  const 晕高 = 网格 * 2;
  const 上顶 = Math.max(尺.屏顶, 扫y - 晕高);
  const 下底 = Math.min(尺.屏底, 扫y + 网格 + 晕高);
  图
    .fillGradientStyle(色.亮, 色.亮, 色.亮, 色.亮, 0, 0, 0.035 * 亮度, 0.035 * 亮度)
    .fillRect(尺.屏左, 上顶, 屏宽, Math.max(0, 扫y - 上顶));
  填(色.亮, 0.035).fillRect(尺.屏左, 扫y, 屏宽, 网格);
  图
    .fillGradientStyle(色.亮, 色.亮, 色.亮, 色.亮, 0.035 * 亮度, 0.035 * 亮度, 0, 0)
    .fillRect(尺.屏左, 扫y + 网格, 屏宽, Math.max(0, 下底 - 扫y - 网格));

  // 2. 侧轨跑马灯泡：两侧各 7 颗 4×4 灯泡按约 1.2s 一轮追逐，亮灯带 2px 光晕。
  const 灯数 = 7;
  const 灯区顶 = 尺.屏顶 + 16;
  const 灯区高 = 高 - 灯区顶 - 尺.底条 - 40;
  const 灯步 = Math.floor(秒 * 6) % 灯数;
  const 灯左x = Math.round((尺.轨宽 - 4) / 2);
  const 灯右x = 宽 - 尺.轨宽 + 灯左x;
  for (let 位 = 0; 位 < 灯数; 位 += 1) {
    const y = Math.round((灯区顶 + (灯区高 * 位) / (灯数 - 1)) / 网格) * 网格;
    const 距 = (灯步 - 位 + 灯数) % 灯数;
    const 灯色 = 七[位 % 七.length] ?? 色.黄;
    for (const x of [灯左x, 灯右x]) {
      填(暗色(色.暗, 0.6), 0.8).fillRect(x, y, 4, 4);
      if (距 === 0) {
        填(灯色, 0.16).fillRect(x - 2, y - 2, 8, 8);
        填(灯色, 0.9).fillRect(x, y, 4, 4);
      } else if (距 === 1) {
        填(灯色, 0.34).fillRect(x, y, 4, 4);
      }
    }
  }

  // 3. 像素余烬：12 个 2–3px 点从屏底缓慢上浮，靠 sin 闪烁，位置全部可复现。
  for (let i = 0; i < 12; i += 1) {
    const 基x = 尺.屏左 + 随机值(i + 601) * 屏宽;
    const x = Math.round((基x + Math.sin(秒 * 0.55 + i * 1.7) * 4) / 2) * 2;
    const 速 = 6 + 随机值(i + 623) * 14;
    const 上移 = (随机值(i + 647) * 屏高 + 秒 * 速) % 屏高;
    const y = 尺.屏底 - Math.round(上移 / 2) * 2;
    const 闪 = 0.5 + 0.5 * Math.sin(秒 * (1.1 + 随机值(i + 691) * 1.4) + i * 2.3);
    const 尺寸 = 2 + (i % 2);
    填(闪 > 0.55 ? 色.亮 : (七[i % 七.length] ?? 色.青), 0.03 + 闪 * 0.1).fillRect(
      x,
      y,
      尺寸,
      尺寸,
    );
  }

  // 4. 中央光呼吸：单层极淡圆，透明度只随 sin 轻摆，避免出现光晕年轮。
  const 呼吸 = 0.5 + 0.5 * Math.sin((秒 * Math.PI * 2) / 4.6);
  填(色.亮, 0.003 + 呼吸 * 0.004).fillCircle(宽 * 0.5, 高 * 0.27, Math.min(宽, 高) * 0.52);

  // 5. 檐口追光：顶部跑马灯逐个点亮，灯位与静态灯行共用一套坐标。
  const 檐灯 = 取檐灯(宽, 尺);
  const 檐位 = Math.floor(秒 * 9) % Math.max(1, 檐灯.数);
  for (let 序 = 0; 序 < 檐灯.数; 序 += 1) {
    const 距 = (檐位 - 序 + 檐灯.数) % 檐灯.数;
    const x = 尺.轨宽 + 12 + 序 * 20;
    const 灯色 = 七[序 % 七.length] ?? 色.黄;
    if (距 === 0) {
      填(灯色, 0.26).fillRect(x - 1, 檐灯.y - 1, 8, 8);
    } else if (距 === 1) {
      填(灯色, 0.16).fillRect(x, 檐灯.y, 6, 6);
    }
  }
}

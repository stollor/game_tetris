function 绘制深空(图: 图形对象, 厅: 晶厅): void {
  // 壳 → 背墙 → 侧壁微光 → 背墙 → 更暗的接地：顶部最深、中央略亮，不出现色带。
  绘制天幕(图, 厅.宽, 0, 厅.高, [
    屏.壳,
    暗色(房.背墙, 0.12),
    混色(房.背墙, 房.侧壁, 0.16),
    房.背墙,
    暗色(房.背墙, 0.4),
  ]);
}

function 绘制纵深平面(图: 图形对象, 厅: 晶厅): void {
  const { 宽, 高, 远左, 远右, 远顶, 远底, 近左, 近右, 近顶, 近底 } = 厅;
  // 天花：近端被顶灯照亮，向尽头收暗。
  图.fillGradientStyle(房.顶面, 房.顶面, 房.顶面, 房.顶面, 0.2, 0.2, 0.05, 0.05).fillPoints(
    [
      { x: 近左, y: 近顶 },
      { x: 近右, y: 近顶 },
      { x: 远右, y: 远顶 },
      { x: 远左, y: 远顶 },
    ],
    true,
  );
  // 地面：近处略亮，向消失点淡出。
  图.fillGradientStyle(房.地面, 房.地面, 房.地面, 房.地面, 0.09, 0.09, 0.4, 0.4).fillPoints(
    [
      { x: 远左, y: 远底 },
      { x: 远右, y: 远底 },
      { x: 近右, y: 近底 },
      { x: 近左, y: 近底 },
    ],
    true,
  );
  // 房间四棱：背口四角与屏幕四角相连。远端收一半透明度，四线不会在中央硬收成一点。
  图.lineStyle(1, 房.棱, 0.05);
  图.lineBetween(远左, 远顶, (远左 + 0) / 2, (远顶 + 0) / 2);
  图.lineBetween(远右, 远顶, (远右 + 宽) / 2, (远顶 + 0) / 2);
  图.lineBetween(远左, 远底, (远左 + 0) / 2, (远底 + 高) / 2);
  图.lineBetween(远右, 远底, (远右 + 宽) / 2, (远底 + 高) / 2);
  图.lineStyle(1, 房.棱, 0.17);
  图.lineBetween((远左 + 0) / 2, (远顶 + 0) / 2, 0, 0);
  图.lineBetween((远右 + 宽) / 2, (远顶 + 0) / 2, 宽, 0);
  图.lineBetween((远左 + 0) / 2, (远底 + 高) / 2, 0, 高);
  图.lineBetween((远右 + 宽) / 2, (远底 + 高) / 2, 宽, 高);
}

function 绘制透视格线(图: 图形对象, 厅: 晶厅): void {
  const { 宽, 高, 消失X, 消失Y, 远左, 远右, 远顶, 远底, 近左, 近右, 近顶, 近底 } = 厅;
  const 半宽 = (远右 - 远左) / 2;
  const 半高 = (远底 - 远顶) / 2;
  // 放射格线：左右各 7 条，从远平面边缘射向画布边缘；三段递减透明度，越靠中央越淡，
  // 免得标题背后交叉成"米字"。
  const 放射: {
    x0: number;
    y0: number;
    x1: number;
    y1: number;
    x2: number;
    y2: number;
    x3: number;
    y3: number;
  }[] = [];
  for (const 侧 of [-1, 1] as const) {
    for (let 序 = 0; 序 < 7; 序 += 1) {
      const 纵移 = -0.9 + 序 * 0.3;
      const 起比 = Math.min(半宽, Math.abs(纵移) > 1e-6 ? 半高 / Math.abs(纵移) : 半宽);
      const 出X = 侧 > 0 ? (宽 - 消失X) / 侧 : 消失X;
      const 出Y =
        纵移 > 0 ? (高 - 消失Y) / 纵移 : 纵移 < 0 ? 消失Y / -纵移 : Number.POSITIVE_INFINITY;
      const 出比 = Math.min(出X, 出Y);
      if (!Number.isFinite(出比)) continue;
      const 起X = 消失X + 侧 * 起比;
      const 起Y = 消失Y + 纵移 * 起比;
      const 止X = 消失X + 侧 * 出比;
      const 止Y = 消失Y + 纵移 * 出比;
      放射.push({
        x0: 起X,
        y0: 起Y,
        x1: 起X + (止X - 起X) / 3,
        y1: 起Y + (止Y - 起Y) / 3,
        x2: 起X + ((止X - 起X) * 2) / 3,
        y2: 起Y + ((止Y - 起Y) * 2) / 3,
        x3: 止X,
        y3: 止Y,
      });
    }
  }
  图.lineStyle(1, 房.格线, 0.028);
  for (const 线 of 放射) 图.lineBetween(线.x0, 线.y0, 线.x1, 线.y1);
  图.lineStyle(1, 房.格线, 0.055);
  for (const 线 of 放射) 图.lineBetween(线.x1, 线.y1, 线.x2, 线.y2);
  图.lineStyle(1, 房.格线, 0.085);
  for (const 线 of 放射) 图.lineBetween(线.x2, 线.y2, 线.x3, 线.y3);
  // 地面楼层线：透视间距，越远越密、越亮。
  for (let 序 = 0; 序 < 6; 序 += 1) {
    const 比 = ((序 + 1) / 6) ** 1.85;
    const y = 远底 + (近底 - 远底) * 比;
    const 左 = 远左 + (近左 - 远左) * 比;
    const 右 = 远右 + (近右 - 远右) * 比;
    图.lineStyle(1, 房.格线, 0.1 * (1 - 比 * 0.45)).lineBetween(左, y, 右, y);
  }
  // 天花横梁：只留 3 条，与地面呼应。
  for (let 序 = 0; 序 < 3; 序 += 1) {
    const 比 = ((序 + 1) / 3) ** 1.75;
    const y = 远顶 + (近顶 - 远顶) * 比;
    const 左 = 远左 + (近左 - 远左) * 比;
    const 右 = 远右 + (近右 - 远右) * 比;
    图.lineStyle(1, 房.格线, 0.075 * (1 - 比 * 0.4)).lineBetween(左, y, 右, y);
  }
}

function 绘制壁板带(图: 图形对象, 厅: 晶厅): void {
  const { 宽, 高 } = 厅;
  const 带高 = Math.max(2, 高 * 0.018);
  const 段宽 = [0.24, 0.29, 0.27, 0.2] as const;
  // 顶部壁板带承接天花，底部壁板带退到地面里：峰亮度只有 0.09，不跟按钮抢视线。
  for (const { 上, 峰 } of [
    { 上: 高 * 0.1, 峰: 0.16 },
    { 上: 高 * 0.79, 峰: 0.085 },
  ]) {
    let x = -宽 * 0.02;
    for (let 段 = 0; 段 < 段宽.length; 段 += 1) {
      const 宽段 = 宽 * (段宽[段] ?? 0.25) + 1;
      const 色 = 壁板色[段 % 壁板色.length] ?? 房.背墙;
      const 退让 = 段 % 2 === 0 ? 0 : Math.max(1, 带高 * 0.22);
      const 段高 = 带高 - 退让;
      // 上下缘渐隐，避免一条横向硬条。
      图
        .fillGradientStyle(色, 色, 色, 色, 0.025, 0.025, 峰, 峰)
        .fillRect(x, 上 + 退让, 宽段, 段高 * 0.5);
      图
        .fillGradientStyle(色, 色, 色, 色, 峰, 峰, 0.025, 0.025)
        .fillRect(x, 上 + 退让 + 段高 * 0.5, 宽段, 段高 * 0.5);
      // 1px 壁缝：压暗一条，把横带拆成独立壁板。
      图.fillStyle(暗色(房.背墙, 0.5), 0.45).fillRect(x + 宽段 - 1, 上, 1, 带高);
      x += 宽段;
    }
  }
}

/** 从灯条向厅内衰减的一段冷光：竖向分两段做出两端淡出，避免矩形硬边。 */
function 绘制灯辉(
  图: 图形对象,
  侧: -1 | 1,
  边: number,
  辉宽: number,
  顶: number,
  底: number,
  峰: number,
): void {
  const 中 = (顶 + 底) / 2;
  // 角值相乘即「纵向淡出 × 横向衰减」：上下角控制纵向，左右角控制横向。
  const 段: readonly { 上: number; 下: number; 起: number; 止: number }[] = [
    { 上: 顶, 下: 中, 起: 0, 止: 峰 },
    { 上: 中, 下: 底, 起: 峰, 止: 0 },
  ];
  for (const { 上, 下, 起, 止 } of 段) {
    if (侧 < 0)
      图.fillGradientStyle(灯色, 灯色, 灯色, 灯色, 起, 0, 止, 0).fillRect(边, 上, 辉宽, 下 - 上);
    else
      图
        .fillGradientStyle(灯色, 灯色, 灯色, 灯色, 0, 起, 0, 止)
        .fillRect(边 - 辉宽, 上, 辉宽, 下 - 上);
  }
}

/** 灯条本体：细亮芯，两端抬暗，像一条嵌进壁板的冷光灯。 */
function 绘制灯芯(
  图: 图形对象,
  边: number,
  芯宽: number,
  顶: number,
  底: number,
  峰: number,
): void {
  const 中 = (顶 + 底) / 2;
  图
    .fillGradientStyle(灯芯, 灯芯, 灯芯, 灯芯, 0, 0, 峰, 峰)
    .fillRect(边 - 芯宽 / 2, 顶, 芯宽, 中 - 顶);
  图
    .fillGradientStyle(灯芯, 灯芯, 灯芯, 灯芯, 峰, 峰, 0, 0)
    .fillRect(边 - 芯宽 / 2, 中, 芯宽, 底 - 中);
}

function 绘制侧灯带(图: 图形对象, 厅: 晶厅): void {
  const { 宽, 高 } = 厅;
  const 顶 = 高 * 0.11;
  const 底 = 高 * 0.86;
  const 带高 = 底 - 顶;
  const 芯宽 = Math.max(1.2, 宽 * 0.0042);
  const 内距 = Math.max(5, 宽 * 0.021);
  for (const 侧 of [-1, 1] as const) {
    const 边 = 侧 < 0 ? 内距 : 宽 - 内距;
    绘制灯辉(图, 侧, 边, 宽 * 0.13, 顶, 底, 0.02);
    绘制灯辉(图, 侧, 边, 宽 * 0.062, 顶, 底, 0.055);
    绘制灯辉(图, 侧, 边, 宽 * 0.028, 顶, 底, 0.085);
    绘制灯芯(图, 边, 芯宽, 顶, 底, 0.19);
    for (let 节点 = 0; 节点 < 4; 节点 += 1) {
      const y = 顶 + 带高 * (0.16 + 节点 * 0.23);
      const 淡 = 1 - Math.abs((y - 顶) / 带高 - 0.5) * 0.9;
      图.fillStyle(灯芯, 0.12 * 淡).fillRect(边 - 芯宽, y, 芯宽 * 2.4, Math.max(1.5, 高 * 0.0024));
    }
  }
}

function 绘制晶面(图: 图形对象, 厅: 晶厅): void {
  const { 宽, 高 } = 厅;
  // 四角晶簇：每个晶簇由两片亮度只差 5–8% 的平面拼成，共用棱线就是"切面"，
  // 不做渐变亮块；整体压在暗角里，只给角落一点实体感。
  const 面亮 = 混色(房.背墙, 房.侧壁, 0.3);
  const 面中 = 混色(房.背墙, 房.侧壁, 0.2);
  const 面暗 = 混色(房.背墙, 房.侧壁, 0.12);
  const 棱光 = 亮色(房.棱, 0.5);
  // 左上晶簇：上片受光、下片背光，共用一条从画面左上角斜下的切棱。
  图.fillStyle(面亮, 0.3).fillPoints(
    [
      { x: 0, y: 0 },
      { x: 宽 * 0.34, y: 0 },
      { x: 宽 * 0.15, y: 高 * 0.28 },
    ],
    true,
  );
  图.fillStyle(面中, 0.28).fillPoints(
    [
      { x: 0, y: 0 },
      { x: 宽 * 0.15, y: 高 * 0.28 },
      { x: 0, y: 高 * 0.11 },
    ],
    true,
  );
  // 右上晶簇：镜像，亮度略低，避免左右完全对称的"贴纸感"。
  图.fillStyle(面中, 0.26).fillPoints(
    [
      { x: 宽, y: 0 },
      { x: 宽 * 0.62, y: 0 },
      { x: 宽 * 0.83, y: 高 * 0.24 },
    ],
    true,
  );
  图.fillStyle(面暗, 0.24).fillPoints(
    [
      { x: 宽, y: 0 },
      { x: 宽 * 0.83, y: 高 * 0.24 },
      { x: 宽, y: 高 * 0.1 },
    ],
    true,
  );
  // 下方两片碎晶，压住画面下缘。
  图.fillStyle(面暗, 0.22).fillPoints(
    [
      { x: 0, y: 高 },
      { x: 宽 * 0.18, y: 高 },
      { x: 0, y: 高 * 0.84 },
    ],
    true,
  );
  图.fillStyle(面中, 0.2).fillPoints(
    [
      { x: 宽, y: 高 },
      { x: 宽 * 0.82, y: 高 },
      { x: 宽, y: 高 * 0.86 },
    ],
    true,
  );
  // 亮棱：晶簇之间的切棱最亮，外轮廓只勾一半，读成"晶体"而不是线框。
  图.lineStyle(1, 棱光, 0.15);
  图.lineBetween(0, 0, 宽 * 0.15, 高 * 0.28);
  图.lineBetween(宽, 0, 宽 * 0.83, 高 * 0.24);
  图.lineStyle(1, 棱光, 0.1);
  图.lineBetween(宽 * 0.15, 高 * 0.28, 宽 * 0.34, 0);
  图.lineBetween(0, 高 * 0.11, 宽 * 0.15, 高 * 0.28);
  图.lineBetween(宽 * 0.83, 高 * 0.24, 宽 * 0.62, 0);
}

function 绘制尽头冷光(图: 图形对象, 厅: 晶厅): void {
  const { 宽, 高, 消失X, 消失Y, 远顶, 远底 } = 厅;
  // 尽头被灯带照亮的那面墙：用很扁的横向光带叠出来，不用圆形光晕也不画矩形边。
  // 越扁越像"远处一堵墙"而不是镜头光斑。
  const 雾层: readonly { 宽比: number; 高比: number; 透明度: number }[] = [
    { 宽比: 1.24, 高比: 0.075, 透明度: 0.011 },
    { 宽比: 0.96, 高比: 0.058, 透明度: 0.014 },
    { 宽比: 0.68, 高比: 0.042, 透明度: 0.017 },
    { 宽比: 0.4, 高比: 0.028, 透明度: 0.02 },
  ];
  for (const { 宽比, 高比, 透明度 } of 雾层) {
    图.fillStyle(灯色, 透明度).fillEllipse(消失X, 消失Y, 宽 * 宽比, 高 * 高比);
  }
  // 尽头的光沿透视洒在地面与天花上：近端散开、远端最亮，把厅的纵深感补满。
  图.fillGradientStyle(灯色, 灯色, 灯色, 灯色, 0.04, 0.04, 0, 0).fillPoints(
    [
      { x: 消失X - 宽 * 0.07, y: 远底 },
      { x: 消失X + 宽 * 0.07, y: 远底 },
      { x: 消失X + 宽 * 0.21, y: 高 * 0.66 },
      { x: 消失X - 宽 * 0.21, y: 高 * 0.66 },
    ],
    true,
  );
  图.fillGradientStyle(灯色, 灯色, 灯色, 灯色, 0, 0, 0.022, 0.022).fillPoints(
    [
      { x: 消失X - 宽 * 0.07, y: 远顶 },
      { x: 消失X + 宽 * 0.07, y: 远顶 },
      { x: 消失X + 宽 * 0.18, y: 高 * 0.05 },
      { x: 消失X - 宽 * 0.18, y: 高 * 0.05 },
    ],
    true,
  );
}


function 绘制灯带呼吸(图: 图形对象, 厅: 晶厅, 秒: number, 亮度: number): void {
  const { 宽, 高 } = 厅;
  const 顶 = 高 * 0.11;
  const 底 = 高 * 0.86;
  const 带高 = 底 - 顶;
  const 芯宽 = Math.max(1.2, 宽 * 0.0042);
  const 内距 = Math.max(5, 宽 * 0.021);
  const 呼吸 = 0.75 + 0.25 * Math.sin((秒 / 3.2) * Math.PI * 2);
  const 强 = 亮度 * 呼吸;
  for (const 侧 of [-1, 1] as const) {
    const 边 = 侧 < 0 ? 内距 : 宽 - 内距;
    绘制灯辉(图, 侧, 边, 宽 * 0.062, 顶, 底, 0.06 * 强);
    绘制灯芯(图, 边, 芯宽, 顶, 底, 0.16 * 强);
    // 沿灯条缓慢上行的能量点：左右反向，读起来像电流在灯带里跑。
    const 进度 = ((((秒 / 2.9) * (侧 < 0 ? 1 : -1)) % 1) + 1) % 1;
    const y = 顶 + 带高 - 带高 * 进度;
    图.fillStyle(灯芯, 0.18 * 强).fillRect(边 - 芯宽, y, 芯宽 * 2.2, Math.max(1.5, 高 * 0.003));
    图.fillStyle(灯色, 0.06 * 强).fillCircle(边, y, 芯宽 * 2.6 + 2);
  }
}

function 绘制格线流光(图: 图形对象, 厅: 晶厅, 秒: number, 亮度: number): void {
  const { 高, 远左, 远右, 远底, 近左, 近右, 近底 } = 厅;
  // 两道朝观众滚来的地面光环：沿透视方向扫描，接近时变亮、走远时淡出。
  for (let 环 = 0; 环 < 2; 环 += 1) {
    const 进度 = (((秒 / 6.5 + 环 * 0.5) % 1) + 1) % 1;
    const 淡 = Math.sin(Math.PI * 进度);
    if (淡 <= 0.02) continue;
    const 比 = 进度 * 进度;
    const y = 远底 + (近底 - 远底) * 比;
    const 左 = 远左 + (近左 - 远左) * 比;
    const 右 = 远右 + (近右 - 远右) * 比;
    const 透 = 0.085 * 淡 * 亮度;
    图.lineStyle(1.1, 灯色, 透).lineBetween(左, y, 右, y);
    图.fillStyle(灯色, 透).fillCircle(左, y, Math.max(1.5, 高 * 0.004));
    图.fillStyle(灯色, 透).fillCircle(右, y, Math.max(1.5, 高 * 0.004));
  }
}

function 绘制晶尘(图: 图形对象, 厅: 晶厅, 秒: number, 亮度: number): void {
  const { 宽, 高 } = 厅;
  for (let 序 = 0; 序 < 26; 序 += 1) {
    const 基X = 随机值(序 + 3) * 宽;
    const 基Y = 随机值(序 + 41) * 高;
    const 上升 = 高 * (0.012 + 随机值(序 + 77) * 0.05);
    const y = (((基Y - 秒 * 上升) % 高) + 高) % 高;
    const x = 基X + Math.sin(秒 * 0.4 + 序 * 1.9) * 宽 * 0.014;
    const 闪 = 0.5 + 0.5 * Math.sin(秒 * (0.7 + 随机值(序 + 113) * 1.8) + 序 * 2.1);
    const 半径 = 0.7 + 随机值(序 + 151) * 1.2;
    图.fillStyle(序 % 6 === 0 ? 灯芯 : 灯色, (0.05 + 0.11 * 闪) * 亮度).fillCircle(x, y, 半径);
  }
}

function 绘制尽头脉动(图: 图形对象, 厅: 晶厅, 秒: number, 亮度: number): void {
  const { 宽, 高, 消失X, 消失Y } = 厅;
  const 脉 = 0.8 + 0.2 * Math.sin((秒 / 4.6) * Math.PI * 2);
  const 半径 = Math.min(宽, 高);
  for (let 层 = 0; 层 < 3; 层 += 1) {
    图
      .fillStyle(灯色, (0.014 - 层 * 0.0035) * 亮度 * 脉)
      .fillCircle(消失X, 消失Y, 半径 * (0.07 + 层 * 0.05));
  }
}

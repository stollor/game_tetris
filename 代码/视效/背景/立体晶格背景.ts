import type { 图形对象 } from "../../../框架/界面/绘制/协议";
import { 亮色, 暗色, 混色 } from "../../../框架/界面/颜色工具";
import { 立体规范 } from "../../主题/立体/立体规范";
import { 绘制天幕, 绘制暗角, 随机值 } from "./通用";

/**
 * 立体晶格的专属后景：一座向画面深处收束的晶体厅。
 * 纵深感全靠一点透视表达——消失点、地面/天花梯形、房间四棱与楼层线，
 * 尽头不画"门框"，只留一团冷光，让通道自然消失在深处；晶体棱面、壁板带与侧灯带补上材质。
 * 颜色只取 `立体规范`（与 3D 房间、HUD 机架同源），静态底烘焙一次，动态层透明度统一乘 亮度。
 */

const 屏 = 立体规范.界面;
const 房 = 立体规范.房间;
const 灯色 = 立体规范.装置.灯色;
const 灯芯 = 立体规范.装置.灯芯;
const 壁板色 = 房.壁板色;

/** 晶体厅的透视构图：消失点在画面上部，远平面只用于定位光雾与四棱，不画实边。 */
interface 晶厅 {
  宽: number;
  高: number;
  消失X: number;
  消失Y: number;
  远左: number;
  远右: number;
  远顶: number;
  远底: number;
  /** 地面/天花的近端边界：略超出画布，梯形边才能贴满屏幕。 */
  近左: number;
  近右: number;
  近顶: number;
  近底: number;
}

function 计算晶厅(宽: number, 高: number): 晶厅 {
  const 消失X = 宽 * 0.5;
  const 消失Y = 高 * 0.42;
  const 远宽 = 宽 * 0.34;
  const 远高 = 高 * 0.16;
  return {
    宽,
    高,
    消失X,
    消失Y,
    远左: 消失X - 远宽 / 2,
    远右: 消失X + 远宽 / 2,
    远顶: 消失Y - 远高 / 2,
    远底: 消失Y + 远高 / 2,
    近左: -宽 * 0.12,
    近右: 宽 * 1.12,
    近顶: -高 * 0.03,
    近底: 高 * 1.02,
  };
}

export function 绘制立体晶格背景(图: 图形对象, 宽: number, 高: number): void {
  if (!(宽 > 0) || !(高 > 0)) return;
  const 厅 = 计算晶厅(宽, 高);
  绘制深空(图, 厅);
  绘制纵深平面(图, 厅);
  绘制透视格线(图, 厅);
  绘制壁板带(图, 厅);
  绘制侧灯带(图, 厅);
  绘制晶面(图, 厅);
  绘制尽头冷光(图, 厅);
  绘制暗角(图, 宽, 高);
}

/** 动态层：灯带呼吸、格线流光、晶尘与尽头脉动；亮度只缩放透明度，不改绘制结构。 */
export function 绘制立体晶格背景动态(
  图: 图形对象,
  宽: number,
  高: number,
  时间秒: number,
  亮度 = 1,
): void {
  if (!(宽 > 0) || !(高 > 0)) return;
  const 厅 = 计算晶厅(宽, 高);
  const 秒 = Number.isFinite(时间秒) ? 时间秒 : 0;
  绘制灯带呼吸(图, 厅, 秒, 亮度);
  绘制格线流光(图, 厅, 秒, 亮度);
  绘制晶尘(图, 厅, 秒, 亮度);
  绘制尽头脉动(图, 厅, 秒, 亮度);
}


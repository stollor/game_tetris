import type { 游戏主题 } from "../../框架/样式/类型";
import { 选取对比文字色 } from "../../框架/界面/颜色工具";
import { 地点皮肤表 } from "./旅行地点";
import { 俄罗斯方块主题 } from "./界面主题";

const 色 = (值: number) => `#${值.toString(16).padStart(6, "0")}`;
export const 旅行主题表: Record<string, 游戏主题> = Object.fromEntries(
  地点皮肤表.map((地点) => {
    const 基础 = 俄罗斯方块主题.夜空鎏金;
    const 强调 = 色(地点.强调);
    const 文字 = "#f6f1e8";
    const 主要 = { 背景: 强调, 文字: 选取对比文字色(强调), 描边: "#fff2cf" };
    const 次要 = { 背景: 地点.面板, 文字, 描边: 强调 };
    const 主题: 游戏主题 = {
      ...基础,
      元信息: { 名称: 地点.名称 },
      页面: { 背景: 地点.面板, 背景远景: 色(地点.远景), 光晕: 强调 },
      文字: { ...基础.文字, 主要: 文字, 次要: "#d1d4cd", 弱化: "#b7c1ba", 强调 },
      面板: {
        ...基础.面板,
        主面板: { 背景: 地点.面板, 描边: 强调, 标题文字: 强调, 正文文字: 文字, 阴影: "#050b13" },
        次级面板: { 背景: 地点.面板, 描边: 色(地点.主色) },
        分组线: 色(地点.主色),
      },
      按钮: {
        ...基础.按钮,
        主要: {
          默认: 主要,
          移入: 主要,
          点击: { ...主要, 描边: 文字 },
          聚焦: { ...主要, 描边: 文字 },
          禁用: { ...基础.按钮.主要.禁用, 文字: "#c8c9c5" },
        },
        次要: {
          默认: 次要,
          移入: { ...次要, 描边: 文字 },
          点击: 次要,
          聚焦: { ...次要, 描边: 文字 },
          禁用: { ...基础.按钮.次要.禁用, 文字: "#c8c9c5" },
        },
      },
      游戏区域: { 背景: "#0d1721", 网格线: 色(地点.远景), 描边: 强调, 高亮: 强调 },
    };
    return [地点.名称, 主题];
  }),
);

import type { 音效条目, 音效谱 } from "../../框架Three/音频/音效目录";
import { type 地点皮肤, 地点皮肤表 } from "./旅行地点";

/** 操作节奏保持一致，地点分别使用竹木、清铃、铜钟和电子谐音等原创合成音色。 */
export function 生成旅行音效谱(基础: 音效谱, 地点: 地点皮肤): 音效谱 {
  const 比例 = 地点.音高 / 220;
  const 音符 = (基础.音符 ?? []).map((音) => ({
    ...音,
    起频: Math.max(30, 音.起频 * 比例),
    终频: 音.终频 === undefined ? undefined : Math.max(30, 音.终频 * 比例),
    波形: 地点.音色,
    音量: 音.音量 * (地点.音色 === "square" ? 0.56 : 0.82),
    时长:
      音.时长 *
      (地点.纹样 === "冰晶" || 地点.纹样 === "莲叶" ? 1.22 : 地点.纹样 === "熊猫" ? 0.72 : 1),
  }));
  const 首音 = 音符[0];
  if (首音 && ["冰晶", "宫阙", "铜纹", "织锦"].includes(地点.纹样))
    音符.push({
      ...首音,
      起频: 首音.起频 * 2.003,
      终频: undefined,
      波形: "sine",
      音量: 首音.音量 * 0.22,
    });
  return {
    音符,
    噪声: 基础.噪声?.map((噪) => ({ ...噪, 频率: 噪.频率 * 比例, 音量: 噪.音量 * 0.65 })),
  };
}
export function 构建旅行音效库(基础: readonly 音效条目[]): 音效条目[] {
  return 地点皮肤表.flatMap((地点) =>
    基础.flatMap((项): 音效条目[] =>
      项.类型 === "合成"
        ? [
            {
              id: `旅行.${地点.名称}.${项.名称}`,
              名称: `${地点.名称}·${项.名称}`,
              用途: ["旅行外观", "对局"],
              说明: `${地点.副题}；${项.名称}专属合成反馈`,
              类型: "合成",
              谱: 生成旅行音效谱(项.谱, 地点),
            },
          ]
        : [],
    ),
  );
}

/** 真实事件谱与商店试听使用同一音色变换，保留消行数/连击动态参数。 */
export function 应用装备音效(基础: 音效谱, 装备: string | null): 音效谱 {
  const 地点 = 地点皮肤表.find((项) => 项.名称 === 装备);
  return 地点 ? 生成旅行音效谱(基础, 地点) : 基础;
}

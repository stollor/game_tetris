/**
 * 原程序音频在播放时会把音量再乘 0.82；现在的合成谱直接交给总线播放，
 * 所以这里先把系数并进谱里，保持实际响度与迁移前一致。
 */
const 音量系数 = 0.82;

/** 半音（MIDI 音高）转频率，与原程序音频的换算一致。 */
const 音高 = (半音: number): number => 440 * 2 ** ((半音 - 69) / 12);

function 音(频率: number, 时长: number, 音量: number, 波形: OscillatorType = "sine", 延迟 = 0) {
  return { 起频: 频率, 时长, 音量: 音量 * 音量系数, 波形, 延迟 };
}

function 滑音(
  起频: number,
  终频: number,
  时长: number,
  音量: number,
  波形: OscillatorType = "sine",
  延迟 = 0,
) {
  return { 起频, 终频, 时长, 音量: 音量 * 音量系数, 波形, 延迟 };
}

function 噪声(时长: number, 音量: number, 频率: number, 滤波: BiquadFilterType, 延迟 = 0) {
  return { 时长, 音量: 音量 * 音量系数, 频率, 滤波, 延迟 };
}

/** 消行数 1–4 对应不同长度的琶音；噪声与辅助音随行数变化。 */
const 消行音符表 = [
  [69, 76],
  [69, 73, 76],
  [64, 69, 73, 76],
  [57, 64, 69, 73, 76],
];
const 消行时长表 = [0.32, 0.42, 0.52, 0.75];

/** 消行音效依赖消行数，注册表里只放「消行数=1」的代表谱。 */
export function 消行谱(消行数: number): 音效谱 {
  const 索引 = Math.max(0, Math.min(3, 消行数 - 1));
  const 时长 = 消行时长表[索引] ?? 0.32;
  const 四行 = 消行数 >= 4;
  return {
    噪声: [噪声(时长, 四行 ? 0.15 : 0.11, 四行 ? 900 : 2600, 四行 ? "bandpass" : "highpass")],
    音符: [
      ...(消行音符表[索引] ?? [69, 76]).map((半音) => 音(音高(半音), 时长, 0.075, "sawtooth")),
      滑音(90, 55, 时长, 四行 ? 0.24 : 0.14, "triangle"),
      ...(消行数 >= 2 ? [音(音高(81), 时长 * 0.8, 0.065, "sine")] : []),
    ],
  };
}

/** 连击音效随连击数升调；注册表里只放「消行数=3」的代表谱。 */
export function 连击谱(消行数: number): 音效谱 {
  const n = Math.min(12, Math.max(0, 消行数 - 2));
  return {
    音符: [音(音高(76 + n), 0.12, 0.06, "sine"), 音(音高(83 + n), 0.15, 0.05, "sine", 0.07)],
  };
}


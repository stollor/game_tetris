/**
 * 排行榜页（7C）：与 Phaser 版同构——标题 + 周期页签 + 我的状态 + 榜单行 + 返回按钮。
 * 几何来自 `代码/视觉/覆盖页布局.ts`；页签与底部按钮按框架原生按钮的选中/默认状态上色，
 * 标题/状态/行文字沿用 Phaser 原生字体族（`覆盖页文字.ts`）。
 */

interface 榜面缓存 {
  状态文案: string;
  分数列表: readonly Tap排行榜分数[];
  需登录?: boolean;
}

export class 排行榜界面 extends 页面基类 {
  private 模式: 游戏模式 = "马拉松";
  private 周期: 排行榜周期 = "总";
  private 滚动: 滚动容器 | null = null;
  private 滚动位置 = 0;
  private 缓存: 榜面缓存 = { 状态文案: "", 分数列表: [] };
  private 加载中 = false;
  private 色: 页面语义色 = 读取页面语义色(this.上下文.服务.设置.读取().样式);
  /** 上一帧榜单滚动位置：惯性滚动只让控件层变化，榜单画在内容层。 */
  private 上次滚动 = 0;

  constructor(上下文: 页面上下文) {
    // 整页不透明底走背景静层；标题/页签/榜单/按钮走内容层。
    super(上下文, { 名称: "排行榜", 独占: true });
  }

  更新(秒: number): void {
    super.更新(秒);
    const 位置 = this.滚动?.读取滚动位置() ?? 0;
    if (位置 !== this.上次滚动) {
      this.上次滚动 = 位置;
      this.标记失效([页面绘制层.内容], "内容");
    }
  }

  protected 绘制背景静底(_环境: 绘制环境, 信息: 页面背景信息): void {
    this.上下文.资源.画笔.图形.fillStyle(this.色.面板, 1).fillRect(0, 0, 信息.宽, 信息.高);
  }

  进入(): void {
    this.模式 = this.上下文.参数.模式 ?? "马拉松";
    this.周期 = "总";
    this.缓存 = { 状态文案: "", 分数列表: [] };
    super.进入();
    void this.刷新在线榜();
  }

  protected 构建(): void {
    this.滚动位置 = this.滚动?.读取滚动位置() ?? this.滚动位置;
    this.控件层.清空();
    this.色 = 读取页面语义色(this.上下文.服务.设置.读取().样式);
    const 英文 = this.上下文.服务.语言.是否英文();
    const 页面布局 = 计算排行榜页布局(this.逻辑宽, this.逻辑高);
    排行榜周期顺序.forEach((周期, i) => {
      const 矩形 = {
        左: 页面布局.页签.左 + i * (页面布局.页签.宽 + 页面布局.页签.间距),
        上: 页面布局.页签.上,
        宽: 页面布局.页签.宽,
        高: 页面布局.页签.高,
      };
      this.创建热区({
        名称: `排行榜周期:${周期}`,
        矩形,
        点击: () => {
          if (this.周期 === 周期 || this.加载中) return;
          this.周期 = 周期;
          this.缓存 = { 状态文案: 英文 ? "Loading…" : "加载中…", 分数列表: [] };
          this.重建();
          void this.刷新在线榜();
        },
      });
    });
    this.滚动 = new 滚动容器类({
      矩形: 页面布局.列表,
      内容高: Math.max(40, this.缓存.分数列表.length * 页面布局.行高 + 8),
      显示滚动条: false,
      惯性: true,
    });
    this.控件层.添加(this.滚动);
    this.滚动.设置滚动位置(this.滚动位置);
    this.滚动位置 = this.滚动.读取滚动位置();
    this.上次滚动 = this.滚动.读取滚动位置();
    for (const [i, 名称] of ["返回主菜单", "登录 Tap"].entries()) {
      this.创建热区({
        名称,
        矩形: {
          左: 页面布局.按钮行.左 + i * (页面布局.按钮行.宽 + 页面布局.按钮行.间距),
          上: 页面布局.按钮行.上,
          宽: 页面布局.按钮行.宽,
          高: 页面布局.按钮行.高,
        },
        点击: () => {
          if (i === 0) {
            this.上下文.导航.返回();
            return;
          }
          void 请求Tap登录().then((结果) => {
            this.缓存.状态文案 = 结果.完成
              ? 英文
                ? "Signed in, refreshing…"
                : "登录成功，正在刷新…"
              : 结果.原因;
            this.重建();
            if (结果.完成) void this.刷新在线榜();
          });
        },
      });
    }
  }

  protected 绘制内容(): void {
    const 画笔 = this.上下文.资源.画笔;
    const 图形 = 画笔.图形;
    if (!this.滚动) return;
    const 英文 = this.上下文.服务.语言.是否英文();
    const 色 = this.色;
    const 页面布局 = 计算排行榜页布局(this.逻辑宽, this.逻辑高);
    画笔.绘制文字(
      生成页面文字项(
        "中中",
        页面布局.标题中心.x,
        页面布局.标题中心.y,
        22,
        色.正文,
        "粗体",
        "中",
        `${this.模式} ${英文 ? "LEADERBOARD" : "排行榜"}`,
      ),
    );
    const 标签 = 排行榜周期标签;
    排行榜周期顺序.forEach((周期, i) => {
      const 矩形 = {
        左: 页面布局.页签.左 + i * (页面布局.页签.宽 + 页面布局.页签.间距),
        上: 页面布局.页签.上,
        宽: 页面布局.页签.宽,
        高: 页面布局.页签.高,
      };
      const 选中 = this.周期 === 周期;
      绘制覆盖页按钮(图形, 矩形.左 + 矩形.宽 / 2, 矩形.上 + 矩形.高 / 2, 矩形.宽, 矩形.高, 选中);
      画笔.绘制文字(
        生成页面文字项(
          "中中",
          矩形.左 + 矩形.宽 / 2,
          矩形.上 + 矩形.高 / 2,
          13,
          色.正文,
          "常规",
          "中",
          英文 ? 标签[周期].英文 : 标签[周期].中文,
          undefined,
          读取覆盖页按钮文字样式(选中, 13),
        ),
      );
    });
    const 状态 = this.加载中 ? (英文 ? "Loading…" : "加载中…") : this.缓存.状态文案;
    if (状态)
      画笔.绘制文字({
        文案: 状态,
        样式: 派生覆盖页文字样式({ 字号: 12, 颜色: 色.次要, 对齐: "中" }),
        锚点: "中上",
        x: 页面布局.状态.中心X,
        y: 页面布局.状态.上,
        最大宽: 页面布局.状态.最大宽,
      });
    const 可视 = this.滚动.读取可视矩形();
    const 偏移 = this.滚动.读取滚动位置();
    const 文字偏移 = { x: 可视.左, y: 可视.上 - 偏移 };
    画笔.压入裁剪(可视);
    图形.save();
    图形.translateCanvas(可视.左, 可视.上 - 偏移);
    this.缓存.分数列表.forEach((项, i) => {
      const 行矩形: 矩形 = { 左: 0, 上: i * 页面布局.行高, 宽: 页面布局.行宽, 高: 页面布局.行板高 };
      图形
        .fillStyle(色.按钮底, 0.65)
        .fillRoundedRect(行矩形.左, 行矩形.上, 行矩形.宽, 行矩形.高, 10);
      const 名 = 项.user?.name || (英文 ? "Player" : "玩家");
      const 排名 = 项.rankDisplay ?? String(项.rank ?? i + 1);
      const 分 = 项.scoreDisplay ?? 格式化榜分数(this.模式, 项.score);
      画笔.绘制文字(
        移位(
          生成页面文字项("左上", 12, 行矩形.上 + 12, 14, 色.强调, "粗体", "左", `#${排名}`),
          文字偏移,
        ),
      );
      画笔.绘制文字(
        移位(生成页面文字项("左上", 64, 行矩形.上 + 12, 14, 色.正文, "常规", "左", 名), 文字偏移),
      );
      画笔.绘制文字(
        移位(
          生成页面文字项("右上", 行矩形.宽 - 12, 行矩形.上 + 12, 14, 色.正文, "常规", "右", 分),
          文字偏移,
        ),
      );
    });
    图形.restore();
    画笔.弹出裁剪();
    for (const [i, 文案] of [英文 ? "Back" : "返回", 英文 ? "Sign in" : "登录 Tap"].entries()) {
      const 按钮矩形 = {
        左: 页面布局.按钮行.左 + i * (页面布局.按钮行.宽 + 页面布局.按钮行.间距),
        上: 页面布局.按钮行.上,
        宽: 页面布局.按钮行.宽,
        高: 页面布局.按钮行.高,
      };
      const 区域 = 由矩形得到装置区域(按钮矩形);
      if (i === 0) {
        绘制返回传送装置(图形, 区域, { 时间秒: 0, 下沉: 0, 点亮: [], 文案 });
        画笔.绘制文字(生成返回按键文字项(区域, 文案));
        continue;
      }
      绘制覆盖页按钮(
        图形,
        按钮矩形.左 + 按钮矩形.宽 / 2,
        按钮矩形.上 + 按钮矩形.高 / 2,
        按钮矩形.宽,
        按钮矩形.高,
      );
      画笔.绘制文字({
        文案,
        样式: 读取覆盖页按钮文字样式(false, 15),
        锚点: "中中",
        x: 按钮矩形.左 + 按钮矩形.宽 / 2,
        y: 按钮矩形.上 + 按钮矩形.高 / 2,
      });
    }
    if (
      !this.缓存.分数列表.length &&
      !this.加载中 &&
      !this.缓存.需登录 &&
      this.缓存.状态文案.includes("我的")
    )
      画笔.绘制文字(
        生成页面文字项(
          "中中",
          页面布局.状态.中心X,
          168,
          14,
          色.次要,
          "常规",
          "中",
          英文 ? "No scores yet" : "暂无上榜成绩",
        ),
      );
  }

  protected 读取文字快照(): readonly string[] {
    const 当地 = this.上下文.服务.纪录.读取(
      this.模式,
      this.模式 === "每日挑战" ? this.上下文.服务.当日日期() : undefined,
    );
    return [
      `模式:${this.模式}`,
      `周期:${this.周期}`,
      `状态:${this.缓存.状态文案}`,
      `我的:${this.缓存.状态文案.startsWith("我的") || this.缓存.状态文案.startsWith("Me:") ? this.缓存.状态文案 : "无"}`,
      `行数:${this.缓存.分数列表.length}`,
      `滚动:${this.滚动?.读取滚动位置() ?? 0}`,
      `本地最佳:${
        当地
          ? this.模式 === "冲刺"
            ? `${typeof 当地.用时 === "number" ? (当地.用时 / 1000).toFixed(2) : "—"}s`
            : 当地.分数
          : 0
      }`,
      `在线:${this.上下文.服务.平台.是否可用() ? "可用" : "仅本地"}`,
    ];
  }

  private async 刷新在线榜(): Promise<void> {
    const 英文 = this.上下文.服务.语言.是否英文();
    if (this.加载中) return;
    this.加载中 = true;
    this.缓存 = { 状态文案: 英文 ? "Loading…" : "加载中…", 分数列表: [] };
    this.重建();
    const 结果 = await 加载排行榜数据({ 模式: this.模式, 周期: this.周期, 条数: 20 });
    this.加载中 = false;
    const 我的 = 结果.我的;
    const 我的行 =
      我的 && (我的.rank != null || 我的.score != null)
        ? 英文
          ? `Me: #${我的.rankDisplay ?? 我的.rank ?? "—"} · ${我的.scoreDisplay ?? 格式化榜分数(this.模式, 我的.score)}`
          : `我的：第 ${我的.rankDisplay ?? 我的.rank ?? "—"} 名 · ${我的.scoreDisplay ?? 格式化榜分数(this.模式, 我的.score)}`
        : 英文
          ? "Me: no score yet"
          : "我的：暂无成绩";
    this.缓存 = {
      状态文案: 结果.完成
        ? `${我的行}${结果.当前周期展示 ? ` · ${结果.当前周期展示}` : ""}`
        : 结果.需登录
          ? 英文
            ? "Please sign in to TapTap first."
            : "尚未登录 TapTap，请点下方登录后再查看。"
          : 格式化排行榜错误(结果.代码, 结果.原因, 英文),
      分数列表: 结果.完成 ? 结果.分数列表 : [],
      需登录: 结果.需登录,
    };
    this.重建();
  }
}

function 生成页面文字项(
  锚点: 文字项["锚点"],
  x: number,
  y: number,
  字号: number,
  颜色: number,
  字重: "常规" | "粗体",
  对齐: "左" | "中" | "右",
  文案: string,
  最大宽?: number,
  样式?: 文字项["样式"],
): 文字项 {
  return {
    文案,
    样式: 样式 ?? 派生覆盖页文字样式({ 字号, 颜色, 字重, 对齐 }),
    锚点,
    x,
    y,
    最大宽,
  };
}

function 移位(项: 文字项, 偏移: { x: number; y: number }): 文字项 {
  return { ...项, x: 项.x + 偏移.x, y: 项.y + 偏移.y };
}

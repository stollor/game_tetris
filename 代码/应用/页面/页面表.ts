import type { 页面上下文, 页面注册表 } from "../接口/上下文";
import { 主界面 } from "./主界面";
import { 商店界面 } from "./商店界面";
import { 成就界面 } from "./成就界面";
import { 排行榜界面 } from "./排行榜界面";
import { 设置界面 } from "./设置界面";

/**
 * 页面表：启动层把这里返回的注册表与对局/结算合并进场景栈。
 * 页面宿主按名称缓存实例；每次进入从 上下文.参数 读取当前参数并重建控件。
 */

export function 创建页面表(_上下文?: 页面上下文): 页面注册表 {
  return {
    主界面: (上下文) => new 主界面(上下文),
    设置: (上下文) => new 设置界面(上下文),
    成就: (上下文) => new 成就界面(上下文),
    排行榜: (上下文) => new 排行榜界面(上下文),
    商店: (上下文) => new 商店界面(上下文),
  };
}

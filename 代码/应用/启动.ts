window.addEventListener("keydown", 隔离开合按键, true);
window.addEventListener("keydown", 处理按键);

// —— 循环与渲染 ——
let 上次文字版本 = 文字.读取版本();
/**
 * 未声明自管子层的旧式页（当前只有结算覆盖页）每帧整页重置后重画；
 * 对局页 P3-3 起自管静态/动态子层，走上面的按需重建分支。
 */
const 重画旧式页 = (名称: string): void => {
  缓存.标记失效(名称, 全部子层, "内容");
  for (const 子层 of 全部子层) {
    if (缓存.需要重建(名称, 子层)) 缓存.开始重建(名称, 子层);
  }
};
/**
 * 是否有页面要求连续帧（包括结算入场和待机循环）：有则保持 rAF 调度，
 * 否则静态页降到 100ms 空闲心跳（与 Phaser 基线 loop.sleep + 100ms 空闲步同口径）。
 */
const 读取需要连续帧 = (): boolean =>
  开合.读取播放中() || 宿主.读取顶页面()?.读取需要连续帧?.() === true;
/**
 * 空闲降频判据：短动画靠交互窗口保帧，长动画靠重绘请求速率区分——
 * 逐帧动画每 250ms 约 40 次请求，低频背景只有 2–3 次；两者数量级差是本判据的依据。
 */
const 允许空闲降频 = (): boolean => {
  if (performance.now() - 最近交互毫秒 < 400) return false;
  return 渲染.读取近期重绘请求数() <= 4;
};
/** 在「最上层非覆盖页」驱动动态背景；返回是否真的重画了。 */
const 刷新顶层背景动态 = (): boolean => {
  const 栈列表 = 栈.读取栈();
  const 顶 = 栈列表.at(-1);
  if (!顶 || 顶.覆盖) return false;
  const 页 = 宿主.读取顶页面();
  if (页?.读取背景动态?.() && 页.刷新背景动态) {
    页.刷新背景动态();
    背景调度.记录绘制();
    return true;
  }
  return false;
};
const 性能观测 =
  import.meta.env.GM_TEST === "1"
    ? 创建游戏性能观测({
        渲染,
        读取场景: () => 宿主.读取当前().覆盖 ?? 读取页面编号(),
        读取音频: () => 服务.音频.读取状态(),
        // 合批账本只在真实提交帧读取；不接这里时性能报告显示图元不可用，不补零。
        读取合批: () => 合批.读取统计(),
      })
    : undefined;
let 标准桥提交 = () => {};
const 循环 = 创建游戏循环({
  失焦自动暂停: false,
  空闲判定: () =>
    !对局进行中 &&
    (import.meta.env.GM_TEST !== "1" || !正在实况观测()) &&
    !读取需要连续帧() &&
    允许空闲降频(),
  空闲心跳毫秒: 画质参数.three空闲心跳毫秒,
  更新: (固定步长秒) => {
    const 开始 = import.meta.env.GM_TEST === "1" ? performance.now() : 0;
    if (开合.更新(固定步长秒)) 渲染.请求重绘();
    栈.更新(固定步长秒);
    性能观测?.记录耗时("逻辑", performance.now() - 开始);
    // 动态背景到点才重画；满帧页按 100ms 到点节奏，空闲拍改在 渲染 里每拍强制一次。
    if (循环.读取统计().空闲) return;
    if (背景调度.到点()) 刷新顶层背景动态();
  },
  渲染: () => {
    // 空闲心跳每拍只有 1 次渲染机会：到点判据（100ms）与拍长（≈94ms）会交错漏画，
    // 所以每个空闲拍在渲染前强制重画一次动态背景，保证画面节奏等于拍长。
    if (循环.读取统计().空闲) 刷新顶层背景动态();
    // 先做按需渲染/帧率判定：被节流或按需跳过时直接返回，不白做任何重建。
    if (!渲染.准备渲染()) return;
    const 绘制开始 = import.meta.env.GM_TEST === "1" ? performance.now() : 0;
    // 文字版本变化（图集扩容/DPR 重建）会让所有持旧 UV 的层失效：本帧全量重画。
    let 全量帧 = 待全量失效;
    // 文字版本变化（图集扩容/DPR 重建）会让所有持旧 UV 的层失效：本帧全量重画。
    const 版本 = 文字.读取版本();
    if (版本 !== 上次文字版本) {
      上次文字版本 = 版本;
      待全量失效 = true;
      全量帧 = true;
      缓存.标记全部失效("文字版本");
    }
    // 允许淘汰必须在本帧绘制前打开（本帧会重画所有可见层，旧图集才有安全释放窗口）。
    if (全量帧) 文字.设置允许淘汰(true);
    文字.开始帧();
    缓存.开始帧();
    // 场景栈从栈底到栈顶逐页渲染：缓存按页名绑定本帧深度，页内只重建脏子层。
    栈.逐层渲染((场景, 深度, 名称) => {
      缓存.进入页面(名称, 深度);
      for (let 子层 = 0; 子层 < 每页子层数; 子层++) {
        合批.设置层变换(
          深度 * 每页子层数 + 子层,
          开合.读取变换(名称, 子层, 资源.逻辑宽, 资源.逻辑高),
        );
      }
      const 种类 = 页面种类.get(名称) ?? "旧式";
      // 旧式页（结算）没有子层脏判定，按旧行为整页重置后再画。
      if (种类 === "旧式") 重画旧式页(名称);
      图层.进入页面(深度, () => {
        画笔.重置();
        场景.渲染?.(上下文);
      });
      // 基类页只用前 6 个子层：把给对局预留的第 7 层当空层重建，清掉全量失效留下的脏标记，
      // 否则「脏层数归零」永远不成立，文字图集的版本确认与退役会被卡住。
      if (种类 === "基类" && 缓存.需要重建(名称, 每页子层数 - 1))
        缓存.开始重建(名称, 每页子层数 - 1);
    });
    合批.提交();
    缓存.提交();
    if (渲染.渲染()) {
      性能观测?.记录耗时("绘制", performance.now() - 绘制开始);
      标准桥提交();
    }
    文字.结束帧();
    if (全量帧) {
      try {
        // 所有可见页都重画完才确认版本：退役图集到这里才允许释放；仍有脏层则下帧继续全量失效。
        if (缓存.读取统计().脏层数 === 0) {
          文字.确认版本(版本);
          // 隐式淘汰只允许发生在全量失效帧；淘汰会让版本 +1，下帧再全量重画一次。
          const 淘汰 = 文字.整理闲置图集();
          待全量失效 = 淘汰.淘汰数 > 0;
        } else {
          待全量失效 = true;
        }
      } finally {
        // 异常时也必须关回，避免后续普通帧释放静态层仍引用的图集。
        文字.设置允许淘汰(false);
      }
    }
  },
});
循环.启动();
// 循环建立后才接管唤醒入口：宿主/初始进入早于此处，之前的请求由启动首帧覆盖。
唤醒循环 = () => 循环.唤醒();

// 失焦暂停/恢复：对局页实现 暂停()/恢复()；覆盖页打开时暂停的是覆盖页本身。
const 同步活动 = () => {
  if (
    document.hidden ||
    (!document.hasFocus() && (import.meta.env.GM_TEST !== "1" || !正在实况观测()))
  ) {
    栈.暂停();
    循环.暂停();
  } else {
    if (栈.读取是否暂停()) 栈.恢复();
    循环.恢复();
    渲染.请求重绘();
    循环.唤醒();
  }
};
document.addEventListener("visibilitychange", 同步活动);
window.addEventListener("blur", 同步活动);
window.addEventListener("focus", 同步活动);
window.addEventListener("gamemaker:实况观测", 同步活动);


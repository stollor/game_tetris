const 循环 = 创建游戏循环({
  失焦自动暂停: false,
  空闲判定: () =>
    !对局进行中 &&
    (import.meta.env.GM_TEST !== "1" || !正在实况观测()) &&
    !读取需要连续帧() &&
    允许空闲降频(),
  空闲心跳毫秒: 画质参数.three空闲心跳毫秒,
  更新: (固定步长秒) => {
    const 开始 = import.meta.env.GM_TEST === "1" ? performance.now() : 0;
    宿主.更新(固定步长秒);
    // 跨页流转只在过渡期间冻结命中；结束那一帧立刻恢复，不能等下一次渲染（否则第一次点击会被吞掉）。
    const 过渡中 = 宿主.读取过渡() !== null;
    if (上次过渡中 && !过渡中) 恢复页面命中();
    上次过渡中 = 过渡中;
    性能观测?.记录耗时("逻辑", performance.now() - 开始);
    // 动态背景到点才重画；满帧页按 100ms 到点节奏，空闲拍改在 渲染 里每拍强制一次。
    if (循环.读取统计().空闲) return;
    if (背景调度.到点()) 刷新顶层背景动态();
  },
  渲染: () => {
    // 空闲心跳每拍只有 1 次渲染机会：到点判据（100ms）与拍长（≈94ms）会交错漏画，
    // 所以每个空闲拍在渲染前强制重画一次动态背景，保证画面节奏等于拍长。
    if (循环.读取统计().空闲) 刷新顶层背景动态();
    // 先做按需渲染/帧率判定：被节流或按需跳过时直接返回，不白做任何重建。
    if (!渲染.准备渲染()) return;
    const 绘制开始 = import.meta.env.GM_TEST === "1" ? performance.now() : 0;
    // 文字版本变化（图集扩容/DPR 重建）会让所有持旧 UV 的层失效：本帧全量重画。
    let 全量帧 = 待全量失效;
    // 文字版本变化（图集扩容/DPR 重建）会让所有持旧 UV 的层失效：本帧全量重画。
    const 版本 = 文字.读取版本();
    if (版本 !== 上次文字版本) {
      上次文字版本 = 版本;
      待全量失效 = true;
      全量帧 = true;
      缓存.标记全部失效("文字版本");
    }
    // 允许淘汰必须在本帧绘制前打开（本帧会重画所有可见层，旧图集才有安全释放窗口）。
    if (全量帧) 文字.设置允许淘汰(true);
    文字.开始帧();
    缓存.开始帧();
    // 图层编号 = 「前面各层页数之和」× 每页子层数 + 层内深度 × 每页子层数；
    // 渲染起点以下的页面把层变换透明度置 0（几何保留，不白画）。
    const 页数 = 宿主.层.读取页数();
    const 基准 = new Map<string, number>();
    let 累计 = 0;
    for (const 项 of 页数) {
      基准.set(项.层名, 累计);
      累计 += 项.页数;
    }
    // 先把所有页的图层透明度清零，再由逐层渲染给真正要画的页置 1：
    // 不透明页挡住的同层页面、自带背景页挡住的层都不参与本帧。
    for (const 项 of 页数) {
      for (let 深度 = 0; 深度 < 项.页数; 深度++) {
        const 页基准 = (基准.get(项.层名) ?? 0) + 深度;
        for (let 子层 = 0; 子层 < 每页子层数; 子层++) {
          合批.设置层变换(页基准 * 每页子层数 + 子层, {
            x: 0,
            y: 0,
            缩放X: 1,
            缩放Y: 1,
            透明度: 0,
          });
        }
      }
    }
    // 逐层逐页画：缓存按页名绑定本帧深度，页内只重建脏子层。
    // 过渡帧两页按各自开合进度绘制；不参与本帧的页整页藏起来。
    const 过渡中 = 宿主.读取过渡() !== null;
    const 过渡 = 上下文.过渡;
    宿主.逐层渲染((页, 名称, 深度, 层名) => {
      const 页基准 = (基准.get(层名) ?? 0) + 深度;
      缓存.进入页面(名称, 页基准);
      const 页可见 = !过渡中 || 层名 !== 界面层名.页面 || 过渡?.页面可见(名称) !== false;
      for (let 子层 = 0; 子层 < 每页子层数; 子层++) {
        // 过渡帧页面只重画内容层：控件/覆盖保留的是过渡前的旧几何，必须藏起来。
        const 子层可见 =
          页可见 && (!(过渡中 && 层名 === 界面层名.页面) || 子层 === 页面绘制层.内容);
        const 透明度 = 子层可见 ? 1 : 0;
        合批.设置层变换(页基准 * 每页子层数 + 子层, {
          x: 0,
          y: 0,
          缩放X: 1,
          缩放Y: 1,
          透明度,
        });
      }
      const 种类 = 页面种类.get(名称);
      图层.进入页面(页基准, () => {
        画笔.重置();
        if (页可见) 页.渲染?.(上下文);
      });
      // 每页只用到自己的前几个子层（基类 3 层、框架层页面 1 层、对局 7 层）；
      // 剩余空层当空层重建一次，清掉新一轮全量失效留下的脏标记，
      // 否则「脏层数归零」永远不成立，文字图集的版本确认与退役会被卡住。
      const 已用子层 = 已用子层数(名称, 种类);
      for (let 子层 = 已用子层; 子层 < 每页子层数; 子层++) {
        if (缓存.需要重建(名称, 子层)) 缓存.开始重建(名称, 子层);
      }
    });
    合批.提交();
    缓存.提交();
    if (渲染.渲染()) {
      性能观测?.记录耗时("绘制", performance.now() - 绘制开始);
      标准桥提交();
    }
    文字.结束帧();
    if (全量帧) {
      try {
        // 可见页都重画完才确认版本；被跳绘的下层可故意保持脏，不能用总脏层数卡住退役。
        const 缓存统计 = 缓存.读取统计();
        if (缓存统计.可见脏层数 === 0 && 缓存统计.本帧重建层数 + 缓存统计.本帧跳过层数 > 0) {
          文字.确认版本(版本);
          // 隐式淘汰只允许发生在全量失效帧；淘汰会让版本 +1，下帧再全量重画一次。
          const 淘汰 = 文字.整理闲置图集();
          待全量失效 = 淘汰.淘汰数 > 0;
        } else {
          待全量失效 = true;
        }
      } finally {
        // 异常时也必须关回，避免后续普通帧释放静态层仍引用的图集。
        文字.设置允许淘汰(false);
      }
    }
  },
});

const 同步活动 = () => {
  if (
    document.hidden ||
    (!document.hasFocus() && (import.meta.env.GM_TEST !== "1" || !正在实况观测()))
  ) {
    页面层().暂停();
    循环.暂停();
  } else {
    if (页面层().读取是否暂停()) 页面层().恢复();
    循环.恢复();
    渲染.请求重绘();
    循环.唤醒();
  }
};
document.addEventListener("visibilitychange", 同步活动);
window.addEventListener("blur", 同步活动);
window.addEventListener("focus", 同步活动);
window.addEventListener("gamemaker:实况观测", 同步活动);

// —— 调试桥 ——
if (import.meta.env.GM_TEST === "1") {
  // 英文覆盖验收读取：英文界面里翻译后仍含汉字的文案。
  window.__未翻译文案__ = 读取未翻译文案;
}
if (import.meta.env.GM_TEST === "1" && 性能观测) {
  const 卸载桥 = 挂载调试桥({
    渲染,
    合批,
    循环,
    服务,
    栈: 页面层(),
    读取页面编号,
    读取当前页: () => 宿主.读取顶页面(),
    读取对局页: () => 宿主.读取页面("对局"),
    读取图元统计: () => 合批.读取统计(),
    读取纹理统计: () => 资源层.读取统计(),
    读取文字图集统计: () => 文字.读取统计(),
    读取图层缓存统计: () => 缓存.读取统计(),
    读取背景调度统计: () => 背景调度.读取统计(),
    性能: 性能观测.接口,
    登记提交: (提交) => {
      标准桥提交 = 提交;
    },
    请求渲染: () => {
      渲染.请求重绘();
      循环.唤醒();
    },
    导航,
    停止: () => {
      卸载桥();
      document.removeEventListener("visibilitychange", 同步活动);
      window.removeEventListener("blur", 同步活动);
      window.removeEventListener("focus", 同步活动);
      window.removeEventListener("gamemaker:实况观测", 同步活动);
      window.removeEventListener("resize", 调整页面尺寸);
      window.removeEventListener("keydown", 隔离开合按键, true);
      window.removeEventListener("keydown", 处理按键);
      画布.removeEventListener("pointerdown", 处理按下);
      画布.removeEventListener("pointerup", 处理抬起);
      画布.removeEventListener("pointercancel", 处理抬起);
      画布.removeEventListener("pointermove", 处理移动);
      画布.removeEventListener("wheel", 处理滚轮);
      取消设置尺寸订阅();
      取消主题订阅();
      服务.主题.销毁?.();
      循环.销毁();
      宿主.销毁();
      绑定指针.解除();
      命中.清空();
      服务.音频.停止全部();
      缓存.销毁();
      文字.销毁();
      资源层.销毁();
      合批.销毁();
      渲染.销毁();
    },
  });
}


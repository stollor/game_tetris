/**
 * 宣发录像用的「主题缓存保留」开关。
 *
 * 正常游戏换主题会清掉文字图集池与糖果底板/烘焙画布缓存：旧主题的字形和整屏底板
 * 都按主题键缓存，清空能回收内存。但宣发片要在几秒内反复切主题，每次清空都意味着
 * 下一帧重新烘焙（1080p 整屏底板 + 文字图集），单次接近一秒的卡帧。
 *
 * 录制前把五套主题各烘一遍并打开这个开关，录制期间就不再清缓存——
 * 缓存键本来就含主题，复用的永远是正确的那一份；只有正式对局才会按默认（false）回收。
 */
let 保留 = false;

export function 读取保留主题缓存(): boolean {
  return 保留;
}

export function 设置保留主题缓存(值: boolean): void {
  保留 = 值;
}

import { 对局入场时长, 模式退场时长 } from "../../../资源/视效/过渡/入场参数";
import type { 转场服务, 转场服务选项, 转场演出 } from "../接口/转场";

/**
 * 转场服务：全局唯一的转场时钟。动画层每帧调 `更新`，页面只读它。
 * 收束结束时先把状态切到「展开 0 秒」再切页，保证对局页一进入就拿到展开时间轴，
 * 不会出现「收束末帧已盖满、对局页入场却是 0.66 秒」的错拍。
 */
export function 创建转场服务(选项: 转场服务选项 = {}): 转场服务 {
  let 演出: 转场演出 | null = null;
  const 订阅者 = new Set<(演出: 转场演出 | null) => void>();

  const 通知 = () => {
    for (const 回调 of 订阅者) 回调(演出);
  };

  const 开始收束 = (模式: 转场演出["模式"], 原卡: NonNullable<转场演出["原卡"]>): void => {
    演出 = { 模式, 阶段: "收束", 秒: 0, 原卡 };
    通知();
  };

  const 开始展开 = (模式: 转场演出["模式"]): void => {
    演出 = { 模式, 阶段: "展开", 秒: 0, 原卡: null };
    通知();
  };

  const 重置 = (): void => {
    if (演出 === null) return;
    演出 = null;
    通知();
  };

  const 更新 = (秒: number): void => {
    if (演出 === null) return;
    const 推进 = Number.isFinite(秒) && 秒 > 0 ? 秒 : 0;
    if (推进 === 0) return;
    演出 = { ...演出, 秒: 演出.秒 + 推进 };
    if (演出.阶段 === "收束" && 演出.秒 >= 模式退场时长) {
      const 模式 = 演出.模式;
      // 先把状态切到展开 0 秒，再切页：对局页进入时读到的时间轴与动画层同源。
      演出 = { 模式, 阶段: "展开", 秒: 演出.秒 - 模式退场时长, 原卡: null };
      通知();
      选项.进入对局?.(模式);
      return;
    }
    if (演出.阶段 === "展开" && 演出.秒 >= 对局入场时长) {
      演出 = null;
      通知();
      return;
    }
    通知();
  };

  return {
    开始收束,
    开始展开,
    重置,
    读取: () => 演出,
    读取入场秒: () => (演出?.阶段 === "展开" ? 演出.秒 : null),
    更新,
    订阅: (回调) => {
      订阅者.add(回调);
      return () => {
        订阅者.delete(回调);
      };
    },
  };
}

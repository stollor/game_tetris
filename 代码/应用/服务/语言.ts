import { 获取文案, 解析语言 } from "../../../.gamemaker/依赖/框架/设置/多语言";
import { 文案 as 英文 } from "../../语言/English";
import { 文案 as 简体中文 } from "../../语言/简体中文";
import type { 设置服务, 语言服务 } from "../接口/服务";

/**
 * 语言服务复用框架多语言入口（通用文案）加游戏自己的文案表；
 * 语言值仍存在游戏设置里，切换语言通过 设置.更新 落盘。
 *
 * 合并结果按语言缓存：`读取()` 每落块/每次提示都会被调用，原本每次都要展开两份字典
 * （{...获取文案, ...项目文案}），是一笔稳定的每帧/每事件分配。
 */
export function 创建语言服务(设置: 设置服务): 语言服务 {
  const 读取语言 = () => 解析语言(设置.读取().语言);
  type 支持语言 = ReturnType<typeof 解析语言>;
  let 缓存语言: 支持语言 | null = null;
  let 缓存文案: ReturnType<typeof 合并> | null = null;
  function 合并(语言: 支持语言) {
    return { ...获取文案(语言), ...(语言 === "English" ? 英文 : 简体中文) };
  }
  const 读取文案 = () => {
    const 语言 = 读取语言();
    if (缓存语言 !== 语言 || 缓存文案 === null) {
      缓存语言 = 语言;
      缓存文案 = 合并(语言);
    }
    return 缓存文案;
  };
  return {
    读取: 读取文案,
    是否英文: () => 读取语言() === "English",
    设置: (语言) => {
      设置.更新({ 语言 });
    },
  };
}

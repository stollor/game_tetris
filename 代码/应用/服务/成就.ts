import { 同步平台成就, 补同步已解锁成就 } from "../../平台/平台成就";
import { 创建再消一行成就, 成就定义, 记录落块成就 } from "../../成就/再消一行成就";
import type { 成就服务 } from "../接口/服务";

/** 成就服务复用游戏成就定义与框架成就系统；进度存在 localStorage。 */
export function 创建成就服务(): 成就服务 {
  const 系统 = 创建再消一行成就();
  const 订阅者 = new Set<() => void>();
  const 通知 = () => {
    for (const 回调 of 订阅者) 回调();
  };
  const 读取已解锁 = () =>
    成就定义.filter((项) => 系统.读取(项.编号).解锁时间 !== null).map((项) => 项.编号);
  // 启动时补同步历史已解锁（含上次失败）；无成就能力时函数内部直接跳过。
  void 补同步已解锁成就(读取已解锁());
  return {
    读取保存成功: () => 系统.保存成功,
    全部定义: () => 成就定义,
    记录落块: (状态) => {
      const 新解锁 = 记录落块成就(系统, 状态);
      if (新解锁.length) {
        通知();
        // 只同步本次真实新解锁；本地保存失败时保留成果，等下次补同步。
        if (系统.保存成功) 同步平台成就(新解锁);
      }
      return 新解锁;
    },
    推进: (编号, 次数 = 1) => {
      const 新解锁 = 系统.累加(编号, 次数);
      if (新解锁) {
        通知();
        if (系统.保存成功) 同步平台成就([编号]);
      }
      return 新解锁;
    },
    读取已解锁,
    读取进度: (编号) => 系统.读取(编号).进度,
    订阅: (回调) => {
      订阅者.add(回调);
      return () => {
        订阅者.delete(回调);
      };
    },
  };
}

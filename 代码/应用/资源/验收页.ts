/**
 * 资源验收页：只做验收、不接游戏导航。用 Three 真实渲染（正交相机 + 图元合批 + 文字图集）
 * 画出「项目图集帧（游戏图标）」与「项目测试散图（裁剪图）」，并把图集帧数/页数/纹理字节/预算/
 * 散图尺寸/请求来源列表显示在画面上，证明 GM 图集资源有真实运行时消费者。
 *
 * P3 起本页也是图层缓存/合批/文字版本统计的真实消费者（不是第二套账本）：整页拆成
 * 背景/内容/统计三个子层，连续跑三帧——首帧重建背景+内容、第二帧无脏层全部跳过、
 * 第三帧只重画统计层，面板显示这三帧的框架读数。`bun run dev`（Three 默认）后访问 `/资源验收`
 * 即可截图（390×844 视口），全局 `window.__资源验收__` 供浏览器脚本读取统计与请求来源。
 */

const 逻辑宽 = 390;
const 逻辑高 = 844;
const 纹理预算字节 = 64 * 1024 * 1024;
const 字体 = 默认字体栈;
const 验收页名 = "资源验收";
/** 与启动层同口径：背景、内容、统计各占一个子层；统计层最后重画，不影响前两层命中率。 */
const 子层 = { 背景: 0, 内容: 1, 统计: 2 } as const;
const 每页子层数 = 3;

const 样式 = {
  标题: { 字体, 字号: 20, 字重: "粗体", 颜色: 0x00e5ff } satisfies 文字样式,
  小标题: { 字体, 字号: 14, 字重: "粗体", 颜色: 0xffee58 } satisfies 文字样式,
  正文: { 字体, 字号: 12, 颜色: 0xe6eefc } satisfies 文字样式,
  弱: { 字体, 字号: 10, 颜色: 0x8fa3c8 } satisfies 文字样式,
} as const;

function 格式化字节(字节: number): string {
  if (字节 >= 1024 * 1024) return `${(字节 / 1024 / 1024).toFixed(2)} MB`;
  if (字节 >= 1024) return `${(字节 / 1024).toFixed(1)} KB`;
  return `${字节} B`;
}

interface 验收统计快照 {
  首帧: 图层缓存统计;
  无脏帧: 图层缓存统计;
  合批首帧: 图元合批统计;
  合批无脏帧: 图元合批统计;
  文字: 文字服务统计;
  渲染: 渲染编排统计;
}

async function 启动(): Promise<void> {
  const 容器 = document.getElementById("游戏容器");
  if (!容器) throw new Error("缺少 #游戏容器");

  const 渲染 = 创建渲染编排({
    容器,
    逻辑宽,
    逻辑高,
    像素比: 1,
    清屏色: 0x0a0e1d,
    最大帧率: 60,
    按需渲染: true,
    纹理预算字节,
  });
  const 合批 = new 图元合批();
  渲染.场景.add(合批.提交());
  const 缓存 = 创建图层缓存({ 合批, 每页子层数 });
  const 图层 = new 图层作用域(合批, { 每页层数: 每页子层数 });
  缓存.同步栈([{ 名称: 验收页名 }]);

  const 来源列表: string[] = [];
  let 资源: 资源层实例;
  try {
    资源 = await 创建资源层({
      图集名: "资源验收",
      图集地址: "./测试资源/图集/",
      登记纹理: 渲染.登记纹理,
      记录来源: (地址) => {
        if (!来源列表.includes(地址)) 来源列表.push(地址);
      },
    });
  } catch (错误) {
    throw 错误 instanceof Error ? 错误 : new Error(String(错误));
  }

  const 文字 = 创建文字服务({
    登记纹理: 渲染.登记纹理,
    字体,
  });
  const 画笔 = 创建画笔({ 合批, 文字服务: 文字, 资源层: 资源 });

  const 统计 = 资源.读取统计();
  const 裁剪图 = 资源.读取散图("测试/裁剪");

  // —— 子层 1：静态背景（渐变 + 标题衬底 + 标题） ——
  const 绘制背景层 = (): void => {
    画笔.重置();
    画笔.图形
      .fillGradientStyle(0x101a33, 0x101a33, 0x060a16, 0x060a16)
      .fillRect(0, 0, 逻辑宽, 逻辑高);
    画笔.图形.fillStyle(0x0f1b33).fillRoundedRect(16, 16, 逻辑宽 - 32, 60, 12);
    画笔.绘制文字({
      文案: "资源验收 · GM 图集运行时消费者",
      样式: 样式.标题,
      锚点: "中上",
      x: 逻辑宽 / 2,
      y: 30,
    });
  };

  // —— 子层 2：内容（图集帧 / 散图 / 请求来源；只有主题或资源变化才需要重建） ——
  const 绘制内容层 = (): void => {
    画笔.重置();
    画笔.图形.fillStyle(0x122240, 0.9).fillRoundedRect(20, 96, 170, 170, 10);
    画笔.绘制纹理帧(
      { 图集: "资源验收", 帧: "裁剪图标.png" },
      { 左: 32, 上: 108, 宽: 144, 高: 144 },
    );
    画笔.绘制文字({
      文案: `项目图集\n${统计.帧数 ? `${统计.帧数} 帧` : "当前无运行时图片"}`,
      样式: 样式.正文,
      锚点: "左上",
      x: 200,
      y: 104,
    });
    画笔.绘制文字({
      文案: `图集帧 ${统计.帧数} · 页 ${统计.页数} · 图集 ${统计.图集数}`,
      样式: 样式.小标题,
      锚点: "左上",
      x: 200,
      y: 210,
    });
    画笔.绘制文字({
      文案: `渲染纹理 ${格式化字节(渲染.读取统计().纹理字节)} / 预算 ${格式化字节(纹理预算字节)}`,
      样式: 样式.正文,
      锚点: "左上",
      x: 200,
      y: 232,
    });
    画笔.绘制文字({
      文案: `资源层纹理 ${格式化字节(统计.纹理字节)}`,
      样式: 样式.弱,
      锚点: "左上",
      x: 200,
      y: 252,
    });
    画笔.绘制文字({
      文案: `运行时散图 ${统计.散图数}`,
      样式: 样式.正文,
      锚点: "左上",
      x: 200,
      y: 272,
    });

    // 项目测试散图：走资源层 → 整图 UV。
    const 裁剪图宽 = 240;
    const 裁剪图高 = 裁剪图 && 裁剪图.宽 > 0 ? Math.round((裁剪图宽 * 裁剪图.高) / 裁剪图.宽) : 240;
    const 裁剪图绘制 = 画笔.绘制散图("测试/裁剪", {
      左: 20,
      上: 300,
      宽: 裁剪图宽,
      高: 裁剪图高,
    });
    画笔.图形.lineStyle(1, 0x00e5ff, 0.8).strokeRoundedRect(18, 298, 裁剪图宽 + 4, 裁剪图高 + 4, 6);
    画笔.绘制文字({
      文案: `项目测试散图\n测试/裁剪\n${裁剪图 ? `${裁剪图.宽}×${裁剪图.高}` : "未加载"}\n绘制${裁剪图绘制 ? "成功" : "失败"}`,
      样式: 样式.正文,
      锚点: "左上",
      x: 20 + 裁剪图宽 + 16,
      y: 304,
    });

    // 请求来源列表。
    const 来源行 = 来源列表.map((地址) => `· ${地址}`).join("\n");
    画笔.图形.fillStyle(0x0d1930).fillRoundedRect(16, 640, 逻辑宽 - 32, 180, 10);
    画笔.绘制文字({
      文案: `请求来源（${来源列表.length}）\n${来源行}`,
      样式: 样式.正文,
      锚点: "左上",
      最大宽: 逻辑宽 - 48,
      x: 28,
      y: 654,
    });
    画笔.绘制文字({
      文案: `默认散图：${读取默认散图()
        .map((项) => 项.键)
        .join("、")}`,
      样式: 样式.弱,
      锚点: "左上",
      x: 28,
      y: 788,
    });
  };

  // —— 子层 3：框架实时统计（真实读数，不另建账本） ——
  let 快照: 验收统计快照 | null = null;
  const 绘制统计层 = (): void => {
    const 数 = 快照;
    if (!数) return;
    画笔.重置();
    const 失效 = 数.无脏帧.失效原因计数;
    画笔.绘制文字({
      文案: "P3 缓存 / 合批 / 文字实时统计（本页即消费者）",
      样式: 样式.小标题,
      锚点: "左上",
      x: 20,
      y: 444,
    });
    const 行 = [
      `图层缓存 每页${数.无脏帧.每页子层数}子层 帧${数.无脏帧.帧序号}`,
      `首帧重建${数.首帧.本帧重建层数}层 · 无脏帧重建${数.无脏帧.本帧重建层数}跳过${数.无脏帧.本帧跳过层数}`,
      `命中率${(数.无脏帧.命中率 * 100).toFixed(0)}% 累计重建${数.无脏帧.累计重建层数}跳过${数.无脏帧.累计跳过层数}`,
      `失效原因 进入${失效.进入} 内容${失效.内容} 尺寸${失效.尺寸} 文字版本${失效.文字版本}`,
      `合批 首帧上传${数.合批首帧.上传批数}批 · 无脏帧上传${数.合批无脏帧.上传批数}批跳过${数.合批无脏帧.跳过批数}批`,
      `缓冲${格式化字节(数.合批无脏帧.缓冲字节)} · 上传字节${格式化字节(数.合批首帧.上传字节估算)}`,
      `文字版本${数.文字.版本} 图集${数.文字.图集数} 纹理${格式化字节(数.文字.纹理字节)} 退役${格式化字节(数.文字.待确认退役字节)}`,
      `渲染纹理${格式化字节(数.渲染.纹理字节)} 峰值${格式化字节(数.渲染.纹理峰值字节)} 预算${格式化字节(纹理预算字节)}`,
    ];
    行.forEach((文案, 序号) => {
      画笔.绘制文字({
        文案,
        样式: 序号 === 0 ? 样式.正文 : 样式.弱,
        锚点: "左上",
        x: 20,
        y: 470 + 序号 * 18,
      });
    });
  };

  /** 缓存门面：只重建本帧需要的子层；不脏返回 false，页面不写任何几何。 */
  const 绘制子层 = (子层号: number, 绘制: () => void): void => {
    缓存.进入页面(验收页名, 0);
    if (!缓存.需要重建(验收页名, 子层号)) return;
    缓存.开始重建(验收页名, 子层号);
    图层.进入页面(0, () => {
      图层.设置子层(子层号);
      绘制();
    });
  };
  const 渲染一帧 = (): void => {
    缓存.开始帧();
    绘制子层(子层.背景, 绘制背景层);
    绘制子层(子层.内容, 绘制内容层);
    绘制子层(子层.统计, 绘制统计层);
    合批.提交();
    缓存.提交();
    渲染.请求重绘();
    渲染.渲染();
  };

  // 第一帧：背景+内容首次重建；第二帧：无脏层 → 全部跳过（命中率证据）。
  渲染一帧();
  const 首帧 = 缓存.读取统计();
  const 合批首帧 = 合批.读取统计();
  渲染一帧();
  const 无脏帧 = 缓存.读取统计();
  const 合批无脏帧 = 合批.读取统计();
  // 第三帧：只补统计面板；前两层保持保留几何。先等一帧，避免被渲染编排的最小帧间隔跳过。
  await new Promise((完成) => setTimeout(完成, 60));
  快照 = {
    首帧,
    无脏帧,
    合批首帧,
    合批无脏帧,
    文字: 文字.读取统计(),
    渲染: 渲染.读取统计(),
  };
  缓存.标记失效(验收页名, [子层.统计], "内容");
  渲染一帧();
  const 第三帧 = 缓存.读取统计();

  const 读取统计 = () => ({
    图集: 统计,
    合批: 合批.读取统计(),
    渲染: 渲染.读取统计(),
    图层缓存: 缓存.读取统计(),
    图层缓存首帧: 首帧,
    图层缓存无脏帧: 无脏帧,
    图层缓存第三帧: 第三帧,
    合批首帧,
    合批无脏帧,
    文字: 文字.读取统计(),
    来源: [...来源列表],
    帧: (() => {
      const 帧 = 资源.读取帧("资源验收", "裁剪图标.png");
      return 帧 ? { 页: 帧.页, 源宽: 帧.源宽, 源高: 帧.源高 } : null;
    })(),
    散图: {
      图标: null,
      裁剪图: 裁剪图 ? { 宽: 裁剪图.宽, 高: 裁剪图.高 } : null,
    },
    纹理预算字节,
  });

  Object.assign(window, {
    __资源验收__: {
      读取统计,
      停止: () => {
        Reflect.deleteProperty(window, "__资源验收__");
        缓存.销毁();
        合批.销毁();
        文字.销毁();
        资源.销毁();
        渲染.销毁();
      },
    },
  });
  console.log("资源验收页已渲染", 读取统计());
}

启动().catch((错误: unknown) => {
  const 文本 = 错误 instanceof Error ? 错误.message : String(错误);
  console.error("资源验收页启动失败", 错误);
  const 提示 = document.getElementById("错误提示");
  if (提示) {
    提示.style.display = "block";
    提示.textContent = `资源验收页启动失败：${文本}`;
  }
});

declare global {
  interface Window {
    __资源验收__?: {
      读取统计: () => {
        图集: { 图集数: number; 页数: number; 帧数: number; 纹理字节: number; 散图数: number };
        合批: { 四边形数: number; 三角形数: number; 绘制批数: number; 顶点数: number };
        渲染: { 纹理数: number; 纹理字节: number; 渲染帧数: number };
        图层缓存: { 帧序号: number; 本帧重建层数: number; 本帧跳过层数: number; 命中率: number };
        图层缓存首帧: { 本帧重建层数: number; 本帧跳过层数: number };
        图层缓存无脏帧: { 本帧重建层数: number; 本帧跳过层数: number; 命中率: number };
        图层缓存第三帧: { 本帧重建层数: number; 本帧跳过层数: number };
        合批首帧: { 上传批数: number; 上传字节估算: number; 跳过批数: number };
        合批无脏帧: { 上传批数: number; 上传字节估算: number; 跳过批数: number };
        文字: { 版本: number; 图集数: number; 纹理字节: number; 待确认退役字节: number };
        来源: string[];
        帧: { 页: number; 源宽: number; 源高: number } | null;
        散图: {
          图标: { 宽: number; 高: number } | null;
          裁剪图: { 宽: number; 高: number } | null;
        };
        纹理预算字节: number;
      };
      停止: () => void;
    };
  }
}

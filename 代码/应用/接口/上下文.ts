/**
 * 《再消一行》Three 版的页面装配契约：b-ui 的页面、b-core 的对局/结算、启动.ts 都按这里对齐。
 * 页面只拿到 上下文（资源/服务/导航/资源/主题/参数），自己实现框架场景接口。
 *
 * 页面清单只有一个：层与页的归属由页面选项（层/自带背景/暂停下层/独占命中）表达，
 * 「覆盖页」概念已取消——暂停菜单与结算是浮在对局上的普通页面。
 */

/** 页面清单：菜单、模式选择、纯享 + 设置/成就/排行榜/商店 + 对局/暂停菜单/结算。 */
export type 页面编号 =
  | "菜单"
  | "模式选择"
  | "纯享"
  | "设置"
  | "成就"
  | "排行榜"
  | "商店"
  | "对局"
  | "暂停菜单"
  | "结算";

/** 根页面：整局应用至少保留它。 */
export const 根页面: 页面编号 = "菜单";

/** 浮在对局上的页面：进入时暂停下层关闭、独占命中打开。 */
export const 浮层页面: readonly 页面编号[] = ["暂停菜单", "结算"];

export function 是浮层页面(页面: string): boolean {
  return (浮层页面 as readonly string[]).includes(页面);
}

/** 纯享页的入口来源：菜单与商店各自回到自己的页面。 */
export type 纯享来源 = "菜单" | "商店";

/** 页面参数：导航时带过去的最小数据，其它状态从服务读取。 */
export interface 页面参数 {
  模式?: 游戏模式;
  入场演出?: boolean;
  /** 素材截图跳过开场，画面立刻可摆。 */
  跳过入场?: boolean;
  提示?: string;
  返回页?: 页面编号;
  /** 纯享页来源：回到来源页。 */
  来源?: 纯享来源;
  /** 纯享页初始风景（商店把当前浏览地点带过去）。 */
  风景?: string;
  /** 商店进入纯享时沿用当前静态/动态预览。 */
  风景动态?: boolean;
  /** 结算覆盖页的输入；对局页结束时填好再打开。 */
  结果?: 对局结果;
}

export interface 帧统计 {
  帧数: number;
  平均帧间隔毫秒: number;
  平均工作毫秒: number;
  绘制调用: number;
  四边形数: number;
  /** 图元合批本帧三角形数（新页面/共享配方绘制）。 */
  三角形数?: number;
  /** 渲染编排纹理预算占用字节。 */
  纹理字节?: number;
}

export interface 页面资源 {
  逻辑宽: number;
  逻辑高: number;
  /** 全应用共用图元合批：控件层/共享配方写图元，同一张合批保证界面层遮挡正确。 */
  合批: 图元合批;
  /** 共享视觉配方的绘制入口（图元合批 + 文字图集 + 资源层）。 */
  画笔: 画笔;
  /** GM 静态图集帧 / 散图纹理的只读查询。 */
  资源: 资源层;
  /** 资源层纹理统计（图集数/页数/帧数/纹理字节/散图数）。 */
  读取纹理统计(): 资源统计;
  /** 全应用共用命中分发：页面在 进入 时注册、在 退出/销毁 时注销。 */
  命中: 命中分发;
  读取帧统计(): 帧统计;
  /** 按需渲染：页面状态变化时调用，启动层在下一帧重绘一次。 */
  请求重绘(): void;
  /** 只唤醒渲染器：输入安全网/背景调度用，不改变任何层的失效状态。 */
  请求渲染(): void;
  /** 标记某页子层失效（启动层图层缓存门面）；子层省略表示该页全部子层。 */
  标记失效(页名: string, 子层?: readonly number[], 原因?: string): void;
  /** 该页该子层是否需要重建（从未建过或已失效）。 */
  需要重建(页名: string, 子层: number): boolean;
  /** 开始重建该子层：清空该图层几何并标脏，绘制由调用方随后执行。 */
  开始重建(页名: string, 子层: number): void;
  /**
   * 页内绘制子层（相对本页基准层）：同一页里覆盖面板/弹层要压住内容时，
   * 在画覆盖内容之前调用（约定 0=内容、1=控件、2=覆盖、3+ 扩展）。
   */
  设置绘制层(偏移: number): void;
  /** 对局页报告玩法是否进行中；启动层据此做按需渲染/省电限帧。 */
  设置玩法进行中(进行中: boolean): void;
  设置镜头偏移?(x: number, y: number): void;
}

export interface 导航服务 {
  进入(页面: 页面编号, 参数?: 页面参数, 过渡?: 页面过渡): void;
  /** 替换：把页面层退到根页后再进入目标页（用于结算→对局、暂停→菜单）。 */
  替换(页面: 页面编号, 参数?: 页面参数): void;
  返回(过渡?: 页面过渡): void;
  /** 浮在对局上的页面（暂停菜单/结算）：不暂停下层、独占命中。 */
  打开浮层(页面: 页面编号, 参数?: 页面参数): void;
  关闭浮层(): void;
  读取当前(): { 页面: 页面编号; 覆盖: 页面编号 | null };
  /** 某层的栈顶页名（框架页面导航语义，直接转发宿主）。 */
  读取层顶名(层: string): string | null;
  /** 进入任意层的页面（背景层 / 货币层 / 提示层）。 */
  打开层(层: string, 名称: string, 参数?: 页面参数): void;
  关闭层(层: string): void;
}

export interface 页面上下文 extends 页面基类上下文 {
  资源: 页面资源;
  服务: 应用服务;
  导航: 导航服务;
  主题: 游戏主题;
  参数: 页面参数;
  /** 控件文字服务：全应用共享一个，控件库按字号档测量/排版/绘制。 */
  文字: 控件文字服务;
  /** 主题 → 控件语义配色；框架页面基类每帧读取，跟随主题切换。 */
  读取配色(): 界面配色;
  /** 页面开合动画（设置/成就/商店）播放中：读取界面据此禁用按钮。 */
  读取界面开合中?(): boolean;
  /** 全应用背景共用的动画时间；页面切换不重置。 */
  读取背景时间?(): number;
  /** 页面注册自己的清理动作；页面退出/销毁时由装配层统一调用（返回解绑函数）。 */
  登记清理(清理: () => void): () => void;
}

/** 对局测试桥控制：b-core 的对局页实现，启动.ts 统一挂到 window.__再消一行测试__。 */
export interface 对局测试控制 {
  设置序列(序列: readonly string[]): void;
  准备单行消除(): void;
  准备四行消除(继续连击?: boolean, 保留堆叠?: boolean): void;
  读取特效(): import("../../../资源/视效/特效/对局特效").特效状态;
  硬降(): void;
  设置暂停(暂停: boolean): void;
  结束当前对局(): void;
  准备目标达成(): void;
  准备结算(完赛?: boolean): void;
  准备倒计时(剩余毫秒: number): void;
  准备贴墙旋转(): void;
  /** 素材录像：自己落子直到通关或失败，不写存档。 */
  开始素材演示(选项: { 目标: "成功" | "失败"; 秒数: number }): void;
  /** 素材截图：摆几手下暂停，棋盘上能看见方块。 */
  摆好素材画面(): void;
  /** 结算截图和录像都不写入纪录、金币或平台。 */
  标记不写存档(): void;
}

/** 页面按钮快照：调试桥按名称驱动真实点击，验收脚本不依赖硬编码坐标。 */
export interface 界面按钮快照 {
  名称: string;
  左: number;
  上: number;
  宽: number;
  高: number;
  /** 当前是否可点（禁用态点击会被命中路由跳过）。 */
  可用?: boolean;
}

export interface 界面快照 {
  按钮: readonly 界面按钮快照[];
  /** 页面上供验收读取的文字/状态（可选）。 */
  文字?: readonly string[];
}

/**
 * 页面实例 = 场景接口 + 可选测试/统计读取（对局页实现，启动层按鸭子类型接入调试桥）。
 * `读取背景动态` / `刷新背景动态` 由自带背景的页面（纯享/商店/透视对局）与背景层页面实现，
 * 启动层背景调度按它们驱动动态层重画。
 */
export interface 页面实例 extends 场景接口<页面上下文> {
  调整尺寸?(): void;
  读取背景动态?(): boolean;
  刷新背景动态?(): void;
  /**
   * 本页是否正在播放需要连续帧的动画（例如结算金币动画）。
   * 启动层空闲判定据此保持 rAF 满帧，动画结束才允许降到 100ms 心跳。
   */
  读取需要连续帧?(): boolean;
  测试?: 对局测试控制;
  读取快照?(): unknown;
  读取原始状态?(): unknown;
  读取对局统计?(): { 操作次数: number; 落块数: number; 消行次数: number };
  读取操作记录?(): unknown[];
  读取界面?(): 界面快照;
}

/** 页面工厂：启动.ts 用页面表按编号延迟创建页面；同名页面只创建一次。 */
export type 页面工厂 = (上下文: 页面上下文) => 页面实例;
export type 页面注册表 = Partial<Record<页面编号, 页面工厂>>;

import type { 矩形 } from "../../../.gamemaker/依赖/框架/界面/绘制/协议";
import type { 游戏模式 } from "../../玩法/再消一行";

/**
 * 转场演出：模式选择 → 对局的一条接力，由动画层负责播放，页面只管自己的内容。
 * 收束（1.06s）：从被选中的模式卡出发，盖满整屏；结束时切页进对局。
 * 展开（1.34s）：从盖满整屏开始，按主题画法露出新画面，随后 Ready/Go 节拍。
 */
export type 转场阶段 = "收束" | "展开";

export interface 转场演出 {
  模式: 游戏模式;
  阶段: 转场阶段;
  /** 本阶段已经过秒数。 */
  秒: number;
  /** 收束阶段被选中的模式卡矩形（页面坐标，y 向下）；展开阶段为 null。 */
  原卡: 矩形 | null;
}

export interface 转场服务选项 {
  /** 收束结束：切页进对局。由启动层接上真实导航，服务本身不碰页面栈。 */
  进入对局?: (模式: 游戏模式) => void;
}

export interface 转场服务 {
  /** 开始收束：模式卡点击时调用。 */
  开始收束(模式: 游戏模式, 原卡: 矩形): void;
  /** 直接开始展开：没有收束的入口（素材演示、直接进对局）。 */
  开始展开(模式: 游戏模式): void;
  /** 清掉演出：跳过入场、直接结算等场景。 */
  重置(): void;
  读取(): 转场演出 | null;
  /** 展开阶段的秒数（对局页的入场时间轴），不在展开阶段返回 null。 */
  读取入场秒(): number | null;
  /** 由动画层每帧推进；阶段切换与页面切页都在这里发生。 */
  更新(秒: number): void;
  /** 演出开始/推进/结束时通知，动画层据此重绘。 */
  订阅(回调: (演出: 转场演出 | null) => void): () => void;
}

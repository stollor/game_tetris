export function 创建默认主题服务(设置: 设置服务): 主题服务 {
  const 订阅者 = new Set<(主题: 游戏主题) => void>();
  const 读取 = (): 游戏主题 => {
    const 设置值 = 设置.读取();
    const 方案 = 调色板[设置值.样式] ?? 调色板.青蓝未来;
    return {
      名称: 设置值.样式,
      深色: 设置值.主题 !== "浅色",
      颜色: { ...方案 },
      方块: 解析方块外观(设置值.方块外观).颜色,
    };
  };
  const 订阅 = (回调: (主题: 游戏主题) => void) => {
    订阅者.add(回调);
    return () => {
      订阅者.delete(回调);
    };
  };
  设置.订阅((变化) => {
    const 主题 = 读取();
    for (const 回调 of 订阅者) 回调(主题);
    void 变化;
  });
  return {
    读取,
    订阅,
  };
}

import { 创建纪录存档, 是否刷新纪录 } from "../../存档/对局纪录";
import { 旅行日期 } from "../../存档/旅行收藏";
import type { 纪录服务 } from "../接口/服务";

/** 纪录服务复用游戏版本化存档：键、校验、旧格式兼容都由 代码/存档/ 决定。 */
export function 创建纪录服务(存储: Storage = localStorage): 纪录服务 {
  return {
    读取: (模式, 日期 = 旅行日期()) => 创建纪录存档(模式, 日期, 存储).读取(),
    保存: (模式, 纪录, 日期 = 旅行日期()) => {
      const 存档 = 创建纪录存档(模式, 日期, 存储);
      if (!是否刷新纪录(模式, 纪录, 存档.读取())) return false;
      if (!存档.保存(纪录)) throw new Error("本地纪录保存失败，停止本次云上传");
      return true;
    },
  };
}

/** 《再消一行》Three 版的界面绘制：只往合批里写四边形，不碰渲染器与场景栈。 */

export interface 界面 {
  合批: 四边形合批;
  字小: 文字图集;
  字大: 文字图集;
}

export interface 消行闪烁 {
  行: number[];
  比例: number;
}

export function 绘制底色(界面: 界面): void {
  const 白块 = 界面.字小.读取纯色紫外线();
  界面.合批.添加({
    左: 0,
    上: 0,
    宽: 逻辑宽,
    高: 逻辑高,
    紫外线: 白块,
    颜色: 十六进制颜色(颜色.底色),
  });
  界面.合批.添加({
    左: 0,
    上: 0,
    宽: 逻辑宽,
    高: 布局.顶部高度,
    紫外线: 白块,
    颜色: 十六进制颜色(颜色.顶部),
  });
}

export function 绘制面板(界面: 界面, 矩形: 矩形, 填充: number, 描边: number): void {
  const 白块 = 界面.字小.读取纯色紫外线();
  界面.合批.添加({ ...矩形, 紫外线: 白块, 颜色: 十六进制颜色(描边) });
  const 边 = 1.5;
  界面.合批.添加({
    左: 矩形.左 + 边,
    上: 矩形.上 + 边,
    宽: Math.max(1, 矩形.宽 - 边 * 2),
    高: Math.max(1, 矩形.高 - 边 * 2),
    紫外线: 白块,
    颜色: 十六进制颜色(填充),
  });
}

/** 宝石质感方块：底色 + 顶部高光 + 底部暗边，三块四边形。 */
export function 绘制方块格(
  界面: 界面,
  色: number,
  左: number,
  上: number,
  尺寸: number,
  透明度 = 1,
): void {
  if (透明度 <= 0) return;
  const 白块 = 界面.字小.读取纯色紫外线();
  const 内缩 = Math.max(1, 尺寸 * 0.05);
  const 内左 = 左 + 内缩;
  const 内上 = 上 + 内缩;
  const 内尺寸 = Math.max(1, 尺寸 - 内缩 * 2);
  const 高光高 = Math.max(2, 内尺寸 * 0.2);
  const 暗边高 = Math.max(2, 内尺寸 * 0.12);
  界面.合批.添加({
    左: 内左,
    上: 内上,
    宽: 内尺寸,
    高: 内尺寸,
    紫外线: 白块,
    颜色: 十六进制颜色(色, 透明度),
  });
  界面.合批.添加({
    左: 内左,
    上: 内上,
    宽: 内尺寸,
    高: 高光高,
    紫外线: 白块,
    颜色: 十六进制颜色(混合颜色(色, 0xffffff, 0.5), 透明度 * 0.9),
  });
  界面.合批.添加({
    左: 内左,
    上: 内上 + 内尺寸 - 暗边高,
    宽: 内尺寸,
    高: 暗边高,
    紫外线: 白块,
    颜色: 十六进制颜色(混合颜色(色, 0x000000, 0.35), 透明度 * 0.85),
  });
}

function 绘制形状(界面: 界面, 类型: 方块类型, 中心X: number, 上: number, 格: number): void {
  const 格子 = 预览格子(类型);
  const 列数 = Math.max(...格子.map(([列]) => 列)) + 1;
  const 左 = 中心X - (列数 * 格) / 2;
  for (const [列, 行] of 格子) {
    绘制方块格(界面, 方块颜色[类型], 左 + 列 * 格, 上 + 行 * 格, 格, 0.95);
  }
}

function 文字(界面: 界面, 大字: boolean, 文本: string, 左: number, 上: number, 色: number): void {
  (大字 ? 界面.字大 : 界面.字小).绘制(界面.合批, 文本, {
    左,
    上,
    颜色: 十六进制颜色(色),
    纹理序号: 大字 ? 1 : 0,
  });
}

function 居中文字(
  界面: 界面,
  大字: boolean,
  文本: string,
  中心X: number,
  上: number,
  色: number,
): void {
  const 图集 = 大字 ? 界面.字大 : 界面.字小;
  const 宽 = 图集.测量(文本);
  文字(界面, 大字, 文本, 中心X - 宽 / 2, 上, 色);
}

function 绘制棋盘(界面: 界面, 状态: 再消一行状态, 影子: [number, number][]): void {
  const { 左, 上, 格, 列, 行 } = 布局.棋盘;
  绘制面板(
    界面,
    { 左: 左 - 5, 上: 上 - 5, 宽: 列 * 格 + 10, 高: 行 * 格 + 10 },
    颜色.面板,
    颜色.线,
  );
  for (let 行号 = 0; 行号 < 行; 行号++) {
    for (let 列号 = 0; 列号 < 列; 列号++) {
      const 类型 = 状态.棋盘[行号 + 2]?.[列号];
      if (类型) {
        绘制方块格(界面, 方块颜色[类型], 左 + 列号 * 格, 上 + 行号 * 格, 格);
      }
    }
  }
  for (const [列号, 行号] of 影子) {
    if (行号 < 0 || 行号 >= 行 || 状态.棋盘[行号 + 2]?.[列号]) continue;
    绘制方块格(界面, 方块颜色[状态.当前方块.类型], 左 + 列号 * 格, 上 + 行号 * 格, 格, 0.18);
  }
}

function 绘制消行闪烁(界面: 界面, 闪烁: 消行闪烁 | null): void {
  if (!闪烁 || 闪烁.比例 <= 0) return;
  const 白块 = 界面.字小.读取纯色紫外线();
  const { 左, 上, 格, 列 } = 布局.棋盘;
  for (const 行号 of 闪烁.行) {
    if (行号 < 0) continue;
    界面.合批.添加({
      左,
      上: 上 + 行号 * 格,
      宽: 列 * 格,
      高: 格,
      紫外线: 白块,
      颜色: 十六进制颜色(0xffffff, 闪烁.比例 * 0.55),
      混合: "叠加",
    });
  }
}

function 绘制顶部(界面: 界面, 状态: 再消一行状态): void {
  const 数值上 = 24;
  文字(界面, false, 界面文案.分数, 20, 6, 颜色.次字);
  文字(界面, true, String(状态.分数), 20, 数值上, 颜色.主字);
  文字(界面, false, 界面文案.消行, 150, 6, 颜色.次字);
  文字(界面, true, String(状态.消行数), 150, 数值上, 颜色.主字);
  文字(界面, false, 界面文案.等级, 280, 6, 颜色.次字);
  文字(界面, true, String(状态.等级), 280, 数值上, 颜色.青);

  const { 暂存左, 下一个左, 上, 宽, 高, 格 } = 布局.预览;
  文字(界面, false, 界面文案.暂存, 20, 52, 颜色.次字);
  文字(界面, false, 界面文案.下一个, 130, 52, 颜色.次字);
  绘制面板(界面, { 左: 暂存左, 上, 宽, 高 }, 颜色.面板, 颜色.线);
  绘制面板(界面, { 左: 下一个左, 上, 宽: 布局.预览.宽 + 10, 高 }, 颜色.面板, 颜色.线);
  if (状态.暂存方块) 绘制形状(界面, 状态.暂存方块, 暂存左 + 宽 / 2, 上 + 5, 格);
  绘制形状(界面, 状态.下一个方块, 下一个左 + 28, 上 + 5, 格);
  const 后续 = 状态.后续方块[0];
  if (后续) 绘制形状(界面, 后续, 下一个左 + 82, 上 + 5, 格);
}

function 绘制控制区(界面: 界面): void {
  控制按钮.forEach((按钮, 序号) => {
    const 列 = 序号 % 3;
    const 行 = 序号 < 3 ? 1 : 2;
    const 矩形 = 控制按钮矩形(列, 行);
    绘制面板(界面, 矩形, 颜色.浮层, 颜色.线);
    居中文字(
      界面,
      true,
      按钮.标签,
      矩形.左 + 矩形.宽 / 2,
      矩形.上 + (矩形.高 - 界面.字大.读取行高()) / 2,
      颜色.主字,
    );
  });
}

export function 绘制对局(
  界面: 界面,
  状态: 再消一行状态,
  影子: [number, number][],
  闪烁: 消行闪烁 | null,
): void {
  绘制底色(界面);
  绘制顶部(界面, 状态);
  绘制棋盘(界面, 状态, 影子);
  绘制消行闪烁(界面, 闪烁);
  绘制控制区(界面);
}

export interface 结算数据 {
  分数: number;
  消行数: number;
  等级: number;
  完赛: boolean;
}

export function 绘制结算(界面: 界面, 状态: 结算数据): void {
  const 白块 = 界面.字小.读取纯色紫外线();
  界面.合批.添加({
    左: 0,
    上: 0,
    宽: 逻辑宽,
    高: 逻辑高,
    紫外线: 白块,
    颜色: 十六进制颜色(颜色.底色, 0.76),
  });
  const { 左, 上, 宽, 高 } = 布局.结算;
  绘制面板(界面, { 左, 上, 宽, 高 }, 颜色.浮层, 颜色.青);
  const 标题 = 状态.完赛 ? 界面文案.挑战完成 : 界面文案.游戏结束;
  居中文字(界面, true, 标题, 左 + 宽 / 2, 上 + 26, 颜色.主字);
  居中文字(界面, false, 界面文案.分数, 左 + 宽 / 2, 上 + 84, 颜色.次字);
  居中文字(界面, true, String(状态.分数), 左 + 宽 / 2, 上 + 104, 颜色.青);
  居中文字(
    界面,
    false,
    `${界面文案.消行} ${状态.消行数} · ${界面文案.等级} ${状态.等级}`,
    左 + 宽 / 2,
    上 + 148,
    颜色.次字,
  );
  绘制面板(界面, 结算按钮, 颜色.面板, 颜色.青);
  居中文字(
    界面,
    true,
    界面文案.重新开始,
    结算按钮.左 + 结算按钮.宽 / 2,
    结算按钮.上 + (结算按钮.高 - 界面.字大.读取行高()) / 2,
    颜色.主字,
  );
}

/**
 * 成就页（7C）：与 Phaser 版同构——顶栏金币条 + 标题/副题 + 成就列表（行底板/进度线/文字）+ 返回按钮。
 * 视觉来自共享配方（页面配方/文字样式/金币条配方/按钮配方），滚动与命中用 GM Three 控件能力自绘。
 */

export class 成就界面 extends 页面基类 {
  private 滚动: 滚动容器 | null = null;
  private 滚动位置 = 0;
  private 色: 页面语义色 = 读取页面语义色(this.上下文.服务.设置.读取().样式);

  constructor(上下文: 页面上下文) {
    super(上下文, { 名称: "成就", 独占: true, 背景: false });
  }

  进入(): void {
    super.进入();
    this.上下文.登记清理(this.上下文.服务.成就.订阅(() => this.重建()));
    this.上下文.登记清理(this.上下文.服务.金币.订阅(() => this.重建()));
    this.自动领取();
  }

  private 自动领取(): void {
    const 已解锁 = this.上下文.服务.成就.读取已解锁();
    if (已解锁.length === 0) return;
    const 结果 = this.上下文.服务.金币.领取成就(已解锁);
    if (结果.新增 <= 0) return;
    this.显示提示(
      this.上下文.服务.语言.是否英文()
        ? `Achievement rewards +${结果.新增}`
        : `成就奖励 +${结果.新增} 方块币`,
    );
  }

  protected 构建(): void {
    this.滚动位置 = this.滚动?.读取滚动位置() ?? this.滚动位置;
    this.控件层.清空();
    this.色 = 读取页面语义色(this.上下文.服务.设置.读取().样式);
    const 页面布局 = 计算成就页布局(this.逻辑宽, this.逻辑高);
    this.滚动 = new 滚动容器类({
      矩形: 页面布局.列表,
      内容高: 成就定义.length * 页面布局.行高,
      显示滚动条: false,
      惯性: true,
    });
    this.控件层.添加(this.滚动);
    this.滚动.设置滚动位置(this.滚动位置);
    this.滚动位置 = this.滚动.读取滚动位置();
    this.创建热区({
      名称: "返回主菜单",
      矩形: 页面布局.返回,
      点击: () => this.上下文.导航.返回(),
    });
  }

  protected 绘制内容(): void {
    const 画笔 = this.上下文.资源.画笔;
    const 图形 = 画笔.图形;
    if (!this.滚动) return;
    const 英文 = this.上下文.服务.语言.是否英文();
    const 色 = this.色;
    const 金币 = this.上下文.服务.金币.读取().金币;
    图形.fillStyle(色.面板, 1).fillRect(0, 0, this.逻辑宽, this.逻辑高);
    const 金币布局 = 计算金币条(16, 12, 金币);
    绘制金币条(图形, 金币布局);
    for (const 项 of 生成金币条文字项(金币布局, 金币)) 画笔.绘制文字(项);
    // 标题（窄屏避让金币条）
    const 标题文案 = `${英文 ? "ACHIEVEMENTS" : "成就收藏"}  ${this.已得()} / ${成就定义.length}`;
    const 标题样式 = 派生覆盖页文字样式({
      字号: 24,
      字重: "粗体",
      颜色: 色.正文,
      对齐: "中",
    });
    const 标题宽 = 画笔.测量文字(标题文案, 标题样式).宽;
    const 标题最小中心 = 16 + 金币布局.宽 + 12 + 标题宽 / 2;
    const 标题中心 = Math.max(
      this.逻辑宽 / 2,
      Math.min(标题最小中心, this.逻辑宽 - 12 - 标题宽 / 2),
    );
    画笔.绘制文字({ 文案: 标题文案, 样式: 标题样式, 锚点: "中中", x: 标题中心, y: 30 });
    画笔.绘制文字(
      生成页面文字项(
        "中中",
        this.逻辑宽 / 2,
        64,
        13,
        色.次要,
        "常规",
        "中",
        `${
          英文 ? "Every game leaves a little progress." : "每项成就 +60 方块币，自动存入旅行收藏。"
        }`,
      ),
    );
    const 可视 = this.滚动.读取可视矩形();
    const 偏移 = this.滚动.读取滚动位置();
    const 页面布局 = 计算成就页布局(this.逻辑宽, this.逻辑高);
    const 文字偏移 = { x: 可视.左, y: 可视.上 - 偏移 };
    const 暂存文字: 文字项[] = [];
    画笔.压入裁剪(可视);
    图形.save();
    图形.translateCanvas(可视.左, 可视.上 - 偏移);
    const 已解锁集合 = new Set(this.上下文.服务.成就.读取已解锁());
    成就定义.forEach((定义, 序号) => {
      const 已解锁 = 已解锁集合.has(定义.编号);
      const 进度 = this.上下文.服务.成就.读取进度(定义.编号);
      const 行矩形 = {
        左: 0,
        上: 序号 * 页面布局.行高,
        宽: 页面布局.行宽,
        高: 页面布局.行板高,
      };
      绘制列表行(图形, 行矩形, 色.按钮底, 已解锁 ? 色.强调 : 色.分组线, 0.7, 12, {
        比例: Math.min(1, 进度 / Math.max(1, 定义.目标)),
        轨道色: 色.分组线,
        强调色: 色.强调,
      });
      暂存文字.push(
        移位(
          生成页面文字项(
            "左上",
            16,
            行矩形.上 + 12,
            16,
            已解锁 ? 色.强调 : 色.正文,
            "粗体",
            "左",
            `${已解锁 ? "✓" : "◇"}  ${英文 ? 定义.英文 : 定义.名称}`,
          ),
          文字偏移,
        ),
        移位(
          生成页面文字项(
            "左上",
            16,
            行矩形.上 + 40,
            12,
            色.次要,
            "常规",
            "左",
            英文 ? 定义.英文说明 : 定义.说明,
            页面布局.说明宽,
          ),
          文字偏移,
        ),
        移位(
          生成页面文字项(
            "右上",
            页面布局.数量X,
            行矩形.上 + 18,
            12,
            色.次要,
            "常规",
            "右",
            `${Math.min(进度, 定义.目标)}/${定义.目标}`,
          ),
          文字偏移,
        ),
      );
    });
    图形.restore();
    // 文字在图形平移之外绘制，仍保留列表屏幕裁剪。
    // 文字在裁剪/平移之外统一绘制（文字渲染不受图形变换影响，也避免裁剪写入器路径）。
    for (const 项 of 暂存文字) {
      if (项.y < 可视.上 - 24 || 项.y > 可视.上 + 可视.高 + 24) continue;
      画笔.绘制文字(项);
    }
    画笔.弹出裁剪();
    this.绘制返回按钮(图形, 画笔, 英文);
  }

  private 绘制返回按钮(图形: 图形对象, 画笔: 画笔, 英文: boolean): void {
    const 矩形 = 计算成就页布局(this.逻辑宽, this.逻辑高).返回;
    绘制覆盖页按钮(图形, 矩形.左 + 矩形.宽 / 2, 矩形.上 + 矩形.高 / 2, 矩形.宽, 矩形.高);
    画笔.绘制文字({
      文案: 英文 ? "Back" : "返回主菜单",
      样式: 读取覆盖页按钮文字样式(false, 15),
      锚点: "中中",
      x: 矩形.左 + 矩形.宽 / 2,
      y: 矩形.上 + 矩形.高 / 2,
    });
  }

  private 已得(): number {
    return this.上下文.服务.成就.读取已解锁().length;
  }

  protected 读取文字快照(): readonly string[] {
    const 已解锁 = new Set(this.上下文.服务.成就.读取已解锁());
    return [
      `滚动:${this.滚动?.读取滚动位置() ?? 0}`,
      `解锁:${已解锁.size}`,
      `已领取:${this.上下文.服务.金币.读取().已领成就.length}`,
      ...成就定义.map((定义) => {
        const 状态 = 已解锁.has(定义.编号) ? "已解锁" : "未解锁";
        const 进度 = Math.min(this.上下文.服务.成就.读取进度(定义.编号), 定义.目标);
        return `${定义.名称}:${状态}:${进度}/${定义.目标}`;
      }),
    ];
  }
}

function 生成页面文字项(
  锚点: 文字项["锚点"],
  x: number,
  y: number,
  字号: number,
  颜色: number,
  字重: "常规" | "粗体",
  对齐: "左" | "中" | "右",
  文案: string,
  最大宽?: number,
): 文字项 {
  return {
    文案,
    样式: 派生覆盖页文字样式({ 字号, 颜色, 字重, 对齐 }),
    锚点,
    x,
    y,
    最大宽,
  };
}

function 移位(项: 文字项, 偏移: { x: number; y: number }): 文字项 {
  return { ...项, x: 项.x + 偏移.x, y: 项.y + 偏移.y };
}

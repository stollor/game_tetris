import { 绘制图标 } from "../../../框架Three/界面/控件/图标";
import { 绘制圆角矩形, 绘制面板 } from "../../../框架Three/界面/控件/工具";
import { 文本行 } from "../../../框架Three/界面/控件/文本行";
import type { 滚动容器 } from "../../../框架Three/界面/控件/滚动容器";
import type { 控件接口, 矩形, 绘制环境 } from "../../../框架Three/界面/控件/类型";
import { 进度条 } from "../../../框架Three/界面/控件/进度条";
import { 成就定义 } from "../../成就/再消一行成就";
import type { 页面上下文 } from "../接口/上下文";
import { 创建滚动区域, 页面基类 } from "./页面工具";

/**
 * 成就页：全部成就的列表、进度与解锁态；进入时把已解锁但未领取的成就奖励
 * 自动折成金币（与 Phaser 版一致），领取结果用 Toast 提示。
 */

const 行高 = 104;
const 顶栏高 = 64;

export class 成就界面 extends 页面基类 {
  private 滚动: 滚动容器 | null = null;

  constructor(上下文: 页面上下文) {
    super(上下文, { 名称: "成就", 独占: true });
  }

  进入(): void {
    super.进入();
    // 成就解锁/金币变化后刷新进度与奖励按钮；调试桥加币也能看到。
    this.上下文.登记清理(this.上下文.服务.成就.订阅(() => this.重建()));
    this.上下文.登记清理(this.上下文.服务.金币.订阅(() => this.重建()));
    this.自动领取();
  }

  protected 构建(): void {
    const 英文 = this.上下文.服务.语言.是否英文();
    const 已解锁 = new Set(this.上下文.服务.成就.读取已解锁());
    const 内容高 = 16 + 成就定义.length * 行高 + 16;
    // 顶栏下单独一行金币，避免与第一条成就行重叠。
    const 列表顶 = 顶栏高 + 30;
    this.滚动 = 创建滚动区域(this.控件层, {
      矩形: { 左: 0, 上: 列表顶, 宽: this.逻辑宽, 高: this.逻辑高 - 列表顶 },
      内容高,
      显示滚动条: true,
      惯性: true,
    });
    成就定义.forEach((定义, 序号) => {
      const 进度 = this.上下文.服务.成就.读取进度(定义.编号);
      this.滚动?.添加(this.创建成就行(定义.编号, 已解锁.has(定义.编号), 进度, 序号));
    });
    this.添加控件(
      new 文本行({
        矩形: { 左: 16, 上: 顶栏高 + 2, 宽: 220, 高: 26 },
        文本: `${英文 ? "COINS" : "方块币"} ${this.上下文.服务.金币.读取().金币}`,
        字号档: "小",
        对齐: "左",
        颜色: this.环境.配色.警告,
      }),
    );
    this.创建奖励按钮(英文);
    this.添加返回按钮(英文 ? "Back" : "返回主菜单");
  }

  protected 绘制内容(环境: 绘制环境): void {
    const 英文 = this.上下文.服务.语言.是否英文();
    const 已解锁 = this.上下文.服务.成就.读取已解锁().length;
    this.绘制顶栏(环境, `${英文 ? "ACHIEVEMENTS" : "成就收藏"}  ${已解锁} / ${成就定义.length}`);
  }

  protected 读取文字快照(): readonly string[] {
    const 已解锁 = new Set(this.上下文.服务.成就.读取已解锁());
    return 成就定义.map((定义) => {
      const 状态 = 已解锁.has(定义.编号) ? "已解锁" : "未解锁";
      const 进度 = Math.min(this.上下文.服务.成就.读取进度(定义.编号), 定义.目标);
      return `${定义.名称}:${状态}:${进度}/${定义.目标}`;
    });
  }

  /** 自动领取已解锁成就的金币，避免玩家漏领（对应 Phaser 版 同步成就金币）。 */
  private 自动领取(): void {
    const 已解锁 = this.上下文.服务.成就.读取已解锁();
    if (已解锁.length === 0) return;
    const 结果 = this.上下文.服务.金币.领取成就(已解锁);
    if (结果.新增 <= 0) return;
    this.显示提示(
      this.上下文.服务.语言.是否英文()
        ? `Achievement rewards +${结果.新增}`
        : `成就奖励 +${结果.新增} 方块币`,
    );
  }

  private 创建奖励按钮(英文: boolean): void {
    const 已领 = new Set(this.上下文.服务.金币.读取().已领成就);
    const 未领取 = this.上下文.服务.成就.读取已解锁().filter((编号) => !已领.has(编号));
    const 文案 = 英文
      ? "Claim"
      : 未领取.length > 0
        ? `领取 ${未领取.length}`
        : 已领.size > 0
          ? "已领取"
          : "领取奖励";
    this.创建按钮("领取奖励", {
      矩形: { 左: 150, 上: 15, 宽: 110, 高: 34 },
      文案,
      字号档: "小",
      变体: "次要",
      圆角: 8,
      禁用: 未领取.length === 0,
      点击: () => {
        const 结果 = this.上下文.服务.金币.领取成就(this.上下文.服务.成就.读取已解锁());
        this.显示提示(结果.原因);
        this.重建();
      },
    });
  }

  private 创建成就行(编号: string, 已解锁: boolean, 进度: number, 序号: number): 控件接口 {
    const 定义 = 成就定义.find((项) => 项.编号 === 编号);
    if (!定义) throw new Error(`未知成就：${编号}`);
    const 英文 = this.上下文.服务.语言.是否英文();
    const 上 = 16 + 序号 * 行高;
    const 行矩形: 矩形 = { 左: 12, 上, 宽: this.逻辑宽 - 24, 高: 行高 - 8 };
    const 控件列表: 控件接口[] = [
      new 行底板(行矩形),
      new 成就图标(已解锁, 行矩形),
      new 文本行({
        矩形: { 左: 行矩形.左 + 40, 上: 行矩形.上 + 8, 宽: 行矩形.宽 - 150, 高: 24 },
        文本: `${已解锁 ? "✓" : "◇"}  ${英文 ? 定义.英文 : 定义.名称}`,
        字号档: "小",
        对齐: "左",
        颜色: 已解锁 ? this.环境.配色.强调 : this.环境.配色.主字,
      }),
      new 文本行({
        矩形: { 左: 行矩形.左 + 40, 上: 行矩形.上 + 34, 宽: 行矩形.宽 - 60, 高: 36 },
        文本: 英文 ? 定义.英文说明 : 定义.说明,
        字号档: "小",
        对齐: "左",
        最大行数: 2,
        颜色: this.环境.配色.次字,
      }),
      new 文本行({
        矩形: { 左: 行矩形.左 + 行矩形.宽 - 104, 上: 行矩形.上 + 8, 宽: 90, 高: 22 },
        文本: `${Math.min(进度, 定义.目标)}/${定义.目标}`,
        字号档: "小",
        对齐: "右",
        颜色: this.环境.配色.次字,
      }),
      new 进度条({
        矩形: { 左: 行矩形.左 + 12, 上: 行矩形.上 + 行矩形.高 - 16, 宽: 行矩形.宽 - 24, 高: 5 },
        进度: Math.min(1, 进度 / 定义.目标),
        颜色: 已解锁 ? this.环境.配色.强调 : this.环境.配色.描边,
      }),
    ];
    return new 组合控件(控件列表, 行矩形);
  }
}

/** 行底板：只画不交互。 */
class 行底板 implements 控件接口 {
  private readonly 矩形值: 矩形;
  constructor(矩形: 矩形) {
    this.矩形值 = 矩形;
  }
  读取矩形(): 矩形 {
    return this.矩形值;
  }
  命中(): null {
    return null;
  }
  绘制(环境: 绘制环境): void {
    绘制面板(环境, this.矩形值, { 圆角: 12, 填充透明度: 0.72, 描边宽: 1 });
  }
}

/** 左侧状态图标：解锁后画对勾。 */
class 成就图标 implements 控件接口 {
  private readonly 解锁: boolean;
  private readonly 行矩形: 矩形;
  constructor(解锁: boolean, 行矩形: 矩形) {
    this.解锁 = 解锁;
    this.行矩形 = 行矩形;
  }
  读取矩形(): 矩形 {
    return this.行矩形;
  }
  命中(): null {
    return null;
  }
  绘制(环境: 绘制环境): void {
    const 方块: 矩形 = {
      左: this.行矩形.左 + 10,
      上: this.行矩形.上 + 10,
      宽: 22,
      高: 22,
    };
    绘制圆角矩形(环境, 方块, this.解锁 ? 环境.配色.强调 : 环境.配色.描边, 6, 0.35);
    绘制图标(
      环境,
      this.解锁 ? "对勾" : "锁",
      { 左: 方块.左 + 3, 上: 方块.上 + 3, 宽: 16, 高: 16 },
      this.解锁 ? 环境.配色.强调字 : 环境.配色.次字,
    );
  }
}

/** 把多个只读绘制控件打包成一个控件（滚动容器只接受单个控件）。 */
class 组合控件 implements 控件接口 {
  private readonly 控件列表: 控件接口[];
  private readonly 矩形值: 矩形;
  constructor(控件列表: 控件接口[], 矩形: 矩形) {
    this.控件列表 = 控件列表;
    this.矩形值 = 矩形;
  }
  读取矩形(): 矩形 {
    return this.矩形值;
  }
  命中(): null {
    return null;
  }
  绘制(环境: 绘制环境): void {
    for (const 控件 of this.控件列表) 控件.绘制(环境);
  }
}

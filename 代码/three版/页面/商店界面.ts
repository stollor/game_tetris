  private 绘制浮层(
    图形: 图形对象,
    画笔: 画笔,
    英文: boolean,
    存档: { 金币: number; 已购: readonly string[] },
  ): void {
    const 玻璃 = this.商店布局.浮层.玻璃;
    绘制霓虹玻璃(图形, 玻璃.左, 玻璃.上, 玻璃.宽, 玻璃.高, {
      透明度: 0.34,
      圆角: 16,
    });
    this.部位卡矩形().forEach((矩形, 序号) => {
      const 部位 = 外观部位列表[序号];
      if (!部位) return;
      const 已有 = 存档.已购.some((项) => 项 === `${this.地点.名称}.${部位}`);
      const 预览中 = this.选中部位 === 部位;
      // 与 Phaser 同层序：风景缩略是后加到容器的图片（盖在底板之上），
      // 其余部位图标画在底板之前的图形层（会透过 0.42 的底板被压暗）。
      if (部位 === "静态背景" || 部位 === "动态背景") {
        绘制商店部位底板Phaser合成(图形, 矩形, 预览中, 已有, false, 商店像素对齐描边);
        this.绘制部位图标(图形, 矩形, 部位);
      } else {
        this.绘制部位图标(图形, 矩形, 部位);
        绘制商店部位底板Phaser合成(图形, 矩形, 预览中, 已有, false, 商店像素对齐描边);
      }
      const 标价 = 已有 ? (英文 ? "Owned" : "已有") : `▣ ${计算报价(this.地点, 部位, 存档.已购)}`;
      const [名称项, 价格项] = 生成商店部位文字项(矩形, 部位短名[部位], 标价);
      if (名称项) 画笔.绘制文字(应用商店文字补偿(名称项, "部位名称"));
      if (价格项) 画笔.绘制文字(应用商店文字补偿(价格项, "部位价格"));
    });
    // 购买 / 整套：文案与按钮状态以 Phaser 商店为准（金币不足不把整套画成禁用暗色）。
    const 单件价 = 计算报价(this.地点, this.选中部位, 存档.已购);
    const 整套价 = 计算报价(this.地点, "整套", 存档.已购);
    const 按钮 = 读取商店购买按钮(部位短名[this.选中部位], 单件价, 整套价, 英文);
    const 矩形 = this.购买按钮矩形();
    this.绘制收藏按钮(图形, 画笔, 矩形.单件, () => 按钮.单件);
    this.绘制收藏按钮(图形, 画笔, 矩形.整套, () => 按钮.整套);
  }


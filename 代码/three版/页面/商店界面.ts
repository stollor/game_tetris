  private readonly 矩形值: 矩形;
  private readonly 地点: 地点皮肤;
  private readonly 选中: boolean;
  constructor(矩形: 矩形, 地点: 地点皮肤, 选中: boolean) {
    this.矩形值 = 矩形;
    this.地点 = 地点;
    this.选中 = 选中;
  }
  读取矩形(): 矩形 {
    return this.矩形值;
  }
  命中(): null {
    return null;
  }

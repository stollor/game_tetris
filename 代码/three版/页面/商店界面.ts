  private 绘制目录(图形: 图形对象, 画笔: 画笔, 存档: { 已购: readonly string[] }): void {
    const 列表矩形 = this.目录矩形();
    const 卡宽 = this.商店布局.目录卡宽;
    const 卡高 = this.商店布局.目录卡高;
    const 间 = 8;
    const 偏移 = this.目录?.读取滚动位置() ?? 0;
    画笔.压入裁剪(列表矩形);
    图形.save();
    图形.translateCanvas(列表矩形.左 - 偏移, 列表矩形.上);
    地点皮肤表.forEach((地点, 序号) => {
      const 卡左 = 序号 * (卡宽 + 间);
      if (卡左 + 卡宽 < 偏移 - 卡宽 || 卡左 > 偏移 + 列表矩形.宽 + 卡宽) return;
      const 选中 = this.地点.名称 === 地点.名称;
      const 卡: 矩形 = { 左: 列表矩形.左 + 卡左 - 偏移, 上: 列表矩形.上, 宽: 卡宽, 高: 卡高 };
      绘制商店目录底板Phaser合成(
        图形,
        { 左: 卡左, 上: 0, 宽: 卡宽, 高: 卡高 },
        选中,
        false,
        商店像素对齐描边,
      );
      图形.save();
      图形.translateCanvas(卡左 + 4, 4);
      绘制背景(图形, {
        宽: 卡宽 - 8,
        高: 卡高 - 22,
        主题: 地点.名称,
        动态: false,
        时间秒: 0,
      });
      图形.restore();
      画笔.绘制文字(应用商店文字补偿(生成商店目录名称文字项(卡, 地点.名称), "目录名称"));
      const 已有 = 存档.已购.filter((项) => 项.startsWith(`${地点.名称}.`)).length;
      if (已有) {
        const 角标 = 生成商店目录角标文字项(卡, 已有);
        const 尺寸 = 画笔.测量文字(角标.文案, 角标.样式);
        图形.fillStyle(颜色值(商店目录角标底色), 0.96).fillRect(角标.x, 角标.y, 尺寸.宽, 尺寸.高);
        画笔.绘制文字(角标);
      }
    });
    图形.restore();
    画笔.弹出裁剪();
  }


  private 绘制方块陈列(图形: 图形对象, 画笔: 画笔): void {
    const { 列, 列距, 行距, 格, 槽宽, 槽高, 块宽, 块高, 左, 顶 } = 计算商店方块陈列(
      this.逻辑宽,
      this.逻辑高,
      this.商店布局.坞高,
    );
    const 面板区: 矩形 = { 左: 左 - 12, 上: 顶 - 12, 宽: 块宽 + 24, 高: 块高 + 24 };
    绘制外落边(图形, 面板区, 颜色值(this.地点.面板), 0.96);
    图形
      .fillStyle(颜色值(this.地点.面板), 0.96)
      .fillRoundedRect(面板区.左, 面板区.上, 面板区.宽, 面板区.高, 14);
    商店像素对齐描边.圆角(图形, 面板区, 14, 1, this.地点.强调, 0.6);
    // 与 Phaser 一致：先铺全部方块辉光，再画方块本体（辉光在下、本体在上）。
    const 外观表 = 七种方块.map((类型) => ({
      方案: 解析方块外观(this.地点.名称),
      格子: 格,
      色值: this.地点.方块[七种方块.indexOf(类型)] ?? this.地点.主色,
    }));
    const 坐标表 = 七种方块.map((类型, i) => {
      const 格点 = 预览格子(类型);
      const 最小X = Math.min(...格点.map((点) => 点[0]));
      const 最大X = Math.max(...格点.map((点) => 点[0]));
      const 最小Y = Math.min(...格点.map((点) => 点[1]));
      const 最大Y = Math.max(...格点.map((点) => 点[1]));
      const 件宽 = (最大X - 最小X + 1) * 格;
      const 件高 = (最大Y - 最小Y + 1) * 格;
      const ox = 左 + (i % 列) * (槽宽 + 列距) + (槽宽 - 件宽) / 2;
      const oy = 顶 + Math.floor(i / 列) * (槽高 + 行距) + (槽高 - 件高) / 2;
      return 格点.map(([gx, gy]) => [ox + (gx - 最小X) * 格, oy + (gy - 最小Y) * 格] as const);
    });
    坐标表.forEach((格坐标表, i) => {
      const 外观 = 外观表[i];
      if (!外观) return;
      for (const [x, y] of 格坐标表) 绘制方块辉光(图形, x, y, 外观);
    });
    坐标表.forEach((格坐标表, i) => {
      const 外观 = 外观表[i];
      if (!外观) return;
      for (const [x, y] of 格坐标表) 绘制方块单元(图形, x, y, 外观);
    });
    void 画笔;
  }


/**
 * 商店 / 旅行收藏：金币、12 套地点皮肤按部位购买、动态背景抵扣、整套折扣补齐、
 * 购买后穿戴、试听音乐。所有交易走 服务.金币，穿戴走 服务.设置，写入即持久化。
 */

const 部位短名: Record<外观部位, string> = {
  静态背景: "静态背景",
  动态背景: "动态背景",
  界面样式: "界面样式",
  方块外观: "方块外观",
  音效套装: "音效套装",
  音乐: "音乐",
};

const 部位说明: Record<外观部位, string> = {
  静态背景: "一张静态风景底图",
  动态背景: "静态底图 + 动态光效",
  界面样式: "面板、按钮与文字配色",
  方块外观: "棋盘与预览的方块质感",
  音效套装: "落块、消行与四行音效",
  音乐: "菜单与对局的背景音乐",
};

const 部位说明英文: Record<外观部位, string> = {
  静态背景: "Static scenery backdrop",
  动态背景: "Static backdrop + motion",
  界面样式: "Panels, buttons and text colors",
  方块外观: "Block style for board and previews",
  音效套装: "Lock, clear and quad sounds",
  音乐: "Menu and game background music",
};

export class 商店界面 extends 页面基类 {
  private 地点: 地点皮肤 = 地点皮肤表[0] ?? 抛出缺少地点();
  private 选中部位: 外观部位 = "方块外观";
  private 目录: 滚动容器 | null = null;
  private 弹层: 模态弹层 | null = null;

  constructor(上下文: 页面上下文) {
    super(上下文, { 名称: "商店", 独占: true });
  }

  进入(): void {
    super.进入();
    // 余额/收藏变化（含调试桥加币）时刷新报价与按钮可用态。
    this.上下文.登记清理(this.上下文.服务.金币.订阅(() => this.重建()));
    this.试听();
  }

  退出(): void {
    this.关闭确认();
    this.上下文.服务.音频.停止音乐();
    super.退出();
  }

  更新(秒: number): void {
    super.更新(秒);
    this.弹层?.更新(秒);
  }

  渲染(): void {
    super.渲染();
    this.弹层?.绘制(this.环境);
  }

  protected 构建(): void {
    const 英文 = this.上下文.服务.语言.是否英文();
    const 存档 = this.上下文.服务.金币.读取();
    // 部位卡与目录卡的透明点击层。
    const 部位卡矩形 = this.部位卡矩形();
    外观部位列表.forEach((部位, 序号) => {
      const 矩形 = 部位卡矩形[序号] ?? 部位卡矩形[0];
      if (!矩形) return;
      this.添加控件(new 部位卡控件(矩形, 部位, this.选中部位 === 部位, this.部位状态(部位)));
      this.创建按钮("", {
        矩形,
        变体: "文字",
        点击: () => this.选择部位(部位),
      });
    });
    // 购买 / 整套。
    const 单件 = 计算报价(this.地点, this.选中部位, 存档.已购);
    const 单件拥有 = 单件 === 0;
    const 整套价 = 计算报价(this.地点, "整套", 存档.已购);
    const 整套拥有 = 整套已拥有(存档.已购, this.地点);
    this.创建按钮(
      单件拥有
        ? `穿戴:${this.地点.名称}.${this.选中部位}`
        : `购买:${this.地点.名称}.${this.选中部位}`,
      {
        矩形: { 左: 12, 上: 438, 宽: 178, 高: 46 },
        文案: 单件拥有 ? (英文 ? "Wear" : "穿戴") : `${英文 ? "Buy" : "购买"} ▣ ${单件}`,
        字号档: "小",
        变体: "主要",
        圆角: 10,
        禁用: !单件拥有 && 存档.金币 < 单件,
        点击: () => this.打开确认(this.选中部位),
      },
    );
    this.创建按钮(整套拥有 ? `穿戴:${this.地点.名称}.整套` : `购买:${this.地点.名称}.整套`, {
      矩形: { 左: 200, 上: 438, 宽: 178, 高: 46 },
      文案: 整套拥有 ? (英文 ? "Wear set" : "穿上整套") : `整套 ▣ ${整套价}`,
      字号档: "小",
      变体: "次要",
      圆角: 10,
      禁用: !整套拥有 && 存档.金币 < 整套价,
      点击: () => this.打开确认("整套"),
    });
    this.创建按钮(`试听:${this.地点.名称}`, {
      矩形: { 左: 12, 上: 496, 宽: 110, 高: 34 },
      文案: 英文 ? "Preview" : "试听音乐",
      图标: "音乐",
      图标尺寸: 18,
      字号档: "小",
      变体: "普通",
      圆角: 9,
      点击: () => this.试听(true),
    });
    this.添加返回按钮(英文 ? "Back" : "返回主菜单");
    this.构建目录();
  }

  protected 绘制内容(环境: 绘制环境): void {
    const 英文 = this.上下文.服务.语言.是否英文();
    this.绘制顶栏(环境, 英文 ? "SHOP · TRAVEL" : "商店 · 旅行收藏");
    const 存档 = this.上下文.服务.金币.读取();
    // 金币。
    绘制圆角矩形(环境, { 左: 12, 上: 70, 宽: 132, 高: 30 }, 环境.配色.浮层, 15, 0.9);
    绘制图标(环境, "金币", { 左: 18, 上: 75, 宽: 20, 高: 20 }, 0xf4cd75);
    绘制单行文字(
      环境,
      { 左: 44, 上: 70, 宽: 96, 高: 30 },
      String(存档.金币),
      "中",
      环境.配色.警告,
      "左",
    );
    // 主视觉。
    const 主视觉: 矩形 = { 左: 12, 上: 108, 宽: this.逻辑宽 - 24, 高: 172 };
    绘制旅行缩略(环境, 主视觉, this.地点.名称);
    绘制圆角矩形(
      环境,
      { 左: 主视觉.左, 上: 主视觉.上 + 主视觉.高 - 62, 宽: 主视觉.宽, 高: 62 },
      环境.配色.底色,
      0,
      0.62,
    );
    绘制单行文字(
      环境,
      { 左: 主视觉.左 + 14, 上: 主视觉.上 + 主视觉.高 - 58, 宽: 主视觉.宽 - 130, 高: 30 },
      英文 ? this.地点.英文 : this.地点.名称,
      "中",
      环境.配色.主字,
      "左",
    );
    绘制单行文字(
      环境,
      { 左: 主视觉.左 + 14, 上: 主视觉.上 + 主视觉.高 - 30, 宽: 主视觉.宽 - 130, 高: 22 },
      this.地点.副题,
      "小",
      环境.配色.次字,
      "左",
    );
    const 已购 = 已购数量(存档.已购, this.地点);
    绘制单行文字(
      环境,
      { 左: 主视觉.左 + 主视觉.宽 - 108, 上: 主视觉.上 + 主视觉.高 - 40, 宽: 94, 高: 24 },
      `${已购} / ${外观部位列表.length}`,
      "小",
      环境.配色.强调,
      "右",
    );
    // 部位标题与购买区提示。
    绘制单行文字(
      环境,
      { 左: 14, 上: 290, 宽: 200, 高: 22 },
      英文 ? "Set parts" : "套装部件",
      "小",
      环境.配色.次字,
      "左",
    );
    const 单件价 = 计算报价(this.地点, this.选中部位, 存档.已购);
    绘制单行文字(
      环境,
      { 左: 130, 上: 496, 宽: 248, 高: 34 },
      单件价 === 0
        ? 英文
          ? "Owned — wear it"
          : "已拥有，可直接穿戴"
        : 英文
          ? 部位说明英文[this.选中部位]
          : 部位说明[this.选中部位],
      "小",
      环境.配色.弱字,
      "左",
    );
  }

  读取界面(): 界面快照 {
    const 基础 = super.读取界面();
    if (!this.弹层) return 基础;
    // 弹层按钮也进快照：验收脚本固定点「购买」→「确认交易」→「穿戴」→「确认交易」。
    const 弹层按钮 = this.弹层.层
      .读取控件列表()
      .filter((控件): 控件 is 按钮 => 控件 instanceof 按钮)
      .filter((控件) => 控件.读取文案() !== "")
      .map((控件) => {
        const 矩形 = 控件.读取矩形();
        return {
          名称: 控件.读取文案().startsWith("取消") ? "取消交易" : "确认交易",
          左: 矩形.左,
          上: 矩形.上,
          宽: 矩形.宽,
          高: 矩形.高,
          可用: !控件.读取禁用(),
        };
      });
    return { 按钮: [...基础.按钮, ...弹层按钮], 文字: 基础.文字 };
  }

  protected 读取文字快照(): readonly string[] {
    const 存档 = this.上下文.服务.金币.读取();
    const 单件 = 计算报价(this.地点, this.选中部位, 存档.已购);
    return [
      `金币:${存档.金币}`,
      `地点:${this.地点.名称}`,
      `部位:${this.选中部位}`,
      `单件价:${单件}`,
      `整套价:${计算报价(this.地点, "整套", 存档.已购)}`,
    ];
  }

  private 构建目录(): void {
    const 卡片宽 = 92;
    const 间距 = 8;
    const 滚动矩形: 矩形 = { 左: 0, 上: 540, 宽: this.逻辑宽, 高: 200 };
    const 上次位置 = this.目录?.读取滚动位置() ?? 0;
    const 目录 = 创建滚动区域(this.控件层, {
      矩形: 滚动矩形,
      内容高: 滚动矩形.高,
      内容宽: 地点皮肤表.length * (卡片宽 + 间距) + 12,
      方向: "水平",
      显示滚动条: true,
      惯性: true,
    });
    this.目录 = 目录;
    目录.设置滚动位置(上次位置);
    地点皮肤表.forEach((地点, 序号) => {
      const 卡矩形: 矩形 = {
        左: 6 + 序号 * (卡片宽 + 间距),
        上: 6,
        宽: 卡片宽,
        高: 滚动矩形.高 - 14,
      };
      目录.添加(new 目录卡控件(卡矩形, 地点, this.地点.名称 === 地点.名称));
      目录.添加(
        new 按钮({
          矩形: 卡矩形,
          变体: "文字",
          点击: () => this.选择地点(地点),
        }),
      );
    });
  }

  private 部位卡矩形(): 矩形[] {
    const 宽 = (this.逻辑宽 - 24 - 16) / 3;
    return 外观部位列表.map((_, 序号) => {
      const 列 = 序号 % 3;
      const 行 = Math.floor(序号 / 3);
      return {
        左: 12 + 列 * (宽 + 8),
        上: 314 + 行 * 58,
        宽,
        高: 52,
      };
    });
  }

  private 部位状态(部位: 外观部位): string {
    const 存档 = this.上下文.服务.金币.读取();
    const 价格 = 计算报价(this.地点, 部位, 存档.已购);
    if (价格 === 0) return this.上下文.服务.语言.是否英文() ? "Owned" : "已有";
    return `▣ ${价格}`;
  }

  private 选择部位(部位: 外观部位): void {
    this.选中部位 = 部位;
    if (部位 === "音乐") this.试听();
    if (部位 === "音效套装") this.上下文.服务.音频.播放音效(`旅行.${this.地点.名称}.消行`);
    this.重建();
  }

  private 选择地点(地点: 地点皮肤): void {
    this.地点 = 地点;
    this.试听();
    this.重建();
  }

  private 试听(提示 = false): void {
    this.上下文.服务.音频.播放音乐(`旅行.${this.地点.名称}`);
    if (提示)
      this.显示提示(
        this.上下文.服务.语言.是否英文()
          ? `Playing ${this.地点.名称}`
          : `正在播放 · ${this.地点.名称}`,
      );
  }

  private 打开确认(部位: 外观部位 | "整套"): void {
    this.关闭确认();
    const 英文 = this.上下文.服务.语言.是否英文();
    const 存档 = this.上下文.服务.金币.读取();
    const 价格 = 计算报价(this.地点, 部位, 存档.已购);
    const 拥有 = 价格 === 0;
    const 弹层 = new 模态弹层({
      逻辑尺寸: { 宽: this.逻辑宽, 高: this.逻辑高 },
      标题: `${this.地点.名称} · ${部位}`,
      面板高: 330,
      关闭: () => this.关闭确认(),
      绘制内容: (环境, 内容矩形) => {
        绘制文本行(
          环境,
          内容矩形,
          拥有
            ? 英文
              ? "This item is already in your collection."
              : "这件收藏已在你的旅行箱里。"
            : 英文
              ? "Purchased permanently for this browser."
              : "购买后永久保留在当前浏览器的收藏中。",
          { 字号档: "小", 颜色: 环境.配色.次字, 最大行数: 2 },
        );
        绘制单行文字(
          环境,
          { 左: 内容矩形.左, 上: 内容矩形.上 + 56, 宽: 内容矩形.宽, 高: 30 },
          拥有 ? (英文 ? "Owned" : "已拥有") : `▣ ${价格}`,
          "中",
          环境.配色.强调,
          "左",
        );
        绘制单行文字(
          环境,
          { 左: 内容矩形.左, 上: 内容矩形.上 + 92, 宽: 内容矩形.宽, 高: 24 },
          `${英文 ? "Balance" : "余额"} ▣ ${存档.金币}${拥有 ? "" : ` · ${英文 ? "after" : "购买后"} ▣ ${Math.max(0, 存档.金币 - 价格)}`}`,
          "小",
          环境.配色.次字,
          "左",
        );
        绘制文本行(
          环境,
          { 左: 内容矩形.左, 上: 内容矩形.上 + 124, 宽: 内容矩形.宽, 高: 40 },
          拥有
            ? 英文
              ? "Wearing only changes visuals, never scoring."
              : "穿戴只改变外观，不影响得分或玩法。"
            : 存档.金币 < 价格
              ? 英文
                ? `Need ${价格 - 存档.金币} more coins.`
                : `还差 ${价格 - 存档.金币} 方块币，继续对局与成就即可获得。`
              : 英文
                ? "Confirm to spend coins, then wear it any time."
                : "确认后扣除方块币；购买完成后可随时穿戴。",
          { 字号档: "小", 颜色: 环境.配色.弱字, 最大行数: 2 },
        );
      },
      按钮: [
        {
          文案: 拥有 ? (英文 ? "Wear" : "穿戴") : 英文 ? "Confirm" : "确认购买",
          主要: true,
          禁用: !拥有 && 存档.金币 < 价格,
          点击: () => this.确认交易(部位, 价格, 拥有),
        },
        { 文案: 英文 ? "Cancel" : "取消", 点击: () => this.关闭确认() },
      ],
    });
    this.弹层 = 弹层;
    弹层.绑定(this.上下文.资源.命中);
    this.请求重绘();
  }

  private 确认交易(部位: 外观部位 | "整套", _价格: number, 拥有: boolean): void {
    const 英文 = this.上下文.服务.语言.是否英文();
    if (拥有) {
      this.穿戴(部位);
      this.显示提示(英文 ? "Worn" : "已穿戴，旅行从此刻开始");
      this.关闭确认();
      this.重建();
      return;
    }
    const 结果 = this.上下文.服务.金币.购买(this.地点.名称, 部位);
    this.显示提示(结果.原因);
    if (结果.成功) {
      this.上下文.服务.音频.播放音效("再消一行.全清");
      this.关闭确认();
      this.重建();
      return;
    }
  }

  private 穿戴(部位: 外观部位 | "整套"): void {
    const 名称 = this.地点.名称;
    const 部位表: readonly 外观部位[] = 部位 === "整套" ? 外观部位列表 : [部位];
    const 变化: Partial<游戏设置> = {};
    for (const 项 of 部位表) {
      if (项 === "静态背景" || 项 === "动态背景") {
        变化.背景主题 = 名称;
        变化.背景动态 = 项 === "动态背景";
      }
      if (项 === "界面样式") {
        变化.旅行样式 = 名称;
        变化.样式 = "夜空鎏金";
      }
      if (项 === "方块外观") 变化.方块外观 = 名称;
      if (项 === "音效套装") 变化.旅行音效 = 名称;
      if (项 === "音乐") 变化.旅行音乐 = 名称;
    }
    this.上下文.服务.设置.更新(变化);
  }

  private 关闭确认(): void {
    this.弹层?.销毁();
    this.弹层 = null;
    this.请求重绘();
  }
}

function 抛出缺少地点(): never {
  throw new Error("旅行地点表为空");
}

/** 部位卡：名字 + 拥有/价格，选中态用强调描边。 */
class 部位卡控件 implements 控件接口 {
  private readonly 矩形值: 矩形;
  private readonly 部位: 外观部位;
  private readonly 选中: boolean;
  private readonly 状态: string;
  constructor(矩形: 矩形, 部位: 外观部位, 选中: boolean, 状态: string) {
    this.矩形值 = 矩形;
    this.部位 = 部位;
    this.选中 = 选中;
    this.状态 = 状态;
  }
  读取矩形(): 矩形 {
    return this.矩形值;
  }
  命中(): null {
    return null;
  }
  绘制(环境: 绘制环境): void {
    绘制圆角矩形(环境, this.矩形值, 环境.配色.浮层, 9, this.选中 ? 1 : 0.75);
    if (this.选中) 绘制矩形描边(环境, this.矩形值, 环境.配色.强调, 1.5, 0.95);
    绘制单行文字(
      环境,
      { 左: this.矩形值.左 + 8, 上: this.矩形值.上 + 5, 宽: this.矩形值.宽 - 16, 高: 22 },
      部位短名[this.部位],
      "小",
      this.选中 ? 环境.配色.强调 : 环境.配色.主字,
      "左",
    );
    绘制单行文字(
      环境,
      { 左: this.矩形值.左 + 8, 上: this.矩形值.上 + 27, 宽: this.矩形值.宽 - 16, 高: 20 },
      this.状态,
      "小",
      环境.配色.次字,
      "左",
    );
  }
}

/** 目录卡：地点缩略 + 名称 + 已购角标。 */

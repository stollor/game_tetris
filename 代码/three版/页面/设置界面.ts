/**
 * 设置页：音量/静音、语言、主题、方块外观、背景、省电、屏幕适配与操作选项。
 * 行用声明式结构生成，改设置后整页重建（与 Phaser 版一致），滚动位置保留。
 */

type 音量键 = "音乐音量" | "音效音量" | "背景音效音量" | "落点影透明度";

type 设置行 =
  | { 类型: "分组"; 标题: string }
  | { 类型: "音量"; 标题: string; 值: number; 键: 音量键 }
  | {
      类型: "选项";
      标题: string;
      选项: readonly string[];
      已选: number;
      变化: (序号: number) => void;
    }
  | { 类型: "开关"; 标题: string; 值: boolean; 变化: (值: boolean) => void };

const 顶栏高 = 64;

function 计算行高(行: 设置行): number {
  if (行.类型 === "分组") return 38;
  if (行.类型 === "音量") return 62;
  if (行.类型 === "开关") return 54;
  const 行数 = Math.ceil(行.选项.length / 4);
  return 34 + 行数 * 36;
}

export class 设置界面 extends 页面基类 {
  private 行列表: 设置行[] = [];
  private 滚动: 滚动容器 | null = null;
  private 滚动位置 = 0;

  constructor(上下文: 页面上下文) {
    super(上下文, { 名称: "设置", 独占: true });
  }

  protected 构建(): void {
    const 设置 = this.上下文.服务.设置.读取();
    const 英文 = this.上下文.服务.语言.是否英文();
    this.行列表 = this.生成行(设置, 英文);
    const 内容高 = this.行列表.reduce((合计, 行) => 合计 + 计算行高(行), 0) + 24;
    this.滚动 = 创建滚动区域(this.控件层, {
      矩形: { 左: 0, 上: 顶栏高, 宽: this.逻辑宽, 高: this.逻辑高 - 顶栏高 },
      内容高,
      显示滚动条: true,
      惯性: true,
    });
    this.滚动.设置滚动位置(this.滚动位置);
    this.填充行();
    this.添加返回按钮(英文 ? "Back" : "返回主菜单");
  }

  protected 绘制内容(环境: 绘制环境): void {
    this.绘制顶栏(环境, this.上下文.服务.语言.是否英文() ? "Settings" : "设置");
  }

  protected 读取文字快照(): readonly string[] {
    const 设置 = this.上下文.服务.设置.读取();
    return [
      `语言:${设置.语言}`,
      `样式:${设置.旅行样式 ?? 设置.样式}`,
      `方块:${设置.方块外观}`,
      `背景:${设置.背景主题}`,
      `省电:${设置.省电模式}`,
      `音乐:${设置.音乐音量}`,
      `音效:${设置.音效音量}`,
      `氛围:${设置.背景音效音量}`,
      `静音:${设置.音乐音量 === 0 && 设置.音效音量 === 0 ? "是" : "否"}`,
    ];
  }

  private 生成行(设置: 游戏设置, 英文: boolean): 设置行[] {
    const 已购 = this.上下文.服务.金币.读取().已购;
    const 语言 = this.上下文.服务.语言;
    const 更新 = (变化: Partial<游戏设置>) => {
      this.滚动位置 = this.滚动?.读取滚动位置() ?? this.滚动位置;
      this.上下文.服务.设置.更新(变化);
      this.重建();
    };
    const 中英 = (中: string, 英: string) => (英文 ? 英 : 中);
    const 已购样式 = 查找已购(已购, "界面样式");
    const 已购方块 = 查找已购(已购, "方块外观");
    const 已购背景 = 查找已购(已购, "静态背景");
    const 样式选项 = ["夜空鎏金", "暖纸古典", "青蓝未来", ...已购样式];
    const 当前样式 = 设置.旅行样式 ?? 设置.样式;
    const 方块选项 = [
      ...方块外观方案表.filter((项) => !查找地点(项.名称)).map((项) => 项.名称),
      ...已购方块,
    ];
    const 背景选项 = [
      ...背景主题选项.filter((项) => !查找地点(项.值) && 是基础背景(项.值)).map((项) => 项.标签),
      ...已购背景,
    ];
    const 静音 = 设置.音乐音量 === 0 && 设置.音效音量 === 0;
    const 上次音量 = { 音乐: 60, 音效: 80 };
    return [
      { 类型: "分组", 标题: 中英("常规", "General") },
      { 类型: "音量", 标题: 中英("音乐音量", "Music"), 值: 设置.音乐音量, 键: "音乐音量" },
      { 类型: "音量", 标题: 中英("音效音量", "Effects"), 值: 设置.音效音量, 键: "音效音量" },
      {
        类型: "音量",
        标题: 中英("背景氛围", "Ambience"),
        值: 设置.背景音效音量,
        键: "背景音效音量",
      },
      {
        类型: "开关",
        标题: 中英("静音", "Mute"),
        值: 静音,
        变化: (值) =>
          更新({
            音乐音量: 值 ? 0 : 上次音量.音乐,
            音效音量: 值 ? 0 : 上次音量.音效,
            背景音乐: !值,
          }),
      },
      {
        类型: "选项",
        标题: 中英("语言", "Language"),
        选项: [中英("跟随系统", "System"), "简体中文", "English"],
        已选: 设置.语言 === "English" ? 2 : 设置.语言 === "简体中文" ? 1 : 0,
        变化: (序号) => {
          const 值 = 序号 === 2 ? "English" : 序号 === 1 ? "简体中文" : "跟随系统";
          语言.设置(值);
          更新({ 语言: 值 });
        },
      },
      { 类型: "分组", 标题: 中英("外观", "Appearance") },
      {
        类型: "选项",
        标题: 中英("界面主题", "Theme"),
        选项: 样式选项,
        已选: Math.max(0, 样式选项.indexOf(当前样式)),
        变化: (序号) => {
          const 名称 = 样式选项[序号] ?? "夜空鎏金";
          if (查找地点(名称)) 更新({ 样式: "夜空鎏金", 旅行样式: 名称 as 地点名称 });
          else 更新({ 样式: 名称 as 游戏设置["样式"] });
        },
      },
      {
        类型: "选项",
        标题: 中英("方块外观", "Blocks"),
        选项: 方块选项,
        已选: Math.max(0, 方块选项.indexOf(设置.方块外观)),
        变化: (序号) => 更新({ 方块外观: (方块选项[序号] ?? "默认") as 游戏设置["方块外观"] }),
      },
      {
        类型: "选项",
        标题: 中英("背景主题", "Background"),
        选项: 背景选项,
        已选: Math.max(0, 背景选项.indexOf(设置.背景主题)),
        变化: (序号) => 更新({ 背景主题: (背景选项[序号] ?? "极光原野") as 游戏设置["背景主题"] }),
      },
      {
        类型: "开关",
        标题: 中英("动态背景", "Background motion"),
        值: 设置.背景动态,
        变化: (值) => 更新({ 背景动态: 值 }),
      },
      { 类型: "分组", 标题: 中英("性能与操作", "Performance") },
      {
        类型: "选项",
        标题: 中英("省电模式", "Power saving"),
        选项: [中英("自动", "Auto"), 中英("开", "On"), 中英("关", "Off")],
        已选: 设置.省电模式 === "开" ? 1 : 设置.省电模式 === "关" ? 2 : 0,
        变化: (序号) =>
          更新({
            省电模式: (序号 === 1 ? "开" : 序号 === 2 ? "关" : "自动") as 游戏设置["省电模式"],
          }),
      },
      {
        类型: "选项",
        标题: 中英("屏幕适配", "Screen fit"),
        选项: [中英("自动", "Auto"), 中英("手机竖屏", "Portrait"), 中英("电脑横屏", "Landscape")],
        已选: 设置.屏幕适配 === "手机竖屏" ? 1 : 设置.屏幕适配 === "电脑横屏" ? 2 : 0,
        变化: (序号) =>
          更新({
            屏幕适配: (序号 === 1
              ? "手机竖屏"
              : 序号 === 2
                ? "电脑横屏"
                : "自动") as 游戏设置["屏幕适配"],
          }),
      },
      {
        类型: "选项",
        标题: 中英("上键旋转", "Up key rotate"),
        选项: [中英("左转", "Left"), 中英("右转", "Right"), "180°"],
        已选: 设置.手机上键旋转 === "右转" ? 1 : 设置.手机上键旋转 === "180度" ? 2 : 0,
        变化: (序号) =>
          更新({
            手机上键旋转: (序号 === 1
              ? "右转"
              : 序号 === 2
                ? "180度"
                : "左转") as 游戏设置["手机上键旋转"],
          }),
      },
      {
        类型: "开关",
        标题: 中英("允许 180° 旋转", "Allow 180°"),
        值: 设置.旋转180,
        变化: (值) => 更新({ 旋转180: 值 }),
      },
      {
        类型: "开关",
        标题: 中英("显示网格", "Show grid"),
        值: 设置.显示网格,
        变化: (值) => 更新({ 显示网格: 值 }),
      },
      {
        类型: "开关",
        标题: 中英("显示按键说明", "Show key guide"),
        值: 设置.显示按键说明,
        变化: (值) => 更新({ 显示按键说明: 值 }),
      },
      {
        类型: "音量",
        标题: 中英("落点影透明度", "Ghost opacity"),
        值: 设置.落点影透明度,
        键: "落点影透明度",
      },
    ];
  }

  private 填充行(): void {
    const 容器 = this.滚动;
    if (!容器) return;
    let y = 10;
    for (const 行 of this.行列表) {
      const 高 = 计算行高(行);
      const 行矩形: 矩形 = { 左: 12, 上: y, 宽: this.逻辑宽 - 24, 高: 高 - 8 };
      if (行.类型 === "分组") {
        容器.添加(
          new 文本行({
            矩形: { 左: 20, 上: y + 4, 宽: this.逻辑宽 - 40, 高: 26 },
            文本: 行.标题,
            字号档: "小",
            对齐: "左",
            颜色: this.环境.配色.强调,
          }),
        );
        y += 高;
        continue;
      }
      容器.添加(new 行底板(行矩形));
      if (行.类型 === "音量") this.填充音量行(容器, 行矩形, 行);
      else if (行.类型 === "选项") this.填充选项行(容器, 行矩形, 行);
      else this.填充开关行(容器, 行矩形, 行);
      y += 高;
    }
  }

  private 填充音量行(容器: 滚动容器, 行矩形: 矩形, 行: Extract<设置行, { 类型: "音量" }>): void {
    容器.添加(
      new 文本行({
        矩形: { 左: 行矩形.左 + 14, 上: 行矩形.上 + 8, 宽: 118, 高: 30 },
        文本: 行.标题,
        字号档: "小",
        对齐: "左",
      }),
    );
    const 数值 = new 文本行({
      矩形: { 左: 行矩形.左 + 132, 上: 行矩形.上 + 8, 宽: 44, 高: 30 },
      文本: `${行.值}%`,
      字号档: "小",
      对齐: "右",
      颜色: this.环境.配色.强调,
    });
    容器.添加(数值);
    容器.添加(
      new 滑块({
        矩形: { 左: 行矩形.左 + 184, 上: 行矩形.上 + 8, 宽: 行矩形.宽 - 198, 高: 30 },
        值: 行.值,
        步进: 5,
        变化: (值) => {
          数值.设置文本(`${值}%`);
          this.滚动位置 = 容器.读取滚动位置();
          if (行.键 === "落点影透明度") this.上下文.服务.设置.更新({ 落点影透明度: 值 });
          else this.上下文.服务.设置.更新({ [行.键]: 值 } as Partial<游戏设置>);
        },
      }),
    );
  }

  private 填充选项行(容器: 滚动容器, 行矩形: 矩形, 行: Extract<设置行, { 类型: "选项" }>): void {
    容器.添加(
      new 文本行({
        矩形: { 左: 行矩形.左 + 14, 上: 行矩形.上 + 6, 宽: 行矩形.宽 - 28, 高: 24 },
        文本: 行.标题,
        字号档: "小",
        对齐: "左",
        颜色: this.环境.配色.次字,
      }),
    );
    const 列数 = 4;
    const 间距 = 6;
    const 按钮宽 = (行矩形.宽 - 28 - 间距 * (列数 - 1)) / 列数;
    行.选项.forEach((选项, 序号) => {
      const 列 = 序号 % 列数;
      const 行号 = Math.floor(序号 / 列数);
      const 按钮矩形: 矩形 = {
        左: 行矩形.左 + 14 + 列 * (按钮宽 + 间距),
        上: 行矩形.上 + 32 + 行号 * 36,
        宽: 按钮宽,
        高: 30,
      };
      容器.添加(
        new 按钮({
          矩形: 按钮矩形,
          文案: 选项,
          字号档: "小",
          变体: "次要",
          已选: 序号 === 行.已选,
          圆角: 8,
          点击: () => {
            this.滚动位置 = 容器.读取滚动位置();
            行.变化(序号);
          },
        }),
      );
    });
  }

  private 填充开关行(容器: 滚动容器, 行矩形: 矩形, 行: Extract<设置行, { 类型: "开关" }>): void {
    容器.添加(
      new 文本行({
        矩形: { 左: 行矩形.左 + 14, 上: 行矩形.上 + 8, 宽: 行矩形.宽 - 110, 高: 32 },
        文本: 行.标题,
        字号档: "小",
        对齐: "左",
      }),
    );
    容器.添加(
      new 开关({
        矩形: { 左: 行矩形.左 + 行矩形.宽 - 78, 上: 行矩形.上 + 8, 宽: 52, 高: 30 },
        值: 行.值,
        变化: (值) => {
          this.滚动位置 = 容器.读取滚动位置();
          行.变化(值);
        },
      }),
    );
  }
}

/** 行底板：只画不交互。 */
class 行底板 implements 控件接口 {
  private readonly 矩形值: 矩形;
  constructor(矩形: 矩形) {
    this.矩形值 = 矩形;
  }
  读取矩形(): 矩形 {
    return this.矩形值;
  }
  命中(): null {
    return null;
  }
  绘制(环境: 绘制环境): void {
    绘制面板(环境, this.矩形值, { 圆角: 10, 填充透明度: 0.72, 描边宽: 1 });
  }
}

function 查找已购(已购: readonly string[], 部位: string): string[] {
  return 已购
    .filter((编号) => 编号.endsWith(`.${部位}`))
    .map((编号) => 编号.slice(0, -部位.length - 1));
}

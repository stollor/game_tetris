  /** 页脚按钮在构建期登记（渲染期只画不登记，避免每帧堆积命中区）。 */
  private 创建页脚(英文: boolean): void {
    const 面板 = this.面板矩形;
    const 底 = 面板.上 + 面板.高;
    const 内容左 = 面板.左 + 14;
    const 内容宽 = 面板.宽 - 28;
    // Phaser 页脚按钮行中心在面板底 -32（页脚高 78、内部主轴居中后的落地位置）。
    const 按钮行Y = 底 - 32;
    // 与 Phaser 设置页同构：立即同步（云存档不可用时禁用）/ 恢复默认 / 完成（主按钮）。
    const 按钮列表: {
      名称: string;
      文案: string;
      宽: number;
      点击: () => void;
      主要?: boolean;
      禁用?: boolean;
    }[] = [
      {
        名称: "立即同步",
        文案: 英文 ? "Sync now" : "立即同步",
        宽: 英文 ? 92 : 88,
        点击: () => {
          if (this.云同步中) return;
          this.云同步中 = true;
          this.重建();
          void 立即同步云存档()
            .catch(() => undefined)
            .finally(() => {
              this.云同步中 = false;
              this.重建();
            });
        },
        禁用: this.云同步中,
      },
      {
        名称: "恢复默认",
        文案: 英文 ? "Reset" : "恢复默认",
        宽: 80,
        点击: () => this.恢复默认(),
      },
      {
        名称: "返回主菜单",
        文案: 英文 ? "Done" : "完成",
        宽: 英文 ? 64 : 56,
        点击: () => this.上下文.导航.返回(),
        主要: true,
      },
    ];
    this.页脚按钮 = [];
    let 右 = 内容左 + 内容宽;
    for (const 按钮 of [...按钮列表].reverse()) {
      const 矩形 = { 左: 右 - 按钮.宽, 上: 按钮行Y - 17, 宽: 按钮.宽, 高: 34 };
      this.页脚按钮.unshift({
        名称: 按钮.名称,
        文案: 按钮.文案,
        矩形,
        点击: 按钮.点击,
        主要: 按钮.主要,
        禁用: 按钮.禁用,
      });
      this.创建热区({
        名称: 按钮.名称,
        矩形,
        点击: 按钮.点击,
        禁用: 按钮.禁用 ?? false,
      });
      右 -= 按钮.宽 + 8;
    }
  }


import { 绘制图标 } from "../../../框架Three/界面/控件/图标";
import { 绘制单行文字, 绘制圆角矩形 } from "../../../框架Three/界面/控件/工具";
import { 开关 } from "../../../框架Three/界面/控件/开关";
import { 绘制文本行 } from "../../../框架Three/界面/控件/文本行";
import type { 矩形, 绘制环境 } from "../../../框架Three/界面/控件/类型";
import type { 游戏模式 } from "../../玩法/再消一行";
import { 游戏模式顺序 } from "../../配置/游戏外观";
import type { 页面上下文 } from "../接口/上下文";
import { 页面基类 } from "./页面工具";

/**
 * 主界面：标题 + 金币 + 功能入口（设置/成就/排行榜/商店）+ 四种模式入口 + 180° 旋转开关。
 * 模式卡自绘（强调色描边 + 说明 + 最佳纪录），命中用透明按钮覆盖，验收按名称点击。
 */

interface 模式卡布局 {
  模式: 游戏模式;
  矩形: 矩形;
  强调色: number;
}

const 模式说明: Record<游戏模式, { 说明: string; 英文: string }> = {
  马拉松: { 说明: "不断挑战更高等级与分数", 英文: "Endless climb" },
  冲刺: { 说明: "最快消满 40 行", 英文: "Clear 40 lines fast" },
  极限: { 说明: "120 秒内冲击最高分", 英文: "Score in 120s" },
  每日挑战: { 说明: "今日固定序列，全球同题", 英文: "Same seed today" },
};

const 模式强调色: Record<游戏模式, number> = {
  马拉松: 0x00e5ff,
  冲刺: 0xffee58,
  极限: 0xff2d9b,
  每日挑战: 0x00e676,
};

const 布局 = {
  金币: { 左: 18, 上: 92, 宽: 122, 高: 32 },
  标题: { 左: 22, 上: 132, 宽: 346, 高: 44 },
  副题: { 左: 22, 上: 180, 宽: 346, 高: 40 },
  入口上: 234,
  入口宽: 84,
  入口高: 60,
  入口间距: 8,
  模式卡左: 22,
  模式卡上: 318,
  模式卡宽: 346,
  模式卡高: 78,
  模式卡间距: 14,
  开关: { 左: 390 - 74, 上: 704, 宽: 52, 高: 30 },
  开关标签: { 左: 22, 上: 704, 宽: 220, 高: 30 },
  底部提示: { 左: 22, 上: 764, 宽: 346, 高: 38 },
} as const;

export class 主界面 extends 页面基类 {
  private 模式卡列表: 模式卡布局[] = [];

  constructor(上下文: 页面上下文) {
    super(上下文, { 名称: "主界面" });
  }

  进入(): void {
    super.进入();
    this.恢复音频();
  }

  恢复(): void {
    super.恢复();
    this.恢复音频();
  }

  /** 从商店/子页面回来时恢复菜单音乐与氛围；已在播放就不重播。 */
  private 恢复音频(): void {
    const 音频 = this.上下文.服务.音频;
    if (音频.读取状态().当前音乐 === null) {
      音频.播放音乐("再消一行.菜单");
      音频.播放氛围(this.上下文.服务.设置.读取().背景主题);
    }
  }

  protected 构建(): void {
    const 英文 = this.上下文.服务.语言.是否英文();
    this.模式卡列表 = 游戏模式顺序.map((模式, 序号) => ({
      模式,
      矩形: {
        左: 布局.模式卡左,
        上: 布局.模式卡上 + 序号 * (布局.模式卡高 + 布局.模式卡间距),
        宽: 布局.模式卡宽,
        高: 布局.模式卡高,
      },
      强调色: 模式强调色[模式],
    }));
    for (const 卡 of this.模式卡列表) {
      this.创建按钮(`开始:${卡.模式}`, {
        矩形: 卡.矩形,
        变体: "文字",
        圆角: 14,
        点击: () => this.开始游戏(卡.模式),
      });
    }

    const 入口列表 = [
      { 名称: "设置", 图标: "设置", 标签: 英文 ? "SET" : "设置", 页面: "设置" as const },
      { 名称: "成就", 图标: "成就", 标签: 英文 ? "BEST" : "成就", 页面: "成就" as const },
      { 名称: "排行榜", 图标: "排行", 标签: 英文 ? "TOP" : "排行", 页面: "排行榜" as const },
      { 名称: "商店", 图标: "商店", 标签: 英文 ? "SHOP" : "商店", 页面: "商店" as const },
    ];
    入口列表.forEach((入口, 序号) => {
      this.创建按钮(入口.名称, {
        矩形: {
          左: 15 + 序号 * (布局.入口宽 + 布局.入口间距),
          上: 布局.入口上,
          宽: 布局.入口宽,
          高: 布局.入口高,
        },
        文案: 入口.标签,
        图标: 入口.图标 as "设置",
        图标位置: "上",
        图标尺寸: 20,
        变体: "次要",
        圆角: 12,
        字号档: "小",
        点击: () => this.跳转(入口.页面),
      });
    });

    // 180° 旋转开关：复用游戏设置里的 旋转180。
    const 设置 = this.上下文.服务.设置.读取();
    this.添加控件(
      new 开关({
        矩形: 布局.开关,
        值: 设置.旋转180,
        变化: (值) => {
          this.上下文.服务.设置.更新({ 旋转180: 值 });
          this.显示提示(值 ? "180° 旋转已开启" : "180° 旋转已关闭");
          this.重建();
        },
      }),
    );
  }

  protected 绘制内容(环境: 绘制环境): void {
    const 英文 = this.上下文.服务.语言.是否英文();
    const 文案 = this.上下文.服务.语言.读取();
    this.绘制金币(环境);
    绘制单行文字(
      环境,
      布局.标题,
      英文 ? "ONE MORE LINE" : 文案.游戏名称,
      "大",
      环境.配色.主字,
      "左",
    );
    绘制文本行(
      环境,
      布局.副题,
      英文 ? "Stack a line, clear a line, survive the next." : "方块落下，消去一行，再消一行。",
      { 字号档: "小", 颜色: 环境.配色.次字, 最大行数: 2 },
    );

    for (const 卡 of this.模式卡列表) this.绘制模式卡(环境, 卡);

    绘制单行文字(
      环境,
      布局.开关标签,
      英文 ? "180° rotation" : "180° 旋转",
      "小",
      环境.配色.次字,
      "左",
    );
    绘制单行文字(
      环境,
      布局.底部提示,
      英文
        ? "Tap a mode to start · Settings / Shop above"
        : "点模式开始 · 上方入口可设置、看成就与商店",
      "小",
      环境.配色.弱字,
      "左",
    );
  }

  protected 读取文字快照(): readonly string[] {
    const 记录 = this.上下文.服务.纪录;
    const 今日 = this.上下文.服务.当日日期();
    return [
      `金币:${this.上下文.服务.金币.读取().金币}`,
      ...游戏模式顺序.map((模式) => {
        const 最佳 = 记录.读取(模式, 模式 === "每日挑战" ? 今日 : undefined);
        return `${模式}:${最佳?.分数 ?? 0}`;
      }),
    ];
  }

  private 绘制金币(环境: 绘制环境): void {
    const 金币 = this.上下文.服务.金币.读取().金币;
    const 矩形 = 布局.金币;
    绘制圆角矩形(环境, 矩形, 环境.配色.浮层, 16, 0.9);
    绘制图标(环境, "金币", { 左: 矩形.左 + 6, 上: 矩形.上 + 5, 宽: 22, 高: 22 }, 0xf4cd75);
    绘制单行文字(
      环境,
      { 左: 矩形.左 + 34, 上: 矩形.上, 宽: 矩形.宽 - 40, 高: 矩形.高 },
      String(金币),
      "中",
      环境.配色.警告,
      "左",
    );
  }

  private 绘制模式卡(环境: 绘制环境, 卡: 模式卡布局): void {
    const 英文 = this.上下文.服务.语言.是否英文();
    const 矩形 = 卡.矩形;
    绘制圆角矩形(环境, 矩形, 环境.配色.浮层, 14, 0.92);
    绘制圆角矩形(环境, 矩形, 卡.强调色, 14, 0.14);
    // 左侧强调条。
    绘制圆角矩形(
      环境,
      { 左: 矩形.左, 上: 矩形.上 + 8, 宽: 4, 高: 矩形.高 - 16 },
      卡.强调色,
      2,
      0.95,
    );
    const 标题 = 英文
      ? { 马拉松: "Marathon", 冲刺: "Sprint", 极限: "Ultra", 每日挑战: "Daily" }[卡.模式]
      : 卡.模式;
    绘制单行文字(
      环境,
      { 左: 矩形.左 + 18, 上: 矩形.上 + 12, 宽: 矩形.宽 - 150, 高: 30 },
      标题,
      "中",
      环境.配色.主字,
      "左",
    );
    绘制单行文字(
      环境,
      { 左: 矩形.左 + 18, 上: 矩形.上 + 42, 宽: 矩形.宽 - 150, 高: 24 },
      英文 ? 模式说明[卡.模式].英文 : 模式说明[卡.模式].说明,
      "小",
      环境.配色.次字,
      "左",
    );
    const 纪录 = this.上下文.服务.纪录.读取(
      卡.模式,
      卡.模式 === "每日挑战" ? this.上下文.服务.当日日期() : undefined,
    );
    const 右侧文字 =
      卡.模式 === "每日挑战"
        ? 纪录
          ? `${纪录.分数}`
          : 英文
            ? "Today"
            : "今日"
        : 纪录
          ? `${英文 ? "BEST" : "最佳"} ${纪录.分数}`
          : "—";
    const 右侧: 矩形 = { 左: 矩形.左 + 矩形.宽 - 128, 上: 矩形.上 + 20, 宽: 108, 高: 34 };
    绘制单行文字(环境, 右侧, 右侧文字, "小", 卡.强调色, "右");
    if (卡.模式 === "每日挑战")
      绘制单行文字(
        环境,
        { 左: 矩形.左 + 矩形.宽 - 128, 上: 矩形.上 + 46, 宽: 108, 高: 20 },
        this.格式化日期(this.上下文.服务.当日日期()),
        "小",
        环境.配色.弱字,
        "右",
      );
  }

  private 格式化日期(日期: string): string {
    const 部分 = 日期.split("-");
    if (部分.length !== 3) return 日期;
    return `${Number(部分[1])}月${Number(部分[2])}日`;
  }

  private 开始游戏(模式: 游戏模式): void {
    this.上下文.导航.进入("对局", { 模式 });
  }
}

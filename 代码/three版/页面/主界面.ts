/**
 * 主界面（7A/7C）：与 Phaser 版同款三态。
 * - 菜单态：共享背景（页面基类）+ 金币条 + 标题 + 3 个左侧角钮 + 开始游戏；
 * - 模式选择态：标题 + 4 张模式卡（含右上角排行榜入口）+ 返回；
 * - 纯享态（7C）：全屏风景 + 胶囊返回 + 风景标题/副题 + 底部圆点，左右切景/下滑返回。
 * 全部视觉来自 `组件/霓虹街机/` 的共享配方，文字统一走 文字项 + 画笔.绘制文字。
 */

interface 按钮区域布局 {
  中心X: number;
  中心Y: number;
  宽: number;
  高: number;
}

interface 模式卡绘制项 {
  区域: 模式卡区域;
  数据: 模式卡数据;
}

function 按钮矩形(区域: 按钮区域布局) {
  return {
    左: 区域.中心X - 区域.宽 / 2,
    上: 区域.中心Y - 区域.高 / 2,
    宽: 区域.宽,
    高: 区域.高,
  };
}

export class 主界面 extends 页面基类 {
  private 状态: "菜单" | "模式选择" | "纯享" = "菜单";
  private 布局!: 主界面布局;
  private 金币 = 0;
  private 英文 = false;
  private 模式卡列表: readonly 模式卡绘制项[] = [];
  private 纯享主题: 背景主题 = "极光原野";
  private 按下中 = new Set<string>();

  constructor(上下文: 页面上下文) {
    super(上下文, { 名称: "主界面" });
  }

  进入(): void {
    super.进入();
    this.恢复音频();
  }

  恢复(): void {
    super.恢复();
    this.恢复音频();
  }

  /** 从商店/子页面回来时恢复菜单音乐与氛围；已在播放就不重播。 */
  private 恢复音频(): void {
    const 音频 = this.上下文.服务.音频;
    if (音频.读取状态().当前音乐 === null) {
      音频.播放音乐("再消一行.菜单");
      音频.播放氛围(this.上下文.服务.设置.读取().背景主题);
    }
  }

  更新(秒: number): void {
    super.更新(秒);
    // 纯享态风景始终动态（与 Phaser 版一致），需要持续重绘。
    if (this.状态 === "纯享") this.请求重绘();
  }

  protected 构建(): void {
    this.控件层.清空();
    this.英文 = this.上下文.服务.语言.是否英文();
    this.金币 = this.上下文.服务.金币.读取().金币;
    this.布局 = 计算主界面布局(this.逻辑宽, this.逻辑高, this.状态);
    if (this.状态 === "纯享") {
      this.构建纯享();
      return;
    }
    const 调色板 = 读取霓虹调色板();
    const 角钮动作: Record<string, () => void> = {
      设置: () => this.跳转("设置"),
      成就: () => this.跳转("成就"),
      商店: () => this.跳转("商店"),
    };
    // 纯享入口手势层先注册：控件层后注册者优先命中，按钮热区在其后注册才能压住它。
    if (this.状态 === "菜单")
      this.创建滑动热区({
        矩形: 全屏区域(this.逻辑宽, this.逻辑高),
        点击: () => this.进入纯享(),
        滑动: (方向) => {
          if (方向 === "上") this.进入纯享();
        },
      });
    // 菜单态才有左侧角钮；模式选择态与 Phaser 版一致：角钮移出并禁用命中。
    if (this.状态 === "菜单")
      this.布局.角钮.项.forEach((项, 索引) => {
        const 点击 = 角钮动作[项.文案.中文];
        this.创建热区({
          名称: 项.文案.中文,
          矩形: 按钮矩形({
            中心X: this.布局.角钮.中心X,
            中心Y: this.布局.角钮.中心Y[索引] ?? 0,
            宽: this.布局.角钮.宽,
            高: this.布局.角钮.高,
          }),
          点击: 点击 ?? (() => undefined),
          按下: () => this.按下刷新(项.文案.中文, true),
          松开: () => this.按下刷新(项.文案.中文, false),
          取消: () => this.按下刷新(项.文案.中文, false),
        });
      });
    const 开始 = this.布局.开始钮;
    if (开始) {
      this.创建热区({
        名称: "开始游戏",
        矩形: 按钮矩形(开始),
        点击: () => this.切换状态("模式选择"),
        按下: () => this.按下刷新("开始游戏", true),
        松开: () => this.按下刷新("开始游戏", false),
        取消: () => this.按下刷新("开始游戏", false),
      });
      return;
    }
    const 模式选择 = this.布局.模式选择;
    if (!模式选择) return;
    const 今日 = this.上下文.服务.当日日期();
    this.模式卡列表 = 模式选择.卡.map((区域) => ({
      区域,
      数据: 组装模式卡数据(
        区域.模式,
        this.英文,
        this.上下文.服务.纪录.读取(区域.模式, 区域.模式 === "每日挑战" ? 今日 : undefined),
        调色板.强调色,
      ),
    }));
    for (const { 区域 } of this.模式卡列表) {
      this.创建热区({
        名称: `开始:${区域.模式}`,
        矩形: 按钮矩形(区域),
        点击: () => this.开始游戏(区域.模式),
        按下: () => this.按下刷新(`开始:${区域.模式}`, true),
        松开: () => this.按下刷新(`开始:${区域.模式}`, false),
        取消: () => this.按下刷新(`开始:${区域.模式}`, false),
      });
      // 排行钮位置与绘制共用模式卡配方的同一份几何。
      const 排行区域 = 计算模式卡排行区域(区域);
      this.创建热区({
        名称: `排行榜:${区域.模式}`,
        矩形: 按钮矩形(排行区域),
        点击: () => this.跳转("排行榜", { 模式: 区域.模式 }),
        按下: () => this.按下刷新(`排行榜:${区域.模式}`, true),
        松开: () => this.按下刷新(`排行榜:${区域.模式}`, false),
        取消: () => this.按下刷新(`排行榜:${区域.模式}`, false),
      });
    }
    this.创建热区({
      名称: "返回",
      矩形: 按钮矩形(模式选择.返回钮),
      点击: () => this.切换状态("菜单"),
      按下: () => this.按下刷新("返回", true),
      松开: () => this.按下刷新("返回", false),
      取消: () => this.按下刷新("返回", false),
    });
  }

  private 构建纯享(): void {
    const 纯享 = 计算纯享布局(this.逻辑宽, this.逻辑高);
    if (!纯享) return;
    const 解锁 = 已解锁风景列表();
    const 当前 = 获取设置背景主题(this.上下文);
    this.纯享主题 = 解锁.includes(当前) ? 当前 : (解锁[0] ?? 当前);
    this.创建滑动热区({
      矩形: 全屏区域(this.逻辑宽, this.逻辑高),
      滑动: (方向) => {
        if (方向 === "左") this.切纯享(1);
        else if (方向 === "右") this.切纯享(-1);
        else if (方向 === "下") this.退出纯享();
      },
    });
    this.创建热区({
      名称: "纯享:返回",
      矩形: 按钮矩形(纯享.返回钮),
      点击: () => this.退出纯享(),
      按下: () => this.按下刷新("纯享:返回", true),
      松开: () => this.按下刷新("纯享:返回", false),
      取消: () => this.按下刷新("纯享:返回", false),
    });
  }

  private 按下刷新(名称: string, 按下: boolean): void {
    if (按下) this.按下中.add(名称);
    else this.按下中.delete(名称);
    this.请求重绘();
  }

  private 进入纯享(): void {
    if (this.状态 === "纯享") return;
    const 解锁 = 已解锁风景列表();
    const 当前 = 获取设置背景主题(this.上下文);
    this.纯享主题 = 解锁.includes(当前) ? 当前 : (解锁[0] ?? 当前);
    this.状态 = "纯享";
    this.重建();
  }

  private 切纯享(方向: -1 | 1): void {
    this.纯享主题 = 相邻已解锁风景(this.纯享主题, 方向);
    this.重建();
  }

  private 退出纯享(): void {
    if (this.状态 !== "纯享") return;
    this.状态 = "菜单";
    this.重建();
  }

  private 切换状态(状态: "菜单" | "模式选择"): void {
    if (this.状态 === 状态) return;
    this.状态 = 状态;
    this.重建();
  }

  private 开始游戏(模式: 游戏模式): void {
    this.上下文.导航.进入("对局", { 模式 });
  }

  protected 绘制内容(): void {
    const 画笔 = this.上下文.资源.画笔;
    const 图形 = 画笔.图形;
    if (this.状态 === "纯享") {
      this.绘制纯享(图形, 画笔);
      return;
    }
    const 调色板 = 读取霓虹调色板();
    const 金币布局 = 计算金币条(this.布局.金币.左, this.布局.金币.上, this.金币);
    this.绘制金币(图形, 画笔, 金币布局);
    for (const 项 of 生成主界面文字项(this.布局, {
      英文: this.英文,
      游戏名称: this.上下文.服务.语言.读取().游戏名称,
    }))
      画笔.绘制文字(项);
    if (this.状态 === "菜单")
      this.布局.角钮.项.forEach((项, 索引) => {
        const 名称 = 项.文案.中文;
        this.绘制按钮(
          图形,
          画笔,
          {
            中心X: this.布局.角钮.中心X,
            中心Y: this.布局.角钮.中心Y[索引] ?? 0,
            宽: this.布局.角钮.宽,
            高: this.布局.角钮.高,
          },
          this.英文 ? 项.文案.英文 : 项.文案.中文,
          {
            变体: "次要",
            字号: 12,
            图标: 项.图标,
            图标尺寸: 18,
            图文方向: "竖排",
            按下: this.按下中.has(名称),
          },
        );
      });
    const 开始 = this.布局.开始钮;
    if (开始) {
      this.绘制按钮(图形, 画笔, 开始, this.英文 ? 开始.文案.英文 : 开始.文案.中文, {
        变体: "主要",
        字号: 16,
        面板透明度: 0.78,
        强调色: 调色板.强调色,
        按下: this.按下中.has("开始游戏"),
      });
      return;
    }
    const 模式选择 = this.布局.模式选择;
    if (!模式选择) return;
    for (const { 区域, 数据 } of this.模式卡列表) {
      绘制模式卡(图形, 区域, 数据, { 按下: this.按下中.has(`开始:${区域.模式}`) });
      for (const 项 of 生成模式卡文字项(区域, 数据)) 画笔.绘制文字(项);
    }
    this.绘制按钮(
      图形,
      画笔,
      模式选择.返回钮,
      this.英文 ? 模式选择.返回钮.文案.英文 : 模式选择.返回钮.文案.中文,
      {
        变体: "次要",
        字号: 16,
        面板透明度: 0.78,
        强调色: 调色板.次要按钮.边框,
        按下: this.按下中.has("返回"),
      },
    );
  }

  /** 纯享态：全屏风景（共享背景配方）+ 胶囊返回 + 标题/副题 + 底部圆点。 */
  private 绘制纯享(图形: 图形对象, 画笔: 画笔): void {
    const 纯享 = 计算纯享布局(this.逻辑宽, this.逻辑高);
    if (!纯享) return;
    绘制背景(图形, {
      宽: this.逻辑宽,
      高: this.逻辑高,
      主题: this.纯享主题,
      动态: true,
      时间秒: this.读取背景时间秒(),
    });
    const 说明 = 风景说明(this.纯享主题);
    for (const 项 of 生成纯享文字项(纯享, 说明)) 画笔.绘制文字(项);
    const 返回 = 纯享.返回钮;
    const 按下 = this.按下中.has("纯享:返回");
    绘制纯享胶囊(图形, 返回.中心X, 返回.中心Y, 返回.宽, 返回.高, { 按下 });
    画笔.绘制文字(纯享返回文字项(返回.中心X, 返回.中心Y, this.英文 ? "Back" : "返回"));
    const 解锁 = 已解锁风景列表();
    const 当前 = Math.max(0, 解锁.indexOf(this.纯享主题));
    绘制纯享圆点(图形, this.逻辑宽, this.逻辑高, 解锁.length, 当前);
  }

  private 绘制金币(图形: 图形对象, 画笔: 画笔, 布局: 金币条布局): void {
    绘制金币条(图形, 布局);
    for (const 项 of 生成金币条文字项(布局, this.金币)) 画笔.绘制文字(项);
  }

  /** 一块共享配方按钮：底板 + 可选图标 + 文字项（文字色按底色对比自动取）。 */
  private 绘制按钮(
    图形: 图形对象,
    画笔: 画笔,
    区域: 按钮区域布局,
    文案: string,
    选项: 霓虹按钮文字选项 & 霓虹按钮状态,
  ): void {
    const 标签尺寸 = 画笔.测量文字(文案, 读取霓虹按钮文字样式(选项));
    const 内容 = 生成霓虹按钮内容(区域.中心X, 区域.中心Y, 文案, 选项, 标签尺寸);
    绘制霓虹按钮(图形, 区域.中心X, 区域.中心Y, 区域.宽, 区域.高, 选项);
    if (内容.图标) 绘制霓虹按钮图标(图形, 内容.图标);
    if (内容.文字项) 画笔.绘制文字(内容.文字项);
  }

  protected 读取文字快照(): readonly string[] {
    const 金币 = this.上下文.服务.金币.读取().金币;
    const 今日 = this.上下文.服务.当日日期();
    return [
      `状态:${this.状态}`,
      `金币:${金币}`,
      ...(this.状态 === "纯享" ? [`纯享:${this.纯享主题}`] : []),
      ...(this.布局.模式选择?.卡.map((区域) => {
        const 纪录 = this.上下文.服务.纪录.读取(
          区域.模式,
          区域.模式 === "每日挑战" ? 今日 : undefined,
        );
        return `${区域.模式}:${纪录?.分数 ?? 0}`;
      }) ?? []),
    ];
  }
}

function 全屏区域(宽: number, 高: number): { 左: number; 上: number; 宽: number; 高: number } {
  return { 左: 0, 上: 0, 宽, 高 };
}

function 获取设置背景主题(上下文: 页面上下文): 背景主题 {
  return 上下文.服务.设置.读取().背景主题;
}

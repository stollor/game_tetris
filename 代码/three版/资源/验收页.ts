import { 创建渲染编排 } from "../../../框架Three/世界/渲染编排";
import { 图元合批 } from "../../../框架Three/界面/图元合批";
import type { 文字样式 } from "../../../组件/绘制/图形对象";
import { 创建画笔 } from "../画笔/index";
import { 创建文字服务 } from "../画笔/文字服务";
import type { 资源层实例 } from "./index";
import { 创建资源层, 读取默认散图 } from "./index";

/**
 * 资源验收页：只做验收、不接游戏导航。用 Three 真实渲染（正交相机 + 图元合批 + 文字图集）
 * 画出「项目图集帧（游戏图标）」与「GM 套件散图（圣所）」，并把图集帧数/页数/纹理字节/预算/
 * 散图尺寸/请求来源列表显示在画面上，证明 GM 图集资源有真实运行时消费者。
 *
 * 单独一条 Three 渲染管线，不复用游戏页面缓存：`bun run dev:three` 后访问 `/资源验收` 即可截图
 * （390×844 视口），全局 `window.__资源验收__` 供浏览器脚本读取统计与请求来源。
 */

const 逻辑宽 = 390;
const 逻辑高 = 844;
const 纹理预算字节 = 64 * 1024 * 1024;
const 字体 = '"Segoe UI", "Microsoft YaHei", sans-serif';

const 样式 = {
  标题: { 字体, 字号: 20, 字重: "粗体", 颜色: 0x00e5ff } satisfies 文字样式,
  小标题: { 字体, 字号: 14, 字重: "粗体", 颜色: 0xffee58 } satisfies 文字样式,
  正文: { 字体, 字号: 12, 颜色: 0xe6eefc } satisfies 文字样式,
  弱: { 字体, 字号: 10, 颜色: 0x8fa3c8 } satisfies 文字样式,
} as const;

function 格式化字节(字节: number): string {
  if (字节 >= 1024 * 1024) return `${(字节 / 1024 / 1024).toFixed(2)} MB`;
  if (字节 >= 1024) return `${(字节 / 1024).toFixed(1)} KB`;
  return `${字节} B`;
}

async function 启动(): Promise<void> {
  const 容器 = document.getElementById("游戏容器");
  if (!容器) throw new Error("缺少 #游戏容器");

  const 渲染 = 创建渲染编排({
    容器,
    逻辑宽,
    逻辑高,
    像素比: 1,
    清屏色: 0x0a0e1d,
    最大帧率: 60,
    按需渲染: true,
    纹理预算字节,
  });
  const 合批 = new 图元合批();
  渲染.场景.add(合批.提交());

  const 来源列表: string[] = [];
  let 资源: 资源层实例;
  try {
    资源 = await 创建资源层({
      登记纹理: 渲染.登记纹理,
      记录来源: (地址) => {
        if (!来源列表.includes(地址)) 来源列表.push(地址);
      },
    });
  } catch (错误) {
    throw 错误 instanceof Error ? 错误 : new Error(String(错误));
  }

  const 文字 = 创建文字服务({
    登记纹理: 渲染.登记纹理,
    字体,
  });
  const 画笔 = 创建画笔({ 合批, 文字服务: 文字, 资源层: 资源 });

  const 统计 = 资源.读取统计();
  const 游戏图标帧 = 资源.读取帧("再消一行", "图标/游戏图标.png");
  const 圣所 = 资源.读取散图("套件/圣所");
  const 图标散图 = 资源.读取散图("图标/游戏图标");

  画笔.重置();
  画笔.图形
    .fillGradientStyle(0x101a33, 0x101a33, 0x060a16, 0x060a16)
    .fillRect(0, 0, 逻辑宽, 逻辑高);
  画笔.图形.fillStyle(0x0f1b33).fillRoundedRect(16, 16, 逻辑宽 - 32, 60, 12);
  画笔.绘制文字({
    文案: "资源验收 · GM 图集运行时消费者",
    样式: 样式.标题,
    锚点: "中上",
    x: 逻辑宽 / 2,
    y: 30,
  });

  // 项目图集帧：走 图集纹理 → 合批 UV。
  画笔.图形.fillStyle(0x122240, 0.9).fillRoundedRect(20, 96, 170, 170, 10);
  const 画到 = 画笔.绘制纹理帧(
    { 图集: "再消一行", 帧: "图标/游戏图标.png" },
    { 左: 25, 上: 101, 宽: 160, 高: 160 },
  );
  画笔.绘制文字({
    文案: `项目图集帧\n图标/游戏图标.png\n${游戏图标帧 ? `${游戏图标帧.源宽}×${游戏图标帧.源高}` : "未入集"}\n绘制${画到 ? "成功" : "失败"}`,
    样式: 样式.正文,
    锚点: "左上",
    x: 200,
    y: 104,
  });
  画笔.绘制文字({
    文案: `图集帧 ${统计.帧数} · 页 ${统计.页数} · 图集 ${统计.图集数}`,
    样式: 样式.小标题,
    锚点: "左上",
    x: 200,
    y: 210,
  });
  画笔.绘制文字({
    文案: `渲染纹理 ${格式化字节(渲染.读取统计().纹理字节)} / 预算 ${格式化字节(纹理预算字节)}`,
    样式: 样式.正文,
    锚点: "左上",
    x: 200,
    y: 232,
  });
  画笔.绘制文字({
    文案: `资源层纹理 ${格式化字节(统计.纹理字节)}`,
    样式: 样式.弱,
    锚点: "左上",
    x: 200,
    y: 252,
  });
  画笔.绘制文字({
    文案: `散图 ${统计.散图数}：图标 ${图标散图?.宽 ?? 0}×${图标散图?.高 ?? 0}`,
    样式: 样式.正文,
    锚点: "左上",
    x: 200,
    y: 272,
  });

  // GM 套件散图：走资源层 → 整图 UV。
  const 圣所宽 = 240;
  const 圣所高 = 圣所 && 圣所.宽 > 0 ? Math.round((圣所宽 * 圣所.高) / 圣所.宽) : 240;
  const 圣所绘制 = 画笔.绘制散图("套件/圣所", { 左: 20, 上: 300, 宽: 圣所宽, 高: 圣所高 });
  画笔.图形.lineStyle(1, 0x00e5ff, 0.8).strokeRoundedRect(18, 298, 圣所宽 + 4, 圣所高 + 4, 6);
  画笔.绘制文字({
    文案: `GM 套件散图\n套件/圣所\n${圣所 ? `${圣所.宽}×${圣所.高}` : "未加载"}\n绘制${圣所绘制 ? "成功" : "失败"}`,
    样式: 样式.正文,
    锚点: "左上",
    x: 20 + 圣所宽 + 16,
    y: 304,
  });

  // 请求来源列表。
  const 来源行 = 来源列表.map((地址) => `· ${地址}`).join("\n");
  画笔.图形.fillStyle(0x0d1930).fillRoundedRect(16, 640, 逻辑宽 - 32, 180, 10);
  画笔.绘制文字({
    文案: `请求来源（${来源列表.length}）\n${来源行}`,
    样式: 样式.正文,
    锚点: "左上",
    最大宽: 逻辑宽 - 48,
    x: 28,
    y: 654,
  });
  画笔.绘制文字({
    文案: `默认散图：${读取默认散图()
      .map((项) => 项.键)
      .join("、")}`,
    样式: 样式.弱,
    锚点: "左上",
    x: 28,
    y: 788,
  });

  合批.提交();
  渲染.请求重绘();
  渲染.渲染();

  const 读取统计 = () => ({
    图集: 统计,
    合批: 合批.读取统计(),
    渲染: 渲染.读取统计(),
    来源: [...来源列表],
    帧: 游戏图标帧 ?? null,
    散图: {
      图标: 图标散图 ? { 宽: 图标散图.宽, 高: 图标散图.高 } : null,
      圣所: 圣所 ? { 宽: 圣所.宽, 高: 圣所.高 } : null,
    },
    纹理预算字节,
  });

  Object.assign(window, {
    __资源验收__: {
      读取统计,
      停止: () => {
        Reflect.deleteProperty(window, "__资源验收__");
        合批.销毁();
        文字.销毁();
        资源.销毁();
        渲染.销毁();
      },
    },
  });
  console.log("资源验收页已渲染", 读取统计());
}

启动().catch((错误: unknown) => {
  const 文本 = 错误 instanceof Error ? 错误.message : String(错误);
  console.error("资源验收页启动失败", 错误);
  const 提示 = document.getElementById("错误提示");
  if (提示) {
    提示.style.display = "block";
    提示.textContent = `资源验收页启动失败：${文本}`;
  }
});

declare global {
  interface Window {
    __资源验收__?: {
      读取统计: () => {
        图集: { 图集数: number; 页数: number; 帧数: number; 纹理字节: number; 散图数: number };
        合批: { 四边形数: number; 三角形数: number; 绘制批数: number; 顶点数: number };
        渲染: { 纹理数: number; 纹理字节: number; 渲染帧数: number };
        来源: string[];
        帧: { 页: number; 源宽: number; 源高: number } | null;
        散图: { 图标: { 宽: number; 高: number } | null; 圣所: { 宽: number; 高: number } | null };
        纹理预算字节: number;
      };
      停止: () => void;
    };
  }
}

/**
 * 结算覆盖页：压在结束的对局上，显示分数/等级/消行/用时/金币/新纪录/成就，
 * 提供「重新开始」「返回主菜单」；马拉松/每日挑战结束 3 秒内不可重开，防误触。
 * 数据来自对局页写入的 最近结算，参数里的 对局结果 只作兜底。
 */

function 兜底结算(结果: 对局结果): 最近结算 {
  return {
    编号: `兜底-${结果.日期}-${结果.分数}`,
    结果,
    目标达成: false,
    刷新纪录: false,
    历史最佳: null,
    金币: null,
    金币失败原因: "",
    新成就: [],
    结束时刻毫秒: Date.now(),
    奖励输入: {
      编号: `兜底-${结果.日期}-${结果.分数}`,
      分数: 结果.分数,
      消行: 结果.消行数,
      用时: 结果.用时毫秒 ?? 0,
      落块: 0,
      破纪录: false,
      日期: 结果.日期,
    },
  };
}

export class 结算页面 implements 页面实例 {
  private readonly 上下文: 页面上下文;
  private 数据: 最近结算;
  private 撤销命中: (() => void)[] = [];
  private 已进入 = false;
  private 上次数秒 = -1;

  constructor(上下文: 页面上下文) {
    this.上下文 = 上下文;
    this.数据 = 兜底结算({
      模式: "马拉松",
      分数: 0,
      消行数: 0,
      等级: 1,
      最长连击: 0,
      用时毫秒: null,
      完赛: false,
      日期: 上下文.服务.当日日期(),
    });
  }

  进入(): void {
    const 结果 = this.上下文.参数.结果;
    this.数据 = 读取最近结算() ?? (结果 ? 兜底结算(结果) : this.数据);
    this.已进入 = true;
    this.上次数秒 = -1;
    this.注册命中();
    this.上下文.资源.请求重绘();
  }

  退出(): void {
    for (const 注销 of this.撤销命中) 注销();
    this.撤销命中 = [];
    this.已进入 = false;
  }

  更新(): void {
    if (!this.已进入) return;
    const 剩余 = this.读取锁剩余毫秒();
    const 秒 = Math.ceil(剩余 / 1000);
    // 3 秒防误触期间每秒重绘一次按钮倒计时。
    if (秒 !== this.上次数秒) {
      this.上次数秒 = 秒;
      this.上下文.资源.请求重绘();
    }
  }

  渲染(): void {
    if (!this.已进入) return;
    const 资源 = this.上下文.资源;
    const 环境: 绘制环境 = {
      合批: 资源.合批,
      图形: 资源.画笔.图形,
      方块方案: 读取方块外观方案(this.上下文.服务.设置.读取()),
      画笔: 资源.画笔,
      主题: this.上下文.主题,
    };
    const 文案 = this.上下文.服务.语言.读取();
    const 英文 = this.上下文.服务.语言.是否英文();
    const 锁剩余 = this.读取锁剩余毫秒();
    绘制结算(环境, {
      结果: this.数据.结果,
      标题: 结算标题(this.数据.结果, 文案),
      徽标: 生成结算徽标(this.数据.结果.模式, this.数据.结果, this.数据.刷新纪录, 文案),
      统计: 生成结算统计(this.数据.结果.模式, this.数据.结果, this.数据.历史最佳, 文案),
      奖励文案: 读取奖励文案(this.数据),
      成就文案: 读取成就文案(this.数据.新成就, this.上下文.服务.成就.全部定义(), 英文),
      金币余额: this.读取金币余额(),
      锁剩余毫秒: 锁剩余,
      可重开: 锁剩余 === 0,
    });
  }

  读取界面(): 界面快照 {
    const 可重开 = this.读取锁剩余毫秒() === 0;
    const 按钮: 界面按钮快照[] = [
      { 名称: "重新开始", ...结算重开按钮, 可用: 可重开 },
      { 名称: "返回主菜单", ...结算菜单按钮, 可用: true },
    ];
    return { 按钮, 文字: [结算标题(this.数据.结果, this.上下文.服务.语言.读取())] };
  }

  /** 调试桥在结算覆盖页上读取的结算明细（验收直接断言金币/纪录/锁）。 */
  读取快照(): unknown {
    const 文案 = this.上下文.服务.语言.读取();
    const 结果 = this.数据.结果;
    return {
      页面: "结算",
      阶段: "结束",
      模式: 结果.模式,
      分数: 结果.分数,
      消行数: 结果.消行数,
      等级: 结果.等级,
      最长连击: 结果.最长连击,
      完赛: 结果.完赛,
      用时毫秒: 结果.用时毫秒,
      日期: 结果.日期,
      标题: 结算标题(结果, 文案),
      徽标: 生成结算徽标(结果.模式, 结果, this.数据.刷新纪录, 文案),
      统计: 生成结算统计(结果.模式, 结果, this.数据.历史最佳, 文案),
      刷新纪录: this.数据.刷新纪录,
      历史最佳: this.数据.历史最佳,
      金币奖励: this.数据.金币,
      金币失败原因: this.数据.金币失败原因,
      新成就: this.数据.新成就,
      奖励文案: 读取奖励文案(this.数据),
      金币余额: this.读取金币余额(),
      重开锁剩余毫秒: this.读取锁剩余毫秒(),
    };
  }

  /* ---------------------------------------------------------------- */

  private 读取锁剩余毫秒(): number {
    return 读取重开锁剩余毫秒(this.数据.结果.模式, this.数据.结束时刻毫秒, Date.now());
  }

  private 读取金币余额(): number {
    try {
      return this.上下文.服务.金币.读取().金币;
    } catch {
      return 0;
    }
  }

  private 注册命中(): void {
    const 命中 = this.上下文.资源.命中;
    this.撤销命中.push(
      命中.注册({
        名称: "结算.重新开始",
        ...结算重开按钮,
        深度: 30,
        禁用: () => this.读取锁剩余毫秒() > 0,
        回调: (事件) => {
          if (事件.类型 !== "抬起") return;
          this.重开();
        },
      }),
    );
    this.撤销命中.push(
      命中.注册({
        名称: "结算.返回主菜单",
        ...结算菜单按钮,
        深度: 30,
        回调: (事件) => {
          if (事件.类型 !== "抬起") return;
          this.返回主菜单();
        },
      }),
    );
  }

  private 重开(): void {
    if (this.读取锁剩余毫秒() > 0) return;
    this.上下文.导航.替换("对局", { 模式: this.数据.结果.模式 });
  }

  private 返回主菜单(): void {
    this.上下文.导航.替换("主界面");
  }

  /** 结算页测试/重试用：金币奖励失败后按同一编号重试并刷新展示数据。 */
  重试奖励(): void {
    if (this.数据.金币 || !this.数据.金币失败原因) return;
    try {
      const 结果 = this.上下文.服务.金币.结算对局(this.数据.奖励输入);
      if (结果.成功) {
        this.数据 = {
          ...this.数据,
          金币: { 新增: 结果.新增, 总额: 结果.金币, 原因: 结果.原因 },
          金币失败原因: "",
        };
        更新最近结算(this.数据);
      } else {
        this.数据 = { ...this.数据, 金币失败原因: 结果.原因 };
      }
    } catch {
      this.数据 = { ...this.数据, 金币失败原因: "旅行奖励保存失败" };
    }
    this.上下文.资源.请求重绘();
  }
}

export const 创建结算页面: 页面工厂 = (上下文: 页面上下文) => new 结算页面(上下文);

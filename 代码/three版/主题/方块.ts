import { 压暗, 填充矩形, 提亮, 颜色四元组, 颜色混合 } from "../../../框架Three/界面/控件/工具";
import type { 绘制环境 } from "../../../框架Three/界面/控件/类型";
import { type 方块类型, 预览格子 } from "../../玩法/再消一行";
import type { 游戏设置 } from "../../配置/再消一行设置";
import { 获取游戏设置 } from "../../配置/再消一行设置";
import { type 方块外观方案, 解析方块外观 } from "../../配置/方块外观";

/**
 * 方块外观：复用 `代码/配置/方块外观.ts` 的配色与质感名，
 * 用四边形做宝石/柔瓷/金属/像素四种简化质感，棋盘、预览、暂存、商店陈列共用。
 */

export function 读取方块外观方案(设置: 游戏设置 = 获取游戏设置()): 方块外观方案 {
  return 解析方块外观(设置.方块外观);
}

export function 读取方块配色(设置: 游戏设置 = 获取游戏设置()): Record<方块类型, number> {
  return { ...读取方块外观方案(设置).颜色 };
}

/** 画一格方块：不同质感只改叠色层次，不增加纹理与 draw call。 */
export function 绘制方块格(
  环境: 绘制环境,
  左: number,
  上: number,
  格: number,
  方案: 方块外观方案,
  类型或颜色: 方块类型 | number,
  透明度 = 1,
): void {
  if (格 <= 0 || 透明度 <= 0) return;
  const 色 = typeof 类型或颜色 === "number" ? 类型或颜色 : (方案.颜色[类型或颜色] ?? 0xffffff);
  const 白块 = 环境.文字.读取纯色紫外线();
  const 画 = (块: { 左: number; 上: number; 宽: number; 高: number }, 颜色: number, 透明: number) =>
    填充矩形(
      环境.合批,
      白块,
      { 左: 块.左, 上: 块.上, 宽: Math.max(1, 块.宽), 高: Math.max(1, 块.高) },
      颜色,
      透明 * 透明度,
    );
  const 内缩 = Math.max(1, 格 * 0.06);
  const 内左 = 左 + 内缩;
  const 内上 = 上 + 内缩;
  const 内格 = Math.max(1, 格 - 内缩 * 2);
  if (方案.辉光 >= 0.4) {
    const 扩张 = 格 * 0.12;
    环境.合批.添加({
      左: 内左 - 扩张,
      上: 内上 - 扩张,
      宽: 内格 + 扩张 * 2,
      高: 内格 + 扩张 * 2,
      紫外线: 白块,
      颜色: 颜色四元组(色, 0.12 * 方案.辉光 * 透明度),
      混合: "叠加",
    });
  }

  if (方案.质感 === "柔瓷") {
    画({ 左: 内左, 上: 内上, 宽: 内格, 高: 内格 }, 色, 1);
    画({ 左: 内左, 上: 内上, 宽: 内格, 高: 内格 * 0.34 }, 提亮(色, 0.28), 0.7);
    画({ 左: 内左, 上: 内上 + 内格 * 0.82, 宽: 内格, 高: 内格 * 0.18 }, 压暗(色, 0.18), 0.5);
    return;
  }
  if (方案.质感 === "金属") {
    画({ 左: 内左, 上: 内上, 宽: 内格, 高: 内格 }, 色, 1);
    画({ 左: 内左, 上: 内上 + 内格 * 0.12, 宽: 内格, 高: 内格 * 0.26 }, 提亮(色, 0.38), 0.75);
    画({ 左: 内左, 上: 内上 + 内格 * 0.52, 宽: 内格, 高: 内格 * 0.16 }, 压暗(色, 0.3), 0.6);
    画({ 左: 内左, 上: 内上 + 内格 * 0.84, 宽: 内格, 高: 内格 * 0.16 }, 提亮(色, 0.18), 0.4);
    return;
  }
  if (方案.质感 === "像素") {
    画({ 左: 内左, 上: 内上, 宽: 内格, 高: 内格 }, 色, 1);
    const 槽 = Math.max(1, 内格 * 0.18);
    画({ 左: 内左, 上: 内上, 宽: 槽, 高: 槽 }, 提亮(色, 0.5), 0.85);
    画({ 左: 内左 + 内格 - 槽, 上: 内上 + 内格 - 槽, 宽: 槽, 高: 槽 }, 压暗(色, 0.45), 0.85);
    画(
      { 左: 内左 + 槽 * 0.2, 上: 内上 + 内格 - 槽 * 0.6, 宽: 内格 - 槽, 高: 槽 * 0.4 },
      压暗(色, 0.2),
      0.4,
    );
    return;
  }
  // 宝石（默认）：底色 + 顶部高光 + 底部暗边 + 左侧反光。
  画({ 左: 内左, 上: 内上, 宽: 内格, 高: 内格 }, 色, 1);
  画({ 左: 内左, 上: 内上, 宽: 内格, 高: Math.max(2, 内格 * 0.2) }, 提亮(色, 0.55), 0.9);
  画(
    {
      左: 内左,
      上: 内上 + 内格 - Math.max(2, 内格 * 0.14),
      宽: 内格,
      高: Math.max(2, 内格 * 0.14),
    },
    压暗(色, 0.38),
    0.85,
  );
  画(
    { 左: 内左, 上: 内上 + 内格 * 0.22, 宽: Math.max(1, 内格 * 0.08), 高: 内格 * 0.5 },
    颜色混合(色, 0xffffff, 0.35),
    0.35,
  );
}

/** 画一个完整方块形状（按出生格相对位置），用于预览/暂存/商店陈列。 */
export function 绘制方块形状(
  环境: 绘制环境,
  方案: 方块外观方案,
  类型: 方块类型,
  中心X: number,
  上: number,
  格: number,
  透明度 = 1,
): void {
  const 格子 = 预览格子(类型);
  const 列数 = Math.max(...格子.map(([列]) => 列)) + 1;
  const 左 = 中心X - (列数 * 格) / 2;
  for (const [列, 行] of 格子) {
    绘制方块格(环境, 左 + 列 * 格, 上 + 行 * 格, 格, 方案, 类型, 透明度);
  }
}

import type { 图形对象 } from "../../../框架Three/界面/绘制/协议";
import { 绘制方块单元, 绘制方块单元辉光 } from "../../../组件/霓虹街机/方块单元";
import { type 方块类型, 预览格子 } from "../../玩法/再消一行";
import type { 游戏设置 } from "../../配置/再消一行设置";
import { 获取游戏设置 } from "../../配置/再消一行设置";
import { type 方块外观名称, type 方块外观方案, 解析方块外观 } from "../../配置/方块外观";

/**
 * Three 版方块外观：只做设置→方案的换算，绘制统一走 `组件/霓虹街机/方块单元.ts`
 * 的共享纯配方（与 Phaser 同一组指令、同一份外观表），不再自造简化质感。
 * 图形对象来自 `上下文.资源.画笔.图形`。
 */

export type { 方块外观名称, 方块外观方案 };

export function 读取方块外观方案(设置: 游戏设置 = 获取游戏设置()): 方块外观方案 {
  return 解析方块外观(设置.方块外观);
}

export function 读取方块配色(设置: 游戏设置 = 获取游戏设置()): Record<方块类型, number> {
  return { ...读取方块外观方案(设置).颜色 };
}

/** 单格方块：共享配方的 Three 入口。 */
export function 绘制方块格(
  绘图: 图形对象,
  左: number,
  上: number,
  格: number,
  方案: 方块外观方案,
  类型或颜色: 方块类型 | number,
  透明度 = 1,
): void {
  if (格 <= 0 || 透明度 <= 0) return;
  const 色 = typeof 类型或颜色 === "number" ? 类型或颜色 : 方案.颜色[类型或颜色];
  绘制方块单元(绘图, 左, 上, { 方案, 色值: 色, 格子: 格, 透明度 });
}

/** 方块外圈辉光：画在叠加混合图层上（调用方负责混合模式）。 */
export function 绘制方块格辉光(
  绘图: 图形对象,
  左: number,
  上: number,
  格: number,
  方案: 方块外观方案,
  类型或颜色: 方块类型 | number,
  透明度 = 1,
): void {
  if (格 <= 0 || 透明度 <= 0) return;
  const 色 = typeof 类型或颜色 === "number" ? 类型或颜色 : 方案.颜色[类型或颜色];
  绘制方块单元辉光(绘图, 左, 上, { 方案, 色值: 色, 格子: 格, 透明度 });
}

/** 画一个完整方块形状（按预览格相对位置），用于预览/暂存/商店陈列。 */
export function 绘制方块形状(
  绘图: 图形对象,
  方案: 方块外观方案,
  类型: 方块类型,
  中心X: number,
  上: number,
  格: number,
  透明度 = 1,
): void {
  const 格子 = 预览格子(类型);
  const 列数 = Math.max(...格子.map(([列]) => 列)) + 1;
  const 左 = 中心X - (列数 * 格) / 2;
  for (const [列, 行] of 格子) {
    绘制方块格(绘图, 左 + 列 * 格, 上 + 行 * 格, 格, 方案, 类型, 透明度);
  }
}

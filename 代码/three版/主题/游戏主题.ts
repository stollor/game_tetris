import type { 地点名称 } from "../../框架配置/旅行地点";
import type { 游戏设置 } from "../../配置/再消一行设置";
import { 获取游戏设置 } from "../../配置/再消一行设置";
import { 解析方块外观 } from "../../配置/方块外观";
import { 界面主题 } from "../../配置/界面主题";
import type { 游戏主题 } from "../接口/服务";

type 样式选择 = "夜空鎏金" | "暖纸古典" | "青蓝未来";

/**
 * 《再消一行》Three 版的游戏主题：把 `代码/配置/界面主题.ts` 的语义主题与方块外观
 * 换算成 Three 版使用的数值色。页面与对局共用同一份主题数据，不各取各的配置。
 */

function 颜色值(颜色: string): number {
  return Number.parseInt(颜色.replace("#", ""), 16);
}

function 亮度(色值: number): number {
  const 红 = (色值 >> 16) & 0xff;
  const 绿 = (色值 >> 8) & 0xff;
  const 蓝 = 色值 & 0xff;
  return (红 * 299 + 绿 * 587 + 蓝 * 114) / 1000;
}

/** 设置 → 游戏主题。旅行样式优先于基础样式，与 Phaser 版取色口径一致。 */
export function 创建游戏主题(
  设置: 游戏设置 = 获取游戏设置(),
  预览样式?: 样式选择 | 地点名称,
): 游戏主题 {
  const 样式 = 预览样式 ?? 设置.旅行样式 ?? 设置.样式;
  const 主题 = 界面主题(样式);
  const 方块 = 解析方块外观(设置.方块外观);
  const 底色 = 颜色值(主题.页面.背景);
  return {
    名称: 主题.元信息.名称,
    深色: 亮度(底色) < 132,
    颜色: {
      底色,
      面板: 颜色值(主题.面板.主面板.背景),
      浮层: 颜色值(主题.面板.次级面板.背景),
      描边: 颜色值(主题.面板.主面板.描边),
      主字: 颜色值(主题.文字.主要),
      次字: 颜色值(主题.文字.次要),
      暗字: 颜色值(主题.文字.弱化),
      强调: 颜色值(主题.文字.强调),
      成功: 颜色值(主题.文字.成功),
      警告: 颜色值(主题.文字.警告),
      危险: 颜色值(主题.文字.危险),
    },
    方块: { ...方块.颜色 },
  };
}

import { 压暗, 填充矩形 } from "../../../框架Three/界面/控件/工具";
import type { 矩形, 绘制环境 } from "../../../框架Three/界面/控件/类型";
import { 查找地点 } from "../../框架配置/旅行地点";
import { 读取背景外观配色 } from "../../视觉/背景配方";
import type { 游戏设置, 背景主题 } from "../../配置/再消一行设置";
import { 获取游戏设置 } from "../../配置/再消一行设置";

/**
 * Three 版背景外观：只把共享配置换算成页面需要的外观值，不再另画简化背景。
 * 页面背景统一用 `代码/视觉/背景配方.ts` 的 `绘制背景(画笔.图形, 参数)`；
 * 这里保留顶栏衬底与外观读取，供游戏页面基类/设置外观卡用。
 */

export interface 背景外观 {
  名称: string;
  旅行: boolean;
  主色: number;
  强调: number;
  文字基调: "浅底" | "深底";
}

/** 读取当前设置对应主题的外观；颜色与文字基调全部来自共享配置（背景主题/旅行地点）。 */
export function 读取背景外观(设置: 游戏设置 = 获取游戏设置()): 背景外观 {
  const 主题 = 设置.背景主题;
  const 地点 = 查找地点(主题);
  const 配色 = 读取背景外观配色(主题);
  return {
    名称: 地点?.名称 ?? 主题,
    旅行: 地点 !== undefined,
    ...配色,
  };
}

/** 悬浮面板/顶部栏底衬：从背景取半透明底色，页面顶栏用。 */
export function 绘制顶栏衬底(环境: 绘制环境, 矩形: 矩形, 外观: 背景外观, 透明度 = 0.72): void {
  填充矩形(环境.合批, 环境.文字.读取纯色紫外线(), 矩形, 压暗(外观.主色, 0.55), 透明度);
  填充矩形(
    环境.合批,
    环境.文字.读取纯色紫外线(),
    { 左: 矩形.左, 上: 矩形.上 + 矩形.高 - 1, 宽: 矩形.宽, 高: 1 },
    外观.强调,
    0.3,
  );
}

/** 背景主题的显示名（设置页外观卡用）。 */
export function 读取背景标签(主题: 背景主题): string {
  return 查找地点(主题)?.名称 ?? 主题;
}

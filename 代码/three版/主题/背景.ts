export function 读取背景外观(设置: 游戏设置 = 获取游戏设置()): 背景外观 {
  const 地点 = 查找地点(设置.背景主题);
  if (地点)
    return {
      名称: 地点.名称,
      旅行: true,
      天空: 地点.天空,
      远景: 地点.远景,
      主色: 地点.主色,
      强调: 地点.强调,
      纹样: 地点.纹样,
      文字基调: "深底",
    };
  const 基础 = 基础背景表[设置.背景主题] ?? 默认背景;
  return { 名称: 设置.背景主题, 旅行: false, ...基础 };
}

export interface 绘制背景选项 {
  /** 动画时间（秒）；不传则画静态底。 */
  时间秒?: number;
  /** 是否画动态极光/光带，默认关闭（省电与按需渲染）。 */
  动态?: boolean;
  /** 简化层次：缩略图跳过大面积星点与山脊。 */
  简化?: boolean;
}

export function 绘制背景(
  环境: 绘制环境,
  矩形: 矩形,
  外观: 背景外观,
  选项: 绘制背景选项 = {},
): void {
  const 白块 = 环境.文字.读取纯色紫外线();
  const 画 = (块: 矩形, 色: number, 透明度 = 1) => 填充矩形(环境.合批, 白块, 块, 色, 透明度);
  const 深色 = 外观.文字基调 === "深底";

  // 天空：8 段横带做垂直渐变。
  const 段数 = 选项.简化 ? 4 : 8;
  const 天空高 = 矩形.高 * 0.74;
  for (let 序号 = 0; 序号 < 段数; 序号++) {
    const 比例 = (序号 + 0.5) / 段数;
    画(
      {
        左: 矩形.左,
        上: 矩形.上 + (天空高 * 序号) / 段数,
        宽: 矩形.宽,
        高: 天空高 / 段数 + 0.5,
      },
      颜色混合(外观.天空[0], 外观.天空[1], 比例),
    );
  }

  // 地平线光晕：一条很淡的强调色亮带，把天空和地面分开。
  const 地平线 = 矩形.上 + 天空高;
  if (深色) {
    环境.合批.添加({
      左: 矩形.左,
      上: 地平线 - 28,
      宽: 矩形.宽,
      高: 32,
      紫外线: 白块,
      颜色: 颜色四元组(外观.强调, 0.06),
    });
  }

  if (!选项.简化) {
    绘制星点(环境, 矩形, 外观);
    绘制远山(环境, 矩形, 外观);
  }

  // 地面：压暗主色，靠近底边再暗一档，让页面内容有落脚点。
  画(
    { 左: 矩形.左, 上: 地平线, 宽: 矩形.宽, 高: 矩形.高 - 天空高 },
    压暗(外观.主色, 深色 ? 0.25 : 0.1),
  );
  if (深色)
    画(
      { 左: 矩形.左, 上: 矩形.上 + 矩形.高 * 0.86, 宽: 矩形.宽, 高: 矩形.高 * 0.14 },
      压暗(外观.主色, 0.5),
    );

  if (外观.纹样) {
    const 格 = Math.min(矩形.宽, 矩形.高) * 0.3;
    绘制旅行纹样(
      环境,
      矩形.左 + 矩形.宽 * 0.62,
      矩形.上 + 矩形.高 * 0.6,
      格,
      外观.纹样,
      外观.强调,
      0.12,
    );
  }

  if (选项.动态 && 选项.时间秒 !== undefined) {
    绘制动态极光(环境, 矩形, 外观, 选项.时间秒);
  }
}

/** 深色背景下画确定性星点（不用随机数，重绘不会闪）。 */
function 绘制星点(环境: 绘制环境, 矩形: 矩形, 外观: 背景外观): void {
  if (外观.文字基调 !== "深底") return;
  const 白块 = 环境.文字.读取纯色紫外线();
  for (let 序号 = 0; 序号 < 30; 序号++) {
    const 横 = ((序号 * 73 + 17) % 101) / 101;
    const 纵 = ((序号 * 37 + 11) % 89) / 89;
    const 大小 = 1 + ((序号 * 7) % 3) * 0.7;
    const 透明 = 0.15 + ((序号 * 13) % 5) * 0.1;
    填充矩形(
      环境.合批,
      白块,
      {
        左: 矩形.左 + 横 * 矩形.宽,
        上: 矩形.上 + 纵 * 矩形.高 * 0.64,
        宽: 大小,
        高: 大小,
      },
      外观.强调,
      透明,
    );
  }
}

/** 远山：两层阶梯剪影，远层更淡更大，近层更深。 */
function 绘制远山(环境: 绘制环境, 矩形: 矩形, 外观: 背景外观): void {
  const 白块 = 环境.文字.读取纯色紫外线();
  const 地平线 = 矩形.上 + 矩形.高 * 0.74;
  const 峰数 = 5;
  const 座宽 = 矩形.宽 / (峰数 + 0.6);
  for (let 层 = 0; 层 < 2; 层++) {
    const 层高 = 矩形.高 * (层 === 0 ? 0.2 : 0.13);
    const 色 =
      层 === 0 ? 颜色混合(外观.远景, 外观.天空[1], 0.45) : 颜色混合(外观.远景, 外观.主色, 0.25);
    for (let 座 = 0; 座 < 峰数; 座++) {
      const 高 = 层高 * (0.62 + ((座 * 29 + 层 * 11) % 5) * 0.09);
      const 中心 = 矩形.左 + 座宽 * (座 + 0.55) + 层 * 14;
      const 阶梯 = 6;
      const 底宽 = 座宽 * (层 === 0 ? 1.15 : 0.92);
      for (let 步 = 0; 步 < 阶梯; 步++) {
        const 宽 = 底宽 * (1 - 步 / 阶梯);
        const 高差 = 高 / 阶梯;
        填充矩形(
          环境.合批,
          白块,
          { 左: 中心 - 宽 / 2, 上: 地平线 - 高 + 步 * 高差, 宽, 高: 高差 + 0.6 },
          色,
          层 === 0 ? 0.75 : 0.95,
        );
      }
    }
  }
  填充矩形(
    环境.合批,
    白块,
    { 左: 矩形.左, 上: 地平线 - 1.5, 宽: 矩形.宽, 高: 1.5 },
    外观.强调,
    0.25,
  );
}

/** 动态光：极淡的整屏呼吸 + 两条边缘柔化的横向光带；不画硬边竖条。 */
function 绘制动态极光(环境: 绘制环境, 矩形: 矩形, 外观: 背景外观, 时间秒: number): void {
  const 白块 = 环境.文字.读取纯色紫外线();
  const 呼吸 = 0.014 + (Math.sin(时间秒 * 0.7) + 1) * 0.008;
  // 动态光全部用普通混合：叠加批次在同图层内排到最后，会盖住页面内容。
  环境.合批.添加({
    左: 矩形.左,
    上: 矩形.上,
    宽: 矩形.宽,
    高: 矩形.高,
    紫外线: 白块,
    颜色: 颜色四元组(外观.强调, 呼吸),
  });

  for (let 带 = 0; 带 < 2; 带++) {
    const 相位 = 时间秒 * (0.18 + 带 * 0.04) + 带 * 2.1;
    const 中心 = 缓入缓出((Math.sin(相位) + 1) / 2);
    const 宽 = 矩形.宽 * (0.42 + 带 * 0.08);
    const 左 = 矩形.左 - 矩形.宽 * 0.2 + 中心 * 矩形.宽 * 0.92;
    const 上 = 矩形.上 + 矩形.高 * (0.2 + 带 * 0.14) + Math.sin(相位 * 1.4) * 8;
    // 三条高度不同的横带叠出柔光晕，避免一条硬边矩形。
    const 层列表 = [
      { 宽比: 1, 高: 10, 透明: 0.028 },
      { 宽比: 0.78, 高: 16, 透明: 0.022 },
      { 宽比: 0.52, 高: 22, 透明: 0.016 },
    ];
    for (const 层 of 层列表) {
      const 层宽 = 宽 * 层.宽比;
      环境.合批.添加({
        左: 左 + (宽 - 层宽) / 2,
        上: 上 + (10 - 层.高) / 2,
        宽: 层宽,
        高: 层.高,
        紫外线: 白块,
        颜色: 颜色四元组(提亮(外观.强调, 带 * 0.08), 层.透明),
      });
    }
  }
}

/** 悬浮面板/顶部栏底衬：从背景取半透底色，页面顶栏用。 */
export function 绘制顶栏衬底(环境: 绘制环境, 矩形: 矩形, 外观: 背景外观, 透明度 = 0.72): void {
  填充矩形(环境.合批, 环境.文字.读取纯色紫外线(), 矩形, 压暗(外观.主色, 0.55), 透明度);
  填充矩形(
    环境.合批,
    环境.文字.读取纯色紫外线(),
    { 左: 矩形.左, 上: 矩形.上 + 矩形.高 - 1, 宽: 矩形.宽, 高: 1 },
    外观.强调,
    0.3,
  );
}

/** 背景主题的显示名（设置页外观卡用）。 */
export function 读取背景标签(主题: 背景主题): string {
  return 查找地点(主题)?.名称 ?? 主题;
}

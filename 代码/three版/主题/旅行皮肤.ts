/**
 * 旅行 12 套地点皮肤的 Three 版简化绘制：颜色与纹样取自 `代码/框架配置/旅行地点.ts`，
 * 只用四边形做意象化图案（不复刻视频级演出），商店缩略、背景与方块都共用这里的入口。
 */

export function 读取旅行皮肤(名称: 地点名称 | string): 地点皮肤 | undefined {
  return 查找地点(名称);
}

export function 读取全部旅行皮肤(): readonly 地点皮肤[] {
  return 地点皮肤表;
}

/** 地点纹样：在 格×格 的方框内画一组可辨识的简化图案。 */
export function 绘制旅行纹样(
  环境: 绘制环境,
  左: number,
  上: number,
  格: number,
  纹样: 地点纹样,
  颜色: number,
  透明度 = 0.9,
): void {
  const 白块 = 环境.文字.读取纯色紫外线();
  const 画 = (x: number, y: number, 宽: number, 高: number, 色 = 颜色, 透明 = 透明度) =>
    填充矩形(
      环境.合批,
      白块,
      { 左: 左 + x * 格, 上: 上 + y * 格, 宽: Math.max(1, 宽 * 格), 高: Math.max(1, 高 * 格) },
      色,
      透明,
    );
  const 线 = 0.04;
  switch (纹样) {
    case "熊猫":
      画(0.24, 0.18, 0.52, 0.5);
      画(0.3, 0.3, 0.12, 0.12, 颜色混合(颜色, 收藏色.夜, 0.75));
      画(0.58, 0.3, 0.12, 0.12, 颜色混合(颜色, 收藏色.夜, 0.75));
      画(0.42, 0.46, 0.16, 0.12, 颜色混合(颜色, 收藏色.夜, 0.6));
      return;
    case "冰晶":
      画(0.48, 0.12, 线, 0.76);
      画(0.12, 0.48, 0.76, 线);
      画(0.22, 0.22, 0.1, 0.1);
      画(0.66, 0.22, 0.1, 0.1);
      画(0.22, 0.66, 0.1, 0.1);
      画(0.66, 0.66, 0.1, 0.1);
      return;
    case "城砖":
      画(0.1, 0.3, 0.8, 线);
      画(0.1, 0.55, 0.8, 线);
      画(0.1, 0.8, 0.8, 线);
      画(0.36, 0.3, 线, 0.25);
      画(0.64, 0.55, 线, 0.25);
      return;
    case "宫阙":
      画(0.16, 0.2, 0.68, 0.14);
      画(0.24, 0.4, 0.52, 0.4);
      画(0.4, 0.5, 0.2, 0.3);
      画(0.1, 0.82, 0.8, 0.1);
      return;
    case "莲叶":
      画(0.2, 0.42, 0.6, 0.16);
      画(0.32, 0.58, 0.36, 0.12);
      画(0.48, 0.26, 线, 0.16);
      return;
    case "流沙":
      画(0.12, 0.36, 0.7, 0.09);
      画(0.2, 0.54, 0.66, 0.09);
      画(0.12, 0.72, 0.58, 0.09);
      return;
    case "山水":
      画(0.36, 0.24, 0.28, 0.12);
      画(0.26, 0.36, 0.48, 0.12);
      画(0.14, 0.48, 0.72, 0.14);
      画(0.1, 0.72, 0.8, 0.1);
      return;
    case "窗棂":
      画(0.46, 0.14, 0.08, 0.72);
      画(0.14, 0.46, 0.72, 0.08);
      画(0.2, 0.2, 0.6, 0.06);
      画(0.2, 0.74, 0.6, 0.06);
      return;
    case "霓虹":
      画(0.24, 0.2, 0.08, 0.6, 提亮(颜色, 0.5));
      画(0.24, 0.2, 0.5, 0.08, 提亮(颜色, 0.5));
      画(0.7, 0.2, 0.1, 0.1, 提亮(颜色, 0.7));
      return;
    case "铜纹":
      画(0.24, 0.24, 0.52, 0.08);
      画(0.24, 0.68, 0.52, 0.08);
      画(0.24, 0.32, 0.08, 0.36);
      画(0.68, 0.32, 0.08, 0.36);
      画(0.42, 0.42, 0.16, 0.16, 提亮(颜色, 0.4));
      return;
    case "松针":
      画(0.3, 0.7, 0.08, 0.08);
      画(0.38, 0.6, 0.08, 0.08);
      画(0.46, 0.5, 0.08, 0.08);
      画(0.54, 0.4, 0.08, 0.08);
      画(0.3, 0.5, 0.08, 0.08, 提亮(颜色, 0.3));
      画(0.46, 0.3, 0.08, 0.08, 提亮(颜色, 0.3));
      return;
    default:
      画(0.18, 0.24, 0.6, 0.1);
      画(0.28, 0.36, 0.4, 0.1, 提亮(颜色, 0.25));
      画(0.38, 0.48, 0.22, 0.1, 提亮(颜色, 0.45));
      画(0.18, 0.62, 0.6, 0.1);
      return;
  }
}

/** 地点缩略图：天空渐变 + 远景山脊 + 中央纹样，商店目录与设置外观卡共用。 */
export function 绘制旅行缩略(
  环境: 绘制环境,
  矩形: 矩形,
  名称: 地点名称 | string,
  强调?: number,
): void {
  const 地点 = 查找地点(名称);
  if (!地点) return;
  const 白块 = 环境.文字.读取纯色紫外线();
  const 段数 = 6;
  for (let 序号 = 0; 序号 < 段数; 序号++) {
    const 色 = 颜色混合(地点.天空[0], 地点.天空[1], (序号 + 0.5) / 段数);
    填充矩形(
      环境.合批,
      白块,
      { 左: 矩形.左, 上: 矩形.上 + (矩形.高 * 序号) / 段数, 宽: 矩形.宽, 高: 矩形.高 / 段数 },
      色,
    );
  }
  // 远景：三层阶梯山脊。
  const 山高 = 矩形.高 * 0.34;
  for (let 层 = 0; 层 < 3; 层++) {
    填充矩形(
      环境.合批,
      白块,
      {
        左: 矩形.左 + 矩形.宽 * (0.12 + 层 * 0.16),
        上: 矩形.上 + 矩形.高 - 山高 + 层 * 山高 * 0.18,
        宽: 矩形.宽 * 0.26,
        高: 山高 * (0.9 - 层 * 0.18),
      },
      颜色混合(地点.远景, 地点.主色, 0.4 + 层 * 0.2),
      0.9,
    );
  }
  填充矩形(
    环境.合批,
    白块,
    { 左: 矩形.左, 上: 矩形.上 + 矩形.高 * 0.82, 宽: 矩形.宽, 高: 矩形.高 * 0.18 },
    颜色混合(地点.主色, 收藏色.夜, 0.25),
    0.95,
  );
  const 格 = Math.min(矩形.宽, 矩形.高) * 0.46;
  绘制旅行纹样(
    环境,
    矩形.左 + (矩形.宽 - 格) / 2,
    矩形.上 + (矩形.高 - 格) / 2 - 2,
    格,
    地点.纹样,
    强调 ?? 地点.强调,
    0.95,
  );
}

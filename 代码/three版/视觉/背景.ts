function 添加矩形(
  环境: 背景绘制环境,
  左: number,
  上: number,
  宽: number,
  高: number,
  颜色: number,
  透明度 = 1,
  叠加 = false,
): void {
  if (宽 <= 0 || 高 <= 0 || 透明度 <= 0) return;
  环境.合批.添加({
    左,
    上,
    宽,
    高,
    紫外线: 环境.纯色紫外线,
    颜色: 十六进制颜色(颜色, 透明度),
    混合: 叠加 ? "叠加" : "普通",
  });
}

/** 多段垂直渐变：逐段双色插值，避免单条色带出现色阶。 */
function 绘制渐变(
  环境: 背景绘制环境,
  左: number,
  上: number,
  宽: number,
  高: number,
  上色: number,
  下色: number,
  段数: number,
  透明度 = 1,
): void {
  const 总段 = Math.max(1, 段数);
  for (let 段 = 0; 段 < 总段; 段++) {
    const 比例 = 段 / 总段;
    const 色 = 混合颜色(上色, 下色, 比例);
    添加矩形(环境, 左, 上 + (高 * 段) / 总段, 宽, 高 / 总段 + 0.6, 色, 透明度);
  }
}

/** 近似径向光晕：同心方块逐层变亮，叠加混合避免灰边。 */
function 绘制光晕(
  环境: 背景绘制环境,
  中心X: number,
  中心Y: number,
  半径: number,
  颜色: number,
  强度 = 1,
): void {
  const 层数 = 5;
  for (let 层 = 层数; 层 >= 1; 层--) {
    const 比例 = 层 / 层数;
    const 边 = 半径 * 2 * 比例;
    添加矩形(环境, 中心X - 边 / 2, 中心Y - 边 / 2, 边, 边, 颜色, 0.05 * 强度 * (1.1 - 比例));
  }
  添加矩形(
    环境,
    中心X - 半径 * 0.34,
    中心Y - 半径 * 0.34,
    半径 * 0.68,
    半径 * 0.68,
    颜色,
    0.5,
    true,
  );
}

function 绘制星野(
  环境: 背景绘制环境,
  高: number,
  时间秒: number,
  动态: boolean,
  数量: number,
  种子: number,
): void {
  for (let i = 0; i < 数量; i++) {
    const x = 伪随机(i + 种子) * 环境.宽;
    const y = 伪随机(i + 种子 + 300) * 高 * 0.62;
    const 半径 = 0.8 + 伪随机(i + 种子 + 600) * 1.8;
    const 闪 = 动态 ? 0.5 + 0.5 * Math.sin(时间秒 * (0.6 + 伪随机(i + 8) * 1.2) + i) : 0.7;
    const 透明度 = 0.18 + 伪随机(i + 种子 + 900) * 0.5;
    添加矩形(环境, x, y, 半径, 半径, 0xffffff, 透明度 * 闪);
  }
}

function 伪随机(索引: number): number {
  const 值 = Math.sin(索引 * 127.1 + 311.7) * 43758.5453123;
  return 值 - Math.floor(值);
}

/** 阶梯山脊：用一列不同高度的矩形拼出剪影，顶上加一条受光棱线。 */
function 绘制山脊(
  环境: 背景绘制环境,
  地平线: number,
  高度: number,
  颜色: number,
  种子: number,
  列数 = 14,
): void {
  const 列宽 = 环境.宽 / 列数;
  for (let 列 = 0; 列 < 列数; 列++) {
    const 峰 = 高度 * (0.34 + 伪随机(列 + 种子) * 0.66);
    添加矩形(环境, 列 * 列宽 - 0.5, 地平线 - 峰, 列宽 + 1, 峰, 颜色);
  }
  for (let 列 = 0; 列 < 列数; 列++) {
    const 峰 = 高度 * (0.34 + 伪随机(列 + 种子) * 0.66);
    添加矩形(
      环境,
      列 * 列宽 - 0.5,
      地平线 - 峰,
      列宽 + 1,
      1.2,
      混合颜色(颜色, 0xffffff, 0.35),
      0.5,
    );
  }
}

/** 云团：三排低透明度方块错位堆叠，近大远小。 */
function 绘制云团(
  环境: 背景绘制环境,
  x: number,
  y: number,
  尺寸: number,
  颜色: number,
  透明度: number,
): void {
  for (const [偏X, 偏Y, 比例] of [
    [0, 0, 1],
    [-0.55, 0.12, 0.72],
    [0.55, 0.14, 0.8],
    [-0.2, -0.22, 0.6],
    [0.24, -0.2, 0.66],
  ] as const) {
    const 宽 = 尺寸 * 1.7 * 比例;
    const 高 = 尺寸 * 0.66 * 比例;
    添加矩形(环境, x + 偏X * 尺寸 - 宽 / 2, y + 偏Y * 尺寸, 宽, 高, 颜色, 透明度);
  }
}


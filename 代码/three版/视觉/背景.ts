/**
 * 简化版程序化背景：只用四边形合批画色带/光斑/山影/建筑/极光帘幕，
 * 不追求与 Phaser 版逐像素一致，但保留四套基础主题与 12 套旅行地点的色调与构图。
 * 每帧重画（共享合批每帧清空），动态元素按时间正弦变化；省电/关闭动态时固定为静态一帧。
 */

export interface 背景绘制环境 {
  合批: 四边形合批;
  /** 纯色紫外线，通常取小字图集的白块。 */
  纯色紫外线: 紫外线矩形;
  宽: number;
  高: number;
}

export interface 背景绘制选项 {
  主题: 背景主题;
  时间秒: number;
  /** 背景动态开关（设置里的 背景动态 + 省电模式）。 */
  动态: boolean;
}

export interface 背景配色 {
  天空上: number;
  天空下: number;
  远景: number;
  主色: number;
  强调: number;
  地点: 地点皮肤 | null;
}

const 基础配色: Record<string, Omit<背景配色, "地点" | "天空上" | "天空下">> = {
  晨光海岸: { 远景: 0x9adcd8, 主色: 0x1d4f6d, 强调: 0xffd9a0 },
  云海山岚: { 远景: 0x7c9db8, 主色: 0x2a4a5c, 强调: 0xfff3d8 },
  极光原野: { 远景: 0x123048, 主色: 0x081726, 强调: 0x3ff0c0 },
  霓虹天际: { 远景: 0x4a2a63, 主色: 0x1a1030, 强调: 0xff5fa2 },
};

export function 读取背景配色(主题: 背景主题): 背景配色 {
  const 地点 = 查找地点(主题);
  if (地点) {
    const 天空 = 地点.天空;
    return {
      天空上: 天空[0],
      天空下: 天空[1],
      远景: 地点.远景,
      主色: 地点.主色,
      强调: 地点.强调,
      地点,
    };
  }
  const 配置 = 背景主题配置[主题];
  const 预览 = 配置?.预览配色 ?? [0x0a1f3e, 0x2c7f8c];
  const 基础 = 基础配色[主题] ?? { 远景: 0x123048, 主色: 0x081726, 强调: 0x65e6dc };
  return { 天空上: 预览[0], 天空下: 预览[1], ...基础, 地点: null };
}


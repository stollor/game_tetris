export function 绘制背景(环境: 背景绘制环境, 选项: 背景绘制选项): void {
  const 配色 = 读取背景配色(选项.主题);
  const 时间 = 选项.动态 ? 选项.时间秒 : 0;
  if (配色.地点) {
    绘制旅行背景(环境, 配色, 时间, 选项.动态);
    return;
  }
  switch (选项.主题) {
    case "晨光海岸":
      绘制海岸(环境, 配色, 时间, 选项.动态);
      break;
    case "云海山岚":
      绘制山岚(环境, 配色, 时间);
      break;
    case "霓虹天际":
      绘制天际(环境, 配色, 时间, 选项.动态);
      break;
    default:
      绘制原野(环境, 配色, 时间, 选项.动态);
  }
}

function 绘制海岸(环境: 背景绘制环境, 配色: 背景配色, 时间: number, 动态: boolean): void {
  const { 宽, 高 } = 环境;
  const 海平线 = 高 * 0.585;
  绘制渐变(环境, 0, 0, 宽, 海平线 + 2, 配色.天空上, 配色.天空下, 14);
  const 日X = 宽 * 0.72;
  const 日Y = 高 * 0.27;
  绘制光晕(环境, 日X, 日Y, Math.min(宽, 高) * 0.1, 配色.强调, 1);
  绘制云团(环境, 宽 * 0.18, 高 * 0.19, 宽 * 0.08, 0xfff6e6, 0.34);
  绘制云团(环境, 宽 * 0.86, 高 * 0.36, 宽 * 0.07, 0xfff2dd, 0.26);
  绘制渐变(环境, 0, 海平线, 宽, 高 - 海平线, 配色.远景, 配色.主色, 10);
  // 海面反光：竖向光路 + 近大远小的横向波光。
  for (let i = 0; i < 8; i++) {
    const 比例 = i / 8;
    const y = 海平线 + (高 - 海平线) * 比例;
    const 宽度 = 宽 * (0.04 + 比例 * 0.12);
    添加矩形(环境, 日X - 宽度 / 2, y, 宽度, 3, 配色.强调, 0.16 * (1 - 比例 * 0.6));
  }
  for (let i = 0; i < 10; i++) {
    const 速度 = 8 + 伪随机(i + 29) * 18;
    const 长 = 宽 * (0.03 + 伪随机(i + 47) * 0.07);
    const x = 动态 ? ((伪随机(i + 77) * 宽 + 时间 * 速度) % (宽 + 长)) - 长 : 伪随机(i + 77) * 宽;
    const y = 海平线 + 伪随机(i + 111) * (高 - 海平线) * 0.9;
    添加矩形(环境, x, y, 长, 2, 0xdbfff6, 0.22);
  }
}

function 绘制山岚(环境: 背景绘制环境, 配色: 背景配色, 时间: number): void {
  const { 宽, 高 } = 环境;
  const 地平线 = 高 * 0.72;
  绘制渐变(环境, 0, 0, 宽, 地平线 + 2, 配色.天空上, 配色.天空下, 12);
  绘制光晕(环境, 宽 * 0.79, 高 * 0.2, Math.min(宽, 高) * 0.08, 配色.强调, 0.7);
  绘制云团(环境, 宽 * 0.2 + 时间 * 2, 高 * 0.16, 宽 * 0.09, 0xffffff, 0.22);
  绘制云团(环境, 宽 * 0.62 - 时间 * 1.4, 高 * 0.26, 宽 * 0.07, 0xffffff, 0.18);
  绘制山脊(环境, 高 * 0.62, 高 * 0.2, 混合颜色(配色.远景, 0xffffff, 0.45), 17);
  绘制山脊(环境, 高 * 0.74, 高 * 0.24, 配色.远景, 41);
  绘制山脊(环境, 高 * 0.86, 高 * 0.3, 配色.主色, 73);
  for (let i = 0; i < 6; i++) {
    const y = 高 * (0.58 + 伪随机(i + 7) * 0.26);
    添加矩形(
      环境,
      伪随机(i + 31) * 宽 - 宽 * 0.1,
      y,
      宽 * (0.22 + 伪随机(i + 43) * 0.3),
      8,
      0xf2f7f5,
      0.14,
    );
  }
}

function 绘制原野(环境: 背景绘制环境, 配色: 背景配色, 时间: number, 动态: boolean): void {
  const { 宽, 高 } = 环境;
  const 地平线 = 高 * 0.68;
  绘制渐变(环境, 0, 0, 宽, 地平线 + 2, 配色.天空上, 配色.天空下, 14);
  绘制星野(环境, 高, 时间, 动态, 36, 500);
  const 月X = 宽 * 0.2;
  const 月Y = 高 * 0.18;
  绘制光晕(环境, 月X, 月Y, Math.min(宽, 高) * 0.07, 0xbfe6ff, 1.1);
  添加矩形(环境, 月X - 8, 月Y - 8, 16, 16, 0xe9f4ff, 0.95);
  // 极光帘幕：三条竖直色带做正弦位移与呼吸，叠加混合。
  const 极光色 = [0x3ff0c0, 0x4de3d8, 0x7ad9ff];
  for (let 条 = 0; 条 < 3; 条++) {
    const 色 = 极光色[条] ?? 0x4de3d8;
    for (let 段 = 0; 段 < 10; 段++) {
      const x = (宽 / 10) * 段;
      const 波 = Math.sin(段 * 0.7 + 条 * 1.9 + 时间 * 0.35) * 高 * 0.04;
      const 波2 = Math.sin(段 * 1.7 + 时间 * 0.2 + 条) * 高 * 0.014;
      const 呼吸 = 动态 ? 0.5 + 0.5 * Math.sin(时间 * 0.5 + 段 * 0.5 + 条) : 0.65;
      const 顶 = 高 * (0.1 + 条 * 0.05) + 波 + 波2;
      const 帘高 = 高 * (0.16 + 0.05 * Math.sin(段 * 0.8 + 条 * 2.2 + 时间 * 0.3));
      添加矩形(环境, x, 顶, 宽 / 10 + 1, 帘高, 色, 0.06 + 0.05 * 呼吸);
    }
  }
  绘制山脊(环境, 地平线 + 2, 高 * 0.09, 配色.远景, 211);
  绘制渐变(环境, 0, 地平线, 宽, 高 - 地平线, 混合颜色(配色.主色, 0x000000, 0.15), 配色.主色, 6);
  // 湖面反光与萤火。
  for (let i = 0; i < 8; i++) {
    const y = 地平线 + 高 * 0.03 + 伪随机(i + 811) * 高 * 0.18;
    const x = 伪随机(i + 855) * 宽 + (动态 ? Math.sin(时间 + i) * 4 : 0);
    添加矩形(环境, x, y, 宽 * (0.04 + 伪随机(i + 877) * 0.08), 1.6, 0x9be8e0, 0.18);
  }
}

function 绘制天际(环境: 背景绘制环境, 配色: 背景配色, 时间: number, 动态: boolean): void {
  const { 宽, 高 } = 环境;
  const 地平线 = 高 * 0.62;
  绘制渐变(环境, 0, 0, 宽, 地平线 + 2, 配色.天空上, 配色.天空下, 14);
  const 日X = 宽 * 0.58;
  const 日Y = 高 * 0.46;
  绘制光晕(环境, 日X, 日Y, Math.min(宽, 高) * 0.11, 配色.强调, 1);
  绘制云团(环境, 宽 * 0.2, 高 * 0.24, 宽 * 0.08, 0xffc3b4, 0.22);
  绘制云团(环境, 宽 * 0.84, 高 * 0.18, 宽 * 0.07, 0xffb8a8, 0.18);
  // 远景与近景楼群：远层低对比，近层深色 + 少量亮窗与霓虹线。
  for (let i = 0; i < 14; i++) {
    const 楼宽 = 宽 * (0.025 + 伪随机(i + 7) * 0.04);
    const x = 伪随机(i + 71) * 宽;
    const 楼高 = 高 * (0.1 + 伪随机(i + 31) * 0.18);
    添加矩形(环境, x, 地平线 - 楼高, 楼宽, 楼高, 配色.远景, 0.8);
  }
  for (let i = 0; i < 12; i++) {
    const 楼宽 = 宽 * (0.035 + 伪随机(i + 17) * 0.05);
    const x = 伪随机(i + 91) * 宽;
    const 楼高 = 高 * (0.14 + 伪随机(i + 53) * 0.26);
    const y = 地平线 - 楼高 + 高 * 0.03;
    添加矩形(环境, x, y, 楼宽, 楼高 + 高 * 0.1, i % 2 ? 0x241743 : 0x2c1c4e);
    添加矩形(
      环境,
      x,
      y,
      楼宽,
      1.6,
      i % 3 === 0 ? 0xff5fa2 : i % 3 === 1 ? 0x5fe9ff : 0xffd166,
      0.7,
    );
    for (let 行 = 0; 行 < 4; 行++) {
      if (伪随机(i * 37 + 行 * 11 + 3) > 0.55) {
        添加矩形(
          环境,
          x + 楼宽 * 0.2,
          y + 8 + 行 * 10,
          Math.max(2, 楼宽 * 0.2),
          Math.max(2, 5),
          (行 + i) % 3 === 0 ? 0xffd48a : 0x7ef0ff,
          0.3,
          true,
        );
      }
    }
  }
  添加矩形(环境, 0, 地平线 + 高 * 0.03, 宽, 高, 配色.主色);
  // 车流光轨。
  for (let i = 0; i < 5; i++) {
    const y = 地平线 + 高 * (0.09 + i * 0.04);
    const 色 = i % 2 ? 0xff5f8f : 0x7ee8ff;
    const x = 动态
      ? ((伪随机(i + 91) * 宽 + 时间 * (0.06 + 伪随机(i + 71) * 0.1)) % (宽 + 220)) - 220
      : 伪随机(i + 91) * 宽;
    添加矩形(环境, x, y, 84, 2.4, 色, 0.22);
    添加矩形(环境, x - 62, y, 56, 2.4, 色, 0.12);
  }
}


function 绘制棋盘(环境: 绘制环境, 视图: 对局视图, 偏移X: number, 偏移Y: number): void {
  const 色 = 环境.主题.颜色;
  const { 左, 上, 格, 列, 行 } = 布局.棋盘;
  const 棋盘左 = 左 + 偏移X;
  const 棋盘上 = 上 + 偏移Y;
  const 外框: 矩形 = { ...棋盘外框, 左: 棋盘外框.左 + 偏移X, 上: 棋盘外框.上 + 偏移Y };
  绘制面板(环境, 外框, 混合颜色(色.底色, 色.面板, 0.55), 色.描边, 0.96);
  if (视图.显示网格) {
    const 网格色 = 混合颜色(色.描边, 色.底色, 0.55);
    for (let 列号 = 1; 列号 < 列; 列号++) {
      添加矩形(环境, { 左: 棋盘左 + 列号 * 格, 上: 棋盘上, 宽: 1, 高: 行 * 格 }, 网格色, 0.35);
    }
    for (let 行号 = 1; 行号 < 行; 行号++) {
      添加矩形(环境, { 左: 棋盘左, 上: 棋盘上 + 行号 * 格, 宽: 列 * 格, 高: 1 }, 网格色, 0.35);
    }
  }
  const { 状态 } = 视图;
  for (let 行号 = 0; 行号 < 行; 行号++) {
    const 行数据 = 状态.棋盘[行号 + 2];
    if (!行数据) continue;
    for (let 列号 = 0; 列号 < 列; 列号++) {
      const 类型 = 行数据[列号];
      if (!类型) continue;
      绘制方块格(环境, 环境.主题.方块[类型], 棋盘左 + 列号 * 格, 棋盘上 + 行号 * 格, 格);
    }
  }
  // 幽灵落点先画，当前方块覆盖在上层。
  const 幽灵透明度 = Math.max(0, Math.min(1, 视图.落点影透明度 / 100)) * 0.32;
  const 当前类型 = 状态.当前方块.类型;
  for (const [列号, 行号] of 视图.影子) {
    if (行号 < 0 || 行号 >= 行 || 状态.棋盘[行号 + 2]?.[列号]) continue;
    绘制方块格(
      环境,
      环境.主题.方块[当前类型],
      棋盘左 + 列号 * 格,
      棋盘上 + 行号 * 格,
      格,
      幽灵透明度,
    );
  }
  for (const [列号, 行号] of 读取格子(状态.当前方块)) {
    if (行号 < 0 || 行号 >= 行) continue;
    绘制方块格(环境, 环境.主题.方块[当前类型], 棋盘左 + 列号 * 格, 棋盘上 + 行号 * 格, 格);
  }
}


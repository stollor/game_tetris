export interface 提示视图 {
  /** 技巧/连击反馈（含换行），比例 1→0。 */
  技巧: { 文本: string; 比例: number } | null;
  /** 成就解锁提示，比例 1→0。 */
  成就: { 文本: string; 比例: number } | null;
  /** 马拉松目标达成提示的剩余比例。 */
  目标: number | null;
  /** 暂停时显示的提示按钮（暂停面板）。 */
  暂停: boolean;
}

function 绘制提示层(环境: 绘制环境, 提示: 提示视图): void {
  const 色 = 环境.主题.颜色;
  const 棋盘中心X = 布局.棋盘.左 + (布局.棋盘.列 * 布局.棋盘.格) / 2;
  const 棋盘中心Y = 布局.棋盘.上 + (布局.棋盘.行 * 布局.棋盘.格) / 2;
  if (提示.技巧 && 提示.技巧.比例 > 0) {
    const 行列表 = 提示.技巧.文本.split("\n");
    const 上 = 棋盘中心Y - 26 - (1 - 提示.技巧.比例) * 20;
    const 宽 = Math.max(...行列表.map((行) => 环境.字.中.测量(行))) + 24;
    const 高 = 行列表.length * 绘制文字行高(环境, "中") + 12;
    添加矩形(
      环境,
      { 左: 棋盘中心X - 宽 / 2, 上: 上 - 6, 宽, 高 },
      混合颜色(色.底色, 0x000000, 0.2),
      提示.技巧.比例 * 0.7,
    );
    for (const [序号, 行] of 行列表.entries()) {
      绘制文字(环境, "中", 行, 棋盘中心X, 上 + 序号 * 绘制文字行高(环境, "中"), {
        颜色: 序号 === 0 ? 色.强调 : 色.主字,
        透明度: 提示.技巧.比例,
        对齐: "中",
      });
    }
  }
  if (提示.成就 && 提示.成就.比例 > 0) {
    const 文本 = 提示.成就.文本;
    const 宽 = 环境.字.小.测量(文本) + 20;
    添加矩形(
      环境,
      { 左: 棋盘中心X - 宽 / 2, 上: 178, 宽, 高: 22 },
      混合颜色(色.面板, 0x000000, 0.15),
      提示.成就.比例 * 0.9,
    );
    绘制文字(环境, "小", 文本, 棋盘中心X, 182, {
      颜色: 色.强调,
      透明度: 提示.成就.比例,
      对齐: "中",
    });
  }
  if (提示.目标 !== null && 提示.目标 > 0) {
    const 脉冲 = 0.6 + 0.4 * Math.sin(提示.目标 * Math.PI * 8);
    绘制文字(环境, "大", "目标达成", 棋盘中心X, 棋盘中心Y - 60, {
      颜色: 色.强调,
      透明度: Math.min(1, 提示.目标 * 1.4) * 脉冲,
      对齐: "中",
    });
  }
}

function 绘制暂停层(环境: 绘制环境, 提示: 提示视图): void {
  if (!提示.暂停) return;
  const 色 = 环境.主题.颜色;
  添加矩形(环境, { 左: 0, 上: 0, 宽: 逻辑宽, 高: 逻辑高 }, 混合颜色(色.底色, 0x000000, 0.3), 0.72);
  const { 左, 上, 宽, 高 } = 布局.暂停面板;
  绘制面板(环境, { 左, 上, 宽, 高 }, 色.浮层, 色.强调);
  绘制文字(环境, "大", "已暂停", 左 + 宽 / 2, 上 + 28, { 颜色: 色.主字, 对齐: "中" });
  绘制文字(环境, "小", "按 P 或 Esc 继续", 左 + 宽 / 2, 上 + 64, {
    颜色: 色.次字,
    对齐: "中",
  });
  for (const 按钮 of 暂停按钮列表) 绘制按钮(环境, 按钮.矩形, 按钮.标签, true);
}


/** 对局页绘制：背景之上的 HUD、棋盘、当前方块/幽灵、提示层与暂停层。只写四边形，不碰渲染器。 */

export interface 绘制环境 {
  合批: 图元合批;
  字: 字形资源;
  字号: { 小: number; 中: number; 大: number };
  /** 纯色白块紫外线，来自任一文字图集。 */
  纯色紫外线: 紫外线矩形;
  主题: 游戏主题;
}

export type 字档 = "小" | "中" | "大";

export interface 文字选项 {
  颜色: number;
  透明度?: number;
  对齐?: "左" | "中" | "右";
}

export function 绘制文字(
  环境: 绘制环境,
  档: 字档,
  文本: string,
  左: number,
  上: number,
  选项: 文字选项,
): number {
  const 图集 = 环境.字[档];
  if (选项.对齐 === "中") {
    const 宽 = 图集.测量(文本);
    return 绘制文字(环境, 档, 文本, 左 - 宽 / 2, 上, { ...选项, 对齐: "左" });
  }
  if (选项.对齐 === "右") {
    const 宽 = 图集.测量(文本);
    return 绘制文字(环境, 档, 文本, 左 - 宽, 上, { ...选项, 对齐: "左" });
  }
  return 图集.绘制(环境.合批, 文本, {
    左,
    上,
    颜色: 十六进制颜色(选项.颜色, 选项.透明度 ?? 1),
    纹理序号: 字体纹理序号[档],
  }).宽;
}

export function 绘制文字行高(环境: 绘制环境, 档: 字档): number {
  return 环境.字[档].读取行高();
}

export function 添加矩形(环境: 绘制环境, 矩形: 矩形, 颜色: number, 透明度 = 1, 叠加 = false): void {
  if (矩形.宽 <= 0 || 矩形.高 <= 0) return;
  环境.合批.添加({
    左: 矩形.左,
    上: 矩形.上,
    宽: 矩形.宽,
    高: 矩形.高,
    紫外线: 环境.纯色紫外线,
    颜色: 十六进制颜色(颜色, 透明度),
    混合: 叠加 ? "叠加" : "普通",
  });
}

/** 面板：外描边 + 内填充，用两层矩形近似描边。 */
export function 绘制面板(环境: 绘制环境, 矩形: 矩形, 填充: number, 描边: number, 透明度 = 1): void {
  添加矩形(环境, 矩形, 描边, 透明度);
  const 边 = 1.5;
  添加矩形(
    环境,
    { 左: 矩形.左 + 边, 上: 矩形.上 + 边, 宽: 矩形.宽 - 边 * 2, 高: 矩形.高 - 边 * 2 },
    填充,
    透明度,
  );
}

/** 按钮：面板 + 居中标签；禁用态降低对比。 */
export function 绘制按钮(
  环境: 绘制环境,
  矩形: 矩形,
  标签: string,
  可用: boolean,
  高亮 = false,
): void {
  const 色 = 环境.主题.颜色;
  绘制面板(环境, 矩形, 高亮 ? 色.浮层 : 色.面板, 可用 ? 色.描边 : 色.暗字, 可用 ? 1 : 0.6);
  绘制文字(
    环境,
    "中",
    标签,
    矩形.左 + 矩形.宽 / 2,
    矩形.上 + (矩形.高 - 绘制文字行高(环境, "中")) / 2,
    {
      颜色: 可用 ? 色.主字 : 色.暗字,
      对齐: "中",
    },
  );
}

const 方块高光比例 = 0.2;
const 方块暗边比例 = 0.12;

/** 方块格：底色 + 顶部高光 + 底部暗边 + 细描边，和 Phaser 版的宝石质感近似。 */
export function 绘制方块格(
  环境: 绘制环境,
  类型颜色: number,
  左: number,
  上: number,
  尺寸: number,
  透明度 = 1,
): void {
  if (透明度 <= 0) return;
  const 内缩 = Math.max(1, 尺寸 * 0.05);
  const 内左 = 左 + 内缩;
  const 内上 = 上 + 内缩;
  const 内尺寸 = Math.max(1, 尺寸 - 内缩 * 2);
  const 高光高 = Math.max(2, 内尺寸 * 方块高光比例);
  const 暗边高 = Math.max(2, 内尺寸 * 方块暗边比例);
  添加矩形(环境, { 左, 上, 宽: 尺寸, 高: 尺寸 }, 混合颜色(类型颜色, 0x000000, 0.55), 透明度);
  添加矩形(环境, { 左: 内左, 上: 内上, 宽: 内尺寸, 高: 内尺寸 }, 类型颜色, 透明度);
  添加矩形(
    环境,
    { 左: 内左, 上: 内上, 宽: 内尺寸, 高: 高光高 },
    混合颜色(类型颜色, 0xffffff, 0.55),
    透明度 * 0.9,
  );
  添加矩形(
    环境,
    { 左: 内左, 上: 内上 + 内尺寸 - 暗边高, 宽: 内尺寸, 高: 暗边高 },
    混合颜色(类型颜色, 0x000000, 0.35),
    透明度 * 0.85,
  );
}


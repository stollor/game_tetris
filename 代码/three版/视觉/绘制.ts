function 绘制顶栏(环境: 绘制环境, 视图: 对局视图): void {
  const 色 = 环境.主题.颜色;
  const { 状态 } = 视图;
  添加矩形(
    环境,
    { 左: 0, 上: 0, 宽: 逻辑宽, 高: 布局.顶栏高度 },
    混合颜色(色.底色, 色.面板, 0.5),
    0.94,
  );
  添加矩形(环境, { 左: 0, 上: 布局.顶栏高度 - 2, 宽: 逻辑宽, 高: 2 }, 色.强调, 0.45);
  绘制按钮(环境, 离开按钮, "‹ 离开", true);
  绘制按钮(环境, 暂停按钮, 视图.暂停 ? "继续" : "暂停", true, 视图.暂停);
  绘制文字(环境, "中", 视图.模式文字, 逻辑宽 / 2, 6, { 颜色: 色.主字, 对齐: "中" });
  绘制文字(环境, "小", 视图.计时文案, 逻辑宽 / 2, 34, { 颜色: 色.次字, 对齐: "中" });
  const 数值 = [String(状态.分数), String(状态.消行数), String(状态.等级)];
  for (const [序号, 列] of 统计列.entries()) {
    绘制文字(环境, "小", 序号 === 0 ? "分数" : 序号 === 1 ? "消行" : "等级", 列.左, 54, {
      颜色: 色.次字,
    });
    绘制文字(环境, "大", 数值[序号] ?? "0", 列.左, 66, { 颜色: 序号 === 2 ? 色.强调 : 色.主字 });
  }
  if (状态.连击 >= 2) {
    绘制文字(环境, "小", `连击 ×${状态.连击}`, 逻辑宽 - 20, 96, { 颜色: 色.强调, 对齐: "右" });
  }
}

function 绘制预览区(环境: 绘制环境, 视图: 对局视图): void {
  const 色 = 环境.主题.颜色;
  const { 状态 } = 视图;
  const { 上, 暂存左, 下一个左, 下一个间距, 下一个数量, 宽, 高 } = 布局.预览;
  绘制文字(环境, "小", "暂存", 暂存左, 上 - 2, { 颜色: 色.次字 });
  const 暂存矩形: 矩形 = { 左: 暂存左, 上, 宽, 高 };
  绘制面板(环境, 暂存矩形, 色.面板, 状态.本块已暂存 ? 色.暗字 : 色.描边);
  if (状态.暂存方块) {
    绘制形状(环境, 状态.暂存方块, 暂存矩形, 状态.本块已暂存 ? 0.45 : 0.95);
  } else {
    绘制文字(环境, "小", "空", 暂存矩形.左 + 暂存矩形.宽 / 2, 暂存矩形.上 + 14, {
      颜色: 色.暗字,
      对齐: "中",
    });
  }
  绘制文字(环境, "小", "下一个", 下一个左, 上 - 2, { 颜色: 色.次字 });
  const 队列 = [状态.下一个方块, ...状态.后续方块].slice(0, 下一个数量);
  for (let i = 0; i < 下一个数量; i++) {
    const 矩形: 矩形 = { 左: 下一个左 + i * 下一个间距, 上, 宽, 高 };
    绘制面板(环境, 矩形, 色.面板, i === 0 ? 色.强调 : 色.描边, i === 0 ? 1 : 0.75);
    const 类型 = 队列[i];
    if (类型) 绘制形状(环境, 类型, 矩形, i === 0 ? 0.95 : 0.7);
  }
}

/** 在矩形内居中画一个方块类型（预览/暂存栏）。 */
function 绘制形状(环境: 绘制环境, 类型: 方块类型, 矩形: 矩形, 透明度: number): void {
  const 格子 = 预览形状(类型);
  const 列数 = Math.max(...格子.map(([列]) => 列)) + 1;
  const 行数 = Math.max(...格子.map(([, 行]) => 行)) + 1;
  const 格 = Math.max(
    7,
    Math.min(布局.预览.格, Math.min(矩形.宽 / (列数 + 1), 矩形.高 / (行数 + 1))),
  );
  const 左 = 矩形.左 + (矩形.宽 - 列数 * 格) / 2;
  const 上 = 矩形.上 + (矩形.高 - 行数 * 格) / 2;
  for (const [列, 行] of 格子) {
    绘制方块格(环境, 环境.主题.方块[类型], 左 + 列 * 格, 上 + 行 * 格, 格, 透明度);
  }
}

/** 出生形状平移到左上角：与规则层的 预览格子 保持一致，避免渲染依赖状态快照。 */
function 预览形状(类型: 方块类型): [number, number][] {
  const 形状: Record<string, [number, number][]> = {
    I: [
      [0, 0],
      [1, 0],
      [2, 0],
      [3, 0],
    ],
    O: [
      [0, 0],
      [1, 0],
      [0, 1],
      [1, 1],
    ],
    T: [
      [1, 0],
      [0, 1],
      [1, 1],
      [2, 1],
    ],
    S: [
      [1, 0],
      [2, 0],
      [0, 1],
      [1, 1],
    ],
    Z: [
      [0, 0],
      [1, 0],
      [1, 1],
      [2, 1],
    ],
    J: [
      [0, 0],
      [0, 1],
      [1, 1],
      [2, 1],
    ],
    L: [
      [2, 0],
      [0, 1],
      [1, 1],
      [2, 1],
    ],
  };
  return 形状[类型] ?? 形状.I ?? [];
}


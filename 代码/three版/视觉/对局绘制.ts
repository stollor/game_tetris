/** 对局界面用到的语义色（全部来自共享主题配方）。 */
type 界面色 = ReturnType<typeof 读取对局界面色>;

/**
 * 按共享文字样式画文字。Phaser 侧同一份样式用于 Text 的 fontFamily/fontSize/fontStyle/
 * letterSpacing，这里交给画笔的文字服务烘焙同一套字体图集。
 */
function 绘制样式文字(
  环境: 绘制环境,
  样式: 文字样式,
  文本: string,
  x: number,
  y: number,
  锚点: 文字锚点 = "左上",
  透明度 = 1,
): { 宽: number; 高: number } {
  const 半透明 = 透明度 < 1;
  if (半透明) {
    环境.图形.save();
    环境.图形.setAlpha(透明度);
  }
  const 行高 = 环境.画笔.测量文字("字", 样式).高;
  const 尺寸 = 环境.画笔.绘制文字({
    文案: 文本,
    样式,
    锚点,
    x,
    y: y - 文字对齐修正(样式.字号, 锚点, 行高),
  });
  if (半透明) 环境.图形.restore();
  return 尺寸;
}

/** 测量共享文字样式的排版尺寸。 */
function 测量样式文字(环境: 绘制环境, 样式: 文字样式, 文本: string) {
  return 环境.画笔.测量文字(文本, 样式);
}

/** 玻璃按钮底板 + 居中标签：按钮视觉由共享配方给出（框架 界面按钮 同算法）。 */
function 绘制按钮视觉(
  上下文: 绘图上下文,
  矩形: 矩形,
  标签: string,
  视觉: 对局按钮视觉,
  文字样式: 文字样式,
): void {
  const { 环境, 图形 } = 上下文;
  绘制玻璃按钮底板(图形, 矩形.左 + 矩形.宽 / 2, 矩形.上 + 矩形.高 / 2, 矩形.宽, 矩形.高, {
    填色: 视觉.填色,
    边框色: 视觉.边框色,
    强调色: 视觉.边框色,
    透明度: 视觉.透明度,
    边透明度: 视觉.边透明度,
  });
  绘制样式文字(环境, 文字样式, 标签, 矩形.左 + 矩形.宽 / 2, 矩形.上 + 矩形.高 / 2, "中中");
}

/** 中心 + 宽高的按钮几何转矩形。 */
function 转矩形(中心按钮: { 中心X: number; 中心Y: number; 宽: number; 高: number }): 矩形 {
  return {
    左: 中心按钮.中心X - 中心按钮.宽 / 2,
    上: 中心按钮.中心Y - 中心按钮.高 / 2,
    宽: 中心按钮.宽,
    高: 中心按钮.高,
  };
}

/** 顶栏：离开 / 模式标题 / 暂停 + 等级·分数·消行统计条。 */
function 绘制顶栏(上下文: 绘图上下文, 输入: 对局绘制输入, 色: 界面色): void {
  const { 环境, 图形, 布局 } = 上下文;
  const 角钮 = 读取角钮视觉(true);
  const 角钮样式 = 读取按钮标签样式(角钮.字号, 角钮.文字色);
  绘制按钮视觉(上下文, 转矩形(布局.离开按钮), "‹ 离开", 角钮, 角钮样式);
  // Phaser 暂停按钮在结束态隐藏；暂停态标签变「继续」。
  if (输入.视图.状态.阶段 !== "结束")
    绘制按钮视觉(上下文, 转矩形(布局.暂停按钮), 输入.视图.暂停 ? "继续" : "暂停", 角钮, 角钮样式);
  // 标题：Phaser 标题 Text 带 backgroundColor(主面板底) + padding(8,3)，这里画同尺寸色块 + 居中文字。
  const 标题样式 = 读取对局文字样式("顶栏标题", { 字号: 布局.标题.字号 });
  const 标题尺寸 = 测量样式文字(环境, 标题样式, 输入.模式名);
  添加矩形(
    环境,
    {
      左: 布局.标题.中心X - 标题尺寸.宽 / 2 - 8,
      上: 布局.标题.中心Y - 标题尺寸.高 / 2 - 3,
      宽: 标题尺寸.宽 + 16,
      高: 标题尺寸.高 + 6,
    },
    色.面板,
    1,
  );
  绘制样式文字(环境, 标题样式, 输入.模式名, 布局.标题.中心X, 布局.标题.中心Y, "中中");

  // 统计条：玻璃面板 + 三列标签/数值 + 分隔线（Phaser 界面数值面板 同算法）。
  const 信息 = 布局.信息栏;
  const 内部 = 计算信息栏内部(信息);
  const 左 = 信息.中心X - 信息.宽 / 2;
  const 上 = 信息.中心Y - 信息.高 / 2;
  绘制玻璃面板基底(图形, 左, 上, 信息.宽, 信息.高, {
    圆角: 12,
    填色: 色.面板,
    透明度: 0.92,
    边色: 色.按钮次要.描边,
    边透明度: 0.55,
    高光: true,
  });
  for (const 分隔X of 内部.分隔X) {
    添加矩形(环境, { 左: 分隔X, 上: 内部.分隔顶, 宽: 1, 高: 内部.分隔高 }, 色.信息分隔亮, 0.35);
    添加矩形(环境, { 左: 分隔X + 1, 上: 内部.分隔顶, 宽: 1, 高: 内部.分隔高 }, 色.信息分隔暗, 0.28);
  }
  const 统计 = [
    { 标签: "等级", 值: String(输入.视图.状态.等级), 颜色: 色.强调 },
    {
      标签: "分数",
      值: String(输入.视图.状态.分数).padStart(6, "0"),
      颜色: 色.正文,
    },
    { 标签: "消行", 值: String(输入.视图.状态.消行数), 颜色: 色.强调 },
  ];
  统计.forEach((项, 索引) => {
    const 中心X = 内部.列中心[索引] ?? 信息.中心X;
    绘制样式文字(环境, 读取对局文字样式("信息标签"), 项.标签, 中心X, 内部.标签Y, "中上");
    const 基础样式 = 读取对局文字样式("信息数值", { 颜色: 项.颜色 });
    const 测量宽 = 测量样式文字(环境, 基础样式, 项.值).宽;
    const 字号 = 适配信息数值字号(内部.数值字号, 测量宽, 内部.列宽);
    const 样式 = 字号 === 内部.数值字号 ? 基础样式 : { ...基础样式, 字号 };
    绘制样式文字(环境, 样式, 项.值, 中心X, 内部.数值Y, "中上");
  });
}

/** 棋盘：共享框/网格 + 固定块 + 幽灵 + 当前方块（可带震屏偏移）。 */
function 绘制棋盘(上下文: 绘图上下文, 输入: 对局绘制输入, 色: 界面色): void {
  const { 图形, 布局 } = 上下文;
  const { 左, 上, 宽, 高, 格 } = {
    左: 布局.棋盘.左,
    上: 布局.棋盘.上,
    宽: 布局.棋盘.宽,
    高: 布局.棋盘.高,
    格: 布局.格子大小,
  };
  const 棋盘左 = 左 + 输入.偏移X;
  const 棋盘上 = 上 + 输入.偏移Y;
  绘制棋盘外框(图形, {
    左: 棋盘左,
    上: 棋盘上,
    宽,
    高,
    格子: 格,
    透明度: 1,
    背景色: 游戏外观.棋盘.背景色,
    边框色: 游戏外观.棋盘.边框色,
  });
  if (输入.视图.显示网格) {
    图形.save();
    图形.translateCanvas(棋盘左, 棋盘上);
    绘制棋盘网格(图形, {
      宽,
      高,
      格子: 格,
      列数: 布局.棋盘.列,
      行数: 布局.棋盘.行,
      网格色: 色.网格线,
    });
    图形.restore();
  }
  const 状态 = 输入.视图.状态;
  const 方案 = 输入.视图.方块外观;
  // Phaser 棋盘预制体把格子贴到 +1.5 的像素对齐位置。
  const 内缩 = 1.5;
  for (let 行 = 0; 行 < 布局.棋盘.行; 行 += 1) {
    const 数据 = 状态.棋盘[行 + 2];
    if (!数据) continue;
    for (let 列 = 0; 列 < 布局.棋盘.列; 列 += 1) {
      const 类型 = 数据[列];
      if (!类型) continue;
      绘制方块单元(图形, 棋盘左 + 列 * 格 + 内缩, 棋盘上 + 行 * 格 + 内缩, {
        方案,
        色值: 方案.颜色[类型],
        格子: 格,
        圆角比例: 0.16,
      });
    }
  }
  const 幽灵透明度 = Math.max(0, Math.min(1, 输入.视图.落点影透明度 / 100));
  const 当前类型 = 状态.当前方块.类型;
  for (const [列, 行] of 输入.视图.影子) {
    if (行 < 0 || 行 >= 布局.棋盘.行 || 状态.棋盘[行 + 2]?.[列]) continue;
    绘制方块单元(图形, 棋盘左 + 列 * 格 + 内缩, 棋盘上 + 行 * 格 + 内缩, {
      方案,
      色值: 方案.颜色[当前类型],
      格子: 格,
      透明度: 幽灵透明度,
      圆角比例: 0.16,
      幽灵: true,
    });
  }
  for (const [列, 行] of 读取格子(状态.当前方块)) {
    if (行 < 0 || 行 >= 布局.棋盘.行) continue;
    绘制方块单元(图形, 棋盘左 + 列 * 格 + 内缩, 棋盘上 + 行 * 格 + 内缩, {
      方案,
      色值: 方案.颜色[当前类型],
      格子: 格,
      圆角比例: 0.16,
    });
  }
}

/** 出生形状（相对包围盒左上角）与 Phaser 下一个方块栏.出生格 一致。 */
function 预览形状(类型: 方块类型): [number, number][] {
  const 形状: Record<string, [number, number][]> = {
    I: [
      [0, 0],
      [1, 0],
      [2, 0],
      [3, 0],
    ],
    O: [
      [0, 0],
      [1, 0],
      [0, 1],
      [1, 1],
    ],
    T: [
      [1, 0],
      [0, 1],
      [1, 1],
      [2, 1],
    ],
    S: [
      [1, 0],
      [2, 0],
      [0, 1],
      [1, 1],
    ],
    Z: [
      [0, 0],
      [1, 0],
      [1, 1],
      [2, 1],
    ],
    J: [
      [0, 0],
      [0, 1],
      [1, 1],
      [2, 1],
    ],
    L: [
      [2, 0],
      [0, 1],
      [1, 1],
      [2, 1],
    ],
  };
  return 形状[类型] ?? 形状.I ?? [];
}

/** 在卡片/暂存格内居中画一个方块：格尺寸与居中口径来自共享布局。 */
function 绘制居中方块(
  上下文: 绘图上下文,
  方案: 方块外观方案,
  类型: 方块类型,
  区域: 矩形,
  格: number,
  透明度: number,
  圆角比例: number,
  /** 首卡辉光：与 Phaser 预览栏同一叠加层。 */
  辉光: boolean,
): void {
  const { 图形 } = 上下文;
  const 点集 = 预览形状(类型);
  const 最小列 = Math.min(...点集.map(([列]) => 列));
  const 最大列 = Math.max(...点集.map(([列]) => 列));
  const 最小行 = Math.min(...点集.map(([, 行]) => 行));
  const 最大行 = Math.max(...点集.map(([, 行]) => 行));
  const 方块宽 = (最大列 - 最小列 + 1) * 格;
  const 方块高 = (最大行 - 最小行 + 1) * 格;
  const 原点X = 区域.左 + (区域.宽 - 方块宽) / 2;
  const 原点Y = 区域.上 + (区域.高 - 方块高) / 2;
  for (const [列, 行] of 点集) {
    const x = 原点X + (列 - 最小列) * 格;
    const y = 原点Y + (行 - 最小行) * 格;
    const 外观 = {
      方案,
      色值: 方案.颜色[类型],
      格子: 格,
      透明度,
      圆角比例,
    };
    绘制方块单元(图形, x, y, 外观);
    if (!辉光) continue;
    // Phaser 预览栏首卡在 ADD 混合层再画一次辉光。
    图形.save();
    图形.setBlendMode(1);
    绘制方块单元辉光(图形, x, y, 外观);
    图形.restore();
  }
}

/** 右侧栏（竖屏）：暂存 + 下一个×3 + 最佳纪录 + 硬降。 */
function 绘制竖屏侧栏(上下文: 绘图上下文, 输入: 对局绘制输入, 色: 界面色): void {
  const { 环境, 图形, 布局 } = 上下文;
  const 侧栏 = 布局.侧栏;
  if (!侧栏) return;
  const 状态 = 输入.视图.状态;
  const 方案 = 输入.视图.方块外观;
  绘制霓虹侧栏(图形, {
    左: 侧栏.左,
    顶: 侧栏.顶,
    宽: 侧栏.宽,
    高: 侧栏.高,
    竖屏: true,
    紧凑: false,
  });
  // 暂存格：与 Phaser 暂存方块栏 一致（次要按钮底色 + 文字强调描边）。
  const 暂存中心X = 侧栏.暂存.左 + 侧栏.暂存.宽 / 2;
  绘制霓虹按钮(图形, 暂存中心X, 侧栏.暂存.上 + 侧栏.暂存.高 / 2, 侧栏.暂存.宽, 侧栏.暂存.高, {
    面板色: 颜色字符串(色.按钮次要.面板),
    强调色: 颜色字符串(色.强调),
    面板透明度: 色.角钮面板透明度,
    边框透明度: 色.角钮边框透明度,
    可用: !状态.本块已暂存 && 状态.阶段 === "进行中",
  });
  if (状态.暂存方块) {
    绘制居中方块(
      上下文,
      方案,
      状态.暂存方块,
      { 左: 暂存中心X, 上: 侧栏.暂存.上 + 侧栏.暂存.高 / 2 - 12, 宽: 0, 高: 0 },
      0,
      状态.本块已暂存 ? 0.55 : 1,
      0.16,
      false,
    );
  } else {
    图形
      .lineStyle(1, 色.面板描边, 0.6)
      .strokeRoundedRect(暂存中心X - 20, 侧栏.暂存.上 + 10, 40, 侧栏.暂存.高 - 36, 4);
  }
  const 暂存可用 = !状态.本块已暂存;
  绘制样式文字(
    环境,
    读取对局文字样式("暂存标签", { 颜色: 暂存可用 ? 色.主字 : 色.暗字 }),
    暂存可用 ? "暂存 C / 长按↑" : "暂存 · 落块后可换",
    暂存中心X,
    侧栏.暂存.上 + 侧栏.暂存.高 / 2 + 23,
    "中中",
  );
  绘制样式文字(
    环境,
    读取对局文字样式("预览标题"),
    "下一个",
    侧栏.下一个标签.左,
    侧栏.下一个标签.上,
  );
  const 队列 = [状态.下一个方块, ...状态.后续方块].slice(0, 3);
  const 卡格 = 侧栏.预览栏.卡格;
  侧栏.下一步卡.forEach((卡, 索引) => {
    const 类型 = 队列[索引];
    const 首位 = 索引 === 0;
    const 方块色 = 类型 ? 方案.颜色[类型] : undefined;
    绘制预览卡(图形, {
      左: 卡.左,
      上: 卡.上,
      宽: 卡.宽,
      高: 卡.高,
      圆角: 12,
      填色: 色.次级面板,
      边色: 首位 && 方块色 ? 亮色(方块色, 0.35) : 色.分组线,
      边透明度: 首位 ? 0.55 : 0.38,
      强调色: 首位 ? 方块色 : undefined,
      高光: true,
      首位: false,
    });
    if (类型) 绘制居中方块(上下文, 方案, 类型, 卡, 卡格, 1, 0.16, 首位);
  });
  绘制样式文字(
    环境,
    读取对局文字样式("纪录标签"),
    "最佳纪录",
    侧栏.最佳纪录.标签X,
    侧栏.最佳纪录.标签Y,
    "中上",
  );
  if (!输入.提示.暂停)
    绘制样式文字(
      环境,
      读取对局文字样式("纪录值"),
      输入.最佳纪录,
      侧栏.最佳纪录.值X,
      侧栏.最佳纪录.值Y,
      "中上",
    );
  绘制按钮视觉(
    上下文,
    转矩形(侧栏.硬降),
    "↓ 硬降",
    读取角钮视觉(状态.阶段 === "进行中"),
    读取按钮标签样式(读取角钮视觉().字号, 状态.阶段 === "进行中" ? 色.主字 : 色.暗字),
  );
}

/** 桌面附属：说明卡 / 暂存 / 下一个×3 / 最佳纪录。 */
function 绘制桌面附属(上下文: 绘图上下文, 输入: 对局绘制输入, 色: 界面色): void {
  const { 环境, 图形, 布局 } = 上下文;
  const 定位 = 计算对局附属布局(布局);
  const 状态 = 输入.视图.状态;
  const 方案 = 输入.视图.方块外观;
  const 暂停中 = 输入.提示.暂停;
  // 侧栏玻璃底板（Phaser 绘制装饰 的桌面分支；暂停时被面板整体遮住，照画不影响）。
  const 预览面板 = 定位.预览面板;
  绘制霓虹侧栏(图形, {
    左: 预览面板.左,
    顶: 预览面板.上,
    宽: 预览面板.宽,
    高: 预览面板.高,
    竖屏: false,
    紧凑: false,
  });

  // 操作说明卡：Phaser 绘制装饰 只按布局条件画底板，文字再单独按可见性隐藏。
  const 说明面板 = 定位.说明.面板;
  if (布局.操作说明卡.底板可见)
    绘制霓虹玻璃(图形, 说明面板.左, 说明面板.上, 说明面板.宽, 说明面板.高, {
      填色: 色.面板,
      透明度: 0.98,
      高光: false,
    });
  if (布局.操作说明卡.可见) {
    const 说明 = 定位.说明;
    绘制样式文字(环境, 读取对局文字样式("说明标题"), 输入.文案.操作标题, 说明.标题.x, 说明.标题.y);
    [
      输入.文案.操作移动,
      输入.文案.操作旋转,
      输入.文案.操作半转,
      输入.文案.操作软降,
      输入.文案.操作硬降,
      输入.文案.操作暂停,
    ].forEach((行, 索引) => {
      const 点 = 说明.行[索引];
      if (点) 绘制样式文字(环境, 读取对局文字样式("说明正文"), 行, 点.x, 点.y);
    });
    绘制样式文字(
      环境,
      读取对局文字样式("说明提示"),
      输入.文案.快速移动提示,
      说明.提示.x,
      说明.提示.y,
    );
  }

  // 最佳纪录：Phaser 霓虹纪录页脚 桌面左对齐在侧栏 X + 16。
  绘制样式文字(
    环境,
    读取对局文字样式("纪录标签"),
    "最佳纪录",
    定位.最佳纪录.左,
    定位.最佳纪录.标签Y,
  );
  if (!暂停中)
    绘制样式文字(
      环境,
      读取对局文字样式("纪录值"),
      输入.最佳纪录,
      定位.最佳纪录.左,
      定位.最佳纪录.值Y,
    );

  // 下一个标题（暂停时被暂停面板整块遮住；同层文字晚于形状绘制，故直接跳过）。
  if (!暂停中)
    绘制样式文字(
      环境,
      读取对局文字样式("预览标题"),
      "下一个",
      定位.下一个标签.左,
      定位.下一个标签.上,
    );
  const 队列 = [状态.下一个方块, ...状态.后续方块].slice(0, 3);
  定位.下一步卡.forEach((卡, 索引) => {
    const 类型 = 队列[索引];
    const 首位 = 索引 === 0;
    const 方块色 = 类型 ? 方案.颜色[类型] : undefined;
    绘制预览卡(图形, {
      左: 卡.左,
      上: 卡.上,
      宽: 卡.宽,
      高: 卡.高,
      圆角: 12,
      填色: 色.次级面板,
      边色: 首位 && 方块色 ? 亮色(方块色, 0.35) : 色.分组线,
      边透明度: 首位 ? 0.55 : 0.38,
      强调色: 首位 ? 方块色 : undefined,
      高光: false,
      首位,
    });
    if (类型) 绘制居中方块(上下文, 方案, 类型, 卡, 定位.预览格, 1, 0.14, 首位 && !暂停中);
  });

  // 暂存格：Phaser 暂存方块栏（桌面宽 200×88，标签 11px Courier，空位 40×52 描边框）。
  if (状态.阶段 === "进行中") {
    const 暂存 = 定位.暂存;
    绘制按钮视觉(上下文, 暂存, "", 读取角钮视觉(true), 读取按钮标签样式(11, 色.主字));
    if (状态.暂存方块)
      绘制居中方块(
        上下文,
        方案,
        状态.暂存方块,
        { 左: 暂存.左 + 暂存.宽 / 2, 上: 暂存.上 + 暂存.高 / 2 - 12, 宽: 0, 高: 0 },
        定位.暂存格,
        状态.本块已暂存 ? 0.55 : 1,
        0.16,
        false,
      );
    else
      图形
        .lineStyle(1, 色.面板描边, 0.6)
        .strokeRoundedRect(暂存.左 + 暂存.宽 / 2 - 20, 暂存.上 + 10, 40, 暂存.高 - 36, 4);
    绘制样式文字(
      环境,
      读取对局文字样式("暂存标签", { 颜色: 状态.本块已暂存 ? 色.暗字 : 色.主字 }),
      状态.本块已暂存 ? "暂存 · 落块后可换" : "暂存 C / 长按↑",
      暂存.左 + 暂存.宽 / 2,
      暂存.上 + 暂存.高 - 13,
      "中中",
    );
  }
}

/** 暂停时状态行（Phaser 状态文字：按 P 或 Esc 继续 + 主面板底衬）。 */
function 绘制状态文字(上下文: 绘图上下文, 输入: 对局绘制输入, 色: 界面色): void {
  const { 环境, 布局 } = 上下文;
  if (!输入.提示.暂停) return;
  // 状态行画在暂停遮罩之下：用压暗后的颜色重画，等价 Phaser「先文字、后遮罩」的像素结果。
  const 基础样式 = 读取对局文字样式("状态文字");
  const 样式 = {
    ...基础样式,
    颜色: 遮罩压暗(解析颜色数值(基础样式.颜色)),
    ...(基础样式.描边
      ? { 描边: { ...基础样式.描边, 颜色: 遮罩压暗(解析颜色数值(基础样式.描边.颜色)) } }
      : {}),
  };
  const 尺寸 = 测量样式文字(环境, 样式, "按 P 或 Esc 继续");
  // Phaser 状态文字高度 = 字号 + 描边（不自带行高），底衬按它外扩 14/6。
  const 底衬宽 = 尺寸.宽 + 28;
  const 底衬高 = 样式.字号 + 1 + 12;
  const 中心X = 布局.状态文字.中心X;
  const 上 = 布局.状态文字.下;
  添加矩形(
    环境,
    {
      左: 中心X - 底衬宽 / 2,
      上: 上 - 底衬高 / 2,
      宽: 底衬宽,
      高: 底衬高,
    },
    色.面板,
    0.95,
  );
  上下文.图形
    .lineStyle(1, 色.分组线, 0.35)
    .strokeRoundedRect(中心X - 底衬宽 / 2, 上 - 底衬高 / 2, 底衬宽, 底衬高, 10);
  绘制样式文字(环境, 样式, "按 P 或 Esc 继续", 中心X, 上, "中中");
}

/** 暂停层：遮罩 + 玻璃面板 + 强调条 + 标题/说明 + 4 个按钮（框架 界面暂停菜单 同参数）。 */
function 绘制暂停层(上下文: 绘图上下文, 输入: 对局绘制输入, 色: 界面色): void {
  if (!输入.提示.暂停) return;
  const { 环境, 图形, 布局 } = 上下文;
  const 面板 = 布局.暂停面板;
  const 比例 = 面板.比例;
  const 宽 = 面板.宽 * 比例;
  const 高 = 面板.高 * 比例;
  const 左 = 面板.中心X - 宽 / 2;
  const 上 = 面板.中心Y - 高 / 2;
  添加矩形(环境, { 左: 0, 上: 0, 宽: 布局.视口宽, 高: 布局.视口高 }, 色.遮罩, 色.遮罩透明度);
  绘制玻璃面板基底(图形, 左, 上, 宽, 高, {
    圆角: 24,
    填色: 色.面板,
    透明度: 0.98,
    边色: 色.面板描边,
    边透明度: 0.9,
    强调色: 色.强调,
    高光: true,
  });
  // 顶部强调条（框架 界面暂停菜单.布局 的强调条几何）。
  添加矩形(环境, { 左: 面板.中心X - 60, 上: 上 + 2, 宽: 120, 高: 4 }, 色.强调, 0.85);
  绘制样式文字(环境, 读取对局文字样式("暂停标题"), "已暂停", 面板.中心X, 上 + 54 - 2, "中中");
  绘制样式文字(环境, 读取对局文字样式("暂停说明"), "当前进度已保留", 面板.中心X, 上 + 96, "中中");
  for (const 按钮 of 面板.按钮) {
    const 视觉 = 读取暂停按钮视觉(按钮.已选);
    绘制按钮视觉(上下文, 按钮.矩形, 按钮.标签, 视觉, 读取按钮标签样式(视觉.字号, 视觉.文字色));
  }
}

/** 暂停时场景层提示（Phaser 在结算几何位置画「已暂停」）：必须画在遮罩之前的内容层。 */
export function 绘制暂停提示文字(环境: 绘制环境, 布局: 对局布局数据): void {
  const 结算几何 = 计算霓虹结算布局(布局.视口宽, 布局.视口高).几何;
  绘制样式文字(
    环境,
    读取对局文字样式("提示标题"),
    "已暂停",
    结算几何.中心X,
    结算几何.顶 + 82 * 结算几何.比例,
    "中中",
  );
}

/** 底部 6 个触屏操作键（含多行提示）：GM 触屏操作区 的按钮视觉。 */
function 绘制操作区(上下文: 绘图上下文): void {
  const { 环境, 布局 } = 上下文;
  if (!布局.操作区.显示) return;
  const 视觉: 对局按钮视觉 = 读取触屏按钮视觉(布局.操作区.字号);
  for (const 键 of 布局.操作区.键) {
    const 矩形 = 转矩形(键);
    绘制玻璃按钮底板(上下文.图形, 键.中心X, 键.中心Y, 键.宽, 键.高, {
      填色: 视觉.填色,
      边框色: 视觉.边框色,
      强调色: 视觉.边框色,
      透明度: 视觉.透明度,
      边透明度: 视觉.边透明度,
    });
    const 行列表 = 键.标签.split("\n");
    const 样式 = 读取按钮标签样式(视觉.字号, 视觉.文字色);
    const 行高 = 测量样式文字(环境, 样式, "字").高;
    行列表.forEach((文本, 序号) => {
      绘制样式文字(
        环境,
        样式,
        文本,
        矩形.左 + 矩形.宽 / 2,
        矩形.上 + 矩形.高 / 2 - (行列表.length * 行高) / 2 + 序号 * 行高,
        "中上",
      );
    });
  }
}

/** 提示层：技巧/成就/目标达成（底衬沿用原实现，文字样式走共享配方）。 */
function 绘制提示层(上下文: 绘图上下文, 输入: 对局绘制输入, 色: 界面色): void {
  const { 环境, 布局 } = 上下文;
  const 中心X = 布局.提示文字.中心X;
  const 中心Y = 布局.提示文字.中心Y;
  if (输入.提示.技巧 && 输入.提示.技巧.比例 > 0) {
    const 行列表 = 输入.提示.技巧.文本.split("\n");
    const 样式 = 读取对局文字样式("说明正文", { 字号: 18, 颜色: 色.强调 });
    const 行高 = 测量样式文字(环境, 样式, "字").高;
    const 上 = 中心Y - 26 - (1 - 输入.提示.技巧.比例) * 20;
    const 宽 = Math.max(...行列表.map((行) => 测量样式文字(环境, 样式, 行).宽)) + 24;
    const 高 = 行列表.length * 行高 + 12;
    添加矩形(环境, { 左: 中心X - 宽 / 2, 上: 上 - 6, 宽, 高 }, 色.遮罩, 输入.提示.技巧.比例 * 0.7);
    for (const [序号, 行] of 行列表.entries())
      绘制样式文字(
        环境,
        { ...样式, 颜色: 序号 === 0 ? 色.强调 : 色.主字 },
        行,
        中心X,
        上 + 序号 * 行高,
        "中上",
        输入.提示.技巧.比例,
      );
  }
  if (输入.提示.成就 && 输入.提示.成就.比例 > 0) {
    const 文本 = 输入.提示.成就.文本;
    const 样式 = 读取对局文字样式("说明正文", { 颜色: 色.强调 });
    const 宽 = 测量样式文字(环境, 样式, 文本).宽 + 20;
    添加矩形(环境, { 左: 中心X - 宽 / 2, 上: 178, 宽, 高: 22 }, 色.面板, 输入.提示.成就.比例 * 0.9);
    绘制样式文字(环境, 样式, 文本, 中心X, 182, "中上", 输入.提示.成就.比例);
  }
  if (输入.提示.目标 !== null && 输入.提示.目标 > 0) {
    const 脉冲 = 0.6 + 0.4 * Math.sin(输入.提示.目标 * Math.PI * 8);
    const 样式 = 读取对局文字样式("说明标题", {
      字号: 布局.目标提示.字号,
      颜色: 色.强调,
    });
    绘制样式文字(
      环境,
      样式,
      "目标达成",
      布局.目标提示.中心X,
      布局.目标提示.中心Y,
      "中中",
      Math.min(1, 输入.提示.目标 * 1.4) * 脉冲,
    );
  }
}

/** 内容层：背景之上的对局本体（顶栏/棋盘/侧栏/操作区/状态文字）。 */
export function 绘制对局内容(环境: 绘制环境, 输入: 对局绘制输入): void {
  const 上下文: 绘图上下文 = { 环境, 图形: 环境.图形, 布局: 输入.布局 };
  const 色 = 读取对局界面色();
  绘制顶栏(上下文, 输入, 色);
  绘制棋盘(上下文, 输入, 色);
  if (输入.布局.侧栏) 绘制竖屏侧栏(上下文, 输入, 色);
  else 绘制桌面附属(上下文, 输入, 色);
  绘制操作区(上下文);
  绘制状态文字(上下文, 输入, 色);
}

/** 提示层：技巧/成就/目标达成，压在对局内容之上、特效应之下。 */
export function 绘制对局提示(环境: 绘制环境, 输入: 对局绘制输入): void {
  if (输入.提示.暂停) return;
  绘制提示层({ 环境, 图形: 环境.图形, 布局: 输入.布局 }, 输入, 读取对局界面色());
}

/** 覆盖层：暂停遮罩 + 面板（必须画在内容/提示/特效的所有图层之后）。 */
export function 绘制对局覆盖(环境: 绘制环境, 输入: 对局绘制输入): void {
  if (!输入.提示.暂停) return;
  绘制暂停层({ 环境, 图形: 环境.图形, 布局: 输入.布局 }, 输入, 读取对局界面色());
}

/** 兼容入口：按内容 → 提示 → 暂停覆盖的顺序一次画完（预览/旧调用方用）。 */
export function 绘制对局画面(环境: 绘制环境, 输入: 对局绘制输入): void {
  绘制对局内容(环境, 输入);
  绘制对局提示(环境, 输入);
  if (输入.提示.暂停) 绘制暂停提示文字(环境, 输入.布局);
  绘制对局覆盖(环境, 输入);
}

/** 操作键名称 → 虚拟键（命中注册与输入映射共用）。 */
export function 操作键虚拟键(键: 对局布局操作键): 虚拟键 {
  if (键.名称 === "左移") return "左";
  if (键.名称 === "右移") return "右";
  if (键.名称 === "软降") return "下";
  if (键.名称 === "硬降") return "硬降";
  if (键.名称 === "左转") return "左转";
  if (键.名称 === "右转") return "右转";
  return "旋转";
}

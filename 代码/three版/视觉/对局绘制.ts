/** 用画笔按档位样式测量文本宽度（与 绘制文字 的档位映射同源）。 */
function 测量文字宽度(环境: 绘制环境, 档: "小" | "中" | "大", 文本: string): number {
  return 环境.画笔.测量文字(文本, {
    字体: 游戏外观.字体.家族,
    字号: 档 === "小" ? 14 : 档 === "中" ? 18 : 24,
    字重: 档 === "大" ? "粗体" : "常规",
    颜色: 环境.主题.颜色.主字,
  }).宽;
}

/** 顶栏：离开 / 模式标题 / 暂停 + 等级·分数·消行统计条。 */
function 绘制顶栏(上下文: 绘图上下文, 输入: 对局绘制输入): void {
  const { 环境, 图形, 布局 } = 上下文;
  const 色 = 环境.主题.颜色;
  const 标题 = 输入.模式名;
  绘制按钮底板(上下文, 布局.离开按钮, "‹ 离开", true, false);
  绘制按钮底板(上下文, 布局.暂停按钮, 输入.视图.暂停 ? "继续" : "暂停", true, false);
  const 暂停 = 输入.提示.暂停;
  // Phaser 标题文字用「主面板底色 + padding」压在背景上：这里同色块 + 居中文字。
  const 标题宽 = 测量文字宽度(环境, "中", 标题);
  const 标题行高 = 绘制文字行高(环境, "中");
  添加矩形(
    环境,
    {
      左: 布局.标题.中心X - 标题宽 / 2 - 8,
      上: 布局.标题.中心Y - 标题行高 / 2 - 3,
      宽: 标题宽 + 16,
      高: 标题行高 + 6,
    },
    色.面板,
    1,
  );
  if (!暂停)
    绘制文字(环境, "中", 标题, 布局.标题.中心X, 布局.标题.中心Y - 标题行高 / 2, {
      颜色: 色.主字,
      对齐: "中",
    });
  // 统计条：玻璃面板 + 三列标签/数值 + 分隔线。
  const 信息 = 布局.信息栏;
  const 左 = 信息.中心X - 信息.宽 / 2;
  const 上 = 信息.中心Y - 信息.高 / 2;
  绘制玻璃面板基底(图形, 左, 上, 信息.宽, 信息.高, {
    圆角: 12,
    填色: 色.面板,
    透明度: 0.92,
    边色: 色.描边,
    边透明度: 0.55,
    高光: true,
  });
  for (let 索引 = 1; 索引 < 3; 索引 += 1) {
    const 分隔X = 左 + 信息.列宽 * 索引;
    添加矩形(环境, { 左: 分隔X, 上: 上 + 信息.高 * 0.2, 宽: 1, 高: 信息.高 * 0.6 }, 色.描边, 0.35);
    添加矩形(
      环境,
      { 左: 分隔X + 1, 上: 上 + 信息.高 * 0.2, 宽: 1, 高: 信息.高 * 0.6 },
      色.暗字,
      0.28,
    );
  }
  const 统计 = [
    { 标签: "等级", 值: String(输入.视图.状态.等级), 色: 色.强调 },
    { 标签: "分数", 值: String(输入.视图.状态.分数).padStart(6, "0"), 色: 色.主字 },
    { 标签: "消行", 值: String(输入.视图.状态.消行数), 色: 色.强调 },
  ];
  统计.forEach((项, 索引) => {
    const 中心X = 左 + 信息.列宽 * (索引 + 0.5);
    绘制文字(环境, "小", 项.标签, 中心X, 上 + 信息.高 * 0.12, { 颜色: 色.次字, 对齐: "中" });
    if (!暂停) 绘制文字(环境, "中", 项.值, 中心X, 上 + 信息.高 * 0.42, { 颜色: 项.色, 对齐: "中" });
  });
}

/** 按钮底板 + 居中（多行）标签：走共享霓虹按钮配方（与 Phaser 同一套状态/配色算法）。 */
function 绘制按钮底板(
  上下文: 绘图上下文,
  中心按钮: { 中心X: number; 中心Y: number; 宽: number; 高: number },
  标签: string,
  可用: boolean,
  高亮: boolean,
  触屏配色 = false,
  主要 = false,
): void {
  const { 环境, 图形 } = 上下文;
  const 色 = 环境.主题.颜色;
  const 选项 = {
    ...(触屏配色
      ? {
          面板色: 游戏外观.按钮.面板,
          边框色: 游戏外观.按钮.边框,
          强调色: 游戏外观.按钮.边框,
          面板透明度: 0.92,
          边框透明度: 0.55,
        }
      : {}),
    ...(主要 ? { 变体: "主要" as const, 强调色: 界面主题().文字.强调 } : {}),
    ...(高亮 ? { 已选: true } : {}),
  };
  绘制霓虹按钮(图形, 中心按钮.中心X, 中心按钮.中心Y, 中心按钮.宽, 中心按钮.高, {
    ...选项,
    可用,
  });
  const 文字色 = 解析颜色数值(读取霓虹按钮文字色({ ...选项, 可用 }));
  const 行 = 标签.split("\n");
  const 行高 = 绘制文字行高(环境, "小");
  行.forEach((文本, 序号) => {
    绘制文字(
      环境,
      "小",
      文本,
      中心按钮.中心X,
      中心按钮.中心Y - (行.length * 行高) / 2 + 序号 * 行高,
      { 颜色: 可用 ? 文字色 : 色.暗字, 对齐: "中" },
    );
  });
}

/** 棋盘：共享框/网格 + 固定块 + 幽灵 + 当前方块（可带震屏偏移）。 */
function 绘制棋盘(上下文: 绘图上下文, 输入: 对局绘制输入): void {
  const { 图形, 布局 } = 上下文;
  const { 左, 上, 宽, 高, 格 } = {
    左: 布局.棋盘.左,
    上: 布局.棋盘.上,
    宽: 布局.棋盘.宽,
    高: 布局.棋盘.高,
    格: 布局.格子大小,
  };
  const 棋盘左 = 左 + 输入.偏移X;
  const 棋盘上 = 上 + 输入.偏移Y;
  绘制棋盘外框(图形, {
    左: 棋盘左,
    上: 棋盘上,
    宽,
    高,
    格子: 格,
    透明度: 1,
    背景色: 游戏外观.棋盘.背景色,
    边框色: 游戏外观.棋盘.边框色,
  });
  if (输入.视图.显示网格) {
    图形.save();
    图形.translateCanvas(棋盘左, 棋盘上);
    绘制棋盘网格(图形, {
      宽,
      高,
      格子: 格,
      列数: 布局.棋盘.列,
      行数: 布局.棋盘.行,
      网格色: 颜色值(界面主题().游戏区域.网格线),
    });
    图形.restore();
  }
  const 状态 = 输入.视图.状态;
  const 方案 = 输入.视图.方块外观;
  for (let 行 = 0; 行 < 布局.棋盘.行; 行 += 1) {
    const 数据 = 状态.棋盘[行 + 2];
    if (!数据) continue;
    for (let 列 = 0; 列 < 布局.棋盘.列; 列 += 1) {
      const 类型 = 数据[列];
      if (!类型) continue;
      绘制方块单元(图形, 棋盘左 + 列 * 格, 棋盘上 + 行 * 格, {
        方案,
        色值: 方案.颜色[类型],
        格子: 格,
        圆角比例: 0.16,
      });
    }
  }
  const 幽灵透明度 = Math.max(0, Math.min(1, 输入.视图.落点影透明度 / 100));
  const 当前类型 = 状态.当前方块.类型;
  for (const [列, 行] of 输入.视图.影子) {
    if (行 < 0 || 行 >= 布局.棋盘.行 || 状态.棋盘[行 + 2]?.[列]) continue;
    绘制方块单元(图形, 棋盘左 + 列 * 格, 棋盘上 + 行 * 格, {
      方案,
      色值: 方案.颜色[当前类型],
      格子: 格,
      透明度: 幽灵透明度,
      圆角比例: 0.16,
      幽灵: true,
    });
  }
  for (const [列, 行] of 读取格子(状态.当前方块)) {
    if (行 < 0 || 行 >= 布局.棋盘.行) continue;
    绘制方块单元(图形, 棋盘左 + 列 * 格, 棋盘上 + 行 * 格, {
      方案,
      色值: 方案.颜色[当前类型],
      格子: 格,
      圆角比例: 0.16,
    });
  }
}

/** 在矩形内居中画一个方块类型（预览/暂存栏）。 */
function 绘制形状(
  上下文: 绘图上下文,
  方案: 方块外观方案,
  类型: 方块类型,
  矩形: 矩形,
  透明度: number,
): void {
  const { 图形 } = 上下文;
  const 格子 = 预览形状(类型);
  const 列数 = Math.max(...格子.map(([列]) => 列)) + 1;
  const 行数 = Math.max(...格子.map(([, 行]) => 行)) + 1;
  const 格 = Math.max(7, Math.min(14, Math.min(矩形.宽 / (列数 + 1), 矩形.高 / (行数 + 1))));
  const 左 = 矩形.左 + (矩形.宽 - 列数 * 格) / 2;
  const 上 = 矩形.上 + (矩形.高 - 行数 * 格) / 2;
  for (const [列, 行] of 格子) {
    绘制方块单元(图形, 左 + 列 * 格, 上 + 行 * 格, {
      方案,
      色值: 方案.颜色[类型],
      格子: 格,
      透明度,
      圆角比例: 0.16,
    });
  }
}

/** 出生形状平移到左上角（与规则层 预览格子 一致）。 */
function 预览形状(类型: 方块类型): [number, number][] {
  const 形状: Record<string, [number, number][]> = {
    I: [
      [0, 0],
      [1, 0],
      [2, 0],
      [3, 0],
    ],
    O: [
      [0, 0],
      [1, 0],
      [0, 1],
      [1, 1],
    ],
    T: [
      [1, 0],
      [0, 1],
      [1, 1],
      [2, 1],
    ],
    S: [
      [1, 0],
      [2, 0],
      [0, 1],
      [1, 1],
    ],
    Z: [
      [0, 0],
      [1, 0],
      [1, 1],
      [2, 1],
    ],
    J: [
      [0, 0],
      [0, 1],
      [1, 1],
      [2, 1],
    ],
    L: [
      [2, 0],
      [0, 1],
      [1, 1],
      [2, 1],
    ],
  };
  return 形状[类型] ?? 形状.I ?? [];
}

/** 右侧栏：暂存 + 下一个×3 + 最佳纪录 + 硬降（竖屏）。 */
function 绘制侧栏(上下文: 绘图上下文, 输入: 对局绘制输入): void {
  const { 环境, 图形, 布局 } = 上下文;
  const 侧栏 = 布局.侧栏;
  if (!侧栏) return;
  const 色 = 环境.主题.颜色;
  const 状态 = 输入.视图.状态;
  const 方案 = 输入.视图.方块外观;
  绘制玻璃面板基底(图形, 侧栏.左, 侧栏.顶, 侧栏.宽, 侧栏.高, {
    圆角: 14,
    填色: 色.面板,
    透明度: 0.98,
    边色: 色.描边,
    边透明度: 0.65,
  });
  // 纪录页脚上方分隔线（Phaser 绘制霓虹侧栏 竖屏同款）。
  添加矩形(
    环境,
    { 左: 侧栏.左 + 10, 上: 侧栏.顶 + 侧栏.高 - 144, 宽: 侧栏.宽 - 20, 高: 1 },
    色.描边,
    0.6,
  );
  // 暂存格：与 Phaser 暂存方块栏 一致，用界面按钮「次要」底色 + 文字强调描边。
  const 主题 = 界面主题();
  绘制霓虹按钮(
    图形,
    侧栏.暂存.左 + 侧栏.暂存.宽 / 2,
    侧栏.暂存.上 + 侧栏.暂存.高 / 2,
    侧栏.暂存.宽,
    侧栏.暂存.高,
    {
      面板色: 主题.按钮.次要.默认.背景,
      强调色: 主题.文字.强调,
      面板透明度: 0.92,
      边框透明度: 0.55,
      可用: 状态.本块已暂存,
    },
  );
  const 暂存中心X = 侧栏.暂存.左 + 侧栏.暂存.宽 / 2;
  if (状态.暂存方块) {
    绘制形状(上下文, 方案, 状态.暂存方块, 侧栏.暂存, 状态.本块已暂存 ? 0.45 : 0.95);
  } else {
    // Phaser 暂存方块栏 空位：40×36 圆角描边框占位（不写「空」字）。
    图形
      .lineStyle(1, 颜色值(主题.面板.主面板.描边), 0.6)
      .strokeRoundedRect(暂存中心X - 20, 侧栏.暂存.上 + 10, 40, 侧栏.暂存.高 - 36, 4);
  }
  const 暂存可用 = !状态.本块已暂存;
  const 暂存文案 = 暂存可用 ? "暂存 C / 长按↑" : "暂存 · 落块后可换";
  const 暂存文案上 = 侧栏.暂存.上 + 侧栏.暂存.高 / 2 + 23 - 绘制文字行高(环境, "小") / 2;
  绘制文字(环境, "小", 暂存文案, 暂存中心X, 暂存文案上, {
    颜色: 颜色值(暂存可用 ? 主题.文字.主要 : 主题.文字.弱化),
    对齐: "中",
  });
  // 下一个标题与三张卡
  绘制文字(环境, "小", "下一个", 侧栏.下一个标签.左, 侧栏.下一个标签.上, { 颜色: 色.次字 });
  const 队列 = [状态.下一个方块, ...状态.后续方块].slice(0, 3);
  侧栏.下一步卡.forEach((矩形, 索引) => {
    const 类型 = 队列[索引];
    const 首位 = 索引 === 0;
    绘制预览卡(图形, {
      左: 矩形.左,
      上: 矩形.上,
      宽: 矩形.宽,
      高: 矩形.高,
      圆角: 12,
      填色: 混合颜色(色.面板, 色.底色, 0.35),
      边色: 首位 && 类型 ? 亮色(方案.颜色[类型], 0.35) : 色.描边,
      边透明度: 首位 ? 0.55 : 0.38,
      强调色: 首位 && 类型 ? 方案.颜色[类型] : undefined,
      高光: true,
      首位,
    });
    if (类型) 绘制形状(上下文, 方案, 类型, 矩形, 首位 ? 0.95 : 0.7);
  });
  // 最佳纪录 + 硬降
  绘制文字(环境, "小", "最佳纪录", 侧栏.最佳纪录.标签X, 侧栏.最佳纪录.标签Y, {
    颜色: 色.次字,
    对齐: "中",
  });
  if (!输入.提示.暂停)
    绘制文字(环境, "中", 输入.最佳纪录, 侧栏.最佳纪录.值X, 侧栏.最佳纪录.值Y, {
      颜色: 色.强调,
      对齐: "中",
    });
  const 硬降矩形: 矩形 = {
    左: 侧栏.硬降.中心X - 侧栏.硬降.宽 / 2,
    上: 侧栏.硬降.中心Y - 侧栏.硬降.高 / 2,
    宽: 侧栏.硬降.宽,
    高: 侧栏.硬降.高,
  };
  绘制按钮底板(
    上下文,
    {
      中心X: 硬降矩形.左 + 硬降矩形.宽 / 2,
      中心Y: 硬降矩形.上 + 硬降矩形.高 / 2,
      宽: 硬降矩形.宽,
      高: 硬降矩形.高,
    },
    "↓ 硬降",
    状态.阶段 === "进行中",
    false,
  );
}

/** 暂停时状态行（Phaser 状态文字：按 P 或 Esc 继续）+ 模式提示。 */
function 绘制状态文字(上下文: 绘图上下文, 输入: 对局绘制输入): void {
  const { 环境, 布局 } = 上下文;
  const 色 = 环境.主题.颜色;
  if (输入.提示.暂停)
    绘制文字(环境, "小", "按 P 或 Esc 继续", 布局.状态文字.中心X, 布局.状态文字.下, {
      颜色: 色.次字,
      对齐: "中",
    });
  if (布局.模式文字.可见)
    绘制文字(环境, "小", 输入.模式名, 布局.模式文字.中心X, 布局.模式文字.上, {
      颜色: 色.次字,
      对齐: "中",
    });
}

/** 底部 6 个触屏操作键（含多行提示）。 */
function 绘制操作区(上下文: 绘图上下文): void {
  const { 布局 } = 上下文;
  if (!布局.操作区.显示) return;
  for (const 键 of 布局.操作区.键) {
    绘制按钮底板(
      上下文,
      { 中心X: 键.中心X, 中心Y: 键.中心Y, 宽: 键.宽, 高: 键.高 },
      键.标签,
      true,
      false,
      true,
    );
  }
}

/** 提示层：技巧/成就/目标达成。 */
function 绘制提示层(上下文: 绘图上下文, 输入: 对局绘制输入): void {
  const { 环境, 布局 } = 上下文;
  const 色 = 环境.主题.颜色;
  const 中心X = 布局.提示文字.中心X;
  const 中心Y = 布局.提示文字.中心Y;
  if (输入.提示.技巧 && 输入.提示.技巧.比例 > 0) {
    const 行列表 = 输入.提示.技巧.文本.split("\n");
    const 上 = 中心Y - 26 - (1 - 输入.提示.技巧.比例) * 20;
    const 宽 = Math.max(...行列表.map((行) => 测量文字宽度(环境, "中", 行))) + 24;
    const 高 = 行列表.length * 绘制文字行高(环境, "中") + 12;
    添加矩形(
      环境,
      { 左: 中心X - 宽 / 2, 上: 上 - 6, 宽, 高 },
      混合颜色(色.底色, 色.暗字, 0.45),
      输入.提示.技巧.比例 * 0.7,
    );
    for (const [序号, 行] of 行列表.entries()) {
      绘制文字(环境, "中", 行, 中心X, 上 + 序号 * 绘制文字行高(环境, "中"), {
        颜色: 序号 === 0 ? 色.强调 : 色.主字,
        透明度: 输入.提示.技巧.比例,
        对齐: "中",
      });
    }
  }
  if (输入.提示.成就 && 输入.提示.成就.比例 > 0) {
    const 文本 = 输入.提示.成就.文本;
    const 宽 = 测量文字宽度(环境, "小", 文本) + 20;
    添加矩形(
      环境,
      { 左: 中心X - 宽 / 2, 上: 178, 宽, 高: 22 },
      混合颜色(色.面板, 色.暗字, 0.3),
      输入.提示.成就.比例 * 0.9,
    );
    绘制文字(环境, "小", 文本, 中心X, 182, {
      颜色: 色.强调,
      透明度: 输入.提示.成就.比例,
      对齐: "中",
    });
  }
  if (输入.提示.目标 !== null && 输入.提示.目标 > 0) {
    const 脉冲 = 0.6 + 0.4 * Math.sin(输入.提示.目标 * Math.PI * 8);
    绘制文字(环境, "大", "目标达成", 布局.目标提示.中心X, 布局.目标提示.中心Y, {
      颜色: 色.强调,
      透明度: Math.min(1, 输入.提示.目标 * 1.4) * 脉冲,
      对齐: "中",
    });
  }
}

/** 暂停层：遮罩 + 共享玻璃面板 + 4 个按钮。 */
function 绘制暂停层(上下文: 绘图上下文, 输入: 对局绘制输入): void {
  if (!输入.提示.暂停) return;
  const { 环境, 图形, 布局 } = 上下文;
  const 色 = 环境.主题.颜色;
  const 面板 = 布局.暂停面板;
  const 面板宽 = 面板.宽 * 面板.比例;
  const 面板高 = 面板.高 * 面板.比例;
  绘制暂停面板(图形, {
    矩形: {
      左: 面板.中心X - 面板宽 / 2,
      上: 面板.中心Y - 面板高 / 2,
      宽: 面板宽,
      高: 面板高,
    },
    遮罩色: 颜色值(Phaser预制体配置.暂停菜单.遮罩色),
    遮罩透明度: 0.78,
    面板色: 色.面板,
    描边色: 色.描边,
    强调色: 色.强调,
    逻辑宽: 布局.视口宽,
    逻辑高: 布局.视口高,
  });
  绘制文字(环境, "大", "已暂停", 面板.中心X, 面板.中心Y + 面板.标题Y * 面板.比例, {
    颜色: 色.主字,
    对齐: "中",
  });
  绘制文字(环境, "小", "当前进度已保留", 面板.中心X, 面板.中心Y + 面板.说明Y * 面板.比例, {
    颜色: 色.次字,
    对齐: "中",
  });
  for (const 按钮 of 面板.按钮) {
    绘制按钮底板(
      上下文,
      {
        中心X: 按钮.矩形.左 + 按钮.矩形.宽 / 2,
        中心Y: 按钮.矩形.上 + 按钮.矩形.高 / 2,
        宽: 按钮.矩形.宽,
        高: 按钮.矩形.高,
      },
      按钮.标签,
      true,
      按钮.已选 ? true : false,
      false,
      按钮.已选,
    );
  }
}

/** 绘制整页对局；调用方负责清屏/提交与文字资源。 */
export function 绘制对局画面(环境: 绘制环境, 输入: 对局绘制输入): void {
  const 上下文: 绘图上下文 = { 环境, 图形: 环境.图形, 布局: 输入.布局 };
  绘制顶栏(上下文, 输入);
  绘制棋盘(上下文, 输入);
  绘制侧栏(上下文, 输入);
  绘制操作区(上下文);
  if (!输入.提示.暂停) 绘制提示层(上下文, 输入);
  绘制状态文字(上下文, 输入);
  绘制暂停层(上下文, 输入);
}

/** 操作键名称 → 虚拟键（命中注册与输入映射共用）。 */
export function 操作键虚拟键(键: 对局布局操作键): 虚拟键 {
  if (键.名称 === "左移") return "左";
  if (键.名称 === "右移") return "右";
  if (键.名称 === "软降") return "下";
  if (键.名称 === "硬降") return "硬降";
  if (键.名称 === "左转") return "左转";
  if (键.名称 === "右转") return "右转";
  return "旋转";
}

import { 绘制玻璃按钮底板 } from "../../../组件/绘制/玻璃绘制";
import { 绘制结算遮罩, 绘制结算面板, 计算霓虹结算布局 } from "../../视觉/结算配方";
import { 绘制结算金币, 读取结算金币动画 } from "../../视觉/结算金币配方";
import { 游戏外观 } from "../../配置/游戏外观";
import type { 结算统计项 } from "../对局/结算数据";
import type { 对局结果 } from "../接口/服务";
import { 混合颜色, type 矩形 } from "./外观";
import { 绘制文字, 绘制文字行高, type 绘制环境 } from "./绘制";

/**
 * 结算覆盖页绘制：遮罩 + 面板走 `组件/霓虹街机/结算面板.ts` 的共享纯配方与布局
 *（与 Phaser 结算面板同一算法），文字/按钮标签用 Three 的文字项与共享玻璃按钮底板。
 */

export interface 结算绘制输入 {
  结果: 对局结果;
  标题: string;
  徽标: string;
  统计: 结算统计项[];
  奖励文案: string;
  成就文案: string;
  金币余额: number;
  锁剩余毫秒: number;
  可重开: boolean;
  宽: number;
  高: number;
  动画毫秒: number;
  省电: boolean;
  金币: { 新增: number; 总额: number; 原因: string } | null;
}

function 居中(
  环境: 绘制环境,
  档: "小" | "中" | "大",
  文本: string,
  中心X: number,
  上: number,
  颜色: number,
  透明度 = 1,
): void {
  绘制文字(环境, 档, 文本, 中心X, 上, { 颜色, 透明度, 对齐: "中" });
}

function 绘制按钮(环境: 绘制环境, 矩形: 矩形, 文本: string, 可用: boolean, 高亮: boolean): void {
  const 色 = 环境.主题.颜色;
  绘制玻璃按钮底板(环境.图形, 矩形.左 + 矩形.宽 / 2, 矩形.上 + 矩形.高 / 2, 矩形.宽, 矩形.高, {
    填色: 可用 ? (高亮 ? 色.强调 : 色.面板) : 混合颜色(色.面板, 色.底色, 0.55),
    边框色: 可用 ? (高亮 ? 色.强调 : 色.描边) : 色.暗字,
    强调色: 高亮 ? 色.强调 : 色.描边,
    透明度: 可用 ? (高亮 ? 0.98 : 0.94) : 0.6,
    边透明度: 可用 ? 0.8 : 0.4,
    选中: 高亮 && 可用,
  });
  绘制文字(
    环境,
    "中",
    文本,
    矩形.左 + 矩形.宽 / 2,
    矩形.上 + (矩形.高 - 绘制文字行高(环境, "中")) / 2,
    {
      颜色: 可用 ? 色.主字 : 色.暗字,
      对齐: "中",
    },
  );
}

export function 绘制结算(环境: 绘制环境, 输入: 结算绘制输入): void {
  const 色 = 环境.主题.颜色;
  const 面板布局 = 计算霓虹结算布局(输入.宽, 输入.高);
  const { 几何 } = 面板布局;
  绘制结算遮罩(环境.图形, 输入.宽, 输入.高);
  绘制结算面板(环境.图形, 面板布局);

  const 比例 = 几何.比例;
  居中(环境, "小", 输入.徽标, 面板布局.徽标.中心X, 面板布局.徽标.上, 色.强调, 0.95);
  // 标题：Phaser 侧为场景 28px 文字（游戏结束/挑战完成），位置与面板同基准。
  居中(环境, "大", 输入.标题, 几何.中心X, 几何.顶 + 82 * 比例, 色.主字);
  居中(环境, "大", 输入.结果.分数.toLocaleString(), 面板布局.分数.中心X, 面板布局.分数.上, 色.强调);

  // 三列统计：标签在上、数值在下，列间分隔线由共享面板绘制。
  for (const [序号, 项] of 输入.统计.slice(0, 3).entries()) {
    const 列中心 = 面板布局.左 + 面板布局.列宽 * (序号 + 0.5);
    居中(环境, "小", 项.标签, 列中心, 面板布局.统计标签Y, 色.次字);
    居中(环境, "中", 项.数值, 列中心, 面板布局.统计数值Y, 色.主字);
  }

  let 行Y = 面板布局.金币行Y;
  if (输入.金币) {
    const 动画 = 读取结算金币动画(输入.动画毫秒, 输入.金币.新增, 输入.省电);
    const 文宽 = 环境.画笔.测量文字(`+${输入.金币.新增}`, {
      字体: 游戏外观.字体.家族,
      字号: 20 * 比例,
      颜色: 色.强调,
      字重: "粗体",
    }).宽;
    const 金币文字 = 绘制结算金币(
      环境.图形,
      面板布局,
      输入.动画毫秒,
      输入.金币.新增,
      输入.省电,
      文宽,
    );
    环境.图形.save().setAlpha(动画.透明度);
    环境.画笔.绘制文字(金币文字);
    环境.图形.restore();
    居中(
      环境,
      "小",
      `${输入.金币.原因} · 余额 ${输入.金币.总额.toLocaleString()}`,
      几何.中心X,
      面板布局.奖励Y + 11 * 比例,
      色.强调,
    );
    行Y = 面板布局.奖励Y + 28 * 比例;
  } else if (输入.奖励文案) {
    for (const [序号, 行] of 输入.奖励文案.split("\n").entries()) {
      居中(环境, "小", 行, 几何.中心X, 行Y + 序号 * 18, 色.次字);
    }
    行Y += 22;
  } else {
    居中(环境, "小", `金币余额 ${输入.金币余额}`, 几何.中心X, 行Y, 色.次字);
    行Y += 20;
  }
  if (输入.成就文案) 居中(环境, "小", 输入.成就文案, 几何.中心X, 行Y, 色.强调);

  const 重开矩形: 矩形 = {
    左: 面板布局.重开.中心X - 面板布局.重开.宽 / 2,
    上: 面板布局.重开.中心Y - 面板布局.重开.高 / 2,
    宽: 面板布局.重开.宽,
    高: 面板布局.重开.高,
  };
  const 菜单矩形: 矩形 = {
    左: 面板布局.菜单.中心X - 面板布局.菜单.宽 / 2,
    上: 面板布局.菜单.中心Y - 面板布局.菜单.高 / 2,
    宽: 面板布局.菜单.宽,
    高: 面板布局.菜单.高,
  };
  const 重开文本 = 输入.可重开 ? "重新开始" : `重新开始 · ${Math.ceil(输入.锁剩余毫秒 / 1000)}s`;
  绘制按钮(环境, 重开矩形, 重开文本, 输入.可重开, true);
  绘制按钮(环境, 菜单矩形, "返回主菜单", true, false);
}

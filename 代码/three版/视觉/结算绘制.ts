import type { 结算统计项 } from "../对局/结算数据";
import type { 对局结果 } from "../接口/服务";
import { 布局, type 矩形, 结算菜单按钮, 结算重开按钮, 逻辑宽, 逻辑高 } from "./外观";
import { 添加矩形, 绘制文字, 绘制文字行高, type 绘制环境, 绘制面板 } from "./绘制";

/** 结算覆盖页绘制：半透明遮罩 + 面板 + 分数/统计/金币/成就 + 重开与返回按钮。 */

export interface 结算绘制输入 {
  结果: 对局结果;
  标题: string;
  徽标: string;
  统计: 结算统计项[];
  奖励文案: string;
  成就文案: string;
  金币余额: number;
  锁剩余毫秒: number;
  可重开: boolean;
}

function 居中(
  环境: 绘制环境,
  档: "小" | "中" | "大",
  文本: string,
  中心X: number,
  上: number,
  颜色: number,
  透明度 = 1,
): void {
  绘制文字(环境, 档, 文本, 中心X, 上, { 颜色, 透明度, 对齐: "中" });
}

function 绘制按钮标签(环境: 绘制环境, 矩形: 矩形, 文本: string, 可用: boolean): void {
  绘制文字(
    环境,
    "中",
    文本,
    矩形.左 + 矩形.宽 / 2,
    矩形.上 + (矩形.高 - 绘制文字行高(环境, "中")) / 2,
    {
      颜色: 可用 ? 环境.主题.颜色.主字 : 环境.主题.颜色.暗字,
      对齐: "中",
    },
  );
}

export function 绘制结算(环境: 绘制环境, 输入: 结算绘制输入): void {
  const 色 = 环境.主题.颜色;
  添加矩形(环境, { 左: 0, 上: 0, 宽: 逻辑宽, 高: 逻辑高 }, 混合遮罩(色.底色), 0.78);
  const { 左, 上, 宽, 高 } = 布局.结算面板;
  const 中心X = 左 + 宽 / 2;
  绘制面板(环境, { 左, 上, 宽, 高 }, 色.浮层, 色.强调);
  添加矩形(环境, { 左: 左 + 2, 上: 上 + 2, 宽: 宽 - 4, 高: 3 }, 色.强调, 0.9);
  居中(环境, "大", 输入.标题, 中心X, 上 + 18, 色.主字);
  居中(环境, "小", 输入.徽标, 中心X, 上 + 58, 色.次字, 0.95);
  居中(环境, "小", "分数", 中心X, 上 + 88, 色.次字);
  居中(环境, "大", 输入.结果.分数.toLocaleString(), 中心X, 上 + 104, 色.强调);

  let 行Y = 上 + 162;
  const 数值左 = 左 + 宽 - 28;
  for (const 项 of 输入.统计) {
    绘制文字(环境, "小", 项.标签, 左 + 24, 行Y, { 颜色: 色.次字 });
    绘制文字(环境, "小", 项.数值, 数值左, 行Y, { 颜色: 色.主字, 对齐: "右" });
    行Y += 30;
  }
  行Y = Math.max(行Y + 6, 上 + 268);
  添加矩形(环境, { 左: 左 + 20, 上: 行Y - 8, 宽: 宽 - 40, 高: 1.5 }, 色.描边, 0.6);
  居中(环境, "小", `金币余额 ${输入.金币余额}`, 中心X, 行Y, 色.次字);
  行Y += 24;
  if (输入.奖励文案) {
    const 失败 = 输入.奖励文案.includes("重试");
    for (const [序号, 行] of 输入.奖励文案.split("\n").entries()) {
      居中(环境, "小", 行, 中心X, 行Y + 序号 * 18, 失败 ? 色.警告 : 色.成功);
    }
    行Y += 22;
  }
  if (输入.成就文案) 居中(环境, "小", 输入.成就文案, 中心X, 行Y, 色.强调);

  const 可重开 = 输入.可重开;
  const 重开文本 = 可重开 ? "重新开始" : `重新开始 · ${Math.ceil(输入.锁剩余毫秒 / 1000)}s`;
  const 重开色 = 可重开 ? 色.强调 : 色.暗字;
  绘制面板(环境, 结算重开按钮, 可重开 ? 色.面板 : 混合遮罩(色.面板), 重开色, 可重开 ? 1 : 0.6);
  绘制按钮标签(环境, 结算重开按钮, 重开文本, 可重开);
  绘制面板(环境, 结算菜单按钮, 色.面板, 色.描边, 0.9);
  绘制按钮标签(环境, 结算菜单按钮, "返回主菜单", true);
}

/** 遮罩色统一往黑里压，保证底下的对局画面退到背景层。 */
function 混合遮罩(底色: number): number {
  const 通道 = (偏移: number) => Math.round(((底色 >> 偏移) & 0xff) * 0.25);
  return (通道(16) << 16) | (通道(8) << 8) | 通道(0);
}

import type { 文字样式, 文字锚点, 矩形 } from "../../../组件/绘制/图形对象";
import { 绘制玻璃按钮底板 } from "../../../组件/绘制/玻璃绘制";
import { 文字对齐修正, 读取按钮标签样式 } from "../../视觉/对局布局";
import {
  绘制结算遮罩,
  绘制结算面板,
  计算霓虹结算布局,
  读取结算按钮视觉,
  读取结算文字样式,
} from "../../视觉/结算配方";
import { 绘制结算金币, 读取结算金币动画 } from "../../视觉/结算金币配方";
import type { 结算统计项 } from "../对局/结算数据";
import type { 对局结果 } from "../接口/服务";
import type { 绘制环境 } from "./绘制";

/**
 * 结算覆盖页绘制：遮罩 + 面板走 `代码/视觉/结算配方.ts` 的共享纯配方与布局
 *（与 Phaser 结算面板同一算法），文字/按钮标签的字号、字距、配色与锚点也来自共享配方。
 */

export interface 结算绘制输入 {
  结果: 对局结果;
  标题: string;
  徽标: string;
  统计: 结算统计项[];
  奖励文案: string;
  成就文案: string;
  金币余额: number;
  锁剩余毫秒: number;
  可重开: boolean;
  宽: number;
  高: number;
  动画毫秒: number;
  省电: boolean;
  金币: { 新增: number; 总额: number; 原因: string } | null;
}

/** 按共享文字样式画一段文字（透明度用画笔当前 alpha 乘入）。 */
function 绘制样式文字(
  环境: 绘制环境,
  样式: 文字样式,
  文本: string,
  x: number,
  y: number,
  锚点: 文字锚点 = "中中",
): void {
  const 行高 = 环境.画笔.测量文字("字", 样式).高;
  环境.画笔.绘制文字({
    文案: 文本,
    样式,
    锚点,
    x,
    y: y - 文字对齐修正(样式.字号, 锚点, 行高),
  });
}

/** 多行文字：按行拆开居中排（Phaser Text 的 align:center + wordWrap 等价物）。 */
function 绘制多行文字(
  环境: 绘制环境,
  样式: 文字样式,
  文本: string,
  中心X: number,
  上: number,
): void {
  const 行高 = 环境.画笔.测量文字("字", 样式).高;
  for (const [序号, 行] of 文本.split("\n").entries())
    绘制样式文字(环境, 样式, 行, 中心X, 上 + 序号 * 行高, "中上");
}

function 绘制按钮(
  环境: 绘制环境,
  矩形: 矩形,
  文本: string,
  视觉: ReturnType<typeof 读取结算按钮视觉>,
): void {
  绘制玻璃按钮底板(环境.图形, 矩形.左 + 矩形.宽 / 2, 矩形.上 + 矩形.高 / 2, 矩形.宽, 矩形.高, {
    填色: 视觉.填色,
    边框色: 视觉.边框色,
    强调色: 视觉.边框色,
    透明度: 视觉.透明度,
    边透明度: 视觉.边透明度,
  });
  绘制样式文字(
    环境,
    读取按钮标签样式(视觉.字号, 视觉.文字色),
    文本,
    矩形.左 + 矩形.宽 / 2,
    矩形.上 + 矩形.高 / 2,
    "中中",
  );
}

export function 绘制结算(环境: 绘制环境, 输入: 结算绘制输入): void {
  const 面板布局 = 计算霓虹结算布局(输入.宽, 输入.高);
  const { 几何 } = 面板布局;
  const 比例 = 几何.比例;
  绘制结算遮罩(环境.图形, 输入.宽, 输入.高);
  绘制结算面板(环境.图形, 面板布局);

  // 徽标：Phaser 12px 粗体强调色，origin 0.5，位于面板顶 + 34。
  绘制样式文字(
    环境,
    读取结算文字样式("徽标", { 字号: 12 * 比例 }),
    输入.徽标,
    面板布局.徽标.中心X,
    面板布局.徽标.上,
  );
  // 标题（游戏结束/挑战完成）：Phaser 场景提示文字 28px 粗体 Courier + 8px 主面板描边。
  绘制样式文字(
    环境,
    读取结算文字样式("标题", { 字号: 28 * 比例 }),
    输入.标题,
    几何.中心X,
    几何.顶 + 82 * 比例,
  );
  // 分数：Phaser 38px 粗体强调色。
  绘制样式文字(
    环境,
    读取结算文字样式("分数", { 字号: 38 * 比例 }),
    输入.结果.分数.toLocaleString(),
    面板布局.分数.中心X,
    面板布局.分数.上,
  );

  // 三列统计：标签在上、数值在下，列间分隔线由共享面板绘制。
  for (const [序号, 项] of 输入.统计.slice(0, 3).entries()) {
    const 列中心 = 面板布局.左 + 面板布局.列宽 * (序号 + 0.5);
    绘制样式文字(
      环境,
      读取结算文字样式("统计标签", { 字号: 11 * 比例 }),
      项.标签,
      列中心,
      面板布局.统计标签Y,
    );
    绘制样式文字(
      环境,
      读取结算文字样式("统计数值", { 字号: 18 * 比例 }),
      项.数值,
      列中心,
      面板布局.统计数值Y,
    );
  }

  // 金币行：只有真正新增金币才播金币行（与 Phaser 领取本局奖励 同口径）；
  // 0 新增时 Phaser 只显示「未达条件」原因文案，不画图标与计数。
  const 有金币行 = 输入.金币 !== null && 输入.金币.新增 > 0;
  if (有金币行 && 输入.金币) {
    const 动画 = 读取结算金币动画(输入.动画毫秒, 输入.金币.新增, 输入.省电);
    const 文宽 = 环境.画笔.测量文字(
      `+${输入.金币.新增}`,
      读取结算文字样式("金币", { 字号: 20 * 比例 }),
    ).宽;
    const 金币文字 = 绘制结算金币(
      环境.图形,
      面板布局,
      输入.动画毫秒,
      输入.金币.新增,
      输入.省电,
      文宽,
    );
    环境.图形.save().setAlpha(动画.透明度);
    环境.画笔.绘制文字(金币文字);
    环境.图形.restore();
    绘制多行文字(
      环境,
      读取结算文字样式("奖励", { 字号: 12 * 比例 }),
      输入.奖励文案,
      几何.中心X,
      面板布局.奖励Y + 11 * 比例,
    );
  } else if (输入.奖励文案) {
    绘制多行文字(
      环境,
      读取结算文字样式("奖励", { 字号: 12 * 比例 }),
      输入.奖励文案,
      几何.中心X,
      面板布局.奖励Y,
    );
  }
  if (输入.成就文案)
    绘制样式文字(
      环境,
      读取结算文字样式("奖励", { 字号: 12 * 比例 }),
      输入.成就文案,
      几何.中心X,
      面板布局.奖励Y + 30 * 比例,
    );

  const 重开矩形: 矩形 = {
    左: 面板布局.重开.中心X - 面板布局.重开.宽 / 2,
    上: 面板布局.重开.中心Y - 面板布局.重开.高 / 2,
    宽: 面板布局.重开.宽,
    高: 面板布局.重开.高,
  };
  const 菜单矩形: 矩形 = {
    左: 面板布局.菜单.中心X - 面板布局.菜单.宽 / 2,
    上: 面板布局.菜单.中心Y - 面板布局.菜单.高 / 2,
    宽: 面板布局.菜单.宽,
    高: 面板布局.菜单.高,
  };
  const 重开文本 = 输入.可重开 ? "重新开始" : `重新开始 · ${Math.ceil(输入.锁剩余毫秒 / 1000)}s`;
  绘制按钮(环境, 重开矩形, 重开文本, 读取结算按钮视觉(输入.可重开 ? "重开" : "重开禁用"));
  绘制按钮(环境, 菜单矩形, "返回主菜单", 读取结算按钮视觉("菜单"));
}

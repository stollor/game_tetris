import type { 渲染编排 } from "../../../框架Three/世界/渲染编排";
import type { 图元合批, 图元合批统计 } from "../../../框架Three/界面/图元合批";
import type { 资源统计 } from "../../../框架Three/界面/绘制/画笔";
import type { 场景栈 } from "../../../框架Three/运行时/场景栈";
import type { 游戏循环 } from "../../../框架Three/运行时/循环";
import type { 界面快照, 页面上下文, 页面实例, 页面编号 } from "../接口/上下文";
import type { 应用服务 } from "../接口/服务";

/**
 * 调试桥：启动层统一挂 window.__three版__ 与 window.__再消一行测试__。
 * 对局页只实现 页面实例 上的可选读取方法/测试控制/读取界面，桥负责转发并拼装
 * 场景栈、循环、渲染、合批、音频与内存统计；浏览器验收脚本只依赖这里的读取接口。
 * __再消一行测试__ 的全局类型由 Phaser 版对局场景声明，Three 侧保证运行时同形。
 */

export interface 调试桥选项 {
  渲染: 渲染编排;
  合批: 图元合批;
  循环: 游戏循环;
  服务: 应用服务;
  栈: 场景栈<页面上下文>;
  读取页面编号(): 页面编号;
  读取当前页(): 页面实例 | undefined;
  读取文字统计?: () => { 小: unknown; 中: unknown; 大: unknown };
  /** 图元合批统计（新绘制层）。 */
  读取图元统计?: () => 图元合批统计;
  /** 资源层纹理统计。 */
  读取纹理统计?: () => 资源统计;
  /** 共享文字服务的文字图集统计。 */
  读取文字图集统计?: () => unknown;
  停止(): void;
}

/** 旧验收脚本用 操作(名称) 驱动键盘；这里转成真实 KeyboardEvent，走对局页自己的按键监听。 */
const 操作按键表: Record<string, KeyboardEventInit> = {
  左移: { code: "ArrowLeft", key: "ArrowLeft" },
  右移: { code: "ArrowRight", key: "ArrowRight" },
  旋转: { code: "ArrowUp", key: "ArrowUp" },
  软降: { code: "ArrowDown", key: "ArrowDown" },
  硬降: { code: "Space", key: " " },
  暂存: { code: "KeyC", key: "c" },
  暂停: { code: "KeyP", key: "p" },
};

export function 挂载调试桥(选项: 调试桥选项): () => void {
  const 读取当前页 = () => 选项.读取当前页();

  const 读取状态 = () => {
    const 快照 = 读取当前页()?.读取快照?.();
    return {
      ...(快照 && typeof 快照 === "object" ? 快照 : {}),
      页面: 选项.读取页面编号(),
      场景栈: 选项.栈.读取栈().map((项) => 项.名称),
    };
  };

  const 读取统计 = () => {
    const 页 = 读取当前页();
    return {
      循环: 选项.循环.读取统计(),
      渲染: 选项.渲染.读取统计(),
      合批: 选项.合批.读取统计(),
      图元: 选项.读取图元统计?.() ?? null,
      纹理: 选项.读取纹理统计?.() ?? null,
      文字: 选项.读取文字统计?.() ?? null,
      文字图集: 选项.读取文字图集统计?.() ?? null,
      内存: 选项.服务.内存(),
      画布: {
        宽: 选项.渲染.画布.width,
        高: 选项.渲染.画布.height,
        视口宽: 选项.渲染.画布.dataset.视口宽 ?? "",
        视口高: 选项.渲染.画布.dataset.视口高 ?? "",
      },
      设备像素比: window.devicePixelRatio,
      页面: 选项.读取页面编号(),
      场景栈: 选项.栈.读取栈().map((项) => 项.名称),
      对局统计: 页?.读取对局统计?.() ?? { 操作次数: 0, 落块数: 0, 消行次数: 0 },
      操作记录: 页?.读取操作记录?.() ?? [],
      主题: 选项.服务.主题.读取().名称,
      省电: 选项.服务.设置.读取().省电模式,
      音频: 选项.服务.音频.读取状态(),
      金币: 选项.服务.金币.读取().金币,
    };
  };

  const 测试控制 = () => 读取当前页()?.测试;

  const 读取界面 = (): 界面快照 => 读取当前页()?.读取界面?.() ?? { 按钮: [] };

  const 派发键 = (类型: KeyboardEventInit): void => {
    window.dispatchEvent(new KeyboardEvent("keydown", { ...类型, bubbles: true }));
    window.dispatchEvent(new KeyboardEvent("keyup", { ...类型, bubbles: true }));
  };

  const 旧接口 = {
    开始绘制采样: () => 选项.渲染.开始绘制采样(),
    结束绘制采样: () => 选项.渲染.结束绘制采样(),
    读取状态,
    读取原始状态: () => 读取当前页()?.读取原始状态?.() ?? null,
    读取统计,
    读取界面,
    读取设置: () => 选项.服务.设置.读取(),
    更新设置: (变化: Parameters<应用服务["设置"]["更新"]>[0]) => 选项.服务.设置.更新(变化),
    读取音频: () => 选项.服务.音频.读取状态(),
    增加金币: (数量: number) => 选项.服务.金币.增加(数量),
    操作: (名称: string) => {
      const 键 = 操作按键表[名称];
      if (键) {
        派发键(键);
        return;
      }
      if (名称 === "重新开始") 派发键({ code: "KeyR", key: "r" });
    },
    停止: () => 选项.停止(),
  };

  const 对局桥 = {
    读取状态,
    读取界面,
    读取音频: () => 选项.服务.音频.读取状态(),
    设置序列: (序列: readonly string[]) => {
      const 控制 = 测试控制();
      if (控制?.设置序列) {
        控制.设置序列(序列);
        return;
      }
      for (const 块 of 序列) if (操作按键表[块]) 派发键(操作按键表[块]);
    },
    准备单行消除: () => 测试控制()?.准备单行消除?.(),
    准备四行消除: (继续连击?: boolean, 保留堆叠?: boolean) =>
      测试控制()?.准备四行消除?.(继续连击, 保留堆叠),
    读取特效: () => 测试控制()?.读取特效?.() ?? null,
    准备目标达成: () => 测试控制()?.准备目标达成?.(),
    硬降: () => {
      const 控制 = 测试控制();
      if (控制?.硬降) 控制.硬降();
      else 派发键({ code: "Space", key: " " });
    },
    设置暂停: (暂停: boolean) => 测试控制()?.设置暂停?.(暂停),
    结束当前对局: () => 测试控制()?.结束当前对局?.(),
    准备结算: (完赛?: boolean) => 测试控制()?.准备结算?.(完赛),
  };

  // 全局类型由 Phaser 版对局场景声明，运行时同形即可；Object.assign 避免重复声明冲突。
  Object.assign(window, { __three版__: 旧接口, __再消一行测试__: 对局桥 });
  return () => {
    Reflect.deleteProperty(window, "__three版__");
    Reflect.deleteProperty(window, "__再消一行测试__");
  };
}

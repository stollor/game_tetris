/**
 * Three 版文字服务：按 (字体, 字号, 字重) 懒创建 GM `文字图集`，把 `文字项` 渲染成合批四边形。
 *
 * - 字形白色光栅化进图集，颜色交给合批顶点色 tint；
 * - 描边用 8 方向偏移的同色副本模拟（Phaser 的 stroke 是沿字形轮廓，这里按粗细/2 的环近似）；
 * - 阴影用偏移暗色副本；
 * - 折行走 GM `文本换行`（中文行首/行尾禁则）；
 * - 字号决定图集页边长（≤16 用 512，其余 1024；预烘焙装不下自动升到 1024/2048）；
 * - 纹理通过注入的 `登记纹理` 进渲染编排的纹理预算，销毁时释放。
 */

/** 文字图集实例里文字服务真正用到的子集；测试可注入假图集（Bun 里没有 canvas）。 */
export type 文字图集接口 = {
  注册(文本: string): void;
  读取纹理(): Texture;
  读取纯色紫外线(): 紫外线矩形;
  读取行高(): number;
  测量(文本: string): number;
  排版(文本: string, 最大宽度: number): 排版结果;
  绘制(合批: 四边形状写入接口, 文本: string, 选项: 文字图集绘制选项): 排版结果;
  读取统计(): 文字图集统计;
  销毁(): void;
};

interface 文字图集绘制选项 {
  左: number;
  上: number;
  颜色?: 顶点颜色;
  最大宽度?: number;
  对齐?: "左" | "中" | "右";
  纹理序号?: number;
}

interface 文字图集统计 {
  页数: number;
  字形数: number;
  页面边长: number;
  纹理字节: number;
}

export interface 文字服务统计项 {
  键: string;
  字号: number;
  字重: "常规" | "粗体" | "基础";
  页数: number;
  字形数: number;
  页面边长: number;
  纹理字节: number;
}

export interface 文字服务统计 {
  图集数: number;
  页数: number;
  纹理字节: number;
  图集列表: 文字服务统计项[];
}

/** 外部纯色白块来源：复用老页面最小号文字图集，使纯色图元与老控件落在同一纹理批次。 */
export interface 纯色来源 {
  键: string;
  纹理: Texture;
  纯色紫外线: 紫外线矩形;
}

export interface 文字服务选项 {
  /** 文字图集纹理登记进纹理预算；通常直接传 `渲染编排.登记纹理`。 */
  登记纹理: (键: string, 纹理: Texture, 字节: number) => () => void;
  /** 复用外部纯色白块（例如老页面的小号文字图集）；提供时不再自建基础图集。 */
  纯色来源?: 纯色来源;
  /** 字形光栅化像素比，默认 1。 */
  像素比?: number;
  /** 默认字体：文字样式未写字体时使用。 */
  字体?: string;
  /** 基础图集字号（只画纯色白块），默认 14。 */
  基础字号?: number;
  /** 测试注入：替换 canvas 文字图集实现。 */
  创建图集?: (选项: 文字图集选项) => 文字图集接口;
}

export interface 文字绘制选项 {
  /** 透明度，通常取画笔当前 `图形` 的 alpha。 */
  透明度?: number;
  /** 混合方式，通常取画笔当前 `图形` 的混合模式。 */
  混合?: 混合方式;
}

export interface 文字服务 {
  /** 把文字项写进合批，返回实际排版宽高（锚点未计入）。 */
  绘制(合批: 图元写入接口, 项: 文字项, 选项?: 文字绘制选项): { 宽: number; 高: number };
  测量(文案: string, 样式: 文字样式): { 宽: number; 高: number };
  /** 纯色图元复用的白块紫外线。 */
  读取纯色紫外线(): 紫外线矩形;
  /** 纯色白块所在的基础图集纹理与登记键（画笔据此注册纹理并复用白块 UV）。 */
  读取基础纹理(): { 键: string; 纹理: Texture };
  读取统计(): 文字服务统计;
  销毁(): void;
}

interface 图集项 {
  键: string;
  图集: 文字图集接口;
  释放: () => void;
  字号: number;
  字重: "常规" | "粗体" | "基础";
}

const 默认字体 = '"Segoe UI", "Microsoft YaHei", sans-serif';
const 基础图集键 = "文字/基础";
const 基础页面边长 = 64;
const 描边方向数 = 8;
const 白块兜底: 紫外线矩形 = { u: 0, v: 0, 宽: 1, 高: 1 };

let 缓存保守字符集: string | null = null;

/**
 * 预烘焙字符集（保守超集）：`代码/语言/简体中文.ts` 的全部中文、ASCII 可打印字符、
 * 代码里会出现的 CJK 标点，以及启动层原本手写的界面词汇。页面里新出现的字仍会在
 * 首次绘制时按需补烘进同一张图集，这里只是尽量避免运行时补字撞上页满边界。
 */
function 读取保守字符集(): string {
  if (缓存保守字符集) return 缓存保守字符集;
  const 字符 = new Set<string>();
  const 加入 = (文本: string) => {
    for (const 项 of 文本) 字符.add(项);
  };
  for (const 文本 of Object.values(中文文案)) 加入(文本);
  加入(
    "再消一行Three版主界面设置成就排行榜商店开始马拉松冲刺极限每日挑战返回重新开始继续暂停离开分数消行等级连击金币购买穿戴暂存下一个提示目标达成完赛挑战局结算",
  );
  加入("，。！？、：；（）「」『』“”‘’…—·《》【】");
  for (let 码 = 32; 码 <= 126; 码++) 字符.add(String.fromCharCode(码));
  缓存保守字符集 = [...字符].join("");
  return 缓存保守字符集;
}

/** 按字号选页边长：小字 512 省显存，中大字号 1024 装下保守字符集。 */
function 选择页面边长(字号: number): number {
  return 字号 <= 16 ? 512 : 1024;
}

function 颜色顶点(颜色: number | string, 透明度: number): 顶点颜色 {
  const 数值 = 解析颜色数值(颜色);
  return [
    ((数值 >> 16) & 0xff) / 255,
    ((数值 >> 8) & 0xff) / 255,
    (数值 & 0xff) / 255,
    Math.min(1, Math.max(0, 透明度)),
  ];
}

function 锚点偏移(
  锚点: 文字项["锚点"],
  宽: number,
  高: number,
  x: number,
  y: number,
): { x: number; y: number } {
  switch (锚点) {
    case "左上":
      return { x, y };
    case "左中":
      return { x, y: y - 高 / 2 };
    case "中上":
      return { x: x - 宽 / 2, y };
    case "中中":
      return { x: x - 宽 / 2, y: y - 高 / 2 };
    case "右上":
      return { x: x - 宽, y };
    case "右中":
      return { x: x - 宽, y: y - 高 / 2 };
  }
}

export function 创建文字服务(选项: 文字服务选项): 文字服务 {
  const 像素比 = 选项.像素比 ?? 1;
  if (!Number.isFinite(像素比) || 像素比 <= 0) throw new Error("文字服务像素比必须是正数");
  const 字体 = 选项.字体 ?? 默认字体;
  const 创建图集 = 选项.创建图集 ?? ((图集选项: 文字图集选项) => 创建文字图集(图集选项));
  const 图集表 = new Map<string, 图集项>();

  const 创建并登记 = (
    图集选项: 文字图集选项,
    键: string,
    字号: number,
    字重: 图集项["字重"],
  ): 图集项 => {
    const 图集 = 创建图集(图集选项);
    const 统计 = 图集.读取统计();
    const 释放 = 选项.登记纹理(键, 图集.读取纹理(), 统计.页面边长 * 统计.页面边长 * 4);
    const 项: 图集项 = { 键, 图集, 释放, 字号, 字重 };
    图集表.set(键, 项);
    return 项;
  };

  // 基础图集只提供纯色白块 UV（画笔的所有纯色图元共用），不预烘焙字形。
  // 启动层把老页面的小号图集作为纯色来源传进来，纯色图元与老控件同纹理、同批次，调用顺序即遮挡。
  const 外部纯色 = 选项.纯色来源 ?? null;
  const 基础 = 外部纯色
    ? null
    : 创建并登记(
        {
          字体,
          字号: 选项.基础字号 ?? 14,
          字重: "normal",
          像素比: 1,
          页面边长: 基础页面边长,
        },
        基础图集键,
        0,
        "基础",
      );

  const 获取图集 = (样式: 文字样式): 图集项 => {
    if (!Number.isFinite(样式.字号) || 样式.字号 <= 0) throw new Error("文字样式字号必须是正数");
    const 样式字体 = 样式.字体 ?? 字体;
    const 样式字重 = 样式.字重 ?? "常规";
    const 键 = `文字/${样式字体}|${样式.字号}|${样式字重}`;
    const 已有 = 图集表.get(键);
    if (已有) return 已有;
    const 光栅字重 = 样式字重 === "粗体" ? "bold" : "normal";
    const 预烘焙字符集 = 读取保守字符集();
    let 最后错误: unknown = null;
    for (const 页面边长 of [选择页面边长(样式.字号), 1024, 2048]) {
      try {
        return 创建并登记(
          {
            字体: 样式字体,
            字号: 样式.字号,
            字重: 光栅字重,
            像素比,
            页面边长,
            预烘焙字符集,
          },
          键,
          样式.字号,
          样式字重,
        );
      } catch (错误) {
        // 预烘焙超集装不下时换更大的页；非「页已满」错误直接抛出，避免吞掉字体/参数问题。
        最后错误 = 错误;
        if (!(错误 instanceof Error) || !错误.message.includes("页已满")) throw 错误;
      }
    }
    throw 最后错误 instanceof Error ? 最后错误 : new Error(`无法创建文字图集：${键}`);
  };

  const 测量含字距 = (图集: 文字图集接口, 文本: string, 字距: number): number =>
    图集.测量(文本) + (字距 > 0 ? 字距 * Math.max(0, Array.from(文本).length - 1) : 0);

  const 排版行 = (文案: string, 样式: 文字样式, 图集: 文字图集接口, 最大宽?: number) => {
    const 字距 = 样式.字距 ?? 0;
    const 测量 = (文本: string) => 测量含字距(图集, 文本, 字距);
    const 行文本列表 =
      最大宽 === undefined || 最大宽 <= 0 ? 文案.split("\n") : 换行文本(文案, 最大宽, 测量);
    const 行 = 行文本列表.map((文本) => ({ 文本, 宽: 测量(文本) }));
    const 宽 = 行.reduce((最大, 项) => Math.max(最大, 项.宽), 0);
    const 行高 = 样式.行高 ?? 图集.读取行高();
    return { 行, 宽, 高: 行.length * 行高 };
  };

  const 写一行 = (
    合批: 图元写入接口,
    图集: 文字图集接口,
    文本: string,
    左: number,
    上: number,
    颜色: 顶点颜色,
    字距: number,
    混合: 混合方式,
    纹理序号: number,
  ): void => {
    const 目标: 四边形状写入接口 =
      混合 === "普通"
        ? 合批
        : {
            添加: (形) => 合批.添加({ ...形, 混合: "叠加" }),
          };
    if (字距 <= 0) {
      图集.绘制(目标, 文本, { 左, 上, 颜色, 纹理序号 });
      return;
    }
    let 笔 = 左;
    for (const 字符 of 文本) {
      图集.绘制(目标, 字符, { 左: 笔, 上, 颜色, 纹理序号 });
      笔 += 图集.测量(字符) + 字距;
    }
  };

  const 绘制 = (
    合批: 图元写入接口,
    项: 文字项,
    绘制选项: 文字绘制选项 = {},
  ): { 宽: number; 高: number } => {
    const 样式 = 项.样式;
    const 图集项 = 获取图集(样式);
    const 图集 = 图集项.图集;
    const 纹理序号 = 合批.注册纹理(图集项.键, 图集.读取纹理());
    const 透明度 = 绘制选项.透明度 ?? 1;
    const 混合 = 绘制选项.混合 ?? "普通";
    const 排版 = 排版行(项.文案, 样式, 图集, 项.最大宽);
    const 行高 = 样式.行高 ?? 图集.读取行高();
    const 对齐 = 样式.对齐 ?? "左";
    const 字距 = 样式.字距 ?? 0;
    const 起点 = 锚点偏移(项.锚点, 排版.宽, 排版.高, 项.x, 项.y);
    const 正文颜色 = 颜色顶点(样式.颜色, 透明度);
    const 描边颜色 = 样式.描边 ? 颜色顶点(样式.描边.颜色, 透明度) : null;
    const 阴影颜色 = 样式.阴影 ? 颜色顶点(样式.阴影.颜色, 透明度) : null;
    const 画一遍 = (颜色: 顶点颜色, 偏移X: number, 偏移Y: number) => {
      for (const [行号, 行] of 排版.行.entries()) {
        const 行偏移 = 对齐 === "中" ? (排版.宽 - 行.宽) / 2 : 对齐 === "右" ? 排版.宽 - 行.宽 : 0;
        写一行(
          合批,
          图集,
          行.文本,
          起点.x + 行偏移 + 偏移X,
          起点.y + 行号 * 行高 + 偏移Y,
          颜色,
          字距,
          混合,
          纹理序号,
        );
      }
    };
    if (样式.阴影 && 阴影颜色) 画一遍(阴影颜色, 样式.阴影.偏移X, 样式.阴影.偏移Y);
    if (样式.描边 && 描边颜色) {
      // Phaser 的描边以字形轮廓为中心线，粗细/2 的 8 方向环足以盖住外沿。
      const 距离 = Math.max(0.5, 样式.描边.粗细 / 2);
      for (let 方向 = 0; 方向 < 描边方向数; 方向++) {
        const 角 = (Math.PI * 2 * 方向) / 描边方向数;
        画一遍(描边颜色, Math.cos(角) * 距离, Math.sin(角) * 距离);
      }
    }
    画一遍(正文颜色, 0, 0);
    return { 宽: 排版.宽, 高: 排版.高 };
  };

  const 测量 = (文案: string, 样式: 文字样式): { 宽: number; 高: number } => {
    const 图集项 = 获取图集(样式);
    return {
      宽: 测量含字距(图集项.图集, 文案, 样式.字距 ?? 0),
      高: 样式.行高 ?? 图集项.图集.读取行高(),
    };
  };

  return {
    绘制,
    测量,
    读取纯色紫外线: () =>
      外部纯色 ? 外部纯色.纯色紫外线 : (基础?.图集.读取纯色紫外线() ?? 白块兜底),
    读取基础纹理: () => {
      if (外部纯色) return { 键: 外部纯色.键, 纹理: 外部纯色.纹理 };
      if (!基础) throw new Error("文字服务缺少纯色来源与基础图集");
      return { 键: 基础.键, 纹理: 基础.图集.读取纹理() };
    },
    读取统计: () => {
      const 列表: 文字服务统计项[] = [];
      let 页数合计 = 0;
      let 纹理字节合计 = 0;
      for (const 项 of 图集表.values()) {
        const 统计 = 项.图集.读取统计();
        列表.push({
          键: 项.键,
          字号: 项.字号,
          字重: 项.字重,
          页数: 统计.页数,
          字形数: 统计.字形数,
          页面边长: 统计.页面边长,
          纹理字节: 统计.纹理字节,
        });
        页数合计 += 统计.页数;
        纹理字节合计 += 统计.纹理字节;
      }
      return { 图集数: 图集表.size, 页数: 页数合计, 纹理字节: 纹理字节合计, 图集列表: 列表 };
    },
    销毁: () => {
      for (const 项 of 图集表.values()) {
        项.释放();
        项.图集.销毁();
      }
      图集表.clear();
    },
  };
}

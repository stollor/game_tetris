/**
 * Three 版文字服务：按 (字体, 字号, 字重, 光栅像素比) 懒创建 GM `文字图集`，把 `文字项` 渲染成合批四边形。
 *
 * - 字形白色光栅化进图集，颜色交给合批顶点色 tint；
 * - 描边用 8 方向偏移的同色副本模拟（Phaser 的 stroke 是沿字形轮廓，这里按粗细/2 的环近似）；
 * - 阴影用偏移暗色副本；
 * - 折行走 GM `文本换行`（中文行首/行尾禁则）；
 * - 光栅像素比对齐 Phaser 文字最低分辨率 2（`Phaser框架/界面/文字清晰度.ts`）：DPR1 也按 2x
 *   光栅、DPR≥2 与画布同倍率，小字不会因 1x 光栅丢笔画；
 * - DPR1 的 2x 字形把位图宽高与页内位置对齐到 2 纹理像素（`对齐像素`），降到 1x 画布时
 *   图元正好覆盖整数设备像素，双线性采样不跨半纹素；
 * - 合批四边形定位到设备像素网格（同 Phaser 文字的 vertexRoundMode=full），避免半像素重采样发虚；
 * - 按实际出现的字符从 256 页开始懒烘焙，满页倍增到 512/1024/2048 并保留已见字符；
 * - 纹理通过注入的 `登记纹理` 进渲染编排的纹理预算，销毁时释放。
 */

/** 文字图集实例里文字服务真正用到的子集；测试可注入假图集（Bun 里没有 canvas）。 */

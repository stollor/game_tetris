const 默认字体 = '"Segoe UI", "Microsoft YaHei", sans-serif';
const 基础图集键 = "文字/基础";
const 基础页面边长 = 64;
const 描边方向数 = 8;
/** 文字光栅最低像素比：与 Phaser 文字最低分辨率 2 同口径，DPR1 也按 2x 光栅。 */
const 最低光栅像素比 = 2;

/** 画布像素比 → 文字光栅像素比：画布 ≥2 与画布同倍率，画布 <2 按 2x 光栅。 */
export function 计算光栅像素比(画布像素比: number): number {
  if (!Number.isFinite(画布像素比) || 画布像素比 <= 0) throw new Error("画布像素比必须是正数");
  return 画布像素比 >= 最低光栅像素比 ? 画布像素比 : 最低光栅像素比;
}

/**
 * 光栅像素比相对画布的整数倍数：2x 光栅降到 1x 画布时为 2，用来把字形位图宽高与页内位置
 * 对齐到纹理像素倍数，保证图元宽度是整数设备像素。非整数倍数（如 1.5 倍画布）返回 1。
 */
export function 计算对齐像素(光栅像素比: number, 画布像素比: number): number {
  const 倍数 = 光栅像素比 / 画布像素比;
  return Number.isInteger(倍数) && 倍数 >= 2 ? 倍数 : 1;
}

function 颜色顶点(颜色: number | string, 透明度: number): 顶点颜色 {
  const 数值 = 解析颜色数值(颜色);
  return [
    ((数值 >> 16) & 0xff) / 255,
    ((数值 >> 8) & 0xff) / 255,
    (数值 & 0xff) / 255,
    Math.min(1, Math.max(0, 透明度)),
  ];
}

function 锚点偏移(
  锚点: 文字项["锚点"],
  宽: number,
  高: number,
  x: number,
  y: number,
): { x: number; y: number } {
  switch (锚点) {
    case "左上":
      return { x, y };
    case "左中":
      return { x, y: y - 高 / 2 };
    case "中上":
      return { x: x - 宽 / 2, y };
    case "中中":
      return { x: x - 宽 / 2, y: y - 高 / 2 };
    case "右上":
      return { x: x - 宽, y };
    case "右中":
      return { x: x - 宽, y: y - 高 / 2 };
  }
}

export function 创建文字服务(选项: 文字服务选项): 文字服务 {
  let 画布像素比 = 选项.像素比 ?? 1;
  if (!Number.isFinite(画布像素比) || 画布像素比 <= 0) throw new Error("文字服务像素比必须是正数");
  let 光栅像素比 = 计算光栅像素比(画布像素比);
  let 对齐像素 = 计算对齐像素(光栅像素比, 画布像素比);
  const 字体 = 选项.字体 ?? 默认字体;
  const 创建图集 = 选项.创建图集 ?? ((图集选项: 文字图集选项) => 创建文字图集(图集选项));
  const 图集表 = new Map<string, 图集项>();
  const 预算 = 选项.纹理预算字节 ?? 28 * 1024 * 1024;
  let 帧 = 0;
  let 版本 = 0;
  const 待释放: 图集项[] = [];
  const 释放图集 = (项: 图集项) => {
    项.释放();
    选项.移除纹理?.(项.纹理键);
    项.图集.销毁();
  };
  const 腾出空间 = (字节: number) => {
    let 已用 = [...图集表.values(), ...待释放].reduce(
      (总, 项) => 总 + 项.图集.读取统计().纹理字节,
      0,
    );
    for (const [键, 项] of 图集表) {
      if (已用 + 字节 <= 预算) break;
      if (项.字重 === "基础" || 项.使用帧 === 帧) continue;
      已用 -= 项.图集.读取统计().纹理字节;
      图集表.delete(键);
      释放图集(项);
    }
    if (已用 + 字节 > 预算) throw new Error(`文字纹理预算不足：${已用} + ${字节} > ${预算}`);
  };

  const 创建并登记 = (
    图集选项: 文字图集选项,
    键: string,
    字号: number,
    字重: 图集项["字重"],
  ): 图集项 => {
    const 字节 = (图集选项.页面边长 ?? 1024) ** 2 * 4;
    腾出空间(字节);
    const 图集 = 创建图集(图集选项);
    const 统计 = 图集.读取统计();
    const 纹理键 = 字重 === "基础" ? 键 : `${键}#${++版本}`;
    let 释放: () => void;
    try {
      释放 = 选项.登记纹理(纹理键, 图集.读取纹理(), 统计.纹理字节);
    } catch (错误) {
      图集.销毁();
      throw 错误;
    }
    const 项: 图集项 = {
      键,
      纹理键,
      图集,
      释放,
      字号,
      字重,
      创建选项: 图集选项,
      字符集: new Set(图集选项.预烘焙字符集 ?? ""),
      使用帧: 帧,
    };
    图集表.set(键, 项);
    return 项;
  };

  const 容错执行 = <结果>(项: 图集项, 文本: string, 执行: () => 结果): 结果 => {
    for (const 字 of 文本) 项.字符集.add(字);
    for (;;) {
      try {
        项.图集.注册(文本);
        return 执行();
      } catch (错误) {
        if (!(错误 instanceof Error) || !错误.message.includes("页已满")) throw 错误;
        let 边长 = 项.图集.读取统计().页面边长 * 2;
        let 新选项: 文字图集选项;
        let 新图集: 文字图集接口;
        for (;;) {
          if (边长 > 2048) throw 错误;
          新选项 = { ...项.创建选项, 页面边长: 边长, 预烘焙字符集: [...项.字符集].join("") };
          腾出空间(边长 ** 2 * 4);
          try {
            新图集 = 创建图集(新选项);
            break;
          } catch (错误) {
            if (!(错误 instanceof Error) || !错误.message.includes("页已满")) throw 错误;
            边长 *= 2;
          }
        }
        const 纹理键 = `${项.键}#${++版本}`;
        let 释放: () => void;
        try {
          释放 = 选项.登记纹理(纹理键, 新图集.读取纹理(), 边长 ** 2 * 4);
        } catch (错误) {
          新图集.销毁();
          throw 错误;
        }
        待释放.push({ ...项 });
        项.图集 = 新图集;
        项.纹理键 = 纹理键;
        项.释放 = 释放;
        项.创建选项 = 新选项;
        // 重建前已出现的文本也要保留，不能只注册当前一行。
        项.图集.注册([...项.字符集].join(""));
      }
    }
  };

  // 基础图集只提供纯色白块 UV（画笔的所有纯色图元共用），不预烘焙字形。
  const 基础 = 创建并登记(
    {
      字体,
      字号: 选项.基础字号 ?? 14,
      字重: "normal",
      像素比: 1,
      页面边长: 基础页面边长,
    },
    基础图集键,
    0,
    "基础",
  );

  const 获取图集 = (样式: 文字样式): 图集项 => {
    if (!Number.isFinite(样式.字号) || 样式.字号 <= 0) throw new Error("文字样式字号必须是正数");
    const 样式字体 = 样式.字体 ?? 字体;
    const 样式字重 = 样式.字重 ?? "常规";
    const 键 = `文字/${样式字体}|${样式.字号}|${样式字重}|${光栅像素比}`;
    const 已有 = 图集表.get(键);
    if (已有) {
      已有.使用帧 = 帧;
      return 已有;
    }
    const 光栅字重 = 样式字重 === "粗体" ? "bold" : "normal";
    let 最后错误: unknown = null;
    // 只烘焙实际出现的字符：DPR1 也按 2x 光栅，预烘焙整份中文超集会让图集页数失控。
    for (const 页面边长 of [256, 512, 1024, 2048]) {
      try {
        return 创建并登记(
          {
            字体: 样式字体,
            字号: 样式.字号,
            字重: 光栅字重,
            像素比: 光栅像素比,
            对齐像素,
            页面边长,
          },
          键,
          样式.字号,
          样式字重,
        );
      } catch (错误) {
        // 首次补字装不下时换更大的页；非「页已满」错误直接抛出，避免吞掉字体/参数问题。
        最后错误 = 错误;
        if (!(错误 instanceof Error) || !错误.message.includes("页已满")) throw 错误;
      }
    }
    throw 最后错误 instanceof Error ? 最后错误 : new Error(`无法创建文字图集：${键}`);
  };

  const 测量含字距 = (图集: 文字图集接口, 文本: string, 字距: number): number =>
    图集.测量(文本) + (字距 > 0 ? 字距 * Math.max(0, Array.from(文本).length - 1) : 0);

  const 排版行 = (文案: string, 样式: 文字样式, 图集: 文字图集接口, 最大宽?: number) => {
    const 字距 = 样式.字距 ?? 0;
    const 测量 = (文本: string) => 测量含字距(图集, 文本, 字距);
    const 行文本列表 =
      最大宽 === undefined || 最大宽 <= 0 ? 文案.split("\n") : 换行文本(文案, 最大宽, 测量);
    const 行 = 行文本列表.map((文本) => ({ 文本, 宽: 测量(文本) }));
    const 宽 = 行.reduce((最大, 项) => Math.max(最大, 项.宽), 0);
    const 行高 = 样式.行高 ?? 图集.读取行高();
    return { 行, 宽, 高: 行.length * 行高 };
  };

  const 写一行 = (
    合批: 图元写入接口,
    图集: 文字图集接口,
    文本: string,
    左: number,
    上: number,
    颜色: 顶点颜色,
    字距: number,
    混合: 混合方式,
    纹理序号: number,
  ): void => {
    const 目标: 四边形状写入接口 =
      混合 === "普通"
        ? 合批
        : {
            添加: (形) => 合批.添加({ ...形, 混合: "叠加" }),
          };
    if (字距 <= 0) {
      图集.绘制(目标, 文本, { 左, 上, 颜色, 纹理序号 });
      return;
    }
    let 笔 = 左;
    for (const 字符 of 文本) {
      图集.绘制(目标, 字符, { 左: 笔, 上, 颜色, 纹理序号 });
      笔 += 图集.测量(字符) + 字距;
    }
  };

  const 绘制 = (
    合批: 图元写入接口,
    项: 文字项,
    绘制选项: 文字绘制选项 = {},
  ): { 宽: number; 高: number } => {
    const 样式 = 项.样式;
    const 缩放 = 项.缩放 ?? 1;
    if (!Number.isFinite(缩放) || 缩放 <= 0) throw new Error("文字缩放必须是正数");
    // 四边形顶点的世界坐标落到设备像素网格：半像素偏移会让双线性采样平均相邻纹素，
    // 小字整行发灰、细笔画被削掉。Phaser 文字用 vertexRoundMode=full 做同一件事。
    const 对齐设备像素 = (值: number) => Math.round(值 * 画布像素比) / 画布像素比;
    const 写入: 图元写入接口 = {
      添加: (形) => {
        const 左 = 缩放 === 1 ? 形.左 : 项.x + (形.左 - 项.x) * 缩放;
        const 上 = 缩放 === 1 ? 形.上 : 项.y + (形.上 - 项.y) * 缩放;
        return 合批.添加({
          ...形,
          左: 对齐设备像素(左),
          上: 对齐设备像素(上),
          宽: 形.宽 * 缩放,
          高: 形.高 * 缩放,
        });
      },
      注册纹理: (键, 纹理) => 合批.注册纹理(键, 纹理),
      添加三角形: (形) => 合批.添加三角形(形),
    };
    const 图集项 = 获取图集(样式);
    const 排版 = 容错执行(图集项, 项.文案, () => 排版行(项.文案, 样式, 图集项.图集, 项.最大宽));
    const 图集 = 图集项.图集;
    const 纹理序号 = 合批.注册纹理(图集项.纹理键, 图集.读取纹理());
    const 透明度 = 绘制选项.透明度 ?? 1;
    const 混合 = 绘制选项.混合 ?? "普通";
    const 行高 = 样式.行高 ?? 图集.读取行高();
    const 对齐 = 样式.对齐 ?? "左";
    const 字距 = 样式.字距 ?? 0;
    const 起点 = 锚点偏移(项.锚点, 排版.宽, 排版.高, 项.x, 项.y);
    const 正文颜色 = 颜色顶点(样式.颜色, 透明度);
    const 描边颜色 = 样式.描边 ? 颜色顶点(样式.描边.颜色, 透明度) : null;
    const 阴影颜色 = 样式.阴影 ? 颜色顶点(样式.阴影.颜色, 透明度) : null;
    const 画一遍 = (颜色: 顶点颜色, 偏移X: number, 偏移Y: number) => {
      for (const [行号, 行] of 排版.行.entries()) {
        const 行偏移 = 对齐 === "中" ? (排版.宽 - 行.宽) / 2 : 对齐 === "右" ? 排版.宽 - 行.宽 : 0;
        写一行(
          写入,
          图集,
          行.文本,
          起点.x + 行偏移 + 偏移X,
          起点.y + 行号 * 行高 + 偏移Y,
          颜色,
          字距,
          混合,
          纹理序号,
        );
      }
    };
    if (样式.阴影 && 阴影颜色) 画一遍(阴影颜色, 样式.阴影.偏移X, 样式.阴影.偏移Y);
    if (样式.描边 && 描边颜色) {
      // Phaser 的描边以字形轮廓为中心线，粗细/2 的 8 方向环足以盖住外沿。
      const 距离 = Math.max(0.5, 样式.描边.粗细 / 2);
      for (let 方向 = 0; 方向 < 描边方向数; 方向++) {
        const 角 = (Math.PI * 2 * 方向) / 描边方向数;
        画一遍(描边颜色, Math.cos(角) * 距离, Math.sin(角) * 距离);
      }
    }
    画一遍(正文颜色, 0, 0);
    return { 宽: 排版.宽 * 缩放, 高: 排版.高 * 缩放 };
  };

  const 测量 = (文案: string, 样式: 文字样式): { 宽: number; 高: number } => {
    const 图集项 = 获取图集(样式);
    const 宽 = 容错执行(图集项, 文案, () => 测量含字距(图集项.图集, 文案, 样式.字距 ?? 0));
    return { 宽, 高: 样式.行高 ?? 图集项.图集.读取行高() };
  };

  return {
    绘制,
    测量,
    开始帧: () => {
      帧++;
    },
    结束帧: () => {
      for (const 项 of 待释放.splice(0)) 释放图集(项);
    },
    设置像素比: (值) => {
      if (!Number.isFinite(值) || 值 <= 0) throw new Error("文字服务像素比必须是正数");
      if (值 === 画布像素比) return;
      画布像素比 = 值;
      const 新光栅像素比 = 计算光栅像素比(值);
      const 新对齐像素 = 计算对齐像素(新光栅像素比, 值);
      // 光栅倍率没变（例如 DPR3 开省电降到 DPR2）时字形图集仍然有效，只更新合批对齐。
      if (新光栅像素比 === 光栅像素比 && 新对齐像素 === 对齐像素) return;
      光栅像素比 = 新光栅像素比;
      对齐像素 = 新对齐像素;
      for (const [键, 项] of 图集表) {
        if (项.字重 === "基础") continue;
        图集表.delete(键);
        待释放.push(项);
      }
    },
    读取纯色紫外线: () => 基础.图集.读取纯色紫外线(),
    读取基础纹理: () => ({ 键: 基础.键, 纹理: 基础.图集.读取纹理() }),
    读取统计: () => {
      const 列表: 文字服务统计项[] = [];
      let 页数合计 = 0;
      let 纹理字节合计 = 0;
      for (const 项 of 图集表.values()) {
        const 统计 = 项.图集.读取统计();
        列表.push({
          键: 项.键,
          字号: 项.字号,
          字重: 项.字重,
          页数: 统计.页数,
          字形数: 统计.字形数,
          页面边长: 统计.页面边长,
          纹理字节: 统计.纹理字节,
        });
        页数合计 += 统计.页数;
        纹理字节合计 += 统计.纹理字节;
      }
      return { 图集数: 图集表.size, 页数: 页数合计, 纹理字节: 纹理字节合计, 图集列表: 列表 };
    },
    销毁: () => {
      for (const 项 of [...图集表.values(), ...待释放.splice(0)]) 释放图集(项);
      图集表.clear();
    },
  };
}

import type {
  三角顶点,
  四边形状,
  图元写入接口,
  图元合批,
  纯色图案,
  顶点颜色,
} from "../../../框架Three/界面/图元合批";
import type { 矩形 } from "../../../组件/绘制/图形对象";
import type { 图形合批接口 } from "./Three图形";

/**
 * 裁剪写入器：给画笔的「图形对象 / 文字 / 图集帧 / 散图」加一个屏幕坐标裁剪矩形。
 *
 * 合批本身没有 scissor，滚动容器里的共享配方又是由页面用 `画笔.图形` 直接画的，
 * 不走 控件/裁剪.ts 的四边形写入器，所以这里在写入合批之前做几何裁剪：
 * - 轴对齐四边形：求交矩形并按比例重映射图集 UV（文字/图片/纯色块都走这条）；
 * - 三角形：逐顶点带 UV/颜色的 Sutherland–Hodgman 裁剪后再扇形三角化（圆、渐变、描边）；
 * - 纹理注册、图层查询、清空图层直接透传给真实合批，序号与外部一致。
 */

/** 裁剪写入器需要的合批能力；真实实现是 GM 图元合批（画笔只依赖这个结构）。 */
export type 裁剪合批接口 = 图形合批接口 & 图元写入接口 & Pick<图元合批, "读取纯色" | "设置纯色">;

export interface 裁剪写入选项 {
  /** 真实合批。 */
  合批: 裁剪合批接口;
  /** 屏幕坐标裁剪矩形；超出部分不写入。 */
  裁剪: 矩形;
  /** 画笔的纯色白块配置（添加纯色需要按裁剪重映射 UV）。 */
  纯色: 纯色图案 | null;
}

interface 带属性点 {
  x: number;
  y: number;
  u: number;
  v: number;
  颜色: 顶点颜色;
}

const 白: 顶点颜色 = [1, 1, 1, 1];

function 裁剪四边形(形: 四边形状, 裁剪: 矩形): 四边形状 | null {
  const 原右 = 形.左 + 形.宽;
  const 原下 = 形.上 + 形.高;
  const 左 = Math.max(形.左, 裁剪.左);
  const 上 = Math.max(形.上, 裁剪.上);
  const 右 = Math.min(原右, 裁剪.左 + 裁剪.宽);
  const 下 = Math.min(原下, 裁剪.上 + 裁剪.高);
  if (右 <= 左 || 下 <= 上) return null;
  const 结果: 四边形状 = { 左, 上, 宽: 右 - 左, 高: 下 - 上 };
  if (形.紫外线) {
    const 比例X = (右 - 左) / 形.宽;
    const 比例Y = (下 - 上) / 形.高;
    const 偏移X = (左 - 形.左) / 形.宽;
    const 偏移Y = (原下 - 下) / 形.高;
    结果.紫外线 = {
      u: 形.紫外线.u + 形.紫外线.宽 * 偏移X,
      // v 指左下角、向上为正：裁剪掉底部时 v 上移，裁剪掉顶部时高度缩短。
      v: 形.紫外线.v + 形.紫外线.高 * 偏移Y,
      宽: 形.紫外线.宽 * 比例X,
      高: 形.紫外线.高 * 比例Y,
    };
  }
  if (形.颜色) 结果.颜色 = 形.颜色;
  if (形.混合) 结果.混合 = 形.混合;
  if (形.纹理 !== undefined) 结果.纹理 = 形.纹理;
  return 结果;
}

function 三角形顶点(顶点: 三角顶点): 带属性点 {
  return {
    x: 顶点.x,
    y: 顶点.y,
    u: 顶点.u ?? 0,
    v: 顶点.v ?? 0,
    颜色: 顶点.颜色 ?? 白,
  };
}

function 插值点(甲: 带属性点, 乙: 带属性点, 比例: number): 带属性点 {
  return {
    x: 甲.x + (乙.x - 甲.x) * 比例,
    y: 甲.y + (乙.y - 甲.y) * 比例,
    u: 甲.u + (乙.u - 甲.u) * 比例,
    v: 甲.v + (乙.v - 甲.v) * 比例,
    颜色: [
      甲.颜色[0] + (乙.颜色[0] - 甲.颜色[0]) * 比例,
      甲.颜色[1] + (乙.颜色[1] - 甲.颜色[1]) * 比例,
      甲.颜色[2] + (乙.颜色[2] - 甲.颜色[2]) * 比例,
      甲.颜色[3] + (乙.颜色[3] - 甲.颜色[3]) * 比例,
    ],
  };
}

interface 半平面 {
  在内部(点: 带属性点): boolean;
  /** 点 在边界外时，返回 点到交点 的比例；调用方保证 点在内部、另一点在外部。 */
  交点比例(内部点: 带属性点, 外部点: 带属性点): number;
}

function 创建半平面(裁剪: 矩形): 半平面[] {
  const 右 = 裁剪.左 + 裁剪.宽;
  const 下 = 裁剪.上 + 裁剪.高;
  return [
    {
      在内部: (点) => 点.x >= 裁剪.左,
      交点比例: (内部, 外部) => (内部.x - 裁剪.左) / (内部.x - 外部.x),
    },
    {
      在内部: (点) => 点.x <= 右,
      交点比例: (内部, 外部) => (右 - 内部.x) / (外部.x - 内部.x),
    },
    {
      在内部: (点) => 点.y >= 裁剪.上,
      交点比例: (内部, 外部) => (内部.y - 裁剪.上) / (内部.y - 外部.y),
    },
    {
      在内部: (点) => 点.y <= 下,
      交点比例: (内部, 外部) => (下 - 内部.y) / (外部.y - 内部.y),
    },
  ];
}

function 裁剪多边形(点集: readonly 带属性点[], 裁剪: 矩形): 带属性点[] {
  let 结果: 带属性点[] = [...点集];
  for (const 半平面 of 创建半平面(裁剪)) {
    if (结果.length === 0) return [];
    const 下一轮: 带属性点[] = [];
    for (let 序号 = 0; 序号 < 结果.length; 序号++) {
      const 当前 = 结果[序号];
      const 下个 = 结果[(序号 + 1) % 结果.length];
      if (!当前 || !下个) continue;
      const 当前内 = 半平面.在内部(当前);
      const 下个内 = 半平面.在内部(下个);
      if (当前内) 下一轮.push(当前);
      if (当前内 !== 下个内) 下一轮.push(插值点(当前, 下个, 半平面.交点比例(当前, 下个)));
    }
    结果 = 下一轮;
  }
  return 结果;
}

export class 裁剪写入 implements 图形合批接口, 图元写入接口 {
  private readonly 合批: 裁剪合批接口;
  private readonly 裁剪: 矩形;
  private 纯色: 纯色图案 | null;

  constructor(选项: 裁剪写入选项) {
    this.合批 = 选项.合批;
    this.裁剪 = { ...选项.裁剪 };
    this.纯色 = 选项.纯色;
  }

  /** 文字图集/图元合批共用的四边形写入。 */
  添加(形: 四边形状): boolean {
    return this.添加四边形(形);
  }

  添加四边形(形: 四边形状): boolean {
    const 裁剪后 = 裁剪四边形(形, this.裁剪);
    if (!裁剪后) return true;
    return this.合批.添加四边形(裁剪后);
  }

  添加三角形(形: {
    顶点: readonly [三角顶点, 三角顶点, 三角顶点];
    混合?: "普通" | "叠加";
    纹理?: number;
  }): boolean {
    const 多边形 = 裁剪多边形(形.顶点.map(三角形顶点), this.裁剪);
    if (多边形.length < 3) return true;
    const 首 = 多边形[0];
    if (!首) return true;
    for (let 序号 = 1; 序号 < 多边形.length - 1; 序号++) {
      const 乙 = 多边形[序号];
      const 丙 = 多边形[序号 + 1];
      if (!乙 || !丙) continue;
      this.合批.添加三角形({
        顶点: [to顶点(首), to顶点(乙), to顶点(丙)],
        混合: 形.混合,
        纹理: 形.纹理,
      });
    }
    return true;
  }

  添加纯色(
    左: number,
    上: number,
    宽: number,
    高: number,
    颜色: 顶点颜色,
    混合?: "普通" | "叠加",
  ): boolean {
    const 纯色 = this.纯色;
    if (!纯色) return this.合批.添加纯色(左, 上, 宽, 高, 颜色, 混合);
    return this.添加四边形({
      左,
      上,
      宽,
      高,
      紫外线: 纯色.紫外线,
      颜色,
      混合,
      纹理: 纯色.纹理 ?? 0,
    });
  }

  注册纹理(键: string, 纹理: Parameters<图元合批["注册纹理"]>[1]): number {
    return this.合批.注册纹理(键, 纹理);
  }

  读取图层(): number {
    return this.合批.读取图层();
  }

  清空图层(图层: number): number {
    return this.合批.清空图层(图层);
  }

  设置纯色(图案: 纯色图案): void {
    this.纯色 = 图案;
    this.合批.设置纯色(图案);
  }
}

function to顶点(点: 带属性点): 三角顶点 {
  return { x: 点.x, y: 点.y, u: 点.u, v: 点.v, 颜色: 点.颜色 };
}

/** 求两个屏幕矩形的交集；无交集返回 null。 */
export function 裁剪矩形交集(甲: 矩形, 乙: 矩形): 矩形 | null {
  const 左 = Math.max(甲.左, 乙.左);
  const 上 = Math.max(甲.上, 乙.上);
  const 右 = Math.min(甲.左 + 甲.宽, 乙.左 + 乙.宽);
  const 下 = Math.min(甲.上 + 甲.高, 乙.上 + 乙.高);
  if (右 <= 左 || 下 <= 上) return null;
  return { 左, 上, 宽: 右 - 左, 高: 下 - 上 };
}

export function 创建裁剪写入(选项: 裁剪写入选项): 裁剪写入 {
  return new 裁剪写入(选项);
}

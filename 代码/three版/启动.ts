/**
 * 《再消一行》Three 版入口：把渲染/资源/服务/导航/场景栈/循环/调试桥装配起来。
 * 页面只实现 `页面实例` 接口；启动层负责页面缓存、导航语义、按需渲染、60fps 上限、失焦暂停。
 * 通用页面生命周期、清理和图层作用域由框架管理，游戏只注册页面、参数与策略。
 */

const 字体 = '"Segoe UI", "Microsoft YaHei", sans-serif';
/** 高清文字按实际文本懒烘焙，文字预算28MB；总32MB保留静态资源与扩容余量。 */
const 纹理预算字节 = 32 * 1024 * 1024;

const 容器 = document.getElementById("游戏容器");
if (!容器) throw new Error("缺少 #游戏容器");

// —— 渲染与共享资源 ——
const 服务 = 创建应用服务({ 主题工厂: (设置) => 创建主题服务({ 设置 }) });
const 读取像素比 = () =>
  计算画布像素比(window.devicePixelRatio, 计算像素比上限(是省电模式(服务.设置.读取().省电模式)));
const 渲染 = 创建渲染编排({
  容器,
  逻辑宽: 1440,
  逻辑高: 900,
  适配策略: "重排",
  像素比: 读取像素比(),
  清屏色: 游戏外观.颜色.底色,
  最大帧率: 60,
  按需渲染: true,
  纹理预算字节,
});
// 全应用一张图元合批：页面/共享配方统一走 画笔（图元 + 按样式懒建的文字图集 + GM 图集帧/散图）。
// 每批（图层×纹理×混合）按小初始容量起步、超出自动 2 倍扩容，受容量上限约束：
// 初始 1024 四边形/4096 三角形 ≈ 663KB 缓冲/批；上限 8192/65536 时单批最大约 9.2MB。
const 合批 = new 图元合批({ 初始四边形数: 1024, 初始三角形数: 4096 });
渲染.场景.add(合批.提交());

// —— 新绘制层：GM 静态图集资源 + 共享文字服务 + 画笔 ——
const 显示启动错误 = (错误: unknown): void => {
  const 文本 = 错误 instanceof Error ? 错误.message : String(错误);
  console.error("Three 版启动失败", 错误);
  const 提示 = document.createElement("div");
  提示.setAttribute("role", "alert");
  提示.style.cssText =
    "position:fixed;left:16px;right:16px;bottom:16px;z-index:10;padding:12px 14px;border:1px solid #ff2d9b;border-radius:8px;background:#1a0b16;color:#ffd7ec;font:13px/1.6 sans-serif;white-space:pre-wrap";
  提示.textContent = `资源加载失败：${文本}`;
  容器.append(提示);
};
let 资源层: 资源层实例;
try {
  资源层 = await 创建资源层({
    登记纹理: 渲染.登记纹理,
    // 游戏运行时只加载游戏图标；GM 套件「圣所」样张只给资源验收页用（见 资源/验收页.ts），
    // 避免把 6.3MB 开发参考图算进 32MB 纹理预算。
    散图: [{ 键: "图标/游戏图标", 来源: "资源", 路径: "图标/游戏图标.png" }],
  });
} catch (错误) {
  显示启动错误(错误);
  throw 错误;
}
const 文字 = 创建文字服务({
  登记纹理: 渲染.登记纹理,
  字体,
  像素比: 读取像素比(),
  移除纹理: (键) => {
    合批.移除纹理(键);
    渲染.移除闲置纹理(键);
  },
});
// 画笔把文字服务的基础白块纹理注册进合批（序号 3 起），纯色图元复用白块 UV。
const 画笔 = 创建画笔({ 合批, 文字服务: 文字, 资源层 });

const 命中 = new 命中分发();
const 绑定指针 = 绑定画布指针(渲染.画布, 命中, {
  get 宽() {
    return 渲染.读取逻辑尺寸().宽;
  },
  get 高() {
    return 渲染.读取逻辑尺寸().高;
  },
});

// —— 服务与性能 ——
const 性能 = 创建性能控制(渲染, 服务.设置);
let 对局进行中 = false;

// —— 页面上下文 ——
let 上下文参数: 页面参数 = {};
const 图层 = new 图层作用域(合批);
const 资源: 页面资源 = {
  get 逻辑宽() {
    return 渲染.读取逻辑尺寸().宽;
  },
  get 逻辑高() {
    return 渲染.读取逻辑尺寸().高;
  },
  合批,
  画笔,
  资源: 资源层,
  读取纹理统计: () => 资源层.读取统计(),
  命中,
  读取帧统计: () => {
    const 渲染统计 = 渲染.读取统计();
    const 循环统计 = 循环.读取统计();
    const 合批统计 = 合批.读取统计();
    return {
      帧数: 循环统计.帧数,
      平均帧间隔毫秒: 循环统计.平均帧间隔毫秒,
      平均工作毫秒: 循环统计.平均工作毫秒,
      绘制调用: 渲染统计.绘制调用,
      四边形数: 合批统计.四边形数,
      三角形数: 合批统计.三角形数,
      纹理字节: 渲染统计.纹理字节,
    };
  },
  请求重绘: () => 渲染.请求重绘(),
  设置绘制层: (偏移) => {
    图层.设置子层(偏移);
  },
  设置镜头偏移: (x, y) => {
    渲染.相机.position.x = -x;
    渲染.相机.position.y = -y;
  },
  设置玩法进行中: (进行中) => {
    对局进行中 = 进行中;
    性能.设置页面(读取页面编号(), 进行中);
  },
};

const 导航: 导航服务 = {
  进入: (页, 参数 = {}) => 宿主.进入(页, 参数),
  替换: (页, 参数 = {}) => 宿主.替换(页, 参数),
  返回: () => 宿主.返回(),
  打开覆盖: (页, 参数 = {}) => 宿主.打开覆盖(页, 参数),
  关闭覆盖: () => 宿主.关闭覆盖(),
  读取当前: () => {
    const 当前 = 宿主.读取当前();
    return { 页面: 当前.页面 as 页面编号, 覆盖: 当前.覆盖 as 覆盖页编号 | null };
  },
};
const 上下文: 页面上下文 = {
  资源,
  服务,
  导航,
  参数: 上下文参数,
  get 主题() {
    return 服务.主题.读取();
  },
  登记清理: () => {
    throw new Error("页面必须使用宿主提供的清理作用域");
  },
};
const 页面工厂 = new Map<string, (上下文: 页面上下文) => 页面实例>();
for (const [名称, 工厂] of Object.entries({
  ...创建页面表(上下文),
  对局: 创建对局页面,
  结算: 创建结算页面,
})) {
  if (工厂) 页面工厂.set(名称, 工厂);
}
const 宿主 = new 页面宿主<页面上下文, 页面实例>(上下文, {
  根页: "主界面",
  命中,
  创建页面: (名称, 登记清理) => {
    const 工厂 = 页面工厂.get(名称);
    if (!工厂) throw new Error(`未注册页面：${名称}`);
    // 参数和主题保持实时读取，清理闭包始终归属创建的页面。
    const 页面上下文: 页面上下文 = {
      ...上下文,
      get 参数() {
        return 上下文.参数;
      },
      get 主题() {
        return 上下文.主题;
      },
      登记清理,
    };
    return 工厂(页面上下文);
  },
  应用参数: (参数) => {
    上下文参数 = { ...参数 };
    上下文.参数 = 上下文参数;
  },
  变化: () => 性能.设置页面(读取页面编号(), 对局进行中),
});
const 栈 = 宿主.栈;
const 读取页面编号 = (): 页面编号 => 宿主.读取当前().页面 as 页面编号;
宿主.进入("主界面");

let 上次布局签名 = `${资源.逻辑宽}|${资源.逻辑高}|${服务.设置.读取().屏幕适配}`;
const 调整页面尺寸 = () => {
  const 像素比 = 读取像素比();
  渲染.设置像素比(像素比);
  文字.设置像素比(像素比);
  渲染.调整尺寸();
  const 布局签名 = `${资源.逻辑宽}|${资源.逻辑高}|${服务.设置.读取().屏幕适配}`;
  if (布局签名 === 上次布局签名) return;
  上次布局签名 = 布局签名;
  宿主.逐页((页) => 页.调整尺寸?.());
  渲染.请求重绘();
};
window.addEventListener("resize", 调整页面尺寸);
const 取消设置尺寸订阅 = 服务.设置.订阅(() => 调整页面尺寸());

// —— 循环与渲染 ——
const 循环 = 创建游戏循环({
  更新: (固定步长秒) => {
    栈.更新(固定步长秒);
  },
  渲染: () => {
    // 先做按需渲染/帧率判定：被节流或按需跳过时直接返回，不白做清空与逐页几何构建。
    if (!渲染.准备渲染()) return;
    合批.清空();
    文字.开始帧();
    // 场景栈从栈底到栈顶逐页渲染：每页一个绘制图层，页内多图集分批也不会串层。
    栈.逐层渲染((场景, 深度) => {
      图层.进入页面(深度, () => {
        画笔.重置();
        场景.渲染?.(上下文);
      });
    });
    合批.提交();
    渲染.渲染();
    文字.结束帧();
  },
});
循环.启动();

// 失焦暂停/恢复：对局页实现 暂停()/恢复()；覆盖页打开时暂停的是覆盖页本身。
if (typeof document !== "undefined") {
  document.addEventListener("visibilitychange", () => {
    if (document.visibilityState === "hidden") 栈.暂停();
    else if (栈.读取是否暂停()) 栈.恢复();
  });
}

// —— 调试桥 ——
const 卸载桥 = 挂载调试桥({
  渲染,
  合批,
  循环,
  服务,
  栈,
  读取页面编号,
  读取当前页: () => 宿主.读取顶页面(),
  读取图元统计: () => 合批.读取统计(),
  读取纹理统计: () => 资源层.读取统计(),
  读取文字图集统计: () => 文字.读取统计(),
  停止: () => {
    卸载桥();
    window.removeEventListener("resize", 调整页面尺寸);
    取消设置尺寸订阅();
    循环.销毁();
    宿主.销毁();
    绑定指针.解除();
    命中.清空();
    服务.音频.停止全部();
    文字.销毁();
    资源层.销毁();
    合批.销毁();
    渲染.销毁();
  },
});

/** 浏览器验收脚本用的读取形状（运行时由 测试桥 拼装）。 */
export interface 调试状态 extends 对局快照 {
  页面: 页面编号;
  场景栈: string[];
}

export interface 调试统计 {
  循环: ReturnType<typeof 循环.读取统计>;
  渲染: ReturnType<typeof 渲染.读取统计>;
  合批: ReturnType<typeof 合批.读取统计>;
  图元: ReturnType<typeof 合批.读取统计>;
  纹理: ReturnType<typeof 资源层.读取统计>;
  文字: { 小: unknown; 中: unknown; 大: unknown } | null;
  文字图集: ReturnType<typeof 文字.读取统计>;
  内存: ReturnType<typeof 服务.内存>;
  画布: { 宽: number; 高: number; 视口宽: string; 视口高: string };
  设备像素比: number;
  页面: 页面编号;
  场景栈: string[];
  对局统计: { 操作次数: number; 落块数: number; 消行次数: number };
  操作记录: unknown[];
  主题: string;
  省电: string;
  音频: ReturnType<typeof 服务.音频.读取状态>;
  金币: number;
}

export interface 调试接口 {
  开始绘制采样: typeof 渲染.开始绘制采样;
  结束绘制采样: typeof 渲染.结束绘制采样;
  读取状态: () => 调试状态;
  读取原始状态: () => unknown;
  读取统计: () => 调试统计;
  读取界面: () => 界面快照;
  读取设置: () => ReturnType<设置服务["读取"]>;
  更新设置: (变化: Partial<ReturnType<设置服务["读取"]>>) => void;
  读取音频: () => ReturnType<typeof 服务.音频.读取状态>;
  增加金币: (数量: number) => void;
  操作: (名称: string) => void;
  停止: () => void;
}

declare global {
  interface Window {
    __three版__?: 调试接口;
  }
}

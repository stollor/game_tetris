const 关闭所有覆盖 = (): boolean => {
  let 关闭过 = false;
  while (读取当前覆盖() !== null) {
    栈.退出();
    关闭过 = true;
  }
  if (关闭过) 同步命中层();
  if (关闭过) 应用页面性能(读取当前页面());
  return 关闭过;
};

const 回到根页面 = () => {
  while (栈.读取数量() > 1) 栈.退出();
  const 根 = 栈.读取顶场景();
  应用参数({});
  if (!根) {
    进入页面("主界面", 取页面("主界面"));
  } else {
    命中.设置注册层("主界面");
    // 根页面一直在栈底、命中绑定还在：用 恢复()（= 重建控件）刷新金币/设置/主题。
    // 不能 退出()+进入()：页面基类.进入 只重新绑定命中 + 构建，不清空旧控件与按钮登记，
    // 会让主界面按钮/命中区翻倍（读取界面按钮 9 → 18）。
    if (根.恢复) 根.恢复();
    else {
      根.退出?.();
      根.进入?.({ 覆盖: false });
    }
    命中.设置活动层("主界面");
  }
  应用页面性能("主界面");
};

const 导航: 导航服务 = {
  进入(页, 参数 = {}) {
    if (页 === "主界面") {
      回到根页面();
      return;
    }
    关闭所有覆盖();
    应用参数(参数);
    进入页面(页, 取页面(页));
    应用页面性能(页);
  },
  替换(页, 参数 = {}) {
    关闭所有覆盖();
    if (页 === "主界面") {
      回到根页面();
      return;
    }
    const 顶名称 = 栈.读取栈().at(-1)?.名称;
    const 顶 = 栈.读取顶场景();
    if (顶名称 === 页) {
      命中.设置注册层(页);
      顶?.退出?.();
      应用参数(参数);
      顶?.进入?.({ 覆盖: false });
      命中.设置活动层(页);
    } else {
      // 主界面永远是栈底：从主界面替换到其它页面时不能把根页弹掉。
      if (栈.读取数量() > 1) 栈.退出();
      同步命中层();
      应用参数(参数);
      进入页面(页, 取页面(页));
    }
    应用页面性能(页);
  },
  返回() {
    if (关闭所有覆盖()) return;
    if (栈.读取数量() <= 1) return;
    栈.退出();
    同步命中层();
    应用页面性能(读取当前页面());
  },
  打开覆盖(页, 参数 = {}) {
    应用参数(参数);
    进入页面(页, 取覆盖页(页), true);
    应用页面性能(读取当前页面());
  },
  关闭覆盖() {
    关闭所有覆盖();
  },
  读取当前() {
    return { 页面: 读取当前页面(), 覆盖: 读取当前覆盖() };
  },
};


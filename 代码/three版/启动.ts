const 包装页面 = (实例: 页面实例): 页面实例 => {
  const 读统计 = 实例.读取对局统计;
  const 读记录 = 实例.读取操作记录;
  const 读界面 = 实例.读取界面;
  const 代理: 页面实例 = {
    进入: (进入上下文) => {
      const 列表: (() => void)[] = [];
      清理表.set(代理, 列表);
      当前清理 = 列表;
      实例.进入?.(进入上下文);
    },
    退出: () => {
      实例.退出?.();
      执行清理(代理);
      当前清理 = null;
    },
    暂停: () => 实例.暂停?.(),
    恢复: () => 实例.恢复?.(),
    更新: (固定步长秒, 上下文) => 实例.更新?.(固定步长秒, 上下文),
    渲染: (上下文) => 实例.渲染?.(上下文),
    调整尺寸: () => 实例.调整尺寸?.(),
    销毁: () => {
      实例.销毁?.();
      执行清理(代理);
    },
    测试: 实例.测试,
    读取快照: () => 实例.读取快照?.(),
    读取原始状态: () => 实例.读取原始状态?.(),
    读取对局统计: 读统计 ? () => 读统计.call(实例) : undefined,
    读取操作记录: 读记录 ? () => 读记录.call(实例) : undefined,
    读取界面: 读界面 ? () => 读界面.call(实例) : undefined,
  };
  return 代理;
};


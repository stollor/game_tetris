const 循环 = 创建游戏循环({
  更新: (固定步长秒) => {
    栈.更新(固定步长秒);
  },
  渲染: () => {
    // 先做按需渲染/帧率判定：被节流或按需跳过时直接返回，不白做清空与逐页几何构建。
    if (!渲染.准备渲染()) return;
    合批.清空();
    文字.开始帧();
    // 场景栈从栈底到栈顶逐页渲染：每页一个绘制图层，页内多图集分批也不会串层。
    栈.逐层渲染((场景, 深度) => {
      // 每页占一段连续绘制层，页内覆盖层/弹层用 资源.设置绘制层 抬到本案之上。
      当前页绘制层 = 深度 * 每页绘制层数;
      合批.设置图层(当前页绘制层);
      // 每页渲染前重置画笔状态，防止上一页的 alpha/混合/变换/路径漏到下一页。
      画笔.重置();
      场景.渲染?.(上下文);
    });
    合批.提交();
    渲染.渲染();
    文字.结束帧();
  },
});

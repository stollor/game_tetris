import type { 紫外线矩形 } from "../../../框架Three/界面/图元合批";
import type {
  字号档,
  文字排版结果,
  文字服务,
  文字绘制请求,
} from "../../../框架Three/界面/控件/类型";
import { 换行文本 } from "../../../框架Three/界面/文本换行";
import type { 文字样式 } from "../../../框架Three/界面/绘制/协议";
import { 读取霓虹文字样式 } from "../../../组件/霓虹街机/文字样式";
import type { 页面资源 } from "../接口/上下文";

/**
 * 7D：把控件库需要的 `文字服务`（旧三档图集接口）收敛为 `画笔` 上的薄适配。
 *
 * 7A 的 `资源.字` 小/中/大三档图集与 `字体纹理序号` 已删除；控件库仍按字号档要
 * 测量/行高/排版/折行/绘制/纯色白块，这里统一换算为共享文字样式 + `画笔.绘制文字`，
 * 视觉与页面自绘的 `文字项` 同源；纯色白块复用图元合批已登记的白块紫外线。
 */

const 档位字号: Record<字号档, { 字号: number; 字重: "常规" | "粗体" }> = {
  小: { 字号: 14, 字重: "常规" },
  中: { 字号: 18, 字重: "常规" },
  大: { 字号: 24, 字重: "粗体" },
};

function 档位样式(档: 字号档): 文字样式 {
  const 样式 = 读取霓虹文字样式("正文");
  const 档位 = 档位字号[档];
  return { ...样式, 字号: 档位.字号, 字重: 档位.字重 };
}

function 带颜色(样式: 文字样式, 请求: 文字绘制请求): 文字样式 {
  return { ...样式, 颜色: 请求.颜色 };
}

export function 创建文字服务(资源: 页面资源): 文字服务 {
  const 画笔 = 资源.画笔;
  const 测量 = (文本: string, 档: 字号档): number => 画笔.测量文字(文本, 档位样式(档)).宽;
  const 行高 = (档: 字号档): number => 画笔.测量文字("行", 档位样式(档)).高;
  return {
    测量,
    读取行高: 行高,
    排版: (文本: string, 档: 字号档, 最大宽度?: number): 文字排版结果 => {
      const 样式 = 档位样式(档);
      const 行 = 换行文本(
        文本,
        最大宽度 ?? Number.MAX_SAFE_INTEGER,
        (片段) => 画笔.测量文字(片段, 样式).宽,
      );
      const 宽 = Math.min(
        最大宽度 ?? Number.MAX_SAFE_INTEGER,
        Math.max(0, ...行.map((片段) => 画笔.测量文字(片段, 样式).宽)),
      );
      return { 宽, 高: 行.length * 行高(档), 行数: 行.length };
    },
    折行: (文本: string, 档: 字号档, 最大宽度: number): string[] =>
      换行文本(文本, 最大宽度, (片段) => 测量(片段, 档)),
    绘制: (_合批, 请求: 文字绘制请求): 文字排版结果 => {
      const 样式 = 带颜色(档位样式(请求.字号档), 请求);
      const 行高值 = 行高(请求.字号档);
      const 宽 = 请求.最大宽度 ?? 画笔.测量文字(请求.文本, 样式).宽;
      const 对齐 = 请求.对齐 ?? "左";
      const 锚点 = 对齐 === "中" ? "中中" : 对齐 === "右" ? "右中" : "左中";
      const x = 对齐 === "中" ? 请求.左 + 宽 / 2 : 对齐 === "右" ? 请求.左 + 宽 : 请求.左;
      const 结果 = 画笔.绘制文字({
        文案: 请求.文本,
        样式,
        锚点,
        x,
        y: 请求.上 + 行高值 / 2,
        最大宽: 请求.最大宽度,
      });
      return {
        宽: 结果.宽,
        高: 结果.高,
        行数: Math.max(1, Math.round(结果.高 / Math.max(1, 行高值))),
      };
    },
    读取纯色紫外线: (): 紫外线矩形 => {
      const 纯色 = 资源.合批.读取纯色();
      if (!纯色) throw new Error("图元合批尚未设置纯色白块");
      return 纯色.紫外线;
    },
  };
}

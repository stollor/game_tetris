import { 十六进制颜色 } from "../../../框架Three/界面/四边形合批";
import type {
  字号档,
  文字排版结果,
  文字服务,
  文字绘制请求,
} from "../../../框架Three/界面/控件/类型";
import { 换行文本 } from "../../../框架Three/界面/文本换行";
import { 字体纹理序号, type 页面资源 } from "../接口/上下文";

/**
 * 把启动层提供的三档文字图集包装成框架控件库的 `文字服务`：
 * 控制只看字号档（小/中/大），具体图集与纹理序号在这里收口，页面不直接碰图集。
 */

export function 创建文字服务(资源: 页面资源): 文字服务 {
  const 图集 = { 小: 资源.字.小, 中: 资源.字.中, 大: 资源.字.大 } as const;
  return {
    测量: (文本: string, 字号档: 字号档) => 图集[字号档].测量(文本),
    读取行高: (字号档: 字号档) => 图集[字号档].读取行高(),
    排版: (文本: string, 字号档: 字号档, 最大宽度?: number) => {
      const 排版 = 图集[字号档].排版(文本, 最大宽度 ?? Number.MAX_SAFE_INTEGER);
      return { 宽: 排版.宽, 高: 排版.高, 行数: 排版.行.length };
    },
    折行: (文本: string, 字号档: 字号档, 最大宽度: number) =>
      换行文本(文本, 最大宽度, (片段) => 图集[字号档].测量(片段)),
    绘制: (合批, 请求: 文字绘制请求): 文字排版结果 => {
      const 排版 = 图集[请求.字号档].绘制(合批, 请求.文本, {
        左: 请求.左,
        上: 请求.上,
        最大宽度: 请求.最大宽度,
        对齐: 请求.对齐 === "中" ? "中" : 请求.对齐 === "右" ? "右" : "左",
        颜色: 十六进制颜色(请求.颜色, 请求.透明度 ?? 1),
        纹理序号: 字体纹理序号[请求.字号档],
      });
      return { 宽: 排版.宽, 高: 排版.高, 行数: 排版.行.length };
    },
    读取纯色紫外线: () => 资源.字.小.读取纯色紫外线(),
  };
}

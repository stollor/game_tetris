/** 颜色混合：比例 0 保留甲，1 变成乙。 */
export function 混合颜色(甲: number, 乙: number, 比例: number): number {
  const 通道 = (偏移: number) =>
    Math.round((((甲 >> 偏移) & 0xff) * (1 - 比例) + ((乙 >> 偏移) & 0xff) * 比例) as number);
  return (通道(16) << 16) | (通道(8) << 8) | 通道(0);
}

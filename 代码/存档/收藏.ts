/** 金币与主题所有权写在同一份版本化存档里，保存失败不会扣款或授予主题。 */
export interface 收藏存档 {
  金币: number;
  累计获得: number;
  已购主题: string[];
  已结算: string[];
  已领成就: string[];
  最近首局日期: string;
}

/**
 * 收藏操作的机器可读原因。
 * UI 需要多语言时按 原因编号 + 原因参数 从 代码/语言 取文案；原因 字段是它的简体中文渲染，
 * 供现有调用方（商店消息行、结算奖励文案）直接展示。
 */
export type 收藏原因编号 =
  | "商品不存在"
  | "已拥有"
  | "余额不足"
  | "保存失败"
  | "对局无效"
  | "奖励已领取"
  | "对局未达标"
  | "成就无待领"
  | "测试金币无效"
  | "购买成功"
  | "成就奖励"
  | "测试金币"
  | "对局奖励";

export interface 收藏结果 {
  成功: boolean;
  原因: string;
  /** 原因编号：机器可读，UI 可据此取本地化文案。 */
  原因编号?: 收藏原因编号;
  /** 原因里的数字（金币差额、奖励数、门槛秒数等）。 */
  原因参数?: Readonly<Record<string, string | number>>;
  金币: number;
  新增: number;
}

/** 存档层拿不到语言服务：原因先用简体中文渲染，英文界面按编号取字典。 */
const 文案 = 按英文取文案(false);

const 原因模板: Record<收藏原因编号, string> = {
  商品不存在: 文案.收藏商品不存在,
  已拥有: 文案.收藏已拥有,
  余额不足: 文案.收藏余额不足,
  保存失败: 文案.收藏保存失败,
  对局无效: 文案.收藏对局无效,
  奖励已领取: 文案.收藏奖励已领取,
  对局未达标: 文案.收藏对局未达标,
  成就无待领: 文案.收藏成就无待领,
  测试金币无效: 文案.收藏测试金币无效,
  购买成功: 文案.收藏购买成功,
  成就奖励: 文案.收藏成就奖励,
  测试金币: 文案.收藏测试金币,
  对局奖励: 文案.收藏对局奖励,
};

interface 收藏原因 {
  编号: 收藏原因编号;
  参数?: Readonly<Record<string, string | number>>;
}

function 取原因文案(原因: 收藏原因): string {
  const 参数 = 原因.参数 ?? {};
  if (原因.编号 === "对局奖励")
    return (
      填充文案(文案.收藏对局奖励, { 数量: 参数.数量 ?? 0 }) +
      (参数.首局 ? 填充文案(文案.收藏对局首局, { 数量: 参数.首局 }) : "") +
      (参数.纪录 ? 填充文案(文案.收藏对局纪录, { 数量: 参数.纪录 }) : "")
    );
  return 填充文案(原因模板[原因.编号], 参数);
}

export interface 对局奖励输入 {
  编号: string;
  分数: number;
  消行: number;
  用时: number;
  落块: number;
  破纪录: boolean;
  日期: string;
}

export const 收藏存档键 = "再消一行:收藏";
/** 上一版把金币与旅行皮肤存在这个键里；只在新键不存在时迁移一次。 */
export const 旧收藏存档键 = "旅行版:收藏";
export const 收藏变化事件 = "再消一行:收藏变化";

const 成就编号 = new Set<string>(成就定义.map((项) => 项.编号));
const 整数 = (值: unknown): 值 is number =>
  typeof 值 === "number" && Number.isSafeInteger(值) && 值 >= 0;
const 字串数组 = (值: unknown): 值 is string[] =>
  Array.isArray(值) &&
  值.every((项) => typeof 项 === "string" && 项.length > 0 && 项.length <= 100) &&
  new Set(值).size === 值.length;

function 校验(值: unknown): 值 is 收藏存档 {
  if (!值 || typeof 值 !== "object") return false;
  const 数据 = 值 as Partial<收藏存档>;
  return (
    整数(数据.金币) &&
    整数(数据.累计获得) &&
    数据.金币 <= 数据.累计获得 &&
    字串数组(数据.已购主题) &&
    数据.已购主题.every((项) => 是主题名(项) && 项 !== 默认主题) &&
    字串数组(数据.已结算) &&
    字串数组(数据.已领成就) &&
    数据.已领成就.every((项) => 成就编号.has(项)) &&
    typeof 数据.最近首局日期 === "string" &&
    /^(\d{4}-\d{2}-\d{2})?$/.test(数据.最近首局日期)
  );
}

function 新档(): 收藏存档 {
  return {
    金币: 金币奖励配置.初始金币,
    累计获得: 金币奖励配置.初始金币,
    已购主题: [],
    已结算: [],
    已领成就: [],
    最近首局日期: "",
  };
}

/**
 * 旧档迁移：金币、累计、已结算、已领成就与每日首局都按原值继承；
 * 旧档买过旅行皮肤（已购非空）的玩家曾为外观花过金币，直接补偿全部在售主题。
 */
function 从旧档迁移(存储: 存储接口): 收藏存档 {
  const 初始 = 新档();
  let 原文: string | null = null;
  try {
    原文 = 存储.getItem(旧收藏存档键);
  } catch {
    return 初始;
  }
  if (原文 === null) return 初始;
  try {
    const 载荷: unknown = JSON.parse(原文);
    if (!载荷 || typeof 载荷 !== "object") return 初始;
    const 数据 = (载荷 as { 数据?: unknown }).数据;
    if (!数据 || typeof 数据 !== "object") return 初始;
    const 旧 = 数据 as Partial<收藏存档> & { 已购?: unknown };
    const 买过外观 = Array.isArray(旧.已购) && 旧.已购.length > 0;
    return {
      金币: 整数(旧.金币) ? 旧.金币 : 初始.金币,
      累计获得: 整数(旧.累计获得) ? Math.max(旧.累计获得, 整数(旧.金币) ? 旧.金币 : 0) : 初始.累计获得,
      已购主题: 买过外观 ? [...可购主题] : [],
      已结算: 字串数组(旧.已结算) ? 旧.已结算 : [],
      已领成就: 字串数组(旧.已领成就) ? 旧.已领成就.filter((项) => 成就编号.has(项)) : [],
      最近首局日期:
        typeof 旧.最近首局日期 === "string" && /^(\d{4}-\d{2}-\d{2})?$/.test(旧.最近首局日期)
          ? 旧.最近首局日期
          : "",
    };
  } catch {
    return 初始;
  }
}

/** 余额、所有权和奖励凭据写在同一份存档里，保存失败不会扣款或授予主题。 */
export class 收藏 {
  private readonly 存档: 存档<收藏存档>;
  错误 = "";
  constructor(存储: 存储接口) {
    this.存档 = new 存档({
      键: 收藏存档键,
      版本: 1,
      存储,
      创建: () => 从旧档迁移(存储),
      校验,
      失败: (_阶段, 错误) => {
        this.错误 = 错误 instanceof Error ? 错误.message : 文案.收藏无法保存;
      },
    });
  }
  读取(): 收藏存档 {
    this.错误 = "";
    return this.存档.读取();
  }
  拥有(主题: 主题名, 数据 = this.读取()): boolean {
    return 主题 === 默认主题 || 数据.已购主题.includes(主题);
  }
  增加测试金币(数量: number): 收藏结果 {
    const 数据 = this.读取();
    if (!整数(数量) || 数量 < 1 || 数量 > 1000000)
      return this.结果(数据, false, { 编号: "测试金币无效" });
    return this.写入(
      数据,
      { ...数据, 金币: 数据.金币 + 数量, 累计获得: 数据.累计获得 + 数量 },
      { 编号: "测试金币", 参数: { 数量 } },
    );
  }
  报价(主题: 主题名, 数据 = this.读取()): number {
    if (this.拥有(主题, 数据)) return 0;
    return 主题价格[主题];
  }
  购买主题(主题: string): 收藏结果 {
    const 数据 = this.读取();
    if (!是主题名(主题) || 主题 === 默认主题)
      return this.结果(数据, false, { 编号: "商品不存在" });
    const 价格 = this.报价(主题, 数据);
    if (!价格) return this.结果(数据, false, { 编号: "已拥有" });
    if (数据.金币 < 价格)
      return this.结果(数据, false, { 编号: "余额不足", 参数: { 数量: 价格 - 数据.金币 } });
    return this.写入(
      数据,
      { ...数据, 金币: 数据.金币 - 价格, 已购主题: [...new Set([...数据.已购主题, 主题])] },
      { 编号: "购买成功" },
    );
  }
  领取成就(已解锁: readonly string[]): 收藏结果 {
    const 数据 = this.读取();
    const 新领 = [...new Set(已解锁)].filter(
      (项) => 成就编号.has(项) && !数据.已领成就.includes(项),
    );
    if (!新领.length) return this.结果(数据, true, { 编号: "成就无待领" });
    const 奖励 = 新领.length * 金币奖励配置.成就;
    return this.写入(
      数据,
      {
        ...数据,
        金币: 数据.金币 + 奖励,
        累计获得: 数据.累计获得 + 奖励,
        已领成就: [...数据.已领成就, ...新领],
      },
      { 编号: "成就奖励", 参数: { 数量: 奖励 } },
    );
  }
  结算对局(对局: 对局奖励输入): 收藏结果 {
    const 数据 = this.读取();
    if (
      !对局.编号 ||
      对局.编号.length > 100 ||
      ![对局.分数, 对局.消行, 对局.落块].every(整数) ||
      !Number.isFinite(对局.用时) ||
      对局.用时 < 0 ||
      !/^\d{4}-\d{2}-\d{2}$/.test(对局.日期)
    )
      return this.结果(数据, false, { 编号: "对局无效" });
    if (数据.已结算.includes(对局.编号))
      return this.结果(数据, true, { 编号: "奖励已领取" });
    if (对局.用时 < 金币奖励配置.有效对局秒 * 1000 || 对局.落块 < 金币奖励配置.有效落块数)
      return this.结果(数据, true, {
        编号: "对局未达标",
        参数: { 秒: 金币奖励配置.有效对局秒, 次数: 金币奖励配置.有效落块数 },
      });
    const 表现 = Math.min(
      金币奖励配置.对局表现上限,
      Math.floor(对局.分数 / 金币奖励配置.每表现分) + 对局.消行,
    );
    const 首局 = 对局.日期 > 数据.最近首局日期 ? 金币奖励配置.每日首局 : 0;
    const 纪录 = 对局.破纪录 ? 金币奖励配置.破纪录 : 0;
    const 奖励 = 金币奖励配置.对局基础 + 表现 + 首局 + 纪录;
    return this.写入(
      数据,
      {
        ...数据,
        金币: 数据.金币 + 奖励,
        累计获得: 数据.累计获得 + 奖励,
        已结算: [...数据.已结算, 对局.编号],
        最近首局日期: 首局 ? 对局.日期 : 数据.最近首局日期,
      },
      {
        编号: "对局奖励",
        参数: { 数量: 金币奖励配置.对局基础 + 表现, 首局, 纪录 },
      },
    );
  }
  private 结果(数据: 收藏存档, 成功: boolean, 原因: 收藏原因, 新增 = 0): 收藏结果 {
    const 结果: 收藏结果 = {
      成功,
      原因: 取原因文案(原因),
      原因编号: 原因.编号,
      金币: 数据.金币,
      新增,
    };
    if (原因.参数) 结果.原因参数 = 原因.参数;
    return 结果;
  }
  private 写入(旧: 收藏存档, 新: 收藏存档, 原因: 收藏原因): 收藏结果 {
    if (!this.存档.保存(新)) return this.结果(旧, false, { 编号: "保存失败" });
    return this.结果(新, true, 原因, Math.max(0, 新.金币 - 旧.金币));
  }
}

/** 支持同源多页签串行修改；每次交易重新读存档，避免使用过期余额。 */
export async function 执行收藏操作(操作: (收藏: 收藏) => 收藏结果): Promise<收藏结果> {
  const 执行 = () => 操作(new 收藏(localStorage));
  const 结果 = navigator.locks ? await navigator.locks.request(收藏存档键, 执行) : 执行();
  window.dispatchEvent(new CustomEvent(收藏变化事件, { detail: 结果 }));
  return 结果;
}

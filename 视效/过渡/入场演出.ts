function 比例(秒: number, 起: number, 止: number): number {
  return Math.min(1, Math.max(0, (秒 - 起) / (止 - 起)));
}
function 快出(t: number, 指数: number): number {
  return 1 - (1 - t) ** 指数;
}

export function 计算模式入场姿态(秒: number, 原: 流转矩形, 宽: number, 高: number) {
  const t = Math.max(0, 秒);
  const 时 = 入场参数.时间;
  const 曲 = 入场参数.曲线;
  const 居中进度 = 快出(比例(t, 时.居中起, 时.居中止), 曲.居中);
  const 收 = 比例(t, 时.收束起, 时.收束止);
  const 压缩进度 = 收 ** 曲.收束;
  const 浮 = Math.sin(Math.PI * 比例(t, 0, 时.收束起)) * 入场参数.运动.聚焦放大;
  const 当前宽 = 原.宽 * (1 + 浮) + (宽 - 原.宽 * (1 + 浮)) * 收 ** 曲.展宽;
  const 当前高 = 原.高 * (1 + 浮) + (入场参数.运动.线高 - 原.高 * (1 + 浮)) * 压缩进度;
  const 中心X = 原.左 + 原.宽 / 2 + (宽 / 2 - 原.左 - 原.宽 / 2) * 居中进度;
  const 中心Y = 原.上 + 原.高 / 2 + (高 / 2 - 原.上 - 原.高 / 2) * 居中进度;
  const 矩形 = { 左: 中心X - 当前宽 / 2, 上: 中心Y - 当前高 / 2, 宽: 当前宽, 高: 当前高 };
  const 幕面进度 = 比例(t, 时.幕布起, 时.收束止) ** 曲.幕布;
  // 幕面终点取卡片正在收束的上下边，不再追逐另一套独立横轴。
  const 幕缝 = {
    顶: Math.max(0, 矩形.上 * 幕面进度),
    底: Math.min(高, 高 - (高 - 矩形.上 - 当前高) * 幕面进度),
  };
  return {
    阶段: t < 0.18 ? "退场" : t < 时.居中止 ? "居中" : t < 时.收束止 ? "压线" : "蓄力",
    退场进度: 比例(t, 0, 时.退场),
    居中进度,
    压缩进度,
    幕面进度,
    矩形,
    幕缝,
    内容透明度: 1 - 比例(t, 时.内容起, 时.内容止) ** 2,
    线脉冲:
      t < 时.收束止
        ? 比例(t, 入场参数.能量.预亮起, 时.收束止) ** 1.5
        : 1 - (1 - 入场参数.能量.释放余辉) * 快出(比例(t, 时.收束止, 时.凝聚止), 2),
    完成: t >= 模式退场时长,
  };
}

export function 计算退场进度(秒: number, 距离: number): number {
  const 时 = 入场参数.时间;
  const 延迟 = Math.min(3, Math.max(0, 距离)) * 时.错峰;
  return 比例(秒, 延迟, 延迟 + 时.退场);
}

export function 计算对局入场姿态(秒: number) {
  const t = Math.max(0, 秒);
  const 时 = 入场参数.时间;
  const 节拍 = t < 时.Ready起 ? "展开" : t < 时.Ready止 ? "Ready" : t < 时.Go止 ? "Go" : "完成";
  return {
    展开进度: 快出(比例(t, 0, 时.释放止), 入场参数.曲线.释放),
    节拍,
    线脉冲: 入场参数.能量.释放余辉 * (1 - 快出(比例(t, 0, 入场参数.能量.释放衰减止), 2)),
    完成: t >= 对局入场时长,
  };
}

export function 计算分组入场姿态(秒: number, 组: 入场分组) {
  const { 起, 止 } = 入场参数.分组[组];
  const p = 快出(比例(秒, 起, 止), 入场参数.曲线.落位);
  if (p === 1) return { 透明度: 1, 偏移X: 0, 偏移Y: 0, 缩放Y: 1, 完成: true };
  const 余 = 1 - p;
  const 幅 = 入场参数.运动;
  return {
    透明度: 组 === "棋盘" ? 1 : p,
    偏移X: 组 === "侧栏" ? 幅.侧栏位移 * 余 : 0,
    偏移Y: 组 === "顶栏" ? -幅.顶栏位移 * 余 : 组 === "操作区" ? 幅.操作位移 * 余 : 0,
    缩放Y: 组 === "棋盘" ? 1 - 幅.棋盘收拢 * 余 : 1,
    完成: 秒 >= 止,
  };
}

export function 计算网格入场透明度(秒: number): number {
  return 快出(比例(秒, 入场参数.网格.起, 入场参数.网格.止), 2);
}

export function 计算展开幕缝(展开: number, 高: number): 入场幕缝 {
  const 顶 = ((高 - 入场参数.运动.线高) / 2) * (1 - Math.min(1, Math.max(0, 展开)));
  return { 顶, 底: 高 - 顶 };
}

export function 读取入场幕色(模式: 游戏模式) {
  const 色 = 入场参数.颜色;
  const 主题 = 模式主题色(模式);
  return { 外: 混色(色.幕外, 主题, 色.主题染色), 内: 混色(色.幕内, 主题, 色.主题染色) };
}

/** 梯度朝中心接缝变亮，幕布和模式线共用同一套颜色与边界。 */
export function 绘制入场幕面(
  画笔: 画笔,
  宽: number,
  高: number,
  模式: 游戏模式,
  缝: 入场幕缝,
  边线 = 0,
): void {
  const 图 = 画笔.图形;
  const 色 = 读取入场幕色(模式);
  const 中 = 混色(色.外, 色.内, 入场参数.颜色.幕中混合);
  const 上亮带 = Math.min(缝.顶 * 入场参数.颜色.亮带范围, 高 * 入场参数.颜色.亮带高度比);
  const 下亮带 = Math.min((高 - 缝.底) * 入场参数.颜色.亮带范围, 高 * 入场参数.颜色.亮带高度比);
  // 亮度集中在接缝附近，幕面的大部分保持与星空衔接的深色。
  if (缝.顶 > 0) {
    图.fillGradientStyle(色.外, 色.外, 中, 中).fillRect(0, 0, 宽, 缝.顶 - 上亮带);
    图.fillGradientStyle(中, 中, 色.内, 色.内).fillRect(0, 缝.顶 - 上亮带, 宽, 上亮带);
  }
  if (缝.底 < 高) {
    图.fillGradientStyle(色.内, 色.内, 中, 中).fillRect(0, 缝.底, 宽, 下亮带);
    图.fillGradientStyle(中, 中, 色.外, 色.外).fillRect(0, 缝.底 + 下亮带, 宽, 高 - 缝.底 - 下亮带);
  }
  if (边线 > 0) {
    图
      .fillStyle(模式主题色(模式), 边线)
      .fillRect(0, 缝.顶, 宽, 1)
      .fillRect(0, 缝.底 - 1, 宽, 1);
  }
}

export function 绘制凝聚横线(
  画笔: 画笔,
  宽: number,
  高: number,
  模式: 游戏模式,
  脉冲: number,
): void {
  const 线高 = 入场参数.运动.线高;
  const 色 = 亮色(模式主题色(模式), 入场参数.颜色.线提亮 * 脉冲);
  画笔.图形.fillStyle(色, 1).fillRect(0, 高 / 2 - 线高 / 2, 宽, 线高);
  if (脉冲 > 0)
    画笔.图形.fillStyle(亮色(色, 0.22), 脉冲 * 0.6).fillRect(宽 * 0.25, 高 / 2 - 0.5, 宽 * 0.5, 1);
}

export function 绘制开局节拍(画笔: 画笔, 宽: number, 高: number, 模式: 游戏模式, 秒: number): void {
  const { 节拍 } = 计算对局入场姿态(秒);
  if (节拍 !== "Ready" && 节拍 !== "Go") return;
  const 时 = 入场参数.时间;
  const 起 = 节拍 === "Ready" ? 时.Ready起 : 时.Ready止;
  const 止 = 节拍 === "Ready" ? 时.Ready止 : 时.Go止;
  const t = Math.max(0, 秒 - 起);
  const 入 = 快出(比例(t, 0, 时.节拍进入), 3);
  const 出 = 比例(秒, 止 - 时.节拍退出, 止) ** 2;
  const 显 = 入 * (1 - 出);
  const 图 = 画笔.图形;
  图.fillStyle(0x0a1220, 入场参数.颜色.节拍压暗 * 显).fillRect(0, 0, 宽, 高);
  图.fillStyle(模式主题色(模式), 显).fillRect(宽 / 2 - 20 * 入, 高 / 2 + 34, 40 * 入, 2);
  图.save().setAlpha(显);
  画笔.绘制文字({
    文案: 节拍.toUpperCase(),
    x: 宽 / 2,
    y: 高 / 2 + (1 - 入) * 入场参数.运动.节拍位移 - 出 * 3,
    锚点: "中中",
    缩放: 0.97 + 入 * 0.03 + 出 * 0.01,
    样式: 派生霓虹文字样式("按钮", {
      字号: Math.min(宽 * 0.125, 节拍 === "Ready" ? 46 : 54),
      字重: "粗体",
      颜色: 节拍 === "Ready" ? "#fff8e7" : 模式主题色文本(模式),
      字距: 2,
      描边: { 颜色: "#101a28", 粗细: 1.5 },
    }),
  });
  图.restore();
}

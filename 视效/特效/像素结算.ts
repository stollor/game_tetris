/** 结算读数与统计仍来自同一份真实输入，像素配方只负责装配。 */
export function 绘制像素结算(笔: 画笔, 输入: 结算演出输入): void {
  const 布局 = 计算霓虹结算布局(输入.宽, 输入.高);
  const { 顶, 宽, 高, 中心X, 比例: s } = 布局.几何;
  const 规 = 对局像素规格.结算;
  const 色 = 像素规范.色;
  const 图 = 笔.图形;
  const p = 像素规范.网格;
  const 帧 = Math.floor(输入.经过毫秒 / (1000 / 像素规范.动画步频));
  图.save();
  绘制像素面板(图, 布局.左, 顶, 宽, 高);
  const 字 = (
    文案: string,
    x: number,
    y: number,
    字号: number,
    最大宽: number,
    颜色: number = 色.墨,
  ) => {
    const 样式 = { 字体: 像素规范.字体, 字号: Math.round(字号 * s), 颜色 };
    const 测 = 笔.测量文字(文案, 样式).宽;
    笔.绘制文字({
      文案,
      样式: {
        ...样式,
        字号: Math.min(样式.字号, Math.floor((样式.字号 * 最大宽) / Math.max(1, 测))),
      },
      锚点: "中中",
      x: Math.round(x),
      y: Math.round(y),
    });
  };
  字(输入.模式, 中心X, 顶 + 规.模式顶 * s, 规.模式字号, 宽);
  const 格 = Math.round(规.方块格 * s);
  for (const [列, 行] of [
    [1, 0],
    [0, 1],
    [1, 1],
    [2, 1],
  ])
    绘制糖果方块(图, 中心X + (列 - 1.5) * 格, 顶 + 规.方块顶 * s + 行 * 格, 格, 色.紫);
  字(输入.标题, 中心X, 顶 + 规.标题顶 * s, 规.标题字号, 宽 - p * 4);
  const 进度 = 输入.省电 ? 1 : Math.min(1, Math.max(0, 输入.经过毫秒 / 规.入场毫秒));
  字(Math.floor(输入.分数 * 进度).toLocaleString(), 中心X, 布局.分数.上, 规.分数字号, 宽 - p * 4);
  if (输入.新纪录) 字(输入.新纪录, 中心X, 顶 + 规.纪录顶 * s, 规.说明字号, 宽 - p * 4, 色.红);
  for (const [序, 项] of 输入.统计.entries()) {
    const x = 布局.左 + (序 + 0.5) * 布局.列宽 + p * 2;
    字(项.标签, x, 布局.统计标签Y, 规.说明字号, 布局.列宽, 色.次字);
    字(项.数值, x, 布局.统计数值Y, 规.统计字号, 布局.列宽);
  }
  const 币区 = 布局.金币区;
  绘制像素面板(图, 币区.左, 币区.上, 币区.宽, 币区.高, 色.暗纸, 色.墨);
  const 金币 =
    输入.金币 === null
      ? "—"
      : `+${读取结算金币动画(输入.经过毫秒 - 规.币起点毫秒, 输入.金币, 输入.省电).显示数量}`;
  字(`${输入.金币标签}  ${金币}`, 中心X, 布局.金币行Y, 规.统计字号, 币区.宽 - p * 4);
  if (输入.循环提示) 字(输入.循环提示.文本, 中心X, 顶 + 规.提示顶 * s, 规.说明字号, 宽 - p * 4);
  if (输入.挑战结果 && 输入.挑战结果 !== "普通") {
    const 图案 = 输入.挑战结果 === "成功" ? 对局像素规格.结算.成功 : 对局像素规格.结算.失败;
    绘制像素图案(
      图,
      图案,
      布局.左 + p * 4,
      顶 + 规.方块顶 * s,
      Math.max(1, Math.round(p * s)),
      输入.挑战结果 === "成功" ? 色.绿 : 色.红,
    );
  }
  if (输入.新纪录 && !输入.省电) {
    for (let i = 0; i < 对局像素规格.特效.金币射线; i++) {
      图.fillStyle((i + 帧) % 2 ? 色.黄 : 色.红);
      const x = 布局.左 + p * 3 + (i * (宽 - p * 6)) / 对局像素规格.特效.金币射线;
      const y = 顶 + p * (2 + ((i + 帧) % 3));
      图.fillRect(Math.round(x / p) * p, Math.round(y / p) * p, p, p);
    }
  }
  图.restore();
}

/** 节点局部坐标 → 绘制空间；整页绘制节点不传（局部即绘制坐标）。 */
export type 点变换 = (点: { x: number; y: number }) => { x: number; y: number };

export function 绘制像素结算按钮(
  笔: 画笔,
  区: 矩形,
  文案: string,
  主要: boolean,
  按下: boolean,
  禁用: boolean,
  文字变换?: 点变换,
): void {
  const 色 = 像素规范.色;
  const 沉 = 按下 ? 像素规范.描边 : 0;
  绘制像素面板(
    笔.图形,
    区.左,
    区.上 + 沉,
    区.宽,
    区.高 - 沉,
    禁用 ? 色.暗纸 : 主要 ? 色.黄 : 色.纸,
    色.暗纸,
    按下,
  );
  const 文字点 = 文字变换?.({ x: 区.左 + 区.宽 / 2, y: 区.上 + 区.高 / 2 + 沉 }) ?? {
    x: 区.左 + 区.宽 / 2,
    y: 区.上 + 区.高 / 2 + 沉,
  };
  笔.绘制文字({
    文案,
    x: Math.round(文字点.x),
    y: Math.round(文字点.y),
    锚点: "中中",
    样式: { 字体: 像素规范.字体, 字号: 对局像素规格.仪表.副字号, 颜色: 色.墨 },
  });
}

export interface 方块单元外观 {
  /** 直接给方案对象（纯配方用法），或给外观名称/留空按当前设置解析（旧调用兼容用法）。 */
  方案?: 方块外观方案 | 方块外观名称;
  色值: number;
  格子: number;
  透明度?: number;
  圆角比例?: number;
  /** 幽灵投影：只画轮廓与微弱填充。 */
  幽灵?: boolean;
}

/** 纯配方参数：方案必须由调用方给出，函数内不读设置/场景。 */
export interface 方块单元绘制参数 extends 方块单元外观 {
  方案: 方块外观方案;
}

/** 解析方块外观方案：传对象直接用；传名称按外观表解析；都不传回退当前设置（兼容旧调用）。 */
export function 解析方块单元方案(外观: 方块单元外观): 方块外观方案 {
  if (typeof 外观.方案 === "object") return 外观.方案;
  if (typeof 外观.方案 === "string") return 解析方块外观(外观.方案);
  return 读取当前方块外观(获取游戏设置().方块外观);
}

/**
 * 统一绘制棋盘格、预览块和原型块使用的程序化方块单元（玩法专属视觉配方，引擎无关）。
 * 宝石质感：外圈暗色包边、受光主体、顶部高光与底部背光，形成斜面体积。
 * Three 只使用纯绘制指令；接口结构满足 `图形对象`。
 */
export function 绘制方块单元(绘图: 图形对象, x: number, y: number, 外观: 方块单元绘制参数): void {
  if (是像素风格()) {
    绘制糖果方块(绘图, x, y, 外观.格子, 外观.色值, 外观.透明度, 外观.幽灵);
    return;
  }
  const 格子 = 外观.格子;
  const 方案 = 外观.方案;
  const 透明度 = 外观.透明度 ?? 1;
  const 圆角 =
    方案.质感 === "金属" || 方案.质感 === "像素" ? 0 : Math.max(2, 格子 * (外观.圆角比例 ?? 0.15));
  if (外观.幽灵) {
    绘制幽灵单元(绘图, x, y, 格子, 圆角, 外观.色值, 透明度);
    return;
  }
  const 色值 = 外观.色值;
  const 深 = 暗色(色值, 0.52);
  const 内缩 = Math.max(1, 格子 * 0.07);
  if (方案.质感 === "柔瓷") {
    const 弧 = 格子 * 0.26;
    绘图.fillStyle(暗色(色值, 0.26), 透明度).fillRoundedRect(x, y + 1, 格子 - 1, 格子 - 1, 弧);
    绘图.fillStyle(色值, 透明度).fillRoundedRect(x + 1, y, 格子 - 3, 格子 - 3, 弧);
    绘图
      .fillStyle(亮色(色值, 0.65), 透明度 * 0.5)
      .fillRoundedRect(x + 格子 * 0.18, y + 格子 * 0.12, 格子 * 0.62, 格子 * 0.3, 弧 * 0.6);
    绘图
      .lineStyle(1, 亮色(色值, 0.65), 透明度 * 0.75)
      .strokeRoundedRect(x + 1, y, 格子 - 3, 格子 - 3, 弧);
    if (方案.纹样) 绘制地点纹样(绘图, x, y, 格子, 方案.纹样, 透明度);
    return;
  }
  if (方案.质感 === "金属") {
    绘图.fillStyle(深, 透明度).fillRect(x, y, 格子 - 1, 格子 - 1);
    const 带 = [
      暗色(色值, 0.25),
      亮色(色值, 0.76),
      暗色(色值, 0.48),
      亮色(色值, 0.56),
      暗色(色值, 0.2),
    ];
    for (let i = 0; i < 带.length - 1; i++) {
      绘图
        .fillGradientStyle(带[i], 带[i], 带[i + 1], 带[i + 1], 透明度)
        .fillRect(
          x + 1,
          y + 1 + (i * (格子 - 3)) / (带.length - 1),
          格子 - 3,
          (格子 - 3) / (带.length - 1) + 0.5,
        );
    }
    绘图.lineStyle(0.5, 0xffffff, 透明度 * 0.06);
    for (let i = 3; i < 格子 - 2; i += 3) 绘图.lineBetween(x + 2, y + i, x + 格子 - 3, y + i);
    绘图.lineStyle(1, 亮色(色值, 0.75), 透明度 * 0.9).strokeRect(x + 1, y + 1, 格子 - 3, 格子 - 3);
    if (方案.纹样) 绘制地点纹样(绘图, x, y, 格子, 方案.纹样, 透明度);
    return;
  }
  if (方案.质感 === "像素") {
    const 边 = Math.max(1, Math.floor(格子 / 8));
    绘图.fillStyle(深, 透明度).fillRect(x, y, 格子 - 1, 格子 - 1);
    绘图.fillStyle(色值, 透明度).fillRect(x + 边, y + 边, 格子 - 边 * 2 - 1, 格子 - 边 * 2 - 1);
    绘图
      .fillStyle(亮色(色值, 0.55), 透明度)
      .fillRect(x + 边, y + 边, 格子 - 边 * 2 - 1, 边)
      .fillRect(x + 边, y + 边, 边, 格子 - 边 * 2 - 1);
    for (let 行 = 0; 行 < 3; 行++)
      for (let 列 = 0; 列 < 3; 列++)
        if ((行 + 列) % 2 === 0)
          绘图
            .fillStyle(亮色(色值, 0.3), 透明度 * 0.42)
            .fillRect(x + 格子 * (0.28 + 列 * 0.2), y + 格子 * (0.28 + 行 * 0.2), 边, 边);
    if (方案.纹样) 绘制地点纹样(绘图, x, y, 格子, 方案.纹样, 透明度);
    return;
  }
  // 底部柔影，让方块浮在格面上
  绘图.fillStyle(0x000000, 0.32 * 透明度).fillRoundedRect(x + 1, y + 2.5, 格子 - 1, 格子 - 1, 圆角);
  // 外圈包边（深色），形成斜面外沿
  绘图.fillStyle(深, 0.96 * 透明度).fillRoundedRect(x, y, 格子 - 1, 格子 - 1, 圆角);
  // 主体受光面
  绘图
    .fillStyle(色值, 0.98 * 透明度)
    .fillRoundedRect(x + 内缩, y + 内缩, 格子 - 1 - 内缩 * 2, 格子 - 1 - 内缩 * 2, 圆角 * 0.8);
  // 上半受光提亮
  const 内宽 = Math.max(0, 格子 - 1 - 内缩 * 2);
  绘图
    .fillStyle(亮色(色值, 0.34), 0.55 * 透明度)
    .fillRect(x + 内缩 + 圆角 * 0.6, y + 内缩 + 1, 内宽 - 圆角 * 1.2, (格子 - 1) * 0.34);
  // 顶部镜面高光
  绘图
    .fillStyle(0xffffff, 0.5 * 透明度)
    .fillRoundedRect(
      x + 格子 * 0.18,
      y + 格子 * 0.11,
      Math.max(1, 格子 * 0.42),
      Math.max(1, 格子 * 0.1),
      格子 * 0.05,
    );
  // 底部背光
  绘图
    .fillStyle(0x000000, 0.26 * 透明度)
    .fillRect(
      x + 内缩 + 圆角 * 0.6,
      y + 格子 - 2.5 - (格子 - 1) * 0.22,
      内宽 - 圆角 * 1.2,
      (格子 - 1) * 0.2,
    );
  // 内侧亮边
  绘图
    .lineStyle(1, 亮色(色值, 0.52), 0.5 * 透明度)
    .strokeRoundedRect(x + 内缩, y + 内缩, 格子 - 1 - 内缩 * 2, 格子 - 1 - 内缩 * 2, 圆角 * 0.8);
  // 外沿描边
  绘图
    .lineStyle(1, 亮色(色值, 0.24), 0.62 * 透明度)
    .strokeRoundedRect(x, y, 格子 - 1, 格子 - 1, 圆角);
  if (方案.纹样) 绘制地点纹样(绘图, x, y, 格子, 方案.纹样, 透明度);
}

/** 幽灵投影：极弱轮廓提示落点，不与实块抢眼。 */
function 绘制幽灵单元(
  绘图: 图形对象,
  x: number,
  y: number,
  格子: number,
  圆角: number,
  色值: number,
  透明度: number,
): void {
  const 内缩 = Math.max(1, 格子 * 0.11);
  绘图
    .fillStyle(色值, 0.1 * 透明度)
    .fillRoundedRect(x + 内缩, y + 内缩, 格子 - 1 - 内缩 * 2, 格子 - 1 - 内缩 * 2, 圆角);
  绘图
    .lineStyle(Math.max(1, 格子 * 0.055), 亮色(色值, 0.35), 0.65 * 透明度)
    .strokeRoundedRect(x + 内缩, y + 内缩, 格子 - 1 - 内缩 * 2, 格子 - 1 - 内缩 * 2, 圆角);
  // 只在左上/右下留两个短角标，弱化提示
  const 角 = Math.max(2, 格子 * 0.13);
  for (const [角X, 角Y, 水平, 垂直] of [
    [x + 内缩, y + 内缩, 1, 1],
    [x + 格子 - 1 - 内缩 - 角, y + 格子 - 1 - 内缩 - 角, -1, -1],
  ] as [number, number, number, number][]) {
    绘图
      .fillStyle(色值, 0.2 * 透明度)
      .fillRect(水平 > 0 ? 角X : 角X, 角Y, 角, 1.5)
      .fillRect(角X, 垂直 > 0 ? 角Y : 角Y, 1.5, 角);
  }
}

/**
 * 绘制方块外圈辉光（建议画在混合模式为 ADD 的图层上，得到霓虹泛光）。
 * 与 绘制方块单元 配套使用，位置尺寸保持一致。
 */
export function 绘制方块单元辉光(
  绘图: 图形对象,
  x: number,
  y: number,
  外观: 方块单元绘制参数,
): void {
  if (是像素风格()) return;
  const 格子 = 外观.格子;
  const 方案 = 外观.方案;
  const 透明度 = (外观.透明度 ?? 1) * 方案.辉光;
  const 圆角 = Math.max(2, 格子 * (外观.圆角比例 ?? 0.15));
  for (let 层 = 0; 层 < 3; 层 += 1) {
    const 外扩 = 1 + 层 * 2.2;
    绘图
      .fillStyle(亮色(外观.色值, 0.18), (0.12 - 层 * 0.035) * 透明度)
      .fillRoundedRect(x - 外扩, y - 外扩, 格子 - 1 + 外扩 * 2, 格子 - 1 + 外扩 * 2, 圆角 + 外扩);
  }
}


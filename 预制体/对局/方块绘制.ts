export const 控件分类 = "业务" as const;

/**
 * Three 版方块外观：只做设置→方案的换算，绘制统一走 `预制体/对局/方块单元.ts`
 * 的共享纯配方（与 Phaser 同一组指令、同一份外观表），不再自造简化质感。
 * 图形对象来自 `上下文.资源.画笔.图形`。
 */

export type { 方块外观名称, 方块外观方案 };

export function 读取方块配色(设置: 游戏设置 = 获取游戏设置()): Record<方块类型, number> {
  return { ...读取方块外观方案(设置).颜色 };
}

/** 单格方块：共享配方的 Three 入口。 */
export function 绘制方块格(
  绘图: 图形对象,
  左: number,
  上: number,
  格: number,
  方案: 方块外观方案,
  类型或颜色: 方块类型 | number,
  透明度 = 1,
): void {
  if (格 <= 0 || 透明度 <= 0) return;
  const 色 = typeof 类型或颜色 === "number" ? 类型或颜色 : 方案.颜色[类型或颜色];
  绘制方块单元(绘图, 左, 上, { 方案, 色值: 色, 格子: 格, 透明度 });
}

/** 方块外圈辉光：画在叠加混合图层上（调用方负责混合模式）。 */
export function 绘制方块格辉光(
  绘图: 图形对象,
  左: number,
  上: number,
  格: number,
  方案: 方块外观方案,
  类型或颜色: 方块类型 | number,
  透明度 = 1,
): void {
  if (格 <= 0 || 透明度 <= 0) return;
  const 色 = typeof 类型或颜色 === "number" ? 类型或颜色 : 方案.颜色[类型或颜色];
  绘制方块单元辉光(绘图, 左, 上, { 方案, 色值: 色, 格子: 格, 透明度 });
}

/** 预览/暂存/飞块：布局矩形加方块类型，外观由调用方传入方案。 */
export interface 方块输入 {
  方案: 方块外观方案;
  类型: 方块类型;
  区域: 矩形;
  格: number;
  透明度?: number;
  圆角比例?: number;
  辉光?: boolean;
}

/** 画一个完整方块形状（按预览格相对位置），用于预览/暂存/商店陈列。 */
export function 绘制方块形状(
  绘图: 图形对象,
  方案: 方块外观方案,
  类型: 方块类型,
  中心X: number,
  上: number,
  格: number,
  透明度 = 1,
): void {
  const 格子 = 预览格子(类型);
  const 列数 = Math.max(...格子.map(([列]) => 列)) + 1;
  const 左 = 中心X - (列数 * 格) / 2;
  for (const [列, 行] of 格子) {
    绘制方块格(绘图, 左 + 列 * 格, 上 + 行 * 格, 格, 方案, 类型, 透明度);
  }
}

/** 在矩形内居中画一个方块；宽高为 0 时把左/上当作中心点（飞块）。 */
export function 绘制居中方块(绘图: 图形对象, 输入: 方块输入): void {
  if (输入.格 <= 0 || (输入.透明度 ?? 1) <= 0) return;
  const 点集 = 预览格子(输入.类型);
  const 最小列 = Math.min(...点集.map(([列]) => 列));
  const 最大列 = Math.max(...点集.map(([列]) => 列));
  const 最小行 = Math.min(...点集.map(([, 行]) => 行));
  const 最大行 = Math.max(...点集.map(([, 行]) => 行));
  const 格 = 输入.格;
  const 方块宽 = (最大列 - 最小列 + 1) * 格;
  const 方块高 = (最大行 - 最小行 + 1) * 格;
  const 原点X = Math.round(输入.区域.左 + (输入.区域.宽 - 方块宽) / 2);
  const 原点Y = Math.round(输入.区域.上 + (输入.区域.高 - 方块高) / 2);
  const 外观 = {
    方案: 输入.方案,
    色值: 输入.方案.颜色[输入.类型],
    格子: 格,
    透明度: 输入.透明度 ?? 1,
    圆角比例: 输入.圆角比例 ?? 0.16,
  };
  for (const [列, 行] of 点集) {
    const x = 原点X + (列 - 最小列) * 格;
    const y = 原点Y + (行 - 最小行) * 格;
    绘制方块单元(绘图, x, y, 外观);
    if (!输入.辉光) continue;
    绘图.save();
    绘图.setBlendMode(混合模式.叠加);
    绘制方块单元辉光(绘图, x, y, 外观);
    绘图.restore();
  }
}

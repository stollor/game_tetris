/** 棋盘外框：三层外侧柔影 + 圆角底板 + 描边（取自预制体 布局 的原绘制）。 */
export function 绘制棋盘外框(绘图: 图形对象, 参数: 棋盘外框参数): void {
  const { 左, 上, 宽, 高, 格子, 透明度, 背景色, 边框色 } = 参数;
  const 圆角 = Math.max(10, 格子 * 0.5);
  // 外侧柔影
  for (let 层 = 0; 层 < 3; 层 += 1) {
    绘图
      .fillStyle(0x03060d, (0.2 - 层 * 0.055) * 透明度)
      .fillRoundedRect(
        左 - 12 - 层 * 3,
        上 - 8 + 层 * 6,
        宽 + 24 + 层 * 6,
        高 + 20 + 层 * 5,
        圆角 + 层 * 3,
      );
  }
  // 两侧导轨和角部扣件给棋盘一个独立装置轮廓，不以持续全页重画制造流光。
  绘图
    .lineStyle(1, 边框色, 0.25)
    .lineBetween(左 - 13, 上 + 20, 左 - 13, 上 + 高 - 20)
    .lineBetween(左 + 宽 + 13, 上 + 20, 左 + 宽 + 13, 上 + 高 - 20);
  绘图
    .fillStyle(背景色, 0.99)
    .fillRoundedRect(左 - 10, 上 - 10, 宽 + 20, 高 + 20, 圆角)
    .lineStyle(1.2, 边框色, 0.95)
    .strokeRoundedRect(左 - 10, 上 - 10, 宽 + 20, 高 + 20, 圆角);
  绘图.lineStyle(2.2, 边框色, 0.78);
  for (const [x, 方向] of [
    [左 - 8, 1],
    [左 + 宽 + 8, -1],
  ]) {
    for (const [y, 纵向] of [
      [上 - 8, 1],
      [上 + 高 + 8, -1],
    ]) {
      绘图
        .beginPath()
        .moveTo(x, y + 纵向 * 14)
        .lineTo(x, y + 纵向 * 5)
        .lineTo(x + 方向 * 5, y)
        .lineTo(x + 方向 * 18, y)
        .strokePath();
    }
  }
  const 中 = 左 + 宽 / 2;
  绘图
    .lineStyle(1.5, 边框色, 0.5)
    .lineBetween(中 - 22, 上 - 14, 中 - 8, 上 - 14)
    .lineBetween(中 + 8, 上 - 14, 中 + 22, 上 - 14);
  绘图.fillStyle(边框色, 0.7).fillTriangle(中 - 4, 上 - 18, 中 + 4, 上 - 18, 中, 上 - 13);
}

export interface 棋盘网格参数 {
  宽: number;
  高: number;
  格子: number;
  列数: number;
  行数: number;
  网格色: number;
}

/** 内部网格 + 中央竖向柔光（取自预制体 布局 的原绘制）。 */
export function 绘制棋盘网格(绘图: 图形对象, 参数: 棋盘网格参数): void {
  const { 宽, 高, 格子, 列数, 行数, 网格色 } = 参数;
  绘图.lineStyle(1, 网格色, 0.32);
  for (let 列 = 1; 列 < 列数; 列 += 1) 绘图.lineBetween(列 * 格子, 0, 列 * 格子, 高);
  for (let 行 = 1; 行 < 行数; 行 += 1) {
    绘图.lineStyle(1, 网格色, 行 % 5 === 0 ? 0.46 : 0.28).lineBetween(0, 行 * 格子, 宽, 行 * 格子);
  }
  // 两侧透明渐变消除光柱的硬边，顶部留一点生成区光线。
  绘图
    .fillGradientStyle(0xffffff, 0xffffff, 0xffffff, 0xffffff, 0, 0.025, 0, 0.025)
    .fillRect(0, 0, 宽 / 2, 高);
  绘图
    .fillGradientStyle(0xffffff, 0xffffff, 0xffffff, 0xffffff, 0.025, 0, 0.025, 0)
    .fillRect(宽 / 2, 0, 宽 / 2, 高);
  绘图
    .fillGradientStyle(网格色, 网格色, 网格色, 网格色, 0.1, 0.1, 0, 0)
    .fillRect(0, 0, 宽, 格子 * 3);
}

/** 布局加玩法快照：页面组装，本模块只画框、网格和格内方块。 */
export interface 棋盘输入 {
  棋盘: { 左: number; 上: number; 宽: number; 高: number; 列: number; 行: number };
  格子大小: number;
  偏移X: number;
  偏移Y: number;
  方案: 方块外观方案;
  /** 玩法棋盘含顶部隐藏 2 行；可见行 r 对应 格子[r + 2]。 */
  格子: (方块类型 | null)[][];
  当前格子: readonly [number, number][];
  当前类型: 方块类型;
  影子: readonly [number, number][];
  显示网格: boolean;
  /** 0–100，来自设置。 */
  落点影透明度: number;
  部分: "静态" | "动态" | "全部";
  网格透明度?: number;
  跳过当前方块?: boolean;
}

const 棋盘格内缩 = 1;

function 绘制棋盘静态(绘图: 图形对象, 输入: 棋盘输入, 棋盘左: number, 棋盘上: number): void {
  const { 宽, 高, 列, 行 } = 输入.棋盘;
  const 格 = 输入.格子大小;
  绘制棋盘外框(绘图, {
    左: 棋盘左,
    上: 棋盘上,
    宽,
    高,
    格子: 格,
    透明度: 1,
    背景色: 游戏外观.棋盘.背景色,
    边框色: 游戏外观.棋盘.边框色,
  });
  if (输入.显示网格) {
    绘图.save();
    if (输入.网格透明度 != null) 绘图.setAlpha(输入.网格透明度);
    绘图.translateCanvas(棋盘左, 棋盘上);
    绘制棋盘网格(绘图, {
      宽,
      高,
      格子: 格,
      列数: 列,
      行数: 行,
      网格色: 读取对局界面色().网格线,
    });
    绘图.restore();
  }
  for (let 行号 = 0; 行号 < 行; 行号 += 1) {
    const 数据 = 输入.格子[行号 + 2];
    if (!数据) continue;
    for (let 列号 = 0; 列号 < 列; 列号 += 1) {
      const 类型 = 数据[列号];
      if (!类型) continue;
      绘制方块单元(绘图, 棋盘左 + 列号 * 格 + 棋盘格内缩, 棋盘上 + 行号 * 格 + 棋盘格内缩, {
        方案: 输入.方案,
        色值: 输入.方案.颜色[类型],
        格子: 格,
        圆角比例: 0.16,
      });
    }
  }
}

function 绘制棋盘动态(绘图: 图形对象, 输入: 棋盘输入, 棋盘左: number, 棋盘上: number): void {
  const { 行 } = 输入.棋盘;
  const 格 = 输入.格子大小;
  const 幽灵透明度 = Math.max(0, Math.min(1, 输入.落点影透明度 / 100));
  const 当前类型 = 输入.当前类型;
  for (const [列号, 行号] of 输入.影子) {
    if (行号 < 0 || 行号 >= 行 || 输入.格子[行号 + 2]?.[列号]) continue;
    绘制方块单元(绘图, 棋盘左 + 列号 * 格 + 棋盘格内缩, 棋盘上 + 行号 * 格 + 棋盘格内缩, {
      方案: 输入.方案,
      色值: 输入.方案.颜色[当前类型],
      格子: 格,
      透明度: 幽灵透明度,
      圆角比例: 0.16,
      幽灵: true,
    });
  }
  if (输入.跳过当前方块) return;
  for (const [列号, 行号] of 输入.当前格子) {
    if (行号 < 0 || 行号 >= 行) continue;
    绘制方块单元(绘图, 棋盘左 + 列号 * 格 + 棋盘格内缩, 棋盘上 + 行号 * 格 + 棋盘格内缩, {
      方案: 输入.方案,
      色值: 输入.方案.颜色[当前类型],
      格子: 格,
      圆角比例: 0.16,
    });
  }
}

/** 棋盘外框、网格、已落格、幽灵与当前块：只消费 棋盘输入，不读玩法状态机。 */
export function 绘制棋盘(绘图: 图形对象, 输入: 棋盘输入): void {
  const 棋盘左 = 输入.棋盘.左 + 输入.偏移X;
  const 棋盘上 = 输入.棋盘.上 + 输入.偏移Y;
  if (输入.部分 !== "动态") 绘制棋盘静态(绘图, 输入, 棋盘左, 棋盘上);
  if (输入.部分 !== "静态") 绘制棋盘动态(绘图, 输入, 棋盘左, 棋盘上);
}


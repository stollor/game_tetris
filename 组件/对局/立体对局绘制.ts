const 面 = 立体规范.界面;

function 绘制舱字(
  笔: 画笔,
  文案: string,
  x: number,
  底: number,
  字号: number,
  宽: number,
  颜色: number,
  选项: { 标签?: boolean; 字距?: number } = {},
): void {
  let 样式 = 读取对局文字样式(选项.标签 ? "信息标签" : "信息数值", {
    字号,
    颜色,
    ...(选项.字距 ? { 字距: 选项.字距 } : {}),
  });
  const 测 = 笔.测量文字(文案, 样式);
  if (测.宽 > 宽) 样式 = { ...样式, 字号: Math.max(11, (字号 * 宽) / 测.宽) };
  const 高 = 笔.测量文字(文案, 样式).高;
  笔.绘制文字({ 文案, 样式, 锚点: "中上", x, y: 底 - 高 + Math.max(0, 样式.字号 - 21) / 4 });
}

export function 绘制立体标题徽章(
  图: 图形对象,
  中心X: number,
  中心Y: number,
  宽: number,
  高: number,
): void {
  绘制金属板(图, 中心X - 宽 / 2, 中心Y - 高 / 2, 宽, 高, { 六角: true, 厚: 面.厚, 强调: true });
}

/** 效果图的 LV / SCORE / LINES 分舱，坐标仍用 `计算对局仪表`。 */
export function 绘制立体仪表(笔: 画笔, 输入: 对局仪表输入, 部分: "静态" | "动态"): void {
  const 定位 = 计算对局仪表(输入.布局, 输入.模式);
  const 图 = 笔.图形;
  const 舱 = [
    { 区: 定位.左, 六角: true },
    { 区: 定位.主, 六角: false },
    { 区: 定位.右, 六角: true },
  ];
  if (部分 === "静态") {
    for (const [序, 项] of 舱.entries())
      绘制金属板(图, 项.区.左, 项.区.上, 项.区.宽, 项.区.高, {
        六角: 项.六角,
        切: 序 === 1 ? 面.切 : 面.徽章切,
        厚: 面.厚,
        凹: true,
      });
    return;
  }
  const 标签 = [
    定位.计时栏 === "左" ? "TIME" : "LV",
    定位.目标行数 ? "LINES" : "SCORE",
    定位.计时栏 === "右" ? "TIME" : 定位.目标行数 ? "SCORE" : "LINES",
  ];
  const 时间 = 输入.模式 === "极限" ? 输入.剩余毫秒 : 输入.有效毫秒;
  const 分数 = Math.floor(Math.max(0, 输入.计分.显示分数)).toString().padStart(6, "0");
  const 值 = [
    定位.计时栏 === "左" ? 格式化仪表时间(时间) : String(输入.等级),
    定位.目标行数 ? `${输入.行数}/${定位.目标行数}` : 分数,
    定位.计时栏 === "右" ? 格式化仪表时间(时间) : 定位.目标行数 ? 分数 : String(输入.行数),
  ];
  for (const [序, 项] of 舱.entries()) {
    const 区 = 项.区;
    绘制舱字(
      笔,
      标签[序] ?? "",
      区.左 + 区.宽 / 2,
      区.上 + 面.仪表标签 + 4,
      面.仪表标签,
      区.宽 - 12,
      面.次字,
      { 标签: true },
    );
    绘制舱字(
      笔,
      值[序] ?? "",
      区.左 + 区.宽 / 2,
      定位.数值底,
      序 === 1 ? 面.仪表分值 : 面.仪表侧值,
      区.宽 - 14,
      面.灯芯,
      { 字距: 序 === 1 ? 面.分值距 : 0 },
    );
  }
  const 比例 = 定位.目标行数
    ? Math.min(1, 输入.行数 / 定位.目标行数)
    : 输入.模式 === "极限"
      ? Math.max(0, 时间 / 模式配置.极限毫秒)
      : null;
  if (比例 !== null) {
    const 区 = 定位.目标行数 ? 定位.主 : 定位.右;
    图.fillStyle(面.灯, 0.85).fillRect(区.左 + 16, 区.上 + 区.高 - 5, (区.宽 - 32) * 比例, 2);
  }
}

export function 绘制立体侧窗(图: 图形对象, 区域: 矩形): void {
  绘制金属板(图, 区域.左, 区域.上, 区域.宽, 区域.高, { 切: 面.窗切, 凹: true, 厚: 面.厚 });
}

export function 绘制立体窗签(图: 图形对象, 区域: 矩形): void {
  const 宽 = Math.min(区域.宽 - 8, 面.标签宽);
  绘制金属板(图, 区域.左 + (区域.宽 - 宽) / 2, 区域.上 - 面.标签高 / 2, 宽, 面.标签高, {
    切: 面.标签切,
    厚: 面.标签厚,
    强调: true,
  });
}

export function 绘制立体侧栏标签(笔: 画笔, 文案: string, x: number, y: number): void {
  笔.绘制文字({
    文案,
    样式: 读取对局文字样式("预览标题", { 字号: 面.侧标, 颜色: 面.灯芯 }),
    锚点: "中中",
    x,
    y,
  });
}

export function 读取立体界面色(): ReturnType<typeof 读取对局界面色> {
  const 色 = 读取对局界面色();
  return {
    ...色,
    面板: 面.板,
    次级面板: 面.壳面,
    强调: 面.灯,
    主字: 面.字,
    次字: 面.次字,
    标题: 面.灯芯,
  };
}

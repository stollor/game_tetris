/** 布局加玩法快照：暂存、下一个队列与纪录。页面组装，本模块只画。 */
export interface 暂存槽输入 {
  布局: 对局布局数据;
  方案: 方块外观方案;
  暂存方块: 方块类型 | null;
  本块已暂存: boolean;
  下一个: readonly 方块类型[];
  阶段: 游戏阶段;
  最佳纪录: string;
  暂无纪录: string;
  暂停: boolean;
  部分: "静态" | "动态";
  省电?: boolean;
  侧栏转场?: 侧栏转场 | null;
}

function 绘制样式文字(
  笔: 画笔,
  样式: 文字样式,
  文本: string,
  x: number,
  y: number,
  锚点: 文字锚点 = "左上",
): void {
  const 行高 = 笔.测量文字("字", 样式).高;
  笔.绘制文字({
    文案: 文本,
    样式,
    锚点,
    x,
    y: y - 文字对齐修正(样式.字号, 锚点, 行高),
  });
}

function 画居中块(
  笔: 画笔,
  方案: 方块外观方案,
  类型: 方块类型,
  区域: 矩形,
  格: number,
  透明度: number,
  圆角比例: number,
  辉光: boolean,
): void {
  绘制居中方块(笔.图形, { 方案, 类型, 区域, 格, 透明度, 圆角比例, 辉光 });
}

function 绘制竖屏暂存槽(笔: 画笔, 输入: 暂存槽输入): void {
  const 图形 = 笔.图形;
  const 侧栏 = 输入.布局.侧栏;
  if (!侧栏) return;
  const 色 = 读取对局界面色();
  const 暂存 = 侧栏.暂存;
  const 中心X = 暂存.左 + 暂存.宽 / 2;
  const 转场 = 输入.侧栏转场;
  const 帧 = 转场 && !输入.省电 ? 读取侧栏转场帧(转场, 输入.布局) : null;
  if (输入.部分 === "静态") {
    绘制传输管道(图形, 暂存);
    const 管 = 侧栏.预览栏;
    绘制传输管道(图形, { 左: 暂存.左, 上: 管.顶, 宽: 暂存.宽, 高: 管.高 + 5 });
    图形
      .lineStyle(1, 色.分组线, 0.4)
      .lineBetween(暂存.左 + 14, 暂存.上 + 27, 暂存.左 + 暂存.宽 - 14, 暂存.上 + 27);
    绘制暂存图标(图形, 中心X, 暂存.上 + 13, 0.72);
    const y = 侧栏.下一个标签.上 + 11;
    图形.lineStyle(1.5, 色.次字, 0.65);
    for (const 偏 of [0, 6])
      图形
        .beginPath()
        .moveTo(中心X - 7, y + 偏)
        .lineTo(中心X, y - 5 + 偏)
        .lineTo(中心X + 7, y + 偏)
        .strokePath();
    绘制霓虹玻璃(图形, 暂存.左, 侧栏.底 - 84, 暂存.宽, 80, {
      圆角: 10,
      透明度: 0.92,
      边色: 色.分组线,
      边透明度: 0.4,
    });
    const 奖杯Y = 侧栏.最佳纪录.标签Y + 1;
    图形
      .lineStyle(1.6, 色.次字, 0.8)
      .beginPath()
      .moveTo(中心X - 8, 奖杯Y)
      .lineTo(中心X - 6, 奖杯Y + 8)
      .lineTo(中心X, 奖杯Y + 12)
      .lineTo(中心X + 6, 奖杯Y + 8)
      .lineTo(中心X + 8, 奖杯Y)
      .closePath()
      .strokePath();
    图形
      .lineBetween(中心X, 奖杯Y + 12, 中心X, 奖杯Y + 16)
      .lineBetween(中心X - 5, 奖杯Y + 16, 中心X + 5, 奖杯Y + 16);
    return;
  }
  const 槽 = { 左: 暂存.左 + 10, 上: 暂存.上 + 31, 宽: 暂存.宽 - 20, 高: 暂存.高 - 39 };
  const 暂存飞行中 = 帧 && 转场?.类型 === "暂存" && 帧.进度 < 0.95;
  if (输入.暂存方块 && !暂存飞行中) {
    画居中块(
      笔,
      输入.方案,
      输入.暂存方块,
      槽,
      Math.floor(Math.min(20, 槽.宽 / 4, 槽.高 / 2)),
      输入.本块已暂存 ? 0.4 : 0.9,
      0.16,
      false,
    );
  } else if (!输入.暂存方块) {
    for (const [x, y] of [
      [0, 1],
      [1, 0],
      [1, 1],
      [2, 1],
    ])
      图形
        .lineStyle(1, 色.强调, 0.18)
        .strokeRoundedRect(中心X - 23 + x * 16, 槽.上 + 12 + y * 16, 14, 14, 2);
  }
  const 队列 = 输入.下一个.slice(0, 3);
  const 卡格 = 侧栏.预览栏.卡格;
  const 首卡 = 侧栏.下一步卡[0];
  if (首卡) {
    图形.fillStyle(色.强调, 0.06).fillRect(首卡.左 + 10, 首卡.上, 首卡.宽 - 20, 首卡.高);
    图形.lineStyle(2, 色.强调, 0.65);
    for (const x of [首卡.左 + 8, 首卡.左 + 首卡.宽 - 8])
      图形.lineBetween(x, 首卡.上 + 12, x, 首卡.上 + 首卡.高 - 12);
  }
  for (const 卡 of 侧栏.下一步卡.slice(1)) {
    const x = 卡.左 + 卡.宽 / 2;
    const y = 卡.上 - 4;
    图形.lineStyle(1.5, 色.强调, 0.3).strokePoints(
      [
        { x: x - 5, y: y + 3 },
        { x, y },
        { x: x + 5, y: y + 3 },
      ],
      false,
    );
  }
  侧栏.下一步卡.forEach((卡, 索引) => {
    const 类型 = 队列[索引];
    const 首位 = 索引 === 0;
    if (!类型) return;
    const 起卡 = 帧?.出队 ? 侧栏.下一步卡[索引 + 1] : null;
    const p = 帧?.进度 ?? 1;
    const 区域 = 起卡
      ? { ...卡, 上: 卡.上 + (起卡.上 - 卡.上) * (1 - p), 高: 卡.高 + (起卡.高 - 卡.高) * (1 - p) }
      : 卡;
    const 淡入 = 帧?.出队 && !起卡 ? p : 1;
    画居中块(笔, 输入.方案, 类型, 区域, 卡格, (首位 ? 1 : 0.82) * 淡入, 0.16, false);
  });
  if (!输入.暂停)
    绘制样式文字(
      笔,
      读取对局文字样式("纪录值"),
      输入.最佳纪录 === 输入.暂无纪录 ? "—" : 输入.最佳纪录.replace(" pts", ""),
      侧栏.最佳纪录.值X,
      侧栏.最佳纪录.值Y + 2,
      "中上",
    );
}

function 绘制桌面暂存槽(笔: 画笔, 输入: 暂存槽输入): void {
  const 图形 = 笔.图形;
  const 色 = 读取对局界面色();
  const 定位 = 计算对局附属布局(输入.布局);
  const 暂停中 = 输入.暂停;
  if (输入.部分 === "静态") {
    const 预览面板 = 定位.预览面板;
    绘制霓虹侧栏(图形, {
      左: 预览面板.左,
      顶: 预览面板.上,
      宽: 预览面板.宽,
      高: 预览面板.高,
      竖屏: false,
      紧凑: false,
    });
    绘制样式文字(
      笔,
      读取对局文字样式("纪录标签"),
      "最佳纪录",
      定位.最佳纪录.左,
      定位.最佳纪录.标签Y,
    );
    if (!暂停中)
      绘制样式文字(
        笔,
        读取对局文字样式("预览标题"),
        "下一个",
        定位.下一个标签.左,
        定位.下一个标签.上,
      );
    return;
  }
  if (!暂停中)
    绘制样式文字(
      笔,
      读取对局文字样式("纪录值"),
      输入.最佳纪录,
      定位.最佳纪录.左,
      定位.最佳纪录.值Y,
    );
  const 队列 = 输入.下一个.slice(0, 3);
  定位.下一步卡.forEach((卡, 索引) => {
    const 类型 = 队列[索引];
    const 首位 = 索引 === 0;
    const 方块色 = 类型 ? 输入.方案.颜色[类型] : undefined;
    绘制预览卡(图形, {
      左: 卡.左,
      上: 卡.上,
      宽: 卡.宽,
      高: 卡.高,
      圆角: 12,
      填色: 色.次级面板,
      边色: 首位 && 方块色 ? 亮色(方块色, 0.35) : 色.分组线,
      边透明度: 首位 ? 0.55 : 0.38,
      强调色: 首位 ? 方块色 : undefined,
      高光: false,
      首位,
    });
    if (类型) 画居中块(笔, 输入.方案, 类型, 卡, 定位.预览格, 1, 0.14, 首位 && !暂停中);
  });
  if (输入.阶段 !== "进行中") return;
  const 暂存 = 定位.暂存;
  const 视觉 = 读取角钮视觉(true);
  绘制玻璃按钮底板(图形, 暂存.左 + 暂存.宽 / 2, 暂存.上 + 暂存.高 / 2, 暂存.宽, 暂存.高, {
    填色: 视觉.填色,
    边框色: 视觉.边框色,
    强调色: 视觉.边框色,
    透明度: 视觉.透明度,
    边透明度: 视觉.边透明度,
  });
  if (输入.暂存方块)
    画居中块(
      笔,
      输入.方案,
      输入.暂存方块,
      { 左: 暂存.左 + 暂存.宽 / 2, 上: 暂存.上 + 暂存.高 / 2 - 12, 宽: 0, 高: 0 },
      定位.暂存格,
      输入.本块已暂存 ? 0.55 : 1,
      0.16,
      false,
    );
  else
    图形
      .lineStyle(1, 色.面板描边, 0.6)
      .strokeRoundedRect(暂存.左 + 暂存.宽 / 2 - 20, 暂存.上 + 10, 40, 暂存.高 - 36, 4);
  绘制样式文字(
    笔,
    读取对局文字样式("暂存标签", { 颜色: 输入.本块已暂存 ? 色.暗字 : 色.主字 }),
    输入.本块已暂存 ? "—" : "C",
    暂存.左 + 暂存.宽 / 2,
    暂存.上 + 暂存.高 - 13,
    "中中",
  );
}

/** 暂存槽与下一个队列：竖屏走管道侧栏，桌面走预览卡加独立暂存格。 */
export function 绘制暂存槽(笔: 画笔, 输入: 暂存槽输入): void {
  if (输入.布局.侧栏) 绘制竖屏暂存槽(笔, 输入);
  else 绘制桌面暂存槽(笔, 输入);
}

/** 仪表舱轮廓：切角读控件规格，底边保留略收的折线以维持装置感。 */
function 仪表轮廓(矩: 矩形, 主: boolean): 点[] {
  const 规格 = 读取仪表规格();
  const c = 主 ? 规格.主切角 : 规格.副切角;
  const { 左: x, 上: y, 宽: w, 高: h } = 矩;
  // 底边折线相对标准倒角多收 10px，保留原装置造型（非纯倒角矩形）。
  return [
    { x: x + c, y },
    { x: x + w - c, y },
    { x: x + w, y: y + c },
    { x: x + w, y: y + h - 10 },
    { x: x + w - c, y: y + h },
    { x: x + c, y: y + h },
    { x, y: y + h - 10 },
    { x, y: y + c },
  ];
}

/** 分离的等级舱、主仪表与副读数，通过连接轨与底部灯条连成一件装置。 */
export function 绘制对局仪表(笔: 画笔, 输入: 对局仪表输入, 部分: "静态" | "动态"): void {
  const 定位 = 计算对局仪表(输入.布局, 输入.模式);
  const 色 = 读取对局界面色();
  const 图 = 笔.图形;
  const 中X = 输入.布局.信息栏.中心X;
  const 右X = 定位.右.左 + 定位.右.宽 / 2;
  const 左X = 定位.左.左 + 定位.左.宽 / 2;
  const 字 = (文案: string, x: number, 底: number, 字号: number, 宽: number, 颜色 = 色.主字) => {
    let 样式 = 读取对局文字样式("信息数值", { 字号, 颜色 });
    const 测 = 笔.测量文字(文案, 样式);
    if (测.宽 > 宽) 样式 = { ...样式, 字号: Math.max(11, (字号 * 宽) / 测.宽) };
    const 高 = 笔.测量文字(文案, 样式).高;
    笔.绘制文字({ 文案, 样式, 锚点: "中上", x, y: 底 - 高 + Math.max(0, 样式.字号 - 21) / 4 });
  };
  if (部分 === "静态") {
    图.lineStyle(2, 色.强调, 0.22).lineBetween(左X, 定位.数值底 + 7, 右X, 定位.数值底 + 7);
    for (const [序, 矩] of [定位.左, 定位.主, 定位.右].entries()) {
      const 主 = 序 === 1;
      const 点集 = 仪表轮廓(矩, 主);
      图
        .save()
        .translateCanvas(0, 3)
        .fillStyle(色.信息分隔暗, 0.95)
        .fillPoints(点集, true)
        .restore();
      const 规 = 读取仪表规格();
      图
        .fillStyle(主 ? 色.次级面板 : 色.面板, 主 ? 规.面透明度 : Math.max(0.5, 规.面透明度 - 0.1))
        .fillPoints(点集, true);
      图
        .lineStyle(主 ? 规.描边宽 : Math.max(1, 规.描边宽 - 0.6), 色.强调, 主 ? 规.描边透明度 : 0.3)
        .strokePoints(点集, true);
      图
        .lineStyle(1, 色.强调, 0.25)
        .lineBetween(矩.左 + 15, 矩.上 + 5, 矩.左 + 矩.宽 - 15, 矩.上 + 5);
      图
        .fillStyle(色.强调, 主 ? 0.75 : 0.28)
        .fillRect(矩.左 + 17, 矩.上 + 矩.高 - 3, 矩.宽 - 34, 2);
    }
    if (定位.计时栏 !== "左") 字("LV", 左X, 定位.左.上 + 19, 11, 定位.左.宽 - 10, 色.次字);
    if (定位.计时栏 !== "右") {
      if (定位.目标行数) {
        图.lineStyle(1.3, 色.次字, 0.8).strokePoints(
          [
            { x: 右X, y: 定位.右.上 + 8 },
            { x: 右X + 5, y: 定位.右.上 + 12 },
            { x: 右X, y: 定位.右.上 + 16 },
            { x: 右X - 5, y: 定位.右.上 + 12 },
          ],
          true,
        );
      } else {
        图.lineStyle(1.4, 色.次字, 0.85);
        for (let i = 0; i < 3; i++)
          图.lineBetween(右X - 7, 定位.右.上 + 8 + i * 4, 右X + 7, 定位.右.上 + 8 + i * 4);
      }
    }
    return;
  }
  if (定位.计时栏 !== "左") 字(String(输入.等级), 左X, 定位.数值底, 21, 定位.左.宽 - 12, 色.强调);
  if (定位.目标行数) {
    const 主值 = String(输入.行数);
    const 主样 = 读取对局文字样式("信息数值", { 字号: 36, 颜色: 色.主字 });
    const 副样 = 读取对局文字样式("信息数值", { 字号: 18, 颜色: 色.次字 });
    const 主宽 = 笔.测量文字(主值, 主样).宽;
    const 副文 = `/${定位.目标行数}`;
    const 副宽 = 笔.测量文字(副文, 副样).宽;
    const 起 = 中X - (主宽 + 副宽 + 5) / 2;
    字(主值, 起 + 主宽 / 2, 定位.数值底, 36, 主宽 + 1);
    字(副文, 起 + 主宽 + 5 + 副宽 / 2, 定位.数值底, 18, 副宽 + 1, 色.次字);
    const 进度 = Math.min(1, 输入.行数 / 定位.目标行数);
    图
      .fillStyle(色.成功, 0.85)
      .fillRect(定位.主.左 + 17, 定位.主.上 + 定位.主.高 - 3, (定位.主.宽 - 34) * 进度, 2);
  } else if (定位.计时栏 !== "右") {
    字(String(输入.行数), 右X, 定位.数值底, 21, 定位.右.宽 - 12, 色.强调);
  }
  const 强度 = 输入.计分.击中;
  if (强度 > 0) {
    const 区 = 定位.目标行数 ? 定位.右 : 定位.主;
    图.fillStyle(色.强调, 强度 * 0.16).fillPoints(仪表轮廓(区, !定位.目标行数), true);
    图
      .lineStyle(1 + 强度, 色.主字, 强度 * 0.65)
      .lineBetween(区.左 + 18, 区.上 + 3, 区.左 + 区.宽 - 18, 区.上 + 3);
  }
  const 值 = 输入.计分.显示分数;
  const 位数 = Math.max(6, Math.floor(Math.max(0, 值)).toString().length);
  let 样式 = 读取对局文字样式("信息数值", {
    字号: 定位.分数字号,
    颜色: 混色(色.正文, 色.主字, 强度),
  });
  const 数宽 = 笔.测量文字("0".repeat(位数), 样式).宽;
  if (数宽 > 定位.分数宽) 样式 = { ...样式, 字号: (样式.字号 * 定位.分数宽) / 数宽 };
  const 字宽 = 笔.测量文字("0", 样式).宽;
  const 行高 = 笔.测量文字("0", 样式).高;
  // 字形行框的底部留白随字号增大，补齐可见数字底线。
  const 底 = 定位.数值底 + Math.max(0, 样式.字号 - 21) / 4 - Math.sin(强度 * Math.PI) * 2;
  const 上 = 底 - 行高;
  笔.压入裁剪({ 左: 定位.分数X - 定位.分数宽 / 2, 上, 宽: 定位.分数宽, 高: 行高 });
  读取滚动数位(值, 位数).forEach((位, i) => {
    const x = 定位.分数X + (i - (位数 - 1) / 2) * 字宽;
    笔.绘制文字({ 文案: String(位.数字), 样式, 锚点: "中上", x, y: 上 - 位.进度 * 行高 });
    if (位.进度 > 0)
      笔.绘制文字({ 文案: String(位.下一个), 样式, 锚点: "中上", x, y: 上 + (1 - 位.进度) * 行高 });
  });
  笔.弹出裁剪();
  if (定位.计时栏) {
    const 时限 = 输入.模式 === "极限";
    const 毫秒 = 时限 ? 输入.剩余毫秒 : 输入.有效毫秒;
    const 紧迫 = 时限 && 毫秒 <= 10000;
    const 临近 = 时限 && 毫秒 <= 30000;
    const 脉冲 = 紧迫 && !输入.省电 ? (1 + Math.sin((输入.有效毫秒 / 1000) * Math.PI * 4)) / 2 : 0;
    const 钟色 = 紧迫 ? 0xff8b76 : 临近 ? 0xf3cf7d : 色.强调;
    const 槽 = 定位.计时栏 === "右" ? 定位.右 : 定位.左;
    const x = 槽.左 + 槽.宽 / 2;
    const y = 槽.上 + 12;
    图.lineStyle(1.5, 钟色, 0.8).strokeCircle(x, y, 9 + 脉冲);
    图
      .lineStyle(1.5, 钟色, 0.9)
      .lineBetween(x, y - 5, x, y)
      .lineBetween(x, y, x + 4, y + 2);
    字(格式化仪表时间(毫秒, 紧迫), x, 定位.数值底, 紧迫 ? 23 : 22, 槽.宽 - 12, 钟色);
    if (时限)
      图
        .fillStyle(钟色, 0.35 + 脉冲 * 0.35)
        .fillRect(
          槽.左 + 17,
          槽.上 + 槽.高 - 3,
          (槽.宽 - 34) * Math.min(1, Math.max(0, 毫秒 / 模式配置.极限毫秒)),
          2,
        );
  }
}

/** 从真实消行/落块位置飞向当前模式的分数槽，命中后由计分反馈启动滚数。 */
export function 绘制计分流光(笔: 画笔, 输入: 对局仪表输入): void {
  const 定位 = 计算对局仪表(输入.布局, 输入.模式);
  const 色 = 读取对局界面色();
  const 图 = 笔.图形;
  for (const 光 of 输入.计分.流光) {
    const 源 = {
      x: 输入.布局.棋盘.左 + (光.列 + 0.5) * 输入.布局.格子大小,
      y: 输入.布局.棋盘.上 + (光.行 + 0.5) * 输入.布局.格子大小,
    };
    const 终 = { x: 定位.分数X, y: 定位.数值底 - 15 };
    const 点 = (t: number) => ({
      x: (1 - t) ** 2 * 源.x + 2 * (1 - t) * t * (源.x + 55) + t ** 2 * 终.x,
      y: (1 - t) ** 2 * 源.y + 2 * (1 - t) * t * (终.y + 40) + t ** 2 * 终.y,
    });
    for (let i = 输入.省电 ? 1 : 5; i > 0; i--) {
      const a = 点(Math.max(0, 光.进度 - i * 0.035));
      const b = 点(Math.max(0, 光.进度 - (i - 1) * 0.035));
      图.lineStyle(1.5 + (5 - i) * 0.35, 色.强调, (6 - i) * 0.1).lineBetween(a.x, a.y, b.x, b.y);
    }
    const 头 = 点(光.进度);
    图
      .fillStyle(色.强调, 0.15)
      .fillCircle(头.x, 头.y, 7)
      .fillStyle(色.主字, 0.9)
      .fillCircle(头.x, 头.y, 2.3);
  }
}

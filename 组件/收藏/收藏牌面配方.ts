/** 部位卡左侧图标（Phaser 商店 绘部位预览 的共享版本）。 */
export function 绘制商店部位图标(
  绘图: 图形对象,
  区: 矩形,
  部位: 外观部位,
  地点: 地点皮肤,
  选项: 商店部位图标选项,
): void {
  绘制商店部位预览底板(绘图, 区);
  if (部位 === "静态背景" || 部位 === "动态背景") {
    选项.绘制风景(区.左 + 2, 区.上 + 2, 区.宽 - 4, 区.高 - 4);
    return;
  }
  if (是像素风格() && 部位 !== "方块外观") {
    const 图案 =
      部位 === "界面样式" ? 像素图标.设置 : 部位 === "音效套装" ? 像素图标.音效 : 像素图标.音乐;
    const 格 = Math.max(1, Math.floor(Math.min(区.宽, 区.高) / 图案.length));
    绘制像素图案(
      绘图,
      图案,
      区.左 + (区.宽 - 格 * 图案.length) / 2,
      区.上 + (区.高 - 格 * 图案.length) / 2,
      格,
      像素规范.色.纸,
    );
    return;
  }
  if (部位 === "界面样式") {
    绘图.fillStyle(地点.主色).fillRoundedRect(区.左 + 6, 区.上 + 10, 区.宽 - 12, 区.高 - 20, 4);
    绘图
      .lineStyle(1, 地点.强调, 0.8)
      .strokeRoundedRect(区.左 + 6, 区.上 + 10, 区.宽 - 12, 区.高 - 20, 4);
    绘制地点纹样(绘图, 区.左 + 10, 区.上 + 14, 16, 地点.纹样, 0.9);
    return;
  }
  if (部位 === "方块外观") {
    const 格 = Math.max(8, Math.min(14, Math.floor((区.宽 - 8) / 4)));
    const 格点 = 预览格子("T");
    const 件宽 = (Math.max(...格点.map((点) => 点[0])) + 1) * 格;
    const 件高 = (Math.max(...格点.map((点) => 点[1])) + 1) * 格;
    const ox = 区.左 + (区.宽 - 件宽) / 2;
    const oy = 区.上 + (区.高 - 件高) / 2;
    const 外观 = {
      方案: 解析方块外观(地点.名称),
      格子: 格,
      色值: 地点.方块[2],
    } as const;
    for (const [gx, gy] of 格点) 绘制方块单元(绘图, ox + gx * 格, oy + gy * 格, 外观);
    return;
  }
  if (部位 === "音效套装") {
    const cy = 区.上 + 区.高 / 2;
    绘图.fillStyle(地点.强调).fillTriangle(区.左 + 8, cy - 10, 区.左 + 8, cy + 10, 区.左 + 18, cy);
    绘图.fillStyle(地点.强调).fillRect(区.左 + 8, cy - 6, 6, 12);
    for (let i = 0; i < 3; i++)
      绘图.lineStyle(1.4, 地点.强调, 0.7 - i * 0.18).strokeCircle(区.左 + 16, cy, 6 + i * 4);
    return;
  }
  const cy = 区.上 + 区.高 / 2;
  绘图.lineStyle(2, 地点.强调).lineBetween(区.左 + 10, 区.上 + 区.高 - 6, 区.左 + 10, 区.上 + 6);
  绘图.fillStyle(地点.强调).fillCircle(区.左 + 10, 区.上 + 8, 4);
  绘图.fillStyle(地点.强调, 0.5).fillEllipse(区.左 + 22, cy, 12, Math.min(18, 区.高 - 8));
}

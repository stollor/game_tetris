import { 界面主题 } from "../../../主题/配色/主题读取";
import type { 图形对象, 文字样式 } from "../../../框架/界面/绘制/协议";
import { 绘制常规按钮, 读取常规按钮文字样式 } from "./按钮配方";

/**
 * 覆盖页（设置/成就/排行榜）按钮视觉：颜色取主题按钮状态，
 * 透明度用 0.92 / 0.55，与常规按钮配方的 0.96 / 0.92 不同。
 * 页面把这组值交给常规按钮配方，不在页面里写色表。
 *
 * 已选时按钮角色为主要、颜色取点击；否则取次要默认。
 */

export interface 覆盖页按钮视觉 {
  已选: boolean;
  面板色: string;
  边框色: string;
  文字色: string;
  面板透明度: number;
  边框透明度: number;
}

/** 框架 `界面按钮` 的默认面板/边框透明度（见 `Phaser预制体配置.按钮`）。 */
const 框架按钮透明度 = { 面板: 0.92, 边框: 0.55 } as const;

export function 读取覆盖页按钮视觉(已选: boolean): 覆盖页按钮视觉 {
  const 按钮 = 界面主题().按钮;
  const 状态 = 已选 ? 按钮.主要.点击 : 按钮.次要.默认;
  return {
    已选,
    面板色: 状态.背景,
    边框色: 状态.描边,
    文字色: 状态.文字,
    面板透明度: 框架按钮透明度.面板,
    边框透明度: 框架按钮透明度.边框,
  };
}

/** 画覆盖页按钮底板（中心定位）：颜色/透明度与 Phaser 框架通用按钮一致。 */
export function 绘制覆盖页按钮(
  绘图: 图形对象,
  中心X: number,
  中心Y: number,
  宽: number,
  高: number,
  已选 = false,
): void {
  const 视觉 = 读取覆盖页按钮视觉(已选);
  绘制常规按钮(绘图, 中心X, 中心Y, 宽, 高, {
    变体: "次要",
    已选: 视觉.已选,
    面板色: 视觉.面板色,
    强调色: 视觉.面板色,
    边框色: 视觉.边框色,
    面板透明度: 视觉.面板透明度,
    边框透明度: 视觉.边框透明度,
  });
}

/** 按钮文字样式取主题按钮状态的文字色（成就/排行榜的框架按钮走这条）。 */
export function 读取覆盖页按钮文字样式(已选: boolean, 字号: number): 文字样式 {
  const 视觉 = 读取覆盖页按钮视觉(已选);
  return 读取常规按钮文字样式({ 变体: "次要", 字号, 已选 }, { 颜色: 视觉.文字色 });
}

/**
 * 按钮文字样式（文字色跟随底色）：设置页按钮在框架里开了 `文字色跟随底色`，
 * 按「已选 ? 强调色 : 面板色」的对比度取深/浅色 —— 复用按钮配方的同一算法。
 */
export function 读取覆盖页按钮对比文字样式(已选: boolean, 字号: number): 文字样式 {
  const 视觉 = 读取覆盖页按钮视觉(已选);
  return 读取常规按钮文字样式({
    变体: "次要",
    字号,
    已选,
    面板色: 视觉.面板色,
    强调色: 视觉.面板色,
  });
}

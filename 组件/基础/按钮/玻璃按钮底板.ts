import { 像素规范 } from "../../../主题/像素/像素规范";
import { 是像素风格 } from "../../../主题/像素/像素风格";
import { 是立体风格 } from "../../../主题/立体/立体风格";
import { 读取按钮规格 } from "../../../框架/样式/控件规格";
import type { 图形对象 } from "../../../框架/界面/绘制/协议";
import { 亮色 } from "../../../框架/界面/颜色工具";
import { 绘制像素面板 } from "../面板/像素面板";
import { 绘制金属板 } from "../面板/金属板";

/** 玻璃质感按钮底板的选项。 */
export interface 玻璃按钮选项 {
  圆角?: number;
  描边宽?: number;
  填色?: number;
  边框色?: number;
  强调色?: number;
  选中?: boolean;
  悬停?: boolean;
  透明度?: number;
  边透明度?: number;
}

/** 玻璃质感按钮底板（中心定位），与 GM 框架 `绘制玻璃按钮` 同算法。 */
export function 绘制玻璃按钮底板(
  绘图: 图形对象,
  中心X: number,
  中心Y: number,
  宽: number,
  高: number,
  选项: 玻璃按钮选项 = {},
): void {
  if (是像素风格()) {
    绘制像素面板(
      绘图,
      中心X - 宽 / 2,
      中心Y - 高 / 2,
      宽,
      高,
      选项.选中 || 选项.悬停 ? (选项.强调色 ?? 像素规范.色.黄) : (选项.填色 ?? 像素规范.色.纸),
    );
    return;
  }
  if (是立体风格()) {
    const 规格 = 读取按钮规格();
    绘制金属板(绘图, 中心X - 宽 / 2, 中心Y - 高 / 2, 宽, 高, {
      切: 选项.圆角 ?? 规格.圆角,
      按下: 选项.选中,
      强调: 选项.选中 || 选项.悬停,
      透明度: 选项.透明度 ?? 规格.面板透明度,
      描边宽: 选项.描边宽 ?? 规格.描边宽,
      描边透明度: 选项.边透明度 ?? 规格.描边透明度,
    });
    return;
  }
  const 规格 = 读取按钮规格();
  const 圆角 = Math.max(0, Math.min(选项.圆角 ?? 规格.圆角, 宽 / 2, 高 / 2));
  const 强调色 = 选项.强调色 ?? 0x65e6dc;
  const 填色 = 选项.选中 ? 强调色 : (选项.填色 ?? 0x16213a);
  const 透明度 = 选项.透明度 ?? 规格.面板透明度;
  const 描边宽 = 选项.描边宽 ?? 规格.描边宽;
  const x = 中心X - 宽 / 2;
  const y = 中心Y - 高 / 2;
  const 悬停 = 选项.悬停 ?? false;
  绘图.fillStyle(填色, 透明度).fillRoundedRect(x, y, 宽, 高, 圆角);
  if (悬停 && !选项.选中) {
    绘图.fillStyle(亮色(填色, 0.12), 0.5).fillRoundedRect(x + 1, y + 1, 宽 - 2, 高 - 2, 圆角 - 1);
  }
  const 边透明度 =
    选项.边透明度 ??
    (选项.选中
      ? Math.max(规格.描边透明度, 0.9)
      : 悬停
        ? Math.max(规格.描边透明度, 0.8)
        : 规格.描边透明度);
  if (描边宽 > 0)
    绘图
      .lineStyle(描边宽, 选项.选中 ? 强调色 : (选项.边框色 ?? 亮色(填色, 0.5)), 边透明度)
      .strokeRoundedRect(x, y, 宽, 高, 圆角);
}

/**
 * 模式选择卡：蓝色玻璃面板是入口牌，左侧槽位放该模式自己的小装置。
 * 排行只是右上角的小牌。文字从槽位右侧起排。数据由调用方提供，不读存档。
 */

export interface 模式卡布局 {
  中心X: number;
  中心Y: number;
  宽: number;
  高: number;
}

export interface 模式卡数据 {
  标题: string;
  细节: string;
  说明: string;
  纪录: string;
  强调色: string;
  /** 主题色数值，画槽位和方块用；缺省时从强调色解析。 */
  色值?: number;
  /** 左侧装置图形。缺省不画图案。 */
  装置?: 游戏模式;
  /** 是否显示右上角排行入口（打开该模式榜）。 */
  有排行?: boolean;
}

export interface 模式卡绘制状态 extends 霓虹按钮状态 {
  /** 面板下沉像素。按下但未给出时按 3。 */
  下沉?: number;
  时间秒?: number;
  /** 四颗图案方块的点亮进度，0..1。 */
  点亮?: readonly number[];
  排行按下?: boolean;
}

/** 排行入口：卡右上角的小牌，比整卡矮一截，避免和标题抢主操作。 */
export function 计算模式卡排行区域(布局: 模式卡布局): {
  中心X: number;
  中心Y: number;
  宽: number;
  高: number;
} {
  return {
    中心X: 布局.中心X + 布局.宽 / 2 - 20,
    中心Y: 布局.中心Y - 布局.高 / 2 + 20,
    宽: 30,
    高: 30,
  };
}

function 读取下沉(状态: 模式卡绘制状态): number {
  if (状态.下沉 !== undefined) return 状态.下沉;
  return 状态.按下 ? 3 : 0;
}

function 读取色值(数据: 模式卡数据): number {
  if (数据.色值 !== undefined) return 数据.色值;
  return 解析颜色数值(数据.强调色);
}

/** 蓝色面板盖在厚度上，外沿用主题色描边；按下不改成整卡填色。 */
export function 绘制模式卡底板(
  绘图: 图形对象,
  布局: 模式卡布局,
  数据: 模式卡数据,
  状态: 模式卡绘制状态 = {},
): void {
  const 下沉 = 读取下沉(状态);
  const 色值 = 读取色值(数据);
  const 圆角 = Math.min(12, 布局.高 * 0.28, 布局.宽 / 2);
  绘制悬浮影(绘图, 布局.中心X, 布局.中心Y + 布局.高 / 2, 布局.宽, 下沉);
  绘图.save();
  绘图.translateCanvas(0, 下沉);
  绘制卡片厚度(绘图, 布局);
  绘制霓虹按钮(绘图, 布局.中心X, 布局.中心Y, 布局.宽, 布局.高, {
    变体: "次要",
    强调色: 数据.强调色,
    已选: 状态.已选,
    悬停: 状态.悬停,
  });
  const x = 布局.中心X - 布局.宽 / 2;
  const y = 布局.中心Y - 布局.高 / 2;
  绘图
    .lineStyle(1.5, 色值, 状态.按下 || 下沉 > 0 ? 0.95 : 0.62)
    .strokeRoundedRect(x, y, 布局.宽, 布局.高, 圆角);
  if (数据.装置) {
    绘制模式插座(绘图, 布局, 数据.装置, 色值, 状态.时间秒 ?? 0, 状态.点亮 ?? []);
  }
  绘图.restore();
}

/** 右上角排行小牌：深底、暖金描边，按下只下沉，不铺满强调色。 */
export function 绘制模式卡排行钮(
  绘图: 图形对象,
  布局: 模式卡布局,
  状态: 模式卡绘制状态 = {},
): void {
  const 区域 = 计算模式卡排行区域(布局);
  const 下沉 = (状态.排行按下 ? 2 : 0) + 读取下沉(状态);
  const x = 区域.中心X - 区域.宽 / 2;
  const y = 区域.中心Y - 区域.高 / 2 + 下沉;
  绘图.fillStyle(0x0b1422, 0.9).fillRoundedRect(x + 1, y + 2, 区域.宽 - 1, 区域.高 - 1, 8);
  绘图.fillStyle(0x172433, 0.96).fillRoundedRect(x, y, 区域.宽, 区域.高, 8);
  绘图.lineStyle(1, 0xffe7a8, 0.9).strokeRoundedRect(x, y, 区域.宽, 区域.高, 8);
  绘制霓虹按钮图标(绘图, {
    名称: "排行",
    中心X: 区域.中心X,
    中心Y: 区域.中心Y + 下沉,
    尺寸: 14,
  });
}

/** 模式卡的全部像素：底板、装置槽、可选排行牌（文字走 生成模式卡文字项）。 */
export function 绘制模式卡(
  绘图: 图形对象,
  布局: 模式卡布局,
  数据: 模式卡数据,
  状态: 模式卡绘制状态 = {},
): void {
  绘制模式卡底板(绘图, 布局, 数据, 状态);
  if (数据.有排行) 绘制模式卡排行钮(绘图, 布局, 状态);
}

/** 标题与细节让开左侧装置槽和右上角排行牌，说明和纪录按卡内行距显示。 */
export function 生成模式卡文字项(布局: 模式卡布局, 数据: 模式卡数据): 文字项[] {
  const { 中心X, 中心Y, 宽, 高 } = 布局;
  const 座 = 计算模式插座(布局);
  const 文字左 = 数据.装置 ? 座.左 + 座.宽 + 12 : 中心X - 宽 / 2 + 22;
  const 右沿 = 中心X + 宽 / 2 - (数据.有排行 ? 46 : 16);
  const 全文右 = 中心X + 宽 / 2 - 16;
  const 细节宽 = Math.min(96, Math.max(64, (右沿 - 文字左) * 0.4));
  return [
    {
      文案: 数据.标题,
      样式: 读取霓虹文字样式("模式卡标题"),
      锚点: "左中",
      x: 文字左,
      y: 中心Y - 高 / 2 + 23,
      最大宽: Math.max(48, 右沿 - 文字左 - 细节宽 - 8),
      适配单行: true,
    },
    {
      文案: 数据.细节,
      样式: { ...读取霓虹文字样式("模式卡细节"), 颜色: 数据.强调色 },
      锚点: "右中",
      x: 右沿,
      y: 中心Y - 高 / 2 + 23,
      最大宽: 细节宽,
      适配单行: true,
    },
    {
      文案: 数据.说明,
      样式: 读取霓虹文字样式("模式卡说明"),
      锚点: "左中",
      x: 文字左,
      y: 中心Y + 1,
      最大宽: Math.max(48, 全文右 - 文字左),
      适配单行: true,
    },
    {
      文案: 数据.纪录,
      样式: 读取霓虹文字样式("模式卡纪录"),
      锚点: "左中",
      x: 文字左,
      y: 中心Y + 高 / 2 - 20,
      最大宽: Math.max(48, 全文右 - 文字左),
      适配单行: true,
    },
  ];
}

/** 「最佳 xxx」文案格式化：存档读取留在 Phaser/Three 各自的接口层，这里只管视觉文本。 */
export function 格式化模式纪录(模式: 游戏模式, 纪录: 对局纪录 | null, 英文: boolean): string {
  if (!纪录) return 英文 ? "NO RECORD YET" : "尚无纪录";
  if (模式 === "冲刺")
    return 纪录.用时
      ? `${(纪录.用时 / 1000).toFixed(2)}s`
      : 英文
        ? "NO FINISH YET"
        : "尚无完赛纪录";
  return `${纪录.分数.toLocaleString()}${英文 ? " pts" : " 分"}`;
}

/** 模式卡纪录行（含「最佳/ BEST」前缀），两版共用同一文案。 */
export function 生成模式纪录行(模式: 游戏模式, 纪录: 对局纪录 | null, 英文: boolean): string {
  const 前缀 = 英文 ? "BEST" : "最佳";
  return `${前缀}  ${格式化模式纪录(模式, 纪录, 英文)}`;
}

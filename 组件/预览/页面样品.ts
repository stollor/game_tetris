/**
 * 六个真实页面的整页样品。元数据阶段只登记源码与尺寸，游戏页面和预览上下文都在
 * `准备资源()` 里动态导入；`创建场景()` 才 new 真实页面并走 进入/更新/渲染/销毁。
 *
 * 页面自己的按钮、导航、存档读取等仍按真实实现运行，但上下文来自 `页面环境.ts`：
 * 导航只读不启动游戏，金币/奖励/成就推进返回失败原因，平台不发请求，音频仅显式试听。
 */

type 页面环境模块 = typeof import("./页面环境");

type 页面构造器 = new (上下文: 页面上下文) => 页面实例;

export interface 页面场景 {
  更新状态(状态: Readonly<Record<string, string>>): void;
  试听音频(): void;
  读取运行状态(): import("../../框架/开发/界面资源协议").资源运行状态;
  更新(秒: number): boolean;
  渲染(): void;
  销毁(): void;
  读取界面(): 界面快照;
}

interface 页面描述 {
  编号: string;
  名称: string;
  页面: 页面编号 | 覆盖页编号;
  路径: string;
  导出: string;
  说明: string;
  加载: () => Promise<页面构造器>;
}

const 空绘制: 界面资源样品["绘制"] = () => {};

let 环境工厂: 页面环境模块 | undefined;

async function 载入页面环境(): Promise<页面环境模块> {
  return await import("./页面环境");
}

function 创建页面样品(描述: 页面描述): 界面资源样品 {
  let 页面类: 页面构造器 | undefined;

  return {
    编号: 描述.编号,
    名称: 描述.名称,
    分类: "应用",
    页面: true,
    功能: 描述.页面,
    主题槽位: 主题组合目录.槽位.map((项) => 项.编号),
    宽: 390,
    高: 844,
    预览: { 方式: "独立" },
    说明: 描述.说明,
    源码: [
      { 路径: 描述.路径, 导出: 描述.导出 },
      { 路径: "组件/预览/页面环境.ts", 导出: "创建预览页面上下文" },
      { 路径: "组件/预览/页面样品.ts", 导出: "页面样品" },
    ],
    状态: [
      主题状态,
      { 键: "音频试听", 名称: "真实音频试听", 默认: "关闭", 选项: ["关闭", "开启"] },
    ],
    绘制: 空绘制,
    async 准备资源(): Promise<void> {
      const [页面模块, 环境模块] = await Promise.all([描述.加载(), 载入页面环境()]);
      页面类 = 页面模块;
      环境工厂 = 环境模块;
    },
    创建场景(场景环境: 界面资源场景环境): 页面场景 {
      if (!页面类 || !环境工厂) throw new Error(`页面样品「${描述.名称}」尚未准备资源`);
      const 会话 = 环境工厂.创建预览页面上下文(场景环境, { 页面: 描述.页面 });
      let 页面: 页面实例 | undefined;
      let 已销毁 = false;
      let 音频开启 = 场景环境.状态.音频试听 === "开启";
      const 销毁 = () => {
        if (已销毁) return;
        已销毁 = true;
        try {
          if (页面?.销毁) 页面.销毁();
          else 页面?.退出?.();
        } finally {
          会话.销毁();
        }
      };
      场景环境.登记清理(销毁);
      try {
        const 当前 = new 页面类(会话.上下文);
        页面 = 当前;
        页面.进入?.({ 覆盖: false });
        if (描述.页面 === "对局") {
          if (!页面.测试) throw new Error("对局预览需要 GM 开发测试入口，拒绝启动正式对局");
          页面.测试.标记不写存档();
          页面.测试.摆好素材画面();
        }
        const 背景调度 = 创建背景调度({
          标准间隔毫秒: 画质参数.标准背景间隔毫秒,
          省电间隔毫秒: 画质参数.省电背景间隔毫秒,
          闲置间隔毫秒: 画质参数.闲置背景间隔毫秒,
          闲置判定毫秒: 画质参数.闲置判定毫秒,
        });
        return {
          更新状态: (状态) => {
            const 设置 = 会话.上下文.服务.设置;
            const 当前设置 = 设置.读取();
            const 主题设置 = 读取预览主题设置(状态, 当前设置);
            const 新音频开启 = 状态.音频试听 === "开启";
            const 音频变化 = 音频开启 !== 新音频开启;
            音频开启 = 新音频开启;
            设置.更新({
              ...主题设置,
              ...(音频变化
                ? { 背景音乐: 音频开启, 音乐音量: 音频开启 ? 40 : 0, 音效音量: 音频开启 ? 60 : 0 }
                : {}),
            });
            if (音频变化) 会话.设置音频开启(音频开启);
          },
          试听音频: () => {
            if (场景环境.状态.音频试听 !== "开启") throw new Error("请先开启真实音频试听");
            会话.上下文.服务.音频.解锁();
            会话.上下文.服务.音频.播放音乐(描述.页面 === "对局" ? "对局" : "菜单");
          },
          读取运行状态: () => ({
            页面: 当前.读取快照?.(),
            主题: 读取预览主题解析(场景环境.状态, 会话.上下文.服务.设置.读取()),
            音频: 会话.上下文.服务.音频.读取状态(),
          }),
          更新(秒: number): boolean {
            if (已销毁) return false;
            当前.更新?.(秒, 会话.上下文);
            背景调度.设置动态(当前.读取背景动态?.() ?? false);
            背景调度.设置省电(会话.上下文.服务.设置.读取().省电模式 === "开");
            const 刷新背景 = 背景调度.到点() && !!当前.刷新背景动态;
            if (刷新背景) {
              当前.刷新背景动态?.();
              背景调度.记录绘制();
            }
            return 刷新背景 || (当前.读取需要连续帧?.() ?? false);
          },
          渲染(): void {
            if (!已销毁) 当前.渲染?.(会话.上下文);
          },
          销毁,
          读取界面(): 界面快照 {
            return 当前.读取界面?.() ?? { 按钮: [] };
          },
        };
      } catch (错误) {
        销毁();
        throw 错误;
      }
    },
  };
}


function 默认参数(页面: 预览页面名称): 页面参数 {
  if (页面 === "对局") return { 模式: "马拉松", 跳过入场: true };
  if (页面 === "结算") return { 结果: { ...固定结算结果 } };
  if (页面 === "排行榜") return { 模式: "马拉松" };
  return {};
}

function 读取基础页面(页面: 预览页面名称): 页面编号 {
  switch (页面) {
    case "主界面":
    case "对局":
    case "设置":
    case "成就":
    case "排行榜":
    case "商店":
      return 页面;
    default:
      return "主界面";
  }
}

function 读取覆盖页(页面: 预览页面名称): 覆盖页编号 | null {
  switch (页面) {
    case "结算":
    case "暂停菜单":
    case "提示":
      return 页面;
    default:
      return null;
  }
}

/** 上下文只为一页服务：设置/金币/成就等状态每次创建都是独立内存副本。 */
export function 创建预览页面上下文(
  场景环境: 界面资源场景环境,
  选项: 创建预览页面选项,
): 预览页面会话 {
  const 页面名 = 选项.页面;
  const 参数: 页面参数 = { ...默认参数(页面名), ...选项.参数 };
  const 清理集 = new Set<() => void>();
  let 已清理 = false;

  function 执行清理(): void {
    if (已清理) return;
    已清理 = true;
    for (const 回调 of [...清理集]) {
      清理集.delete(回调);
      try {
        回调();
      } catch {
        // 单个页面的清理失败不应阻断其余订阅/监听解除。
      }
    }
  }

  // 框架的登记清理只接收回调、不返回解绑函数；这里包装成页面契约要求的 () => void。
  场景环境.登记清理(执行清理);

  function 登记清理(回调: () => void): () => void {
    if (已清理) {
      回调();
      return () => {};
    }
    清理集.add(回调);
    return () => {
      清理集.delete(回调);
    };
  }

  const 设置 = 创建设置服务(读取预览主题设置(场景环境.状态));
  设置预览主题读取(
    () => 设置.读取(),
    () => 读取预览主题解析(场景环境.状态, 设置.读取()),
  );
  登记清理(() => 设置预览主题读取());
  const 试听 = 场景环境.状态.音频试听 === "开启";
  设置.更新(
    试听
      ? { 背景音乐: true, 音乐音量: 40, 音效音量: 60 }
      : { 背景音乐: false, 音乐音量: 0, 音效音量: 0, 背景音效音量: 0 },
  );
  let 音频 = 试听 ? 创建真实音频服务(设置) : 创建音频服务();
  登记清理(() => 音频.停止全部());
  if (试听) 音频.播放音乐(页面名 === "对局" ? "对局" : "菜单");
  if (页面名 === "结算") {
    // 奖励只是隔离窗口里的视觉样本；不调用发奖服务，演出仍由真实结算页推进。
    记录最近结算({
      编号: "预览-结算",
      结果: { ...固定结算结果 },
      目标达成: false,
      刷新纪录: true,
      历史最佳: null,
      金币: { 新增: 80, 总额: 固定旅行存档.金币, 原因: "固定预览样本" },
      金币失败原因: "",
      新成就: [...固定已解锁成就],
      结束时刻毫秒: Date.now() - 结算重开锁毫秒,
      奖励输入: {
        编号: "预览-结算",
        分数: 固定结算结果.分数,
        消行: 固定结算结果.消行数,
        用时: 0,
        落块: 0,
        破纪录: true,
        日期: 预览日期,
      },
    });
    登记清理(清空最近结算);
  }
  const 主题环境 = 创建主题服务(设置);
  登记清理(主题环境.取消);
  const 同步清屏色 = () => 场景环境.资源.设置清屏色?.(主题环境.读取().颜色.底色);
  同步清屏色();
  const 取消设置失效 = 设置.订阅(() => {
    同步清屏色();
    场景环境.资源.标记失效(页面名, undefined, "设置");
    const 请求渲染 = 场景环境.资源.请求渲染;
    if (请求渲染) 请求渲染();
    else 场景环境.资源.请求重绘();
  });
  登记清理(取消设置失效);

  const 服务: 应用服务 = {
    设置,
    语言: 创建语言服务(设置),
    纪录: 创建纪录服务(),
    金币: 创建金币服务(),
    成就: 创建成就服务(),
    音频,
    平台: 创建平台服务(),
    主题: 主题环境.服务,
    内存: () => ({ 已用MB: null, 总额MB: null }),
    当日日期: () => 预览日期,
  };

  const 控件文字: 控件文字服务 = 创建控件文字服务({
    画笔: 场景环境.资源.画笔,
    读取档位样式: (档) => {
      const 语义 = 读取页面语义色(设置.读取().旅行样式 ?? 设置.读取().样式);
      return { ...读取档位文字样式(档), 颜色: 语义.正文 };
    },
    读取纯色紫外线: () => 场景环境.资源.画笔.读取纯色紫外线(),
  });

  const 资源: 页面资源 = {
    get 逻辑宽() {
      return 场景环境.资源.逻辑宽;
    },
    get 逻辑高() {
      return 场景环境.资源.逻辑高;
    },
    合批: 场景环境.资源.合批,
    画笔: 场景环境.资源.画笔,
    资源: 场景环境.资源.资源,
    读取纹理统计: (): 资源统计 => 场景环境.资源.资源.读取统计(),
    命中: 场景环境.资源.命中,
    读取帧统计: (): 帧统计 => {
      const 合批统计 = 场景环境.资源.合批.读取统计();
      return {
        帧数: 0,
        平均帧间隔毫秒: 0,
        平均工作毫秒: 0,
        绘制调用: 0,
        四边形数: 合批统计.四边形数,
        三角形数: 合批统计.三角形数,
        纹理字节: 场景环境.资源.资源.读取统计().纹理字节,
      };
    },
    请求重绘: () => 场景环境.资源.请求重绘(),
    请求渲染: () => {
      const 请求渲染 = 场景环境.资源.请求渲染;
      if (请求渲染) 请求渲染();
      else 场景环境.资源.请求重绘();
    },
    标记失效: (页名, 子层, 原因) => 场景环境.资源.标记失效(页名, 子层, 原因),
    需要重建: (页名, 子层) => 场景环境.资源.需要重建(页名, 子层),
    开始重建: (页名, 子层) => 场景环境.资源.开始重建(页名, 子层),
    设置绘制层: (偏移) => 场景环境.资源.设置绘制层(偏移),
    设置玩法进行中: () => {},
  };

  const 导航: 导航服务 = {
    进入: () => {},
    替换: () => {},
    返回: () => {},
    打开覆盖: () => {},
    关闭覆盖: () => {},
    读取当前: () => ({ 页面: 读取基础页面(页面名), 覆盖: 读取覆盖页(页面名) }),
  };

  const 上下文: 页面上下文 = {
    资源,
    服务,
    导航,
    参数,
    get 主题() {
      return 主题环境.读取();
    },
    文字: 控件文字,
    读取配色: () => 主题转界面配色(主题环境.读取()),
    绘制背景静底: (绘制环境, 信息) => {
      const 当前设置 = 设置.读取();
      绘制背景静底(资源.画笔.图形, {
        宽: 信息.宽,
        高: 信息.高,
        主题: 当前设置.背景主题,
        静态主体: !信息.动态,
      });
      if (读取背景外观(当前设置).文字基调 === "浅底") {
        资源.画笔.图形.fillStyle(绘制环境.配色.底色, 0.34).fillRect(0, 0, 信息.宽, 信息.高);
      }
    },
    绘制背景动态: (_绘制环境, 信息) => {
      const 主题 = 设置.读取().背景主题;
      绘制背景动态(资源.画笔.图形, {
        宽: 信息.宽,
        高: 信息.高,
        主题,
        时间秒: 信息.时间秒,
        亮度: 读取背景动态亮度(主题),
      });
    },
    读取背景动态: () => {
      const 当前设置 = 设置.读取();
      return 当前设置.背景动态 && 当前设置.省电模式 !== "开";
    },
    登记清理,
  };

  return {
    上下文,
    设置音频开启: (开启) => {
      音频.停止全部();
      音频 = 开启 ? 创建真实音频服务(设置) : 创建音频服务();
      服务.音频 = 音频;
    },
    销毁: 执行清理,
  };
}

function 创建设置服务(初始: 游戏设置): 设置服务 {
  let 当前: 游戏设置 = { ...初始 };
  const 监听 = new Set<(设置: 游戏设置) => void>();
  return {
    读取: () => 当前,
    更新: (变化) => {
      当前 = { ...当前, ...变化 };
      for (const 回调 of [...监听]) {
        回调(当前);
      }
      return 当前;
    },
    订阅: (回调) => {
      监听.add(回调);
      return () => {
        监听.delete(回调);
      };
    },
  };
}


/** 上下文只为一页服务：设置/金币/成就等状态每次创建都是独立内存副本。 */
export function 创建预览页面上下文(
  场景环境: 界面资源场景环境,
  选项: 创建预览页面选项,
): 预览页面会话 {
  const 页面名 = 选项.页面;
  const 参数: 页面参数 = { ...默认参数(页面名), ...选项.参数 };
  const 清理集 = new Set<() => void>();
  let 已清理 = false;

  function 执行清理(): void {
    if (已清理) return;
    已清理 = true;
    for (const 回调 of [...清理集]) {
      清理集.delete(回调);
      try {
        回调();
      } catch {
        // 单个页面的清理失败不应阻断其余订阅/监听解除。
      }
    }
  }

  // 框架的登记清理只接收回调、不返回解绑函数；这里包装成页面契约要求的 () => void。
  场景环境.登记清理(执行清理);

  function 登记清理(回调: () => void): () => void {
    if (已清理) {
      回调();
      return () => {};
    }
    清理集.add(回调);
    return () => {
      清理集.delete(回调);
    };
  }

  const 设置 = 创建设置服务(读取预览主题设置(场景环境.状态));
  设置预览主题读取(
    () => 设置.读取(),
    () => 读取预览主题解析(场景环境.状态, 设置.读取()),
  );
  登记清理(() => 设置预览主题读取());
  const 试听 = 场景环境.状态.音频试听 === "开启";
  设置.更新(
    试听
      ? { 背景音乐: true, 音乐音量: 40, 音效音量: 60 }
      : { 背景音乐: false, 音乐音量: 0, 音效音量: 0, 背景音效音量: 0 },
  );
  let 音频 = 试听 ? 创建真实音频服务(设置) : 创建音频服务();
  登记清理(() => 音频.停止全部());
  if (试听) 音频.播放音乐(页面名 === "对局" ? "对局" : "菜单");
  if (页面名 === "结算") {
    // 奖励只是隔离窗口里的视觉样本；不调用发奖服务，演出仍由真实结算页推进。
    记录最近结算({
      编号: "预览-结算",
      结果: { ...固定结算结果 },
      目标达成: false,
      刷新纪录: true,
      历史最佳: null,
      金币: { 新增: 80, 总额: 固定旅行存档.金币, 原因: "固定预览样本" },
      金币失败原因: "",
      新成就: [...固定已解锁成就],
      结束时刻毫秒: Date.now() - 结算重开锁毫秒,
      奖励输入: {
        编号: "预览-结算",
        分数: 固定结算结果.分数,
        消行: 固定结算结果.消行数,
        用时: 0,
        落块: 0,
        破纪录: true,
        日期: 预览日期,
      },
    });
    登记清理(清空最近结算);
  }
  const 主题环境 = 创建主题服务(设置);
  登记清理(主题环境.取消);
  const 同步清屏色 = () => 场景环境.资源.设置清屏色?.(主题环境.读取().颜色.底色);
  同步清屏色();
  const 取消设置失效 = 设置.订阅(() => {
    同步清屏色();
    场景环境.资源.标记失效(页面名, undefined, "设置");
    const 请求渲染 = 场景环境.资源.请求渲染;
    if (请求渲染) 请求渲染();
    else 场景环境.资源.请求重绘();
  });
  登记清理(取消设置失效);

  const 服务: 应用服务 = {
    设置,
    语言: 创建语言服务(设置),
    纪录: 创建纪录服务(),
    金币: 创建金币服务(),
    成就: 创建成就服务(),
    音频,
    平台: 创建平台服务(),
    主题: 主题环境.服务,
    内存: () => ({ 已用MB: null, 总额MB: null }),
    当日日期: () => 预览日期,
  };

  const 读取配色 = (): 界面配色 => 主题转界面配色(主题环境.读取());

  const 控件文字: 控件文字服务 = 创建控件文字服务({
    画笔: 场景环境.资源.画笔,
    读取档位样式: (档) => {
      const 语义 = 读取页面语义色(设置.读取().旅行样式 ?? 设置.读取().样式);
      return { ...读取档位文字样式(档), 颜色: 语义.正文 };
    },
    读取纯色紫外线: () => 场景环境.资源.画笔.读取纯色紫外线(),
  });

  const 基础资源: 页面资源 = {
    get 逻辑宽() {
      return 场景环境.资源.逻辑宽;
    },
    get 逻辑高() {
      return 场景环境.资源.逻辑高;
    },
    合批: 场景环境.资源.合批,
    画笔: 场景环境.资源.画笔,
    资源: 场景环境.资源.资源,
    读取纹理统计: (): 资源统计 => 场景环境.资源.资源.读取统计(),
    命中: 场景环境.资源.命中,
    读取帧统计: (): 帧统计 => {
      const 合批统计 = 场景环境.资源.合批.读取统计();
      return {
        帧数: 0,
        平均帧间隔毫秒: 0,
        平均工作毫秒: 0,
        绘制调用: 0,
        四边形数: 合批统计.四边形数,
        三角形数: 合批统计.三角形数,
        纹理字节: 场景环境.资源.资源.读取统计().纹理字节,
      };
    },
    请求重绘: () => 场景环境.资源.请求重绘(),
    请求渲染: () => {
      const 请求渲染 = 场景环境.资源.请求渲染;
      if (请求渲染) 请求渲染();
      else 场景环境.资源.请求重绘();
    },
    标记失效: (页名, 子层, 原因) => 场景环境.资源.标记失效(页名, 子层, 原因),
    需要重建: (页名, 子层) => 场景环境.资源.需要重建(页名, 子层),
    开始重建: (页名, 子层) => 场景环境.资源.开始重建(页名, 子层),
    设置绘制层: (偏移) => 场景环境.资源.设置绘制层(偏移),
    设置玩法进行中: () => {},
  };

  /**
   * 每层一份资源视图：把该层页面的子层号抬到自己的基准上，
   * 这样背景/页面/货币/提示的绘制层互不覆盖（图层缓存每页 8 个子层）。
   */
  function 资源视图(子层基: number): 页面资源 {
    return {
      get 逻辑宽() {
        return 基础资源.逻辑宽;
      },
      get 逻辑高() {
        return 基础资源.逻辑高;
      },
      合批: 基础资源.合批,
      画笔: 基础资源.画笔,
      资源: 基础资源.资源,
      读取纹理统计: 基础资源.读取纹理统计,
      命中: 基础资源.命中,
      读取帧统计: 基础资源.读取帧统计,
      请求重绘: 基础资源.请求重绘,
      请求渲染: 基础资源.请求渲染,
      标记失效: (页名, 子层, 原因) =>
        基础资源.标记失效(
          页名,
          子层?.map((层) => 层 + 子层基),
          原因,
        ),
      需要重建: (页名, 子层) => 基础资源.需要重建(页名, 子层 + 子层基),
      开始重建: (页名, 子层) => 基础资源.开始重建(页名, 子层 + 子层基),
      设置绘制层: (偏移) => 基础资源.设置绘制层(偏移 + 子层基),
      设置玩法进行中: 基础资源.设置玩法进行中,
      ...(基础资源.设置镜头偏移 ? { 设置镜头偏移: 基础资源.设置镜头偏移 } : {}),
    };
  }

  /** 页面上下文按层派生：资源换成该层的视图，其余（主题/服务/导航）共用一份。 */
  function 层上下文(子层基: number, 提示?: 提示接口): 页面上下文 {
    return {
      资源: 资源视图(子层基),
      服务,
      导航,
      参数,
      文字: 控件文字,
      get 主题() {
        return 主题环境.读取();
      },
      读取配色,
      ...(提示 ? { 提示 } : {}),
      登记清理,
    };
  }

  const 导航: 导航服务 = {
    // 预览是单页窗口：导航只读，不真的切页；层顶名与层栈保持一致。
    进入: () => {},
    替换: () => {},
    返回: () => {},
    打开浮层: () => {},
    关闭浮层: () => {},
    读取当前: () => ({ 页面: 页面名, 覆盖: null }),
    读取层顶名: (层) => 层栈.读取顶页面名(层),
    打开层: () => {},
    关闭层: () => {},
  };

  // ---- 四层组装（背景 < 页面 < 货币 < 提示） ----
  const 提示页 = new 提示层页面(
    { 资源: 资源视图(子层基准.提示), 文字: 控件文字, 读取配色 },
    提示页名,
  );
  const 页面视图 = 层上下文(子层基准.页面, { 显示: (文本, 秒) => 提示页.显示(文本, 秒) });
  const 层栈 = new 界面层栈<页面上下文>(页面视图);

  const 远景 = new 远景页(层上下文(子层基准.远景));
  层栈.进入(界面层名.背景, 远景页名, 远景, 远景.读取窗口策略());
  const 近景 = new 近景页(层上下文(子层基准.近景));
  层栈.进入(界面层名.背景, 近景页名, 近景, 近景.读取窗口策略());
  const 货币 = 创建货币页(层上下文(子层基准.货币));
  // 正式启动按页面发显示列表；预览常驻显示金币，和主菜单一致。
  货币.发送(默认货币键);
  层栈.进入(界面层名.货币, 货币页名, 货币, 辅助层策略);
  层栈.进入(界面层名.提示, 提示页名, 提示页 as 场景接口<页面上下文>, 辅助层策略);

  const 背景调度 = 创建背景调度({
    标准间隔毫秒: 画质参数.标准背景间隔毫秒,
    省电间隔毫秒: 画质参数.省电背景间隔毫秒,
    闲置间隔毫秒: 画质参数.闲置背景间隔毫秒,
    闲置判定毫秒: 画质参数.闲置判定毫秒,
  });

  function 更新(秒: number): boolean {
    if (已清理) return false;
    层栈.更新(秒);
    背景调度.设置动态(近景.读取背景动态());
    背景调度.设置省电(设置.读取().省电模式 === "开");
    if (!背景调度.到点()) return false;
    近景.刷新背景动态();
    背景调度.记录绘制();
    return true;
  }

  function 渲染(): void {
    if (已清理) return;
    层栈.逐层渲染((_层名, 场景) => {
      基础资源.画笔.重置();
      场景.渲染?.(页面视图);
    });
  }

  return {
    上下文: 页面视图,
    进入页面层: (名称, 页面) => {
      const 策略 = (页面 as 页面实例 & { 读取窗口策略?(): 场景进入选项 }).读取窗口策略?.();
      层栈.进入(界面层名.页面, 名称, 页面, 策略 ?? {});
    },
    更新,
    渲染,
    读取层顶名: (层) => 层栈.读取顶页面名(层),
    设置音频开启: (开启) => {
      音频.停止全部();
      音频 = 开启 ? 创建真实音频服务(设置) : 创建音频服务();
      服务.音频 = 音频;
    },
    销毁: () => {
      if (已清理) return;
      try {
        层栈.销毁();
      } finally {
        执行清理();
      }
    },
  };
}

interface 按钮外观 {
  悬停: boolean;
  按下: boolean;
  已选: boolean;
  可用: boolean;
}
const 尺寸 = (环境: 界面资源绘制环境) =>
  环境.状态.尺寸 === "方形"
    ? { 宽: 64, 高: 64 }
    : 环境.状态.尺寸 === "紧凑"
      ? { 宽: 120, 高: 38 }
      : 环境.状态.尺寸 === "宽幅"
        ? { 宽: 292, 高: 52 }
        : { 宽: 232, 高: 46 };
function 变体(状态: Readonly<Record<string, string>>): 霓虹按钮变体 {
  return 状态.变体 === "主要" || 状态.变体 === "普通" ? 状态.变体 : "次要";
}
function 底板(编号: string, 环境: 界面资源绘制环境, 外观: 按钮外观) {
  const { 画笔, 状态 } = 环境;
  const g = 画笔.图形;
  const { 宽, 高 } = 尺寸(环境);
  g.setAlpha(外观.可用 ? 1 : 0.45);
  if (编号 === "button-menu") {
    const 缩放 = 计算霓虹按钮按压(外观.按下, 1000, 1, 1);
    if (状态.变体 === "覆盖页") 绘制覆盖页按钮(g, 170, 80, 宽 * 缩放.x, 高 * 缩放.y, 外观.已选);
    else 绘制霓虹按钮(g, 170, 80, 宽 * 缩放.x, 高 * 缩放.y, { 变体: 变体(状态), ...外观 });
  }
  if (编号 === "button-paper")
    绘制收藏按钮底板(
      g,
      170,
      80,
      宽,
      高,
      { 金色: 状态.材质 === "金", 纸面: 状态.材质 === "纸" },
      外观,
    );
  if (编号 === "button-landscape") 绘制纯享胶囊(g, 170, 80, 宽, 高, 外观);
  if (编号 === "button-operation") {
    const 色 = 读取触屏按钮视觉(14);
    绘制玻璃按钮底板(g, 170, 80, 74, 70, {
      填色: 色.填色,
      边框色: 色.边框色,
      强调色: 色.边框色,
      透明度: 外观.按下 ? 0.98 : 外观.悬停 ? 0.97 : 色.透明度,
      边透明度: 色.边透明度,
    });
  }
  g.setAlpha(1);
}
function 文字(编号: string, 环境: 界面资源绘制环境, 外观: 按钮外观, 文案: string) {
  const { 画笔, 状态 } = 环境;
  if (编号 === "button-menu" && 状态.内容 === "图标") {
    画笔.图形.save().translateCanvas(154, 64);
    绘制旅行图标(画笔.图形, "设置");
    画笔.图形.restore();
    return;
  }
  if (编号 === "button-paper") {
    画笔.绘制文字(
      生成收藏按钮文字项(170, 80, 文案, { 金色: 状态.材质 === "金", 纸面: 状态.材质 === "纸" }),
    );
    return;
  }
  if (编号 === "button-landscape") {
    画笔.绘制文字(纯享返回文字项(170, 80, 文案));
    return;
  }
  const 样式 =
    编号 === "button-menu"
      ? 状态.变体 === "覆盖页"
        ? 读取覆盖页按钮文字样式(外观.已选, 16)
        : 读取霓虹按钮文字样式({ 变体: 变体(状态), ...外观 })
      : { 字号: 14, 颜色: 读取触屏按钮视觉(14).文字色 };
  画笔.绘制文字({ 文案, 样式, 锚点: "中中", x: 170, y: 80 });
}

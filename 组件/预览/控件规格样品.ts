/** 在隔离的预览主题里执行绘制，结束后撤掉读取器，避免影响后续样品。 */
function 在预览主题内(
  状态: Readonly<Record<string, string>>,
  主题读取: 主题读取模块,
  绘制: (设置: ReturnType<typeof 读取预览主题设置>) => void,
): void {
  const 设置 = 读取预览主题设置(状态);
  主题读取.设置预览主题读取(() => 设置);
  try {
    绘制(设置);
  } finally {
    主题读取.设置预览主题读取();
  }
}


import { 绘制四行庆祝, 绘制消行光带, 绘制落块拖尾, 绘制锁定闪光 } from "../../代码/视觉/特效配方";
import type { 界面资源样品, 界面资源状态字段 } from "../../框架/开发/界面资源协议";
import { 读取霓虹调色板, 霓虹界面主题 } from "../霓虹街机/调色板";

const 状态: readonly 界面资源状态字段[] = [
  { 键: "配色", 名称: "配色方案", 默认: "夜空鎏金", 选项: 霓虹界面主题 },
  { 键: "播放", 名称: "播放", 默认: "播放", 选项: ["播放", "暂停"] },
  { 键: "进度", 名称: "定格进度", 默认: "25", 选项: ["0", "25", "50", "75", "100"] },
];
const 格 = 18,
  左 = 80,
  上 = 34;
export const 特效样品: readonly 界面资源样品[] = (
  [
    ["fx-line", "消行光带", "绘制消行光带", 0.65],
    ["fx-tetris", "四行庆祝", "绘制四行庆祝", 0.9],
    ["fx-drop", "硬降拖尾", "绘制落块拖尾", 0.24],
    ["fx-lock", "锁定闪光", "绘制锁定闪光", 0.15],
  ] as const
).map(([编号, 名称, 导出, 时长]) => ({
  编号,
  名称,
  分类: "特效",
  说明: `对局真实${名称}配方；循环间隔1.5秒，可暂停按进度检查。`,
  宽: 340,
  高: 430,
  源码: [{ 路径: "代码/视觉/特效配方.ts", 导出 }, { 路径: "组件/预览/特效样品.ts" }],
  状态,
  图片引用: [],
  绘制: ({ 画笔, 状态 }) => {
    const 色 = 读取霓虹调色板(霓虹界面主题.find((项) => 项 === 状态.配色));
    const g = 画笔.图形;
    g.fillStyle(色.背景).fillRect(0, 0, 340, 430);
    g.fillStyle(色.棋盘底).fillRect(左, 上, 10 * 格, 20 * 格);
    g.lineStyle(0.5, 色.棋盘描边, 0.5);
    for (let x = 0; x <= 10; x++) g.lineBetween(左 + x * 格, 上, 左 + x * 格, 上 + 20 * 格);
    for (let y = 0; y <= 20; y++) g.lineBetween(左, 上 + y * 格, 左 + 10 * 格, 上 + y * 格);
    画笔.绘制文字({
      文案: `${名称} · ${Math.round(时长 * 1000)} ms`,
      样式: { 字号: 12, 颜色: 色.次要文字 },
      锚点: "中中",
      x: 170,
      y: 412,
    });
  },
  绘制帧: ({ 画笔, 状态 }, 时间秒) => {
    const 色 = 读取霓虹调色板(霓虹界面主题.find((项) => 项 === 状态.配色));
    const 秒 = 状态.播放 === "暂停" ? (Number(状态.进度) / 100) * 时长 : 时间秒 % 1.5;
    if (秒 > 时长) return;
    const g = 画笔.图形;
    if (编号 === "fx-line")
      绘制消行光带(g, { 行: [17, 18, 19], 时间毫秒: 秒 * 1000, 格, 强调色: 色.强调, 左, 上 });
    if (编号 === "fx-tetris") {
      绘制消行光带(g, { 行: [16, 17, 18, 19], 时间毫秒: 秒 * 1000, 格, 强调色: 色.强调, 左, 上 });
      绘制四行庆祝(g, {
        时间毫秒: 秒 * 1000,
        时长毫秒: 900,
        格,
        扫过起点: 16 * 格 * (1 - 秒 / 0.6),
        左,
        上,
      });
    }
    if (编号 === "fx-drop")
      绘制落块拖尾(g, {
        列: [
          { 列: 3, 底: 20 * 格, 初始高度: 10 * 格 },
          { 列: 4, 底: 20 * 格, 初始高度: 10 * 格 },
        ],
        色: 色.方块.I,
        格,
        进度: 秒 / 时长,
        拖尾长: 10 * 格,
        左,
        上,
      });
    if (编号 === "fx-lock")
      绘制锁定闪光(g, {
        格子: [
          [3, 18],
          [4, 18],
          [4, 19],
          [5, 19],
        ],
        格,
        透明度: Math.max(0, 1 - 秒 / 时长),
        左,
        上,
      });
    return 状态.播放 !== "暂停";
  },
}));

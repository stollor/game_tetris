/** 登记条目始终切到当前配色；只有套件/应用/布局/配色铺主题大背景。 */
function 准备(环境: 界面资源绘制环境, 分类: 样品["分类"]) {
  应用预览配色(环境);
  if (!大背景分类.has(分类)) return;
  const 色 = 读取霓虹调色板();
  环境.画笔.图形.fillStyle(色.背景).fillRect(0, 0, 340, 300);
}
function 加按钮(环境: 界面资源绘制环境, 文案: string, 上: number, 变体: 霓虹按钮变体 = "主要") {
  let 次数 = 0;
  const 选项 = {
    变体,
    悬停: false,
    按下: 环境.状态.阶段 === "按下",
    已选: 环境.状态.阶段 === "选中",
  };
  const 控件 = 环境.控件层.添加(
    new 按钮({
      矩形: { 左: 24, 上, 宽: 292, 高: 48 },
      文案,
      禁用: 环境.状态.阶段 === "禁用",
      点击: () => 控件.设置文案(`${文案} · ${++次数}`),
      绘制底板: (_绘制环境, 状态) => {
        环境.画笔.图形.setAlpha(状态.阶段 === "禁用" ? 0.45 : 1);
        const 按下 = 选项.按下 || 状态.阶段 === "按下";
        const 缩放 = 计算霓虹按钮按压(按下, 1000, 1, 1);
        绘制霓虹按钮(环境.画笔.图形, 170, 上 + 24, 292 * 缩放.x, 48 * 缩放.y, {
          ...选项,
          悬停: 状态.悬停 === true,
          按下: 选项.按下 || 状态.阶段 === "按下",
        });
        环境.画笔.图形.setAlpha(1);
      },
      绘制文字: (_绘制环境, 请求) =>
        环境.画笔.绘制文字({
          文案: 请求.文本,
          样式: 读取霓虹按钮文字样式(选项),
          锚点: "中中",
          x: 170,
          y: 上 + 24,
        }),
    }),
  );
}
const 原始配方 = new Map<string, 样品["绘制"]>();
function 登记(
  编号: string,
  名称: string,
  分类: 样品["分类"],
  文件: string,
  导出: string,
  绘制: 样品["绘制"],
  状态: readonly 界面资源状态字段[] = [配色状态],
): 样品 {
  原始配方.set(编号, 绘制);
  return {
    编号,
    名称,
    分类,
    说明: `直接调用游戏的${名称}配方；样品数据与玩家存档隔离。`,
    宽: 340,
    高: 260,
    源码: [{ 路径: `组件/${文件}.ts`, 导出 }, { 路径: "组件/预览/界面资源.ts" }],
    状态,
    绘制: (环境) => {
      准备(环境, 分类);
      绘制(环境);
    },
  };
}

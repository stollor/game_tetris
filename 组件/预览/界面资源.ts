/** 返回厚按键的区域与文字同一套数值，供预览与各页共用的姿态计算一起使用。 */
function 绘制返回按键(
  画笔: 界面资源绘制环境["画笔"],
  时间秒: number,
  姿态: { 下沉: number; 点亮: readonly number[] },
  文案: string,
): void {
  const 区域 = { 中心X: 195, 中心Y: 75, 宽: 200, 高: 48 };
  模式装置.绘制返回传送装置(画笔.图形, 区域, {
    时间秒,
    下沉: 姿态.下沉,
    点亮: 姿态.点亮,
    文案,
  });
  画笔.绘制文字(模式装置.生成返回按键文字项(区域, 文案, 姿态.下沉));
}


/**
 * 方块单元固定资产：同一结构只登记一个中性白色基元，颜色由程序配方按外观生成。
 * 宝石/金属等明暗随色值做非线性调色，不能视为简单乘色，也不改游戏运行时渲染。
 */
function 绘制方块单元资产(环境: 界面资源绘制环境) {
  const 方案 = 方块外观方案表.find((项) => 项.名称 === 环境.状态.外观) ?? 方块外观方案表[0];
  绘制方块单元(环境.画笔.图形, 16, 16, { 方案, 色值: 0xffffff, 格子: 32 });
}

/** 底板/纸面板固定资产：直接调用同源配方，在 16,16 以 48×48 紧凑尺寸绘制。 */
function 绘制底板资产(环境: 界面资源绘制环境, 编号: string) {
  const g = 环境.画笔.图形;
  if (编号 === "paper-panel") {
    绘制收藏纸页(g, 16, 16, 48, 48);
    return;
  }
  if (环境.状态.形态 === "覆盖页面板") {
    const 色 = 读取霓虹调色板();
    绘制覆盖页面板(g, { 左: 16, 上: 16, 宽: 48, 高: 48 }, 色.面板底, 色.面板描边);
    return;
  }
  // 侧栏分隔线只在运行时叠加，不烘焙进底板图集。
  绘制霓虹玻璃(g, 16, 16, 48, 48);
}

function 资产说明(编号: string): string {
  if (编号 === "block-unit")
    return "同结构复用：仅登记一个中性白色基元，示意方块单元的几何与明暗结构；颜色由程序配方按所选外观生成。宝石、金属等明暗是非线性调色，简单乘色不能完全复现原样，不改变游戏运行时渲染。";
  if (编号 === "panel")
    return "同源底板配方以 48×48 紧凑尺寸生成，不含文字；侧栏分隔线保持运行时叠加，不烘焙进底板图集。";
  if (编号 === "paper-panel")
    return "同源纸面板配方以 48×48 紧凑尺寸生成，保留纸面材质与内描边，不含文字。";
  return "实际配方的固定图形图集，不含文字；分隔线作为叠加装饰，不重复占用底板图集。";
}


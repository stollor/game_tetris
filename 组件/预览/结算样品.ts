import { 解析方块外观 } from "../../代码/视觉/外观/方块外观";
import { 计算霓虹结算布局 } from "../../代码/视觉/结算配方";
import type { 界面资源样品, 界面资源绘制环境 } from "../../框架/开发/界面资源协议";
import { 数值面板 } from "../../框架/界面/控件/数值面板";
import { 轻提示队列 } from "../../框架/界面/控件/轻提示";
import {
  结算奖励开始毫秒,
  结算奖励秒,
  结算成就开始毫秒,
  结算成就秒,
  绘制结算操作,
  绘制结算演出,
  绘制结算飘字,
} from "../霓虹街机/结算演出";
import { 设置预览界面样式, 读取霓虹调色板, 霓虹界面主题 } from "../霓虹街机/调色板";

function 绘制样品(环境: 界面资源绘制环境, 时间: number) {
  设置预览界面样式(霓虹界面主题.find((项) => 项 === 环境.状态.配色));
  const 英文 = 环境.状态.语言 === "English";
  const 省电 = 环境.状态.省电 === "开";
  const { 画笔 } = 环境;
  const 色 = 读取霓虹调色板();
  画笔.图形.fillStyle(色.背景).fillRect(0, 0, 390, 844);
  const 数值 = new 数值面板({ 矩形: { 左: 0, 上: 0, 宽: 1, 高: 1 }, 标签: "", 值: 0 });
  数值.设置数值(34510, 省电);
  for (let t = 260; t < Math.min(时间, 2000); t += 1000 / 60) 数值.更新(1 / 60);
  绘制结算演出(画笔, {
    宽: 390,
    高: 844,
    标题: 英文 ? "GAME OVER" : "游戏结束",
    模式: 英文 ? "MARATHON" : "马拉松",
    新纪录: 英文 ? "NEW BEST" : "新纪录",
    分数: Math.round(数值.读取显示值()),
    金币: 95,
    金币标签: 英文 ? "COINS EARNED" : "本局获得",
    循环提示: { 文本: 英文 ? "First piece" : "已收藏 · 第一块拼图", 图标: "first-lock" },
    统计: [
      { 标签: 英文 ? "LINES" : "消除行数", 数值: "62" },
      { 标签: 英文 ? "LEVEL" : "最高等级", 数值: "7" },
      { 标签: 英文 ? "COMBO" : "最佳连击", 数值: "5" },
    ],
    方块方案: 解析方块外观("默认"),
    经过毫秒: 时间,
    省电,
  });
  const 定位 = 计算霓虹结算布局(390, 844);
  for (const 种类 of ["重开", "菜单"] as const) {
    const 区 = 定位[种类];
    绘制结算操作(
      画笔,
      { 左: 区.中心X - 区.宽 / 2, 上: 区.中心Y - 区.高 / 2, 宽: 区.宽, 高: 区.高 },
      种类 === "重开" ? (英文 ? "PLAY AGAIN" : "再来一局") : 英文 ? "MENU" : "返回主菜单",
      种类,
      "默认",
      时间,
      省电,
    );
  }
  const 是成就 = 时间 >= 结算成就开始毫秒;
  const 起点 = 是成就 ? 结算成就开始毫秒 : 结算奖励开始毫秒;
  const 秒 = 是成就 ? 结算成就秒 : 结算奖励秒;
  if (时间 < 起点 || 时间 >= 起点 + 秒 * 1000) return;
  const 队列 = new 轻提示队列(1);
  队列.显示(
    是成就 ? (英文 ? "First piece +5" : "第一块拼图 等6项") : 英文 ? "REWARD SAVED" : "奖励已入账",
    秒,
  );
  队列.更新((时间 - 起点) / 1000);
  绘制结算飘字(画笔, 环境.控件环境, 队列, 定位, {
    类型: 是成就 ? "成就" : "说明",
    经过毫秒: 时间 - 起点,
    数量: 95,
    成就图标: "first-lock",
    省电,
  });
}

export const 结算样品: 界面资源样品 = {
  编号: "settlement",
  名称: "方块结算",
  分类: "应用",
  宽: 390,
  高: 844,
  说明: "游戏实际结算配方：爆炸纪录章、常驻分数/金币、一次性上飘提示与待机循环，可播放或定格；不读写游戏存档。",
  源码: [
    { 路径: "组件/霓虹街机/结算演出.ts" },
    { 路径: "代码/视觉/结算配方.ts" },
    { 路径: "组件/预览/结算样品.ts" },
  ],
  状态: [
    { 键: "配色", 名称: "配色", 默认: "青蓝未来", 选项: 霓虹界面主题 },
    { 键: "播放", 名称: "播放", 默认: "播放", 选项: ["播放", "定格"] },
    {
      键: "时间",
      名称: "定格时间ms",
      默认: "1200",
      选项: ["150", "600", "800", "1200", "2400", "3300", "5000", "6600", "8200"],
    },
    { 键: "语言", 名称: "语言", 默认: "简体中文", 选项: ["简体中文", "English"] },
    { 键: "省电", 名称: "省电", 默认: "关", 选项: ["关", "开"] },
  ],
  绘制: (环境) => {
    if (环境.状态.播放 === "定格") 绘制样品(环境, Number(环境.状态.时间));
  },
  绘制帧: (环境, 秒) => {
    if (环境.状态.播放 !== "播放") return false;
    绘制样品(环境, 秒 * 1000);
    return true;
  },
};

function 绘制演示棋盘(
  场景: Phaser.Scene,
  舞台: Phaser.GameObjects.Container,
  左: number,
  顶: number,
  格: number,
): void {
  const 宽 = 格 * 10;
  const 高 = 格 * 20;
  const 图形 = 场景.add.graphics();
  图形
    .fillStyle(读取霓虹调色板().棋盘底, 0.96)
    .fillRoundedRect(左 - 5, 顶 - 5, 宽 + 10, 高 + 10, 8);
  图形
    .lineStyle(1, 读取霓虹调色板().棋盘描边, 0.8)
    .strokeRoundedRect(左 - 5, 顶 - 5, 宽 + 10, 高 + 10, 8);
  图形.lineStyle(1, 0xffffff, 0.1);
  for (let 列 = 0; 列 <= 10; 列 += 1) 图形.lineBetween(左 + 列 * 格, 顶, 左 + 列 * 格, 顶 + 高);
  for (let 行 = 0; 行 <= 20; 行 += 1) 图形.lineBetween(左, 顶 + 行 * 格, 左 + 宽, 顶 + 行 * 格);
  舞台.add(图形);
}


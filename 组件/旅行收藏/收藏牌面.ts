import type Phaser from "phaser";
import { 创建霓虹按钮, type 霓虹按钮参数 } from "../霓虹街机/按钮";
import { type 收藏按钮数据, 绘制收藏按钮底板, 读取收藏按钮配色 } from "./收藏牌面配方";

export { 收藏色, 绘制收藏纸页 } from "./收藏牌面配方";

export interface 收藏按钮参数 extends 霓虹按钮参数, 收藏按钮数据 {}

/** 收藏馆只替换牌面配方，命中、按下、取消与键鼠手势继续使用现有按钮。 */
export function 创建收藏按钮(场景: Phaser.Scene, 参数: 收藏按钮参数) {
  const 数据: 收藏按钮数据 = { 金色: 参数.金色, 纸面: 参数.纸面 };
  const 配色 = 读取收藏按钮配色(数据);
  return 创建霓虹按钮(场景, {
    ...参数,
    覆盖: {
      文字色跟随底色: true,
      面板色: 配色.面板色,
      强调色: 配色.强调色,
      字重: 配色.字重,
      绘制底板: (绘图, 宽, 高, 状态) => 绘制收藏按钮底板(绘图, 0, 0, 宽, 高, 数据, 状态),
      ...参数.覆盖,
    },
  });
}

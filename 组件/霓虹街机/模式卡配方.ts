import type { 对局纪录 } from "../../代码/存档/对局纪录";
import type { 游戏模式 } from "../../代码/玩法/再消一行";
import type { 图形对象, 文字项 } from "../../框架Three/界面/绘制/协议";
import { 绘制霓虹按钮, 绘制霓虹按钮图标, type 霓虹按钮状态 } from "./按钮配方";
import { 读取霓虹文字样式 } from "./文字样式";

/**
 * 模式选择卡的引擎无关配方：整卡是一块次要按钮玻璃底板，
 * 标题/细节/说明/纪录叠在卡内，右上角可选排行入口。数据由调用方提供，不读存档。
 */

export interface 模式卡布局 {
  中心X: number;
  中心Y: number;
  宽: number;
  高: number;
}

export interface 模式卡数据 {
  标题: string;
  细节: string;
  说明: string;
  纪录: string;
  强调色: string;
  /** 是否显示右上角排行入口（打开该模式榜）。 */
  有排行?: boolean;
}

/** 排行钮区域：与 Phaser 版 霓虹模式卡 内的位置一致（卡右上角 40×40）。 */
export function 计算模式卡排行区域(布局: 模式卡布局): {
  中心X: number;
  中心Y: number;
  宽: number;
  高: number;
} {
  return {
    中心X: 布局.中心X + 布局.宽 / 2 - 24,
    中心Y: 布局.中心Y - 布局.高 / 2 + 24,
    宽: 40,
    高: 40,
  };
}

/** 整卡底板：次要按钮玻璃底板 + 模式强调色。 */
export function 绘制模式卡底板(
  绘图: 图形对象,
  布局: 模式卡布局,
  数据: 模式卡数据,
  状态: 霓虹按钮状态 = {},
): void {
  绘制霓虹按钮(绘图, 布局.中心X, 布局.中心Y, 布局.宽, 布局.高, {
    变体: "次要",
    强调色: 数据.强调色,
    已选: 状态.已选,
    悬停: 状态.悬停,
    按下: 状态.按下,
  });
}

/** 右上角排行入口（深底 + 暖金描边 + 排行图标），颜色取自现 Phaser 版覆盖值。 */
export function 绘制模式卡排行钮(绘图: 图形对象, 布局: 模式卡布局, 状态: 霓虹按钮状态 = {}): void {
  const 区域 = 计算模式卡排行区域(布局);
  绘制霓虹按钮(绘图, 区域.中心X, 区域.中心Y, 区域.宽, 区域.高, {
    变体: "次要",
    面板色: "#1a2430",
    边框色: "#ffe7a8",
    强调色: "#ffe7a8",
    面板透明度: 0.78,
    边框透明度: 1,
    已选: 状态.已选,
    悬停: 状态.悬停,
    按下: 状态.按下,
  });
  绘制霓虹按钮图标(绘图, {
    名称: "排行",
    中心X: 区域.中心X,
    中心Y: 区域.中心Y,
    尺寸: 20,
  });
}

/** 模式卡的全部像素：底板 + 可选排行钮（文字走 生成模式卡文字项）。 */
export function 绘制模式卡(
  绘图: 图形对象,
  布局: 模式卡布局,
  数据: 模式卡数据,
  状态: 霓虹按钮状态 = {},
): void {
  绘制模式卡底板(绘图, 布局, 数据, 状态);
  if (数据.有排行) 绘制模式卡排行钮(绘图, 布局);
}

/** 模式卡文字项：标题/右上细节/说明/底部纪录，锚点与 Phaser 版现行位置逐字一致。 */
export function 生成模式卡文字项(布局: 模式卡布局, 数据: 模式卡数据): 文字项[] {
  const { 中心X, 中心Y, 宽, 高 } = 布局;
  const 细节右 = 数据.有排行 ? 宽 / 2 - 52 : 宽 / 2 - 20;
  return [
    {
      文案: 数据.标题,
      样式: 读取霓虹文字样式("模式卡标题"),
      锚点: "左中",
      x: 中心X - 宽 / 2 + 22,
      y: 中心Y - 高 / 2 + 25,
    },
    {
      文案: 数据.细节,
      样式: { ...读取霓虹文字样式("模式卡细节"), 颜色: 数据.强调色 },
      锚点: "右中",
      x: 中心X + 细节右,
      y: 中心Y - 高 / 2 + 25,
    },
    {
      文案: 数据.说明,
      样式: 读取霓虹文字样式("模式卡说明"),
      锚点: "左中",
      x: 中心X - 宽 / 2 + 22,
      y: 中心Y + 2,
    },
    {
      文案: 数据.纪录,
      样式: 读取霓虹文字样式("模式卡纪录"),
      锚点: "左中",
      x: 中心X - 宽 / 2 + 22,
      y: 中心Y + 高 / 2 - 20,
    },
  ];
}

/** 「最佳 xxx」文案格式化：存档读取留在 Phaser/Three 各自的接口层，这里只管视觉文本。 */
export function 格式化模式纪录(模式: 游戏模式, 纪录: 对局纪录 | null, 英文: boolean): string {
  if (!纪录) return 英文 ? "NO RECORD YET" : "尚无纪录";
  if (模式 === "冲刺")
    return 纪录.用时
      ? `${(纪录.用时 / 1000).toFixed(2)}s`
      : 英文
        ? "NO FINISH YET"
        : "尚无完赛纪录";
  return `${纪录.分数.toLocaleString()}${英文 ? " pts" : " 分"}`;
}

/** 模式卡纪录行（含「最佳/ BEST」前缀），两版共用同一文案。 */
export function 生成模式纪录行(模式: 游戏模式, 纪录: 对局纪录 | null, 英文: boolean): string {
  const 前缀 = 英文 ? "BEST" : "最佳";
  return `${前缀}  ${格式化模式纪录(模式, 纪录, 英文)}`;
}
